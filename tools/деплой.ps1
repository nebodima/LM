	if ($Прогон -ne 'Полный') { $Арг += '--быстро' }
	if ($script:Ошибок -gt 0 -or -not $Прогон) {
		Write-Host "Рабочий цикл дальше: python tools\прогон.py $($Арг -join ' ')   (граница этапа — без --быстро)"
		return
	}
	Write-Host "── прогон ($Прогон): python tools\прогон.py $($Арг -join ' ')"
	python "$Инструменты\прогон.py" @Арг | ForEach-Object { Write-Host $_ }
	if ($LASTEXITCODE -ne 0) { $script:Ошибок++ }
}

# ───────────── 2а. несколько баз — параллельно: дочерний деплой на базу (свой замок, свой агент и порт) ─────────────
if ($Базы.Count -gt 1) {
	$Дети = foreach ($Имя in $Базы) {
		$Б = $Стенд[$Имя]
		$Вывод = Join-Path $Логи "$Имя`_деплой.txt"
		$Арг = @('-NoProfile', '-File', "$PSScriptRoot\деплой.ps1", '-СвояБаза', $Б.Путь, '-Пользователь', $Б.Пользователь,
			'-Имя', $Имя, '-БезОфлайна', '-Сдвиг', ([string]$Часы.Elapsed.TotalSeconds).Replace(',', '.'))
		if ($Исходники) { $Арг += @('-Исходники', $Src) }
		if ($Полная) { $Арг += '-Полная' }
		if ($БезАгента) { $Арг += '-БезАгента' }
		$Арг += @('-ПростойАгента', $Простой)
		$П = Start-Process pwsh -ArgumentList (Кавычки $Арг) -RedirectStandardOutput $Вывод -RedirectStandardError "$Вывод.err" -PassThru -NoNewWindow
		$null = $П.Handle
		@{ Имя = $Имя; П = $П; Вывод = $Вывод }
	}
	foreach ($Д in $Дети) {
		$Осталось = [math]::Max(1, 3 * $Бюджет.Цикл - $Часы.Elapsed.TotalSeconds)
		if (-not $Д.П.WaitForExit([int]($Осталось * 1000))) { $Д.П.Kill(); $Код = 99 } else { $Код = $Д.П.ExitCode }
		Get-Content $Д.Вывод, "$($Д.Вывод).err" -Encoding utf8 -ErrorAction SilentlyContinue |
			Where-Object { $_ -notmatch '^ИТОГО' } | ForEach-Object { Write-Host $_ }
		if ($Код -ne 0) {
			$script:Ошибок++
			Write-Host "        $($Д.Имя): $(if ($Код -eq 99) { 'ТАЙМАУТ — процесс снят' } else { "код $Код" }) (журнал $($Д.Вывод))"
		}
	}
	$Цикл = $Часы.Elapsed.TotalSeconds
	Write-Host ('ИТОГО: баз {0} параллельно, баз с ошибкой {1}, время {2:N1} с (бюджет {3} с){4}' -f $Базы.Count, $script:Ошибок,
		$Цикл, $Бюджет.Цикл, $(if ($Цикл -gt $Бюджет.Цикл) { '  ПРЕДУПРЕЖДЕНИЕ: бюджет превышен' } else { '' }))
	Прогнать-Тесты
	exit [int]($script:Ошибок -gt 0)
}

# ───────────── 2. базы ─────────────
foreach ($Имя in $Базы) {
	$База = $Стенд[$Имя]
	$Начало = $Часы.Elapsed.TotalSeconds
	$ИмяБазы = (python "$Инструменты\отпечаток_src.py" "--имя-базы=$($База.Путь)").Trim()
	# сервер итераций этой базы (tools\итерация.py) держит агента и COM-сеанс — деплою база нужна целиком
	if (Test-Path (Join-Path ([IO.Path]::GetTempPath()) "uz_agent\$(Split-Path $База.Путь -Leaf)\итерация.json")) {
		$н = $Часы.Elapsed.TotalSeconds
		python "$Инструменты\итерация.py" --стоп "--база=$($База.Путь)" | Out-Null
		Отметить "$Имя сервер итераций" ($Часы.Elapsed.TotalSeconds - $н) 3 $true 'остановлен (с его агентом)'
	}
	$н = $Часы.Elapsed.TotalSeconds
	$Замок = Взять-Замок $ИмяБазы (3 * 60)
	Отметить "$Имя замок" ($Часы.Elapsed.TotalSeconds - $н) $Бюджет.Замок ($null -ne $Замок) $(if (-not $Замок) { 'база занята дольше 3 мин' })
	if (-not $Замок) { continue }
	try {
		# что менялось с прошлой удачной загрузки в эту базу
		$ФайлОтпечатка = Join-Path $Состояние "$ИмяБазы.отпечаток.json"
		$Сейчас = Отпечаток-Файлов $Src
		$Было = @{}; $БылоПапка = ''; $БылоSrc = ''; $БылоИтерация = $false
		if ((Test-Path $ФайлОтпечатка) -and -not $Полная) {
			$Ст = Get-Content $ФайлОтпечатка -Raw -Encoding utf8 | ConvertFrom-Json
			$БылоПапка = $Ст.папка; $БылоSrc = $Ст.src; $БылоИтерация = [bool]$Ст.итерация
			$Ст.файлы.PSObject.Properties | ForEach-Object { $Было[$_.Name] = $_.Value }
		}
		$ФайлОтметки = Join-Path $Состояние "$ИмяБазы.деплой.json"
		$Отметка = if (Test-Path $ФайлОтметки) { (Get-Content $ФайлОтметки -Raw -Encoding utf8 | ConvertFrom-Json).src } else { '' }
		$Изменено = @($Сейчас.Keys | Where-Object { $Было[$_] -ne $Сейчас[$_] })
		$Удалено = @($Было.Keys | Where-Object { -not $Сейчас.ContainsKey($_) })
		# полная: первый раз, другая папка, в базу грузили не мы (отметка ≠ нашему отпечатку), удаления, новые файлы, корень
		$НужнаПолная = $Полная -or $Было.Count -eq 0 -or $БылоПапка -ne $Src -or $Отметка -ne $БылоSrc -or $Удалено.Count -gt 0 -or
			@($Изменено | Where-Object { -not $Было.ContainsKey($_) -or $_ -eq 'Configuration.xml' }).Count -gt 0
		if (-not $НужнаПолная -and $Изменено.Count -eq 0) {
			Отметить "$Имя загрузка" 0 $Бюджет.ЗагрузкаЧастичная $true "изменений нет, в базе src $Отметка — не гружу"
			if ($БылоИтерация) {
				# в базу грузила итерация (tools\итерация.py) без /CheckModules — гейт компиляции здесь, до коммита
				$н = $Часы.Elapsed.TotalSeconds
				$Р = Конфигуратор $База "$Логи\$Имя`_check.log" @('/CheckModules', '-ThinClient', '-Server', '-Extension', 'УЗ_ext') (3 * $Бюджет.Модули)
				$Чисто = МодулиЧисто $Р
				Отметить "$Имя проверка модулей" ($Часы.Elapsed.TotalSeconds - $н) $Бюджет.Модули $Чисто "код $($Р.Код); код в базу загрузила итерация"
				if (-not $Чисто) { Хвост $Р.Текст; continue }
				@{ папка = $Src; src = $SrcОтпечаток; файлы = $Сейчас } | ConvertTo-Json -Compress -Depth 3 |
					Set-Content $ФайлОтпечатка -Encoding utf8
			}
			continue
		}
		$Вид = if ($НужнаПолная) { 'полная' } else { "частичная, файлов $($Изменено.Count)" }
		$БюджетЗагрузки = if ($НужнаПолная) { $Бюджет.ЗагрузкаПолная } else { $Бюджет.ЗагрузкаЧастичная }
		# список — в ASCII-папке агента: путь с кириллицей агент отвергает («Directory access violation», 28.09.2026)
		$ПапкаАгента = Join-Path ([IO.Path]::GetTempPath()) "uz_agent\$(Split-Path $База.Путь -Leaf)"
		New-Item -ItemType Directory -Force $ПапкаАгента | Out-Null
		$Список = Join-Path $ПапкаАгента 'list.txt'
		$ЗеркалоSrc = Join-Path $ПапкаАгента 'src'
		# пути списка — в зеркале, если грузит агент, иначе в самих исходниках
		$КореньСписка = if ($БезАгента) { $Src } else { $ЗеркалоSrc }
		if (-not $НужнаПолная) {
			[IO.File]::WriteAllLines($Список, [string[]]($Изменено | ForEach-Object { Join-Path $КореньСписка $_ }), [Text.UTF8Encoding]::new($false))
		}

		# с этого места конфигурация расширения в конфигураторе базы может разойтись с отпечатком (загрузка упала,
		# гейт не пустил применение, загружена мутация) — отпечаток снимаем, вернётся только после применения;
		# следующий деплой без отпечатка идёт полной загрузкой (иначе частичная легла бы на неизвестное состояние)
		Remove-Item $ФайлОтпечатка -ErrorAction SilentlyContinue

		# загрузка: агент конфигуратора (без ~6 с старта), при отказе — пакетно
		$ЧерезАгента = -not $БезАгента
		if ($ЧерезАгента) {
			$Р = Агент @('старт', "--база=$($База.Путь)", "--пользователь=$($База.Пользователь)", "--простой=$Простой") (3 * $Бюджет.Агент)
			$ЧерезАгента = $Р.Код -eq 0
			Отметить "$Имя агент" $Р.Сек $Бюджет.Агент $true $(if ($ЧерезАгента) { ($Р.Текст -split "`n")[0].Trim() } else { 'не поднялся — пакетно: ' + ($Р.Текст.Trim() -split "`n")[-1] })
		}
		$Загружено = $false
		if ($ЧерезАгента) {
			$н = $Часы.Elapsed.TotalSeconds
			$Скопировано = Зеркало $Src $ЗеркалоSrc $Сейчас
			Отметить "$Имя зеркало для агента" ($Часы.Elapsed.TotalSeconds - $н) 2 $true "скопировано файлов $Скопировано"
			$Команда = "config load-files --dir=`"$ЗеркалоSrc`" --extension=УЗ_ext --format=hierarchical"
			if (-not $НужнаПолная) { $Команда += " --list-file=`"$Список`" --partial" }
			$Р = Агент @('команды', "--база=$($База.Путь)", $Команда) (3 * $БюджетЗагрузки)
			$Загружено = $Р.Код -eq 0
			Отметить "$Имя загрузка (агент)" $Р.Сек $БюджетЗагрузки $Загружено $Вид
			if (-not $Загружено) {
				Хвост $Р.Текст 8
				Агент @('стоп', "--база=$($База.Путь)") 10 | Out-Null
				$ЧерезАгента = $false
				$script:Ошибок--          # отказ агента не провал: ниже пакетная полная загрузка решит
				$НужнаПолная = $true; $БюджетЗагрузки = $Бюджет.ЗагрузкаПолная
			}
		}
		if (-not $Загружено) {
			$н = $Часы.Elapsed.TotalSeconds
			$Команда = @('/LoadConfigFromFiles', $Src, '-Extension', 'УЗ_ext')
			if (-not $НужнаПолная) {
				[IO.File]::WriteAllLines($Список, [string[]]($Изменено | ForEach-Object { Join-Path $Src $_ }), [Text.UTF8Encoding]::new($false))
				$Команда += @('-listFile', $Список, '-partial', '-Format', 'Hierarchical')
			}
			$Р = Конфигуратор $База "$Логи\$Имя`_load.log" $Команда (3 * $БюджетЗагрузки)
			$Загружено = Молчит $Р
			Отметить "$Имя загрузка (пакетно)" ($Часы.Elapsed.TotalSeconds - $н) $БюджетЗагрузки $Загружено "$(if ($НужнаПолная) { 'полная' } else { $Вид }), код $($Р.Код)"
			if (-not $Загружено) { Хвост $Р.Текст; continue }
		}

		# загрузка дошла? Агент и пакетный конфигуратор на части ошибок XML отвечают «успешно» и молча выбрасывают
		# загружаемое (картинка команды → <xr:Ref>0</xr:Ref>) — /CheckModules тогда проверил бы не то, а отметка
		# записала бы новый отпечаток. Выгрузка конфигурации обратно и сверка с исходниками — до гейта и применения.
		$Выгрузка = Join-Path $ПапкаАгента 'dump'
		function Загрузка-Дошла([bool]$Агентом) {
			$н = $Часы.Elapsed.TotalSeconds
			$Обновить = Test-Path (Join-Path $Выгрузка 'ConfigDumpInfo.xml')
			if ($Агентом) {
				$Команда = "config dump-files --dir=`"$Выгрузка`" --extension=УЗ_ext --format=hierarchical"
				if ($Обновить) { $Команда += ' --update' }
				$Р = Агент @('команды', "--база=$($База.Путь)", $Команда) (3 * $Бюджет.Сверка)
				$Выгружено = $Р.Код -eq 0
			} else {
				$Команда = @('/DumpConfigToFiles', $Выгрузка, '-Extension', 'УЗ_ext', '-Format', 'Hierarchical')
				if ($Обновить) { $Команда += '-update' }
				$Р = Конфигуратор $База "$Логи\$Имя`_dump.log" $Команда (3 * $Бюджет.Сверка)
				$Выгружено = Молчит $Р
			}
			if ($Выгружено) {
				$Р = Питон-Ждать (Питон-Старт 'сверка' @("$Инструменты\сверка_выгрузки.py", $Выгрузка, "--исходники=$Src")) 30
				$Выгружено = $Р.Код -eq 0
			}
			$Строка = ($Р.Текст -split "`r?`n" | Where-Object { $_ -match 'ИТОГО|линия' } | Select-Object -First 2) -join '; '
			Отметить "$Имя загрузка дошла ($(if ($Агентом) { 'агент' } else { 'пакетно' }))" ($Часы.Elapsed.TotalSeconds - $н) $Бюджет.Сверка $Выгружено $Строка
			if (-not $Выгружено) { Хвост $Р.Текст 12 }
			$Выгружено
		}
		$Дошла = Загрузка-Дошла $ЧерезАгента
		if (-not $Дошла -and $ЧерезАгента) {
			# агент ответил «ок», а в конфигураторе не то (28.09.2026, UZ_BP_E: StdPicture.FillForm в форме, FillValue у
			# реквизита ТЧ — агент не загрузил НИЧЕГО и промолчал). Причину называет только пакетная загрузка в /Out —
			# полная пакетная загрузка: красная — печатаем её журнал; зелёная — сверка ещё раз, уже пакетной выгрузкой
			Write-Host "        агент ответил «ок», но загрузил не то — пакетная полная загрузка: она называет причину в /Out"
			Агент @('стоп', "--база=$($База.Путь)") 10 | Out-Null
			$ЧерезАгента = $false
			$script:Ошибок--          # молчаливый отказ агента не провал сам по себе: решают пакетная загрузка и сверка
			$н = $Часы.Elapsed.TotalSeconds
			$Р = Конфигуратор $База "$Логи\$Имя`_load.log" @('/LoadConfigFromFiles', $Src, '-Extension', 'УЗ_ext') (3 * $Бюджет.ЗагрузкаПолная)
			$Загружено = Молчит $Р
			Отметить "$Имя загрузка (пакетно, причина)" ($Часы.Elapsed.TotalSeconds - $н) $Бюджет.ЗагрузкаПолная $Загружено "полная, код $($Р.Код)"
			if (-not $Загружено) {
				Хвост $Р.Текст
				Write-Host "        в базу НЕ применено: причина — журнал пакетной загрузки выше ($Логи\$Имя`_load.log)"
				continue
			}
			$Дошла = Загрузка-Дошла $false
		}
		if (-not $Дошла) {
			Write-Host "        в базу НЕ применено: конфигуратор принял не то, что в исходниках"
			continue
		}

		# гейт компиляции — до применения, только пакетно (у агента такой команды нет)
		$н = $Часы.Elapsed.TotalSeconds
		$Р = Конфигуратор $База "$Логи\$Имя`_check.log" @('/CheckModules', '-ThinClient', '-Server', '-Extension', 'УЗ_ext') (3 * $Бюджет.Модули)
		$Чисто = МодулиЧисто $Р
		Отметить "$Имя проверка модулей" ($Часы.Elapsed.TotalSeconds - $н) $Бюджет.Модули $Чисто "код $($Р.Код)"
		if (-not $Чисто) {
			Хвост $Р.Текст
			Write-Host "        в базу НЕ применено: загруженная конфигурация расширения осталась в конфигураторе"
			continue
		}

		# применение
		$Применено = $false
		if ($ЧерезАгента) {
			$Р = Агент @('команды', "--база=$($База.Путь)", 'config update-db-cfg --extension=УЗ_ext') (3 * $Бюджет.Применение)
			$Применено = $Р.Код -eq 0
			Отметить "$Имя применение (агент)" $Р.Сек $Бюджет.Применение $Применено
			# после update-db-cfg агент следующую загрузку не выполняет — перезапуск в фоне к следующему деплою
			# (со сторожем простоя: без команд -ПростойАгента мин — остановится сам); -ПростойАгента 0 — не перезапускать
			Агент @('стоп', "--база=$($База.Путь)") 10 | Out-Null
			if ($ПростойАгента -gt 0) {
				Агент @('старт', "--база=$($База.Путь)", "--пользователь=$($База.Пользователь)", '--не-ждать', "--простой=$Простой") 10 | Out-Null
			}
			if (-not $Применено) { Хвост $Р.Текст 8; $script:Ошибок-- }
		}
		if (-not $Применено) {
			$н = $Часы.Elapsed.TotalSeconds
			$Р = Конфигуратор $База "$Логи\$Имя`_upd.log" @('/UpdateDBCfg', '-Extension', 'УЗ_ext') (3 * $Бюджет.Применение)
			$Применено = ПрименениеЧисто $Р
			Отметить "$Имя применение (пакетно)" ($Часы.Elapsed.TotalSeconds - $н) $Бюджет.Применение $Применено "код $($Р.Код)"
			if (-not $Применено) { Хвост $Р.Текст; continue }
		}

		# отметка деплоя (сверяет прогон) и отпечаток файлов для следующей частичной загрузки. ХешСумма расширения
		# берётся из базы сразу (--хеш-из-базы, COM ~6 с): привязка «этот src_ext = это расширение в базе» делается
		# в момент применения, а не первым прогоном — чужая заливка между деплоем и прогоном даёт красный прогон (T06)
		$н = $Часы.Elapsed.TotalSeconds
		$null = python "$Инструменты\отпечаток_src.py" "--отметить=$($База.Путь)" "--каталог=$Src" '--хеш-из-базы' "--пользователь=$($База.Пользователь)"
		@{ папка = $Src; src = $SrcОтпечаток; файлы = $Сейчас } | ConvertTo-Json -Compress -Depth 3 |
			Set-Content $ФайлОтпечатка -Encoding utf8
		Отметить "$Имя отметка деплоя" ($Часы.Elapsed.TotalSeconds - $н) $Бюджет.Отметка ($LASTEXITCODE -eq 0) "src $SrcОтпечаток"
		$Цикл = $Сдвиг + $Часы.Elapsed.TotalSeconds
		Write-Host ('{0,6:N1} с  {1} готово: цикл от начала деплоя {0:N1} с (бюджет {2} с){3}' -f $Цикл, $Имя, $Бюджет.Цикл,
			$(if ($Цикл -gt $Бюджет.Цикл) { '  ПРЕДУПРЕЖДЕНИЕ: бюджет превышен' } else { '' }))
	} finally {
		# -ПростойАгента 0: агент не переживает деплой — при любом исходе (и после ошибки загрузки или гейта)
		if ($ПростойАгента -le 0 -and -not $БезАгента) { Агент @('стоп', "--база=$($База.Путь)") 10 | Out-Null }
		$Замок.Close()
	}
}

Write-Host ('ИТОГО: шагов с ошибкой {0}, время {1:N1} с (логи: {2})' -f $script:Ошибок, $Часы.Elapsed.TotalSeconds, $Логи)
Прогнать-Тесты
exit [int]($script:Ошибок -gt 0)
