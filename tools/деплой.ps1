# Замок базы — тот же файл и байт, что у прогона (прогон.py _замок): %TEMP%\уз_прогон\c_1c_bases_uz_unf_d.lock, байт 0
function Взять-Замок([string]$ИмяБазы, [int]$Ждать) {
	$Путь = Join-Path $Состояние "$ИмяБазы.lock"
	$Срок = $Часы.Elapsed.TotalSeconds + $Ждать
	while ($true) {
		$Поток = [IO.File]::Open($Путь, 'OpenOrCreate', 'ReadWrite', 'ReadWrite')
		try { $Поток.Lock(0, 1); return $Поток } catch [IO.IOException] { $Поток.Close() }
		if ($Часы.Elapsed.TotalSeconds -gt $Срок) { return $null }
		Write-Host ('{0,6:N1} с  ожидание: базу держит прогон или другой деплой (замок {1}.lock) — жду 5 с' -f $Часы.Elapsed.TotalSeconds, $ИмяБазы)
		Start-Sleep -Seconds 5
	}
}

# Зеркало исходников в папке агента: агент грузит только из-под своего /AgentBaseDir — из C:\Users\User02\LESSONS_MANAGER\src_ext
# (основная рабочая копия) он отвечает «Ошибка разбора параметра: dir / Directory access violation» и печатает справку
# (проверено 28.09.2026 на UZ_UNF_E: из подпапки AgentBaseDir — ок). Копируются только изменённые файлы (время
# записи сохраняется — отпечаток зеркала совпадает с исходником), лишние удаляются. → число скопированных
function Зеркало([string]$Из, [string]$В, [hashtable]$Нужно) {
	$Есть = if (Test-Path $В) { Отпечаток-Файлов $В } else { @{} }
	$Скопировано = 0
	foreach ($Отн in $Нужно.Keys) {
		if ($Есть[$Отн] -eq $Нужно[$Отн]) { continue }
		$Куда = Join-Path $В $Отн
		New-Item -ItemType Directory -Force (Split-Path $Куда) | Out-Null
		Copy-Item -LiteralPath (Join-Path $Из $Отн) -Destination $Куда -Force
		$Скопировано++
	}
	foreach ($Отн in @($Есть.Keys | Where-Object { -not $Нужно.ContainsKey($_) })) { Remove-Item -LiteralPath (Join-Path $В $Отн) -Force }
	$Скопировано
}

# Отпечаток «длина|время» файлов папки: относительный путь → строка
function Отпечаток-Файлов([string]$Папка) {
	$Итого = @{}
	Get-ChildItem $Папка -Recurse -File | Where-Object { $_.Name -ne 'ConfigDumpInfo.xml' } | ForEach-Object {
		$Итого[$_.FullName.Substring($Папка.Length + 1)] = "$($_.Length)|$($_.LastWriteTimeUtc.Ticks)"
	}
	$Итого
}

