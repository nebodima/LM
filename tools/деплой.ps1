# аргумент с пробелом — в кавычки, внутренние кавычки — \" (разбор командной строки Windows / python)
function Кавычки([string[]]$Арг) { $Арг | ForEach-Object { if ($_ -match '[\s"]') { '"' + ($_ -replace '"', '\"') + '"' } else { $_ } } }

# Python-скрипт отдельным процессом: вывод в файл, таймаут. → @{ Код; Текст; Сек }
function Питон-Старт([string]$Имя, [string[]]$Арг) {
	$Вывод = Join-Path $Логи "$Имя.txt"
	$П = Start-Process python -ArgumentList (Кавычки $Арг) -RedirectStandardOutput $Вывод -RedirectStandardError "$Вывод.err" `
		-PassThru -NoNewWindow
	$null = $П.Handle   # без этого ExitCode у Start-Process бывает пустым
	@{ П = $П; Вывод = $Вывод; Старт = $Часы.Elapsed.TotalSeconds; Имя = $Имя }
}
function Питон-Ждать($З, [int]$Таймаут) {
	$Осталось = [math]::Max(1, $Таймаут - ($Часы.Elapsed.TotalSeconds - $З.Старт))
	$Код = if ($З.П.WaitForExit([int]($Осталось * 1000))) { $З.П.ExitCode } else { $З.П.Kill(); 99 }
	$Текст = ((Get-Content $З.Вывод -Raw -Encoding utf8 -ErrorAction SilentlyContinue) + (Get-Content "$($З.Вывод).err" -Raw -Encoding utf8 -ErrorAction SilentlyContinue))
	if ($Код -eq 99) { $Текст += "`nТАЙМАУТ $Таймаут с: процесс снят" }
	@{ Код = $Код; Текст = "$Текст"; Сек = $Часы.Elapsed.TotalSeconds - $З.Старт }
}
function Хвост([string]$Текст, [int]$Строк = 15) {
	($Текст -split "`r?`n" | Where-Object { $_.Trim() } | Select-Object -Last $Строк) | ForEach-Object { Write-Host "        $_" }
}

# Пакетный конфигуратор с таймаутом. → @{ Код; Текст }
function Конфигуратор([hashtable]$База, [string]$Лог, [string[]]$Команда, [int]$Таймаут) {
	$Арг = @('DESIGNER', '/F', $База.Путь, '/N', $База.Пользователь, '/DisableStartupDialogs', '/DisableStartupMessages') +
		$Команда + @('/Out', $Лог)
	Remove-Item $Лог -ErrorAction SilentlyContinue
	$П = Start-Process -FilePath $Exe -ArgumentList (Кавычки $Арг) -PassThru -WindowStyle Hidden
	$null = $П.Handle
	if (-not $П.WaitForExit($Таймаут * 1000)) {
		$П.Kill()
		return @{ Код = 99; Текст = "ТАЙМАУТ $Таймаут с (3× бюджета): конфигуратор снят" }
	}
	$Текст = if (Test-Path $Лог) { Get-Content $Лог -Raw -Encoding utf8 } else { '' }
	@{ Код = $П.ExitCode; Текст = "$Текст".Trim([char]0xFEFF, ' ', "`r", "`n", "`t") }
}
# Загрузка/применение: зелёные только при коде 0 и пустом журнале
function Молчит($Р) { $Р.Код -eq 0 -and -not $Р.Текст }
# Применение: при новых объектах платформа пишет в журнал сообщения, не ошибки («Новый объект: …», «Обработка
# структуры…», «Принятие изменений…», «Создано поколение…») — зелёное, если код 0 и КАЖДАЯ строка журнала из этого
# списка; любая другая строка — её сообщение, красное (раньше любой текст краснел — ложно на «Новый объект»).
# Формы строк — из настоящих журналов /UpdateDBCfg 8.3.27 (UZ_BP_E 28.09.2026 и C:\1c_bases\UZ_BP_upd.log):
# «Новый объект: Документ.УЗ_ПереводУченика», «Объект изменен: ЖурналДокументов.УЗ_ОбщийЖурнал», «Регистрация изменена: …».
# «Ошибка исключительной блокировки…», «Активны сеансы…» — не из списка, красные
function ПрименениеЧисто($Р) {
	$Р.Код -eq 0 -and -not ($Р.Текст -split "`r?`n" | Where-Object { $_.Trim([char]0xFEFF, ' ', "`t") -and $_ -notmatch
		'^[\s\uFEFF]*(Новый объект:|Объект (изменен|удален|добавлен)\w*:|Изменен\w* объект|Удален\w* объект|Регистрация изменена:|Обработка структуры|Реорганизация|Принятие изменений|Создано поколение|Операция завершена успешно|Прогресс)' })
}
# самопроверка разбора на образцах настоящего журнала (грабля 28.09.2026: «Объект изменен: …» считался ошибкой)
if (-not (ПрименениеЧисто @{ Код = 0; Текст = "Новый объект: Документ.УЗ_ПереводУченика`r`nОбъект изменен: ЖурналДокументов.УЗ_ОбщийЖурнал`r`nРегистрация изменена: ПланОбмена.Полный" }) -or
	(ПрименениеЧисто @{ Код = 0; Текст = "Новый объект: Документ.Х`r`nОшибка исключительной блокировки информационной базы." }) -or
	(ПрименениеЧисто @{ Код = 1; Текст = '' })) { throw 'ПрименениеЧисто: разбор журнала применения не прошёл самопроверку' }
# /CheckModules: код 0, строка успеха и ни одной строки ошибки формата «{Модуль(стр,кол)}:»
function МодулиЧисто($Р) {
	$Р.Код -eq 0 -and $Р.Текст -match 'Синтаксических ошибок не обнаружено' -and $Р.Текст -notmatch '(?m)^\{.*\(\d+,\d+\)\}:'
}

