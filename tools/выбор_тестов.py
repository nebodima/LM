"""Быстрый прогон (прогон.py --быстро): какие COM-тесты затронуты изменениями src_ext и tools с прошлого
ЗЕЛЁНОГО ПОЛНОГО прогона этой базы, и почему.

Снимок — %TEMP%\\уз_прогон\\зелёный_полный.json: {ключ базы (имя журнала прогона): {"время", "src",
"файлы": {путь от корня репо: sha1 содержимого (CRLF → LF)}}} по src_ext/** и tools/** (без __pycache__).
Пишет его прогон.py после полного прогона (без --тест и --быстро), где провалов 0 и сверка расширения включена.

Карта «тест → объекты src_ext» строится при каждом запуске, по исходникам тестов:
  * имена объектов src_ext (справочники, документы, регистры, общие модули, роли… — имя папки/файла вида в
    src_ext) в СОБСТВЕННОМ тексте теста, словом целиком: «УЗ_Касса» не совпадает с «УЗ_Кассы» и «УЗ_КассовыйЖурнал»;
  * явная метка в тексте теста, когда объект не назван: строка «# затрагивает: УЗ_Касса, МодульПриложения»;
  * объекты вспомогательных модулей (_деньги, фабрика…) тесту НЕ приписываются — иначе правка регистра, который
    helper заполняет попутно, тянула бы полсотни тестов; правка САМОГО helper-а выбирает все тесты, что его
    импортируют (транзитивно: тест_права → тест_отчеты → …).
Изменённый файл → объект: src_ext/<Вид>/<Имя>[.xml|/…] → «Имя»; src_ext/Ext/ManagedApplicationModule.bsl →
«МодульПриложения»; src_ext/Configuration.xml и Languages — без тестов (версию и состав сверяет шаг «расширение»).
tools: тест/логика — сам тест; helper в tools/тесты — импортирующие его тесты; сеанс.py, прогон.py,
выбор_тестов.py, отпечаток_src.py, адрес_базы.py — ВСЕ тесты (изменилась обвязка); проверка_запросов.py — «запросы»; прочее
(аудиты, деплой, нагрузка, демо, макеты) COM-тесты не трогает.
Всегда: «расширение» (сверка src_ext с базой — идёт первой в любом прогоне), «аудит_данных» (последним: тесты
убрали за собой), «запросы» — если менялся хоть один файл src_ext.
Нет снимка для базы — выбираются все тесты (быстрый = полный, печатается).

    python tools\\выбор_тестов.py                                   — что выбрал бы --быстро для СВОЯ_UZ_UNF_A
    python tools\\выбор_тестов.py --ключ=СВОЯ_UZ_BP_C
    python tools\\выбор_тестов.py --изменено=src_ext/AccumulationRegisters/УЗ_Касса.xml   — как будто изменён файл
    python tools\\выбор_тестов.py --карта                           — карта «тест → объекты» целиком
"""
import glob
import hashlib
import json
import os
import re
import sys
import tempfile

ПАПКА = os.path.dirname(os.path.abspath(__file__))
КОРЕНЬ = os.path.dirname(ПАПКА)
SRC = os.path.join(КОРЕНЬ, "src_ext")
ТЕСТЫ = os.path.join(ПАПКА, "тесты")
СНИМОК = os.path.join(tempfile.gettempdir(), "уз_прогон", "зелёный_полный.json")
ВСЕГДА = ("аудит_данных",)
ОБВЯЗКА = {"tools/тесты/сеанс.py", "tools/прогон.py", "tools/выбор_тестов.py", "tools/отпечаток_src.py",
           "tools/адрес_базы.py"}
ЗАПРОСЫ = {"tools/проверка_запросов.py"}
БЕЗ_ТЕСТОВ = {"Configuration.xml", "Languages"}
МЕТКА = re.compile(r"^#\s*затрагивает:\s*(.+)$", re.M)


# ───────────────────────── снимок файлов ─────────────────────────

def файлы():
    """{путь от корня репо через «/»: sha1 содержимого без различия CRLF/LF} по src_ext и tools."""
    итог = {}
    for верх in ("src_ext", "tools"):
        for корень, папки, имена in os.walk(os.path.join(КОРЕНЬ, верх)):
            папки[:] = [п for п in папки if п != "__pycache__"]
            for имя in имена:
                if имя.endswith(".pyc") or имя == "ConfigDumpInfo.xml":
                    continue
                путь = os.path.join(корень, имя)
                with open(путь, "rb") as ф:
                    данные = ф.read().replace(b"\r\n", b"\n")
                итог[os.path.relpath(путь, КОРЕНЬ).replace("\\", "/")] = hashlib.sha1(данные).hexdigest()
    return итог


def прочитать_снимки():
    try:
        return json.load(open(СНИМОК, encoding="utf-8"))
    except (OSError, ValueError):
        return {}


def записать_снимок(ключи, src, время):
    """После зелёного полного прогона: текущее состояние src_ext/tools — точка отсчёта быстрых прогонов."""
    снимки = прочитать_снимки()
    сейчас = файлы()
    for ключ in ключи:
        снимки[ключ] = {"время": время, "src": src, "файлы": сейчас}
    os.makedirs(os.path.dirname(СНИМОК), exist_ok=True)
    with open(СНИМОК + ".новый", "w", encoding="utf-8") as ф:
        json.dump(снимки, ф, ensure_ascii=False)
    os.replace(СНИМОК + ".новый", СНИМОК)


def изменения(ключ):
    """(список изменённых путей, запись снимка) или (None, None) — снимка нет."""
    снимок = прочитать_снимки().get(ключ)
    if not снимок:
        return None, None
    было, стало = снимок["файлы"], файлы()
    return sorted(п for п in set(было) | set(стало) if было.get(п) != стало.get(п)), снимок


# ───────────────────────── карта «тест → объекты» ─────────────────────────

def объекты_src():
    """Имена объектов src_ext (имя файла/папки вида) → вид."""
    итог = {}
    for вид in sorted(os.listdir(SRC)):
        папка = os.path.join(SRC, вид)
        if not os.path.isdir(папка) or вид in БЕЗ_ТЕСТОВ or вид == "Ext":
            continue
        for имя in os.listdir(папка):
            итог.setdefault(имя[:-4] if имя.endswith(".xml") else имя, вид)
    итог["МодульПриложения"] = "Ext"
    return итог


def объект_файла(путь):
    """src_ext/<Вид>/<Имя>… → имя объекта; None — файл без объекта (Configuration.xml, Languages)."""
    части = путь.split("/")
    if части[0] != "src_ext" or len(части) < 2:
        return None
    if части[1] == "Ext":
        return "МодульПриложения"
    if части[1] in БЕЗ_ТЕСТОВ or len(части) < 3:
        return None
    return части[2][:-4] if части[2].endswith(".xml") else части[2]


def тесты_на_диске():
    """Имена тестов, как их понимает прогон: тест_X.py → «X», логика_Y.py → «логика_Y»; → {имя: путь}."""
    итог = {}
    for п in sorted(glob.glob(os.path.join(ТЕСТЫ, "тест_*.py"))):
        итог[os.path.basename(п)[len("тест_"):-3]] = п
    for п in sorted(glob.glob(os.path.join(ТЕСТЫ, "логика_*.py"))):
        итог[os.path.basename(п)[:-3]] = п
    return итог


def _импорты(текст):
    """Имена модулей из «import X» / «from X import …» и importlib.import_module("X")."""
    итог = {а or б for а, б in re.findall(r"^\s*(?:from\s+(\w+)\s+import|import\s+(\w+))", текст, re.M)}
    итог |= set(re.findall(r"import_module\(\s*[\"'](\w+)[\"']", текст))
    return итог


def карта():
    """{тест: {"объекты": {имя: "текст"|"метка"}, "модули": {файлы tools, от которых зависит, транзитивно}}}."""
    имена = объекты_src()
    шаблон = re.compile(r"(?<![\w])(%s)(?![\w])" % "|".join(re.escape(и) for и in sorted(имена, key=len, reverse=True)))
    локальные = {os.path.basename(п)[:-3]: п for п in glob.glob(os.path.join(ТЕСТЫ, "*.py"))}
    локальные.update({os.path.basename(п)[:-3]: п for п in glob.glob(os.path.join(ПАПКА, "*.py"))})
    тексты = {}

    def текст(путь):
        if путь not in тексты:
            тексты[путь] = open(путь, encoding="utf-8").read()
        return тексты[путь]

    def модули(путь):
        """Файлы tools, которые модуль импортирует (транзитивно), включая его самого."""
        итог, очередь = set(), [путь]
        while очередь:
            п = очередь.pop()
            отн = os.path.relpath(п, КОРЕНЬ).replace("\\", "/")
            if отн in итог:
                continue
            итог.add(отн)
            for и in _импорты(текст(п)):
                if и in локальные:
                    очередь.append(локальные[и])
        return итог

    итог = {}
    for тест, путь in тесты_на_диске().items():
        т = текст(путь)
        объекты = {м: "текст" for м in set(шаблон.findall(т))}
        for строка in МЕТКА.findall(т):
            for м in re.split(r"[,\s]+", строка.strip()):
                if м:
                    объекты[м] = "метка"
        итог[тест] = {"объекты": объекты, "модули": модули(путь)}
    return итог


# ───────────────────────── выбор ─────────────────────────

def выбрать(изменённые, все_тесты=None):
    """(выбранные тесты по порядку прогона, {тест: [причины]}, [строки для печати: изменения без тестов]).
    Тест «запросы» — если изменён src_ext или проверка_запросов.py; «аудит_данных» — всегда."""
    к = карта()
    все = list(все_тесты if все_тесты is not None else к)
    причины = {}
    без_тестов = []

    def добавить(тест, причина):
        причины.setdefault(тест, [])
        if причина not in причины[тест]:
            причины[тест].append(причина)

    for путь in изменённые:
        попало = False
        if путь.startswith("src_ext/"):
            добавить("запросы", "изменён src_ext")
            объект = объект_файла(путь)
            if объект is None:
                без_тестов.append("%s — версию и состав сверяет шаг «расширение»" % путь)
                continue
            for тест in все:
                if объект in к.get(тест, {}).get("объекты", {}):
                    добавить(тест, "%s (%s: %s)" % (объект, "метка в тесте" if к[тест]["объекты"][объект] == "метка"
                                                     else "имя в тексте теста", путь))
                    попало = True
            if not попало:
                без_тестов.append("%s — объект %s не назван ни в одном тесте (метка «# затрагивает: %s»)"
                                  % (путь, объект, объект))
            continue
        if путь in ОБВЯЗКА:
            for тест in все:
                добавить(тест, "обвязка прогона: %s" % путь)
            continue
        if путь in ЗАПРОСЫ:
            добавить("запросы", путь)
            continue
        if путь.startswith("tools/тесты/"):
            на_диске = тесты_на_диске()
            for тест in все:
                if путь in к.get(тест, {}).get("модули", set()):
                    сам = тест in на_диске and путь.endswith("/" + os.path.basename(на_диске[тест]))
                    добавить(тест, "изменён %s%s" % (путь, "" if сам else " (импорт)"))
                    попало = True
            if not попало:
                без_тестов.append("%s — не тест и никем из тестов не импортируется" % путь)
            continue
        без_тестов.append("%s — COM-тестов не касается (аудиты/деплой/прочие инструменты)" % путь)
    for тест in ВСЕГДА:
        if тест in все:
            добавить(тест, "всегда (после уборки всех тестов база чистая)")
    выбранные = [т for т in все if т in причины and т not in ВСЕГДА] + [т for т in все if т in ВСЕГДА]
    return выбранные, причины, без_тестов


def главный():
    for поток in (sys.stdout, sys.stderr):
        try:
            поток.reconfigure(encoding="utf-8")
        except Exception:
            pass
    аргументы = {а.split("=", 1)[0]: (а.split("=", 1)[1] if "=" in а else "") for а in sys.argv[1:]}
    if "--карта" in аргументы:
        for тест, д in карта().items():
            print("%-26s %s" % (тест, ", ".join(sorted(д["объекты"])) or "—"))
        return 0
    if "--изменено" in аргументы:
        изменённые = [п.strip().replace("\\", "/") for п in аргументы["--изменено"].split(",") if п.strip()]
        откуда = "заданы ключом --изменено"
    else:
        ключ = аргументы.get("--ключ", "СВОЯ_UZ_UNF_A")
        изменённые, снимок = изменения(ключ)
        if изменённые is None:
            print("нет зелёного полного прогона для %s — быстрый прогон взял бы все тесты" % ключ)
            return 0
        откуда = "с зелёного полного прогона %s (%s)" % (ключ, снимок["время"])
    выбранные, причины, без_тестов = выбрать(изменённые, list(тесты_на_диске()) + ["запросы"])
    print("изменено файлов %d, %s" % (len(изменённые), откуда))
    for т in выбранные:
        print("  %-26s ← %s" % (т, "; ".join(причины[т][:3]) + (" …и ещё %d" % (len(причины[т]) - 3)
                                                                   if len(причины[т]) > 3 else "")))
    for с in без_тестов:
        print("  без тестов: " + с)
    return 0


if __name__ == "__main__":
    sys.exit(главный())
