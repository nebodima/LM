"""Массовое изменение уроков (обработка УЗ_ИзменениеУроков): отметки меняют и движения (Codex A01, A02).

Было: обработка писала проведённый урок РежимЗаписиДокумента.Запись — документ пересчитывался, а
движения оставались прежними (сняли оплату — списание в регистре осталось). Признаки «изменено»
заполнялись исходными значениями отметок: снятые отметки не менялись, поставленные — переписывались.
Стало: ИзменитьОтметкиУрока сравнивает с документом, проведённый урок перепроводит; закрытый
период — отказ с причиной.

    python tools\\тесты\\тест_изменение_уроков.py --база=C:\\1c_bases\\UZ_UNF_A
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import дата, запустить  # noqa: E402
from _деньги import Данные  # noqa: E402
from тест_даты_запрета import прочитать_регистр, записать_регистр  # noqa: E402

МЕТКА = "_Тест изменение уроков"


def сценарий(т):
    c = т.c
    д = Данные(т, МЕТКА)
    ученик = д.элемент("УЗ_ФизЛица", "ученик")
    педагог = д.элемент("УЗ_ФизЛица", "педагог", ЭтоПедагог=True)
    тариф = д.элемент("УЗ_Тарифы", "8 уроков", Сумма=8000, КоличествоУроков=8, КоличествоЧасов=8)

    урок = д.документ("УЗ_Урок", Дата=дата(2026, 9, 10, 10), Педагог=педагог, КоличествоЧасов=1)
    строка = урок.Ученики.Добавить()
    строка.Ученик = ученик
    строка.Тариф = тариф
    ош = д.записать(урок)
    т.проверить(ош is None, "урок без явки и оплаты проведён", ош)
    ссылка = урок.Ссылка
    _, строк = д.итог("УЗ_СписанияСуммЗаУроки", ссылка)
    т.проверить(строк == 0, "без отметок движений ученика нет", строк)

    обработка = c.Обработки.УЗ_ИзменениеУроков

    def изменить(оплата, явка):
        с = c.NewObject("Структура")
        с.Вставить("Ученик", ученик)
        с.Вставить("СписатьОплату", оплата)
        с.Вставить("Явка", явка)
        return обработка.ИзменитьОтметкиУрока(ссылка, т.массив(с))

    def состояние():
        о = ссылка.ПолучитьОбъект()
        сумма, строк = д.итог("УЗ_СписанияСуммЗаУроки", ссылка)
        return о, float(о.Сумма), сумма, строк

    # 1. поставили явку и оплату — урок перепроведён, списание 1 000 в регистре
    итог = изменить(True, True)
    о, в_документе, в_регистре, строк = состояние()
    т.проверить(итог.Успех, "отметки поставлены", итог.Текст)
    т.проверить(о.Проведен and в_документе == 1000 and строк == 1 and в_регистре == -1000,
                "документ и регистр согласованы: 1 000 к оплате, списание 1 000",
                "документ %s, регистр %s (строк %s)" % (в_документе, в_регистре, строк))

    # 2. сняли оплату — списание из регистра ушло (явка осталась: строка с суммой 0)
    итог = изменить(False, True)
    о, в_документе, в_регистре, строк = состояние()
    т.проверить(итог.Успех and в_документе == 0 and в_регистре == 0 and строк == 1,
                "оплату сняли — в документе и регистре 0",
                "%s; документ %s, регистр %s (строк %s)" % (итог.Текст, в_документе, в_регистре, строк))

    # 3. те же значения — урок не переписывается (признак «изменено» не путается с исходным значением)
    версия = c.String(ссылка.ПолучитьОбъект().ВерсияДанных)
    итог = изменить(False, True)
    т.проверить(итог.Успех and c.String(ссылка.ПолучитьОбъект().ВерсияДанных) == версия,
                "без изменений — урок не перезаписан", итог.Текст)

    # 4. закрытый период — отказ с причиной, движения прежние
    прежнее = прочитать_регистр(c)
    т.убрать(lambda: записать_регистр(c, прежнее), "регистр УЗ_ДатыЗапрета")
    записать_регистр(c, [(c.Справочники.Пользователи.ПустаяСсылка(), дата(2026, 9, 10), 0)])
    итог = изменить(True, True)
    _, _, в_регистре, _ = состояние()
    т.проверить(not итог.Успех and "закрыт" in итог.Текст and в_регистре == 0,
                "урок в закрытом периоде не меняется, причина в ответе", итог.Текст)


if __name__ == "__main__":
    запустить("изменение_уроков", сценарий)
