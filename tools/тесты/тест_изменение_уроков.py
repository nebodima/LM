"""Массовое изменение уроков (обработка УЗ_ИзменениеУроков): отметки меняют и движения (Codex A01, A02).

Было: обработка писала проведённый урок РежимЗаписиДокумента.Запись — документ пересчитывался, а
движения оставались прежними (сняли оплату — списание в регистре осталось). Признаки «изменено»
заполнялись исходными значениями отметок: снятые отметки не менялись, поставленные — переписывались.
Стало: ИзменитьОтметкиУрока сравнивает с документом, начавшийся проведённый урок перепроводит;
не начавшийся — только записывает (В10); закрытый период и отказ проведения (пересечение педагога) —
Успех = Ложь с причиной, без исключения. Уроки — вчерашние (будущий урок не проводится).

    python tools\\тесты\\тест_изменение_уроков.py --база=C:\\1c_bases\\UZ_UNF_A
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from _деньги import Данные  # noqa: E402
from фабрика import Фабрика  # noqa: E402
from тест_даты_запрета import прочитать_регистр, записать_регистр  # noqa: E402

МЕТКА = "_Тест изменение уроков"


def сценарий(т):
    c = т.c
    д = Данные(т, МЕТКА)
    ф = Фабрика(т, МЕТКА)
    ученик = д.элемент("УЗ_ФизЛица", "ученик")
    педагог = д.элемент("УЗ_ФизЛица", "педагог", ЭтоПедагог=True)
    тариф = д.элемент("УЗ_Тарифы", "8 уроков", Сумма=8000, КоличествоУроков=8, КоличествоЧасов=8)

    def новый_урок(начало):
        урок = д.документ("УЗ_Урок", Дата=начало, Педагог=педагог, КоличествоЧасов=1)
        строка = урок.Ученики.Добавить()
        строка.Ученик = ученик
        строка.Тариф = тариф
        return урок

    урок = новый_урок(ф.день(-1, 10))
    ош = д.записать(урок)
    т.проверить(ош is None, "вчерашний урок без явки и оплаты проведён", ош)
    ссылка = урок.Ссылка
    _, строк = д.итог("УЗ_СписанияСуммЗаУроки", ссылка)
    т.проверить(строк == 0, "без отметок движений ученика нет", строк)

    обработка = c.Обработки.УЗ_ИзменениеУроков

    def изменить(оплата, явка, какой=None):
        с = c.NewObject("Структура")
        с.Вставить("Ученик", ученик)
        с.Вставить("СписатьОплату", оплата)
        с.Вставить("Явка", явка)
        return обработка.ИзменитьОтметкиУрока(ссылка if какой is None else какой, т.массив(с))

    def состояние(какой=None):
        какой = ссылка if какой is None else какой
        о = какой.ПолучитьОбъект()
        сумма, строк = д.итог("УЗ_СписанияСуммЗаУроки", какой)
        return о, float(о.Сумма), сумма, строк

    # 1. поставили явку и оплату — урок перепроведён, списание 1 000 в регистре
    итог = изменить(True, True)
    о, в_документе, в_регистре, строк = состояние()
    т.проверить(итог.Успех, "отметки поставлены", итог.Текст)
    т.проверить(о.Проведен and в_документе == 1000 and строк == 1 and в_регистре == -1000,
                "документ и регистр согласованы: 1 000 к оплате, списание 1 000",
                "документ %s, регистр %s (строк %s)" % (в_документе, в_регистре, строк))

    # 2. сняли оплату — списание из регистра ушло (явка осталась: строка с суммой 0)
    итог = изменить(False, True)
    о, в_документе, в_регистре, строк = состояние()
    т.проверить(итог.Успех and в_документе == 0 and в_регистре == 0 and строк == 1,
                "оплату сняли — в документе и регистре 0",
                "%s; документ %s, регистр %s (строк %s)" % (итог.Текст, в_документе, в_регистре, строк))

    # 3. те же значения — урок не переписывается (признак «изменено» не путается с исходным значением)
    версия = c.String(ссылка.ПолучитьОбъект().ВерсияДанных)
    итог = изменить(False, True)
    т.проверить(итог.Успех and c.String(ссылка.ПолучитьОбъект().ВерсияДанных) == версия,
                "без изменений — урок не перезаписан", итог.Текст)

    # 4. урок завтра (план) — отметки записываются, урок не проводится (В10)
    будущий = новый_урок(ф.день(1, 10))
    ош = д.записать(будущий, c.РежимЗаписиДокумента.Запись)
    т.проверить(ош is None, "завтрашний урок записан без проведения", ош)
    итог = изменить(True, True, будущий.Ссылка)
    о, в_документе, _, строк = состояние(будущий.Ссылка)
    т.проверить(итог.Успех and not о.Проведен and строк == 0 and в_документе == 1000,
                "будущий урок: отметки записаны, не проведён, движений нет",
                "%s; проведён %s, строк %s" % (итог.Текст, о.Проведен, строк))

    # 5. отказ проведения (пересечение педагога) — Успех = Ложь с причиной, не исключение
    занявший = новый_урок(ф.день(-1, 14))
    т.проверить(д.записать(занявший) is None, "вчерашний урок 14:00–15:00 проведён")
    сдвинутый = новый_урок(ф.день(-1, 16))
    т.проверить(д.записать(сдвинутый) is None, "вчерашний урок 16:00–17:00 проведён")
    о = сдвинутый.Ссылка.ПолучитьОбъект()          # как будто время поправили мимо проверок
    о.Дата = ф.день(-1, 14, 30)
    о.Окончание = ф.день(-1, 15, 30)
    о.ОбменДанными.Загрузка = True
    о.Записать()
    итог = изменить(True, True, сдвинутый.Ссылка)
    _, _, в_регистре, строк = состояние(сдвинутый.Ссылка)
    т.проверить(not итог.Успех and "пересека" in итог.Текст and строк == 0,
                "перепроведение с пересечением педагога — отказ с причиной, движения прежние",
                "%s; строк %s" % (итог.Текст, строк))

    # 6. закрытый период — отказ с причиной, движения прежние
    прежнее = прочитать_регистр(c)
    т.убрать(lambda: записать_регистр(c, прежнее), "регистр УЗ_ДатыЗапрета")
    записать_регистр(c, [(c.Справочники.Пользователи.ПустаяСсылка(), ф.день(-1), 0)])
    итог = изменить(True, True)
    _, _, в_регистре, _ = состояние()
    т.проверить(not итог.Успех and "закрыт" in итог.Текст and в_регистре == 0,
                "урок в закрытом периоде не меняется, причина в ответе", итог.Текст)


if __name__ == "__main__":
    запустить("изменение_уроков", сценарий)
