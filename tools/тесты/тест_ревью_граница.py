"""Ревью Codex логик 28.09.2026 — R25: запись правила дат запрета сразу пересчитывает границу просмотра кассы.

Граница просмотра кассы менеджера (регистр УЗ_ГраницаПросмотраКассы, по ней ограничение доступа роли) считается
по общей строке дат запрета. Руководитель меняет общее правило с «0» на «старше 7 дней» — граница в регистре сразу
«сегодня − 7 дней», а не при следующем входе или ночном задании (до того действующий сеанс менеджера читал кассу
любой давности). Смена обратно на 0 — граница снова пустая (видно всё).
Старый код: запись правила границу не трогала — оставалась пустой до входа руководителя или задания в 00:05.

    python tools\\тесты\\тест_ревью_граница.py --база=C:\\1c_bases\\UZ_UNF_D
"""
# затрагивает: УЗ_ДатыЗапрета, УЗ_ГраницаПросмотраКассы
import datetime
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить, как_дата  # noqa: E402


def сценарий(т):
    c = т.c
    пусто = c.Справочники.Пользователи.ПустаяСсылка()
    было = т.выбрать("ВЫБРАТЬ Д.ДатаЗапрета КАК ДатаЗапрета, Д.ЗапретСтаршеДней КАК Дней "
                     "ИЗ РегистрСведений.УЗ_ДатыЗапрета КАК Д ГДЕ Д.Пользователь = &П", П=пусто)
    прежнее = None
    if было.Количество():
        д = было.Получить(0).ДатаЗапрета
        прежнее = (д if д.year >= 1900 else None, было.Получить(0).Дней)

    def записать(правило):
        набор = c.РегистрыСведений.УЗ_ДатыЗапрета.СоздатьНаборЗаписей()
        набор.Отбор.Пользователь.Установить(пусто)
        if правило is not None:
            з = набор.Добавить()
            з.Пользователь = пусто
            if правило[0] is not None:
                з.ДатаЗапрета = правило[0]
            з.ЗапретСтаршеДней = правило[1]
        набор.Записать()

    def вернуть():
        записать(прежнее)
        c.УЗ_ДатыЗапрета.ОбновитьГраницуПросмотраКассы()
    т.убрать(вернуть, "общее правило дат запрета и граница просмотра кассы")

    сегодня = datetime.date.today()
    записать((None if прежнее is None else прежнее[0], 0))
    c.УЗ_ДатыЗапрета.ОбновитьГраницуПросмотраКассы()
    г = c.УЗ_ДатыЗапрета.ЗаписаннаяГраницаПросмотраКассы()
    т.проверить(г is not None and как_дата(г.НачалоПросмотра) is None, "заготовка: правило 0 дней — граница пустая (видно всё)",
                None if г is None else г.НачалоПросмотра)
    записать((None if прежнее is None else прежнее[0], 7))
    г = c.УЗ_ДатыЗапрета.ЗаписаннаяГраницаПросмотраКассы()
    т.проверить(г is not None and как_дата(г.НачалоПросмотра) == сегодня - datetime.timedelta(days=7),
                "R25: записали общее правило «старше 7 дней» — граница в регистре сразу сегодня − 7 дней (было: пустая "
                "до входа или ночного задания)", None if г is None else г.НачалоПросмотра)
    записать((None if прежнее is None else прежнее[0], 0))
    г = c.УЗ_ДатыЗапрета.ЗаписаннаяГраницаПросмотраКассы()
    т.проверить(г is not None and как_дата(г.НачалоПросмотра) is None,
                "R25: правило снова 0 дней — граница сразу пустая", None if г is None else г.НачалоПросмотра)


if __name__ == "__main__":
    запустить("ревью_граница", сценарий)
