def удалить_тестовые(т):
    """Объекты, заведённые сотрудником (по метке в наименовании/комментарии), — под администратором."""
    c = т.c
    for вид in ("УЗ_Урок", "УЗ_ПриходДенег"):
        for с in т.выбрать("ВЫБРАТЬ Д.Ссылка КАК Ссылка ИЗ Документ.%s КАК Д "
                           "ГДЕ ВЫРАЗИТЬ(Д.Комментарий КАК СТРОКА(100)) = &М" % вид, М=МЕТКА):
            оповещения = c.РегистрыСведений.УЗ_Оповещения.СоздатьНаборЗаписей()
            оповещения.Отбор.Источник.Установить(с.Ссылка)
            оповещения.Записать()
            # мимо дат запрета (Загрузка). Движения в режиме загрузки платформа НЕ удаляет вместе с
            # документом — удалить_объект снимает их сам (отсюда были сироты в базах A/B/C, 28.09)
            т.удалить_объект(с.Ссылка, загрузка=True)
    for вид in ("УЗ_Абонемент", "УЗ_Тарифы", "УЗ_ПредметыОбучения", "УЗ_ФизЛица"):
        for с in т.выбрать("ВЫБРАТЬ С.Ссылка КАК Ссылка ИЗ Справочник.%s КАК С "
                           "ГДЕ С.Наименование ПОДОБНО &М" % вид, М=МЕТКА + "%"):
            о = с.Ссылка.ПолучитьОбъект()
            о.ОбменДанными.Загрузка = True
            о.Удалить()
    набор = c.РегистрыСведений.УЗ_НастройкиПочты.СоздатьНаборЗаписей()
    набор.Отбор.Идентификатор.Установить("ТЕСТ ПРАВ")
    набор.Записать()


def сформировать_скд(c, отчет):
    макет = c.NewObject("КомпоновщикМакетаКомпоновкиДанных").Выполнить(
        отчет.СхемаКомпоновкиДанных, отчет.КомпоновщикНастроек.ПолучитьНастройки())
    процессор = c.NewObject("ПроцессорКомпоновкиДанных")
    процессор.Инициализировать(макет)
    документ = c.NewObject("ТабличныйДокумент")
    вывод = c.NewObject("ПроцессорВыводаРезультатаКомпоновкиДанныхВТабличныйДокумент")
    вывод.УстановитьДокумент(документ)
    вывод.Вывести(процессор)
    return документ


def сценарий(т):
    c = т.c
    база = т.база
    удалить_тестовые(т)
    удалить_сотрудника(т)
    роли = роли_сотрудника(c)
    print("  (конфигурация %s, роли сотрудника: %s)" % (c.Метаданные.Имя, ", ".join(роли)))
    сотрудник = {"c": None}

    def уборка_сотрудника():
        сотрудник["c"] = None   # отпустить COM-сеанс сотрудника до удаления пользователя ИБ
        н = time.time()
        удалить_сотрудника(т)
        print("  (уборка пользователя — %.2f с)" % (time.time() - н))

    def уборка_объектов():
        н = time.time()
        удалить_тестовые(т)
        print("  (уборка объектов — %.2f с)" % (time.time() - н))

    т.убрать(уборка_сотрудника, "пользователь ИБ и элемент Пользователи")
    т.убрать(уборка_объектов, "объекты сотрудника")
    # пользователь ИБ + элемент Пользователи — подготовка подключения сотрудника, меряется вместе с ним
    # вне бюджета: в холодном сеансе администратора первая запись в Пользователи ~4,5 с (компиляция модулей
    # БСП хозяина), в тёплом — 0,6 с
    н = time.time()
    я = завести_сотрудника(т, роли)
    т.вне_бюджета += time.time() - н
    print("  (завести пользователя ИБ и элемент Пользователи — %.2f с, вне бюджета)" % (time.time() - н))

    позиция = позиция_журнала(база)
    с2 = сотрудник["c"] = т.подключить(ИМЯ)
    # ссылки разных соединений не сравнить — сравниваем уникальные идентификаторы строкой
    свой = с2.УЗ_Среда.ТекущийПользователь()
    т.проверить(с2.String(свой.УникальныйИдентификатор()) == c.String(я.УникальныйИдентификатор()),
                "сотрудник: ТекущийПользователь — свой элемент справочника Пользователи", с2.String(свой))

    def шаг(что, действие):
        """Действие сотрудника; при ошибке — текст платформы и отказы прав из журнала."""
        нач = позиция_журнала(база)
        н = time.time()
        try:
            итог = действие()
            т.проверить(True, "%s (%.2f с)" % (что, time.time() - н))
            return итог
        except Exception as е:
            отказы = отказы_прав(база, нач)
            т.проверить(False, что, "%s%s" % (текст_ошибки(е, 200),
                                              "; журнал — не хватило прав: " + "; ".join(отказы) if отказы else ""))
            return None

    def запрещено(что, действие, объект):
        """Ожидаемый отказ: действие падает И журнал показывает отказ прав на объект."""
        нач = позиция_журнала(база)
        try:
            действие()
            т.проверить(False, что, "запись прошла — у сотрудника есть право")
        except Exception as е:
            отказы = отказы_прав(база, нач)
            т.проверить(any(объект in о for о in отказы), что,
                        "ошибка: %s; журнал: %s" % (текст_ошибки(е, 150), "; ".join(отказы) or "отказа прав нет"))

    # ── чтение справочников хозяина ──
    def организация():
        з = с2.NewObject("Запрос")
        з.Текст = ("ВЫБРАТЬ ПЕРВЫЕ 1 О.Ссылка КАК Ссылка ИЗ Справочник.Организации КАК О "
                   "ГДЕ НЕ О.ПометкаУдаления УПОРЯДОЧИТЬ ПО О.Наименование")
        в = з.Выполнить().Выбрать()
        if not в.Следующий():
            raise RuntimeError("сотрудник не видит ни одной организации")
        с2.УЗ_Общий.ЗначениеРеквизита(в.Ссылка, "ИНН", "")
        return в.Ссылка
    орг = шаг("сотрудник читает Организации хозяина и ИНН", организация)

    # ── справочники продукта ──
    сегодня = datetime.date.today()

    def элемент(вид, наименование, **реквизиты):
        о = getattr(с2.Справочники, вид).СоздатьЭлемент()
        о.Наименование = "%s %s" % (МЕТКА, наименование)
        for к, в in реквизиты.items():
            setattr(о, к, в)
        о.Записать()
        return о.Ссылка

    ученик = шаг("сотрудник создаёт ученика", lambda: элемент("УЗ_ФизЛица", "Ученик Петров"))
    педагог = шаг("сотрудник создаёт педагога", lambda: элемент("УЗ_ФизЛица", "Педагог Иванова", ЭтоПедагог=True))
    предмет = шаг("сотрудник создаёт предмет", lambda: элемент("УЗ_ПредметыОбучения", "Сольфеджио"))
    тариф = шаг("сотрудник создаёт тариф", lambda: элемент("УЗ_Тарифы", "8 занятий", Сумма=8000,
                                                           КоличествоУроков=8, КоличествоЧасов=8))
    вчера = сегодня - datetime.timedelta(days=1)
    через_месяц = сегодня + datetime.timedelta(days=30)
    абонемент = шаг("сотрудник создаёт абонемент", lambda: элемент(
        "УЗ_Абонемент", "Абонемент Петров", ФизЛицо=ученик, ПредметОбучения=предмет, Активный=True,
        ДатаНачала=дата(вчера.year, вчера.month, вчера.day), ДатаАктивации=дата(вчера.year, вчера.month, вчера.day),
        ДатаОкончания=дата(через_месяц.year, через_месяц.month, через_месяц.day),
        КоличествоЗанятий=8, ЦенаАбонемента=8000))
    if None in (орг, ученик, педагог, предмет, тариф, абонемент):
        return

    # ── документы ──
    def приход():
        д = с2.Документы.УЗ_ПриходДенег.СоздатьДокумент()
        д.Заполнить(абонемент)
        д.Дата = дата(сегодня.year, сегодня.month, сегодня.day, 9)
        д.Организация = орг
        д.Тариф = тариф
        д.СуммаДокумента = 8000
        д.Комментарий = МЕТКА
        д.Записать(с2.РежимЗаписиДокумента.Проведение)
        return д.Ссылка
    пко = шаг("сотрудник проводит приход денег", приход)

    def урок():
        д = с2.Документы.УЗ_Урок.СоздатьДокумент()
        д.Дата = дата(сегодня.year, сегодня.month, сегодня.day, 10)
        д.Организация = орг
        д.Педагог = педагог
        д.ПредметОбучения = предмет
        д.КоличествоЧасов = 1
        д.Комментарий = МЕТКА
        строка = д.Ученики.Добавить()
        строка.Ученик = ученик
        строка.Абонемент = абонемент
        строка.Тариф = тариф
        строка.Явка = True
        д.Записать(с2.РежимЗаписиДокумента.Проведение)
        return д.Ссылка
    урок_ = шаг("сотрудник проводит урок с учеником", урок)
    if урок_ is not None:
        з = с2.NewObject("Запрос")
        з.Текст = ("ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Строк ИЗ РегистрНакопления.УЗ_СписанияСуммЗаУроки КАК Р "
                   "ГДЕ Р.Регистратор = &Урок")
        з.УстановитьПараметр("Урок", урок_)
        в = з.Выполнить().Выбрать()
        в.Следующий()
        т.проверить(в.Строк == 1, "урок сотрудника: движение по УЗ_СписанияСуммЗаУроки", в.Строк)

    # ── отчёт и печать ──
    # первый отчёт на СКД в сеансе ~2,5–4 с (инициализация ФабрикиXDTO по метаданным хозяина), остальные — доли
    for имя in sorted(НА_СКД):
        отчет = шаг("сотрудник формирует отчёт %s (СКД)" % имя,
                    lambda: сформировать_скд(с2, getattr(с2.Отчеты, имя).Создать()))
        if отчет is not None and имя == "УЗ_ВедомостьПоКассе":
            # цифры, а не «высота > 0» (шапка СКД есть и на пустых данных): RLS или ошибка запроса, обнулившие
            # данные сотрудника, дадут пустую строку его ПКО
            строка = т.строка_отчета(отчет, с2.String(пко)) if пко is not None else ""
            т.проверить("8 000" in строка, "отчёт сотрудника: в строке его ПКО приход 8 000", "строка: «%s»" % строка)

    # ── служебное, что сеанс сотрудника зовёт сам: обновление данных, напоминания ──
    шаг("сотрудник: УЗ_ОбновлениеДанных.ОбновитьДанныеПриНеобходимости (журнал уроков)",
        с2.УЗ_ОбновлениеДанных.ОбновитьДанныеПриНеобходимости)
    if урок_ is not None:
        def напоминание():
            ключ = с2.УЗ_Сервер.СоздатьНапоминание(урок_, с2.ТекущаяДатаСеанса(), МЕТКА)
            с2.УЗ_Сервер.ПолучитьОповещения(None)
            ключи = с2.NewObject("Массив")
            ключи.Добавить(ключ)
            с2.УЗ_Сервер.ЗавершитьОповещения(ключи)
        шаг("сотрудник: напоминание по уроку — создать, получить, завершить (УЗ_Оповещения)", напоминание)
    if пко is not None:
        печать = шаг("сотрудник печатает ПКО (менеджер печати документа)",
                     lambda: с2.УЗ_Печать.СформироватьСвоейПечатью("Документ.УЗ_ПриходДенег", "ПКО", пко))
        if печать is not None:
            т.проверить(печать.ТабличныйДокумент.НайтиТекст("Ученик Петров") is not None,
                        "ПКО сотрудника: «Принято от» — ученик")
        if с2.УЗ_Среда.ФормаПечатиХозяина():
            def печать_бсп():
                объекты = с2.NewObject("Массив")
                объекты.Добавить(пко)
                итог = с2.УправлениеПечатью.СформироватьПечатныеФормы("Документ.УЗ_ПриходДенег", "ПКО", объекты,
                                                                     с2.NewObject("Структура"))
                if итог.КоллекцияПечатныхФорм.Получить(0).ТабличныйДокумент.ВысотаТаблицы == 0:
                    raise RuntimeError("печатная форма пустая")
            шаг("сотрудник печатает ПКО через БСП хозяина (форма «Печать документов»)", печать_бсп)

    # ── запреты: настройки почты и даты запрета — только администратору ──
    def почта_напрямую():
        з = с2.РегистрыСведений.УЗ_НастройкиПочты.СоздатьМенеджерЗаписи()
        з.Идентификатор = "ТЕСТ ПРАВ"
        з.СерверSMTP = "smtp.example.invalid"
        з.Записать()
    запрещено("сотруднику запрещена запись УЗ_НастройкиПочты", почта_напрямую, "РегистрСведений.УЗ_НастройкиПочты")

    def почта_модулем():
        данные = с2.NewObject("Структура")
        данные.Вставить("СерверSMTP", "smtp.example.invalid")
        с2.УЗ_Почта.СохранитьНастройки(данные)
    try:
        почта_модулем()
        т.проверить(False, "УЗ_Почта.СохранитьНастройки сотруднику запрещена", "настройки записаны")
    except Exception as е:
        т.проверить("только администратор" in текст_ошибки(е), "УЗ_Почта.СохранитьНастройки сотруднику запрещена",
                    текст_ошибки(е, 150))

    def даты_запрета():
        набор = с2.РегистрыСведений.УЗ_ДатыЗапрета.СоздатьНаборЗаписей()
        запись = набор.Добавить()
        запись.Пользователь = с2.УЗ_Среда.ТекущийПользователь()   # своя строка: уборка снимет её с пользователем
        запись.ДатаЗапрета = дата(2000, 1, 1)
        набор.Записать(False)   # добавить, не заменяя: при ошибке прав ничего не стирается
    запрещено("сотруднику запрещено менять даты запрета (УЗ_ДатыЗапрета)", даты_запрета,
              "РегистрСведений.УЗ_ДатыЗапрета")

    # ── итог по журналу: отказы на наши объекты, кроме ожидаемых, — дыры роли ──
    ожидаемые = ("УЗ_НастройкиПочты", "УЗ_ДатыЗапрета")
    все = отказы_прав(база, позиция)
    лишние = list(dict.fromkeys(о for о in все if "УЗ_" in о and not any(и in о for и in ожидаемые)))
    т.проверить(not лишние, "журнал: нет отказов прав сотрудника на объекты УЗ_", "; ".join(лишние))
    чужие = [о for о in все if "УЗ_" not in о]
    if чужие:
        print("  (отказы на объекты хозяина — роли хозяина, не наша роль: %s)" % "; ".join(sorted(set(чужие))))


