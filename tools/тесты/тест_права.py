def день_менеджера(т, свой, ид_ставки, чужое):
    """Рабочий день менеджера и его запреты. → данные для руководителя строками (ссылки сеанса менеджера
    наружу не выходят: сеанс закрывается здесь)."""
    с = Сотрудник(т, МЕНЕДЖЕР, "менеджер")
    м = с.c
    итог = {}
    try:
        касса_без_начала_работы(т, с)
        _день_менеджера(т, с, м, свой, ид_ставки, итог)
        if итог.get("урок"):
            зарплата_урока(т, с, итог["урок"])
            расходы_урока_один_источник(т, с, итог["урок"])
        журналы_и_напоминания(т, с, чужое, итог.get("пко_ид"))
        граница_при_входе(т, с)          # вход — в конце: всё выше шло без ПриНачалеРаботы
    finally:
        м = None
        с.закрыть()
    return итог


