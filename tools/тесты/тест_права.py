def удалить_пользователя(т, имя):
    """Пользователь ИБ, его элемент Пользователи и записи БСП о нём — всё, что осталось от прошлых прогонов."""
    c = т.c
    пользователь_ИБ = c.ПользователиИнформационнойБазы.НайтиПоИмени(имя)
    if пользователь_ИБ is None:
        return
    for ссылка in элементы_пользователя(т, пользователь_ИБ.УникальныйИдентификатор):
        for регистр, измерение in ЗАПИСИ_БСП:
            if c.Метаданные.РегистрыСведений.Найти(регистр) is None:
                continue
            набор = getattr(c.РегистрыСведений, регистр).СоздатьНаборЗаписей()
            getattr(набор.Отбор, измерение).Установить(ссылка)
            набор.ОбменДанными.Загрузка = True
            набор.Записать()
        объект = ссылка.ПолучитьОбъект()
        объект.ОбменДанными.Загрузка = True   # мимо подписок БСП: элемент тестовый
        объект.Удалить()
    пользователь_ИБ.Удалить()


