def справка_и_договор(т, с, м, орг, ученик, мама, абонемент):
    """Этап 2.1, часть 2 (В40–В43): менеджер заполняет ИНН мамы, выписывает и печатает справку об оплате обучения
    (мама — основной плательщик ученика, приход по абонементу — её оплата) и договор на основании абонемента;
    лицензию организации менять не может. Лицензию (и ИНН организации, если в копии базы его нет) на время теста
    ставит администратор. → ид справки для руководителя."""
