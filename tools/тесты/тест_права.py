    if not прежний_инн:
        о.ИНН = "7701001236"
        о.ОбменДанными.Загрузка = True
        о.Записать()

        def вернуть_инн():
            о_ = орг_а.ПолучитьОбъект()
            о_.ИНН = прежний_инн
            о_.ОбменДанными.Загрузка = True
            о_.Записать()
        т.убрать(вернуть_инн, "ИНН организации")
    набор = c.РегистрыСведений.УЗ_РеквизитыОрганизаций.СоздатьНаборЗаписей()
    набор.Отбор.Организация.Установить(орг_а)
    набор.Прочитать()
    прежние = набор.Выгрузить()
    набор.Очистить()
    з = набор.Добавить()
    з.Организация = орг_а
    з.НомерЛицензии = "Л035-00000-00/00000001"
    з.ДатаЛицензии = дата(2020, 1, 1)
    з.Ответственный = "Администратор Теста Прав"
    набор.Записать()

    def вернуть_реквизиты():
        н = c.РегистрыСведений.УЗ_РеквизитыОрганизаций.СоздатьНаборЗаписей()
        н.Отбор.Организация.Установить(орг_а)
        н.Загрузить(прежние)
        н.Записать()
    т.убрать(вернуть_реквизиты, "реквизиты организации")

