def _день_руководителя(т, с, р, свой, данные):
    сегодня = сеанс.сегодня()
    вчера = сегодня - datetime.timedelta(days=1)
    позиция = позиция_журнала(т.база)
    с.свой_пользователь(свой)
    начало_работы(т, с)
    т.проверить(р.УЗ_Общий.ДоступнаЗарплата(), "руководитель: УЗ_Общий.ДоступнаЗарплата — Истина (ставка и начисления видны)")
    # S02 как в типовых: движения регистров вручную не правит и руководитель — только «Полные права» хозяина;
    # проведение пишет их по праву «Изменение»
    for рег in р.Метаданные.РегистрыНакопления:
        if рег.Имя.startswith("УЗ_"):
            т.проверить(not р.ПравоДоступа("Редактирование", рег) and р.ПравоДоступа("Изменение", рег),
                        "руководитель: движения %s вручную не редактируются (проведение пишет их)" % рег.Имя)
    for коллекция, объект, вид, имя in ЗАРПЛАТНЫЕ_ПОЛЯ + ССЫЛКИ_НА_СТАВКУ:
        поле = поле_метаданных(р, коллекция, объект, вид, имя)
        т.проверить(р.ПравоДоступа("Просмотр", поле) and р.ПравоДоступа("Редактирование", поле),
                    "руководитель: поле %s.%s видно и редактируется" % (объект, имя))

    def ставка():
        о = р.Справочники.УЗ_СтавкиПедагогов.СоздатьЭлемент()
        о.Наименование = "%s руководитель" % МЕТКА
        о.ОплатаЗаЧас = 700
        о.Записать()
    с.шаг("заводит ставку педагога", ставка)
    команды_видны(т, с)
    if данные.get("справка"):   # этап 2.1, часть 2: справку печатает и руководитель, реквизиты организации — его
        справка = с.ссылка("Документы", "УЗ_СправкаОбОплатеОбучения", данные["справка"])
        печать = с.шаг("печатает справку об оплате обучения менеджера", lambda: р.УЗ_Печать.СформироватьСвоейПечатью(
            "Документ.УЗ_СправкаОбОплатеОбучения", "Справка", справка))
        т.проверить(печать is not None and печать.ПечатныхФорм == 1, "руководитель: справка напечатана")
        орг_р = с.ссылка("Справочники", "Организации", данные["орг"])

        def ответственный():
            н = р.РегистрыСведений.УЗ_РеквизитыОрганизаций.СоздатьМенеджерЗаписи()
            н.Организация = орг_р
            н.Прочитать()
            н.Ответственный = "Руководитель Теста Прав"
            н.Записать()
        с.шаг("меняет ответственного за справки в реквизитах организации", ответственный)
    if данные.get("педагог"):
        педагог = с.ссылка("Справочники", "УЗ_ФизЛица", данные["педагог"])
        орг = с.ссылка("Справочники", "Организации", данные["орг"])

        def расчет():
            д = р.Документы.УЗ_РасчетЗарплаты.СоздатьДокумент()
            д.Заполнить(None)
            д.Дата = дата(сегодня.year, сегодня.month, сегодня.day, 15)
            д.Организация = орг
            д.Педагог = педагог
            д.ДатаНачала = дата(вчера.year, вчера.month, вчера.day)
            д.ДатаОкончания = дата(сегодня.year, сегодня.month, сегодня.day)
            д.Комментарий = МЕТКА
            д.ЗаполнитьНачисления()
            if float(д.СуммаДокумента) != СТАВКА:
                raise RuntimeError("к выплате %s, а по уроку менеджера %d" % (д.СуммаДокумента, СТАВКА))
            д.Записать(р.РежимЗаписиДокумента.Проведение)
            return д.Ссылка
        расчет_ = с.шаг("проводит расчёт зарплаты педагога по уроку менеджера (%d)" % СТАВКА, расчет)
        if расчет_ is not None:
            def выплата():
                д = р.Документы.УЗ_РасходДенег.СоздатьДокумент()
                д.Заполнить(расчет_)
                д.Дата = дата(сегодня.year, сегодня.month, сегодня.day, 16)
                д.Комментарий = МЕТКА
                if р.String(д.ВидОперации) != р.String(р.Перечисления.УЗ_ВидыОпераций.ВыплатаЗарплаты) \
                        or float(д.СуммаДокумента) != СТАВКА:
                    raise RuntimeError("РКО по расчёту: %s на %s" % (р.String(д.ВидОперации), д.СуммаДокумента))
                д.Записать(р.РежимЗаписиДокумента.Проведение)
            с.шаг("выплачивает зарплату по расчёту (РКО «Выплата зарплаты»)", выплата)
    с.шаг("проводит РКО «Прочий расход»", lambda: рко(с, "ПрочийРасход", None, 100, 17))
    с.шаг("записывает настройки (УЗ_Настройки, без изменений)",
          lambda: р.РегистрыСведений.УЗ_Настройки.ЗаписатьНастройки(р.NewObject("Структура")))
    с.шаг("записывает дату запрета (своя строка УЗ_ДатыЗапрета)", lambda: даты_запрета(с))
    for имя in sorted(НА_СКД):
        отчет = с.скд(имя)
        if отчет is not None and имя == "УЗ_ВедомостьПоКассе":
            # цифры, а не «высота > 0» (шапка СКД есть и на пустых данных): RLS или ошибка запроса, обнулившие
            # данные, дадут пустую строку ПКО
            строка = т.строка_отчета(отчет, данные["пко"]) if данные.get("пко") else ""
            т.проверить("8 000" in строка, "отчёт руководителя: в полной ведомости по кассе строка ПКО менеджера 8 000",
                        "строка: «%s»" % строка)
    с.шаг("выгружает фото учеников (УЗ_ОбработкаФото.ФайлыФотографий)", lambda: р.Обработки.УЗ_ОбработкаФото.ФайлыФотографий())
    с.запрещено("запись УЗ_НастройкиПочты (только администратор)", lambda: почта_напрямую(с),
                "РегистрСведений.УЗ_НастройкиПочты")
    отказы = отказы_прав(т.база, позиция, РУКОВОДИТЕЛЬ)
    лишние = list(dict.fromkeys(о for о in отказы if "УЗ_" in о and "УЗ_НастройкиПочты" not in о))
    т.проверить(not лишние, "журнал: у руководителя нет отказов прав на объекты УЗ_ (кроме настроек почты)",
                "; ".join(лишние))
    чужие = [о for о in отказы if "УЗ_" not in о]
    if чужие:
        print("  (отказы руководителю на объекты хозяина — роли хозяина: %s)" % "; ".join(sorted(set(чужие))))


КОНФИГУРАЦИИ_ДОКУМЕНТА = {"УНФ": "УправлениеНебольшойФирмой", "БП": "БухгалтерияПредприятия", "УТ": "УправлениеТорговлей"}


def роли_из_документа():
    """{имя конфигурации: {роли хозяина}} — таблица «Имена ролей в конфигураторе» docs/роли_и_права.md."""
    путь = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), "docs",
                        "роли_и_права.md")
    итог = {}
    for строка in open(путь, encoding="utf-8").read().splitlines():
        м = re.match(r"\|\s*(УНФ|БП|УТ)\s[\d.]+\s*\|([^|]*)\|", строка)
        if м:
            итог[КОНФИГУРАЦИИ_ДОКУМЕНТА[м.group(1)]] = set(re.findall(r"`(\w+)`", м.group(2)))
    return итог


def сценарий(т):
    c = т.c
    # набор ролей хозяина теста — тот же, что в инструкции покупателю (docs/роли_и_права.md): тест проверяет
    # права именно с ним, разойтись они не должны (набор УНФ 28.09.2026 дополнен «Чтение курсов валют»)
    в_документе = роли_из_документа().get(c.Метаданные.Имя)
    в_тесте = set(ОБЩИЕ_РОЛИ + РОЛИ_ХОЗЯИНА.get(c.Метаданные.Имя, []))
    т.проверить(в_документе == в_тесте, "роли хозяина в тесте = роли в docs/роли_и_права.md (%s)" % c.Метаданные.Имя,
                "в документе нет: %s; в тесте нет: %s" % (sorted(в_тесте - (в_документе or set())),
                                                         sorted((в_документе or set()) - в_тесте)))

    def убрать_пользователей():
        for имя in (МЕНЕДЖЕР, РУКОВОДИТЕЛЬ) + СТАРЫЕ_ИМЕНА:
            удалить_пользователя(т, имя)

    удалить_тестовые(т)
    убрать_пользователей()

    def уборка_пользователей():
        gc.collect()   # сеансы сотрудников закрыты в их днях; на всякий случай — до удаления пользователей ИБ
        н = time.time()
        убрать_пользователей()
        print("  (уборка пользователей — %.2f с)" % (time.time() - н))

    def уборка_объектов():
        # одной транзакцией: сеансы сотрудников уже закрыты, таблицы держать некому; запись файловой базы вне
        # транзакции — своя фиксация 10–20 мс, а удалений с наборами движений и оповещений здесь ~80 (1,8 с → 0,2 с,
        # UZ_UNF_E 29.09.2026). Не прошла транзакцией — отменена целиком и уборка идёт по одному, как раньше
        н = time.time()
        как = "одной транзакцией"
        try:
            with т.транзакция():
                удалить_тестовые(т)
        except Exception as е:
            как = "по одному (транзакцией не прошла: %s)" % текст_ошибки(е, 150)
            удалить_тестовые(т)
        print("  (уборка объектов %s — %.2f с)" % (как, time.time() - н))

    т.убрать(уборка_пользователей, "пользователи ИБ и элементы Пользователи")
    т.убрать(уборка_объектов, "объекты сотрудников")
    # пользователи ИБ + элементы Пользователи — подготовка подключений, меряется вместе с ними вне бюджета
    н = time.time()
    свои = {имя: завести_пользователя(т, имя, роли_пользователя(c, имя)) for имя in (МЕНЕДЖЕР, РУКОВОДИТЕЛЬ)}
    т.вне_бюджета += time.time() - н
    print("  (конфигурация %s; завести двух пользователей — %.2f с, вне бюджета)" % (c.Метаданные.Имя, time.time() - н))

    # S07: карточка Пользователи по данным пользователя ИБ — только по идентификатору; одноимённая чужая
    # карточка (реквизит ИдентификаторПользователяИБ у хозяина есть) — не наша (было: поиск по имени)
    чужой = c.УЗ_Среда.ПользовательПоДаннымИБ(c.String(c.NewObject("УникальныйИдентификатор")), МЕНЕДЖЕР, МЕНЕДЖЕР)
    т.проверить(чужой.Пустая(), "S07: пользователь ИБ без карточки не получает одноимённую чужую карточку",
                c.String(чужой))
    пользователь_ИБ = c.ПользователиИнформационнойБазы.НайтиПоИмени(МЕНЕДЖЕР)
    свой = c.УЗ_Среда.ПользовательПоДаннымИБ(c.String(пользователь_ИБ.УникальныйИдентификатор), "другое имя", "другое имя")
    т.проверить(c.String(свой.УникальныйИдентификатор()) == c.String(свои[МЕНЕДЖЕР].УникальныйИдентификатор()),
                "S07: карточка находится по идентификатору пользователя ИБ, имя не важно")

    # ставка педагога — справочник руководителя; её заводит администратор теста, руководитель заводит свою ниже
    ставка = c.Справочники.УЗ_СтавкиПедагогов.СоздатьЭлемент()
    ставка.Наименование = "%s %d" % (МЕТКА, СТАВКА)
    ставка.ОплатаЗаЗанятие = СТАВКА
    ставка.Записать()
    чужое = подготовить_чужое(т, свои, ставка.Ссылка)
    # сеансы по очереди, не одновременно: два лишних сеанса в одном процессе исчерпывали лицензии ключа
    # защиты при параллельных прогонах других баз («Ключ защиты программы больше не доступен», 28.09.2026)
    данные = день_менеджера(т, свои[МЕНЕДЖЕР], c.String(ставка.Ссылка.УникальныйИдентификатор()), чужое)
    напоминание = т.выбрать("ВЫБРАТЬ О.Завершено КАК Завершено ИЗ РегистрСведений.УЗ_Оповещения КАК О "
                            "ГДЕ О.Источник = &И", И=ставка.Ссылка)
    т.проверить(напоминание.Количество() == 1 and not напоминание.Получить(0).Завершено,
                "S06: напоминание руководителя после попытки менеджера не завершено")
    день_руководителя(т, свои[РУКОВОДИТЕЛЬ], данные)


def общее_правило_недели(т):
    """Общая строка дат запрета (пустой пользователь) «старше 7 дней» — по ней граница просмотра кассы в ограничении
    роли (одна на всех: своей строки сотрудника условие роли не видит). Прежнее общее правило возвращает уборка,
    с пересчётом границы: копия остаётся как была."""
    c = т.c
    пусто = c.Справочники.Пользователи.ПустаяСсылка()
    было = т.выбрать("ВЫБРАТЬ Д.ДатаЗапрета КАК ДатаЗапрета, Д.ЗапретСтаршеДней КАК Дней "
                     "ИЗ РегистрСведений.УЗ_ДатыЗапрета КАК Д ГДЕ Д.Пользователь = &П", П=пусто)
    прежнее = None
    if было.Количество():
        д = было.Получить(0).ДатаЗапрета
        прежнее = (д if д.year >= 1900 else None, было.Получить(0).Дней)   # пустая дата по COM — 0100-01-01

    def записать(правило):
        набор = c.РегистрыСведений.УЗ_ДатыЗапрета.СоздатьНаборЗаписей()
        набор.Отбор.Пользователь.Установить(пусто)
        if правило is not None:
            запись = набор.Добавить()
            запись.Пользователь = пусто
            if правило[0] is not None:
                запись.ДатаЗапрета = правило[0]
            запись.ЗапретСтаршеДней = правило[1]
        набор.Записать()

    def вернуть():
        записать(прежнее)
        c.УЗ_ДатыЗапрета.ОбновитьГраницуПросмотраКассы()
    т.убрать(вернуть, "общее правило дат запрета и граница просмотра кассы")
    записать((None if прежнее is None else прежнее[0], 7))


def граница_фоновым_заданием(т, ученики):
    """S04: сеансы без клиента — под администратором. (1) Журналы и кассовые документы без РАЗРЕШЕННЫЕ и без
    ПриНачалеРаботы читаются. (2) Регламентное задание границы (метод из метаданных задания) и регламентное
    ПроверкаЗадолженности (только по ученикам теста — чужим письма не уйдут) — фоновыми заданиями: завершены без
    ошибки; граница — сегодня − 7 дней (общее правило). Старый код: ошибка чтения на копии БП, задания границы нет."""
    c = т.c
    ошибки = читается_касса(c, False)
    т.проверить(not ошибки, "администратор без ПриНачалеРаботы: кассовые документы и журналы читаются без ошибки",
                "; ".join("%s: %s" % о for о in ошибки))
    задания = {"граница": c.Метаданные.РегламентныеЗадания.УЗ_ОбновлениеГраницыПросмотраКассы.ИмяМетода,
               "задолженность": c.Метаданные.РегламентныеЗадания.УЗ_ПроверкаЗадолженности.ИмяМетода}
    # состояния — строками эталонов (системные перечисления по COM сравнивать нельзя)
    активно = c.String(c.СостояниеФоновогоЗадания.Активно)
    завершено = c.String(c.СостояниеФоновогоЗадания.Завершено)
    файловая = c.СтрокаСоединенияИнформационнойБазы().upper().startswith("FILE=")
