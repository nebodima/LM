def _день_менеджера(т, с, м, свой, ид_ставки, итог):
    c = т.c
    сегодня = datetime.date.today()
    вчера = сегодня - datetime.timedelta(days=1)
    через_месяц = сегодня + datetime.timedelta(days=30)
    позиция = позиция_журнала(т.база)
    с.свой_пользователь(свой)

    def организация():
        з = м.NewObject("Запрос")
        з.Текст = ("ВЫБРАТЬ ПЕРВЫЕ 1 О.Ссылка КАК Ссылка ИЗ Справочник.Организации КАК О "
                   "ГДЕ НЕ О.ПометкаУдаления УПОРЯДОЧИТЬ ПО О.Наименование")
        в = з.Выполнить().Выбрать()
        if not в.Следующий():
            raise RuntimeError("менеджер не видит ни одной организации")
        м.УЗ_Общий.ЗначениеРеквизита(в.Ссылка, "ИНН", "")
        return в.Ссылка
    орг = с.шаг("читает Организации хозяина и ИНН", организация)

    def элемент(вид, наименование, **реквизиты):
        о = getattr(м.Справочники, вид).СоздатьЭлемент()
        о.Наименование = "%s %s" % (МЕТКА, наименование)
        for к, в in реквизиты.items():
            setattr(о, к, в)
        о.Записать()
        return о.Ссылка

    ставка = с.ссылка("Справочники", "УЗ_СтавкиПедагогов", ид_ставки)
    ученик = с.шаг("создаёт ученика", lambda: элемент("УЗ_ФизЛица", "Ученик Петров"))
    педагог = с.шаг("создаёт педагога со ставкой руководителя", lambda: элемент(
        "УЗ_ФизЛица", "Педагог Иванова", ЭтоПедагог=True, СтавкаПедагога=ставка))
    предмет = с.шаг("создаёт предмет", lambda: элемент("УЗ_ПредметыОбучения", "Сольфеджио"))
    тариф = с.шаг("создаёт тариф", lambda: элемент("УЗ_Тарифы", "8 занятий", Сумма=ПКО,
                                                    КоличествоУроков=8, КоличествоЧасов=8))
    абонемент = с.шаг("создаёт абонемент", lambda: элемент(
        "УЗ_Абонемент", "Абонемент Петров", ФизЛицо=ученик, ПредметОбучения=предмет, Активный=True,
        ДатаНачала=дата(вчера.year, вчера.month, вчера.day), ДатаАктивации=дата(вчера.year, вчера.month, вчера.day),
        ДатаОкончания=дата(через_месяц.year, через_месяц.month, через_месяц.day),
        КоличествоЗанятий=8, ЦенаАбонемента=ПКО))
    if None in (орг, ученик, педагог, предмет, тариф, абонемент):
        return

    def приход():
        д = м.Документы.УЗ_ПриходДенег.СоздатьДокумент()
        д.Заполнить(абонемент)
        д.Дата = дата(сегодня.year, сегодня.month, сегодня.day, 9)
        д.Организация = орг
        д.Тариф = тариф
        д.СуммаДокумента = ПКО
        д.Комментарий = МЕТКА
        д.Записать(м.РежимЗаписиДокумента.Проведение)
        return д.Ссылка
    пко = с.шаг("проводит приход денег", приход)

    def урок():
        д = м.Документы.УЗ_Урок.СоздатьДокумент()
        д.Дата = дата(вчера.year, вчера.month, вчера.day, 10)   # урок нельзя провести раньше начала (В10)
        д.Организация = орг
        д.Педагог = педагог
        д.СтавкаПедагога = ставка   # так делает форма урока при выборе педагога
        д.ПредметОбучения = предмет
        д.КоличествоЧасов = 1
        д.Комментарий = МЕТКА
        строка = д.Ученики.Добавить()
        строка.Ученик = ученик
        строка.Абонемент = абонемент
        строка.Тариф = тариф
        строка.Явка = True
        д.Записать(м.РежимЗаписиДокумента.Проведение)
        return д.Ссылка
    урок_ = с.шаг("проводит урок педагога со ставкой", урок)
    if пко is not None:
        итог["пко_ид"] = с.ид(пко)
    if урок_ is not None:
        итог["урок"] = с.ид(урок_)

        def тема():
            о = урок_.ПолучитьОбъект()
            о.ТемаУрока = "Интервалы"
            о.Записать(м.РежимЗаписиДокумента.Проведение)
        # проверка ручных начислений (УЗ_ЗарплатаУрока) не мешает обычной правке урока
        с.шаг("меняет тему урока и перепроводит его", тема)
        урок_а = c.Документы.УЗ_Урок.ПолучитьСсылку(c.NewObject("УникальныйИдентификатор", с.ид(урок_)))
        движения = т.выбрать("ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Строк ИЗ РегистрНакопления.УЗ_СписанияСуммЗаУроки КАК Р "
                             "ГДЕ Р.Регистратор = &Урок", Урок=урок_а)
        т.проверить(движения.Получить(0).Строк == 1, "урок менеджера: движение по УЗ_СписанияСуммЗаУроки",
                    движения.Получить(0).Строк)
        зарплата = т.выбрать("ВЫБРАТЬ ЕСТЬNULL(СУММА(Р.Сумма), 0) КАК Сумма ИЗ РегистрНакопления.УЗ_РасчетыПоЗарплате КАК Р "
                             "ГДЕ Р.Регистратор = &Урок", Урок=урок_а)
        т.проверить(float(зарплата.Получить(0).Сумма) == СТАВКА,
                    "урок менеджера: начисление педагогу %d в УЗ_РасчетыПоЗарплате (ставку он не видит)" % СТАВКА,
                    зарплата.Получить(0).Сумма)

    def возврат():
        д = м.Документы.УЗ_РасходДенег.СоздатьДокумент()
        д.Заполнить(ученик)   # как «Вернуть деньги» из карточки ученика: вид «Касса ученики»
        д.Дата = дата(сегодня.year, сегодня.month, сегодня.day, 11)
        д.Организация = орг
        д.ПредметОбучения = предмет
        д.СуммаДокумента = ВОЗВРАТ
        д.Комментарий = МЕТКА
        д.Записать(м.РежимЗаписиДокумента.Проведение)
    с.шаг("проводит возврат денег ученику (РКО «Касса ученики»)", возврат)

    # ── свои отчёты на СКД ──
    for имя in sorted(НА_СКД - ОТЧЕТЫ_РУКОВОДИТЕЛЯ):
        с.скд(имя)

    # ── журналы и связанные документы: в общем журнале есть расчёты зарплаты — менеджеру их не видно ──
    def журналы():
        м.УЗ_ДатыЗапрета.ГраницаПросмотра()   # как форма кассового журнала: ставит границу просмотра кассы
        for журнал in ("УЗ_ОбщийЖурнал", "УЗ_КассовыйЖурнал"):
            з = м.NewObject("Запрос")
            з.Текст = "ВЫБРАТЬ РАЗРЕШЕННЫЕ ПЕРВЫЕ 100 Ж.Ссылка КАК Ссылка ИЗ ЖурналДокументов.%s КАК Ж" % журнал
            з.Выполнить()
        з = м.NewObject("Запрос")
        з.Текст = "ВЫБРАТЬ РАЗРЕШЕННЫЕ К.Ссылка КАК Ссылка ИЗ КритерийОтбора.УЗ_СвязанныеДокументы(&П) КАК К"
        з.УстановитьПараметр("П", педагог)
        з.Выполнить()
    с.шаг("читает журналы документов и связанные документы педагога (РАЗРЕШЕННЫЕ, как формы списка)", журналы)

    # ── служебное, что сеанс зовёт сам: обновление данных, напоминания, печать ──
    с.шаг("УЗ_ОбновлениеДанных.ОбновитьДанныеПриНеобходимости (журнал уроков)",
          м.УЗ_ОбновлениеДанных.ОбновитьДанныеПриНеобходимости)
    if урок_ is not None:
        def напоминание():
            ключ = м.УЗ_Сервер.СоздатьНапоминание(урок_, м.ТекущаяДатаСеанса(), МЕТКА)
            м.УЗ_Сервер.ПолучитьОповещения(None)
            ключи = м.NewObject("Массив")
            ключи.Добавить(ключ)
            м.УЗ_Сервер.ЗавершитьОповещения(ключи)
        с.шаг("напоминание по уроку — создать, получить, завершить (УЗ_Оповещения)", напоминание)
    if пко is not None:
        печать = с.шаг("печатает ПКО (менеджер печати документа)",
                       lambda: м.УЗ_Печать.СформироватьСвоейПечатью("Документ.УЗ_ПриходДенег", "ПКО", пко))
        if печать is not None:
            т.проверить(печать.ТабличныйДокумент.НайтиТекст("Ученик Петров") is not None,
                        "ПКО менеджера: «Принято от» — ученик")
        if м.УЗ_Среда.ФормаПечатиХозяина():
            def печать_бсп():
                объекты = м.NewObject("Массив")
                объекты.Добавить(пко)
                п = м.УправлениеПечатью.СформироватьПечатныеФормы("Документ.УЗ_ПриходДенег", "ПКО", объекты,
                                                                 м.NewObject("Структура"))
                if п.КоллекцияПечатныхФорм.Получить(0).ТабличныйДокумент.ВысотаТаблицы == 0:
                    raise RuntimeError("печатная форма пустая")
            с.шаг("печатает ПКО через БСП хозяина (форма «Печать документов»)", печать_бсп)

    # зарплатные поля форм: признак, по которому формы урока, ученика, РКО и список уроков их прячут
    т.проверить(not м.УЗ_Общий.ДоступнаЗарплата(), "менеджер: УЗ_Общий.ДоступнаЗарплата — Ложь (ставка и начисления скрыты)")
    т.проверить(not м.ПравоДоступа("Просмотр", м.Метаданные.Справочники.УЗ_СтавкиПедагогов),
                "менеджер: справочник ставок не открыть (нет права «Просмотр»)")
    # рабочий день — без единого отказа на объекты УЗ_
    отказы = отказы_прав(т.база, позиция, МЕНЕДЖЕР, позиция_журнала(т.база))
    лишние = list(dict.fromkeys(о for о in отказы if "УЗ_" in о))
    т.проверить(not лишние, "журнал: в рабочем дне менеджера нет отказов прав на объекты УЗ_", "; ".join(лишние))
    чужие = [о for о in отказы if "УЗ_" not in о]
    if чужие:
        print("  (отказы на объекты хозяина — роли хозяина, не наша роль: %s)" % "; ".join(sorted(set(чужие))))

    # ════════════════════ чего менеджеру нельзя ════════════════════
    def прочитать_расчеты():
        з = м.NewObject("Запрос")
        з.Текст = "ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка КАК Ссылка ИЗ Документ.УЗ_РасчетЗарплаты КАК Д"
        з.Выполнить()
    с.запрещено("прочитать расчёты зарплаты", прочитать_расчеты, "Документ.УЗ_РасчетЗарплаты")

    def записать_расчет():
        д = м.Документы.УЗ_РасчетЗарплаты.СоздатьДокумент()
        д.Дата = дата(сегодня.year, сегодня.month, сегодня.day, 12)
        д.Педагог = педагог
        д.Комментарий = МЕТКА
        д.Записать(м.РежимЗаписиДокумента.Запись)
    с.запрещено("записать расчёт зарплаты", записать_расчет, "Документ.УЗ_РасчетЗарплаты")

    def записать_ставку():
        о = м.Справочники.УЗ_СтавкиПедагогов.СоздатьЭлемент()
        о.Наименование = "%s менеджер" % МЕТКА
        о.ОплатаЗаЗанятие = 1
        о.Записать()
    с.запрещено("завести ставку педагога", записать_ставку, "Справочник.УЗ_СтавкиПедагогов")
    for имя in sorted(ОТЧЕТЫ_РУКОВОДИТЕЛЯ):
        с.запрещено("отчёт %s" % имя, lambda: сформировать_скд(м, getattr(м.Отчеты, имя).Создать()), "Отчет.%s" % имя)
    с.запрещено("выгрузить фото учеников (УЗ_ОбработкаФото)", lambda: м.Обработки.УЗ_ОбработкаФото.ФайлыФотографий(),
                "Обработка.УЗ_ОбработкаФото")
    с.запрещено("изменить настройки (УЗ_Настройки)",
                lambda: м.РегистрыСведений.УЗ_Настройки.ЗаписатьНастройки(м.NewObject("Структура")),
                "РегистрСведений.УЗ_Настройки")
    с.запрещено("менять даты запрета (УЗ_ДатыЗапрета)", lambda: даты_запрета(с), "РегистрСведений.УЗ_ДатыЗапрета")
    с.запрещено("РКО «Выплата зарплаты» педагогу", lambda: рко(с, "ВыплатаЗарплаты", педагог, СТАВКА, 13),
                "Документ.УЗ_РасходДенег")
    с.запрещено("РКО «Прочий расход»", lambda: рко(с, "ПрочийРасход", None, 100, 14), "Документ.УЗ_РасходДенег")
    с.запрещено("запись УЗ_НастройкиПочты", lambda: почта_напрямую(с), "РегистрСведений.УЗ_НастройкиПочты")
    try:
        данные = м.NewObject("Структура")
        данные.Вставить("СерверSMTP", "smtp.example.invalid")
        м.УЗ_Почта.СохранитьНастройки(данные)
        т.проверить(False, "менеджер — запрещено: УЗ_Почта.СохранитьНастройки", "настройки записаны")
    except Exception as е:
        т.проверить("только администратор" in текст_ошибки(е), "менеджер — запрещено: УЗ_Почта.СохранитьНастройки",
                    текст_ошибки(е, 150))

    итог.update(педагог=с.ид(педагог), орг=с.ид(орг), пко=м.String(пко) if пко is not None else None)


def день_руководителя(т, свой, данные):
    """Руководитель: всё проходит — зарплата, выплата, расходы, настройки, даты запрета, все отчёты, фото."""
    с = Сотрудник(т, РУКОВОДИТЕЛЬ, "руководитель")
    try:
        _день_руководителя(т, с, с.c, свой, данные)
    finally:
        с.закрыть()


def _день_руководителя(т, с, р, свой, данные):
    сегодня = datetime.date.today()
    вчера = сегодня - datetime.timedelta(days=1)
    позиция = позиция_журнала(т.база)
    с.свой_пользователь(свой)
    т.проверить(р.УЗ_Общий.ДоступнаЗарплата(), "руководитель: УЗ_Общий.ДоступнаЗарплата — Истина (ставка и начисления видны)")
    for коллекция, объект, вид, имя in ЗАРПЛАТНЫЕ_ПОЛЯ + ССЫЛКИ_НА_СТАВКУ:
        поле = поле_метаданных(р, коллекция, объект, вид, имя)
        т.проверить(р.ПравоДоступа("Просмотр", поле) and р.ПравоДоступа("Редактирование", поле),
                    "руководитель: поле %s.%s видно и редактируется" % (объект, имя))

    def ставка():
        о = р.Справочники.УЗ_СтавкиПедагогов.СоздатьЭлемент()
        о.Наименование = "%s руководитель" % МЕТКА
        о.ОплатаЗаЧас = 700
        о.Записать()
    с.шаг("заводит ставку педагога", ставка)
    if данные.get("педагог"):
        педагог = с.ссылка("Справочники", "УЗ_ФизЛица", данные["педагог"])
        орг = с.ссылка("Справочники", "Организации", данные["орг"])

        def расчет():
            д = р.Документы.УЗ_РасчетЗарплаты.СоздатьДокумент()
            д.Заполнить(None)
            д.Дата = дата(сегодня.year, сегодня.month, сегодня.day, 15)
            д.Организация = орг
            д.Педагог = педагог
            д.ДатаНачала = дата(вчера.year, вчера.month, вчера.day)
            д.ДатаОкончания = дата(сегодня.year, сегодня.month, сегодня.day)
            д.Комментарий = МЕТКА
            д.ЗаполнитьНачисления()
            if float(д.СуммаДокумента) != СТАВКА:
                raise RuntimeError("к выплате %s, а по уроку менеджера %d" % (д.СуммаДокумента, СТАВКА))
            д.Записать(р.РежимЗаписиДокумента.Проведение)
            return д.Ссылка
        расчет_ = с.шаг("проводит расчёт зарплаты педагога по уроку менеджера (%d)" % СТАВКА, расчет)
        if расчет_ is not None:
            def выплата():
                д = р.Документы.УЗ_РасходДенег.СоздатьДокумент()
                д.Заполнить(расчет_)
                д.Дата = дата(сегодня.year, сегодня.month, сегодня.day, 16)
                д.Комментарий = МЕТКА
                if р.String(д.ВидОперации) != р.String(р.Перечисления.УЗ_ВидыОпераций.ВыплатаЗарплаты) \
                        or float(д.СуммаДокумента) != СТАВКА:
                    raise RuntimeError("РКО по расчёту: %s на %s" % (р.String(д.ВидОперации), д.СуммаДокумента))
                д.Записать(р.РежимЗаписиДокумента.Проведение)
            с.шаг("выплачивает зарплату по расчёту (РКО «Выплата зарплаты»)", выплата)
    с.шаг("проводит РКО «Прочий расход»", lambda: рко(с, "ПрочийРасход", None, 100, 17))
    с.шаг("записывает настройки (УЗ_Настройки, без изменений)",
          lambda: р.РегистрыСведений.УЗ_Настройки.ЗаписатьНастройки(р.NewObject("Структура")))
    с.шаг("записывает дату запрета (своя строка УЗ_ДатыЗапрета)", lambda: даты_запрета(с))
    for имя in sorted(НА_СКД):
        отчет = с.скд(имя)
        if отчет is not None and имя == "УЗ_ВедомостьПоКассе":
            # цифры, а не «высота > 0» (шапка СКД есть и на пустых данных): RLS или ошибка запроса, обнулившие
            # данные, дадут пустую строку ПКО
            строка = т.строка_отчета(отчет, данные["пко"]) if данные.get("пко") else ""
            т.проверить("8 000" in строка, "отчёт руководителя: в полной ведомости по кассе строка ПКО менеджера 8 000",
                        "строка: «%s»" % строка)
    с.шаг("выгружает фото учеников (УЗ_ОбработкаФото.ФайлыФотографий)", lambda: р.Обработки.УЗ_ОбработкаФото.ФайлыФотографий())
    с.запрещено("запись УЗ_НастройкиПочты (только администратор)", lambda: почта_напрямую(с),
                "РегистрСведений.УЗ_НастройкиПочты")
    отказы = отказы_прав(т.база, позиция, РУКОВОДИТЕЛЬ)
    лишние = list(dict.fromkeys(о for о in отказы if "УЗ_" in о and "УЗ_НастройкиПочты" not in о))
    т.проверить(not лишние, "журнал: у руководителя нет отказов прав на объекты УЗ_ (кроме настроек почты)",
                "; ".join(лишние))
    чужие = [о for о in отказы if "УЗ_" not in о]
    if чужие:
        print("  (отказы руководителю на объекты хозяина — роли хозяина: %s)" % "; ".join(sorted(set(чужие))))


def сценарий(т):
    c = т.c

    def убрать_пользователей():
        for имя in (МЕНЕДЖЕР, РУКОВОДИТЕЛЬ) + СТАРЫЕ_ИМЕНА:
            удалить_пользователя(т, имя)

    удалить_тестовые(т)
    убрать_пользователей()

    def уборка_пользователей():
        gc.collect()   # сеансы сотрудников закрыты в их днях; на всякий случай — до удаления пользователей ИБ
        н = time.time()
        убрать_пользователей()
        print("  (уборка пользователей — %.2f с)" % (time.time() - н))

    def уборка_объектов():
        н = time.time()
        удалить_тестовые(т)
        print("  (уборка объектов — %.2f с)" % (time.time() - н))

    т.убрать(уборка_пользователей, "пользователи ИБ и элементы Пользователи")
    т.убрать(уборка_объектов, "объекты сотрудников")
    # пользователи ИБ + элементы Пользователи — подготовка подключений, меряется вместе с ними вне бюджета
    н = time.time()
    свои = {имя: завести_пользователя(т, имя, роли_пользователя(c, имя)) for имя in (МЕНЕДЖЕР, РУКОВОДИТЕЛЬ)}
    т.вне_бюджета += time.time() - н
    print("  (конфигурация %s; завести двух пользователей — %.2f с, вне бюджета)" % (c.Метаданные.Имя, time.time() - н))

    # S07: карточка Пользователи по данным пользователя ИБ — только по идентификатору; одноимённая чужая
    # карточка (реквизит ИдентификаторПользователяИБ у хозяина есть) — не наша (было: поиск по имени)
    чужой = c.УЗ_Среда.ПользовательПоДаннымИБ(c.String(c.NewObject("УникальныйИдентификатор")), МЕНЕДЖЕР, МЕНЕДЖЕР)
    т.проверить(чужой.Пустая(), "S07: пользователь ИБ без карточки не получает одноимённую чужую карточку",
                c.String(чужой))
    пользователь_ИБ = c.ПользователиИнформационнойБазы.НайтиПоИмени(МЕНЕДЖЕР)
    свой = c.УЗ_Среда.ПользовательПоДаннымИБ(c.String(пользователь_ИБ.УникальныйИдентификатор), "другое имя", "другое имя")
    т.проверить(c.String(свой.УникальныйИдентификатор()) == c.String(свои[МЕНЕДЖЕР].УникальныйИдентификатор()),
                "S07: карточка находится по идентификатору пользователя ИБ, имя не важно")

    # ставка педагога — справочник руководителя; её заводит администратор теста, руководитель заводит свою ниже
    ставка = c.Справочники.УЗ_СтавкиПедагогов.СоздатьЭлемент()
    ставка.Наименование = "%s %d" % (МЕТКА, СТАВКА)
    ставка.ОплатаЗаЗанятие = СТАВКА
    ставка.Записать()
    чужое = подготовить_чужое(т, свои, ставка.Ссылка)
    # сеансы по очереди, не одновременно: два лишних сеанса в одном процессе исчерпывали лицензии ключа
    # защиты при параллельных прогонах других баз («Ключ защиты программы больше не доступен», 28.09.2026)
    данные = день_менеджера(т, свои[МЕНЕДЖЕР], c.String(ставка.Ссылка.УникальныйИдентификатор()), чужое)
    напоминание = т.выбрать("ВЫБРАТЬ О.Завершено КАК Завершено ИЗ РегистрСведений.УЗ_Оповещения КАК О "
                            "ГДЕ О.Источник = &И", И=ставка.Ссылка)
    т.проверить(напоминание.Количество() == 1 and not напоминание.Получить(0).Завершено,
                "S06: напоминание руководителя после попытки менеджера не завершено")
    день_руководителя(т, свои[РУКОВОДИТЕЛЬ], данные)


def подготовить_чужое(т, свои, ставка):
    """Под администратором — то, чего менеджер видеть и трогать не должен (S04, S06):
    непроведённый расчёт зарплаты (в общем журнале), ПКО 40-дневной давности (касса старше его недели —
    ему задан скользящий запрет 7 дней) и напоминание руководителю. → идентификаторы строками."""
    c = т.c
    сегодня = datetime.date.today()
    давно = сегодня - datetime.timedelta(days=40)
    расчет = c.Документы.УЗ_РасчетЗарплаты.СоздатьДокумент()
    расчет.Дата = дата(сегодня.year, сегодня.month, сегодня.day, 8)
    расчет.Комментарий = МЕТКА
    расчет.Записать(c.РежимЗаписиДокумента.Запись)
    старый = c.Документы.УЗ_ПриходДенег.СоздатьДокумент()
    старый.Дата = дата(давно.year, давно.month, давно.day, 9)
    старый.СуммаДокумента = 777
    старый.Комментарий = МЕТКА
