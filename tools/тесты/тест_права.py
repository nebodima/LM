# ───────────────────────── журнал регистрации: отказы прав ─────────────────────────

def _журнал(база):
    return os.path.join(база, "1Cv8Log")


def позиция_журнала(база):
    """Размеры файлов журнала сейчас — читать потом только новое."""
    return {п: os.path.getsize(п) for п in glob.glob(os.path.join(_журнал(база), "*.lgp"))}


def отказы_прав(база, позиция, пользователь=ИМЯ):
    """Отказы прав пользователя с позиции: список строк «Право: Объект» в порядке появления."""
    try:
        словарь = open(os.path.join(_журнал(база), "1Cv8.lgf"), encoding="utf-8-sig", errors="replace").read()
    except OSError:
        return ["(журнал регистрации не найден: %s)" % _журнал(база)]
    события = {и: имя for имя, и in re.findall(r'^\{4,"([^"]*)",(\d+)\}', словарь, re.M)}
    метаданные = {и: имя for имя, и in re.findall(r'^\{5,[0-9a-f-]+,"([^"]*)",(\d+)\}', словарь, re.M)}
    пользователи = {и for имя, и in re.findall(r'^\{1,[0-9a-f-]+,"([^"]*)",(\d+)\}', словарь, re.M) if имя == пользователь}
    отказ = {и for и, имя in события.items() if имя == "_$Access$_.AccessDenied"}
    итог = []
    for файл in sorted(glob.glob(os.path.join(_журнал(база), "*.lgp"))):
        with open(файл, "rb") as ф:
            ф.seek(позиция.get(файл, 0))
            текст = ф.read().decode("utf-8", errors="replace")
        for запись in re.split(r"(?m)^(?=\{\d{14},)", текст):
            шапка = re.match(r'\{\d{14},\w,\s*\{[^}]*\},(\d+),\d+,\d+,\d+,(\d+),\w,"(?:[^"]|"")*",(\d+),', запись, re.S)
            if not шапка or шапка.group(1) not in пользователи or шапка.group(2) not in отказ:
                continue
            хвост = re.search(r',\d+,\d+,\d+,\d+,(\d+)((?:,\d+)*),\s*\{[\d,]*\}\s*\},?\s*$', запись)
            номера = [шапка.group(3)] + (хвост.group(2).strip(",").split(",") if хвост and хвост.group(2) else [])
            объекты = [метаданные.get(н, н) for н in номера if н != "0"]
            права = re.findall(r'\{"S","((?:[^"]|"")*)"\}', запись)
            итог.append("%s: %s" % (", ".join(права) or "?", ", ".join(объекты) or "?"))
    return итог


# ───────────────────────── пользователь ИБ и элемент Пользователи ─────────────────────────

def роли_сотрудника(c):
    конфигурация = c.Метаданные.Имя
    if конфигурация not in РОЛИ_ХОЗЯИНА:
        raise RuntimeError("нет набора ролей для конфигурации %s — добавить в РОЛИ_ХОЗЯИНА" % конфигурация)
    return ОБЩИЕ_РОЛИ + РОЛИ_ХОЗЯИНА[конфигурация] + ["УЗ_ОсновнаяРоль"] + ТОЛЬКО_ДЛЯ_ТЕСТА


def элементы_пользователя(т, идентификатор):
    return [с.Ссылка for с in т.выбрать("ВЫБРАТЬ П.Ссылка КАК Ссылка ИЗ Справочник.Пользователи КАК П "
                                        "ГДЕ П.ИдентификаторПользователяИБ = &И", И=идентификатор)]


def удалить_сотрудника(т):
    """Пользователь ИБ, его элемент Пользователи и записи БСП о нём — всё, что осталось от прошлых прогонов."""
    c = т.c
    пользователь_ИБ = c.ПользователиИнформационнойБазы.НайтиПоИмени(ИМЯ)
    if пользователь_ИБ is None:
        return
    for ссылка in элементы_пользователя(т, пользователь_ИБ.УникальныйИдентификатор):
        for регистр, измерение in ЗАПИСИ_БСП:
            if c.Метаданные.РегистрыСведений.Найти(регистр) is None:
                continue
            набор = getattr(c.РегистрыСведений, регистр).СоздатьНаборЗаписей()
            getattr(набор.Отбор, измерение).Установить(ссылка)
            набор.ОбменДанными.Загрузка = True
            набор.Записать()
        объект = ссылка.ПолучитьОбъект()
        объект.ОбменДанными.Загрузка = True   # мимо подписок БСП: элемент тестовый
        объект.Удалить()
    пользователь_ИБ.Удалить()


def завести_сотрудника(т, роли):
    c = т.c
    пользователь_ИБ = c.ПользователиИнформационнойБазы.СоздатьПользователя()
    пользователь_ИБ.Имя = ИМЯ
    пользователь_ИБ.ПолноеИмя = ИМЯ
    пользователь_ИБ.АутентификацияСтандартная = True
    пользователь_ИБ.ПоказыватьВСпискеВыбора = False
    for роль in роли:
        пользователь_ИБ.Роли.Добавить(c.Метаданные.Роли.Найти(роль))
    пользователь_ИБ.Записать()
    # элемент Пользователи с ИдентификаторПользователяИБ — без него БСП не пустит сеанс. Обычная запись
    # в УНФ падает в ПерсональныеНастройкиРУНФ.ПриЗаписи («Не удалось определить имя пользователя ИБ»),
    # поэтому пишем в режиме загрузки: служебное БСП хозяина дозаполнит при входе
    элемент = c.Справочники.Пользователи.СоздатьЭлемент()
    элемент.Наименование = ИМЯ
    элемент.ИдентификаторПользователяИБ = пользователь_ИБ.УникальныйИдентификатор
    элемент.ОбменДанными.Загрузка = True
    # тестового пользователя не регистрировать к обмену (и без этого запись ~1 с дольше)
    элемент.ДополнительныеСвойства.Вставить("ОтключитьМеханизмРегистрацииОбъектов", True)
    элемент.ОбменДанными.Получатели.АвтоЗаполнение = False
    элемент.Записать()
    return элемент.Ссылка


