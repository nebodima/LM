"""Права рядового сотрудника: базовые роли хозяина + УЗ_ОсновнаяРоль, живой сеанс под ним.

Под администратором заводится пользователь ИБ «УЗ тест сотрудник» (без пароля, аутентификация 1С)
с ролями хозяина для рядового сотрудника (РОЛИ_ХОЗЯИНА, по конфигурации) + УЗ_ОсновнаяРоль и элемент
Справочник.Пользователи для него. Потом ВТОРОЕ COM-подключение под сотрудником:
  * читает организацию хозяина и её ИНН, находит себя в Пользователи (УЗ_Среда.ТекущийПользователь);
  * заводит ученика, педагога, предмет, тариф, абонемент;
  * проводит приход денег по абонементу и урок с учеником;
  * формирует отчёт на СКД и печать ПКО (менеджер печати документа; у хозяина с БСП — ещё и через
    УправлениеПечатью, как форма «Печать документов»);
  * пытается записать УЗ_НастройкиПочты (напрямую и через УЗ_Почта.СохранитьНастройки) и
    УЗ_ДатыЗапрета — ожидается отказ (PASS = отказ, и в журнале — отказ прав именно на этот регистр).
Каждый отказ прав диагностируется по журналу регистрации (событие _$Access$_.AccessDenied: какое
право на какой объект) — файл 1Cv8Log базы читается напрямую с позиции начала теста, без
ВыгрузитьЖурналРегистрации (по COM она медленная).

Уборка — под администратором: документы, справочники, элемент Пользователи и записи БСП о нём,
пользователь ИБ. Сотрудник физически ничего не удаляет (права на удаление у него нет по замыслу).
ЗапускВнешнегоСоединения выдаётся только ради COM-теста — покупателю сотруднику эта роль не нужна.

    python tools\\тесты\\тест_права.py --база=C:\\1c_bases\\UZ_UNF_B
    python tools\\прогон.py --база=C:\\1c_bases\\UZ_BP_B --пользователь=1 --тест=права

Мутация (27.09.2026): из УЗ_ОсновнаяРоль убран блок Document.УЗ_ПриходДенег → тест красный,
журнал показал «Добавление: Документ.УЗ_ПриходДенег». Первый прогон нашёл дыру роли: «Чтение:
РегистрСведений.УЗ_ВерсииДанных» — расширение из файла стоит в безопасном режиме, а в нём
УстановитьПривилегированныйРежим не действует; право добавлено в роль.

Бюджет 10 с без подключения сотрудника (сценарий 5–7 с). Вне бюджета, как подключение: заведение
пользователя ИБ с элементом Пользователи — в холодном сеансе администратора первая запись в
Справочник.Пользователи ~4,5 с (компиляция модулей БСП хозяина; ПараметрыСеанса ни при чём — 0,35 с),
в общем прогоне 0,6 с. Первый отчёт на СКД в сеансе сотрудника — 2,5–4 с (ФабрикаXDTO), остальные — сотые.
"""
