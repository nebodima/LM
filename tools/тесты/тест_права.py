def сформировать_скд(c, отчет, вариант=None):
    """вариант — имя варианта настроек схемы (по умолчанию — первый, как открывает пользователь)."""
    if вариант:
        найден = [в for в in отчет.СхемаКомпоновкиДанных.ВариантыНастроек if в.Имя == вариант]
        отчет.КомпоновщикНастроек.ЗагрузитьНастройки(найден[0].Настройки)
    макет = c.NewObject("КомпоновщикМакетаКомпоновкиДанных").Выполнить(
        отчет.СхемаКомпоновкиДанных, отчет.КомпоновщикНастроек.ПолучитьНастройки())
    процессор = c.NewObject("ПроцессорКомпоновкиДанных")
    процессор.Инициализировать(макет)
    документ = c.NewObject("ТабличныйДокумент")
    вывод = c.NewObject("ПроцессорВыводаРезультатаКомпоновкиДанныхВТабличныйДокумент")
    вывод.УстановитьДокумент(документ)
    вывод.Вывести(процессор)
    return документ


def перенести(куда, коллекция, вид, ссылка, откуда):
    """Ссылка другого COM-соединения → ссылка этого (по уникальному идентификатору)."""
    ид = откуда.String(ссылка.УникальныйИдентификатор())
    return getattr(getattr(куда, коллекция), вид).ПолучитьСсылку(куда.NewObject("УникальныйИдентификатор", ид))


class Сотрудник:
    """Сеанс сотрудника и его шаги: удачный (шаг) и ожидаемый отказ (запрещено), оба — с журналом регистрации."""

    def __init__(self, т, имя, кто):
        self.т = т
        self.имя = имя
        self.кто = кто
        self.c = т.подключить(имя)
        self.первый_скд = True

    def шаг(self, что, действие):
        """Действие сотрудника; при ошибке — текст платформы и отказы прав из журнала."""
        т = self.т
        нач = позиция_журнала(т.база)
        н = time.time()
        try:
            итог = действие()
            т.проверить(True, "%s: %s (%.2f с)" % (self.кто, что, time.time() - н))
            return итог
        except Exception as е:
            отказы = отказы_прав(т.база, нач, self.имя)
            т.проверить(False, "%s: %s" % (self.кто, что), "%s%s" % (
                текст_ошибки(е, 200), "; журнал — не хватило прав: " + "; ".join(отказы) if отказы else ""))
            return None

    def запрещено(self, что, действие, объект):
        """Ожидаемый отказ: действие падает И журнал показывает отказ прав именно на этот объект."""
        т = self.т
        нач = позиция_журнала(т.база)
        try:
            действие()
            т.проверить(False, "%s — запрещено: %s" % (self.кто, что), "прошло — право у роли есть")
        except Exception as е:
            отказы = отказы_прав(т.база, нач, self.имя)
            т.проверить(any(объект in о for о in отказы), "%s — запрещено: %s" % (self.кто, что),
                        "ошибка: %s; журнал: %s" % (текст_ошибки(е, 150), "; ".join(отказы) or "отказа прав нет"))

    def скд(self, имя):
        """Отчёт на СКД. Первый в сеансе (2,5–4 с: платформа строит ФабрикуXDTO по метаданным хозяина) —
        разовая цена сеанса, как подключение: вне бюджета."""
        н = time.time()
        итог = self.шаг("формирует отчёт %s (СКД)" % имя, lambda: сформировать_скд(self.c, getattr(self.c.Отчеты, имя).Создать()))
        if self.первый_скд:
            self.первый_скд = False
            self.т.вне_бюджета += time.time() - н
        return итог

    def свой_пользователь(self, свой):
        """УЗ_Среда.ТекущийПользователь — свой элемент справочника Пользователи (свой — ссылка администратора)."""
        с = self.c.УЗ_Среда.ТекущийПользователь()
        self.т.проверить(self.c.String(с.УникальныйИдентификатор()) == self.т.c.String(свой.УникальныйИдентификатор()),
                         "%s: ТекущийПользователь — свой элемент справочника Пользователи" % self.кто, self.c.String(с))

    def ид(self, ссылка):
        return self.c.String(ссылка.УникальныйИдентификатор())

    def ссылка(self, коллекция, вид, ид):
        """Ссылка этого сеанса по уникальному идентификатору (ссылки разных COM-соединений не смешивать)."""
        return getattr(getattr(self.c, коллекция), вид).ПолучитьСсылку(self.c.NewObject("УникальныйИдентификатор", ид))

    def закрыть(self):
        """Отпустить COM-сеанс: иначе он живёт до сборки мусора и закрывается посреди следующих тестов
        (процесс прогона падал 0xC0000409), а одновременные сеансы занимают лицензии ключа защиты.
        Завершение сеанса платформой — 1,1–1,3 с (замер 29.09.2026, UZ_UNF_E) — цена сеанса, как подключение:
        вне бюджета (печатается)."""
        н = time.time()
        self.c = None
        gc.collect()
        сек = time.time() - н
        self.т.вне_бюджета += сек
        print("  (завершение сеанса «%s» %.1f с — вне бюджета)" % (self.имя, сек))


