# ───────────────────────── журнал регистрации: отказы прав ─────────────────────────

def _журнал(база):
    return os.path.join(база, "1Cv8Log")


def позиция_журнала(база):
    """Размеры файлов журнала сейчас — читать потом только новое."""
    return {п: os.path.getsize(п) for п in glob.glob(os.path.join(_журнал(база), "*.lgp"))}


def отказы_прав(база, позиция, пользователь, до=None):
    """Отказы прав пользователя между позициями журнала (до=None — до конца): строки «Право: Объект»."""
    try:
        словарь = open(os.path.join(_журнал(база), "1Cv8.lgf"), encoding="utf-8-sig", errors="replace").read()
    except OSError:
        return ["(журнал регистрации не найден: %s)" % _журнал(база)]
    события = {и: имя for имя, и in re.findall(r'^\{4,"([^"]*)",(\d+)\}', словарь, re.M)}
    метаданные = {и: имя for имя, и in re.findall(r'^\{5,[0-9a-f-]+,"([^"]*)",(\d+)\}', словарь, re.M)}
    пользователи = {и for имя, и in re.findall(r'^\{1,[0-9a-f-]+,"([^"]*)",(\d+)\}', словарь, re.M) if имя == пользователь}
    отказ = {и for и, имя in события.items() if имя == "_$Access$_.AccessDenied"}
    итог = []
    for файл in sorted(glob.glob(os.path.join(_журнал(база), "*.lgp"))):
        with open(файл, "rb") as ф:
            начало = позиция.get(файл, 0)
            ф.seek(начало)
            сколько = -1 if до is None or файл not in до else max(0, до[файл] - начало)
            текст = ф.read(сколько).decode("utf-8", errors="replace")
        for запись in re.split(r"(?m)^(?=\{\d{14},)", текст):
            шапка = re.match(r'\{\d{14},\w,\s*\{[^}]*\},(\d+),\d+,\d+,\d+,(\d+),\w,"(?:[^"]|"")*",(\d+),', запись, re.S)
            if not шапка or шапка.group(1) not in пользователи or шапка.group(2) not in отказ:
                continue
            хвост = re.search(r',\d+,\d+,\d+,\d+,(\d+)((?:,\d+)*),\s*\{[\d,]*\}\s*\},?\s*$', запись)
            номера = [шапка.group(3)] + (хвост.group(2).strip(",").split(",") if хвост and хвост.group(2) else [])
            объекты = [метаданные.get(н, н) for н in номера if н != "0"]
            права = re.findall(r'\{"S","((?:[^"]|"")*)"\}', запись)
            итог.append("%s: %s" % (", ".join(права) or "?", ", ".join(объекты) or "?"))
    return итог


