"""Аудит данных УЗ_ext: регистры против документов, ссылки в никуда (по образцу com_аудит_данных ПЛ).

На тестовой базе UZ_UNF_B в отчётах всплывало «<Объект не найден>»: в данных лежали ссылки на
удалённые объекты. Компиляция, офлайн-аудиты и функциональные тесты этого не видят — это
состояние данных, а не кода. Тест ничего не меняет в базе (самопроверка — в транзакции с откатом)
и проверяет три инварианта по метаданным расширения (всё с префиксом УЗ_, без списков руками):

  1. у каждого ПРОВЕДЁННОГО документа УЗ, у которого есть регистры движений, есть хоть одна запись
     в них (проведён, а движений нет — отчёты его не видят);
  2. у каждой записи регистров, подчинённых регистратору, регистратор жив (документ существует)
     и проведён (движения непроведённого документа остаются в остатках);
  3. в регистрах, документах (шапка и табличные части) и справочниках УЗ нет ссылок на
     несуществующие элементы справочников и документы — источник «<Объект не найден>».

Самопроверка (детектор обязан краснеть): в транзакции подкладываются запись цен тарифа со ссылкой
на несуществующий тариф, запись кассы с несуществующим регистратором и снятые движения
проведённого документа — каждый детектор должен увидеть ровно на одну беду больше; затем откат.

    python tools\\тесты\\тест_аудит_данных.py --база=C:\\1c_bases\\UZ_UNF_B
    python tools\\прогон.py --база=C:\\1c_bases\\UZ_UNF_B --пользователь=Администратор --тест=аудит_данных
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить, дата  # noqa: E402

ПРЕФИКС = "УЗ_"
ПОРЦИЯ = 50                      # подзапросов в одном ОБЪЕДИНИТЬ ВСЕ
ССЫЛОЧНЫЕ = ("Справочник.", "Документ.")


def _свои(коллекция):
    return [о for о in коллекция if о.Имя.startswith(ПРЕФИКС)]


def _выбрать(c, текст):
    з = c.NewObject("Запрос")
    з.Текст = текст
    return з.Выполнить().Выгрузить()


def _строки(таблица):
    return [таблица.Получить(н) for н in range(таблица.Количество())]


def _куда(c, реквизит):
    """Полные имена ссылочных таблиц, на которые может указывать реквизит."""
    итог = []
    типы = реквизит.Тип.Типы()
    for н in range(типы.Количество()):
        мд = c.Метаданные.НайтиПоТипу(типы.Получить(н))
        if мд is not None:
            полное = мд.ПолноеИмя()
            if полное.startswith(ССЫЛОЧНЫЕ):
                итог.append(полное)
    return итог


def _поля_ссылок(c):
    """[(источник, поле, куда)] по всем своим объектам с данными."""
    мд = c.Метаданные
    поля = []

    def добавить(источник, коллекция):
        for р in коллекция:
            for куда in _куда(c, р):
                поля.append((источник, р.Имя, куда))

    for р in _свои(мд.РегистрыНакопления):
        источник = "РегистрНакопления." + р.Имя
        for к in (р.Измерения, р.Ресурсы, р.Реквизиты):
            добавить(источник, к)
    for р in _свои(мд.РегистрыСведений):
        источник = "РегистрСведений." + р.Имя
        for к in (р.Измерения, р.Ресурсы, р.Реквизиты):
            добавить(источник, к)
    for вид, коллекция in (("Документ", мд.Документы), ("Справочник", мд.Справочники)):
        for о in _свои(коллекция):
            источник = "%s.%s" % (вид, о.Имя)
            добавить(источник, о.Реквизиты)
            for тч in о.ТабличныеЧасти:
                добавить("%s.%s" % (источник, тч.Имя), тч.Реквизиты)
    return поля


def битые_ссылки(c, поля):
    """{«источник.поле → куда»: число записей со ссылкой на несуществующий объект}."""
    итог = {}
    for н in range(0, len(поля), ПОРЦИЯ):
        части = []
        for источник, поле, куда in поля[н:н + ПОРЦИЯ]:
            части.append(
                'ВЫБРАТЬ "%s.%s → %s" КАК Место, КОЛИЧЕСТВО(*) КАК Битых\n'
                "ИЗ %s КАК Т ЛЕВОЕ СОЕДИНЕНИЕ %s КАК Цель ПО Т.%s = Цель.Ссылка\n"
                "ГДЕ Т.%s ССЫЛКА %s И Т.%s <> ЗНАЧЕНИЕ(%s.ПустаяСсылка) И Цель.Ссылка ЕСТЬ NULL"
                % (источник, поле, куда, источник, куда, поле, поле, куда, поле, куда))
        for с in _строки(_выбрать(c, "\nОБЪЕДИНИТЬ ВСЕ\n".join(части))):
            итог[с.Место] = int(с.Битых)
    return итог


def _кто(c, ссылка, тип):
    """«Документ.УЗ_Урок bb77e865…» — у удалённого объекта представление «<Объект не найден>» ничего не говорит."""
    мд = c.Метаданные.НайтиПоТипу(тип)
    return "%s %s" % (мд.ПолноеИмя() if мд is not None else "?", c.String(ссылка.УникальныйИдентификатор())[:8])


def регистраторы(c):
    """{регистр: (мёртвых регистраторов, непроведённых регистраторов, [примеры])} — регистры накопления."""
    итог = {}
    for р in _свои(c.Метаданные.РегистрыНакопления):
        имя = "РегистрНакопления." + р.Имя
        таблица = _выбрать(c, "ВЫБРАТЬ РАЗЛИЧНЫЕ Р.Регистратор КАК Регистратор, ТИПЗНАЧЕНИЯ(Р.Регистратор) КАК Тип,\n"
                              "  ВЫБОР КОГДА Р.Регистратор.Ссылка ЕСТЬ NULL ТОГДА 1 ИНАЧЕ 0 КОНЕЦ КАК Мёртвый,\n"
                              "  ВЫБОР КОГДА Р.Регистратор.Проведен = ЛОЖЬ ТОГДА 1 ИНАЧЕ 0 КОНЕЦ КАК НеПроведён\n"
                              "ИЗ %s КАК Р\n"
                              "ГДЕ Р.Регистратор.Ссылка ЕСТЬ NULL ИЛИ Р.Регистратор.Проведен = ЛОЖЬ" % имя)
        строки = _строки(таблица)
        итог[имя] = (sum(int(с.Мёртвый) for с in строки), sum(int(с.НеПроведён) for с in строки),
                     [_кто(c, с.Регистратор, с.Тип) for с in строки[:3]])
    return итог


def без_движений(c):
    """{документ: [проведённые без единой записи в регистрах движений]}."""
    итог = {}
    for д in _свои(c.Метаданные.Документы):
        регистры = [р.ПолноеИмя() for р in д.Движения]
        if not регистры:
            continue
        подзапрос = "\nОБЪЕДИНИТЬ ВСЕ\n".join("ВЫБРАТЬ Р.Регистратор ИЗ %s КАК Р" % р for р in регистры)
        таблица = _выбрать(c, "ВЫБРАТЬ Д.Ссылка КАК Ссылка ИЗ Документ.%s КАК Д\n"
                              "ГДЕ Д.Проведен И НЕ Д.Ссылка В (%s)" % (д.Имя, подзапрос))
        итог["Документ." + д.Имя] = [c.String(с.Ссылка) for с in _строки(таблица)]
    return итог


def самопроверка(т, поля):
    """В транзакции подкладываем по одной беде на каждый детектор и откатываем."""
    c = т.c
    было_ссылок = битые_ссылки(c, поля)
    было_рег = регистраторы(c)
    было_движ = без_движений(c)
    образец = _выбрать(c, "ВЫБРАТЬ ПЕРВЫЕ 1 Р.Регистратор КАК Регистратор ИЗ РегистрНакопления.УЗ_Касса КАК Р\n"
                          "ГДЕ Р.Регистратор ССЫЛКА Документ.УЗ_ПриходДенег И Р.Регистратор.Проведен")
    c.НачатьТранзакцию()
    try:
        запись = c.РегистрыСведений.УЗ_ЦеныТарифов.СоздатьМенеджерЗаписи()
        запись.Период = дата(2001, 1, 1)
        запись.Тариф = c.Справочники.УЗ_Тарифы.ПолучитьСсылку(c.NewObject("УникальныйИдентификатор"))
        запись.Сумма = 1
        запись.Записать()
        призрак = c.Документы.УЗ_ПриходДенег.ПолучитьСсылку(c.NewObject("УникальныйИдентификатор"))
        набор = c.РегистрыНакопления.УЗ_Касса.СоздатьНаборЗаписей()
        набор.Отбор.Регистратор.Установить(призрак)
        строка = набор.Добавить()
        строка.Период = дата(2001, 1, 1)
        строка.Сумма = 1
        набор.Записать()
        документ = образец.Получить(0).Регистратор if образец.Количество() else None
        if документ is not None:
            for р in документ.Метаданные().Движения:
                пустой = getattr(c.РегистрыНакопления, р.Имя).СоздатьНаборЗаписей()
                пустой.Отбор.Регистратор.Установить(документ)
                пустой.Записать()
        стало_ссылок = битые_ссылки(c, поля)
        стало_рег = регистраторы(c)
        стало_движ = без_движений(c)
    finally:
        if c.ТранзакцияАктивна():
            c.ОтменитьТранзакцию()
    ключ = next((к for к in стало_ссылок if к.startswith("РегистрСведений.УЗ_ЦеныТарифов.Тариф ")), None)
    т.проверить(ключ is not None and стало_ссылок[ключ] == было_ссылок.get(ключ, 0) + 1,
                "самопроверка: подложенная ссылка на несуществующий тариф найдена ровно одна",
                "%s: было %s, стало %s" % (ключ, было_ссылок.get(ключ), стало_ссылок.get(ключ)))
    т.проверить(стало_рег["РегистрНакопления.УЗ_Касса"][0] == было_рег["РегистрНакопления.УЗ_Касса"][0] + 1,
                "самопроверка: запись кассы с несуществующим регистратором найдена",
                "было %s, стало %s" % (было_рег["РегистрНакопления.УЗ_Касса"][0],
                                       стало_рег["РегистрНакопления.УЗ_Касса"][0]))
    if документ is not None:
        т.проверить(len(стало_движ["Документ.УЗ_ПриходДенег"]) == len(было_движ["Документ.УЗ_ПриходДенег"]) + 1,
                    "самопроверка: проведённый приход денег со снятыми движениями найден")
    else:
        print("  (самопроверка «проведён без движений» пропущена: в базе нет проведённого прихода денег "
              "с движениями по кассе)")


def сценарий(т):
    c = т.c
    поля = _поля_ссылок(c)
    самопроверка(т, поля)

    for документ, список in sorted(без_движений(c).items()):
        т.проверить(not список, "%s: у каждого проведённого есть движения" % документ,
                    "без движений %d: %s" % (len(список), "; ".join(список[:3])))
    for регистр, (мёртвых, непроведённых, примеры) in sorted(регистраторы(c).items()):
        т.проверить(not мёртвых and not непроведённых, "%s: у движений живой проведённый регистратор" % регистр,
                    "удалён: %d, не проведён: %d; например %s" % (мёртвых, непроведённых, "; ".join(примеры)))
    битые = битые_ссылки(c, поля)
    по_источнику = {}
    for где, сколько in битые.items():
        источник = где.split(" → ")[0].rsplit(".", 1)[0]
        по_источнику.setdefault(источник, []).append((где, сколько))
    for источник, список in sorted(по_источнику.items()):
        плохие = [(г, с) for г, с in список if с]
        т.проверить(not плохие, "%s: нет ссылок на несуществующие объекты" % источник,
                    "; ".join("%s — %d" % (г.split(".", 2)[-1] if г.count(".") > 1 else г, с) for г, с in плохие[:4]))
    print("  (ссылочных полей проверено: %d)" % len(поля))


if __name__ == "__main__":
    запустить("аудит_данных", сценарий)
