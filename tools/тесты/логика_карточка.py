"""Логика «карточка ученика» (docs/логики/карточка_ученика.md, сценарии с числами; решения В12, В18, В19).

  1. В12 (Р4, сценарий 9): аванс 8 000 в организации А и долг 1 000 в Б по гитаре.
     * карточка — строки «организация × предмет» (УЗ_Сервер.ОстаткиДенегУченика): А +8 000, Б −1 000; итог каждой
       организации совпадает с УЗ_Сервер.ОстатокДенегУченика (одна формула в карточке, уроке, ПКО, панели);
     * списки учеников (формы списка, выбора, подбора): запрос динамического списка из src_ext выполняется с
       параметрами, которые ставит форма (УЗ_Сервер.УстановитьПараметрыОстатка), — в А +8 000, в Б −1 000
       (было: +7 000 одной строкой); колонка называется «Остаток денег»;
     * диаграмма должников журнала уроков (УЗ_Сервер.Должники): одна строка — Б, 1 000 (было: ни одной).
  2. Возраст вычисляется, не хранится (Р7, сценарий 3): ДР 15.10.2015 — на 16.10.2026 11 лет, на 01.09.2026 — 10;
     ДР 29.02.2016 — 28.02.2027 ещё 10, 01.03.2027 уже 11; после записи карточки хранимый «Возраст» — 0; колонка
     «Возраст» списка — от даты рождения на &Сегодня.
  3. Дни рождения (оповещения, сценарии 15–16): 25.12.2026 — ДР 03.01.2010 через 9 дней, исполнится 17;
     20.02.2027 — ДР 29.02.2012 через 9 дней (1 марта), исполнится 15; выбывший в список не попадает.
  4. «По тарифу» (сценарии 5–8): тариф 12 000/8 уроков, остаток 4 500 — 3 урока; 10 000/10 ч, остаток 2 500 —
     2,5 ч; тариф с историей цен (карточка 0, цена 8 000/8 в регистре) и остатком 3 000 — 3 урока (было: пусто);
     тариф 5 000 без уроков и часов — без деления на ноль, уроки не считаются.
  5. В18/В19 и роль при выборе (Р8, сценарий 15): у ученика реквизит «Выбыл»; параметры выбора в базе —
     ученик урока: не педагог и не выбывший, педагог урока и группы — только педагог; флажков «SMS» и «по
     телефону» в формах карточки и списков нет.
Красное на старом коде (28.09.2026, до правки): 1 (+7 000, функций нет), 2, 3 (нет функций, хранимый возраст),
4 (нет функции), 5 (нет реквизита и параметров выбора, флажки в форме).

    python tools\\тесты\\логика_карточка.py --база=C:\\1c_bases\\UZ_UNF_A
"""
import os
import re
import sys
from xml.sax.saxutils import unescape

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import дата, запустить, текст_ошибки  # noqa: E402
from _деньги import Данные  # noqa: E402
from фабрика import Фабрика  # noqa: E402

МЕТКА = "_Тест логика карточки"
ИСХОДНИКИ = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "src_ext"))
ФОРМЫ_СПИСКОВ = ("ФормаСписка", "ФормаВыбора", "ФормаПодбора")


def запрос_формы(форма, реквизит="Список"):
    """QueryText динамического списка формы справочника УЗ_ФизЛица из src_ext (как его выполнит платформа)."""
    путь = os.path.join(ИСХОДНИКИ, "Catalogs", "УЗ_ФизЛица", "Forms", форма, "Ext", "Form.xml")
    текст = open(путь, encoding="utf-8-sig").read()
    м = re.search(r'<Attribute name="%s".*?<QueryText>(.*?)</QueryText>' % реквизит, текст, re.S)
    return (unescape(м.group(1)) if м else None), текст


def попытка(действие):
    try:
        return действие()
    except Exception as е:
        return "ошибка: " + текст_ошибки(е, 160)


def сценарий(т):
    c = т.c
    д = Данные(т, МЕТКА)
    ф = Фабрика(т, МЕТКА)
    орг_а = ф.организация("Студия А")
    орг_б = ф.организация("Студия Б")
    ученик = д.элемент("УЗ_ФизЛица", "ученик Авансов")
    гитара = д.элемент("УЗ_ПредметыОбучения", "гитара")
    д.движения("УЗ_СписанияСуммЗаУроки", д.регистратор(), [
        ("+", дата(2026, 9, 1, 10), {"Клиент": ученик, "ПредметОбучения": гитара, "Сумма": 8000, "Организация": орг_а}),
        ("-", дата(2026, 9, 1, 10), {"Клиент": ученик, "ПредметОбучения": гитара, "Сумма": 1000, "Организация": орг_б})])

    # ── 1. В12: карточка ──
    строки = попытка(lambda: [(c.String(с.Организация), c.String(с.ПредметОбучения), float(с.Остаток))
                               for с in c.УЗ_Сервер.ОстаткиДенегУченика(ученик)])
    ждём = sorted([(c.String(орг_а), c.String(гитара), 8000.0), (c.String(орг_б), c.String(гитара), -1000.0)])
    т.проверить(isinstance(строки, list) and sorted(строки) == ждём,
                "В12 карточка: строки «организация × предмет» — А +8 000, Б −1 000 (было общее +7 000)", строки)
    for орг in (орг_а, орг_б):
        итог = sum(с[2] for с in (строки if isinstance(строки, list) else []) if с[0] == c.String(орг))
        т.проверить(итог == float(c.УЗ_Сервер.ОстатокДенегУченика(ученик, орг)),
                    "итог карточки в %s = УЗ_Сервер.ОстатокДенегУченика (одна формула)" % c.String(орг), итог)
    модуль = open(os.path.join(ИСХОДНИКИ, "Catalogs", "УЗ_ФизЛица", "Forms", "ФормаЭлемента", "Ext", "Form",
                               "Module.bsl"), encoding="utf-8-sig").read()
    тело = re.search(r"Процедура ЗаполнитьИтоги\(\).*?КонецПроцедуры", модуль, re.S)
    т.проверить(тело is not None and "УЗ_Сервер.ОстатокДенегУченика(" in тело.group(0)
                and "РегистрНакопления" not in тело.group(0),
                "форма карточки: остатки — общими функциями УЗ_Сервер, своего запроса к регистру нет")

    # ── 1. В12: списки учеников, выбор, подбор ──
    for форма in ФОРМЫ_СПИСКОВ:
        текст, xml = запрос_формы(форма)
        if текст is None:
            т.проверить(False, "%s: запрос списка найден" % форма)
            continue
        значения = {}
        for орг in (орг_а, орг_б):
            з = c.NewObject("Запрос")
            з.Текст = текст + "\nГДЕ СправочникУЗ_ФизЛица.Ссылка = &Ученик"
            з.УстановитьПараметр("Ученик", ученик)
            з.УстановитьПараметр("Организация", орг)
            з.УстановитьПараметр("ВсеОрганизации", False)
            з.УстановитьПараметр("Сегодня", дата(2026, 9, 28))
            в = попытка(lambda: [float(с.Долг or 0) for с in з.Выполнить().Выгрузить()])
            значения[c.String(орг)] = в
        т.проверить(значения == {c.String(орг_а): [8000.0], c.String(орг_б): [-1000.0]},
                    "В12 %s: колонка остатка — по организации: А +8 000, Б −1 000 (было +7 000)" % форма, значения)
        модуль_формы = os.path.join(ИСХОДНИКИ, "Catalogs", "УЗ_ФизЛица", "Forms", форма, "Ext", "Form", "Module.bsl")
        есть = os.path.isfile(модуль_формы) and "УЗ_Сервер.УстановитьПараметрыОстатка(Список)" in open(
            модуль_формы, encoding="utf-8-sig").read() and "ПриСозданииНаСервере" in xml
        т.проверить(есть, "%s: параметры остатка ставит ПриСозданииНаСервере формы" % форма)
        т.проверить("<v8:content>Остаток денег</v8:content>" in xml and "ОповеститьПоSMS" not in xml
                    and "ОповеститьПоТелефону" not in xml,
                    "%s: колонка «Остаток денег», полей SMS/телефон нет (В19)" % форма)
    заголовок = попытка(lambda: c.УЗ_Сервер.ОрганизацияОстатков())
    print("  (организация остатков списков в этой базе: %s)" % (c.String(заголовок) if заголовок is not None else "все"))

    # ── 1. В12: диаграмма должников ──
    должники = попытка(lambda: [(c.String(с.Организация), float(с.Долг)) for с in c.УЗ_Сервер.Должники(т.массив(ученик))])
    т.проверить(должники == [(c.String(орг_б), 1000.0)],
                "В12 диаграмма должников: ученик — должник только в Б, 1 000 (было: не должник, +7 000)", должники)

    # ── 2. возраст ──
    возраст = lambda др, на: попытка(lambda: int(c.УЗ_ОбщийКлиентСервер.ВозрастНаДату(др, на)))  # noqa: E731
    т.проверить((возраст(дата(2015, 10, 15), дата(2026, 10, 16)), возраст(дата(2015, 10, 15), дата(2026, 9, 1)))
                == (11, 10), "возраст: ДР 15.10.2015 — 16.10.2026 11 лет, 01.09.2026 10 лет",
                (возраст(дата(2015, 10, 15), дата(2026, 10, 16)), возраст(дата(2015, 10, 15), дата(2026, 9, 1))))
    т.проверить((возраст(дата(2016, 2, 29), дата(2027, 2, 28)), возраст(дата(2016, 2, 29), дата(2027, 3, 1)))
                == (10, 11), "возраст: ДР 29.02.2016 — 28.02.2027 ещё 10, 01.03.2027 уже 11",
                (возраст(дата(2016, 2, 29), дата(2027, 2, 28)), возраст(дата(2016, 2, 29), дата(2027, 3, 1))))
    о = ученик.ПолучитьОбъект()
    о.ДатаРождения = дата(2015, 10, 15)
    о.Возраст = 10
    о.Записать()
    т.проверить(int(ученик.ПолучитьОбъект().Возраст) == 0, "возраст при известной дате рождения не хранится",
                ученик.ПолучитьОбъект().Возраст)
    текст, _ = запрос_формы("ФормаСписка")
    з = c.NewObject("Запрос")
    з.Текст = (текст or "ВЫБРАТЬ 1") + "\nГДЕ СправочникУЗ_ФизЛица.Ссылка = &Ученик"
    for имя, знач in (("Ученик", ученик), ("Организация", орг_а), ("ВсеОрганизации", False),
                      ("Сегодня", дата(2026, 10, 16))):
        з.УстановитьПараметр(имя, знач)
    в_списке = попытка(lambda: [int(с.Возраст) for с in з.Выполнить().Выгрузить()])
    т.проверить(в_списке == [11], "список учеников: «Возраст» на 16.10.2026 — 11 (от даты рождения)", в_списке)

    # ── 3. дни рождения ──
    именинник = д.элемент("УЗ_ФизЛица", "именинник", ДатаРождения=дата(2010, 1, 3))
    високосный = д.элемент("УЗ_ФизЛица", "високосный", ДатаРождения=дата(2012, 2, 29))
    выбывший = д.элемент("УЗ_ФизЛица", "выбывший", ДатаРождения=дата(2010, 1, 3), Выбыл=True) \
        if попытка(lambda: c.Метаданные.Справочники.УЗ_ФизЛица.Реквизиты.Найти("Выбыл")) is not None else None

    def дни(сегодня):
        итог = попытка(lambda: c.Справочники.УЗ_ФизЛица.ДниРождения(сегодня, 10))
        if isinstance(итог, str):
            return итог
        return {c.String(с.ФизЛицо): (int(с.ОсталосьДней), int(с.Исполнится)) for с in итог}
    д1 = дни(дата(2026, 12, 25))
    т.проверить(isinstance(д1, dict) and д1.get(c.String(именинник)) == (9, 17),
                "дни рождения 25.12.2026: ДР 03.01.2010 — через 9 дней, исполнится 17", д1 if isinstance(д1, str)
                else д1.get(c.String(именинник)))
    т.проверить(isinstance(д1, dict) and выбывший is not None and c.String(выбывший) not in д1,
                "дни рождения: выбывший не показывается")
    д2 = дни(дата(2027, 2, 20))
    т.проверить(isinstance(д2, dict) and д2.get(c.String(високосный)) == (9, 15),
                "дни рождения 20.02.2027: ДР 29.02.2012 — 1 марта, через 9 дней, исполнится 15",
                д2 if isinstance(д2, str) else д2.get(c.String(високосный)))

    # ── 4. остаток по тарифу ──
    def по_тарифу(имя, сумма_тарифа, уроков, часов, остаток, **реквизиты):
        тариф = д.элемент("УЗ_Тарифы", имя, Сумма=сумма_тарифа, КоличествоУроков=уроков, КоличествоЧасов=часов,
                          **реквизиты)
        return тариф

    т1 = по_тарифу("12000 за 8", 12000, 8, 0, 4500)
    т2 = по_тарифу("10000 за 10 ч", 10000, 0, 10, 2500)
    т3 = по_тарифу("история цен", 0, 0, 0, 3000, ИспользоватьИсториюЦен=True)
    ф.цена_тарифа(т3, дата(2026, 1, 1), 8000, уроков=8)
    т4 = по_тарифу("без уроков и часов", 5000, 0, 0, 1000)
    д.движения("УЗ_СписанияСуммЗаУроки", д.регистратор(), [
        ("+", дата(2026, 9, 1, 11), {"Клиент": ученик, "Тариф": тр, "Сумма": сумма, "Организация": орг_а})
        for тр, сумма in ((т1, 4500), (т2, 2500), (т3, 3000), (т4, 1000))])

    def единиц(тариф):
        р = попытка(lambda: c.Справочники.УЗ_ФизЛица.ОстатокПоТарифу(ученик, тариф, орг_а, дата(2026, 9, 28)))
        if isinstance(р, str):
            return р
        return (float(р.Остаток), None if р.Единиц is None else float(р.Единиц), р.ЕдиницаИзмерения)
    т.проверить(единиц(т1) == (4500.0, 3.0, "уроков"), "по тарифу 12 000/8 уроков, остаток 4 500 — 3 урока", единиц(т1))
    т.проверить(единиц(т2) == (2500.0, 2.5, "ч"), "по тарифу 10 000/10 ч, остаток 2 500 — 2,5 ч", единиц(т2))
    т.проверить(единиц(т3) == (3000.0, 3.0, "уроков"),
                "по тарифу с историей цен (8 000/8 на дату), остаток 3 000 — 3 урока (было пусто)", единиц(т3))
    т.проверить(единиц(т4) == (1000.0, None, ""), "тариф 5 000 без уроков и часов — без деления на ноль", единиц(т4))

    # ── 5. В18, В19, роль при выборе ──
    т.проверить(c.Метаданные.Справочники.УЗ_ФизЛица.Реквизиты.Найти("Выбыл") is not None,
                "В18: у физ. лица реквизит «Выбыл»")

    def параметры_выбора(реквизит):
        return sorted((п.Имя, bool(п.Значение)) for п in реквизит.ПараметрыВыбора)
    урок = c.Метаданные.Документы.УЗ_Урок
    т.проверить(параметры_выбора(урок.ТабличныеЧасти.Ученики.Реквизиты.Ученик)
                == [("Отбор.Выбыл", False), ("Отбор.ЭтоПедагог", False)],
                "ученик урока выбирается без педагогов и выбывших", параметры_выбора(урок.ТабличныеЧасти.Ученики.Реквизиты.Ученик))
    т.проверить(параметры_выбора(урок.Реквизиты.Педагог) == [("Отбор.ЭтоПедагог", True)],
                "педагог урока выбирается только из педагогов", параметры_выбора(урок.Реквизиты.Педагог))
    группа = c.Метаданные.Справочники.УЗ_ГруппыОбучения
    т.проверить(параметры_выбора(группа.Реквизиты.Педагог) == [("Отбор.ЭтоПедагог", True)],
                "педагог группы выбирается только из педагогов", параметры_выбора(группа.Реквизиты.Педагог))
    карточка = open(os.path.join(ИСХОДНИКИ, "Catalogs", "УЗ_ФизЛица", "Forms", "ФормаЭлемента", "Ext", "Form.xml"),
                    encoding="utf-8-sig").read()
    т.проверить("Объект.ОповеститьПоSMS" not in карточка and "Объект.ОповеститьПоТелефону" not in карточка
                and "<DataPath>Объект.Выбыл</DataPath>" in карточка,
                "В18/В19: в карточке флажок «Выбыл», флажков SMS и «по телефону» нет")


if __name__ == "__main__":
    запустить("логика_карточка", сценарий)
