"""Общие заготовки тестов логики абонементов и заморозок (тест_логика_абонементы*, тест_логика_заморозки*).

Вызов функции продукта через COM — вызов(): на старом коде новой функции нет, и сценарий не должен падать целиком
на первой же проверке — ошибка возвращается и становится красной проверкой (а не пропуском).
"""


def вызов(действие):
    """(значение, текст ошибки или None)."""
    from сеанс import текст_ошибки
    try:
        return действие(), None
    except Exception as е:
        return None, текст_ошибки(е)


def пустая_дата(c):
    """Пустая дата 1С: год 1 через COM не передать — собираем значение в 1С."""
    тип_дата = c.NewObject("ОписаниеТипов", "Дата").Типы().Получить(0)
    return c.XMLЗначение(тип_дата, "0001-01-01T00:00:00")


def время(c, час, минута=0):
    тип_дата = c.NewObject("ОписаниеТипов", "Дата").Типы().Получить(0)
    return c.XMLЗначение(тип_дата, "0001-01-01T%02d:%02d:00" % (час, минута))


def структура(c, **поля):
    с = c.NewObject("Структура")
    for к, в in поля.items():
        с.Вставить(к, в)
    return с


def строка(урок, номер=0):
    """Строка «Ученики» записанного урока (перечитанного объекта, не кэша ссылки)."""
    return урок.Ссылка.ПолучитьОбъект().Ученики.Получить(номер)


def есть_слово(сообщения, слово):
    return any(слово in текст for текст, _ in сообщения)


def пусто(ссылка):
    return ссылка is None or ссылка.Пустая()


def та_же(c, первая, вторая):
    """Одна ли это ссылка: COM-объекты «==» не сравнить — сравниваем уникальные идентификаторы."""
    if первая is None or вторая is None or isinstance(первая, str) or isinstance(вторая, str):
        return False
    return c.String(первая.УникальныйИдентификатор()) == c.String(вторая.УникальныйИдентификатор())


def абонемент_с_паузами(ф, ученик, имя, паузы, **реквизиты):
    """Абонемент с ТЧ «Приостановки» [(начало, возобновление или None)] → (ссылка или None, ошибка записи, сообщения)."""
    c = ф.c
    о = c.Справочники.УЗ_Абонемент.СоздатьЭлемент()
    о.Наименование = "%s %s" % (ф.метка, имя)
    поля = dict(ФизЛицо=ученик, Активный=True, ДатаНачала=ф.день(-40), ДатаАктивации=ф.день(-40),
                ДатаОкончания=ф.день(-10), КоличествоЗанятий=8, ЦенаАбонемента=6400)
    поля.update(реквизиты)
    for к, в in поля.items():
        setattr(о, к, в)
    for начало, возобновление in паузы:
        с = о.Приостановки.Добавить()
        с.ДатаПриостановки = начало
        с.ДатаВозобновления = возобновление if возобновление is not None else пустая_дата(c)
    c.ПолучитьСообщенияПользователю(True)
    ошибка = None
    try:
        о.Записать()
    except Exception as е:
        from сеанс import текст_ошибки
        ошибка = текст_ошибки(е)
    сообщения = [(" ".join(str(с.Текст).split()), str(с.Поле or "")) for с in c.ПолучитьСообщенияПользователю(True)]
    if о.Ссылка.Пустая():
        return None, ошибка, сообщения
    ссылка = о.Ссылка
    ф.т.убрать(lambda: ф.т.удалить_объект(ссылка), "абонемент %s" % имя, пакет=True)
    return ссылка, ошибка, сообщения
