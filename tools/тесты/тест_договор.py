"""Договор на оказание платных образовательных услуг (этап 2.1, часть 2; В43): документ «Договор обучения» и печать.

  * на основании ученика: обучающийся — он, заказчик — основной плательщик, стоимость — по тарифу ученика;
  * на основании абонемента: предмет, срок и цена абонемента;
  * отказы записи: нет обучающегося, абонемент другого ученика, абонемент другой организации (находка 8 аудита
    Codex 2.1: исполнитель договора — организация абонемента), конец обучения раньше начала;
  * заказчик = обучающийся — поле «Заказчик» очищается (взрослый заключает сам: «Заказчик, он же Обучающийся»);
  * печать: номер и дата договора, «об оказании платных образовательных услуг» у организации с лицензией
    (преамбула — лицензия и подписант, ч. 3 ст. 54 об индексации цены), стоимость прописью, отказ и возврат
    (ст. 32 Закона о защите прав потребителей, ст. 782 ГК РФ), реквизиты сторон: ИНН/КПП и банк исполнителя,
    паспорт и ИНН заказчика; обучающийся отдельным пунктом; у организации без лицензии — договор возмездного
    оказания услуг по обучению без пункта об индексации.

    python tools\\тесты\\тест_договор.py --база=C:\\1c_bases\\UZ_BP_E --пользователь=1
"""
# затрагивает: УЗ_ДоговорОбучения, УЗ_РеквизитыОрганизаций, УЗ_ДокументыФизЛиц, УЗ_Печать
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import дата, запустить  # noqa: E402
from фабрика import Фабрика  # noqa: E402

МЕТКА = "_Тест договор"


def сценарий(т):
    c = т.c
    ф = Фабрика(т, МЕТКА)
    ст = c.String

    def организация(имя, ИНН, **реквизиты_регистра):
        о = c.Справочники.Организации.СоздатьЭлемент()
        о.Наименование = "%s %s" % (МЕТКА, имя)
        о.ИНН, о.КПП = ИНН, "772501001"
        о.ОбменДанными.Загрузка = True
        о.Записать()
        ссылка = о.Ссылка
        т.убрать(lambda: т.удалить_объект(ссылка, загрузка=True), "организация %s" % имя, пакет=True)
        if реквизиты_регистра:
            з = c.РегистрыСведений.УЗ_РеквизитыОрганизаций.СоздатьМенеджерЗаписи()
            з.Организация = ссылка
            for к, в in реквизиты_регистра.items():
                setattr(з, к, в)
            з.Записать()

            def убрать():
                н = c.РегистрыСведений.УЗ_РеквизитыОрганизаций.СоздатьНаборЗаписей()
                н.Отбор.Организация.Установить(ссылка)
                н.Записать()
            т.убрать(убрать, "реквизиты организации %s" % имя, пакет=True)
        return ссылка

    орг = организация("с лицензией", "7701001236", НомерЛицензии="Л035-01234-77/00123456",
                      ДатаЛицензии=дата(2021, 3, 1), ЛицензиюВыдал="Департаментом образования",
                      Подписант="Сидорова Анна Петровна", ДолжностьПодписанта="директор", ОснованиеПолномочий="Устава",
                      Адрес="г. Москва, ул. Тестовая, д. 1", Телефон="+7 900 000-00-01",
                      ПлатежныеРеквизиты="р/с 40702810900000000001 в АО «Тест-Банк», БИК 044525000")
    без_лицензии = организация("без лицензии", "7701004567")

    мама = ф.элемент("УЗ_ФизЛица", "мама Кузнецова", Телефон="+7 900 000-00-02")
    данные = c.РегистрыСведений.УЗ_ДокументыФизЛиц.НовыеДанныеФизЛица()
    данные.КодВидаДокумента, данные.СерияНомерДокумента, данные.ДатаВыдачиДокумента = "21", "45 10 123456", дата(2010, 5, 20)
    c.РегистрыСведений.УЗ_ДокументыФизЛиц.ЗаписатьДанныеФизЛица(мама, данные)

    def убрать_документ():
        н = c.РегистрыСведений.УЗ_ДокументыФизЛиц.СоздатьНаборЗаписей()
        н.Отбор.ФизЛицо.Установить(мама)
        н.Записать()
    т.убрать(убрать_документ, "документ мамы", пакет=True)
    тариф = ф.элемент("УЗ_Тарифы", "урок 1 500")
    ф.цена_тарифа(тариф, дата(2020, 1, 1), 1500, уроков=1)
    о = c.Справочники.УЗ_ФизЛица.СоздатьЭлемент()
    о.Наименование = "%s ученик Кузнецов" % МЕТКА
    о.ДатаРождения = дата(2014, 4, 5)
    о.Тариф = тариф
    с = о.Плательщики.Добавить()
    с.Плательщик, с.КемПриходится, с.Основной = мама, "мама", True
    о.Записать()
    ученик = о.Ссылка
    т.убрать(lambda: т.удалить_объект(ученик), "ученик", пакет=True)
    другой = ф.ученик("другой ученик")
    предмет = ф.элемент("УЗ_ПредметыОбучения", "робототехника")
    абонемент = ф.абонемент(ученик, "абонемент 8 занятий", ПредметОбучения=предмет, Организация=орг,
                            ЦенаАбонемента=8000, КоличествоЗанятий=8, ДатаНачала=дата(2026, 9, 1),
                            ДатаОкончания=дата(2026, 12, 31))
    чужой_абонемент = ф.абонемент(другой, "абонемент другого", ПредметОбучения=предмет, Организация=орг,
                                  ЦенаАбонемента=100)
    договоры = c.Документы.УЗ_ДоговорОбучения

    def договор(основание, **поля):
        д = договоры.СоздатьДокумент()
        д.Заполнить(основание)
        д.Дата = ф.день(0, 10)
        д.Комментарий = МЕТКА
        for к, в in поля.items():
            setattr(д, к, в)
        ош, сообщ = ф.записать(д, "Запись")
        return д, (ош and " | ".join(м for м, _ in сообщ) or ош)

    # ── на основании ученика: заказчик — основной плательщик, стоимость — по тарифу ──
    д1, ош = договор(ученик, Организация=орг)
    т.проверить(ош is None and ст(д1.Обучающийся) == ст(ученик) and ст(д1.Заказчик) == ст(мама)
                and float(д1.Стоимость) == 1500 and "по тарифу" in д1.ОписаниеСтоимости and д1.Номер != ""
                and д1.ПорядокОплаты != "",
                "на основании ученика: обучающийся, заказчик — мама, 1 500 по тарифу, номер, порядок оплаты",
                "%s / %s / %s / %s" % (ош, ст(д1.Заказчик), д1.Стоимость, д1.ОписаниеСтоимости))
    # ── на основании абонемента ──
    д2, ош = договор(абонемент)
    т.проверить(ош is None and float(д2.Стоимость) == 8000 and "8 занятий" in д2.ОписаниеСтоимости
                and ст(д2.ПредметОбучения) == ст(предмет) and ст(д2.Организация) == ст(орг)
                and д2.ДатаОкончания.year == 2026 and д2.ДатаОкончания.month == 12 and ст(д2.Заказчик) == ст(мама),
                "на основании абонемента: 8 000 за 8 занятий, предмет, организация и срок абонемента",
                "%s / %s / %s" % (ош, д2.Стоимость, д2.ОписаниеСтоимости))

    # ── отказы и нормализация ──
    _, ош = договор(None, Организация=орг)
    т.проверить(ош is not None and "обучающегося" in ош, "без обучающегося — отказ", ош)
    _, ош = договор(ученик, Организация=орг, Абонемент=чужой_абонемент)
    т.проверить(ош is not None and "другого ученика" in ош, "абонемент другого ученика — отказ", ош)
    _, ош = договор(ученик, Организация=без_лицензии, Абонемент=абонемент)
    т.проверить(ош is not None and "организации" in ош and ст(орг) in ош,
                "находка 8: абонемент организации «с лицензией» в договоре организации «без лицензии» — отказ", ош)
    _, ош = договор(ученик, Организация=орг, ДатаНачала=дата(2026, 9, 1), ДатаОкончания=дата(2026, 8, 1))
    т.проверить(ош is not None and "раньше даты начала" in ош, "окончание раньше начала — отказ", ош)
    д3, ош = договор(другой, Организация=орг, Заказчик=другой)
    т.проверить(ош is None and д3.Заказчик.Пустая(), "заказчик = обучающийся — поле очищено (заключает сам)", ош)

    # ── печать ──
    р = c.УЗ_Печать.СформироватьСвоейПечатью("Документ.УЗ_ДоговорОбучения", "Договор", д2.Ссылка)
    тд = р.ТабличныйДокумент
    номер = c.УЗ_ОбщийКлиентСервер.НомерНаПечать(д2.Номер)
    for текст, что in (
            ("ДОГОВОР № %s" % номер, "номер договора"),
            ("об оказании платных образовательных услуг", "вид договора — образовательный (есть лицензия)"),
            ("лицензии на осуществление образовательной деятельности от 01.03.2021 № Л035-01234-77/00123456",
             "преамбула: основание деятельности — лицензия"),
            ("от имени которого действует директор Сидорова Анна Петровна на основании Устава", "преамбула: подписант"),
            ("действующий(ая) в интересах обучающегося", "преамбула: заказчик — в интересах обучающегося"),
            ("Восемь тысяч рублей 00 копеек", "стоимость прописью"),
            ("за 8 занятий по абонементу", "за что стоимость"),
            ("часть 3 статьи 54", "индексация цены — только по инфляции"),
            ("статья 782 Гражданского кодекса", "отказ от договора и возврат — ст. 32 ЗоЗПП, ст. 782 ГК"),
            ("ИНН 7701001236, КПП 772501001", "реквизиты исполнителя: ИНН и КПП из карточки организации"),
            ("40702810900000000001", "реквизиты исполнителя: банк"),
            ("Паспорт гражданина Российской Федерации 45 10 123456", "реквизиты заказчика: паспорт"),
            ("5.3. Обучающийся:", "обучающийся отдельным пунктом"),
            ("Сидорова А. П.", "подпись исполнителя")):
        т.проверить(т.найти_текст(тд, текст), "печать договора: %s" % что, текст)
    т.проверить(р.Заголовок == "Договор обучения" and not т.найти_текст(тд, "возмездного оказания услуг"),
                "печать: заголовок окна «Договор обучения»", р.Заголовок)

    сам = c.УЗ_Печать.СформироватьСвоейПечатью("Документ.УЗ_ДоговорОбучения", "Договор", д3.Ссылка).ТабличныйДокумент
    т.проверить(т.найти_текст(сам, "он же Обучающийся") and not т.найти_текст(сам, "5.3. Обучающийся"),
                "печать: взрослый заключает сам — «Заказчик, он же Обучающийся», без пункта об обучающемся")

    д4, ош = договор(ученик, Организация=без_лицензии)
    тд = c.УЗ_Печать.СформироватьСвоейПечатью("Документ.УЗ_ДоговорОбучения", "Договор", д4.Ссылка).ТабличныйДокумент
    т.проверить(ош is None and т.найти_текст(тд, "возмездного оказания услуг по обучению")
                and not т.найти_текст(тд, "часть 3 статьи 54") and not т.найти_текст(тд, "лицензии на осуществление"),
                "без лицензии: договор возмездного оказания услуг по обучению, без лицензии и пункта об индексации", ош)


if __name__ == "__main__":
    запустить("договор", сценарий)
