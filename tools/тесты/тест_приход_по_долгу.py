"""Приход денег: «Заполнить сумму по долгу ученика» подставляет и предмет долга (дефект записи видео 29.09.2026).

Прежде кнопка без выбранного предмета ставила общую сумму долга, а предмет оставался пустым: приход без предмета
долг предмета не гасит — в отчётах долг по предмету оставался. Теперь (УЗ_Сервер.ЗаполнениеПоЗадолженности):
  1. долг по одному предмету — подставляются он и его сумма (аванс без предмета уже зачтён, как в R09);
  2. долг по нескольким — предмет, чей долг начался раньше, его сумма и пояснение с остальными предметами;
  3. предмет выбран — сумма по нему, предмет не меняется;
  4. долга нет — сумма 0, предмет не меняется.
Красная на старом коде: функции не было (форма брала ЗадолженностьУченика без предмета).

    python tools\\тесты\\тест_приход_по_долгу.py --база=C:\\1c_bases\\UZ_BP_E --пользователь=1
"""
# затрагивает: УЗ_Сервер, УЗ_ПриходДенег, УЗ_СписанияСуммЗаУроки
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from _деньги import Данные  # noqa: E402
from фабрика import Фабрика  # noqa: E402
from логика_урок import деньги  # noqa: E402

МЕТКА = "_Тест приход по долгу"


def сценарий(т):
    c = т.c
    ф = Фабрика(т, МЕТКА)
    д_ = Данные(т, МЕТКА)
    орг = ф.организация("А")
    математика = ф.элемент("УЗ_ПредметыОбучения", "математика")
    гитара = ф.элемент("УЗ_ПредметыОбучения", "гитара")
    пусто = c.Справочники.УЗ_ПредметыОбучения.ПустаяСсылка()
    сервер = c.УЗ_Сервер

    def движения(кто, строки):
        д_.движения("УЗ_СписанияСуммЗаУроки", д_.регистратор(),
                    [("+" if сумма > 0 else "-", когда, dict({"Клиент": кто, "Сумма": abs(сумма)}, **поля))
                     for когда, сумма, поля in строки])

    def заполнить(кто, предмет=None):
        з = сервер.ЗаполнениеПоЗадолженности(кто, орг, предмет) if предмет is not None else \
            сервер.ЗаполнениеПоЗадолженности(кто, орг)
        return (None if з.ПредметОбучения is None else c.String(з.ПредметОбучения), деньги(з.Сумма), з.Пояснение)

    # 1. аванс 1 000 без предмета, долги математики и гитары по 1 000: аванс зачтён в математику (её долг раньше) —
    #    долг только по гитаре
    один = ф.ученик("один предмет")
    движения(один, [(ф.день(-5, 9), 1000, {"Организация": орг, "ПредметОбучения": пусто}),
                    (ф.день(-4, 9), -1000, {"Организация": орг, "ПредметОбучения": математика}),
                    (ф.день(-4, 10), -1000, {"Организация": орг, "ПредметОбучения": гитара})])
    итог = заполнить(один)
    т.проверить(итог == (c.String(гитара), 1000.0, ""),
                "1: долг по одному предмету — подставлены предмет «гитара» и 1 000 (было: без предмета)", итог)

    # 2. долги математики 1 000 (раньше) и гитары 500 — математика, 1 000, гитара названа в пояснении
    два = ф.ученик("два предмета")
    движения(два, [(ф.день(-4, 9), -1000, {"Организация": орг, "ПредметОбучения": математика}),
                   (ф.день(-3, 9), -500, {"Организация": орг, "ПредметОбучения": гитара})])
    итог = заполнить(два)
    т.проверить(итог[:2] == (c.String(математика), 1000.0) and c.String(гитара) in итог[2] and "500" in итог[2],
                "2: долг по двум предметам — предмет с ранним долгом (математика 1 000), гитара 500 — в пояснении", итог)

    # 3. предмет выбран — сумма по нему, предмет не меняется
    итог = заполнить(два, гитара)
    т.проверить(итог == (None, 500.0, ""), "3: выбран предмет «гитара» — сумма 500, предмет не меняется", итог)

    # 4. долга нет
    нет = ф.ученик("без долга")
    движения(нет, [(ф.день(-4, 9), 300, {"Организация": орг, "ПредметОбучения": пусто})])
    итог = заполнить(нет)
    т.проверить(итог == (None, 0.0, ""), "4: долга нет — сумма 0, предмет не подставляется", итог)

    # 5. A5-03: проведённый приход 1 000 по математике пересчитывает долг без своей оплаты — 1 000, а не 0
    оплатил = ф.ученик("перезаполнение прихода")
    движения(оплатил, [(ф.день(-4, 9), -1000, {"Организация": орг, "ПредметОбучения": математика})])
    приход = д_.регистратор()
    д_.движения("УЗ_СписанияСуммЗаУроки", приход, [("+", ф.день(-3, 9), {"Клиент": оплатил, "Сумма": 1000,
                                                                       "Организация": орг,
                                                                       "ПредметОбучения": математика})])
    без_себя = сервер.ЗаполнениеПоЗадолженности(оплатил, орг, математика, приход)
    с_собой = сервер.ЗаполнениеПоЗадолженности(оплатил, орг, математика)
    т.проверить((деньги(без_себя.Сумма), деньги(с_собой.Сумма)) == (1000.0, 0.0),
                "5 (A5-03): долг для перезаполнения прихода — без его оплаты 1 000; с ней 0",
                (деньги(без_себя.Сумма), деньги(с_собой.Сумма)))


if __name__ == "__main__":
    запустить("приход_по_долгу", сценарий)
