"""Ревью Codex логик 28.09.2026 — отчёты: R10, R18, R19.

  R10 «Аналитика по ученикам», полный блок периода: оплата робототехники 5 000 (аванс за следующий месяц), уроков
      робототехники в периоде нет — строка предмета есть, «Оплаты − возвраты» 5 000 (оплаты всех предметов, как
      приход кассы). Старый код: строки нет — список предметов строился только из уроков, аванс выпадал из итога.
  R18 «Расчёты по зарплате»: урок 1 000 без начисления по ставке, доплаты 100 и 200 с одинаковым пустым
      комментарием — «Сумма урока» 1 000 (один раз на урок), «Выручка» 700. Старый код: обе строки получали сумму
      урока — 2 000 / 1 700. С R24 (28.09.2026) доплаты — документы «Начисление педагогам» на основании урока (урок
      начисление не хранит).
  R19 «Аналитика», групповой урок 1 ч с тремя пришедшими: ячейка «Кол. часов» 1,00 и итог её расшифровки 1,00
      (часы урока — один раз, В26). Старый код: расшифровка суммировала часы учеников — 3,00.

    python tools\\тесты\\тест_ревью_отчеты.py --база=C:\\1c_bases\\UZ_UNF_D
"""
# затрагивает: УЗ_АналитикаПоУченикам, УЗ_РасчетыПоЗарплате
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from _деньги import Данные  # noqa: E402
from фабрика import Фабрика  # noqa: E402
from логика_урок import строка  # noqa: E402
from логика_отчеты_сверка import таблица, строка_с, число  # noqa: E402
from тест_отчет_зарплаты import итог_педагога  # noqa: E402
import стенд_форм  # noqa: E402

МЕТКА = "_Тест ревью отчётов"


def сценарий(т):
    c = т.c
    ф = Фабрика(т, МЕТКА)
    д_ = Данные(т, МЕТКА)
    виды = c.Перечисления.УЗ_ВидыОпераций
    орг = c.РегистрыСведений.УЗ_Настройки.Настройки().Организация
    касса = д_.элемент("УЗ_Кассы", "касса")
    педагог = ф.педагог()
    тариф = ф.элемент("УЗ_Тарифы", "1 000 за урок", Сумма=1000, КоличествоУроков=1)

    # ── R18 ──
    п18 = ф.педагог("педагог R18")
    у18 = ф.урок(п18, ф.день(-2, 10), 1, [строка(ф.ученик("ученик R18"), Тариф=тариф)])
    ош, сооб = ф.записать(у18)
    доплаты = [ф.доплата(у18, сумма, "") for сумма in (100, 200)]
    итог18 = sum(ф.начислено_педагогу(д) for д, _ in доплаты)
    т.проверить(ош is None and ф.начислено_педагогу(у18) == 0 and итог18 == 300,
                "R18: заготовка — урок 1 000 без ставки, доплаты 100 + 200 без комментария",
                ош or сооб or [о for _, (о, _) in доплаты] or итог18)
    # поле «Комментарий» в выбранных: без него СКД убирает поле из запроса, и строки регистра сливаются (у ревью
    # было ещё измерение «Не изменять» — в 2.0 его нет: после R24 его никто не писал)
    значения = итог_педагога(т, ф, п18, True)
    т.проверить(значения == {"Сумма урока": 1000.0, "Выручка": 700.0},
                "R18: «Расчёты по зарплате» — сумма урока 1 000 один раз, выручка 700 (было 2 000 / 1 700)", значения)

    # ── R10, R19: аналитика ──
    роботы = ф.элемент("УЗ_ПредметыОбучения", "робототехника R10")
    группа_предмет = ф.элемент("УЗ_ПредметыОбучения", "математика R19")
    ученики = [ф.ученик("ученик R19 %d" % н) for н in range(3)]
    у19 = ф.урок(педагог, ф.день(-1, 10), 1, [строка(у, Тариф=тариф) for у in ученики], ПредметОбучения=группа_предмет)
    ош, сооб = ф.записать(у19)
    т.проверить(ош is None, "R19: заготовка — групповой урок 1 ч, трое пришли", ош or сооб)
    пко = д_.документ("УЗ_ПриходДенег", Дата=ф.день(-1, 12), Касса=касса, Организация=орг, ФизЛицо=ученики[0],
                      ПредметОбучения=роботы, СуммаДокумента=5000, ВидОперации=виды.КассаУченики)
    ош = д_.записать(пко)
    т.проверить(ош is None, "R10: заготовка — ПКО робототехники 5 000 (уроков робототехники нет)", ош)

    об, сборка = стенд_форм.создать(c, "УЗ_АналитикаПоУченикам", "ФормаОтчета")
    т.вне_бюджета += сборка
    об.ПриСозданииНаСервере(False, True)
    об.Период.Вариант = c.ВариантСтандартногоПериода.ПроизвольныйПериод
    об.Период.ДатаНачала, об.Период.ДатаОкончания = ф.день(-3), ф.день(0, 23, 59)
    об.ПолучитьОстатки()
    строки = таблица(об.ТабДок)
    первый = строка_с(строки, "Данные с")
    полные = (строка_с(строки, "Данные с", первый + 1) if первый is not None else None) or 0   # второй блок «Данные с» — полный
    р = строка_с(строки, c.String(роботы), полные)
    т.проверить(р is not None and число(строки[р][5]) == 5000,
                "R10: полный блок — строка робототехники, «Оплаты − возвраты» 5 000 (было: строки нет, аванс выпадал)",
                строки[р] if р is not None else "строки нет")
    р = строка_с(строки, c.String(группа_предмет), полные)
    часы = строки[р][3] if р is not None else None
    итог_расшифровки = None
    if р is not None:
        расшифровка = об.ТабДок.Область(р + 1, 4, р + 1, 4).Расшифровка
        тд = об.ТабДокОбработкаРасшифровкиНаСервере(расшифровка)
        строки_р = таблица(тд)
        и = строка_с(строки_р, "ИТОГО")
        итог_расшифровки = строки_р[и][4] if и is not None else None
    т.проверить(часы == "1,00" and итог_расшифровки == "1,00",
                "R19: групповой урок 1 ч с тремя учениками — «Кол. часов» 1,00 и итог расшифровки 1,00 (было 3,00)",
                (часы, итог_расшифровки))


if __name__ == "__main__":
    запустить("ревью_отчеты", сценарий)
