"""Логика тарифов, скидок и бонусов, часть 2: сценарии 10–17 из docs/логики/тарифы_скидки_бонусы.md §5.

ПКО «По тарифу» — сумма тарифа на дату (Документы.УЗ_Урок.СуммаТарифаНаДату, история цен); скидка — с каждой
строки по тарифу: процент от цены, рубли со строки, в пределах [0; цена], вне срока — не применяется с сообщением
(В23); карта — единые проверки (Документы.УЗ_ПриходДенег.ПроверитьНачислениеБонусов / ПроверитьСписаниеБонусов,
В24): «Не действует», срок, сумма бонусов ≥ 0 — в уроке, «Начислении бонусов», ПКО; в уроке ещё — карта ученика строки.

Красные на старом коде (28.09.2026, UZ_UNF_D до правки): №10 (ПКО брал сумму карточки — 0 у тарифа с историей),
№16 (начисление бонусов на просроченную / выключенную карту и отрицательное начисление проводились), карта
чужого ученика в уроке проводилась.
Сценарии 15 и 17 (списание остатков бонусами сверх остатка; ПКО «Внутренняя касса» с бонусами) — код агента оплат
(списание остатков и ПКО), здесь — числа сценариев документа.

    python tools\\тесты\\логика_тарифы_2.py --база=C:\\1c_bases\\UZ_UNF_D
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from фабрика import Фабрика  # noqa: E402
from логика_урок import безопасно, деньги, строка, перечитать  # noqa: E402
from логика_тарифы import тариф, записать_цену  # noqa: E402

МЕТКА = "_Тест логика тарифов 2"


def сценарий(т):
    c = т.c
    ф = Фабрика(т, МЕТКА)
    педагог = ф.педагог()
    ученик = ф.ученик()
    минута = [0]

    def урок(тариф_=None, часов=1, **поля):
        """Уроки сегодня с 00:00 по минутам (длиной ≤ 0,01 ч не пересекаются) или вчера, если задан час."""
        час = поля.pop("час", None)
        if час is None:
            минута[0] += 1
            начало = ф.день(-1, 20, минута[0])
            часов = min(часов, 0.0167)
        else:
            начало = ф.день(-1, час)
        if тариф_ is not None:
            поля["Тариф"] = тариф_
        д = ф.урок(педагог, начало, часов, [строка(поля.pop("Ученик", ученик), **поля)])
        ош, сооб = ф.записать(д)
        return д, ош, сооб

    # 10. тариф с историей цен (сумма карточки 0) — ПКО «По тарифу» берёт цену на дату ПКО
    ист = тариф(т, ф, "история для ПКО", ИспользоватьИсториюЦен=True)
    записать_цену(т, ист, ф.день(-30), 4000, уроков=8)
    записать_цену(т, ист, ф.день(-5), 4800, уроков=8)
    сумма, ош = безопасно(lambda: c.Документы.УЗ_Урок.СуммаТарифаНаДату(ист, ф.день(-10)))
    т.проверить(ош is None and деньги(сумма) == 4000, "10: ПКО «По тарифу» 10 дней назад — 4 000 (цена на дату, было 0)", ош or сумма)
    сумма, ош = безопасно(lambda: c.Документы.УЗ_Урок.СуммаТарифаНаДату(ист, ф.день(0)))
    т.проверить(ош is None and деньги(сумма) == 4800, "10: ПКО «По тарифу» сегодня — 4 800", ош or сумма)

    # 11. скидки при цене 1 000: 10 % / 1 500 ₽ / 150 % / просроченная
    за_урок = тариф(т, ф, "1 000 за урок", Сумма=1000, КоличествоУроков=1)

    def скидка(имя, **р):
        return ф.элемент("УЗ_Скидки", имя, **р)
    for ск, час, ждём, что in (
            (скидка("10 %", КоэффициентПроцент=10), 8, (900, 100), "10 % — 900"),
            (скидка("1 500 ₽", КоэффициентСумма=1500), 9, (0, 1000), "1 500 ₽ при цене 1 000 — 0, не минус"),
            (скидка("150 %", КоэффициентПроцент=150), 10, (0, 1000), "150 % — 0, не минус"),
            (скидка("просрочена", КоэффициентПроцент=50, ПериодДействияС=ф.день(-30), ПериодДействияПо=ф.день(-3)), 11,
             (1000, 0), "просроченная — 1 000 и сообщение")):
        д = ф.урок(педагог, ф.день(-1, час), 1, [строка(ученик, Тариф=за_урок, Скидка=ск)])
        ош, сооб = ф.записать(д, "Запись")
        с = перечитать(д).Ученики.Получить(0)
        т.проверить(ош is None and (деньги(с.Сумма), деньги(с.СуммаСкидки)) == ждём, "11: скидка " + что,
                    ош or (с.Сумма, с.СуммаСкидки))
    ош, сооб = ф.записать(перечитать(д), "Проведение")
    т.проверить(any("не действует" in с for с, _ in сооб), "11: о просроченной скидке — сообщение при проведении",
                ош or сооб)

    # 12. скидка 100 ₽ со строки: урок 40 мин по 1 000/ч — 566,67; урок 2 ч — 1 900
    за_час = тариф(т, ф, "1 000 за час", Сумма=1000, КоличествоЧасов=1)
    сто = скидка("100 ₽", КоэффициентСумма=100)
    д, ош, _ = урок(за_час, 0.6667, Скидка=сто, час=12)
    д2, ош2, _ = урок(за_час, 2, Скидка=сто, час=13)
    т.проверить(ош is None and ош2 is None and (деньги(д.Сумма), деньги(д2.Сумма)) == (566.67, 1900),
                "12: рублёвая скидка 100 — со строки урока: 40 мин 566,67, 2 ч 1 900 (В23)", (ош, ош2, д.Сумма, д2.Сумма))

    # 13. карта: урок начислил 300 — ПКО бонусами 500 отказ, 300 проводится (остаток 0), затем 1 — отказ
    карта = ф.карта(ученик, "300 бонусов")
    _, ош, сооб = урок(ДисконтнаяКарта=карта, СуммаБонусов=300, СписатьОплату=False)
    т.проверить(ош is None, "13: урок начислил 300 бонусов", ош or сооб)

    def списать(карта_, бонусов, сдвиг=0):
        return ф.записать(ф.приход(ученик, 0, ДисконтнаяКарта=карта_, СуммаБонусов=бонусов, Дата=ф.день(сдвиг, 0, 30)))
    ош, _ = списать(карта, 500)
    т.проверить(ош is not None, "13: ПКО бонусами 500 при остатке 300 — отказ", ош)
    ош, сооб = списать(карта, 300)
    остаток, _ = безопасно(lambda: c.Документы.УЗ_ПриходДенег.ОстатокБонусовКарты(карта))
    т.проверить(ош is None and деньги(остаток) == 0, "13: ПКО бонусами 300 — проводится, остаток карты 0", ош or сооб or остаток)
    ош, _ = списать(карта, 1)
    т.проверить(ош is not None, "13: затем ПКО бонусами 1 — отказ", ош)

    # 14. карта «по вчера»: урок сегодня и ПКО сегодня — отказ
    вчера = ф.карта(ученик, "по вчера", ДатаОкончанияДействия=ф.день(-2))
    _, ош, сооб = урок(ДисконтнаяКарта=вчера, СуммаБонусов=100, СписатьОплату=False)
    т.проверить(ош is not None and any("срок действия" in с for с, _ in сооб), "14: карта истекла — урок: отказ «срок действия»",
                ош or сооб)
    ош, сооб = списать(вчера, 100)
    т.проверить(ош is not None, "14: карта истекла — ПКО: отказ", ош or сооб)

    # 15. карта с остатком 300: списание остатков бонусами 500 — отказ (было: проводилось, остаток −200)
    карта15 = ф.карта(ученик, "300 для списания остатков")
    урок(ДисконтнаяКарта=карта15, СуммаБонусов=300, СписатьОплату=False)
    из_деньги = __import__("_деньги")
    д_ = из_деньги.Данные(т, МЕТКА)
    сп = д_.документ("УЗ_СписаниеОстатков", Дата=ф.день(-1, 22))
    с = сп.ДисконтныеКарты.Добавить()
    с.ДисконтнаяКарта = карта15
    с.СуммаБонусов = 500
    ош = д_.записать(сп)
    т.проверить(ош is not None and "Недостаточно бонусов" in ош and деньги(c.Документы.УЗ_ПриходДенег.ОстатокБонусовКарты(карта15)) == 300,
                "15: списание остатков бонусами 500 при остатке 300 — отказ, на карте 300", ош)

    # 17. ПКО «Внутренняя касса», сумма 0, бонусы 300 — отказ: ученику в деньги бонусы не зачисляются
    д = ф.приход(ученик, 0, ДисконтнаяКарта=карта15, СуммаБонусов=300, Дата=ф.день(0, 0, 40),
                 ВидОперации=c.Перечисления.УЗ_ВидыОпераций.ВнутренняяКасса)
    ош, сооб = ф.записать(д)
    т.проверить(ош is not None and any("Бонусы принимаются только" in с for с, _ in сооб)
                and деньги(c.Документы.УЗ_ПриходДенег.ОстатокБонусовКарты(карта15)) == 300,
                "17: ПКО «Внутренняя касса» с бонусами 300 — отказ, карта не тронута, ученику не зачислено", ош or сооб)

    # 16. «Начисление бонусов» на истёкшую / выключенную карту и отрицательное начисление — отказ (как урок)
    def начислить(карта_, бонусов):
        д = c.Документы.УЗ_НачислениеБонусов.СоздатьДокумент()
        д.Дата = ф.день(-1, 21)
        д.Комментарий = МЕТКА
        с = д.ДисконтныеКарты.Добавить()
        с.ДисконтнаяКарта = карта_
        с.СуммаБонусов = бонусов
        return ф.записать(д)
    ош, сооб = начислить(вчера, 100)
    т.проверить(ош is not None and any("срок действия" in с for с, _ in сооб),
                "16: «Начисление бонусов» 100 на истёкшую карту — отказ (было: проводилось)", ош or сооб)
    выкл = ф.карта(ученик, "не действует", НеДействует=True)
    ош, сооб = начислить(выкл, 100)
    т.проверить(ош is not None and any("не действует" in с for с, _ in сооб),
                "16: «Начисление бонусов» на карту «Не действует» — отказ", ош or сооб)
    живая = ф.карта(ученик, "действующая")
    ош, сооб = начислить(живая, -50)
    т.проверить(ош is not None and any("отрицательн" in с for с, _ in сооб),
                "16: отрицательное «начисление» −50 (скрытое списание) — отказ", ош or сооб)
    ош, сооб = начислить(живая, 50)
    т.проверить(ош is None, "16: начисление 50 на действующую карту — проводится", ош or сооб)

    # доп.: карта чужого ученика в строке урока — отказ (В24: карта ученика строки)
    другой = ф.ученик("другой ученик")
    чужая = ф.карта(другой, "карта другого ученика")
    _, ош, сооб = урок(ДисконтнаяКарта=чужая, СуммаБонусов=10, СписатьОплату=False)
    т.проверить(ош is not None and any("а не" in с for с, _ in сооб), "доп.: карта другого ученика в уроке — отказ", ош or сооб)
    # доп.: отрицательное «начисление» бонусов в уроке — не списывает с карты (отказ проверки карты или колонка
    # бонусов неотрицательная — платформа сама не даёт минус)
    было = деньги(c.Документы.УЗ_ПриходДенег.ОстатокБонусовКарты(живая))
    д, ош, сооб = урок(ДисконтнаяКарта=живая, СуммаБонусов=-10, СписатьОплату=False)
    т.проверить((ош is not None and any("отрицательн" in с for с, _ in сооб))
                or (ош is None and деньги(c.Документы.УЗ_ПриходДенег.ОстатокБонусовКарты(живая)) == было),
                "доп.: бонусы −10 в уроке — карта не уменьшается (скрытого списания нет)",
                ош or (сооб, было, c.Документы.УЗ_ПриходДенег.ОстатокБонусовКарты(живая)))


if __name__ == "__main__":
    запустить("логика_тарифы_2", сценарий)
