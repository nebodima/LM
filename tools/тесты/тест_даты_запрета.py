"""Даты запрета изменения (регистр УЗ_ДатыЗапрета, модуль УЗ_ДатыЗапрета, две подписки).

    python tools\\тесты\\тест_даты_запрета.py --база=C:\\1c_bases\\UZ_UNF_B

Что проверяет: запрет записи и удаления до даты (включительно), разрешение после, перенос
документа из закрытого периода, пустой пользователь = все, своя строка пользователя важнее
общей, скользящая граница «старше N дней», все документы УЗ_ в подписках.
Мутация (проверена 27.09.2026): Отказ в УЗ_ДатыЗапрета.ПередЗаписьюДокумента закомментирован →
тест красный. Бюджет 10 с. За собой убирает: регистр возвращается к прежнему содержимому,
тестовые документы (Комментарий «_Тест даты запрета») удаляются в режиме загрузки.
"""
# объекты src_ext, которых нет в тексте теста (выбор тестов --быстро, tools/выбор_тестов.py):
# затрагивает: УЗ_ДатаЗапретаПередЗаписью, УЗ_ДатаЗапретаПередУдалением
import datetime
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import сеанс  # noqa: E402
from сеанс import дата, как_дата, ошибка_записи, запустить, удалить_объект  # noqa: E402

МЕТКА = "_Тест даты запрета"


def прочитать_регистр(c):
    """Прежнее содержимое регистра — вернуть после теста."""
    запрос = c.NewObject("Запрос")
    запрос.Текст = ("ВЫБРАТЬ Д.Пользователь КАК Пользователь, Д.ДатаЗапрета КАК ДатаЗапрета, "
                    "Д.ЗапретСтаршеДней КАК ЗапретСтаршеДней ИЗ РегистрСведений.УЗ_ДатыЗапрета КАК Д")
    выборка = запрос.Выполнить().Выбрать()
    строки = []
    while выборка.Следующий():
        строки.append((выборка.Пользователь, выборка.ДатаЗапрета, выборка.ЗапретСтаршеДней))
    return строки


def записать_регистр(c, строки):
    """Заменить всё содержимое регистра: [(Пользователь, ДатаЗапрета|None, Дней)]."""
    набор = c.РегистрыСведений.УЗ_ДатыЗапрета.СоздатьНаборЗаписей()
    for пользователь, дата_запрета, дней in строки:
        запись = набор.Добавить()
        запись.Пользователь = пользователь
        if дата_запрета is not None and дата_запрета.year >= 1900:
            запись.ДатаЗапрета = дата_запрета
        запись.ЗапретСтаршеДней = дней
    набор.Записать()


def удалить_тестовые(c):
    запрос = c.NewObject("Запрос")
    запрос.Текст = ("ВЫБРАТЬ Д.Ссылка КАК Ссылка ИЗ Документ.УЗ_ДополнительныеРасходы КАК Д "
                    "ГДЕ ВЫРАЗИТЬ(Д.Комментарий КАК СТРОКА(100)) = &Метка")
    запрос.УстановитьПараметр("Метка", МЕТКА)
    выборка = запрос.Выполнить().Выбрать()
    while выборка.Следующий():
        # мимо подписки (Загрузка): уборка не должна зависеть от запрета; движения — вместе с документом
        удалить_объект(c, выборка.Ссылка, загрузка=True)


def отказ_по_запрету(c, действие):
    """Действие упало И причина — наш запрет (сообщение «закрытом периоде»), а не что-то ещё."""
    c.ПолучитьСообщенияПользователю(True)
    ош = ошибка_записи(действие)
    сообщения = c.ПолучитьСообщенияПользователю(True)
    тексты = " | ".join(сообщения.Получить(н).Текст for н in range(сообщения.Количество()))
    return ош is not None and "закрытом периоде" in тексты


def новый_документ(c, когда):
    документ = c.Документы.УЗ_ДополнительныеРасходы.СоздатьДокумент()
    документ.Дата = когда
    документ.Комментарий = МЕТКА
    return документ


def сценарий(т):
    c = т.c
    прежнее = прочитать_регистр(c)
    удалить_тестовые(c)
    т.убрать(lambda: записать_регистр(c, прежнее), "регистр УЗ_ДатыЗапрета")
    т.убрать(lambda: удалить_тестовые(c), "тестовые документы")   # уборка в обратном порядке: сначала документы

    пусто = c.Справочники.Пользователи.ПустаяСсылка()
    я = c.УЗ_Среда.ТекущийПользователь()
    т.проверить(c.ЗначениеЗаполнено(я), "текущий пользователь найден в справочнике Пользователи")
    запрос = c.NewObject("Запрос")
    запрос.Текст = "ВЫБРАТЬ ПЕРВЫЕ 1 П.Ссылка КАК Ссылка ИЗ Справочник.Пользователи КАК П ГДЕ П.Ссылка <> &Я"
    запрос.УстановитьПараметр("Я", я)
    выборка = запрос.Выполнить().Выбрать()
    другой = выборка.Ссылка if выборка.Следующий() else None
    т.проверить(другой is not None, "есть второй пользователь")

    # 0. все документы УЗ_ под подписками
    без = c.УЗ_ДатыЗапрета.ДокументыБезПроверки()
    т.проверить(без.Количество() == 0, "все документы УЗ_ в подписках ПередЗаписью/ПередУдалением",
                ", ".join(без.Получить(н) for н in range(без.Количество())))

    # 1. без запретов — старый документ пишется
    записать_регистр(c, [])
    старый = новый_документ(c, дата(2020, 1, 10, 12))
    ош = ошибка_записи(старый.Записать)
    т.проверить(ош is None, "без запретов документ 10.01.2020 записан", ош)

    # 2. общая дата 31.01.2020 — запрет записи и удаления, дата включительно
    записать_регистр(c, [(пусто, дата(2020, 1, 31), 0)])
    т.проверить(как_дата(c.УЗ_ДатыЗапрета.ДатаЗапрета(другой)) == datetime.date(2020, 1, 31),
                "ДатаЗапрета(другой) = общая 31.01.2020")
    объект = старый.Ссылка.ПолучитьОбъект()
    объект.Комментарий = МЕТКА
    т.проверить(c.УЗ_ДатыЗапрета.ИзменениеЗапрещено(объект), "ИзменениеЗапрещено(документ 10.01) = Истина")
    т.проверить(отказ_по_запрету(c, объект.Записать), "запись документа 10.01.2020 запрещена")
    # свежий объект: после отказа в записи тот же объект считается изменённым
    т.проверить(отказ_по_запрету(c, lambda: старый.Ссылка.ПолучитьОбъект().Удалить()),
                "удаление документа 10.01.2020 запрещено")
    в_последний_день = новый_документ(c, дата(2020, 1, 31, 18))
    т.проверить(отказ_по_запрету(c, в_последний_день.Записать),
                "новый документ 31.01.2020 18:00 (день запрета) запрещён")

    # 3. после даты — можно; перенос в закрытый период — нельзя
    свежий = новый_документ(c, дата(2020, 2, 1, 9))
    т.проверить(ошибка_записи(свежий.Записать) is None, "документ 01.02.2020 после даты запрета записан")
    свежий.Дата = дата(2020, 1, 15)
    т.проверить(отказ_по_запрету(c, свежий.Записать), "перенос документа на 15.01.2020 запрещён")
    свежий = свежий.Ссылка.ПолучитьОбъект()
    т.проверить(ошибка_записи(свежий.Удалить) is None, "удаление документа после даты разрешено")

    # 4. своя строка пользователя важнее общей
    записать_регистр(c, [(пусто, дата(2020, 1, 31), 0), (я, дата(2019, 12, 31), 0)])
    т.проверить(как_дата(c.УЗ_ДатыЗапрета.ДатаЗапрета(я)) == datetime.date(2019, 12, 31),
                "ДатаЗапрета(я) = своя 31.12.2019")
    т.проверить(как_дата(c.УЗ_ДатыЗапрета.ДатаЗапрета(другой)) == datetime.date(2020, 1, 31),
                "ДатаЗапрета(другой) = общая 31.01.2020")
    объект = старый.Ссылка.ПолучитьОбъект()
    т.проверить(ошибка_записи(объект.Записать) is None, "своя строка сняла общий запрет: документ 10.01.2020 записан")

    # 5. строка только для другого пользователя меня не касается
    записать_регистр(c, [(другой, дата(2020, 1, 31), 0)])
    т.проверить(ошибка_записи(объект.Записать) is None, "запрет другого пользователя не действует на меня")

    # 6. скользящая граница «старше 7 дней» (на администратора не действует — проверяем на другом)
    записать_регистр(c, [(пусто, None, 7)])
    сегодня = сеанс.сегодня()   # день тестов = дата сеанса (сеанс.закрепить_время)
    ожидаемая = сегодня - datetime.timedelta(days=8)
    т.проверить(как_дата(c.УЗ_ДатыЗапрета.ДатаЗапрета(другой)) == ожидаемая,
                "скользящая граница: ДатаЗапрета(другой) = сегодня − 8 дней",
                как_дата(c.УЗ_ДатыЗапрета.ДатаЗапрета(другой)))
    т.проверить(как_дата(c.УЗ_ДатыЗапрета.ДатаЗапрета(я)) is None, "скользящая граница не действует на администратора")

    # 7. запреты сняты — удаление разрешено
    записать_регистр(c, [])
    объект = старый.Ссылка.ПолучитьОбъект()
    т.проверить(ошибка_записи(объект.Удалить) is None, "без запретов удаление документа 10.01.2020 разрешено")


if __name__ == "__main__":
    запустить("даты_запрета", сценарий)
