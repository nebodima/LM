"""Даты запрета изменения (регистр УЗ_ДатыЗапрета, модуль УЗ_ДатыЗапрета, две подписки).

    python tools\\тесты\\тест_даты_запрета.py --база=C:\\1c_bases\\UZ_UNF_B

Что проверяет: запрет записи и удаления до даты (включительно), разрешение после, перенос
документа из закрытого периода, пустой пользователь = все, своя строка пользователя важнее
общей, скользящая граница «старше N дней», все документы УЗ_ в подписках.
Мутация (проверена 27.09.2026): Отказ в УЗ_ДатыЗапрета.ПередЗаписьюДокумента закомментирован →
тест красный. Бюджет 10 с. За собой убирает: регистр возвращается к прежнему содержимому,
тестовые документы (Комментарий «_Тест даты запрета») удаляются в режиме загрузки.
"""
import atexit
import datetime
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import com_сеанс as к  # noqa: E402

МЕТКА = "_Тест даты запрета"
БЮДЖЕТ = 10


def прочитать_регистр(c):
    """Прежнее содержимое регистра — вернуть после теста."""
    запрос = c.NewObject("Запрос")
    запрос.Текст = ("ВЫБРАТЬ Д.Пользователь КАК Пользователь, Д.ДатаЗапрета КАК ДатаЗапрета, "
                    "Д.ЗапретСтаршеДней КАК ЗапретСтаршеДней ИЗ РегистрСведений.УЗ_ДатыЗапрета КАК Д")
    выборка = запрос.Выполнить().Выбрать()
    строки = []
    while выборка.Следующий():
        строки.append((выборка.Пользователь, выборка.ДатаЗапрета, выборка.ЗапретСтаршеДней))
    return строки


def записать_регистр(c, строки):
    """Заменить всё содержимое регистра: [(Пользователь, ДатаЗапрета|None, Дней)]."""
    набор = c.РегистрыСведений.УЗ_ДатыЗапрета.СоздатьНаборЗаписей()
    for пользователь, дата_запрета, дней in строки:
        запись = набор.Добавить()
        запись.Пользователь = пользователь
        if дата_запрета is not None and дата_запрета.year >= 1900:
            запись.ДатаЗапрета = дата_запрета
        запись.ЗапретСтаршеДней = дней
    набор.Записать()


def удалить_тестовые(c):
    запрос = c.NewObject("Запрос")
    запрос.Текст = ("ВЫБРАТЬ Д.Ссылка КАК Ссылка ИЗ Документ.УЗ_ДополнительныеРасходы КАК Д "
                    "ГДЕ ВЫРАЗИТЬ(Д.Комментарий КАК СТРОКА(100)) = &Метка")
    запрос.УстановитьПараметр("Метка", МЕТКА)
    выборка = запрос.Выполнить().Выбрать()
    while выборка.Следующий():
        объект = выборка.Ссылка.ПолучитьОбъект()
        объект.ОбменДанными.Загрузка = True   # мимо подписки: уборка не должна зависеть от запрета
        объект.Удалить()


def отказ_по_запрету(c, действие):
    """Действие упало И причина — наш запрет (сообщение «закрытом периоде»), а не что-то ещё."""
    c.ПолучитьСообщенияПользователю(True)
    ош = к.ошибка_записи(действие)
    сообщения = c.ПолучитьСообщенияПользователю(True)
    тексты = " | ".join(сообщения.Получить(и).Текст for и in range(сообщения.Количество()))
    return ош is not None and "закрытом периоде" in тексты


def новый_документ(c, дата):
    документ = c.Документы.УЗ_ДополнительныеРасходы.СоздатьДокумент()
    документ.Дата = дата
    документ.Комментарий = МЕТКА
    return документ


def главный():
    к.настроить_вывод()
    c = к.сеанс()
    прежнее = прочитать_регистр(c)
    удалить_тестовые(c)

    def уборка():
        удалить_тестовые(c)
        записать_регистр(c, прежнее)
    atexit.register(уборка)

    пусто = c.Справочники.Пользователи.ПустаяСсылка()
    я = c.УЗ_Среда.ТекущийПользователь()
    к.проверка("текущий пользователь найден в справочнике Пользователи", c.ЗначениеЗаполнено(я))
    запрос = c.NewObject("Запрос")
    запрос.Текст = "ВЫБРАТЬ ПЕРВЫЕ 1 П.Ссылка КАК Ссылка ИЗ Справочник.Пользователи КАК П ГДЕ П.Ссылка <> &Я"
    запрос.УстановитьПараметр("Я", я)
    выборка = запрос.Выполнить().Выбрать()
    другой = выборка.Ссылка if выборка.Следующий() else None
    к.проверка("есть второй пользователь", другой is not None)

    # 0. все документы УЗ_ под подписками
    без = c.УЗ_ДатыЗапрета.ДокументыБезПроверки()
    к.проверка("все документы УЗ_ в подписках ПередЗаписью/ПередУдалением", без.Количество() == 0,
               ", ".join(без.Получить(и) for и in range(без.Количество())))

    # 1. без запретов — старый документ пишется
    записать_регистр(c, [])
    старый = новый_документ(c, к.дата(2020, 1, 10, 12))
    ош = к.ошибка_записи(старый.Записать)
    к.проверка("без запретов документ 10.01.2020 записан", ош is None, ош)

    # 2. общая дата 31.01.2020 — запрет записи и удаления, дата включительно
    записать_регистр(c, [(пусто, к.дата(2020, 1, 31), 0)])
    к.проверка("ДатаЗапрета(другой) = общая 31.01.2020",
               к.как_дата(c.УЗ_ДатыЗапрета.ДатаЗапрета(другой)) == datetime.date(2020, 1, 31))
    объект = старый.Ссылка.ПолучитьОбъект()
    объект.Комментарий = МЕТКА
    к.проверка("ИзменениеЗапрещено(документ 10.01) = Истина", c.УЗ_ДатыЗапрета.ИзменениеЗапрещено(объект))
    к.проверка("запись документа 10.01.2020 запрещена", отказ_по_запрету(c, объект.Записать))
    # свежий объект: после отказа в записи тот же объект считается изменённым
    к.проверка("удаление документа 10.01.2020 запрещено",
               отказ_по_запрету(c, lambda: старый.Ссылка.ПолучитьОбъект().Удалить()))
    в_последний_день = новый_документ(c, к.дата(2020, 1, 31, 18))
    к.проверка("новый документ 31.01.2020 18:00 (день запрета) запрещён",
               отказ_по_запрету(c, в_последний_день.Записать))

    # 3. после даты — можно; перенос в закрытый период — нельзя
    свежий = новый_документ(c, к.дата(2020, 2, 1, 9))
    к.проверка("документ 01.02.2020 после даты запрета записан", к.ошибка_записи(свежий.Записать) is None)
    свежий.Дата = к.дата(2020, 1, 15)
    к.проверка("перенос документа на 15.01.2020 запрещён", отказ_по_запрету(c, свежий.Записать))
    свежий = свежий.Ссылка.ПолучитьОбъект()
    к.проверка("удаление документа после даты разрешено", к.ошибка_записи(свежий.Удалить) is None)

    # 4. своя строка пользователя важнее общей
    записать_регистр(c, [(пусто, к.дата(2020, 1, 31), 0), (я, к.дата(2019, 12, 31), 0)])
    к.проверка("ДатаЗапрета(я) = своя 31.12.2019",
               к.как_дата(c.УЗ_ДатыЗапрета.ДатаЗапрета(я)) == datetime.date(2019, 12, 31))
    к.проверка("ДатаЗапрета(другой) = общая 31.01.2020",
               к.как_дата(c.УЗ_ДатыЗапрета.ДатаЗапрета(другой)) == datetime.date(2020, 1, 31))
    объект = старый.Ссылка.ПолучитьОбъект()
    к.проверка("своя строка сняла общий запрет: документ 10.01.2020 записан", к.ошибка_записи(объект.Записать) is None)

    # 5. строка только для другого пользователя меня не касается
    записать_регистр(c, [(другой, к.дата(2020, 1, 31), 0)])
    к.проверка("запрет другого пользователя не действует на меня", к.ошибка_записи(объект.Записать) is None)

    # 6. скользящая граница «старше 7 дней» (на администратора не действует — проверяем на другом)
    записать_регистр(c, [(пусто, None, 7)])
    сегодня = datetime.date.today()   # база файловая на этом же ПК
    ожидаемая = сегодня - datetime.timedelta(days=8)
    к.проверка("скользящая граница: ДатаЗапрета(другой) = сегодня − 8 дней",
               к.как_дата(c.УЗ_ДатыЗапрета.ДатаЗапрета(другой)) == ожидаемая,
               к.как_дата(c.УЗ_ДатыЗапрета.ДатаЗапрета(другой)))
    к.проверка("скользящая граница не действует на администратора",
               к.как_дата(c.УЗ_ДатыЗапрета.ДатаЗапрета(я)) is None)

    # 7. запреты сняты — удаление разрешено
    записать_регистр(c, [])
    объект = старый.Ссылка.ПолучитьОбъект()
    к.проверка("без запретов удаление документа 10.01.2020 разрешено", к.ошибка_записи(объект.Удалить) is None)

    return к.итог(БЮДЖЕТ)


if __name__ == "__main__":
    sys.exit(главный())
