"""Обработка фото (УЗ_ОбработкаФото): выгрузка всех фото файлами и загрузка по имени файла — в памяти, без папок на
диске сервера (расширение в безопасном режиме; форма передаёт файлы через ПолучитьФайлыССервераАсинх /
ПоместитьФайлыНаСерверАсинх, логика — в модуле менеджера, его и проверяем).

Самотест: файл с именем, которого нет в справочнике, не загружается (0), битая картинка попадает в «Пропущено».
Ошибки справки №26–27: наименование фото — полное ФИО (50 знаков физ. лица; было 25 — имя обрезалось, и загрузка
по имени файла фото не находила); новая картинка карточки заменяет файл текущего фото, а не плодит записи
(Справочники.УЗ_Фото.ФотоСКартинкой — её зовёт «Выбрать фото» карточки предмета).
Данные создаёт сам (два элемента «Фото») и удаляет за собой.

    python tools\\тесты\\тест_фото.py --база=C:\\1c_bases\\UZ_UNF_C
"""
import base64
import os
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402

МЕТКА = "тест_фото"
# PNG 1×1 (прозрачный пиксель)
PNG = base64.b64decode("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mNk+M9QDwADhgGAWjR9awAAAABJRU5ErkJggg==")


def двоичные(c, данные):
    ф = tempfile.NamedTemporaryFile(delete=False, suffix=".bin")
    ф.write(данные)
    ф.close()
    try:
        return c.NewObject("ДвоичныеДанные", ф.name)
    finally:
        os.unlink(ф.name)


def сценарий(т):
    c = т.c
    менеджер = c.Обработки.УЗ_ОбработкаФото

    def фото(имя, данные):
        о = c.Справочники.УЗ_Фото.СоздатьЭлемент()
        о.Наименование = имя
        о.Файл = c.NewObject("ХранилищеЗначения", двоичные(c, данные))
        о.Записать()
        т.убрать(lambda с=о.Ссылка: т.удалить_объект(с), имя)
        return о.Ссылка

    было = менеджер.ФайлыФотографий().Файлы.Количество()
    хорошее = фото("%s Петров" % МЕТКА, PNG)
    фото("%s битое" % МЕТКА, b"not a picture")

    выгрузка = менеджер.ФайлыФотографий()
    файлы = [выгрузка.Файлы.Получить(н) for н in range(выгрузка.Файлы.Количество())]
    т.проверить(len(файлы) == было + 1, "выгрузка: +1 фото (битое не в счёт)", "%d -> %d" % (было, len(файлы)))
    пропущено = [выгрузка.Пропущено.Получить(н) for н in range(выгрузка.Пропущено.Количество())]
    т.проверить("%s битое" % МЕТКА in пропущено, "самотест: битая картинка в «Пропущено»", пропущено)
    имя_файла = "%s Петров [%d].png" % (МЕТКА, int(хорошее.Код))
    наш = [ф for ф in файлы if ф.ИмяФайла == имя_файла]
    т.проверить(len(наш) == 1, "выгрузка: файл «<наименование> [код].png» (расширение по формату, L5-08)",
                [ф.ИмяФайла for ф in файлы][:5])
    if наш:
        т.проверить(наш[0].Данные.Размер() == len(PNG), "выгрузка: данные фото без изменений", наш[0].Данные.Размер())

    т.проверить(менеджер.ЗагрузитьФото("%s Петров.png" % МЕТКА, двоичные(c, PNG + b"\0")) == 1,
                "загрузка: файл «<наименование>.png» заменил фото")
    данные = хорошее.ПолучитьОбъект().Файл.Получить()
    т.проверить(данные is not None and данные.Размер() == len(PNG) + 1, "загрузка: в справочнике новые данные")
    т.проверить(менеджер.ЗагрузитьФото("%s нет такого.jpg" % МЕТКА, двоичные(c, PNG)) == 0,
                "самотест: файл без фото с таким наименованием не загружен")
    # L5-08: тёзки — по наименованию не загружаем ни одно, по коду из имени файла — ровно своё
    тёзка1 = фото("%s Тёзка" % МЕТКА, PNG)
    тёзка2 = фото("%s Тёзка" % МЕТКА, PNG)
    т.проверить(менеджер.ЗагрузитьФото("%s Тёзка.png" % МЕТКА, двоичные(c, PNG + b"\0")) == 0
                and тёзка1.ПолучитьОбъект().Файл.Получить().Размер() == len(PNG),
                "L5-08: два фото с одним наименованием — файл без кода не загружен ни в одно")
    т.проверить(менеджер.ЗагрузитьФото("%s Тёзка [%d].png" % (МЕТКА, int(тёзка2.Код)), двоичные(c, PNG + b"\0")) == 1
                and тёзка2.ПолучитьОбъект().Файл.Получить().Размер() == len(PNG) + 1
                and тёзка1.ПолучитьОбъект().Файл.Получить().Размер() == len(PNG),
                "L5-08: файл с кодом в имени — загружен в своё фото, тёзка не тронут")
    # A8-03: в фото — только картинка не больше 5 МБ
    т.проверить(менеджер.ЗагрузитьФото(имя_файла, двоичные(c, b"not a picture")) == 0,
                "A8-03: не картинка не загружается")
    причины = [c.Справочники.УЗ_Фото.ПричинаНеПодходит(двоичные(c, д)) for д in (b"not a picture", PNG,
                                                                              PNG + b"\0" * (5 * 1048576))]
    т.проверить("не картинка" in причины[0] and причины[1] == "" and "больше 5 МБ" in причины[2],
                "A8-03: причина — не картинка; маленький PNG подходит; больше 5 МБ — нет", причины)

    # №26: полное ФИО (50 знаков) — наименование фото не обрезается, загрузка по имени находит фото
    фио = ("%s Константинопольская Александра В" % МЕТКА)[:50].ljust(50, "а")
    длинное = фото(фио, PNG)
    т.проверить(длинное.ПолучитьОбъект().Наименование == фио, "№26: наименование фото — все 50 знаков ФИО",
                "%d знаков" % len(длинное.ПолучитьОбъект().Наименование))
    т.проверить(менеджер.ЗагрузитьФото(фио + ".png", двоичные(c, PNG)) == 1,
                "№26: загрузка по имени файла «<ФИО 50 знаков>.png» находит фото")

    # №27: картинка карточки заменяет файл текущего фото, новая запись — только если фото не было
    def число_фото():
        return т.выбрать("ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Н ИЗ Справочник.УЗ_Фото КАК Ф").Получить(0).Н
    было_фото = число_фото()
    то_же = c.Справочники.УЗ_Фото.ФотоСКартинкой(хорошее, "%s другое имя" % МЕТКА, двоичные(c, PNG + b"\0\0"))
    т.проверить(c.String(то_же.УникальныйИдентификатор()) == c.String(хорошее.УникальныйИдентификатор())
                and число_фото() == было_фото, "№27: новая картинка — в то же фото, записей не прибавилось",
                "фото %d -> %d" % (было_фото, число_фото()))
    т.проверить(хорошее.ПолучитьОбъект().Файл.Получить().Размер() == len(PNG) + 2, "№27: в фото новая картинка")
    новое = c.Справочники.УЗ_Фото.ФотоСКартинкой(c.Справочники.УЗ_Фото.ПустаяСсылка(), "%s новое" % МЕТКА,
                                                двоичные(c, PNG))
    т.убрать(lambda: т.удалить_объект(новое), "новое фото")
    т.проверить(not новое.Пустая() and число_фото() == было_фото + 1, "№27: без фото — создаётся одно новое")


if __name__ == "__main__":
    запустить("фото", сценарий)
