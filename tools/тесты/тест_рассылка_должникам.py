"""Рассылка должникам (запрос покупателей Инфостарта) и асинхронность почты/оповещений (архитектор 2.2–2.3), 28.09.2026.

Песочница: сеанс теста в песочнице (сеанс.подключить), почта копии включена только на выдуманный SMTP
(smtp.example.invalid) и возвращается уборкой; за весь тест — ни одного события «Учёт занятий.Почта.Отправка».
Всё по своей организации и своим ученикам — чужим письма не уходят.
  1. Список: организация А, «Долг от» 200, «Долг старше» 2 дня — долг 1 500 трёхдневный есть (Дней 3, адрес,
     можно писать), 100 — нет (сумма), 800 сегодняшний — нет (срок), без e-mail — есть, но писать нельзя
     («нет e-mail»).
  2. Письмо по шаблону: «[Ученик] [Сумма] [Предмет] [Организация] [ДнейДолга]» — точная строка.
  3. Отправка отмеченным: должнику — «Отправлено» (письмо в журнале песочницы на его адрес), без e-mail —
     «Не отправлено: нет e-mail»; журнал писем: отправлено, вручную, сумма 1 500, адрес.
  4. Повтор сразу — «Не отправлено: письмо было …», писем в песочнице не прибавилось.
  5. Согласование с В27: после ручного письма регламентное оповещение о долге (N = 2) письма не шлёт; письмо
     регламентного задания другому должнику — в журнале писем (вручную = нет), и ручная рассылка ему «писали недавно».
  6. Долг погашен после формирования списка — «долга уже нет», письма нет.
  7. Безопасный режим / почта не настроена — понятная причина (как снять безопасный режим — из
     УЗ_Общий.КакСнятьБезопасныйРежим); почта выключена — отправка отказывает с причиной.
  8. Фоновые задания: рассылка и «Проверить» почты запускаются фоновым заданием с песочницей вызвавшего сеанса;
     состояние задания читается (отменённое — «отменено»). Файловая база не исполняет фон, запущенный из COM
     (см. тест_права) — задание снимается, процедура задания выполняется в этом сеансе с тем же параметром.
  9. Период опроса оповещений не чаще 5 минут: настройка 60 с — 300, 600 с — 600.
 10. Панель ученика: выбор дат периода — ОписаниеОповещения и Закрыть(Результат), без глобального Оповестить.
Красное на старом коде: всё (обработки, журнала и фоновой отправки не было; период 60 → 60).

    python tools\\тесты\\тест_рассылка_должникам.py --база=C:\\1c_bases\\UZ_UNF_D
"""
# объекты src_ext, которых нет в тексте теста (выбор тестов --быстро, tools/выбор_тестов.py):
# затрагивает: УЗ_НастройкиПочты, УЗ_ОповещенияГлобальный, УЗ_Настройки, УЗ_ПесочницаПочты, УЗ_ПанельУченика
import datetime
import os
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить, позиция_журнала, события_журнала, текст_ошибки  # noqa: E402
from _деньги import Данные  # noqa: E402
from фабрика import Фабрика  # noqa: E402
import тест_оповещения as оп  # noqa: E402

МЕТКА = "_Тест рассылка должникам"
ИСХОДНИКИ = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "src_ext"))
ПЕСОЧНИЦА = "Учёт занятий.Почта.Песочница"
ОТПРАВКА = "Учёт занятий.Почта.Отправка"


def структура(c, з):
    return {c.String(э.Ключ): э.Значение for э in з}


def текст(путь):
    return open(os.path.join(ИСХОДНИКИ, путь), encoding="utf-8-sig").read()


def сценарий(т):
    c = т.c
    if not c.УЗ_Почта.ПесочницаВключена():
        raise RuntimeError("песочница почты не включена — сценарий не запускаю")
    журнал = позиция_журнала(т.база)
    т.проверить(события_журнала(т.база, журнал, ОТПРАВКА) is not None, "журнал регистрации файловой базы читается")
    оп.выключить_почту(т)
    д = Данные(т, МЕТКА)
    ф = Фабрика(т, МЕТКА)
    орг = ф.организация("Студия А")
    имя_орг = c.String(орг)
    математика = ф.элемент("УЗ_ПредметыОбучения", "математика")
    сейчас = c.ТекущаяДатаСеанса()
    обработка = c.Обработки.УЗ_РассылкаДолжникам

    def назад(дней=0, часов=0):
        return сейчас - datetime.timedelta(days=дней, hours=часов)

    def ученик(имя, адрес=None):
        реквизиты = {"EMail": адрес, "ОповеститьПоEmail": True} if адрес else {}
        у = д.элемент("УЗ_ФизЛица", имя, **реквизиты)
        т.убрать(lambda: оп.удалить_оповещения(т, у), "оповещения и журнал писем %s" % имя)
        return у

    def долг(кто, сумма, дней, предмет=None):
        поля = {"Клиент": кто, "Сумма": abs(сумма), "Организация": орг}
        if предмет is not None:
            поля["ПредметОбучения"] = предмет
        д.движения("УЗ_СписанияСуммЗаУроки", д.регистратор(),
                   [("+" if сумма > 0 else "-", назад(дней, 1 if дней == 0 else 0), поля)])

    def параметры(**значения):
        п = c.NewObject("Структура")
        поля = dict(Организация=орг, МинимальнаяСумма=200, ДолгСтаршеДней=2, НеЧащеДней=7)
        поля.update(значения)
        for к, в in поля.items():
            п.Вставить(к, в)
        return п

    def строки(п):
        return {c.String(с.Ученик): с for с in обработка.Должники(п)}

    def получатели(*ученики):
        м = c.NewObject("Массив")
        for у in ученики:
            с = c.NewObject("Структура")
            с.Вставить("Ученик", у)
            с.Вставить("Организация", орг)
            м.Добавить(с)
        return м

    def писем(позиция, адрес):
        return len([з for з in (события_журнала(т.база, позиция, ПЕСОЧНИЦА) or []) if адрес in з])

    def результаты(массив):
        return {c.String(р.Ученик): (bool(р.Отправлено), c.String(р.Результат)) for р in массив}

    # ── 7. почта выключена — причина и отказ отправки ──
    причина = c.String(обработка.ПричинаНевозможностиОтправки())
    т.проверить("выключена" in причина, "почта выключена — причина «Отправка писем выключена…» и кто настраивает",
                причина)
    как_для_всех = c.String(обработка.ПричинаНевозможностиОтправки(False))
    if c.УЗ_Общий.БезопасныйРежимДействует():
        # стенд: расширение загружено в безопасном режиме — обычный сеанс видит, как его снять; песочнице он не
        # помеха (письмо наружу не уходит), поэтому дальше сценарий идёт в песочнице
        т.проверить(c.String(c.УЗ_Общий.КакСнятьБезопасныйРежим()) in как_для_всех,
                    "безопасный режим — причина с тем, как его снять (УЗ_Общий.КакСнятьБезопасныйРежим)", как_для_всех)
    else:
        print("  (расширение не в безопасном режиме — ветку «как снять» здесь не проверить)")
        т.проверить(как_для_всех == причина, "без безопасного режима причина одна и та же", как_для_всех)

    # ── 1. список должников по отбору ──
    АДРЕС = "rassylka.test@example.invalid"
    должник = ученик("должник", АДРЕС)
    долг(должник, -1500, 3, математика)
    малый = ученик("малый долг", "maly.test@example.invalid")
    долг(малый, -100, 3)
    свежий = ученик("свежий долг", "svezhiy.test@example.invalid")
    долг(свежий, -800, 0)
    без_адреса = ученик("без e-mail")
    долг(без_адреса, -700, 3)
    список = строки(параметры())
    имя_д, имя_б = c.String(должник), c.String(без_адреса)
    т.проверить(set(список) == {имя_д, имя_б},
                "отбор: долг от 200 и старше 2 дней — должник 1 500 и без e-mail 700 (малый 100 и сегодняшний 800 — нет)",
                sorted(список))
    с = список.get(имя_д)
    т.проверить(с is not None and round(float(с.Долг), 2) == 1500.0 and int(с.ДнейДолга) == 3
                and АДРЕС in c.String(с.Адреса) and bool(с.МожноПисать) and c.String(с.Предметы) == c.String(математика),
                "строка должника: 1 500,00, 3 дня, адрес, предмет, можно писать",
                None if с is None else (с.Долг, с.ДнейДолга, с.Адреса, с.МожноПисать, с.Предметы))
    с = список.get(имя_б)
    т.проверить(с is not None and not bool(с.МожноПисать) and "нет e-mail" in c.String(с.Причина),
                "без e-mail — в списке, писать нельзя, причина «нет e-mail»", None if с is None else c.String(с.Причина))
    т.проверить(len(строки(параметры(МинимальнаяСумма=0, ДолгСтаршеДней=0))) == 4,
                "без отбора по сумме и сроку — все 4 должника организации")

    # ── 2. письмо по шаблону ──
    с = список.get(имя_д)
    письмо = обработка.ПодготовитьПисьмо(с, "Долг [Ученик]", "[Ученик] [Сумма] [Предмет] [Организация] [ДнейДолга]")
    ждём = "%s 1 500,00 %s %s 3" % (имя_д, c.String(математика), имя_орг)
    т.проверить(c.String(письмо.Текст).replace("\xa0", " ") == ждём and c.String(письмо.Тема) == "Долг " + имя_д
                and [c.String(а) for а in письмо.Адреса] == [АДРЕС],
                "подстановки: «%s»" % ждём, (c.String(письмо.Текст), c.String(письмо.Тема)))

    # почта включена на выдуманный SMTP — дальше письма уходят только в песочницу
    оп.настроить_почту(т, Включена=True, СерверSMTP=оп.ВЫДУМАННЫЙ_SMTP, Порт=25, ИспользоватьSSL=False, Логин="",
                       АдресОтправителя="uz-test@example.invalid", ПисьмаОЗадолженности=True)
    т.проверить(c.String(обработка.ПричинаНевозможностиОтправки()) == "", "почта настроена — отправлять можно")

    # ── 3. отправка отмеченным ──
    шаблон = c.String(обработка.ШаблонПоУмолчанию())
    п1 = позиция_журнала(т.база)
    итог = результаты(обработка.ОтправитьПисьма(получатели(должник, без_адреса), "Задолженность", шаблон, 7))
    т.проверить(итог.get(имя_д, (False, ""))[0] and итог[имя_д][1].startswith("Отправлено"),
                "должнику — «Отправлено»", итог.get(имя_д))
    т.проверить(итог.get(имя_б, (True, ""))[0] is False and "нет e-mail" in итог[имя_б][1],
                "без e-mail — «Не отправлено: нет e-mail»", итог.get(имя_б))
    т.проверить(писем(п1, АДРЕС) == 1, "в журнале песочницы одно письмо на адрес должника", писем(п1, АДРЕС))
    записи = т.выбрать("""ВЫБРАТЬ Ж.Отправлено КАК Отправлено, Ж.Вручную КАК Вручную, Ж.Сумма КАК Сумма, Ж.Адреса КАК Адреса,
        Ж.Организация КАК Организация ИЗ РегистрСведений.УЗ_ЖурналРассылки КАК Ж ГДЕ Ж.Ученик = &У""", У=должник)
    в_журнале = [(bool(з.Отправлено), bool(з.Вручную), round(float(з.Сумма), 2), c.String(з.Адреса), c.String(з.Организация))
                 for з in записи]
    т.проверить(в_журнале == [(True, True, 1500.0, АДРЕС, имя_орг)],
                "журнал писем: отправлено, вручную, 1 500,00, адрес, организация", в_журнале)

    # ── 4. повтор сразу ──
    п2 = позиция_журнала(т.база)
    итог = результаты(обработка.ОтправитьПисьма(получатели(должник), "Задолженность", шаблон, 7))
    т.проверить(итог.get(имя_д, (True, ""))[0] is False and "письмо было" in итог[имя_д][1] and писем(п2, АДРЕС) == 0,
                "повтор сразу — «Не отправлено: письмо было …», писем не прибавилось", (итог.get(имя_д), писем(п2, АДРЕС)))

    # ── 5. согласование с регламентным оповещением (В27) ──
    настройка = c.РегистрыСведений.УЗ_Настройки.СоздатьМенеджерЗаписи()
    настройка.Прочитать()
    была = настройка.Выбран()
    прежние = (настройка.ИспользоватьОповещения, настройка.ОповещатьОЗадолженности, настройка.ПериодОповещения)

    def вернуть_настройку():
        н = c.РегистрыСведений.УЗ_Настройки.СоздатьМенеджерЗаписи()
        н.Прочитать()
        if была:
            н.ИспользоватьОповещения, н.ОповещатьОЗадолженности, н.ПериодОповещения = прежние
            н.Записать()
        else:
            н.Удалить()
    т.убрать(вернуть_настройку, "настройки оповещений")
    настройка.ИспользоватьОповещения = True
    настройка.ОповещатьОЗадолженности = 2
    настройка.Записать()
    п3 = позиция_журнала(т.база)
    c.УЗ_Сервер.ПроверкаЗадолженности(т.массив(должник))
    оповещено = т.выбрать("""ВЫБРАТЬ О.ДатаПисьма КАК ДатаПисьма ИЗ РегистрСведений.УЗ_Оповещения КАК О
        ГДЕ О.Источник = &У И НЕ О.Завершено""", У=должник)
    т.проверить(оповещено.Количество() == 1 and писем(п3, АДРЕС) == 0,
                "после ручного письма регламентное оповещение заведено, но письма не шлёт (было бы второе письмо)",
                (оповещено.Количество(), писем(п3, АДРЕС)))
    АДРЕС2 = "rassylka2.test@example.invalid"
    второй = ученик("письмо от задания", АДРЕС2)
    долг(второй, -900, 3)
    п4 = позиция_журнала(т.база)
    c.УЗ_Сервер.ПроверкаЗадолженности(т.массив(второй))
    записи = т.выбрать("""ВЫБРАТЬ Ж.Отправлено КАК Отправлено, Ж.Вручную КАК Вручную ИЗ РегистрСведений.УЗ_ЖурналРассылки КАК Ж
        ГДЕ Ж.Ученик = &У""", У=второй)
    т.проверить(писем(п4, АДРЕС2) == 1 and [(bool(з.Отправлено), bool(з.Вручную)) for з in записи] == [(True, False)],
                "письмо регламентного задания — в журнале писем (отправлено, не вручную)",
                (писем(п4, АДРЕС2), [(з.Отправлено, з.Вручную) for з in записи]))
    с = строки(параметры()).get(c.String(второй))
    т.проверить(с is not None and not bool(с.МожноПисать) and "письмо было" in c.String(с.Причина),
                "ручная рассылка после письма задания — «письмо было …», не отмечен", None if с is None else c.String(с.Причина))

    # ── 6. долг погашен после формирования списка ──
    АДРЕС3 = "rassylka3.test@example.invalid"
    погасил = ученик("погасил", АДРЕС3)
    долг(погасил, -600, 3)
    т.проверить(c.String(погасил) in строки(параметры()), "должник 600 в списке")
    долг(погасил, 600, 0)
    п5 = позиция_журнала(т.база)
    итог = результаты(обработка.ОтправитьПисьма(получатели(погасил), "Задолженность", шаблон, 7))
    т.проверить(итог.get(c.String(погасил), (True, ""))[0] is False and "долга уже нет" in итог[c.String(погасил)][1]
                and писем(п5, АДРЕС3) == 0, "долг погашен после списка — «долга уже нет», письма нет", итог)

    # ── 8. фоновые задания: рассылка и проверочное письмо ──
    файловая = c.СтрокаСоединенияИнформационнойБазы().upper().startswith("FILE=")
    АДРЕС4 = "rassylka4.test@example.invalid"
    фоном = ученик("фоновая рассылка", АДРЕС4)
    долг(фоном, -1100, 3)
    ид_формы = c.NewObject("УникальныйИдентификатор")
    пар = c.NewObject("Массив")
    for з in (получатели(фоном), "Задолженность", шаблон, 7):
        пар.Добавить(з)
    имя_метода = "УЗ_Почта.ОтправитьПисьмаДолжникамВФоне"
    п6 = позиция_журнала(т.база)
    запуск = c.УЗ_Общий.ЗапуститьФоновоеЗадание(имя_метода, пар, ид_формы, "УЗ тест рассылки")
    т.проверить(запуск is not None, "рассылка запускается фоновым заданием")
    if запуск is not None:
        задание = c.ФоновыеЗадания.НайтиПоУникальномуИдентификатору(запуск.Задание)
        т.проверить(задание is not None and c.String(задание.ИмяМетода) == имя_метода,
                    "фоновое задание рассылки создано с методом %s" % имя_метода,
                    None if задание is None else c.String(задание.ИмяМетода))
        срок = time.time() + (1 if файловая else 30)
        состояние = c.УЗ_Общий.СостояниеДлительнойОперации(запуск.Задание, запуск.АдресРезультата)
        while not состояние.Завершено and time.time() < срок:
            time.sleep(0.2)
            состояние = c.УЗ_Общий.СостояниеДлительнойОперации(запуск.Задание, запуск.АдресРезультата)
        if not состояние.Завершено and файловая:
            задание.Отменить()
            time.sleep(0.3)
            состояние = c.УЗ_Общий.СостояниеДлительнойОперации(запуск.Задание, запуск.АдресРезультата)
            т.проверить(bool(состояние.Завершено) and "отменено" in c.String(состояние.Ошибка),
                        "снятое задание — состояние «отменено» (форма покажет ошибку, а не зависнет)",
                        c.String(состояние.Ошибка))
            # файловая база: фон из COM не исполняется — та же процедура задания в этом сеансе, песочница — параметром
            c.УЗ_Почта.ОтправитьПисьмаДолжникамВФоне(True, получатели(фоном), "Задолженность", шаблон, 7,
                                                                   запуск.АдресРезультата)
            итог = результаты(c.ПолучитьИзВременногоХранилища(запуск.АдресРезультата))
        else:
            итог = результаты(состояние.Результат) if состояние.Результат is not None else {}
        т.проверить(итог.get(c.String(фоном), (False, ""))[0] and писем(п6, АДРЕС4) == 1,
                    "процедура фонового задания: письмо в песочницу, результат — во временном хранилище формы",
                    (итог, писем(п6, АДРЕС4)))
    проба = c.УЗ_Почта.НачатьОтправкуТестовогоПисьма(c.NewObject("УникальныйИдентификатор"))
    т.проверить(c.String(проба.Ошибка) == "" and проба.Задание is not None,
                "«Проверить» почты — фоновым заданием (форма не ждёт SMTP)", c.String(проба.Ошибка))
    if проба.Задание is not None:
        задание = c.ФоновыеЗадания.НайтиПоУникальномуИдентификатору(проба.Задание)
        if задание is not None and файловая:
            задание.Отменить()

    # ── 7 (продолжение). почта выключена — отправка отказывает с причиной ──
    оп.настроить_почту(т, Включена=False)
    try:
        обработка.ОтправитьПисьма(получатели(должник), "Задолженность", шаблон, 7)
        отказ = ""
    except Exception as е:
        отказ = текст_ошибки(е, 500)
    т.проверить("выключена" in отказ, "почта выключена — отправка отказывает: «Отправка писем выключена…»", отказ[-200:])

    попытки = события_журнала(т.база, журнал, ОТПРАВКА)
    т.проверить(попытки == [], "журнал: ни одной настоящей отправки письма за тест", попытки)

    # ── 9. период опроса оповещений ──
    for значение, ждём in ((60, 300), (600, 600), (0, 300)):
        н = c.РегистрыСведений.УЗ_Настройки.СоздатьМенеджерЗаписи()
        н.Прочитать()
        н.ПериодОповещения = значение
        н.Записать()
        т.проверить(int(c.УЗ_Сервер.ПараметрыОповещений().Период) == ждём,
                    "период опроса: настройка %d с — опрос раз в %d с (не чаще 5 минут)" % (значение, ждём),
                    int(c.УЗ_Сервер.ПараметрыОповещений().Период))

