    выбор = текст(r"DataProcessors\УЗ_ПанельУченика\Forms\ФормаВыбораПериода\Ext\Form\Module.bsl")
    панель = текст(r"DataProcessors\УЗ_ПанельУченика\Forms\Форма\Ext\Form\Module.bsl")
    разметка = текст(r"DataProcessors\УЗ_ПанельУченика\Forms\Форма\Ext\Form.xml")
    т.проверить("Оповестить(" not in выбор and "Закрыть(ВыбранныеДаты)" in выбор
                and 'Новый ОписаниеОповещения("ВыборПериодаЗавершение"' in панель
                and "Процедура ВыборПериодаЗавершение(ВыбранныеДаты, ИдентификаторСтроки) Экспорт" in панель
                and "NotificationProcessing" not in разметка,
                "выбор дат панели — ОписаниеОповещения и Закрыть(результат), без глобального Оповестить")
    почта = текст(r"CommonForms\УЗ_НастройкиПочты\Ext\Form\Module.bsl")
    т.проверить('ПодключитьОбработчикОжидания("ПроверитьЗавершение", 0.1' not in почта
                and "УЗ_Почта.НачатьОтправкуТестовогоПисьма(" in почта,
                "настройки почты: «Проверить» — фоновым заданием с опросом, без синхронной отправки")


