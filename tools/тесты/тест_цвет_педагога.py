"""Цвет педагога в карточке физ. лица: старое сохранённое имя «Королевскийголубой» не роняет карточку.

Карточка читала цвет как WebЦвета[Объект.Цвет] (ОбновитьВидимостьЭлементов при открытии), а запоминала имя,
собранное из представления цвета: у «Королевский голубой» ключ WebЦвета — «КоролевскиГолубой», и карточка
педагога с таким цветом не открывалась (та же ошибка, что №56 у помещений). Стало: запись — общей функцией
УЗ_ОбщийКлиентСервер.ИмяWebЦвета, чтение — WebЦветПоИмени (понимает и старые имена).

Код карточки клиентский — COM его не выполнит, поэтому тест проверяет три звена:
  1. факт платформы (самотест): WebЦвета по старому имени — ошибка; значит, старая строка карточки падала;
  2. модуль карточки (src_ext) не берёт WebЦвета[…] по сохранённому имени и читает/пишет цвет общими функциями
     (на старом модуле — красный);
  3. общая функция по цвету педагога из базы возвращает «Королевский голубой», ключ записи — «КоролевскиГолубой».
Карточка с таким педагогом открыта в веб-клиенте после исправления (стенд 8099).

    python tools\\тесты\\тест_цвет_педагога.py --база=C:\\1c_bases\\UZ_UNF_D
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить, текст_ошибки  # noqa: E402
from фабрика import Фабрика  # noqa: E402

МЕТКА = "УЗ тест цвета педагога"
МОДУЛЬ = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), "src_ext",
                      "Catalogs", "УЗ_ФизЛица", "Forms", "ФормаЭлемента", "Ext", "Form", "Module.bsl")


def сценарий(т):
    c = т.c
    ф = Фабрика(т, МЕТКА)
    педагог = ф.педагог("педагог", Цвет="Королевскийголубой")
    цвета = c.УЗ_ОбщийКлиентСервер

    try:
        getattr(c.WebЦвета, педагог.Цвет)
        старое_падает = False
        ошибка = ""
    except Exception as е:
        старое_падает = True
        ошибка = текст_ошибки(е, 120)
    т.проверить(старое_падает, "самотест: WebЦвета[«Королевскийголубой»] — ошибка (так падала старая карточка)", ошибка)

    with open(МОДУЛЬ, encoding="utf-8-sig") as ф_:
        код = ф_.read()
    код = "\n".join(с.split("//")[0] for с in код.splitlines())   # без комментариев
    т.проверить(not re.search(r"WebЦвета\[\s*Объект\.Цвет", код),
                "карточка физ. лица не берёт WebЦвета[Объект.Цвет] (сохранённое имя может быть старым)")
    т.проверить("УЗ_ОбщийКлиентСервер.WebЦветПоИмени(Объект.Цвет)" in код
                and "Объект.Цвет = УЗ_ОбщийКлиентСервер.ИмяWebЦвета(" in код,
                "карточка читает и пишет цвет общими функциями WebЦветПоИмени / ИмяWebЦвета")

    т.проверить(цвета.ИмяWebЦвета(цвета.WebЦветПоИмени(педагог.Цвет)) == "КоролевскиГолубой",
                "цвет педагога «Королевскийголубой» читается как «Королевский голубой», ключ записи «КоролевскиГолубой»")


if __name__ == "__main__":
    запустить("цвет_педагога", сценарий)
