"""Оповещения и напоминания УЗ_ext (замена напоминаний БСП), задолженность, почта.

  0. Предохранитель (N05, повторный аудит 28.09): тест идёт на копиях баз, где могут остаться рабочие SMTP,
     настоящие адреса и долги учеников. ДО любого действия: песочница почты сеанса включена (её включает
     сеанс.подключить — иначе тест не запустится), почта в копии принудительно выключена на время теста
     (настройки возвращаются уборкой), позиция журнала регистрации запомнена.
  1. ПолучитьОповещения на пустом для пользователя регистре — не дольше 50 мс (зовётся раз в минуту).
  2. Напоминание: наступившее выдаётся один раз за сеанс, будущее — нет, завершённое — нет.
  3. Регламентное УЗ_ПроверкаЗадолженности — только по тестовым ученикам (параметр Ученики: чужие ученики
     копии не получают ни оповещений, ни писем; проверяется, что общих оповещений о чужих не прибавилось):
     ученик с отрицательным остатком по УЗ_СписанияСуммЗаУроки получает оповещение; повторный запуск второго
     не заводит. «Оповещать о задолженности за 2 дня» — срок: долг трёхдневной давности оповещается, вчерашний — нет.
  3а. В12 — долг в разрезе организации (как взаиморасчёты в типовых), две свои организации А и Б: ученик
     с авансом 8 000 в А и долгом 1 000 в Б — одно оповещение, в Б, «Задолженность … (Б): 1 000,00» (было: общий
     остаток +7 000 — ни одного); ученик с долгами 500 в А и 1 000 в Б — два оповещения, по организации каждое
     (одинаковое время события — ключи записей различает измерение Организация); повторный запуск — ни одного
     нового; в письме — строка «Организация: Б.».
  4. Почта выключена: письмо о задолженности готовится (адрес, текст), но не отправляется; Отправить — Ложь,
     причина «выключена».
  5. Почта включена на выдуманный сервер smtp.example.invalid (домен .invalid не разрешается никогда) — путь
     письма до транспорта: задание заводит оповещение и отдаёт письмо песочнице (событие журнала
     «Учёт занятий.Почта.Песочница» с адресом ученика).
  6. Итог по журналу регистрации: за весь тест ни одной попытки отправки («Учёт занятий.Почта.Отправка»).
  7. Безопасный режим расширения: доступна ли интернет-почта (печатается для отчёта).

Всё, что создаёт, удаляет за собой (ученик, движение, настройки учёта и почты, оповещения).

    python tools\\тесты\\тест_оповещения.py --база=C:\\1c_bases\\UZ_UNF_C
"""
