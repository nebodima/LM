ПРЕДЕЛ_МС = 50
ИМЯ_УЧЕНИКА = "УЗ тест оповещений Сидорова Анна"
ДОЛГ = 1234.56
ДОЛГ_СТРОКОЙ = "1 234,56"      # как пишет продукт: Формат(Долг, "ЧДЦ=2; ЧН=0")
РЕГИСТРАТОР_ДОЛГА = "0b7e5a1c-7a3e-4c55-9d2e-5ea5e0a0d0c1"   # постоянный, чтобы уборка находила и после обрыва
РЕГИСТРАТОР_СВЕЖЕГО = "0b7e5a1c-7a3e-4c55-9d2e-5ea5e0a0d0c2"
РЕГИСТРАТОР_ОРГАНИЗАЦИЙ = "0b7e5a1c-7a3e-4c55-9d2e-5ea5e0a0d0c3"   # В12: движения учеников в двух организациях
МЕТКА_ОРГАНИЗАЦИЙ = "УЗ тест оповещений"
ИМЯ_СВЕЖЕГО = "УЗ тест оповещений Свежев Пётр"
СРОК_ДНЕЙ = 2
АДРЕС = "anna.test@example.invalid"
ВЫДУМАННЫЙ_SMTP = "smtp.example.invalid"          # RFC 2606: домен .invalid не разрешается никогда
ПОЛЯ_ПОЧТЫ = ("Включена", "СерверSMTP", "Порт", "ИспользоватьSSL", "Логин", "АдресОтправителя", "ИмяОтправителя",
              "ПисьмаОЗадолженности")                 # пароль тест не читает и не трогает


class Предохранитель(Exception):
    """Предохранитель почты не встал — сценарий дальше не идёт."""


def выключить_почту(т):
    """Почта копии выключается до сценария; прежние настройки (кроме пароля — он не меняется) — уборкой."""
    c = т.c
    з = c.РегистрыСведений.УЗ_НастройкиПочты.СоздатьМенеджерЗаписи()
    з.Идентификатор = c.УЗ_Почта.ИдентификаторНастроек()
    з.Прочитать()
    была = з.Выбран()
    прежние = {п: getattr(з, п) for п in ПОЛЯ_ПОЧТЫ} if была else None

    def вернуть():
        н = c.РегистрыСведений.УЗ_НастройкиПочты.СоздатьМенеджерЗаписи()
        н.Идентификатор = c.УЗ_Почта.ИдентификаторНастроек()
        н.Прочитать()
        if была:
            for п, в in прежние.items():
                setattr(н, п, в)
            н.Записать()
        elif н.Выбран():
            н.Удалить()
    т.убрать(вернуть, "настройки почты копии")
    настроить_почту(т, Включена=False)
    if c.УЗ_Почта.Настройки().Включена:
        raise Предохранитель("почта копии не выключилась")
    if прежние and прежние["Включена"]:
        print("  (почта копии была включена, сервер %s — на время теста выключена)" % прежние["СерверSMTP"])


def настроить_почту(т, **значения):
    c = т.c
    з = c.РегистрыСведений.УЗ_НастройкиПочты.СоздатьМенеджерЗаписи()
    з.Идентификатор = c.УЗ_Почта.ИдентификаторНастроек()
    з.Прочитать()
    з.Идентификатор = c.УЗ_Почта.ИдентификаторНастроек()
    for п, в in значения.items():
        setattr(з, п, в)
    з.Записать()


def чужие_общие_оповещения(т, свои, с_момента):
    """Общие (для всех) оповещения о долге, заведённые после момента, по ученикам не из теста."""
    return т.выбрать("""ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Число ИЗ РегистрСведений.УЗ_Оповещения КАК О
        ГДЕ О.Пользователь = &Пустой И О.ВремяСобытия >= &С И НЕ О.Источник В (&Свои)""",
                     Пустой=т.c.Справочники.Пользователи.ПустаяСсылка(), С=с_момента, Свои=свои).Получить(0).Число


def пробелы(текст):
    """Неразрывный пробел разделителя разрядов — как обычный (Формат ставит U+00A0)."""
    return текст.replace("\xa0", " ")


def записи_оповещений(т, источник):
    return т.выбрать("""ВЫБРАТЬ О.Источник, О.ВремяСобытия, О.Пользователь, О.Завершено, О.Описание, О.Организация
        ИЗ РегистрСведений.УЗ_Оповещения КАК О ГДЕ О.Источник = &Источник
        УПОРЯДОЧИТЬ ПО О.Описание""", Источник=источник)


def удалить_оповещения(т, источник):
    набор = т.c.РегистрыСведений.УЗ_Оповещения.СоздатьНаборЗаписей()
    набор.Отбор.Источник.Установить(источник)
    набор.Записать()


def в_ответе(ответ, источник, c):
    return any(c.String(о.Источник) == c.String(источник) for о in ответ.Оповещения)


def сценарий(т):
    c = т.c

    # ── 0. предохранитель: ДО любого действия ──
    т.проверить(c.УЗ_Почта.ПесочницаВключена(), "песочница почты включена в сеансе теста (письма не отправляются)")
    if not c.УЗ_Почта.ПесочницаВключена():
        raise Предохранитель("песочница почты не включена — сценарий не запускаю")
    журнал = позиция_журнала(т.база)
    if события_журнала(т.база, журнал, "Учёт занятий.Почта.Отправка") is None:
        raise Предохранитель("журнала регистрации нет (%s\\1Cv8Log) — доказать «писем не было» нечем" % т.база)
    выключить_почту(т)
    т.проверить(not c.УЗ_Почта.Настройки().Включена, "почта копии выключена на время теста")
    начало = c.ТекущаяДатаСеанса()

    # ── 1. скорость проверки на пустом регистре ──
    замеры = []
    for _ in range(10):
        н = time.perf_counter()
        ответ = c.УЗ_Сервер.ПолучитьОповещения(None)
        замеры.append((time.perf_counter() - н) * 1000)
    замеры.sort()
    медиана = замеры[len(замеры) // 2]
    print("  (ПолучитьОповещения: первый %.1f мс, медиана %.1f мс, наибольший %.1f мс; оповещений %d)"
          % (замеры[0], медиана, замеры[-1], ответ.Всего))
    т.проверить(медиана <= ПРЕДЕЛ_МС, "ПолучитьОповещения: не дольше %d мс" % ПРЕДЕЛ_МС, "%.1f мс" % медиана)
    параметры = c.УЗ_Сервер.ПараметрыОповещений()
    т.проверить(параметры.Включено and параметры.Период >= 30, "ПараметрыОповещений: показ включён, период",
                параметры.Период)

    ученик = c.Справочники.УЗ_ФизЛица.СоздатьЭлемент()
    ученик.Наименование = ИМЯ_УЧЕНИКА
    ученик.EMail = АДРЕС
    ученик.ОповеститьПоEmail = True
    ученик.Записать()
    ученик = ученик.Ссылка
    т.убрать(lambda: т.удалить_объект(ученик), "ученик")
    т.убрать(lambda: удалить_оповещения(т, ученик), "оповещения ученика")

    # ── 2. напоминание ──
    сейчас = ответ.Сейчас
    значения = c.УЗ_Сервер.ЗначенияНапоминания(ученик)
    т.проверить(c.String(значения.Пользователь) == c.String(c.УЗ_Среда.ТекущийПользователь())
                and значения.СрокНапоминания > значения.ВремяСобытия,
                "«Напомнить»: пользователь — текущий, срок позже создания")
    c.УЗ_Сервер.СоздатьНапоминание(ученик, сейчас - datetime.timedelta(minutes=1), "Позвонить маме Анны (тест)")
    будущий = c.УЗ_Сервер.СоздатьНапоминание(c.Справочники.УЗ_ФизЛица.ПустаяСсылка(),
                                             сейчас + datetime.timedelta(hours=2), "будущее (тест)")
    т.убрать(lambda: удалить_оповещения(т, c.Справочники.УЗ_ФизЛица.ПустаяСсылка()), "будущее напоминание")
    первый = c.УЗ_Сервер.ПолучитьОповещения(None)
    т.проверить(в_ответе(первый, ученик, c), "наступившее напоминание выдаётся при первой проверке сеанса")
    т.проверить(all("будущее" not in о.Описание for о in первый.Оповещения), "будущее напоминание не выдаётся")
    второй = c.УЗ_Сервер.ПолучитьОповещения(первый.Сейчас)
    т.проверить(not в_ответе(второй, ученик, c), "показанное напоминание не выдаётся повторно в том же сеансе")
    т.проверить(any(о.Ссылка.startswith("e1cib/") for о in первый.Оповещения),
                "у оповещения есть навигационная ссылка на запись")

    записи = записи_оповещений(т, ученик)
    ключ = c.РегистрыСведений.УЗ_Оповещения.СоздатьКлючЗаписи(c.NewObject("Структура",
        "Источник, ВремяСобытия, Пользователь, Завершено",
        записи.Получить(0).Источник, записи.Получить(0).ВремяСобытия, записи.Получить(0).Пользователь, False))
    c.УЗ_Сервер.ЗавершитьОповещения(т.массив(ключ))
    записи = записи_оповещений(т, ученик)
    т.проверить(записи.Количество() == 1 and записи.Получить(0).Завершено,
                "«Завершить»: запись одна и отмечена завершённой")
    т.проверить(not в_ответе(c.УЗ_Сервер.ПолучитьОповещения(None), ученик, c),
                "завершённое напоминание больше не выдаётся")
    удалить_оповещения(т, ученик)

    # ── 3. регламентное задание: задолженность ──
    организация = c.Справочники.Организации.Выбрать()
    организация.Следующий()
    # регистратор — постоянный «призрак»: если прошлый прогон убили до уборки, его движение этот же набор
    # (отбор по регистратору) перезапишет, а уборка снимет — сиротой навсегда оно не останется
    свежий = c.Справочники.УЗ_ФизЛица.СоздатьЭлемент()
    свежий.Наименование = ИМЯ_СВЕЖЕГО
    свежий.Записать()
    свежий = свежий.Ссылка
    т.убрать(lambda: т.удалить_объект(свежий), "ученик со свежим долгом")
    т.убрать(lambda: удалить_оповещения(т, свежий), "оповещения ученика со свежим долгом")

    def долг(гуид, клиент, дней_назад):
        регистратор = c.Документы.УЗ_СписаниеОстатков.ПолучитьСсылку(c.NewObject("УникальныйИдентификатор", гуид))
        движения = c.РегистрыНакопления.УЗ_СписанияСуммЗаУроки.СоздатьНаборЗаписей()
        движения.Отбор.Регистратор.Установить(регистратор)
        запись = движения.Добавить()
        запись.Период = сейчас - datetime.timedelta(days=дней_назад)
        запись.ВидДвижения = c.ВидДвиженияНакопления.Расход
        запись.Организация = организация.Ссылка
        запись.Клиент = клиент
        запись.Сумма = ДОЛГ
        движения.Записать()

        def убрать_движения():
            н = c.РегистрыНакопления.УЗ_СписанияСуммЗаУроки.СоздатьНаборЗаписей()
            н.Отбор.Регистратор.Установить(регистратор)
            н.Записать()
        т.убрать(убрать_движения, "движение задолженности")
    долг(РЕГИСТРАТОР_ДОЛГА, ученик, СРОК_ДНЕЙ + 1)
    долг(РЕГИСТРАТОР_СВЕЖЕГО, свежий, 1)

    настройка = c.РегистрыСведений.УЗ_Настройки.СоздатьМенеджерЗаписи()
    настройка.Прочитать()
    была = настройка.Выбран()
    прежние = (настройка.ИспользоватьОповещения, настройка.ОповещатьОЗадолженности) if была else None
    настройка.ИспользоватьОповещения = True
    настройка.ОповещатьОЗадолженности = СРОК_ДНЕЙ
    настройка.Записать()

    def вернуть_настройку():
        н = c.РегистрыСведений.УЗ_Настройки.СоздатьМенеджерЗаписи()
        н.Прочитать()
        if была:
            н.ИспользоватьОповещения, н.ОповещатьОЗадолженности = прежние
            н.Записать()
        else:
            н.Удалить()
    т.убрать(вернуть_настройку, "настройка оповещений")

    свои = т.массив(ученик, свежий)
    c.УЗ_Сервер.ПроверкаЗадолженности(свои)   # только тестовые ученики: чужие в копии не трогаем
    записи = записи_оповещений(т, ученик)
    т.проверить(записи.Количество() == 1, "задание: долг старше %d дней — оповещение" % СРОК_ДНЕЙ, записи.Количество())
    т.проверить(записи_оповещений(т, свежий).Количество() == 0,
                "задание: вчерашний долг при сроке %d дня — без оповещения (срок, а не вкл/выкл)" % СРОК_ДНЕЙ,
                записи_оповещений(т, свежий).Количество())
    if записи.Количество():
        з = записи.Получить(0)
        # точная строка: префикс, ученик, сумма в формате продукта (было «"1" in Описание» — единица есть везде)
        ждём = "Задолженность %s (%s): %s" % (ИМЯ_УЧЕНИКА, c.String(организация.Ссылка), ДОЛГ_СТРОКОЙ)
        т.проверить(з.Пользователь.Пустая() and пробелы(з.Описание) == ждём,
                    "оповещение о долге — для всех пользователей, точная сумма «%s»" % ДОЛГ_СТРОКОЙ,
                    "ждали «%s», получили «%s»" % (ждём, з.Описание))
    else:
        т.проверить(False, "оповещение о долге — для всех пользователей, точная сумма", "записи нет")
    c.УЗ_Сервер.ПроверкаЗадолженности(свои)
    т.проверить(записи_оповещений(т, ученик).Количество() == 1, "повторный запуск задания второе оповещение не заводит")
    т.проверить(в_ответе(c.УЗ_Сервер.ПолучитьОповещения(None), ученик, c), "оповещение о долге всплывает у пользователя")
    чужие = чужие_общие_оповещения(т, свои, начало)
    т.проверить(чужие == 0, "задание по тестовым ученикам: общих оповещений о чужих учениках копии не прибавилось",
                "прибавилось %d" % чужие)

    долги_по_организациям(т, сейчас)

    # ── 4. почта выключена ──
    письмо = c.УЗ_Почта.ПодготовитьПисьмоОЗадолженности(ученик, ДОЛГ)
    т.проверить(письмо.Адреса.Количество() == 1 and письмо.Адреса.Получить(0) == АДРЕС
                and "Сидорова Анна" in письмо.Текст
                and "задолженность %s руб." % ДОЛГ_СТРОКОЙ in пробелы(письмо.Текст),
                "письмо о задолженности: адрес ученика, имя и точная сумма «%s руб.»" % ДОЛГ_СТРОКОЙ, письмо.Текст)
    т.проверить(c.УЗ_Почта.ПисьмоОЗадолженности(ученик, ДОЛГ) is None,
                "почта выключена — письмо о задолженности не отправляется")
    # ТекстОшибки — выходной параметр, через COM не возвращается: причину берём строкой
    отправлено = c.УЗ_Почта.Отправить(АДРЕС, "тест", "тест", "")
    причина = c.УЗ_Почта.ПричинаНеготовности()
    т.проверить(not отправлено and "выключена" in причина,
                "почта не настроена: Отправить — Ложь, причина «выключена», письма нет", причина)

    # ── 5. почта включена на выдуманный сервер: письмо доходит до транспорта — и остаётся в песочнице ──
    настроить_почту(т, Включена=True, СерверSMTP=ВЫДУМАННЫЙ_SMTP, Порт=25, ИспользоватьSSL=False, Логин="",
                    АдресОтправителя="uz-test@example.invalid", ПисьмаОЗадолженности=True)
    удалить_оповещения(т, ученик)          # иначе задание не заведёт новое оповещение и письма не будет
    с_письма = позиция_журнала(т.база)
    c.УЗ_Сервер.ПроверкаЗадолженности(т.массив(ученик))
    настроить_почту(т, Включена=False)     # сразу обратно: дальше в тесте почта не нужна
    в_песочнице = [з for з in события_журнала(т.база, с_письма, "Учёт занятий.Почта.Песочница") if АДРЕС in з]
    т.проверить(len(в_песочнице) == 1 and "Задолженность за занятия" in в_песочнице[0],
                "почта включена: письмо о долге ушло в песочницу (журнал «Учёт занятий.Почта.Песочница», адрес ученика)",
                в_песочнице)

    # ── 6. итог: ни одной попытки отправки за весь тест ──
    попытки = события_журнала(т.база, журнал, "Учёт занятий.Почта.Отправка")
    т.проверить(попытки == [], "журнал: за тест ни одной попытки отправки письма («Учёт занятий.Почта.Отправка»)",
                попытки)

    # ── 7. безопасный режим ──
    доступность = c.УЗ_Почта.ДоступностьИнтернетПочты()
    print("  (интернет-почта: разрешена=%s, безопасный режим=%s: %s)"
          % (доступность.Разрешена, доступность.БезопасныйРежим, доступность.Текст[:120]))
    for р in c.РасширенияКонфигурации.Получить():
        if р.Имя == "УЗ_ext":
            print("  (расширение УЗ_ext: БезопасныйРежим=%s)" % р.БезопасныйРежим)


def долги_по_организациям(т, сейчас):
    """3а. В12: долг ученика — в разрезе организации. Две свои тестовые организации (фабрика), движения трёхдневной
    давности одним постоянным регистратором (уборка снимает их и после обрыва прошлого прогона)."""
    c = т.c
    ф = Фабрика(т, МЕТКА_ОРГАНИЗАЦИЙ)
    а = ф.организация("Студия А")
    б = ф.организация("Студия Б")
    аванс = ф.ученик("Авансов Иван")        # +8 000 в А, −1 000 в Б: общий остаток +7 000
    двойной = ф.ученик("Двойнов Олег")      # −500 в А, −1 000 в Б
    for у in (аванс, двойной):
        т.убрать(lambda у=у: удалить_оповещения(т, у), "оповещения ученика двух организаций")
    регистратор = c.Документы.УЗ_СписаниеОстатков.ПолучитьСсылку(c.NewObject("УникальныйИдентификатор",
                                                                            РЕГИСТРАТОР_ОРГАНИЗАЦИЙ))
    движения = c.РегистрыНакопления.УЗ_СписанияСуммЗаУроки.СоздатьНаборЗаписей()
    движения.Отбор.Регистратор.Установить(регистратор)
    for клиент, организация, сумма in ((аванс, а, 8000), (аванс, б, -1000), (двойной, а, -500), (двойной, б, -1000)):
        запись = движения.Добавить()
        запись.Период = сейчас - datetime.timedelta(days=СРОК_ДНЕЙ + 1)
        запись.ВидДвижения = c.ВидДвиженияНакопления.Приход if сумма > 0 else c.ВидДвиженияНакопления.Расход
        запись.Организация = организация
        запись.Клиент = клиент
        запись.Сумма = abs(сумма)
    движения.Записать()

    def убрать_движения():
        н = c.РегистрыНакопления.УЗ_СписанияСуммЗаУроки.СоздатьНаборЗаписей()
        н.Отбор.Регистратор.Установить(регистратор)
        н.Записать()
    т.убрать(убрать_движения, "движения учеников двух организаций")

    свои = т.массив(аванс, двойной)
    давно = datetime.datetime(2000, 1, 1, tzinfo=datetime.timezone.utc)
    чужих_до = чужие_общие_оповещения(т, свои, давно)   # все общие о чужих: секунда начала у раздела 3 та же
    c.УЗ_Сервер.ПроверкаЗадолженности(свои)
    записи = записи_оповещений(т, аванс)
    имя_б = c.String(б)
    ждём = "Задолженность %s (%s): 1 000,00" % (c.String(аванс), имя_б)
    т.проверить(записи.Количество() == 1 and c.String(записи.Получить(0).Организация) == имя_б
                and пробелы(записи.Получить(0).Описание) == ждём,
                "В12: аванс 8 000 в А не гасит долг 1 000 в Б — одно оповещение, в Б: «%s»" % ждём,
                "; ".join("%s [%s]" % (пробелы(з.Описание), c.String(з.Организация))
                          for з in (записи.Получить(н) for н in range(записи.Количество()))) or "оповещений нет")
    записи = записи_оповещений(т, двойной)
    по_организациям = sorted(c.String(записи.Получить(н).Организация) for н in range(записи.Количество()))
    т.проверить(по_организациям == sorted([c.String(а), имя_б]),
                "В12: долги 500 в А и 1 000 в Б — два оповещения, по организации каждое", по_организациям)
    c.УЗ_Сервер.ПроверкаЗадолженности(свои)
    т.проверить(записи_оповещений(т, аванс).Количество() == 1 and записи_оповещений(т, двойной).Количество() == 2,
                "В12: повторный запуск задания новых оповещений по организациям не заводит")
    чужие = чужие_общие_оповещения(т, свои, давно) - чужих_до
    т.проверить(чужие == 0, "В12: задание по тестовым ученикам — общих оповещений о чужих не прибавилось",
                "прибавилось %d" % чужие)
    письмо = c.УЗ_Почта.ПодготовитьПисьмоОЗадолженности(аванс, 1000, б)
    т.проверить("Организация: %s." % имя_б in письмо.Текст and "задолженность 1 000,00 руб." in пробелы(письмо.Текст),
                "В12: письмо о долге называет организацию: «Организация: %s.»" % имя_б, письмо.Текст)


