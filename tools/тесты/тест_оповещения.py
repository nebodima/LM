"""Оповещения и напоминания УЗ_ext (замена напоминаний БСП), задолженность, почта.

  1. ПолучитьОповещения на пустом для пользователя регистре — не дольше 50 мс (зовётся раз в минуту).
  2. Напоминание: наступившее выдаётся один раз за сеанс, будущее — нет, завершённое — нет.
  3. Регламентное УЗ_ПроверкаЗадолженности: ученик с отрицательным остатком по
     УЗ_СписанияСуммЗаУроки получает оповещение; повторный запуск второго не заводит.
  4. Почта: письмо о задолженности готовится (адрес, текст), но при выключенной почте не
     отправляется; Отправить без настроек — ошибка «выключена». Реальных писем нет.
  5. Безопасный режим расширения: доступна ли интернет-почта (печатается для отчёта).

Всё, что создаёт, удаляет за собой (ученик, движение, настройка, оповещения).

    python tools\\тесты\\тест_оповещения.py --база=C:\\1c_bases\\UZ_UNF_C
"""
import datetime
import os
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402

ПРЕДЕЛ_МС = 50
ИМЯ_УЧЕНИКА = "УЗ тест оповещений Сидорова Анна"
ДОЛГ = 1234.56
ДОЛГ_СТРОКОЙ = "1 234,56"      # как пишет продукт: Формат(Долг, "ЧДЦ=2; ЧН=0")
РЕГИСТРАТОР_ДОЛГА = "0b7e5a1c-7a3e-4c55-9d2e-5ea5e0a0d0c1"   # постоянный, чтобы уборка находила и после обрыва


def пробелы(текст):
    """Неразрывный пробел разделителя разрядов — как обычный (Формат ставит U+00A0)."""
    return текст.replace("\xa0", " ")


def записи_оповещений(т, источник):
    return т.выбрать("""ВЫБРАТЬ О.Источник, О.ВремяСобытия, О.Пользователь, О.Завершено, О.Описание
        ИЗ РегистрСведений.УЗ_Оповещения КАК О ГДЕ О.Источник = &Источник""", Источник=источник)


def удалить_оповещения(т, источник):
    набор = т.c.РегистрыСведений.УЗ_Оповещения.СоздатьНаборЗаписей()
    набор.Отбор.Источник.Установить(источник)
    набор.Записать()


def в_ответе(ответ, источник, c):
    return any(c.String(о.Источник) == c.String(источник) for о in ответ.Оповещения)


def сценарий(т):
    c = т.c

    # ── 1. скорость проверки на пустом регистре ──
    замеры = []
    for _ in range(10):
        н = time.perf_counter()
        ответ = c.УЗ_Сервер.ПолучитьОповещения(None)
        замеры.append((time.perf_counter() - н) * 1000)
    замеры.sort()
    медиана = замеры[len(замеры) // 2]
    print("  (ПолучитьОповещения: первый %.1f мс, медиана %.1f мс, наибольший %.1f мс; оповещений %d)"
          % (замеры[0], медиана, замеры[-1], ответ.Всего))
    т.проверить(медиана <= ПРЕДЕЛ_МС, "ПолучитьОповещения: не дольше %d мс" % ПРЕДЕЛ_МС, "%.1f мс" % медиана)
    параметры = c.УЗ_Сервер.ПараметрыОповещений()
    т.проверить(параметры.Включено and параметры.Период >= 30, "ПараметрыОповещений: показ включён, период",
                параметры.Период)

    ученик = c.Справочники.УЗ_ФизЛица.СоздатьЭлемент()
    ученик.Наименование = ИМЯ_УЧЕНИКА
    ученик.EMail = "anna.test@example.invalid"
    ученик.ОповеститьПоEmail = True
    ученик.Записать()
    ученик = ученик.Ссылка
    т.убрать(lambda: т.удалить_объект(ученик), "ученик")
    т.убрать(lambda: удалить_оповещения(т, ученик), "оповещения ученика")

    # ── 2. напоминание ──
    сейчас = ответ.Сейчас
    значения = c.УЗ_Сервер.ЗначенияНапоминания(ученик)
    т.проверить(c.String(значения.Пользователь) == c.String(c.УЗ_Среда.ТекущийПользователь())
                and значения.СрокНапоминания > значения.ВремяСобытия,
                "«Напомнить»: пользователь — текущий, срок позже создания")
    c.УЗ_Сервер.СоздатьНапоминание(ученик, сейчас - datetime.timedelta(minutes=1), "Позвонить маме Анны (тест)")
    будущий = c.УЗ_Сервер.СоздатьНапоминание(c.Справочники.УЗ_ФизЛица.ПустаяСсылка(),
                                             сейчас + datetime.timedelta(hours=2), "будущее (тест)")
    т.убрать(lambda: удалить_оповещения(т, c.Справочники.УЗ_ФизЛица.ПустаяСсылка()), "будущее напоминание")
    первый = c.УЗ_Сервер.ПолучитьОповещения(None)
    т.проверить(в_ответе(первый, ученик, c), "наступившее напоминание выдаётся при первой проверке сеанса")
    т.проверить(all("будущее" not in о.Описание for о in первый.Оповещения), "будущее напоминание не выдаётся")
    второй = c.УЗ_Сервер.ПолучитьОповещения(первый.Сейчас)
    т.проверить(not в_ответе(второй, ученик, c), "показанное напоминание не выдаётся повторно в том же сеансе")
    т.проверить(any(о.Ссылка.startswith("e1cib/") for о in первый.Оповещения),
                "у оповещения есть навигационная ссылка на запись")

    записи = записи_оповещений(т, ученик)
    ключ = c.РегистрыСведений.УЗ_Оповещения.СоздатьКлючЗаписи(c.NewObject("Структура",
        "Источник, ВремяСобытия, Пользователь, Завершено",
        записи.Получить(0).Источник, записи.Получить(0).ВремяСобытия, записи.Получить(0).Пользователь, False))
    c.УЗ_Сервер.ЗавершитьОповещения(т.массив(ключ))
    записи = записи_оповещений(т, ученик)
    т.проверить(записи.Количество() == 1 and записи.Получить(0).Завершено,
                "«Завершить»: запись одна и отмечена завершённой")
    т.проверить(not в_ответе(c.УЗ_Сервер.ПолучитьОповещения(None), ученик, c),
                "завершённое напоминание больше не выдаётся")
    удалить_оповещения(т, ученик)

    # ── 3. регламентное задание: задолженность ──
    организация = c.Справочники.Организации.Выбрать()
    организация.Следующий()
    # регистратор — постоянный «призрак»: если прошлый прогон убили до уборки, его движение этот же набор
    # (отбор по регистратору) перезапишет, а уборка снимет — сиротой навсегда оно не останется
    регистратор = c.Документы.УЗ_СписаниеОстатков.ПолучитьСсылку(
        c.NewObject("УникальныйИдентификатор", РЕГИСТРАТОР_ДОЛГА))
    движения = c.РегистрыНакопления.УЗ_СписанияСуммЗаУроки.СоздатьНаборЗаписей()
    движения.Отбор.Регистратор.Установить(регистратор)
    запись = движения.Добавить()
    запись.Период = сейчас - datetime.timedelta(days=1)
    запись.ВидДвижения = c.ВидДвиженияНакопления.Расход
    запись.Организация = организация.Ссылка
    запись.Клиент = ученик
    запись.Сумма = ДОЛГ
    движения.Записать()

    def убрать_движения():
        н = c.РегистрыНакопления.УЗ_СписанияСуммЗаУроки.СоздатьНаборЗаписей()
        н.Отбор.Регистратор.Установить(регистратор)
        н.Записать()
    т.убрать(убрать_движения, "движение задолженности")

    настройка = c.РегистрыСведений.УЗ_Настройки.СоздатьМенеджерЗаписи()
    настройка.Прочитать()
    была = настройка.Выбран()
    прежние = (настройка.ИспользоватьОповещения, настройка.ОповещатьОЗадолженности) if была else None
    настройка.ИспользоватьОповещения = True
    настройка.ОповещатьОЗадолженности = 1
    настройка.Записать()

    def вернуть_настройку():
        н = c.РегистрыСведений.УЗ_Настройки.СоздатьМенеджерЗаписи()
        н.Прочитать()
        if была:
            н.ИспользоватьОповещения, н.ОповещатьОЗадолженности = прежние
            н.Записать()
        else:
            н.Удалить()
    т.убрать(вернуть_настройку, "настройка оповещений")

    c.УЗ_Сервер.ПроверкаЗадолженности()
    записи = записи_оповещений(т, ученик)
    т.проверить(записи.Количество() == 1, "задание: должник получил оповещение", записи.Количество())
    if записи.Количество():
        з = записи.Получить(0)
        # точная строка: префикс, ученик, сумма в формате продукта (было «"1" in Описание» — единица есть везде)
        ждём = "Задолженность %s: %s" % (ИМЯ_УЧЕНИКА, ДОЛГ_СТРОКОЙ)
        т.проверить(з.Пользователь.Пустая() and пробелы(з.Описание) == ждём,
                    "оповещение о долге — для всех пользователей, точная сумма «%s»" % ДОЛГ_СТРОКОЙ,
                    "ждали «%s», получили «%s»" % (ждём, з.Описание))
    else:
        т.проверить(False, "оповещение о долге — для всех пользователей, точная сумма", "записи нет")
    c.УЗ_Сервер.ПроверкаЗадолженности()
    т.проверить(записи_оповещений(т, ученик).Количество() == 1, "повторный запуск задания второе оповещение не заводит")
    т.проверить(в_ответе(c.УЗ_Сервер.ПолучитьОповещения(None), ученик, c), "оповещение о долге всплывает у пользователя")

    # ── 4. почта ──
    письмо = c.УЗ_Почта.ПодготовитьПисьмоОЗадолженности(ученик, ДОЛГ)
    т.проверить(письмо.Адреса.Количество() == 1 and письмо.Адреса.Получить(0) == "anna.test@example.invalid"
                and "Сидорова Анна" in письмо.Текст
                and "задолженность %s руб." % ДОЛГ_СТРОКОЙ in пробелы(письмо.Текст),
                "письмо о задолженности: адрес ученика, имя и точная сумма «%s руб.»" % ДОЛГ_СТРОКОЙ, письмо.Текст)
    настройки_почты = c.УЗ_Почта.Настройки()
    if not настройки_почты.Включена:
        т.проверить(c.УЗ_Почта.ПисьмоОЗадолженности(ученик, ДОЛГ) is None,
                    "почта выключена — письмо о задолженности не отправляется")
        # ТекстОшибки — выходной параметр, через COM не возвращается: причину берём строкой
        отправлено = c.УЗ_Почта.Отправить("anna.test@example.invalid", "тест", "тест", "")
        причина = c.УЗ_Почта.ПричинаНеготовности()
        т.проверить(not отправлено and "выключена" in причина,
                    "почта не настроена: Отправить — Ложь, причина «выключена», письма нет", причина)
    else:
        print("  (почта в базе включена — проверка «не настроена» пропущена, писем не шлём)")

    # ── 5. безопасный режим ──
    доступность = c.УЗ_Почта.ДоступностьИнтернетПочты()
    print("  (интернет-почта: разрешена=%s, безопасный режим=%s: %s)"
          % (доступность.Разрешена, доступность.БезопасныйРежим, доступность.Текст[:120]))
    for р in c.РасширенияКонфигурации.Получить():
        if р.Имя == "УЗ_ext":
            print("  (расширение УЗ_ext: БезопасныйРежим=%s)" % р.БезопасныйРежим)


if __name__ == "__main__":
    запустить("оповещения", сценарий)
