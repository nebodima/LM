"""Бот Telegram для родителей и учеников, часть 1 — только чтение (версия 2.2.0.2): команды привязанного чата.

Заглушка сервисов на 127.0.0.1 (как в тест_каналы_сообщений): Telegram — на заглушку, каждый ответ бота виден.
  1. Приём (регламентное задание, getUpdates): «/расписание» от мамы (чат 5001) — одним sendMessage ответ с
     клавиатурой-кнопками (reply_markup.keyboard: Расписание, Долг, Абонемент, Помощь); журнал сообщений — вид
     «Ответ бота», канал Telegram, получатель мама, статус «Отправлено».
  2. Расписание мамы: занятия Ани (через 2 дня) и Бори (через 3 дня) — да; Ани через 9 дней (вне 7 дней) и чужого
     ученика Васи (завтра) — нет. Кнопка «Расписание» без косой черты — тот же ответ.
  3. Долг мамы: Аня «долг 1 500,00 руб.», Боря «оплачено вперёд 800,00 руб.», по организации; Васин долг не виден.
  4. Абонемент мамы: Аня «8 из 8 зан.» и «до <дата>»; Васин абонемент не виден.
  5. Ученица Аня (свой чат 5002): видит только себя — ни Бори, ни Васи.
  6. /помощь — список команд; незнакомый чат — «Попросите администратора прислать ссылку привязки», без клавиатуры.
  7. Telegram отвечает 503: ответ не ушёл, журнал «Ошибка»; в приёме следующим не отвечаем, смещение — по
     обработанному, остальные сообщения — в следующий приём.
Красное на старом коде (2.2.0.1): бот на команды не отвечал (ОбработатьСообщениеТелеграм → "").

    python tools\\тесты\\тест_бот_телеграм.py --база=C:\\1c_bases\\UZ_BP_T --пользователь=1
"""
# затрагивает: УЗ_Сообщения, УЗ_ПровайдерыСообщений, УЗ_ПривязкиКаналов, УЗ_ЖурналРассылки, УЗ_ФизЛица, УЗ_Абонемент
import datetime
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from _деньги import Данные  # noqa: E402
from фабрика import Фабрика  # noqa: E402
import тест_оповещения as оп  # noqa: E402
from тест_каналы_сообщений import Заглушка, КЛЮЧИ, привязать, сохранить_настройки  # noqa: E402

МЕТКА = "_Тест бот Telegram"
НЕЗНАКОМЫЙ = "Попросите администратора прислать ссылку привязки"


def сценарий(т):
    c = т.c
    if not c.УЗ_Почта.ПесочницаВключена():
        raise RuntimeError("песочница не включена — сценарий не запускаю")
    if c.УЗ_Общий.БезопасныйРежимДействует():
        print("  (стенд в безопасном режиме: HTTP к заглушке недоступен — тест бота пропущен)")
        т.проверить(False, "стенд без безопасного режима расширения (нужен HTTP к заглушке)")
        return
    оп.выключить_почту(т)
    зг = Заглушка()
    т.убрать(зг.сервер.shutdown, "заглушка сервисов")
    сохранить_настройки(т)
    К = c.Перечисления.УЗ_КаналыСообщений
    П = c.Перечисления.УЗ_ПровайдерыСообщений
    ст = c.String

    д_ = c.NewObject("Структура")
    for к, в in dict(Включен=True, Провайдер=П.TelegramBotAPI, АдресСервиса=зг.адрес + "/tg", Логин="",
                     Отправитель="", ИмяБота="uz_test_bot").items():
        д_.Вставить(к, в)
    c.УЗ_Сообщения.СохранитьНастройкиКанала(К.Телеграм, д_, КЛЮЧИ["Телеграм"], True)

    д = Данные(т, МЕТКА)
    ф = Фабрика(т, МЕТКА)
    люди = []

    def человек(имя, плательщики=()):
        о = c.Справочники.УЗ_ФизЛица.СоздатьЭлемент()
        о.Наименование = "%s %s" % (МЕТКА, имя)
        о.ОповеститьПоEmail = True
        for кто, кем, основной in плательщики:
            с = о.Плательщики.Добавить()
            с.Плательщик, с.КемПриходится, с.Основной = кто, кем, основной
        о.Записать()
        ссылка = о.Ссылка
        люди.append(ссылка)
        т.убрать(lambda: т.удалить_объект(ссылка), "физ. лицо %s" % имя, пакет=True)
        return ссылка

    def убрать_журнал_и_привязки():
        for у in люди:
            for поле in ("Ученик", "Получатель"):
                н = c.РегистрыСведений.УЗ_ЖурналРассылки.СоздатьНаборЗаписей()
                getattr(н.Отбор, поле).Установить(у)
                н.Записать()
            н = c.РегистрыСведений.УЗ_ПривязкиКаналов.СоздатьНаборЗаписей()
            н.Отбор.ФизЛицо.Установить(у)
            н.Записать()
    т.убрать(убрать_журнал_и_привязки, "журнал сообщений и привязки теста")

    мама = человек("мама")
    чужая = человек("чужая мама")
    аня = человек("Аня", плательщики=[(мама, "мама", True)])
    боря = человек("Боря", плательщики=[(мама, "мама", True)])
    вася = человек("Вася", плательщики=[(чужая, "мама", True)])
    привязать(c, мама, "5001")
    привязать(c, аня, "5002")
    привязать(c, чужая, "5003")

    орг = ф.организация("Студия бота")
    педагог = ф.педагог()
    предмет = ф.элемент("УЗ_ПредметыОбучения", "скрипка")
    уроки = {}
    for имя, кто, дней in (("аня2", аня, 2), ("боря3", боря, 3), ("аня9", аня, 9), ("вася1", вася, 1)):
        у = ф.урок(педагог, ф.день(дней, 17, 30 + (дней % 3) * 5), ПредметОбучения=предмет, Организация=орг,
                   строки=[{"Ученик": кто}])
        ош, _ = ф.записать(у, "Запись")
        т.проверить(ош is None, "урок %s записан" % имя, ош)
        уроки[имя] = у
    сейчас = c.ТекущаяДатаСеанса()
    д.движения("УЗ_СписанияСуммЗаУроки", д.регистратор(), [
        ("-", сейчас - datetime.timedelta(days=3), {"Клиент": аня, "Сумма": 1500, "Организация": орг}),
        ("+", сейчас - datetime.timedelta(days=3), {"Клиент": боря, "Сумма": 800, "Организация": орг}),
        ("-", сейчас - datetime.timedelta(days=3), {"Клиент": вася, "Сумма": 3000, "Организация": орг})])
    срок = ф.день(40)
    ф.абонемент(аня, "восемь занятий", ПредметОбучения=предмет, Организация=орг, КоличествоЗанятий=8,
                ДатаОкончания=срок)
    ф.абонемент(вася, "васин", ПредметОбучения=предмет, Организация=орг, КоличествоЗанятий=4)

    def дата_урока(имя):
        д_у = уроки[имя].Дата
        return "%02d.%02d %02d:%02d" % (д_у.day, д_у.month, д_у.hour, д_у.minute)

    def бот(чат, текст):
        return ст(c.УЗ_Сообщения.ОбработатьСообщениеТелеграм(чат, текст)).replace("\xa0", " ")

    # ── 1. приём через getUpdates: ответ с клавиатурой, журнал ──
    настройка = c.РегистрыСведений.УЗ_НастройкиКаналов.СоздатьМенеджерЗаписи()
    настройка.Канал = К.Телеграм
    настройка.Прочитать()
    настройка.СмещениеОбновлений = 899
    настройка.Записать()
    зг.сброс()
    зг.вызвать("/__обновления", [{"update_id": 900, "message": {"chat": {"id": 5001}, "text": "/расписание",
                                                                 "from": {"first_name": "Мама"}}}])
    c.УЗ_Сообщения.ПриемСообщенийТелеграм()
    ответы = зг.запросы("/sendMessage")
    тело = ответы[0]["тело"] if ответы else {}
    кнопки = [к_.get("text") for ряд in ((тело.get("reply_markup") or {}).get("keyboard") or []) for к_ in ряд]
    т.проверить(len(ответы) == 1 and str(тело.get("chat_id")) == "5001" and дата_урока("аня2") in тело.get("text", ""),
                "приём getUpdates: «/расписание» мамы — один ответ в чат 5001 с занятием Ани", ответы)
    т.проверить(кнопки == ["Расписание", "Долг", "Абонемент", "Помощь"],
                "ответ с клавиатурой-кнопками: Расписание, Долг, Абонемент, Помощь", тело.get("reply_markup"))
    строки = т.выбрать("""ВЫБРАТЬ Ж.Вид КАК Вид, Ж.Канал КАК Канал, Ж.Статус КАК Статус, Ж.Адреса КАК Адреса
        ИЗ РегистрСведений.УЗ_ЖурналРассылки КАК Ж ГДЕ Ж.Получатель = &П""", П=мама)
    т.проверить([(ст(з.Вид), ст(з.Канал), ст(з.Статус), ст(з.Адреса)) for з in строки]
                == [("Ответ бота Telegram", "Telegram", "Отправлено", "5001")],
                "журнал сообщений: «Ответ бота», Telegram, получатель мама, «Отправлено»",
                [(ст(з.Вид), ст(з.Канал), ст(з.Статус)) for з in строки])

    # ── 2. расписание: свои ученики на 7 дней ──
    р = бот("5001", "/расписание")
    т.проверить(дата_урока("аня2") in р and дата_урока("боря3") in р and "Аня" in р and "Боря" in р,
                "расписание мамы: занятия Ани и Бори на 7 дней", р)
    т.проверить(дата_урока("аня9") not in р and дата_урока("вася1") not in р and "Вася" not in р,
                "расписание мамы: занятие через 9 дней и чужой ученик Вася — не видны", р)
    т.проверить(бот("5001", "Расписание") == р, "кнопка «Расписание» — тот же ответ, что /расписание")

    # ── 3. долг по организации ──
    р = бот("5001", "/долг")
    т.проверить("долг 1 500,00 руб." in р and "оплачено вперёд 800,00 руб." in р and "Студия бота" in р,
                "долг мамы: Аня — долг 1 500,00 руб., Боря — оплачено вперёд 800,00 руб., по организации", р)
    т.проверить("Вася" not in р and "3 000" not in р, "Васин долг маме не виден", р)

    # ── 4. абонемент ──
    р = бот("5001", "Абонемент")
    т.проверить("8 из 8 зан." in р and срок.strftime("%d.%m.%Y") in р and "Аня" in р,
                "абонемент Ани: осталось 8 из 8 зан., срок", р)
    т.проверить("васин" not in р and "Вася" not in р, "Васин абонемент маме не виден", р)

    # ── 5. ученица видит только себя ──
    р = бот("5002", "/расписание") + бот("5002", "/долг") + бот("5002", "/абонемент")
    т.проверить("Аня" in р and "Боря" not in р and "Вася" not in р and "800" not in р,
                "ученица Аня (свой чат) — только о себе: ни Бори, ни Васи", р)
    р = бот("5003", "/долг")
    т.проверить("Вася" in р and "Аня" not in р and "Боря" not in р, "чужая мама — только Вася", р)

    # ── 6. помощь и незнакомый чат ──
    р = бот("5001", "/помощь")
    т.проверить(all(к_ in р for к_ in ("/расписание", "/долг", "/абонемент", "/stop")), "помощь — список команд", р)
    зг.сброс()
    р = бот("5999", "/долг")
    тело = (зг.запросы("/sendMessage") or [{"тело": {}}])[0]["тело"]
    т.проверить(НЕЗНАКОМЫЙ in р and "долг" not in р.lower().replace("попросите", "") and "reply_markup" not in тело,
                "незнакомый чат — «Попросите администратора прислать ссылку привязки», без данных и клавиатуры", р)

    # ── 7. сбой Telegram ──
    зг.сброс()
    зг.вызвать("/__сбой", {"префикс": "/tg", "код": 503})
    р = бот("5001", "/долг")
    з = т.выбрать("""ВЫБРАТЬ ПЕРВЫЕ 1 Ж.Статус КАК Статус, Ж.ТекстОшибки КАК Ошибка
        ИЗ РегистрСведений.УЗ_ЖурналРассылки КАК Ж ГДЕ Ж.Получатель = &П УПОРЯДОЧИТЬ ПО Ж.Период УБЫВ""", П=мама)
    т.проверить("1 500,00" in р and з.Количество() == 1 and ст(з.Получить(0).Статус) == "Ошибка"
                and "503" in ст(з.Получить(0).Ошибка), "Telegram 503: ответ не ушёл — журнал «Ошибка» с кодом",
                None if з.Количество() == 0 else ст(з.Получить(0).Ошибка))
    # приём при сбое: первому ответ не ушёл — остальные сообщения ждут следующего приёма (смещение — по обработанному)
    настройка = c.РегистрыСведений.УЗ_НастройкиКаналов.СоздатьМенеджерЗаписи()
    настройка.Канал = К.Телеграм
    настройка.Прочитать()
    настройка.СмещениеОбновлений = 909
    настройка.Записать()
    зг.сброс()
    зг.вызвать("/__сбой", {"префикс": "/tg/bot%s/sendMessage" % КЛЮЧИ["Телеграм"], "код": 503})
    зг.вызвать("/__обновления", [{"update_id": 910, "message": {"chat": {"id": 5001}, "text": "/долг"}},
                                 {"update_id": 911, "message": {"chat": {"id": 5002}, "text": "/долг"}}])
    c.УЗ_Сообщения.ПриемСообщенийТелеграм()
    смещение = ст(c.УЗ_Сообщения.НастройкиКанала(К.Телеграм).СмещениеОбновлений)
    т.проверить(len(зг.запросы("/sendMessage")) == 1 and смещение == "910",
                "приём при сбое Telegram: второму не отвечаем, смещение 910 — сообщение 911 придёт в следующий приём",
                (len(зг.запросы("/sendMessage")), смещение))
    зг.вызвать("/__сбой", {"префикс": "/tg/bot%s/sendMessage" % КЛЮЧИ["Телеграм"], "код": 0})
    зг.сброс()
    зг.вызвать("/__обновления", [{"update_id": 911, "message": {"chat": {"id": 5002}, "text": "/долг"}}])
    c.УЗ_Сообщения.ПриемСообщенийТелеграм()
    ответы = зг.запросы("/sendMessage")
    т.проверить(len(ответы) == 1 and str(ответы[0]["тело"]["chat_id"]) == "5002"
                and ст(c.УЗ_Сообщения.НастройкиКанала(К.Телеграм).СмещениеОбновлений) == "911",
                "следующий приём: сообщению 911 ответили, смещение 911", ответы)


if __name__ == "__main__":
    запустить("тест_бот_телеграм", сценарий)
