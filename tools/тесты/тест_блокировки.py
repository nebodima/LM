"""Управляемые блокировки при чтении остатков в проведении (Codex A11, учёт №24, внешний ревьюер).

Правило: в проведении каждый запрос выполняется после БлокировкаДанных.Заблокировать(), и блокировка
стоит на тот регистр накопления, который запрос читает. Иначе два сеанса одновременно видят один
остаток и оба его расходуют.

Почему по исходникам, а не поведением: на файловой базе транзакция одного COM-сеанса блокирует всю
базу («Ошибка разделенного доступа», проверено 28.09.2026) — гонку двух сеансов на стенде не
воспроизвести, она возможна только в клиент-серверной базе. Поэтому тест разбирает модули объектов
документов из src_ext: процедуры, достижимые из ОбработкаПроведения, и их запросы.

Документы без чтения остатков в своём модуле (списание остатков, начисление бонусов) блокировку
не требуют: запись набора сама ставит исключительную блокировку на свои записи. Если туда добавят
чтение остатков без блокировки — тест покраснеет. С 28.09.2026 (логики оплат и кассы) остатки кассы и карт
в проведении читают общие функции — Справочники.УЗ_Кассы.ДоступныйОстатокДляРасхода (через ПроверитьОстаткиКасс)
и Документы.УЗ_ПриходДенег.ПроверитьСписаниеБонусов: блокировку они ставят сами, до запроса (в транзакции);
деньги ученика — УЗ_Сервер.ЗаблокироватьДеньгиУченика перед УЗ_Сервер.ОстатокДенегУченика.

Мутация (проверена 28.09.2026): убрать Блокировка.Заблокировать() в перемещении → красный.
УЗ_Урок и УЗ_ПриходДенег ведёт другая задача — здесь не проверяются.
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402

КОРЕНЬ = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "src_ext"))
# документ → читает ли остатки в проведении (Истина — обязан читать и блокировать)
ДОКУМЕНТЫ = {
    "УЗ_ПеремещениеДенег": True,
    "УЗ_РасчетЗарплаты": True,
    "УЗ_РасходДенег": True,      # выплата по расчёту зарплаты: сколько уже выплачено
    "УЗ_СписаниеОстатков": False,
    "УЗ_НачислениеБонусов": False,
}
ПРОЦЕДУРА = re.compile(r"^\s*(?:Процедура|Функция)\s+(\w+)\s*\((.*?)^\s*(?:КонецПроцедуры|КонецФункции)",
                       re.M | re.S)


def без_комментариев(текст):
    return "\n".join(с.split("//", 1)[0] if not с.lstrip().startswith("|") else с for с in текст.splitlines())


def процедуры(текст):
    return {м.group(1): м.group(2) for м in ПРОЦЕДУРА.finditer(без_комментариев(текст))}


def достижимые(проц, начало):
    итог, очередь = set(), [начало]
    while очередь:
        имя = очередь.pop()
        if имя in итог or имя not in проц:
            continue
        итог.add(имя)
        очередь += [в for в in re.findall(r"\b(\w+)\s*\(", проц[имя]) if в in проц]
    return итог


def разбор(документ):
    """[(процедура, регистры в запросе, блокируемые регистры, блокировка до Выполнить)] для запросов проведения."""
    путь = os.path.join(КОРЕНЬ, "Documents", документ, "Ext", "ObjectModule.bsl")
    with open(путь, encoding="utf-8-sig") as ф:
        проц = процедуры(ф.read())
    итог = []
    for имя in sorted(достижимые(проц, "ОбработкаПроведения")):
        тело = проц[имя]
        if ".Выполнить(" not in тело:
            continue
        регистры = set(re.findall(r"РегистрНакопления\.(\w+)", re.sub(r'Добавить\("[^"]*"\)', "", тело)))
        блокируемые = set(re.findall(r'Добавить\("РегистрНакопления\.(\w+)"\)', тело))
        заблокировать = тело.find(".Заблокировать()")
        выполнить = тело.find(".Выполнить(")
        итог.append((имя, регистры, блокируемые, 0 <= заблокировать < выполнить))
    return итог


def сценарий(т):
    for документ, читает in ДОКУМЕНТЫ.items():
        запросы = разбор(документ)
        if not читает:
            т.проверить(not запросы, "%s: в проведении нет чтения остатков — блокировка не нужна" % документ,
                        [з[0] for з in запросы])
            continue
        т.проверить(bool(запросы), "%s: проведение читает остатки (проверка не пустая)" % документ)
        for имя, регистры, блокируемые, до in запросы:
            т.проверить(до, "%s.%s: БлокировкаДанных.Заблокировать() до выполнения запроса" % (документ, имя))
            т.проверить(регистры <= блокируемые,
                        "%s.%s: блокируются читаемые регистры %s" % (документ, имя, ", ".join(sorted(регистры))),
                        "заблокированы: %s" % (", ".join(sorted(блокируемые)) or "ничего"))


if __name__ == "__main__":
    запустить("блокировки", сценарий)
