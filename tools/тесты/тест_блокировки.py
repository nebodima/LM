"""Управляемые блокировки при чтении остатков в проведении (Codex A11, учёт №24, внешний ревьюер; ревью логик 28.09 —
T04, R21, R22).

Правило: в транзакции записи документа каждый запрос к регистру накопления выполняется после
БлокировкаДанных.Заблокировать() на этот регистр. Иначе два сеанса одновременно видят один остаток и оба его
расходуют (или один считает цену, пока другой расходует абонемент).

Почему по исходникам, а не поведением: на файловой базе транзакция одного COM-сеанса блокирует всю базу («Ошибка
разделенного доступа», проверено 28.09.2026) — гонку двух сеансов на стенде не воспроизвести, она возможна только в
клиент-серверной базе. Поэтому тест разбирает исходники src_ext.

T04 (ревью 28.09): прежде читался только модуль объекта документа, а с централизацией остатки читают общие функции
(менеджер касс, менеджер ПКО, УЗ_Сервер, менеджер абонемента) — удаление блокировки из них тест не замечал. Теперь
обход идёт по вызовам: от ПередЗаписью и ОбработкаПроведения документа — в его процедуры, в модули менеджеров
(Справочники.X.Ф(), Документы.X.Ф(), РегистрыСведений.X.Ф()) и общие модули (УЗ_X.Ф()), с учётом порядка: блокировка,
поставленная раньше в вызывающей процедуре (или в процедуре, вызванной раньше), действует до конца транзакции.
Запросы, читающие только СВОИ движения документа (Регистратор = &Ссылка), — не остатки, блокировки не требуют.

Ещё два правила порядка (ревью 28.09):
  R21 урок: остаток абонементов блокируется в ПередЗаписью ДО расчёта цен строк (хвост абонемента считается по
      заблокированному остатку, а не до блокировки);
  R22 абонемент: запись приостановок блокирует движения абонемента (тот же ключ, что проведение урока) ДО проверки
      проведённых уроков — заморозка и проведение урока по одному абонементу идут по очереди.

Мутации (28.09.2026): убрать Блокировка.Заблокировать() в перемещении → красный; убрать блокировку из
Справочники.УЗ_Кассы.ДоступныйОстатокДляРасхода → красный (T04: старый тест оставался зелёным).
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402

КОРЕНЬ = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "src_ext"))
# документ → читает ли остатки регистров накопления в транзакции записи (Истина — обязан и блокировать)
ДОКУМЕНТЫ = {
    "УЗ_ПеремещениеДенег": True,
    "УЗ_РасчетЗарплаты": True,       # начисления источников (R03: сверка с текущими движениями)
    "УЗ_РасходДенег": True,
    "УЗ_СписаниеОстатков": True,     # касса через Справочники.УЗ_Кассы.ПроверитьОстаткиКасс, бонусы — через ПКО
    "УЗ_НачислениеБонусов": True,    # находка 3 аудита Codex 3: уменьшение/отмена — остаток карты (ПроверитьИзъятиеБонусов)
    "УЗ_ПриходДенег": True,
    "УЗ_Урок": True,
    "УЗ_НачислениеУченику": False,
    "УЗ_НачисленияПедагогам": False,
    "УЗ_ДополнительныеРасходы": False,
}
КОЛЛЕКЦИИ = {"Справочники": "Catalogs", "Документы": "Documents", "Обработки": "DataProcessors",
             "РегистрыСведений": "InformationRegisters", "РегистрыНакопления": "AccumulationRegisters"}
ПРОЦЕДУРА = re.compile(r"^\s*(?:Процедура|Функция)\s+(\w+)\s*\((.*?)^\s*(?:КонецПроцедуры|КонецФункции)",
                       re.M | re.S)
ВЫЗОВ = re.compile(r"(?:\b(Справочники|Документы|Обработки|РегистрыСведений|РегистрыНакопления)\.(\w+)\.(\w+)"
                   r"|\b(УЗ_\w+)\.(\w+)|(?<![.\w])(\w+))\s*\(")
_кэш = {}


def без_комментариев(текст):
    return "\n".join(с.split("//", 1)[0] if not с.lstrip().startswith("|") else с for с in текст.splitlines())


def модуль(путь):
    """{процедура: тело} модуля (пусто — нет файла)."""
    if путь not in _кэш:
        полный = os.path.join(КОРЕНЬ, путь)
        _кэш[путь] = {}
        if os.path.isfile(полный):   # «УЗ_Касса.Добавить(» — движения, а не общий модуль: файла нет
            with open(полный, encoding="utf-8-sig") as ф:
                _кэш[путь] = {м.group(1): м.group(2) for м in ПРОЦЕДУРА.finditer(без_комментариев(ф.read()))}
    return _кэш[путь]


def цель(текущий, м):
    """(путь модуля, процедура) вызова или None."""
    if м.group(1):
        return os.path.join(КОЛЛЕКЦИИ[м.group(1)], м.group(2), "Ext", "ManagerModule.bsl"), м.group(3)
    if м.group(4):
        return os.path.join("CommonModules", м.group(4), "Ext", "Module.bsl"), м.group(5)
    if м.group(6) in модуль(текущий):
        return текущий, м.group(6)
    return None


def читаемые(тело):
    """Регистры накопления, которые читают запросы процедуры (своих движений «Регистратор = &Ссылка» не считаем)."""
    текст = re.sub(r'Добавить\("[^"]*"\)', "", тело)
    if re.search(r"Регистратор\s*=\s*&Ссылка", текст) and not re.search(r"\.(Остатки|ОстаткиИОбороты)\(", текст):
        return set()
    return set(re.findall(r"РегистрНакопления\.(\w+)", текст))


def обход(путь, имя, заблокировано, нарушения, запросы, стек):
    """Идёт по телу процедуры по порядку: блокировки копятся (до конца транзакции), вызовы — вглубь, у каждого
    Выполнить — читаемые регистры должны быть уже заблокированы. Возврат — множество блокировок после процедуры."""
    тело = модуль(путь).get(имя)
    if тело is None or (путь, имя) in стек:
        return заблокировано
    стек = стек | {(путь, имя)}
    заблокировано = set(заблокировано)
    ожидают = set()
    события = []
    for м in re.finditer(r'Добавить\("РегистрНакопления\.(\w+)"\)', тело):
        события.append((м.start(), "добавить", м.group(1)))
    for м in re.finditer(r"\.Заблокировать\(\)", тело):
        события.append((м.start(), "заблокировать", None))
    for м in re.finditer(r"\.Выполнить(?:Пакет)?\(", тело):
        события.append((м.start(), "выполнить", None))
    for м in ВЫЗОВ.finditer(тело):
        ц = цель(путь, м)
        if ц is not None and ц != (путь, имя):
            события.append((м.start(), "вызов", ц))
    регистры = читаемые(тело)
    for _, вид, значение in sorted(события, key=lambda с: с[0]):
        if вид == "добавить":
            ожидают.add(значение)
        elif вид == "заблокировать":
            заблокировано |= ожидают
            ожидают = set()
        elif вид == "выполнить" and регистры:
            запросы.add((путь, имя))
            нет = регистры - заблокировано
            if нет:
                нарушения.add((путь, имя, ", ".join(sorted(нет))))
        elif вид == "вызов":
            заблокировано = обход(значение[0], значение[1], заблокировано, нарушения, запросы, стек)
    return заблокировано


def разбор(документ):
    """(нарушения, процедуры с чтением остатков) — от ПередЗаписью, затем ОбработкаПроведения документа."""
    путь = os.path.join("Documents", документ, "Ext", "ObjectModule.bsl")
    нарушения, запросы = set(), set()
    заблокировано = set()
    for начало in ("ПередЗаписью", "ОбработкаПроведения"):
        заблокировано = обход(путь, начало, заблокировано, нарушения, запросы, frozenset())
    return нарушения, запросы


def порядок(путь, процедура, раньше, позже):
    """Позиция первого вхождения шаблона раньше < позиции позже в теле процедуры (None — тела нет)."""
    тело = модуль(путь).get(процедура)
    if тело is None:
        return None
    а, б = re.search(раньше, тело), re.search(позже, тело)
    return а is not None and б is not None and а.start() < б.start()


def сценарий(т):
    for документ, читает in ДОКУМЕНТЫ.items():
        нарушения, запросы = разбор(документ)
        if not читает:
            т.проверить(not запросы, "%s: в транзакции записи нет чтения остатков — блокировка не нужна" % документ,
                        sorted(п for _, п in запросы))
            continue
        т.проверить(bool(запросы), "%s: в транзакции записи читаются остатки (проверка не пустая): %s"
                    % (документ, ", ".join(sorted(п for _, п in запросы))))
        т.проверить(not нарушения, "%s: каждый запрос к регистру накопления — после его блокировки (с общими "
                    "функциями по вызовам)" % документ,
                    "; ".join("%s → %s: не заблокировано %s" % (os.path.dirname(os.path.dirname(п)), и, р)
                              for п, и, р in sorted(нарушения)))

    урок = os.path.join("Documents", "УЗ_Урок", "Ext", "ObjectModule.bsl")
    т.проверить(порядок(урок, "ПередЗаписью", r"ЗаблокироватьОстаткиАбонементов\(", r"РассчитатьТабличнуюЧасть\("),
                "R21: урок — остаток абонементов заблокирован в ПередЗаписью до расчёта цен строк (хвост В25)")
    абонемент = os.path.join("Catalogs", "УЗ_Абонемент", "Ext", "ObjectModule.bsl")
    т.проверить(порядок(абонемент, "ПередЗаписью", r'Добавить\("РегистрНакопления\.УЗ_СписанияСуммЗаУроки"\)[\s\S]*?'
                        r"\.Заблокировать\(\)", r"ОшибкиПриостановок\("),
                "R22: абонемент — движения абонемента заблокированы до проверки приостановок поверх проведённых уроков")


if __name__ == "__main__":
    запустить("блокировки", сценарий)
