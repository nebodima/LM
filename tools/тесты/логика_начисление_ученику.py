"""Начисление ученику (решение В15; docs/логики/оплаты.md сц. 13, доп_расходы.md ВР1): набор, материалы, взнос уменьшают
баланс ученика по предмету в организации документа (УЗ_СписанияСуммЗаУроки, Расход), кассу не меняют.

Сценарии (организация А — своя тестовая; на старом коде документа не было — красные все):
  Н1  набор робототехники 5 000 ученику без аванса → остаток −5 000, долг к оплате 5 000; касса без движений.
  Н2  ПКО 5 000 по робототехнике → остаток 0, долг 0; 5 уроков съедают только оплату уроков, не набор.
  Н3  сумма 0, без статьи, без ученика → отказ.
  Н4  на основании ученика: ученик и организация по умолчанию заполнены.
  Н5  отмена проведения → долг за набор исчезает; документ без организации получает организацию по умолчанию.
  Н6  у менеджера («Учёт занятий: менеджер») права на начисление — рабочий набор роли; живой сеанс менеджера создаёт
      и проводит начисление в tools/тесты/тест_права.py («проводит начисление ученику»).

    python tools\\тесты\\логика_начисление_ученику.py --база=C:\\1c_bases\\UZ_UNF_C
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import дата, запустить, текст_ошибки  # noqa: E402
from _деньги import Данные  # noqa: E402
from фабрика import Фабрика  # noqa: E402

МЕТКА = "_Тест начисление ученику"


def сценарий(т):
    c = т.c
    д = Данные(т, МЕТКА)
    ф = Фабрика(т, МЕТКА)
    орг = ф.организация("А")
    ученик = д.элемент("УЗ_ФизЛица", "ученик")
    робототехника = д.элемент("УЗ_ПредметыОбучения", "робототехника")
    набор = д.элемент("УЗ_СтатьиДвиженияДенег", "набор робототехники")
    касса = д.элемент("УЗ_Кассы", "касса")

    def остаток():
        return float(c.УЗ_Сервер.ОстатокДенегУченика(ученик, орг, робототехника))

    def начисление(сумма, **поля):
        for ключ, значение in (("ФизЛицо", ученик), ("ПредметОбучения", робототехника), ("Организация", орг),
                               ("СтатьяЗатрат", набор)):
            поля.setdefault(ключ, значение)
        н = д.документ("УЗ_НачислениеУченику", Дата=поля.pop("Дата", дата(2026, 9, 5, 10)), Сумма=сумма, **поля)
        return н, д.записать(н)

    # ── Н1 ──
    н1, ош = начисление(5000)
    т.проверить(ош is None and остаток() == -5000 and д.итог("УЗ_СписанияСуммЗаУроки", н1.Ссылка) == (-5000.0, 1)
                and float(c.УЗ_Сервер.ЗадолженностьУченика(ученик, орг, робототехника)) == 5000
                and д.итог("УЗ_Касса", н1.Ссылка) == (0.0, 0),
                "Н1: набор 5 000 без аванса — остаток −5 000, долг к оплате 5 000, касса не тронута", ош)

    # ── Н2 ──
    пко = д.документ("УЗ_ПриходДенег", Дата=дата(2026, 9, 6, 10), Касса=касса, Организация=орг, ФизЛицо=ученик,
                     ПредметОбучения=робототехника, ВидОперации=c.Перечисления.УЗ_ВидыОпераций.КассаУченики,
                     СуммаДокумента=5000)
    ош = д.записать(пко)
    т.проверить(ош is None and остаток() == 0 and float(c.УЗ_Сервер.ЗадолженностьУченика(ученик, орг, робототехника)) == 0,
                "Н2: оплата набора ПКО 5 000 — остаток 0, долга нет", ош)

    # ── Н3 ──
    _, ош = начисление(0)
    т.проверить(ош is not None and "больше нуля" in ош, "Н3: начисление на 0 — отказ", ош)
    _, ош = начисление(100, СтатьяЗатрат=c.Справочники.УЗ_СтатьиДвиженияДенег.ПустаяСсылка())
    т.проверить(ош is not None, "Н3: начисление без статьи — отказ", ош)
    _, ош = начисление(100, ФизЛицо=c.Справочники.УЗ_ФизЛица.ПустаяСсылка())
    т.проверить(ош is not None, "Н3: начисление без ученика — отказ", ош)

    # ── Н4 ──
    н = д.документ("УЗ_НачислениеУченику")
    н.Заполнить(ученик)
    по_умолчанию = c.РегистрыСведений.УЗ_Настройки.Настройки().Организация
    т.проверить(c.String(н.ФизЛицо) == c.String(ученик) and c.String(н.Организация) == c.String(по_умолчанию),
                "Н4: на основании ученика — ученик и организация по умолчанию", (c.String(н.ФизЛицо), c.String(н.Организация)))

    # ── Н5 ──
    ош = None
    try:
        о = н1.Ссылка.ПолучитьОбъект()
        о.Записать(c.РежимЗаписиДокумента.ОтменаПроведения)
    except Exception as е:
        ош = текст_ошибки(е)
    т.проверить(ош is None and остаток() == 5000, "Н5: отмена проведения начисления — долг за набор исчез (аванс 5 000)", ош)
    н5, ош = начисление(300, Организация=c.Справочники.Организации.ПустаяСсылка())
    о = н5.Ссылка.ПолучитьОбъект() if not н5.Ссылка.Пустая() else None
    т.проверить(ош is None and о is not None and c.String(о.Организация) == c.String(по_умолчанию),
                "Н5: начисление без организации — организация по умолчанию", ош)

    # ── Н6: права менеджера — рабочий набор роли (тот же разбор, что аудит права_роли) ──
    роль = c.Метаданные.Роли.Найти("УЗ_ОсновнаяРоль")
    объект = c.Метаданные.Документы.УЗ_НачислениеУченику
    права = {п: bool(c.ПравоДоступа(п, объект, роль)) for п in ("Чтение", "Добавление", "Изменение", "Проведение",
                                                                 "Просмотр", "ИнтерактивноеДобавление")}
    т.проверить(all(права.values()), "Н6: у менеджера (УЗ_ОсновнаяРоль) права на начисление ученику: чтение, добавление, "
                "изменение, проведение, просмотр", права)


if __name__ == "__main__":
    запустить("логика_начисление_ученику", сценарий)
