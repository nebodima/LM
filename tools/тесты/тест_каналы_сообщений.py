def hasattr_safe(структура, имя):
    try:
        return bool(структура.Свойство(имя))
    except Exception:
        return False


def привязать(c, кто, чат):
    з = c.РегистрыСведений.УЗ_ПривязкиКаналов.СоздатьМенеджерЗаписи()
    з.ФизЛицо = кто
    з.Канал = c.Перечисления.УЗ_КаналыСообщений.Телеграм
    з.Адрес = чат
    з.Записать()


def сохранить_настройки(т):
    """Записи регистров каналов, ключей и шаблонов копии — вернуть уборкой как были."""
    c = т.c
    прежние = {}
    for имя in РЕГИСТРЫ:
        н = getattr(c.РегистрыСведений, имя).СоздатьНаборЗаписей()
        н.Прочитать()
        прежние[имя] = н.Выгрузить()

    def вернуть():
        for имя, таблица in прежние.items():
            н = getattr(c.РегистрыСведений, имя).СоздатьНаборЗаписей()
            н.Загрузить(таблица)
            н.Записать()
    т.убрать(вернуть, "настройки каналов, ключи и шаблоны копии")


