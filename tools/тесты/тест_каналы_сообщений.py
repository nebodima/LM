class Заглушка:
    def __init__(self):
        self.сервер, self.порт = заглушка_каналов.запустить()
        self.адрес = "http://127.0.0.1:%d" % self.порт

    def вызвать(self, путь, данные=None):
        тело = None if данные is None else json.dumps(данные).encode("utf-8")
        запрос = urllib.request.Request(self.адрес + urllib.parse.quote(путь), data=тело, method="POST" if данные is not None else "GET",
                                        headers={"Content-Type": "application/json"})
        with urllib.request.urlopen(запрос, timeout=5) as о:
            return json.loads(о.read().decode("utf-8"))

    def запросы(self, часть=""):
        return [з for з in self.вызвать("/__запросы") if часть in з["путь"]]

    def сброс(self):
        self.вызвать("/__сброс", {})


