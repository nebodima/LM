"""Урок, перенесённый в будущее (В10, ревью Codex логик 28.09, находка «будущий план сохраняет проведение»).

Проведённый урок перенесли на будущую дату и «просто записали» — документ оставался проведённым,
а его движения (списание ученика, зарплата педагога) висели на прошлой дате. Теперь:
  * запись проведённого урока с будущей датой без отмены проведения — отказ с сообщением у поля «Дата»;
  * отмена проведения с будущей датой — проходит, движений урока не остаётся;
  * будущий непроведённый урок записывается как план без движений.

    python tools\\тесты\\тест_урок_будущий.py --база=C:\\1c_bases\\UZ_UNF_A
"""
# затрагивает: Документ.УЗ_Урок
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from фабрика import Фабрика  # noqa: E402


def движений_урока(ф, урок):
    return ф.число("""ВЫБРАТЬ КОЛИЧЕСТВО(*) ИЗ (
        ВЫБРАТЬ С.Регистратор КАК Р ИЗ РегистрНакопления.УЗ_СписанияСуммЗаУроки КАК С ГДЕ С.Регистратор = &Урок
        ОБЪЕДИНИТЬ ВСЕ
        ВЫБРАТЬ З.Регистратор ИЗ РегистрНакопления.УЗ_РасчетыПоЗарплате КАК З ГДЕ З.Регистратор = &Урок) КАК Т""",
                   Урок=урок)


def сценарий(т):
    ф = Фабрика(т, "УЗ тест будущего урока")
    педагог = ф.педагог()
    # урок с учеником: без учеников урок не проводится (тест тексты_отказов, 29.09.2026); бесплатная явка — без тарифа
    урок = ф.урок(педагог, ф.день(-1, 10), часов=1, строки=[dict(Ученик=ф.ученик(), Явка=True, СписатьОплату=False)])
    ошибка, _ = ф.записать(урок, "Проведение")
    т.проверить(ошибка is None, "вчерашний урок проводится", ошибка)

    урок.Дата = ф.день(3, 10)
    ошибка, сообщения = ф.записать(урок, "Запись")
    т.проверить(ошибка is not None and any("отмените проведение" in с for с, _ in сообщения),
                "проведённый урок с будущей датой просто записать нельзя — отказ с пояснением", (ошибка, сообщения))

    урок = урок.Ссылка.ПолучитьОбъект()
    урок.Дата = ф.день(3, 10)
    ошибка, _ = ф.записать(урок, "ОтменаПроведения")
    т.проверить(ошибка is None and not урок.Проведен, "отмена проведения с будущей датой проходит", ошибка)
    т.проверить(движений_урока(ф, урок.Ссылка) == 0, "движений перенесённого урока не осталось")

    план = ф.урок(педагог, ф.день(2, 12), часов=1)
    ошибка, _ = ф.записать(план, "Запись")
    т.проверить(ошибка is None and not план.Проведен, "будущий урок записывается планом", ошибка)
    т.проверить(движений_урока(ф, план.Ссылка) == 0, "у плана нет движений")


if __name__ == "__main__":
    запустить("урок_будущий", сценарий)
