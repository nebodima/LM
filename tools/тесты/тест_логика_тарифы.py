"""Логика тарифов, часть 1: сценарии 1–9 из docs/логики/тарифы_скидки_бонусы.md §5 (числа — оттуда).

Цена урока по тарифу — Документы.УЗ_Урок.ЦенаСтрокиУрока: цена на дату урока (история цен, иначе карточка, В8),
«за уроки» — сумма / уроки, «за часы» — сумма × часы урока / часы (сначала уроки, затем часы — так же говорят
подсказки: Документы.УЗ_Урок.ПредставлениеЦеныТарифа). Часы тарифа — до минуты (13.4, В13/В25): «1 000 за 40 мин»
= 0,6667 ч. Запись истории с суммой без единицы не записывается; старая запись без единицы — «нет цены», как и
карточка без единицы. Обе единицы (старые данные LM) — везде «за урок», при записи — предупреждение.

Красные на старом коде (28.09.2026, UZ_UNF_D до правки): №5 (подпись формы тарифа — функции ПредставлениеЦеныТарифаНаДату
не было), №6 (часы тарифа 10.1: 0,6667 → 0,7 — урок 40 мин 952,38), №7 (запись истории «3 000» без единицы
записывалась и считалась «за урок»), №9 (представление и подсказка тарифа с обеими единицами — «за 1 час», урок — за урок).

    python tools\\тесты\\тест_логика_тарифы.py --база=C:\\1c_bases\\UZ_UNF_D
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from фабрика import Фабрика  # noqa: E402
from тест_логика_урок import безопасно, деньги, строка, перечитать  # noqa: E402

МЕТКА = "_Тест логика тарифов"


def текст(значение):
    """Строка 1С: неразрывный пробел разделителя разрядов — как обычный."""
    return str(значение or "").replace("\xa0", " ")


def убрать_цены(т, тариф):
    """Все записи истории цен тарифа — загрузкой (мимо проверки В8; уроки к этому моменту уже убраны)."""
    c = т.c

    def убрать():
        набор = c.РегистрыСведений.УЗ_ЦеныТарифов.СоздатьНаборЗаписей()
        набор.Отбор.Тариф.Установить(тариф)
        набор.ОбменДанными.Загрузка = True
        набор.Записать()
    т.убрать(убрать, "история цен тарифа")


def тариф(т, ф, имя, **реквизиты):
    ссылка = ф.элемент("УЗ_Тарифы", имя, **реквизиты)
    убрать_цены(т, ссылка)
    return ссылка


def записать_цену(т, тариф_, период, сумма, уроков=0, часов=0, загрузка=False):
    """Запись истории цен → текст ошибки или None."""
    c = т.c
    набор = c.РегистрыСведений.УЗ_ЦеныТарифов.СоздатьНаборЗаписей()
    набор.Отбор.Тариф.Установить(тариф_)
    набор.Отбор.Период.Установить(период)
    з = набор.Добавить()
    з.Период = период
    з.Тариф = тариф_
    з.Сумма = сумма
    з.КоличествоУроков = уроков
    з.КоличествоЧасов = часов
    набор.ОбменДанными.Загрузка = загрузка
    c.ПолучитьСообщенияПользователю(True)
    _, ош = безопасно(lambda: набор.Записать())
    return ош


def цены(т, тариф_):
    """История цен тарифа: [(дата, сумма, уроков, часов)]."""
    тз = т.выбрать("""ВЫБРАТЬ Ц.Период КАК Период, Ц.Сумма КАК Сумма, Ц.КоличествоУроков КАК Уроков, Ц.КоличествоЧасов КАК Часов
        ИЗ РегистрСведений.УЗ_ЦеныТарифов КАК Ц ГДЕ Ц.Тариф = &Т УПОРЯДОЧИТЬ ПО Ц.Период""", Т=тариф_)
    return [(тз.Получить(н).Период.date(), деньги(тз.Получить(н).Сумма), float(тз.Получить(н).Уроков),
             float(тз.Получить(н).Часов)) for н in range(тз.Количество())]


def сценарий(т):
    c = т.c
    ф = Фабрика(т, МЕТКА)
    педагог = ф.педагог()
    ученик = ф.ученик()

    def урок(тариф_, день, час, часов=1, **поля):
        д = ф.урок(педагог, ф.день(день, час), часов, [строка(ученик, Тариф=тариф_, **поля)])
        ош, сооб = ф.записать(д)
        return д, ош, сооб

    # 1. карточка «8 000 за 8 уроков» — урок 1 000
    д, ош, сооб = урок(тариф(т, ф, "8 000 за 8", Сумма=8000, КоличествоУроков=8), -1, 8)
    т.проверить(ош is None and деньги(д.Сумма) == 1000, "1: карточка 8 000 за 8 уроков — урок 1 000", ош or сооб)

    # 2. карточка «1 000 за 1 ч» — урок 2 ч 2 000
    д, ош, сооб = урок(тариф(т, ф, "1 000 за 1 ч", Сумма=1000, КоличествоЧасов=1), -1, 9, 2)
    т.проверить(ош is None and деньги(д.Сумма) == 2000, "2: карточка 1 000 за 1 ч — урок 2 ч 2 000", ош or сооб)

    # 3. история: вчера 1 000, сегодня 2 000 за урок — урок вчера 1 000, перенесённый на сегодня 2 000
    ист = тариф(т, ф, "история", ИспользоватьИсториюЦен=True)
    записать_цену(т, ист, ф.день(-1), 1000, уроков=1)
    записать_цену(т, ист, ф.день(0), 2000, уроков=1)
    д = ф.урок(педагог, ф.день(-1, 11), 1, [строка(ученик, Тариф=ист)])
    ф.записать(д, "Запись")
    вчера = деньги(перечитать(д).Сумма)
    о = перечитать(д)
    о.Дата = ф.день(0, 0, 1)
    ф.записать(о, "Запись")
    т.проверить((вчера, деньги(перечитать(д).Сумма)) == (1000, 2000),
                "3: история цен — урок вчера 1 000, перенесённый на сегодня 2 000", (вчера, перечитать(д).Сумма))

    # 4. карточка 1 000, урок вчера проведён, цена карточки → 2 000: в истории 01.01.1980 — 1 000, сегодня — 2 000
    карт = тариф(т, ф, "карточка 1 000", Сумма=1000, КоличествоУроков=1)
    д, ош, _ = урок(карт, -1, 12)
    о = карт.ПолучитьОбъект()
    о.Сумма = 2000
    о.Записать()
    история = цены(т, карт)
    т.проверить([(с[0].year, с[1]) for с in история] == [(1980, 1000), (ф.день(0).year, 2000)]
                and история[-1][0] == ф.сегодня,
                "4: смена цены карточки — история: 01.01.1980 1 000 и сегодня 2 000", история)
    о = перечитать(д)
    ош, _ = ф.записать(о)
    т.проверить(ош is None and деньги(перечитать(д).Сумма) == 1000, "4: урок вчера при перепроведении — по-прежнему 1 000",
                ош or перечитать(д).Сумма)

    # 5. то же, но урок проведён сегодня: новая цена — с завтра; урок сегодня 1 000; форма «на сегодня» — 1 000
    карт5 = тариф(т, ф, "карточка 1 000 (урок сегодня)", Сумма=1000, КоличествоУроков=1)
    д, ош, _ = урок(карт5, 0, 0)
    о = карт5.ПолучитьОбъект()
    о.Сумма = 2000
    о.Записать()
    история = цены(т, карт5)
    т.проверить(len(история) == 2 and (история[-1][0] - ф.сегодня).days == 1 and история[-1][1] == 2000,
                "5: урок сегодня уже проведён — новая цена действует с завтра", история)
    ош, _ = ф.записать(перечитать(д))
    т.проверить(ош is None and деньги(перечитать(д).Сумма) == 1000, "5: урок сегодня — 1 000", ош or перечитать(д).Сумма)
    подпись, ош = безопасно(lambda: c.Документы.УЗ_Урок.ПредставлениеЦеныТарифаНаДату(карт5, ф.день(0, 12)))
    т.проверить(ош is None and текст(подпись).startswith("1 000,00 за 1 урок"),
                "5: подпись формы тарифа «действующая цена на сегодня» — 1 000 (не новая 2 000)", ош or подпись)

    # 6. «1 000 за 40 мин» (0,6667 ч) — урок 40 мин стоит 1 000 (было 0,7 ч и 952,38)
    мин40 = тариф(т, ф, "1 000 за 40 мин", Сумма=1000, КоличествоЧасов=0.6667)
    т.проверить(round(float(мин40.ПолучитьОбъект().КоличествоЧасов), 4) == 0.6667, "6: часы тарифа хранятся до минуты: 0,6667",
                мин40.ПолучитьОбъект().КоличествоЧасов)
    д, ош, сооб = урок(мин40, -1, 13, 0.6667)
    т.проверить(ош is None and деньги(д.Сумма) == 1000, "6: урок 40 мин по «1 000 за 40 мин» — 1 000 (было 952,38)",
                ош or сооб or д.Сумма)

    # 7. запись истории «3 000» без единицы — не записывается; карточка «3 000» без единицы — урок отказ «нет цены»
    без_ед = тариф(т, ф, "история без единицы", ИспользоватьИсториюЦен=True)
    ош = записать_цену(т, без_ед, ф.день(-10), 3000)
    т.проверить(ош is not None, "7: цена по дате «3 000» без уроков и часов — не записывается (было: «за 1 урок»)", ош)
    карт7 = тариф(т, ф, "карточка 3 000 без единицы", Сумма=3000)
    д, ош, сооб = урок(карт7, -1, 14)
    т.проверить(ош is not None and any("нет цены" in с for с, _ in сооб), "7: карточка «3 000» без единицы — урок: отказ «нет цены»",
                ош or сооб)
    ош = записать_цену(т, без_ед, ф.день(-10), 0)
    т.проверить(ош is None, "7: цена по дате с суммой 0 без единицы — записывается (явно бесплатно)", ош)

    # 8. история: запись на дату последнего урока / правка прошлой — отказ; на будущее — записывается
    ист8 = тариф(т, ф, "история для В8", ИспользоватьИсториюЦен=True)
    записать_цену(т, ист8, ф.день(-10), 1000, уроков=1)
    урок(ист8, -2, 8)
    т.проверить(записать_цену(т, ист8, ф.день(-2), 1500, уроков=1) is not None, "8: цена на дату последнего урока — отказ")
    т.проверить(записать_цену(т, ист8, ф.день(-10), 900, уроков=1) is not None, "8: правка прошлой цены — отказ")
    т.проверить(записать_цену(т, ист8, ф.день(5), 1500, уроков=1) is None, "8: цена на будущее — записывается")

    # 9. обе единицы (старые данные LM, загрузка): запись истории «6 000, 4 урока, 2 ч» записывается с предупреждением
    #    «считается за урок»; урок 1 ч = 1 500 и подсказка «1 500,00 за 1 урок» — одно и то же (было «3 000,00 за 1 час»)
    ист9 = тариф(т, ф, "обе единицы", ИспользоватьИсториюЦен=True)
    ош = записать_цену(т, ист9, ф.день(-10), 6000, уроков=4, часов=2)
    сооб = [str(м.Текст) for м in c.ПолучитьСообщенияПользователю(True)]
    т.проверить(ош is None and any("за урок" in м for м in сооб),
                "9: цена по дате с обеими единицами — записывается с предупреждением «считается за урок»", ош or сооб)
    д, ош, сооб = урок(ист9, -1, 15)
    подпись, ош_п = безопасно(lambda: c.Документы.УЗ_Урок.ПредставлениеЦеныТарифаНаДату(ист9, ф.день(-1)))
    т.проверить(ош is None and деньги(д.Сумма) == 1500 and ош_п is None and текст(подпись).startswith("1 500,00 за 1 урок"),
                "9: запись с обеими единицами — урок 1 500 и подсказка «1 500,00 за 1 урок» (было «3 000,00 за 1 час»)",
                "%s %s %s" % (ош or д.Сумма, ош_п or "", подпись))
    карт9 = тариф(т, ф, "карточка с обеими единицами", Сумма=6000, КоличествоУроков=4, КоличествоЧасов=2)
    т.проверить(c.String(карт9).replace("\xa0", " ").endswith("(1 500,00 за 1 урок)"),
                "9: представление тарифа с обеими единицами — «за 1 урок», как считает урок (было «3 000,00 за 1 час»)",
                c.String(карт9))


if __name__ == "__main__":
    запустить("логика_тарифы", сценарий)
