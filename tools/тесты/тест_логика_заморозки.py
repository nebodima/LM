"""Логика заморозок (приостановок абонемента), часть 1: docs/логики/заморозки.md, сценарии 1–10 и 15–16.

В4: приостановка — с даты начала включительно по дату возобновления не включая, срок абонемента продлевается на
дни приостановок. Абонемент З «8 занятий, 6 400», срок −40…−10 дней от сегодня (уроки в прошлом — проводятся).

Сценарии (К — красный на старом коде, проверено прогоном до правки 28.09.2026):
  №1  окно «с −30 по −26» → возобновление −25 (последний день паузы — последний день окна); срок −10 + 5 = −5
      (К: функции ВозобновлениеПоПоследнемуДню не было — окно считало на клиенте)
  №2–3 урок в день начала паузы и внутри — отказ «приостановлен», в день возобновления — проводится
  №4  урок в продлённый срок (−6) — проводится; после продлённого (−4) — отказ «дата окончания … с продлением»
  №5–6 пауза после окончания записывается, срок продлевается; вторая пауза в продлённом сроке — записывается
  №7  пауза раньше начала / после продлённого срока — отказ
  №8  смежные паузы «−30→−25» и «−25→−20» записываются, срок +10 (К: «Ошибка в датах приостановок»)
  №9  бессрочная «−30→…» и «−25→−20» — отказ, пересекаются (К: записывались, срок +5)
  №10 окно с пустым «по» — бессрочная пауза (пустое возобновление), ошибок нет (К: «Дата возобновления должна быть
      позже»; функции не было)
  №15 неактивный абонемент с паузой раньше начала — отказ записи (К: проверка только у активного)
  №16 бессрочная пауза: урок после её начала — отказ, срок не продлевается, состояние «приостановлен» без даты

    python tools\\тесты\\тест_логика_заморозки.py --база=C:\\1c_bases\\UZ_UNF_B
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from фабрика import Фабрика  # noqa: E402
from _логика_абонементов import абонемент_с_паузами, вызов, есть_слово  # noqa: E402

МЕТКА = "УЗ тест логики заморозок"


def сценарий(т):
    c = т.c
    ф = Фабрика(т, МЕТКА)
    аб = c.Справочники.УЗ_Абонемент
    предмет = ф.элемент("УЗ_ПредметыОбучения", "математика")
    педагог = ф.педагог()
    тариф = ф.элемент("УЗ_Тарифы", "8 000 за 8", Сумма=8000, КоличествоУроков=8)
    ученик = ф.ученик("Замороженный")
    д = ф.день

    def урок(день, абонемент, час=10):
        у = ф.урок(педагог, д(день, час), 1, [dict(Ученик=ученик, Абонемент=абонемент, Явка=True, СписатьОплату=True,
                                                    Тариф=тариф)], ПредметОбучения=предмет)
        return ф.записать(у, "Проведение")

    def срок(абонемент):
        return c.Справочники.УЗ_Абонемент.СостояниеАбонемента(абонемент, д(0)).Срок.date()

    # ── №1: окно «с −30 по −26» ──
    возобновление, ошибка = вызов(lambda: аб.ВозобновлениеПоПоследнемуДню(д(-26)))
    т.проверить(ошибка is None and возобновление.date() == д(-25).date(),
                "№1: окно «по −26» → возобновление −25 (последний день паузы — последний день окна)", ошибка)
    з, ошибка, сообщения = абонемент_с_паузами(ф, ученик, "З", [(д(-30), д(-25))], ПредметОбучения=предмет)
    т.проверить(з is not None and ошибка is None, "№1: абонемент с паузой −30→−25 записан", (ошибка, сообщения))
    т.проверить(срок(з) == д(-5).date(), "№1 (В4): срок продлён на 5 дней: −10 → −5", срок(з))

    # ── №2–4: уроки в паузе, в день возобновления, в продлённом сроке ──
    итог = урок(-30, з)
    т.проверить(итог[0] is not None and есть_слово(итог[1], "приостановлен"), "№2: урок в день начала паузы — отказ", итог)
    итог = урок(-26, з)
    т.проверить(итог[0] is not None and есть_слово(итог[1], "приостановлен"), "№3: урок внутри паузы — отказ", итог)
    итог = урок(-25, з)
    т.проверить(итог[0] is None, "№3: урок в день возобновления — проводится", итог)
    итог = урок(-6, з)
    т.проверить(итог[0] is None, "№4: урок в продлённый срок (−6 ≤ −5) — проводится", итог)
    итог = урок(-4, з)
    т.проверить(итог[0] is not None and есть_слово(итог[1], "с продлением на 5 дн."),
                "№4: урок после продлённого срока (−4) — отказ «дата окончания … с продлением на 5 дн.»", итог)

    # ── №5–7: пауза после окончания, вторая в продлённом сроке, вне срока ──
    з2, ошибка, сообщения = абонемент_с_паузами(ф, ученик, "З2", [(д(-22), д(-12)), (д(-11), д(-9))],
                                                ДатаОкончания=д(-20), ПредметОбучения=предмет)
    т.проверить(з2 is not None and ошибка is None, "№5–6: пауза −22→−12 после окончания (−20) и вторая −11→−9 "
                "в продлённом сроке записаны", (ошибка, сообщения))
    if з2 is not None:
        т.проверить(срок(з2) == д(-8).date(), "№5–6: срок −20 + 10 + 2 = −8", срок(з2))
    _, ошибка, сообщения = абонемент_с_паузами(ф, ученик, "до начала", [(д(-45), д(-42))], ПредметОбучения=предмет)
    т.проверить(ошибка is not None and есть_слово(сообщения, "раньше начала"), "№7: пауза раньше начала — отказ", сообщения)
    _, ошибка, сообщения = абонемент_с_паузами(ф, ученик, "после срока", [(д(-8), д(-6))], ПредметОбучения=предмет)
    т.проверить(ошибка is not None and есть_слово(сообщения, "после окончания"),
                "№7: пауза после срока (−8 > −10) — отказ", сообщения)

    # ── №8–9: смежные и бессрочная ──
    з8, ошибка, сообщения = абонемент_с_паузами(ф, ученик, "смежные", [(д(-30), д(-25)), (д(-25), д(-20))],
                                                ПредметОбучения=предмет)
    т.проверить(ошибка is None, "№8 (З-1): смежные паузы −30→−25 и −25→−20 записываются", сообщения)
    if з8 is not None:
        т.проверить(срок(з8) == д(0).date(), "№8: срок −10 + 10 = сегодня", срок(з8))
    _, ошибка, сообщения = абонемент_с_паузами(ф, ученик, "бессрочная и вторая", [(д(-30), None), (д(-25), д(-20))],
                                               ПредметОбучения=предмет)
    т.проверить(ошибка is not None and есть_слово(сообщения, "пересекается"),
                "№9 (З-2): бессрочная −30→… и −25→−20 пересекаются — отказ", сообщения)

    # ── №10: окно с пустым «по» — бессрочная ──
    пустое, ошибка = вызов(lambda: аб.ВозобновлениеПоПоследнемуДню(None))
    т.проверить(ошибка is None and пустое.year < 1900, "№10 (З-3): пустое «по» — пустая дата возобновления", ошибка)
    текст, ошибка = вызов(lambda: аб.ОшибкаПриостановки(з2, д(-30), пустое))
    т.проверить(ошибка is None and текст == "", "№10: бессрочная пауза −30→… в сроке абонемента без уроков — без ошибки",
                (ошибка, текст))

    # ── №15: неактивный абонемент ──
    _, ошибка, сообщения = абонемент_с_паузами(ф, ученик, "неактивный", [(д(-45), д(-42))], Активный=False,
                                               ПредметОбучения=предмет)
    т.проверить(ошибка is not None and есть_слово(сообщения, "раньше начала"),
                "№15 (З-9): у неактивного абонемента пауза раньше начала — отказ записи", сообщения)

    # ── №16: бессрочная пауза ──
    з16, ошибка, сообщения = абонемент_с_паузами(ф, ученик, "бессрочно", [(д(-20), None)], ДатаОкончания=д(20),
                                                 ПредметОбучения=предмет)
    т.проверить(з16 is not None and ошибка is None, "№16: бессрочная пауза записана", (ошибка, сообщения))
    if з16 is not None:
        итог = урок(-15, з16, 12)
        т.проверить(итог[0] is not None and есть_слово(итог[1], "приостановлен"), "№16: урок после начала бессрочной "
                    "паузы — отказ", итог)
        состояние = c.Справочники.УЗ_Абонемент.СостояниеАбонемента(з16, д(0))
        т.проверить(состояние.Приостановлен and состояние.ДатаВозобновления.year < 1900
                    and состояние.Срок.date() == д(20).date(),
                    "№16: «приостановлен» без даты возобновления, срок не продлён (+20)",
                    (состояние.Приостановлен, состояние.ДатаВозобновления, состояние.Срок))


if __name__ == "__main__":
    запустить("логика_заморозки", сценарий)
