"""Бот Telegram, часть 2 — кабинет родителя (версия 2.2.0.3, В60): «Не придём» и «Написать администратору».

Заглушка сервисов на 127.0.0.1 (как в тест_бот_телеграм): Telegram — на заглушку, каждый ответ бота виден.
  1. /пропуск мамы (чат 5001): одним sendMessage — inline-кнопки ближайших занятий её детей на 7 дней (Аня через
     2 дня, Боря через 3); без проведённого вчерашнего, без урока через час (ближе 2 ч), без чужого Васи.
  2. Нажатие (callback_query через getUpdates): answerCallbackQuery на нажатие, в уроке у строки Ани — явка снята,
     причина «Предупредил о пропуске», заметка «Сообщил через бота <дата время>»; «К оплате» не тронута (В60);
     строка Бори в том же уроке — без изменений; администратору — оповещение (УЗ_Оповещения, источник — урок);
     журнал сообщений — «Сообщение боту Telegram», статус «Получено». Повторное нажатие — «уже отмечено».
  3. Отказы: проведённый урок, урок через час (ближе 2 ч), урок чужого ученика Васи, Аня на уроке, где её нет;
     ни одна из этих строк не изменилась. Настройка «за 5 ч» — урок через 3 ч уже нельзя; «по умолчанию» (0) — 2 ч.
  4. /написать: следующее сообщение — администратору (оповещение с текстом, источник — мама) и в журнал; ответ
     «Передали»; сообщение после этого — снова команда (помощь), администратору не уходит.
  5. Ответ администратора из «Сообщение ученику» (ОтправитьВручную по маме) приходит в чат 5001.
Красное на коде 2.2.0.2: /пропуск и /написать — помощь, нажатия не разбираются, отметок и оповещений нет.

    python tools\\тесты\\тест_бот_кабинет.py --база=C:\\1c_bases\\UZ_BP_T --пользователь=1
"""
# затрагивает: УЗ_Сообщения, УЗ_ПровайдерыСообщений, УЗ_ПривязкиКаналов, УЗ_ЖурналРассылки, УЗ_Урок, УЗ_Оповещения, УЗ_НастройкиКаналов
import base64
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from фабрика import Фабрика  # noqa: E402
import тест_оповещения as оп  # noqa: E402
from тест_каналы_сообщений import Заглушка, КЛЮЧИ, привязать, сохранить_настройки  # noqa: E402

МЕТКА = "_Тест бот кабинет"
ОТМЕТКА = "Предупредил о пропуске"


def сценарий(т):
    c = т.c
    if not c.УЗ_Почта.ПесочницаВключена():
        raise RuntimeError("песочница не включена — сценарий не запускаю")
    if c.УЗ_Общий.БезопасныйРежимДействует():
        т.проверить(False, "стенд без безопасного режима расширения (нужен HTTP к заглушке)")
        return
    оп.выключить_почту(т)
    зг = Заглушка()
    т.убрать(зг.сервер.shutdown, "заглушка сервисов")
    т.убрать(зг.сброс, "запросы заглушки")
    зг.сброс()
    сохранить_настройки(т)
    К = c.Перечисления.УЗ_КаналыСообщений
    П = c.Перечисления.УЗ_ПровайдерыСообщений
    ст = c.String

    def настроить(часов):
        д_ = c.NewObject("Структура")
        for к, в in dict(Включен=True, Провайдер=П.TelegramBotAPI, АдресСервиса=зг.адрес + "/tg", Логин="",
                         Отправитель="", ИмяБота="uz_test_bot", ПропускЗаЧасов=часов).items():
            д_.Вставить(к, в)
        c.УЗ_Сообщения.СохранитьНастройкиКанала(К.Телеграм, д_, КЛЮЧИ["Телеграм"], True)
    настроить(0)

    ф = Фабрика(т, МЕТКА)
    люди = []

    def человек(имя, плательщики=()):
        о = c.Справочники.УЗ_ФизЛица.СоздатьЭлемент()
        о.Наименование = "%s %s" % (МЕТКА, имя)
        о.ОповеститьПоEmail = True
        о.ПредпочитаемыйКанал = К.Телеграм
        for кто, кем, основной in плательщики:
            с = о.Плательщики.Добавить()
            с.Плательщик, с.КемПриходится, с.Основной = кто, кем, основной
        о.Записать()
        ссылка = о.Ссылка
        люди.append(ссылка)
        т.убрать(lambda: т.удалить_объект(ссылка), "физ. лицо %s" % имя, пакет=True)
        return ссылка

    уроки = {}

    def убрать_журнал_привязки_оповещения():
        for у in люди:
            for поле in ("Ученик", "Получатель"):
                н = c.РегистрыСведений.УЗ_ЖурналРассылки.СоздатьНаборЗаписей()
                getattr(н.Отбор, поле).Установить(у)
                н.Записать()
            н = c.РегистрыСведений.УЗ_ПривязкиКаналов.СоздатьНаборЗаписей()
            н.Отбор.ФизЛицо.Установить(у)
            н.Записать()
        for источник in люди + [у.Ссылка for у in уроки.values()]:
            н = c.РегистрыСведений.УЗ_Оповещения.СоздатьНаборЗаписей()
            н.Отбор.Источник.Установить(источник)
            н.ДополнительныеСвойства.Вставить(c.УЗ_Сервер.КлючПроверенныхПрав(), True)
            н.Записать()
    т.убрать(убрать_журнал_привязки_оповещения, "журнал сообщений, привязки и оповещения теста")

    мама = человек("мама")
    чужая = человек("чужая мама")
    аня = человек("Аня", плательщики=[(мама, "мама", True)])
    боря = человек("Боря", плательщики=[(мама, "мама", True)])
    вася = человек("Вася", плательщики=[(чужая, "мама", True)])
    привязать(c, мама, "5001")
    привязать(c, чужая, "5003")

    орг = ф.организация("Студия кабинета")
    педагог = ф.педагог()
    предмет = ф.элемент("УЗ_ПредметыОбучения", "флейта")
    строка = {"Явка": True, "СписатьОплату": True}
    for имя, дней, час, кто, режим in (
            ("общий2", 2, 17, [аня, боря], "Запись"),
            ("боря3", 3, 18, [боря], "Запись"),
            ("аня_через1ч", 0, 13, [аня], "Запись"),
            ("аня_через3ч", 0, 15, [аня], "Запись"),
            ("аня_вчера", -1, 10, [аня], "Проведение"),
            ("вася1", 1, 16, [вася], "Запись")):
        поля = [dict(строка, Ученик=кто_, СписатьОплату=(режим == "Запись"), Заметка="тест") for кто_ in кто]
        у = ф.урок(педагог, ф.день(дней, час, 30), ПредметОбучения=предмет, Организация=орг, строки=поля)
        ош, сообщ = ф.записать(у, режим)
        т.проверить(ош is None, "урок %s: %s" % (имя, режим), (ош, сообщ))
        уроки[имя] = у

    def уид64(ссылка):
        return base64.b64encode(bytes.fromhex(ст(ссылка.УникальныйИдентификатор()).replace("-", ""))).decode() \
            .rstrip("=")

    def данные(урок, ученик):
        return "absent:%s:%s" % (уид64(урок.Ссылка), уид64(ученик))

    def строка_урока(имя, ученик):
        о = уроки[имя].Ссылка.ПолучитьОбъект()
        нужен = ст(ученик.УникальныйИдентификатор())
        for с in о.Ученики:
            if ст(с.Ученик.УникальныйИдентификатор()) == нужен:
                return dict(Явка=bool(с.Явка), Оплата=bool(с.СписатьОплату), Причина=ст(с.Причина),
                            Заметка=ст(с.Заметка))
        return None

    def нажать(чат, текст_данных):
        return ст(c.УЗ_Сообщения.ОбработатьНажатиеТелеграм(чат, текст_данных, "cb1")).replace("\xa0", " ")

    def бот(чат, текст):
        return ст(c.УЗ_Сообщения.ОбработатьСообщениеТелеграм(чат, текст)).replace("\xa0", " ")

    def настройка_смещения(значение):
        н = c.РегистрыСведений.УЗ_НастройкиКаналов.СоздатьМенеджерЗаписи()
        н.Канал = К.Телеграм
        н.Прочитать()
        н.СмещениеОбновлений = значение
        н.Записать()

    # ── 1. /пропуск: кнопки своих ближайших занятий ──
    зг.сброс()
    р = бот("5001", "/пропуск")
    ответы = зг.запросы("/sendMessage")
    тело = ответы[-1]["тело"] if ответы else {}
    кнопки = [к_ for ряд in ((тело.get("reply_markup") or {}).get("inline_keyboard") or []) for к_ in ряд]
    все_данные = [к_.get("callback_data", "") for к_ in кнопки]
    т.проверить(данные(уроки["общий2"], аня) in все_данные and данные(уроки["общий2"], боря) in все_данные
                and данные(уроки["боря3"], боря) in все_данные and данные(уроки["аня_через3ч"], аня) in все_данные,
                "/пропуск мамы — inline-кнопки: Аня и Боря через 2 дня, Боря через 3, Аня через 3 ч", (р, кнопки))
    т.проверить(len(кнопки) == 4 and all(len(д_.encode()) <= 64 for д_ in все_данные),
                "/пропуск: без проведённого, без урока через час, без чужого Васи; данные кнопок ≤ 64 байт",
                все_данные)
    т.проверить(бот("5001", "Не придём") == р, "кнопка «Не придём» — тот же ответ, что /пропуск")

    # ── 2. нажатие через getUpdates ──
    настройка_смещения(1199)
    зг.сброс()
    зг.вызвать("/__обновления", [{"update_id": 1200, "callback_query": {
        "id": "cbq-1", "from": {"first_name": "Мама"}, "data": данные(уроки["общий2"], аня),
        "message": {"message_id": 7, "chat": {"id": 5001}}}}])
    c.УЗ_Сообщения.ПриемСообщенийТелеграм()
    обн = зг.запросы("/getUpdates")
    т.проверить(bool(обн) and "callback_query" in обн[0]["параметры"].get("allowed_updates", ""),
                "getUpdates просит и нажатия (allowed_updates с callback_query)", обн and обн[0]["параметры"])
    нажатия = зг.запросы("/answerCallbackQuery")
    т.проверить(len(нажатия) == 1 and нажатия[0]["тело"].get("callback_query_id") == "cbq-1",
                "на нажатие — answerCallbackQuery с его id", нажатия)
    ответы = зг.запросы("/sendMessage")
    т.проверить(len(ответы) == 1 and str(ответы[0]["тело"].get("chat_id")) == "5001"
                and "Аня" in ответы[0]["тело"].get("text", ""), "подтверждение отметки — в чат 5001", ответы)
    с_ = строка_урока("общий2", аня)
    т.проверить(с_ and not с_["Явка"] and с_["Причина"] == ОТМЕТКА and "Сообщил через бота" in с_["Заметка"]
                and с_["Оплата"], "строка Ани: явка снята, «Предупредил о пропуске», заметка; «К оплате» осталась",
                с_)
    т.проверить(строка_урока("общий2", боря) == dict(Явка=True, Оплата=True, Причина="", Заметка="тест"),
                "строка Бори в том же уроке не тронута", строка_урока("общий2", боря))
    опов = т.выбрать("""ВЫБРАТЬ О.Описание КАК Описание, О.Пользователь КАК Пользователь
        ИЗ РегистрСведений.УЗ_Оповещения КАК О ГДЕ О.Источник = &И И НЕ О.Завершено""", И=уроки["общий2"].Ссылка)
    т.проверить(опов.Количество() == 1 and "Аня" in ст(опов.Получить(0).Описание)
                and опов.Получить(0).Пользователь.Пустая(),
                "администратору — оповещение по уроку (для всех): «… Аня …»",
                [ст(о.Описание) for о in опов])
    жур = т.выбрать("""ВЫБРАТЬ Ж.Вид КАК Вид, Ж.Статус КАК Статус, Ж.Текст КАК Текст
        ИЗ РегистрСведений.УЗ_ЖурналРассылки КАК Ж ГДЕ Ж.Получатель = &П И Ж.Ученик = &У""", П=мама, У=аня)
    т.проверить([(ст(з.Вид), ст(з.Статус)) for з in жур] == [("Сообщение боту Telegram", "Получено")],
                "журнал сообщений: «Сообщение боту Telegram», «Получено», ученик Аня, от мамы",
                [(ст(з.Вид), ст(з.Статус), ст(з.Текст)) for з in жур])
    р = нажать("5001", данные(уроки["общий2"], аня))
    т.проверить("уже" in р.lower() and опов.Количество() == 1, "повторное нажатие — «уже отмечено»", р)

    # ── 3. отказы ──
    проверяемые = (("аня_вчера", аня), ("аня_через1ч", аня), ("вася1", вася), ("боря3", боря))
    было = [строка_урока(и, у_) for и, у_ in проверяемые]
    р = нажать("5001", данные(уроки["аня_вчера"], аня))
    т.проверить("проведено" in р, "проведённый урок — отказ «уже проведено»", р)
    р = нажать("5001", данные(уроки["аня_через1ч"], аня))
    т.проверить("2 ч" in р and "позвоните" in р.lower(), "урок через час (ближе 2 ч) — отказ, позвонить", р)
    р = нажать("5001", данные(уроки["вася1"], вася))
    т.проверить("не найден" in р.lower() or "чуж" in р.lower() or "не ваш" in р.lower(),
                "урок чужого ученика Васи — отказ", р)
    р = нажать("5001", данные(уроки["боря3"], аня))
    т.проверить("нет" in р.lower() and строка_урока("боря3", аня) is None, "Аня на уроке, где её нет — отказ", р)
    р = нажать("5003", данные(уроки["общий2"], боря))
    т.проверить(строка_урока("общий2", боря)["Причина"] == "", "чужая мама не может отметить Борю", р)
    т.проверить([строка_урока(и, у_) for и, у_ in проверяемые] == было, "после отказов строки уроков не изменились",
                [строка_урока(и, у_) for и, у_ in проверяемые])
    настроить(5)
    р = нажать("5001", данные(уроки["аня_через3ч"], аня))
    т.проверить("5 ч" in р and строка_урока("аня_через3ч", аня)["Причина"] == "",
                "настройка «за 5 ч»: урок через 3 ч — отказ", р)
    настроить(0)
    р = нажать("5001", данные(уроки["аня_через3ч"], аня))
    т.проверить(строка_урока("аня_через3ч", аня)["Причина"] == ОТМЕТКА, "настройка 0 — по умолчанию 2 ч: урок "
                "через 3 ч отмечен", р)

    # ── 4. /написать ──
    зг.сброс()
    р = бот("5001", "/написать")
    т.проверить("напишите" in р.lower(), "/написать — просьба написать сообщение", р)
    т.проверить(бот("5001", "Написать администратору") == р, "кнопка «Написать администратору» — тот же ответ")
    текст = "Аня заболела, можно перенести на пятницу?"
    р = бот("5001", текст)
    т.проверить("передали" in р.lower(), "сообщение после /написать — «Передали администратору»", р)
    опов = т.выбрать("""ВЫБРАТЬ О.Описание КАК Описание ИЗ РегистрСведений.УЗ_Оповещения КАК О
        ГДЕ О.Источник = &И И НЕ О.Завершено""", И=мама)
    т.проверить(опов.Количество() == 1 and текст in ст(опов.Получить(0).Описание),
                "администратору — оповещение с текстом (источник — мама)", [ст(о.Описание) for о in опов])
    жур = т.выбрать("""ВЫБРАТЬ Ж.Текст КАК Текст, Ж.Статус КАК Статус ИЗ РегистрСведений.УЗ_ЖурналРассылки КАК Ж
        ГДЕ Ж.Получатель = &П И Ж.Вид = ЗНАЧЕНИЕ(Перечисление.УЗ_ВидыСообщений.СообщениеБоту)
        И Ж.Ученик = ЗНАЧЕНИЕ(Справочник.УЗ_ФизЛица.ПустаяСсылка)""", П=мама)
    т.проверить([ст(з.Текст) for з in жур] == [текст], "журнал: сообщение мамы администратору",
                [ст(з.Текст) for з in жур])
    р = бот("5001", "спасибо")
    опов = т.выбрать("""ВЫБРАТЬ О.Описание КАК Описание ИЗ РегистрСведений.УЗ_Оповещения КАК О
        ГДЕ О.Источник = &И""", И=мама)
    т.проверить(опов.Количество() == 1 and "/расписание" in р,
                "следующее сообщение — уже не администратору (помощь)", р)
    р = бот("5999", "/написать") + бот("5999", "секрет")
    т.проверить("Попросите администратора прислать ссылку" in р, "незнакомый чат не пишет администратору", р)

    # ── 5. ответ администратора ──
    зг.сброс()
    итог = c.УЗ_Сообщения.ОтправитьВручную(мама, "", "Перенесём на пятницу, 17:30")
    ответы = зг.запросы("/sendMessage")
    т.проверить(any(str(о["тело"].get("chat_id")) == "5001" and "Перенесём" in о["тело"].get("text", "")
                    for о in ответы), "ответ администратора из «Сообщение ученику» — в чат 5001",
                (ответы, ст(итог.Итог) if hasattr(итог, "Итог") else ""))


if __name__ == "__main__":
    запустить("тест_бот_кабинет", сценарий)
