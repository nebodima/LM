def поле(тд, строка):
    """Знакоместа строки табличного документа: тексты клеток по одному знаку (цифры, буквы, «-», «.»)."""
    знаки = []
    for к in range(1, тд.ШиринаТаблицы + 1):
        т = тд.Область(строка, к, строка, к).Текст
        if len(т) == 1 and т != " ":   # пустая клетка между словами — не знак
            знаки.append(т)
    return "".join(знаки)


def строки_с(тд, текст, в_первой_колонке=False):
    """Номера строк, где встречается текст (по порядку). в_первой_колонке — только строки, где это подпись поля
    (первая клетка строки = текст): поиск платформы находит и «фамилия» в пояснениях под полями."""
    итог, о = [], тд.НайтиТекст(текст)
    while о is not None and (not итог or о.Верх > итог[-1]):
        итог.append(о.Верх)
        о = тд.НайтиТекст(текст, о)
    if в_первой_колонке:
        итог = [н for н in итог if тд.Область(н, 1, н, 1).Текст.strip() == текст]
    return итог


