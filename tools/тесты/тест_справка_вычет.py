def инн(цифры):
    """ИНН с верными контрольными цифрами: 9 цифр → ИНН организации (10), 10 цифр → физ. лица (12)."""
    def разряд(ц, веса):
        return sum(int(а) * в for а, в in zip(ц, веса)) % 11 % 10
    if len(цифры) == 9:
        return цифры + str(разряд(цифры, (2, 4, 10, 3, 5, 9, 4, 6, 8)))
    ц = цифры + str(разряд(цифры, (7, 2, 4, 10, 3, 5, 9, 4, 6, 8)))
    return ц + str(разряд(ц, (3, 7, 2, 4, 10, 3, 5, 9, 4, 6, 8)))


