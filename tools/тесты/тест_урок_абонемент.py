"""Урок: абонемент не расходуется сверх количества занятий/часов, после деактивации и чужим учеником
(аудит 28.09: учёт №7–8, Codex A06–A08, ревьюер-1 №1).

Факт по №7 (спор аудита и Codex): остаток абонемента читается из виртуальной таблицы Остатки с условием
только по абонементу — платформа сворачивает остальные измерения (Явка, Педагог, Тариф…) в одну строку.
Абонемент на 2 занятия: явка + оплаченная неявка у разных педагогов → 3-й урок отклонён и на старом коде
(проверки ниже «факт №7» зелёные до правки) — прав Codex, перерасхода по разрезам нет.
Настоящие дыры (красные на старом коде): две строки одного абонемента в одном уроке проходили по одному
остатку; выключенный абонемент (Активный = Ложь) с датой активации работал; абонемент другого ученика
списывался.
В16 (решение 28.09): сверх занятий/часов абонемент не расходуется, но урок не отказывает — строка идёт по тарифу
с предупреждением «абонемент исчерпан» (абонемент снимается со строки перед записью; подробные числа —
тест_логика_абонементы.py). Проверки «сверх остатка» ниже — на это: урок проведён, предупреждение есть.
Блокировка: в проведении теперь исключительная управляемая блокировка УЗ_СписанияСуммЗаУроки по
абонементу до чтения остатка. На файловой базе её не покраснить: файловая база сама сериализует проведения
(опыт 28.09: два сеанса одновременно проводят последний урок абонемента — второй ждёт ~0,4 с и получает
отказ, 3 из 3 попыток, и на старом коде). Гонка возможна только на клиент-серверной базе.

Codex A08 (повторный аудит, красные на старом коде): абонемент на гитару проводился в уроке ударных и давал
цену урока; абонемент с пустым владельцем проходил проверку. Стало: отказ «по предмету» / «не указан ученик»,
цена строки — по тарифу (Документы.УЗ_Урок.АбонементПодходитКУроку).

Р7 (решение 28.09): занятие абонемента расходует только строка «К оплате» (явка без неё — бесплатное занятие,
тест_урок_ошибки), поэтому строки здесь — «К оплате» с тарифом.

    python tools\\тесты\\тест_урок_абонемент.py --база=C:\\1c_bases\\UZ_UNF_B
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from фабрика import Фабрика  # noqa: E402

МЕТКА = "УЗ тест абонемента"


def сценарий(т):
    ф = Фабрика(т, МЕТКА)
    ученик = ф.ученик()
    чужой = ф.ученик("другой ученик")
    п1 = ф.педагог("педагог 1")
    п2 = ф.педагог("педагог 2")
    тариф = ф.элемент("УЗ_Тарифы", "500 за урок", Сумма=500, КоличествоУроков=1)

    def урок(педагог, час, строки, часов=1):
        return ф.записать(ф.урок(педагог, ф.день(-1, час), часов, строки), "Проведение")

    def проведён(итог, что):
        т.проверить(итог[0] is None, что, "%s %s" % итог)

    def отказ(итог, что, слово):
        ошибка, сообщения = итог
        т.проверить(ошибка is not None and any(слово in текст for текст, _ in сообщения), что,
                    "ошибка: %s, сообщения: %s" % (ошибка, сообщения))

    def по_тарифу(итог, что):
        ошибка, сообщения = итог
        т.проверить(ошибка is None and any("исчерпан" in текст and "по тарифу" in текст for текст, _ in сообщения), что,
                    "ошибка: %s, сообщения: %s" % (ошибка, сообщения))

    # ── факт №7: остаток не дробится по явке и педагогу ──
    на_2 = ф.абонемент(ученик, "на 2 занятия", КоличествоЗанятий=2)
    проведён(урок(п1, 8, [dict(Ученик=ученик, Абонемент=на_2, Явка=True, СписатьОплату=True, Тариф=тариф)]), "факт №7: урок 1 — явка (педагог 1)")
    второй = ф.урок(п2, ф.день(-1, 8), 1, [dict(Ученик=ученик, Абонемент=на_2, Явка=False, СписатьОплату=True, Тариф=тариф)])
    проведён(ф.записать(второй, "Проведение"), "факт №7: урок 2 — оплаченная неявка (педагог 2)")
    по_тарифу(урок(п1, 9, [dict(Ученик=ученик, Абонемент=на_2, Явка=True, СписатьОплату=True, Тариф=тариф)]),
              "факт №7 / В16: 3-й урок по абонементу на 2 занятия — по тарифу с предупреждением «исчерпан»")
    проведён(ф.записать(второй.Ссылка.ПолучитьОбъект(), "Проведение"),
             "перепроведение последнего урока абонемента — проводится (свои движения не считаются)")

    # ── две строки одного абонемента в одном уроке ──
    на_1 = ф.абонемент(ученик, "на 1 занятие", КоличествоЗанятий=1)
    по_тарифу(урок(п1, 10, [dict(Ученик=ученик, Абонемент=на_1, Явка=True, СписатьОплату=True, Тариф=тариф),
                            dict(Ученик=ученик, Абонемент=на_1, Явка=True, СписатьОплату=True, Тариф=тариф)]),
              "абонемент на 1 занятие в двух строках одного урока — вторая строка по тарифу (В16)")

    на_2ч = ф.абонемент(ученик, "на 2 часа", КоличествоЧасов=2)
    по_тарифу(урок(п1, 11, [dict(Ученик=ученик, Абонемент=на_2ч, Явка=True, СписатьОплату=True, Тариф=тариф),
                            dict(Ученик=ученик, Абонемент=на_2ч, Явка=True, СписатьОплату=True, Тариф=тариф)], часов=1.5),
              "абонемент на 2 часа, две строки по 1,5 ч — первая по абонементу, вторая по тарифу (В16)")
    по_тарифу(урок(п1, 15, [dict(Ученик=ученик, Абонемент=на_2ч, Явка=True, СписатьОплату=True, Тариф=тариф)], часов=1),
              "абонемент на 2 часа: после 1,5 ч урок 1 ч — по тарифу (осталось 0,5, В16)")
    проведён(урок(п1, 13, [dict(Ученик=ученик, Абонемент=на_2ч, Явка=True, СписатьОплату=True, Тариф=тариф)], часов=0.5),
             "абонемент на 2 часа: урок 0,5 ч в остаток — проводится по абонементу")

    # ── выключенный абонемент ──
    выключен = ф.абонемент(ученик, "выключенный", КоличествоЗанятий=8, Активный=False)
    отказ(урок(п1, 17, [dict(Ученик=ученик, Абонемент=выключен, Явка=True, СписатьОплату=True, Тариф=тариф)]),
          "выключенный абонемент (дата активации есть, «Активный» снят) — отказ", "не активен")

    # ── чужой абонемент ──
    свой = ф.абонемент(ученик, "на 8 занятий", КоличествоЗанятий=8)
    отказ(урок(п1, 18, [dict(Ученик=чужой, Абонемент=свой, Явка=True, СписатьОплату=True, Тариф=тариф)]),
          "абонемент другого ученика — отказ", "другого ученика")
    проведён(урок(п1, 19, [dict(Ученик=ученик, Абонемент=свой, Явка=True, СписатьОплату=True, Тариф=тариф)]), "свой абонемент на 8 занятий — проводится")

    # ── Codex A08: предмет абонемента и пустой владелец ──
    гитара = ф.элемент("УЗ_ПредметыОбучения", "гитара")
    ударные = ф.элемент("УЗ_ПредметыОбучения", "ударные")
    на_гитару = ф.абонемент(ученик, "на гитару", КоличествоЗанятий=8, ПредметОбучения=гитара, ЦенаАбонемента=8000)
    урок_ударных = ф.урок(п2, ф.день(-1, 18), 1, [dict(Ученик=ученик, Абонемент=на_гитару, Явка=True,
                                                     СписатьОплату=True, Тариф=тариф)], ПредметОбучения=ударные)
    отказ(ф.записать(урок_ударных, "Проведение"), "A08: абонемент на гитару в уроке ударных — отказ", "по предмету")
    сумма = float(урок_ударных.Ученики.Получить(0).Сумма)
    т.проверить(сумма == 500, "A08: цена строки не по абонементу чужого предмета (1 000), а по тарифу (500)", сумма)
    урок_гитары = ф.урок(п2, ф.день(-1, 19), 1, [dict(Ученик=ученик, Абонемент=на_гитару, Явка=True,
                                                    СписатьОплату=True, Тариф=тариф)], ПредметОбучения=гитара)
    проведён(ф.записать(урок_гитары, "Проведение"), "A08: абонемент на гитару в уроке гитары — проводится")
    т.проверить(float(урок_гитары.Ученики.Получить(0).Сумма) == 1000,
                "A08: цена урока гитары — по абонементу (8 000 / 8 = 1 000)", урок_гитары.Ученики.Получить(0).Сумма)
    ничей = ф.абонемент(ученик, "без ученика", КоличествоЗанятий=8, ФизЛицо=c_пусто(ф))
    отказ(урок(п2, 20, [dict(Ученик=ученик, Абонемент=ничей, Явка=True, СписатьОплату=True, Тариф=тариф)]),
          "A08: абонемент без ученика (пустой владелец) — отказ", "не указан ученик")


def c_пусто(ф):
    return ф.c.Справочники.УЗ_ФизЛица.ПустаяСсылка()


if __name__ == "__main__":
    запустить("урок_абонемент", сценарий)
