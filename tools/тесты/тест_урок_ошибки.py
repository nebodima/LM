"""Урок, тарифы, ставки, график педагога, настройки урока: ошибки из сверки справки 28.09.2026
(docs\\ошибки_из_справки_2026-09-28.md). Каждая проверка краснела на коде до правки.

  Р7  явка без «К оплате» — бесплатное занятие: абонемент (занятия, часы) не расходует; расходует «К оплате»;
  Р2  цена в карточке тарифа (одна цена) фиксируется на дату: после смены цены перепроведение старого урока
      оставляет прежнюю цену, урок после смены — новую; прежняя и новая цены — в истории цен;
  Р1  действующий абонемент для помощника уроков — со сроком, продлённым на дни приостановки (как в уроке);
      приостановленный не берётся; из двух — кончающийся раньше;
  №9  «Не изменять» у начисления педагогу по ставке — перепроведение его не пересчитывает;
  №24 пустая «Дата окончания» группы у ученика «Только выбранные группы» урок не блокирует;
  №33 тариф с историей цен — без ложного предупреждения «не указана сумма»;
  №34 цена по дате с суммой 0 (бесплатный тариф) проходит проверку заполнения;
  №49 график педагога: урок, начатый раньше рабочего времени, предупреждается (смотрели только конец урока);
  №53 ставка вне срока «Действует с/по» не начисляет;
  №59 «Требовать описание к неоплаченным урокам» — строка без «К оплате» и без заметки не проводится.

    python tools\\тесты\\тест_урок_ошибки.py --база=C:\\1c_bases\\UZ_UNF_A
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить, дата  # noqa: E402
from фабрика import Фабрика  # noqa: E402

МЕТКА = "УЗ тест ошибок урока"


def сценарий(т):
    ф = Фабрика(т, МЕТКА)
    c = т.c
    ученик = ф.ученик()
    педагог = ф.педагог()
    тариф = ф.элемент("УЗ_Тарифы", "500 за урок", Сумма=500, КоличествоУроков=1)

    def проведён(итог, что):
        т.проверить(итог[0] is None, что, "%s %s" % итог)
        return итог[0] is None

    def отказ(итог, что, слово, поле=None):
        ошибка, сообщения = итог
        нужные = [(текст, п) for текст, п in сообщения if слово in текст and (поле is None or поле in п)]
        т.проверить(ошибка is not None and нужные, что, "ошибка: %s, сообщения: %s" % (ошибка, сообщения))

    def перечитать(д):
        return д.Ссылка.ПолучитьОбъект()

    def использовано(абонемент):
        # остаток КоличествоУроков — число использованных занятий (урок пишет расход −1)
        return ф.число("""ВЫБРАТЬ ЕСТЬNULL(СУММА(О.КоличествоУроковОстаток), 0)
            ИЗ РегистрНакопления.УЗ_СписанияСуммЗаУроки.Остатки(, Абонемент = &А) КАК О""", А=абонемент)

    # ── Р7: явка без «К оплате» абонемент не расходует ──
    на_1 = ф.абонемент(ученик, "на 1 занятие", КоличествоЗанятий=1)
    for час in (8, 9):
        проведён(ф.записать(ф.урок(педагог, ф.день(-2, час), 1,
                                   [dict(Ученик=ученик, Абонемент=на_1, Явка=True, СписатьОплату=False)]), "Проведение"),
                 "Р7: бесплатная явка %d по абонементу на 1 занятие — проводится" % (час - 7))
    т.проверить(использовано(на_1) == 0, "Р7: две бесплатные явки — занятия абонемента не израсходованы", использовано(на_1))
    проведён(ф.записать(ф.урок(педагог, ф.день(-2, 10), 1,
                               [dict(Ученик=ученик, Абонемент=на_1, Явка=True, СписатьОплату=True, Тариф=тариф)]),
                        "Проведение"), "Р7: урок «К оплате» по абонементу — проводится")
    т.проверить(использовано(на_1) == 1, "Р7: урок «К оплате» расходует 1 занятие", использовано(на_1))
    ошибка, сообщения = ф.записать(ф.урок(педагог, ф.день(-2, 11), 1,
                                         [dict(Ученик=ученик, Абонемент=на_1, Явка=False, СписатьОплату=True, Тариф=тариф)]),
                                  "Проведение")
    т.проверить(ошибка is None and any("исчерпан" in текст for текст, _ in сообщения) and использовано(на_1) == 1,
                "Р7/В16: оплаченная неявка сверх абонемента — по тарифу с предупреждением «исчерпан», занятий 1 из 1",
                (ошибка, сообщения, использовано(на_1)))

    # ── Р2: цена карточки фиксируется на дату ──
    карточка = ф.элемент("УЗ_Тарифы", "карточка 1 000", Сумма=1000, КоличествоУроков=1)

    def убрать_цены():
        набор = c.РегистрыСведений.УЗ_ЦеныТарифов.СоздатьНаборЗаписей()
        набор.Отбор.Тариф.Установить(карточка)
        набор.ОбменДанными.Загрузка = True
        набор.Записать()
    т.убрать(убрать_цены, "история цен тарифа-карточки")
    вчера = ф.урок(педагог, ф.день(-1, 9), 1, [dict(Ученик=ученик, Тариф=карточка, Явка=True, СписатьОплату=True)])
    if проведён(ф.записать(вчера, "Проведение"), "Р2: урок вчера по цене карточки — проводится"):
        т.проверить(float(перечитать(вчера).Сумма) == 1000, "Р2: урок вчера — 1 000", перечитать(вчера).Сумма)
    о = карточка.ПолучитьОбъект()
    о.Сумма = 2000
    c.ПолучитьСообщенияПользователю(True)
    о.Записать()
    сообщения = [str(м.Текст) for м in c.ПолучитьСообщенияПользователю(True)]
    т.проверить(any("действует с" in м for м in сообщения), "Р2: при смене цены карточки — сообщение, с какой даты новая цена",
                сообщения)
    проведён(ф.записать(перечитать(вчера), "Проведение"), "Р2: перепроведение вчерашнего урока после смены цены")
    т.проверить(float(перечитать(вчера).Сумма) == 1000,
                "Р2: перепроведённый старый урок — прежняя цена 1 000 (было: новая 2 000)", перечитать(вчера).Сумма)
    сегодня = ф.урок(педагог, ф.день(0, 0, 1), 1, [dict(Ученик=ученик, Тариф=карточка, Явка=True, СписатьОплату=True)])
    if проведён(ф.записать(сегодня, "Проведение"), "Р2: урок сегодня после смены цены — проводится"):
        т.проверить(float(перечитать(сегодня).Сумма) == 2000, "Р2: урок сегодня — новая цена 2 000", перечитать(сегодня).Сумма)
    цены = т.выбрать("""ВЫБРАТЬ Ц.Период КАК Период, Ц.Сумма КАК Сумма ИЗ РегистрСведений.УЗ_ЦеныТарифов КАК Ц
        ГДЕ Ц.Тариф = &Т УПОРЯДОЧИТЬ ПО Ц.Период""", Т=карточка)
    суммы = [float(цены.Получить(н).Сумма) for н in range(цены.Количество())]
    т.проверить(суммы == [1000, 2000], "Р2: в истории цен прежняя 1 000 и новая 2 000", суммы)

    # ── №9: «Не изменять» у начисления по ставке ──
    ставка = ф.элемент("УЗ_СтавкиПедагогов", "500 за занятие", ОплатаЗаЗанятие=500)
    п9 = ф.педагог("педагог 9", СтавкаПедагога=ставка)
    д = ф.урок(п9, ф.день(-1, 12), 1, [dict(Ученик=ученик, Явка=True)], СтавкаПедагога=ставка)
    проведён(ф.записать(д, "Проведение"), "№9: урок со ставкой 500 за занятие — проводится")
    о = перечитать(д)
    о.НачисленияПедагогу.Получить(0).НеИзменять = True
    проведён(ф.записать(о, "Проведение"), "№9: отметка «Не изменять» — перепроводится")
    ос = ставка.ПолучитьОбъект()
    ос.ОплатаЗаЗанятие = 700
    ос.Записать()
    проведён(ф.записать(перечитать(д), "Проведение"), "№9: перепроведение после смены ставки на 700")
    т.проверить(float(перечитать(д).НачисленоПедагогу) == 500,
                "№9: «Не изменять» — начисление осталось 500 (было: пересчитано 700)", перечитать(д).НачисленоПедагогу)

    # ── №53: ставка вне срока ──
    истекла = ф.элемент("УЗ_СтавкиПедагогов", "истекла", ОплатаЗаЗанятие=500, НачалоДействия=ф.день(-60),
                        ОкончаниеДействия=ф.день(-10))
    п53 = ф.педагог("педагог 53", СтавкаПедагога=истекла)
    д = ф.урок(п53, ф.день(-1, 13), 1, [dict(Ученик=ученик, Явка=True)], СтавкаПедагога=истекла)
    итог = ф.записать(д, "Проведение")
    if проведён(итог, "№53: урок со ставкой вне срока — проводится"):
        т.проверить(float(перечитать(д).НачисленоПедагогу) == 0,
                    "№53: ставка, истёкшая 10 дней назад, не начисляет (было: 500)", перечитать(д).НачисленоПедагогу)
        т.проверить(any("не действует" in текст for текст, _ in итог[1]), "№53: сообщение «ставка не действует»", итог[1])

    # ── №24: пустая дата окончания группы ученика ──
    группа = ф.элемент("УЗ_ГруппыОбучения", "группа")
    избранный = ф.ученик("только выбранные группы")
    о = избранный.ПолучитьОбъект()
    о.ТолькоВыбранныеГруппыОбучения = True
    с = о.ГруппыОбучения.Добавить()
    с.ГруппаОбучения = группа
    о.Записать()
    д = ф.урок(педагог, ф.день(-1, 14), 1, [dict(Ученик=избранный, Явка=True)], ГруппаОбучения=группа)
    ошибка, сообщения = ф.записать(д, "Запись")
    т.проверить(ошибка is None, "№24: пустая «Дата окончания» группы у ученика — урок записывается (было: «окончен срок»)",
                "%s %s" % (ошибка, сообщения))
    о = избранный.ПолучитьОбъект()
    о.ГруппыОбучения.Получить(0).ДатаОкончания = ф.день(-5)
    о.Записать()
    ошибка, сообщения = ф.записать(ф.урок(педагог, ф.день(-1, 15), 1, [dict(Ученик=избранный, Явка=True)],
                                          ГруппаОбучения=группа), "Запись")
    т.проверить(ошибка is not None, "№24: срок группы у ученика кончился 5 дней назад — урок не записывается", сообщения)

    # ── №59: заметка к неоплаченному уроку ──
    настройки = c.РегистрыСведений.УЗ_Настройки.СоздатьМенеджерЗаписи()
    настройки.Прочитать()
    было = (настройки.ТребоватьОписаниеКНеоплаченнымУрокам, настройки.ТребоватьОписаниеКНеоплаченнымУрокамС)

    def вернуть_настройки():
        н = c.РегистрыСведений.УЗ_Настройки.СоздатьМенеджерЗаписи()
        н.Прочитать()
        н.ТребоватьОписаниеКНеоплаченнымУрокам, н.ТребоватьОписаниеКНеоплаченнымУрокамС = было
        н.Записать()
    т.убрать(вернуть_настройки, "настройки учёта")
    настройки.ТребоватьОписаниеКНеоплаченнымУрокам = True
    настройки.ТребоватьОписаниеКНеоплаченнымУрокамС = ф.день(-30)
    настройки.Записать()
    отказ(ф.записать(ф.урок(педагог, ф.день(-1, 16), 1, [dict(Ученик=ученик, Явка=True)]), "Проведение"),
          "№59: неоплачиваемая строка без заметки — отказ у поля «Заметка»", "заметка", "Заметка")
    проведён(ф.записать(ф.урок(педагог, ф.день(-1, 17), 1, [dict(Ученик=ученик, Явка=True, Заметка="болел, отработка")]),
                        "Проведение"), "№59: неоплачиваемая строка с заметкой — проводится")
    проведён(ф.записать(ф.урок(педагог, ф.день(-31, 17), 1, [dict(Ученик=ученик, Явка=True)]), "Проведение"),
             "№59: урок до даты начала требования — без заметки проводится")
    вернуть_настройки()

    # ── №33, №34: тариф с историей цен и бесплатная цена ──
    c.ПолучитьСообщенияПользователю(True)
    с_историей = ф.элемент("УЗ_Тарифы", "история цен", ИспользоватьИсториюЦен=True)
    сообщения = [str(м.Текст) for м in c.ПолучитьСообщенияПользователю(True)]
    т.проверить(not any("сумм" in м.lower() for м in сообщения),
                "№33: запись тарифа с историей цен — без предупреждения о сумме", сообщения)
    набор = c.РегистрыСведений.УЗ_ЦеныТарифов.СоздатьНаборЗаписей()
    з = набор.Добавить()
    з.Период = ф.день(-5)
    з.Тариф = с_историей
    з.Сумма = 0
    з.КоличествоУроков = 1
    т.проверить(набор.ПроверитьЗаполнение(), "№34: цена по дате с суммой 0 (бесплатный тариф) — проверка заполнения проходит")

    # ── №49: урок, начатый раньше рабочего времени ──
    день = ф.день(-1)
    г = c.Документы.УЗ_ГрафикРабочегоВремениПедагога.СоздатьДокумент()
    г.Дата = день
    г.Педагог = п9
    г.Комментарий = МЕТКА
    строка = г.ТЧ.Добавить()
    строка.Дата = день
    строка.ВремяНачала = дата(100, 1, 1, 10)   # COM: 0100-01-01 — это пустая дата 1С, время сохраняется
    строка.ВремяОкончания = дата(100, 1, 1, 18)
    ошибка, _ = ф.записать(г, "Проведение")
    час_графика = ф.число("""ВЫБРАТЬ ЧАС(Т.ВремяНачала) + ГОД(Т.ВремяНачала) * 100
        ИЗ Документ.УЗ_ГрафикРабочегоВремениПедагога.ТЧ КАК Т ГДЕ Т.Ссылка = &С""", С=г.Ссылка)
    if т.проверить(ошибка is None and час_графика == 110, "№49: график педагога 10:00–18:00 проведён (время — дата 01.01.0001)",
                   "%s, час+год×100 = %s" % (ошибка, час_графика)):
        рано = ф.урок(п9, дата(день.year, день.month, день.day, 9, 30), 1, [dict(Ученик=ученик, Явка=True)])
        т.проверить(c.Документы.УЗ_Урок.ПроверитьДокументПоГрафикуРабочегоВремени(рано) is not None,
                    "№49: урок 9:30–10:30 при графике с 10:00 — предупреждение (было: смотрели только конец)")
        внутри = ф.урок(п9, дата(день.year, день.month, день.day, 11), 1, [dict(Ученик=ученик, Явка=True)])
        т.проверить(c.Документы.УЗ_Урок.ПроверитьДокументПоГрафикуРабочегоВремени(внутри) is None,
                    "№49: урок 11:00–12:00 внутри графика — без предупреждения")
        поздно = ф.урок(п9, дата(день.year, день.month, день.day, 17, 30), 1, [dict(Ученик=ученик, Явка=True)])
        т.проверить(c.Документы.УЗ_Урок.ПроверитьДокументПоГрафикуРабочегоВремени(поздно) is not None,
                    "№49: урок 17:30–18:30 при графике до 18:00 — предупреждение")

    # ── Р1: действующий абонемент для помощника (последним: на старом коде функции нет) ──
    ученик_р1 = ф.ученик("абонементы помощника")
    продлён = ф.абонемент(ученик_р1, "продлён приостановкой", КоличествоЗанятий=8, ДатаОкончания=ф.день(-3))
    о = продлён.ПолучитьОбъект()
    п = о.Приостановки.Добавить()
    п.ДатаПриостановки = ф.день(-20)
    п.ДатаВозобновления = ф.день(-15)    # 5 дней паузы → срок до +2
    о.Записать()
    ф.абонемент(ученик_р1, "кончается позже", КоличествоЗанятий=8, ДатаОкончания=ф.день(30))
    ученик_пауза = ф.ученик("абонемент на паузе")
    пауза = ф.абонемент(ученик_пауза, "на паузе", КоличествоЗанятий=8)
    о = пауза.ПолучитьОбъект()
    п = о.Приостановки.Добавить()
    п.ДатаПриостановки = ф.день(-1)
    п.ДатаВозобновления = ф.день(3)
    о.Записать()
    найдено = c.Документы.УЗ_Урок.ДействующиеАбонементы(т.массив(ученик_р1, ученик_пауза),
                                                         c.Справочники.УЗ_ПредметыОбучения.ПустаяСсылка(), ф.день(0, 12))
    выбран = найдено.Получить(ученик_р1)
    т.проверить(выбран is not None and c.String(выбран.УникальныйИдентификатор()) == c.String(продлён.УникальныйИдентификатор()),
                "Р1: срок кончился 3 дня назад, продлён на 5 дней приостановки — абонемент подставляется (он кончается раньше)",
                c.String(найдено.Получить(ученик_р1)))
    т.проверить(найдено.Получить(ученик_пауза) is None, "Р1: абонемент, приостановленный со вчера по +3 дня, — не подставляется",
                c.String(найдено.Получить(ученик_пауза)))


if __name__ == "__main__":
    запустить("урок_ошибки", сценарий)
