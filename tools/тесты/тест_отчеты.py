def период_по_умолчанию(текст_формы, текст_модуля):
    """Отчёт со своей формой и реквизитом «Период» (СтандартныйПериод): пустой период заполняется и при
    создании формы, и после загрузки сохранённых настроек (иначе «с  по 01.01.0001» и «Неправильно задан период»)."""
    if not re.search(r'<Attribute name="Период"[^>]*>(?:(?!</Attribute>).)*v8:StandardPeriod', текст_формы, re.S):
        return None
    нет = [с for с in ("OnCreateAtServer", "OnLoadDataFromSettingsAtServer")
           if not re.search(r'<Event name="%s">' % с, текст_формы)]
    if "ВариантСтандартногоПериода.ЭтотМесяц" not in текст_модуля:
        нет.append("период по умолчанию «Этот месяц»")
    return нет


def основная_форма(c, имя):
    форма = c.Метаданные.Отчеты.Найти(имя).ОсновнаяФорма
    return форма.ПолноеИмя() if форма is not None else ""


def сценарий(т):
    c = т.c

    # самотест: сломанная схема обязана упасть, чужая основная форма — не пройти проверку формы
    поймано = 0
    схема = c.Отчеты.УЗ_Расходы.ПолучитьМакет("ОсновнаяСхемаКомпоновкиДанных")
    набор = схема.НаборыДанных.Получить(0)
    набор.Запрос = набор.Запрос.replace("ВЫБРАТЬ", "ВЫБРАТЬ Проба.НетТакогоПоля КАК НетТакогоПоля,", 1)
    отчет = c.Отчеты.УЗ_Расходы.Создать()
    try:
        сформировать(c, схема, отчет.КомпоновщикНастроек.ПолучитьНастройки())
    except Exception:
        поймано += 1
    if основная_форма(c, "УЗ_ДвиженияДокумента") != ФОРМА:
        поймано += 1
    # включённый пустой отбор «Клиент В группе из списка ""» (№13 осмотра 28.09)
    схема = c.Отчеты.УЗ_ВедомостьПоКассе.ПолучитьМакет("ОсновнаяСхемаКомпоновкиДанных")
    настройки = схема.ВариантыНастроек.Получить(0).Настройки
    for э in настройки.Отбор.Элементы:
        if имя_поля(c, э.ЛевоеЗначение) == "Клиент":
            э.Использование = True
    if пустые_отборы(c, настройки.Отбор.Элементы):
        поймано += 1
    # поле без заголовка в отборе варианта — «Сумма Оборот» (№24)
    схема = c.Отчеты.УЗ_Взаиморасчеты.ПолучитьМакет("ОсновнаяСхемаКомпоновкиДанных")
    схема.НаборыДанных.Получить(0).Поля.Найти("СуммаОборот").Заголовок = ""
    вариант = [в for в in схема.ВариантыНастроек if в.Имя == "ВзаиморасчетыПоПреподавателям"][0]
    if any("СуммаОборот" in з for з in сырые_заголовки(c, схема, вариант.Настройки)):
        поймано += 1
    # безымянная колонка: заголовок поля выборки из пробела (№29, «ЗПКонечныйОстаток»)
    схема = c.Отчеты.УЗ_РасчетыПоЗарплате.ПолучитьМакет("ОсновнаяСхемаКомпоновкиДанных")
    схема.НаборыДанных.Получить(0).Поля.Найти("Выручка").Заголовок = " "
    if any("Выручка" in з for з in сырые_заголовки(c, схема, схема.ВариантыНастроек.Получить(0).Настройки)):
        поймано += 1
    # заголовок отчёта выключен — вверху пустая серая ячейка (№29)
    схема = c.Отчеты.УЗ_РасчетыПоЗарплате.ПолучитьМакет("ОсновнаяСхемаКомпоновкиДанных")
    настройки = схема.ВариантыНастроек.Получить(0).Настройки
    настройки.ПараметрыВывода.НайтиЗначениеПараметра(c.NewObject("ПараметрКомпоновкиДанных", "Заголовок")).Использование = False
    if not заголовок_результата(сформировать_документ(c, схема, настройки)):
        поймано += 1
    # своя форма отчёта без заполнения периода после загрузки настроек (№2, №12)
    путь = os.path.join(ИСХОДНИКИ, "Reports", "УЗ_АналитикаПоУченикам", "Forms", "ФормаОтчета", "Ext", "Form.xml")
    with open(путь, encoding="utf-8-sig") as ф:
        форма = ф.read().replace('<Event name="OnLoadDataFromSettingsAtServer">', '<Event name="Проба">')
    if период_по_умолчанию(форма, "ВариантСтандартногоПериода.ЭтотМесяц"):
        поймано += 1
    т.проверить(поймано == 7, "самотест: 7 подложенных ошибок пойманы", "поймано %d из 7" % поймано)

    # отчёты со своей формой: пустой период заполняется при создании и после загрузки настроек
    for имя in ОТЧЕТЫ:
        for путь in sorted(glob.glob(os.path.join(ИСХОДНИКИ, "Reports", имя, "Forms", "*", "Ext", "Form.xml"))):
            with open(путь, encoding="utf-8-sig") as ф:
                форма = ф.read()
            модуль = os.path.join(os.path.dirname(путь), "Form", "Module.bsl")
            with open(модуль, encoding="utf-8-sig") as ф:
                код = ф.read()
            нет = период_по_умолчанию(форма, код)
            if нет is not None:
                т.проверить(not нет, "%s: пустой период по умолчанию заполняется (форма)" % имя, ", ".join(нет))

    состав = [о.Имя for о in c.Метаданные.Подсистемы.УЗ_УчетЗанятий.Подсистемы.УЗ_Отчеты.Состав
              if c.Метаданные.Отчеты.Содержит(о)]
    т.проверить(sorted(состав) == sorted(ОТЧЕТЫ), "состав УЗ_Отчеты = 9 отчетов теста", ", ".join(состав))
    т.проверить(c.Метаданные.ОбщиеФормы.Найти("УЗ_ФормаОтчета") is not None, "общая форма УЗ_ФормаОтчета есть")
    т.проверить(c.Метаданные.ОбщиеФормы.Найти("УЗ_СписокОтчетов") is not None, "общая форма УЗ_СписокОтчетов есть")

    for имя in ОТЧЕТЫ:
        н = time.time()
        try:
            отчет = getattr(c.Отчеты, имя).Создать()
            if имя in НА_СКД:
                высота = сформировать(c, отчет.СхемаКомпоновкиДанных, отчет.КомпоновщикНастроек.ПолучитьНастройки())
                форма = основная_форма(c, имя)
                т.проверить(высота > 0, "%s: сформирован (строк %d, %.2f с)" % (имя, высота, time.time() - н))
                т.проверить(форма == ФОРМА, "%s: основная форма %s" % (имя, ФОРМА), форма)
                замечания = проверить_варианты(c, имя, отчет.СхемаКомпоновкиДанных)
                т.проверить(not замечания, "%s: варианты — заголовок, отборы, поля, пустой период (%.2f с)"
                            % (имя, time.time() - н), "; ".join(замечания))
            else:
                # отчет со своей формой и макетами: объект создается, макеты читаются
                макеты = [м.Имя for м in c.Метаданные.Отчеты.Найти(имя).Макеты]
                for м in макеты:
                    getattr(c.Отчеты, имя).ПолучитьМакет(м)
                т.проверить(True, "%s: объект и макеты (%d) без СКД" % (имя, len(макеты)))
        except Exception as исключение:
            т.проверить(False, "%s: формирование" % имя, текст_ошибки(исключение, 200))


if __name__ == "__main__":
    запустить("отчеты", сценарий)
