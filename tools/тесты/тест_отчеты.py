def сформировать(c, схема, настройки):
    """Высота табличного документа; исключение — ошибка формирования."""
    макет = c.NewObject("КомпоновщикМакетаКомпоновкиДанных").Выполнить(схема, настройки)
    процессор = c.NewObject("ПроцессорКомпоновкиДанных")
    процессор.Инициализировать(макет)
    документ = c.NewObject("ТабличныйДокумент")
    вывод = c.NewObject("ПроцессорВыводаРезультатаКомпоновкиДанныхВТабличныйДокумент")
    вывод.УстановитьДокумент(документ)
    вывод.Вывести(процессор)
    return документ.ВысотаТаблицы


def имя_поля(c, поле):
    """«Клиент» из ПолеКомпоновкиДанных (Строка()/СокрЛП через COM недоступны — берём из внутренней строки)."""
    м = re.search(r'\{"([^"]*)"\}\s*\}\s*$', c.ЗначениеВСтрокуВнутр(поле))
    return м.group(1) if м else "?"


def пустые_отборы(c, элементы):
    """Включённые отборы со ссылкой/списком без значения: «Клиент В группе из списка ""» — отбор, который
    пользователь не задавал. Числа, даты, булево не считаем: «Сумма > 0» — законный отбор."""
    без_значения = {c.ЗначениеВСтрокуВнутр(getattr(c.ВидСравненияКомпоновкиДанных, в)) for в in ("Заполнено", "НеЗаполнено")}
    итог = []
    for э in элементы:
        if not э.Использование:
            continue
        try:
            вложенные = э.Элементы
        except Exception:
            вложенные = None
        if вложенные is not None:
            итог += пустые_отборы(c, вложенные)
            continue
        if c.ЗначениеВСтрокуВнутр(э.ВидСравнения) in без_значения:
            continue
        знач = э.ПравоеЗначение
        if знач is None or знач == "":
            итог.append(имя_поля(c, э.ЛевоеЗначение))
        elif hasattr(знач, "_oleobj_"):
            try:
                пусто = знач.Количество() == 0
            except Exception:
                пусто = not c.ЗначениеЗаполнено(знач)
            if пусто:
                итог.append(имя_поля(c, э.ЛевоеЗначение))
    return итог


def заголовок_результата(документ):
    """Заголовок отчёта в первых трёх строках результата (СКД начинает вывод с пустой строки-отступа).
    Без заголовка вверху пустое место, а при печати непонятно, что за отчёт."""
    for строка in range(1, min(документ.ВысотаТаблицы, 3) + 1):
        текст = " ".join(документ.Область(строка, к, строка, к).Текст
                         for к in range(1, min(документ.ШиринаТаблицы, 6) + 1)).strip()
        if текст and not текст.startswith("Параметры"):
            return текст
    return ""


def сырые_заголовки(c, схема, настройки, компоновщик=None):
    """Заголовки полей выборки и отборов варианта, собранные платформой из имени поля («Сумма Оборот»):
    в части пути второе и дальше слово с заглавной буквы (аббревиатуры КАПСОМ не в счёт); и «преподаватель»
    вместо «педагог»."""
    if компоновщик is None:
        компоновщик = c.NewObject("КомпоновщикНастроекКомпоновкиДанных")
        компоновщик.Инициализировать(c.NewObject("ИсточникДоступныхНастроекКомпоновкиДанных", схема))
    поля = []

    def собрать(элементы, отбор):
        for э in элементы:
            try:
                собрать(э.Элементы, отбор)
                continue
            except Exception:
                pass
            try:
                поле = э.ЛевоеЗначение if отбор else э.Поле
                свой = "" if отбор else (э.Заголовок or "")
            except Exception:
                continue
            поля.append((имя_поля(c, поле), свой))

    # в таблице с группировками колонок (явки по датам) ресурс без заголовка — законно: заголовок колонки даёт дата
    def есть_колонки(структура):
        for элемент in структура:
            try:
                if элемент.Колонки.Количество() > 0:
                    return True
            except Exception:
                pass
            try:
                if есть_колонки(элемент.Структура):
                    return True
            except Exception:
                pass
        return False

    кросс_таблица = есть_колонки(настройки.Структура)
    собрать(настройки.Выбор.Элементы, False)
    собрать(настройки.Отбор.Элементы, True)
    плохие = []
    for имя, свой in поля:
        заг = свой
        if not заг:
            поле = компоновщик.Настройки.ДоступныеПоляОтбора.НайтиПоле(c.NewObject("ПолеКомпоновкиДанных", имя))
            if поле is None:
                continue
            заг = поле.Заголовок
        сырой = any(any(с[:1].isupper() and not с.isupper() for с in часть.split()[1:]) for часть in заг.split("."))
        if not заг.strip() and not кросс_таблица:
            плохие.append("%s — пустой заголовок: безымянная колонка" % имя)
            continue
        if сырой or "реподават" in заг.lower():
            плохие.append("%s «%s»" % (имя, заг))
    return плохие

def проверить_варианты(c, имя, схема):
    """[замечания] по всем вариантам отчёта на СКД: формируется (и с пустым периодом), нет пустых включённых
    отборов, есть заголовок результата, нет сырых заголовков полей, вариант не назван как сам отчёт."""
    замечания = []
    синоним = c.Метаданные.Отчеты.Найти(имя).Синоним
    варианты = list(схема.ВариантыНастроек)
    компоновщик = c.NewObject("КомпоновщикНастроекКомпоновкиДанных")
    компоновщик.Инициализировать(c.NewObject("ИсточникДоступныхНастроекКомпоновкиДанных", схема))
    for вариант in варианты:
        кто = "%s/%s" % (имя, вариант.Представление)
        настройки = вариант.Настройки
        пустые = пустые_отборы(c, настройки.Отбор.Элементы)
        if пустые:
            замечания.append("%s: включён пустой отбор %s" % (кто, ", ".join(пустые)))
        сырые = сырые_заголовки(c, схема, настройки, компоновщик)
        if сырые:
            замечания.append("%s: заголовки из имени поля: %s" % (кто, "; ".join(сырые)))
        if len(варианты) > 1 and вариант.Представление.strip().lower() == синоним.strip().lower():
            замечания.append("%s: вариант назван как отчёт — заголовок формы «%s (%s)»" % (кто, синоним, синоним))
        try:
            документ = сформировать_документ(c, схема, настройки)
            if not заголовок_результата(документ):
                замечания.append("%s: нет заголовка отчёта в начале результата" % кто)
        except Exception as исключение:
            замечания.append("%s: не формируется: %s" % (кто, текст_ошибки(исключение, 150)))
        период = настройки.ПараметрыДанных.НайтиЗначениеПараметра(c.NewObject("ПараметрКомпоновкиДанных", "Период"))
        if период is not None:
            период.Значение = c.NewObject("СтандартныйПериод")
            период.Использование = True
            try:
                сформировать_документ(c, схема, настройки)
            except Exception as исключение:
                замечания.append("%s: не формируется при пустом периоде: %s" % (кто, текст_ошибки(исключение, 150)))
    return замечания


def сформировать_документ(c, схема, настройки):
    макет = c.NewObject("КомпоновщикМакетаКомпоновкиДанных").Выполнить(схема, настройки)
    процессор = c.NewObject("ПроцессорКомпоновкиДанных")
    процессор.Инициализировать(макет)
    документ = c.NewObject("ТабличныйДокумент")
    вывод = c.NewObject("ПроцессорВыводаРезультатаКомпоновкиДанныхВТабличныйДокумент")
    вывод.УстановитьДокумент(документ)
    вывод.Вывести(процессор)
    return документ


