def период_по_умолчанию(текст_формы, текст_модуля):
    """Отчёт со своей формой и реквизитом «Период» (СтандартныйПериод): пустой период заполняется и при
    создании формы, и после загрузки сохранённых настроек (иначе «с  по 01.01.0001» и «Неправильно задан период»)."""
    if not re.search(r'<Attribute name="Период"[^>]*>(?:(?!</Attribute>).)*v8:StandardPeriod', текст_формы, re.S):
        return None
    нет = [с for с in ("OnCreateAtServer", "OnLoadDataFromSettingsAtServer")
           if not re.search(r'<Event name="%s">' % с, текст_формы)]
    if "ВариантСтандартногоПериода.ЭтотМесяц" not in текст_модуля:
        нет.append("период по умолчанию «Этот месяц»")
    return нет


