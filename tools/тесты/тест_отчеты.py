"""COM-тест отчетов УЗ_ext: каждый отчет подсистемы УЗ_Отчеты создается, отчеты на СКД формируются
программно (КомпоновщикМакета + ПроцессорКомпоновки → ТабличныйДокумент) без ошибок; у отчетов на СКД
основная форма — своя УЗ_ФормаОтчета (не форма БСП хозяина); панель отчетов и форма есть в метаданных.

Встроенный самотест (проверке не верим без него): схема с неизвестным полем обязана дать ошибку
формирования, отчет со своей формой (УЗ_ДвиженияДокумента) — не пройти проверку «форма УЗ_ФормаОтчета».

    python tools\\тесты\\тест_отчеты.py --база=C:\\1c_bases\\UZ_UNF_A
Бюджет: 10 с без подключения (подключение к файловой УНФ ~6 с — цена платформы, меряется отдельно).
Первое чтение макета СКД в сеансе стоит ~3–4 с: инициализация ФабрикиXDTO по метаданным УНФ (замерено).
"""
import sys
import time

import win32com.client

БАЗА = r"C:\1c_bases\UZ_UNF_A"
БЮДЖЕТ = 10
ФОРМА = "ОбщаяФорма.УЗ_ФормаОтчета"
ОТЧЕТЫ = ["УЗ_АналитикаПоУченикам", "УЗ_ВедомостьПоКассе", "УЗ_ВедомостьПоКассеДляМенеджеров", "УЗ_Взаиморасчеты",
          "УЗ_ДвиженияДокумента", "УЗ_ОтчетПоДисконтнымКартам", "УЗ_Расходы", "УЗ_РасчетыПоЗарплате", "УЗ_Явки_2"]
НА_СКД = {"УЗ_ВедомостьПоКассе", "УЗ_Взаиморасчеты", "УЗ_ОтчетПоДисконтнымКартам", "УЗ_Расходы",
          "УЗ_РасчетыПоЗарплате", "УЗ_Явки_2"}

провалов = 0


def _пользователь():
    """--пользователь=1 (БП), Admin (УТ); по умолчанию Администратор (УНФ)."""
    import sys as _sys
    for арг in _sys.argv[1:]:
        if арг.startswith("--пользователь="):
            return арг.split("=", 1)[1]
    return "Администратор"


def проверка(имя, условие, подробности=""):
    global провалов
    print("[%s] %s%s" % ("PASS" if условие else "FAIL", имя, ("  — " + подробности) if подробности else ""))
    if not условие:
        провалов += 1


def текст_ошибки(исключение):
    аргументы = getattr(исключение, "excepinfo", None) or исключение.args
    сообщение = str(аргументы[2] if isinstance(аргументы, tuple) and len(аргументы) > 2 else исключение)
    return " ".join(сообщение.split())[:200]


def сформировать(c, схема, настройки):
    """Высота табличного документа; исключение — ошибка формирования."""
    макет = c.NewObject("КомпоновщикМакетаКомпоновкиДанных").Выполнить(схема, настройки)
    процессор = c.NewObject("ПроцессорКомпоновкиДанных")
    процессор.Инициализировать(макет)
    документ = c.NewObject("ТабличныйДокумент")
    вывод = c.NewObject("ПроцессорВыводаРезультатаКомпоновкиДанныхВТабличныйДокумент")
    вывод.УстановитьДокумент(документ)
    вывод.Вывести(процессор)
    return документ.ВысотаТаблицы


def основная_форма(c, имя):
    форма = c.Метаданные.Отчеты.Найти(имя).ОсновнаяФорма
    return форма.ПолноеИмя() if форма is not None else ""


def main():
    база = БАЗА
    for арг in sys.argv[1:]:
        if арг.startswith("--база="):
            база = арг.split("=", 1)[1]
    начало = time.time()
    c = win32com.client.Dispatch("V83.COMConnector").Connect('File="%s";Usr="%s";' % (база, _пользователь()))
    подключение = time.time() - начало
    начало = time.time()

    # самотест: сломанная схема обязана упасть, чужая основная форма — не пройти проверку формы
    поймано = 0
    схема = c.Отчеты.УЗ_Расходы.ПолучитьМакет("ОсновнаяСхемаКомпоновкиДанных")
    набор = схема.НаборыДанных.Получить(0)
    набор.Запрос = набор.Запрос.replace("ВЫБРАТЬ", "ВЫБРАТЬ Проба.НетТакогоПоля КАК НетТакогоПоля,", 1)
    отчет = c.Отчеты.УЗ_Расходы.Создать()
    try:
        сформировать(c, схема, отчет.КомпоновщикНастроек.ПолучитьНастройки())
    except Exception:
        поймано += 1
    if основная_форма(c, "УЗ_ДвиженияДокумента") != ФОРМА:
        поймано += 1
    проверка("самотест: 2 подложенные ошибки пойманы", поймано == 2, "поймано %d из 2" % поймано)

    состав = [о.Имя for о in c.Метаданные.Подсистемы.УЗ_УчетЗанятий.Подсистемы.УЗ_Отчеты.Состав
              if c.Метаданные.Отчеты.Содержит(о)]
    проверка("состав УЗ_Отчеты = 9 отчетов теста", sorted(состав) == sorted(ОТЧЕТЫ), ", ".join(состав))
    проверка("общая форма УЗ_ФормаОтчета есть", c.Метаданные.ОбщиеФормы.Найти("УЗ_ФормаОтчета") is not None)
    проверка("общая форма УЗ_СписокОтчетов есть", c.Метаданные.ОбщиеФормы.Найти("УЗ_СписокОтчетов") is not None)

    for имя in ОТЧЕТЫ:
        т = time.time()
        try:
            отчет = getattr(c.Отчеты, имя).Создать()
            if имя in НА_СКД:
                высота = сформировать(c, отчет.СхемаКомпоновкиДанных, отчет.КомпоновщикНастроек.ПолучитьНастройки())
                форма = основная_форма(c, имя)
                проверка("%s: сформирован (строк %d, %.2f с)" % (имя, высота, time.time() - т), высота > 0)
                проверка("%s: основная форма %s" % (имя, ФОРМА), форма == ФОРМА, форма)
            else:
                # отчет со своей формой и макетами: объект создается, макеты читаются
                макеты = [м.Имя for м in c.Метаданные.Отчеты.Найти(имя).Макеты]
                for м in макеты:
                    getattr(c.Отчеты, имя).ПолучитьМакет(м)
                проверка("%s: объект и макеты (%d) без СКД" % (имя, len(макеты)), True)
        except Exception as исключение:
            проверка("%s: формирование" % имя, False, текст_ошибки(исключение))

    всего = time.time() - начало
    метка = "  ПРЕДУПРЕЖДЕНИЕ: бюджет %d с превышен" % БЮДЖЕТ if всего > БЮДЖЕТ else ""
    print("Время: тест %.1f с (подключение %.1f с)%s" % (всего, подключение, метка))
    print("ИТОГО провалов: %d" % провалов)
    return 1 if провалов else 0


if __name__ == "__main__":
    sys.exit(main())
