БЮДЖЕТ_СЕК = 10
УТС = datetime.timezone.utc
БАЗА_ПО_УМОЛЧАНИЮ = r"C:\1c_bases\UZ_UNF"
ПОЛЬЗОВАТЕЛЬ_ПО_УМОЛЧАНИЮ = "Администратор"


def настроить_вывод():
    for поток in (sys.stdout, sys.stderr):
        try:
            поток.reconfigure(encoding="utf-8")
        except Exception:
            pass


def аргумент(имя, по_умолчанию=None):
    """--имя=значение из командной строки."""
    for арг in sys.argv[1:]:
        if арг.startswith("--%s=" % имя):
            return арг.split("=", 1)[1]
    return по_умолчанию


def подключить(база, пользователь, закрепить=True):
    """COM-соединение с файловой базой (без пароля) → (соединение, секунд).

    Первым делом — песочница почты сеанса (N05): тесты идут на копиях баз, где могут остаться рабочие
    настройки SMTP и настоящие адреса учеников. В песочнице продукт письма не отправляет, а пишет в журнал
    регистрации. Не включилась — соединение не отдаём: ни один тест не запустится без предохранителя."""
    import win32com.client
    н = time.time()
    c = win32com.client.Dispatch("V83.COMConnector").Connect('File="%s";Usr="%s";' % (база, пользователь))
    включить_песочницу(c)
    if закрепить:   # демо-данные (tools\демо) — в реальном времени владельца, не во времени тестов
        закрепить_время(c)
    return c, time.time() - н


# ── время тестов: не зависит от времени суток ──
# Тесты строят данные «сегодня в ЧЧ:ММ» (урок сегодня проводится, ПКО сегодня в кассе), а продукт сравнивает их
# с ТекущаяДатаСеанса(): урок раньше начала не проводится, остаток кассы — на сейчас. Прогон в 00:03 давал провалы
# (урок сегодня в 00:05 — «ещё не начался»), прогон в 08:00 — другие, в 23:59 — переход суток посреди прогона.
# Поэтому каждый COM-сеанс тестов получает часовой пояс, в котором «сейчас» — около полудня ДНЯ ТЕСТОВ (реального
# сегодня на момент первого подключения процесса): до полудня — прошлое сегодня (проводится), после — будущее
# сегодня (план). ТекущаяДатаСеанса() и серверный код продукта видят именно это время; даты в тестах — от
# сегодня() этого модуля, а не от datetime.date.today(). Пояса Etc/GMT±N — целые часы от −12 до +14.
# Проверка подменой: UZ_ЧАС_ТЕСТОВ=0 — сеансы «около полуночи» (минуты — реальные; в 01:03 компьютера сеанс — 00:03),
# UZ_ВРЕМЯ_КАК_ЕСТЬ=1 — без закрепления (часы компьютера)
ЧАС_ТЕСТОВ = 12
ОКНО_ЧАСОВ = (10, 14)      # допустимый час сеанса вокруг ЧАС_ТЕСТОВ по умолчанию
_день_тестов = None
_смещение = None           # часы пояса сеансов тестов от UTC


def пояс_для(утс, день, час):
    """Пояс Etc/GMT±N, в котором момент утс (aware UTC) — день day около часа час → (имя, смещение ч) | None."""
    лучшее = None
    for смещение in range(-12, 15):
        местное = (утс + datetime.timedelta(hours=смещение)).replace(tzinfo=None)
        if местное.date() != день:
            continue
        отклонение = abs(местное.hour - час)
        if лучшее is None or отклонение < лучшее[0]:
            лучшее = (отклонение, смещение)
    if лучшее is None:
        return None
    смещение = лучшее[1]
    # имена Etc/GMT — со знаком наоборот: Etc/GMT-3 = UTC+3
    return ("Etc/GMT%+d" % -смещение if смещение else "Etc/GMT"), смещение


def закрепить_время(c, заново=False):
    """Часовой пояс сеанса c: сейчас — около ЧАС_ТЕСТОВ дня тестов. заново — день тестов взять заново (долгоживущий
    сервер итераций). → ТекущаяДатаСеанса() после закрепления."""
    global _день_тестов, _смещение
    if _день_тестов is None or заново:
        _день_тестов = datetime.date.today()
    if os.environ.get("UZ_ВРЕМЯ_КАК_ЕСТЬ"):   # мутация: без закрепления (как было до 29.09.2026)
        return c.ТекущаяДатаСеанса()
    час = int(os.environ.get("UZ_ЧАС_ТЕСТОВ", ЧАС_ТЕСТОВ))
    пояс = пояс_для(datetime.datetime.now(УТС), _день_тестов, час)
    if пояс is None:
        raise RuntimeError("время тестов: нет пояса, где сейчас %s около %d ч" % (_день_тестов, час))
    c.УстановитьЧасовойПоясСеанса(пояс[0])
    _смещение = пояс[1]
    сейчас = c.ТекущаяДатаСеанса()
    if как_дата(сейчас) != _день_тестов or ("UZ_ЧАС_ТЕСТОВ" not in os.environ
                                            and not ОКНО_ЧАСОВ[0] <= сейчас.hour < ОКНО_ЧАСОВ[1]):
        raise RuntimeError("время тестов не закрепилось: сеанс %s, ждали %s около %d ч" % (сейчас, _день_тестов, час))
    return сейчас


def сегодня():
    """День тестов (дата сеансов тестов) — вместо datetime.date.today(): после полуночи посреди прогона он тот же."""
    return _день_тестов or datetime.date.today()


def сейчас():
    """«Сейчас» сеансов тестов (до минуты, для передачи в COM) — вместо datetime.datetime.now()."""
    if _смещение is None:
        н = datetime.datetime.now()
    else:
        н = datetime.datetime.now(УТС) + datetime.timedelta(hours=_смещение)
    return дата(н.year, н.month, н.day, н.hour, н.minute)


def включить_песочницу(c):
    """Песочница почты (параметр сеанса УЗ_ПесочницаПочты) — и проверка, что она действительно включена."""
    try:
        c.УЗ_Почта.ВключитьПесочницу()
        включена = c.УЗ_Почта.ПесочницаВключена()
    except Exception as е:
        raise RuntimeError("песочница почты не включилась (%s) — тесты не запускаю: письма могли бы уйти "
                           "ученикам копии" % текст_ошибки(е))
    if not включена:
        raise RuntimeError("песочница почты не включилась — тесты не запускаю: письма могли бы уйти ученикам копии")


# ── журнал регистрации файловой базы: читается напрямую (ВыгрузитьЖурналРегистрации по COM висит) ──

def позиция_журнала(база):
    """Размеры файлов журнала сейчас — потом читать только новое."""
    return {п: os.path.getsize(п) for п in glob.glob(os.path.join(база, "1Cv8Log", "*.lgp"))}


def события_журнала(база, позиция, событие):
    """Комментарии записей события (имя события 1С, например «Учёт занятий.Почта.Отправка») после позиции.
    None — журнала нет (серверная база): доказать по журналу ничего нельзя."""
    папка = os.path.join(база, "1Cv8Log")
    try:
        словарь = open(os.path.join(папка, "1Cv8.lgf"), encoding="utf-8-sig", errors="replace").read()
    except OSError:
        return None
    номера = {и for имя, и in re.findall(r'^\{4,"((?:[^"]|"")*)",(\d+)\}', словарь, re.M) if имя == событие}
    итог = []
    for файл in sorted(glob.glob(os.path.join(папка, "*.lgp"))):
        with open(файл, "rb") as ф:
            ф.seek(позиция.get(файл, 0))
            текст = ф.read().decode("utf-8", errors="replace")
        for м in re.finditer(r'\{\d{14},\w,\s*\{[^}]*\},\d+,\d+,\d+,\d+,(\d+),\w,"((?:[^"]|"")*)"', текст):
            if м.group(1) in номера:
                итог.append(м.group(2).replace('""', '"'))
    return итог


def текст_ошибки(исключение, длина=300):
    """Текст ошибки платформы — в последнем аргументе COM-исключения."""
    аргументы = getattr(исключение, "excepinfo", None) or исключение.args
    текст = аргументы[2] if isinstance(аргументы, tuple) and len(аргументы) > 2 else исключение
    return " ".join(str(текст).split())[:длина]


def ошибка_записи(действие):
    """Текст ошибки, если действие упало, иначе None."""
    try:
        действие()
        return None
    except Exception as исключение:
        return текст_ошибки(исключение)


def удалить_объект(c, ссылка, загрузка=None):
    """Удалить объект по ссылке; у документа — сначала его движения по всем регистрам.

    загрузка=None (по умолчанию): элемент справочника удаляется в режиме загрузки, документ — без него.
    Замер 29.09.2026 на UZ_BP_E: удаление элемента справочника без загрузки — 40–48 мс, с загрузкой — 9 мс:
    при удалении идут подписки хозяина на «все справочники» (УправлениеСвойствамиСлужебный, УправлениеДоступом,
    ПомеченныеНаУдаление…), к объектам УЗ_ext не относящиеся; своих ПередУдалением у справочников УЗ_ext нет
    (только у документов — даты запрета). Тест на 70 элементов тратил на уборку 3,8 с из 6.

    Опыт 28.09.2026 на UZ_UNF_D: при ОбменДанными.Загрузка = Истина платформа удаляет документ, а его
    движения оставляет («движений до 1, после удаления 1»; без Загрузки — 0). Отсюда сироты в регистрах
    баз A/B/C: тест_права убирал ПКО и уроки сотрудника в режиме загрузки. Поэтому движения чистим сами —
    набором записей с отбором по регистратору, тоже в режиме загрузки (мимо дат запрета)."""
    о = ссылка.ПолучитьОбъект()
    if о is None:
        return
    мд = ссылка.Метаданные()
    документ = c.Метаданные.Документы.Содержит(мд)
    if загрузка is None:
        загрузка = not документ
    if документ:
        for р in мд.Движения:
            полное = р.ПолноеИмя()
            менеджер = getattr(c.РегистрыНакопления if полное.startswith("РегистрНакопления.") else
                               c.РегистрыСведений if полное.startswith("РегистрСведений.") else
                               c.РегистрыБухгалтерии if полное.startswith("РегистрБухгалтерии.") else
                               c.РегистрыРасчета, р.Имя)
            набор = менеджер.СоздатьНаборЗаписей()
            набор.Отбор.Регистратор.Установить(ссылка)
            набор.ОбменДанными.Загрузка = True
            набор.Записать()
    о.ОбменДанными.Загрузка = загрузка
    о.Удалить()


def _регистры_с_регистратором(c):
    """Полные имена своих (УЗ_) регистров, записи которых подчинены регистратору."""
    имена = ["РегистрНакопления." + р.Имя for р in c.Метаданные.РегистрыНакопления if р.Имя.startswith("УЗ_")]
    подчинение = c.String(c.Метаданные.СвойстваОбъектов.РежимЗаписиРегистра.ПодчинениеРегистратору)
    имена += ["РегистрСведений." + р.Имя for р in c.Метаданные.РегистрыСведений
              if р.Имя.startswith("УЗ_") and c.String(р.РежимЗаписи) == подчинение]
    return имена


def сироты(c):
    """{регистр: число регистраторов, которых нет в базе} — движения удалённых документов. Один запрос."""
    регистры = _регистры_с_регистратором(c)
    if not регистры:
        return {}
    з = c.NewObject("Запрос")
    з.Текст = "\nОБЪЕДИНИТЬ ВСЕ\n".join(
        'ВЫБРАТЬ "%s" КАК Регистр, КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Р.Регистратор) КАК Сирот ИЗ %s КАК Р '
        "ГДЕ Р.Регистратор.Ссылка ЕСТЬ NULL" % (р, р) for р in регистры)
    в = з.Выполнить().Выбрать()
    итог = {}
    while в.Следующий():
        итог[в.Регистр] = int(в.Сирот)
    return итог


def дата(год, месяц, день, час=0, минута=0, секунда=0):
    # наивный datetime через COM сдвигается по поясу — только с tzinfo=utc
    return datetime.datetime(год, месяц, день, час, минута, секунда, tzinfo=УТС)


def как_дата(значение):
    """Дата 1С из COM → datetime.date; пустая дата 1С приходит 0100-01-01 → None."""
    if значение is None or значение.year < 1900:
        return None
    return datetime.date(значение.year, значение.month, значение.day)


class Тест:
    def __init__(self, имя, c=None, база=None):
        """c — готовое соединение общего прогона; без него подключаемся по --база/--пользователь."""
        self.имя = имя
        self.ошибок = 0
        self.проверок = 0
        self.уборка = []
        self.подключение = 0.0
        self.вне_бюджета = 0.0   # доп. подключения внутри сценария (сеанс сотрудника) — меряются отдельно
        self.контроль = 0.0      # общий контроль сирот до и после теста — тоже вне бюджета сценария
        self.база = база or аргумент("база", БАЗА_ПО_УМОЛЧАНИЮ)
        if c is None:
            настроить_вывод()
            c, self.подключение = подключить(self.база, аргумент("пользователь", ПОЛЬЗОВАТЕЛЬ_ПО_УМОЛЧАНИЮ))
            print("== тест %s: база %s, подключение %.1f с" % (имя, self.база, self.подключение))
        else:
            print("== тест %s" % имя)
        self.c = c
        self.начало = time.time()
        self.сек = 0.0

    def проверить(self, условие, что, подробности=""):
        self.проверок += 1
        if условие:
            print("  ок    %s" % что)
        else:
            self.ошибок += 1
            print("  ОШИБКА %s %s" % (что, подробности))
        return условие

    def подключить(self, пользователь):
        """Второе COM-соединение с той же базой под другим пользователем; время — вне бюджета сценария."""
        c, сек = подключить(self.база, пользователь)
        self.вне_бюджета += сек
        print("  (подключение под «%s» %.1f с — вне бюджета)" % (пользователь, сек))
        return c

    def убрать(self, действие, что="", пакет=False):
        """пакет=True — простое удаление объекта, созданного тестом в этом же сеансе (помощники фабрики и _деньги):
        подряд идущие такие уборки идут ОДНОЙ транзакцией. Замер 29.09.2026, UZ_BP_E: запись файловой базы вне
        транзакции — своя фиксация на диск, 10–20 мс; в транзакции — 1,5–2 мс (тест на 70 объектов: уборка 3,8 с →
        0,3 с). Упала хоть одна — транзакция отменяется и пакет убирается по одному, как раньше. Уборки с другими
        сеансами, пользователями ИБ, настройками — без пакета (транзакция этого сеанса держала бы таблицы)."""
        self.уборка.append((действие, что, пакет))

    @contextlib.contextmanager
    def транзакция(self):
        """Массовая заготовка данных одной транзакцией (та же экономия фиксаций, что у пакетной уборки).
        Исключение внутри — транзакция отменяется, созданное не остаётся (уборка найдёт пустые ссылки)."""
        self.c.НачатьТранзакцию()
        try:
            yield
        except BaseException:
            if self.c.ТранзакцияАктивна():
                self.c.ОтменитьТранзакцию()
            raise
        self.c.ЗафиксироватьТранзакцию()

    def выполнить(self, сценарий):
        """Сценарий, уборка, затем общий контроль: после теста сирот в регистрах не прибавилось
        (движения удалённых документов — «<Объект не найден>» в отчётах). Контроль — вне бюджета сценария."""
        н = time.time()
        try:
            сироты_до = сироты(self.c)
        except Exception as е:
            сироты_до = None
            self.ошибок += 1
            print("  ОШИБКА контроль сирот не выполнился: %s" % текст_ошибки(е))
        self.контроль = time.time() - н
        self.начало = time.time()
        try:
            self._выполнить(сценарий)
        finally:
            н = time.time()
            if сироты_до is not None:
                try:
                    после = сироты(self.c)
                    прибавилось = {р: после[р] - сироты_до.get(р, 0) for р in после
                                   if после[р] > сироты_до.get(р, 0)}
                    self.проверить(not прибавилось, "после теста нет новых сирот — движений удалённых документов",
                                   "; ".join("%s +%d" % (р, к) for р, к in sorted(прибавилось.items())))
                except Exception as е:
                    self.ошибок += 1
                    print("  ОШИБКА контроль сирот не выполнился: %s" % текст_ошибки(е))
            self.контроль += time.time() - н
            print("  (контроль сирот %.2f с — вне бюджета)" % self.контроль)

    def _выполнить(self, сценарий):
        self.начало = time.time()
        try:
            сценарий(self)
        except Exception as е:
            self.ошибок += 1
            # traceback.format_exc спотыкается о кириллицу в строке с «^^^» — печатаем кадры сами
            кадры = "".join("    %s:%d %s\n" % (os.path.basename(к.filename), к.lineno, к.line)
                            for к in traceback.extract_tb(е.__traceback__))
            print("  ОШИБКА сценарий упал: %s\n%s" % (текст_ошибки(е, 500), кадры))
        finally:
            действия, self.уборка = list(reversed(self.уборка)), []
            поз = 0
            while поз < len(действия):
                конец = поз + 1
                while действия[поз][2] and конец < len(действия) and действия[конец][2]:
                    конец += 1
                if конец - поз > 1 and not self._уборка_пакетом(действия[поз:конец]):
                    print("  (пакетная уборка %d объектов не прошла одной транзакцией — по одному)" % (конец - поз))
                    for действие in действия[поз:конец]:
                        self._убрать_одно(*действие[:2])
                elif конец - поз == 1:
                    self._убрать_одно(*действия[поз][:2])
                поз = конец
            self.сек = time.time() - self.начало - self.вне_бюджета

    def _убрать_одно(self, действие, что):
        try:
            действие()
        except Exception as е:
            self.ошибок += 1
            print("  ОШИБКА уборки %s: %s" % (что, текст_ошибки(е)))

    def _уборка_пакетом(self, действия):
        """Все действия одной транзакцией → True; упало — транзакция отменена (ничего не удалено), False."""
        try:
            self.c.НачатьТранзакцию()
        except Exception:
            return False
        try:
            for действие in действия:
                действие[0]()
            self.c.ЗафиксироватьТранзакцию()
            return True
        except Exception:
            if self.c.ТранзакцияАктивна():
                self.c.ОтменитьТранзакцию()
            return False

    def итог(self):
        метка = "  ПРЕДУПРЕЖДЕНИЕ: бюджет %d с превышен" % БЮДЖЕТ_СЕК if self.сек > БЮДЖЕТ_СЕК else ""
        подключение = " (+ подключение %.1f с)" % self.подключение if self.подключение else ""
        if self.вне_бюджета:
            подключение += " (+ вне бюджета внутри сценария %.1f с)" % self.вне_бюджета
        print("== %s: проверок %d, ошибок %d, сценарий %.1f с%s%s"
              % (self.имя, self.проверок, self.ошибок, self.сек, подключение, метка))
        return 1 if self.ошибок else 0

    # ── помощники ──
    def массив(self, *значения):
        м = self.c.NewObject("Массив")
        for з in значения:
            м.Добавить(з)
        return м

    def удалить_объект(self, ссылка, загрузка=None):
        """Объект по ссылке; документ — вместе с движениями (см. удалить_объект модуля)."""
        удалить_объект(self.c, ссылка, загрузка)

    def найти_текст(self, тд, текст):
        """Есть ли текст в табличном документе (НайтиТекст ищет по частичному совпадению)."""
        return тд.НайтиТекст(текст) is not None

    def строка_отчета(self, тд, текст):
        """Текст всей строки табличного документа, где впервые встретился текст («» — не нашёлся).
        Неразрывный пробел разделителя разрядов — как обычный: «1 234,56»."""
        область = тд.НайтиТекст(текст)
        if область is None:
            return ""
        н = область.Верх
        ячейки = (тд.Область(н, к, н, к).Текст for к in range(1, тд.ШиринаТаблицы + 1))
        return " | ".join(я.strip() for я in ячейки if я and я.strip()).replace("\xa0", " ")

    def выбрать(self, текст, **параметры):
        з = self.c.NewObject("Запрос")
        з.Текст = текст
        for к, в in параметры.items():
            з.УстановитьПараметр(к, в)
        return з.Выполнить().Выгрузить()


def запустить(имя, сценарий):
    """Запуск одного теста отдельным процессом: своё подключение, код выхода 0/1."""
    т = Тест(имя)
    т.выполнить(сценарий)
    sys.exit(т.итог())
