"""Логика доп. расходов (docs/логики/доп_расходы.md, сценарии Д1–Д13): один расход вводится один раз (урок ИЛИ документ
по уроку), РКО «Прочий расход» попадает в отчёт «Расходы», отчёт — обороты без «остатка», организация документа по
уроку — из урока, статья обязательна, сумма > 0.

Сценарии (организация Б — своя тестовая; «старый код» — src_ext до правок логик 28.09.2026):
  Д1  урок организации Б с расходом «Материалы 800» проведён → УЗ_Расходы −800 (Б, Материалы).
  Д2  «Доп. расходы» на основании этого урока → отказ: расходы урока уже введены. Старый код: проводился, отчёт 1 600.
  Д8  документ на основании урока — организация урока (Б), а не из настроек. Старый код: из настроек.
  Д2б урок без расходов, «Доп. расходы» по нему 500 проведён; в урок добавили расход 300 → проведение урока — отказ.
      Старый код: урок проводился, расход задвоен.
  Д3  РКО «Прочий расход» 800 со статьёй → УЗ_Расходы −800 (в отчёт «Расходы»). Старый код: только касса, в отчёте 0.
  Д4  сентябрь 10 000, октябрь 3 000 (РКО 1 000 + доп. расходы 2 000) → отчёт «Расходы» за октябрь: итог 3 000, колонок
      прихода и «остатка» нет. Старый код: «Итого» −13 000 и «Сумма прихода» 0.
  Д9  отмена проведения урока Д1 → −800 исчезает.
  Д10 «Доп. расходы» с пустой статьёй → отказ; без строк → отказ. Старый код: проводились.
  Д11 урок с расходом без статьи → отказ (подписка УЗ_РасходыУрокаОдинИсточник).
  Д13 урок без расходов → движений УЗ_Расходы нет.

    python tools\\тесты\\логика_доп_расходы.py --база=C:\\1c_bases\\UZ_UNF_C
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import дата, запустить, текст_ошибки  # noqa: E402
from _деньги import Данные  # noqa: E402
from фабрика import Фабрика  # noqa: E402

МЕТКА = "_Тест логика доп расходов"


def сформировать(c, схема, настройки):
    макет = c.NewObject("КомпоновщикМакетаКомпоновкиДанных").Выполнить(схема, настройки)
    процессор = c.NewObject("ПроцессорКомпоновкиДанных")
    процессор.Инициализировать(макет)
    документ = c.NewObject("ТабличныйДокумент")
    вывод = c.NewObject("ПроцессорВыводаРезультатаКомпоновкиДанныхВТабличныйДокумент")
    вывод.УстановитьДокумент(документ)
    вывод.Вывести(процессор)
    return документ


def сценарий(т):
    c = т.c
    д = Данные(т, МЕТКА)
    ф = Фабрика(т, МЕТКА)
    виды = c.Перечисления.УЗ_ВидыОпераций
    орг = ф.организация("Б")
    материалы = д.элемент("УЗ_СтатьиДвиженияДенег", "материалы")
    педагог = д.элемент("УЗ_ФизЛица", "педагог", ЭтоПедагог=True)
    ученик = д.элемент("УЗ_ФизЛица", "ученик")
    касса = д.элемент("УЗ_Кассы", "касса")

    def расходы(регистратор):
        return д.итог("УЗ_Расходы", регистратор)

    def урок(час, строки_расходов=()):
        у = ф.урок(педагог, дата(2026, 9, 3, час), 1, [dict(Ученик=ученик, Явка=True)], Организация=орг)
        for статья, сумма in строки_расходов:
            с = у.Расходы.Добавить()
            с.СтатьяЗатрат, с.Сумма = статья, сумма
        return у, ф.записать(у)[0]

    def доп_расходы(строки, основание=None, когда=дата(2026, 9, 4, 10)):
        документ = д.документ("УЗ_ДополнительныеРасходы")
        if основание is not None:
            документ.Заполнить(основание)
        else:
            документ.Организация = орг
        документ.Дата = когда
        for статья, сумма in строки:
            с = документ.Расходы.Добавить()
            с.СтатьяЗатрат, с.Сумма = статья, сумма
        return документ, д.записать(документ)

    # ── Д1, Д13 ──
    у1, ош = урок(10, [(материалы, 800)])
    т.проверить(ош is None and расходы(у1.Ссылка) == (-800.0, 1)
                and c.String(т.выбрать("ВЫБРАТЬ Р.Организация КАК Орг ИЗ РегистрНакопления.УЗ_Расходы КАК Р "
                                       "ГДЕ Р.Регистратор = &Р", Р=у1.Ссылка).Получить(0).Орг) == c.String(орг),
                "Д1: урок организации Б с расходом 800 — УЗ_Расходы −800 по Б", (ош, расходы(у1.Ссылка)))
    у13, ош = урок(12)
    т.проверить(ош is None and расходы(у13.Ссылка) == (0.0, 0), "Д13: урок без расходов — движений УЗ_Расходы нет", ош)

    # ── Д2, Д8: документ по уроку с расходами ──
    д2, ош = доп_расходы([(материалы, 800)], у1.Ссылка)
    т.проверить(c.String(д2.Организация) == c.String(орг), "Д8: «Доп. расходы» на основании урока — организация урока",
                c.String(д2.Организация))
    т.проверить(ош is not None and "уже введены" in ош and расходы(д2.Ссылка) == (0.0, 0),
                "Д2: «Доп. расходы» по уроку, где расходы уже введены, — отказ (было: отчёт 1 600)", ош)

    # ── Д2б: документ по уроку, потом расход в уроке ──
    у2, _ = урок(14)
    д2б, ош = доп_расходы([(материалы, 500)], у2.Ссылка)
    т.проверить(ош is None and расходы(д2б.Ссылка) == (-500.0, 1), "Д2б: «Доп. расходы» 500 по уроку без расходов — проведён", ош)
    о = у2.Ссылка.ПолучитьОбъект()
    с = о.Расходы.Добавить()
    с.СтатьяЗатрат, с.Сумма = материалы, 300
    ош, _ = ф.записать(о)
    т.проверить(ош is not None and расходы(у2.Ссылка) == (0.0, 0),
                "Д2б: расход 300 в урок, по которому уже проведены «Доп. расходы», — отказ проведения урока", ош)

    # ── Д11: урок с расходом без статьи ──
    _, ош = урок(16, [(c.Справочники.УЗ_СтатьиДвиженияДенег.ПустаяСсылка(), 100)])
    т.проверить(ош is not None, "Д11: расход урока без статьи — отказ", ош)

    # ── Д9: отмена проведения урока ──
    ош = None
    try:
        о = у1.Ссылка.ПолучитьОбъект()
        о.Записать(c.РежимЗаписиДокумента.ОтменаПроведения)
    except Exception as е:
        ош = текст_ошибки(е)
    т.проверить(ош is None and расходы(у1.Ссылка) == (0.0, 0), "Д9: отмена проведения урока — расход 800 исчез", ош)

    # ── Д10 ──
    _, ош = доп_расходы([(c.Справочники.УЗ_СтатьиДвиженияДенег.ПустаяСсылка(), 500)])
    т.проверить(ош is not None and "статью" in ош, "Д10: «Доп. расходы» с пустой статьёй — отказ (было: проводился)", ош)
    _, ош = доп_расходы([])
    т.проверить(ош is not None, "Д10: «Доп. расходы» без строк — отказ", ош)

    # ── Д3, Д4: РКО «Прочий расход» и отчёт «Расходы» (свой период 2031 — чужих данных там нет) ──
    пко = д.документ("УЗ_ПриходДенег", Дата=дата(2031, 9, 1, 9), Касса=касса, Организация=орг, ФизЛицо=ученик,
                     ВидОперации=виды.ВнутренняяКасса, СуммаДокумента=5000)
    д.записать(пко)
    рко = д.документ("УЗ_РасходДенег", Дата=дата(2031, 10, 5, 10), Касса=касса, Организация=орг, СуммаДокумента=1000,
                     ВидОперации=виды.ПрочийРасход, СтатьяЗатрат=материалы)
    ош = д.записать(рко)
    т.проверить(ош is None and расходы(рко.Ссылка) == (-1000.0, 1),
                "Д3: РКО «Прочий расход» 1 000 со статьёй — расход по статье в УЗ_Расходы (было: только касса)", ош)
    доп_расходы([(материалы, 10000)], когда=дата(2031, 9, 10, 10))
    доп_расходы([(материалы, 2000)], когда=дата(2031, 10, 6, 10))
    схема = c.Отчеты.УЗ_Расходы.ПолучитьМакет("ОсновнаяСхемаКомпоновкиДанных")
    настройки = схема.ВариантыНастроек.Получить(0).Настройки
    период = c.NewObject("СтандартныйПериод")
    период.ДатаНачала = дата(2031, 10, 1)
    период.ДатаОкончания = дата(2031, 10, 31, 23, 59)
    параметр = настройки.ПараметрыДанных.НайтиЗначениеПараметра(c.NewObject("ПараметрКомпоновкиДанных", "Период"))
    параметр.Значение = период
    параметр.Использование = True
    try:
        тд = сформировать(c, схема, настройки)
        итог = т.строка_отчета(тд, "Итого")
        прихода = т.найти_текст(тд, "Сумма прихода")
    except Exception as е:
        итог, прихода = "ошибка: " + текст_ошибки(е, 150), None
    т.проверить("3 000" in итог and "13 000" not in итог and "10 000" not in итог and прихода is False,
                "Д4: отчёт «Расходы» за октябрь — итог 3 000 (РКО 1 000 + доп. расходы 2 000), без прихода и «остатка» "
                "(было: «Итого» −13 000)", (итог, прихода))


if __name__ == "__main__":
    запустить("логика_доп_расходы", сценарий)
