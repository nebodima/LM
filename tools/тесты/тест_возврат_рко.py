"""Возврат денег ученику: РКО на основании карточки ученика (учёт №13, Codex C01).

Было (воспроизведено на базе 28.09.2026): ОбработкаЗаполнения ставила ученика в ДокументОснования,
проведение «Касса ученики» читало ДокументОснования.Ученики — у справочника такой табличной части нет:
«Поле объекта не обнаружено (Ученики)», возврат не проводился. Стало: табличная часть читается
только у урока-основания.

    python tools\\тесты\\тест_возврат_рко.py --база=C:\\1c_bases\\UZ_UNF_A
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import дата, запустить  # noqa: E402
from _деньги import Данные  # noqa: E402

МЕТКА = "_Тест возврат РКО"


def сценарий(т):
    c = т.c
    д = Данные(т, МЕТКА)
    ученик = д.элемент("УЗ_ФизЛица", "ученик")
    касса = д.элемент("УЗ_Кассы", "касса")
    предмет = д.элемент("УЗ_ПредметыОбучения", "предмет")

    рко = д.документ("УЗ_РасходДенег")
    рко.Заполнить(ученик)
    рко.Дата = дата(2026, 9, 4, 10)
    рко.Комментарий = МЕТКА
    рко.Касса = касса
    рко.ПредметОбучения = предмет
    рко.СуммаДокумента = 700
    т.проверить(c.String(рко.ВидОперации) == c.String(c.Перечисления.УЗ_ВидыОпераций.КассаУченики),
                "на основании ученика — вид «Касса ученики»", c.String(рко.ВидОперации))
    ош = д.записать(рко)
    т.проверить(ош is None, "возврат ученику из карточки проводится", ош)
    if ош is None:
        касса_итог, _ = д.итог("УЗ_Касса", рко.Ссылка)
        ученику, строк = д.итог("УЗ_СписанияСуммЗаУроки", рко.Ссылка)
        часы, _ = д.итог("УЗ_СписанияСуммЗаУроки", рко.Ссылка, "Часы")
        т.проверить(касса_итог == -700, "касса: расход 700", касса_итог)
        т.проверить(строк == 1 and ученику == -700 and часы == 0,
                    "баланс ученика: расход 700, часы не списаны", "%s / %s / %s" % (строк, ученику, часы))


if __name__ == "__main__":
    запустить("возврат_рко", сценарий)
