"""Возврат денег ученику: РКО на основании карточки ученика (учёт №13, Codex C01).

Было (воспроизведено на базе 28.09.2026): ОбработкаЗаполнения ставила ученика в ДокументОснования,
проведение «Касса ученики» читало ДокументОснования.Ученики — у справочника такой табличной части нет:
«Поле объекта не обнаружено (Ученики)», возврат не проводился. Стало: табличная часть читается
только у урока-основания.

Решение владельца В5 (28.09.2026): возврат по уроку (РКО на основании урока) возвращает только деньги —
часы ученика второй раз не уменьшает (было: в расход шли ещё и часы урока, и часы списывались дважды).

    python tools\\тесты\\тест_возврат_рко.py --база=C:\\1c_bases\\UZ_UNF_A
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import дата, запустить  # noqa: E402
from _деньги import Данные  # noqa: E402

МЕТКА = "_Тест возврат РКО"


def сценарий(т):
    c = т.c
    д = Данные(т, МЕТКА)
    ученик = д.элемент("УЗ_ФизЛица", "ученик")
    касса = д.элемент("УЗ_Кассы", "касса")
    # В14: касса не уходит в минус — деньги в кассе заранее, движением на носителе
    д.движения("УЗ_Касса", д.регистратор(), [("+", дата(2026, 9, 1, 9), {"Касса": касса, "Сумма": 10000})])
    предмет = д.элемент("УЗ_ПредметыОбучения", "предмет")
    # В5: возврат — только из аванса ученика по предмету (в организации ордера, на его дату): аванс 3 000 заранее
    д.движения("УЗ_СписанияСуммЗаУроки", д.регистратор(), [("+", дата(2026, 9, 1, 9),
                                                      {"Клиент": ученик, "ПредметОбучения": предмет, "Сумма": 3000})])

    рко = д.документ("УЗ_РасходДенег")
    рко.Заполнить(ученик)
    рко.Дата = дата(2026, 9, 4, 10)
    рко.Комментарий = МЕТКА
    рко.Касса = касса
    рко.ПредметОбучения = предмет
    рко.СуммаДокумента = 700
    т.проверить(c.String(рко.ВидОперации) == c.String(c.Перечисления.УЗ_ВидыОпераций.КассаУченики),
                "на основании ученика — вид «Касса ученики»", c.String(рко.ВидОперации))
    ош = д.записать(рко)
    т.проверить(ош is None, "возврат ученику из карточки проводится", ош)
    if ош is None:
        касса_итог, _ = д.итог("УЗ_Касса", рко.Ссылка)
        ученику, строк = д.итог("УЗ_СписанияСуммЗаУроки", рко.Ссылка)
        часы, _ = д.итог("УЗ_СписанияСуммЗаУроки", рко.Ссылка, "Часы")
        т.проверить(касса_итог == -700, "касса: расход 700", касса_итог)
        т.проверить(строк == 1 and ученику == -700 and часы == 0,
                    "баланс ученика: расход 700, часы не списаны", "%s / %s / %s" % (строк, ученику, часы))

    # В5: возврат по уроку — только деньги, часы урока второй раз не списываются
    педагог = д.элемент("УЗ_ФизЛица", "педагог", ЭтоПедагог=True)
    тариф = д.элемент("УЗ_Тарифы", "8 уроков", Сумма=8000, КоличествоУроков=8, КоличествоЧасов=8)
    урок = д.документ("УЗ_Урок", Дата=дата(2026, 9, 4, 12), Педагог=педагог, КоличествоЧасов=1,
                      ПредметОбучения=предмет)
    строка = урок.Ученики.Добавить()
    строка.Ученик = ученик
    строка.Тариф = тариф
    строка.Явка = True
    строка.СписатьОплату = True
    ош = д.записать(урок)
    т.проверить(ош is None, "урок 1 ч по тарифу проведён", ош)
    возврат = д.документ("УЗ_РасходДенег", Дата=дата(2026, 9, 4, 13), Касса=касса, ПредметОбучения=предмет,
                         ВидОперации=c.Перечисления.УЗ_ВидыОпераций.КассаУченики, ФизЛицо=ученик,
                         ДокументОснования=урок.Ссылка, СуммаДокумента=1000)
    ош = д.записать(возврат)
    т.проверить(ош is None, "возврат по уроку проведён", ош)
    if ош is None:
        деньги, _ = д.итог("УЗ_СписанияСуммЗаУроки", возврат.Ссылка)
        часы, _ = д.итог("УЗ_СписанияСуммЗаУроки", возврат.Ссылка, "Часы")
        т.проверить(деньги == -1000 and часы == 0, "возврат по уроку: деньги 1 000, часы урока не списаны второй раз",
                    "деньги %s, часы %s" % (деньги, часы))


if __name__ == "__main__":
    запустить("возврат_рко", сценарий)
