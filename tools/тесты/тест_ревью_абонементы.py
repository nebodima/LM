"""Ревью Codex логик 28.09.2026 — абонементы и панель: R07, R12, R13, R14, R20.

  R07 пакет 8 занятий, «Списание остатков» по абонементу на 2 занятия — остаток 6 из 8 (корректировки абонемента
      учитываются, как в типовых: остаток — по всем движениям). Отрицательная корректировка −1 возвращает занятие —
      7 из 8. Старый код: 8 из 8 (единая функция читала только уроки).
  R12 панель ученика без абонемента: остаток денег 2 000, личный тариф 500 за урок, тариф группы 1 000 — «≈4»
      (цена — тариф строки по В20: ученик → группа). Старый код: «≈2» (тариф группы).
  R13 цена 8 000, ПКО по абонементу 8 000, РКО возврата по абонементу 3 000: «Оплачено» 5 000, не оплачен
      полностью, осталось оплатить 3 000 — то же, что предложит новый ПКО (одна функция
      Справочники.УЗ_Абонемент.ОплатаАбонемента для карточки и ПКО). Старый код: функции нет, карточка — «Оплачено
      8 000, оплачен полностью».
  R14 два оплаченных абонемента одного ученика и предмета по 1 000; РКО возврата по первому на 1 500 — отказ
      (остаток абонемента 1 000); по первому на 1 000 — можно. Старый код: 1 500 проходило (аванс ученика по
      предмету 2 000), у первого абонемента −500.
  R20 подбор действующих абонементов 30 учеников (ДействующиеАбонементы) — пакетно: не медленнее трети подбора по
      одному ученику (было: подбор по одному — 90 запросов). Замер — лучший из трёх.

    python tools\\тесты\\тест_ревью_абонементы.py --база=C:\\1c_bases\\UZ_UNF_D
"""
# затрагивает: УЗ_Абонемент, УЗ_СписаниеОстатков, УЗ_ПанельУченика, УЗ_РасходДенег, УЗ_ПриходДенег, УЗ_Сервер
import os
import re
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from _деньги import Данные  # noqa: E402
from фабрика import Фабрика  # noqa: E402
from логика_урок import безопасно, деньги  # noqa: E402

МЕТКА = "_Тест ревью абонементов"
ИСХОДНИКИ = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "src_ext"))


def сценарий(т):
    c = т.c
    ф = Фабрика(т, МЕТКА)
    д_ = Данные(т, МЕТКА)
    виды = c.Перечисления.УЗ_ВидыОпераций
    орг = c.РегистрыСведений.УЗ_Настройки.Настройки().Организация
    касса = д_.элемент("УЗ_Кассы", "касса")
    д_.движения("УЗ_Касса", д_.регистратор(), [("+", ф.день(-30, 9), {"Касса": касса, "Сумма": 100000})])
    предмет = ф.элемент("УЗ_ПредметыОбучения", "предмет")
    менеджер = c.Справочники.УЗ_Абонемент

    # ── R07: корректировка занятий абонемента ──
    ученик = ф.ученик("ученик R07")
    а8 = ф.абонемент(ученик, "8 занятий", ПредметОбучения=предмет, КоличествоЗанятий=8, ЦенаАбонемента=8000, Организация=орг)

    def списание(уроков):
        с = д_.документ("УЗ_СписаниеОстатков", Дата=ф.день(-1, 12), Организация=орг)
        стр = с.ТЗСписания.Добавить()
        стр.Ученик, стр.Абонемент, стр.ПредметОбучения, стр.КоличествоУроков = ученик, а8, предмет, уроков
        return д_.записать(с)
    ош = списание(2)
    остаток, ош2 = безопасно(lambda: менеджер.ОстатокАбонемента(а8))
    т.проверить(ош is None and ош2 is None and остаток.Осталось == 6 and "6 из 8" in остаток.Текст,
                "R07: 8 занятий, списание остатков 2 занятия — остаток 6 из 8 (было 8 из 8)",
                ош or ош2 or (остаток.Осталось, остаток.Текст))
    ош = списание(-1)
    остаток, _ = безопасно(lambda: менеджер.ОстатокАбонемента(а8))
    т.проверить(ош is None and остаток is not None and остаток.Осталось == 7,
                "R07: возврат занятия корректировкой −1 — остаток 7 из 8", ош or (остаток and остаток.Осталось))

    # ── R12: панель — тариф строки ученика (В20) ──
    личный = ф.элемент("УЗ_Тарифы", "500 за урок", Сумма=500, КоличествоУроков=1)
    групповой = ф.элемент("УЗ_Тарифы", "1 000 за урок", Сумма=1000, КоличествоУроков=1)
    ученик12 = ф.элемент("УЗ_ФизЛица", "ученик R12", Тариф=личный)
    группа = ф.элемент("УЗ_ГруппыОбучения", "группа R12", ПредметОбучения=предмет, Тариф=групповой)
    текст, ош = безопасно(lambda: c.Обработки.УЗ_ПанельУченика.ОсталосьУроковТекстом(ученик12, группа, 2000))
    т.проверить(ош is None and текст == "≈4", "R12: панель, остаток 2 000, личный тариф 500, группы 1 000 — «≈4» (было «≈2»)",
                ош or текст)

    # ── R13: «Оплачено» абонемента — одна функция карточки и ПКО ──
    родитель13 = ф.ученик("родитель R13")
    ученик13 = ф.элемент("УЗ_ФизЛица", "ученик R13", Родитель1=родитель13)
    а13 = ф.абонемент(ученик13, "8 000", ПредметОбучения=предмет, КоличествоЗанятий=8, ЦенаАбонемента=8000, Организация=орг)

    def по_абонементу(вид, абонемент, сумма, час):
        д = д_.документ(вид)
        д.Заполнить(абонемент)
        д.Дата = ф.день(-2, час)
        д.Касса = касса
        д.СуммаДокумента = сумма
        д.Комментарий = МЕТКА
        return д_.записать(д)
    ош = по_абонементу("УЗ_ПриходДенег", а13, 8000, 9)
    ош2 = по_абонементу("УЗ_РасходДенег", а13, 3000, 10)
    оплата, ош3 = безопасно(lambda: менеджер.ОплатаАбонемента(а13))
    т.проверить(ош is None and ош2 is None and ош3 is None and деньги(оплата.Оплачено) == 5000
                and not оплата.ОплаченПолностью and деньги(оплата.ОсталосьОплатить) == 3000,
                "R13: цена 8 000, ПКО 8 000, возврат 3 000 — оплачено 5 000, осталось оплатить 3 000 (было: карточка — "
                "«оплачен полностью»)", ош or ош2 or ош3 or (оплата.Оплачено, оплата.ОплаченПолностью))
    пко = д_.документ("УЗ_ПриходДенег")
    пко.Заполнить(а13)
    т.проверить(оплата is not None and деньги(пко.СуммаДокумента) == деньги(оплата.ОсталосьОплатить),
                "R13: новый ПКО по абонементу предлагает ту же сумму, что карточка «осталось оплатить» (3 000)",
                пко.СуммаДокумента)
    т.проверить(пко.Родитель.Наименование == родитель13.Наименование,
                "ПКО на основании абонемента подставляет «Отв. лицо ученика» из карточки ученика (платит родитель)",
                пко.Родитель)
    модуль = open(os.path.join(ИСХОДНИКИ, "Catalogs", "УЗ_Абонемент", "Forms", "ФормаЭлемента", "Ext", "Form", "Module.bsl"),
                  encoding="utf-8-sig").read()
    т.проверить(re.search(r"Справочники\.УЗ_Абонемент\.ОплатаАбонемента\(", модуль) is not None
                and 'Итог("СуммаПриход")' not in модуль,
                "R13: карточка абонемента считает «Оплачено» той же функцией (прежней формулы «весь приход» нет)")

    # ── R14: возврат по абонементу — не больше остатка этого абонемента ──
    ученик14 = ф.ученик("ученик R14")
    а1 = ф.абонемент(ученик14, "первый", ПредметОбучения=предмет, КоличествоЗанятий=4, ЦенаАбонемента=1000, Организация=орг)
    а2 = ф.абонемент(ученик14, "второй", ПредметОбучения=предмет, КоличествоЗанятий=4, ЦенаАбонемента=1000, Организация=орг)
    ош = по_абонементу("УЗ_ПриходДенег", а1, 1000, 11)
    ош2 = по_абонементу("УЗ_ПриходДенег", а2, 1000, 12)
    т.проверить(ош is None and ош2 is None, "R14: заготовка — оба абонемента оплачены по 1 000", ош or ош2)
    ош = по_абонементу("УЗ_РасходДенег", а1, 1500, 13)
    т.проверить(ош is not None and деньги(c.УЗ_Сервер.ОстатокДенегПоАбонементу(а1)) == 1000,
                "R14: возврат 1 500 по первому абонементу (его остаток 1 000) — отказ (было: проходил, у абонемента −500)", ош)
    ош = по_абонементу("УЗ_РасходДенег", а1, 1000, 14)
    т.проверить(ош is None and деньги(c.УЗ_Сервер.ОстатокДенегПоАбонементу(а1)) == 0, "R14: возврат 1 000 по первому — можно", ош)

    # ── R20: пакетный подбор абонементов ──
    ученики = т.массив()
    for н in range(30):
        у = ф.ученик("ученик R20 %02d" % н)
        ф.абонемент(у, "R20 %02d" % н, ПредметОбучения=предмет, КоличествоЗанятий=8, ЦенаАбонемента=8000, Организация=орг)
        ученики.Добавить(у)
    день = ф.день(0, 10)

    def по_одному():
        for н in range(ученики.Количество()):
            менеджер.ПодобратьАбонемент(ученики.Получить(н), предмет, день, орг)

    def замер(действие):
        лучшее = None
        for _ in range(3):
            н = time.perf_counter()
            действие()
            с = time.perf_counter() - н
            лучшее = с if лучшее is None else min(лучшее, с)
        return лучшее
    итог = менеджер.ДействующиеАбонементы(ученики, предмет, день, орг)
    одному = замер(по_одному)
    пакетно = замер(lambda: менеджер.ДействующиеАбонементы(ученики, предмет, день, орг))
    т.проверить(итог.Количество() == 30 and пакетно * 3 <= одному,
                "R20: подбор абонементов 30 учеников пакетно %.0f мс — не больше трети подбора по одному (%.0f мс)"
                % (пакетно * 1000, одному * 1000), итог.Количество())


if __name__ == "__main__":
    запустить("ревью_абонементы", сценарий)
