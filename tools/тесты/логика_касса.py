"""Логика кассы (docs/логики/касса.md, сценарии К1–К16): касса принадлежит организации (В12), не уходит в минус ни
расходом, ни перемещением, ни отменой прихода, ни списанием остатков (В14) — одна функция
Справочники.УЗ_Кассы.ДоступныйОстатокДляРасхода везде (РКО, перемещение, списание, отмена прихода, расчёт зарплаты);
раздел кассы переезжает при перемещении; кассовый журнал = документы, которые двигают кассу.

Сценарии (организации А и Б — свои тестовые; «старый код» — src_ext до правок логик 28.09.2026):
  К1  ПКО А 1 000 от 10.09, РКО А 500 от 09.09 → отказ.
  К3  ПКО А 5 000, РКО А 4 000; отмена проведения ПКО → отказ; ПКО уменьшить до 3 000 → отказ; до 4 000 — можно.
      Старый код: отмена проходила, касса −4 000.
  К4  пустая касса: списание остатков, строка кассы 1 000 → отказ; строка −700 (излишек) → касса +700, раздел
      «Внутренняя касса»; строка с разделом «Выплата зарплаты» → отказ. Старый код: касса −1 000.
  К5  одна касса: ПКО А 5 000; РКО «Прочий расход» Б 3 000 → отказ (у Б в кассе 0); РКО А 3 000 — можно.
      Старый код: проводился, у Б в кассе −3 000.
  К6/К7 касса: ПКО А 5 000, ПКО Б 3 000, ПКО А +2 000 датой через неделю; расчёт зарплаты организации А:
      «Остаток в кассе»/«Переместить деньги» — 5 000 (деньги А сейчас), перемещение проведено, у Б 3 000 остались.
      Старый код: 10 000 — перемещение само себе отказывало («уйдёт в минус»).
  К9  деньги учеников 10 000 в кассе, перемещение в другую кассу 10 000 → раздел «Касса ученики» переезжает.
      Старый код: в обеих кассах раздел «Внутренняя касса» (ученики +10 000 / внутренняя −10 000 в зале).
  К11 кассовый журнал: списание остатков с кассой — в журнале; перемещение между предметами помечено
      «Между предметами» (форма журнала его не показывает). Старый код: списания нет, отметки нет.
  К12 касса организации Б (реквизит «Организация»): ПКО организации А в неё → отказ.
  К13 перемещение между кассами 1 000, из кассы-получателя выдано 1 000; отмена проведения перемещения → отказ.
      Старый код: проходила, касса-получатель −1 000.
  К14 РКО без кассы → отказ; прочий расход без статьи → отказ. Старый код: проводились.

    python tools\\тесты\\логика_касса.py --база=C:\\1c_bases\\UZ_UNF_C
"""
import datetime
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import дата, запустить, текст_ошибки  # noqa: E402
from _деньги import Данные, сообщения  # noqa: E402
from фабрика import Фабрика  # noqa: E402

МЕТКА = "_Тест логика кассы"


def сценарий(т):
    c = т.c
    д = Данные(т, МЕТКА)
    ф = Фабрика(т, МЕТКА)
    виды = c.Перечисления.УЗ_ВидыОпераций
    орг_а = ф.организация("А")
    орг_б = ф.организация("Б")
    ученик = д.элемент("УЗ_ФизЛица", "ученик")
    статья = д.элемент("УЗ_СтатьиДвиженияДенег", "аренда")

    def касса(имя, **поля):
        return д.элемент("УЗ_Кассы", имя, **поля)

    def остаток(к, орг=None):
        # None в COM приходит NULL — «по всем организациям» только без аргумента
        return float(c.Справочники.УЗ_Кассы.ОстатокДенег(к) if орг is None else c.Справочники.УЗ_Кассы.ОстатокДенег(к, орг))

    def пко(к, орг, сумма, когда):
        п = д.документ("УЗ_ПриходДенег", Дата=когда, Касса=к, Организация=орг, ФизЛицо=ученик, СуммаДокумента=сумма,
                       ВидОперации=виды.КассаУченики)
        return п, д.записать(п)

    def рко(к, орг, сумма, когда, **поля):
        поля.setdefault("СтатьяЗатрат", статья)
        р = д.документ("УЗ_РасходДенег", Дата=когда, Касса=к, Организация=орг, СуммаДокумента=сумма,
                       ВидОперации=поля.pop("ВидОперации", виды.ПрочийРасход), **поля)
        return р, д.записать(р)

    def отменить(документ):
        о = документ.Ссылка.ПолучитьОбъект()
        сообщения(c)
        try:
            о.Записать(c.РежимЗаписиДокумента.ОтменаПроведения)
            return None
        except Exception as е:
            return "%s [%s]" % (текст_ошибки(е), сообщения(c))

    # ── К1 ──
    к1 = касса("К1")
    пко(к1, орг_а, 1000, дата(2026, 9, 10, 10))
    _, ош = рко(к1, орг_а, 500, дата(2026, 9, 9, 10))
    т.проверить(ош is not None and "в минус" in ош, "К1: РКО 500 от 09.09 при приходе 10.09 — отказ", ош)

    # ── К3: отмена и уменьшение прихода ──
    к3 = касса("К3")
    п3, _ = пко(к3, орг_а, 5000, дата(2026, 9, 10, 10))
    _, ош = рко(к3, орг_а, 4000, дата(2026, 9, 11, 10))
    ош_отмены = отменить(п3)
    т.проверить(ош is None and ош_отмены is not None and "в минус" in ош_отмены and остаток(к3, орг_а) == 1000,
                "К3: ПКО 5 000, РКО 4 000 — отмена проведения ПКО: отказ, касса 1 000 (было: −4 000)", (ош, ош_отмены))
    о = п3.Ссылка.ПолучитьОбъект()
    о.СуммаДокумента = 3000
    ош = д.записать(о)
    т.проверить(ош is not None and "в минус" in ош and остаток(к3, орг_а) == 1000,
                "К3: ПКО уменьшить до 3 000 — отказ (выдано уже 4 000)", ош)
    о = п3.Ссылка.ПолучитьОбъект()
    о.СуммаДокумента = 4000
    ош = д.записать(о)
    т.проверить(ош is None and остаток(к3, орг_а) == 0, "К3: ПКО уменьшить до 4 000 — можно, касса 0", ош)

    # ── К4: списание остатков по кассе ──
    к4 = касса("К4")

    def списание(сумма, раздел=None):
        с = д.документ("УЗ_СписаниеОстатков", Дата=дата(2026, 9, 12, 10), Организация=орг_а)
        стр = с.ТЗСписаниеКасса.Добавить()
        стр.Касса, стр.Сумма = к4, сумма
        if раздел is not None:
            стр.ВидОперации = раздел
        return с, д.записать(с)
    _, ош = списание(1000)
    т.проверить(ош is not None and "в минус" in ош and остаток(к4) == 0, "К4: пустая касса, списание 1 000 — отказ (было: −1 000)", ош)
    с4, ош = списание(-700)
    разделы = т.выбрать("ВЫБРАТЬ РАЗЛИЧНЫЕ Р.ВидОперации КАК Раздел ИЗ РегистрНакопления.УЗ_Касса КАК Р ГДЕ Р.Регистратор = &Р",
                        Р=с4.Ссылка)
    т.проверить(ош is None and остаток(к4, орг_а) == 700 and разделы.Количество() == 1
                and c.String(разделы.Получить(0).Раздел) == c.String(виды.ВнутренняяКасса),
                "К4: излишек −700 — касса +700, раздел «Внутренняя касса»", ош)
    _, ош = списание(100, виды.ВыплатаЗарплаты)
    т.проверить(ош is not None and "раздел кассы" in ош, "К4: раздел «Выплата зарплаты» в строке кассы — отказ", ош)

    # ── К5: касса организации ──
    к5 = касса("К5")
    пко(к5, орг_а, 5000, дата(2026, 9, 10, 10))
    _, ош = рко(к5, орг_б, 3000, дата(2026, 9, 11, 10))
    т.проверить(ош is not None and "в минус" in ош and остаток(к5, орг_б) == 0,
                "К5: ПКО А 5 000, РКО «Прочий расход» Б 3 000 — отказ, у Б в кассе 0 (было: Б −3 000)", ош)
    _, ош = рко(к5, орг_а, 3000, дата(2026, 9, 11, 11))
    т.проверить(ош is None and остаток(к5, орг_а) == 2000, "К5: РКО А 3 000 — можно, у А 2 000", ош)

    # ── К6/К7: расчёт зарплаты «Переместить деньги» ──
    к6 = касса("К6")
    сегодня = datetime.date.today()
    через_неделю = сегодня + datetime.timedelta(days=7)
    пко(к6, орг_а, 5000, дата(сегодня.year, сегодня.month, сегодня.day, 0, 5))
    пко(к6, орг_б, 3000, дата(сегодня.year, сегодня.month, сегодня.day, 0, 6))
    пко(к6, орг_а, 2000, дата(через_неделю.year, через_неделю.month, через_неделю.day, 10))
    try:
        доступно = float(c.Справочники.УЗ_Кассы.ДоступныйОстатокДляРасхода(к6, None, орг_а))
    except Exception as е:
        доступно = "ошибка: " + текст_ошибки(е, 100)
    педагог = д.элемент("УЗ_ФизЛица", "педагог", ЭтоПедагог=True)
    расчет = д.документ("УЗ_РасчетЗарплаты", Дата=дата(2026, 9, 2, 12), Педагог=педагог, Касса=к6, Организация=орг_а,
                        ДатаНачала=дата(2026, 8, 1), ДатаОкончания=дата(2026, 8, 31))
    сообщения(c)
    перемещение = расчет.ПереместитьОстатокВОсновнуюКассу()
    д.следить(перемещение)
    сумма = float(перемещение.ПолучитьОбъект().Сумма) if not перемещение.Пустая() else сообщения(c)
    т.проверить(доступно == 5000 and сумма == 5000 and остаток(к6, орг_б) == 3000,
                "К6/К7: деньги А в кассе сейчас 5 000 (Б 3 000, будущий приход А 2 000) — перемещено 5 000, у Б 3 000 "
                "остались (было: 10 000 и отказ)", (доступно, сумма, остаток(к6, орг_б)))

    # ── К9: раздел кассы переезжает ──
    к9, основная9 = касса("К9 зал"), касса("К9 основная")
    пко(к9, орг_а, 10000, дата(2026, 9, 10, 10))
    п9 = д.документ("УЗ_ПеремещениеДенег", Дата=дата(2026, 9, 10, 12), Сумма=10000, Организация=орг_а,
                    КассаОтправитель=к9, КассаПолучатель=основная9, ВидОперации=виды.ВнутренняяКасса)
    ош = д.записать(п9)
    разделы = т.выбрать("ВЫБРАТЬ Р.Касса КАК Касса, Р.ВидОперации КАК Раздел, СУММА(ВЫБОР КОГДА Р.ВидДвижения = "
                        "ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА Р.Сумма ИНАЧЕ -Р.Сумма КОНЕЦ) КАК Сумма "
                        "ИЗ РегистрНакопления.УЗ_Касса КАК Р ГДЕ Р.Регистратор = &Р СГРУППИРОВАТЬ ПО Р.Касса, Р.ВидОперации",
                        Р=п9.Ссылка)
    строки = sorted(("зал" if c.String(с.Касса) == c.String(к9) else "основная", c.String(с.Раздел), float(с.Сумма)) for с in разделы)
    ученики = c.String(виды.КассаУченики)
    т.проверить(ош is None and строки == sorted([("основная", ученики, 10000.0), ("зал", ученики, -10000.0)]),
                "К9: перемещение денег учеников 10 000 — раздел «Касса ученики» в обеих кассах (было: «Внутренняя»)",
                (ош, строки))

    # ── К11: кассовый журнал ──
    з = ("ВЫБРАТЬ Ж.Ссылка КАК Док, ЕСТЬNULL(Ж.МеждуПредметами, ЛОЖЬ) КАК Помечен ИЗ ЖурналДокументов.УЗ_КассовыйЖурнал КАК Ж "
         "ГДЕ Ж.Ссылка = &Док")
    в_журнале = т.выбрать(з, Док=с4.Ссылка).Количество()
    вокал = д.элемент("УЗ_ПредметыОбучения", "вокал")
    гитара = д.элемент("УЗ_ПредметыОбучения", "гитара")
    д.движения("УЗ_СписанияСуммЗаУроки", д.регистратор(), [("+", дата(2026, 9, 1, 9), {"Клиент": ученик, "Сумма": 500,
                                                                                    "ПредметОбучения": гитара,
                                                                                    "Организация": орг_а})])
    п11 = д.документ("УЗ_ПеремещениеДенег", Дата=дата(2026, 9, 2, 12), Клиент=ученик, Сумма=300, Организация=орг_а,
                     СделатьДвиженияПоВзаиморасчетам=True, ПредметОбученияОтправитель=гитара, ПредметОбученияПолучатель=вокал)
    ош = д.записать(п11)
    try:
        между = т.выбрать(з, Док=п11.Ссылка)
        между = [bool(с.Помечен) for с in между]
    except Exception as е:
        между = "ошибка: " + текст_ошибки(е, 100)
    т.проверить(в_журнале == 1 and ош is None and между == [True],
                "К11: списание остатков с кассой — в кассовом журнале; перемещение между предметами — «Между предметами»",
                (в_журнале, ош, между))

    # ── К12: касса организации ──
    касса_б = касса("К12 касса Б", Организация=орг_б)
    _, ош = пко(касса_б, орг_а, 100, дата(2026, 9, 10, 10))
    т.проверить(ош is not None and "принадлежит организации" in ош, "К12: ПКО организации А в кассу Б — отказ", ош)

    # ── К13: отмена перемещения, деньги которого выданы ──
    к13, основная13 = касса("К13 зал"), касса("К13 основная")
    пко(к13, орг_а, 1000, дата(2026, 9, 10, 10))
    п13 = д.документ("УЗ_ПеремещениеДенег", Дата=дата(2026, 9, 10, 12), Сумма=1000, Организация=орг_а,
                     КассаОтправитель=к13, КассаПолучатель=основная13, ВидОперации=виды.ВнутренняяКасса)
    д.записать(п13)
    _, ош = рко(основная13, орг_а, 1000, дата(2026, 9, 11, 10))
    ош_отмены = отменить(п13)
    т.проверить(ош is None and ош_отмены is not None and "в минус" in ош_отмены and остаток(основная13, орг_а) == 0,
                "К13: из кассы-получателя выдано 1 000 — отмена перемещения: отказ (было: −1 000)", (ош, ош_отмены))

    # ── К14: обязательные ──
    _, ош = рко(c.Справочники.УЗ_Кассы.ПустаяСсылка(), орг_а, 10, дата(2026, 9, 11, 10))
    т.проверить(ош is not None and "кассу" in ош, "К14: РКО без кассы — отказ", ош)
    _, ош = рко(к5, орг_а, 10, дата(2026, 9, 11, 12), СтатьяЗатрат=c.Справочники.УЗ_СтатьиДвиженияДенег.ПустаяСсылка())
    т.проверить(ош is not None and "статью" in ош, "К14: прочий расход без статьи — отказ", ош)


if __name__ == "__main__":
    запустить("логика_касса", сценарий)
