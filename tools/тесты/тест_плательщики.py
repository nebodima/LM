    т.проверить(ст(старый_возврат.Ссылка.ПолучитьОбъект().Получатель) == ст(папа), "возврат 2.0: получатель записан")
    обн.ОбновитьДанныеПриНеобходимости()
    о = старый.ПолучитьОбъект()
    т.проверить(о.Плательщики.Количество() == 1, "повторный проход ничего не добавляет")


