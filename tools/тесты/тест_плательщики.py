"""Плательщики ученика и один платёж за нескольких учеников (этап 2.1, решения В33–В39).

  В33 У ученика несколько плательщиков (мама, папа, бабушка — физ. лица), один основной: он подставляется в приход
      денег (на основании ученика, из отчёта); основной — один, плательщик не повторяется, ученик — не свой
      плательщик; ни одного отмеченного — основным становится первый. Письмо о долге — плательщикам с отметкой
      «Оповестить по email» (В34).
  В35 Один платёж за нескольких учеников: расшифровка платежа (ученик, предмет, абонемент, сумма), сумма документа —
      итог строк, движения кассы и денег — по каждому ученику, плательщик — в движении кассы. «Заполнить по долгам»
      плательщика — все его ученики с долгами. Частичная оплата гасит долг частично. Строка с абонементом чужого
      ученика и строка без суммы — отказ. Один ученик — прежний простой случай: строка = шапка.
  В37 Отчёт «Оплаты по плательщикам»: кто сколько внёс за кого за год (прошлый год в отчёт этого года не входит),
      возврат уменьшает внесённое получателем.
  В38 Возврат ученику — получателю: по умолчанию плательщик последней оплаты по предмету; проверка «не больше
      аванса по предмету» сохраняется.
  В39 Шаг обновления данных 2: «Родитель (родств.)» 2.0 → основной плательщик; приход 2.0 без расшифровки —
      строка из шапки; движения кассы без плательщика — плательщик прихода (пусто — ученик), возврат — получатель.
На коде 2.0 тест красный с первой проверки (у карточки нет табличной части «Плательщики», у прихода —
«Расшифровка платежа»); мутации продукта — docs/проверки.md.

    python tools\\тесты\\тест_плательщики.py --база=C:\\1c_bases\\UZ_BP_E --пользователь=1
"""
# затрагивает: УЗ_ФизЛица, УЗ_ПриходДенег, УЗ_РасходДенег, УЗ_Касса, УЗ_Сервер, УЗ_ОбновлениеДанных, УЗ_Почта
# затрагивает: УЗ_ОплатыПоПлательщикам, УЗ_СписанияСуммЗаУроки
import datetime
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import дата, запустить  # noqa: E402
from _деньги import Данные  # noqa: E402
from фабрика import Фабрика  # noqa: E402
from логика_отчеты_сверка import скд, колонка, строка_с, число  # noqa: E402

МЕТКА = "_Тест плательщики"
ДОЛГ = ("ВЫБРАТЬ ЕСТЬNULL(СУММА(Р.СуммаОстаток), 0) ИЗ РегистрНакопления.УЗ_СписанияСуммЗаУроки.Остатки(, "
        "Клиент = &Ученик И Организация = &Организация) КАК Р")
КАССА_ДОКУМЕНТА = ("ВЫБРАТЬ Р.Клиент КАК Клиент, Р.Плательщик КАК Плательщик, Р.Сумма КАК Сумма, "
                   "Р.ПредметОбучения КАК Предмет ИЗ РегистрНакопления.УЗ_Касса КАК Р ГДЕ Р.Регистратор = &Р "
                   "УПОРЯДОЧИТЬ ПО Р.НомерСтроки")


def сценарий(т):
    c = т.c
    ф = Фабрика(т, МЕТКА)
    д_ = Данные(т, МЕТКА)
    виды = c.Перечисления.УЗ_ВидыОпераций
    ст = c.String
    орг = ф.организация("П")
    касса = ф.элемент("УЗ_Кассы", "касса")
    математика = ф.элемент("УЗ_ПредметыОбучения", "математика")
    гитара = ф.элемент("УЗ_ПредметыОбучения", "гитара")
    мама = ф.элемент("УЗ_ФизЛица", "мама", EMail="mama@example.invalid", ОповеститьПоEmail=True)
    папа = ф.элемент("УЗ_ФизЛица", "папа", EMail="papa@example.invalid", ОповеститьПоEmail=True)
    бабушка = ф.элемент("УЗ_ФизЛица", "бабушка", EMail="babushka@example.invalid")   # писем не хочет

    def ученик(имя, плательщики, записать=True):
        """плательщики — [(физлицо, кем, основной)] → (ссылка или None, текст ошибки или None)."""
        о = c.Справочники.УЗ_ФизЛица.СоздатьЭлемент()
        о.Наименование = "%s %s" % (МЕТКА, имя)
        for кто, кем, основной in плательщики:
            с = о.Плательщики.Добавить()
            с.Плательщик = кто if кто is not None else о.Ссылка
            с.КемПриходится = кем
            с.Основной = основной
        c.ПолучитьСообщенияПользователю(True)
        try:
            о.Записать()
        except Exception:
            сообщения = " | ".join(str(м.Текст) for м in c.ПолучитьСообщенияПользователю(True))
            return None, сообщения or "отказ"
        ссылка = о.Ссылка
        т.убрать(lambda: т.удалить_объект(ссылка), "ученик %s" % имя, пакет=True)
        return ссылка, None

    # ── В33: плательщики карточки ──
    сын, ош = ученик("сын", [(мама, "мама", True), (папа, "папа", False), (бабушка, "бабушка", False)])
    т.проверить(ош is None, "ученик с тремя плательщиками записан", ош)
    дочь, ош = ученик("дочь", [(папа, "папа", False), (мама, "мама", True)])
    т.проверить(ош is None, "второй ученик тех же родителей записан", ош)
    т.проверить(ст(c.Справочники.УЗ_ФизЛица.ОсновнойПлательщик(сын)) == ст(мама), "основной плательщик сына — мама",
                ст(c.Справочники.УЗ_ФизЛица.ОсновнойПлательщик(сын)))
    т.проверить(ст(c.Справочники.УЗ_ФизЛица.ОсновнойПлательщик(дочь)) == ст(мама),
                "основной — отмеченный, а не первый по порядку (дочь: папа первым, мама основная)")
    у_мамы = [ст(у) for у in c.Справочники.УЗ_ФизЛица.УченикиПлательщика(мама)]
    т.проверить(у_мамы == [ст(дочь), ст(сын)], "мама платит за двоих (по наименованию)", у_мамы)
    т.проверить([ст(у) for у in c.Справочники.УЗ_ФизЛица.УченикиПлательщика(бабушка)] == [ст(сын)],
                "бабушка платит только за сына")
    _, ош = ученик("два основных", [(мама, "", True), (папа, "", True)])
    т.проверить(ош is not None and "один" in ош, "два основных плательщика — отказ", ош)
    _, ош = ученик("дубль", [(мама, "", True), (мама, "", False)])
    т.проверить(ош is not None and "уже есть" in ош, "плательщик повторяется — отказ", ош)
    без_отметки, ош = ученик("без отметки", [(папа, "папа", False), (мама, "мама", False)])
    т.проверить(ош is None and ст(c.Справочники.УЗ_ФизЛица.ОсновнойПлательщик(без_отметки)) == ст(папа)
                and без_отметки.ПолучитьОбъект().Плательщики.Получить(0).Основной,
                "ни одного отмеченного — основным стал первый (папа)", ош)

    письмо = c.УЗ_Почта.ПодготовитьПисьмоОЗадолженности(сын, 100)
    адреса = sorted(письмо.Адреса.Получить(н) for н in range(письмо.Адреса.Количество()))
    т.проверить(адреса == ["mama@example.invalid", "papa@example.invalid"],
                "письмо о долге сына — плательщикам с «Оповестить по email» (мама, папа; бабушка — без отметки)", адреса)

    # ── В33: основной подставляется в приход ──
    пко = c.Документы.УЗ_ПриходДенег.СоздатьДокумент()
    пко.Заполнить(сын)
    т.проверить(ст(пко.Плательщик) == ст(мама), "приход на основании ученика: плательщик — основной (мама)",
                ст(пко.Плательщик))
    заполнение = c.УЗ_Сервер.ЗаполнениеДенежногоДокумента("УЗ_ПриходДенег", дочь, орг, None)
    т.проверить(ст(заполнение.Заполнение.Плательщик) == ст(мама), "приход из отчёта: плательщик — основной (мама)")

    # долги: сын — математика 3 000, дочь — гитара 2 000 (вчера, организация П)
    носитель = д_.регистратор()
    д_.движения("УЗ_СписанияСуммЗаУроки", носитель, [
        ("-", ф.день(-1, 9), {"Клиент": сын, "ПредметОбучения": математика, "Сумма": 3000, "Организация": орг}),
        ("-", ф.день(-1, 9), {"Клиент": дочь, "ПредметОбучения": гитара, "Сумма": 2000, "Организация": орг})])

    # ── В35: «Заполнить по долгам» плательщика ──
    строки = c.Документы.УЗ_ПриходДенег.СтрокиПоДолгамПлательщика(мама, орг)
    по_долгам = [(ст(с.Ученик), ст(с.ПредметОбучения), float(с.Сумма)) for с in строки]
    т.проверить(по_долгам == [(ст(дочь), ст(гитара), 2000.0), (ст(сын), ст(математика), 3000.0)],
                "по долгам мамы: дочь — гитара 2 000, сын — математика 3 000", по_долгам)
    т.проверить(c.Документы.УЗ_ПриходДенег.СтрокиПоДолгамПлательщика(бабушка, орг).Количество() == 1,
                "по долгам бабушки — только сын")

    # ── В35: один платёж за двоих, дочь — частично ──
    общий = c.Документы.УЗ_ПриходДенег.СоздатьДокумент()
    общий.Дата = ф.день(0, 9)
    общий.ВидОперации = виды.КассаУченики
    общий.Организация = орг
    общий.Касса = касса
    общий.Плательщик = мама
    общий.Комментарий = МЕТКА
    for у, п, сумма in ((сын, математика, 3000), (дочь, гитара, 1500)):
        с = общий.РасшифровкаПлатежа.Добавить()
        с.Ученик, с.ПредметОбучения, с.Сумма = у, п, сумма
    ош, сообщ = ф.записать(общий)
    т.проверить(ош is None, "общий платёж за двоих проводится", "%s %s" % (ош, сообщ))
    т.проверить(float(общий.СуммаДокумента) == 4500 and общий.ФизЛицо.Пустая(),
                "сумма документа — итог строк 4 500, ученика в шапке нет", "%s / %s"
                % (общий.СуммаДокумента, ст(общий.ФизЛицо)))
    касса_строки = [(ст(з.Клиент), ст(з.Плательщик), float(з.Сумма)) for з in т.выбрать(КАССА_ДОКУМЕНТА,
                                                                                    Р=общий.Ссылка)]
    т.проверить(касса_строки == [(ст(сын), ст(мама), 3000.0), (ст(дочь), ст(мама), 1500.0)],
                "касса: приход по каждому ученику, плательщик — мама", касса_строки)
    деньги, строк = д_.итог("УЗ_СписанияСуммЗаУроки", общий.Ссылка)
    т.проверить(строк == 2 and деньги == 4500, "деньги учеников: две строки, 4 500", "%s / %s" % (строк, деньги))
    долг_сына = ф.число(ДОЛГ, Ученик=сын, Организация=орг)
    долг_дочери = ф.число(ДОЛГ, Ученик=дочь, Организация=орг)
    т.проверить(долг_сына == 0 and долг_дочери == -500, "долг сына закрыт, у дочери осталось 500 (частичная оплата)",
                "%s / %s" % (долг_сына, долг_дочери))
    т.проверить(c.УЗ_Сервер.ЗадолженностьУченика(дочь, орг, гитара) == 500,
                "«Заполнить сумму по задолженности» дочери — 500")

    # ── В35: отказы по строкам ──
    абонемент_сына = ф.абонемент(сын, "абонемент сына", ПредметОбучения=гитара, Организация=орг, ЦенаАбонемента=8000)
    чужой = c.Документы.УЗ_ПриходДенег.СоздатьДокумент()
    чужой.Дата, чужой.ВидОперации, чужой.Организация, чужой.Касса = ф.день(0, 9), виды.КассаУченики, орг, касса
    чужой.Плательщик, чужой.Комментарий = мама, МЕТКА
    for у, п, сумма, аб in ((сын, математика, 100, None), (дочь, гитара, 200, абонемент_сына)):
        с = чужой.РасшифровкаПлатежа.Добавить()
        с.Ученик, с.ПредметОбучения, с.Сумма = у, п, сумма
        if аб is not None:
            с.Абонемент = аб
    ош, сообщ = ф.записать(чужой)
    т.проверить(ош is not None and any("строка 2" in м and "Абонемент" in м for м, _ in сообщ),
                "строка с абонементом чужого ученика — отказ с номером строки", "%s %s" % (ош, сообщ))
    пустая = c.Документы.УЗ_ПриходДенег.СоздатьДокумент()
    пустая.Дата, пустая.ВидОперации, пустая.Организация, пустая.Касса = ф.день(0, 9), виды.КассаУченики, орг, касса
    пустая.Комментарий = МЕТКА
    for у, сумма in ((сын, 100), (дочь, 0)):
        с = пустая.РасшифровкаПлатежа.Добавить()
        с.Ученик, с.Сумма = у, сумма
    ош, сообщ = ф.записать(пустая)
    т.проверить(ош is not None and any("укажите сумму" in м for м, _ in сообщ),
                "строка без суммы в общем платеже — отказ", "%s %s" % (ош, сообщ))

    # ── один ученик — прежний простой случай; плательщик — бабушка ──
    простой = ф.приход(сын, 1000, Организация=орг, Касса=касса, ПредметОбучения=математика, Плательщик=бабушка,
                     Дата=ф.день(0, 9, 30))
    ош, сообщ = ф.записать(простой)
    т.проверить(ош is None, "приход за одного ученика по шапке проводится", "%s %s" % (ош, сообщ))
    строка = простой.РасшифровкаПлатежа.Получить(0) if простой.РасшифровкаПлатежа.Количество() == 1 else None
    т.проверить(строка is not None and ст(строка.Ученик) == ст(сын) and float(строка.Сумма) == 1000
                and ст(строка.ПредметОбучения) == ст(математика), "одна строка расшифровки = шапка")
    касса_строки = [(ст(з.Клиент), ст(з.Плательщик), float(з.Сумма)) for з in т.выбрать(КАССА_ДОКУМЕНТА,
                                                                                    Р=простой.Ссылка)]
    т.проверить(касса_строки == [(ст(сын), ст(бабушка), 1000.0)], "касса: плательщик — бабушка", касса_строки)

    # ── В38: возврат плательщику; предел — аванс по предмету ──
    больше = д_.документ("УЗ_РасходДенег", Дата=ф.день(0, 10), Организация=орг, Касса=касса,
                         ВидОперации=виды.КассаУченики, ФизЛицо=сын, ПредметОбучения=математика, СуммаДокумента=1500)
    ош = д_.записать(больше)
    т.проверить(ош is not None and "Вернуть" in ош, "возврат больше аванса по предмету — отказ (как было)", ош)
    возврат = д_.документ("УЗ_РасходДенег", Дата=ф.день(0, 10), Организация=орг, Касса=касса,
                          ВидОперации=виды.КассаУченики, ФизЛицо=сын, ПредметОбучения=математика, СуммаДокумента=1000)
    ош = д_.записать(возврат)
    т.проверить(ош is None, "возврат аванса 1 000 проводится", ош)
    т.проверить(ст(возврат.Получатель) == ст(бабушка), "получатель по умолчанию — плательщик последней оплаты "
                "по предмету (бабушка, не основной — мама)", ст(возврат.Получатель))
    касса_строки = [(ст(з.Плательщик), float(з.Сумма)) for з in т.выбрать(КАССА_ДОКУМЕНТА, Р=возврат.Ссылка)]
    т.проверить(касса_строки == [(ст(бабушка), 1000.0)], "касса: возврат уменьшает внесённое бабушкой", касса_строки)
    т.проверить(ст(c.УЗ_Сервер.ПолучательВозврата(дочь, орг, гитара)) == ст(мама),
                "получатель возврата дочери — мама (платила за гитару)")

    # ── В37: отчёт «Оплаты по плательщикам» за год ──
    сегодня = ф.сегодня
    прошлый = ф.приход(сын, 700, Организация=орг, Касса=касса, ПредметОбучения=математика, Плательщик=мама,
                       Дата=дата(сегодня.year - 1, 12, 20, 10))
    ош, сообщ = ф.записать(прошлый)
    т.проверить(ош is None, "оплата прошлого года проводится", "%s %s" % (ош, сообщ))
    год = скд(c, "УЗ_ОплатыПоПлательщикам", "ОплатыПоПлательщикам", дата(сегодня.year, 1, 1),
              дата(сегодня.year, 12, 31, 23, 59, 59), {"Организация": орг})
    к_вн, к_воз, к_ит = колонка(год, "Внесено"), колонка(год, "Возвращено"), колонка(год, "Оплачено (внесено минус возвращено)")
    т.проверить(None not in (к_вн, к_воз, к_ит), "в отчёте колонки «Внесено», «Возвращено», «Оплачено…»",
                "%s %s %s" % (к_вн, к_воз, к_ит))

    def цифры(строка_):
        return tuple(число(год[строка_][к]) for к in (к_вн, к_воз, к_ит)) if строка_ is not None else None
    р_мамы = строка_с(год, ст(мама))
    р_бабушки = строка_с(год, ст(бабушка))
    т.проверить(цифры(р_мамы) == (4500, 0, 4500), "мама за год: внесено 4 500 (прошлый год не входит)",
                цифры(р_мамы))
    т.проверить(цифры(строка_с(год, ст(сын), (р_мамы or 0) + 1)) == (3000, 0, 3000)
                and цифры(строка_с(год, ст(дочь), (р_мамы or 0) + 1)) == (1500, 0, 1500),
                "мама за сына 3 000, за дочь 1 500 — основа двух справок")
    т.проверить(цифры(р_бабушки) == (1000, 1000, 0), "бабушка: внесено 1 000, возвращено 1 000, итог 0",
                цифры(р_бабушки))
    прошлый_год = скд(c, "УЗ_ОплатыПоПлательщикам", "ОплатыПоПлательщикам", дата(сегодня.year - 1, 1, 1),
                      дата(сегодня.year - 1, 12, 31, 23, 59, 59), {"Организация": орг})
    р = строка_с(прошлый_год, ст(мама))
    т.проверить(р is not None and число(прошлый_год[р][к_ит]) == 700, "мама за прошлый год — 700")

    # ── В39: шаг обновления данных 2 (данные 2.0) ──
    обн = c.УЗ_ОбновлениеДанных
    версия = c.РегистрыСведений.УЗ_ВерсииДанных.СоздатьМенеджерЗаписи()
    версия.Прочитать()
    прежняя = версия.Версия if версия.Выбран() else 0

    def вернуть_версию():
        з = c.РегистрыСведений.УЗ_ВерсииДанных.СоздатьМенеджерЗаписи()
        з.Прочитать()
        з.Версия = max(прежняя, обн.АктуальнаяВерсияДанных())
        з.Записать()
    т.убрать(вернуть_версию, "версия данных")
    старый, ош = ученик("ученик 2.0", [])
    о = старый.ПолучитьОбъект()
    о.Родитель1Прежний = папа
