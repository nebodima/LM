    с_плательщиком = ф.приход(старый, 600, Организация=орг, Касса=касса, ПредметОбучения=математика,
                              Плательщик=папа, Дата=ф.день(0, 8))
    сам = ф.приход(старый, 400, Организация=орг, Касса=касса, ПредметОбучения=гитара, Дата=ф.день(0, 8))
    старый_возврат = д_.документ("УЗ_РасходДенег", Дата=ф.день(0, 11), Организация=орг, Касса=касса,
                                 ВидОперации=виды.КассаУченики, ФизЛицо=старый, ПредметОбучения=математика,
                                 СуммаДокумента=100)
    for док in (с_плательщиком, сам):
        ош, сообщ = ф.записать(док)
