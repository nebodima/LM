"""Денежные документы из отчёта и панели — по актуальным данным; «план/факт» по серверному времени
(модернизация Codex Т1–Т2, 28.09.2026).

Команды «Оформить приход денег» / «Оформить перемещение денег» формы отчёта «Взаиморасчёты» (и панели ученика,
которая открывает этот отчёт с отбором) больше не разбирают сумму из текста ячейки: ученик, организация и предмет —
из расшифровки/отбора, сумма — УЗ_Сервер.ЗаполнениеДенежногоДокумента на момент документа.
  1. Приход: долг 1 234,56 в организации А — сумма 1 234,56, организация А, вид «Касса ученики».
  2. Оплата 234,56 после «формирования отчёта» — сумма 1 000,00 (актуальный остаток, не текст устаревшей ячейки).
  3. Организация не задана, деньги только в А — берётся А; деньги в А и Б — отказ с пояснением, без заполнения.
  4. Итог нескольких учеников (ученика нет) — отказ, суммы нет.
  5. Перемещение: аванс 500 по математике — сумма 500, отправитель математика; по гитаре аванса нет — без суммы.
  6. Долга нет — приход без суммы, в пояснении «нет».
  7. Код: форма отчёта не читает текст ячейки; панель ставит отбор организации; клиентское ТекущаяДата() в
     бизнес-логике — только в формах урока и календаря (поимённый долг: их меняет другой агент).
Красное на старом коде: 2 (сумма из текста), 3 (организации не было), 4 (итог превращался в оплату), 7.

    python tools\\тесты\\тест_деньги_из_отчета.py --база=C:\\1c_bases\\UZ_UNF_D
"""
# объекты src_ext, которых нет в тексте теста (выбор тестов --быстро, tools/выбор_тестов.py):
# затрагивает: УЗ_ФормаОтчета, УЗ_ПанельУченика, УЗ_Абонемент, УЗ_ДисконтныеКарты, УЗ_ИзменениеУроков
import datetime
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from _деньги import Данные  # noqa: E402
from фабрика import Фабрика  # noqa: E402

МЕТКА = "_Тест деньги из отчёта"
ИСХОДНИКИ = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "src_ext"))
# клиентское ТекущаяДата() в бизнес-логике оставлено только здесь — формы другого агента (урок, календарь)
ДОЛГ_ДАТЫ_КЛИЕНТА = {r"Documents\УЗ_Урок\Forms\ФормаДокумента\Ext\Form\Module.bsl",
                     r"DataProcessors\УЗ_Календарь\Forms\ФормаКалендарь\Ext\Form\Module.bsl"}


def структура(c, з):
    """Структура 1С → dict (ключ — строка)."""
    return {c.String(э.Ключ): э.Значение for э in з}


def текст(путь):
    return open(os.path.join(ИСХОДНИКИ, путь), encoding="utf-8-sig").read()


def клиентская_дата():
    """Модули форм, где ТекущаяДата() стоит в клиентской процедуре (не в комментарии)."""
    найдено = set()
    for папка, _, файлы in os.walk(ИСХОДНИКИ):
        for ф in файлы:
            if ф != "Module.bsl" or "Form" not in папка:
                continue
            путь = os.path.join(папка, ф)
            директива = ""
            for строка in open(путь, encoding="utf-8-sig"):
                с = строка.strip()
                if с.startswith("&На"):
                    директива = с
                if "ТекущаяДата()" in с.split("//")[0] and директива.startswith("&НаКлиенте"):
                    найдено.add(os.path.relpath(путь, ИСХОДНИКИ))
    return найдено


def сценарий(т):
    c = т.c
    д = Данные(т, МЕТКА)
    ф = Фабрика(т, МЕТКА)
    орг_а = ф.организация("Студия А")
    орг_б = ф.организация("Студия Б")
    математика = ф.элемент("УЗ_ПредметыОбучения", "математика")
    гитара = ф.элемент("УЗ_ПредметыОбучения", "гитара")
    сейчас = c.ТекущаяДатаСеанса()

    def назад(часов):
        return сейчас - datetime.timedelta(hours=часов)

    def движение(кто, сумма, орг, предмет=None, часов=2):
        поля = {"Клиент": кто, "Сумма": abs(сумма), "Организация": орг}
        if предмет is not None:
            поля["ПредметОбучения"] = предмет
        д.движения("УЗ_СписанияСуммЗаУроки", д.регистратор(), [("+" if сумма > 0 else "-", назад(часов), поля)])

    def заполнить(документ, ученик, орг=None, предмет=None):
        р = c.УЗ_Сервер.ЗаполнениеДенежногоДокумента(документ, ученик, орг, предмет)
        return c.String(р.Отказ), структура(c, р.Заполнение), c.String(р.Пояснение)

    # ── 1. приход по долгу ──
    должник = ф.ученик("должник")
    движение(должник, -1234.56, орг_а, математика)
    отказ, з, _ = заполнить("УЗ_ПриходДенег", должник, орг_а)
    т.проверить(отказ == "" and round(float(з.get("СуммаДокумента", 0)), 2) == 1234.56
                and c.String(з.get("Организация")) == c.String(орг_а)
                and c.String(з.get("ВидОперации")) == c.String(c.Перечисления.УЗ_ВидыОпераций.КассаУченики),
                "приход: долг 1 234,56 в А — сумма 1 234,56, организация А, «Касса ученики»",
                (отказ, {к: c.String(в) for к, в in з.items()}))

    # ── 2. оплата после формирования отчёта — актуальный остаток ──
    движение(должник, 234.56, орг_а, математика, часов=1)
    отказ, з, пояснение = заполнить("УЗ_ПриходДенег", должник, орг_а, математика)
    т.проверить(round(float(з.get("СуммаДокумента", 0)), 2) == 1000.0 and "1 000,00" in пояснение.replace("\xa0", " "),
                "оплата 234,56 после отчёта — сумма 1 000,00 по остатку на сейчас (было: текст ячейки 1 234,56)",
                (з.get("СуммаДокумента"), пояснение))

    # ── 3. организация из денег ученика ──
    отказ, з, _ = заполнить("УЗ_ПриходДенег", должник)
    т.проверить(отказ == "" and c.String(з.get("Организация")) == c.String(орг_а)
                and round(float(з.get("СуммаДокумента", 0)), 2) == 1000.0,
                "организация не задана, деньги только в А — берётся А, сумма 1 000,00", (отказ, з.get("СуммаДокумента")))
    двое = ф.ученик("долги в двух организациях")
    движение(двое, -300, орг_а)
    движение(двое, -400, орг_б)
    отказ, з, _ = заполнить("УЗ_ПриходДенег", двое)
    т.проверить("нескольких организациях" in отказ and not з,
                "деньги в А и Б, организация не задана — отказ с пояснением, документ не заполняется", (отказ, з))
    отказ, з, _ = заполнить("УЗ_ПриходДенег", двое, орг_б)
    т.проверить(round(float(з.get("СуммаДокумента", 0)), 2) == 400.0, "та же ячейка в строке Б — долг Б 400,00",
                з.get("СуммаДокумента"))

    # ── 4. итог нескольких учеников ──
    отказ, з, _ = заполнить("УЗ_ПриходДенег", None, орг_а)
    т.проверить("одного ученика" in отказ and not з, "итог без ученика — отказ, суммы нет (было: итог = оплата)",
                (отказ, з))

    # ── 5. перемещение: доступный аванс предмета ──
    аванс = ф.ученик("аванс")
    движение(аванс, 500, орг_а, математика)
    отказ, з, _ = заполнить("УЗ_ПеремещениеДенег", аванс, орг_а, математика)
    т.проверить(round(float(з.get("Сумма", 0)), 2) == 500.0
                and c.String(з.get("ПредметОбученияОтправитель")) == c.String(математика)
                and bool(з.get("СделатьДвиженияПоВзаиморасчетам")),
                "перемещение: аванс 500 по математике — сумма 500, отправитель математика", {к: c.String(в) for к, в in з.items()})
    отказ, з, _ = заполнить("УЗ_ПеремещениеДенег", аванс, орг_а, гитара)
    т.проверить(отказ == "" and "Сумма" not in з, "по гитаре аванса нет — перемещение без суммы",
                {к: c.String(в) for к, в in з.items()})

    # ── 6. долга нет ──
    отказ, з, пояснение = заполнить("УЗ_ПриходДенег", аванс, орг_а)
    т.проверить(отказ == "" and "СуммаДокумента" not in з and "нет" in пояснение,
                "долга нет — приход без суммы, пояснение «нет — сумма не заполнена»", (з.get("СуммаДокумента"), пояснение))

    # ── 7. код: текст ячейки, отбор панели, клиентское время ──
    форма = текст(r"CommonForms\УЗ_ФормаОтчета\Ext\Form\Module.bsl")
    т.проверить("ЧислоИзТекста" not in форма and not re.search(r"\.Текст\b", форма)
                and "УЗ_Сервер.ЗаполнениеДенежногоДокумента(" in форма,
                "форма отчёта: текст ячейки не читается, заполнение — УЗ_Сервер.ЗаполнениеДенежногоДокумента")
    панель = текст(r"DataProcessors\УЗ_ПанельУченика\Forms\Форма\Ext\Form\Module.bsl")
    т.проверить('УстановитьОтборВзаиморасчетов(КомпоновщикНастроек, "Организация", Организация)' in панель,
                "панель ученика открывает «Взаиморасчёты» с отбором своей организации")
    клиент = клиентская_дата()
    т.проверить(клиент == ДОЛГ_ДАТЫ_КЛИЕНТА,
                "ТекущаяДата() в клиентском коде форм — только поимённый долг (урок, календарь — зона другого агента)",
                sorted(клиент ^ ДОЛГ_ДАТЫ_КЛИЕНТА))
    разница = abs((c.УЗ_Сервер.ДатаСеанса() - c.ТекущаяДатаСеанса()).total_seconds())
    т.проверить(разница < 5, "УЗ_Сервер.ДатаСеанса — время сервера для клиента", разница)


if __name__ == "__main__":
    запустить("тест_деньги_из_отчета", сценарий)
