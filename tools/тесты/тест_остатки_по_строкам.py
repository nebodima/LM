"""Остаток ученика «по первой строке» в перемещении денег между предметами (учёт №14, Codex C02).

Спор аудитов: учёт — остаток берётся по последней строке, а строки дробятся по педагогу/тарифу/явке;
Codex — виртуальная таблица сворачивает измерения, которых нет в запросе. Проверено на базе
28.09.2026: сворачивает (строка одна, 5 000 − 2 000 = 3 000) — ошибки нет, Codex прав. Тест это
закрепляет: платформа (одна строка), и документ (3 500 — отказ, 3 000 — проводится).

    python tools\\тесты\\тест_остатки_по_строкам.py --база=C:\\1c_bases\\UZ_UNF_A
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import дата, запустить  # noqa: E402
from _деньги import Данные  # noqa: E402

МЕТКА = "_Тест остатки по строкам"


def сценарий(т):
    c = т.c
    д = Данные(т, МЕТКА)
    ученик = д.элемент("УЗ_ФизЛица", "ученик")
    педагог = д.элемент("УЗ_ФизЛица", "педагог", ЭтоПедагог=True)
    гитара = д.элемент("УЗ_ПредметыОбучения", "гитара")
    вокал = д.элемент("УЗ_ПредметыОбучения", "вокал")
    носитель = д.регистратор()
    когда = дата(2026, 9, 1, 10)
    # оплата без педагога +5 000, урок педагога −2 000: две строки по измерениям регистра
    д.движения("УЗ_СписанияСуммЗаУроки", носитель, [
        ("+", когда, {"Клиент": ученик, "ПредметОбучения": гитара, "Сумма": 5000}),
        ("-", когда, {"Клиент": ученик, "ПредметОбучения": гитара, "Педагог": педагог, "Сумма": 2000})])

    з = c.NewObject("Запрос")
    з.Текст = ("ВЫБРАТЬ О.СуммаОстаток КАК СуммаОстаток ИЗ РегистрНакопления.УЗ_СписанияСуммЗаУроки.Остатки(, ) КАК О "
               "ГДЕ О.Клиент = &Клиент И О.ПредметОбучения = &Предмет")
    з.УстановитьПараметр("Клиент", ученик)
    з.УстановитьПараметр("Предмет", гитара)
    таблица = з.Выполнить().Выгрузить()
    т.проверить(таблица.Количество() == 1 and float(таблица.Получить(0).СуммаОстаток) == 3000,
                "платформа: Остатки без педагога в запросе — одна строка 3 000 (разрезы свёрнуты)",
                "строк %s" % таблица.Количество())

    def перемещение(сумма, откуда, час):
        п = д.документ("УЗ_ПеремещениеДенег", Дата=дата(2026, 9, 2, час), Клиент=ученик, Сумма=сумма,
                       СделатьДвиженияПоВзаиморасчетам=True, ПредметОбученияПолучатель=вокал)
        if откуда is not None:
            п.ПредметОбученияОтправитель = откуда
        return д.записать(п)

    ош = перемещение(3500, гитара, 10)
    т.проверить(ош is not None and "3000" in ош.replace(" ", "").replace("\xa0", ""),
                "перемещение 3 500 с гитары при остатке 3 000 — отказ с остатком 3 000", ош)
    ош = перемещение(3000, гитара, 11)
    т.проверить(ош is None, "перемещение 3 000 (весь остаток) — проводится", ош)
    # без предмета-отправителя — общий остаток ученика: после перемещения 3 000 гитара 0, вокал 3 000
    ош = перемещение(3001, None, 12)
    т.проверить(ош is not None, "без предмета: 3 001 при общем остатке 3 000 — отказ", ош)


if __name__ == "__main__":
    запустить("остатки_по_строкам", сценарий)
