"""Урок: цена тарифа при проведении и новый педагог в справочнике физ. лиц (УЗ_ext).

Осмотр форм 28.09 (№6): урок «к оплате» по тарифу без цены проводился с суммой 0 — молча бесплатный
урок. Теперь:
  * тариф с историей цен и без записи цены — проведение отказано, сообщение у поля «Тариф» строки;
  * явно бесплатный тариф (запись истории цен с суммой 0) — проводится с суммой 0;
  * тариф без истории цен с суммой в карточке («8 уроков, 8 000») — цена из карточки (1 000 за урок),
    как её и показывает представление тарифа;
  * ученик без тарифа — проводится бесплатно (тариф не выбран — нечего проверять).
№27: новый педагог без папки ложится в группу «Педагоги»; пол у нового физ. лица не указан (пусто).

Данные создаёт сам и удаляет за собой.

    python tools\\тесты\\тест_урок.py --база=C:\\1c_bases\\UZ_UNF_A
"""
import datetime
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить, дата, ошибка_записи  # noqa: E402

МЕТКА = "УЗ тест урока"


def сценарий(т):
    c = т.c
    сегодня = datetime.date.today() - datetime.timedelta(days=1)   # урок нельзя провести раньше начала (В10)
    год, месяц, день = сегодня.year, сегодня.month, сегодня.day

    def элемент(вид, наименование, **реквизиты):
        о = getattr(c.Справочники, вид).СоздатьЭлемент()
        о.Наименование = "%s %s" % (МЕТКА, наименование)
        for к, в in реквизиты.items():
            setattr(о, к, в)
        о.Записать()
        ссылка = о.Ссылка
        т.убрать(lambda: т.удалить_объект(ссылка), "%s %s" % (вид, наименование))
        return ссылка

    # ── №27: педагог и пол ──
    педагог = элемент("УЗ_ФизЛица", "педагог", ЭтоПедагог=True)
    def ид(ссылка):  # ссылки через COM сравниваем по уникальному идентификатору
        return c.String(ссылка.УникальныйИдентификатор())
    папка = ид(c.Справочники.УЗ_ФизЛица.Педагоги)
    т.проверить(ид(педагог.Родитель) == папка, "новый педагог без папки — в группе «Педагоги»",
                c.String(педагог.Родитель))
    ученик = элемент("УЗ_ФизЛица", "ученик")
    т.проверить(ид(ученик.Родитель) != папка, "новый ученик не попадает в «Педагоги»")
    т.проверить(ученик.Пол is None, "у нового физ. лица пол не указан (не угадываем «Жен.»)", repr(ученик.Пол))

    # ── №6: тарифы ──
    без_цены = элемент("УЗ_Тарифы", "без цены", ИспользоватьИсториюЦен=True)
    бесплатный = элемент("УЗ_Тарифы", "бесплатный", ИспользоватьИсториюЦен=True)
    запись = c.РегистрыСведений.УЗ_ЦеныТарифов.СоздатьМенеджерЗаписи()
    запись.Период = дата(год - 1, 1, 1)
    запись.Тариф = бесплатный
    запись.Сумма = 0
    запись.КоличествоУроков = 1
    запись.Записать()

    def удалить_цену():
        з = c.РегистрыСведений.УЗ_ЦеныТарифов.СоздатьМенеджерЗаписи()
        з.Период = дата(год - 1, 1, 1)
        з.Тариф = бесплатный
        з.Прочитать()
        if з.Выбран():
            з.Удалить()
    т.убрать(удалить_цену, "цена бесплатного тарифа")
    в_карточке = элемент("УЗ_Тарифы", "8 уроков", Сумма=8000, КоличествоУроков=8, КоличествоЧасов=8)

    def урок(тариф, час):
        д = c.Документы.УЗ_Урок.СоздатьДокумент()
        д.Дата = дата(год, месяц, день, час)
        д.Педагог = педагог
        д.КоличествоЧасов = 1
        д.Комментарий = МЕТКА
        строка = д.Ученики.Добавить()
        строка.Ученик = ученик
        if тариф is not None:
            строка.Тариф = тариф
        строка.Явка = True
        строка.СписатьОплату = True
        return д

    def провести(д):
        ошибка = ошибка_записи(lambda: д.Записать(c.РежимЗаписиДокумента.Проведение))
        if not д.Ссылка.Пустая():
            ссылка = д.Ссылка
            т.убрать(lambda: т.удалить_объект(ссылка), "урок")
        return ошибка

    д = урок(без_цены, 8)
    c.ПолучитьСообщенияПользователю(True)
    ошибка = провести(д)
    сообщения = c.ПолучитьСообщенияПользователю(True)
    сообщения = [(сообщения.Получить(н).Текст, сообщения.Получить(н).Поле) for н in range(сообщения.Количество())]
    # отказ засчитывается только по своей причине: сообщение «нет цены» про этот тариф у поля строки,
    # а не любая ошибка записи (обязательная организация, права, дата запрета…)
    по_цене = [(текст, поле) for текст, поле in сообщения
               if "нет цены" in текст and "%s без цены" % МЕТКА in текст and поле == "Ученики[0].Тариф"]
    т.проверить(ошибка is not None and по_цене,
                "к оплате по тарифу без цены — проведение отказано, причина «нет цены» у поля Ученики[0].Тариф",
                "ошибка: %s; сообщения: %s" % (ошибка, сообщения))
    т.проверить(д.Ссылка.Пустая() or not д.Ссылка.Проведен, "урок без цены не проведён")

    д = урок(бесплатный, 9)
    ошибка = провести(д)
    т.проверить(ошибка is None, "явно бесплатный тариф (цена 0 в истории) — урок проводится", ошибка or "")
    if ошибка is None:
        т.проверить(д.Ссылка.Сумма == 0, "бесплатный урок — сумма 0", д.Ссылка.Сумма)

    д = урок(в_карточке, 10)
    ошибка = провести(д)
    т.проверить(ошибка is None, "тариф с ценой в карточке (без истории цен) — урок проводится", ошибка or "")
    if ошибка is None:
        т.проверить(д.Ссылка.Сумма == 1000, "цена из карточки: 8 000 / 8 уроков = 1 000", д.Ссылка.Сумма)

    д = урок(None, 11)
    ошибка = провести(д)
    т.проверить(ошибка is None, "ученик без тарифа — урок проводится (бесплатно)", ошибка or "")


if __name__ == "__main__":
    запустить("урок", сценарий)
