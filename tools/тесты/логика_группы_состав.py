"""Логика «состав групп» (docs/логики/группы_и_расписание.md Р3–Р4, сценарии 6–9; карточка_ученика.md правило 12;
решения В18, В22). Единое правило «член группы на дату урока» — Справочники.УЗ_ФизЛица.ПроверитьЧленствоВГруппе:
строка ТЧ «Группы обучения» действует на дату, если «Дата начала» пустая или не позже, «Дата окончания» пустая или
не раньше; строк группы несколько — достаточно одной действующей.

  1. Проверка урока (ученик с «Только выбранные группы»), запись урока группы А на день Д:
     * ТЧ: А с Д+6 (ещё не начал) — отказ «начинается с» (было: записывался — «Дата начала» не проверялась);
     * ТЧ: А по Д−10 и А с Д−5 (ушёл и вернулся) — записывается (было: отказ из-за первой строки);
     * ТЧ: А по Д−2 — отказ «окончен срок» (как было).
  2. Состав группы на дату (СоставГруппыНаДату, для помощника/продления/календаря): на Д — только действующий
     ученик; не входят: строка с Д+6, строка по Д−2, выбывший (В18), педагог; на Д+6 — входит и «с Д+6».
  3. В22 перевод А → Б датой Д (ПеревестиВГруппу): строка А закрыта днём Д−1, строка Б открыта с Д; на Д−1
     ученик в А и не в Б, на Д — в Б и не в А.
Красное на старом коде (28.09.2026): 1 — первые два случая, 2 и 3 — функций не было.

    python tools\\тесты\\логика_группы_состав.py --база=C:\\1c_bases\\UZ_UNF_A
"""
import datetime
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить, текст_ошибки  # noqa: E402
from фабрика import Фабрика  # noqa: E402

МЕТКА = "_Тест логика групп"


def попытка(действие):
    try:
        return действие()
    except Exception as е:
        return "ошибка: " + текст_ошибки(е, 160)


def сценарий(т):
    c = т.c
    ф = Фабрика(т, МЕТКА)
    Д = -3                                    # день урока — три дня назад (сдвиг от сегодня)
    педагог = ф.педагог("педагог")
    группа_а = ф.элемент("УЗ_ГруппыОбучения", "группа А")
    группа_б = ф.элемент("УЗ_ГруппыОбучения", "группа Б")

    def ученик(имя, строки, **реквизиты):
        """строки — [(группа, сдвиг начала или None, сдвиг окончания или None)] от сегодня."""
        о = c.Справочники.УЗ_ФизЛица.СоздатьЭлемент()
        о.Наименование = "%s %s" % (МЕТКА, имя)
        о.ТолькоВыбранныеГруппыОбучения = True
        for к, в in реквизиты.items():
            setattr(о, к, в)
        for гр, нач, кон in строки:
            с = о.ГруппыОбучения.Добавить()
            с.ГруппаОбучения = гр
            if нач is not None:
                с.ДатаНачала = ф.день(нач)
            if кон is not None:
                с.ДатаОкончания = ф.день(кон)
        о.Записать()
        ссылка = о.Ссылка
        т.убрать(lambda: т.удалить_объект(ссылка), "ученик %s" % имя)
        return ссылка

    ещё_не = ученик("ещё не начал", [(группа_а, Д + 6, None)])
    вернулся = ученик("вернулся", [(группа_а, None, Д - 10), (группа_а, Д - 5, None)])
    ушёл = ученик("ушёл", [(группа_а, None, Д - 2)])
    действует = ученик("действует", [(группа_а, Д - 30, None)])
    выбыл = ученик("выбыл", [(группа_а, None, None)], Выбыл=True) \
        if c.Метаданные.Справочники.УЗ_ФизЛица.Реквизиты.Найти("Выбыл") is not None else None
    педагог_в_группе = ученик("педагог в группе", [(группа_а, None, None)], ЭтоПедагог=True)

    # ── 1. проверка урока ──
    def урок(кто):
        д = ф.урок(педагог, ф.день(Д, 10), 1, [dict(Ученик=кто, Явка=True)], ГруппаОбучения=группа_а)
        return ф.записать(д, "Запись")
    ошибка, сообщения = урок(ещё_не)
    т.проверить(ошибка is not None and any("начинается" in с for с, _ in сообщения),
                "урок группы А раньше «Дата начала» ученика — отказ «начинается с» (было: записывался)",
                ошибка or "записан")
    ошибка, сообщения = урок(вернулся)
    т.проверить(ошибка is None, "две строки группы (ушёл и вернулся) — урок записывается (было: отказ по первой)",
                "%s %s" % (ошибка, сообщения))
    ошибка, сообщения = урок(ушёл)
    т.проверить(ошибка is not None and any("окончен" in с for с, _ in сообщения),
                "урок позже «Дата окончания» — отказ «окончен срок группы»", ошибка or "записан")

    # ── 2. состав группы на дату ──
    def состав(сдвиг):
        р = попытка(lambda: c.Справочники.УЗ_ФизЛица.СоставГруппыНаДату(группа_а, ф.день(сдвиг, 10)))
        if isinstance(р, str):
            return р
        return sorted(c.String(у) for у in р)
    на_д = состав(Д)
    т.проверить(на_д == sorted([c.String(вернулся), c.String(действует)]),
                "состав А на день урока: «вернулся» и «действует»; без не начавшего, ушедшего, выбывшего, педагога",
                на_д)
    т.проверить(isinstance(на_д, list) and выбыл is not None and c.String(выбыл) not in на_д
                and c.String(педагог_в_группе) not in на_д, "В18: выбывший и педагог в состав группы не входят")
    позже = состав(Д + 6)
    т.проверить(isinstance(позже, list) and c.String(ещё_не) in позже,
                "состав А на «Дата начала» не начавшего — он уже в группе", позже)

    # ── 3. В22: перевод закрывает старую группу и открывает новую ──
    переводимый = ученик("переводимый", [(группа_а, Д - 30, None)])
    итог = попытка(lambda: c.Справочники.УЗ_ФизЛица.ПеревестиВГруппу(переводимый, группа_а, группа_б, ф.день(Д)))
    т.проверить(not isinstance(итог, str), "В22: перевод в карточке выполнен", итог)
    о = переводимый.ПолучитьОбъект()
    строки = sorted((c.String(с.ГруппаОбучения),
                     с.ДатаНачала.date() if с.ДатаНачала.year >= 1900 else None,
                     с.ДатаОкончания.date() if с.ДатаОкончания.year >= 1900 else None) for с in о.ГруппыОбучения)
    день = ф.сегодня + datetime.timedelta(days=Д)
    т.проверить(строки == sorted([(c.String(группа_а), день - datetime.timedelta(days=30), день - datetime.timedelta(days=1)),
                                  (c.String(группа_б), день, None)]),
                "В22: строка А закрыта днём перед переводом, строка Б открыта с даты перевода", строки)

    def член(группа, сдвиг):
        return попытка(lambda: bool(c.Справочники.УЗ_ФизЛица.ЧленГруппыНаДату(переводимый, группа, ф.день(сдвиг, 12))))
    т.проверить((член(группа_а, Д - 1), член(группа_б, Д - 1), член(группа_а, Д), член(группа_б, Д))
                == (True, False, False, True),
                "В22: накануне перевода — в А, не в Б; в день перевода — в Б, не в А",
                (член(группа_а, Д - 1), член(группа_б, Д - 1), член(группа_а, Д), член(группа_б, Д)))


if __name__ == "__main__":
    запустить("логика_группы_состав", сценарий)
