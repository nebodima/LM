"""Логика «состав групп» (docs/логики/группы_состав.md; решения В18, В22, В29). Единое правило «в группе на дату» —
регистр УЗ_СоставГрупп (РегистрыСведений.УЗ_СоставГрупп.ПричинаНеВГруппе / СоставГруппыНаДату): последняя запись пары
«ученик — группа» на дату — «Состоит». Пишет регистр только документ «Перевод ученика» (зачисление, перевод, выбытие).

  1. Проверка урока (ученик с «Только выбранные группы»), запись урока группы А на день Д:
     * зачислен в А с Д+6 (ещё не начал) — отказ «зачислен только с»;
     * в А до Д−10, снова с Д−5 (ушёл и вернулся) — записывается;
     * выбыл из А с Д−1 — отказ «выбыл из группы».
  2. Состав группы на дату (для помощника/продления/календаря): на Д — только действующие; не входят: зачисленный с
     Д+6, выбывший из группы с Д−1, выбывший из студии (В18), педагог; на Д+6 — входит и зачисленный с Д+6.
  3. В22 перевод А → Б датой Д (документ «Перевод ученика»): на Д−1 ученик в А и не в Б, на Д — в Б и не в А.
Красное на прежнем коде (строки табличной части карточки): функций регистра не было.

    python tools\\тесты\\логика_группы_состав.py --база=C:\\1c_bases\\UZ_UNF_A
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить, текст_ошибки  # noqa: E402
from фабрика import Фабрика  # noqa: E402

МЕТКА = "_Тест логика групп"


def попытка(действие):
    try:
        return действие()
    except Exception as е:
        return "ошибка: " + текст_ошибки(е, 160)


def сценарий(т):
    c = т.c
    ф = Фабрика(т, МЕТКА)
    Д = -3                                    # день урока — три дня назад (сдвиг от сегодня)
    педагог = ф.педагог("педагог")
    группа_а = ф.элемент("УЗ_ГруппыОбучения", "группа А")
    группа_б = ф.элемент("УЗ_ГруппыОбучения", "группа Б")

    def ученик(имя, строки, выбыл=False, **реквизиты):
        """строки — [(группа, сдвиг начала или None — давно, сдвиг последнего дня или None)] от сегодня: зачисление
        и выбытие документами «Перевод ученика»; выбыл — отметка «Выбыл» после зачисления."""
        о = c.Справочники.УЗ_ФизЛица.СоздатьЭлемент()
        о.Наименование = "%s %s" % (МЕТКА, имя)
        о.ТолькоВыбранныеГруппыОбучения = True
        for к, в in реквизиты.items():
            setattr(о, к, в)
        о.Записать()
        ссылка = о.Ссылка
        т.убрать(lambda: т.удалить_объект(ссылка), "ученик %s" % имя)
        for гр, нач, кон in строки:
            ф.в_группу(ссылка, гр, нач if нач is not None else Д - 60, кон)
        if выбыл:
            о = ссылка.ПолучитьОбъект()
            о.Выбыл = True
            о.Записать()
        return ссылка

    ещё_не = ученик("ещё не начал", [(группа_а, Д + 6, None)])
    вернулся = ученик("вернулся", [(группа_а, None, Д - 10), (группа_а, Д - 5, None)])
    ушёл = ученик("ушёл", [(группа_а, None, Д - 2)])
    действует = ученик("действует", [(группа_а, Д - 30, None)])
    выбыл = ученик("выбыл", [(группа_а, None, None)], выбыл=True)
    педагог_в_группе = ученик("педагог в группе", [(группа_а, None, None)], ЭтоПедагог=True)

    # ── 1. проверка урока ──
    def урок(кто):
        д = ф.урок(педагог, ф.день(Д, 10), 1, [dict(Ученик=кто, Явка=True)], ГруппаОбучения=группа_а)
        return ф.записать(д, "Запись")
    ошибка, сообщения = урок(ещё_не)
    т.проверить(ошибка is not None and any("зачислен только с" in с for с, _ in сообщения),
                "урок группы А раньше зачисления ученика — отказ «зачислен только с»",
                ошибка or "записан")
    ошибка, сообщения = урок(вернулся)
    т.проверить(ошибка is None, "ушёл из группы и вернулся — урок после возвращения записывается",
                "%s %s" % (ошибка, сообщения))
    ошибка, сообщения = урок(ушёл)
    т.проверить(ошибка is not None and any("выбыл из группы" in с for с, _ in сообщения),
                "урок после выбытия из группы — отказ «выбыл из группы»", ошибка or "записан")

    # ── 2. состав группы на дату ──
    def состав(сдвиг):
        р = попытка(lambda: c.РегистрыСведений.УЗ_СоставГрупп.СоставГруппыНаДату(группа_а, ф.день(сдвиг, 10)))
        if isinstance(р, str):
            return р
        return sorted(c.String(у) for у in р)
    на_д = состав(Д)
    т.проверить(на_д == sorted([c.String(вернулся), c.String(действует)]),
                "состав А на день урока: «вернулся» и «действует»; без не начавшего, ушедшего, выбывшего, педагога",
                на_д)
    т.проверить(isinstance(на_д, list) and выбыл is not None and c.String(выбыл) not in на_д
                and c.String(педагог_в_группе) not in на_д, "В18: выбывший и педагог в состав группы не входят")
    позже = состав(Д + 6)
    т.проверить(isinstance(позже, list) and c.String(ещё_не) in позже,
                "состав А на день зачисления не начавшего — он уже в группе", позже)

    # ── 3. В22: перевод закрывает старую группу и открывает новую (документ «Перевод ученика») ──
    переводимый = ученик("переводимый", [(группа_а, Д - 30, None)])
    _, (ошибка, сообщения) = ф.перевод([переводимый], из_группы=группа_а, в_группу=группа_б, день=ф.день(Д))
    т.проверить(ошибка is None, "В22: перевод проведён", "%s %s" % (ошибка, сообщения))

    def член(группа, сдвиг):
        return попытка(lambda: bool(c.РегистрыСведений.УЗ_СоставГрупп.ВГруппеНаДату(переводимый, группа,
                                                                                 ф.день(сдвиг, 12))))
    т.проверить((член(группа_а, Д - 1), член(группа_б, Д - 1), член(группа_а, Д), член(группа_б, Д))
                == (True, False, False, True),
                "В22: накануне перевода — в А, не в Б; в день перевода — в Б, не в А",
                (член(группа_а, Д - 1), член(группа_б, Д - 1), член(группа_а, Д), член(группа_б, Д)))


if __name__ == "__main__":
    запустить("логика_группы_состав", сценарий)
