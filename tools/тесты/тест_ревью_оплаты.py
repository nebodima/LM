"""Ревью Codex логик 28.09.2026 — долг ученика и оповещения: R09, R15, R17.

  R09 одна организация: аванс без предмета 1 000, долги математики 1 000 и гитары 1 000. Аванс распределяется
      между предметами без двойного покрытия (одна сумма на ученика и организацию — как В12): сумма долгов по
      предметам = общему долгу 1 000. Старый код: аванс вычитался из каждого предмета целиком — 0 + 0.
  R15 урок 1 000 оплачен ПКО 1 000, затем «Начисление ученику» (набор) 500: долг 500 — за набор, «Назначение
      платежа» уроков не называет. Старый код: называл оплаченный урок (долг покрывался только уроками).
  R17 долг ученика в А 1 000 и в Б 2 000: после проверки задолженности — два оповещения, по одному на организацию,
      с их суммами (одно общее оповещение на ученика теряло бы долг одной из организаций).

    python tools\\тесты\\тест_ревью_оплаты.py --база=C:\\1c_bases\\UZ_UNF_D
"""
# затрагивает: УЗ_Сервер, УЗ_Оповещения, УЗ_НачислениеУченику, УЗ_СписанияСуммЗаУроки
import datetime
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from _деньги import Данные  # noqa: E402
from фабрика import Фабрика  # noqa: E402
from логика_урок import безопасно, деньги, строка  # noqa: E402
import тест_оповещения as оп  # noqa: E402

МЕТКА = "_Тест ревью оплат"


def сценарий(т):
    c = т.c
    ф = Фабрика(т, МЕТКА)
    д_ = Данные(т, МЕТКА)
    орг = ф.организация("А")
    орг_б = ф.организация("Б")
    математика = ф.элемент("УЗ_ПредметыОбучения", "математика")
    гитара = ф.элемент("УЗ_ПредметыОбучения", "гитара")
    пусто = c.Справочники.УЗ_ПредметыОбучения.ПустаяСсылка()
    сервер = c.УЗ_Сервер

    def движения(кто, строки):
        д_.движения("УЗ_СписанияСуммЗаУроки", д_.регистратор(),
                    [("+" if сумма > 0 else "-", когда, dict({"Клиент": кто, "Сумма": abs(сумма)}, **поля))
                     for когда, сумма, поля in строки])

    # ── R09 ──
    ученик = ф.ученик("ученик R09")
    движения(ученик, [(ф.день(-5, 9), 1000, {"Организация": орг, "ПредметОбучения": пусто}),
                      (ф.день(-4, 9), -1000, {"Организация": орг, "ПредметОбучения": математика}),
                      (ф.день(-4, 10), -1000, {"Организация": орг, "ПредметОбучения": гитара})])
    м = деньги(сервер.ЗадолженностьУченика(ученик, орг, математика))
    г = деньги(сервер.ЗадолженностьУченика(ученик, орг, гитара))
    всего = деньги(сервер.ЗадолженностьУченика(ученик, орг))
    т.проверить(всего == 1000 and м + г == всего and {м, г} == {0.0, 1000.0},
                "R09: аванс 1 000 без предмета, долги математики и гитары по 1 000 — по предметам %.0f + %.0f = общему "
                "долгу 1 000 (было 0 + 0)" % (м, г), (м, г, всего))

    # ── R15 ──
    ученик15 = ф.ученик("ученик R15")
    педагог = ф.педагог()
    тариф = ф.элемент("УЗ_Тарифы", "1 000 за урок", Сумма=1000, КоличествоУроков=1)
    урок = ф.урок(педагог, ф.день(-3, 10), 1, [строка(ученик15, Тариф=тариф)], Организация=орг, ПредметОбучения=математика)
    ош, сооб = ф.записать(урок)
    движения(ученик15, [(ф.день(-3, 12), 1000, {"Организация": орг, "ПредметОбучения": математика})])
    статья = д_.элемент("УЗ_СтатьиДвиженияДенег", "набор")
    н = д_.документ("УЗ_НачислениеУченику", Дата=ф.день(-2, 10), ФизЛицо=ученик15, Организация=орг,
                    ПредметОбучения=математика, СтатьяЗатрат=статья, Сумма=500)
    ош2 = д_.записать(н)
    долг = деньги(сервер.ЗадолженностьУченика(ученик15, орг, математика))
    уроки, ош3 = безопасно(lambda: сервер.НеоплаченныеУрокиУченика(ученик15, орг, математика))
    т.проверить(ош is None and ош2 is None and ош3 is None and долг == 500 and уроки.Количество() == 0,
                "R15: урок 1 000 оплачен, набор 500 — долг 500 за набор, неоплаченных уроков нет (было: оплаченный урок)",
                ош or ош2 or ош3 or (долг, уроки.Количество()))

    # ── R17 ──
    оп.выключить_почту(т)
    настройка = c.РегистрыСведений.УЗ_Настройки.СоздатьМенеджерЗаписи()
    настройка.Прочитать()
    была = настройка.Выбран()
    прежние = (настройка.ИспользоватьОповещения, настройка.ОповещатьОЗадолженности)

    def вернуть_настройку():
        н_ = c.РегистрыСведений.УЗ_Настройки.СоздатьМенеджерЗаписи()
        н_.Прочитать()
        if была:
            н_.ИспользоватьОповещения, н_.ОповещатьОЗадолженности = прежние
            н_.Записать()
        else:
            н_.Удалить()
    т.убрать(вернуть_настройку, "настройки оповещений")
    настройка.ИспользоватьОповещения = True
    настройка.ОповещатьОЗадолженности = 2
    настройка.Записать()
    ученик17 = ф.ученик("ученик R17")
    т.убрать(lambda: оп.удалить_оповещения(т, ученик17), "оповещения ученика R17")
    сейчас = c.ТекущаяДатаСеанса()
    движения(ученик17, [(сейчас - datetime.timedelta(days=5), -1000, {"Организация": орг}),
                        (сейчас - datetime.timedelta(days=5), -2000, {"Организация": орг_б})])
    сервер.ПроверкаЗадолженности(т.массив(ученик17))
    записи = т.выбрать("""ВЫБРАТЬ О.Описание КАК Описание, О.Организация КАК Организация, О.Завершено КАК Завершено
        ИЗ РегистрСведений.УЗ_Оповещения КАК О ГДЕ О.Источник = &И""", И=ученик17)
    открытые = sorted((c.String(з_.Организация), оп.пробелы(з_.Описание)) for з_ in записи if not з_.Завершено)
    ждём = sorted([(c.String(орг), "Задолженность %s (%s): 1 000,00" % (c.String(ученик17), c.String(орг))),
                   (c.String(орг_б), "Задолженность %s (%s): 2 000,00" % (c.String(ученик17), c.String(орг_б)))])
    т.проверить(открытые == ждём,
                "R17: долги А 1 000 и Б 2 000 — два оповещения, по одному на организацию", открытые)


if __name__ == "__main__":
    запустить("ревью_оплаты", сценарий)
