def сохранить_настройки_банка(т):
    """Настройки и ключи банков копии — вернуть уборкой как были."""
    c = т.c
    прежние = {}
    for имя in ("УЗ_НастройкиОплатыQR", "УЗ_КлючиОплатыQR"):
        н = getattr(c.РегистрыСведений, имя).СоздатьНаборЗаписей()
        н.Прочитать()
        прежние[имя] = н.Выгрузить()

    def вернуть():
        for имя, таблица in прежние.items():
            н = getattr(c.РегистрыСведений, имя).СоздатьНаборЗаписей()
            н.Загрузить(таблица)
            н.Записать()
    т.убрать(вернуть, "настройки и ключи банков копии")


