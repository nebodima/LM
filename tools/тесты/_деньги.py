"""Общие помощники денежных тестов (расчёт зарплаты, кассы, возврат, списание остатков, массовое изменение).

Не тест (прогон берёт только тест_*.py). Всё, что создаётся, помечается и убирается через т.убрать:
документы удаляются вместе с движениями в режиме загрузки — мимо даты запрета и без хвостов
«<Объект не найден>» в регистрах.
"""
from сеанс import сейчас, ошибка_записи  # noqa: F401 — сейчас: время сеансов тестов (сеанс.закрепить_время)


def удалить_документ(c, ссылка):
    """Сначала движения (пустые наборы по регистратору), потом документ — без проверок даты запрета."""
    движения = ссылка.Метаданные().Движения   # только регистры, где этот вид документа — регистратор
    for р in движения:
        полное = р.ПолноеИмя()
        if полное.startswith("РегистрНакопления."):
            набор = getattr(c.РегистрыНакопления, р.Имя).СоздатьНаборЗаписей()
        elif полное.startswith("РегистрСведений."):   # подчинённые регистратору (УЗ_УрокиВРасчетахЗарплаты)
            набор = getattr(c.РегистрыСведений, р.Имя).СоздатьНаборЗаписей()
        else:
            continue
        набор.Отбор.Регистратор.Установить(ссылка)
        набор.ОбменДанными.Загрузка = True
        набор.Записать()
    объект = ссылка.ПолучитьОбъект()
    if объект is not None:
        объект.ОбменДанными.Загрузка = True
        объект.Удалить()


def сообщения(c):
    """Тексты сообщений пользователю, накопленных с прошлого вызова (и очистка)."""
    м = c.ПолучитьСообщенияПользователю(True)
    return " | ".join(м.Получить(н).Текст for н in range(м.Количество()))


class Данные:
    """Создание помеченных тестовых данных с уборкой за собой."""

    def __init__(self, т, метка):
        self.т = т
        self.c = т.c
        self.метка = метка
        self._убраны = set()

    def элемент(self, вид, наименование, **реквизиты):
        о = getattr(self.c.Справочники, вид).СоздатьЭлемент()
        о.Наименование = "%s %s" % (self.метка, наименование)
        for к, в in реквизиты.items():
            setattr(о, к, в)
        о.Записать()
        ссылка = о.Ссылка
        self.т.убрать(lambda: self.т.удалить_объект(ссылка), "%s %s" % (вид, наименование), пакет=True)
        return ссылка

    def документ(self, вид, **реквизиты):
        д = getattr(self.c.Документы, вид).СоздатьДокумент()
        д.Комментарий = self.метка
        for к, в in реквизиты.items():
            setattr(д, к, в)
        return д

    def записать(self, документ, режим=None):
        """Записать (по умолчанию — провести). Текст ошибки или None; уборка документа — после первой записи."""
        c = self.c
        режим = c.РежимЗаписиДокумента.Проведение if режим is None else режим
        сообщения(c)
        ош = ошибка_записи(lambda: документ.Записать(режим))
        self.следить(документ.Ссылка)
        if ош is not None:
            ош = "%s [%s]" % (ош, сообщения(c))
        return ош

    def следить(self, ссылка):
        if ссылка.Пустая():
            return
        ключ = self.c.String(ссылка.УникальныйИдентификатор())
        if ключ in self._убраны:
            return
        self._убраны.add(ключ)
        self.т.убрать(lambda: удалить_документ(self.c, ссылка), "документ %s" % self.метка, пакет=True)

    def регистратор(self):
        """Непроведённый документ-носитель для движений, записанных тестом напрямую в регистр."""
        д = self.документ("УЗ_СписаниеОстатков", Дата=сейчас())
        ош = self.записать(д, self.c.РежимЗаписиДокумента.Запись)
        if ош is not None:
            raise RuntimeError("носитель движений не записан: %s" % ош)
        return д.Ссылка

    def движения(self, регистр, регистратор, строки):
        """строки: [(вид «+»/«-», период, {поле: значение})] — набор записей по регистратору.
        Касса и деньги ученика — по организации (В12): без «Организация» в строке — организация по умолчанию
        (так же её получают ПКО, РКО, перемещение и списание, созданные программно без организации)."""
        c = self.c
        if регистр in ("УЗ_Касса", "УЗ_СписанияСуммЗаУроки"):
            по_умолчанию = c.РегистрыСведений.УЗ_Настройки.Настройки().Организация
            строки = [(вид, период, dict({"Организация": по_умолчанию}, **поля)) for вид, период, поля in строки]
        набор = getattr(c.РегистрыНакопления, регистр).СоздатьНаборЗаписей()
        набор.Отбор.Регистратор.Установить(регистратор)
        for вид, период, поля in строки:
            з = набор.Добавить()
            з.Период = период
            з.ВидДвижения = c.ВидДвиженияНакопления.Приход if вид == "+" else c.ВидДвиженияНакопления.Расход
            for к, в in поля.items():
                setattr(з, к, в)
        набор.Записать()

    def итог(self, регистр, регистратор, ресурс="Сумма"):
        """Сумма ресурса по движениям регистратора: приход +, расход − (как вклад в остаток)."""
        з = self.c.NewObject("Запрос")
        з.Текст = ("ВЫБРАТЬ ЕСТЬNULL(СУММА(ВЫБОР КОГДА Р.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) "
                   "ТОГДА Р.%s ИНАЧЕ -Р.%s КОНЕЦ), 0) КАК Значение, КОЛИЧЕСТВО(*) КАК Строк "
                   "ИЗ РегистрНакопления.%s КАК Р ГДЕ Р.Регистратор = &Р" % (ресурс, ресурс, регистр))
        з.УстановитьПараметр("Р", регистратор)
        в = з.Выполнить().Выбрать()
        в.Следующий()
        return float(в.Значение), int(в.Строк)
