"""Ревью Codex логик 28.09.2026 — R08: касса не уходит в минус ни в одной точке после изменения (В14).

Контроль остатка — на каждую дату, начиная с самой ранней даты, которую документ меняет (новая или прежняя дата
его движений), до последнего движения кассы: остаток после документа не должен стать отрицательным там, где
документ его уменьшил. Прежде проверялись только две точки — остаток на дату документа и текущий, — и только
если сумма уменьшалась.
  К1 ПКО 10.09 +1 000, РКО 15.09 −500 (касса 500). Перенести ПКО на 20.09 без смены суммы — отказ: с 15.09 по
     20.09 касса −500. Старый код: сумма та же — проверки нет, перенос проходил.
  К2 +1 000 (10.09), −1 000 (15.09), +1 000 (20.09). Новый РКО 12.09 на 600 — отказ: с 15.09 по 20.09 −600.
     Старый код: остаток на 12.09 = 1 000 и текущий = 1 000 — пропускал.
  К3 тот же РКО 21.09 на 600 — можно (после прихода 20.09 денег хватает всюду).

    python tools\\тесты\\тест_ревью_касса.py --база=C:\\1c_bases\\UZ_UNF_D
"""
# затрагивает: УЗ_Кассы, УЗ_Касса, УЗ_ПриходДенег, УЗ_РасходДенег
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import дата, запустить  # noqa: E402
from _деньги import Данные  # noqa: E402
from фабрика import Фабрика  # noqa: E402

МЕТКА = "_Тест ревью кассы"


def сценарий(т):
    c = т.c
    д = Данные(т, МЕТКА)
    ф = Фабрика(т, МЕТКА)
    виды = c.Перечисления.УЗ_ВидыОпераций
    орг = ф.организация("А")
    ученик = д.элемент("УЗ_ФизЛица", "ученик")
    статья = д.элемент("УЗ_СтатьиДвиженияДенег", "аренда")

    def остаток(к):
        return float(c.Справочники.УЗ_Кассы.ОстатокДенег(к, орг))

    def рко(к, сумма, когда):
        р = д.документ("УЗ_РасходДенег", Дата=когда, Касса=к, Организация=орг, СуммаДокумента=сумма,
                       ВидОперации=виды.ПрочийРасход, СтатьяЗатрат=статья)
        return р, д.записать(р)

    # ── К1: перенос прихода позже расхода ──
    к1 = д.элемент("УЗ_Кассы", "К1")
    п = д.документ("УЗ_ПриходДенег", Дата=дата(2026, 9, 10, 10), Касса=к1, Организация=орг, ФизЛицо=ученик,
                   СуммаДокумента=1000, ВидОперации=виды.КассаУченики)
    ош = д.записать(п)
    _, ош2 = рко(к1, 500, дата(2026, 9, 15, 10))
    т.проверить(ош is None and ош2 is None and остаток(к1) == 500, "К1: заготовка — ПКО 10.09 1 000, РКО 15.09 500", ош or ош2)
    о = п.Ссылка.ПолучитьОбъект()
    о.Дата = дата(2026, 9, 20, 10)
    ош = д.записать(о)
    т.проверить(ош is not None and "в минус" in ош and п.Ссылка.ПолучитьОбъект().Дата.day == 10,
                "К1: перенос ПКО 1 000 с 10.09 на 20.09 (после РКО 15.09) — отказ: с 15.09 по 20.09 касса −500", ош)

    # ── К2: минус внутри периода при неотрицательных остатках на дату и текущем ──
    к2 = д.элемент("УЗ_Кассы", "К2")
    д.движения("УЗ_Касса", д.регистратор(), [
        ("+", дата(2026, 9, 10, 10), {"Касса": к2, "Организация": орг, "Сумма": 1000}),
        ("-", дата(2026, 9, 15, 10), {"Касса": к2, "Организация": орг, "Сумма": 1000}),
        ("+", дата(2026, 9, 20, 10), {"Касса": к2, "Организация": орг, "Сумма": 1000})])
    _, ош = рко(к2, 600, дата(2026, 9, 12, 10))
    т.проверить(ош is not None and "в минус" in ош and остаток(к2) == 1000,
                "К2: РКО 12.09 на 600 — отказ: с 15.09 по 20.09 касса −600 (на 12.09 и сейчас остаток 1 000)", ош)
    _, ош = рко(к2, 600, дата(2026, 9, 21, 10))
    т.проверить(ош is None and остаток(к2) == 400, "К3: тот же РКО 21.09 на 600 — проводится, касса 400", ош)


if __name__ == "__main__":
    запустить("ревью_касса", сценарий)
