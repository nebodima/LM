"""Мост в учёт программы, вкладка «Сверка» закрытия смены (05.10.2026, docs/мост_в_учёт_хозяина.md).

Пример владельца: в учёте занятий провели приход, в программе документ тоже провели, но поменяли сумму; или у нас
платит «Марина», а в документе программы контрагент «Марианна». За день: приходы 1 000 и 500 оформлены одним документом
на 1 500 — в программе исправили на 1 400 — «Сумма дня». Каждым документом: приход 1 000 на контрагента мамы — в
программе сумма 900 — «Сумма»; контрагент «Марианна» — «Контрагент»; документ программы не проведён, помечен на
удаление, удалён — по строке на каждый случай. Изменения в программе делаются в обход её проверок (как правка руками).

    python tools\\тесты\\тест_мост_сверка.py --база=C:\\1c_bases\\UZ_BP_Q --пользователь=1
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from фабрика import Фабрика  # noqa: E402

МЕТКА = "_Тест мост сверка"


def сценарий(т):
    c = т.c
    ф = Фабрика(т, МЕТКА)
    мост = c.УЗ_СредаМост
    по_дням, по_документам = мост.РежимЗаДень(), мост.РежимКаждымДокументом()

    def одно(первое, второе):
        return первое is not None and второе is not None and str(c.XMLString(первое)) == str(c.XMLString(второе))

    орг = c.РегистрыСведений.УЗ_Настройки.Настройки().Организация
    if орг.Пустая():
        орг = ф.организация("студия")
    касса = ф.элемент("УЗ_Кассы", "касса моста сверки", Организация=орг)
    мама = ф.элемент("УЗ_ФизЛица", "Марина Сверкина")
    сын = ф.элемент("УЗ_ФизЛица", "Сын Сверкин")
    созданные = []
    общий_был = мост.СвязанныйОбъект(None, "ОбщийКонтрагент") is not None

    def убрать_программу():
        for ссылка in reversed(созданные):
            т.удалить_объект(ссылка, загрузка=True)
    т.убрать(убрать_программу, "документы и контрагенты программы")
    наши = []

    def связи_убрать():
        for объект in [мама, касса] + наши:
            набор = c.РегистрыСведений.УЗ_СвязиСУчетомХозяина.СоздатьНаборЗаписей()
            набор.Отбор.Объект.Установить(объект)
            набор.Записать()
        if not общий_был:
            мост.Отвязать(None, "ОбщийКонтрагент")
    т.убрать(связи_убрать, "связи моста")

    def запомнить(ссылка):
        if ссылка is not None and not any(одно(ссылка, с) for с in созданные):
            созданные.append(ссылка)

    if str(мост.СправочникДляСвязи(мост.РольКасса())) != "":      # УНФ, УТ: наша касса — с кассой программы
        поле = "Т.Владелец = &Организация И " if c.Метаданные.Справочники.Кассы.Владельцы.Количество() > 0 else ""
        запрос = c.NewObject("Запрос")
        запрос.Текст = "ВЫБРАТЬ ПЕРВЫЕ 1 Т.Ссылка КАК Ссылка ИЗ Справочник.Кассы КАК Т ГДЕ %sНЕ Т.ПометкаУдаления" % поле
        запрос.УстановитьПараметр("Организация", орг)
        выборка = запрос.Выполнить().Выбрать()
        т.проверить(выборка.Следующий(), "у организации есть касса программы")
        мост.Связать(касса, мост.РольКасса(), выборка.Ссылка)

    def приход(сумма, час):
        д = ф.приход(сын, сумма, Организация=орг, Касса=касса, Плательщик=мама, Дата=ф.день(0, час))
        ош, сообщ = ф.записать(д)
        т.проверить(ош is None, "приход %s проведён" % сумма, "%s %s" % (ош, сообщ))
        наши.append(д.Ссылка)
        return д

    def связанный(д):
        return мост.СвязанныйОбъект(д.Ссылка, мост.РольДокумент())

    def расхождения():
        таблица = мост.Расхождения(орг, касса, ф.день(0), ф.день(0, 23, 59))
        итог = []
        for н in range(таблица.Количество()):
            с = таблица.Получить(н)
            if any(одно(с.Объект, о) for о in наши) or any(одно(с.ОбъектХозяина, о) for о in созданные):
                итог.append((str(с.Расхождение), str(с.УНас), str(с.ВПрограмме)))
        return итог

    def править(ссылка, **поля):
        """Правка документа программы «руками» в обход её проверок."""
        о = ссылка.ПолучитьОбъект()
        for к, в in поля.items():
            setattr(о, к, в)
        о.ОбменДанными.Загрузка = True
        о.Записать()

    def массив(*документы):
        м = c.NewObject("Массив")
        for д in документы:
            м.Добавить(д.Ссылка)
        return м

    # ── за день: 1 000 + 500 одним документом, в программе исправили на 1 400 ──
    первый, второй = приход(1000, 9), приход(500, 10)
    итог = мост.Оформить(массив(первый, второй), по_дням)
    т.проверить(int(итог.Оформлено) == 1, "за день: один документ программы", итог.Оформлено)
    день = связанный(первый)
    запомнить(день)
    if день is not None and not общий_был:
        запомнить(день.Контрагент)
    т.проверить(расхождения() == [], "оформленное без правок — расхождений нет", расхождения())
    править(день, СуммаДокумента=1400)
    сейчас = расхождения()
    т.проверить(len(сейчас) == 1 and сейчас[0][0] == "Сумма дня" and "1 500" in сейчас[0][1].replace("\xa0", " ")
                and "1 400" in сейчас[0][2].replace("\xa0", " "),
                "в программе сумму дня исправили на 1 400 — «Сумма дня» 1 500 / 1 400", сейчас)
    править(день, ПометкаУдаления=True, Проведен=False)
    for д in (первый, второй):
        мост.Отвязать(д.Ссылка, мост.РольДокумент())

    # ── каждым документом: мама «Марина», в программе — «Марианна» ──
    создано = мост.СоздатьУХозяина(мама, мост.РольПлательщик())
    контрагент = создано.Ссылка
    т.проверить(str(создано.Ошибка) == "" and контрагент is not None, "мама связана с контрагентом", str(создано.Ошибка))
    if контрагент is None:
        return
    партнер = контрагент.Партнер if c.Метаданные.Справочники.Контрагенты.Реквизиты.Найти("Партнер") is not None else None
    for ссылка in (партнер, контрагент):
        if ссылка is not None:
            созданные.insert(0, ссылка)
    итог = мост.Оформить(массив(первый), по_документам)
    док = связанный(первый)
    т.проверить(int(итог.Оформлено) == 1 and док is not None, "приход 1 000 оформлен каждым документом", итог.Оформлено)
    if док is None:
        return
    запомнить(док)
    т.проверить(расхождения() == [], "после оформления расхождений нет", расхождения())

    править(док, СуммаДокумента=900)
    сейчас = расхождения()
    т.проверить([р[0] for р in сейчас] == ["Сумма"] and "900" in сейчас[0][2], "в программе 900 — «Сумма»", сейчас)
    марианна = c.Справочники.Контрагенты.СоздатьЭлемент()
    марианна.Наименование = "Марианна Сверкина" + МЕТКА
    марианна.ОбменДанными.Загрузка = True
    марианна.Записать()
    созданные.insert(0, марианна.Ссылка)
    править(док, СуммаДокумента=1000, Контрагент=марианна.Ссылка)
    сейчас = расхождения()
    т.проверить([р[0] for р in сейчас] == ["Контрагент"] and "Марина" in сейчас[0][1] and "Марианна" in сейчас[0][2],
                "в программе контрагент «Марианна» вместо «Марины» — «Контрагент»", сейчас)
    править(док, Контрагент=контрагент, Проведен=False)
    сейчас = расхождения()
    т.проверить([р[0] for р in сейчас] == ["Не проведён в программе"], "документ программы не проведён", сейчас)
    править(док, ПометкаУдаления=True)
    сейчас = расхождения()
    т.проверить([р[0] for р in сейчас] == ["Помечен на удаление в программе"], "документ программы помечен", сейчас)
    т.удалить_объект(док, загрузка=True)
    сейчас = расхождения()
    т.проверить([р[0] for р in сейчас] == ["Документ программы удалён"], "документ программы удалён", сейчас)


if __name__ == "__main__":
    запустить("мост_сверка", сценарий)
