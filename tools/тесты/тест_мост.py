"""Мост в учёт программы, вкладка «Люди» закрытия смены (05.10.2026, docs/мост_в_учёт_хозяина.md).

Мама платит за сына сегодня; педагог есть всегда. В списке «Люди» — мама (плательщик) и педагог, сына нет (дети в учёт
программы не уходят). Контрагент программы с ИНН мамы — кандидат «по ИНН»; связали — в списке несвязанных мамы нет;
связь с элементом не того справочника — отказ; отвязали — снова в списке. «Создать» по бабушке — контрагент программы
(физическое лицо, её ФИО и ИНН; в Управлении торговлей — с партнёром) и связь. Педагог: в Бухгалтерии и УНФ сотрудника
не создаём (принимает бухгалтер) — понятный отказ; в Управлении торговлей — физическое лицо программы.
Права: связи пишут менеджер и руководитель, педагог не видит.

    python tools\\тесты\\тест_мост.py --база=C:\\1c_bases\\UZ_BP_Q --пользователь=1
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from фабрика import Фабрика  # noqa: E402

МЕТКА = "_Тест мост"
ИНН_МАМЫ = "500100732259"
ИНН_БАБУШКИ = "770123456703"


def сценарий(т):
    c = т.c
    ф = Фабрика(т, МЕТКА)
    мост = c.УЗ_СредаМост
    плательщик, педагог_роль = мост.РольПлательщик(), мост.РольПедагог()
    возможно = мост.Возможности()

    def одно(первое, второе):
        return первое is not None and второе is not None and str(c.XMLString(первое)) == str(c.XMLString(второе))

    орг = ф.организация("студия")
    мама = ф.элемент("УЗ_ФизЛица", "Мама Мостова")
    бабушка = ф.элемент("УЗ_ФизЛица", "Бабушка Мостова")
    for кто, инн in ((мама, ИНН_МАМЫ), (бабушка, ИНН_БАБУШКИ)):
        данные = c.РегистрыСведений.УЗ_ДокументыФизЛиц.НовыеДанныеФизЛица()
        данные.ИНН = инн
        c.РегистрыСведений.УЗ_ДокументыФизЛиц.ЗаписатьДанныеФизЛица(кто, данные)

        def убрать_данные(кто=кто):
            н = c.РегистрыСведений.УЗ_ДокументыФизЛиц.СоздатьНаборЗаписей()
            н.Отбор.ФизЛицо.Установить(кто)
            н.Записать()
        т.убрать(убрать_данные, "ИНН")
    сын = ф.элемент("УЗ_ФизЛица", "Сын Мостов")
    педагог = ф.педагог("Педагог Мостов")
    касса = ф.элемент("УЗ_Кассы", "касса моста", Организация=орг)
    for кто, сумма in ((мама, 1000), (бабушка, 500)):
        д = ф.приход(сын, сумма, Организация=орг, Касса=касса, Плательщик=кто, Дата=ф.день(0, 9))
        ош, сообщ = ф.записать(д)
        т.проверить(ош is None, "приход от плательщика проведён", "%s %s" % (ош, сообщ))

    def связи_убрать():
        for кто in (мама, бабушка, педагог):
            for роль in (плательщик, педагог_роль):
                мост.Отвязать(кто, роль)
    т.убрать(связи_убрать, "связи моста")

    начало, конец = ф.день(0), ф.день(0, 23, 59)

    def люди(только_несвязанные=True):
        итог = {}
        таблица = мост.ЛюдиДляСвязи(орг, начало, конец, только_несвязанные)
        for н in range(таблица.Количество()):
            строка = таблица.Получить(н)
            итог[(str(строка.ФизЛицо.Наименование), str(строка.Роль))] = строка
        return итог

    имя_мамы, имя_бабушки = "%s Мама Мостова" % МЕТКА, "%s Бабушка Мостова" % МЕТКА
    имя_сына, имя_педагога = "%s Сын Мостов" % МЕТКА, "%s Педагог Мостов" % МЕТКА
    список = люди()
    т.проверить((имя_мамы, плательщик) in список and (имя_бабушки, плательщик) in список
                and (имя_педагога, педагог_роль) in список,
                "в «Людях» — плательщики периода и педагог", sorted(список))
    т.проверить(not any(имя == имя_сына for имя, _ in список), "ученик в «Люди» не попадает (152-ФЗ)")
    т.проверить("не найден" in str(список[(имя_мамы, плательщик)].Состояние),
                "у мамы кандидата в программе нет", str(список[(имя_мамы, плательщик)].Состояние))

    # контрагент программы с ИНН мамы (заведён бухгалтером) — кандидат по ИНН
    к = c.Справочники.Контрагенты.СоздатьЭлемент()
    к.Наименование = "Мостова М. (бухгалтерия)"
    к.ИНН = ИНН_МАМЫ
    к.ОбменДанными.Загрузка = True
    к.Записать()
    контрагент = к.Ссылка
    т.убрать(lambda: т.удалить_объект(контрагент, загрузка=True), "контрагент мамы")
    строка = люди()[(имя_мамы, плательщик)]
    т.проверить(одно(строка.Кандидат, контрагент) and "по ИНН" in str(строка.Состояние),
                "кандидат мамы — контрагент программы по ИНН", str(строка.Состояние))

    т.проверить(str(мост.Связать(мама, плательщик, контрагент)) == "", "мама связана с контрагентом")
    т.проверить((имя_мамы, плательщик) not in люди(), "связанной мамы среди несвязанных нет")
    все = люди(False)
    т.проверить(одно(все[(имя_мамы, плательщик)].ОбъектХозяина, контрагент)
                and str(все[(имя_мамы, плательщик)].Состояние) == "Связан", "во «всех» мама связана с контрагентом")
    т.проверить(одно(мост.СвязанныйОбъект(мама, плательщик), контрагент), "СвязанныйОбъект — контрагент мамы")
    ошибка = str(мост.Связать(мама, плательщик, орг))
    т.проверить("Выберите элемент справочника" in ошибка, "связь с организацией вместо контрагента — отказ", ошибка)
    мост.Отвязать(мама, плательщик)
    т.проверить((имя_мамы, плательщик) in люди() and мост.СвязанныйОбъект(мама, плательщик) is None,
                "отвязали — мама снова среди несвязанных")

    # «Создать» по бабушке — контрагент программы физическое лицо с её ФИО и ИНН
    создано = мост.СоздатьУХозяина(бабушка, плательщик)
    новый = создано.Ссылка
    if новый is not None:
        партнер = новый.Партнер if возможно.Партнеры else None
        т.убрать(lambda: т.удалить_объект(новый, загрузка=True), "контрагент бабушки")
        if партнер is not None:
            т.убрать(lambda: т.удалить_объект(партнер, загрузка=True), "партнёр бабушки")
    т.проверить(str(создано.Ошибка) == "" and новый is not None, "бабушка создана в программе", str(создано.Ошибка))
    if новый is not None:
        т.проверить(str(новый.Наименование) == имя_бабушки and str(новый.ИНН) == ИНН_БАБУШКИ
                    and str(c.XMLString(новый.ЮридическоеФизическоеЛицо)) == "ФизическоеЛицо",
                    "контрагент бабушки — физическое лицо, её ФИО и ИНН",
                    "%s %s %s" % (новый.Наименование, новый.ИНН, c.XMLString(новый.ЮридическоеФизическоеЛицо)))
        т.проверить(одно(мост.СвязанныйОбъект(бабушка, плательщик), новый), "бабушка связана с созданным контрагентом")
        if возможно.Партнеры:
            т.проверить(not новый.Партнер.Пустая(), "в Управлении торговлей — с партнёром")
        повтор = мост.СоздатьУХозяина(бабушка, плательщик)
        т.проверить(одно(повтор.Ссылка, новый) and str(повтор.Ошибка) == "", "повторное «Создать» — тот же контрагент")

    # педагог: сотрудника Бухгалтерии и УНФ не создаём
    создано = мост.СоздатьУХозяина(педагог, педагог_роль)
    if возможно.СоздаватьПедагогов:
        новый_педагог = создано.Ссылка
        if новый_педагог is not None:
            т.убрать(lambda: т.удалить_объект(новый_педагог, загрузка=True), "физлицо педагога")
        т.проверить(str(создано.Ошибка) == "" and новый_педагог is not None, "педагог — физическое лицо программы",
                    str(создано.Ошибка))
    else:
        т.проверить(создано.Ссылка is None and "принимает на работу бухгалтер" in str(создано.Ошибка),
                    "сотрудника не создаём — понятный отказ", str(создано.Ошибка))

    # ── права ──
    рег = c.Метаданные.РегистрыСведений.УЗ_СвязиСУчетомХозяина
    роли = c.Метаданные.Роли
    т.проверить(c.ПравоДоступа("Изменение", рег, роли.УЗ_ОсновнаяРоль)
                and c.ПравоДоступа("Изменение", рег, роли.УЗ_Руководитель)
                and not c.ПравоДоступа("Чтение", рег, роли.УЗ_Педагог),
                "связи пишут менеджер и руководитель, педагог — нет")


if __name__ == "__main__":
    запустить("мост", сценарий)
