"""Ревью Codex логик 28.09.2026 (docs/ревью_codex_логики_2026-09-28.md) — зарплата: R02, R03, R11.

Правило ведомости (В9, как в типовых): расчёт зарплаты выплачивает начисления источников (урок, «Начисления
педагогам»); источник, вошедший в проведённый расчёт, не отменяется и не меняет начисление; сумма источника во
всех расчётах не больше его текущего начисления; невыплаченный остаток источника попадает в следующий расчёт.

  R02     урок в проведённом расчёте «просто записать» (без проведения) с другим начислением — отказ. Старый код:
          запись проходила (начисление 300 в документе, 500 в регистре и ведомости), перепроведение потом
          сравнивало 300 с 300.
  R03     расчёт 1 000 записан, не проведён; урок перепровели с начислением 600; провести старый расчёт — отказ
          «начисление изменилось»; перезаполненный — 600 проводится. Старый код: проводился на 1 000 (долг −400).
  R11     «Начисления педагогам» 1 000 в проведённом расчёте — отмена проведения и смена суммы: отказ. Старый код:
          отмена проходила (начислено 0, к выплате по ведомости 1 000).

    python tools\\тесты\\тест_ревью_зарплата.py --база=C:\\1c_bases\\UZ_UNF_D
"""
# затрагивает: УЗ_РасчетЗарплаты, УЗ_НачисленияПедагогам, УЗ_УрокиВРасчетахЗарплаты, УЗ_Урок
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить, ошибка_записи  # noqa: E402
from фабрика import Фабрика  # noqa: E402
from _деньги import Данные, сообщения  # noqa: E402
from логика_урок import деньги, строка  # noqa: E402

МЕТКА = "_Тест ревью зарплаты"


def сценарий(т):
    c = т.c
    ф = Фабрика(т, МЕТКА)
    д_ = Данные(т, МЕТКА)
    орг = c.РегистрыСведений.УЗ_Настройки.Настройки().Организация
    касса = д_.элемент("УЗ_Кассы", "касса")
    д_.движения("УЗ_Касса", д_.регистратор(), [("+", ф.день(-30, 9), {"Касса": касса, "Сумма": 100000})])
    ученик = ф.ученик()
    за_урок = ф.элемент("УЗ_Тарифы", "1 000 за урок", Сумма=1000, КоличествоУроков=1)
    ставки = {с: ф.элемент("УЗ_СтавкиПедагогов", "%d за занятие" % с, ОплатаЗаЗанятие=с) for с in (300, 500, 600, 700, 1000)}

    def урок(педагог, день, ставка):
        д = ф.урок(педагог, ф.день(день, 10), 1, [строка(ученик, Тариф=за_урок)], СтавкаПедагога=ставки[ставка])
        ош, сооб = ф.записать(д)
        т.проверить(ош is None, "заготовка: урок %d дн. назад, ставка %d — проведён" % (-день, ставка), ош or сооб)
        return д

    def расчёт(педагог, начало, конец):
        р = д_.документ("УЗ_РасчетЗарплаты", Дата=ф.день(0, 0, 1), Педагог=педагог, Касса=касса, Организация=орг,
                        ДатаНачала=ф.день(начало), ДатаОкончания=ф.день(конец))
        р.ЗаполнитьНачисления()
        return р

    def долг(педагог):
        return ф.число("""ВЫБРАТЬ ЕСТЬNULL(СУММА(Р.СуммаОстаток), 0) ИЗ РегистрНакопления.УЗ_РасчетыПоЗарплате.Остатки(,
            Педагог = &П) КАК Р""", П=педагог)

    def попытка(действие):
        сообщения(c)
        ош = ошибка_записи(действие)
        return "%s [%s]" % (ош, сообщения(c)) if ош else None

    # ── R02: урок в проведённом расчёте — запись без проведения с другим начислением ──
    п2 = ф.педагог("педагог записи")
    у2 = урок(п2, -7, 500)
    р2 = расчёт(п2, -8, -6)
    ош = д_.записать(р2)
    т.проверить(ош is None and деньги(р2.СуммаДокумента) == 500, "R02: заготовка — расчёт 500 проведён", ош)
    о = у2.Ссылка.ПолучитьОбъект()
    о.СтавкаПедагога = ставки[300]
    ош = попытка(lambda: о.Записать(c.РежимЗаписиДокумента.Запись))
    т.проверить(ош is not None and "расчёте зарплаты" in ош and ф.начислено_педагогу(у2) == 500,
                "R02: запись (без проведения) урока из расчёта с начислением 300 вместо 500 — отказ, в уроке 500", ош)
    о = у2.Ссылка.ПолучитьОбъект()
    о.Комментарий = МЕТКА + " (тема)"
    ош = попытка(lambda: о.Записать(c.РежимЗаписиДокумента.Запись))
    т.проверить(ош is None, "R02: запись урока из расчёта без изменения начисления (комментарий) — можно", ош)

    # ── R03: записанная, не проведённая ведомость устарела ──
    п3 = ф.педагог("педагог устаревшей ведомости")
    у3 = урок(п3, -6, 1000)
    р3 = расчёт(п3, -7, -5)
    ош = д_.записать(р3, c.РежимЗаписиДокумента.Запись)
    т.проверить(ош is None and деньги(р3.СуммаДокумента) == 1000, "R03: заготовка — расчёт 1 000 записан без проведения", ош)
    о = у3.Ссылка.ПолучитьОбъект()
    о.СтавкаПедагога = ставки[600]
    ош = попытка(lambda: о.Записать(c.РежимЗаписиДокумента.Проведение))
    т.проверить(ош is None and деньги(долг(п3)) == 600, "R03: урок перепроведён с начислением 600 (расчёт не проведён)", ош)
    р3 = р3.Ссылка.ПолучитьОбъект()
    ош = д_.записать(р3)
    т.проверить(ош is not None and not р3.Ссылка.ПолучитьОбъект().Проведен,
                "R03: провести старую ведомость 1 000 при начислении урока 600 — отказ (было: проводилась, выплата 1 000, "
                "долг −400)", ош)
    р3 = р3.Ссылка.ПолучитьОбъект()
    р3.ЗаполнитьНачисления()
    ош = д_.записать(р3)
    т.проверить(ош is None and деньги(р3.СуммаДокумента) == 600, "R03: перезаполненная ведомость 600 проводится", ош)

    # ── R11: ручное начисление в проведённом расчёте ──
    п4 = ф.педагог("педагог ручного начисления")
    н = д_.документ("УЗ_НачисленияПедагогам", Дата=ф.день(-5, 16), Педагог=п4, Организация=орг)
    с = н.НачисленияПедагогам.Добавить()
    с.Сумма = 1000
    ош = д_.записать(н)
    р4 = расчёт(п4, -6, -4)
    ош2 = д_.записать(р4)
    т.проверить(ош is None and ош2 is None and деньги(р4.СуммаДокумента) == 1000,
                "R11: заготовка — начисление 1 000 вошло в проведённый расчёт", ош or ош2)
    о = н.Ссылка.ПолучитьОбъект()
    ош = попытка(lambda: о.Записать(c.РежимЗаписиДокумента.ОтменаПроведения))
    т.проверить(ош is not None and н.Ссылка.ПолучитьОбъект().Проведен and деньги(долг(п4)) == 1000,
                "R11: отмена проведения начисления из проведённого расчёта — отказ, долг 1 000 (было: отмена, долг 0 "
                "при ведомости 1 000)", ош or долг(п4))
    о = н.Ссылка.ПолучитьОбъект()
    о.НачисленияПедагогам.Получить(0).Сумма = 1500
    ош = попытка(lambda: о.Записать(c.РежимЗаписиДокумента.Проведение))
    т.проверить(ош is not None and деньги(долг(п4)) == 1000, "R11: смена суммы начисления из расчёта 1 000 → 1 500 — отказ", ош)


if __name__ == "__main__":
    запустить("ревью_зарплата", сценарий)
