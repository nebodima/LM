"""Логика зарплаты, часть 2: сценарии 14–21 из docs/логики/зарплата.md §5 (ведомость, выплата, отчёт) и старые выплаты.

Расчёт зарплаты — ведомость (В9): вошедший урок фиксируется — урок в проведённом расчёте нельзя отменить, удалить,
перепровести с другим начислением («документ использован в ведомости», сообщение с номером расчёта); «К оплате» =
начисление (только для чтения); состояние выплаты — по всем проведённым РКО на основании
(Документы.УЗ_РасчетЗарплаты.СостояниеВыплаты: РКО «на основании» тоже считается — дефект демо-снимков «НЕ ВЫПЛАЧЕНО!»);
отчёт «Расчёты по зарплате»: «Выручка» — уроки без начисления не выпадают, ручные начисления вычитаются, пустого поля
остатка ЗП нет; старые выплаты без расчёта — шаг обновления 3 даёт им расчёт-перенос в основание.

Красные на старом коде (28.09.2026, UZ_UNF_D до правки): №17 (функции СостояниеВыплаты не было, форма смотрела один
РКО), №18 (отмена, удаление и перепроведение урока из оплаченного расчёта проходили), №19 («К оплате» 150 при
начислении 200 проводилось), №21 (урок без начисления выпадал из «Выручки», ручное начисление давало NULL — итог 600
вместо 1 400; поле «Остаток по расчётам зарплаты» всегда 0), старые выплаты (шага 3 не было).

    python tools\\тесты\\тест_логика_зарплата_2.py --база=C:\\1c_bases\\UZ_UNF_D
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить, ошибка_записи  # noqa: E402
from фабрика import Фабрика  # noqa: E402
from _деньги import Данные, сообщения  # noqa: E402
from тест_логика_урок import безопасно, деньги, строка, перечитать  # noqa: E402
from тест_отчет_зарплаты import итог_педагога  # noqa: E402

МЕТКА = "_Тест логика зарплаты 2"


def сценарий(т):
    c = т.c
    ф = Фабрика(т, МЕТКА)
    д_ = Данные(т, МЕТКА)
    виды = c.Перечисления.УЗ_ВидыОпераций
    орг = c.РегистрыСведений.УЗ_Настройки.Настройки().Организация
    касса = д_.элемент("УЗ_Кассы", "касса")
    д_.движения("УЗ_Касса", д_.регистратор(), [("+", ф.день(-20, 9), {"Касса": касса, "Сумма": 10000})])
    ученик = ф.ученик()
    за_урок = ф.элемент("УЗ_Тарифы", "1 000 за урок", Сумма=1000, КоличествоУроков=1)
    ставка500 = ф.элемент("УЗ_СтавкиПедагогов", "500 за занятие", ОплатаЗаЗанятие=500)
    ставка300 = ф.элемент("УЗ_СтавкиПедагогов", "300 за занятие", ОплатаЗаЗанятие=300)
    ставка200 = ф.элемент("УЗ_СтавкиПедагогов", "200 за занятие", ОплатаЗаЗанятие=200)
    педагог = ф.педагог("педагог ведомости")

    def урок(день, ставка):
        д = ф.урок(педагог, ф.день(день, 10), 1, [строка(ученик, Тариф=за_урок)], СтавкаПедагога=ставка)
        ош, сооб = ф.записать(д)
        т.проверить(ош is None, "заготовка: урок %d дн. назад со ставкой проведён" % -день, ош or сооб)
        return д

    def расчёт(начало, конец, заполнить=True):
        р = д_.документ("УЗ_РасчетЗарплаты", Дата=ф.день(0, 0, 1), Педагог=педагог, Касса=касса, Организация=орг,
                        ДатаНачала=ф.день(начало), ДатаОкончания=ф.день(конец))
        if заполнить:
            р.ЗаполнитьНачисления()
        return р

    def документы(р):
        return sorted(c.String(р.ДД.Получить(н).Документ) for н in range(р.ДД.Количество()))

    def долг():
        return ф.число("""ВЫБРАТЬ ЕСТЬNULL(СУММА(Р.СуммаОстаток), 0) ИЗ РегистрНакопления.УЗ_РасчетыПоЗарплате.Остатки(,
            Педагог = &П) КАК Р""", П=педагог)

    # 14. уроки −9 (500) и −6 (300); расчёт А за −10…−5 проведён; расчёт Б за −10…−1 их не берёт, ручной ввод — отказ
    у9 = урок(-9, ставка500)
    у6 = урок(-6, ставка300)
    у3 = урок(-3, ставка200)
    а = расчёт(-10, -5)
    т.проверить(документы(а) == sorted([c.String(у9.Ссылка), c.String(у6.Ссылка)]) and деньги(а.СуммаДокумента) == 800,
                "14: расчёт А за −10…−5 — уроки 500 + 300 = 800", (документы(а), а.СуммаДокумента))
    ош = д_.записать(а)
    т.проверить(ош is None, "14: расчёт А проведён", ош)
    б = расчёт(-10, -1)
    т.проверить(документы(б) == [c.String(у3.Ссылка)] and деньги(б.СуммаДокумента) == 200,
                "14: расчёт Б за −10…−1 — только урок −3 (200): уроки из А повторно не берутся", (документы(б), б.СуммаДокумента))
    ручной = расчёт(-10, -1, заполнить=False)
    с = ручной.ДД.Добавить()
    с.Документ = у9.Ссылка
    с.Начисление = 500
    с.КОплате = 500
    ош = д_.записать(ручной)
    т.проверить(ош is not None and "уже вошло" in ош, "14: урок из А, вписанный в другой расчёт руками, — отказ", ош)

    # 15. расчёт 800 проведён: ЗП +800 и −800 на конец периода, долг (Сумма) не меняется
    зп = ф.выбрать("""ВЫБРАТЬ Р.ВидДвижения КАК Вид, Р.ЗП КАК ЗП, Р.Сумма КАК Сумма, Р.Период КАК Период
        ИЗ РегистрНакопления.УЗ_РасчетыПоЗарплате КАК Р ГДЕ Р.Регистратор = &Р""", Р=а.Ссылка)
    строки = sorted((c.String(зп.Получить(н).Вид), деньги(зп.Получить(н).ЗП), деньги(зп.Получить(н).Сумма),
                     зп.Получить(н).Период.hour) for н in range(зп.Количество()))
    т.проверить(строки == [("Приход", 800, 0, 23), ("Расход", 800, 0, 23)] and долг() == 1000,
                "15: расчёт 800 — ЗП +800/−800 в конце дня периода, долг педагогу прежний 1 000 (500 + 300 + 200)",
                (строки, долг()))

    # 16. РКО 500 по расчёту А — проводится (долг −500); затем РКО 400 — отказ «остаток 300»
    def рко(сумма, минута):
        р = д_.документ("УЗ_РасходДенег")
        р.Заполнить(а.Ссылка)
        р.Дата = ф.день(-1, 22, минута)
        р.Комментарий = МЕТКА
        р.СуммаДокумента = сумма
        return р, д_.записать(р)
    _, ош = рко(500, 1)
    т.проверить(ош is None and долг() == 500, "16: РКО 500 по расчёту — проведён, долг 1 000 − 500 = 500", ош or долг())
    _, ош = рко(400, 2)
    т.проверить(ош is not None and "остаток 300" in ош.replace("\xa0", " "), "16: РКО 400 при остатке 300 — отказ", ош)

    # 17. второй РКО 300 «на основании» (реквизит «РКО» расчёта пуст) — состояние «Выплачено» по сумме выплат
    _, ош = рко(300, 3)
    состояние, ош_с = безопасно(lambda: c.Документы.УЗ_РасчетЗарплаты.СостояниеВыплаты(а.Ссылка))
    т.проверить(ош is None and ош_с is None and состояние.Статус == "Выплачено" and деньги(состояние.Выплачено) == 800
                and состояние.Выплат == 2 and а.Ссылка.ПолучитьОбъект().РКО.Пустая(),
                "17: РКО 500 + 300 «на основании» — расчёт ВЫПЛАЧЕН полностью (было «НЕ ПОЛНОСТЬЮ» / «НЕ ВЫПЛАЧЕНО»)",
                ош or ош_с or (состояние.Статус, состояние.Выплачено))

    # 18. урок из оплаченного расчёта: отмена, удаление, пометка, перепроведение с другим начислением — отказ
    def попытка(действие):
        сообщения(c)
        ош = ошибка_записи(действие)
        return "%s [%s]" % (ош, сообщения(c)) if ош else None
    номер = str(а.Ссылка.Номер).lstrip("0")
    о = у9.Ссылка.ПолучитьОбъект()
    ош = попытка(lambda: о.Записать(c.РежимЗаписиДокумента.ОтменаПроведения))
    т.проверить(ош is not None and "расчёте зарплаты № " + номер in ош and у9.Ссылка.ПолучитьОбъект().Проведен,
                "18: отмена проведения урока из оплаченного расчёта — отказ с номером расчёта, урок проведён", ош)
    о = у9.Ссылка.ПолучитьОбъект()
    ош = попытка(lambda: о.УстановитьПометкуУдаления(True))
    т.проверить(ош is not None and not у9.Ссылка.ПолучитьОбъект().ПометкаУдаления, "18: пометка удаления урока — отказ", ош)
    о = у9.Ссылка.ПолучитьОбъект()
    ош = попытка(lambda: о.Удалить())
    т.проверить(ош is not None and у9.Ссылка.ПолучитьОбъект() is not None, "18: удаление урока — отказ", ош)
    о = у9.Ссылка.ПолучитьОбъект()
    о.СтавкаПедагога = ставка300
    ош = попытка(lambda: о.Записать(c.РежимЗаписиДокумента.Проведение))
    т.проверить(ош is not None and долг() == 200,
                "18: перепроведение с другим начислением (300 вместо 500) — отказ, долг прежний 200 (урок −3 вне А)", ош or долг())
    о = у9.Ссылка.ПолучитьОбъект()
    о.Комментарий = МЕТКА + " (тема)"
    ош = попытка(lambda: о.Записать(c.РежимЗаписиДокумента.Проведение))
    т.проверить(ош is None, "18: перепроведение без изменения начисления (комментарий) — можно", ош)

    # 19. «К оплате» 150 при начислении 200 — отказ; равное начислению — проводится
    б.ДД.Получить(0).КОплате = 150
    ош = д_.записать(б)
    т.проверить(ош is not None and "не равно начислению" in ош, "19: «К оплате» 150 при начислении 200 — отказ (недоплата не зависает)", ош)
    б.ДД.Получить(0).КОплате = 200
    ош = д_.записать(б)
    т.проверить(ош is None and деньги(б.СуммаДокумента) == 200, "19: «К оплате» = начислению 200 — проводится", ош)

    # 20. оплаченный расчёт: отмена и смена суммы — отказ (N01)
    о = а.Ссылка.ПолучитьОбъект()
    ош = попытка(lambda: о.Записать(c.РежимЗаписиДокумента.ОтменаПроведения))
    т.проверить(ош is not None and "уже выплачена" in ош, "20: отмена проведения оплаченного расчёта — отказ", ош)
    о = а.Ссылка.ПолучитьОбъект()
    о.Комментарий = МЕТКА + " (правка)"
    о.ДД.Получить(0).Начисление = 100
    о.ДД.Получить(0).КОплате = 100
    ош = попытка(lambda: о.Записать(c.РежимЗаписиДокумента.Проведение))
    т.проверить(ош is not None and "изменить" in ош, "20: смена начисления оплаченного расчёта — отказ", ош)

    # 21. отчёт: урок 1 000 со ставкой 40 % (начислено 400), урок 1 000 без начисления, ручное начисление 200
    п40 = ф.элемент("УЗ_СтавкиПедагогов", "40 %", ПроцентСОплатыУченика=40)
    педагог_о = ф.педагог("педагог отчёта")
    д = ф.урок(педагог_о, ф.день(-2, 12), 1, [строка(ученик, Тариф=за_урок)], СтавкаПедагога=п40)
    ф.записать(д)
    д2 = ф.урок(педагог_о, ф.день(-2, 14), 1, [строка(ученик, Тариф=за_урок)])
    ош, _ = ф.записать(д2)
    н = д_.документ("УЗ_НачисленияПедагогам", Дата=ф.день(-2, 16), Педагог=педагог_о, Организация=орг)
    с = н.НачисленияПедагогам.Добавить()
    с.Сумма = 200
    ош2 = д_.записать(н)
    значения = итог_педагога(т, ф, педагог_о, False)
    т.проверить(ош is None and ош2 is None and значения == {"Сумма урока": 2000.0, "Выручка": 1400.0},
                "21: отчёт «Расчёты по зарплате»: сумма уроков 2 000, выручка 1 000 − 400 + 1 000 − 200 = 1 400 "
                "(урок без начисления не выпал, ручное начисление вычтено)", (ош, ош2, значения))
    схема = c.Отчеты.УЗ_РасчетыПоЗарплате.ПолучитьМакет("ОсновнаяСхемаКомпоновкиДанных")
    т.проверить(схема.НаборыДанных.Получить(0).Поля.Найти("ЗПКонечныйОстаток") is None,
                "21: пустого поля «Остаток по расчётам зарплаты» (всегда 0) в отчёте нет")

    # старая выплата зарплаты без расчёта в основании (до версии 1.1) — шаг обновления 3 даёт ей расчёт-перенос
    старый = д_.документ("УЗ_РасходДенег", Дата=ф.день(-1, 23), Касса=касса, СуммаДокумента=700, Организация=орг,
                         ВидОперации=виды.ПрочийРасход, ФизЛицо=педагог)
    ош = д_.записать(старый)
    о = старый.Ссылка.ПолучитьОбъект()
    о.ВидОперации = виды.ВыплатаЗарплаты
    о.ОбменДанными.Загрузка = True
    о.Записать()
    ош = попытка(lambda: старый.Ссылка.ПолучитьОбъект().Записать(c.РежимЗаписиДокумента.Проведение))
    т.проверить(ош is not None, "старая выплата без расчёта: перепровести до обновления нельзя (расчёта в основании нет)", ош)
    _, ош = безопасно(lambda: c.УЗ_ОбновлениеДанных.ШагРасчетыСтарыхВыплат())
    основание = старый.Ссылка.ПолучитьОбъект().ДокументОснования
    перенос = not ош and c.String(основание) != "" and основание.Метаданные().Имя == "УЗ_РасчетЗарплаты"
    if перенос:
        д_.следить(основание)
    т.проверить(перенос and основание.Проведен and деньги(основание.СуммаДокумента) == 700
                and c.String(основание.Педагог) == c.String(педагог),
                "старая выплата: шаг обновления 3 — расчёт-перенос 700 того же педагога в основании", ош or основание)
    ош = попытка(lambda: старый.Ссылка.ПолучитьОбъект().Записать(c.РежимЗаписиДокумента.Проведение))
    т.проверить(ош is None, "старая выплата после обновления перепроводится", ош)


if __name__ == "__main__":
    запустить("логика_зарплата_2", сценарий)
