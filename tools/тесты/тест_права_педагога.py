"""Роль «Учёт занятий: педагог» (УЗ_Педагог): живой сеанс педагога видит и отмечает только свои уроки.

Своё — через ограничение доступа на уровне записей: урок читается и пишется, если педагог урока связан с текущим
пользователем (`Педагог.Пользователь = &ТекущийПользователь`; параметр сеанса хозяина ТекущийПользователь, заимствован —
его ставит модуль сеанса хозяина в любом сеансе, в том числе COM без клиента; свой параметр сеанса расширения
в безопасном режиме не установить). Под администратором заводятся пользователь ИБ с ролями хозяина рядового сотрудника
(те же наборы, что в тест_права.py и docs/роли_и_права.md) + УЗ_Педагог, педагог А (связан с ним), педагог Б, ученик,
тариф с ценой, ставка 500 за занятие, общий абонемент ученика 2 (ходит и к А, и к Б), помещение; уроки (все
в одном помещении): А — вчера проведённый (ученик «К оплате»; ученик 2 «К оплате» без абонемента — проведение
подбирает ему абонемент и считает записанные планом уроки по нему), А — вчера план, Б — вчера проведённый (ученик 2
по общему абонементу), Б — сегодня план (ученик 2 по общему абонементу); ПКО ученику. Потом COM-сеанс педагога
(без клиента):
  * «Мои уроки»: ПедагогТекущегоПользователя = А; УрокиПедагога — оба урока А; запрос РАЗРЕШЕННЫЕ по урокам недели —
    ни одного урока Б; без РАЗРЕШЕННЫЕ — отказ (журнал: Документ.УЗ_Урок); урок Б по ссылке — отказ прав на чтение;
    ДанныеУрока(Б) и ЗаписатьОтметки(Б) — отказ «урок другого педагога»;
  * отметки своего проведённого урока: явка, тема, ДЗ записаны, урок перепроведён (явка в регистре), «К оплате»
    и сумма урока прежние; план — записан с отметками и остался планом;
  * общий абонемент двух педагогов: перепроведение урока А не падает с нарушением прав на урок-план Б (запрос
    записанных планом уроков по абонементу — РАЗРЕШЕННЫЕ), расход абонемента проведённым уроком Б педагог видит
    (регистр списаний без ограничения): использовано 1;
  * деньги: касса, приходы денег — отказ по журналу; у регистра списаний и уроков нет «Просмотр» (интерфейса нет);
  * зарплата: движения расчётов с педагогами РАЗРЕШЕННЫЕ — только А; страница «Моя зарплата» формы «Мои уроки»
    (ЗарплатаПедагога модуля менеджера — её вызывает форма): одна строка — урок А, начислено и к оплате 500,
    документ назван (не «<Объект не найден>»); та же функция по педагогу Б — пусто (у администратора — строка);
    отчёта «Расчёты по зарплате» и общей формы отчёта у роли нет (СКД без «Просмотр» уроков и физ. лиц выбрасывает
    поля педагога и документа — отчёт был бы пуст); расчёт зарплаты — отказ записи;
  * Codex 3, находка 5: отметки — по ученику с версией урока (ДанныеУрока.Версия); план С (-9 дней): педагог
    открыл урок и отметил ученика 1, администратор убрал ученика 1 (ученик 3 стал строкой № 1) — запись отметок:
    отказ «урок изменили», ученику 3 явка не досталась (было: по номеру строки — досталась); после своей записи
    форма получает новую версию (ЗаписатьОтметки.Версия = версия урока при следующем открытии);
  * Codex 3, находка 6: урок закрытого периода педагога (-10 дней, дата запрета педагога — тот же день):
    ДанныеУрока.ТолькоПросмотр и причина в состоянии; запись — отказ с причиной. Клиентская часть (отказ записи
    не переключает урок, период и «Обновить», введённое остаётся) — модуль формы «Мои уроки», COM её не видит.
Уборка — под администратором: уроки, ПКО, справочники, пользователь ИБ и его элемент Пользователи.
Мутации: из роли убрать ограничение у Document.УЗ_Урок (Read без условия) → красное «ни одного урока Б» (живая,
docs/проверки.md) и офлайн — аудит права_роли (самотест: «педагогу чтение урока без ограничения»); РАЗРЕШЕННЫЕ
убрать из запроса планов в ИспользованоАбонементов → красное «общий абонемент».

    python tools\\тесты\\тест_права_педагога.py --база=C:\\1c_bases\\UZ_UNF_B
    python tools\\прогон.py --база=C:\\1c_bases\\UZ_BP_C --пользователь=1 --тест=права_педагога
"""
import os
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import дата, запустить, текст_ошибки  # noqa: E402
from фабрика import Фабрика  # noqa: E402
from тест_права import (ОБЩИЕ_РОЛИ, РОЛИ_ХОЗЯИНА, ТОЛЬКО_ДЛЯ_ТЕСТА, Сотрудник, завести_пользователя,  # noqa: E402
                        удалить_пользователя)

ПЕДАГОГ = "УЗ тест педагог"
МЕТКА = "УЗ тест прав педагога"
СТАВКА = 500
ЦЕНА = 800


def роли(c):
    return ОБЩИЕ_РОЛИ + РОЛИ_ХОЗЯИНА[c.Метаданные.Имя] + ["УЗ_Педагог"] + ТОЛЬКО_ДЛЯ_ТЕСТА


def сценарий(т):
    c = т.c
    удалить_пользователя(т, ПЕДАГОГ)
    н = time.time()
    пользователь = завести_пользователя(т, ПЕДАГОГ, роли(c))
    т.вне_бюджета += time.time() - н
    т.убрать(lambda: удалить_пользователя(т, ПЕДАГОГ), "пользователь ИБ педагога")

    ф = Фабрика(т, МЕТКА)
    ставка = ф.элемент("УЗ_СтавкиПедагогов", "ставка", ОплатаЗаЗанятие=СТАВКА)
    педагог_а = ф.педагог("Педагог А", Пользователь=пользователь, СтавкаПедагога=ставка)
    педагог_б = ф.педагог("Педагог Б", СтавкаПедагога=ставка)
    ученик = ф.ученик("Ученик")
    предмет = ф.элемент("УЗ_ПредметыОбучения", "предмет")
    тариф = ф.элемент("УЗ_Тарифы", "тариф")
    ф.цена_тарифа(тариф, ф.день(-400), ЦЕНА, уроков=1)
    ученик_2 = ф.ученик("Ученик 2")
    общий = ф.абонемент(ученик_2, "общий абонемент", ПредметОбучения=предмет, КоличествоЗанятий=8, ЦенаАбонемента=6400)
    класс = ф.элемент("УЗ_Помещения", "класс")

    def урок(педагог, день, час, провести, второй, явка=False):
        # у Б ученик пришёл — начисление по ставке (В6: без явки урок педагогу не начисляется); у А явку отмечает педагог
        д = ф.урок(педагог, ф.день(день, час), 1,
                   [dict(Ученик=ученик, Тариф=тариф, СписатьОплату=True, Явка=явка), второй],
                   ПредметОбучения=предмет, Тариф=тариф, СтавкаПедагога=ставка, Помещение=класс)
        ошибка, сообщения = ф.записать(д, "Проведение" if провести else "Запись")
        т.проверить(ошибка is None, "подготовка: урок %s %s" % (c.String(педагог), "проведён" if провести else "записан"),
                    "%s %s" % (ошибка, сообщения))
        return д.Ссылка
    без_абонемента = dict(Ученик=ученик_2, Тариф=тариф, СписатьОплату=True)
    по_абонементу = dict(Ученик=ученик_2, Тариф=тариф, СписатьОплату=True, Абонемент=общий)
    урок_а = урок(педагог_а, -1, 10, True, без_абонемента)
    план_а = урок(педагог_а, -1, 12, False, без_абонемента)
    урок_б = урок(педагог_б, -1, 14, True, по_абонементу, явка=True)
    план_б = урок(педагог_б, 0, 23, False, по_абонементу)
    т.проверить(c.Справочники.УЗ_Абонемент.Использовано(общий, урок_а, True).Уроков == 2,
                "самопроверка: у администратора по общему абонементу урок Б и план Б (без урока А)")
    # Codex 3, находки 5 и 6 — планы А вне недели «Мои уроки» (-9 и -10 дней), ученик 3 без абонемента:
    # план С — состав меняет администратор, пока педагог отмечает; закрытый — в закрытом периоде педагога
    ученик_3 = ф.ученик("Ученик 3")
    третий = dict(Ученик=ученик_3, Тариф=тариф, СписатьОплату=True)
    план_с = урок(педагог_а, -9, 12, False, третий)
    закрытый = урок(педагог_а, -10, 12, False, третий)
    запрет = c.РегистрыСведений.УЗ_ДатыЗапрета.СоздатьМенеджерЗаписи()
    запрет.Пользователь = пользователь
    запрет.ДатаЗапрета = ф.день(-10)
    запрет.Записать()

    def снять_запрет():
        набор = c.РегистрыСведений.УЗ_ДатыЗапрета.СоздатьНаборЗаписей()
        набор.Отбор.Пользователь.Установить(пользователь)
        набор.Записать()
    т.убрать(снять_запрет, "дата запрета педагога")

    def убрать_уроки():
        """Уроки после правки педагогом: объект в сеансе администратора закэширован со старой версией —
        перечитать (Прочитать) до отмены проведения и удаления; уборка фабрики потом их уже не найдёт."""
        for ссылка in (урок_а, план_а, урок_б, план_б, план_с, закрытый):
            о = ссылка.ПолучитьОбъект()
            if о is None:
                continue
            о.Прочитать()
            if о.Проведен:
                о.Записать(c.РежимЗаписиДокумента.ОтменаПроведения)
            о.Удалить()
    т.убрать(убрать_уроки, "уроки педагогов")
    пко = ф.приход(ученик, 1600, ПредметОбучения=предмет, Касса=c.Справочники.УЗ_Кассы.ПолучитьОсновнуюКассу())
    ошибка, сообщения = ф.записать(пко)
    т.проверить(ошибка is None, "подготовка: приход денег ученика проведён", "%s %s" % (ошибка, сообщения))
    сумма_а = float(урок_а.ПолучитьОбъект().Сумма)

    админ = c.Обработки.УЗ_МоиУроки.ЗарплатаПедагога(педагог_б, ф.день(-2), ф.день(0, 23, 59))
    т.проверить(админ.Строки.Количество() == 1 and abs(float(админ.Начислено) - СТАВКА) < 0.01,
                "самопроверка: у администратора «Моя зарплата» педагога Б — урок Б на %d" % СТАВКА,
                "строк %s, начислено %s" % (админ.Строки.Количество(), админ.Начислено))

    def убрать_ученика_из_плана_с():
        """Администратор, пока педагог отмечает план С: убирает первого ученика — второй становится строкой № 1."""
        о = план_с.ПолучитьОбъект()
        о.Прочитать()
        о.Ученики.Удалить(0)
        о.Записать(c.РежимЗаписиДокумента.Запись)

    с = Сотрудник(т, ПЕДАГОГ, "педагог")
    try:
        def ид(ссылка):   # идентификатор — в сеансе администратора (ссылки разных соединений не смешивать)
            return c.String(ссылка.УникальныйИдентификатор())
        день_педагога(т, с, dict(урок_а=ид(урок_а), план_а=ид(план_а), урок_б=ид(урок_б),
                                 педагог_а=ид(педагог_а), педагог_б=ид(педагог_б), пко=ид(пко.Ссылка),
                                 общий=ид(общий), план_с=ид(план_с), закрытый=ид(закрытый)), ф,
                     убрать_ученика_из_плана_с)
    finally:
        с.закрыть()

    # после сеанса педагога — под администратором: что записалось. Запросом, а не ПолучитьОбъект: объект урока
    # в сеансе администратора закэширован до правки педагогом (ссылка отдаёт прежние реквизиты)
    def урок_в_базе(ссылка):
        тз = т.выбрать("ВЫБРАТЬ У.Проведен КАК Проведен, У.ТемаУрока КАК Тема, У.ДомашнееЗадание КАК ДЗ, У.Сумма КАК Сумма, "
                       "С.Явка КАК Явка, С.СписатьОплату КАК КОплате ИЗ Документ.УЗ_Урок КАК У "
                       "ЛЕВОЕ СОЕДИНЕНИЕ Документ.УЗ_Урок.Ученики КАК С ПО С.Ссылка = У.Ссылка И С.НомерСтроки = 1 ГДЕ У.Ссылка = &Д", Д=ссылка)
        return тз.Получить(0)
    о = урок_в_базе(урок_а)
    т.проверить(о.Проведен and о.Явка and о.Тема == "Гаммы" and о.ДЗ == "Этюд 5",
                "проведённый урок А: явка, тема и ДЗ записаны, урок проведён", "%s %s %r %r" % (о.Проведен, о.Явка, о.Тема, о.ДЗ))
    т.проверить(о.КОплате and abs(float(о.Сумма) - сумма_а) < 0.01,
                "отметки не тронули «К оплате» и сумму урока", "сумма %s, была %s" % (о.Сумма, сумма_а))
    явок = т.выбрать("ВЫБРАТЬ ЕСТЬNULL(СУММА(Р.КоличествоЯвок), 0) КАК Явок ИЗ РегистрНакопления.УЗ_СписанияСуммЗаУроки КАК Р "
                     "ГДЕ Р.Регистратор = &Д", Д=урок_а).Получить(0).Явок
    # КоличествоЯвок у расхода урока −1 на явку (смысл ресурсов — модуль объекта урока)
    т.проверить(int(явок) == -1, "урок перепроведён: явка в регистре списаний", "явок %s" % явок)
    п = урок_в_базе(план_а)
    т.проверить(not п.Проведен and п.Явка and п.Тема == "Аккорды",
                "план А: отметки записаны, урок остался непроведённым (проводит администратор)")
    б = урок_в_базе(урок_б)
    т.проверить(б.Явка and б.Тема == "", "урок Б не изменился")
    с = урок_в_базе(план_с)
    т.проверить(not с.Явка and с.Тема == "", "5: план С — отметка ученика 1 не досталась ученику 3 (теперь строка № 1), "
                "тема не записана", "явка %s, тема %r" % (с.Явка, с.Тема))


def отметки(c, данные, явка_первого=True):
    """Отметки педагога по данным урока (ДанныеУрока): строка — по ученику (Codex 3, находка 5); явка первого
    ученика — явка_первого, остальных — как были. НомерСтроки — чтобы прежний код (по номеру строки) показал дефект."""
    м = c.NewObject("Массив")
    for н in range(данные.Ученики.Количество()):
        строка = данные.Ученики.Получить(н)
        о = c.NewObject("Структура")
        о.Вставить("НомерСтроки", строка.НомерСтроки)
        о.Вставить("Ученик", строка.Ученик)
        о.Вставить("Явка", явка_первого if н == 0 else строка.Явка)
        м.Добавить(о)
    return м


def записать_отметки(мои, урок, отм, тема, задание, версия):
    """ЗаписатьОтметки с версией урока; прежний код (без параметра версии) — без неё, чтобы показать сам дефект."""
    try:
        return мои.ЗаписатьОтметки(урок, отм, тема, задание, версия)
    except Exception as е:
        if "параметр" not in текст_ошибки(е).lower():
            raise
        return мои.ЗаписатьОтметки(урок, отм, тема, задание)


def версия(данные):
    try:
        return данные.Версия
    except Exception:  # честно: прежний код — версии в данных урока нет, тест красный на проверке результата
        return None


def день_педагога(т, с, ид, ф, убрать_ученика_из_плана_с):
    c = с.c
    урок_а = с.ссылка("Документы", "УЗ_Урок", ид["урок_а"])
    план_а = с.ссылка("Документы", "УЗ_Урок", ид["план_а"])
    урок_б = с.ссылка("Документы", "УЗ_Урок", ид["урок_б"])
    мои = c.Обработки.УЗ_МоиУроки

    педагог = с.шаг("находит свою карточку педагога", lambda: мои.ПедагогТекущегоПользователя())
    т.проверить(педагог is not None and с.ид(педагог) == ид["педагог_а"], "педагог текущего пользователя — А")
    уроки = с.шаг("читает свои уроки за неделю", lambda: мои.УрокиПедагога(педагог, ф.день(-7), ф.день(1)))
    иды = {с.ид(уроки.Получить(к).Урок) for к in range(уроки.Количество())} if уроки is not None else set()
    т.проверить(иды == {ид["урок_а"], ид["план_а"]}, "«Мои уроки»: оба урока А, других нет", str(len(иды)))

    def запрос(текст, **пар):
        з = c.NewObject("Запрос")
        з.Текст = текст
        for к, в in пар.items():
            з.УстановитьПараметр(к, в)
        return з.Выполнить().Выгрузить()
    все = с.шаг("запрос РАЗРЕШЕННЫЕ по урокам недели", lambda: запрос(
        "ВЫБРАТЬ РАЗРЕШЕННЫЕ У.Ссылка КАК Ссылка ИЗ Документ.УЗ_Урок КАК У ГДЕ У.Дата МЕЖДУ &Н И &К",
        Н=ф.день(-7), К=ф.день(1)))
    видит = {с.ид(все.Получить(к).Ссылка) for к in range(все.Количество())} if все is not None else set()
    т.проверить(ид["урок_а"] in видит and ид["урок_б"] not in видит,
                "ограничение роли: свой урок виден, ни одного урока Б", "видно уроков %d" % len(видит))
    с.запрещено("все уроки без РАЗРЕШЕННЫЕ", lambda: запрос(
        "ВЫБРАТЬ У.Ссылка КАК Ссылка ИЗ Документ.УЗ_Урок КАК У ГДЕ У.Дата МЕЖДУ &Н И &К", Н=ф.день(-7), К=ф.день(1)),
        "Документ.УЗ_Урок")
    с.запрещено("открыть урок Б по ссылке", lambda: урок_б.ПолучитьОбъект().Номер, "Документ.УЗ_Урок")

    def чужой(что, действие):
        try:
            итог = действие()
            ок = hasattr(итог, "Успех") and not итог.Успех and "другого педагога" in итог.Текст
            т.проверить(ок, "педагог — отказ: %s" % что, итог.Текст if hasattr(итог, "Текст") else "прошло")
        except Exception as е:
            т.проверить("другого педагога" in текст_ошибки(е), "педагог — отказ: %s" % что, текст_ошибки(е, 150))
    чужой("данные урока Б", lambda: мои.ДанныеУрока(урок_б))
    отметки_б = c.NewObject("Массив")
    строка = c.NewObject("Структура")
    строка.Вставить("НомерСтроки", 1)
    строка.Вставить("Явка", True)
    отметки_б.Добавить(строка)
    чужой("отметки в уроке Б", lambda: мои.ЗаписатьОтметки(урок_б, отметки_б, "взлом", ""))

    данные = с.шаг("открывает свой урок", lambda: мои.ДанныеУрока(урок_а))
    т.проверить(данные is not None and данные.Ученики.Количество() == 2 and данные.Проведен,
                "свой урок: два ученика и признак «проведён»")
    итог = с.шаг("отмечает явку, тему и ДЗ проведённого урока", lambda: записать_отметки(
        мои, урок_а, отметки(c, данные), "Гаммы", "Этюд 5", версия(данные)))
    т.проверить(итог is not None and итог.Успех, "отметки проведённого урока записаны", итог.Текст if итог else "")
    версия_а = версия(итог) if итог is not None and итог.Успех else None
    план = с.шаг("открывает урок-план", lambda: мои.ДанныеУрока(план_а))
    итог = с.шаг("отмечает урок-план", lambda: записать_отметки(мои, план_а, отметки(c, план), "Аккорды", "",
                                                                 версия(план)))
    т.проверить(итог is not None and итог.Успех, "отметки плана записаны", итог.Текст if итог else "")

    # Codex 3, находка 5: педагог отмечает ученика 1 плана С, администратор тем временем убирает ученика 1 (ученик 3
    # становится строкой № 1), педагог записывает — отказ «урок изменили», ученику 3 отметка не достаётся
    план_с = с.ссылка("Документы", "УЗ_Урок", ид["план_с"])
    данные_с = с.шаг("открывает план С (ученик 1 и ученик 3)", lambda: мои.ДанныеУрока(план_с))
    if данные_с is not None:
        отметки_с = отметки(c, данные_с)
        убрать_ученика_из_плана_с()
        итог = записать_отметки(мои, план_с, отметки_с, "Тема С", "", версия(данные_с))
        т.проверить(not итог.Успех and "изменили" in итог.Текст,
                    "5: состав урока изменился после открытия — отметки не записаны, причина «урок изменили»", итог.Текст)

    # Codex 3, находка 6: урок закрытого периода педагога — сразу только для чтения, причина в состоянии
    закрытый = с.ссылка("Документы", "УЗ_Урок", ид["закрытый"])
    данные_з = с.шаг("открывает урок закрытого периода", lambda: мои.ДанныеУрока(закрытый))
    try:
        только_просмотр = bool(данные_з.ТолькоПросмотр) and "закрытом периоде" in данные_з.Состояние
    except Exception as е:  # честно: прежний код — признака нет, это и есть красное
        только_просмотр = False
        print("    прежний код: %s" % текст_ошибки(е, 120))
    т.проверить(только_просмотр, "6: урок закрытого периода — только для чтения, в состоянии причина (дата запрета)",
                данные_з.Состояние if данные_з is not None else "-")
    if данные_з is not None:
        итог = записать_отметки(мои, закрытый, отметки(c, данные_з), "Поздно", "", версия(данные_з))
        т.проверить(not итог.Успех and "закрытом периоде" in итог.Текст,
                    "6: запись отметок закрытого урока — отказ с причиной", итог.Текст)

    # общий абонемент с педагогом Б: проведение урока А подбирает абонемент ученику 2 и читает записанные планом
    # уроки по нему (в том числе план Б) — без нарушения прав; расход проведённым уроком Б виден
    общий = с.ссылка("Справочники", "УЗ_Абонемент", ид["общий"])
    исп = с.шаг("остаток общего абонемента (проведённые уроки)",
                lambda: c.Справочники.УЗ_Абонемент.Использовано(общий, урок_а))
    т.проверить(исп is not None and int(исп.Уроков) == 1,
                "общий абонемент: педагог видит расход абонемента уроком Б", str(исп.Уроков) if исп else "-")
    повтор = с.шаг("открывает свой урок ещё раз", lambda: мои.ДанныеУрока(урок_а))
    т.проверить(повтор is not None and версия_а is not None and версия(повтор) == версия_а,
                "5: после записи отметок форма получает новую версию урока (следующие отметки без перечитывания)")
    итог = с.шаг("перепроводит свой урок при общем абонементе с педагогом Б",
                 lambda: записать_отметки(мои, урок_а, отметки(c, повтор), "Гаммы", "Этюд 5", версия_а))
    т.проверить(итог is not None and итог.Успех,
                "общий абонемент: перепроведение урока А без нарушения прав на урок-план Б", итог.Текст if итог else "")

    # деньги учеников и касса — не его
    с.запрещено("касса (регистр)", lambda: запрос("ВЫБРАТЬ ПЕРВЫЕ 1 К.Сумма КАК Сумма ИЗ РегистрНакопления.УЗ_Касса КАК К"),
                "РегистрНакопления.УЗ_Касса")
    с.запрещено("приход денег ученика", lambda: с.ссылка("Документы", "УЗ_ПриходДенег", ид["пко"]).ПолучитьОбъект().Номер,
                "Документ.УЗ_ПриходДенег")
    т.проверить(not c.ПравоДоступа("Просмотр", c.Метаданные.РегистрыНакопления.УЗ_СписанияСуммЗаУроки)
                and not c.ПравоДоступа("Просмотр", c.Метаданные.Документы.УЗ_Урок)
                and not c.ПравоДоступа("Просмотр", c.Метаданные.Справочники.УЗ_ФизЛица),
                "нет «Просмотр» уроков, списаний и физ. лиц: списков и карточек в интерфейсе педагога нет")

    # зарплата — только своя
    движения = с.шаг("читает расчёты с педагогами (РАЗРЕШЕННЫЕ)", lambda: запрос(
        "ВЫБРАТЬ РАЗРЕШЕННЫЕ РАЗЛИЧНЫЕ Р.Педагог КАК Педагог ИЗ РегистрНакопления.УЗ_РасчетыПоЗарплате КАК Р "
        "ГДЕ Р.Период >= &Н", Н=ф.день(-2)))
    педагоги = {с.ид(движения.Получить(к).Педагог) for к in range(движения.Количество())} if движения is not None else set()
    т.проверить(педагоги == {ид["педагог_а"]}, "зарплата: видны только свои начисления", str(len(педагоги)))
    # страница «Моя зарплата» формы «Мои уроки» — ЗарплатаПедагога (форма вызывает её же на сервере)
    зп = с.шаг("страница «Моя зарплата» за три дня", lambda: мои.ЗарплатаПедагога(педагог, ф.день(-2), ф.день(0, 23, 59)))
    строки = [зп.Строки.Получить(к) for к in range(зп.Строки.Количество())] if зп is not None else []
    т.проверить(len(строки) == 1 and abs(float(строки[0].Начислено) - СТАВКА) < 0.01 and float(строки[0].Выплачено) == 0,
                "«Моя зарплата»: одна строка — урок А, начислено %d" % СТАВКА,
                "; ".join("%s %s/%s" % (с_.Документ, с_.Начислено, с_.Выплачено) for с_ in строки) or "строк нет")
    т.проверить(len(строки) == 1 and "Урок" in строки[0].Документ and "не найден" not in строки[0].Документ,
                "«Моя зарплата»: документ строки назван", строки[0].Документ if строки else "-")
    т.проверить(зп is not None and abs(float(зп.Начислено) - СТАВКА) < 0.01 and abs(float(зп.Остаток) - СТАВКА) < 0.01,
                "«Моя зарплата»: итог начислено и к оплате %d" % СТАВКА,
                "начислено %s, остаток %s" % (зп.Начислено, зп.Остаток) if зп is not None else "-")
    педагог_б = с.ссылка("Справочники", "УЗ_ФизЛица", ид["педагог_б"])
    чужая = с.шаг("«Моя зарплата» по педагогу Б", lambda: мои.ЗарплатаПедагога(педагог_б, ф.день(-2), ф.день(0, 23, 59)))
    т.проверить(чужая is not None and чужая.Строки.Количество() == 0 and float(чужая.Остаток) == 0,
                "«Моя зарплата» по педагогу Б пуста (ограничение роли)")
    т.проверить(not c.ПравоДоступа("Использование", c.Метаданные.Отчеты.УЗ_РасчетыПоЗарплате)
                and not c.ПравоДоступа("Просмотр", c.Метаданные.ОбщиеФормы.УЗ_ФормаОтчета),
                "отчёта «Расчёты по зарплате» и общей формы отчёта у педагога нет (СКД без «Просмотр» был бы пуст)")

    def записать_расчет():
        д = c.Документы.УЗ_РасчетЗарплаты.СоздатьДокумент()
        д.Дата = дата(ф.сегодня.year, ф.сегодня.month, ф.сегодня.day, 8)
        д.Комментарий = МЕТКА
        д.Записать(c.РежимЗаписиДокумента.Запись)
    с.запрещено("записать расчёт зарплаты", записать_расчет, "Документ.УЗ_РасчетЗарплаты")


