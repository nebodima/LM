"""Логика урока, часть 2: сценарии 11–19 из docs/логики/урок_и_списание.md §5 (числа — оттуда).

Хвост округления абонемента — на последнее занятие (В25: сумма уроков = цене абонемента); «Использовать округление»
— цена и скидка до рубля, сумма разностью; урок раньше начала не проводится (В10); пересечения педагога; абонемент
с одним занятием на две строки; приостановка (В4); знаки списания остатков — как у урока; урок без явок —
доп. расход есть, начисления «за занятие» нет (В6).

Красные на старом коде (28.09.2026, UZ_UNF_D до правки): №12 (333,33 × 3 = 999,99 — копейка терялась),
№13 (скидка 50 % к абонементу и округление каждого числа отдельно: 1 667 / 833 / 833).

    python tools\\тесты\\логика_урок_2.py --база=C:\\1c_bases\\UZ_UNF_D
"""
import datetime
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import дата, запустить  # noqa: E402
from фабрика import Фабрика  # noqa: E402
from _деньги import Данные  # noqa: E402
from логика_урок import деньги, движения, использовано, строка, перечитать  # noqa: E402

МЕТКА = "_Тест логика урока 2"


def сценарий(т):
    c = т.c
    ф = Фабрика(т, МЕТКА)
    педагог = ф.педагог()
    ученик = ф.ученик()
    за_8 = ф.элемент("УЗ_Тарифы", "8 000 за 8 уроков", Сумма=8000, КоличествоУроков=8)

    # 11. универсальный абонемент (без предмета) 6 400/8 — урок «Математика» 800 по нему
    математика = ф.элемент("УЗ_ПредметыОбучения", "математика")
    уни = ф.абонемент(ученик, "универсальный 6 400/8", КоличествоЗанятий=8, ЦенаАбонемента=6400)
    д = ф.урок(педагог, ф.день(-1, 8), 1, [строка(ученик, Тариф=за_8, Абонемент=уни)], ПредметОбучения=математика)
    ош, сооб = ф.записать(д)
    дв = движения(т, д)
    т.проверить(ош is None and len(дв) == 1 and дв[0]["Сумма"] == 800 and дв[0]["Абонемент"] and использовано(ф, уни) == 1,
                "11: абонемент без предмета оплачивает урок «Математика»: 800, занятие абонемента израсходовано",
                ош or сооб or дв)

    # 12. абонемент 1 000 / 3 — 333,33 + 333,33 + 333,34 = 1 000 (В25: хвост на последний урок)
    ученик3 = ф.ученик("ученик 1 000 за 3")
    аб3 = ф.абонемент(ученик3, "1 000 за 3", КоличествоЗанятий=3, ЦенаАбонемента=1000)
    суммы = []
    for час in (9, 10, 11):
        д = ф.урок(педагог, ф.день(-1, час), 1, [строка(ученик3, Тариф=за_8, Абонемент=аб3)])
        ош, сооб = ф.записать(д)
        суммы.append(деньги(д.Сумма) if ош is None else ош)
    т.проверить(суммы == [333.33, 333.33, 333.34] and round(sum(суммы), 2) == 1000,
                "12: три урока по абонементу 1 000/3 — 333,33 + 333,33 + 333,34 = 1 000 (было 999,99)", суммы)

    # 13. абонемент 5 000/3, скидка 50 %, «Использовать округление» — 1 667, скидки нет, цена = сумма + скидка
    н = c.РегистрыСведений.УЗ_Настройки.СоздатьМенеджерЗаписи()
    н.Прочитать()
    было = н.ИспользоватьОкругление

    def вернуть():
        в = c.РегистрыСведений.УЗ_Настройки.СоздатьМенеджерЗаписи()
        в.Прочитать()
        в.ИспользоватьОкругление = было
        в.Записать()
    т.убрать(вернуть, "настройка округления")
    н.ИспользоватьОкругление = True
    н.Записать()
    ученик5 = ф.ученик("ученик 5 000 за 3")
    аб5 = ф.абонемент(ученик5, "5 000 за 3", КоличествоЗанятий=3, ЦенаАбонемента=5000)
    пол = ф.элемент("УЗ_Скидки", "50 %", КоэффициентПроцент=50)
    за_3 = ф.элемент("УЗ_Тарифы", "1 000 за 3 урока", Сумма=1000, КоличествоУроков=3)
    д = ф.урок(педагог, ф.день(-1, 13), 1, [строка(ученик5, Тариф=за_8, Абонемент=аб5, Скидка=пол)])
    ф.записать(д)
    с = перечитать(д).Ученики.Получить(0)
    т.проверить((деньги(с.ЦенаТарифа), деньги(с.СуммаСкидки), деньги(с.Сумма)) == (1667, 0, 1667),
                "13: абонемент 5 000/3 со скидкой 50 % и округлением — цена 1 667, скидка 0, сумма 1 667 (было 1 667/833/833)",
                (с.ЦенаТарифа, с.СуммаСкидки, с.Сумма))
    # тариф с округлением: цена и скидка до рубля, сумма — разностью (цена = сумма + скидка)
    д = ф.урок(педагог, ф.день(-1, 14), 1, [строка(ученик5, Тариф=за_3, Скидка=пол)])
    ф.записать(д)
    с = перечитать(д).Ученики.Получить(0)
    т.проверить(деньги(с.ЦенаТарифа) == 333 and деньги(с.СуммаСкидки) == 167 and деньги(с.Сумма) == 166
                and деньги(с.ЦенаТарифа) == деньги(с.Сумма) + деньги(с.СуммаСкидки),
                "13: тариф 1 000/3 со скидкой 50 % и округлением — 333 = 166 + 167 (цена = сумма + скидка)",
                (с.ЦенаТарифа, с.СуммаСкидки, с.Сумма))
    вернуть()

    # 14. урок, который ещё не начался, — отказ (В10)
    через_час = datetime.datetime.now() + datetime.timedelta(hours=1)
    ош, сооб = ф.записать(ф.урок(педагог, дата(через_час.year, через_час.month, через_час.day, через_час.hour,
                                              через_час.minute), 1, [строка(ученик, Тариф=за_8)]))
    т.проверить(ош is not None and any("раньше начала" in с for с, _ in сооб), "14: урок через час провести нельзя (В10)",
                ош or сооб)

    # 15. урок педагога 9:00–9:40; урок 9:40 — стык, проводится; урок 9:39 — пересечение, отказ
    педагог2 = ф.педагог("педагог пересечений")
    ф.записать(ф.урок(педагог2, ф.день(-2, 9), 0.6667, [строка(ученик, Явка=True, СписатьОплату=False)]))
    ош, сооб = ф.записать(ф.урок(педагог2, ф.день(-2, 9, 40), 1, [строка(ученик, СписатьОплату=False)]))
    т.проверить(ош is None, "15: урок того же педагога 9:40 после 9:00–9:40 — стык, проводится", ош or сооб)
    ош, сооб = ф.записать(ф.урок(педагог2, ф.день(-3, 9), 0.6667, [строка(ученик, СписатьОплату=False)]))
    ош, сооб = ф.записать(ф.урок(педагог2, ф.день(-3, 9, 39), 1, [строка(ученик, СписатьОплату=False)]))
    т.проверить(ош is not None and any("занят" in с for с, _ in сооб), "15: урок 9:39 при уроке 9:00–9:40 — отказ «педагог занят»",
                ош or сооб)

    # 16. абонемент с одним занятием, две строки этого абонемента — отказ по второй
    ученик1 = ф.ученик("ученик одного занятия")
    аб1 = ф.абонемент(ученик1, "1 занятие", КоличествоЗанятий=1, ЦенаАбонемента=500)
    # В16 (решение владельца): вторая строка исчерпала абонемент — она по тарифу с предупреждением, не отказ
    д = ф.урок(педагог, ф.день(-2, 15), 1, [строка(ученик1, Абонемент=аб1, Тариф=за_8), строка(ученик1, Абонемент=аб1, Тариф=за_8)])
    ош, сооб = ф.записать(д)
    с1, с2 = перечитать(д).Ученики.Получить(0), перечитать(д).Ученики.Получить(1)
    т.проверить(ош is None and any(с.startswith("Строка 2") and "исчерпан" in с for с, _ in сооб)
                and (деньги(с1.Сумма), деньги(с2.Сумма)) == (500, 1000) and использовано(ф, аб1) == 1,
                "16: абонемент на 1 занятие в двух строках — первая по абонементу 500, вторая по тарифу 1 000 с предупреждением (В16)",
                ош or (сооб, с1.Сумма, с2.Сумма))

    # 17. приостановка 5 дней (с −20 по −15, срок до −5) — в день возобновления и в продлённый срок урок проводится
    ученик_п = ф.ученик("ученик с приостановкой")
    аб_п = ф.абонемент(ученик_п, "с приостановкой", КоличествоЗанятий=8, ЦенаАбонемента=8000, ДатаОкончания=ф.день(-5))
    о = аб_п.ПолучитьОбъект()
    п = о.Приостановки.Добавить()
    п.ДатаПриостановки = ф.день(-20)
    п.ДатаВозобновления = ф.день(-15)
    о.Записать()
    ош, сооб = ф.записать(ф.урок(педагог, ф.день(-17, 10), 1, [строка(ученик_п, Абонемент=аб_п)]))
    т.проверить(ош is not None and any("приостановлен" in с for с, _ in сооб), "17: урок во время приостановки — отказ",
                ош or сооб)
    ош, сооб = ф.записать(ф.урок(педагог, ф.день(-15, 10), 1, [строка(ученик_п, Абонемент=аб_п)]))
    т.проверить(ош is None, "17: урок в день возобновления — проводится (В4)", ош or сооб)
    ош, сооб = ф.записать(ф.урок(педагог, ф.день(-1, 16), 1, [строка(ученик_п, Абонемент=аб_п)]))
    т.проверить(ош is None, "17: урок после исходного срока, в продлённые 5 дней — проводится (В4)", ош or сооб)

    # 18. списание остатков: 1,5 ч, 1 урок, 1 явка — те же знаки, что у урока
    д_ = Данные(т, МЕТКА)
    сп = д_.документ("УЗ_СписаниеОстатков", Дата=ф.день(-1, 20))
    стр = сп.ТЗСписания.Добавить()
    стр.Ученик = ученик
    стр.КоличествоЧасов = 1.5
    стр.КоличествоУроков = 1
    стр.КоличествоЯвок = 1
    ош = д_.записать(сп)
    дв = движения(т, сп)
    т.проверить(ош is None and len(дв) == 1 and дв[0]["Расход"] and дв[0]["Часы"] == 5400 and дв[0]["Уроков"] == -1
                and дв[0]["Явок"] == -1 and not дв[0]["Абонемент"],
                "18: списание остатков 1,5 ч / 1 урок / 1 явка — Расход: Часы +5 400, КолУроков −1, Явок −1 (как урок)",
                ош or дв)

    # 19. робототехника: никто не пришёл, доп. расход «наборы» 2 000, ставка «за занятие» 500
    ставка = ф.элемент("УЗ_СтавкиПедагогов", "500 за занятие", ОплатаЗаЗанятие=500)
    статья = ф.элемент("УЗ_СтатьиДвиженияДенег", "наборы")
    д = ф.урок(педагог, ф.день(-2, 18), 1, [строка(ученик, Явка=False, СписатьОплату=False),
                                            строка(ученик3, Явка=False, СписатьОплату=False)], СтавкаПедагога=ставка)
    р = д.Расходы.Добавить()
    р.СтатьяЗатрат = статья
    р.Сумма = 2000
    ош, сооб = ф.записать(д)
    расходы = ф.число("""ВЫБРАТЬ ЕСТЬNULL(СУММА(Р.Сумма), 0) ИЗ РегистрНакопления.УЗ_Расходы КАК Р
        ГДЕ Р.Регистратор = &Р И Р.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Расход)""", Р=д.Ссылка)
    т.проверить(ош is None and движения(т, д) == [] and расходы == 2000 and деньги(д.НачисленоПедагогу) == 0,
                "19: никто не пришёл — движений ученикам нет, доп. расход 2 000, «за занятие» 0 (В6)",
                "%s дв %s расх %s нач %s" % (ош or сооб, движения(т, д), расходы, д.НачисленоПедагогу))


if __name__ == "__main__":
    запустить("логика_урок_2", сценарий)
