"""Мост в учёт программы, вкладка «Зарплата» закрытия смены (05.10.2026, docs/мост_в_учёт_хозяина.md, вариант
владельца «черновики бухгалтеру»; Бухгалтерия и УНФ).

Педагогу начислено 3 000 за месяц, выплачено 2 000 расходным ордером «Выплата зарплаты». Педагог не связан с
сотрудником — черновики не оформляются («свяжите на вкладке «Люди»»). Связали — «Начисление зарплаты» программы за
месяц со строкой 3 000 на сотрудника и «Ведомость в кассу» на 2 000, обе не проведены. Повтор ничего не делает.
Бухгалтер сменил вид начисления в черновике, у нас доначислили 500 — тот же черновик переписан на 3 500, вид начисления
бухгалтера сохранён. Бухгалтер провёл начисление (если программа проводит без приёма на работу), у нас ещё 100 —
черновик не трогаем, строка «проведено бухгалтером … сверка». Отменили наш ордер — ведомость помечена на удаление.
В Управлении торговлей зарплату не оформляем — понятная причина.

    python tools\\тесты\\тест_мост_зарплата.py --база=C:\\1c_bases\\UZ_BP_Q --пользователь=1
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from фабрика import Фабрика  # noqa: E402

МЕТКА = "_Тест мост зарплата"


def сценарий(т):
    c = т.c
    ф = Фабрика(т, МЕТКА)
    мост = c.УЗ_СредаМост
    виды = c.Перечисления.УЗ_ВидыОпераций

    def одно(первое, второе):
        return первое is not None and второе is not None and str(c.XMLString(первое)) == str(c.XMLString(второе))

    орг = c.РегистрыСведений.УЗ_Настройки.Настройки().Организация
    if орг.Пустая():
        орг = ф.организация("студия")
    начало, конец = ф.день(0), ф.день(0, 23, 59)
    if not мост.Возможности().Зарплата:
        итог = мост.ОформитьЗарплату(орг, начало, конец)
        т.проверить(итог.Ошибки.Количество() == 1 and "Бухгалтерия и УНФ" in str(итог.Ошибки.Получить(0).Текст),
                    "программа без зарплаты — понятная причина")
        return

    касса = ф.элемент("УЗ_Кассы", "касса моста зарплаты", Организация=орг)
    педагог = ф.педагог("Педагогова Зарплатная")
    ученик = ф.ученик("ученик моста зарплаты")
    ош, сообщ = ф.записать(ф.приход(ученик, 5000, Организация=орг, Касса=касса, Дата=ф.день(0, 8)))
    т.проверить(ош is None, "в кассе 5 000 на выплату", "%s %s" % (ош, сообщ))

    созданные = []                      # объекты программы — убрать в конце (документы, затем сотрудник и физлицо)

    def убрать_программу():
        for ссылка in reversed(созданные):
            т.удалить_объект(ссылка, загрузка=True)
    т.убрать(убрать_программу, "документы и сотрудник программы")
    наши = []

    def связи_убрать():
        for объект in [педагог] + наши:
            набор = c.РегистрыСведений.УЗ_СвязиСУчетомХозяина.СоздатьНаборЗаписей()
            набор.Отбор.Объект.Установить(объект)
            набор.Записать()
    т.убрать(связи_убрать, "связи моста")

    def начислить(сумма, час):
        н = c.Документы.УЗ_НачисленияПедагогам.СоздатьДокумент()
        н.Дата, н.Педагог, н.Организация, н.Комментарий = ф.день(0, час), педагог, орг, МЕТКА
        н.НачисленияПедагогам.Добавить().Сумма = сумма
        ош, сообщ = ф.записать(н)
        т.проверить(ош is None, "начислено педагогу %s" % сумма, "%s %s" % (ош, сообщ))

    начислить(3000, 9)
    расчёт = c.Документы.УЗ_РасчетЗарплаты.СоздатьДокумент()
    расчёт.Дата, расчёт.Педагог, расчёт.Касса, расчёт.Организация = ф.день(0, 10), педагог, касса, орг
    расчёт.ДатаНачала, расчёт.ДатаОкончания = ф.день(0), ф.день(0, 23, 59)
    расчёт.ЗаполнитьНачисления()
    ош, сообщ = ф.записать(расчёт)
    т.проверить(ош is None, "расчёт зарплаты проведён", "%s %s" % (ош, сообщ))
    ордер = c.Документы.УЗ_РасходДенег.СоздатьДокумент()
    ордер.Заполнить(расчёт.Ссылка)
    ордер.Дата, ордер.СуммаДокумента, ордер.Комментарий = ф.день(0, 11), 2000, МЕТКА
    ош, сообщ = ф.записать(ордер)
    т.проверить(ош is None and c.String(ордер.ВидОперации) == c.String(виды.ВыплатаЗарплаты),
                "выплачено педагогу 2 000", "%s %s" % (ош, сообщ))
    наши.append(ордер.Ссылка)

    def строки():
        таблица = мост.ЗарплатаДляОформления(орг, начало, конец)
        итог = {}
        for н in range(таблица.Количество()):
            с = таблица.Получить(н)
            if одно(с.Педагог, педагог):
                итог[str(с.Вид)] = с
        return итог

    def оформить():
        итог = мост.ОформитьЗарплату(орг, начало, конец)
        ошибки = [итог.Ошибки.Получить(н) for н in range(итог.Ошибки.Количество())]
        # в базе могут быть начисления других педагогов за этот день — их причины не наши
        return int(итог.Оформлено), [str(о.Текст) for о in ошибки
                                     if одно(о.Объект, педагог) or одно(о.Объект, ордер.Ссылка)]

    # ── педагог не связан с сотрудником ──
    сейчас = строки()
    т.проверить(set(сейчас) == {"Начисление", "Выплата"} and float(сейчас["Начисление"].Сумма) == 3000
                and float(сейчас["Выплата"].Сумма) == 2000 and not сейчас["Начисление"].МожноОформить
                and "не связан" in str(сейчас["Начисление"].Состояние),
                "начисление 3 000 и выплата 2 000 — педагог не связан, оформлять нельзя",
                {к: "%s %s" % (в.Сумма, в.Состояние) for к, в in сейчас.items()})
    оформлено, ошибки = оформить()
    т.проверить(оформлено == 0 and len(ошибки) == 2 and all("Люди" in о for о in ошибки),
                "без сотрудника — причина у обеих строк", "%s %s" % (оформлено, ошибки))

    # сотрудника принимает бухгалтер: заводим физлицо и сотрудника программы
    физлицо = c.Справочники.ФизическиеЛица.СоздатьЭлемент()
    физлицо.Наименование = "Педагогова Зарплатная" + МЕТКА
    физлицо.Записать()
    созданные.insert(0, физлицо.Ссылка)
    сотрудник = c.Справочники.Сотрудники.СоздатьЭлемент()
    сотрудник.Наименование = физлицо.Наименование
    сотрудник.ФизическоеЛицо = физлицо.Ссылка
    if c.Метаданные.Справочники.Сотрудники.Реквизиты.Найти("Физлицо") is not None:
        сотрудник.Физлицо = физлицо.Ссылка    # УНФ: «ФизическоеЛицо» перед записью берётся из «Физлицо»
    сотрудник.ГоловнаяОрганизация = орг
    сотрудник.Записать()
    созданные.insert(1, сотрудник.Ссылка)
    ошибка = мост.Связать(педагог, мост.РольПедагог(), сотрудник.Ссылка)
    т.проверить(str(ошибка) == "", "педагог связан с сотрудником", str(ошибка))

    оформлено, ошибки = оформить()
    т.проверить(оформлено == 2 and not ошибки, "два черновика: начисление и ведомость", "%s %s" % (оформлено, ошибки))
    сейчас = строки()
    начисление, ведомость = сейчас["Начисление"].ОбъектХозяина, сейчас["Выплата"].ОбъектХозяина
    for док in (начисление, ведомость):
        if док is not None:
            созданные.append(док)
    if начисление is None or ведомость is None:
        т.проверить(False, "черновики связаны со строками", {к: str(в.Состояние) for к, в in сейчас.items()})
        return
    т.проверить(not начисление.Проведен and начисление.Начисления.Количество() == 1
                and одно(начисление.Начисления.Получить(0).Сотрудник, сотрудник.Ссылка)
                and float(начисление.Начисления.Получить(0).Результат) == 3000
                and str(сейчас["Начисление"].Состояние) == "Черновик у бухгалтера",
                "«Начисление зарплаты» — черновик, строка 3 000 на сотрудника",
                "%s %s" % (начисление.Проведен, сейчас["Начисление"].Состояние))
    к_выплате = sum(float(ведомость.Зарплата.Получить(н).КВыплате) for н in range(ведомость.Зарплата.Количество()))
    т.проверить(not ведомость.Проведен and к_выплате == 2000 and str(сейчас["Выплата"].Состояние) == "Черновик у бухгалтера",
                "«Ведомость в кассу» — черновик на 2 000", "%s %s" % (ведомость.Проведен, к_выплате))

    оформлено, ошибки = оформить()
    т.проверить(оформлено == 0 and not ошибки, "повтор ничего не трогает", "%s %s" % (оформлено, ошибки))

    # бухгалтер сменил вид начисления в черновике; у нас доначислили 500
    запрос = c.NewObject("Запрос")
    запрос.Текст = ("ВЫБРАТЬ ПЕРВЫЕ 1 Т.Ссылка КАК Ссылка ИЗ ПланВидовРасчета.Начисления КАК Т "
                    "ГДЕ НЕ Т.ПометкаУдаления И Т.Ссылка <> &Был")
    запрос.УстановитьПараметр("Был", начисление.Начисления.Получить(0).Начисление)
    выборка = запрос.Выполнить().Выбрать()
    другой = выборка.Ссылка if выборка.Следующий() else None
    if другой is not None:
        черновик = начисление.ПолучитьОбъект()
        черновик.Начисления.Получить(0).Начисление = другой
        черновик.Записать(c.РежимЗаписиДокумента.Запись)
    начислить(500, 12)
    с = строки()["Начисление"]
    т.проверить(с.МожноОформить and "изменено" in str(с.Состояние).lower(), "доначисление — «изменено после оформления»",
                str(с.Состояние))
    оформить()
    с = строки()["Начисление"]
    стр = с.ОбъектХозяина.Начисления.Получить(0)
    т.проверить(одно(с.ОбъектХозяина, начисление) and float(стр.Результат) == 3500
                and (другой is None or одно(стр.Начисление, другой)) and not с.ОбъектХозяина.Проведен,
                "тот же черновик переписан на 3 500, вид начисления бухгалтера сохранён",
                "%s %s" % (стр.Результат, с.Состояние))

    # бухгалтер провёл начисление — дальше не трогаем, расхождение для сверки
    черновик = начисление.ПолучитьОбъект()
    try:
        черновик.Записать(c.РежимЗаписиДокумента.Проведение)
        проведено = True
    except Exception as е:
        проведено = False
        c.ПолучитьСообщенияПользователю(True)
        print("    (программа не проводит начисление без приёма на работу — шаг «проведено бухгалтером» пропущен: %s)"
              % str(е).splitlines()[-1][:120])
    if проведено:
        начислить(100, 13)
        оформлено, ошибки = оформить()
        с = строки()["Начисление"]
        т.проверить(оформлено == 0 and float(с.ОбъектХозяина.Начисления.Получить(0).Результат) == 3500
                    and not с.МожноОформить and "сверка" in str(с.Состояние),
                    "проведённое бухгалтером не переписывается — «сверка»", "%s %s" % (оформлено, с.Состояние))
        таблица = мост.Расхождения(орг, None, начало, конец)
        сверка = [(str(р.Расхождение), str(р.УНас), str(р.ВПрограмме))
                  for р in (таблица.Получить(н) for н in range(таблица.Количество())) if одно(р.Объект, педагог)]
        т.проверить(len(сверка) == 1 and сверка[0][0] == "Начислено" and "3 600" in сверка[0][1].replace("\xa0", " ")
                    and "3 500" in сверка[0][2].replace("\xa0", " "),
                    "сверка: начислено у нас 3 600, в программе 3 500", сверка)

    # наш ордер отменён — ведомость помечена на удаление, связь снята
    ош, сообщ = ф.записать(ордер, "ОтменаПроведения")
    т.проверить(ош is None, "выплата отменена", ош)
    оформить()
    т.проверить(ведомость.ПометкаУдаления and "Выплата" not in строки(),
                "отменённая выплата — ведомость помечена на удаление, строки нет", str(ведомость.ПометкаУдаления))


if __name__ == "__main__":
    запустить("мост_зарплата", сценарий)
