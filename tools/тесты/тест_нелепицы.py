"""Нелепые данные, которые всё равно однажды введут (образец — «Путевые листы», com_test_нелепицы).

Обычные тесты ходят по разумным числам, а покупатель — нет: оплата на сто миллионов (лишние нули), копейка,
абонемент «на 99 999 занятий», урок на сутки, группа в двести учеников, эмодзи и строка во всю длину в имени,
теме и комментарии. Ни одно из этих действий не должно ронять программу, молча округлять деньги или обрезать
их до другого числа. Правило: либо программа считает честно, либо говорит вслух, что не так (отказ с понятным
сообщением). Молчаливое искажение — дефект.

  ПКО: 99 999 999,99 (предел поля) доходит до кассы и баланса ученика копейка в копейку; второй такой же в ту же
       кассу — остаток кассы 199 999 999,98 (итоги регистра шире поля); копейка 0,01 — не ноль;
  абонемент на 150 000 000 (цена абонемента шире суммы прихода и урока) — отказ у поля «Цена абонемента»; цена
       тарифа 150 000 000 в истории цен — отказ (было: приход «на основании» и урок молча брали 99 999 999,99);
       абонемент ровно на предел — приход и урок берут его копейка в копейку;
  абонемент на 99 999 занятий: урок по нему стоит 0,06, а не 0 и не ошибка деления;
  урок на 30 часов по тарифу 1 000 за час — 30 000, окончание через 30 ч, в регистре 108 000 с;
  урок группы на 200 учеников: проводится, 200 строк в регистре, сумма 200 × 1 000, проведение ≤ 3 с;
  эмодзи и строки во всю длину: ученик с эмодзи в имени (50 знаков), тема урока и комментарий 255 знаков
       с эмодзи, назначение платежа 500 знаков — записываются без потерь, ПКО печатается; наименование абонемента
       по умолчанию (обрезка до 30 знаков) не режет эмодзи пополам.

    python tools\\тесты\\тест_нелепицы.py --база=C:\\1c_bases\\UZ_BP_E --пользователь=1
"""
import os
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from фабрика import Фабрика  # noqa: E402

МЕТКА = "УЗ тест нелепиц"
ПРЕДЕЛ = 99999999.99          # СуммаДокумента прихода, Сумма строки урока и регистров — Число(10, 2)

КАССА = ("ВЫБРАТЬ ЕСТЬNULL(СУММА(Р.СуммаОстаток), 0) "
         "ИЗ РегистрНакопления.УЗ_Касса.Остатки(, Касса = &Кто) КАК Р")
БАЛАНС = ("ВЫБРАТЬ ЕСТЬNULL(СУММА(Р.СуммаОстаток), 0) "
          "ИЗ РегистрНакопления.УЗ_СписанияСуммЗаУроки.Остатки(, Клиент = &Кто) КАК Р")
СТРОК_УРОКА = ("ВЫБРАТЬ КОЛИЧЕСТВО(*), ЕСТЬNULL(СУММА(Р.Сумма), 0), ЕСТЬNULL(СУММА(Р.Часы), 0) "
               "ИЗ РегистрНакопления.УЗ_СписанияСуммЗаУроки КАК Р ГДЕ Р.Регистратор = &Кто")


def половинка_эмодзи(строка):
    """Одиночная половинка суррогатной пары (эмодзи, разрезанный обрезкой строки 1С) — или None."""
    for поз, символ in enumerate(строка or ""):
        код = ord(символ)
        if 0xD800 <= код <= 0xDFFF:
            return "U+%04X в позиции %d" % (код, поз)
    return None


def обрезать(строка, длина):
    """Строка не длиннее длина знаков 1С (единиц UTF-16: эмодзи — два знака), без разрезанного эмодзи."""
    итог = ""
    for символ in строка:
        if len((итог + символ).encode("utf-16-le")) // 2 > длина:
            break
        итог += символ
    return итог


def сценарий(т):
    ф = Фабрика(т, МЕТКА)
    c = т.c

    def равно(что, факт, ожидаем):
        т.проверить(abs(float(факт) - ожидаем) < 0.005, "%s = %s" % (что, ожидаем), "факт %s" % факт)

    def строка_урока(урок):
        тз = ф.выбрать(СТРОК_УРОКА, Кто=урок.Ссылка)
        с = тз.Получить(0)
        return int(с.Получить(0)), float(с.Получить(1)), float(с.Получить(2))

    ученик = ф.ученик("крупный плательщик")
    касса = ф.элемент("УЗ_Кассы", "касса нелепиц")
    педагог = ф.педагог("педагог нелепиц")
    за_час = ф.элемент("УЗ_Тарифы", "1 000 за час", Сумма=1000, КоличествоЧасов=1)
    за_урок = ф.элемент("УЗ_Тарифы", "1 000 за урок", Сумма=1000, КоличествоУроков=1)

    # ── предел поля прихода доходит до кассы копейка в копейку ──
    пко = ф.приход(ученик, ПРЕДЕЛ, Касса=касса, Дата=ф.день(-2, 9))
    ошибка, сообщения = ф.записать(пко)
    т.проверить(ошибка is None, "ПКО на 99 999 999,99 проводится", (ошибка, сообщения))
    равно("касса после ПКО на предел поля", ф.число(КАССА, Кто=касса), ПРЕДЕЛ)
    равно("баланс ученика после ПКО на предел поля", ф.число(БАЛАНС, Кто=ученик), ПРЕДЕЛ)
    пко2 = ф.приход(ученик, ПРЕДЕЛ, Касса=касса, Дата=ф.день(-2, 9, 5))
    ошибка, сообщения = ф.записать(пко2)
    т.проверить(ошибка is None, "второй ПКО на 99 999 999,99 в ту же кассу проводится (итог шире поля)",
                (ошибка, сообщения))
    равно("остаток кассы 199 999 999,98 — итоги регистра не переполнились", ф.число(КАССА, Кто=касса), 2 * ПРЕДЕЛ)
    копейка = ф.приход(ученик, 0.01, Касса=касса, Дата=ф.день(-2, 9, 10))
    ошибка, сообщения = ф.записать(копейка)
    т.проверить(ошибка is None, "ПКО на одну копейку проводится", (ошибка, сообщения))
    равно("копейка дошла до кассы", ф.число(КАССА, Кто=касса), 2 * ПРЕДЕЛ + 0.01)

    # ── абонемент дороже поля прихода и урока: вслух, а не молча 99 999 999,99 ──
    # было (29.09.2026): цена абонемента Число(15,2), сумма прихода и строки урока — Число(10,2); абонемент за
    # 150 000 000 записывался, а приход «на основании» и урок по нему молча брали 99 999 999,99
    об = c.Справочники.УЗ_Абонемент.СоздатьЭлемент()
    for к, в in dict(Наименование=МЕТКА + " 150 млн", ФизЛицо=ученик, Активный=True, ДатаНачала=ф.день(-30),
                     ДатаАктивации=ф.день(-30), КоличествоЗанятий=1, ЦенаАбонемента=150000000).items():
        setattr(об, к, в)
    c.ПолучитьСообщенияПользователю(True)
    try:
        об.Записать()
        ошибка = None
    except Exception as е:
        ошибка = str(е)
    сообщения = [(str(м.Текст), str(м.Поле or "")) for м in c.ПолучитьСообщенияПользователю(True)]
    if ошибка is None:
        ссылка150 = об.Ссылка
        т.убрать(lambda: т.удалить_объект(ссылка150), "абонемент 150 млн", пакет=True)
    т.проверить(ошибка is not None and any(п == "ЦенаАбонемента" and "99 999 999,99" in м for м, п in [(м.replace("\xa0", " "), п) for м, п in сообщения]),
                "абонемент за 150 000 000 — отказ у поля «Цена абонемента» с пределом 99 999 999,99",
                "ошибка %s, сообщения %s" % (ошибка, сообщения))
    набор = c.РегистрыСведений.УЗ_ЦеныТарифов.СоздатьНаборЗаписей()
    набор.Отбор.Тариф.Установить(за_урок)
    набор.Отбор.Период.Установить(ф.день(-40))
    з = набор.Добавить()
    з.Период, з.Тариф, з.Сумма, з.КоличествоУроков = ф.день(-40), за_урок, 150000000, 1
    c.ПолучитьСообщенияПользователю(True)
    try:
        набор.Записать()
        ошибка = None
        т.убрать(lambda: (набор.Очистить(), набор.Записать()), "цена тарифа 150 млн")
    except Exception as е:
        ошибка = str(е)
    сообщения = [str(м.Текст) for м in c.ПолучитьСообщенияПользователю(True)]
    т.проверить(ошибка is not None and any("99 999 999,99" in м.replace("\xa0", " ") for м in сообщения),
                "цена тарифа 150 000 000 в истории цен — отказ с пределом", "ошибка %s, сообщения %s" % (ошибка, сообщения))
    # абонемент ровно на предел — приход «на основании» и урок берут его копейка в копейку
    предельный = ф.абонемент(ученик, "на предел", КоличествоЗанятий=1, ЦенаАбонемента=ПРЕДЕЛ)
    основание = c.Документы.УЗ_ПриходДенег.СоздатьДокумент()
    основание.Дата = ф.день(-2, 10)
    основание.Заполнить(предельный)
    основание.Касса = касса
    основание.Комментарий = МЕТКА
    равно("приход на основании абонемента на предел", основание.СуммаДокумента, ПРЕДЕЛ)
    ошибка, сообщения = ф.записать(основание)
    т.проверить(ошибка is None, "приход на основании абонемента на предел проводится", (ошибка, сообщения))
    урок = ф.урок(педагог, ф.день(-1, 8), 1, [dict(Ученик=ученик, Абонемент=предельный, Тариф=за_урок, Явка=True,
                                                  СписатьОплату=True)])
    ошибка, сообщения = ф.записать(урок)
    т.проверить(ошибка is None, "урок по абонементу на предел проводится", (ошибка, сообщения))
    if ошибка is None:
        равно("урок по абонементу на предел — списан весь предел", строка_урока(урок)[1], ПРЕДЕЛ)

    # ── абонемент на 99 999 занятий: цена урока не ноль и не ошибка ──
    долгий = ф.абонемент(ученик, "99 999 занятий", КоличествоЗанятий=99999, ЦенаАбонемента=6400)
    урок = ф.урок(педагог, ф.день(-1, 10), 1, [dict(Ученик=ученик, Абонемент=долгий, Тариф=за_урок, Явка=True,
                                                   СписатьОплату=True)])
    ошибка, сообщения = ф.записать(урок)
    т.проверить(ошибка is None, "урок по абонементу на 99 999 занятий проводится", (ошибка, сообщения))
    if ошибка is None:
        равно("урок по абонементу 6 400 / 99 999 занятий стоит 0,06", урок.Ученики.Получить(0).Сумма, 0.06)

    # ── урок на 30 часов: всё посчитано, ничего не обрезано ──
    сутки = ф.урок(педагог, ф.день(-5, 1), 30, [dict(Ученик=ученик, Тариф=за_час, Явка=True, СписатьОплату=True)])
    ошибка, сообщения = ф.записать(сутки)
    т.проверить(ошибка is None, "урок на 30 часов проводится (или честный отказ)", (ошибка, сообщения))
    if ошибка is None:
        о = сутки.Ссылка.ПолучитьОбъект()
        длительность = (о.Окончание - о.Дата).total_seconds()
        т.проверить(abs(длительность - 30 * 3600) < 1, "окончание урока на 30 часов — через 30 ч", длительность)
        строк, сумма, секунд = строка_урока(сутки)
        т.проверить(abs(сумма - 30000) < 0.005 and abs(секунд - 108000) < 1,
                    "урок на 30 часов по 1 000 за час: 30 000 и 108 000 с в регистре", (сумма, секунд))

    # ── группа в 200 учеников ──
    with т.транзакция():
        толпа = [ф.ученик("ученик %03d" % н) for н in range(200)]
    большой = ф.урок(педагог, ф.день(-1, 12), 1,
                     [dict(Ученик=у, Тариф=за_урок, Явка=True, СписатьОплату=True) for у in толпа])
    н = time.time()
    ошибка, сообщения = ф.записать(большой)
    сек = time.time() - н
    т.проверить(ошибка is None, "урок на 200 учеников проводится", (ошибка, сообщения[:3]))
    if ошибка is None:
        строк, сумма, _ = строка_урока(большой)
        т.проверить(строк == 200 and abs(сумма - 200000) < 0.005,
                    "урок на 200 учеников: 200 строк в регистре на 200 000", (строк, сумма))
        равно("сумма урока на 200 учеников", большой.Ссылка.ПолучитьОбъект().Сумма, 200000)
        т.проверить(сек <= 3, "проведение урока на 200 учеников ≤ 3 с", "%.1f с" % сек)

    # ── эмодзи и строки во всю длину ──
    имя = "Анна Иванова 🎹 Ля-Минорная Скрипичная-Басовая"   # эмодзи на границе обрезки наименования абонемента
    имя = обрезать(имя + " Длинновская", 50)
    комментарий = обрезать("Комментарий 🎸🥁 " * 20, 255)
    певица = c.Справочники.УЗ_ФизЛица.СоздатьЭлемент()
    певица.Наименование = имя
    певица.Комментарий = комментарий
    певица.Записать()
    ссылка = певица.Ссылка
    т.убрать(lambda: т.удалить_объект(ссылка), "ученица с эмодзи", пакет=True)
    о = ссылка.ПолучитьОбъект()
    т.проверить(о.Наименование == имя and о.Комментарий == комментарий,
                "имя и комментарий с эмодзи во всю длину записаны без потерь", (о.Наименование, len(о.Комментарий)))
    об = c.Справочники.УЗ_Абонемент.СоздатьЭлемент()   # наименование пустое — продукт составит его сам
    for к, в in dict(ФизЛицо=ссылка, Активный=True, ДатаНачала=ф.день(-30), ДатаАктивации=ф.день(-30),
                     ДатаОкончания=ф.день(60), КоличествоЗанятий=8, ЦенаАбонемента=8000).items():
        setattr(об, к, в)
    об.Записать()
    абонемент = об.Ссылка
    т.убрать(lambda: т.удалить_объект(абонемент), "абонемент ученицы с эмодзи", пакет=True)
    наименование = абонемент.Наименование
    т.проверить(половинка_эмодзи(наименование) is None,
                "наименование абонемента по умолчанию не режет эмодзи пополам", "%r: %s"
                % (наименование, половинка_эмодзи(наименование)))
    тема = обрезать("Гаммы 🎼 и арпеджио 🎶 " * 20, 255)
    урок = ф.урок(педагог, ф.день(-1, 14), 1, [dict(Ученик=ссылка, Абонемент=абонемент, Тариф=за_урок, Явка=True,
                                                   СписатьОплату=True, Заметка=тема)], ТемаУрока=тема)
    урок.Комментарий = тема
    ошибка, сообщения = ф.записать(урок)
    т.проверить(ошибка is None, "урок с эмодзи в теме, заметке и комментарии проводится", (ошибка, сообщения))
    if ошибка is None:
        о = урок.Ссылка.ПолучитьОбъект()
        т.проверить(о.ТемаУрока == тема and о.Ученики.Получить(0).Заметка == тема,
                    "тема урока и заметка с эмодзи (255 знаков) записаны без потерь", len(о.ТемаУрока))
    назначение = обрезать("Оплата за Анну 🎹, " * 40, 500)
    пко = ф.приход(ссылка, 8000, Касса=касса, Абонемент=абонемент, Дата=ф.день(-2, 11), НазначениеПлатежа=назначение)
    ошибка, сообщения = ф.записать(пко)
    т.проверить(ошибка is None, "ПКО ученицы с эмодзи в имени и назначении 500 знаков проводится",
                (ошибка, сообщения))
    if ошибка is None:
        т.проверить(пко.Ссылка.ПолучитьОбъект().НазначениеПлатежа == назначение,
                    "назначение платежа 500 знаков с эмодзи записано без потерь")
        try:
            р = c.УЗ_Печать.СформироватьСвоейПечатью("Документ.УЗ_ПриходДенег", "ПКО", пко.Ссылка)
            т.проверить(р.ПечатныхФорм == 1 and р.ТабличныйДокумент.ВысотаТаблицы > 0,
                        "ПКО ученицы с эмодзи печатается", р.ПечатныхФорм)
        except Exception as е:
            т.проверить(False, "ПКО ученицы с эмодзи печатается", str(е)[:200])


if __name__ == "__main__":
    запустить("нелепицы", сценарий)
