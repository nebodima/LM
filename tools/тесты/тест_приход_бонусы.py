"""Приход денег: списание бонусов дисконтной карты (аудит 28.09: учёт №11–12, Codex A09–A10, ревьюер-1 №4, №9).

Было: у карты без движений запрос остатков не возвращал строки, функция отдавала Неопределено и проверка
«хватает ли бонусов» пропускалась — ПКО зачислял ученику деньги из ничего, карта уходила в минус.
Срок карты: урок начислял бонусы в последний день действия, ПКО в этот же день уже отказывал.
Стало: нет остатка = 0 → отказ; срок карты одинаков в уроке и ПКО (действует по день окончания
включительно, с даты начала, флаг «Не действует» — не действует); остаток карты читается под
исключительной управляемой блокировкой (на файловой базе не краснеет — см. тест_урок_абонемент.py).

    python tools\\тесты\\тест_приход_бонусы.py --база=C:\\1c_bases\\UZ_UNF_B
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from фабрика import Фабрика  # noqa: E402

МЕТКА = "УЗ тест бонусов"
ОСТАТОК_КАРТЫ = ("ВЫБРАТЬ ЕСТЬNULL(СУММА(Р.СуммаБонусовОстаток), 0) "
                 "ИЗ РегистрНакопления.УЗ_ДвижениеДисконтныхКарт.Остатки(, ДисконтнаяКарта = &Карта) КАК Р")


def сценарий(т):
    ф = Фабрика(т, МЕТКА)
    c = т.c
    ученик = ф.ученик()
    педагог = ф.педагог()
    минута = [0]

    def начислить(карта, бонусов, сдвиг=0):
        """Урок с начислением бонусов на карту (Приход в УЗ_ДвижениеДисконтныхКарт). Уроки «сегодня» — с 00:00
        по минуте (провести раньше начала нельзя, В10), длиной 0,01 ч — не пересекаются у одного педагога."""
        минута[0] += 1
        д = ф.урок(педагог, ф.день(сдвиг, 0, минута[0]), 0.01,
                   [dict(Ученик=ученик, Явка=True, ДисконтнаяКарта=карта, СуммаБонусов=бонусов)])
        return ф.записать(д, "Проведение")

    def списать(карта, бонусов, сдвиг=0):
        д = ф.приход(ученик, 0, ДисконтнаяКарта=карта, СуммаБонусов=бонусов, Дата=ф.день(сдвиг, 0, 30))
        return ф.записать(д, "Проведение")

    def остаток(карта):
        return ф.число(ОСТАТОК_КАРТЫ, Карта=карта)

    def проведён(итог, что):
        т.проверить(итог[0] is None, что, "%s %s" % итог)

    def отказ(итог, что, слово):
        ошибка, сообщения = итог
        т.проверить(ошибка is not None and any(слово in текст for текст, _ in сообщения), что,
                    "ошибка: %s, сообщения: %s" % (ошибка, сообщения))

    # ── пустая карта ──
    пустая = ф.карта(ученик, "новая")
    отказ(списать(пустая, 500), "новая карта без начислений: списать 500 бонусов — отказ", "Недостаточно бонусов")
    т.проверить(остаток(пустая) == 0, "на новой карте остаток 0 (не минус)", остаток(пустая))

    # ── остаток 300 ──
    карта = ф.карта(ученик, "300 бонусов")
    проведён(начислить(карта, 300), "урок начислил 300 бонусов")
    отказ(списать(карта, 500), "на карте 300: списать 500 — отказ", "Недостаточно бонусов")
    проведён(списать(карта, 300), "на карте 300: списать 300 — проводится")
    т.проверить(остаток(карта) == 0, "после списания 300 остаток карты 0", остаток(карта))
    отказ(списать(карта, 1), "на карте 0 (после списаний): списать 1 — отказ", "Недостаточно бонусов")

    # ── срок: последний день действия — одинаково в уроке и ПКО ──
    сегодня = ф.карта(ученик, "действует по сегодня", ДатаОкончанияДействия=ф.день(0))
    проведён(начислить(сегодня, 100), "карта «по сегодня»: урок сегодня начисляет бонусы")
    проведён(списать(сегодня, 100), "карта «по сегодня»: ПКО сегодня списывает бонусы (как и урок)")

    вчера = ф.карта(ученик, "действовала по вчера", ДатаОкончанияДействия=ф.день(-1))
    проведён(начислить(вчера, 100, -1), "карта «по вчера»: урок вчера начисляет бонусы")
    отказ(начислить(вчера, 100), "карта «по вчера»: урок сегодня — отказ", "срок действия")
    отказ(списать(вчера, 100), "карта «по вчера»: ПКО сегодня — отказ", "срок действия")

    завтра = ф.карта(ученик, "с завтра", ДатаНачалаДействия=ф.день(1))
    отказ(начислить(завтра, 100), "карта «с завтра»: урок сегодня — отказ", "срок действия")

    выключена = ф.карта(ученик, "выключенная", НеДействует=True)
    отказ(начислить(выключена, 100), "карта «Не действует»: урок — отказ", "не действует")


if __name__ == "__main__":
    запустить("приход_бонусы", сценарий)
