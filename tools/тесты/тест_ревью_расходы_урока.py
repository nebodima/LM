"""Регистр расходов менеджеру (29.09.2026, продолжение R24): урок менеджера пишет свои расходы, но прочитать расходы
студии менеджер не может. Живой COM-сеанс менеджера (УЗ_ОсновнаяРоль + роли хозяина рядового сотрудника, как в
тест_права.py).

Было: у роли менеджера на регистр УЗ_Расходы одно «Изменение» (для движений вкладки «Доп. расходы» урока) —
платформа считает его и «Чтением» без ограничений: запрос менеджера читал все расходы студии, в том числе прочие
расходы руководителя (аренда, материалы). Как у регистра расчётов с педагогами (R24) — «Чтение» с условием
«ГДЕ ЛОЖЬ». «Движения документа» показывали менеджеру и расходы урока руководителя; теперь регистр отсекает
ПравоДоступа («Чтение» «ГДЕ ЛОЖЬ» платформа считает отсутствием права — как у регистра расчётов с педагогами), а
регистр с другим условием чтения — РАЗРЕШЕННЫЕ в запросах отчёта (без него запрос упал бы «Недостаточно прав»).
На коде до 29.09.2026 (uz-ext 0f17a7e3, UZ_BP_E): 3 ошибки — запрос прошёл, РАЗРЕШЕННЫЕ 3 строки, в «Движениях
документа» регистр «Расходы» и 347.
Проверки под менеджером:
  * урок менеджера с вкладкой «Доп. расходы» 213 проводится — движение 213 в регистре расходов (под
    администратором);
  * регистр расходов запросом — отказ по журналу (было: читались расходы урока руководителя 347 и прочие 719);
    с РАЗРЕШЕННЫЕ — 0 строк;
  * «Движения документа» урока руководителя (серверный код формы на стенде, как в тест_права) — формируются:
    регистр «Оплаты и часы» есть, «Расходы» и «Расчеты по зарплате» — нет, суммы 347 нет;
  * перепроведение урока руководителя (тема) — его расходы 347 на месте (под администратором).

    python tools\\тесты\\тест_ревью_расходы_урока.py --база=C:\\1c_bases\\UZ_BP_E --пользователь=1
    python tools\\прогон.py --база=C:\\1c_bases\\UZ_BP_E --пользователь=1 --тест=ревью_расходы_урока
"""
# затрагивает: УЗ_ДвиженияДокумента
import os
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from фабрика import Фабрика  # noqa: E402
import стенд_форм  # noqa: E402
from тест_права import (ОБЩИЕ_РОЛИ, РОЛИ_ХОЗЯИНА, ТОЛЬКО_ДЛЯ_ТЕСТА, Сотрудник, завести_пользователя,  # noqa: E402
                        удалить_пользователя)

МЕНЕДЖЕР = "УЗ тест менеджер расходы"
МЕТКА = "_Тест расходы урока"
РАСХОД_РУКОВОДИТЕЛЯ = 347      # вкладка «Доп. расходы» урока руководителя
ПРОЧИЙ = 719                   # «Доп. расходы» руководителя не по уроку
РАСХОД_МЕНЕДЖЕРА = 213         # вкладка «Доп. расходы» урока менеджера


def роли(c):
    return ОБЩИЕ_РОЛИ + РОЛИ_ХОЗЯИНА[c.Метаданные.Имя] + ["УЗ_ОсновнаяРоль"] + ТОЛЬКО_ДЛЯ_ТЕСТА


def расходы(т, регистратор):
    """Под администратором: сумма движений регистратора в регистре расходов."""
    return float(т.выбрать(
        "ВЫБРАТЬ ЕСТЬNULL(СУММА(Р.Сумма), 0) КАК Сумма ИЗ РегистрНакопления.УЗ_Расходы КАК Р ГДЕ Р.Регистратор = &Р",
        Р=регистратор).Получить(0).Сумма)


def сценарий(т):
    c = т.c
    удалить_пользователя(т, МЕНЕДЖЕР)
    н = time.time()
    завести_пользователя(т, МЕНЕДЖЕР, роли(c))
    т.вне_бюджета += time.time() - н
    т.убрать(lambda: удалить_пользователя(т, МЕНЕДЖЕР), "пользователь ИБ менеджера")

    ф = Фабрика(т, МЕТКА)
    ставка = ф.элемент("УЗ_СтавкиПедагогов", "500 за занятие", ОплатаЗаЗанятие=500)
    педагог = ф.педагог("педагог", СтавкаПедагога=ставка)
    ученик = ф.ученик()
    тариф = ф.элемент("УЗ_Тарифы", "тариф")
    ф.цена_тарифа(тариф, ф.день(-400), 800, уроков=1)
    статья = ф.элемент("УЗ_СтатьиДвиженияДенег", "материалы")
    строка = dict(Ученик=ученик, Тариф=тариф, Явка=True, СписатьОплату=True)

    # урок руководителя (здесь — администратор) с расходами 347 во вкладке и прочие «Доп. расходы» 719
    урок_р = ф.урок(педагог, ф.день(-1, 9), 1, [строка], СтавкаПедагога=ставка)
    р = урок_р.Расходы.Добавить()
    р.СтатьяЗатрат = статья
    р.Сумма = РАСХОД_РУКОВОДИТЕЛЯ
    ош, сооб = ф.записать(урок_р)
    прочий = c.Документы.УЗ_ДополнительныеРасходы.СоздатьДокумент()
    прочий.Дата = ф.день(-1, 10)
    прочий.Комментарий = МЕТКА
    р = прочий.Расходы.Добавить()
    р.СтатьяЗатрат = статья
    р.Сумма = ПРОЧИЙ
    ош2, сооб2 = ф.записать(прочий)
    т.проверить(ош is None and ош2 is None and расходы(т, урок_р.Ссылка) == РАСХОД_РУКОВОДИТЕЛЯ
                and расходы(т, прочий.Ссылка) == ПРОЧИЙ,
                "заготовка: урок руководителя с расходами 347 и прочие «Доп. расходы» 719 в регистре расходов",
                ош or ош2 or сооб or сооб2)

    ид = {"педагог": педагог, "ученик": ученик, "тариф": тариф, "статья": статья, "урок_р": урок_р.Ссылка}
    ид = {к: c.String(в.УникальныйИдентификатор()) for к, в in ид.items()}
    уроки = []
    с = Сотрудник(т, МЕНЕДЖЕР, "менеджер")
    try:
        день_менеджера(т, ф, с, ид, уроки)
    finally:
        с.закрыть()
    for ид_урока in уроки:   # уроки менеджера — уборка под администратором (с движениями)
        ссылка = c.Документы.УЗ_Урок.ПолучитьСсылку(c.NewObject("УникальныйИдентификатор", ид_урока))
        т.убрать(lambda ссылка=ссылка: т.удалить_объект(ссылка, загрузка=True), "урок менеджера")

    т.проверить(расходы(т, урок_р.Ссылка) == РАСХОД_РУКОВОДИТЕЛЯ,
                "после менеджера: расходы урока руководителя 347 на месте", расходы(т, урок_р.Ссылка))


def день_менеджера(т, ф, с, ид, уроки):
    c = т.c
    м = с.c

    def ссылка(коллекция, вид, ключ):
        return с.ссылка(коллекция, вид, ид[ключ])
    урок_р = ссылка("Документы", "УЗ_Урок", "урок_р")

    def запрос(текст, **параметры):
        з = м.NewObject("Запрос")
        з.Текст = текст
        for к, в in параметры.items():
            з.УстановитьПараметр(к, в)
        return з.Выполнить().Выгрузить()

    # ── урок менеджера с расходами проводится: движения пишутся ──
    def свой_урок():
        д = м.Документы.УЗ_Урок.СоздатьДокумент()
        д.Дата = ф.день(-1, 11)
        д.Педагог = ссылка("Справочники", "УЗ_ФизЛица", "педагог")
        д.КоличествоЧасов = 1
        д.Комментарий = МЕТКА
        с_ = д.Ученики.Добавить()
        с_.Ученик = ссылка("Справочники", "УЗ_ФизЛица", "ученик")
        с_.Тариф = ссылка("Справочники", "УЗ_Тарифы", "тариф")
        с_.Явка = True
        с_.СписатьОплату = True
        р = д.Расходы.Добавить()
        р.СтатьяЗатрат = ссылка("Справочники", "УЗ_СтатьиДвиженияДенег", "статья")
        р.Сумма = РАСХОД_МЕНЕДЖЕРА
        д.Записать(м.РежимЗаписиДокумента.Проведение)
        уроки.append(с.ид(д.Ссылка))
        return с.ид(д.Ссылка)
    ид_урока = с.шаг("проводит свой урок с вкладкой «Доп. расходы» 213", свой_урок)
    if ид_урока is not None:
        свой = c.Документы.УЗ_Урок.ПолучитьСсылку(c.NewObject("УникальныйИдентификатор", ид_урока))
        т.проверить(расходы(т, свой) == РАСХОД_МЕНЕДЖЕРА,
                    "урок менеджера: движение 213 в регистре расходов (пишет, не читая)", расходы(т, свой))

    # ── прочитать расходы студии нельзя ──
    с.запрещено("прочитать регистр расходов запросом (УЗ_Расходы: урок руководителя 347, прочие 719)",
                lambda: запрос("ВЫБРАТЬ Р.Регистратор КАК Регистратор, Р.Сумма КАК Сумма "
                               "ИЗ РегистрНакопления.УЗ_Расходы КАК Р ГДЕ Р.Период >= &С", С=ф.день(-2)),
                "РегистрНакопления.УЗ_Расходы")
    строк = с.шаг("ищет расходы запросом (РАЗРЕШЕННЫЕ)", lambda: запрос(
        "ВЫБРАТЬ РАЗРЕШЕННЫЕ Р.Сумма КАК Сумма ИЗ РегистрНакопления.УЗ_Расходы КАК Р ГДЕ Р.Период >= &С",
        С=ф.день(-2)).Количество())
    т.проверить(строк == 0, "менеджер: расходы студии не видны (РАЗРЕШЕННЫЕ — 0 строк)", строк)

    # ── «Движения документа» урока: формируются без регистров, которые менеджеру не видны ──
    def движения():
        н = time.time()
        об, сборка = стенд_форм.создать(м, "УЗ_ДвиженияДокумента", "ДвиженияДокумента", безопасный=True)
        т.вне_бюджета += сборка
        if сборка:
            print("  (стенд УЗ_ДвиженияДокумента собран за %.1f с — вне бюджета)" % (time.time() - н))
        об.Параметры.Вставить("Документ", урок_р)
        об.ПриСозданииНаСервере(False, True)
        return об.ТабличныйДокумент
    тд = с.шаг("открывает «Движения документа» урока руководителя (стенд формы)", движения)
    if тд is not None:
        есть = {что: т.найти_текст(тд, что) for что in ('"Оплаты и часы"', '"Расходы"', '"Расчеты по зарплате"',
                                                          str(РАСХОД_РУКОВОДИТЕЛЯ))}
        т.проверить(есть['"Оплаты и часы"'] and not any(в for к, в in есть.items() if к != '"Оплаты и часы"'),
                    "менеджер: в «Движениях документа» урока — «Оплаты и часы», без «Расходы», «Расчеты по "
                    "зарплате» и суммы 347", есть)

    # ── обычная работа с уроком руководителя: тема, перепроведение — расходы на месте ──
    def тема():
        о_ = урок_р.ПолучитьОбъект()
        о_.ТемаУрока = "Интервалы"
        о_.Записать(м.РежимЗаписиДокумента.Проведение)
    с.шаг("меняет тему урока руководителя и перепроводит его", тема)


if __name__ == "__main__":
    запустить("ревью_расходы_урока", сценарий)
