"""Аудит Codex версии 2.1 (docs/аудит_codex_2.1_2026-09-30.md), справка об оплате обучения — находки 2, 3, 4.

2. Одни расходы не подтверждаются двумя справками супругам: справки налогоплательщика и супруга («Учесть оплаты
   супруга») за обучающегося в организации за год вместе — не больше внесённого минус возвращено ими обоими (с учётом
   последней корректировки каждой справки, аннулированные не считаются): мама 2 500, затем папа с оплатами мамы
   2 500 — отказ (было: обе записаны, подтверждено 5 000 при расходах 2 500); 1 500 + 1 000 — можно.
3. Выданная (напечатанная) справка не переписывается: печать фиксирует выдачу, после неё номер, корректировку, год,
   лица, сумму и прочее, что печатается, изменить нельзя (было: № 1 / 0 / 2 500 после «По оплатам» печатался
   № 1 / 0 / 2 200 — две разные бумаги с одним номером); комментарий — можно; пометка удаления — нельзя. Исправление —
   корректирующей справкой: № 1 / корректировка 1 со ссылкой на исходную.
4. Корректирующая и аннулирующая справки — только к выданной первичной (ссылка «Исходная справка»): номер справки —
   её, организация, год и лица — те же; новый номер получает только первичная (было: новая справка с корректировкой 1
   или 999 без первичной получала номер и печаталась, 999 — даже при нуле оплат).

    python tools\\тесты\\тест_codex_21_справка.py --база=C:\\1c_bases\\UZ_BP_K --пользователь=1
"""
# затрагивает: УЗ_СправкаОбОплатеОбучения, УЗ_РеквизитыОрганизаций, УЗ_ДокументыФизЛиц, УЗ_Печать, УЗ_Касса
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import дата, запустить  # noqa: E402
from _деньги import Данные  # noqa: E402
from фабрика import Фабрика  # noqa: E402
from тест_справка_вычет import инн  # noqa: E402

МЕТКА = "_Тест Codex 2.1 справка"


def сценарий(т):
    c = т.c
    ф = Фабрика(т, МЕТКА)
    д_ = Данные(т, МЕТКА)
    ст = c.String
    год = ф.сегодня.year
    справки = c.Документы.УЗ_СправкаОбОплатеОбучения

    о = c.Справочники.Организации.СоздатьЭлемент()
    о.Наименование = "%s ООО" % МЕТКА
    о.ИНН, о.КПП = инн("770100777"), "772501001"
    о.ОбменДанными.Загрузка = True
    о.Записать()
    орг = о.Ссылка
    т.убрать(lambda: т.удалить_объект(орг, загрузка=True), "организация", пакет=True)
    з = c.РегистрыСведений.УЗ_РеквизитыОрганизаций.СоздатьМенеджерЗаписи()
    з.Организация, з.НомерЛицензии, з.ДатаЛицензии = орг, "Л035-01234-77/00999999", дата(2021, 3, 1)
    з.Ответственный = "Сидорова Анна Петровна"
    з.Записать()

    def убрать_реквизиты():
        н = c.РегистрыСведений.УЗ_РеквизитыОрганизаций.СоздатьНаборЗаписей()
        н.Отбор.Организация.Установить(орг)
        н.Записать()
    т.убрать(убрать_реквизиты, "реквизиты организации", пакет=True)

    def человек(имя, цифры=None, плательщики=()):
        о = c.Справочники.УЗ_ФизЛица.СоздатьЭлемент()
        о.Наименование = "%s %s" % (МЕТКА, имя)
        for кто, кем in плательщики:
            с = о.Плательщики.Добавить()
            с.Плательщик, с.КемПриходится = кто, кем
        о.Записать()
        ссылка = о.Ссылка

        def убрать():
            н = c.РегистрыСведений.УЗ_ДокументыФизЛиц.СоздатьНаборЗаписей()
            н.Отбор.ФизЛицо.Установить(ссылка)
            н.Записать()
            т.удалить_объект(ссылка)
        т.убрать(убрать, "физ. лицо %s" % имя, пакет=True)
        if цифры:
            данные = c.РегистрыСведений.УЗ_ДокументыФизЛиц.НовыеДанныеФизЛица()
            данные.ИНН = инн(цифры)
            c.РегистрыСведений.УЗ_ДокументыФизЛиц.ЗаписатьДанныеФизЛица(ссылка, данные)
        return ссылка

    мама = человек("мама", "5001007711")
    папа = человек("папа", "5001007722")
    бабушка = человек("бабушка", "5001007733")
    сын = человек("сын", плательщики=[(мама, "мама"), (папа, "папа"), (бабушка, "бабушка")])
    другой = человек("другой ученик", плательщики=[(мама, "мама")])
    касса = ф.элемент("УЗ_Кассы", "касса", Организация=орг)
    предмет = ф.элемент("УЗ_ПредметыОбучения", "робототехника")
    for кто, сумма, час in ((мама, 3000, 8), (бабушка, 1000, 8)):
        п = ф.приход(сын, сумма, Организация=орг, Касса=касса, ПредметОбучения=предмет, Плательщик=кто,
                     Дата=ф.день(0, час))
        ош, сообщ = ф.записать(п)
        т.проверить(ош is None, "подготовка: оплата %s" % сумма, "%s %s" % (ош, сообщ))

    def возврат(сумма, час):
        р = д_.документ("УЗ_РасходДенег", Дата=ф.день(0, час), Организация=орг, Касса=касса,
                        ВидОперации=c.Перечисления.УЗ_ВидыОпераций.КассаУченики, ФизЛицо=сын, ПредметОбучения=предмет,
                        СуммаДокумента=сумма, Получатель=мама)
        return д_.записать(р)
    т.проверить(возврат(500, 9) is None, "подготовка: возврат маме 500")

    def записать(д):
        ош, сообщ = ф.записать(д, "Запись")
        return ош and (" | ".join(м for м, _ in сообщ) or ош)

    def справка(налогоплательщик, обучающийся=сын, **поля):
        д = справки.СоздатьДокумент()
        д.Заполнить(обучающийся)
        д.Дата = ф.день(0, 10)
        д.Организация = орг
        д.Налогоплательщик = налогоплательщик
        д.Год = год
        д.Комментарий = МЕТКА
        д.ЗаполнитьПоУчету()
        for к, в in поля.items():
            setattr(д, к, в)
        return д, записать(д)

    def напечатать(д):
        return c.УЗ_Печать.СформироватьСвоейПечатью("Документ.УЗ_СправкаОбОплатеОбучения", "Справка",
                                                     д.Ссылка).ТабличныйДокумент

    # ── находка 2: справки супругам — вместе не больше их общих расходов ──
    с_мамы, ош = справка(мама)
    т.проверить(ош is None and float(с_мамы.Сумма) == 2500, "справка мамы 2 500", "%s %s" % (ош, с_мамы.Сумма))
    _, ош = справка(папа, ОплатыСупруга=мама)
    т.проверить(ош is not None and "супруг" in ош and "2 500" in ош.replace("\xa0", " "),
                "находка 2: папе с оплатами мамы 2 500 при справке мамы 2 500 — отказ (подтверждено было бы 5 000)", ош)
    о = с_мамы.Ссылка.ПолучитьОбъект()
    о.Сумма = 1500
    т.проверить(записать(о) is None, "мама согласилась на 1 500")
    с_папы, ош = справка(папа, ОплатыСупруга=мама, Сумма=1000)
    т.проверить(ош is None, "находка 2: 1 500 маме + 1 000 папе при расходах 2 500 — можно", ош)
    о = с_папы.Ссылка.ПолучитьОбъект()
    о.Сумма = 1100
    ош = записать(о)
    т.проверить(ош is not None and "супруг" in ош, "находка 2: папе 1 100 (вместе 2 600 > 2 500) — отказ", ош)

    # ── находка 3: выданная справка не переписывается ──
    напечатать(с_мамы)
    т.проверить(с_мамы.Ссылка.ПолучитьОбъект().Выдана, "находка 3: печать фиксирует выдачу справки мамы")
    т.проверить(возврат(300, 11) is None, "подготовка: ещё возврат маме 300")
    о = с_мамы.Ссылка.ПолучитьОбъект()
    о.ЗаполнитьПоУчету()
    ош = записать(о)
    т.проверить(ош is not None and "выдана" in ош, "находка 3: «По оплатам» в выданной справке и запись — отказ", ош)
    о = с_мамы.Ссылка.ПолучитьОбъект()
    о.Комментарий = МЕТКА + " (выдана на руки)"
    т.проверить(записать(о) is None, "находка 3: комментарий выданной справки менять можно")
    о = с_мамы.Ссылка.ПолучитьОбъект()
    c.ПолучитьСообщенияПользователю(True)
    try:
        о.УстановитьПометкуУдаления(True)
        ош = None
    except Exception:
        ош = " | ".join(str(м.Текст) for м in c.ПолучитьСообщенияПользователю(True)) or "отказ"
    т.проверить(ош is not None and "аннулирующ" in ош, "находка 3: пометка удаления выданной справки — отказ", ош)
    т.проверить(float(с_мамы.Ссылка.ПолучитьОбъект().Сумма) == 1500, "выданная справка мамы — по-прежнему 1 500")

    копия = с_мамы.Ссылка.ПолучитьОбъект().Скопировать()
    копия.Дата = ф.день(0, 12)
    копия.НомерСправки = 77   # номер корректирующей — всегда номер исходной
    копия.Сумма = 1200        # по кассе 2 200, из них 1 000 уже у папы
    ош = записать(копия)
    т.проверить(ош is None and ст(копия.ИсходнаяСправка) == ст(с_мамы.Ссылка)
                and копия.НомерСправки == с_мамы.НомерСправки and копия.НомерКорректировки == 1,
                "находка 3: корректирующая — ссылка на исходную, её номер, корректировка 1, 1 200",
                "%s / %s / %s / %s" % (ош, копия.НомерСправки, копия.НомерКорректировки, копия.Сумма))

    # ── находка 4: корректировка и аннулирование — только к выданной первичной ──
    _, ош = справка(бабушка, НомерКорректировки=1)
    т.проверить(ош is not None and "исходн" in ош, "находка 4: корректирующая без исходной справки — отказ", ош)
    _, ош = справка(мама, другой, НомерКорректировки=999)
    т.проверить(ош is not None and "исходн" in ош, "находка 4: аннулирующая без исходной (оплат нет) — отказ", ош)
    с_бабушки, ош = справка(бабушка)
    т.проверить(ош is None and float(с_бабушки.Сумма) == 1000, "справка бабушки 1 000 (не выдана)", ош)
    ош = записать(с_бабушки.Ссылка.ПолучитьОбъект().Скопировать())
    т.проверить(ош is not None and "не выдана" in ош,
                "находка 4: корректирующая к невыданной справке — отказ (исправьте её саму)", ош)
    чужой_год = с_мамы.Ссылка.ПолучитьОбъект().Скопировать()
    чужой_год.Год = год - 1
    чужой_год.Сумма = 100
    ош = записать(чужой_год)
    т.проверить(ош is not None and "исходн" in ош, "находка 4: корректирующая за другой год — отказ", ош)
    аннул = копия.Ссылка.ПолучитьОбъект().Скопировать()
    аннул.НомерКорректировки = 999
    ош = записать(аннул)
    т.проверить(ош is None and ст(аннул.ИсходнаяСправка) == ст(с_мамы.Ссылка) and аннул.НомерСправки == с_мамы.НомерСправки,
                "аннулирующая к выданной справке мамы — можно, исходная — первичная", ош)


if __name__ == "__main__":
    запустить("codex_21_справка", сценарий)
