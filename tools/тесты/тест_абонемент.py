"""Карточка абонемента (УЗ_Абонемент): приостановки и копирование (ошибки справки №30, №31).

№30. Форма проверяла приостановку одним правилом (`ДатаОкончания <= возобновление` — отказ), запись — другим
(`ДатаОкончания < ДатаВозобновления`); обе не давали приостановке дойти до конца абонемента, хотя по В4 срок
абонемента продлевается на дни приостановки. Стало одно правило (Справочники.УЗ_Абонемент.ОшибкаПриостановки)
и для окна «Приостановить», и для записи: приостановка начинается в сроке абонемента (не раньше начала и не
позже окончания), возобновление позже приостановки, а закончиться может и после окончания абонемента.
№31. Копия абонемента оставалась с наименованием, ценой, датой активации и приостановками оригинала.
(№29 — закрытие окна приостановки крестиком — клиентское, проверено в веб-клиенте.)

    python tools\\тесты\\тест_абонемент.py --база=C:\\1c_bases\\UZ_UNF_D
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from фабрика import Фабрика  # noqa: E402
from _деньги import сообщения  # noqa: E402

МЕТКА = "УЗ тест карточки абонемента"


def сценарий(т):
    c = т.c
    ф = Фабрика(т, МЕТКА)
    ученик = ф.ученик()
    абонемент = ф.абонемент(ученик, "абонемент", КоличествоЗанятий=8, ЦенаАбонемента=5000)
    # срок фабрики: с −30 до +60 дней от сегодня

    def записать_с_приостановкой(с, по):
        о = абонемент.ПолучитьОбъект()
        о.Приостановки.Очистить()
        строка = о.Приостановки.Добавить()
        строка.ДатаПриостановки = с
        строка.ДатаВозобновления = по
        сообщения(c)
        try:
            о.Записать()
            return None
        except Exception:
            return сообщения(c) or "отказ без сообщения"

    ош = записать_с_приостановкой(ф.день(55), ф.день(70))
    т.проверить(ош is None, "№30: приостановка с 55-го дня по 70-й (после окончания абонемента) записывается — "
                "срок продлевается (было: отказ «ошибка в датах»)", ош)
    ош = записать_с_приостановкой(ф.день(61), ф.день(65))
    т.проверить(ош is not None and "после окончания" in ош, "№30: приостановка после окончания абонемента — отказ", ош)
    ош = записать_с_приостановкой(ф.день(-40), ф.день(-35))
    т.проверить(ош is not None and "раньше начала" in ош, "№30: приостановка раньше начала абонемента — отказ", ош)
    ош = записать_с_приостановкой(ф.день(10), ф.день(10))
    т.проверить(ош is not None and "позже даты приостановки" in ош,
                "№30: возобновление в день приостановки — отказ", ош)
    # то же правило, что вызывает окно «Приостановить» карточки
    о = абонемент.ПолучитьОбъект()
    т.проверить(c.Справочники.УЗ_Абонемент.ОшибкаПриостановки(о.ДатаНачала, о.ДатаОкончания, ф.день(55), ф.день(70)) == "",
                "№30: правило окна «Приостановить» то же — до конца абонемента и дальше можно")

    # №31: копия — новый абонемент
    ош = записать_с_приостановкой(ф.день(5), ф.день(8))
    т.проверить(ош is None, "приостановка в сроке записывается", ош)
    копия = абонемент.ПолучитьОбъект().Скопировать()
    т.проверить(копия.Наименование == "" and float(копия.ЦенаАбонемента) == 0,
                "№31: у копии нет наименования и цены оригинала (составятся заново)",
                "«%s», %s" % (копия.Наименование, копия.ЦенаАбонемента))
    т.проверить(копия.ДатаАктивации is None or копия.ДатаАктивации.year < 1900,
                "№31: копия не активирована (нет даты активации)", копия.ДатаАктивации)
    т.проверить(копия.Приостановки.Количество() == 0, "№31: у копии нет приостановок оригинала",
                копия.Приостановки.Количество())


if __name__ == "__main__":
    запустить("абонемент", сценарий)
