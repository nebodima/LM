"""Расчёт зарплаты педагога (УЗ_РасчетЗарплаты) — двойная выплата и закрытый период.

Аудит 28.09 (учёт №19, Codex B01–B04):
  * заполнение брало начисления с НачалаМесяца по КонецМесяца — период расширялся молча;
  * начисления, уже вошедшие в другой проведённый расчёт, брались снова → вторая выплата;
  * смена педагога/периода очищала таблицу, но оставляла сумму документа → РКО на старую сумму;
  * копия расчёта сохраняла РКО, перемещение и таблицу;
  * движения пишутся датой окончания периода, а дата запрета проверяла только дату документа.

Мутации (проверены 28.09.2026): вернуть НачалоМесяца/КонецМесяца в ЗаполнитьНачисления → красный;
убрать условие «НЕ В (уже рассчитанные)» → красный; убрать ПроверитьЗапретПоПериоду → красный.

    python tools\\тесты\\тест_расчет_зарплаты.py --база=C:\\1c_bases\\UZ_UNF_A
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import дата, ошибка_записи, запустить  # noqa: E402
from _деньги import Данные  # noqa: E402
from тест_даты_запрета import прочитать_регистр, записать_регистр  # noqa: E402

МЕТКА = "_Тест расчёт зарплаты"


def сценарий(т):
    c = т.c
    д = Данные(т, МЕТКА)
    педагог = д.элемент("УЗ_ФизЛица", "педагог", ЭтоПедагог=True)

    def начисление(когда, сумма):
        н = д.документ("УЗ_НачисленияПедагогам", Дата=когда, Педагог=педагог)
        строка = н.НачисленияПедагогам.Добавить()
        строка.Сумма = сумма
        строка.Комментарий = МЕТКА
        ош = д.записать(н)
        т.проверить(ош is None, "начисление %s проведено" % сумма, ош)
        return н.Ссылка

    н1 = начисление(дата(2026, 8, 5, 10), 1000)
    н2 = начисление(дата(2026, 8, 20, 10), 2000)

    def расчёт(когда, с, по):
        return д.документ("УЗ_РасчетЗарплаты", Дата=когда, Педагог=педагог, ДатаНачала=с, ДатаОкончания=по)

    def документы(р):
        return sorted(c.String(р.ДД.Получить(н).Документ) for н in range(р.ДД.Количество()))

    # 1. период документа — строго 01–15.08, без расширения до месяца
    р1 = расчёт(дата(2026, 8, 16, 12), дата(2026, 8, 1), дата(2026, 8, 15))
    р1.ЗаполнитьНачисления()
    т.проверить(документы(р1) == [c.String(н1)] and float(р1.СуммаДокумента) == 1000,
                "расчёт 01–15.08 берёт только начисление 05.08 (1 000), а не весь август",
                "%s, сумма %s" % (документы(р1), р1.СуммаДокумента))
    ош = д.записать(р1)
    т.проверить(ош is None, "расчёт 01–15.08 проведён", ош)

    # 2. расчёт за весь август не берёт начисление, уже вошедшее в проведённый расчёт
    р2 = расчёт(дата(2026, 9, 1, 12), дата(2026, 8, 1), дата(2026, 8, 31))
    р2.ЗаполнитьНачисления()
    т.проверить(документы(р2) == [c.String(н2)] and float(р2.СуммаДокумента) == 2000,
                "расчёт 01–31.08 берёт только 20.08 (2 000): 05.08 уже рассчитано",
                "%s, сумма %s" % (документы(р2), р2.СуммаДокумента))
    ош = д.записать(р2)
    т.проверить(ош is None, "расчёт 01–31.08 проведён", ош)

    # 3. то же начисление, вписанное руками в третий расчёт, — проведение отказано
    р3 = расчёт(дата(2026, 9, 2, 12), дата(2026, 8, 1), дата(2026, 8, 31))
    строка = р3.ДД.Добавить()
    строка.Документ = н1
    строка.Начисление = 1000
    строка.КОплате = 1000
    ош = д.записать(р3)
    т.проверить(ош is not None and "уже" in ош, "начисление из проведённого расчёта второй раз не проводится", ош)

    # 4. сумма документа = итог таблицы (смена педагога очистила таблицу — старая сумма не остаётся)
    р4 = расчёт(дата(2026, 9, 3, 12), дата(2026, 8, 1), дата(2026, 8, 31))
    р4.СуммаДокумента = 5000
    ош = д.записать(р4, c.РежимЗаписиДокумента.Запись)
    т.проверить(ош is None and float(р4.Ссылка.ПолучитьОбъект().СуммаДокумента) == 0,
                "пустая таблица → сумма документа 0 (не прежние 5 000)", ош or р4.Ссылка.ПолучитьОбъект().СуммаДокумента)

    # 5. копия не тащит РКО, перемещение и таблицу
    рко = д.документ("УЗ_РасходДенег", Дата=дата(2026, 9, 1, 13), СуммаДокумента=1000)
    д.записать(рко, c.РежимЗаписиДокумента.Запись)
    о1 = р1.Ссылка.ПолучитьОбъект()
    о1.РКО = рко.Ссылка
    о1.ОбменДанными.Загрузка = True
    о1.Записать()
    копия = р1.Ссылка.ПолучитьОбъект().Скопировать()
    т.проверить(копия.РКО.Пустая() and копия.Перемещение.Пустая() and копия.ДД.Количество() == 0
                and float(копия.СуммаДокумента) == 0,
                "копия расчёта без РКО, перемещения, таблицы и суммы",
                "РКО пуст %s, строк %s, сумма %s" % (копия.РКО.Пустая(), копия.ДД.Количество(), копия.СуммаДокумента))

    # 6. дата запрета — по дате движений (КонецДня(ДатаОкончания)), а не только по дате документа
    прежнее = прочитать_регистр(c)
    т.убрать(lambda: записать_регистр(c, прежнее), "регистр УЗ_ДатыЗапрета")
    записать_регистр(c, [(c.Справочники.Пользователи.ПустаяСсылка(), дата(2026, 8, 31), 0)])
    р5 = расчёт(дата(2026, 9, 5, 12), дата(2026, 7, 1), дата(2026, 7, 31))
    строка = р5.ДД.Добавить()
    строка.Начисление = 100
    строка.КОплате = 100
    ош = д.записать(р5)
    т.проверить(ош is not None and "закрыт" in ош,
                "документ 05.09 за июль при запрете по 31.08 — проведение отказано (движения в закрытом июле)", ош)
    о2 = р2.Ссылка.ПолучитьОбъект()
    ош = ошибка_записи(lambda: о2.Записать(c.РежимЗаписиДокумента.ОтменаПроведения))
    т.проверить(ош is not None, "отмена проведения расчёта 01.09 с движениями 31.08 при запрете по 31.08 — отказ")
    т.проверить(р2.Ссылка.ПолучитьОбъект().Проведен, "расчёт за август остался проведённым")


if __name__ == "__main__":
    запустить("расчет_зарплаты", сценарий)
