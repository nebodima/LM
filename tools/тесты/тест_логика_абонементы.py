"""Логика абонементов, часть 1 (docs/логики/абонементы.md, сценарии 1–7): расход, остаток, исчерпание, часовой.

Тариф «8 000 за 8» (1 000 за урок), абонемент А «6 400 за 8 занятий» (800 за урок) — числа из документа.
Остаток — одна функция Справочники.УЗ_Абонемент.ТекстОстатка для карточки, формы урока, помощника и панели.

Сценарии (К — красный на старом коде, проверено прогоном до правки 28.09.2026):
  №1  урок «К оплате» с явкой — строка 800, в регистре 800 и 1 занятие; остаток «7 из 8 зан.» (К: функции не было,
      карточка писала «7 ур.», панель — «7 из 8» суммой всех абонементов)
  №2  неявка «К оплате» (В3) — 800, занятие израсходовано, «6 из 8 зан.» (К: как №1)
  №3  явка без «К оплате» (Р7) — 0 ₽, абонемент в движении пуст, остаток прежний
  №4  В16: абонемент на 2 занятия, 3-й урок — проводится по тарифу 1 000, абонемент из строки снят,
      предупреждение «исчерпан» (К: отказ «Не хватает занятий»)
  №5  «3 000 за 2 ч», три урока по 40 мин — по 1 000,00, 4-й — по тарифу (К: 4-й — отказ)
  №6  «3 000 за 2 ч» после одного урока 40 мин — «1:20 из 2:00 ч» (К: карточка «1,3333333… ч»)
  №7  бессрочный абонемент (пустая дата окончания) записывается и действует (К: отказ «Дата начала больше…»)

    python tools\\тесты\\тест_логика_абонементы.py --база=C:\\1c_bases\\UZ_UNF_B
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from фабрика import Фабрика  # noqa: E402
from _логика_абонементов import вызов, есть_слово, пусто, строка  # noqa: E402

МЕТКА = "УЗ тест логики абонементов"


def сценарий(т):
    c = т.c
    ф = Фабрика(т, МЕТКА)
    аб = c.Справочники.УЗ_Абонемент
    предмет = ф.элемент("УЗ_ПредметыОбучения", "математика")
    педагог = ф.педагог()
    тариф = ф.элемент("УЗ_Тарифы", "8 000 за 8", Сумма=8000, КоличествоУроков=8)

    def урок(час, строки, минута=0, часов=1):
        д = ф.урок(педагог, ф.день(-1, час, минута), часов, строки, ПредметОбучения=предмет)
        return д, ф.записать(д, "Проведение")

    def остаток(абонемент):
        значение, ошибка = вызов(lambda: аб.ТекстОстатка(абонемент))
        return значение if ошибка is None else "ошибка: " + ошибка

    def движение(д, поле):
        return ф.число("""ВЫБРАТЬ СУММА(Р.%s) ИЗ РегистрНакопления.УЗ_СписанияСуммЗаУроки КАК Р
            ГДЕ Р.Регистратор = &У""" % поле, У=д.Ссылка)

    # ── №1–3: расход и остаток абонемента А ──
    ученик = ф.ученик("Иванов")
    а = ф.абонемент(ученик, "А 6400 за 8", КоличествоЗанятий=8, ЦенаАбонемента=6400, ПредметОбучения=предмет)
    д1, итог = урок(8, [dict(Ученик=ученик, Абонемент=а, Явка=True, СписатьОплату=True, Тариф=тариф)])
    т.проверить(итог[0] is None, "№1: урок по абонементу проведён", итог)
    т.проверить(float(строка(д1).Сумма) == 800 and движение(д1, "Сумма") == 800 and движение(д1, "КоличествоУроков") == -1,
                "№1: строка 800 = 6 400 / 8, в регистре 800 и одно занятие (КоличествоУроков −1)",
                (строка(д1).Сумма, движение(д1, "Сумма"), движение(д1, "КоличествоУроков")))
    т.проверить(остаток(а) == "7 из 8 зан.", "№1: остаток абонемента «7 из 8 зан.»", остаток(а))

    д2, итог = урок(9, [dict(Ученик=ученик, Абонемент=а, Явка=False, СписатьОплату=True, Тариф=тариф)])
    т.проверить(итог[0] is None and float(строка(д2).Сумма) == 800, "№2 (В3): неявка «К оплате» — 800", итог)
    т.проверить(остаток(а) == "6 из 8 зан.", "№2: неявка «К оплате» расходует занятие — «6 из 8 зан.»", остаток(а))

    д3, итог = урок(10, [dict(Ученик=ученик, Абонемент=а, Явка=True, СписатьОплату=False, Тариф=тариф)])
    абонемент_в_движении = т.выбрать("""ВЫБРАТЬ Р.Абонемент КАК А ИЗ РегистрНакопления.УЗ_СписанияСуммЗаУроки КАК Р
        ГДЕ Р.Регистратор = &У""", У=д3.Ссылка)
    т.проверить(итог[0] is None and float(строка(д3).Сумма) == 0 and абонемент_в_движении.Количество() == 1
                and абонемент_в_движении.Получить(0).А.Пустая(),
                "№3 (Р7): явка без «К оплате» — 0 ₽, абонемент в движении пуст", итог)
    т.проверить(остаток(а) == "6 из 8 зан.", "№3: бесплатное занятие остатка не меняет — «6 из 8 зан.»", остаток(а))

    # ── №4: В16 — исчерпан, строка по тарифу с предупреждением ──
    петров = ф.ученик("Петров")
    на_2 = ф.абонемент(петров, "Б 1600 за 2", КоличествоЗанятий=2, ЦенаАбонемента=1600, ПредметОбучения=предмет)
    for час in (11, 12):
        _, итог = урок(час, [dict(Ученик=петров, Абонемент=на_2, Явка=True, СписатьОплату=True, Тариф=тариф)])
        т.проверить(итог[0] is None, "№4: урок %d по абонементу на 2 занятия проведён" % (час - 10), итог)
    д4, итог = урок(13, [dict(Ученик=петров, Абонемент=на_2, Явка=True, СписатьОплату=True, Тариф=тариф)])
    т.проверить(итог[0] is None, "№4 (В16): 3-й урок при исчерпанном абонементе проведён, не отказ", итог)
    т.проверить(есть_слово(итог[1], "исчерпан"), "№4 (В16): предупреждение «абонемент исчерпан — по тарифу»", итог[1])
    if итог[0] is None:
        т.проверить(пусто(строка(д4).Абонемент) and float(строка(д4).Сумма) == 1000 and движение(д4, "Сумма") == 1000,
                    "№4: абонемент снят со строки, цена по тарифу 1 000 (8 000 / 8)", (строка(д4).Абонемент, строка(д4).Сумма))
    т.проверить(остаток(на_2) == "исчерпан: 2 из 2 зан.", "№4: остаток «исчерпан: 2 из 2 зан.»", остаток(на_2))

    # ── №5–6: часовой «3 000 за 2 ч», уроки по 40 мин ──
    сидоров = ф.ученик("Сидоров")
    часовой = ф.абонемент(сидоров, "Ч 3000 за 2 ч", КоличествоЧасов=2, ЦенаАбонемента=3000, ПредметОбучения=предмет)
    суммы = []
    for номер, (час, минута) in enumerate(((14, 0), (14, 40), (15, 20)), 1):
        д, итог = урок(час, [dict(Ученик=сидоров, Абонемент=часовой, Явка=True, СписатьОплату=True, Тариф=тариф)],
                       минута=минута, часов=0.6667)
        суммы.append(float(строка(д).Сумма) if итог[0] is None else итог)
        if номер == 1:
            т.проверить(остаток(часовой) == "1:20 из 2:00 ч", "№6: после урока 40 мин остаток «1:20 из 2:00 ч»", остаток(часовой))
    т.проверить(суммы == [1000, 1000, 1000], "№5: три урока по 40 мин — по 1 000,00 (3 000 × 40 / 120)", суммы)
    д5, итог = урок(16, [dict(Ученик=сидоров, Абонемент=часовой, Явка=True, СписатьОплату=True, Тариф=тариф)],
                    часов=0.6667)
    т.проверить(итог[0] is None and пусто(строка(д5).Абонемент) and float(строка(д5).Сумма) == 1000,
                "№5 (В16): 4-й урок — по тарифу, абонемент снят", итог)

    # ── №7: бессрочный абонемент ──
    бессрочный_ученик = ф.ученик("Бессрочный")
    бессрочный, ошибка = вызов(lambda: ф.абонемент(бессрочный_ученик, "бессрочный", КоличествоЗанятий=8,
                                                   ЦенаАбонемента=6400, ПредметОбучения=предмет, ДатаОкончания=None))
    т.проверить(ошибка is None, "№7 (Р-1): абонемент без даты окончания записывается", ошибка)
    if ошибка is None:
        д7, итог = урок(17, [dict(Ученик=бессрочный_ученик, Абонемент=бессрочный, Явка=True, СписатьОплату=True,
                                  Тариф=тариф)])
        т.проверить(итог[0] is None and float(строка(д7).Сумма) == 800, "№7: урок по бессрочному абонементу — 800", итог)


if __name__ == "__main__":
    запустить("логика_абонементы", сценарий)
