"""Помощник первого запуска (общая форма УЗ_ПервыйЗапуск) — сквозной путь «пустая студия → первый урок».

Форма собирает семь шагов и одним вызовом отдаёт их УЗ_Общий.ВыполнитьПервуюНастройку; «Создать уроки на неделю»
открывает помощник создания уроков с группой — он выделяет дни Документы.УЗ_Урок.ДатыЗанятийГруппы и пишет уроки
Документы.УЗ_Урок.ЗаписатьУчениковВУрок. Тест идёт тем же путём, что человек:
  1. ровно те поля, которые человек вводит в помощнике (организация, касса, предмет, педагог и ставка, цена, группа,
     дни, время, два ученика с телефоном и родителем), — не больше 20 полей до первого урока;
  2. всё связано: касса организации и настройки учёта, педагог со ставкой, группа с педагогом, предметом, тарифом и
     расписанием, ученики с телефоном, родителем и группой;
  3. уроки на неделю: дни по расписанию группы на 7 дней вперёд — столько, сколько отмечено дней недели; урок
     записан с учениками группы по цене занятия;
  4. повторный вызов тех же данных ничего не создаёт (журнал «Уже есть»), с одним новым учеником — создаёт одного;
  5. открытие при первом входе (УЗ_Сервер.НуженПервыйЗапуск): в базе с людьми — не открывается.
Мутация (проверено 28.09.2026 на UZ_UNF_D): в УЗ_Общий.НайтиПоНаименованиюПервойНастройки вместо «Возврат
Выборка.Ссылка» — «Продолжить» (поиск ничего не находит) — краснеют проверки повторного вызова (дубли).

    python tools\\тесты\\тест_первый_запуск.py --база=C:\\1c_bases\\UZ_UNF_D
"""
import datetime
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import дата, запустить  # noqa: E402
from фабрика import Фабрика  # noqa: E402

# затрагивает: УЗ_Общий, УЗ_Сервер, УЗ_Урок, УЗ_Настройки, УЗ_ФизЛица, УЗ_ГруппыОбучения, УЗ_Тарифы, УЗ_Кассы
МЕТКА = "УЗ тест ПЗ"
ЦЕНА = 700
СТАВКА = 1713          # необычная сумма: ставка «1713 за занятие» в базе заведомо своя
ПОЛЕЙ_НЕ_БОЛЬШЕ = 20
ТАРИФ_ЗАНЯТИЯ = "Разовое занятие"


def сценарий(т):
    c = т.c
    ф = Фабрика(т, МЕТКА)
    сегодня = datetime.date.today()

    def равны(первая, вторая):
        """Ссылки через COM — разные объекты-обёртки: сравнивать по уникальному идентификатору."""
        return (первая is not None and вторая is not None
                and c.String(первая.УникальныйИдентификатор()) == c.String(вторая.УникальныйИдентификатор()))

    def одно(текст, **п):
        тз = т.выбрать(текст, **п)
        return тз.Получить(0).Ссылка if тз.Количество() else None

    def по_имени(справочник, имя):
        return одно("ВЫБРАТЬ ПЕРВЫЕ 1 С.Ссылка КАК Ссылка ИЗ Справочник.%s КАК С ГДЕ С.Наименование = &И "
                    "И НЕ С.ЭтоГруппа" % справочник if справочник != "УЗ_Тарифы" else
                    "ВЫБРАТЬ ПЕРВЫЕ 1 С.Ссылка КАК Ссылка ИЗ Справочник.%s КАК С ГДЕ С.Наименование = &И" % справочник,
                    И=имя)

    # общие объекты, которые помощник находит по наименованию: если они были до теста — не наши, не убирать
    тариф_был = по_имени("УЗ_Тарифы", ТАРИФ_ЗАНЯТИЯ)
    ставка_была = по_имени("УЗ_СтавкиПедагогов", "%d за занятие" % СТАВКА)
    настройки_до = c.РегистрыСведений.УЗ_Настройки.Настройки()
    организация = ф.организация("организация")   # в уборке — последней

    def уборка():
        # настройки учёта — как были (ссылаются на кассу теста)
        в = c.NewObject("Структура")
        в.Вставить("Организация", настройки_до.Организация)
        в.Вставить("Касса", настройки_до.Касса)
        c.РегистрыСведений.УЗ_Настройки.ЗаписатьНастройки(в)
        уроки = т.выбрать("ВЫБРАТЬ У.Ссылка КАК Ссылка ИЗ Документ.УЗ_Урок КАК У ГДЕ У.ГруппаОбучения.Наименование = &Г",
                          Г=МЕТКА + " группа")
        for н in range(уроки.Количество()):
            т.удалить_объект(уроки.Получить(н).Ссылка, загрузка=True)
        люди = т.выбрать("ВЫБРАТЬ Ф.Ссылка КАК Ссылка, Ф.ЭтоПедагог КАК П ИЗ Справочник.УЗ_ФизЛица КАК Ф "
                         "ГДЕ Ф.Наименование ПОДОБНО &М И НЕ Ф.ЭтоГруппа УПОРЯДОЧИТЬ ПО Ф.ЭтоПедагог",
                         М=МЕТКА + "%")
        for н in range(люди.Количество()):
            т.удалить_объект(люди.Получить(н).Ссылка, загрузка=True)
        for справочник in ("УЗ_ГруппыОбучения", "УЗ_ПредметыОбучения", "УЗ_Кассы"):
            тз = т.выбрать("ВЫБРАТЬ С.Ссылка КАК Ссылка ИЗ Справочник.%s КАК С ГДЕ С.Наименование ПОДОБНО &М" % справочник,
                           М=МЕТКА + "%")
            for н in range(тз.Количество()):
                т.удалить_объект(тз.Получить(н).Ссылка, загрузка=True)
        # тариф и ставка с общим именем: убираем все одноимённые, если до теста их не было (при дублях — все дубли)
        for справочник, имя, был in (("УЗ_Тарифы", ТАРИФ_ЗАНЯТИЯ, тариф_был),
                                     ("УЗ_СтавкиПедагогов", "%d за занятие" % СТАВКА, ставка_была)):
            if был is not None:
                continue
            тз = т.выбрать("ВЫБРАТЬ С.Ссылка КАК Ссылка ИЗ Справочник.%s КАК С ГДЕ С.Наименование = &И" % справочник,
                           И=имя)
            for н in range(тз.Количество()):
                т.удалить_объект(тз.Получить(н).Ссылка, загрузка=True)
    т.убрать(уборка, "объекты помощника первого запуска, настройки учёта")

    # ── 1. то, что человек вводит в помощнике ──
    начало = дата(сегодня.year, сегодня.month, сегодня.day, 6, 30)   # время начала (дата помощнику не нужна)
    длительность = дата(сегодня.year, сегодня.month, сегодня.day, 1, 0)
    поля = {
        "Организация": организация,                                   # шаг 1
        "Касса": МЕТКА + " касса",                                    # шаг 2
        "Предметы": МЕТКА + " вокал",                                 # шаг 3
        "Педагоги": [{"ФИО": МЕТКА + " педагог", "ЗаЗанятие": СТАВКА}],   # шаг 4
        "ЦенаЗанятия": ЦЕНА,                                          # шаг 5
        "Группа": МЕТКА + " группа",                                  # шаг 6
        "ДниНедели": "ПН,ЧТ",
        "ВремяНачала": начало,
        "Продолжительность": длительность,
        "Ученики": [{"ФИО": МЕТКА + " ученик 1", "Телефон": "+7 900 000-00-01", "Родитель": МЕТКА + " родитель 1"},
                    {"ФИО": МЕТКА + " ученик 2", "Телефон": "+7 900 000-00-02", "Родитель": МЕТКА + " родитель 2"}],
    }

    def число_полей(значение):
        if isinstance(значение, dict):
            return sum(число_полей(в) for в in значение.values())
        if isinstance(значение, list):
            return sum(число_полей(в) for в in значение)
        if isinstance(значение, str) and "," in значение and значение.isupper():
            return len(значение.split(","))      # дни недели — по флажку на день
        return 1 if значение not in (None, "", 0) else 0
    полей = число_полей(поля)
    т.проверить(полей <= ПОЛЕЙ_НЕ_БОЛЬШЕ, "до первого урока — не больше %d полей (введено %d)" % (ПОЛЕЙ_НЕ_БОЛЬШЕ, полей))

    def в_1с(значение):
        if isinstance(значение, dict):
            с = c.NewObject("Структура")
            for к, в in значение.items():
                с.Вставить(к, в_1с(в))
            return с
        if isinstance(значение, list):
            return т.массив(*[в_1с(в) for в in значение])
        return значение

    итог = c.УЗ_Общий.ВыполнитьПервуюНастройку(в_1с(поля))
    журнал = [итог.Журнал.Получить(н) for н in range(итог.Журнал.Количество())]
    т.проверить(итог.Создано >= 9 and all(с.startswith("Создано") or с.startswith("Записано") or
                                          (с.startswith("Уже есть: тариф") and тариф_был is not None) for с in журнал),
                "первый вызов: всё создано (%d объектов), журнал «Создано»" % итог.Создано, журнал)

    # ── 2. связи ──
    касса = итог.Касса.ПолучитьОбъект()
    т.проверить(равны(касса.Организация, организация), "касса — организации помощника")
    настройки = c.РегистрыСведений.УЗ_Настройки.Настройки()
    т.проверить(равны(настройки.Организация, организация) and равны(настройки.Касса, итог.Касса),
                "настройки учёта: организация и касса новых документов — из помощника")
    педагог = итог.Педагоги.Получить(0).ПолучитьОбъект()
    т.проверить(педагог.ЭтоПедагог and педагог.СтавкаПедагога.ОплатаЗаЗанятие == СТАВКА,
                "педагог со ставкой %d за занятие" % СТАВКА, педагог.СтавкаПедагога.Наименование)
    группа = итог.Группа.ПолучитьОбъект()
    т.проверить(равны(группа.Педагог, итог.Педагоги.Получить(0)) and равны(группа.ПредметОбучения, итог.Предметы.Получить(0))
                and равны(группа.Тариф, итог.ТарифЗанятия) and группа.ПН and группа.ЧТ and not группа.СР
                and группа.Время.hour == 6 and группа.Время.minute == 30 and группа.ВремяОкончания.hour == 7,
                "группа: педагог, предмет, тариф, ПН и ЧТ 06:30–07:30")
    т.проверить(c.Документы.УЗ_Урок.ЦенаТарифаНаДату(итог.ТарифЗанятия, ф.день()).Сумма == ЦЕНА
                or тариф_был is not None, "тариф «%s» — %d за занятие" % (ТАРИФ_ЗАНЯТИЯ, ЦЕНА))
    ученик = итог.Ученики.Получить(0).ПолучитьОбъект()
    т.проверить(ученик.Телефон == "+7 900 000-00-01" and ученик.Родитель1.Наименование == МЕТКА + " родитель 1"
                and ученик.ГруппыОбучения.Найти(итог.Группа, "ГруппаОбучения") is not None and not ученик.ЭтоПедагог,
                "ученик: телефон, родитель, группа в карточке")

    # ── 3. «Создать уроки на неделю»: дни по расписанию и запись уроков, как помощник создания уроков ──
    менеджер = c.Документы.УЗ_Урок
    даты = менеджер.ДатыЗанятийГруппы(итог.Группа, ф.день(), 7)
    дни = [даты.Получить(н) for н in range(даты.Количество())]
    т.проверить(len(дни) == 2 and sorted(д.isoweekday() for д in дни) == [1, 4]
                and all(0 <= (datetime.date(д.year, д.month, д.day) - сегодня).days < 7 for д in дни),
                "на 7 дней вперёд — два дня занятий: понедельник и четверг", [str(д) for д in дни])
    # цена урока — тарифа группы на дату: свой тариф помощника — 700, уже бывший в базе — его цена за занятие
    цена_тарифа = c.Документы.УЗ_Урок.ЦенаТарифаНаДату(итог.ТарифЗанятия, ф.день())
    цена_урока = ЦЕНА if тариф_был is None else round(float(цена_тарифа.Сумма) / max(1, цена_тарифа.КоличествоУроков), 2)
    уроков = 0
    for день in дни:
        расписание = менеджер.РасписаниеГруппыНаДень(итог.Группа, день)
        п = c.NewObject("Структура")
        п.Вставить("Дата", расписание.Начало)
        п.Вставить("КоличествоЧасов", расписание.КоличествоЧасов)
        п.Вставить("ПредметОбучения", группа.ПредметОбучения)
        п.Вставить("Педагог", группа.Педагог)
        п.Вставить("Помещение", группа.Помещение)
        п.Вставить("ГруппаОбучения", итог.Группа)
        строки = []
        for н in range(итог.Ученики.Количество()):
            с = c.NewObject("Структура")
            с.Вставить("Ученик", итог.Ученики.Получить(н))
            с.Вставить("Тариф", менеджер.ТарифНовойСтроки(итог.Ученики.Получить(н), итог.Группа))
            с.Вставить("СписатьОплату", True)
            строки.append(с)
        записано = менеджер.ЗаписатьУчениковВУрок(п, т.массив(*строки), True)
        if записано.Успех and записано.Урок is not None:
            урок = записано.Урок.ПолучитьОбъект()
            if урок.Ученики.Количество() == 2 and all(урок.Ученики.Получить(н).Сумма == цена_урока for н in range(2)):
                уроков += 1
        else:
            print("    отказ урока %s: %s" % (день, [записано.Строки.Получить(н).Описание
                                                   for н in range(записано.Строки.Количество())]))
    т.проверить(уроков == 2, "уроки на неделю записаны: 2 урока по 2 ученика, по %s за занятие" % цена_урока, уроков)

    # ── 4. повторный вызов — без дублей; с новым учеником — один новый ──
    повтор = c.УЗ_Общий.ВыполнитьПервуюНастройку(в_1с(поля))
    журнал = [повтор.Журнал.Получить(н) for н in range(повтор.Журнал.Количество())]
    т.проверить(повтор.Создано == 0 and all(с.startswith("Уже есть") for с in журнал),
                "повторный вызов тех же данных ничего не создаёт — журнал «Уже есть»", журнал)
    людей = т.выбрать("ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Ч ИЗ Справочник.УЗ_ФизЛица КАК Ф ГДЕ Ф.Наименование ПОДОБНО &М",
                      М=МЕТКА + "%").Получить(0).Ч
    т.проверить(людей == 5 and равны(повтор.Группа, итог.Группа) and равны(повтор.Касса, итог.Касса),
                "людей помощника по-прежнему 5 (педагог, 2 ученика, 2 родителя), та же группа и касса", людей)
    поля["Ученики"].append({"ФИО": МЕТКА + " ученик 3"})
    третий = c.УЗ_Общий.ВыполнитьПервуюНастройку(в_1с(поля))
    т.проверить(третий.Создано == 1 and третий.Ученики.Количество() == 3,
                "дописан ученик — создан ровно один объект", [третий.Журнал.Получить(н) for н in range(третий.Журнал.Количество())])

    # ── 5. открытие при первом входе: в базе есть люди — помощник сам не открывается ──
    т.проверить(c.УЗ_Сервер.НуженПервыйЗапуск() is False and c.УЗ_Сервер.ПриНачалеРаботы().ПервыйЗапуск is False,
                "в базе есть люди — при входе помощник не открывается (ПриНачалеРаботы.ПервыйЗапуск = Ложь)")


if __name__ == "__main__":
    запустить("первый_запуск", сценарий)
