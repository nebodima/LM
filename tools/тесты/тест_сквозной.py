"""Сквозной тест денег: абонемент → ПКО → уроки (явка, неявка «К оплате») → остатки учеников, кассы, абонемента →
начисление педагогам → выплата РКО и расчёт зарплаты → отмена проведения урока → перепроведение → уборка.
Все проверки — числами по регистрам (УЗ_СписанияСуммЗаУроки, УЗ_Касса, УЗ_РасчетыПоЗарплате).
Правила учёта — решения владельца 28.09.2026 (docs\аудит_полный_2026-09-28.md, раздел 7): урок по абонементу стоит
цена абонемента / число занятий (В2); неявка с «К оплате» расходует занятие и деньги (В3); урок без явки —
без «за занятие» (В6); урок проводится только после начала (В10) — поэтому все даты теста вчерашние.

Данные (тариф «8 000 за 8 уроков» = 1 000 за урок; абонемент А «6 400 за 8 занятий» = 800 за урок):
  ученик А — абонемент, ПКО 6 400; ученик Б — без абонемента, ПКО 500;
  урок 1 (педагог 1, 500 за занятие): А — явка, «К оплате» (800), Б — неявка с «К оплате» (1 000) → 1 800, педагогу 500;
  урок 2 (педагог 2, 40 % с оплаты): А — явка (800) → педагогу 320;
  урок 3 (педагог 1): только неявка Б с «К оплате» (1 000) → педагогу 0 (никто не пришёл).
Ожидаем: баланс А 4 800, Б −1 500 (долг); абонемент А — использовано 2 занятия; касса 6 900;
педагог 1 — 500, педагог 2 — 320; расчёт зарплаты педагогу 1 за вчера (ЗаполнитьНачисления) — 500, ведомость
(ЗП ±, долг не меняет); РКО «Выплата зарплаты» на основании расчёта — долг 0, касса 6 400; второй РКО сверх
остатка расчёта — отказ (В7, В9); расчёт педагогу 2 — 320, долг 320 остаётся.
Отмена проведения урока 1 — его движений нет, баланс А 5 600, Б −500; перепроведение — движения те же.
Уборка — все документы распроведены и удалены, по ученикам/педагогам/кассе теста в регистрах ни строки.
Ставка педагога — одна ветвь (с человека → % → за занятие → за час), не сумма.
    python tools\\тесты\\тест_сквозной.py --база=C:\\1c_bases\\UZ_UNF_B
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from фабрика import Фабрика  # noqa: E402

МЕТКА = "УЗ сквозной тест"

БАЛАНС = ("ВЫБРАТЬ ЕСТЬNULL(СУММА(Р.СуммаОстаток), 0) "
          "ИЗ РегистрНакопления.УЗ_СписанияСуммЗаУроки.Остатки(, Клиент = &Кто) КАК Р")
ЗАНЯТИЙ_АБОНЕМЕНТА = ("ВЫБРАТЬ ЕСТЬNULL(СУММА(Р.КоличествоУроковОстаток), 0) "
                      "ИЗ РегистрНакопления.УЗ_СписанияСуммЗаУроки.Остатки(, Абонемент = &Кто) КАК Р")
КАССА = ("ВЫБРАТЬ ЕСТЬNULL(СУММА(Р.СуммаОстаток), 0) "
         "ИЗ РегистрНакопления.УЗ_Касса.Остатки(, Касса = &Кто) КАК Р")
ДОЛГ_ПЕДАГОГУ = ("ВЫБРАТЬ ЕСТЬNULL(СУММА(Р.СуммаОстаток), 0) "
                 "ИЗ РегистрНакопления.УЗ_РасчетыПоЗарплате.Остатки(, Педагог = &Кто) КАК Р")
ЗП_ОБОРОТ = ("ВЫБРАТЬ ЕСТЬNULL(СУММА(Р.ЗППриход), 0), ЕСТЬNULL(СУММА(Р.ЗПРасход), 0) "
             "ИЗ РегистрНакопления.УЗ_РасчетыПоЗарплате.Обороты(, , , Педагог = &Кто) КАК Р")
ДВИЖЕНИЯ = {
    "УЗ_СписанияСуммЗаУроки": "Р.ВидДвижения, Р.Клиент, Р.Абонемент, Р.Педагог, Р.Тариф, Р.Явка, Р.Сумма, "
                              "Р.Часы, Р.КоличествоУроков, Р.КоличествоЯвок",
    "УЗ_Касса": "Р.ВидДвижения, Р.Клиент, Р.Касса, Р.Сумма",
    "УЗ_РасчетыПоЗарплате": "Р.ВидДвижения, Р.Педагог, ВЫРАЗИТЬ(Р.Комментарий КАК СТРОКА(100)), Р.Сумма, Р.ЗП",
    "УЗ_ДвижениеДисконтныхКарт": "Р.ВидДвижения, Р.ДисконтнаяКарта, Р.СуммаБонусов",
}


def сценарий(т):
    ф = Фабрика(т, МЕТКА)
    c = т.c
    документы = []

    ученик_а = ф.ученик("ученик А")
    ученик_б = ф.ученик("ученик Б")
    ставка_занятие = ф.элемент("УЗ_СтавкиПедагогов", "500 за занятие", ОплатаЗаЗанятие=500)
    ставка_процент = ф.элемент("УЗ_СтавкиПедагогов", "40% с оплаты", ПроцентСОплатыУченика=40)
    педагог1 = ф.педагог("педагог 1", СтавкаПедагога=ставка_занятие)
    педагог2 = ф.педагог("педагог 2", СтавкаПедагога=ставка_процент)
    тариф = ф.элемент("УЗ_Тарифы", "8 000 за 8 уроков", Сумма=8000, КоличествоУроков=8)
    касса = ф.элемент("УЗ_Кассы", "касса")
    абонемент = ф.абонемент(ученик_а, "6 400 за 8 занятий", КоличествоЗанятий=8, ЦенаАбонемента=6400)

    def число(запрос, кто):
        return ф.число(запрос, Кто=кто)

    def равно(что, факт, ожидаем):
        т.проверить(abs(факт - ожидаем) < 0.005, "%s = %s" % (что, ожидаем), "факт %s" % факт)

    def провести(д, что):
        ошибка, сообщения = ф.записать(д, "Проведение")
        т.проверить(ошибка is None, что, "%s %s" % (ошибка, сообщения))
        if ошибка is None:
            документы.append(д.Ссылка)
        return ошибка is None

    def значение(з):
        if isinstance(з, bool):
            return з
        if isinstance(з, (int, float)) or type(з).__name__ == "Decimal":
            return round(float(з), 2)
        return c.String(з)

    def движения(ссылка):
        """Движения документа по всем денежным регистрам — упорядоченный список строк (для сравнения)."""
        итог = []
        for регистр, поля in ДВИЖЕНИЯ.items():
            тз = ф.выбрать("ВЫБРАТЬ %s ИЗ РегистрНакопления.%s КАК Р ГДЕ Р.Регистратор = &Д" % (поля, регистр), Д=ссылка)
            for н in range(тз.Количество()):
                с = тз.Получить(н)
                итог.append((регистр,) + tuple(значение(с.Получить(к)) for к in range(тз.Колонки.Количество())))
        return sorted(итог)

    # ── оплата ──
    пко_а = ф.приход(ученик_а, 6400, Касса=касса, Абонемент=абонемент, Тариф=тариф, Дата=ф.день(-1, 7))
    if not провести(пко_а, "ПКО ученика А по абонементу, 6 400"):
        return
    пко_б = ф.приход(ученик_б, 500, Касса=касса, Дата=ф.день(-1, 7, 5))
    провести(пко_б, "ПКО ученика Б, 500")
    равно("касса после оплат", число(КАССА, касса), 6900)
    равно("баланс ученика А после оплаты", число(БАЛАНС, ученик_а), 6400)

    # ── уроки ──
    урок1 = ф.урок(педагог1, ф.день(-1, 8), 1, [
        dict(Ученик=ученик_а, Тариф=тариф, Абонемент=абонемент, Явка=True, СписатьОплату=True),
        dict(Ученик=ученик_б, Тариф=тариф, Явка=False, СписатьОплату=True)], СтавкаПедагога=ставка_занятие)
    if not провести(урок1, "урок 1: А — явка, Б — неявка с «К оплате»"):
        return
    урок2 = ф.урок(педагог2, ф.день(-1, 10), 1, [
        dict(Ученик=ученик_а, Тариф=тариф, Абонемент=абонемент, Явка=True, СписатьОплату=True)],
        СтавкаПедагога=ставка_процент)
    провести(урок2, "урок 2: А — явка")
    урок3 = ф.урок(педагог1, ф.день(-1, 12), 1, [dict(Ученик=ученик_б, Тариф=тариф, Явка=False, СписатьОплату=True)],
                   СтавкаПедагога=ставка_занятие)
    провести(урок3, "урок 3: только неявка Б с «К оплате»")

    о1 = урок1.Ссылка.ПолучитьОбъект()
    равно("сумма урока 1: 800 по абонементу + 1 000 по тарифу", о1.Сумма, 1800)
    равно("начислено педагогу 1 в уроке (за занятие)", о1.НачисленоПедагогу, 500)
    равно("начислено педагогу 2 в уроке (40 % от 800)", урок2.Ссылка.ПолучитьОбъект().НачисленоПедагогу, 320)
    равно("урок 3 без явки: педагогу 1 «за занятие» не начислено", урок3.Ссылка.ПолучитьОбъект().НачисленоПедагогу, 0)

    равно("баланс ученика А: 6 400 − 800 − 800", число(БАЛАНС, ученик_а), 4800)
    равно("баланс ученика Б: 500 − 1 000 − 1 000 (долг)", число(БАЛАНС, ученик_б), -1500)
    равно("абонемент А: использовано занятий", число(ЗАНЯТИЙ_АБОНЕМЕНТА, абонемент), 2)
    равно("касса после уроков не меняется", число(КАССА, касса), 6900)
    равно("долг педагогу 1 (УЗ_РасчетыПоЗарплате)", число(ДОЛГ_ПЕДАГОГУ, педагог1), 500)
    равно("долг педагогу 2 (УЗ_РасчетыПоЗарплате)", число(ДОЛГ_ПЕДАГОГУ, педагог2), 320)

    были = движения(урок1.Ссылка)
    по_урокам = [с for с in были if с[0] == "УЗ_СписанияСуммЗаУроки"]
    т.проверить(len(по_урокам) == 2 and sorted(с[7] for с in по_урокам) == [800, 1000]
                and all(с[8] == 3600 for с in по_урокам),
                "урок 1: две строки УЗ_СписанияСуммЗаУроки — 800 и 1 000, по 3 600 с", по_урокам)
    явок = sorted(с[10] for с in по_урокам)
    т.проверить(явок == [-1, 0], "урок 1: явка отмечена только у ученика А", явок)
    т.проверить([с for с in были if с[0] == "УЗ_Касса"] == [], "урок не двигает кассу")

    # ── расчёт зарплаты за период → выплата РКО на основании расчёта (В7, В9) ──
    def расчет_зарплаты(педагог, час):
        д = c.Документы.УЗ_РасчетЗарплаты.СоздатьДокумент()
        д.Заполнить(None)
        д.Дата = ф.день(-1, час)
        д.Педагог = педагог
        д.Касса = касса
        д.ДатаНачала = ф.день(-1)
        д.ДатаОкончания = ф.день(-1)
        д.Комментарий = МЕТКА
        д.ЗаполнитьНачисления()   # начисления педагога за период, не вошедшие в другие расчёты
        return д

    расчет1 = расчет_зарплаты(педагог1, 20)
    равно("расчёт педагогу 1 за вчера: к выплате (урок 1 — 500, урок 3 без явки — 0)", расчет1.СуммаДокумента, 500)
    провести(расчет1, "расчёт зарплаты педагогу 1 проведён")
    равно("расчёт — ведомость: долг педагогу 1 не меняется", число(ДОЛГ_ПЕДАГОГУ, педагог1), 500)

    def рко_по_расчету(расчет, сумма, час):
        д = c.Документы.УЗ_РасходДенег.СоздатьДокумент()
        д.Заполнить(расчет.Ссылка)
        д.Дата = ф.день(-1, час)
        д.Касса = касса
        д.СуммаДокумента = сумма
        д.Комментарий = МЕТКА
        return д
    рко = рко_по_расчету(расчет1, 500, 21)
    т.проверить(c.String(рко.ВидОперации) == c.String(c.Перечисления.УЗ_ВидыОпераций.ВыплатаЗарплаты)
                and c.String(рко.ФизЛицо) == c.String(педагог1),
                "РКО на основании расчёта: вид «Выплата зарплаты», педагог 1", c.String(рко.ВидОперации))
    провести(рко, "РКО «Выплата зарплаты» педагогу 1 на основании расчёта, 500")
    равно("долг педагогу 1 после выплаты", число(ДОЛГ_ПЕДАГОГУ, педагог1), 0)
    равно("касса после выплаты уменьшилась на 500", число(КАССА, касса), 6400)
    ошибка, сообщения = ф.записать(рко_по_расчету(расчет1, 1, 22), "Проведение")
    т.проверить(ошибка is not None, "второй РКО сверх остатка расчёта — отказ", "провёлся")
    равно("касса после отказа не изменилась", число(КАССА, касса), 6400)

    расчет2 = расчет_зарплаты(педагог2, 22)
    провести(расчет2, "расчёт зарплаты педагогу 2 (40 % от 800 = 320)")
    зп = ф.выбрать(ЗП_ОБОРОТ, Кто=педагог2)
    зп_приход, зп_расход = (float(зп.Получить(0).Получить(0)), float(зп.Получить(0).Получить(1))) if зп.Количество() else (0, 0)
    т.проверить(зп_приход == 320 and зп_расход == 320, "расчёт зарплаты педагогу 2: ЗП +320 / −320 (ведомость)",
                "%s / %s" % (зп_приход, зп_расход))
    равно("долг педагогу 2 после расчёта не меняется (не выплачено)", число(ДОЛГ_ПЕДАГОГУ, педагог2), 320)
    # ── отмена проведения и перепроведение урока 1 ──
    о1 = урок1.Ссылка.ПолучитьОбъект()
    ошибка, сообщения = ф.записать(о1, "ОтменаПроведения")
    т.проверить(ошибка is None, "отмена проведения урока 1", "%s %s" % (ошибка, сообщения))
    т.проверить(движения(урок1.Ссылка) == [], "после отмены проведения у урока 1 нет движений", движения(урок1.Ссылка))
    равно("баланс ученика А без урока 1", число(БАЛАНС, ученик_а), 5600)
    равно("баланс ученика Б без урока 1", число(БАЛАНС, ученик_б), -500)
    равно("абонемент А без урока 1: использовано", число(ЗАНЯТИЙ_АБОНЕМЕНТА, абонемент), 1)
    равно("педагог 1 без урока 1: выплачено 500 сверх начисленного", число(ДОЛГ_ПЕДАГОГУ, педагог1), -500)

    о1 = урок1.Ссылка.ПолучитьОбъект()
    ошибка, сообщения = ф.записать(о1, "Проведение")
    т.проверить(ошибка is None, "перепроведение урока 1", "%s %s" % (ошибка, сообщения))
    т.проверить(движения(урок1.Ссылка) == были, "перепроведение: движения урока 1 те же, что при первом проведении",
                движения(урок1.Ссылка))
    равно("баланс ученика А после перепроведения", число(БАЛАНС, ученик_а), 4800)
    равно("баланс ученика Б после перепроведения", число(БАЛАНС, ученик_б), -1500)
    равно("долг педагогу 1 после перепроведения", число(ДОЛГ_ПЕДАГОГУ, педагог1), 0)

    # ── уборка за собой (здесь, чтобы проверить, что в регистрах не осталось ни строки) ──
    for ссылка in reversed(документы):
        о = ссылка.ПолучитьОбъект()
        if о.Проведен:
            о.Записать(c.РежимЗаписиДокумента.ОтменаПроведения)
        о.Удалить()
    осталось = 0
    for регистр, поле, кто in (("УЗ_СписанияСуммЗаУроки", "Клиент", ученик_а), ("УЗ_СписанияСуммЗаУроки", "Клиент", ученик_б),
                               ("УЗ_Касса", "Касса", касса), ("УЗ_РасчетыПоЗарплате", "Педагог", педагог1),
                               ("УЗ_РасчетыПоЗарплате", "Педагог", педагог2)):
        осталось += int(ф.число("ВЫБРАТЬ КОЛИЧЕСТВО(*) ИЗ РегистрНакопления.%s КАК Р ГДЕ Р.%s = &Кто" % (регистр, поле), Кто=кто))
    т.проверить(осталось == 0, "уборка: документы теста удалены, движений по его ученикам, кассе, педагогам нет",
                "строк %d" % осталось)


if __name__ == "__main__":
    запустить("сквозной", сценарий)
