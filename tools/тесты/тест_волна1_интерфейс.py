"""Волна 1, интерфейс: то, что проверяется без формы (формы — глазами в веб-клиенте, снимки
C:\\1c_bases\\веб\\снимки_волна1\\).

  * абонемент: наименование составляется само (ФИО + дата начала, в 30 символов, уникально — « (2)»),
    пустое наименование заполняется при проверке заполнения; уроки и цена берутся из тарифа;
  * В10 для помощника уроков и календаря (УЗ_Общий.ЗаписатьУрок): урок, который ещё не начался, в режиме
    «проводить» только записывается с пометкой; прошедший — проводится; отказ — причиной, а не исключением;
  * настройки: запись менеджером записи не плодит записей (форма настроек пишет именно так).

    python tools\\тесты\\тест_волна1_интерфейс.py --база=C:\\1c_bases\\UZ_UNF_C
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from фабрика import Фабрика  # noqa: E402

МЕТКА = "УЗ тест волны 1"


def сценарий(т):
    ф = Фабрика(т, МЕТКА)
    c = т.c
    менеджер = c.Справочники.УЗ_Абонемент

    # ── абонемент: наименование ──
    ученик = ф.ученик("Длиннофамильный Ученик Иванович")
    имя_ученика = "%s %s" % (МЕТКА, "Длиннофамильный Ученик Иванович")
    начало = ф.день(0)
    хвост = " с " + ф.сегодня.strftime("%d.%m.%y")
    первое = менеджер.АвтоНаименование(ученик, начало)
    т.проверить(len(первое) <= 30 and первое.endswith(хвост) and первое.startswith(имя_ученика[:10]),
                "абонемент: наименование «ФИО с дд.мм.гг» в 30 символов", первое)
    аб = ф.абонемент(ученик, "x", ДатаНачала=начало)
    о = аб.ПолучитьОбъект()
    о.Наименование = первое
    о.Записать()
    второе = менеджер.АвтоНаименование(ученик, начало)
    т.проверить(второе == первое + " (2)" or (второе.endswith(" (2)") and len(второе) <= 30),
                "абонемент: второе наименование того же ученика с той же даты — « (2)»", второе)
    т.проверить(менеджер.АвтоНаименование(ученик, начало, аб) == первое,
                "абонемент: при перезаписи своё наименование не считается занятым")
    пустой = менеджер.СоздатьЭлемент()
    пустой.ФизЛицо = ученик
    пустой.ДатаНачала = ф.день(1)
    пустой.ПроверитьЗаполнение()
    т.проверить(str(пустой.Наименование).startswith(имя_ученика[:10]),
                "абонемент: пустое наименование заполняется при проверке заполнения", пустой.Наименование)

    # ── абонемент: уроки и цена из тарифа ──
    тариф = ф.элемент("УЗ_Тарифы", "8 занятий", Сумма=6400, КоличествоУроков=8)
    знач = менеджер.ЗначенияПоТарифу(тариф, начало)
    т.проверить(знач is not None and float(знач.Сумма) == 6400 and float(знач.КоличествоУроков) == 8,
                "абонемент: по тарифу 6 400 за 8 уроков", знач and (знач.Сумма, знач.КоличествоУроков))
    т.проверить(менеджер.ЗначенияПоТарифу(c.Справочники.УЗ_Тарифы.ПустаяСсылка(), начало) is None,
                "абонемент: без тарифа — ничего не заполняется")

    # ── В10: будущий урок только записывается ──
    педагог = ф.педагог()
    будущий = ф.урок(педагог, ф.день(3, 10), 1, [dict(Ученик=ученик, Явка=False, СписатьОплату=False)])
    итог = c.УЗ_Общий.ЗаписатьУрок(будущий, True)
    if not будущий.Ссылка.Пустая():
        ф.уборка_документа(будущий)
    т.проверить(итог.Успех and not будущий.Проведен and "без проведения" in str(итог.Пометка),
                "В10: урок через 3 дня в режиме «проводить» записан без проведения, с пометкой",
                "%s %s %s" % (итог.Успех, будущий.Проведен, итог.Пометка))
    прошедший = ф.урок(педагог, ф.день(-1, 10), 1, [dict(Ученик=ученик, Явка=False, СписатьОплату=False)])
    итог = c.УЗ_Общий.ЗаписатьУрок(прошедший, True)
    if not прошедший.Ссылка.Пустая():
        ф.уборка_документа(прошедший)
    т.проверить(итог.Успех and прошедший.Проведен and str(итог.Пометка) == "",
                "В10: вчерашний урок проводится", "%s %s %s" % (итог.Успех, прошедший.Проведен, итог.Текст))
    # то же время и педагог — пересечение: отказ текстом, без исключения
    двойник = ф.урок(педагог, ф.день(-1, 10), 1, [dict(Ученик=ученик, Явка=False, СписатьОплату=False)])
    итог = c.УЗ_Общий.ЗаписатьУрок(двойник, True)
    if not двойник.Ссылка.Пустая():
        ф.уборка_документа(двойник)
    т.проверить(not итог.Успех and str(итог.Текст) != "",
                "В10: отказ проведения (пересечение педагога) — причиной в ответе", итог.Текст)

    # ── настройки: одна запись ──
    набор = c.РегистрыСведений.УЗ_Настройки.СоздатьНаборЗаписей()
    набор.Прочитать()
    было = набор.Количество()
    if было == 0:
        print("  (настройки: записи нет — проверку одной записи пропускаем, базу не меняем)")
        return
    м = c.РегистрыСведений.УЗ_Настройки.СоздатьМенеджерЗаписи()
    м.Прочитать()
    м.Записать(True)
    набор.Прочитать()
    т.проверить(набор.Количество() == 1, "настройки: запись менеджером записи — одна запись",
                набор.Количество())


if __name__ == "__main__":
    запустить("волна1_интерфейс", сценарий)
