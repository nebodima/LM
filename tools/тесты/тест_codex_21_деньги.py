"""Аудит Codex версии 2.1 (docs/аудит_codex_2.1_2026-09-30.md), денежные находки 1, 5, 6, 7, 9.

1. Шаг обновления 2 (приходы 2.0 без расшифровки → строка из шапки) не удваивает оплату, если приход записали
   обычной записью между запросом шага и обработкой документа: строка из шапки добавляется под исключительной
   блокировкой ПОСЛЕ перечитывания, только если строк нет (было: вторая строка 2 000, следующая запись — 4 000).
2. (5) «Заполнить по долгам» плательщика берёт и долг без предмета (начисление ученику без предмета) вместе с
   долгами предметов (было: только математика 500, вступительный взнос 1 000 оставался долгом).
3. (6) «Заполнить по долгам» проведённого прихода считает долг без его собственных движений (он их заменит):
   исходные долги 3 000 / 2 000, приход 1 000 / 1 000 → строки 3 000 / 2 000, повторное заполнение — то же
   (было: 2 000 / 1 000, после перепроведения — 1 000 / 1 000, результат колебался).
4. (7) Возврат на основании абонемента: получатель — кто платил на ДАТУ возврата (было: оплата папы будущей датой).
5. (9) Итог расшифровки больше вместимости суммы документа (99 999 999,99) — отказ записи (было: сумма документа
   молча урезалась, движения кассы — полные 120 000 000).

    python tools\\тесты\\тест_codex_21_деньги.py --база=C:\\1c_bases\\UZ_BP_K --пользователь=1
"""
# затрагивает: УЗ_ПриходДенег, УЗ_РасходДенег, УЗ_ОбновлениеДанных, УЗ_Сервер, УЗ_Общий, УЗ_Касса
# затрагивает: УЗ_СписанияСуммЗаУроки
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from _деньги import Данные  # noqa: E402
from фабрика import Фабрика  # noqa: E402

МЕТКА = "_Тест Codex 2.1 деньги"
ДОЛГ = ("ВЫБРАТЬ ЕСТЬNULL(СУММА(Р.СуммаОстаток), 0) ИЗ РегистрНакопления.УЗ_СписанияСуммЗаУроки.Остатки(, "
        "Клиент = &Ученик И Организация = &Организация) КАК Р")
КАССА = ("ВЫБРАТЬ ЕСТЬNULL(СУММА(Р.Сумма), 0) ИЗ РегистрНакопления.УЗ_Касса КАК Р ГДЕ Р.Регистратор = &Р")


def сценарий(т):
    c = т.c
    ф = Фабрика(т, МЕТКА)
    д_ = Данные(т, МЕТКА)
    ст = c.String
    орг = ф.организация("А")
    касса = ф.элемент("УЗ_Кассы", "касса", Организация=орг)
    математика = ф.элемент("УЗ_ПредметыОбучения", "математика")
    гитара = ф.элемент("УЗ_ПредметыОбучения", "гитара")
    мама = ф.элемент("УЗ_ФизЛица", "мама")
    папа = ф.элемент("УЗ_ФизЛица", "папа")

    def ученик(имя):
        о = c.Справочники.УЗ_ФизЛица.СоздатьЭлемент()
        о.Наименование = "%s %s" % (МЕТКА, имя)
        с = о.Плательщики.Добавить()
        с.Плательщик, с.КемПриходится, с.Основной = мама, "мама", True
        с = о.Плательщики.Добавить()
        с.Плательщик, с.КемПриходится = папа, "папа"
        о.Записать()
        ссылка = о.Ссылка
        т.убрать(lambda: т.удалить_объект(ссылка), "ученик %s" % имя, пакет=True)
        return ссылка

    сын = ученик("сын")
    дочь = ученик("дочь")
    третий = ученик("третий")

    def строки_по_долгам(плательщик, исключить=None):
        менеджер = c.Документы.УЗ_ПриходДенег
        строки = (менеджер.СтрокиПоДолгамПлательщика(плательщик, орг) if исключить is None
                  else менеджер.СтрокиПоДолгамПлательщика(плательщик, орг, исключить))
        return sorted((ст(с.Ученик), ст(с.ПредметОбучения), float(с.Сумма)) for с in строки)

    # ── находка 1: шаг обновления 2 и приход, записанный обычной записью после запроса шага ──
    старый = ф.приход(третий, 2000, Организация=орг, Касса=касса, ПредметОбучения=гитара, Дата=ф.день(-3, 9))
    ош, сообщ = ф.записать(старый)
    т.проверить(ош is None, "подготовка: приход 2 000", "%s %s" % (ош, сообщ))
    о = старый.Ссылка.ПолучитьОбъект()
    о.РасшифровкаПлатежа.Очистить()   # «как в 2.0»: расшифровки нет — шаг 2 выберет его запросом
    о.ОбменДанными.Загрузка = True
    о.Записать()
    о = старый.Ссылка.ПолучитьОбъект()   # менеджер меняет комментарий: обычная запись строит строку из шапки
    о.Комментарий = МЕТКА + " комментарий менеджера"
    ош, сообщ = ф.записать(о)
    т.проверить(ош is None and о.РасшифровкаПлатежа.Количество() == 1, "подготовка: обычная запись — строка из шапки",
                "%s %s" % (ош, сообщ))
    c.УЗ_ОбновлениеДанных.РасшифровкаПрежнегоПрихода(старый.Ссылка)   # шаг 2 обрабатывает выбранный ранее приход
    о = старый.Ссылка.ПолучитьОбъект()
    т.проверить(о.РасшифровкаПлатежа.Количество() == 1 and float(о.РасшифровкаПлатежа.Получить(0).Сумма) == 2000,
                "находка 1: шаг 2 перечитал приход — вторая строка из шапки не добавлена",
                "строк %s" % о.РасшифровкаПлатежа.Количество())
    ош, сообщ = ф.записать(о)
    т.проверить(ош is None and float(о.СуммаДокумента) == 2000 and ф.число(КАССА, Р=старый.Ссылка) == 2000,
                "находка 1: после перепроведения сумма и касса — 2 000 (не 4 000)",
                "%s %s / %s / %s" % (ош, сообщ, о.СуммаДокумента, ф.число(КАССА, Р=старый.Ссылка)))

    # долги: сын — математика 500 и взнос без предмета 1 000; дочь — гитара 2 000 (вчера)
    носитель = д_.регистратор()
    д_.движения("УЗ_СписанияСуммЗаУроки", носитель, [
        ("-", ф.день(-1, 9), {"Клиент": сын, "ПредметОбучения": математика, "Сумма": 500, "Организация": орг}),
        ("-", ф.день(-1, 9), {"Клиент": сын, "Сумма": 1000, "Организация": орг}),
        ("-", ф.день(-1, 9), {"Клиент": дочь, "ПредметОбучения": гитара, "Сумма": 2000, "Организация": орг})])

    # ── находка 5: долг без предмета вместе с долгами предметов ──
    пусто = ст(c.Справочники.УЗ_ПредметыОбучения.ПустаяСсылка())
    по_долгам = строки_по_долгам(мама)
    ждём = sorted([(ст(сын), ст(математика), 500.0), (ст(сын), пусто, 1000.0), (ст(дочь), ст(гитара), 2000.0)])
    т.проверить(по_долгам == ждём, "находка 5: по долгам мамы — математика 500, без предмета 1 000, гитара 2 000",
                по_долгам)

    # ── находка 6: заполнение проведённого прихода по долгам — без его собственных движений ──
    пко = c.Документы.УЗ_ПриходДенег.СоздатьДокумент()
    пко.Дата, пко.ВидОперации, пко.Организация, пко.Касса = ф.день(0, 9), c.Перечисления.УЗ_ВидыОпераций.КассаУченики, орг, касса
    пко.Плательщик, пко.Комментарий = мама, МЕТКА
    for у, п, сумма in ((сын, математика, 500), (сын, None, 500), (дочь, гитара, 1000)):
        с = пко.РасшифровкаПлатежа.Добавить()
        с.Ученик, с.Сумма = у, сумма
        if п is not None:
            с.ПредметОбучения = п
    ош, сообщ = ф.записать(пко)
    т.проверить(ош is None, "подготовка: частичный приход 500 / 500 / 1 000", "%s %s" % (ош, сообщ))
    по_долгам = строки_по_долгам(мама, пко.Ссылка)
    т.проверить(по_долгам == ждём, "находка 6: заполнение проведённого прихода — долги до него (500 / 1 000 / 2 000)",
                по_долгам)
    о = пко.Ссылка.ПолучитьОбъект()   # как форма: строки по долгам заменяют расшифровку, перепроведение
    о.РасшифровкаПлатежа.Очистить()
    for строка in c.Документы.УЗ_ПриходДенег.СтрокиПоДолгамПлательщика(мама, орг, пко.Ссылка):
        с = о.РасшифровкаПлатежа.Добавить()
        с.Ученик, с.ПредметОбучения, с.Сумма = строка.Ученик, строка.ПредметОбучения, строка.Сумма
    ош, сообщ = ф.записать(о)
    долги = (ф.число(ДОЛГ, Ученик=сын, Организация=орг), ф.число(ДОЛГ, Ученик=дочь, Организация=орг))
    т.проверить(ош is None and долги == (0, 0), "находка 6: после перепроведения долгов нет", "%s %s %s" % (ош, сообщ, долги))
    т.проверить(строки_по_долгам(мама, пко.Ссылка) == ждём, "находка 6: повторное заполнение — то же (не колеблется)",
                строки_по_долгам(мама, пко.Ссылка))

    # ── находка 7: получатель возврата — кто платил на дату возврата ──
    абонемент = ф.абонемент(дочь, "абонемент", ПредметОбучения=математика, Организация=орг, ЦенаАбонемента=1000)
    for кто, сдвиг, аб in ((мама, -10, абонемент), (папа, 10, None)):
        п = ф.приход(дочь, 1000, Организация=орг, Касса=касса, ПредметОбучения=математика, Плательщик=кто,
                     Дата=ф.день(сдвиг, 9))
        if аб is not None:
            п.Абонемент = аб
        ош, сообщ = ф.записать(п)
        т.проверить(ош is None, "подготовка: оплата %s (день %+d)" % (ст(кто), сдвиг), "%s %s" % (ош, сообщ))
    возврат = c.Документы.УЗ_РасходДенег.СоздатьДокумент()
    возврат.Дата = ф.день(0, 10)
    возврат.Заполнить(абонемент)
    т.проверить(ст(возврат.Получатель) == ст(мама),
                "находка 7: возврат по абонементу на сегодня — получатель мама (оплата папы — будущей датой)",
                ст(возврат.Получатель))

    # ── находка 9: итог расшифровки больше вместимости суммы документа ──
    большой = c.Документы.УЗ_ПриходДенег.СоздатьДокумент()
    большой.Дата, большой.ВидОперации, большой.Организация, большой.Касса = (
        ф.день(0, 9), c.Перечисления.УЗ_ВидыОпераций.КассаУченики, орг, касса)
    большой.Комментарий = МЕТКА
    for у in (сын, дочь):
        с = большой.РасшифровкаПлатежа.Добавить()
        с.Ученик, с.ПредметОбучения, с.Сумма = у, гитара, 60000000
    ош, сообщ = ф.записать(большой)
    т.проверить(ош is not None and any("99 999 999,99" in м for м, _ in сообщ),
                "находка 9: итог 120 000 000 больше 99 999 999,99 — отказ с причиной",
                "%s %s / сумма документа %s" % (ош, сообщ, большой.СуммаДокумента))


if __name__ == "__main__":
    запустить("codex_21_деньги", сценарий)
