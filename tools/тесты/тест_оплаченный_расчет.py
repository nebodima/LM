"""Оплаченный расчёт зарплаты и организация выплаты (повторный аудит Codex 28.09.2026: N01, N02).

N01. Было: оплаченный расчёт (по нему проведён РКО «Выплата зарплаты») можно было отменить, изменить, пометить
на удаление; его начисления освобождались, входили в новый расчёт и выплачивались второй раз — начислено 1 000,
выдано 2 000. Стало: пока по расчёту есть проведённая выплата — отмена, пометка удаления, удаление и смена
состава/суммы отказываются (комментарий менять можно); после отмены выплаты расчёт снова свободен. Расчёт
оплаченный, но не проведённый (записан загрузкой — обмен данными идёт мимо проверок), всё равно держит свои
начисления: новый расчёт их не заполняет и не проводит.
N02. Было: РКО по ведомости организации А можно было провести от организации Б — ведомость А «оплачена», долг А
остался, в Б переплата. Стало: выплата только от организации расчёта.

    python tools\\тесты\\тест_оплаченный_расчет.py --база=C:\\1c_bases\\UZ_UNF_A
"""
# объекты src_ext, которых нет в тексте теста (выбор тестов --быстро, tools/выбор_тестов.py):
# затрагивает: УЗ_УрокиВРасчетахЗарплаты
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import дата, запустить, ошибка_записи  # noqa: E402
from _деньги import Данные, сообщения  # noqa: E402
from фабрика import Фабрика  # noqa: E402

МЕТКА = "_Тест оплаченный расчёт"


def сценарий(т):
    c = т.c
    д = Данные(т, МЕТКА)
    ф = Фабрика(т, МЕТКА)
    виды = c.Перечисления.УЗ_ВидыОпераций
    орг_а = ф.организация("А")
    орг_б = ф.организация("Б")
    педагог = д.элемент("УЗ_ФизЛица", "педагог", ЭтоПедагог=True)
    касса = д.элемент("УЗ_Кассы", "касса")
    # деньги в кассе (В14: касса не уходит в минус) — движением на носителе
    д.движения("УЗ_Касса", д.регистратор(), [("+", дата(2026, 8, 1, 9), {"Касса": касса, "Сумма": 10000, "Организация": орг_а})])

    н = д.документ("УЗ_НачисленияПедагогам", Дата=дата(2026, 8, 5, 10), Педагог=педагог, Организация=орг_а)
    н.НачисленияПедагогам.Добавить().Сумма = 1000
    т.проверить(д.записать(н) is None, "начисление педагогу 1 000 в организации А проведено")

    def расчёт(час):
        р = д.документ("УЗ_РасчетЗарплаты", Дата=дата(2026, 9, 1, час), Педагог=педагог, Касса=касса, Организация=орг_а,
                       ДатаНачала=дата(2026, 8, 1), ДатаОкончания=дата(2026, 8, 31))
        р.ЗаполнитьНачисления()
        return р

    р1 = расчёт(9)
    т.проверить(д.записать(р1) is None and float(р1.СуммаДокумента) == 1000, "расчёт Р1 на 1 000 (организация А) проведён")

    def долг(организация):
        return т.выбрать("ВЫБРАТЬ ЕСТЬNULL(СУММА(О.СуммаОстаток), 0) КАК Сумма ИЗ "
                         "РегистрНакопления.УЗ_РасчетыПоЗарплате.Остатки(, Педагог = &П И Организация = &О) КАК О",
                         П=педагог, О=организация).Получить(0).Сумма

    def рко(час, организация):
        р = д.документ("УЗ_РасходДенег")
        р.Заполнить(р1.Ссылка)
        р.Дата = дата(2026, 9, 7, час)
        р.Комментарий = МЕТКА
        р.Организация = организация
        return р

    # ── N02: выплата по ведомости А от организации Б — отказ, долги А и Б прежние ──
    ош = д.записать(рко(10, орг_б))
    т.проверить(ош is not None and "организации" in ош and float(долг(орг_а)) == 1000 and float(долг(орг_б)) == 0,
                "N02: РКО от организации Б по расчёту организации А — отказ; долг А 1 000, Б 0",
                "%s; долг А %s, Б %s" % (ош, долг(орг_а), долг(орг_б)))
    выплата = рко(11, орг_а)
    ош = д.записать(выплата)
    т.проверить(ош is None and float(долг(орг_а)) == 0, "выплата 1 000 от организации А по расчёту А проведена, долг А 0",
                ош or долг(орг_а))

    # ── N01: оплаченный расчёт не отменяется и не меняется ──
    def попытка(действие):
        сообщения(c)
        ош = ошибка_записи(действие)
        return "%s [%s]" % (ош, сообщения(c)) if ош else None

    о = р1.Ссылка.ПолучитьОбъект()
    ош = попытка(lambda: о.Записать(c.РежимЗаписиДокумента.ОтменаПроведения))
    т.проверить(ош is not None and "уже выплачена" in ош and р1.Ссылка.ПолучитьОбъект().Проведен,
                "N01: отмена проведения оплаченного расчёта — отказ с причиной, расчёт проведён", ош)
    о = р1.Ссылка.ПолучитьОбъект()
    ош = попытка(lambda: о.УстановитьПометкуУдаления(True))
    т.проверить(ош is not None and not р1.Ссылка.ПолучитьОбъект().ПометкаУдаления,
                "N01: пометка удаления оплаченного расчёта — отказ", ош)
    о = р1.Ссылка.ПолучитьОбъект()
    о.ДД.Получить(0).КОплате = 500
    ош = попытка(lambda: о.Записать(c.РежимЗаписиДокумента.Проведение))
    т.проверить(ош is not None and "изменить" in ош and float(р1.Ссылка.ПолучитьОбъект().СуммаДокумента) == 1000,
                "N01: смена суммы к оплате оплаченного расчёта — отказ, сумма 1 000", ош)
    о = р1.Ссылка.ПолучитьОбъект()
    ош = попытка(lambda: о.Удалить())
    т.проверить(ош is not None and not р1.Ссылка.ПолучитьОбъект() is None, "N01: удаление оплаченного расчёта — отказ", ош)
    о = р1.Ссылка.ПолучитьОбъект()
    о.Комментарий = МЕТКА + " (комментарий)"
    ош = попытка(lambda: о.Записать(c.РежимЗаписиДокумента.Проведение))
    т.проверить(ош is None, "комментарий оплаченного расчёта менять можно (перепроведение без изменения состава)", ош)

    # после отмены выплаты расчёт снова свободен
    ош = попытка(lambda: выплата.Ссылка.ПолучитьОбъект().Записать(c.РежимЗаписиДокумента.ОтменаПроведения))
    т.проверить(ош is None, "отмена проведения выплаты", ош)
    о = р1.Ссылка.ПолучитьОбъект()
    ош = попытка(lambda: о.Записать(c.РежимЗаписиДокумента.ОтменаПроведения))
    т.проверить(ош is None, "без выплаты расчёт отменяется", ош)
    о = р1.Ссылка.ПолучитьОбъект()
    ош = попытка(lambda: о.Записать(c.РежимЗаписиДокумента.Проведение))
    т.проверить(ош is None, "…и проводится снова", ош)
    ош = попытка(lambda: выплата.Ссылка.ПолучитьОбъект().Записать(c.РежимЗаписиДокумента.Проведение))
    т.проверить(ош is None and float(долг(орг_а)) == 0, "выплата проведена снова, долг А 0", ош or долг(орг_а))

    # ── оплаченный расчёт снят с проведения загрузкой (обмен данными — мимо проверок) ──
    о = р1.Ссылка.ПолучитьОбъект()
    о.ОбменДанными.Загрузка = True   # отмена проведения в загрузке запрещена: снимаем флаг и движения сами
    о.Проведен = False
    о.Записать()
    набор = c.РегистрыНакопления.УЗ_РасчетыПоЗарплате.СоздатьНаборЗаписей()
    набор.Отбор.Регистратор.Установить(р1.Ссылка)
    набор.ОбменДанными.Загрузка = True
    набор.Записать()
    т.проверить(not р1.Ссылка.ПолучитьОбъект().Проведен, "заготовка: оплаченный Р1 не проведён (записан загрузкой)")
    р2 = расчёт(12)
    т.проверить(р2.ДД.Количество() == 0 and float(р2.СуммаДокумента) == 0,
                "N01: новый расчёт не заполняет начисления оплаченного (хоть и непроведённого) Р1",
                "строк %s, сумма %s" % (р2.ДД.Количество(), р2.СуммаДокумента))
    строка = р2.ДД.Добавить()
    строка.Документ = н.Ссылка
    строка.Начисление = 1000
    строка.КОплате = 1000
    ош = д.записать(р2)
    т.проверить(ош is not None and "уже вошло" in ош and (р2.Ссылка.Пустая() or not р2.Ссылка.ПолучитьОбъект().Проведен),
                "N01: начисление оплаченного Р1, вписанное в новый расчёт руками, — отказ проведения", ош)


if __name__ == "__main__":
    запустить("оплаченный_расчет", сценарий)
