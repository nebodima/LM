"""Логика «оповещения о долге» (docs/логики/оповещения_и_почта.md, сценарии 6–9, 14; решение В27; N08 прав).

Две свои организации (фабрика), «Оповещать о задолженности за» 2 дня, задание — только по своим ученикам.
  1. Срок — от даты ВОЗНИКНОВЕНИЯ долга (сценарий 6): −1 000 три дня назад, погашено вчера (0), −500 час назад —
     оповещения нет (долгу час; было: две точки «сейчас» и «2 дня назад» обе в минусе — оповещал сразу).
  2. Сумма обновляется (сценарий 7): долг 1 000 трёхдневный — одно оповещение «… (А): 1 000,00»; ещё −2 000 —
     то же одно оповещение, в нём «3 000,00» (было: «замерзало» на 1 000).
  3. Погашенный долг закрывает оповещение (сценарий 8): +3 000 — оповещение завершено (было: висело у всех).
  4. Письмо раз в N дней, пока долг не погашен (В27): почта включена на выдуманный SMTP, песочница сеанса. Первый
     запуск — одно письмо и «Дата письма»; повторный — писем нет; «Дата письма» сдвинута на 3 дня назад — ещё одно
     письмо (было: одно письмо на «эпизод» до ручного «Завершить»). Ни одной настоящей отправки в журнале.
  5. Права (N08, сценарий 14): менеджер (свой пользователь ИБ с ролью УЗ_ОсновнаяРоль) напрямую — как форма
     записи — не может завершить общее оповещение о долге, записать общее и передать своё напоминание всем;
     своё напоминание записывает. Общее оповещение после попыток не завершено.
  6. Период показа по умолчанию один — 300 с (УЗ_ОбщийКлиентСервер.ПериодОповещенияПоУмолчанию): сервер при
     пустой настройке отдаёт 300 (было 60), форма настроек и обновление данных берут ту же функцию.
Красное на старом коде (28.09.2026): 1, 2, 3, 4 (повтор письма; «Дата письма» не было), 5, 6.

    python tools\\тесты\\логика_оповещения.py --база=C:\\1c_bases\\UZ_UNF_A
"""
import datetime
import gc
import os
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить, позиция_журнала, события_журнала, текст_ошибки  # noqa: E402
from _деньги import Данные  # noqa: E402
from фабрика import Фабрика  # noqa: E402
import тест_оповещения as оп  # noqa: E402
import тест_права as права  # noqa: E402

МЕТКА = "_Тест логика оповещений"
МЕНЕДЖЕР = "УЗ тест логика оповещений менеджер"
АДРЕС = "dolg.test@example.invalid"
ИСХОДНИКИ = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "src_ext"))


def попытка(действие):
    try:
        return действие()
    except Exception as е:
        return "ошибка: " + текст_ошибки(е, 200)


def оповещения(т, ученик):
    """[(Описание, Завершено, Организация, ДатаПисьма есть)] незавершённые и завершённые записи ученика."""
    тз = т.выбрать("""ВЫБРАТЬ О.Описание КАК Описание, О.Завершено КАК Завершено, О.Организация КАК Организация,
        О.ВремяСобытия КАК ВремяСобытия ИЗ РегистрСведений.УЗ_Оповещения КАК О ГДЕ О.Источник = &Источник""",
                   Источник=ученик)
    return [(оп.пробелы(з.Описание), bool(з.Завершено), т.c.String(з.Организация)) for з in тз]


def сценарий(т):
    c = т.c
    if not c.УЗ_Почта.ПесочницаВключена():
        raise RuntimeError("песочница почты не включена — сценарий не запускаю")
    журнал = позиция_журнала(т.база)
    оп.выключить_почту(т)
    д = Данные(т, МЕТКА)
    ф = Фабрика(т, МЕТКА)
    орг_а = ф.организация("Студия А")
    сейчас = c.ТекущаяДатаСеанса()

    def назад(дней=0, часов=0):
        return сейчас - datetime.timedelta(days=дней, hours=часов)

    def ученик(имя, **реквизиты):
        у = д.элемент("УЗ_ФизЛица", имя, **реквизиты)
        т.убрать(lambda: оп.удалить_оповещения(т, у), "оповещения %s" % имя)
        return у

    def движение(кто, когда, сумма):
        д.движения("УЗ_СписанияСуммЗаУроки", д.регистратор(), [
            ("+" if сумма > 0 else "-", когда, {"Клиент": кто, "Сумма": abs(сумма), "Организация": орг_а})])

    настройка = c.РегистрыСведений.УЗ_Настройки.СоздатьМенеджерЗаписи()
    настройка.Прочитать()
    была = настройка.Выбран()
    прежние = (настройка.ИспользоватьОповещения, настройка.ОповещатьОЗадолженности, настройка.ПериодОповещения)

    def вернуть_настройку():
        н = c.РегистрыСведений.УЗ_Настройки.СоздатьМенеджерЗаписи()
        н.Прочитать()
        if была:
            н.ИспользоватьОповещения, н.ОповещатьОЗадолженности, н.ПериодОповещения = прежние
            н.Записать()
        else:
            н.Удалить()
    т.убрать(вернуть_настройку, "настройки оповещений")
    настройка.ИспользоватьОповещения = True
    настройка.ОповещатьОЗадолженности = 2
    настройка.Записать()

    # ── 1. срок — от возникновения долга ──
    свежий = ученик("свежий долг")
    движение(свежий, назад(3), -1000)
    движение(свежий, назад(1), 1000)
    движение(свежий, назад(0, 1), -500)
    c.УЗ_Сервер.ПроверкаЗадолженности(т.массив(свежий))
    т.проверить(оповещения(т, свежий) == [],
                "срок от возникновения долга: погашен вчера, новый долг час назад — оповещения нет (было: сразу)",
                оповещения(т, свежий))

    # ── 2–3. сумма обновляется, погашенный долг закрывает ──
    должник = ученик("должник")
    движение(должник, назад(3), -1000)
    c.УЗ_Сервер.ПроверкаЗадолженности(т.массив(должник))
    имя_а = c.String(орг_а)
    ждём = "Задолженность %s (%s): 1 000,00" % (c.String(должник), имя_а)
    т.проверить(оповещения(т, должник) == [(ждём, False, имя_а)], "долг 1 000 трёхдневный — одно оповещение «%s»" % ждём,
                оповещения(т, должник))
    движение(должник, назад(0, 1), -2000)
    c.УЗ_Сервер.ПроверкаЗадолженности(т.массив(должник))
    ждём = "Задолженность %s (%s): 3 000,00" % (c.String(должник), имя_а)
    т.проверить(оповещения(т, должник) == [(ждём, False, имя_а)],
                "долг вырос до 3 000 — то же оповещение, сумма обновлена (было: 1 000)", оповещения(т, должник))
    движение(должник, назад(0, 0.5), 3000)
    c.УЗ_Сервер.ПроверкаЗадолженности(т.массив(должник))
    т.проверить([з[1] for з in оповещения(т, должник)] == [True],
                "долг погашен — оповещение закрыто само (было: висело незавершённым)", оповещения(т, должник))

    # ── 4. письмо раз в N дней ──
    с_адресом = ученик("с адресом", EMail=АДРЕС, ОповеститьПоEmail=True)
    движение(с_адресом, назад(3), -1000)
    оп.настроить_почту(т, Включена=True, СерверSMTP=оп.ВЫДУМАННЫЙ_SMTP, Порт=25, ИспользоватьSSL=False, Логин="",
                       АдресОтправителя="uz-test@example.invalid", ПисьмаОЗадолженности=True)

    def писем(позиция):
        return len([з for з in (события_журнала(т.база, позиция, "Учёт занятий.Почта.Песочница") or []) if АДРЕС in з])
    п1 = позиция_журнала(т.база)
    c.УЗ_Сервер.ПроверкаЗадолженности(т.массив(с_адресом))
    п2 = позиция_журнала(т.база)
    c.УЗ_Сервер.ПроверкаЗадолженности(т.массив(с_адресом))
    п3 = позиция_журнала(т.база)
    т.проверить((писем(п1) - писем(п2), писем(п2)) == (1, 0),
                "письмо о долге: первый запуск — одно письмо, повторный в тот же день — ни одного",
                (писем(п1) - писем(п2), писем(п2)))
    набор = c.РегистрыСведений.УЗ_Оповещения.СоздатьНаборЗаписей()
    набор.Отбор.Источник.Установить(с_адресом)
    набор.Прочитать()
    есть_дата = попытка(lambda: [з.ДатаПисьма.year >= 1900 for з in набор])
    т.проверить(есть_дата == [True], "в оповещении записана «Дата письма»", есть_дата)
    if есть_дата == [True]:
        for з in набор:
            з.ДатаПисьма = назад(3)
        набор.Записать()
    c.УЗ_Сервер.ПроверкаЗадолженности(т.массив(с_адресом))
    оп.настроить_почту(т, Включена=False)
    т.проверить(писем(п3) == 1, "долг не погашен, с прошлого письма 3 дня (N = 2) — письмо повторено (было: нет)",
                писем(п3))
    попытки = события_журнала(т.база, журнал, "Учёт занятий.Почта.Отправка")
    т.проверить(попытки == [], "журнал: ни одной настоящей отправки письма", попытки)

    # ── 6. период показа по умолчанию ──
    н = c.РегистрыСведений.УЗ_Настройки.СоздатьМенеджерЗаписи()
    н.Прочитать()
    н.ПериодОповещения = 0
    н.Записать()
    период = попытка(lambda: (int(c.УЗ_Сервер.ПараметрыОповещений().Период),
                              int(c.УЗ_ОбщийКлиентСервер.ПериодОповещенияПоУмолчанию())))
    т.проверить(период == (300, 300), "период показа при пустой настройке — 300 с, одна функция (было 60)", период)
    for путь in (r"CommonModules\УЗ_ОбновлениеДанных\Ext\Module.bsl",
                 r"InformationRegisters\УЗ_Настройки\Forms\ФормаЗаписи\Ext\Form\Module.bsl"):
        текст = open(os.path.join(ИСХОДНИКИ, путь), encoding="utf-8-sig").read()
        т.проверить("ПериодОповещенияПоУмолчанию()" in текст and "ПериодОповещения = 300" not in текст
                    and '"ПериодОповещения", 300' not in текст,
                    "%s: период по умолчанию — из общей функции" % путь.split("\\")[1])

    # ── 5. права: менеджер в обход API ──
    общий = ученик("общее оповещение")
    движение(общий, назад(3), -700)
    c.УЗ_Сервер.ПроверкаЗадолженности(т.массив(общий))
    записи = т.выбрать("""ВЫБРАТЬ О.ВремяСобытия КАК ВремяСобытия ИЗ РегистрСведений.УЗ_Оповещения КАК О
        ГДЕ О.Источник = &И И НЕ О.Завершено""", И=общий)
    т.проверить(записи.Количество() == 1, "общее оповещение о долге для проверки прав заведено", записи.Количество())
    if записи.Количество() != 1:
        return
    время = записи.Получить(0).ВремяСобытия
    н = time.time()
    права.удалить_пользователя(т, МЕНЕДЖЕР)
    конфигурация = c.Метаданные.Имя
    свой = права.завести_пользователя(т, МЕНЕДЖЕР, права.ОБЩИЕ_РОЛИ + права.РОЛИ_ХОЗЯИНА[конфигурация]
                                      + ["УЗ_ОсновнаяРоль"] + права.ТОЛЬКО_ДЛЯ_ТЕСТА)
    т.убрать(lambda: (gc.collect(), права.удалить_пользователя(т, МЕНЕДЖЕР)), "пользователь-менеджер")
    т.вне_бюджета += time.time() - н
    м = т.подключить(МЕНЕДЖЕР)
    try:
        ид = c.String(общий.УникальныйИдентификатор())
        источник = м.Справочники.УЗ_ФизЛица.ПолучитьСсылку(м.NewObject("УникальныйИдентификатор", ид))
        организация = м.Справочники.Организации.ПолучитьСсылку(
            м.NewObject("УникальныйИдентификатор", c.String(орг_а.УникальныйИдентификатор())))
        пустой = м.Справочники.Пользователи.ПустаяСсылка()

        def завершить_формой():
            з = м.РегистрыСведений.УЗ_Оповещения.СоздатьМенеджерЗаписи()
            з.Источник, з.ВремяСобытия, з.Пользователь, з.Завершено, з.Организация = источник, время, пустой, False, организация
            з.Прочитать()
            if not з.Выбран():
                raise AssertionError("запись не прочитана — проверка ничего не пробует")
            з.Завершено = True
            з.Записать()
        ош = попытка(завершить_формой)
        т.проверить(isinstance(ош, str) and "руководитель" in ош and "не прочитана" not in ош,
                    "менеджер через форму записи не завершает общее оповещение о долге (было: завершал)", ош)

        def общее_напоминание():
            з = м.РегистрыСведений.УЗ_Оповещения.СоздатьМенеджерЗаписи()
            з.Источник, з.ВремяСобытия, з.Пользователь = источник, м.ТекущаяДатаСеанса(), пустой
            з.СрокНапоминания, з.Описание = м.ТекущаяДатаСеанса(), "всем от менеджера (тест)"
            з.Записать()
        ош = попытка(общее_напоминание)
        т.проверить(isinstance(ош, str) and "руководитель" in ош,
                    "менеджер не записывает общее напоминание (для всех) в обход API", ош)

        def своё_напоминание():
            з = м.РегистрыСведений.УЗ_Оповещения.СоздатьМенеджерЗаписи()
            з.Источник, з.ВремяСобытия, з.Пользователь = источник, м.ТекущаяДатаСеанса(), м.УЗ_Среда.ТекущийПользователь()
            з.СрокНапоминания, з.Описание = м.ТекущаяДатаСеанса(), "себе (тест)"
            з.Записать()
            return з
        своё = попытка(своё_напоминание)
        т.проверить(not isinstance(своё, str), "своё напоминание менеджер записывает", своё)
        if not isinstance(своё, str):
            def передать_всем():
                своё.Пользователь = пустой
                своё.Записать()
            ош = попытка(передать_всем)
            т.проверить(isinstance(ош, str) and "руководитель" in ош,
                        "менеджер не меняет пользователя своего напоминания на «всем»", ош)
    finally:
        м = None
        gc.collect()
    т.проверить([з[1] for з in оповещения(т, общий) if "Задолженность" in з[0]] == [False],
                "общее оповещение о долге после попыток менеджера не завершено", оповещения(т, общий))
    т.проверить(c.String(свой) != "", "пользователь-менеджер заведён")


if __name__ == "__main__":
    запустить("логика_оповещения", сценарий)
