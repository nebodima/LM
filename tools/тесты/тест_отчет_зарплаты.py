"""Числа отчёта «Расчёты по зарплате» (повторный аудит Codex B08, N07).

Было: у урока с двумя начислениями педагогу (по ставке с «#» и ручная премия — разные комментарии, т. е. две строки
регистра) каждая строка отчёта брала всю сумму урока: урок 1 000, начисления 300 + 100 — «Сумма урока» 2 000,
«Выручка» 1 600 вместо 600. Стало: сумма урока — один раз на документ (первая строка), выручка остальных строк —
минус начисление. Отчёт формируется по варианту поставки (СКД → табличный документ), числа читаются в строке
педагога под заголовками колонок. С R24 (28.09.2026) премия — документ «Начисление педагогам» на основании урока
(урок начисление не хранит): её строка отчёта — выручка минус премия, сумма урока — только у строки урока.

    python tools\\тесты\\тест_отчет_зарплаты.py --база=C:\\1c_bases\\UZ_UNF_A
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from фабрика import Фабрика  # noqa: E402

МЕТКА = "_Тест отчёт зарплаты"


def число(текст):
    текст = (текст or "").replace("\xa0", "").replace(" ", "").replace(",", ".")
    try:
        return float(текст)
    except ValueError:
        return None


def сценарий(т):
    c = т.c
    ф = Фабрика(т, МЕТКА)
    ставка = ф.элемент("УЗ_СтавкиПедагогов", "ставка 30%", ПроцентСОплатыУченика=30)
    педагог = ф.педагог("педагог отчёта", СтавкаПедагога=ставка)
    ученик = ф.ученик()
    тариф = ф.элемент("УЗ_Тарифы", "тариф")
    ф.цена_тарифа(тариф, ф.день(-400), 1000, уроков=1)
    у = ф.урок(педагог, ф.день(-2, 10), 1, [dict(Ученик=ученик, Тариф=тариф, Явка=True, СписатьОплату=True)],
               СтавкаПедагога=ставка)
    ош, сообщения = ф.записать(у)
    премия, (ош2, _) = ф.доплата(у, 100, "премия")
    т.проверить(ош is None and ош2 is None and float(у.Сумма) == 1000 and ф.начислено_педагогу(у) == 300
                and ф.начислено_педагогу(премия) == 100,
                "урок 1 000 проведён: начисление 300 (30%) + премия 100 документом на основании урока",
                ош or ош2 or сообщения or (у.Сумма, ф.начислено_педагогу(у), ф.начислено_педагогу(премия)))

    for с_комментарием in (False, True):
        значения = итог_педагога(т, ф, педагог, с_комментарием)
        т.проверить(значения == {"Сумма урока": 1000.0, "Выручка": 600.0},
                    "B08: итог педагога %s — сумма урока 1 000 (один раз), выручка 600 = 1 000 − 400%s"
                    % ("с полем «Комментарий» в детальных записях" if с_комментарием else "(вариант поставки)",
                       " (было 2 000 / 1 600)" if с_комментарием else ""), значения)


def итог_педагога(т, ф, педагог, с_комментарием, поле="Комментарий"):
    """{«Сумма урока», «Выручка»} в строке группировки педагога; с_комментарием — пользователь добавил поле
    (по умолчанию «Комментарий») в выбранные: тогда урок с двумя начислениями — две детальные
    строки (невыбранные поля СКД из запроса убирает, и строки регистра сливаются)."""
    c = т.c
    схема = c.Отчеты.УЗ_РасчетыПоЗарплате.ПолучитьМакет("ОсновнаяСхемаКомпоновкиДанных")
    настройки = схема.ВариантыНастроек.Получить(0).Настройки
    период = настройки.ПараметрыДанных.НайтиЗначениеПараметра(c.NewObject("ПараметрКомпоновкиДанных", "Период"))
    период.Значение = c.NewObject("СтандартныйПериод", ф.день(-3), ф.день(-1, 23, 59))
    период.Использование = True
    if с_комментарием:
        # Тип() через COM недоступен — берём его из описания типов
        тип = c.NewObject("ОписаниеТипов", "ВыбранноеПолеКомпоновкиДанных").Типы().Получить(0)
        выбранное = настройки.Выбор.Элементы.Добавить(тип)
        выбранное.Поле = c.NewObject("ПолеКомпоновкиДанных", поле)
        выбранное.Использование = True
    макет = c.NewObject("КомпоновщикМакетаКомпоновкиДанных").Выполнить(схема, настройки)
    процессор = c.NewObject("ПроцессорКомпоновкиДанных")
    процессор.Инициализировать(макет)
    тд = c.NewObject("ТабличныйДокумент")
    вывод = c.NewObject("ПроцессорВыводаРезультатаКомпоновкиДанныхВТабличныйДокумент")
    вывод.УстановитьДокумент(тд)
    вывод.Вывести(процессор)

    def колонка(заголовок):
        о = тд.НайтиТекст(заголовок)
        return о.Лево if о is not None else None

    строка_педагога = тд.НайтиТекст(c.String(педагог))
    колонки = {"Сумма урока": колонка("Сумма урока"), "Выручка": колонка("Выручка")}
    if строка_педагога is None or None in колонки.values():
        return "нет строки педагога или колонок: %s" % колонки
    н = строка_педагога.Верх
    return {имя: число(тд.Область(н, к, н, к).Текст) for имя, к in колонки.items()}


if __name__ == "__main__":
    запустить("отчет_зарплаты", сценарий)
