"""Жизненный цикл урока и прихода денег (образец — «Путевые листы», com_test_жизненный_цикл).

Тесты обычно создают документ, смотрят цифру и удаляют. Покупатель живёт иначе: записывает черновик, проводит,
перепроводит, переносит задним числом, распроводит и проводит снова, копирует прошлый документ, помечает на
удаление. На этих переходах остатки задваиваются, движения остаются сиротами, копия наследует чужое проведение.
После каждого шага остатки регистров сверяются с тем, что должно быть:

  приход денег 1 000 (касса, баланс ученика):
    черновик — движений нет; провели — касса и баланс +1 000; перепровели — те же движения, остатки те же;
    перенесли на 7 дней назад — на дату между старой и новой датой деньги уже есть, итог тот же; распровели —
    движений нет, остатки 0; провели снова — +1 000; копия записана — не проведена, без движений, остатки прежние;
    пометили проведённый на удаление — проведение снято, движений нет, остатки 0;
  урок по абонементу 6 400 / 8 занятий, ставка педагога 500 за занятие:
    черновик — движений нет; провели — баланс ученика −800, абонемент: использовано 1, долг педагогу 500;
    перепровели — те же движения; перенесли назад — остатки те же, движения на новой дате; распровели — всё 0;
    провели снова; копия записана — не проведена, без движений; пометили на удаление — всё 0.

    python tools\\тесты\\тест_жизненный_цикл.py --база=C:\\1c_bases\\UZ_BP_E --пользователь=1
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from фабрика import Фабрика  # noqa: E402

МЕТКА = "УЗ тест жизненного цикла"

КАССА = ("ВЫБРАТЬ ЕСТЬNULL(СУММА(Р.СуммаОстаток), 0) "
         "ИЗ РегистрНакопления.УЗ_Касса.Остатки(&НаДату, Касса = &Кто) КАК Р")
БАЛАНС = ("ВЫБРАТЬ ЕСТЬNULL(СУММА(Р.СуммаОстаток), 0) "
          "ИЗ РегистрНакопления.УЗ_СписанияСуммЗаУроки.Остатки(&НаДату, Клиент = &Кто) КАК Р")
ЗАНЯТИЙ = ("ВЫБРАТЬ ЕСТЬNULL(СУММА(Р.КоличествоУроковОстаток), 0) "
           "ИЗ РегистрНакопления.УЗ_СписанияСуммЗаУроки.Остатки(&НаДату, Абонемент = &Кто) КАК Р")
ДОЛГ = ("ВЫБРАТЬ ЕСТЬNULL(СУММА(Р.СуммаОстаток), 0) "
        "ИЗ РегистрНакопления.УЗ_РасчетыПоЗарплате.Остатки(&НаДату, Педагог = &Кто) КАК Р")
РЕГИСТРЫ = {"УЗ_Касса": "Р.ВидДвижения, Р.Касса, Р.Клиент, Р.Сумма",
            "УЗ_СписанияСуммЗаУроки": "Р.ВидДвижения, Р.Клиент, Р.Абонемент, Р.Сумма, Р.КоличествоУроков, Р.Часы",
            "УЗ_РасчетыПоЗарплате": "Р.ВидДвижения, Р.Педагог, Р.Сумма"}


def сценарий(т):
    ф = Фабрика(т, МЕТКА)
    c = т.c
    дальше = ф.день(1)   # остатки «на сейчас» — граница после всех дат теста

    def остаток(запрос, кто, на=None):
        return ф.число(запрос, Кто=кто, НаДату=на or дальше)

    def равно(что, факт, ожидаем):
        т.проверить(abs(float(факт) - ожидаем) < 0.005, "%s = %s" % (что, ожидаем), "факт %s" % факт)

    def значение(з):
        if isinstance(з, bool):
            return з
        if isinstance(з, (int, float)) or type(з).__name__ == "Decimal":
            return round(float(з), 2)
        return c.String(з)

    def движения(ссылка, с_периодом=False):
        итог = []
        for регистр, поля in РЕГИСТРЫ.items():
            тз = ф.выбрать("ВЫБРАТЬ %s%s ИЗ РегистрНакопления.%s КАК Р ГДЕ Р.Регистратор = &Д"
                           % (поля, ", Р.Период" if с_периодом else "", регистр), Д=ссылка)
            for н in range(тз.Количество()):
                с = тз.Получить(н)
                итог.append((регистр,) + tuple(значение(с.Получить(к)) for к in range(тз.Колонки.Количество())))
        return sorted(итог)

    def шаг(д, режим, что):
        ошибка, сообщения = ф.записать(д, режим)
        т.проверить(ошибка is None, что, (ошибка, сообщения))
        return ошибка is None

    def перечитать(д):
        return д.Ссылка.ПолучитьОбъект()

    def копия_без_движений(д, что):
        копия = д.Ссылка.ПолучитьОбъект().Скопировать()
        копия.Дата = д.Дата
        if not шаг(копия, "Запись", "%s: копия записывается" % что):
            return
        о = копия.Ссылка.ПолучитьОбъект()
        т.проверить(not о.Проведен and not о.ПометкаУдаления, "%s: копия не проведена" % что,
                    (о.Проведен, о.ПометкаУдаления))
        т.проверить(движения(копия.Ссылка) == [], "%s: у копии нет движений" % что, движения(копия.Ссылка))
        т.проверить(c.String(о.Номер) != c.String(д.Ссылка.Номер), "%s: у копии свой номер" % что, о.Номер)

    def пометить(д, что):
        о = д.Ссылка.ПолучитьОбъект()
        c.ПолучитьСообщенияПользователю(True)
        try:
            о.УстановитьПометкуУдаления(True)
            ошибка = None
        except Exception as е:
            ошибка = str(е)[:200]
        т.проверить(ошибка is None, "%s: пометка на удаление проведённого проходит" % что, ошибка)
        о = д.Ссылка.ПолучитьОбъект()
        т.проверить(о.ПометкаУдаления and not о.Проведен, "%s: помеченный на удаление не проведён" % что,
                    (о.ПометкаУдаления, о.Проведен))
        т.проверить(движения(д.Ссылка) == [], "%s: у помеченного на удаление нет движений" % что, движения(д.Ссылка))

    ученик = ф.ученик()
    касса = ф.элемент("УЗ_Кассы", "касса цикла")
    ставка = ф.элемент("УЗ_СтавкиПедагогов", "500 за занятие", ОплатаЗаЗанятие=500)
    педагог = ф.педагог(СтавкаПедагога=ставка)
    тариф = ф.элемент("УЗ_Тарифы", "1 000 за урок", Сумма=1000, КоличествоУроков=1)
    абонемент = ф.абонемент(ученик, "6 400 за 8", КоличествоЗанятий=8, ЦенаАбонемента=6400, Тариф=тариф)

    # ══ приход денег ══
    пко = ф.приход(ученик, 1000, Касса=касса, Дата=ф.день(-3, 9))
    шаг(пко, "Запись", "ПКО: черновик записывается")
    т.проверить(движения(пко.Ссылка) == [], "ПКО: у черновика нет движений", движения(пко.Ссылка))
    равно("ПКО: касса после черновика", остаток(КАССА, касса), 0)
    if not шаг(перечитать(пко), "Проведение", "ПКО: проведение"):
        return
    равно("ПКО: касса после проведения", остаток(КАССА, касса), 1000)
    равно("ПКО: баланс ученика после проведения", остаток(БАЛАНС, ученик), 1000)
    были = движения(пко.Ссылка)
    шаг(перечитать(пко), "Проведение", "ПКО: перепроведение")
    т.проверить(движения(пко.Ссылка) == были, "ПКО: перепроведение не задваивает движения", движения(пко.Ссылка))
    равно("ПКО: касса после перепроведения", остаток(КАССА, касса), 1000)
    о = перечитать(пко)
    о.Дата = ф.день(-10, 9)
    шаг(о, "Проведение", "ПКО: перенос на 7 дней назад и перепроведение")
    равно("ПКО задним числом: на −5 день деньги уже в кассе", остаток(КАССА, касса, ф.день(-5)), 1000)
    равно("ПКО задним числом: касса итого та же", остаток(КАССА, касса), 1000)
    т.проверить(движения(пко.Ссылка) == были, "ПКО задним числом: движения те же (кроме даты)", движения(пко.Ссылка))
    шаг(перечитать(пко), "ОтменаПроведения", "ПКО: отмена проведения")
    т.проверить(движения(пко.Ссылка) == [], "ПКО: после отмены проведения движений нет", движения(пко.Ссылка))
    равно("ПКО: касса после отмены проведения", остаток(КАССА, касса), 0)
    равно("ПКО: баланс ученика после отмены проведения", остаток(БАЛАНС, ученик), 0)
    шаг(перечитать(пко), "Проведение", "ПКО: проведение снова")
    равно("ПКО: касса после повторного проведения", остаток(КАССА, касса), 1000)
    копия_без_движений(пко, "ПКО")
    равно("ПКО: копия не тронула кассу", остаток(КАССА, касса), 1000)

    # ══ урок ══
    урок = ф.урок(педагог, ф.день(-2, 9), 1, [dict(Ученик=ученик, Абонемент=абонемент, Тариф=тариф, Явка=True,
                                                  СписатьОплату=True)], СтавкаПедагога=ставка)
    шаг(урок, "Запись", "урок: черновик записывается")
    т.проверить(движения(урок.Ссылка) == [], "урок: у черновика нет движений", движения(урок.Ссылка))
    if not шаг(перечитать(урок), "Проведение", "урок: проведение"):
        return
    равно("урок: баланс ученика 1 000 − 800", остаток(БАЛАНС, ученик), 200)
    равно("урок: использовано занятий абонемента", остаток(ЗАНЯТИЙ, абонемент), 1)
    равно("урок: долг педагогу", остаток(ДОЛГ, педагог), 500)
    были = движения(урок.Ссылка)
    шаг(перечитать(урок), "Проведение", "урок: перепроведение")
    т.проверить(движения(урок.Ссылка) == были, "урок: перепроведение не задваивает движения", движения(урок.Ссылка))
    равно("урок: долг педагогу после перепроведения", остаток(ДОЛГ, педагог), 500)
    о = перечитать(урок)
    о.Дата = ф.день(-6, 9)
    шаг(о, "Проведение", "урок: перенос на 4 дня назад и перепроведение")
    т.проверить(движения(урок.Ссылка) == были, "урок задним числом: движения те же (кроме даты)", движения(урок.Ссылка))
    даты = {с[-1] for с in движения(урок.Ссылка, с_периодом=True)}
    т.проверить(даты == {c.String(ф.день(-6, 9))}, "урок задним числом: движения на новой дате", даты)
    равно("урок задним числом: на −4 день занятие уже списано", остаток(ЗАНЯТИЙ, абонемент, ф.день(-4)), 1)
    равно("урок задним числом: баланс ученика тот же", остаток(БАЛАНС, ученик), 200)
    шаг(перечитать(урок), "ОтменаПроведения", "урок: отмена проведения")
    т.проверить(движения(урок.Ссылка) == [], "урок: после отмены проведения движений нет", движения(урок.Ссылка))
    равно("урок: баланс после отмены проведения", остаток(БАЛАНС, ученик), 1000)
    равно("урок: занятий после отмены проведения", остаток(ЗАНЯТИЙ, абонемент), 0)
    равно("урок: долг педагогу после отмены проведения", остаток(ДОЛГ, педагог), 0)
    шаг(перечитать(урок), "Проведение", "урок: проведение снова")
    равно("урок: долг педагогу после повторного проведения", остаток(ДОЛГ, педагог), 500)
    копия_без_движений(урок, "урок")
    равно("урок: копия не тронула абонемент", остаток(ЗАНЯТИЙ, абонемент), 1)

    # ══ пометка на удаление проведённых ══
    пометить(урок, "урок")
    равно("урок помечен: занятий абонемента", остаток(ЗАНЯТИЙ, абонемент), 0)
    равно("урок помечен: долг педагогу", остаток(ДОЛГ, педагог), 0)
    пометить(пко, "ПКО")
    равно("ПКО помечен: касса", остаток(КАССА, касса), 0)
    равно("всё помечено: баланс ученика", остаток(БАЛАНС, ученик), 0)


if __name__ == "__main__":
    запустить("жизненный_цикл", сценарий)
