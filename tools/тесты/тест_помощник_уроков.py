"""Помощник создания уроков и общая запись урока (Codex A01, N03, Q03 — повторный аудит 28.09.2026).

A01. Было: помощник в режиме «только записывать» дописывал ученика в уже ПРОВЕДЁННЫЙ урок обычной записью
(УЗ_Общий.ЗаписатьУрок(Урок, Ложь)) — ученик и сумма в документе есть, списания в регистре нет.
Стало: проведённый урок перепроводится всегда, не проведённый будущий — только записывается (В10).
N03. Было: поиск существующего урока без группы и педагога (условия закомментированы) и по попаданию в интервал —
ученика группы Б дописывало в урок группы А того же помещения. Стало (Документы.УЗ_Урок.ЗаписатьУчениковВУрок):
существующий урок — только точное совпадение начала, группы, педагога, предмета, помещения; иначе новый урок, но
не поверх урока того же педагога/помещения/группы (и записанного планом) — отказ с причиной.
Q03 («Перевод из группы» помощника) — с 28.09.2026 не режим помощника, а документ «Перевод ученика» (В29): план,
проверки целиком, потом запись — тест_перевод_ученика.
Мутации: в УЗ_Общий.ЗаписатьУрок вернуть «Если Не Провести Тогда» — краснеет A01; в УрокиПомощникаНаДату убрать
условие по группе и педагогу — краснеет N03.

    python tools\\тесты\\тест_помощник_уроков.py --база=C:\\1c_bases\\UZ_UNF_B
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from фабрика import Фабрика  # noqa: E402

МЕТКА = "УЗ тест помощника уроков"
ЦЕНА = 500


def сценарий(т):
    c = т.c
    ф = Фабрика(т, МЕТКА)
    педагог_а = ф.педагог("педагог А")
    педагог_б = ф.педагог("педагог Б")
    ученик1 = ф.ученик("ученик 1")
    ученик2 = ф.ученик("ученик 2")
    ученик3 = ф.ученик("ученик 3")
    тариф = ф.элемент("УЗ_Тарифы", "500 за урок", Сумма=ЦЕНА, КоличествоУроков=1)
    без_цены = ф.элемент("УЗ_Тарифы", "без цены")
    предмет = ф.элемент("УЗ_ПредметыОбучения", "предмет")
    помещение = ф.элемент("УЗ_Помещения", "класс 1")
    группа_а = ф.элемент("УЗ_ГруппыОбучения", "группа А")
    группа_б = ф.элемент("УЗ_ГруппыОбучения", "группа Б")
    без_помещения = c.Справочники.УЗ_Помещения.ПустаяСсылка()

    def уроки(**отбор):
        условия = " И ".join("У.%s = &%s" % (к, к) for к in отбор)
        return т.выбрать("ВЫБРАТЬ У.Ссылка КАК Ссылка ИЗ Документ.УЗ_Урок КАК У ГДЕ " + условия, **отбор)

    def убрать_уроки():
        for п in (педагог_а, педагог_б):
            тз = уроки(Педагог=п)
            for н in range(тз.Количество()):
                т.удалить_объект(тз.Получить(н).Ссылка, загрузка=True)
    т.убрать(убрать_уроки, "уроки помощника")

    def списано(ссылка):
        return ф.число("""ВЫБРАТЬ СУММА(Р.Сумма) ИЗ РегистрНакопления.УЗ_СписанияСуммЗаУроки КАК Р
            ГДЕ Р.Регистратор = &У""", У=ссылка)

    def строка(ученик, тариф_строки=тариф):
        с = c.NewObject("Структура")
        с.Вставить("Ученик", ученик)
        с.Вставить("Тариф", тариф_строки)
        с.Вставить("СписатьОплату", True)
        с.Вставить("Явка", True)
        return с

    def параметры(начало, часов, педагог, группа, пом=помещение):
        п = c.NewObject("Структура")
        п.Вставить("Дата", начало)
        п.Вставить("КоличествоЧасов", часов)
        п.Вставить("ПредметОбучения", предмет)
        п.Вставить("Педагог", педагог)
        п.Вставить("Помещение", пом)
        п.Вставить("ГруппаОбучения", группа)
        return п

    def журнал(итог):
        return [итог.Строки.Получить(н).Описание for н in range(итог.Строки.Количество())]

    # ── A01: дописать ученика в проведённый урок «обычной записью» — урок перепроведён, списание по обоим ──
    д = ф.урок(педагог_а, ф.день(-1, 8), 1, [dict(Ученик=ученик1, Тариф=тариф, СписатьОплату=True, Явка=True)])
    ошибка, сообщения = ф.записать(д, "Проведение")
    т.проверить(ошибка is None, "A01: вчерашний урок с одним учеником проведён", "%s %s" % (ошибка, сообщения))
    о = д.Ссылка.ПолучитьОбъект()
    с = о.Ученики.Добавить()
    с.Ученик = ученик2
    с.Тариф = тариф
    с.СписатьОплату = True
    итог = c.УЗ_Общий.ЗаписатьУрок(о, False)
    т.проверить(итог.Успех, "A01: запись «без проведения» проведённого урока успешна", итог.Текст)
    сумма = списано(д.Ссылка)
    т.проверить(д.Ссылка.ПолучитьОбъект().Проведен and сумма == 2 * ЦЕНА,
                "A01: проведённый урок перепроведён — списано %d за двух учеников (было: %d, движения старые)"
                % (2 * ЦЕНА, ЦЕНА), сумма)
    будущий = ф.урок(педагог_а, ф.день(2, 8), 1, [dict(Ученик=ученик1, Тариф=тариф, СписатьОплату=True)])
    ошибка, _ = ф.записать(будущий, "Запись")
    итог = c.УЗ_Общий.ЗаписатьУрок(будущий.Ссылка.ПолучитьОбъект(), False)
    т.проверить(ошибка is None and итог.Успех and not будущий.Ссылка.ПолучитьОбъект().Проведен,
                "A01/В10: будущий записанный урок — только записан, не проведён", "%s %s" % (ошибка, итог.Текст))

    # ── N03: урок группы А (педагог А, класс 1) вчера 12:00–13:00 ──
    урок_а = ф.урок(педагог_а, ф.день(-1, 12), 1, [dict(Ученик=ученик1, Тариф=тариф, СписатьОплату=True, Явка=True)],
                    ГруппаОбучения=группа_а, ПредметОбучения=предмет, Помещение=помещение)
    ошибка, сообщения = ф.записать(урок_а, "Проведение")
    т.проверить(ошибка is None, "N03: урок группы А проведён", "%s %s" % (ошибка, сообщения))
    менеджер = c.Документы.УЗ_Урок

    def учеников(ссылка):
        return ссылка.ПолучитьОбъект().Ученики.Количество()

    итог = менеджер.ЗаписатьУчениковВУрок(параметры(ф.день(-1, 12), 1, педагог_б, группа_б), т.массив(строка(ученик3)), True)
    т.проверить(not итог.Успех and учеников(урок_а.Ссылка) == 1 and уроки(ГруппаОбучения=группа_б).Количество() == 0,
                "N03: группа Б у педагога Б в том же классе и время — отказ (помещение занято), в урок группы А не "
                "дописан, урок Б не создан", журнал(итог))
    т.проверить(any("помещение" in текст and "занято уроком" in текст for текст in журнал(итог)),
                "N03: причина отказа — помещение занято уроком группы А", журнал(итог))

    итог = менеджер.ЗаписатьУчениковВУрок(параметры(ф.день(-1, 12, 15), 0.5, педагог_а, группа_а),
                                          т.массив(строка(ученик3)), True)
    т.проверить(not итог.Успех and учеников(урок_а.Ссылка) == 1,
                "N03: урок 12:15–12:45 внутри урока 12:00–13:00 — не тот урок: отказ, в урок А не дописан", журнал(итог))

    итог = менеджер.ЗаписатьУчениковВУрок(параметры(ф.день(-1, 12), 1, педагог_а, группа_а),
                                          т.массив(строка(ученик3)), True)
    т.проверить(итог.Успех and not итог.Создан and учеников(урок_а.Ссылка) == 2 and списано(урок_а.Ссылка) == 2 * ЦЕНА,
                "N03: точно тот же урок (начало, группа, педагог, предмет, помещение) — ученик дописан, урок перепроведён",
                журнал(итог))

    итог = менеджер.ЗаписатьУчениковВУрок(параметры(ф.день(-1, 15), 1, педагог_б, группа_б),
                                          т.массив(строка(ученик2)), True)
    т.проверить(итог.Успех and итог.Создан and итог.Урок is not None and итог.Урок.ПолучитьОбъект().Проведен,
                "N03: без пересечений — новый урок группы Б создан и проведён", журнал(итог))



if __name__ == "__main__":
    запустить("помощник_уроков", сценарий)
