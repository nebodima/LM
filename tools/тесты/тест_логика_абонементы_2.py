"""Логика абонементов, часть 2 (docs/логики/абонементы.md, сценарии 8, 13–16 и решения В12, В23, В25, Р-6).

Тариф «8 000 за 8» (1 000 за урок), абонементы «6 400 за 8» (800 за урок), если не сказано иное.

Сценарии (К — красный на старом коде, проверено прогоном до правки 28.09.2026):
  №8  Р-4: старый абонемент исчерпан (2 из 2), кончается раньше нового — действующим подбирается новый, и помощник
      (ЗаписатьУчениковВУрок) ставит в урок новый, даже если ему передали старый (К: подставлялся старый →
      «Не хватает занятий»)
  №13 Р-7: 2 урока по 800 проведены, цену абонемента меняют на 8 000 — перепроведение урока 2 оставляет 800, новый
      урок — 1 000 (К: перепроведение переписывало урок 2 на 1 000)
  №14 В25: «1 000 за 3 занятия» — уроки 333,33; 333,33; 333,34, сумма ровно 1 000 (К: 333,33 × 3 = 999,99)
  №15 Р-6: «Активный» без даты активации (загрузка) — при записи дата активации ставится, урок проводится
      (К: урок — «не активен», карточка и панель — «активен»)
  №16 A08: абонемент на гитару в уроке ударных — цена по тарифу, отказ «по предмету»; подбор для ударных — пусто
  Р-6: помеченный на удаление абонемент, выбранный руками, — отказ (К: урок проводился)
  В23: скидка 10 % у строки по абонементу не применяется (800), у строки по тарифу — применяется (900) (К: 720)
  В12: абонемент организации А не подбирается и не проводится в уроке организации Б (К: реквизита не было)

    python tools\\тесты\\тест_логика_абонементы_2.py --база=C:\\1c_bases\\UZ_UNF_B
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from фабрика import Фабрика  # noqa: E402
from _логика_абонементов import вызов, есть_слово, пустая_дата, строка, структура, та_же  # noqa: E402

МЕТКА = "УЗ тест логики абонементов 2"


def сценарий(т):
    c = т.c
    ф = Фабрика(т, МЕТКА)
    аб = c.Справочники.УЗ_Абонемент
    предмет = ф.элемент("УЗ_ПредметыОбучения", "математика")
    педагог = ф.педагог()
    тариф = ф.элемент("УЗ_Тарифы", "8 000 за 8", Сумма=8000, КоличествоУроков=8)

    def урок(час, строки, минута=0, **реквизиты):
        поля = dict(ПредметОбучения=предмет)
        поля.update(реквизиты)
        д = ф.урок(педагог, ф.день(-1, час, минута), 1, строки, **поля)
        return д, ф.записать(д, "Проведение")

    def убрать_уроки_педагога():
        тз = т.выбрать("ВЫБРАТЬ У.Ссылка КАК Ссылка ИЗ Документ.УЗ_Урок КАК У ГДЕ У.Педагог = &П", П=педагог)
        for н in range(тз.Количество()):
            т.удалить_объект(тз.Получить(н).Ссылка, загрузка=True)
    т.убрать(убрать_уроки_педагога, "уроки помощника")

    # ── №8: переход на новый абонемент до конца срока старого ──
    ученик = ф.ученик("Переходов")
    старый = ф.абонемент(ученик, "старый 2 зан", КоличествоЗанятий=2, ЦенаАбонемента=1600, ПредметОбучения=предмет,
                         ДатаОкончания=ф.день(5))
    новый = ф.абонемент(ученик, "новый 8 зан", КоличествоЗанятий=8, ЦенаАбонемента=6400, ПредметОбучения=предмет,
                        ДатаНачала=ф.день(-10), ДатаОкончания=ф.день(40))
    for час in (8, 9):
        _, итог = урок(час, [dict(Ученик=ученик, Абонемент=старый, Явка=True, СписатьОплату=True, Тариф=тариф)])
        т.проверить(итог[0] is None, "№8: урок %d по старому абонементу проведён" % (час - 7), итог)
    найдено = c.Документы.УЗ_Урок.ДействующиеАбонементы(т.массив(ученик), предмет, ф.день(-1, 12))
    т.проверить(та_же(c, найдено.Получить(ученик), новый), "№8 (Р-4): действующий — новый абонемент, исчерпанный старый не берётся",
                c.String(найдено.Получить(ученик)))
    параметры = структура(c, Дата=ф.день(-1, 10), КоличествоЧасов=1, ПредметОбучения=предмет, Педагог=педагог,
                          Помещение=c.Справочники.УЗ_Помещения.ПустаяСсылка(),
                          ГруппаОбучения=c.Справочники.УЗ_ГруппыОбучения.ПустаяСсылка())
    итог = c.Документы.УЗ_Урок.ЗаписатьУчениковВУрок(параметры, т.массив(структура(
        c, Ученик=ученик, Абонемент=старый, Тариф=тариф, СписатьОплату=True, Явка=True)), True)
    урок8 = итог.Урок
    т.проверить(итог.Успех and урок8 is not None and not урок8.Пустая(), "№8: помощник записал урок",
                [итог.Строки.Получить(н).Описание for н in range(итог.Строки.Количество())])
    if урок8 is not None and not урок8.Пустая():
        с8 = урок8.ПолучитьОбъект().Ученики.Получить(0)
        т.проверить(та_же(c, с8.Абонемент, новый) and float(с8.Сумма) == 800,
                    "№8: в уроке помощника — новый абонемент, 800 (переданный исчерпанный заменён)",
                    (c.String(с8.Абонемент), с8.Сумма))

    # ── №13: цена проведённого урока не меняется при смене цены абонемента ──
    фикс = ф.ученик("Фиксов")
    а13 = ф.абонемент(фикс, "6400 за 8", КоличествоЗанятий=8, ЦенаАбонемента=6400, ПредметОбучения=предмет)
    д1, _ = урок(11, [dict(Ученик=фикс, Абонемент=а13, Явка=True, СписатьОплату=True, Тариф=тариф)])
    д2, _ = урок(12, [dict(Ученик=фикс, Абонемент=а13, Явка=True, СписатьОплату=True, Тариф=тариф)])
    о = а13.ПолучитьОбъект()
    о.ЦенаАбонемента = 8000
    о.Записать()
    итог = ф.записать(д2.Ссылка.ПолучитьОбъект(), "Проведение")
    т.проверить(итог[0] is None and float(строка(д2).Сумма) == 800,
                "№13 (Р-7): перепроведение урока 2 после смены цены абонемента — 800, не 1 000", (итог, строка(д2).Сумма))
    д3, итог = урок(13, [dict(Ученик=фикс, Абонемент=а13, Явка=True, СписатьОплату=True, Тариф=тариф)])
    т.проверить(итог[0] is None and float(строка(д3).Сумма) == 1000, "№13: новый урок — по новой цене 8 000 / 8 = 1 000",
                (итог, строка(д3).Сумма))

    # ── №14: В25 — хвост округления на последний урок ──
    хвост = ф.ученик("Хвостов")
    а14 = ф.абонемент(хвост, "1000 за 3", КоличествоЗанятий=3, ЦенаАбонемента=1000, ПредметОбучения=предмет)
    суммы = []
    for час in (14, 15, 16):
        д, итог = урок(час, [dict(Ученик=хвост, Абонемент=а14, Явка=True, СписатьОплату=True, Тариф=тариф)])
        суммы.append(float(строка(д).Сумма) if итог[0] is None else итог)
    т.проверить(суммы == [333.33, 333.33, 333.34], "№14 (В25): 333,33 + 333,33 + 333,34 — последний урок добирает хвост",
                суммы)
    т.проверить(round(sum(с for с in суммы if isinstance(с, float)), 2) == 1000, "№14: сумма уроков = цене абонемента 1 000",
                суммы)

    # ── №15: «Активный» без даты активации ──
    загруженный_ученик = ф.ученик("Загрузкин")
    загруженный = ф.абонемент(загруженный_ученик, "без даты активации", КоличествоЗанятий=8, ЦенаАбонемента=6400,
                              ПредметОбучения=предмет, ДатаАктивации=пустая_дата(c))
    т.проверить(загруженный.ПолучитьОбъект().ДатаАктивации.year >= 1900,
                "№15 (Р-6): активный абонемент без даты активации — дата ставится при записи")
    д15, итог = урок(17, [dict(Ученик=загруженный_ученик, Абонемент=загруженный, Явка=True, СписатьОплату=True, Тариф=тариф)])
    т.проверить(итог[0] is None, "№15: урок по нему проводится (одно правило «активен» везде)", итог)

    # ── №16: A08 — абонемент другого предмета ──
    гитара = ф.элемент("УЗ_ПредметыОбучения", "гитара")
    ударные = ф.элемент("УЗ_ПредметыОбучения", "ударные")
    гитарист = ф.ученик("Гитаров")
    на_гитару = ф.абонемент(гитарист, "8000 гитара", КоличествоЗанятий=8, ЦенаАбонемента=8000, ПредметОбучения=гитара)
    д16, итог = урок(18, [dict(Ученик=гитарист, Абонемент=на_гитару, Явка=True, СписатьОплату=True, Тариф=тариф)],
                     ПредметОбучения=ударные)
    т.проверить(итог[0] is not None and есть_слово(итог[1], "по предмету") and float(д16.Ученики.Получить(0).Сумма) == 1000,
                "№16 (A08): абонемент на гитару в уроке ударных — отказ «по предмету», цена по тарифу 1 000", итог)
    подбор, ошибка = вызов(lambda: аб.ПодобратьАбонемент(гитарист, ударные, ф.день(-1)))
    т.проверить(ошибка is None and подбор.Абонемент.Пустая(), "№16: для урока ударных абонемент на гитару не подбирается",
                ошибка)

    # ── Р-6: помеченный на удаление ──
    удалённый_ученик = ф.ученик("Помечкин")
    помеченный = ф.абонемент(удалённый_ученик, "помеченный", КоличествоЗанятий=8, ЦенаАбонемента=6400,
                             ПредметОбучения=предмет)
    о = помеченный.ПолучитьОбъект()
    о.ПометкаУдаления = True
    о.Записать()
    _, итог = урок(19, [dict(Ученик=удалённый_ученик, Абонемент=помеченный, Явка=True, СписатьОплату=True, Тариф=тариф)])
    т.проверить(итог[0] is not None and есть_слово(итог[1], "помечен на удаление"),
                "Р-6: помеченный на удаление абонемент, выбранный руками, — отказ", итог)

    # ── В23: скидка — один раз при продаже абонемента ──
    скидка = ф.элемент("УЗ_Скидки", "10 %", КоэффициентПроцент=10)
    скидочник = ф.ученик("Скидкин")
    без_абонемента = ф.ученик("Тарифов")
    а23 = ф.абонемент(скидочник, "6400 за 8", КоличествоЗанятий=8, ЦенаАбонемента=6400, ПредметОбучения=предмет)
    д23, итог = урок(20, [dict(Ученик=скидочник, Абонемент=а23, Скидка=скидка, Явка=True, СписатьОплату=True, Тариф=тариф),
                          dict(Ученик=без_абонемента, Скидка=скидка, Явка=True, СписатьОплату=True, Тариф=тариф)])
    по_абонементу, по_тарифу = строка(д23, 0), строка(д23, 1)
    т.проверить(итог[0] is None and float(по_абонементу.Сумма) == 800 and float(по_абонементу.СуммаСкидки) == 0,
                "В23: строка по абонементу — 800 без скидки (скидка вошла в цену абонемента)",
                (итог, по_абонементу.Сумма, по_абонементу.СуммаСкидки))
    т.проверить(float(по_тарифу.Сумма) == 900 and float(по_тарифу.СуммаСкидки) == 100,
                "В23: строка по тарифу — 1 000 − 10 % = 900", (по_тарифу.Сумма, по_тарифу.СуммаСкидки))

    # ── В12: организация абонемента ──
    орг_а = ф.организация("организация А")
    орг_б = ф.организация("организация Б")
    ученик12 = ф.ученик("Организацин")
    а12, ошибка = вызов(lambda: ф.абонемент(ученик12, "организации А", КоличествоЗанятий=8, ЦенаАбонемента=6400,
                                            ПредметОбучения=предмет, Организация=орг_а))
    т.проверить(ошибка is None, "В12: у абонемента есть организация", ошибка)
    if ошибка is None:
        подбор_б, ошибка = вызов(lambda: аб.ПодобратьАбонемент(ученик12, предмет, ф.день(-1), орг_б))
        подбор_а, _ = вызов(lambda: аб.ПодобратьАбонемент(ученик12, предмет, ф.день(-1), орг_а))
        т.проверить(ошибка is None and подбор_б.Абонемент.Пустая() and подбор_а is not None and та_же(c, подбор_а.Абонемент, а12),
                    "В12: для урока организации Б абонемент организации А не подбирается, для А — подбирается", ошибка)
        _, итог = урок(21, [dict(Ученик=ученик12, Абонемент=а12, Явка=True, СписатьОплату=True, Тариф=тариф)],
                       Организация=орг_б)
        т.проверить(итог[0] is not None and есть_слово(итог[1], "организации"),
                    "В12: урок организации Б по абонементу организации А — отказ", итог)


if __name__ == "__main__":
    запустить("логика_абонементы_2", сценарий)
