"""Деньги ученика раздельно по организациям (решение владельца В12; повторный аудит Codex: A03, C02, C03).

Было: остатки и долги ученика считались по всем организациям сразу — аванс 8 000 в А и долг 1 000 в Б
выглядели общими +7 000; перемещение денег между предметами проверяло текущий остаток без организации и даты
(деньги А разрешали расход в Б, поступление после даты перемещения — расход задним числом); панель ученика и
программное перемещение писали деньги в пустую организацию. Стало:
  * общая функция УЗ_Сервер.ОстатокДенегУченика(Ученик, Организация, Предмет, Граница) — ей считают формы
    урока, ПКО, перемещения и панель ученика;
  * перемещение между предметами — остаток в организации документа на его дату;
  * перемещение без организации — организация из настроек; панель — организация панели;
  * списание остатков на основании ученика — остатки организации документа.

    python tools\\тесты\\тест_деньги_организаций.py --база=C:\\1c_bases\\UZ_UNF_A
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import дата, запустить, текст_ошибки  # noqa: E402
from _деньги import Данные  # noqa: E402
from фабрика import Фабрика  # noqa: E402

МЕТКА = "_Тест деньги организаций"
ИСХОДНИКИ = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "src_ext"))
# формы, которые показывают деньги ученика: модуль → функция, которой считают остаток
ФОРМЫ = {
    r"Documents\УЗ_Урок\Forms\ФормаДокумента\Ext\Form\Module.bsl": "РассчитатьЗадолженность",
    r"Documents\УЗ_ПриходДенег\Forms\ФормаДокумента\Ext\Form\Module.bsl": "РассчитатьЗадолженностьНаСервере",
    r"Documents\УЗ_ПеремещениеДенег\Forms\ФормаДокумента\Ext\Form\Module.bsl": "РассчитатьЗадолженностьНаСервере",
}


def сценарий(т):
    c = т.c
    д = Данные(т, МЕТКА)
    ф = Фабрика(т, МЕТКА)
    орг_а = ф.организация("А")
    орг_б = ф.организация("Б")
    ученик = д.элемент("УЗ_ФизЛица", "ученик")
    гитара = д.элемент("УЗ_ПредметыОбучения", "гитара")
    вокал = д.элемент("УЗ_ПредметыОбучения", "вокал")
    # аванс 8 000 в А и долг 1 000 в Б — по гитаре, 01.09.2026
    д.движения("УЗ_СписанияСуммЗаУроки", д.регистратор(), [
        ("+", дата(2026, 9, 1, 10), {"Клиент": ученик, "ПредметОбучения": гитара, "Сумма": 8000, "Организация": орг_а}),
        ("-", дата(2026, 9, 1, 10), {"Клиент": ученик, "ПредметОбучения": гитара, "Сумма": 1000, "Организация": орг_б})])

    # ── A03/В12: общая функция остатка ──
    def остаток(*аргументы):
        try:
            return float(c.УЗ_Сервер.ОстатокДенегУченика(ученик, *аргументы))
        except Exception as е:
            return "ошибка: " + текст_ошибки(е, 120)
    т.проверить((остаток(орг_а), остаток(орг_б)) == (8000.0, -1000.0),
                "A03: остаток ученика по организациям — А +8 000, Б −1 000 (было общее +7 000)",
                (остаток(орг_а), остаток(орг_б)))
    т.проверить((остаток(орг_а, гитара), остаток(орг_а, вокал), остаток(орг_а, None, дата(2026, 8, 31))) == (8000.0, 0.0, 0.0),
                "остаток по предмету и на дату: гитара 8 000, вокал 0, на 31.08 — 0",
                (остаток(орг_а, гитара), остаток(орг_а, вокал), остаток(орг_а, None, дата(2026, 8, 31))))
    for путь, функция in ФОРМЫ.items():
        with open(os.path.join(ИСХОДНИКИ, путь), encoding="utf-8-sig") as файл:
            текст = файл.read()
        тело = re.search(r"Функция %s\(.*?КонецФункции" % функция, текст, re.S)
        т.проверить(тело is not None and "УЗ_Сервер.ОстатокДенегУченика(" in тело.group(0)
                    and "Организация" in тело.group(0) and "РегистрНакопления" not in тело.group(0),
                    "форма %s: остаток ученика — общей функцией по организации документа" % путь.split("\\")[1])

    # ── C02: перемещение между предметами — в организации документа и на его дату ──
    def перемещение(сумма, организация, когда, режим=None):
        п = д.документ("УЗ_ПеремещениеДенег", Дата=когда, Клиент=ученик, Сумма=сумма, СделатьДвиженияПоВзаиморасчетам=True,
                       ПредметОбученияОтправитель=гитара, ПредметОбученияПолучатель=вокал)
        if организация is not None:
            п.Организация = организация
        return п, д.записать(п, режим)
    _, ош = перемещение(500, орг_б, дата(2026, 9, 2, 10))
    т.проверить(ош is not None and "остаток" in ош, "C02: перемещение 500 в Б (там долг 1 000) — отказ, деньги А не в счёт", ош)
    _, ош = перемещение(500, орг_а, дата(2026, 8, 31, 10))
    т.проверить(ош is not None, "C02: перемещение 500 в А 31.08 — отказ: деньги пришли 01.09", ош)
    п, ош = перемещение(500, орг_а, дата(2026, 9, 2, 11))
    т.проверить(ош is None and остаток(орг_а, вокал) == 500.0 and остаток(орг_а, гитара) == 7500.0,
                "перемещение 500 в А 02.09 — проведено: гитара 7 500, вокал 500", ош or (остаток(орг_а, гитара), остаток(орг_а, вокал)))
    о = п.Ссылка.ПолучитьОбъект()
    о.Сумма = 7500 + 500
    ош = д.записать(о)
    т.проверить(ош is None, "перепроведение на весь остаток гитары (8 000) — свои движения не мешают", ош)

    # ── C03: перемещение без организации — организация из настроек ──
    настройка = c.РегистрыСведений.УЗ_Настройки.Настройки().Организация
    п, ош = перемещение(1, None, дата(2026, 9, 2, 12), c.РежимЗаписиДокумента.Запись)
    о = п.Ссылка.ПолучитьОбъект()
    т.проверить(ош is None and c.ЗначениеЗаполнено(о.Организация) and c.String(о.Организация) == c.String(настройка),
                "C03: перемещение без организации — организация из настроек (было пустая)", ош or c.String(о.Организация))

    # ── C03: «Переместить деньги» панели — в организации панели ──
    try:
        итог = c.Обработки.УЗ_ПанельУченика.ПереместитьДеньгиУченика(ученик, орг_а, вокал, гитара, 300)
        д.следить(итог.Урок)
        успех, док = итог.Успех, итог.Урок
    except Exception as е:
        успех, док = "ошибка: " + текст_ошибки(е, 120), None
    т.проверить(успех is True and c.String(док.Организация) == c.String(орг_а)
                and д.итог("УЗ_СписанияСуммЗаУроки", док)[1] == 2 and остаток(орг_а, гитара) == 300.0,
                "C03: панель — перемещение 300 с вокала на гитару в организации панели (А): гитара А 300", успех)

    # ── В12: списание остатков на основании ученика — остатки организации документа ──
    с = д.документ("УЗ_СписаниеОстатков", Организация=орг_б)
    с.Заполнить(ученик)
    строки = [(c.String(стр.ПредметОбучения), float(стр.Сумма)) for стр in с.ТЗСписания]
    т.проверить(строки == [(c.String(гитара), -1000.0)],
                "списание остатков в Б: одна строка — долг гитары −1 000 (деньги А не смешаны)", строки)


if __name__ == "__main__":
    запустить("деньги_организаций", сценарий)
