"""R24 (ревью Codex логик 28.09.2026): менеджер не видит и не меняет зарплату педагога в уроке, а урок менеджера
проводится с верным начислением педагогу. Живой COM-сеанс менеджера (УЗ_ОсновнаяРоль + роли хозяина рядового
сотрудника, как в тест_права.py).

Было: «Начислено педагогу» и таблица «Начисления педагогу» хранились в уроке; права на поля роли прятали их только в
интерфейсе, а запрос менеджера `ВЫБРАТЬ НачисленоПедагогу ИЗ Документ.УЗ_Урок` читал 500 (ограничение доступа на
поле закрыло бы чтение урока целиком, привилегированного режима в безопасном режиме расширения нет). Ставку урока
менеджер менял в обход формы (права на поле — интерфейсные): урок на ставке 900 вместо 500 начислял 900.
Стало (как в типовых: наряд закрывает мастер, начисление считает программа, ставку назначает руководитель):
  * урок начисление не хранит — проведение считает его по ставке (Документы.УЗ_Урок.НачисленияПоСтавке) и пишет
    сразу в регистр УЗ_РасчетыПоЗарплате; менеджер движения пишет, но регистр прочитать не может;
  * доплаты сверх ставки — документ «Начисление педагогам» на основании урока (руководитель); менеджеру —
    ни одной строки, записать нельзя;
  * ставку урока, карточки педагога и группы меняет только руководитель: новый урок менеджера — ставка по
    умолчанию, смена ставки записанного урока, ставка в карточке педагога и группе — отказ на сервере.
Проверки под менеджером:
  * урок менеджера проводится: движение педагогу 500 по ставке «за занятие» (явка есть); новый урок с чужой ставкой
    900 — ставка заменена на ставку по умолчанию, начислено 500 (было 900);
  * прочитать начисление нельзя: запрос поля «НачисленоПедагогу» и таблицы «НачисленияПедагогу» урока — отказ (было:
    500), регистр расчётов с педагогами — отказ по журналу, доплата руководителя 1 000 — РАЗРЕШЕННЫЕ пусто, по
    ссылке — отказ по журналу;
  * изменить нельзя: ставка записанного урока (было: записано, начислено 900), документ доплаты — отказ по журналу,
    ставка справочника — отказ по журналу, ставка в карточке педагога и в группе, новый педагог со ставкой — отказ
    «назначает и меняет руководитель»;
  * перепроведение урока руководителя менеджером (тема) — урок 500 и доплата 1 000 остались (1 500).
Предел (не проверка): суммы ставок читает код проведения урока в сеансе менеджера — запросом к справочнику ставок
менеджер их прочитать может (без «Просмотр» справочника нет в интерфейсе); привилегированного режима в безопасном
режиме расширения нет, начисление педагогу и доплаты ему недоступны.

    python tools\\тесты\\тест_ревью_зарплата_урока.py --база=C:\\1c_bases\\UZ_BP_E --пользователь=1
    python tools\\прогон.py --база=C:\\1c_bases\\UZ_BP_E --пользователь=1 --тест=ревью_зарплата_урока
"""
# затрагивает: УЗ_ЗарплатаУрокаПередЗаписью, УЗ_ЗарплатаУрока
import os
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить, текст_ошибки  # noqa: E402
from фабрика import Фабрика  # noqa: E402
from тест_права import (ОБЩИЕ_РОЛИ, РОЛИ_ХОЗЯИНА, ТОЛЬКО_ДЛЯ_ТЕСТА, Сотрудник, завести_пользователя,  # noqa: E402
                        удалить_пользователя)

МЕНЕДЖЕР = "УЗ тест менеджер R24"
МЕТКА = "_Тест R24 зарплата урока"
СТАВКА = 500
ЧУЖАЯ = 900
ДОПЛАТА = 1000


def роли(c):
    return ОБЩИЕ_РОЛИ + РОЛИ_ХОЗЯИНА[c.Метаданные.Имя] + ["УЗ_ОсновнаяРоль"] + ТОЛЬКО_ДЛЯ_ТЕСТА


def сценарий(т):
    c = т.c
    удалить_пользователя(т, МЕНЕДЖЕР)
    н = time.time()
    завести_пользователя(т, МЕНЕДЖЕР, роли(c))
    т.вне_бюджета += time.time() - н
    т.убрать(lambda: удалить_пользователя(т, МЕНЕДЖЕР), "пользователь ИБ менеджера")

    ф = Фабрика(т, МЕТКА)
    ставка = ф.элемент("УЗ_СтавкиПедагогов", "500 за занятие", ОплатаЗаЗанятие=СТАВКА)
    чужая = ф.элемент("УЗ_СтавкиПедагогов", "900 за занятие", ОплатаЗаЗанятие=ЧУЖАЯ)
    педагог = ф.педагог("педагог", СтавкаПедагога=ставка)
    ученик = ф.ученик()
    тариф = ф.элемент("УЗ_Тарифы", "тариф")
    ф.цена_тарифа(тариф, ф.день(-400), 800, уроков=1)
    группа = ф.элемент("УЗ_ГруппыОбучения", "группа", Педагог=педагог)
    строка = dict(Ученик=ученик, Тариф=тариф, Явка=True, СписатьОплату=True)

    # урок руководителя (здесь — администратор) с доплатой 1 000 на основании урока
    урок_р = ф.урок(педагог, ф.день(-1, 9), 1, [строка], СтавкаПедагога=ставка)
    ош, сооб = ф.записать(урок_р)
    доплата, (ош2, _) = ф.доплата(урок_р, ДОПЛАТА, "доплата руководителя")
    т.проверить(ош is None and ош2 is None and ф.начислено_педагогу(урок_р) == СТАВКА
                and ф.начислено_педагогу(доплата) == ДОПЛАТА,
                "заготовка: урок руководителя 500 по ставке + доплата 1 000 на основании урока", ош or ош2 or сооб)

    ид = {"ставка": ставка, "чужая": чужая, "педагог": педагог, "ученик": ученик, "тариф": тариф, "группа": группа,
          "урок_р": урок_р.Ссылка, "доплата": доплата.Ссылка}
    ид = {к: c.String(в.УникальныйИдентификатор()) for к, в in ид.items()}
    уроки = []
    с = Сотрудник(т, МЕНЕДЖЕР, "менеджер")
    try:
        день_менеджера(т, ф, с, ид, уроки)
    finally:
        с.закрыть()
    for ид_урока in уроки:   # уроки менеджера — уборка под администратором (с движениями)
        ссылка = c.Документы.УЗ_Урок.ПолучитьСсылку(c.NewObject("УникальныйИдентификатор", ид_урока))
        т.убрать(lambda ссылка=ссылка: т.удалить_объект(ссылка, загрузка=True), "урок менеджера")
    # объекты, которые менеджер завести не должен был, — если проверка покраснела и они записались
    for с_ in т.выбрать("ВЫБРАТЬ С.Ссылка КАК Ссылка ИЗ Справочник.УЗ_ФизЛица КАК С ГДЕ С.Наименование = &И",
                        И=МЕТКА + " новый педагог со ставкой"):
        т.убрать(lambda ссылка=с_.Ссылка: т.удалить_объект(ссылка, загрузка=True), "педагог менеджера")

    # после сеанса менеджера — под администратором: урок руководителя и доплата целы
    а = c.Документы.УЗ_Урок.ПолучитьСсылку(c.NewObject("УникальныйИдентификатор", ид["урок_р"]))
    итог = ф.начислено_педагогу(а) + ф.начислено_педагогу(доплата)
    т.проверить(итог == СТАВКА + ДОПЛАТА and c.String(а.СтавкаПедагога) == c.String(ставка),
                "после менеджера: урок руководителя 500 по прежней ставке + доплата 1 000 = 1 500",
                "%s, ставка %s" % (итог, c.String(а.СтавкаПедагога)))
    п = ф.число("ВЫБРАТЬ КОЛИЧЕСТВО(*) ИЗ Справочник.УЗ_ФизЛица КАК С ГДЕ С.Ссылка = &П И С.СтавкаПедагога = &С",
                П=педагог, С=ставка)
    г = ф.число("ВЫБРАТЬ КОЛИЧЕСТВО(*) ИЗ Справочник.УЗ_ГруппыОбучения КАК Г "
                "ГДЕ Г.Ссылка = &Г И Г.СтавкаПедагога = ЗНАЧЕНИЕ(Справочник.УЗ_СтавкиПедагогов.ПустаяСсылка)", Г=группа)
    т.проверить(п == 1 and г == 1, "после менеджера: ставка в карточке педагога и в группе прежняя", (п, г))


def день_менеджера(т, ф, с, ид, уроки):
    c = т.c
    м = с.c

    def ссылка(коллекция, вид, ключ):
        return с.ссылка(коллекция, вид, ид[ключ])
    ставка = ссылка("Справочники", "УЗ_СтавкиПедагогов", "ставка")
    чужая = ссылка("Справочники", "УЗ_СтавкиПедагогов", "чужая")
    педагог = ссылка("Справочники", "УЗ_ФизЛица", "педагог")
    урок_р = ссылка("Документы", "УЗ_Урок", "урок_р")

    def начислено(ид_урока):
        """Под администратором: движение урока менеджера в регистре расчётов с педагогами."""
        return ф.начислено_педагогу(c.Документы.УЗ_Урок.ПолучитьСсылку(c.NewObject("УникальныйИдентификатор", ид_урока)))

    def записать(объект, режим="Проведение"):
        """→ текст отказа (ошибка и сообщения) или None, если записано."""
        м.ПолучитьСообщенияПользователю(True)
        try:
            объект.Записать(getattr(м.РежимЗаписиДокумента, режим)) if режим else объект.Записать()
            return None
        except Exception as е:
            сообщения = м.ПолучитьСообщенияПользователю(True)
            return " | ".join([сообщения.Получить(н).Текст for н in range(сообщения.Количество())]
                              + [текст_ошибки(е, 200)])

    def новый_урок(час, **реквизиты):
        д = м.Документы.УЗ_Урок.СоздатьДокумент()
        д.Дата = ф.день(-1, час)
        д.Педагог = педагог
        д.КоличествоЧасов = 1
        д.Комментарий = МЕТКА
        for к, в in реквизиты.items():
            setattr(д, к, в)
        с_ = д.Ученики.Добавить()
        с_.Ученик = ссылка("Справочники", "УЗ_ФизЛица", "ученик")
        с_.Тариф = ссылка("Справочники", "УЗ_Тарифы", "тариф")
        с_.Явка = True
        с_.СписатьОплату = True
        м.ПолучитьСообщенияПользователю(True)
        д.Записать(м.РежимЗаписиДокумента.Проведение)
        сообщения = м.ПолучитьСообщенияПользователю(True)
        уроки.append(с.ид(д.Ссылка))
        return д, [сообщения.Получить(н).Текст for н in range(сообщения.Количество())]

    # ── урок менеджера проводится, начисление педагогу верное ──
    итог = с.шаг("проводит свой урок (ставку не выбирает — форма подставляет ставку педагога)",
                 lambda: новый_урок(11))
    if итог is not None:
        д, _ = итог
        т.проверить(начислено(с.ид(д.Ссылка)) == СТАВКА and м.String(д.СтавкаПедагога) == м.String(ставка),
                    "урок менеджера: ставка педагога по умолчанию, движение педагогу 500 в УЗ_РасчетыПоЗарплате",
                    начислено(с.ид(д.Ссылка)))
    итог = с.шаг("проводит новый урок с чужой ставкой 900 в обход формы", lambda: новый_урок(13, СтавкаПедагога=чужая))
    if итог is not None:
        д, сообщения = итог
        т.проверить(начислено(с.ид(д.Ссылка)) == СТАВКА and м.String(д.СтавкаПедагога) == м.String(ставка)
                    and any("выбирает руководитель" in с_ for с_ in сообщения),
                    "новый урок менеджера со ставкой 900: ставка заменена на ставку по умолчанию, начислено 500 "
                    "(было 900), сообщение", (начислено(с.ид(д.Ссылка)), м.String(д.СтавкаПедагога), сообщения))

    # ── прочитать начисление нельзя ──
    def запрос(текст, **параметры):
        з = м.NewObject("Запрос")
        з.Текст = текст
        for к, в in параметры.items():
            з.УстановитьПараметр(к, в)
        return з.Выполнить().Выгрузить()

    for что, текст in (("поле «Начислено педагогу» урока",
                        "ВЫБРАТЬ У.НачисленоПедагогу КАК Сумма ИЗ Документ.УЗ_Урок КАК У ГДЕ У.Ссылка = &У"),
                       ("таблицу «Начисления педагогу» урока",
                        "ВЫБРАТЬ Н.СуммаНачисления КАК Сумма ИЗ Документ.УЗ_Урок.НачисленияПедагогу КАК Н "
                        "ГДЕ Н.Ссылка = &У")):
        try:
            тз = запрос(текст, У=урок_р)
            т.проверить(False, "менеджер — не прочитать %s запросом" % что,
                        "прочитано: %s" % [float(тз.Получить(н).Сумма) for н in range(тз.Количество())])
        except Exception as е:
            т.проверить(True, "менеджер — не прочитать %s запросом (в уроке его нет: %s)" % (что, текст_ошибки(е, 80)))
    с.запрещено("прочитать регистр расчётов с педагогами (УЗ_РасчетыПоЗарплате)",
                lambda: запрос("ВЫБРАТЬ Р.Сумма КАК Сумма ИЗ РегистрНакопления.УЗ_РасчетыПоЗарплате КАК Р "
                               "ГДЕ Р.Регистратор = &У", У=урок_р),
                "РегистрНакопления.УЗ_РасчетыПоЗарплате")
    доплат = с.шаг("ищет доплаты руководителя запросом (РАЗРЕШЕННЫЕ)", lambda: запрос(
        "ВЫБРАТЬ РАЗРЕШЕННЫЕ Д.Ссылка КАК Ссылка, Д.СуммаДокумента КАК Сумма ИЗ Документ.УЗ_НачисленияПедагогам КАК Д "
        "ГДЕ Д.ДокументОснования = &У", У=урок_р).Количество())
    т.проверить(доплат == 0, "менеджер: доплаты руководителя по уроку не видны (0 строк)", доплат)
    с.запрещено("открыть доплату руководителя по ссылке",
                lambda: ссылка("Документы", "УЗ_НачисленияПедагогам", "доплата").ПолучитьОбъект().СуммаДокумента,
                "Документ.УЗ_НачисленияПедагогам")

    # ── изменить нельзя ──
    о = урок_р.ПолучитьОбъект()
    о.СтавкаПедагога = чужая
    отказ = записать(о)
    т.проверить(отказ is not None and "меняет руководитель" in отказ,
                "менеджер — запрещено: сменить ставку записанного урока на 900 (было: записано, начислено 900)",
                отказ or "записано: начислено %s" % начислено(ид["урок_р"]))

    def новая_доплата():
        д = м.Документы.УЗ_НачисленияПедагогам.СоздатьДокумент()
        д.Заполнить(урок_р)
        с_ = д.НачисленияПедагогам.Добавить()
        с_.Сумма = 5000
        с_.Комментарий = МЕТКА
        д.Комментарий = МЕТКА
        д.Записать(м.РежимЗаписиДокумента.Проведение)
    с.запрещено("доплата педагогу (документ «Начисление педагогам»)", новая_доплата, "Документ.УЗ_НачисленияПедагогам")

    def изменить_ставку_справочника():
        о_ = ставка.ПолучитьОбъект()
        о_.ОплатаЗаЗанятие = ЧУЖАЯ
        о_.Записать()
    с.запрещено("изменить сумму ставки", изменить_ставку_справочника, "Справочник.УЗ_СтавкиПедагогов")

    о = педагог.ПолучитьОбъект()
    о.СтавкаПедагога = чужая
    отказ = записать(о, None)
    т.проверить(отказ is not None and "назначает и меняет руководитель" in отказ,
                "менеджер — запрещено: сменить ставку в карточке педагога", отказ or "записано")
    о = м.Справочники.УЗ_ФизЛица.СоздатьЭлемент()
    о.Наименование = МЕТКА + " новый педагог со ставкой"
    о.ЭтоПедагог = True
    о.СтавкаПедагога = чужая
    отказ = записать(о, None)
    т.проверить(отказ is not None and "назначает и меняет руководитель" in отказ,
                "менеджер — запрещено: завести педагога со ставкой", отказ or "записано")
    о = ссылка("Справочники", "УЗ_ГруппыОбучения", "группа").ПолучитьОбъект()
    о.СтавкаПедагога = чужая
    отказ = записать(о, None)
    т.проверить(отказ is not None and "назначает и меняет руководитель" in отказ,
                "менеджер — запрещено: поставить ставку группе", отказ or "записано")

    # ── обычная работа с уроком руководителя: тема, перепроведение — доплата и начисление на месте ──
    def тема():
        о_ = урок_р.ПолучитьОбъект()
        о_.ТемаУрока = "Интервалы"
        о_.Записать(м.РежимЗаписиДокумента.Проведение)
    с.шаг("меняет тему урока руководителя и перепроводит его", тема)
    print("  (предел R24: суммы ставок читает код проведения урока в сеансе менеджера — запросом к справочнику ставок "
          "их можно прочитать; начисления, доплаты и регистр расчётов с педагогами менеджеру недоступны)")


if __name__ == "__main__":
    запустить("ревью_зарплата_урока", сценарий)
