"""Урок: длительность с точностью до минуты (решение В13, Codex A12) — 40 и 50 минут.

Было: КоличествоЧасов с 2 знаками — 40 минут хранились как 0,67 ч: в регистр уходило 0,67 × 3 600 = 2 412 секунд
вместо 2 400, по тарифу 1 000 ₽/ч урок стоил 670 ₽ вместо 666,67, «за час» 600 ₽ начисляли 402 ₽ вместо 400;
урок кончался в 9:40:12 — следующий урок педагога в 9:40 считался пересечением; три урока по 40 минут
(3 × 0,67 = 2,01 ч) не помещались в абонемент на 2 часа.
Стало: часы с 4 знаками (0,6667), время/секунды/деньги — от целых минут (Документы.УЗ_Урок.СекундУрока,
ЧасовУрока), деньги до копеек.
Мутация: в СекундУрока вернуть КоличествоЧасов * 3600 — краснеют «регистр 2 400 с», «стык 9:40», «абонемент».

    python tools\\тесты\\тест_урок_точность.py --база=C:\\1c_bases\\UZ_UNF_B
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from фабрика import Фабрика  # noqa: E402

МЕТКА = "УЗ тест точности урока"


def сценарий(т):
    ф = Фабрика(т, МЕТКА)
    ставка = ф.элемент("УЗ_СтавкиПедагогов", "600 за час", ОплатаЗаЧас=600)
    педагог = ф.педагог(СтавкаПедагога=ставка)
    педагог2 = ф.педагог("педагог абонемента")
    ученик = ф.ученик()
    тариф = ф.элемент("УЗ_Тарифы", "1000 в час", Сумма=1000, КоличествоЧасов=1)

    def урок(п, час, минута, минут, строки, **реквизиты):
        д = ф.урок(п, ф.день(-1, час, минута), минут / 60, строки, **реквизиты)
        return д, ф.записать(д, "Проведение")

    def секунд_в_регистре(ссылка):
        return ф.число("""ВЫБРАТЬ СУММА(Р.Часы) ИЗ РегистрНакопления.УЗ_СписанияСуммЗаУроки КАК Р
            ГДЕ Р.Регистратор = &У""", У=ссылка)

    строка = dict(Ученик=ученик, Тариф=тариф, Явка=True, СписатьОплату=True)
    for минут, час, цена, начисление in ((40, 9, 666.67, 400.0), (50, 11, 833.33, 500.0)):
        д, (ошибка, сообщения) = урок(педагог, час, 0, минут, [строка], СтавкаПедагога=ставка)
        т.проверить(ошибка is None, "%d мин: урок проведён" % минут, "%s %s" % (ошибка, сообщения))
        о = д.Ссылка.ПолучитьОбъект()
        часов = round(float(о.КоличествоЧасов), 4)
        т.проверить(часов == round(минут / 60, 4), "%d мин: часы хранятся с 4 знаками (%s)" % (минут, round(минут / 60, 4)),
                    часов)
        длительность = (о.Окончание - о.Дата).total_seconds()
        т.проверить(длительность == минут * 60, "%d мин: окончание урока ровно через %d мин" % (минут, минут),
                    длительность)
        секунд = секунд_в_регистре(д.Ссылка)
        т.проверить(секунд == минут * 60, "%d мин: в регистр списаний %d секунд" % (минут, минут * 60), секунд)
        сумма = round(float(о.Ученики.Получить(0).Сумма), 2)
        т.проверить(сумма == цена, "%d мин по 1 000 ₽/ч: сумма строки %.2f (до копеек)" % (минут, цена), сумма)
        начислено = round(float(о.НачисленоПедагогу), 2)
        т.проверить(начислено == начисление, "%d мин, «за час» 600 ₽: педагогу %.2f" % (минут, начисление), начислено)

    # стык: урок того же педагога сразу после 40-минутного (9:00–9:40 → 9:40) — не пересечение
    _, (ошибка, сообщения) = урок(педагог, 9, 40, 20, [строка], СтавкаПедагога=ставка)
    т.проверить(ошибка is None, "урок в 9:40 после урока 9:00–9:40 проводится (стык, не пересечение)",
                "%s %s" % (ошибка, сообщения))

    # абонемент на 2 часа: ровно три урока по 40 минут, четвёртый — отказ
    абонемент = ф.абонемент(ученик, "на 2 часа", КоличествоЧасов=2, ЦенаАбонемента=3000)
    по_абонементу = dict(строка, Абонемент=абонемент)
    for номер, час in enumerate((13, 14, 15), 1):
        д, (ошибка, сообщения) = урок(педагог2, час, 0, 40, [по_абонементу])
        т.проверить(ошибка is None, "абонемент 2 ч: урок %d по 40 мин проводится" % номер, "%s %s" % (ошибка, сообщения))
        if номер == 1 and ошибка is None:
            сумма = round(float(д.Ссылка.ПолучитьОбъект().Ученики.Получить(0).Сумма), 2)
            т.проверить(сумма == 1000.0, "цена 40 мин по абонементу 3 000 ₽ / 2 ч = 1 000,00", сумма)
    _, (ошибка, сообщения) = урок(педагог2, 16, 0, 40, [по_абонементу])
    т.проверить(ошибка is not None and any("хватает" in текст for текст, _ in сообщения),
                "абонемент 2 ч исчерпан тремя уроками по 40 мин — четвёртый отказ", "%s %s" % (ошибка, сообщения))


if __name__ == "__main__":
    запустить("урок_точность", сценарий)
