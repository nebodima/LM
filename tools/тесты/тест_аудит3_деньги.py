"""Третий аудит Codex (28.09.2026), находки 1–3: деньги ученика, оплата абонемента, бонусы.

  Н1 Возврат без предмета проверял сумму ВСЕХ предметов, а расход писал в пустой предмет: аванс математики 1 000
     возвращался «без предмета», затем ещё раз «по математике» (внёс 1 000 — получил 2 000). То же перемещение
     «без предмета → математика» при деньгах только на математике. Стало: проверяется тот же разрез, куда пишется
     расход; без предмета — свободный аванс без предмета (не зачтённый в долги предметов); перемещение аванса без
     предмета в предмет с долгом (зачёт) — можно.
  Н2 Приход по абонементу организации А / математика проводился в организации Б или по гитаре — абонемент
     показывался оплаченным, деньги лежали в другом разрезе. Стало: ученик, организация и предмет прихода — как у
     абонемента (форма очищает несогласованный абонемент при смене ученика, организации, предмета).
  Н3 Начисление 100 бонусов, оплата ими 100, затем начисление уменьшали до 10 / отменяли / переносили на другую
     карту — карта уходила в минус, оплата оставалась. То же урок — источник бонусов. Стало: изъятие уже
     потраченных бонусов — отказ (под блокировкой карты); уменьшение в пределах неиспользованного — можно.

    python tools\\тесты\\тест_аудит3_деньги.py --база=C:\\1c_bases\\UZ_BP_B --пользователь=1
"""
# затрагивает: УЗ_Сервер, УЗ_РасходДенег, УЗ_ПеремещениеДенег, УЗ_ПриходДенег, УЗ_НачислениеБонусов, УЗ_Урок
# затрагивает: УЗ_СписаниеОстатков, УЗ_ДвижениеДисконтныхКарт, УЗ_СписанияСуммЗаУроки
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from _деньги import Данные  # noqa: E402
from фабрика import Фабрика  # noqa: E402

МЕТКА = "_Тест аудит3 деньги"
ОСТАТОК_КАРТЫ = ("ВЫБРАТЬ ЕСТЬNULL(СУММА(Р.СуммаБонусовОстаток), 0) "
                 "ИЗ РегистрНакопления.УЗ_ДвижениеДисконтныхКарт.Остатки(, ДисконтнаяКарта = &Карта) КАК Р")
ОСТАТОК_УЧЕНИКА = ("ВЫБРАТЬ ЕСТЬNULL(СУММА(Р.СуммаОстаток), 0) ИЗ РегистрНакопления.УЗ_СписанияСуммЗаУроки.Остатки(, "
                   "Клиент = &Ученик И Организация = &Организация) КАК Р")


def сценарий(т):
    c = т.c
    ф = Фабрика(т, МЕТКА)
    д_ = Данные(т, МЕТКА)
    виды = c.Перечисления.УЗ_ВидыОпераций
    орг = ф.организация("А")
    орг_б = ф.организация("Б")
    касса = ф.элемент("УЗ_Кассы", "касса")
    математика = ф.элемент("УЗ_ПредметыОбучения", "математика")
    гитара = ф.элемент("УЗ_ПредметыОбучения", "гитара")
    пусто = c.Справочники.УЗ_ПредметыОбучения.ПустаяСсылка()
    д_.движения("УЗ_Касса", д_.регистратор(), [("+", ф.день(-10, 9), {"Касса": касса, "Сумма": 100000,
                                                                     "Организация": орг, "ВидОперации": виды.КассаУченики})])

    def деньги(кто, строки):
        д_.движения("УЗ_СписанияСуммЗаУроки", д_.регистратор(),
                    [("+" if сумма > 0 else "-", ф.день(-10, 9), {"Клиент": кто, "Сумма": abs(сумма),
                                                                 "Организация": орг, "ПредметОбучения": предмет})
                     for предмет, сумма in строки])

    def возврат(кто, сумма, предмет, сдвиг):
        р = д_.документ("УЗ_РасходДенег", Дата=ф.день(сдвиг, 10), Организация=орг, Касса=касса,
                        ВидОперации=виды.КассаУченики, ФизЛицо=кто, ПредметОбучения=предмет, СуммаДокумента=сумма)
        return д_.записать(р)

    def перемещение(кто, сумма, откуда, куда, сдвиг):
        п = д_.документ("УЗ_ПеремещениеДенег", Дата=ф.день(сдвиг, 10), Организация=орг, Клиент=кто,
                        СделатьДвиженияПоВзаиморасчетам=True, ПредметОбученияОтправитель=откуда,
                        ПредметОбученияПолучатель=куда, Сумма=сумма)
        return д_.записать(п)

    def остаток(кто):
        return ф.число(ОСТАТОК_УЧЕНИКА, Ученик=кто, Организация=орг)

    def отказ(ош, что, слово):
        т.проверить(ош is not None and слово in ош, что, ош)

    def проведён(ош, что):
        т.проверить(ош is None, что, ош)

    # ── Н1: возврат ──
    у1 = ф.ученик("Н1 аванс математики")
    деньги(у1, [(математика, 1000)])
    отказ(возврат(у1, 1000, пусто, -5), "Н1: аванс только по математике 1 000 — возврат 1 000 без предмета: отказ "
          "(было: проводился из аванса математики)", "Вернуть")
    проведён(возврат(у1, 1000, математика, -4), "Н1: возврат 1 000 по математике проводится")
    отказ(возврат(у1, 1, математика, -3), "Н1: после возврата аванса математики ещё 1 по математике — отказ", "Вернуть")
    т.проверить(остаток(у1) == 0, "Н1: внёс 1 000 — вернули 1 000, остаток 0 (было: −1 000, выдано 2 000)", остаток(у1))

    у2 = ф.ученик("Н1 аванс без предмета зачтён")
    деньги(у2, [(пусто, 1000), (математика, -1000), (гитара, 500)])
    отказ(возврат(у2, 500, пусто, -5), "Н1: без предмета +1 000, долг математики 1 000, гитара +500 — возврат 500 без "
          "предмета: отказ (аванс без предмета оплатил математику; было: сумма всех предметов 500 — проводился)",
          "Вернуть")
    проведён(возврат(у2, 500, гитара, -4), "Н1: тот же ученик — возврат 500 по гитаре (её аванс) проводится")

    # ── Н1: перемещение ──
    у3 = ф.ученик("Н1 перемещение")
    деньги(у3, [(математика, 1000)])
    отказ(перемещение(у3, 1000, пусто, математика, -5), "Н1: деньги только на математике — перемещение 1 000 «без "
          "предмета → математика»: отказ (было: проводилось, аванс математики удваивался)", "Невозможно переместить")
    т.проверить(остаток(у3) == 1000, "Н1: остаток ученика не изменился — 1 000", остаток(у3))

    у4 = ф.ученик("Н1 зачёт аванса")
    деньги(у4, [(пусто, 1000), (математика, -1000)])
    проведён(перемещение(у4, 1000, пусто, математика, -5),
             "Н1: аванс без предмета 1 000 и долг математики 1 000 — перемещение в математику (зачёт) проводится")
    у5 = ф.ученик("Н1 аванс в другой предмет")
    деньги(у5, [(пусто, 1000), (математика, -1000)])
    отказ(перемещение(у5, 1000, пусто, гитара, -5), "Н1: аванс без предмета, зачтённый в долг математики, в гитару не "
          "уводится — отказ", "Невозможно переместить")

    # ── Н2: оплата абонемента ──
    уа = ф.ученик("Н2 ученик")
    чужой = ф.ученик("Н2 другой ученик")
    аб = ф.абонемент(уа, "Н2 абонемент", Организация=орг, ПредметОбучения=математика, ЦенаАбонемента=8000)

    def оплата(кто, организация, предмет, **ещё):
        п = ф.приход(кто, 8000, Абонемент=аб, Организация=организация, Касса=касса, ПредметОбучения=предмет,
                     Дата=ф.день(-2, 10), **ещё)
        ош, сообщения = ф.записать(п)
        return None if ош is None else "%s %s" % (ош, " ".join(т_ for т_, _ in сообщения))

    отказ(оплата(уа, орг_б, математика), "Н2: абонемент организации А — оплата в организации Б: отказ (было: проводилась, "
          "абонемент «оплачен»)", "продан организацией")
    отказ(оплата(уа, орг, гитара), "Н2: абонемент по математике — оплата по гитаре: отказ", "по предмету")
    отказ(оплата(чужой, орг, математика), "Н2: абонемент ученика — оплата от другого ученика: отказ", "ученика")
    отказ(оплата(уа, орг, математика, ВидОперации=виды.ВнутренняяКасса), "Н2: абонемент во «Внутренней кассе»: отказ",
          "Касса ученики")
    проведён(оплата(уа, орг, математика), "Н2: оплата абонемента его учеником, организацией и предметом проводится")
    оплачено = float(c.УЗ_Сервер.ОплаченоПоАбонементу(аб))
    т.проверить(оплачено == 8000, "Н2: по абонементу оплачено 8 000 (одна верная оплата)", оплачено)

    # ── Н3: «Начисление бонусов» ──
    ув = ф.ученик("Н3 ученик")
    карта = ф.карта(ув, "Н3 карта")
    карта2 = ф.карта(ув, "Н3 вторая карта")

    def остаток_карты(к):
        return ф.число(ОСТАТОК_КАРТЫ, Карта=к)

    нач = д_.документ("УЗ_НачислениеБонусов", Дата=ф.день(-5, 10), Организация=орг)
    с = нач.ДисконтныеКарты.Добавить()
    с.ДисконтнаяКарта = карта
    с.СуммаБонусов = 100
    проведён(д_.записать(нач), "Н3: начисление 100 бонусов проведено")
    пко = ф.приход(ув, 0, ДисконтнаяКарта=карта, СуммаБонусов=100, Организация=орг, Дата=ф.день(-4, 10))
    ош, сооб = ф.записать(пко)
    т.проверить(ош is None, "Н3: оплата 100 бонусами проведена", (ош, сооб))

    def изменить_начисление(сумма=None, карта_=None, режим="Проведение"):
        о = нач.Ссылка.ПолучитьОбъект()
        if сумма is not None:
            о.ДисконтныеКарты.Получить(0).СуммаБонусов = сумма
        if карта_ is not None:
            о.ДисконтныеКарты.Получить(0).ДисконтнаяКарта = карта_
        return д_.записать(о, getattr(c.РежимЗаписиДокумента, режим))

    отказ(изменить_начисление(10), "Н3: потрачено 100 — уменьшить начисление до 10: отказ (было: карта −90)",
          "уже потрачены")
    отказ(изменить_начисление(режим="ОтменаПроведения"), "Н3: отменить проведение начисления: отказ (было: карта −100)",
          "уже потрачены")
    отказ(изменить_начисление(карта_=карта2), "Н3: перенести начисление на другую карту: отказ", "уже потрачены")
    т.проверить(остаток_карты(карта) == 0 and остаток_карты(карта2) == 0, "Н3: карты не в минусе (0 и 0)",
                (остаток_карты(карта), остаток_карты(карта2)))
    проведён(изменить_начисление(150), "Н3: увеличить начисление до 150 — можно")
    проведён(изменить_начисление(100), "Н3: уменьшить до 100 (в пределах неиспользованных 50) — можно")

    # ── Н3: урок — источник бонусов ──
    педагог = ф.педагог("Н3 педагог")
    карта3 = ф.карта(ув, "Н3 карта урока")
    урок = ф.урок(педагог, ф.день(-3, 10), 1, [dict(Ученик=ув, Явка=True, ДисконтнаяКарта=карта3, СуммаБонусов=50,
                                                     Заметка=МЕТКА)], Организация=орг)
    ош, сооб = ф.записать(урок)
    т.проверить(ош is None, "Н3: урок начислил 50 бонусов", (ош, сооб))
    ош, сооб = ф.записать(ф.приход(ув, 0, ДисконтнаяКарта=карта3, СуммаБонусов=50, Организация=орг,
                                   Дата=ф.день(-2, 11)))
    т.проверить(ош is None, "Н3: оплата 50 бонусами урока проведена", (ош, сооб))

    def изменить_урок(сумма=None, режим="Проведение"):
        о = урок.Ссылка.ПолучитьОбъект()
        if сумма is not None:
            о.Ученики.Получить(0).СуммаБонусов = сумма
        ош_, сооб_ = ф.записать(о, режим)
        return None if ош_ is None else "%s %s" % (ош_, " ".join(т_ for т_, _ in сооб_))

    отказ(изменить_урок(0), "Н3: урок — убрать потраченные 50 бонусов из строки: отказ", "уже потрачены")
    отказ(изменить_урок(режим="ОтменаПроведения"), "Н3: урок — отменить проведение: отказ", "уже потрачены")
    т.проверить(остаток_карты(карта3) == 0, "Н3: карта урока не в минусе", остаток_карты(карта3))


if __name__ == "__main__":
    запустить("аудит3_деньги", сценарий)
