"""Ревью Codex логик 28.09.2026 — R16 (и T06): «Продление группы» берёт состав группы на дату урока.

Единое правило состава (РегистрыСведений.УЗ_СоставГрупп.СоставГруппыНаДату, В18/В22/В29): ученик в группе на дату
по документам «Перевод ученика»; выбывший («Выбыл») не подбирается. Продление — через рабочий маршрут
(Документы.УЗ_Урок.ПродлитьГруппу, как помощник уроков), а не вызовом самой функции состава (T06).
  Группа каждый день 10:00–11:30. Последний урок группы (3 дня назад): Анна и Вера. Анна из группы ушла (последний
  день — позавчера), Борис зачислен со вчерашнего дня, Вера без единого документа по группе (записывали только в
  уроки — старые данные), Глеб зачислен, но «Выбыл».
  Продление на послезавтра: в уроке Борис и Вера; Анны и Глеба нет.
Старый код: копия учеников последнего урока — Анна и Вера, Бориса нет (Анне спишут занятия за чужую группу).

    python tools\\тесты\\тест_ревью_группы.py --база=C:\\1c_bases\\UZ_UNF_D
"""
# затрагивает: УЗ_Урок, УЗ_ФизЛица, УЗ_ГруппыОбучения, УЗ_СоставГрупп
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from фабрика import Фабрика  # noqa: E402
from _логика_абонементов import вызов  # noqa: E402
from логика_урок import строка  # noqa: E402
from тест_логика_абонементы_3 import группа_обучения  # noqa: E402

МЕТКА = "_Тест ревью групп"


def сценарий(т):
    c = т.c
    ф = Фабрика(т, МЕТКА)
    предмет = ф.элемент("УЗ_ПредметыОбучения", "предмет")
    педагог = ф.педагог()
    тариф = ф.элемент("УЗ_Тарифы", "1 000 за урок", Сумма=1000, КоличествоУроков=1)
    группа = группа_обучения(т, ф, "группа", педагог, тариф, предмет)

    def убрать_уроки():
        тз = т.выбрать("ВЫБРАТЬ У.Ссылка КАК Ссылка ИЗ Документ.УЗ_Урок КАК У ГДЕ У.ГруппаОбучения = &Г", Г=группа)
        for н in range(тз.Количество()):
            т.удалить_объект(тз.Получить(н).Ссылка, загрузка=True)
    т.убрать(убрать_уроки, "уроки группы")

    def ученик(имя, начало=None, конец=None, выбыл=False):
        у = ф.элемент("УЗ_ФизЛица", имя)
        if начало is not None:
            ф.в_группу(у, группа, начало, конец)
        if выбыл:
            о = у.ПолучитьОбъект()
            о.Выбыл = True
            о.Записать()
        return у
    анна = ученик("Анна", -30, -2)
    борис = ученик("Борис", -1)
    вера = ученик("Вера")
    глеб = ученик("Глеб", -30, выбыл=True)
    урок = ф.урок(педагог, ф.день(-3, 10), 1.5, [строка(анна, Тариф=тариф), строка(вера, Тариф=тариф)],
                  ГруппаОбучения=группа, ПредметОбучения=предмет)
    ош, сооб = ф.записать(урок)
    т.проверить(ош is None, "заготовка: последний урок группы 3 дня назад — Анна и Вера", ош or сооб)

    _, ошибка = вызов(lambda: c.Документы.УЗ_Урок.ПродлитьГруппу(группа, т.массив(ф.день(2))))
    тз = т.выбрать("""ВЫБРАТЬ С.Ученик КАК Ученик ИЗ Документ.УЗ_Урок.Ученики КАК С
        ГДЕ С.Ссылка.ГруппаОбучения = &Г И С.Ссылка.Дата МЕЖДУ &Н И &К""", Г=группа, Н=ф.день(2), К=ф.день(2, 23, 59))
    имена = sorted(c.String(тз.Получить(н).Ученик).replace(МЕТКА + " ", "") for н in range(тз.Количество()))
    т.проверить(ошибка is None and имена == ["Борис", "Вера"],
                "R16: продление на послезавтра — Борис (принят вчера) и Вера (без документов по группе); Анны (ушла) и "
                "Глеба (выбыл) нет (было: Анна и Вера)", ошибка or имена)


if __name__ == "__main__":
    запустить("ревью_группы", сценарий)
