"""Выплата зарплаты и прочие расходы внутренней кассы (решения владельца В7, В9 от 28.09.2026).

Было: любой РКО «Внутренняя касса» уменьшал долг педагогу (аренда на педагога гасила его зарплату,
без физ. лица — «выплата» с пустым педагогом); выплата по расчёту зарплаты ничем не ограничивалась.
Стало:
  * вид «Выплата зарплаты» — педагогу («Это педагог», Р4) и только на основании проведённого расчёта (Р3),
    закрывает долг (расход УЗ_РасчетыПоЗарплате); ученику или без расчёта — отказ, долг не тронут;
  * вид «Прочий расход» — только касса, долг педагогу не меняет;
  * «Внутренняя касса» в новом РКО — отказ с подсказкой; в кассе оба вида — раздел «Внутренняя касса»;
  * РКО на основании проведённого расчёта: педагог, касса, невыплаченный остаток; переплата — отказ.

    python tools\\тесты\\тест_выплата_зарплаты.py --база=C:\\1c_bases\\UZ_UNF_A
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import дата, запустить  # noqa: E402
from _деньги import Данные  # noqa: E402

МЕТКА = "_Тест выплата зарплаты"


def сценарий(т):
    c = т.c
    д = Данные(т, МЕТКА)
    виды = c.Перечисления.УЗ_ВидыОпераций
    педагог = д.элемент("УЗ_ФизЛица", "педагог", ЭтоПедагог=True)
    касса = д.элемент("УЗ_Кассы", "касса")
    # В14: касса не уходит в минус — деньги в кассе заранее, движением на носителе
    д.движения("УЗ_Касса", д.регистратор(), [("+", дата(2026, 9, 1, 9), {"Касса": касса, "Сумма": 10000})])

    статья = д.элемент("УЗ_СтатьиДвиженияДенег", "аренда")

    def рко(вид, сумма, физлицо=None, час=10):
        р = д.документ("УЗ_РасходДенег", Дата=дата(2026, 9, 6, час), Касса=касса, СуммаДокумента=сумма, ВидОперации=вид,
                       СтатьяЗатрат=статья)   # прочий расход — со статьёй (попадает в отчёт «Расходы»)
        if физлицо is not None:
            р.ФизЛицо = физлицо
        return р

    def долг(р):
        return д.итог("УЗ_РасчетыПоЗарплате", р.Ссылка)

    def раздел_кассы(р):
        з = c.NewObject("Запрос")
        з.Текст = "ВЫБРАТЬ РАЗЛИЧНЫЕ Р.ВидОперации КАК Вид ИЗ РегистрНакопления.УЗ_Касса КАК Р ГДЕ Р.Регистратор = &Р"
        з.УстановитьПараметр("Р", р.Ссылка)
        в = з.Выполнить().Выгрузить()
        return [c.String(в.Получить(н).Вид) for н in range(в.Количество())]

    внутренняя = c.String(виды.ВнутренняяКасса)

    # 1. прочий расход на педагога — долг не меняет
    р = рко(виды.ПрочийРасход, 300, педагог)
    ош = д.записать(р)
    т.проверить(ош is None and долг(р) == (0.0, 0), "«Прочий расход» (аренда) на педагога — долг педагогу не меняется",
                ош or долг(р))
    т.проверить(раздел_кассы(р) == [внутренняя], "в кассе прочий расход — раздел «Внутренняя касса»", раздел_кассы(р))

    # 2. выплата зарплаты: без физ. лица, не педагогу (Р4/В7), без расчёта в основании (Р3/В9) — отказ
    ош = д.записать(рко(виды.ВыплатаЗарплаты, 1000, None, 12))
    т.проверить(ош is not None, "«Выплата зарплаты» без физ. лица — отказ", ош)
    ученик = д.элемент("УЗ_ФизЛица", "ученик")
    р = рко(виды.ВыплатаЗарплаты, 1000, ученик, 11)
    ош = д.записать(р)
    т.проверить(ош is not None and "не педагог" in ош and долг(р) == (0.0, 0),
                "«Выплата зарплаты» ученику (не «Это педагог») — отказ, долг не тронут (Р4)", ош or долг(р))
    р = рко(виды.ВыплатаЗарплаты, 1000, педагог, 11)
    ош = д.записать(р)
    т.проверить(ош is not None and "на основании проведённого расчёта" in ош and долг(р) == (0.0, 0),
                "«Выплата зарплаты» педагогу без расчёта в основании — отказ, долг мимо ведомости не гасится (Р3)",
                ош or долг(р))

    # 3. «Внутренняя касса» в новом РКО — отказ с подсказкой
    ош = д.записать(рко(виды.ВнутренняяКасса, 100, педагог, 13))
    т.проверить(ош is not None and "Прочий расход" in ош, "РКО «Внутренняя касса» — отказ: выбрать выплату или прочий расход", ош)

    # 4. РКО на основании проведённого расчёта: остаток к выплате, переплата — отказ
    # В12: касса — по организации; расчёт и начисление — в организации по умолчанию, как РКО без организации
    орг = c.РегистрыСведений.УЗ_Настройки.Настройки().Организация
    н = д.документ("УЗ_НачисленияПедагогам", Дата=дата(2026, 8, 5, 10), Педагог=педагог, Организация=орг)
    строка = н.НачисленияПедагогам.Добавить()
    строка.Сумма = 1500
    т.проверить(д.записать(н) is None, "начисление 1 500 проведено")
    расчёт = д.документ("УЗ_РасчетЗарплаты", Дата=дата(2026, 9, 1, 9), Педагог=педагог, Касса=касса, Организация=орг,
                        ДатаНачала=дата(2026, 8, 1), ДатаОкончания=дата(2026, 8, 31))
    расчёт.ЗаполнитьНачисления()
    т.проверить(д.записать(расчёт) is None and float(расчёт.СуммаДокумента) == 1500, "расчёт на 1 500 проведён")
    первая = д.документ("УЗ_РасходДенег")
    первая.Заполнить(расчёт.Ссылка)
    т.проверить(c.String(первая.ВидОперации) == c.String(виды.ВыплатаЗарплаты)
                and c.String(первая.ФизЛицо) == c.String(педагог) and float(первая.СуммаДокумента) == 1500
                and c.String(первая.Касса) == c.String(касса),
                "РКО на основании расчёта: выплата зарплаты педагогу 1 500 из кассы расчёта",
                "%s, %s, %s" % (c.String(первая.ВидОперации), c.String(первая.ФизЛицо), первая.СуммаДокумента))
    первая.Дата = дата(2026, 9, 7, 10)
    первая.Комментарий = МЕТКА
    первая.СуммаДокумента = 1000
    т.проверить(д.записать(первая) is None, "частичная выплата 1 000 по расчёту проведена")
    т.проверить(долг(первая) == (-1000.0, 1) and раздел_кассы(первая) == [внутренняя],
                "выплата по расчёту — расход долга 1 000, в кассе раздел «Внутренняя касса»", долг(первая))
    вторая = д.документ("УЗ_РасходДенег")
    вторая.Заполнить(расчёт.Ссылка)
    т.проверить(float(вторая.СуммаДокумента) == 500, "вторая выплата по расчёту — остаток 500", вторая.СуммаДокумента)
    вторая.Дата = дата(2026, 9, 7, 11)
    вторая.Комментарий = МЕТКА
    вторая.СуммаДокумента = 600
    ош = д.записать(вторая)
    т.проверить(ош is not None and "остат" in ош, "выплата 600 при остатке 500 — отказ (переплата)", ош)


if __name__ == "__main__":
    запустить("выплата_зарплаты", сценарий)
