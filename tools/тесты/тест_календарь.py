"""Календарь (Обработки.УЗ_Календарь): данные недели одним пакетным запросом и перенос урока без вопроса «Да/Нет».

Форма календаря строит планировщик из ДанныеКалендаря (один серверный вызов, один пакет: уроки с подписями и
цветами, ученики, помещения, график педагога, напоминания, дни навигатора) — прежде каждый урок, его группа,
предмет, педагог и ученики читались через точку в цикле. Тест сверяет содержимое с документами:
  * три урока недели (проведённый прошлый, записанный будущий, чужой педагог) — все в данных недели, подписи:
    предмет, «Фамилия И. О.» педагога, ученики (флажок «Ученики»), «✓» только у проведённого, цвет — по помещению;
  * отборы педагог, ученик, помещение — только свои уроки; дни навигатора — дни уроков, без отбора — оба дня;
  * ОписаниеПереноса: время и помещение словами; тот же интервал — Неопределено (перенос не предлагается);
  * ПеренестиУрок: прошлый проведённый урок перепроведён на новое время (движения на новой дате), будущий —
    записан планом; значения нового урока из отбора группы — педагог, предмет, тариф группы.
Мутация: в тексте запроса ВТ_Уроки убрать отбор по педагогу → красное «отбор педагог».

    python tools\\тесты\\тест_календарь.py --база=C:\\1c_bases\\UZ_UNF_B
"""
# затрагивает: УЗ_Календарь
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить, как_дата  # noqa: E402
from фабрика import Фабрика  # noqa: E402

МЕТКА = "УЗ тест календаря"


def момент(значение):
    """Дата-время 1С из COM до минуты (как_дата сеанса отрезает время)."""
    return (значение.year, значение.month, значение.day, значение.hour, значение.minute)


def сценарий(т):
    c = т.c
    ф = Фабрика(т, МЕТКА)
    обработка = c.Обработки.УЗ_Календарь
    предмет = ф.элемент("УЗ_ПредметыОбучения", "предмет")
    помещение = ф.элемент("УЗ_Помещения", "зал", Цвет="Бирюзовый")
    помещение2 = ф.элемент("УЗ_Помещения", "класс")
    педагог = ф.педагог("Педагогова Анна Сергеевна")
    педагог2 = ф.педагог("Другой Пётр")
    ученик = ф.ученик("Ученикова Мария")
    тариф = ф.элемент("УЗ_Тарифы", "тариф")
    ф.цена_тарифа(тариф, ф.день(-400), 1000, уроков=1)
    группа = ф.элемент("УЗ_ГруппыОбучения", "группа", Педагог=педагог, ПредметОбучения=предмет, Тариф=тариф)

    # неделя вокруг вчера и завтра: вчера — проведённый урок, завтра — план, вчера же — урок другого педагога
    прошлый = ф.урок(педагог, ф.день(-1, 10), 1, [dict(Ученик=ученик, Явка=True)], ПредметОбучения=предмет,
                     Помещение=помещение)
    ошибка, _ = ф.записать(прошлый, "Проведение")
    т.проверить(ошибка is None, "подготовка: прошлый урок проведён", ошибка)
    будущий = ф.урок(педагог, ф.день(1, 12), 1.5, [dict(Ученик=ученик)], ПредметОбучения=предмет, Помещение=помещение2)
    ошибка, _ = ф.записать(будущий, "Запись")
    т.проверить(ошибка is None, "подготовка: будущий урок записан", ошибка)
    чужой = ф.урок(педагог2, ф.день(-1, 15), 1, [], ПредметОбучения=предмет)
    ошибка, _ = ф.записать(чужой, "Запись")
    т.проверить(ошибка is None, "подготовка: урок другого педагога записан", ошибка)

    начало, конец = ф.день(-1), ф.день(1, 23, 59)

    def показ(**поля):
        с = c.NewObject("Структура")
        значения = dict(ГруппаОбучения=False, ПредметОбучения=True, Педагог=True, Ученики=True, Цвет="Помещение",
                        Помещения=True, ВсеПомещения=False, Напоминания=False)
        значения.update(поля)
        for к, в in значения.items():
            с.Вставить(к, в)
        return с

    def отборы(**поля):
        с = c.NewObject("Структура")
        for к, в in поля.items():
            с.Вставить(к, в)
        return с

    def уроки(данные):
        итог = {}
        for к in range(данные.Уроки.Количество()):
            у = данные.Уроки.Получить(к)
            итог[c.String(у.Ссылка.УникальныйИдентификатор())] = у
        return итог

    def ид(ссылка):
        return c.String(ссылка.УникальныйИдентификатор())

    данные = обработка.ДанныеКалендаря(начало, конец, отборы(), показ(), ф.день(0))
    все = уроки(данные)
    т.проверить(all(ид(д.Ссылка) in все for д in (прошлый, будущий, чужой)),
                "неделя без отбора: все три урока в данных календаря", "уроков в данных %d" % len(все))
    у = все.get(ид(прошлый.Ссылка))
    if т.проверить(у is not None, "проведённый урок есть в данных"):
        кратко = c.УЗ_ОбщийКлиентСервер.КраткоеФИО
        строки = у.Текст.splitlines()
        т.проверить(строки == ["✓ %s предмет" % МЕТКА, кратко(c.String(педагог)), кратко(c.String(ученик))],
                    "подпись проведённого: «✓ предмет», «Фамилия И. О.» педагога, ученик — по строкам", repr(у.Текст))
        т.проверить(у.Цвет == "Бирюзовый" and у.Проведен, "цвет урока — цвет помещения, признак «проведён»",
                    "%s %s" % (у.Цвет, у.Проведен))
        т.проверить(у.ТекстНедели.splitlines() == ["✓ %s" % у.Начало.strftime("%H:%M"), "%s предмет" % МЕТКА],
                    "подпись недели: «✓ время» и предмет, без педагога и учеников", repr(у.ТекстНедели))
        т.проверить((у.Конец - у.Начало).total_seconds() == 3600, "конец урока = начало + 1 ч", "%s — %s" % (у.Начало, у.Конец))
    у = все.get(ид(будущий.Ссылка))
    if т.проверить(у is not None, "записанный планом урок есть в данных"):
        т.проверить(not у.Текст.startswith("✓") and not у.Проведен, "план без «✓»", repr(у.Текст))

    без_учеников = уроки(обработка.ДанныеКалендаря(начало, конец, отборы(), показ(Ученики=False)))
    у = без_учеников.get(ид(прошлый.Ссылка))
    т.проверить(у is not None and len(у.Текст.splitlines()) == 2, "флажок «Ученики» снят — учеников в подписи нет",
                repr(у.Текст) if у else "")

    свои = уроки(обработка.ДанныеКалендаря(начало, конец, отборы(Педагог=педагог), показ()))
    т.проверить(ид(чужой.Ссылка) not in свои and ид(прошлый.Ссылка) in свои and ид(будущий.Ссылка) in свои,
                "отбор педагог: только его уроки", "уроков %d" % len(свои))
    по_ученику = уроки(обработка.ДанныеКалендаря(начало, конец, отборы(Ученик=ученик), показ()))
    т.проверить(set(по_ученику) == {ид(прошлый.Ссылка), ид(будущий.Ссылка)}, "отбор ученик: два его урока",
                "уроков %d" % len(по_ученику))
    по_помещению = уроки(обработка.ДанныеКалендаря(начало, конец, отборы(Помещение=помещение2), показ()))
    т.проверить(set(по_помещению) == {ид(будущий.Ссылка)}, "отбор помещение: один урок", "уроков %d" % len(по_помещению))

    дни = данные.ЗанятыеДаты
    дни = {как_дата(дни.Получить(к)) for к in range(дни.Количество())}
    т.проверить(как_дата(ф.день(-1)) in дни and как_дата(ф.день(1)) in дни, "дни навигатора: вчера и завтра — с уроками")
    помещения = [данные.Помещения.Получить(к).Текст for к in range(данные.Помещения.Количество())]
    т.проверить("%s зал" % МЕТКА in помещения and "%s класс" % МЕТКА in помещения,
                "измерение «Помещение»: помещения уроков периода", ", ".join(помещения))
    # A16-03: «все помещения» — справочник и строка для уроков без помещения (урок другого педагога)
    все_пом = обработка.ДанныеКалендаря(начало, конец, отборы(), показ(ВсеПомещения=True)).Помещения
    пустые = [к for к in range(все_пом.Количество()) if все_пом.Получить(к).Помещение.Пустая()]
    т.проверить(len(пустые) == 1, "«все помещения»: есть строка для уроков без помещения", "пустых %d" % len(пустые))

    # перенос: описание словами вместо вопроса «Да/Нет», тот же интервал — переносить нечего
    т.проверить(обработка.ОписаниеПереноса(прошлый.Ссылка, ф.день(-1, 10), ф.день(-1, 11), None, False) is None,
                "перенос на то же время и в то же помещение — не предлагается")
    перенос = обработка.ОписаниеПереноса(прошлый.Ссылка, ф.день(-1, 11), ф.день(-1, 12), помещение2, True)
    т.проверить(перенос is not None and "11:00" in перенос.Текст and "класс" in перенос.Текст,
                "описание переноса: новое время и помещение словами", перенос.Текст if перенос else "")
    итог = обработка.ПеренестиУрок(перенос)
    о = прошлый.Ссылка.ПолучитьОбъект()
    т.проверить(итог.Успех and о.Проведен and момент(о.Дата) == момент(ф.день(-1, 11)),
                "прошлый урок перенесён и перепроведён", итог.Текст)
    движение = т.выбрать("ВЫБРАТЬ МАКСИМУМ(Р.Период) КАК Период ИЗ РегистрНакопления.УЗ_СписанияСуммЗаУроки КАК Р "
                         "ГДЕ Р.Регистратор = &Д", Д=прошлый.Ссылка)
    т.проверить(момент(движение.Получить(0).Период) == момент(ф.день(-1, 11)), "движения урока — на новой дате")
    перенос = обработка.ОписаниеПереноса(будущий.Ссылка, ф.день(2, 12), ф.день(2, 13), None, False)
    итог = обработка.ПеренестиУрок(перенос)
    о = будущий.Ссылка.ПолучитьОбъект()
    т.проверить(итог.Успех and not о.Проведен and момент(о.Дата) == момент(ф.день(2, 12))
                and abs(float(о.КоличествоЧасов) - 1) < 0.001, "будущий урок перенесён, остался планом, 1 ч", итог.Текст)
    # A16-04: перенос проведённого урока в будущее — предупреждение до переноса
    перенос = обработка.ОписаниеПереноса(прошлый.Ссылка, ф.день(3, 15), ф.день(3, 16), None, False)
    т.проверить(перенос is not None and "будет отменено" in перенос.Текст,
                "перенос проведённого в будущее: описание предупреждает об отмене проведения", перенос.Текст if перенос else "")
    # A16-02: поверх урока того же педагога (будущий, послезавтра 12–13) — отказ, урок на месте
    перенос = обработка.ОписаниеПереноса(прошлый.Ссылка, ф.день(2, 12, 30), ф.день(2, 13, 30), None, False)
    итог = обработка.ПеренестиУрок(перенос)
    о = прошлый.Ссылка.ПолучитьОбъект()
    т.проверить(not итог.Успех and "занят" in итог.Текст and о.Проведен and момент(о.Дата) == момент(ф.день(-1, 11)),
                "перенос на время, где педагог занят, — отказ, урок не тронут", итог.Текст)

    значения = обработка.ЗначенияНовогоУрока(ф.день(3, 9), ф.день(3, 10), помещение, группа, None)
    т.проверить(c.String(значения.Педагог) == c.String(педагог) and c.String(значения.Тариф) == c.String(тариф)
                and c.String(значения.ПредметОбучения) == c.String(предмет) and float(значения.КоличествоЧасов) == 1,
                "новый урок из отбора группы: её педагог, предмет, тариф; 1 ч")

    # A1-07, A2-07: копия урока (кнопка «Скопировать» в календаре и журнале) — скидка строки та же, тема и ДЗ пустые
    скидка = ф.элемент("УЗ_Скидки", "скидка")
    со_скидкой = ф.урок(педагог, ф.день(4, 9), 1, [dict(Ученик=ученик, Скидка=скидка)], ПредметОбучения=предмет,
                        ТемаУрока="тема", ДомашнееЗадание="задание")
    ошибка, _ = ф.записать(со_скидкой, "Запись")
    т.проверить(ошибка is None, "подготовка: урок со скидкой записан", ошибка)
    копия = со_скидкой.Ссылка.ПолучитьОбъект().Скопировать()
    т.проверить(c.String(копия.Ученики.Получить(0).Скидка) == c.String(скидка) and копия.ТемаУрока == ""
                and копия.ДомашнееЗадание == "", "копия урока: скидка ученика та же, тема и домашнее задание пустые",
                (c.String(копия.Ученики.Получить(0).Скидка), копия.ТемаУрока, копия.ДомашнееЗадание))


if __name__ == "__main__":
    запустить("календарь", сценарий)
