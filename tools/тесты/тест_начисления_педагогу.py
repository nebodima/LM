"""Начисления педагогу в уроке (повторный аудит Codex 28.09.2026: B06, B07, C03 для уроков панели).

B06. Было: ручная доплата без комментария (премия 500 ₽) исчезала при каждой записи урока. С R24 (28.09.2026) урок
начисление не хранит: доплата — документ «Начисление педагогам» на основании урока, перепроведение урока её не
трогает; по ставке урок начисляет при проведении (Документы.УЗ_Урок.НачисленияПоСтавке).
B07. Было: урок, созданный программно (панель ученика, помощник, обработки), ставку педагога не получал — педагог
со ставкой 500 ₽ за занятие получал 0. Стало: общая функция Документы.УЗ_Урок.ЗаполнитьСтавкуПедагога — новый
урок без ставки берёт её из карточки педагога при записи; выбранную вручную ставку не трогает.
C03. Панель задаёт организацию новых уроков (параметр «Организация» ЗаписатьУченикаВГруппу).

    python tools\\тесты\\тест_начисления_педагогу.py --база=C:\\1c_bases\\UZ_UNF_A
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from фабрика import Фабрика  # noqa: E402
from тест_панель_ученика import группа_обучения, список  # noqa: E402

МЕТКА = "_Тест начисления педагогу"


def сценарий(т):
    c = т.c
    ф = Фабрика(т, МЕТКА)
    ставка = ф.элемент("УЗ_СтавкиПедагогов", "ставка 500 за занятие", ОплатаЗаЗанятие=500)
    педагог = ф.педагог("педагог со ставкой", СтавкаПедагога=ставка)
    ученик = ф.ученик()

    def начисления(урок):
        """Начисление по ставке записанного урока — как его запишет проведение."""
        м = c.Документы.УЗ_Урок.НачисленияПоСтавке(урок.Ссылка)
        return sorted((float(м.Получить(н).Сумма), str(м.Получить(н).Комментарий)) for н in range(м.Количество()))

    # ── B07: программный урок без ставки ──
    у = ф.урок(педагог, ф.день(-3, 10), 1, [dict(Ученик=ученик, Явка=True)])
    ош, _ = ф.записать(у, "Запись")
    о = у.Ссылка.ПолучитьОбъект()
    т.проверить(ош is None and c.String(о.СтавкаПедагога) == c.String(ставка),
                "B07: новый урок без ставки — ставка из карточки педагога", ош or c.String(о.СтавкаПедагога))
    т.проверить(начисления(у) == [(500.0, "Оплата за занятие")],
                "B07: начисление педагогу по ставке — 500 за занятие (было 0)", начисления(у))
    другая = ф.элемент("УЗ_СтавкиПедагогов", "ставка 300 за занятие", ОплатаЗаЗанятие=300)
    у2 = ф.урок(педагог, ф.день(-3, 12), 1, [dict(Ученик=ученик, Явка=True)], СтавкаПедагога=другая)
    ош, _ = ф.записать(у2, "Запись")
    т.проверить(ош is None and начисления(у2) == [(300.0, "Оплата за занятие")],
                "выбранная вручную ставка не заменяется ставкой карточки (300)", ош or начисления(у2))

    # ── B06: доплаты 200 и 100 документами на основании урока переживают перепроведение урока ──
    ош, _ = ф.записать(у.Ссылка.ПолучитьОбъект())
    доплаты = [ф.доплата(у, сумма, комментарий) for сумма, комментарий in ((200, "премия"), (100, "замена"))]
    ош2, _ = ф.записать(у.Ссылка.ПолучитьОбъект())
    итог = ф.начислено_педагогу(у) + sum(ф.начислено_педагогу(д) for д, _ in доплаты)
    т.проверить(ош is None and ош2 is None and all(о is None for _, (о, _) in доплаты) and ф.начислено_педагогу(у) == 500
                and итог == 800,
                "B06: урок проведён 500 по ставке + доплаты 200 и 100 — после перепроведения урока педагогу 800",
                ош or ош2 or [о for _, (о, _) in доплаты] or итог)

    # ── B07 + C03: урок из панели ученика — ставка педагога группы и организация панели ──
    орг = ф.организация("организация панели")
    тариф = ф.элемент("УЗ_Тарифы", "тариф")
    ф.цена_тарифа(тариф, ф.день(-400), 800, уроков=1)
    # урок панели — без явки (отмечена только оплата): по В6 «за занятие» не начисляется, поэтому ставка 30 % с оплаты
    процент = ф.элемент("УЗ_СтавкиПедагогов", "ставка 30% с оплаты", ПроцентСОплатыУченика=30)
    педагог_группы = ф.педагог("педагог группы", СтавкаПедагога=процент)
    группа = группа_обучения(т, ф, "группа", педагог_группы, тариф)

    def убрать_уроки():
        тз = т.выбрать("ВЫБРАТЬ У.Ссылка КАК Ссылка ИЗ Документ.УЗ_Урок КАК У ГДЕ У.ГруппаОбучения = &Г", Г=группа)
        for н in range(тз.Количество()):
            т.удалить_объект(тз.Получить(н).Ссылка, загрузка=True)
    т.убрать(убрать_уроки, "уроки группы панели")
    панель = c.Обработки.УЗ_ПанельУченика
    когда = панель.НачалоУрокаГруппы(группа, ф.день(-2))
    try:
        итог = список(панель.ЗаписатьУченикаВГруппу(ученик, группа, т.массив(когда), None, орг))
    except Exception as е:  # старая сигнатура без организации
        итог = [str(е)]
    урок = итог[0].Урок if итог and not isinstance(итог[0], str) else None
    т.проверить(урок is not None and итог[0].Успех, "панель: урок группы записан и проведён",
                итог[0] if итог and isinstance(итог[0], str) else [(с.Описание, с.ДопОписание) for с in итог])
    if урок is not None:
        о = урок.ПолучитьОбъект()
        т.проверить(c.String(о.СтавкаПедагога) == c.String(процент) and ф.начислено_педагогу(о) == 240,
                    "B07: урок из панели — ставка педагога группы (30 %% с оплаты 800), начислено 240 (было 0)",
                    "%s, %s" % (c.String(о.СтавкаПедагога), ф.начислено_педагогу(о)))
        т.проверить(c.String(о.Организация) == c.String(орг), "C03: урок из панели — в организации панели",
                    c.String(о.Организация))
        зп = ф.число("ВЫБРАТЬ СУММА(Р.Сумма) ИЗ РегистрНакопления.УЗ_РасчетыПоЗарплате КАК Р "
                     "ГДЕ Р.Регистратор = &У И Р.Организация = &О", У=урок, О=орг)
        т.проверить(зп == 240, "долг педагогу 240 — в организации панели", зп)


if __name__ == "__main__":
    запустить("начисления_педагогу", сценарий)
