МЕТКА = "УЗ тест Codex 3"
ЦЕНА = 500


def сценарий(т):
    c = т.c
    ф = Фабрика(т, МЕТКА)

    def равны(первая, вторая):
        return (первая is not None and вторая is not None
                and c.String(первая.УникальныйИдентификатор()) == c.String(вторая.УникальныйИдентификатор()))

    находка_4(т, ф, равны)
    находки_7_8(т, ф)
    находка_9(т, ф, равны)


def пользователь_программы(т, имя):
    """Элемент Справочник.Пользователи без пользователя ИБ (связь карточки педагога) — в режиме загрузки, мимо БСП."""
    c = т.c
    элемент = c.Справочники.Пользователи.СоздатьЭлемент()
    элемент.Наименование = "%s %s" % (МЕТКА, имя)
    элемент.ОбменДанными.Загрузка = True
    элемент.ДополнительныеСвойства.Вставить("ОтключитьМеханизмРегистрацииОбъектов", True)
    элемент.ОбменДанными.Получатели.АвтоЗаполнение = False
    элемент.Записать()
    ссылка = элемент.Ссылка
    т.убрать(lambda: т.удалить_объект(ссылка, загрузка=True), "пользователь программы")
    return ссылка


def находка_4(т, ф, равны):
    c = т.c
    сергей_пользователь = пользователь_программы(т, "Сергей")
    сергей = ф.педагог("Сергей", Пользователь=сергей_пользователь)

    копия = сергей.ПолучитьОбъект().Скопировать()
    копия.Наименование = "%s Андрей" % МЕТКА
    копия.ЭтоПедагог = True
    т.проверить(копия.Пользователь.Пустая(),
                "4: копия карточки педагога — без «Пользователь программы» (учётная запись у человека своя)",
                c.String(копия.Пользователь))
    c.ПолучитьСообщенияПользователю(True)
    try:
        копия.Записать()
        записана = True
    except Exception as е:
        записана = False
        т.проверить(False, "4: копия карточки педагога записывается", текст_ошибки(е))
    if записана:
        ссылка = копия.Ссылка
        т.убрать(lambda: т.удалить_объект(ссылка), "копия педагога")

    второй = c.Справочники.УЗ_ФизЛица.СоздатьЭлемент()
    второй.Наименование = "%s Андрей 2" % МЕТКА
    второй.ЭтоПедагог = True
    второй.Пользователь = сергей_пользователь
    c.ПолучитьСообщенияПользователю(True)
    try:
        второй.Записать()
        ошибка = None
    except Exception as е:
        ошибка = текст_ошибки(е)
    сообщения = " ".join(str(с.Текст) for с in c.ПолучитьСообщенияПользователю(True))
    if ошибка is None:
        ссылка_второго = второй.Ссылка
        т.убрать(lambda: т.удалить_объект(ссылка_второго), "второй педагог с тем же пользователем")
    т.проверить(ошибка is not None and "уже связан с педагогом" in сообщения,
                "4: второй действующий педагог с тем же пользователем программы — отказ с причиной", сообщения or "записан")

    # помеченный на удаление прежний педагог связь не держит; ученик (не педагог) — тоже
    о = сергей.ПолучитьОбъект()
    о.УстановитьПометкуУдаления(True)
    третий = ф.элемент("УЗ_ФизЛица", "Андрей 3", ЭтоПедагог=True, Пользователь=сергей_пользователь)
    т.проверить(not третий.Пустая(), "4: прежний педагог помечен на удаление — связь можно отдать новому")


def находки_7_8(т, ф):
    c = т.c
    менеджер = c.Документы.УЗ_Урок
    педагог = ф.педагог("педагог групп")
    тариф = ф.элемент("УЗ_Тарифы", "500 за урок", Сумма=ЦЕНА, КоличествоУроков=1)
    предмет = ф.элемент("УЗ_ПредметыОбучения", "предмет")
    группа_а = ф.элемент("УЗ_ГруппыОбучения", "группа А")
    группа_б = ф.элемент("УЗ_ГруппыОбучения", "группа Б")
    группа_г = ф.элемент("УЗ_ГруппыОбучения", "группа Г")
    без_помещения = c.Справочники.УЗ_Помещения.ПустаяСсылка()

    def ученик(имя, группа, с_дня, выбыл=False):
        ссылка = ф.ученик(имя)
        о = ссылка.ПолучитьОбъект()
        с = о.ГруппыОбучения.Добавить()
        с.ГруппаОбучения = группа
        с.ДатаНачала = ф.день(с_дня)
        о.Выбыл = выбыл
        о.Записать()
        return ссылка

    def убрать_уроки():
        тз = т.выбрать("ВЫБРАТЬ У.Ссылка КАК Ссылка ИЗ Документ.УЗ_Урок КАК У ГДЕ У.Педагог = &П", П=педагог)
        for н in range(тз.Количество()):
            т.удалить_объект(тз.Получить(н).Ссылка, загрузка=True)
    т.убрать(убрать_уроки, "уроки теста")

    def параметры(начало, группа):
        п = c.NewObject("Структура")
        п.Вставить("Дата", начало)
        п.Вставить("КоличествоЧасов", 1)
        п.Вставить("ПредметОбучения", предмет)
        п.Вставить("Педагог", педагог)
        п.Вставить("Помещение", без_помещения)
        п.Вставить("ГруппаОбучения", группа)
        return п

    def строка(уч):
        с = c.NewObject("Структура")
        с.Вставить("Ученик", уч)
        с.Вставить("Тариф", тариф)
        с.Вставить("СписатьОплату", True)
        с.Вставить("Явка", True)
        return с

    def журнал(итог):
        return [итог.Строки.Получить(н).Описание for н in range(итог.Строки.Количество())]

    def урок_группы(начало, *ученики):
        д = ф.урок(педагог, начало, 1, [dict(Ученик=у, Тариф=тариф, СписатьОплату=True, Явка=True) for у in ученики],
                   ГруппаОбучения=группа_а, ПредметОбучения=предмет)
        ошибка, сообщения = ф.записать(д, "Проведение")
        т.проверить(ошибка is None, "подготовка: урок группы А проведён", "%s %s" % (ошибка, сообщения))
        return д.Ссылка

    def в_уроке(ссылка, уч):
        return т.выбрать("ВЫБРАТЬ 1 КАК Найдено ИЗ Документ.УЗ_Урок.Ученики КАК С ГДЕ С.Ссылка = &У И С.Ученик = &Уч",
                         У=ссылка, Уч=уч).Количество() > 0

    def помечен(ссылка):
        return bool(т.выбрать("ВЫБРАТЬ У.ПометкаУдаления КАК П ИЗ Документ.УЗ_Урок КАК У ГДЕ У.Ссылка = &У",
                              У=ссылка).Получить(0).П)

    def уроков_группы(группа, начало):
        return т.выбрать("ВЫБРАТЬ У.Ссылка КАК Ссылка ИЗ Документ.УЗ_Урок КАК У ГДЕ У.ГруппаОбучения = &Г И У.Дата = &Д "
                         "И НЕ У.ПометкаУдаления", Г=группа, Д=начало)

    # ── 7: один выбывший — отказ, ничего не изменено ──
    активный = ученик("активный", группа_а, -30)
    выбывший = ученик("выбывший", группа_а, -30, выбыл=True)
    урок_х = урок_группы(ф.день(-1, 10), выбывший)
    итог = менеджер.ПеревестиУчениковВУрок(параметры(ф.день(-1, 17), группа_б), группа_а, т.массив(строка(выбывший)), True)
    строка_группы = т.выбрать("ВЫБРАТЬ Г.ДатаОкончания = ДАТАВРЕМЯ(1, 1, 1) КАК Открыта "
                              "ИЗ Справочник.УЗ_ФизЛица.ГруппыОбучения КАК Г "
                              "ГДЕ Г.Ссылка = &У И Г.ГруппаОбучения = &Г", У=выбывший, Г=группа_а)
    т.проверить(not итог.Успех and в_уроке(урок_х, выбывший) and not помечен(урок_х),
                "7: перевод одного выбывшего — отказ, он остался в старом уроке, урок не помечен на удаление",
                "успех %s, в уроке %s, помечен %s; %s" % (итог.Успех, в_уроке(урок_х, выбывший), помечен(урок_х),
                                                         журнал(итог)))
    т.проверить(строка_группы.Количество() == 1 and строка_группы.Получить(0).Открыта,
                "7: карточка выбывшего не изменена — группа А не закрыта")
    т.проверить(уроков_группы(группа_б, ф.день(-1, 17)).Количество() == 0, "7: урок группы Б не создан")

    # ── 7: смешанный список — активный переведён, выбывший остался ──
    урок_у = урок_группы(ф.день(-2, 10), активный, выбывший)
    итог = менеджер.ПеревестиУчениковВУрок(параметры(ф.день(-2, 17), группа_б), группа_а,
                                           т.массив(строка(активный), строка(выбывший)), True)
    новый = итог.Урок
    т.проверить(итог.Успех and новый is not None and в_уроке(новый, активный) and not в_уроке(новый, выбывший),
                "7: смешанный список — в уроке группы Б только активный", журнал(итог))
    т.проверить(not в_уроке(урок_у, активный) and в_уроке(урок_у, выбывший) and not помечен(урок_у),
                "7: из старого урока ушёл только активный, выбывший остался, урок не помечен на удаление")
    т.проверить(any("не переведён" in с and "выбыл" in с for с in журнал(итог)),
                "7: в журнале помощника — выбывший не переведён", журнал(итог))

    # ── 8: А в группе Г с -6, Б — с -3; уроки -6, -3, -1 ──
    ученик_а = ученик("Г ранний", группа_г, -6)
    ученик_б = ученик("Г поздний", группа_г, -3)
    даты = [ф.день(-6), ф.день(-3), ф.день(-1)]
    try:
        состав = менеджер.УченикиГруппыДляПомощника(группа_г, т.массив(*даты), тариф)
        кто = {c.String(состав.Получить(н).Ученик) for н in range(состав.Количество())}
    except Exception as е:
        состав, кто = None, {"ошибка: " + текст_ошибки(е, 150)}
    т.проверить(кто == {c.String(ученик_а), c.String(ученик_б)},
                "8: таблица помощника на даты -6, -3, -1 — оба ученика (вступивший позже первой даты тоже)", sorted(кто))
    уроки = {}
    if состав is not None:
        for д in даты:
            итог = менеджер.ЗаписатьУчениковВУрок(параметры(дата_урока(д), группа_г), состав, True)
            уроки[д] = итог.Урок
    с_поздним = [д for д, у in уроки.items() if у is not None and в_уроке(у, ученик_б)]
    с_ранним = [д for д, у in уроки.items() if у is not None and в_уроке(у, ученик_а)]
    т.проверить(len(с_ранним) == 3 and len(с_поздним) == 2 and даты[0] not in с_поздним,
                "8: ранний — во всех трёх уроках, поздний — в уроках -3 и -1, в уроке -6 (до вступления) его нет",
                "ранний %d, поздний %d" % (len(с_ранним), len(с_поздним)))


def дата_урока(день):
    """Начало урока 09:00 в тот же день."""
    return дата(день.year, день.month, день.day, 9)


def находка_9(т, ф, равны):
    c = т.c
    настройки_до = c.РегистрыСведений.УЗ_Настройки.Настройки()
    орг_а = ф.организация("организация А")
    орг_б = ф.организация("организация Б")
    имя_кассы = МЕТКА + " касса"

    def уборка():
        в = c.NewObject("Структура")
        в.Вставить("Организация", настройки_до.Организация)
        в.Вставить("Касса", настройки_до.Касса)
        c.РегистрыСведений.УЗ_Настройки.ЗаписатьНастройки(в)
        тз = т.выбрать("ВЫБРАТЬ К.Ссылка КАК Ссылка ИЗ Справочник.УЗ_Кассы КАК К ГДЕ К.Наименование = &И", И=имя_кассы)
        for н in range(тз.Количество()):
            т.удалить_объект(тз.Получить(н).Ссылка, загрузка=True)
    т.убрать(уборка, "кассы помощника и настройки учёта")

    def данные(**поля):
        с = c.NewObject("Структура")
        for к, в in поля.items():
            с.Вставить(к, в)
        return с

    первый = c.УЗ_Общий.ВыполнитьПервуюНастройку(данные(Организация=орг_а, Касса=имя_кассы))
    касса_а = первый.Касса
    т.проверить(касса_а is not None and равны(касса_а.Организация, орг_а), "9: касса «%s» организации А" % имя_кассы)
    второй = c.УЗ_Общий.ВыполнитьПервуюНастройку(данные(Организация=орг_б, Касса=имя_кассы))
    касса_б = второй.Касса
    настройки = c.РегистрыСведений.УЗ_Настройки.Настройки()
    т.проверить(касса_б is not None and not равны(касса_б, касса_а) and равны(касса_б.Организация, орг_б),
                "9: для организации Б создана своя касса с тем же именем (касса А не подходит)",
                [второй.Журнал.Получить(н) for н in range(второй.Журнал.Количество())])
    т.проверить(равны(настройки.Организация, орг_б) and равны(настройки.Касса.Организация, орг_б),
                "9: в настройках пара согласована — организация Б и её касса")

    # пара настроек: в настройках касса А, помощник меняет только организацию на Б — отказ, настройки прежние
    в = c.NewObject("Структура")
    в.Вставить("Организация", орг_а)
    в.Вставить("Касса", касса_а)
    c.РегистрыСведений.УЗ_Настройки.ЗаписатьНастройки(в)
    try:
        c.УЗ_Общий.ВыполнитьПервуюНастройку(данные(Организация=орг_б))
        ошибка = ""
    except Exception as е:
        ошибка = текст_ошибки(е)
    настройки = c.РегистрыСведений.УЗ_Настройки.Настройки()
    т.проверить("принадлежит организации" in ошибка and равны(настройки.Организация, орг_а)
                and равны(настройки.Касса, касса_а),
                "9: организация Б при кассе А в настройках — отказ с причиной, настройки не тронуты", ошибка or "прошло")


if __name__ == "__main__":
    запустить("codex_третий", сценарий)
