def попытка(действие):
    try:
        return действие()
    except Exception as е:
        return "ошибка: " + текст_ошибки(е, 160)


def ид(c, ссылка):
    return c.String(ссылка.УникальныйИдентификатор())


def исходник(*путь):
    with open(os.path.join(КОРЕНЬ, "src_ext", *путь), encoding="utf-8-sig") as ф:
        return ф.read()


def состав_группы(т, ф):
    c = т.c
    педагог = ф.педагог("педагог")
    предмет = ф.элемент("УЗ_ПредметыОбучения", "предмет")
    помещение = ф.элемент("УЗ_Помещения", "класс")
    тариф = ф.элемент("УЗ_Тарифы", "500 за урок", Сумма=500, КоличествоУроков=1)
    группа = ф.элемент("УЗ_ГруппыОбучения", "группа")
    Д1, Д2, Д3 = -5, -2, -1                  # дни уроков (сдвиг от сегодня): ушедший — в группе на Д1, не на Д2

    def ученик(имя, строки, выбыл=False):
        """строки — [(сдвиг зачисления или None — давно, последний день в группе или None)]: документы «Перевод
        ученика» (В29); выбыл — отметка «Выбыл» после зачисления."""
        ссылка = ф.ученик(имя)
        for нач, кон in строки:
            ф.в_группу(ссылка, группа, нач if нач is not None else -60, кон)
        if выбыл:
            о = ссылка.ПолучитьОбъект()
            о.Выбыл = True
            о.Записать()
        return ссылка

    действует = ученик("действует", [(-30, None)])
    выбыл = ученик("выбыл", [(None, None)], выбыл=True)
    ушёл = ученик("ушёл из группы", [(-30, Д1 + 1)])
    вручную = ученик("без строки группы", [])

    def убрать_уроки():
        тз = т.выбрать("ВЫБРАТЬ У.Ссылка КАК Ссылка ИЗ Документ.УЗ_Урок КАК У ГДЕ У.Педагог = &П", П=педагог)
        for н in range(тз.Количество()):
            т.удалить_объект(тз.Получить(н).Ссылка, загрузка=True)
    т.убрать(убрать_уроки, "уроки группы")

    # ── помощник: состав группы на первую дату уроков ──
    р = попытка(lambda: c.Документы.УЗ_Урок.УченикиГруппыДляПомощника(группа, ф.день(Д1), тариф))
    имена = sorted(c.String(р.Получить(н).Ученик) for н in range(р.Количество())) if not isinstance(р, str) else р
    т.проверить(имена == sorted([c.String(действует), c.String(ушёл)]),
                "помощник: ученики группы на дату урока — действующий и ещё не ушедший; выбывшего нет (В18)", имена)
    р = попытка(lambda: c.Документы.УЗ_Урок.УченикиГруппыДляПомощника(группа, ф.день(Д2), тариф))
    имена = sorted(c.String(р.Получить(н).Ученик) for н in range(р.Количество())) if not isinstance(р, str) else р
    т.проверить(имена == [c.String(действует)], "помощник: на дату после выбытия ушедшего из группы — только "
                "действующий", имена)

    # ── запись урока группы на каждую дату ──
    def строка(кто):
        с = c.NewObject("Структура")
        с.Вставить("Ученик", кто)
        с.Вставить("Тариф", тариф)
        с.Вставить("Явка", True)
        return с

    def параметры(сдвиг):
        п = c.NewObject("Структура")
        п.Вставить("Дата", ф.день(сдвиг, 10))
        п.Вставить("КоличествоЧасов", 1)
        п.Вставить("ПредметОбучения", предмет)
        п.Вставить("Педагог", педагог)
        п.Вставить("Помещение", помещение)
        п.Вставить("ГруппаОбучения", группа)
        return п

    def журнал(итог):
        return [итог.Строки.Получить(н).Описание for н in range(итог.Строки.Количество())]

    def в_уроке(итог):
        if итог.Урок is None:
            return []
        о = итог.Урок.ПолучитьОбъект()
        return sorted(c.String(о.Ученики.Получить(н).Ученик) for н in range(о.Ученики.Количество()))

    таблица = т.массив(*(строка(у) for у in (действует, выбыл, ушёл, вручную)))
    менеджер = c.Документы.УЗ_Урок
    итог = менеджер.ЗаписатьУчениковВУрок(параметры(Д1), таблица, False)
    т.проверить(в_уроке(итог) == sorted([c.String(действует), c.String(ушёл), c.String(вручную)]),
                "урок на Д1: действующий, ещё не ушедший и добавленный вручную; выбывший не записан (было: записан)",
                (в_уроке(итог), журнал(итог)))
    т.проверить(any("выбыл" in с for с in журнал(итог)), "урок на Д1: в журнале — выбывший пропущен и почему",
                журнал(итог))
    итог = менеджер.ЗаписатьУчениковВУрок(параметры(Д2), таблица, False)
    т.проверить(в_уроке(итог) == sorted([c.String(действует), c.String(вручную)]),
                "урок на Д2 (после выбытия ушедшего из группы): ушедший и выбывший не записаны (было: все четверо)",
                (в_уроке(итог), журнал(итог)))
    т.проверить(any("выбыл из группы" in с for с in журнал(итог)),
                "урок на Д2: причина ушедшего — выбыл из группы", журнал(итог))
    т.проверить(таблица.Количество() == 4, "таблица помощника не изменилась (одна на все даты)",
                таблица.Количество())
    итог = менеджер.ЗаписатьУчениковВУрок(параметры(Д3), т.массив(строка(выбыл)), False)
    т.проверить(итог.Урок is None and not итог.Создан,
                "урок на Д3 только с выбывшим — некого записывать, урок не создан (было: урок с выбывшим)",
                журнал(итог))


def фото_карточки(т):
    c = т.c
    с_фото = c.Справочники.УЗ_Фото.СоздатьЭлемент()
    с_фото.Наименование = "%s фото" % МЕТКА
    с_фото.Файл = c.NewObject("ХранилищеЗначения", двоичные(c, PNG))
    с_фото.Записать()
    фото = с_фото.Ссылка
    т.убрать(lambda: т.удалить_объект(фото), "фото")
    о = c.Справочники.УЗ_ФизЛица.СоздатьЭлемент()
    о.Наименование = "%s с фото" % МЕТКА
    о.Фото = фото
    о.Записать()
    ученик = о.Ссылка
    т.убрать(lambda: т.удалить_объект(ученик), "ученик с фото")

    def размер(ссылка):
        данные = ссылка.ПолучитьОбъект().Файл.Получить()
        return данные.Размер() if данные is not None else None

    # выбрали новое фото и не записали карточку — в базе фото прежнее
    о = ученик.ПолучитьОбъект()
    о.ДополнительныеСвойства.Вставить("УЗ_НовоеФото", двоичные(c, PNG + b"\0"))
    т.проверить(размер(фото) == len(PNG), "фото выбрано, карточка не записана — в базе прежнее фото")
    о.Записать()
    т.проверить(размер(фото) == len(PNG) + 1 and ид(c, ученик.ПолучитьОбъект().Фото) == ид(c, фото),
                "карточка записана — новое фото в том же элементе «Фото» (было: не применялось)", размер(фото))

    о = c.Справочники.УЗ_ФизЛица.СоздатьЭлемент()
    о.Наименование = "%s без фото" % МЕТКА
    о.ДополнительныеСвойства.Вставить("УЗ_НовоеФото", двоичные(c, PNG))
    о.Записать()
    новый = о.Ссылка
    новое_фото = новый.ПолучитьОбъект().Фото
    if not новое_фото.Пустая():
        т.убрать(lambda: т.удалить_объект(новое_фото), "новое фото")
    т.убрать(lambda: т.удалить_объект(новый), "ученик без фото")
    т.проверить(not новое_фото.Пустая() and размер(новое_фото) == len(PNG),
                "новая карточка с выбранным фото — фото создано при записи")

    # форма: выбор файла только показывает картинку, в базу — при записи (ПередЗаписьюНаСервере)
    модуль = исходник("Catalogs", "УЗ_ФизЛица", "Forms", "ФормаЭлемента", "Ext", "Form", "Module.bsl")
    выбор = re.search(r"Процедура ОбработатьВыборФайла\(.*?КонецПроцедуры", модуль, re.S)
    тело = выбор.group(0) if выбор else ""
    т.проверить(тело and "НаСервере(" not in тело and "ФотоВыбрано = Истина" in тело
                and "ЗаписатьНовуюКартинкуНаСервере" not in модуль,
                "форма: выбор файла не пишет фото в базу (было: ЗаписатьНовуюКартинкуНаСервере)")
    форма = исходник("Catalogs", "УЗ_ФизЛица", "Forms", "ФормаЭлемента", "Ext", "Form.xml")
    т.проверить('<Event name="BeforeWriteAtServer">ПередЗаписьюНаСервере</Event>' in форма
                and "УЗ_НовоеФото" in модуль, "форма: фото передаётся в запись карточки (ПередЗаписьюНаСервере)")


def касса_организации(т):
    c = т.c
    ф = Фабрика(т, МЕТКА)
    д = Данные(т, МЕТКА)
    кассы = c.Справочники.УЗ_Кассы
    орг_а, орг_б = ф.организация("организация А"), ф.организация("организация Б")

    # основные кассы базы на время теста снимаем (вернём как было)
    основные = т.выбрать("ВЫБРАТЬ К.Ссылка КАК Ссылка ИЗ Справочник.УЗ_Кассы КАК К ГДЕ К.Основная")

    def отметить(касса, значение):
        о = касса.ПолучитьОбъект()
        о.Основная = значение
        о.ОбменДанными.Загрузка = True
        о.Записать()
    for н in range(основные.Количество()):
        касса = основные.Получить(н).Ссылка
        отметить(касса, False)
        т.убрать(lambda к=касса: отметить(к, True), "вернуть «Основная»")

    касса_а = д.элемент("УЗ_Кассы", "основная А", Организация=орг_а)
    зал_б = д.элемент("УЗ_Кассы", "зал Б", Организация=орг_б)
    т.проверить(кассы.НазначитьОсновной(касса_а) == "", "касса А — основная организации А")
    нет = попытка(lambda: кассы.ПолучитьОсновнуюКассу(орг_б))
    т.проверить(not isinstance(нет, str) and нет.Пустая(),
                "у организации Б основной кассы нет — пустая ссылка, не касса организации А", нет)

    педагог = д.элемент("УЗ_ФизЛица", "педагог", ЭтоПедагог=True)
    вчера = datetime.date.today() - datetime.timedelta(days=1)
    д.движения("УЗ_Касса", д.регистратор(), [("+", дата(вчера.year, вчера.month, вчера.day, 10),
                                               {"Касса": зал_б, "Организация": орг_б, "Сумма": 3000})])
    р = д.документ("УЗ_РасчетЗарплаты", Дата=дата(вчера.year, вчера.month, вчера.day, 12), Педагог=педагог,
                   Касса=зал_б, Организация=орг_б, ДатаНачала=дата(2026, 8, 1), ДатаОкончания=дата(2026, 8, 31))
    сообщения(c)
    перемещение = р.ПереместитьОстатокВОсновнуюКассу()
    д.следить(перемещение)
    текст = сообщения(c)
    т.проверить(перемещение.Пустая() and "нет основной кассы" in текст and "Сделать основной" in текст,
                "Б без основной кассы — перемещения нет, сообщение: чего нет и что нажать (было: отказ «касса "
                "другой организации» без подсказки)", текст)

    основная_б = д.элемент("УЗ_Кассы", "основная Б", Организация=орг_б)
    т.проверить(кассы.НазначитьОсновной(основная_б) == "", "касса Б — основная организации Б")
    т.проверить(касса_а.ПолучитьОбъект().Основная and основная_б.ПолучитьОбъект().Основная,
                "у каждой организации своя основная: отметка у кассы А осталась (было: снималась)")
    а = попытка(lambda: ид(c, кассы.ПолучитьОсновнуюКассу(орг_а)))
    б = попытка(lambda: ид(c, кассы.ПолучитьОсновнуюКассу(орг_б)))
    т.проверить((а, б) == (ид(c, касса_а), ид(c, основная_б)), "основная касса — по организации: А и Б свои",
                (а, б))
    перемещение = р.ПереместитьОстатокВОсновнуюКассу()
    д.следить(перемещение)
    текст = сообщения(c)
    if перемещение.Пустая():
        т.проверить(False, "перемещение Б в основную кассу Б проведено", текст)
    else:
        о = перемещение.ПолучитьОбъект()
        т.проверить(о.Проведен and float(о.Сумма) == 3000 and ид(c, о.КассаПолучатель) == ид(c, основная_б),
                    "перемещение Б: 3 000 в основную кассу Б, проведено",
                    (о.Проведен, float(о.Сумма), c.String(о.КассаПолучатель), текст))


def сценарий(т):
    ф = Фабрика(т, МЕТКА)
    состав_группы(т, ф)
    фото_карточки(т)
    касса_организации(т)


if __name__ == "__main__":
    запустить("выбывшие_фото_касса", сценарий)
