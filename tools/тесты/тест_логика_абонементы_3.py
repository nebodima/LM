"""Логика абонементов, часть 3: подстановка абонемента везде, где создаётся строка ученика (docs/логики/абонементы.md
№10, №11, №17; группы_и_расписание.md №3, №4, №18; решения В20, В21, В22).

Группа занимается каждый день 10:00–11:30, общая «Продолжительность» — 1 ч; тариф группы 1 000 за урок; абонемент
«6 400 за 8» (800 за урок).

Сценарии (К — красный на старом коде, проверено прогоном до правки 28.09.2026):
  №10 панель ученика «Добавить в группу» — строка с абонементом, 800 (К: по тарифу 1 000, абонемент «8 из 8» навсегда)
  В20 панель: у ученика свой тариф 500 — строка по тарифу ученика, а не группы (К: тариф группы 1 000)
  В21 расписание дня группы — 10:00 и 1,5 ч, а не общая 1 ч (К: функции не было, форма урока и продление — 1 ч)
  №18 «Продление группы» — урок по расписанию дня (1,5 ч) с абонементом ученика, 800 (К: общее время 1 ч, без
      абонемента — по тарифу; функции менеджера не было, продление жило в форме)
  В22 перевод из группы (панель) — в карточке ученика старая группа закрыта днём перед переводом, новая открыта
      днём перевода (К: карточка не менялась)
  №17 копирование урока — у копии абонемент, действующий на дату копии (К: копия без абонемента — по тарифу)
  №11 абонемент без предмета в карточке не записывается (проверка заполнения): оплата ПКО на основании и уроки идут
      по одному предмету (К: пустой предмет допускался — оплата на пустой предмет, уроки — на предмет урока)

    python tools\\тесты\\тест_логика_абонементы_3.py --база=C:\\1c_bases\\UZ_UNF_B
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from фабрика import Фабрика  # noqa: E402
from _логика_абонементов import вызов, время, та_же  # noqa: E402

МЕТКА = "УЗ тест логики абонементов 3"


def сценарий(т):
    c = т.c
    ф = Фабрика(т, МЕТКА)
    панель = c.Обработки.УЗ_ПанельУченика
    менеджер = c.Документы.УЗ_Урок
    предмет = ф.элемент("УЗ_ПредметыОбучения", "математика")
    педагог = ф.педагог("педагог 1")
    педагог2 = ф.педагог("педагог 2")
    тариф = ф.элемент("УЗ_Тарифы", "1000 за урок", Сумма=1000, КоличествоУроков=1)
    свой_тариф = ф.элемент("УЗ_Тарифы", "500 за урок", Сумма=500, КоличествоУроков=1)
    группа = группа_обучения(т, ф, "группа", педагог, тариф, предмет)
    группа2 = группа_обучения(т, ф, "группа 2", педагог2, тариф, предмет)

    def убрать_уроки():
        тз = т.выбрать("""ВЫБРАТЬ У.Ссылка КАК Ссылка ИЗ Документ.УЗ_Урок КАК У
            ГДЕ У.Педагог В (&П) ИЛИ У.ГруппаОбучения В (&Г)""", П=т.массив(педагог, педагог2), Г=т.массив(группа, группа2))
        for н in range(тз.Количество()):
            т.удалить_объект(тз.Получить(н).Ссылка, загрузка=True)
    т.убрать(убрать_уроки, "уроки групп")

    def строка_ученика(ученик, гр, день):
        тз = т.выбрать("""ВЫБРАТЬ С.Ссылка КАК Урок, С.Абонемент КАК Абонемент, С.Тариф КАК Тариф, С.Сумма КАК Сумма,
                С.Ссылка.КоличествоЧасов КАК Часов, С.Ссылка.Проведен КАК Проведен
            ИЗ Документ.УЗ_Урок.Ученики КАК С
            ГДЕ С.Ученик = &У И С.Ссылка.ГруппаОбучения = &Г И С.Ссылка.Дата МЕЖДУ &Н И &К И НЕ С.Ссылка.ПометкаУдаления""",
                       У=ученик, Г=гр, Н=ф.день(день), К=ф.день(день, 23, 59))
        return тз.Получить(0) if тз.Количество() else None

    ученик = ф.ученик("Абонементов")
    а = ф.абонемент(ученик, "6400 за 8", КоличествоЗанятий=8, ЦенаАбонемента=6400, ПредметОбучения=предмет)
    индивид = ф.элемент("УЗ_ФизЛица", "Своетарифов", Тариф=свой_тариф)

    # ── В21: расписание дня группы ──
    расписание, ошибка = вызов(lambda: менеджер.РасписаниеГруппыНаДень(группа, ф.день(-2)))
    т.проверить(ошибка is None and расписание is not None and расписание.Начало.hour == 10
                and round(float(расписание.КоличествоЧасов), 4) == 1.5,
                "В21: урок группы в день — 10:00 и 1,5 ч по расписанию дня (общая длительность 1 ч не берётся)", ошибка)

    # ── №10 и В20: панель ученика ──
    дата = панель.НачалоУрокаГруппы(группа, ф.день(-2))
    итог = панель.ЗаписатьУченикаВГруппу(ученик, группа, т.массив(дата))
    итог = панель.ЗаписатьУченикаВГруппу(индивид, группа, т.массив(дата))
    с = строка_ученика(ученик, группа, -2)
    т.проверить(с is not None and та_же(c, с.Абонемент, а) and float(с.Сумма) == 800,
                "№10 (Р-2): панель — строка с абонементом, 800 (не тариф группы 1 000)",
                None if с is None else (c.String(с.Абонемент), с.Сумма))
    т.проверить(с is not None and round(float(с.Часов), 4) == 1.5, "В21: урок панели — 1,5 ч по расписанию дня",
                None if с is None else с.Часов)
    с = строка_ученика(индивид, группа, -2)
    т.проверить(с is not None and та_же(c, с.Тариф, свой_тариф) and float(с.Сумма) == 500,
                "В20: панель — тариф ученика (500) главнее тарифа группы (1 000)",
                None if с is None else (c.String(с.Тариф), с.Сумма))

    # ── №18: продление группы (ученики последнего урока) ──
    строки, ошибка = вызов(lambda: менеджер.ПродлитьГруппу(группа, т.массив(ф.день(-1))))
    т.проверить(ошибка is None, "№18: продление группы — функция менеджера урока", ошибка)
    с = строка_ученика(ученик, группа, -1)
    т.проверить(с is not None and та_же(c, с.Абонемент, а) and float(с.Сумма) == 800 and round(float(с.Часов), 4) == 1.5
                and с.Проведен,
                "№18: продлённый урок — по расписанию дня (1,5 ч), с абонементом ученика, 800, проведён",
                None if с is None else (c.String(с.Абонемент), с.Сумма, с.Часов, с.Проведен))
    с = строка_ученика(индивид, группа, -1)
    т.проверить(с is not None and та_же(c, с.Тариф, свой_тариф), "№18/В20: в продлённом уроке у ученика — его тариф",
                None if с is None else c.String(с.Тариф))

    # ── В22: перевод из группы — карточка ученика ──
    о = ученик.ПолучитьОбъект()
    стр = о.ГруппыОбучения.Добавить()
    стр.ГруппаОбучения = группа
    стр.ДатаНачала = ф.день(-30)
    о.Записать()
    перевод = панель.ПеревестиУченика(ученик, группа, группа2, т.массив(панель.НачалоУрокаГруппы(группа, ф.день(-1))))
    успех = all(перевод.Получить(н).Успех or перевод.Получить(н).УжеЕсть for н in range(перевод.Количество()))
    т.проверить(успех, "В22: перевод из группы в группу 2 выполнен",
                [перевод.Получить(н).Описание for н in range(перевод.Количество())])
    группы = {}
    карточка = ученик.ПолучитьОбъект()
    for н in range(карточка.ГруппыОбучения.Количество()):
        г = карточка.ГруппыОбучения.Получить(н)
        группы[c.String(г.ГруппаОбучения)] = (г.ДатаНачала.date() if г.ДатаНачала.year >= 1900 else None,
                                             г.ДатаОкончания.date() if г.ДатаОкончания.year >= 1900 else None)
    старая = группы.get(c.String(группа))
    новая = группы.get(c.String(группа2))
    т.проверить(старая is not None and старая[1] == ф.день(-2).date(),
                "В22: в карточке старая группа закрыта днём перед переводом", группы)
    т.проверить(новая is not None and новая[0] == ф.день(-1).date() and новая[1] is None,
                "В22: в карточке новая группа открыта днём перевода", группы)
    с = строка_ученика(ученик, группа2, -1)
    т.проверить(с is not None and та_же(c, с.Абонемент, а), "В22: в уроке новой группы — абонемент ученика",
                None if с is None else c.String(с.Абонемент))

    # ── №17: копирование урока ──
    урок = ф.урок(педагог, ф.день(-3, 15), 1, [dict(Ученик=ученик, Абонемент=а, СписатьОплату=True, Тариф=тариф)],
                  ПредметОбучения=предмет)
    ф.записать(урок, "Запись")
    копия = урок.Ссылка.Скопировать()
    т.проверить(копия.Ученики.Количество() == 1 and та_же(c, копия.Ученики.Получить(0).Абонемент, а),
                "№17: копия урока — с абонементом, действующим на дату копии",
                c.String(копия.Ученики.Получить(0).Абонемент) if копия.Ученики.Количество() else "нет строк")

    # ── №11: предмет абонемента обязателен (оплата и уроки — по одному предмету) ──
    без_предмета = c.Справочники.УЗ_Абонемент.СоздатьЭлемент()
    без_предмета.ФизЛицо = ученик
    без_предмета.Наименование = МЕТКА + " без предмета"
    c.ПолучитьСообщенияПользователю(True)
    заполнен = без_предмета.ПроверитьЗаполнение()
    сообщения = [str(с.Текст) for с in c.ПолучитьСообщенияПользователю(True)]
    т.проверить(not заполнен and any("Предмет" in с for с in сообщения),
                "№11: абонемент без предмета не проходит проверку заполнения", сообщения)


def группа_обучения(т, ф, имя, педагог, тариф, предмет):
    """Группа каждый день 10:00–11:30, общая продолжительность 1 ч."""
    c = т.c
    о = c.Справочники.УЗ_ГруппыОбучения.СоздатьЭлемент()
    о.Наименование = "%s %s" % (ф.метка, имя)
    о.Педагог = педагог
    о.Тариф = тариф
    о.ПредметОбучения = предмет
    о.Время = время(c, 10)
    о.Продолжительность = время(c, 1)
    for день in ("ПН", "ВТ", "СР", "ЧТ", "ПТ", "СБ", "ВС"):
        setattr(о, день, True)
        setattr(о, день + "Время", время(c, 10))
        setattr(о, день + "Время2", время(c, 11, 30))
    о.Записать()
    ссылка = о.Ссылка
    т.убрать(lambda: т.удалить_объект(ссылка), "группа %s" % имя)
    return ссылка


if __name__ == "__main__":
    запустить("логика_абонементы_3", сценарий)
