"""Урок: пересечения по педагогу и помещению запрещают проведение (аудит 28.09: Codex Q06, ревьюер-1 №2–3).

Было: пересечение искали только по попаданию начала или конца существующего урока внутрь нового — урок
10:30–11:00 внутри 10:00–12:00 не находился; найденное пересечение лишь сообщалось, урок проводился.
Стало: полная проверка интервалов (начало раньше чужого конца И конец позже чужого начала), отказ
проведения с сообщением у поля «Педагог» / «Помещение»; помещение с флагом «Не контролировать
пересечения» и пустое помещение не проверяются; стык (12:00 после урока до 12:00) — не пересечение.

    python tools\\тесты\\тест_урок_пересечения.py --база=C:\\1c_bases\\UZ_UNF_B
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from фабрика import Фабрика  # noqa: E402

МЕТКА = "УЗ тест пересечений"


def сценарий(т):
    ф = Фабрика(т, МЕТКА)
    ученик = ф.ученик()
    п1 = ф.педагог("педагог 1")
    п2 = ф.педагог("педагог 2")
    п3 = ф.педагог("педагог 3")
    класс = ф.элемент("УЗ_Помещения", "класс")
    зал = ф.элемент("УЗ_Помещения", "зал без контроля", НеКонтролироватьПересечения=True)
    строки = [dict(Ученик=ученик, Явка=True)]

    def провести(педагог, час, минута, часов, помещение=None):
        реквизиты = {"Помещение": помещение} if помещение is not None else {}
        д = ф.урок(педагог, ф.день(-1, час, минута), часов, строки, **реквизиты)
        return ф.записать(д, "Проведение")

    def отказ(итог, что, поле):
        ошибка, сообщения = итог
        о_пересечении = [(текст, п) for текст, п in сообщения if "пересекается" in текст]
        т.проверить(ошибка is not None, что + " — отказ проведения", "урок провёлся")
        т.проверить(any(поле in п for _, п in о_пересечении),
                    что + " — сообщение о пересечении у поля «%s»" % поле, сообщения)

    def проведён(итог, что):
        ошибка, сообщения = итог
        т.проверить(ошибка is None, что, "%s %s" % (ошибка, сообщения))

    # ── педагог ──
    проведён(провести(п1, 10, 0, 2), "педагог 1: урок 10:00–12:00 проводится")
    отказ(провести(п1, 10, 30, 0.5), "педагог 1: урок 10:30–11:00 внутри 10:00–12:00", "Педагог")
    отказ(провести(п1, 9, 0, 1.5), "педагог 1: урок 09:00–10:30 заходит на 10:00–12:00", "Педагог")
    отказ(провести(п1, 9, 0, 4), "педагог 1: урок 09:00–13:00 накрывает 10:00–12:00", "Педагог")
    проведён(провести(п1, 12, 0, 1), "педагог 1: урок 12:00–13:00 встык после 12:00 — проводится")
    проведён(провести(п2, 10, 30, 0.5), "педагог 2 в то же время, помещения нет — проводится")

    # ── помещение ──
    проведён(провести(п2, 14, 0, 1, класс), "класс: педагог 2, 14:00–15:00 проводится")
    отказ(провести(п3, 14, 15, 0.5, класс), "класс: педагог 3, 14:15–14:45 в занятом классе", "Помещение")
    проведён(провести(п2, 16, 0, 1, зал), "зал без контроля: педагог 2, 16:00–17:00 проводится")
    проведён(провести(п3, 16, 0, 1, зал), "зал без контроля: педагог 3 в то же время — проводится")

    # ── записанный (не проведённый) урок не занимает время ──
    д = ф.урок(п3, ф.день(-1, 18, 0), 1, строки)
    ф.записать(д, "Запись")
    проведён(провести(п3, 18, 0, 1), "педагог 3: непроведённый урок 18:00 не мешает провести другой")


if __name__ == "__main__":
    запустить("урок_пересечения", сценарий)
