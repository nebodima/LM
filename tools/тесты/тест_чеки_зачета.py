"""Чеки зачёта предоплаты (2.2.0.4, В63, В64): очередь при проведении урока, данные чека, отметка, запрет отмены.

Урок математики вчера, тариф 1 000 за урок, организация с «Пробивать чеки зачёта предоплаты»:
  Аня  — аванс 1 000 по математике до урока            → зачёт 1 000;
  Боря — денег нет (урок в долг)                         → чека зачёта нет;
  Гоша — аванс 300 без предмета                          → зачёт 300 (свободный аванс гасит любой предмет);
  Вера — абонемент 3 200 / 4 (оплачен до урока), 800     → зачёт 800.
Чек зачёта — «Приход», позиция «Занятие ДД.ММ.ГГГГ: математика» «полный расчёт» (ПередачаСПолнойОплатой), «Услуга»,
оплата «Предоплата» (зачёт аванса); пакет драйвера кодом хозяина: PaymentMethod 4, оплата предоплатой. Отметка
пробитого (Аня) — повторно не пробивается, урок не распроводится и не помечается на удаление, перепроводится
только без изменения зачёта Ани (В64). Флажок организации выключен — очереди нет.

    python tools\\тесты\\тест_чеки_зачета.py --база=C:\\1c_bases\\UZ_BP_S --пользователь=1
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from фабрика import Фабрика  # noqa: E402
from _деньги import Данные  # noqa: E402
from тест_чеки import пакет_драйвера, позиции, структура  # noqa: E402

МЕТКА = "_Тест чеки зачёта"


def сценарий(т):
    c = т.c
    ф = Фабрика(т, МЕТКА)
    д = Данные(т, МЕТКА)

    def имя(значение):
        return str(c.XMLString(значение))

    орг = ф.организация("студия")
    з = c.РегистрыСведений.УЗ_РеквизитыОрганизаций.СоздатьМенеджерЗаписи()
    з.Организация = орг
    з.СистемаНалогообложения = "УСНДоход"
    з.ПробиватьЧекиЗачета = True
    з.Записать()

    def убрать_реквизиты():
        н = c.РегистрыСведений.УЗ_РеквизитыОрганизаций.СоздатьМенеджерЗаписи()
        н.Организация = орг
        н.Прочитать()
        if н.Выбран():
            н.Удалить()
    т.убрать(убрать_реквизиты, "реквизиты организации")

    математика = ф.элемент("УЗ_ПредметыОбучения", "математика")
    педагог = ф.педагог()
    тариф = ф.элемент("УЗ_Тарифы", "8 000 за 8", Сумма=8000, КоличествоУроков=8)
    аня = ф.элемент("УЗ_ФизЛица", "Аня", Телефон="8 (912) 111-22-33")
    боря = ф.ученик("Боря")
    гоша = ф.ученик("Гоша")
    вера = ф.ученик("Вера")
    абонемент = ф.абонемент(вера, "3200 за 4", Организация=орг, ПредметОбучения=математика, КоличествоЗанятий=4,
                            ЦенаАбонемента=3200)
    пустой_предмет = c.Справочники.УЗ_ПредметыОбучения.ПустаяСсылка()
    # деньги учеников до урока (как от приходов денег): аванс Ани по математике, Гоши без предмета, абонемент Веры
    д.движения("УЗ_СписанияСуммЗаУроки", д.регистратор(), [
        ("+", ф.день(-2, 10), {"Клиент": аня, "ПредметОбучения": математика, "Сумма": 1000, "Организация": орг}),
        ("+", ф.день(-2, 10), {"Клиент": гоша, "ПредметОбучения": пустой_предмет, "Сумма": 300, "Организация": орг}),
        ("+", ф.день(-2, 10), {"Клиент": вера, "ПредметОбучения": математика, "Сумма": 3200, "Организация": орг,
                               "Абонемент": абонемент})])

    строки = [dict(Ученик=аня, Явка=True, СписатьОплату=True, Тариф=тариф),
              dict(Ученик=боря, Явка=True, СписатьОплату=True, Тариф=тариф),
              dict(Ученик=гоша, Явка=False, СписатьОплату=True, Тариф=тариф),
              dict(Ученик=вера, Явка=True, СписатьОплату=True, Тариф=тариф, Абонемент=абонемент)]
    урок = ф.урок(педагог, ф.день(-1, 10), 1, строки, ПредметОбучения=математика, Организация=орг)
    ош, сообщ = ф.записать(урок)
    т.проверить(ош is None, "урок на четверых проведён", "%s %s" % (ош, сообщ))
    if ош is not None:
        return
    ссылка = урок.Ссылка

    def очередь_урока():
        тз = т.выбрать("""ВЫБРАТЬ О.Ученик.Наименование КАК Ученик, О.Сумма КАК Сумма
            ИЗ РегистрСведений.УЗ_ЧекиЗачетаПредоплаты КАК О ГДЕ О.Регистратор = &Урок
            УПОРЯДОЧИТЬ ПО О.Ученик.Наименование""", Урок=ссылка)
        return [(str(тз.Получить(н).Ученик).replace(МЕТКА + " ", ""), float(тз.Получить(н).Сумма))
                for н in range(тз.Количество())]

    ждём = [("Аня", 1000.0), ("Вера", 800.0), ("Гоша", 300.0)]
    т.проверить(очередь_урока() == ждём,
                "очередь зачёта: аванс по предмету, абонемент, аванс без предмета; урок в долг — без чека",
                очередь_урока())
    непробитые = c.УЗ_Чеки.ОчередьЧековЗачета(ф.день(-1), ф.день(-1, 23, 59), орг)
    т.проверить(непробитые.Количество() == 3 and float(непробитые.Итог("Сумма")) == 2100,
                "обработка видит 3 непробитых чека зачёта на 2 100 за вчера", непробитые.Количество())

    # ── данные чека зачёта Ани ──
    данные = c.УЗ_Чеки.ДанныеЧека(ссылка, "Наличные", аня)
    т.проверить(str(данные.Причина) == "" and str(данные.ТипРасчета) == "ЗачетПредоплаты"
                and str(данные.ВидОплаты) == "Предоплата" and float(данные.Сумма) == 1000,
                "чек зачёта Ани: 1 000, оплата — предоплата (вид оплаты из формы не важен)",
                "%s %s %s %s" % (данные.Причина, данные.ТипРасчета, данные.ВидОплаты, данные.Сумма))
    вчера = ф.день(-1)
    позиция = "Занятие %02d.%02d.%04d: %s" % (вчера.day, вчера.month, вчера.year, c.String(математика).strip())
    т.проверить(позиции(данные) == [(позиция, 1000.0, "ПередачаСПолнойОплатой", "Услуга")],
                "позиция: занятие с датой и предметом, «полный расчёт», «Услуга»", позиции(данные))
    т.проверить(str(данные.ПокупательНомер) == "+79121112233", "покупатель — ученик (его телефон)",
                данные.ПокупательНомер)
    п = c.УЗ_СредаКасса.ПараметрыЧекаХозяина(данные)
    оплата = п.ТаблицаОплат.Получить(0)
    т.проверить(имя(п.ТипРасчета) == "ПриходДенежныхСредств" and имя(оплата.ТипОплаты) == "Предоплата"
                and float(оплата.Сумма) == 1000
                and имя(п.ПозицииЧека.Получить(0).ПризнакСпособаРасчета) == "ПередачаСПолнойОплатой",
                "касса хозяина: приход, оплата «Предоплата» 1 000, признак «полный расчёт»",
                "%s %s" % (имя(п.ТипРасчета), имя(оплата.ТипОплаты)))
    xml = пакет_драйвера(c, п)
    т.проверить('OperationType="1"' in xml and 'PaymentMethod="4"' in xml and 'PrePayment="1000"' in xml
                and 'Cash="0"' in xml, "пакет драйвера: приход, полный расчёт (4), зачёт предоплаты 1 000", xml[:600])
    т.проверить("нет зачёта предоплаты" in str(c.УЗ_Чеки.ДанныеЧека(ссылка, "Наличные", боря).Причина),
                "урок Бори в долг — чека зачёта нет")

    # ── отметка пробитого чека Ани: повторно не пробивается ──
    def убрать_чек():
        н = c.РегистрыСведений.УЗ_ЧекиККТ.СоздатьМенеджерЗаписи()
        н.Документ = ссылка
        н.Ученик = аня
        н.Прочитать()
        if н.Выбран():
            н.Удалить()
    т.убрать(убрать_чек, "отметка чека зачёта")
    ответ = структура(c, НомерЧека=21, НомерСмены=4, ФискальныйПризнак="555", ДатаЧека=ф.день(0, 9),
                      Устройство="Эмулятор", Сумма=1000, ТипРасчета="ЗачетПредоплаты", Электронно=False)
    т.проверить(str(c.УЗ_Чеки.ОтметитьЧек(ссылка, ответ, аня)) == "", "ответ кассы по чеку зачёта отмечен")
    сведения = str(c.УЗ_Чеки.СведенияОЧеке(ссылка, аня))
    т.проверить("Зачёт предоплаты" in сведения and "№ 21" in сведения, "в регистре чеков — «Зачёт предоплаты» № 21",
                сведения)
    т.проверить(str(c.УЗ_Чеки.СведенияОЧеке(ссылка, вера)) == "", "чек Веры не пробит (отметка — по ученику)")
    т.проверить("уже пробит" in str(c.УЗ_Чеки.ДанныеЧека(ссылка, "Наличные", аня).Причина),
                "пробитый чек зачёта повторно не пробивается")
    т.проверить("уже отмечен" in str(c.УЗ_Чеки.ОтметитьЧек(ссылка, ответ, аня)),
                "второй ответ кассы не перезаписывает отметку")
    непробитые = c.УЗ_Чеки.ОчередьЧековЗачета(ф.день(-1), ф.день(-1, 23, 59), орг)
    т.проверить(непробитые.Количество() == 2, "в очереди остались Вера и Гоша", непробитые.Количество())

    # ── В64: урок с пробитым чеком зачёта ──
    о = ссылка.ПолучитьОбъект()
    ош, сообщ = ф.записать(о, "ОтменаПроведения")
    т.проверить(ош is not None and any("чеки зачёта" in текст for текст, _ in сообщ),
                "отмена проведения урока с пробитым чеком зачёта — отказ", "%s %s" % (ош, сообщ))
    о = ссылка.ПолучитьОбъект()
    c.ПолучитьСообщенияПользователю(True)
    try:
        о.УстановитьПометкуУдаления(True)
        пометка = None
    except Exception as е:  # noqa: BLE001
        пометка = str(е)
    т.проверить(пометка is not None and not ссылка.ПометкаУдаления, "пометка на удаление — отказ", пометка)
    о = ссылка.ПолучитьОбъект()
    ош, сообщ = ф.записать(о)
    т.проверить(ош is None, "перепроведение без изменений — можно", "%s %s" % (ош, сообщ))
    о = ссылка.ПолучитьОбъект()
    о.Ученики.Получить(0).СписатьОплату = False
    ош, сообщ = ф.записать(о)
    т.проверить(ош is not None and any("уже пробит чек зачёта" in текст for текст, _ in сообщ),
                "перепроведение, меняющее зачёт Ани, — отказ", "%s %s" % (ош, сообщ))
    о = ссылка.ПолучитьОбъект()
    о.Ученики.Удалить(1)
    ош, сообщ = ф.записать(о)
    т.проверить(ош is None and ("Аня", 1000.0) in очередь_урока(),
                "перепроведение без Бори (зачёт Ани прежний) — можно", "%s %s" % (ош, сообщ))

    # ── флажок организации выключен — очереди нет (кроме пробитого) ──
    з.ПробиватьЧекиЗачета = False
    з.Записать()
    о = ссылка.ПолучитьОбъект()
    ош, сообщ = ф.записать(о)
    т.проверить(ош is None and очередь_урока() == [("Аня", 1000.0)],
                "флажок снят — перепроведение ставит в очередь только уже пробитый чек", очередь_урока())
    т.проверить(not c.УЗ_Чеки.ЧекиЗачетаВключены(орг), "организация без чеков зачёта")

    # ── права ──
    рег = c.Метаданные.РегистрыСведений.УЗ_ЧекиЗачетаПредоплаты
    роли = c.Метаданные.Роли
    обр = c.Метаданные.Обработки.УЗ_ЧекиЗачета
    т.проверить(c.ПравоДоступа("Просмотр", рег, роли.УЗ_ОсновнаяРоль)
                and not c.ПравоДоступа("Изменение", рег, роли.УЗ_ОсновнаяРоль)
                and c.ПравоДоступа("Использование", обр, роли.УЗ_ОсновнаяРоль)
                and c.ПравоДоступа("Использование", обр, роли.УЗ_Руководитель)
                and not c.ПравоДоступа("Просмотр", рег, роли.УЗ_Педагог),
                "очередь видят менеджер и руководитель (только чтение), педагог — нет")


if __name__ == "__main__":
    запустить("чеки_зачета", сценарий)
