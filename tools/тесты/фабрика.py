"""Общие заготовки денежных COM-тестов УЗ_ext: справочники, уроки, ПКО, проведение с сообщениями, уборка.

Каждый созданный объект сам встаёт в уборку теста (т.убрать): документы — отмена проведения и удаление
(движения уходят вместе с проведением), справочники — удаление. Уборка идёт в обратном порядке создания.
"""
import datetime

from сеанс import дата, текст_ошибки


class Фабрика:
    def __init__(self, т, метка):
        self.т = т
        self.c = т.c
        self.метка = метка
        сег = datetime.date.today()
        self.сегодня = сег

    # ── даты ──
    def день(self, сдвиг_дней=0, час=0, минута=0):
        д = self.сегодня + datetime.timedelta(days=сдвиг_дней)
        return дата(д.year, д.month, д.day, час, минута)

    # ── справочники ──
    def элемент(self, вид, наименование, **реквизиты):
        о = getattr(self.c.Справочники, вид).СоздатьЭлемент()
        о.Наименование = "%s %s" % (self.метка, наименование)
        for к, в in реквизиты.items():
            setattr(о, к, в)
        о.Записать()
        ссылка = о.Ссылка
        self.т.убрать(lambda: self.т.удалить_объект(ссылка), "%s %s" % (вид, наименование))
        return ссылка

    def организация(self, имя):
        """Своя тестовая организация (две организации — В12, N02, C02): в копиях баз их может не быть или одна.
        Запись в режиме загрузки — мимо обязательных реквизитов типовой; убирается за тестом (после документов)."""
        о = self.c.Справочники.Организации.СоздатьЭлемент()
        о.Наименование = "%s %s" % (self.метка, имя)
        о.ОбменДанными.Загрузка = True
        о.Записать()
        ссылка = о.Ссылка
        self.т.убрать(lambda: self.т.удалить_объект(ссылка, загрузка=True), "организация %s" % имя)
        return ссылка

    def ученик(self, имя="ученик"):
        return self.элемент("УЗ_ФизЛица", имя)

    def педагог(self, имя="педагог", **реквизиты):
        return self.элемент("УЗ_ФизЛица", имя, ЭтоПедагог=True, **реквизиты)

    def абонемент(self, ученик, имя="абонемент", **реквизиты):
        поля = dict(ФизЛицо=ученик, Активный=True, ДатаНачала=self.день(-30), ДатаАктивации=self.день(-30),
                    ДатаОкончания=self.день(60))
        поля.update(реквизиты)
        return self.элемент("УЗ_Абонемент", имя, **поля)

    def карта(self, владелец, имя="карта", **реквизиты):
        о = self.c.Справочники.УЗ_ДисконтныеКарты.СоздатьЭлемент()
        о.Владелец = владелец
        о.Наименование = "%s %s" % (self.метка, имя)
        for к, в in реквизиты.items():
            setattr(о, к, в)
        о.Записать()
        ссылка = о.Ссылка
        self.т.убрать(lambda: self.т.удалить_объект(ссылка), "карта %s" % имя)
        return ссылка

    def цена_тарифа(self, тариф, период, сумма, уроков=0, часов=0):
        c = self.c
        з = c.РегистрыСведений.УЗ_ЦеныТарифов.СоздатьМенеджерЗаписи()
        з.Период = период
        з.Тариф = тариф
        з.Сумма = сумма
        з.КоличествоУроков = уроков
        з.КоличествоЧасов = часов
        з.Записать()

        def удалить():
            н = c.РегистрыСведений.УЗ_ЦеныТарифов.СоздатьМенеджерЗаписи()
            н.Период = период
            н.Тариф = тариф
            н.Прочитать()
            if н.Выбран():
                н.Удалить()
        self.т.убрать(удалить, "цена тарифа")

    # ── документы ──
    def урок(self, педагог, начало, часов=1, строки=(), **реквизиты):
        """строки — словари реквизитов строк «Ученики»."""
        д = self.c.Документы.УЗ_Урок.СоздатьДокумент()
        д.Дата = начало
        д.Педагог = педагог
        д.КоличествоЧасов = часов
        д.Комментарий = self.метка
        for к, в in реквизиты.items():
            setattr(д, к, в)
        for поля in строки:
            с = д.Ученики.Добавить()
            for к, в in поля.items():
                setattr(с, к, в)
        return д

    def приход(self, физлицо, сумма=0, **реквизиты):
        д = self.c.Документы.УЗ_ПриходДенег.СоздатьДокумент()
        д.Дата = реквизиты.pop("Дата", self.день(0, 9))
        д.ВидОперации = self.c.Перечисления.УЗ_ВидыОпераций.КассаУченики
        д.ФизЛицо = физлицо
        д.СуммаДокумента = сумма
        д.Комментарий = self.метка
        for к, в in реквизиты.items():
            setattr(д, к, в)
        return д

    def уборка_документа(self, д):
        if д.Ссылка.Пустая():
            return
        ссылка = д.Ссылка

        def убрать():
            о = ссылка.ПолучитьОбъект()
            if о is None:
                return
            # документ мог изменить сеанс сотрудника (тест прав): ПолучитьОбъект отдаёт данные из кэша этого сеанса
            # (прочитанные раньше через ссылку) — запись падала «несоответствие версии»; Прочитать берёт из базы
            о.Прочитать()
            if о.Проведен:
                о.Записать(self.c.РежимЗаписиДокумента.ОтменаПроведения)
            о.Удалить()
        self.т.убрать(убрать, "документ %s" % self.c.String(ссылка))

    def записать(self, д, режим="Проведение"):
        """Запись/проведение → (текст ошибки или None, [(текст, поле) сообщений]). Документ встаёт в уборку."""
        c = self.c
        c.ПолучитьСообщенияПользователю(True)
        новый = д.Ссылка.Пустая()
        try:
            д.Записать(getattr(c.РежимЗаписиДокумента, режим))
            ошибка = None
        except Exception as е:
            ошибка = текст_ошибки(е)
        сообщения = [(" ".join(str(с.Текст).split()), str(с.Поле or ""))
                     for с in c.ПолучитьСообщенияПользователю(True)]
        if новый and not д.Ссылка.Пустая():
            self.уборка_документа(д)
        return ошибка, сообщения

    # ── состав групп (В29: только документом «Перевод ученика») ──
    def перевод(self, ученики, из_группы=None, в_группу=None, день=None, режим="Проведение", **реквизиты):
        """Документ «Перевод ученика» (зачисление — без из_группы, выбытие — без в_группу) на день (по умолчанию
        сегодня) → (документ, (ошибка, [(текст, поле)])). Уборка — движения набором и документ загрузкой (мимо
        перестроения уроков-планов: уроки теста убираются сами)."""
        c = self.c
        д = c.Документы.УЗ_ПереводУченика.СоздатьДокумент()
        д.Дата = день if день is not None else self.день(0)
        if из_группы is not None:
            д.ГруппаИз = из_группы
        if в_группу is not None:
            д.ГруппаВ = в_группу
        д.Комментарий = self.метка
        for к, в in реквизиты.items():
            setattr(д, к, в)
        for у in ученики:
            д.Ученики.Добавить().Ученик = у
        c.ПолучитьСообщенияПользователю(True)
        try:
            д.Записать(getattr(c.РежимЗаписиДокумента, режим))
            ошибка = None
        except Exception as е:
            ошибка = текст_ошибки(е)
        сообщения = [(" ".join(str(с.Текст).split()), str(с.Поле or ""))
                     for с in c.ПолучитьСообщенияПользователю(True)]
        if not д.Ссылка.Пустая():
            ссылка = д.Ссылка
            self.т.убрать(lambda: self.т.удалить_объект(ссылка, загрузка=True), "перевод ученика")
        return д, (ошибка, сообщения)

    def в_группу(self, ученик, группа, с_дня, по_день=None):
        """Ученик в группе с дня с_дня (сдвиг от сегодня) и, если задано, по день по_день включительно — документами
        «Перевод ученика» (зачисление; выбытие со следующего дня). Отказ проведения — провал теста."""
        _, (ошибка, сообщения) = self.перевод([ученик], в_группу=группа, день=self.день(с_дня))
        self.т.проверить(ошибка is None, "подготовка: зачисление в группу", "%s %s" % (ошибка, сообщения))
        if по_день is not None:
            _, (ошибка, сообщения) = self.перевод([ученик], из_группы=группа, день=self.день(по_день + 1))
            self.т.проверить(ошибка is None, "подготовка: выбытие из группы", "%s %s" % (ошибка, сообщения))

    def выбрать(self, текст, **параметры):
        return self.т.выбрать(текст, **параметры)

    def число(self, текст, **параметры):
        """Первое поле первой строки запроса числом (нет строк / NULL → 0)."""
        тз = self.т.выбрать(текст, **параметры)
        if тз.Количество() == 0:
            return 0
        значение = тз.Получить(0).Получить(0)
        return float(значение) if значение is not None else 0.0

    # ── зарплата урока (R24: урок начисление не хранит — только движения регистра) ──
    def начислено_педагогу(self, урок):
        """Начисление педагогу за урок (урок — объект или ссылка): приход его движений в УЗ_РасчетыПоЗарплате."""
        return self.число("ВЫБРАТЬ ЕСТЬNULL(СУММА(Р.Сумма), 0) КАК Сумма ИЗ РегистрНакопления.УЗ_РасчетыПоЗарплате КАК Р "
                          "ГДЕ Р.Регистратор = &Урок И Р.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход)",
                          Урок=урок.Ссылка)

    def доплата(self, урок, сумма, комментарий="доплата за урок"):
        """Доплата педагогу сверх ставки — документ «Начисление педагогам» на основании урока (как кнопка
        «Добавить доплату» формы урока). → (документ, (ошибка, сообщения))."""
        д = self.c.Документы.УЗ_НачисленияПедагогам.СоздатьДокумент()
        д.Заполнить(урок.Ссылка)
        с = д.НачисленияПедагогам.Добавить()
        с.Комментарий = комментарий
        с.Сумма = сумма
        return д, self.записать(д)
