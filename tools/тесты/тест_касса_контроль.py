"""Контроль кассовых документов (ошибки из сверки справки 28.09.2026: Р4, 40, 41, 43, 56).

Было → стало:
  * Р4/В7: в ПКО можно было провести «Выплата зарплаты»/«Прочий расход» — деньги молча добавлялись в кассу.
    Теперь приход — только «Касса ученики» или «Внутренняя касса», расходный вид — отказ;
  * 40: перемещение между кассами ничего не проверяло — пустая касса, одна и та же касса, сумма 0, касса
    в минус. Теперь отказ с причиной; остаток кассы-отправителя — текущий, без движений самого документа
    (перепроведение перемещения «всего остатка» проходит);
  * 43: «Начисления педагогам» проводились без педагога — долг «никому». Теперь без педагога и не педагогу — отказ;
  * 41: «Сделать основной» падало без строки/на группе, ошибка записи уходила в журнал молча. Теперь
    Справочники.УЗ_Кассы.НазначитьОсновной: причина отказа текстом, «Основная» — у одной кассы;
  * 56: цвет «Королевский голубой» сохранялся ключом «Королевскийголубой», которого нет в WebЦвета, —
    урок с таким помещением не открывался. Теперь ключ — по сравнению цвета с палитрой
    (УЗ_ОбщийКлиентСервер.ИмяWebЦвета), чтение терпит старые имена (WebЦветПоИмени).

    python tools\\тесты\\тест_касса_контроль.py --база=C:\\1c_bases\\UZ_UNF_B --пользователь=Администратор
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import дата, запустить, текст_ошибки  # noqa: E402
from _деньги import Данные, сейчас  # noqa: E402

МЕТКА = "_Тест касса контроль"


def ид(c, ссылка):
    return c.String(ссылка.УникальныйИдентификатор())


def сценарий(т):
    c = т.c
    д = Данные(т, МЕТКА)
    виды = c.Перечисления.УЗ_ВидыОпераций
    ученик = д.элемент("УЗ_ФизЛица", "ученик")

    # ── Р4: расходные виды в ПКО не проводятся ──
    касса = д.элемент("УЗ_Кассы", "приход")

    def пко(вид, час):
        return д.документ("УЗ_ПриходДенег", Дата=дата(2026, 9, 10, час), Касса=касса, ФизЛицо=ученик,
                          СуммаДокумента=500, ВидОперации=вид)
    for вид, имя, час in ((виды.ВыплатаЗарплаты, "Выплата зарплаты", 10), (виды.ПрочийРасход, "Прочий расход", 11)):
        п = пко(вид, час)
        ош = д.записать(п)
        т.проверить(ош is not None and "для расхода" in ош and д.итог("УЗ_Касса", п.Ссылка) == (0.0, 0),
                    "ПКО с видом «%s» — отказ, в кассу ничего не пришло" % имя, ош or д.итог("УЗ_Касса", п.Ссылка))
    п = пко(виды.ВнутренняяКасса, 12)
    ош = д.записать(п)
    т.проверить(ош is None and д.итог("УЗ_Касса", п.Ссылка) == (500.0, 1),
                "ПКО «Внутренняя касса» (прочее поступление) проводится: касса +500", ош or д.итог("УЗ_Касса", п.Ссылка))

    # ── 40: перемещение между кассами ──
    отправитель = д.элемент("УЗ_Кассы", "отправитель")
    получатель = д.элемент("УЗ_Кассы", "получатель")
    носитель = д.регистратор()
    д.движения("УЗ_Касса", носитель, [("+", дата(2026, 9, 1, 10), {"Касса": отправитель, "Клиент": ученик, "Сумма": 1000})])

    def остаток(касса):
        return float(c.Справочники.УЗ_Кассы.ОстатокДенег(касса))

    def перемещение(сумма, из_кассы, в_кассу):
        п = д.документ("УЗ_ПеремещениеДенег", Дата=сейчас(), Сумма=сумма, ВидОперации=виды.ВнутренняяКасса)
        if из_кассы is not None:
            п.КассаОтправитель = из_кассы
        if в_кассу is not None:
            п.КассаПолучатель = в_кассу
        return п

    for (сумма, из_кассы, в_кассу, причина, что) in (
            (100, None, получатель, "отправителя", "без кассы-отправителя"),
            (100, отправитель, None, "получателя", "без кассы-получателя"),
            (100, отправитель, отправитель, "совпадают", "из кассы в неё же"),
            (0, отправитель, получатель, "больше нуля", "на сумму 0"),
            (-50, отправитель, получатель, "больше нуля", "на отрицательную сумму"),
            (1500, отправитель, получатель, "в минус", "1 500 при остатке 1 000")):
        п = перемещение(сумма, из_кассы, в_кассу)
        ош = д.записать(п)
        т.проверить(ош is not None and причина in ош and д.итог("УЗ_Касса", п.Ссылка) == (0.0, 0),
                    "перемещение %s — отказ с причиной «%s», касса не тронута" % (что, причина), ош)
    т.проверить(остаток(отправитель) == 1000 and остаток(получатель) == 0,
                "после отказов остатки прежние: 1 000 / 0", "%s / %s" % (остаток(отправитель), остаток(получатель)))

    п = перемещение(1000, отправитель, получатель)
    ош = д.записать(п)
    т.проверить(ош is None and остаток(отправитель) == 0 and остаток(получатель) == 1000,
                "перемещение всего остатка 1 000 проведено: 0 / 1 000",
                ош or "%s / %s" % (остаток(отправитель), остаток(получатель)))
    ош = д.записать(п.Ссылка.ПолучитьОбъект())
    т.проверить(ош is None and остаток(отправитель) == 0 and остаток(получатель) == 1000,
                "перепроведение того же перемещения: свои движения не считаются расходом остатка", ош)
    ош = д.записать(перемещение(1, отправитель, получатель))
    т.проверить(ош is not None and "в минус" in ош, "из пустой кассы ещё 1 — отказ", ош)

    # ── 43: начисления педагогам ──
    педагог = д.элемент("УЗ_ФизЛица", "педагог", ЭтоПедагог=True)

    def начисление(кому):
        н = д.документ("УЗ_НачисленияПедагогам", Дата=дата(2026, 9, 5, 10))
        if кому is not None:
            н.Педагог = кому
        н.НачисленияПедагогам.Добавить().Сумма = 300
        return н
    for кому, что, причина in ((None, "без педагога", "Укажите педагога"), (ученик, "ученику", "не педагог")):
        н = начисление(кому)
        ош = д.записать(н)
        т.проверить(ош is not None and причина in ош and д.итог("УЗ_РасчетыПоЗарплате", н.Ссылка) == (0.0, 0),
                    "начисление %s — отказ, долг никому не записан" % что, ош)
    н = начисление(педагог)
    ош = д.записать(н)
    т.проверить(ош is None and д.итог("УЗ_РасчетыПоЗарплате", н.Ссылка) == (300.0, 1),
                "начисление педагогу 300 проведено", ош or д.итог("УЗ_РасчетыПоЗарплате", н.Ссылка))

    # ── 41: «Сделать основной» ──
    кассы = c.Справочники.УЗ_Кассы
    з = c.NewObject("Запрос")
    з.Текст = "ВЫБРАТЬ К.Ссылка КАК Ссылка ИЗ Справочник.УЗ_Кассы КАК К ГДЕ К.Основная"
    выборка = з.Выполнить().Выбрать()
    основные = []
    while выборка.Следующий():
        основные.append(выборка.Ссылка)

    def отметить(касса, значение):
        о = касса.ПолучитьОбъект()
        о.Основная = значение
        о.ОбменДанными.Загрузка = True
        о.Записать()
    for касса_б in основные:
        т.убрать(lambda к=касса_б: отметить(к, True), "вернуть «Основная»")

    группа = кассы.СоздатьГруппу()
    группа.Наименование = МЕТКА + " группа"
    группа.Записать()
    группа = группа.Ссылка
    т.убрать(lambda: т.удалить_объект(группа), "группа касс")
    for значение, что in ((кассы.ПустаяСсылка(), "без выбранной строки"), (группа, "на группе касс")):
        try:
            ответ = кассы.НазначитьОсновной(значение)
        except Exception as исключение:  # noqa: BLE001 — падение и есть старая ошибка
            ответ = None
            причина = текст_ошибки(исключение)
        else:
            причина = ответ
        т.проверить(bool(ответ), "«Сделать основной» %s — причина текстом, не падение" % что, причина)
    т.проверить(ид(c, кассы.ПолучитьОсновнуюКассу()) != ид(c, группа), "группа не стала основной")

    первая = д.элемент("УЗ_Кассы", "основная 1")
    вторая = д.элемент("УЗ_Кассы", "основная 2")
    т.проверить(кассы.НазначитьОсновной(первая) == "" and ид(c, кассы.ПолучитьОсновнуюКассу()) == ид(c, первая),
                "первая касса стала основной")
    т.проверить(кассы.НазначитьОсновной(вторая) == "", "вторая касса стала основной")
    з = c.NewObject("Запрос")
    # В12: основная касса — у каждой организации своя; первая и вторая — без организации (общие), сравниваем их
    з.Текст = ("ВЫБРАТЬ К.Ссылка КАК Ссылка ИЗ Справочник.УЗ_Кассы КАК К ГДЕ К.Основная "
               "И К.Организация = ЗНАЧЕНИЕ(Справочник.Организации.ПустаяСсылка)")
    в = з.Выполнить().Выгрузить()
    отмеченные = [ид(c, в.Получить(н).Ссылка) for н in range(в.Количество())]
    т.проверить(отмеченные == [ид(c, вторая)],
                "«Основная» среди касс без организации — только у второй (у прежних снята)",
                "отмечено касс: %d" % len(отмеченные))

    # ── 56: цвет помещения «Королевский голубой» ──
    цвета = c.УЗ_ОбщийКлиентСервер
    т.проверить(цвета.ИмяWebЦвета(цвета.WebЦветПоИмени("КоролевскиГолубой")) == "КоролевскиГолубой",
                "«Королевский голубой»: ключ — «КоролевскиГолубой»")
    т.проверить(цвета.ИмяWebЦвета(цвета.WebЦветПоИмени("Королевскийголубой")) == "КоролевскиГолубой",
                "старое сохранённое имя «Королевскийголубой» читается тем же цветом (урок не падает)")
    т.проверить(цвета.ИмяWebЦвета(цвета.WebЦветПоИмени("нет такого цвета")) == ""
                and цвета.ИмяWebЦвета(цвета.WebЦветПоИмени("")) == "",
                "неизвестное и пустое имя — без цвета, без ошибки")
    имена = цвета.ИменаWebЦветов()
    плохие = []
    for н in range(имена.Количество()):
        имя = имена.Получить(н)
        if цвета.ИмяWebЦвета(цвета.WebЦветПоИмени(имя)) != имя:
            плохие.append(имя)
    т.проверить(имена.Количество() > 100 and not плохие,
                "все %d цветов палитры: имя → цвет → то же имя" % имена.Количество(), ", ".join(плохие[:10]))
    помещение = д.элемент("УЗ_Помещения", "зал", Цвет="Королевскийголубой")
    т.проверить(цвета.ИмяWebЦвета(цвета.WebЦветПоИмени(помещение.Цвет)) == "КоролевскиГолубой",
                "помещение со старым цветом «Королевскийголубой» — цвет читается")


if __name__ == "__main__":
    запустить("касса_контроль", сценарий)
