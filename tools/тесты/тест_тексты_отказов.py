"""Что продукт говорит человеку, когда данные неверны (образец — «Путевые листы», com_test_диалог_ошибок).

Остальные тесты проверяют, что отказ случился. Этот — что человек его поймёт: нажал «Провести», получил красную
строку и должен по ней понять, какое поле исправить. Для каждого типичного отказа урока, прихода и расхода денег,
абонемента (документ записывается как кнопкой формы: проверка заполнения, потом проведение) проверяется:
  * отказ есть (документ не проведён / элемент не записан);
  * есть сообщение, привязанное к нужному полю (СообщениеПользователю.Поле — щелчок по нему ставит курсор в поле);
И для всех собранных сообщений разом:
  * текст не пустой и не обрывок (фраза от 15 знаков);
  * без имён из конфигуратора: латиницы, «УЗ_», слитных имён реквизитов вроде «СписатьОплату» или
    «СуммаДокумента» (вне «ёлочек» — в них названия из данных);
  * каждое сообщение отказа привязано к полю.

    python tools\\тесты\\тест_тексты_отказов.py --база=C:\\1c_bases\\UZ_BP_E --пользователь=1
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from фабрика import Фабрика  # noqa: E402

МЕТКА = "УЗ тест текстов отказов"
СЛИТНОЕ_ИМЯ = re.compile(r"\b[А-ЯЁ][а-яё]+(?:[А-ЯЁ][а-яё]*)+\b")   # «СписатьОплату», «ФизЛицо»
ЛАТИНИЦА = re.compile(r"[A-Za-z_]{3,}")


def вне_ёлочек(текст):
    """Текст без названий из данных: «…» и "…" выбрасываются."""
    return re.sub(r"«[^»]*»|\"[^\"]*\"", " ", текст)


def сценарий(т):
    ф = Фабрика(т, МЕТКА)
    c = т.c
    виды = c.Перечисления.УЗ_ВидыОпераций
    все = []   # (случай, текст, поле) — всё, что продукт сказал при отказах

    def отказ(случай, итог, поле, слово=None):
        """итог — (ошибка, [(текст, поле)]) фабрики. Отказ есть, и у поля «поле» — сообщение (со словом)."""
        ошибка, сообщения = итог
        все.extend((случай, текст, п) for текст, п in сообщения)
        у_поля = [текст for текст, п in сообщения if п.split(".")[-1] == поле or п.endswith(поле)]
        if слово:
            у_поля = [текст for текст in у_поля if слово in текст.lower()]
        т.проверить(ошибка is not None and у_поля, "%s — отказ, сообщение у поля «%s»" % (случай, поле),
                    "ошибка %s, сообщения %s" % (ошибка, сообщения))

    def записать_элемент(о):
        c.ПолучитьСообщенияПользователю(True)
        try:
            о.Записать()
            ошибка = None
        except Exception as е:
            ошибка = str(е)[:200]
        сообщения = [(" ".join(str(м.Текст).split()), str(м.Поле or "")) for м in c.ПолучитьСообщенияПользователю(True)]
        if ошибка is None:
            ссылка = о.Ссылка
            т.убрать(lambda: т.удалить_объект(ссылка), "элемент теста", пакет=True)
        return ошибка, сообщения

    def записать(д):
        """Как кнопка «Провести» формы: сначала проверка заполнения (реквизиты «обязательно»), потом проведение."""
        c.ПолучитьСообщенияПользователю(True)
        if not д.ПроверитьЗаполнение():
            return "не прошла проверку заполнения", [(" ".join(str(м.Текст).split()), str(м.Поле or ""))
                                                       for м in c.ПолучитьСообщенияПользователю(True)]
        return ф.записать(д)

    ученик = ф.ученик()
    педагог = ф.педагог()
    тариф = ф.элемент("УЗ_Тарифы", "1 000 за урок", Сумма=1000, КоличествоУроков=1)
    касса = ф.элемент("УЗ_Кассы", "касса")
    статья = ф.элемент("УЗ_СтатьиДвиженияДенег", "аренда")

    # ── урок ──
    отказ("урок без педагога",
          записать(ф.урок(c.Справочники.УЗ_ФизЛица.ПустаяСсылка(), ф.день(-1, 8), 1,
                            [dict(Ученик=ученик, Тариф=тариф, Явка=True, СписатьОплату=True)])), "Педагог")
    отказ("урок без учеников", записать(ф.урок(педагог, ф.день(-1, 9), 1, [])), "Ученики")
    отказ("строка «К оплате» без тарифа",
          записать(ф.урок(педагог, ф.день(-1, 10), 1, [dict(Ученик=ученик, Явка=True, СписатьОплату=True)])),
          "Тариф", "тариф")
    отказ("строка без ученика",
          записать(ф.урок(педагог, ф.день(-1, 11), 1, [dict(Тариф=тариф, Явка=True, СписатьОплату=True)])),
          "Ученик")
    первый = ф.урок(педагог, ф.день(-1, 12), 1, [dict(Ученик=ученик, Тариф=тариф, Явка=True, СписатьОплату=True)])
    т.проверить(записать(первый)[0] is None, "подготовка: урок педагога 12:00–13:00 проведён")
    отказ("урок педагога поверх его другого урока",
          записать(ф.урок(педагог, ф.день(-1, 12, 30), 1,
                            [dict(Ученик=ф.ученик("второй"), Тариф=тариф, Явка=True, СписатьОплату=True)])),
          "Педагог")
    отказ("урок нулевой длительности",
          записать(ф.урок(педагог, ф.день(-1, 14), 0, [dict(Ученик=ученик, Тариф=тариф, Явка=True,
                                                                СписатьОплату=True)])), "КоличествоЧасов")

    # ── приход денег ──
    отказ("приход без суммы", записать(ф.приход(ученик, 0, Касса=касса)), "СуммаДокумента")
    отказ("приход с минусом", записать(ф.приход(ученик, -500, Касса=касса)), "СуммаДокумента")
    отказ("приход без кассы", записать(ф.приход(ученик, 500)), "Касса")
    отказ("оплата ученика без ученика",
          записать(ф.приход(c.Справочники.УЗ_ФизЛица.ПустаяСсылка(), 500, Касса=касса)), "ФизЛицо")

    # ── расход денег ──
    def расход(сумма, **поля):
        д = c.Документы.УЗ_РасходДенег.СоздатьДокумент()
        д.Дата = ф.день(0, 9)
        д.Комментарий = МЕТКА
        д.СуммаДокумента = сумма
        for к, в in поля.items():
            setattr(д, к, в)
        return д
    отказ("расход больше остатка кассы",
          записать(расход(5000, Касса=касса, ВидОперации=виды.ПрочийРасход, СтатьяЗатрат=статья)),
          "СуммаДокумента", "минус")
    отказ("расход без кассы", записать(расход(100, ВидОперации=виды.ПрочийРасход, СтатьяЗатрат=статья)), "Касса")

    # ── абонемент ──
    о = c.Справочники.УЗ_Абонемент.СоздатьЭлемент()
    о.Наименование = МЕТКА + " сроки наоборот"
    о.ФизЛицо = ученик
    о.ДатаНачала = ф.день(10)
    о.ДатаОкончания = ф.день(-10)
    отказ("абонемент: начало позже окончания", записать_элемент(о), "ДатаОкончания")

    # ── язык сообщений: всё, что прозвучало при отказах ──
    т.проверить(все, "при отказах продукт что-то сказал", "сообщений 0")
    пустые = [(с, т_) for с, т_, _ in все if not т_.strip()]
    т.проверить(not пустые, "пустых сообщений нет", пустые)
    обрывки = [(с, т_) for с, т_, _ in все if 0 < len(т_.strip()) < 15]
    т.проверить(not обрывки, "каждое сообщение — фраза, а не обрывок (от 15 знаков)", обрывки)
    сырые = []
    for с, текст, _ in все:
        чистый = вне_ёлочек(текст)
        for слово in ЛАТИНИЦА.findall(чистый) + СЛИТНОЕ_ИМЯ.findall(чистый):
            сырые.append("%s: «%s» в «%s»" % (с, слово, текст[:80]))
        if "УЗ_" in текст:
            сырые.append("%s: префикс УЗ_ в «%s»" % (с, текст[:80]))
    т.проверить(not сырые, "в сообщениях нет имён из конфигуратора (латиница, УЗ_, слитные имена реквизитов)",
                "; ".join(сырые[:6]))
    без_поля = [(с, т_[:70]) for с, т_, п in все if not п]
    т.проверить(not без_поля, "каждое сообщение отказа привязано к полю", без_поля[:6])


if __name__ == "__main__":
    запустить("тексты_отказов", сценарий)
