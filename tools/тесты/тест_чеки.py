"""Чеки 54-ФЗ, часть 1 (этап 2.2, В61, В62): данные чека прихода и возврата, параметры кассы хозяина, отказы, отметка.

Без кассы: УЗ_Чеки.ДанныеЧека (что попадает в чек, простыми значениями) и УЗ_СредаКасса.ПараметрыЧекаХозяина (те же
данные в параметрах фискализации библиотеки подключаемого оборудования хозяина — её перечисления). Пробитие на
кассе — клиент (УЗ_СредаКлиент); через COM его нет, отметка пробитого чека проверяется вызовом УЗ_Чеки.ОтметитьЧек
с ответом «как от кассы».

    python tools\\тесты\\тест_чеки.py --база=C:\\1c_bases\\UZ_BP_S --пользователь=1
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from фабрика import Фабрика  # noqa: E402
from _деньги import Данные  # noqa: E402

МЕТКА = "_Тест чеки"


def структура(c, **поля):
    с = c.NewObject("Структура")
    for к, в in поля.items():
        с.Вставить(к, в)
    return с


def пакет_драйвера(c, параметры):
    """XML чека для драйвера ККТ — процедурой библиотеки подключаемого оборудования хозяина (как при пробитии)."""
    пф = c.ОборудованиеЧекопечатающиеУстройства.ПараметрыФискализацииЧека()
    пф.РевизияИнтерфейса = 4004
    c.ОборудованиеЧекопечатающиеУстройства.СформироватьXMLПакетДляФискализацияЧека(параметры, пф)
    return str(пф.ДанныеЧекаXML)


def позиции(данные):
    return [(str(п.Наименование), float(п.Сумма), str(п.СпособРасчета), str(п.ПредметРасчета))
            for п in (данные.Позиции.Получить(н) for н in range(данные.Позиции.Количество()))]


def сценарий(т):
    c = т.c
    ф = Фабрика(т, МЕТКА)
    д = Данные(т, МЕТКА)
    перечисления = c.Перечисления

    def имя(значение):
        """Имя значения перечисления хозяина (COM-объекты между собой через == не сравниваются)."""
        return str(c.XMLString(значение))

    орг = ф.организация("студия")
    з = c.РегистрыСведений.УЗ_РеквизитыОрганизаций.СоздатьМенеджерЗаписи()
    з.Организация = орг
    з.СистемаНалогообложения = "УСНДоход"
    з.Записать()

    def убрать_реквизиты():
        н = c.РегистрыСведений.УЗ_РеквизитыОрганизаций.СоздатьМенеджерЗаписи()
        н.Организация = орг
        н.Прочитать()
        if н.Выбран():
            н.Удалить()
    т.убрать(убрать_реквизиты, "реквизиты организации")

    касса = ф.элемент("УЗ_Кассы", "касса", Организация=орг)
    математика = ф.элемент("УЗ_ПредметыОбучения", "математика")
    гитара = ф.элемент("УЗ_ПредметыОбучения", "гитара")
    мама = ф.элемент("УЗ_ФизЛица", "мама", Телефон="8 (912) 345-67-89", EMail="mama@example.ru")
    сын = ф.элемент("УЗ_ФизЛица", "сын", Телефон="+7 900 000-00-01")
    дочь = ф.ученик("дочь")
    абонемент = ф.абонемент(дочь, "гитара", Организация=орг, ПредметОбучения=гитара)
    # долг сына по математике 700: занятия уже проведены (списание раньше оплаты)
    д.движения("УЗ_СписанияСуммЗаУроки", д.регистратор(),
               [("-", ф.день(-1, 10), {"Клиент": сын, "ПредметОбучения": математика, "Сумма": 700,
                                       "Организация": орг})])

    приход = ф.приход(сын, 0, Организация=орг, Касса=касса, Плательщик=мама, Дата=ф.день(0, 9))
    for ученик, предмет, аб, сумма in ((сын, математика, None, 1000), (дочь, гитара, абонемент, 3000)):
        с = приход.РасшифровкаПлатежа.Добавить()
        с.Ученик = ученик
        с.ПредметОбучения = предмет
        if аб is not None:
            с.Абонемент = аб
        с.Сумма = сумма
    ош, сообщ = ф.записать(приход)
    т.проверить(ош is None, "приход за двоих проведён", "%s %s" % (ош, сообщ))
    if ош is not None:
        return
    ссылка = приход.Ссылка

    # ── данные чека прихода ──
    данные = c.УЗ_Чеки.ДанныеЧека(ссылка, "Наличные")
    т.проверить(str(данные.Причина) == "", "чек прихода можно пробить", данные.Причина)
    т.проверить(str(данные.ТипРасчета) == "Приход" and float(данные.Сумма) == 4000,
                "чек «Приход» на 4 000", "%s %s" % (данные.ТипРасчета, данные.Сумма))
    т.проверить(str(данные.СистемаНалогообложения) == "УСНДоход", "система налогообложения — из реквизитов организации",
                данные.СистемаНалогообложения)
    т.проверить(str(данные.ПокупательНомер) == "+79123456789" and str(данные.ПокупательEmail) == "mama@example.ru",
                "контакты плательщика для электронного чека (телефон в формате кассы)",
                "%s / %s" % (данные.ПокупательНомер, данные.ПокупательEmail))
    мат = "Оплата занятий: %s математика" % МЕТКА
    гит = "Оплата занятий: %s гитара" % МЕТКА
    ждём = [(мат, 700.0, "ПередачаСПолнойОплатой", "Услуга"), (мат, 300.0, "ПредоплатаПолная", "Услуга"),
            (гит, 3000.0, "ПредоплатаПолная", "Услуга")]
    т.проверить(позиции(данные) == ждём,
                "позиции: долг за проведённые занятия — «полный расчёт», остаток и абонемент — «предоплата 100%»",
                позиции(данные))

    # ── параметры кассы хозяина ──
    п = c.УЗ_СредаКасса.ПараметрыЧекаХозяина(данные)
    строки = [п.ПозицииЧека.Получить(н) for н in range(п.ПозицииЧека.Количество())]
    способы = [имя(с.ПризнакСпособаРасчета) for с in строки]
    т.проверить(способы == ["ПередачаСПолнойОплатой", "ПредоплатаПолная", "ПредоплатаПолная"],
                "три позиции; признаки способа расчёта — значения перечисления хозяина", способы)
    т.проверить(len(строки) == 3 and all(имя(с.ПризнакПредметаРасчета) == "Услуга" and с.СтавкаНДС is None
                                         and float(с.Сумма) == float(с.Цена) for с in строки),
                "предмет расчёта «Услуга», без НДС, цена = сумма", [имя(с.ПризнакПредметаРасчета) for с in строки])
    т.проверить(имя(п.ТипРасчета) == "ПриходДенежныхСредств" and имя(п.СистемаНалогообложения) == "УСНДоход"
                and c.XMLString(п.ДокументОснование) == c.XMLString(ссылка)
                and str(п.ПокупательНомер) == "+79123456789",
                "шапка чека хозяина: приход, УСН доходы, документ-основание, телефон покупателя",
                "%s %s" % (имя(п.ТипРасчета), имя(п.СистемаНалогообложения)))
    оплата = п.ТаблицаОплат.Получить(0) if п.ТаблицаОплат.Количество() == 1 else None
    т.проверить(оплата is not None and имя(оплата.ТипОплаты) == "Наличные" and float(оплата.Сумма) == 4000,
                "оплата: наличными 4 000", оплата and float(оплата.Сумма))
    безнал = c.УЗ_СредаКасса.ПараметрыЧекаХозяина(c.УЗ_Чеки.ДанныеЧека(ссылка, "Электронно"))
    т.проверить(имя(безнал.ТаблицаОплат.Получить(0).ТипОплаты) == "Электронно",
                "оплата картой или переводом — «Электронно»")

    # ── пакет драйвера кассы, собранный кодом хозяина (то, что уйдёт в ККТ; ФФД 1.2 — ревизия 4004) ──
    xml = пакет_драйвера(c, п)
    т.проверить('OperationType="1"' in xml and 'TaxationSystem="1"' in xml and 'CustomerPhone="+79123456789"' in xml
                and 'CustomerEmail="mama@example.ru"' in xml and 'Cash="4000"' in xml,
                "пакет кассы хозяина: приход (1), УСН доходы (1), контакты покупателя, наличными 4 000", xml[:400])
    т.проверить([с.split('"')[0] for с in xml.split('PaymentMethod="')[1:]] == ["4", "1", "1"]
                and xml.count('CalculationSubject="4"') == 3 and xml.count('VATRate="none"') == 3,
                "пакет кассы: признак способа расчёта 4 (полный расчёт), 1, 1 (предоплата 100%); услуга (4); без НДС",
                xml)

    # ── отказы ──
    касса_есть = c.УЗ_СредаКасса.ЕстьОнлайнКасса()
    подготовка = c.УЗ_Чеки.ПодготовитьЧек(ссылка, "Наличные")
    if касса_есть:
        т.проверить(str(подготовка.Причина) == "" and подготовка.ПараметрыОперации is not None,
                    "касса в программе есть — чек подготовлен для неё", подготовка.Причина)
    else:
        т.проверить("не подключена онлайн-касса" in str(подготовка.Причина),
                    "касса в программе не подключена — отказ с подсказкой, где подключить", подготовка.Причина)
    нет_подсистемы = c.УЗ_Среда.ОнлайнКассаПоМетаданным("ОборудованиеЧекопечатающиеУстройстваКлиент,УЗ_НетТакогоМодуля",
                                                        "ПризнакиСпособаРасчета")
    т.проверить(not нет_подсистемы.Есть and "УЗ_НетТакогоМодуля" in str(нет_подсистемы.Причина),
                "нет подсистемы онлайн-касс у хозяина — отказ с причиной", нет_подсистемы.Причина)
    т.проверить(c.УЗ_Среда.ОнлайнКассаХозяина().Есть, "у хозяина (БП/УНФ/УТ) подсистема онлайн-касс есть")

    з.СистемаНалогообложения = ""
    з.Записать()
    т.проверить("не указана система налогообложения" in str(c.УЗ_Чеки.ДанныеЧека(ссылка, "Наличные").Причина),
                "без системы налогообложения — отказ с подсказкой, где указать")
    з.СистемаНалогообложения = "УСНДоход"
    з.Записать()

    внутр = ф.приход(ф.ученик("прочее"), 500, Организация=орг, Касса=касса,
                     ВидОперации=перечисления.УЗ_ВидыОпераций.ВнутренняяКасса)
    ош, сообщ = ф.записать(внутр)
    т.проверить(ош is None, "прочее поступление проведено", "%s %s" % (ош, сообщ))
    т.проверить("Касса ученики" in str(c.УЗ_Чеки.ДанныеЧека(внутр.Ссылка, "Наличные").Причина),
                "прочее поступление («Внутренняя касса») — не чек оплаты ученика")
    черновик = ф.приход(сын, 100, Организация=орг, Касса=касса)
    ф.записать(черновик, "Запись")
    т.проверить("Проведите" in str(c.УЗ_Чеки.ДанныеЧека(черновик.Ссылка, "Наличные").Причина),
                "непроведённый — отказ «проведите»")

    # ── отметка пробитого чека: повторно не пробивается ──
    def убрать_чек():
        н = c.РегистрыСведений.УЗ_ЧекиККТ.СоздатьМенеджерЗаписи()
        н.Документ = ссылка
        н.Прочитать()
        if н.Выбран():
            н.Удалить()
    т.убрать(убрать_чек, "отметка чека")
    # Блокер 2: вторая попытка до фискализации уже запрещена; никаких вызовов настоящей ККТ.
    резерв = c.УЗ_Чеки.ЗарезервироватьЧек(ссылка)
    т.проверить(str(резерв.Причина) == "" and str(резерв.ИдентификаторОперации), "первый чек зарезервирован")
    повтор = c.УЗ_Чеки.ЗарезервироватьЧек(ссылка)
    т.проверить("уже пробивается или пробит" in str(повтор.Причина), "вторая попытка до ответа кассы запрещена")
    c.УЗ_Чеки.ЗавершитьНеудачныйЧек(ссылка, резерв.ИдентификаторОперации, True)
    резерв = c.УЗ_Чеки.ЗарезервироватьЧек(ссылка)
    т.проверить(str(резерв.Причина) == "", "после явного отказа ККТ новая попытка разрешена")
    c.УЗ_Чеки.ЗавершитьНеудачныйЧек(ссылка, резерв.ИдентификаторОперации, False)
    т.проверить("Требует сверки" in str(c.УЗ_Чеки.СведенияОЧеке(ссылка))
                and "уже пробивается или пробит" in str(c.УЗ_Чеки.ЗарезервироватьЧек(ссылка).Причина),
                "неизвестный результат ККТ: резерв требует сверки, повтор запрещён")
    # Поздний отказ от прежней попытки не снимает резерв новой.
    c.УЗ_Чеки.ЗавершитьНеудачныйЧек(ссылка, "чужая-попытка", True)
    т.проверить("Требует сверки" in str(c.УЗ_Чеки.СведенияОЧеке(ссылка)), "чужой ответ не снимает резерв")
    c.УЗ_Чеки.СнятьРезервЧека(ссылка)  # тестовый пользователь — руководитель, ККТ в сценарии не вызывается
    резерв = c.УЗ_Чеки.ЗарезервироватьЧек(ссылка)
    т.проверить(str(резерв.Причина) == "", "руководитель снял резерв после сверки")
    ответ = структура(c, НомерЧека=17, НомерСмены=3, ФискальныйПризнак="1234567890", ДатаЧека=ф.день(0, 11),
                      Устройство="Эмулятор", Сумма=4000, ТипРасчета="Приход", Электронно=False)
    ответ.Вставить("ИдентификаторОперации", резерв.ИдентификаторОперации)
    ош = str(c.УЗ_Чеки.ОтметитьЧек(ссылка, ответ))
    т.проверить(ош == "", "ответ кассы отмечен в регистре чеков", ош)
    сведения = str(c.УЗ_Чеки.СведенияОЧеке(ссылка))
    т.проверить("№ 17" in сведения and "смена 3" in сведения and "ФП 1234567890" in сведения,
                "форма покажет номер, смену и фискальный признак", сведения)
    т.проверить("уже пробит" in str(c.УЗ_Чеки.ДанныеЧека(ссылка, "Наличные").Причина),
                "пробитый чек повторно не пробивается")
    т.проверить("уже отмечен" in str(c.УЗ_Чеки.ОтметитьЧек(ссылка, ответ)),
                "второй ответ кассы не перезаписывает отметку")
    # A11-01 (аудит 2.3.0.2): приход с пробитым чеком не распроводится, не удаляется, сумма не меняется
    ош, сообщ = ф.записать(ссылка.ПолучитьОбъект(), "ОтменаПроведения")
    т.проверить(ош is not None and any("уже пробит чек" in с for с, _ in сообщ),
                "приход с пробитым чеком не распроводится", (ош, сообщ))
    правка = ссылка.ПолучитьОбъект()
    правка.РасшифровкаПлатежа.Получить(0).Сумма = 900
    ош, сообщ = ф.записать(правка)
    т.проверить(ош is not None and any("менять нельзя" in с for с, _ in сообщ),
                "в приходе с пробитым чеком сумма строки не меняется", (ош, сообщ))
    c.ПолучитьСообщенияПользователю(True)
    try:
        ссылка.ПолучитьОбъект().Удалить()
        удален = "удалён"
    except Exception as ошибка:
        удален = ""
        т.проверить("уже пробит чек" in str(ошибка) + " ".join(str(с.Текст) for с in c.ПолучитьСообщенияПользователю(True)),
                    "приход с пробитым чеком не удаляется", str(ошибка))
    т.проверить(удален == "", "приход с пробитым чеком не удаляется")

    # ── права: пробивают менеджер и руководитель, педагог — нет ──
    рег = c.Метаданные.РегистрыСведений.УЗ_ЧекиККТ
    роли = c.Метаданные.Роли
    т.проверить(c.ПравоДоступа("Изменение", рег, роли.УЗ_ОсновнаяРоль)
                and c.ПравоДоступа("Изменение", рег, роли.УЗ_Руководитель)
                and not c.ПравоДоступа("Просмотр", рег, роли.УЗ_Педагог),
                "чеки пробивают менеджер и руководитель; педагогу регистр чеков недоступен")

    # ── возврат прихода ──
    возврат = д.документ("УЗ_РасходДенег", Дата=ф.день(0, 10), Организация=орг, Касса=касса, ФизЛицо=сын,
                         ПредметОбучения=математика, СуммаДокумента=200,
                         ВидОперации=перечисления.УЗ_ВидыОпераций.КассаУченики)
    ош = д.записать(возврат)
    т.проверить(ош is None, "возврат сыну 200 из аванса по математике проведён", ош)
    if ош is not None:
        return
    дв = c.УЗ_Чеки.ДанныеЧека(возврат.Ссылка, "Наличные")
    т.проверить(str(дв.Причина) == "" and str(дв.ТипРасчета) == "ВозвратПрихода"
                and позиции(дв) == [(мат, 200.0, "ПредоплатаПолная", "Услуга")]
                and str(дв.ПокупательНомер) == "+79123456789",
                "возврат — чек «Возврат прихода»: аванс по математике, телефон получателя (платила мама, В38)",
                "%s %s %s" % (дв.Причина, дв.ТипРасчета, позиции(дв)))
    пв = c.УЗ_СредаКасса.ПараметрыЧекаХозяина(дв)
    т.проверить(имя(пв.ТипРасчета) == "ВозвратДенежныхСредств",
                "в кассу хозяина — «Возврат денежных средств»", имя(пв.ТипРасчета))
    т.проверить('OperationType="2"' in пакет_драйвера(c, пв), "пакет кассы: возврат прихода (2)")


    # Тот же урок, два ученика: независимые ключи, повтор по одному ученику запрещён.
    урок = ф.урок(ф.педагог("для резервов"), ф.день(1, 10), Организация=орг)
    ошибка, сообщения = ф.записать(урок, "Запись")
    т.проверить(ошибка is None, "урок для проверки ключей резерва записан", (ошибка, сообщения))
    if ошибка is not None:
        return

    def убрать_резервы_урока():
        набор = c.РегистрыСведений.УЗ_ЧекиККТ.СоздатьНаборЗаписей()
