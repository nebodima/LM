"""Мост в учёт программы, вкладка «Деньги» закрытия смены (05.10.2026, docs/мост_в_учёт_хозяина.md).

Мама платит за сына 1 000 и 500 наличными в одну кассу, вечером ей возвращают 200. Режим «каждым документом» без связи
мамы с контрагентом — оформлять нельзя («свяжите на вкладке «Люди»»); связали — каждый приход и возврат становится
документом программы (ПКО/РКО, в УНФ «Поступление в кассу»/«Расход из кассы») на её контрагента, проведённым, с той же
суммой. Повтор — ничего не делает. Изменили сумму прихода — «изменено после оформления», повтор переписывает тот же
документ программы. Отменили проведение прихода — документ программы помечен на удаление, связь снята.
Режим «за день»: приходы дня — один документ программы на общего контрагента «Физические лица (учёт занятий)» на сумму
дня; новый приход в тот же день — тот же документ переписан на новую сумму.

    python tools\\тесты\\тест_мост_деньги.py --база=C:\\1c_bases\\UZ_BP_Q --пользователь=1
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from фабрика import Фабрика  # noqa: E402

МЕТКА = "_Тест мост деньги"


def сценарий(т):
    c = т.c
    ф = Фабрика(т, МЕТКА)
    мост = c.УЗ_СредаМост
    по_дням, по_документам = мост.РежимЗаДень(), мост.РежимКаждымДокументом()

    def одно(первое, второе):
        return первое is not None and второе is not None and str(c.XMLString(первое)) == str(c.XMLString(второе))

    # организация базы: документу программы нужна её учётная политика (у тестовой организации её нет)
    орг = c.РегистрыСведений.УЗ_Настройки.Настройки().Организация
    if орг.Пустая():
        орг = ф.организация("студия")
    касса = ф.элемент("УЗ_Кассы", "касса моста денег", Организация=орг)
    мама = ф.элемент("УЗ_ФизЛица", "Мама Деньгова")
    сын = ф.элемент("УЗ_ФизЛица", "Сын Деньгов")
    созданные = []                      # документы программы — убрать в конце (сначала документы, потом контрагенты)

    def убрать_программу():
        for ссылка in reversed(созданные):
            т.удалить_объект(ссылка, загрузка=True)
    т.убрать(убрать_программу, "документы и контрагенты программы")

    наши = []                           # наши документы — их связи снять в конце
    общий_был = мост.СвязанныйОбъект(None, "ОбщийКонтрагент") is not None

    def связи_убрать():
        for объект in [мама, касса] + [д.Ссылка for д in наши]:
            набор = c.РегистрыСведений.УЗ_СвязиСУчетомХозяина.СоздатьНаборЗаписей()
            набор.Отбор.Объект.Установить(объект)
            набор.Записать()
        if not общий_был:               # общий контрагент создан тестом и удаляется — его связь тоже
            мост.Отвязать(None, "ОбщийКонтрагент")
    т.убрать(связи_убрать, "связи моста")

    def приход(сумма, час):
        д = ф.приход(сын, сумма, Организация=орг, Касса=касса, Плательщик=мама, Дата=ф.день(0, час))
        ош, сообщ = ф.записать(д)
        т.проверить(ош is None, "приход %s проведён" % сумма, "%s %s" % (ош, сообщ))
        наши.append(д)
        return д

    первый, второй = приход(1000, 9), приход(500, 10)
    возврат = c.Документы.УЗ_РасходДенег.СоздатьДокумент()
    возврат.Заполнить(сын)
    возврат.Дата, возврат.Организация, возврат.Касса = ф.день(0, 11), орг, касса
    возврат.Получатель, возврат.СуммаДокумента, возврат.Комментарий = мама, 200, МЕТКА
    ош, сообщ = ф.записать(возврат)
    т.проверить(ош is None, "возврат маме проведён", "%s %s" % (ош, сообщ))
    наши.append(возврат)

    начало, конец = ф.день(0), ф.день(0, 23, 59)

    # касса периода — на вкладке «Люди», если у программы есть справочник касс (УНФ, УТ; в Бухгалтерии касса — счёт)
    кассы_есть = str(мост.СправочникДляСвязи(мост.РольКасса())) != ""
    люди = мост.ЛюдиДляСвязи(орг, начало, конец, False)
    роли = {str(c.XMLString(люди.Получить(н).ФизЛицо)): str(люди.Получить(н).Роль) for н in range(люди.Количество())}
    т.проверить(роли.get(str(c.XMLString(касса))) == (str(мост.РольКасса()) if кассы_есть else None),
                "касса периода на вкладке «Люди» — только при справочнике касс у программы",
                "%s %s" % (кассы_есть, роли.get(str(c.XMLString(касса)))))
    if кассы_есть:                      # связываем с кассой программы этой организации, как сделает менеджер
        мета = c.Метаданные.Справочники.Кассы   # УТ: владелец — организация; УНФ: касса общая для организаций
        поле = ("Т.Владелец = &Организация И " if мета.Владельцы.Количество() > 0 else "")
        запрос = c.NewObject("Запрос")
        запрос.Текст = ("ВЫБРАТЬ ПЕРВЫЕ 1 Т.Ссылка КАК Ссылка ИЗ Справочник.Кассы КАК Т "
                        "ГДЕ %sНЕ Т.ПометкаУдаления" % поле)
        запрос.УстановитьПараметр("Организация", орг)
        выборка = запрос.Выполнить().Выбрать()
        т.проверить(выборка.Следующий(), "у организации есть касса программы")
        ошибка = мост.Связать(касса, мост.РольКасса(), выборка.Ссылка)
        т.проверить(str(ошибка) == "", "наша касса связана с кассой программы", str(ошибка))

    def деньги(режим):
        итог = {}
        таблица = мост.ДеньгиДляОформления(орг, касса, начало, конец, режим)
        for н in range(таблица.Количество()):
            с = таблица.Получить(н)
            итог[str(c.XMLString(с.Документ))] = с
        return итог

    def строка(д, режим):
        return деньги(режим).get(str(c.XMLString(д.Ссылка)))

    def массив(*документы):
        м = c.NewObject("Массив")
        for д in документы:
            м.Добавить(д.Ссылка)
        return м

    def оформить(режим, *документы):
        итог = мост.Оформить(массив(*документы), режим)
        ошибки = [str(итог.Ошибки.Получить(н).Текст) for н in range(итог.Ошибки.Количество())]
        return int(итог.Оформлено), ошибки

    def запомнить(ссылка):
        if ссылка is not None and not any(одно(ссылка, с) for с in созданные):
            созданные.append(ссылка)

    # ── каждым документом: мама не связана ──
    с = строка(первый, по_документам)
    т.проверить(с is not None and not с.МожноОформить and "не связан" in str(с.Состояние),
                "без связи мамы с контрагентом оформлять нельзя", с and str(с.Состояние))
    оформлено, ошибки = оформить(по_документам, первый)
    т.проверить(оформлено == 0 and ошибки and "Люди" in ошибки[0], "«Оформить» без связи — причина у строки", ошибки)

    создано = мост.СоздатьУХозяина(мама, мост.РольПлательщик())
    контрагент = создано.Ссылка
    т.проверить(str(создано.Ошибка) == "" and контрагент is not None, "мама связана с новым контрагентом",
                str(создано.Ошибка))
    if контрагент is None:
        return
    партнер = контрагент.Партнер if c.Метаданные.Справочники.Контрагенты.Реквизиты.Найти("Партнер") is not None else None
    if партнер is not None:
        созданные.insert(0, партнер)
    созданные.insert(0 if партнер is None else 1, контрагент)

    оформлено, ошибки = оформить(по_документам, первый, второй, возврат)
    т.проверить(оформлено == 3 and not ошибки, "каждым документом: три документа программы", "%s %s" % (оформлено, ошибки))
    if оформлено != 3:
        return
    сейчас = деньги(по_документам)
    for д, сумма, вид in ((первый, 1000, "Приход"), (второй, 500, "Приход"), (возврат, 200, "Возврат")):
        с = сейчас.get(str(c.XMLString(д.Ссылка)))
        док = с.ОбъектХозяина if с is not None else None
        запомнить(док)
        т.проверить(с is not None and str(с.Состояние) == "Оформлено" and док is not None and док.Проведен
                    and float(док.СуммаДокумента) == сумма and одно(док.Контрагент, контрагент),
                    "%s %s — документ программы проведён на контрагента мамы" % (вид, сумма),
                    с and "%s %s %s" % (с.Состояние, док and док.Проведен, док and док.СуммаДокумента))
    док_первого = сейчас[str(c.XMLString(первый.Ссылка))].ОбъектХозяина
    т.проверить(not одно(док_первого, сейчас[str(c.XMLString(второй.Ссылка))].ОбъектХозяина),
                "два прихода — два документа программы")

    оформлено, ошибки = оформить(по_документам, первый, второй, возврат)
    т.проверить(оформлено == 0 and not ошибки, "повтор ничего не трогает", "%s %s" % (оформлено, ошибки))
    т.проверить(одно(строка(первый, по_документам).ОбъектХозяина, док_первого), "повтор не плодит документы")

    первый.СуммаДокумента = 1200
    первый.РасшифровкаПлатежа.Очистить()
    ош, сообщ = ф.записать(первый)
    т.проверить(ош is None, "приход исправлен на 1 200", "%s %s" % (ош, сообщ))
    с = строка(первый, по_документам)
    т.проверить(с.МожноОформить and "изменено" in str(с.Состояние).lower(), "изменённый приход — «изменено после "
                "оформления»", str(с.Состояние))
    оформить(по_документам, первый)
    с = строка(первый, по_документам)
    т.проверить(одно(с.ОбъектХозяина, док_первого) and float(с.ОбъектХозяина.СуммаДокумента) == 1200
                and str(с.Состояние) == "Оформлено", "повтор переписал тот же документ программы на 1 200",
                "%s %s" % (с.Состояние, с.ОбъектХозяина.СуммаДокумента))

    # отменяем первый приход: на второй (последний до возврата) в УНФ опирается возврат — его программа не отменит
    ош, сообщ = ф.записать(первый, "ОтменаПроведения")
    т.проверить(ош is None, "первый приход отменён", ош)
    док_первого_отм = строка(первый, по_документам).ОбъектХозяина
    оформить(по_документам, первый)
    осталось = строка(первый, по_документам)
    т.проверить(док_первого_отм.ПометкаУдаления and осталось is None,
                "отменённый приход — документ программы помечен на удаление, связь снята",
                осталось and str(осталось.Состояние))
    ош, сообщ = ф.записать(первый)
    т.проверить(ош is None, "первый приход снова проведён", ош)

    # ── за день: один документ на общего контрагента ──
    for д in (первый, второй):
        мост.Отвязать(д.Ссылка, мост.РольДокумент())
    оформлено, ошибки = оформить(по_дням, первый)
    т.проверить(оформлено == 1 and not ошибки, "за день: один документ программы", "%s %s" % (оформлено, ошибки))
    с1, с2 = строка(первый, по_дням), строка(второй, по_дням)
    день = с1.ОбъектХозяина
    запомнить(день)
    if день is not None and not общий_был:
        запомнить(день.Контрагент)
    т.проверить(одно(день, с2.ОбъектХозяина) and float(день.СуммаДокумента) == 1700 and день.Проведен
                and "учёт занятий" in str(день.Контрагент.Наименование),
                "приходы дня — один документ на 1 700 на «Физические лица (учёт занятий)»",
                "%s %s" % (день and день.СуммаДокумента, день and день.Контрагент.Наименование))
    третий = приход(300, 12)
    оформить(по_дням, третий)
    т.проверить(одно(строка(третий, по_дням).ОбъектХозяина, день) and float(день.СуммаДокумента) == 2000,
                "новый приход дня — тот же документ переписан на 2 000", день.СуммаДокумента)


if __name__ == "__main__":
    запустить("мост_деньги", сценарий)
