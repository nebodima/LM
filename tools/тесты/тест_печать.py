"""Печать ПКО, РКО и начисления бонусов (УЗ_ext).

Проверяет обе дороги печати:
  * своя печать (у хозяина нет БСП): УЗ_Печать.СформироватьСвоейПечатью — её открывает форма
    УЗ_ПечатнаяФорма;
  * БСП хозяина (УНФ): УправлениеПечатью.СформироватьПечатныеФормы с нашим менеджером печати —
    то же, что делает форма «Печать документов» из подменю «Печать».
Плюс офлайн: каждый параметр области «Шапка» макетов ПКО/РКО заполняется кодом менеджера.

Данные создаёт сам (ученик, два ПКО, РКО, начисление бонусов) и удаляет за собой.

    python tools\\тесты\\тест_печать.py --база=C:\\1c_bases\\UZ_UNF_C
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ДОКУМЕНТЫ = os.path.join(КОРЕНЬ, "src_ext", "Documents")


def параметры_макета(документ, макет):
    т = open(os.path.join(ДОКУМЕНТЫ, документ, "Templates", макет, "Ext", "Template.xml"), encoding="utf-8-sig").read()
    return set(re.findall(r"<parameter>([^<]+)</parameter>", т))


def присвоенные_параметры(документ):
    т = open(os.path.join(ДОКУМЕНТЫ, документ, "Ext", "ManagerModule.bsl"), encoding="utf-8-sig").read()
    return set(re.findall(r"Шапка\.Параметры\.(\w+)\s*=", т))


def проверить_макеты(т):
    for документ, макет in (("УЗ_ПриходДенег", "ПечатьПКО"), ("УЗ_РасходДенег", "ПечатьРКО")):
        не_заполнены = параметры_макета(документ, макет) - присвоенные_параметры(документ)
        т.проверить(not не_заполнены, "%s: все параметры макета %s заполняются кодом" % (документ, макет),
                    sorted(не_заполнены))


def сценарий(т):
    c = т.c
    проверить_макеты(т)

    организация = c.Справочники.Организации.НайтиПоРеквизиту("ИНН", "7725192493")
    if организация.Пустая():
        выборка = т.выбрать("ВЫБРАТЬ ПЕРВЫЕ 1 О.Ссылка КАК Ссылка ИЗ Справочник.Организации КАК О ГДЕ О.ИНН <> \"\"")
        if выборка.Количество() > 0:
            организация = выборка.Получить(0).Ссылка
        else:
            # в копии БП нет организации с ИНН — заводим свою на время теста
            новая = c.Справочники.Организации.СоздатьЭлемент()
            новая.Наименование = "УЗ тест печати ООО"
            новая.ИНН = "7725192493"
            новая.ОбменДанными.Загрузка = True
            новая.Записать()
            организация = новая.Ссылка
            т.убрать(lambda: т.удалить_объект(организация), "тестовая организация")
    инн = c.УЗ_Общий.ЗначениеРеквизита(организация, "ИНН", "")
    окпо = c.УЗ_Общий.ЗначениеРеквизита(организация, "КодПоОКПО", "")

    ученик = c.Справочники.УЗ_ФизЛица.СоздатьЭлемент()
    ученик.Наименование = "УЗ тест печати Иванов Пётр"
    ученик.Записать()
    ученик = ученик.Ссылка
    т.убрать(lambda: т.удалить_объект(ученик), "ученик")

    def документ(вид, сумма, **реквизиты):
        о = getattr(c.Документы, вид).СоздатьДокумент()
        о.Дата = c.ТекущаяДатаСеанса()
        о.Организация = организация
        о.ФизЛицо = ученик
        о.СуммаДокумента = сумма
        о.НазначениеПлатежа = "Оплата занятий (тест печати)"
        for к, в in реквизиты.items():
            setattr(о, к, в)
        о.Записать(c.РежимЗаписиДокумента.Запись)
        ссылка = о.Ссылка
        т.убрать(lambda: т.удалить_объект(ссылка), вид)
        return ссылка

    пко1 = документ("УЗ_ПриходДенег", 1234.56)
    пко2 = документ("УЗ_ПриходДенег", 700)
    рко = документ("УЗ_РасходДенег", 500)
    бонусы = c.Документы.УЗ_НачислениеБонусов.СоздатьДокумент()
    бонусы.Дата = c.ТекущаяДатаСеанса()
    бонусы.СуммаБонусов = 150
    бонусы.Комментарий = "тест печати"
    бонусы.Записать(c.РежимЗаписиДокумента.Запись)
    бонусы = бонусы.Ссылка
    т.убрать(lambda: т.удалить_объект(бонусы), "начисление бонусов")

    # ── своя печать (как без БСП) ──
    р = c.УЗ_Печать.СформироватьСвоейПечатью("Документ.УЗ_ПриходДенег", "ПКО", т.массив(пко1, пко2))
    тд = р.ТабличныйДокумент
    т.проверить(р.ПечатныхФорм == 1 and тд.ВысотаТаблицы > 30, "своя печать ПКО: табличный документ сформирован",
                "форм %s, строк %s" % (р.ПечатныхФорм, тд.ВысотаТаблицы))
    т.проверить(р.Заголовок == "Приходный кассовый ордер", "своя печать ПКО: заголовок окна", р.Заголовок)
    т.проверить(тд.Области.Найти("Документ_1") is not None and тд.Области.Найти("Документ_2") is not None,
                "своя печать ПКО: два документа — две размеченные области (по странице на ордер)")
    try:
        страниц = тд.КоличествоСтраниц()
        т.проверить(страниц >= 2, "своя печать ПКО: страниц не меньше двух", страниц)
    except Exception as е:  # без принтера платформа может не посчитать страницы
        print("  (число страниц не посчитано: %s)" % str(е)[:120])
    т.проверить(bool(инн) and т.найти_текст(тд, инн), "ПКО: ИНН организации в шапке", инн)
    if окпо:
        т.проверить(т.найти_текст(тд, окпо), "ПКО: код по ОКПО", окпо)
    т.проверить(т.найти_текст(тд, "Одна тысяча двести тридцать четыре рубля 56 копеек"), "ПКО: сумма прописью")
    т.проверить(т.найти_текст(тд, "Иванов Пётр"), "ПКО: принято от — ученик")
    т.проверить(not т.найти_текст(тд, "50.01") and not т.найти_текст(тд, "62.01"),
                "ПКО: счета 50.01/62 не зашиты в печать")

    р = c.УЗ_Печать.СформироватьСвоейПечатью("Документ.УЗ_РасходДенег", "РКО", рко)
    тд = р.ТабличныйДокумент
    т.проверить(р.ПечатныхФорм == 1 and тд.ВысотаТаблицы >= 35, "своя печать РКО (КО-2): сформирован",
                "строк %s" % тд.ВысотаТаблицы)
    т.проверить(т.найти_текст(тд, "РАСХОДНЫЙ КАССОВЫЙ ОРДЕР") and т.найти_текст(тд, "0310002"),
                "РКО: тексты макета КО-2 на месте")
    т.проверить(т.найти_текст(тд, инн) and т.найти_текст(тд, "Пятьсот рублей 00 копеек")
                and т.найти_текст(тд, "Иванов Пётр"), "РКО: ИНН, сумма прописью, «Выдать»")

    р = c.УЗ_Печать.СформироватьСвоейПечатью("Документ.УЗ_НачислениеБонусов", "НачислениеБонусов", бонусы)
    тд = р.ТабличныйДокумент
    т.проверить(р.ПечатныхФорм == 1 and тд.ВысотаТаблицы > 5 and т.найти_текст(тд, "Начисление бонусов")
                and т.найти_текст(тд, "150"), "своя печать начисления бонусов: заголовок и сумма",
                "строк %s" % тд.ВысотаТаблицы)

    try:
        c.УЗ_Печать.СформироватьСвоейПечатью("Справочник.Организации", "ПКО", организация)
        т.проверить(False, "своя печать не печатает чужие менеджеры")
    except Exception:
        т.проверить(True, "своя печать не печатает чужие менеджеры")

    # ── печать через БСП хозяина ──
    форма = c.УЗ_Среда.ФормаПечатиХозяина()
    if not форма:
        print("  (у хозяина нет БСП — проверена только своя печать)")
        return
    т.проверить(форма == "ОбщаяФорма.ПечатьДокументов", "УЗ_Среда: у хозяина есть форма печати БСП", форма)
    for вид, макет, объекты, текст in (("УЗ_ПриходДенег", "ПКО", т.массив(пко1, пко2), "ПРИХОДНЫЙ КАССОВЫЙ ОРДЕР"),
                                       ("УЗ_РасходДенег", "РКО", т.массив(рко), "РАСХОДНЫЙ КАССОВЫЙ ОРДЕР"),
                                       ("УЗ_НачислениеБонусов", "НачислениеБонусов", т.массив(бонусы),
                                        "Начисление бонусов")):
        итог = c.УправлениеПечатью.СформироватьПечатныеФормы("Документ." + вид, макет, объекты, c.NewObject("Структура"))
        коллекция = итог.КоллекцияПечатныхФорм
        тд = коллекция.Получить(0).ТабличныйДокумент if коллекция.Количество() == 1 else None
        т.проверить(тд is not None and тд.ВысотаТаблицы > 0 and т.найти_текст(тд, текст),
                    "БСП хозяина: %s сформирован через наш менеджер печати" % макет)
        if тд is not None and макет != "НачислениеБонусов":
            т.проверить(т.найти_текст(тд, инн), "БСП хозяина: %s — ИНН организации" % макет)
            т.проверить(итог.ОбъектыПечати.Количество() == объекты.Количество(),
                        "БСП хозяина: %s — области документов размечены для комплекта" % макет,
                        итог.ОбъектыПечати.Количество())


if __name__ == "__main__":
    запустить("печать", сценарий)
