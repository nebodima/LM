"""Сводка панели ученика (визуальный аудит 28.09.2026, правка №9): деньги по предметам со знаком, абонементы
«Осталось уроков 3 из 8», ближайший урок — Обработки.УЗ_ПанельУченика.СводкаУченика / ТекстОстаткаАбонементаСводки.

Было: остаток денег — узкая колонка среди 11, «Задолженность 5 600,00» у переплатившего, «Осталось уроков 0 из 8»
рядом с пустыми колонками действий. Стало: сводка над таблицами; цвет плюса/минуса — палитра
(УЗ_ОбщийКлиентСервер.ЦветПлюсаДенег / ЦветМинусаДенег), знак — ПредставлениеОстаткаДенег.

Проверяется:
  1. долг за проведённый урок — в «Остатки» минусом по предмету урока, текст «−800,00»; переплата — «+1 800,00»;
  2. абонемент на 8 занятий — «Осталось уроков 8 из 8», после урока по абонементу — «7 из 8»; абонемент на 2 часа —
     «Осталось 2:00 из 2:00» (часы — ч:мм);
  3. будущий урок ученика — «БлижайшийУрок» с его датой;
  4. палитра: плюс — зелёный (G > R), минус — красный (R > G).
Мутация: в СводкаУченика убрать ИМЕЮЩИЕ … <> 0 — нулевой предмет попадает в сводку («только ненулевые» краснеет);
в ТекстОстаткаАбонементаСводки вернуть Остаток.Текст — краснеют «Осталось уроков …».

    python tools\\тесты\\тест_сводка_ученика.py --база=C:\\1c_bases\\UZ_UNF_B
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from фабрика import Фабрика  # noqa: E402

МЕТКА = "УЗ тест сводки ученика"


def _список(массив):
    return [массив.Получить(поз) for поз in range(массив.Количество())]


def сценарий(т):
    c = т.c
    ф = Фабрика(т, МЕТКА)
    панель = c.Обработки.УЗ_ПанельУченика
    м = c.УЗ_ОбщийКлиентСервер
    педагог = ф.педагог()
    ученик = ф.ученик("ученик Сводкин")
    предмет = ф.элемент("УЗ_ПредметыОбучения", "вокал сводки")
    предмет2 = ф.элемент("УЗ_ПредметыОбучения", "гитара сводки")
    тариф = ф.элемент("УЗ_Тарифы", "тариф сводки")
    ф.цена_тарифа(тариф, ф.день(-400), 800, уроков=1)
    по_урокам = ф.абонемент(ученик, "8 занятий", КоличествоЗанятий=8, ПредметОбучения=предмет2, ЦенаАбонемента=8000)
    ф.абонемент(ученик, "2 часа", КоличествоЧасов=2, ПредметОбучения=предмет2, ЦенаАбонемента=2000,
                ДатаНачала=ф.день(-20), ДатаАктивации=ф.день(-20))

    def сводка():
        с = панель.СводкаУченика(ученик)
        остатки = {о.Предмет: round(float(о.Остаток), 2) for о in _список(с.Остатки)}
        абонементы = {а.Абонемент.Наименование: а.Текст for а in _список(с.Абонементы)}
        return с, остатки, абонементы

    с, остатки, абонементы = сводка()
    имя8 = по_урокам.Наименование
    т.проверить(абонементы.get(имя8) == "Осталось уроков 8 из 8", "абонемент на 8 занятий — «Осталось уроков 8 из 8»",
                абонементы)
    т.проверить(any(текст == "Осталось 2:00 из 2:00" for текст in абонементы.values()),
                "абонемент на 2 часа — «Осталось 2:00 из 2:00» (ч:мм)", абонементы)
    т.проверить(not остатки, "без уроков и оплат — денег в сводке нет (нулевые предметы не показываются)", остатки)

    строка = dict(Ученик=ученик, Тариф=тариф, Явка=True, СписатьОплату=True)
    д = ф.урок(педагог, ф.день(-2, 10), 1, [строка], ПредметОбучения=предмет)
    ошибка, сообщения = ф.записать(д, "Проведение")
    т.проверить(ошибка is None, "урок по тарифу проведён", "%s %s" % (ошибка, сообщения))
    д2 = ф.урок(педагог, ф.день(-1, 10), 1, [dict(строка, Абонемент=по_урокам)], ПредметОбучения=предмет2)
    ошибка, сообщения = ф.записать(д2, "Проведение")
    т.проверить(ошибка is None, "урок по абонементу проведён", "%s %s" % (ошибка, сообщения))
    будущий = ф.урок(педагог, ф.день(3, 18, 30), 1, [строка], ПредметОбучения=предмет)
    ошибка, сообщения = ф.записать(будущий, "Запись")
    т.проверить(ошибка is None, "будущий урок записан", "%s %s" % (ошибка, сообщения))

    с, остатки, абонементы = сводка()
    имя_предмета = предмет.Наименование
    т.проверить(остатки.get(имя_предмета) == -800.0, "долг за урок — минус по предмету урока (−800)", остатки)
    т.проверить(абонементы.get(имя8) == "Осталось уроков 7 из 8", "после урока по абонементу — «Осталось уроков 7 из 8»",
                абонементы)
    т.проверить(с.БлижайшийУрок is not None and с.БлижайшийУрок.Урок.Номер == будущий.Ссылка.Номер,
                "ближайший урок — будущий урок ученика")

    т.проверить(м.ПредставлениеОстаткаДенег(-800) == "−800,00"
                and м.ПредставлениеОстаткаДенег(1800).replace(" ", " ") == "+1 800,00"
                and м.ПредставлениеОстаткаДенег(0) == "0,00",
                "знак остатка: «−800,00», «+1 800,00», «0,00»",
                "%s %s %s" % (м.ПредставлениеОстаткаДенег(-800), м.ПредставлениеОстаткаДенег(1800),
                              м.ПредставлениеОстаткаДенег(0)))
    плюс, минус = м.ЦветПлюсаДенег(), м.ЦветМинусаДенег()
    т.проверить(плюс.Зеленый > плюс.Красный and минус.Красный > минус.Зеленый,
                "палитра: плюс денег — зелёный, минус — красный")
    т.проверить(м.КраткоеФИО("Воронцова Елена Сергеевна") == "Воронцова Е. С." and м.КраткоеФИО("Анна") == "Анна",
                "краткое ФИО для календаря: «Воронцова Е. С.»")


if __name__ == "__main__":
    запустить("сводка_ученика", сценарий)
