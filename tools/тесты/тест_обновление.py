"""Обновление данных (регистр УЗ_ВерсииДанных, модуль УЗ_ОбновлениеДанных).

    python tools\\тесты\\тест_обновление.py --база=C:\\1c_bases\\UZ_UNF_B

Что проверяет: сброс версии → координатор проходит шаги, версия = актуальной, замок отпущен,
ошибок нет, шаг 1 заполнил пустые настройки (касса, организация, периоды оповещений);
повторный вызов ничего не делает (стёртое после обновления не возвращается) и быстрый
(≤ 0,1 с); свежий замок чужого сеанса — координатор уходит молча; брошенный замок — занимает.
Мутация (проверена 27.09.2026): в координаторе убран вызов ОтметитьВыполненныйШаг → тест красный.
Бюджет 10 с. За собой убирает: запись настроек и запись версии возвращаются как были.
"""
import atexit
import datetime
import os
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import com_сеанс as к  # noqa: E402

БЮДЖЕТ = 10
РЕСУРСЫ_НАСТРОЕК = ("Организация", "Касса", "ИспользоватьОкругление", "ТребоватьОписаниеКНеоплаченнымУрокам",
                    "ТребоватьОписаниеКНеоплаченнымУрокамС", "ИспользоватьОповещения", "ПериодОповещения",
                    "ОповещатьОЗадолженности")


def снимок_записи(менеджер, ресурсы):
    менеджер.Прочитать()
    if not менеджер.Выбран():
        return None
    return {р: getattr(менеджер, р) for р in ресурсы}


def вернуть_запись(c, регистр, снимок):
    набор = getattr(c.РегистрыСведений, регистр).СоздатьНаборЗаписей()
    if снимок is not None:
        запись = набор.Добавить()
        for р, з in снимок.items():
            if hasattr(з, "year") and з.year < 1900:
                continue            # пустую дату через COM не передать — остаётся пустой
            setattr(запись, р, з)
    набор.Записать()


def записать_версию(c, версия, начато=None):
    запись = c.РегистрыСведений.УЗ_ВерсииДанных.СоздатьМенеджерЗаписи()
    запись.Версия = версия
    if начато is not None:
        запись.ОбновлениеНачато = начато
    запись.Записать()


def главный():
    к.настроить_вывод()
    c = к.сеанс()
    обн = c.УЗ_ОбновлениеДанных
    прежние_настройки = снимок_записи(c.РегистрыСведений.УЗ_Настройки.СоздатьМенеджерЗаписи(), РЕСУРСЫ_НАСТРОЕК)
    прежняя_версия = снимок_записи(c.РегистрыСведений.УЗ_ВерсииДанных.СоздатьМенеджерЗаписи(),
                                   ("Версия", "ОбновлениеНачато", "ОшибкиОбновления"))

    основная_касса = c.Справочники.УЗ_Кассы.ОсновнаяКасса
    прежний_флаг = основная_касса.ПолучитьОбъект().Основная

    def уборка():
        касса = основная_касса.ПолучитьОбъект()
        if касса.Основная != прежний_флаг:
            касса.Основная = прежний_флаг
            касса.Записать()
        вернуть_запись(c, "УЗ_Настройки", прежние_настройки)
        вернуть_запись(c, "УЗ_ВерсииДанных", прежняя_версия)
    atexit.register(уборка)

    актуальная = обн.АктуальнаяВерсияДанных()
    к.проверка("актуальная версия данных ≥ 1", актуальная >= 1, актуальная)

    # 1. чистая база: настроек нет, версия 0 → координатор проходит все шаги
    c.РегистрыСведений.УЗ_Настройки.СоздатьНаборЗаписей().Записать()
    записать_версию(c, 0)
    н = time.time()
    обн.ОбновитьДанныеПриНеобходимости()
    print("первый прогон координатора %.2f с" % (time.time() - н))
    с = обн.СостояниеОбновления()
    к.проверка("версия после обновления = актуальной", с.Версия == актуальная, с.Версия)
    к.проверка("замок отпущен", к.как_дата(с.ОбновлениеНачато) is None, с.ОбновлениеНачато)
    к.проверка("ошибок обновления нет", с.Ошибки == "", с.Ошибки)
    настройки = c.РегистрыСведений.УЗ_Настройки.Настройки()
    к.проверка("шаг 1: касса по умолчанию = Основная касса",
               c.String(настройки.Касса) == c.String(c.Справочники.УЗ_Кассы.ОсновнаяКасса), c.String(настройки.Касса))
    есть_организации = c.Справочники.Организации.Выбрать().Следующий()
    к.проверка("шаг 1: организация по умолчанию заполнена",
               c.ЗначениеЗаполнено(настройки.Организация) or not есть_организации)
    к.проверка("шаг 1: период оповещений 300 с, задолженность за 2 дня",
               настройки.ПериодОповещения == 300 and настройки.ОповещатьОЗадолженности == 2)
    запрос = c.NewObject("Запрос")
    запрос.Текст = "ВЫБРАТЬ ПЕРВЫЕ 1 К.Ссылка КАК Ссылка ИЗ Справочник.УЗ_Кассы КАК К ГДЕ К.Основная И НЕ К.ПометкаУдаления"
    к.проверка("шаг 1: в базе есть касса с отметкой «Основная»", not запрос.Выполнить().Пустой())

    # 2. повторный вызов ничего не делает и быстрый
    набор = c.РегистрыСведений.УЗ_Настройки.СоздатьМенеджерЗаписи()
    набор.Прочитать()
    набор.ПериодОповещения = 0
    набор.Записать()
    н = time.time()
    for _ in range(10):
        обн.ОбновитьДанныеПриНеобходимости()
    за_вызов = (time.time() - н) / 10
    к.проверка("повторный вызов ≤ 0,1 с (%.4f с)" % за_вызов, за_вызов <= 0.1)
    к.проверка("повторный вызов не перезапускает шаги (стёртый период остался 0)",
               c.РегистрыСведений.УЗ_Настройки.Настройки().ПериодОповещения == 0)

    # 3. свежий замок чужого сеанса — уходим молча, версия не растёт.
    #    Отметка «через сутки» свежа при любом сдвиге пояса в COM (свежесть = позже «сейчас − 10 мин»)
    сейчас = datetime.datetime.now(datetime.timezone.utc)
    записать_версию(c, 0, сейчас + datetime.timedelta(days=1))
    обн.ОбновитьДанныеПриНеобходимости()
    к.проверка("свежий чужой замок: координатор не пошёл", обн.СостояниеОбновления().Версия == 0)

    # 4. брошенный замок (сутки назад) — занимаем и догоняем
    записать_версию(c, 0, сейчас - datetime.timedelta(days=1))
    обн.ОбновитьДанныеПриНеобходимости()
    с = обн.СостояниеОбновления()
    к.проверка("брошенный замок: координатор догнал версию", с.Версия == актуальная, с.Версия)
    к.проверка("брошенный замок: шаг 1 заполнил стёртый период снова",
               c.РегистрыСведений.УЗ_Настройки.Настройки().ПериодОповещения == 300)

    return к.итог(БЮДЖЕТ)


if __name__ == "__main__":
    sys.exit(главный())
