"""Обновление данных (регистр УЗ_ВерсииДанных, модуль УЗ_ОбновлениеДанных).

    python tools\\тесты\\тест_обновление.py --база=C:\\1c_bases\\UZ_UNF_B

Что проверяет: шагов обновления два — первичное заполнение (2.0) и плательщики (2.1, его данные проверяет
тест_плательщики), актуальная версия данных = 2; сброс версии → координатор проходит шаги, версия = актуальной, замок отпущен,
ошибок нет, шаг 1 заполнил пустые настройки (касса, организация, периоды оповещений) и записал границу
просмотра кассы менеджера (регистр УЗ_ГраницаПросмотраКассы был очищен);
повторный вызов ничего не делает (стёртое после обновления не возвращается) и быстрый
(≤ 0,1 с); свежий замок чужого сеанса — координатор уходит молча; брошенный замок — занимает.
Мутация (проверена 27.09.2026): в координаторе убран вызов ОтметитьВыполненныйШаг → тест красный.
Бюджет 10 с. За собой убирает: запись настроек и запись версии возвращаются как были, граница просмотра кассы
пересчитывается.
"""
import datetime
import os
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import как_дата, запустить  # noqa: E402

РЕСУРСЫ_НАСТРОЕК = ("Организация", "Касса", "ИспользоватьОкругление", "ТребоватьОписаниеКНеоплаченнымУрокам",
                    "ТребоватьОписаниеКНеоплаченнымУрокамС", "ИспользоватьОповещения", "ПериодОповещения",
                    "ОповещатьОЗадолженности")


def снимок_записи(менеджер, ресурсы):
    менеджер.Прочитать()
    if not менеджер.Выбран():
        return None
    return {р: getattr(менеджер, р) for р in ресурсы}


def вернуть_запись(c, регистр, снимок):
    набор = getattr(c.РегистрыСведений, регистр).СоздатьНаборЗаписей()
    if снимок is not None:
        запись = набор.Добавить()
        for р, з in снимок.items():
            if hasattr(з, "year") and з.year < 1900:
                continue            # пустую дату через COM не передать — остаётся пустой
            setattr(запись, р, з)
    набор.Записать()


def записать_версию(c, версия, начато=None):
    запись = c.РегистрыСведений.УЗ_ВерсииДанных.СоздатьМенеджерЗаписи()
    запись.Версия = версия
    if начато is not None:
        запись.ОбновлениеНачато = начато
    запись.Записать()


def сценарий(т):
    c = т.c
    обн = c.УЗ_ОбновлениеДанных
    прежние_настройки = снимок_записи(c.РегистрыСведений.УЗ_Настройки.СоздатьМенеджерЗаписи(), РЕСУРСЫ_НАСТРОЕК)
    прежняя_версия = снимок_записи(c.РегистрыСведений.УЗ_ВерсииДанных.СоздатьМенеджерЗаписи(),
                                   ("Версия", "ОбновлениеНачато", "ОшибкиОбновления"))

    основная_касса = c.Справочники.УЗ_Кассы.ОсновнаяКасса
    прежний_флаг = основная_касса.ПолучитьОбъект().Основная

    def уборка():
        касса = основная_касса.ПолучитьОбъект()
        if касса.Основная != прежний_флаг:
            касса.Основная = прежний_флаг
            касса.Записать()
        вернуть_запись(c, "УЗ_Настройки", прежние_настройки)
        вернуть_запись(c, "УЗ_ВерсииДанных", прежняя_версия)
        c.УЗ_ДатыЗапрета.ОбновитьГраницуПросмотраКассы()
    т.убрать(уборка, "настройки, версия данных, флаг основной кассы, граница просмотра кассы")

    актуальная = обн.АктуальнаяВерсияДанных()
    т.проверить(актуальная == 2, "2.1: два шага обновления (первичное заполнение 2.0, плательщики 2.1), версия 2",
                актуальная)

    # 1. чистая база: настроек и границы просмотра кассы нет, версия 0 → координатор проходит все шаги
    c.РегистрыСведений.УЗ_Настройки.СоздатьНаборЗаписей().Записать()
    c.РегистрыСведений.УЗ_ГраницаПросмотраКассы.СоздатьНаборЗаписей().Записать()
    записать_версию(c, 0)
    н = time.time()
    обн.ОбновитьДанныеПриНеобходимости()
    print("  (первый прогон координатора %.2f с)" % (time.time() - н))
    с = обн.СостояниеОбновления()
    т.проверить(с.Версия == актуальная, "версия после обновления = актуальной", с.Версия)
    т.проверить(как_дата(с.ОбновлениеНачато) is None, "замок отпущен", с.ОбновлениеНачато)
    т.проверить(с.Ошибки == "", "ошибок обновления нет", с.Ошибки)
    настройки = c.РегистрыСведений.УЗ_Настройки.Настройки()
    т.проверить(c.String(настройки.Касса) == c.String(c.Справочники.УЗ_Кассы.ОсновнаяКасса),
                "шаг 1: касса по умолчанию = Основная касса", c.String(настройки.Касса))
    есть_организации = c.Справочники.Организации.Выбрать().Следующий()
    т.проверить(c.ЗначениеЗаполнено(настройки.Организация) or not есть_организации,
                "шаг 1: организация по умолчанию заполнена")
    т.проверить(настройки.ПериодОповещения == 300 and настройки.ОповещатьОЗадолженности == 2,
                "шаг 1: период оповещений 300 с, задолженность за 2 дня")
    запрос = c.NewObject("Запрос")
    запрос.Текст = "ВЫБРАТЬ ПЕРВЫЕ 1 К.Ссылка КАК Ссылка ИЗ Справочник.УЗ_Кассы КАК К ГДЕ К.Основная И НЕ К.ПометкаУдаления"
    т.проверить(not запрос.Выполнить().Пустой(), "шаг 1: в базе есть касса с отметкой «Основная»")
    т.проверить(c.УЗ_ДатыЗапрета.ЗаписаннаяГраницаПросмотраКассы() is not None,
                "шаг 1: граница просмотра кассы менеджера записана (без неё менеджер кассы не видит)")

    # 2. повторный вызов ничего не делает и быстрый
    набор = c.РегистрыСведений.УЗ_Настройки.СоздатьМенеджерЗаписи()
    набор.Прочитать()
    набор.ПериодОповещения = 0
    набор.Записать()
    н = time.time()
    for _ in range(10):
        обн.ОбновитьДанныеПриНеобходимости()
    за_вызов = (time.time() - н) / 10
    т.проверить(за_вызов <= 0.1, "повторный вызов ≤ 0,1 с (%.4f с)" % за_вызов)
    т.проверить(c.РегистрыСведений.УЗ_Настройки.Настройки().ПериодОповещения == 0,
                "повторный вызов не перезапускает шаги (стёртый период остался 0)")

    # 3. свежий замок чужого сеанса — уходим молча, версия не растёт.
    #    Отметка «через сутки» свежа при любом сдвиге пояса в COM (свежесть = позже «сейчас − 10 мин»)
    сейчас = datetime.datetime.now(datetime.timezone.utc)
    записать_версию(c, 0, сейчас + datetime.timedelta(days=1))
    обн.ОбновитьДанныеПриНеобходимости()
    т.проверить(обн.СостояниеОбновления().Версия == 0, "свежий чужой замок: координатор не пошёл")

    # 4. брошенный замок (сутки назад) — занимаем и догоняем
    записать_версию(c, 0, сейчас - datetime.timedelta(days=1))
    обн.ОбновитьДанныеПриНеобходимости()
    с = обн.СостояниеОбновления()
    т.проверить(с.Версия == актуальная, "брошенный замок: координатор догнал версию", с.Версия)
    т.проверить(c.РегистрыСведений.УЗ_Настройки.Настройки().ПериодОповещения == 300,
                "брошенный замок: шаг 1 заполнил стёртый период снова")

    # 5. отказ не теряется молча: версия отстала, обновление не прошло — форма получает текст
    т.проверить(обн.ПроблемаОбновления() == "", "версия актуальна — проблемы нет")
    записать_версию(c, 0)
    проблема = обн.ПроблемаОбновления()
    if c.УЗ_Общий.БезопасныйРежимДействует():
        т.проверить("безопасный режим" in проблема.lower(),
                    "безопасный режим: пользователь узнаёт, что снять флажок", проблема)
    else:
        т.проверить(проблема == "", "без безопасного режима и без ошибок — молчим", проблема)
    записать_версию(c, актуальная)


if __name__ == "__main__":
    запустить("обновление", сценарий)
