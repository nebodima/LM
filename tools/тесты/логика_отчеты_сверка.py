def таблица(тд):
    """Табличный документ → строки ячеек (текст, неразрывный пробел — обычный)."""
    return [[(тд.Область(р, к, р, к).Текст or "").replace("\xa0", " ").strip() for к in range(1, тд.ШиринаТаблицы + 1)]
            for р in range(1, тд.ВысотаТаблицы + 1)]


def колонка(строки, заголовок):
    """Номер колонки с заголовком (первое точное совпадение сверху)."""
    for строка in строки:
        for к, я in enumerate(строка):
            if я == заголовок:
                return к
    return None


def строка_с(строки, текст, после=0):
    """Первая строка (с номера после), где ячейка начинается с текста."""
    for н in range(после, len(строки)):
        if any(я.startswith(текст) for я in строки[н]):
            return н
    return None


def число(текст):
    т = текст.replace(" ", "").replace(",", ".")
    try:
        return float(т) if т else 0.0
    except ValueError:
        return None


def скд(c, отчет, вариант, начало, конец, отборы):
    """Вариант отчёта на СКД с периодом и значениями существующих в варианте отборов {поле: значение} → строки."""
    схема = getattr(c.Отчеты, отчет).ПолучитьМакет("ОсновнаяСхемаКомпоновкиДанных")
    найден = [в for в in схема.ВариантыНастроек if в.Имя == вариант]
    if not найден:
        raise AssertionError("нет варианта %s" % вариант)
    компоновщик = c.NewObject("КомпоновщикНастроекКомпоновкиДанных")
    компоновщик.Инициализировать(c.NewObject("ИсточникДоступныхНастроекКомпоновкиДанных", схема))
    компоновщик.ЗагрузитьНастройки(найден[0].Настройки)
    настройки = компоновщик.Настройки
    период = настройки.ПараметрыДанных.НайтиЗначениеПараметра(c.NewObject("ПараметрКомпоновкиДанных", "Период"))
    сп = c.NewObject("СтандартныйПериод")
    сп.ДатаНачала, сп.ДатаОкончания = начало, конец
    период.Значение = сп
    период.Использование = True
    осталось = dict(отборы)
    for э in настройки.Отбор.Элементы:
        имя = имя_поля(c, э.ЛевоеЗначение)
        if имя in осталось:
            э.ПравоеЗначение = осталось.pop(имя)
            э.ВидСравнения = c.ВидСравненияКомпоновкиДанных.Равно
            э.Использование = True
    if осталось:
        raise AssertionError("в варианте %s нет отборов %s" % (вариант, ", ".join(осталось)))
    return таблица(сформировать_документ(c, схема, настройки))


