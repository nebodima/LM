"""Панель ученика (УЗ_ПанельУченика): «Продлить/Добавить в группу», «Удалить из группы» (ошибки справки Р5/В10,
№18; логика — в модуле менеджера обработки, форма только показывает итог). «Перевести из группы» с 28.09.2026 не
действие панели, а документ «Перевод ученика» (В29) — тест_перевод_ученика.

Было (Р5): панель создавала и сразу ПРОВОДИЛА уроки, в том числе будущие, — будущий урок не проводится (В10) и
«Продлить группу» на следующий месяц давал отказы; урок группы на дату искался только среди проведённых —
записанный планом урок не находился, и рядом создавался второй; «Удалить из группы» записанные уроки не видел.
№18: «Проведено!» писалось в итог и после ошибки проведения.
Стало: будущий урок только записывается (УЗ_Общий.ЗаписатьУрок), прошедший — проводится с ценой тарифа;
ученик добавляется в уже записанный урок группы; итог строки — по факту записи.
Мутация: в ЗаписатьИРезультат провести любой урок (Урок.Записать(Проведение)) — проверки «будущий урок записан
без проведения» и «итог отказа» краснеют.

    python tools\\тесты\\тест_панель_ученика.py --база=C:\\1c_bases\\UZ_UNF_D
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from фабрика import Фабрика  # noqa: E402

МЕТКА = "УЗ тест панели ученика"
ЦЕНА = 800


def сценарий(т):
    c = т.c
    ф = Фабрика(т, МЕТКА)
    панель = c.Обработки.УЗ_ПанельУченика
    педагог = ф.педагог()
    первый = ф.ученик("ученик Первов")
    второй = ф.ученик("ученик Вторых")
    тариф = ф.элемент("УЗ_Тарифы", "тариф")
    ф.цена_тарифа(тариф, ф.день(-400), ЦЕНА, уроков=1)
    без_цены = ф.элемент("УЗ_Тарифы", "тариф без цены")
    группа = группа_обучения(т, ф, "группа", педагог, тариф)
    группа2 = группа_обучения(т, ф, "группа 2", педагог, тариф)
    группа_без_цены = группа_обучения(т, ф, "группа без цены", педагог, без_цены)

    def уроки_группы(гр):
        return т.выбрать("""ВЫБРАТЬ У.Ссылка КАК Ссылка, У.Дата КАК Дата, У.Проведен КАК Проведен,
            У.ПометкаУдаления КАК Удален ИЗ Документ.УЗ_Урок КАК У ГДЕ У.ГруппаОбучения = &Г""", Г=гр)

    def убрать_уроки():
        for гр in (группа, группа2, группа_без_цены):
            тз = уроки_группы(гр)
            for н in range(тз.Количество()):
                т.удалить_объект(тз.Получить(н).Ссылка, загрузка=True)
    т.убрать(убрать_уроки, "уроки групп панели")

    прошлый = панель.НачалоУрокаГруппы(группа, ф.день(-2))
    будущий = панель.НачалоУрокаГруппы(группа, ф.день(3))
    т.проверить(прошлый.hour == 10 and будущий.hour == 10, "время урока — по расписанию дня группы (10:00)",
                "%s / %s" % (прошлый, будущий))

    итог = список(панель.ЗаписатьУченикаВГруппу(первый, группа, т.массив(прошлый, будущий)))
    т.проверить(len(итог) == 2 and all(с.Успех for с in итог), "«Продлить/Добавить»: обе даты записаны",
                [(с.Описание, с.ДопОписание) for с in итог])
    уроки = уроки_группы(группа)
    т.проверить(уроки.Количество() == 2, "создано по уроку на дату", уроки.Количество())
    по_дате = {как_дата(уроки.Получить(н).Дата): уроки.Получить(н) for н in range(уроки.Количество())}
    у_прошлый = по_дате.get(как_дата(прошлый))
    у_будущий = по_дате.get(как_дата(будущий))
    т.проверить(у_прошлый is not None and у_прошлый.Проведен, "прошедший урок проведён")
    т.проверить(у_будущий is not None and not у_будущий.Проведен,
                "В10: будущий урок только записан, не проведён (было: проведение — отказ)")
    if у_прошлый is not None:
        сумма = ф.число("""ВЫБРАТЬ СУММА(Р.Сумма) ИЗ РегистрНакопления.УЗ_СписанияСуммЗаУроки КАК Р
            ГДЕ Р.Регистратор = &У И Р.Клиент = &К""", У=у_прошлый.Ссылка, К=первый)
        т.проверить(сумма == ЦЕНА, "прошедший урок списал оплату по тарифу группы: %d" % ЦЕНА, сумма)
    if у_будущий is not None:
        движений = ф.число("""ВЫБРАТЬ КОЛИЧЕСТВО(*) ИЗ РегистрНакопления.УЗ_СписанияСуммЗаУроки КАК Р
            ГДЕ Р.Регистратор = &У""", У=у_будущий.Ссылка)
        т.проверить(движений == 0, "будущий урок денег не списывает (движений нет)", движений)
    т.проверить([с.ДопОписание for с in итог] == ["Проведено", "Записан без проведения (план)"],
                "итог: «Проведено» только у проведённого урока", [с.ДопОписание for с in итог])

    # второй ученик — в уже записанный планом урок, а не в новый рядом
    итог = список(панель.ЗаписатьУченикаВГруппу(второй, группа, т.массив(будущий)))
    уроки = уроки_группы(группа)
    т.проверить(len(итог) == 1 and итог[0].Успех and уроки.Количество() == 2,
                "Р5: второй ученик добавлен в записанный планом урок, второго урока на дату нет",
                "уроков %d; %s" % (уроки.Количество(), [(с.Описание, с.ДопОписание) for с in итог]))
    if у_будущий is not None:
        учеников = у_будущий.Ссылка.ПолучитьОбъект().Ученики.Количество()
        т.проверить(учеников == 2, "в будущем уроке два ученика", учеников)
    итог = список(панель.ЗаписатьУченикаВГруппу(второй, группа, т.массив(будущий)))
    т.проверить(len(итог) == 1 and not итог[0].Успех and "Уже есть" in итог[0].Описание,
                "повторное добавление — отказ «уже есть в уроке»", [(с.Описание, с.ДопОписание) for с in итог])

    # «Удалить из группы» видит записанный планом урок
    итог = список(панель.УдалитьУченикаИзГруппы(второй, группа, т.массив(будущий)))
    т.проверить(len(итог) == 1 and итог[0].Успех, "«Удалить из группы»: записанный урок найден, ученик убран",
                [(с.Описание, с.ДопОписание) for с in итог])
    if у_будущий is not None:
        учеников = у_будущий.Ссылка.ПолучитьОбъект().Ученики.Количество()
        т.проверить(учеников == 1, "в будущем уроке снова один ученик", учеников)

    # A16-01 (облачный аудит 2.3.0.2): урок перенесли на другое время того же дня — панель находит его, дубля нет
    if у_будущий is not None:
        перенос = у_будущий.Ссылка.ПолучитьОбъект()
        перенос.Дата = будущий.replace(hour=11)
        ош, сообщ = ф.записать(перенос, "Запись")
        т.проверить(ош is None, "урок группы перенесён на 11:00", (ош, сообщ))
        итог = список(панель.ЗаписатьУченикаВГруппу(второй, группа, т.массив(будущий)))
        уроки = уроки_группы(группа)
        т.проверить(len(итог) == 1 and итог[0].Успех and уроки.Количество() == 2,
                    "A16-01: перенесённый урок найден по дню, второго урока на дату нет",
                    "уроков %d; %s" % (уроки.Количество(), [(с.Описание, с.ДопОписание) for с in итог]))
    пусто = панель.НачалоУрокаГруппы(группа, ф.день(10))
    итог = список(панель.УдалитьУченикаИзГруппы(второй, группа, т.массив(пусто)))
    т.проверить(len(итог) == 1 and not итог[0].Успех and "не найден" in итог[0].ДопОписание,
                "A16-01: «Удалить из группы» на дату без урока — строка «Урок не найден», а не тишина",
                [(с.Описание, с.ДопОписание) for с in итог])

    # №18: отказ проведения — не «Проведено»
    итог = список(панель.ЗаписатьУченикаВГруппу(первый, группа_без_цены,
                                                т.массив(панель.НачалоУрокаГруппы(группа_без_цены, ф.день(-3)))))
    т.проверить(len(итог) == 1 and not итог[0].Успех and итог[0].ДопОписание != "Проведено"
                and "цен" in итог[0].Описание.lower(),
                "№18: тариф без цены — итог «Не записан» с причиной, не «Проведено»",
                [(с.Описание, с.ДопОписание) for с in итог])



def как_дата(значение):
    return (значение.year, значение.month, значение.day)


def список(массив):
    return [массив.Получить(н) for н in range(массив.Количество())]


def группа_обучения(т, ф, имя, педагог, тариф):
    """Группа, занимающаяся каждый день 10:00–11:00."""
    c = т.c
    о = c.Справочники.УЗ_ГруппыОбучения.СоздатьЭлемент()
    о.Наименование = "%s %s" % (ф.метка, имя)
    о.Педагог = педагог
    о.Тариф = тариф
    for день in ("ПН", "ВТ", "СР", "ЧТ", "ПТ", "СБ", "ВС"):
        setattr(о, день, True)
        setattr(о, день + "Время", _время(c, 10))
        setattr(о, день + "Время2", _время(c, 11))
    о.Записать()
    ссылка = о.Ссылка
    т.убрать(lambda: т.удалить_объект(ссылка), "группа %s" % имя)
    return ссылка


def _время(c, час):
    """Время без даты (0001-01-01 чч:00): год 1 через COM не передать — собираем значение в 1С."""
    тип_дата = c.NewObject("ОписаниеТипов", "Дата").Типы().Получить(0)   # Тип() через COM недоступен
    return c.XMLЗначение(тип_дата, "0001-01-01T%02d:00:00" % час)


if __name__ == "__main__":
    запустить("панель_ученика", сценарий)
