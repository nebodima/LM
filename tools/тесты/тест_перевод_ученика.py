"""Документ «Перевод ученика» (решение В29, 28.09.2026): состав групп — регистр УЗ_СоставГрупп, меняет его только
документ; проведение строит план (уроки-планы, из которых ученик уйдёт и в которые добавится), проверяет всё целиком
и только потом пишет регистр и перестраивает планы. Проведённые уроки не меняются никогда.

Сценарий (группы А и Б — один предмет, В — другой; уроки: А проведён −5, планы А +2 и +4, план Б +5):
  1. зачисление: У1, У2, У4 в А с −10; У3 в Б с −10; У5 в А с +1 — планы А +2 и +4 получили У5, проведённый −5 — нет;
  2. перевод У1 из А в Б с +3: предпросмотр = план (уйдёт из А +4, добавится в Б +5); после проведения А +2 (до даты)
     с У1, А +4 без него, Б +5 с ним; проведённый А −5 не тронут; состав А на +2 — с У1, на +3 — без, Б на +3 — с ним;
  3. отмена проведения возвращает всё (А +4 снова с У1, Б +5 без него, состав как до перевода); перепроведение —
     снова как в 2;
  4. отказ: перевод У2 из А с −7 — после даты есть проведённый урок А −5 с У2: документ не проведён, в сообщении
     урок, ни регистр, ни планы не изменены;
  5. смешанный список: У2 и выбывший (отметка «Выбыл») У4 из А в Б — отказ ЦЕЛИКОМ с причиной про У4, У2 не
     переведён (раньше помощник переводил часть списка);
  6. выбытие У2 из А с +3 (группа «В» пуста): А +4 без У2, урок-план без учеников не помечен на удаление (В29),
     подсказка «больше нет групп», отметка «Выбыл» не ставится;
  7. состав на дату в прошлом: А на −11 — пусто, на −10 — У1, У2 (выбывший У4 не в составе); более поздний документ
     по той же паре — отказ «позже есть … сначала отмените»; другой предмет у группы «В» — предупреждение;
  8. шаг обновления данных 6: строки групп карточки прежней версии (А с −20 по −10 и снова с −5, Б без дат) —
     документы «Перевод ученика» и состав на даты; повторный шаг ничего не добавляет.
Мутации (tools\\мутации_проверок.py, «перевод_*»): урок А −5 записать планом, а не провести — красное 4; У4 не
отмечать «Выбыл» — красное 5.

    python tools\\тесты\\тест_перевод_ученика.py --база=C:\\1c_bases\\UZ_BP_E --пользователь=1
"""
# затрагивает: УЗ_ПереводУченика, УЗ_СоставГрупп, УЗ_Урок, УЗ_ФизЛица, УЗ_ГруппыОбучения
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from фабрика import Фабрика  # noqa: E402

МЕТКА = "УЗ тест перевода"
ЦЕНА = 500


def сценарий(т):
    c = т.c
    ф = Фабрика(т, МЕТКА)
    состав_групп = c.РегистрыСведений.УЗ_СоставГрупп
    педагог = ф.педагог("педагог")
    тариф = ф.элемент("УЗ_Тарифы", "500 за урок", Сумма=ЦЕНА, КоличествоУроков=1)
    предмет = ф.элемент("УЗ_ПредметыОбучения", "сольфеджио")
    другой_предмет = ф.элемент("УЗ_ПредметыОбучения", "вокал")
    группа_а = ф.элемент("УЗ_ГруппыОбучения", "группа А", ПредметОбучения=предмет, Тариф=тариф)
    группа_б = ф.элемент("УЗ_ГруппыОбучения", "группа Б", ПредметОбучения=предмет, Тариф=тариф)
    группа_в = ф.элемент("УЗ_ГруппыОбучения", "группа В", ПредметОбучения=другой_предмет, Тариф=тариф)
    у1, у2, у3, у4, у5 = (ф.ученик("ученик %d" % н) for н in range(1, 6))
    имена = {c.String(у): "У%d" % н for н, у in enumerate((у1, у2, у3, у4, у5), 1)}

    def убрать_уроки():
        тз = т.выбрать("ВЫБРАТЬ У.Ссылка КАК Ссылка ИЗ Документ.УЗ_Урок КАК У ГДЕ У.Педагог = &П", П=педагог)
        for н in range(тз.Количество()):
            т.удалить_объект(тз.Получить(н).Ссылка, загрузка=True)
    т.убрать(убрать_уроки, "уроки теста")

    def урок(группа, сдвиг, час, ученики, режим="Запись"):
        д = ф.урок(педагог, ф.день(сдвиг, час), 1,
                   [dict(Ученик=у, Тариф=тариф, СписатьОплату=True, Явка=True) for у in ученики],
                   ГруппаОбучения=группа, ПредметОбучения=предмет)
        ошибка, сообщения = ф.записать(д, режим)
        т.проверить(ошибка is None, "подготовка: урок %s %+d (%s)" % (c.String(группа)[-1], сдвиг, режим),
                    "%s %s" % (ошибка, сообщения))
        return д.Ссылка

    def кто(урок_):
        тз = т.выбрать("ВЫБРАТЬ С.Ученик КАК Ученик ИЗ Документ.УЗ_Урок.Ученики КАК С ГДЕ С.Ссылка = &У", У=урок_)
        return {имена.get(c.String(тз.Получить(н).Ученик), "?") for н in range(тз.Количество())}

    def состав(группа, сдвиг):
        return {имена.get(c.String(у), "?") for у in состав_групп.СоставГруппыНаДату(группа, ф.день(сдвиг, 12))}

    def помечен(урок_):
        return bool(т.выбрать("ВЫБРАТЬ У.ПометкаУдаления КАК П ИЗ Документ.УЗ_Урок КАК У ГДЕ У.Ссылка = &У",
                              У=урок_).Получить(0).П)

    def тексты(сообщения):
        return " | ".join(т_ for т_, _ in сообщения)

    # ── 1: зачисление ──
    ф.перевод([у1, у2, у4], в_группу=группа_а, день=ф.день(-10))
    ф.в_группу(у3, группа_б, -10)
    урок_а_проведен = урок(группа_а, -5, 10, (у1, у2), "Проведение")
    план_а2 = урок(группа_а, 2, 10, (у1, у2))
    план_а4 = урок(группа_а, 4, 10, (у1, у2))
    план_б5 = урок(группа_б, 5, 12, (у3,))
    у4_объект = у4.ПолучитьОбъект()
    у4_объект.Выбыл = True
    у4_объект.Записать()
    _, (ошибка, сообщения) = ф.перевод([у5], в_группу=группа_а, день=ф.день(1))
    т.проверить(ошибка is None and "У5" in кто(план_а2) and "У5" in кто(план_а4)
                and "У5" not in кто(урок_а_проведен),
                "1: зачисление с +1 — ученик добавлен в планы группы +2 и +4, проведённый урок −5 не тронут",
                "%s %s; А+2 %s, А+4 %s, А−5 %s" % (ошибка, тексты(сообщения), кто(план_а2), кто(план_а4),
                                                   кто(урок_а_проведен)))

    # ── 2: перевод с планами до и после даты ──
    перевод, (ошибка, сообщения) = ф.перевод([у1], из_группы=группа_а, в_группу=группа_б, день=ф.день(3),
                                            режим="Запись")
    вид = c.Документы.УЗ_ПереводУченика.Предпросмотр(перевод.Ссылка)
    убрать = [(c.String(вид.Убрать.Получить(н).Урок), имена.get(c.String(вид.Убрать.Получить(н).Ученик)))
              for н in range(вид.Убрать.Количество())]
    добавить = [(c.String(вид.Добавить.Получить(н).Урок), имена.get(c.String(вид.Добавить.Получить(н).Ученик)))
                for н in range(вид.Добавить.Количество())]
    т.проверить(убрать == [(c.String(план_а4), "У1")] and добавить == [(c.String(план_б5), "У1")]
                and вид.Ошибки.Количество() == 0,
                "2: предпросмотр — уйдёт из плана А +4, добавится в план Б +5 (план А +2 до даты не меняется)",
                "убрать %s, добавить %s" % (убрать, добавить))
    ошибка, сообщения = ф.записать(перевод, "Проведение")

    def как_после_перевода(что):
        т.проверить(ошибка is None and "У1" in кто(план_а2) and "У1" not in кто(план_а4) and "У1" in кто(план_б5)
                    and кто(урок_а_проведен) == {"У1", "У2"},
                    "%s: А +2 (до даты) с У1, А +4 без него, Б +5 с ним, проведённый А −5 прежний" % что,
                    "%s %s; А+2 %s, А+4 %s, Б+5 %s, А−5 %s" % (ошибка, тексты(сообщения), кто(план_а2),
                                                                кто(план_а4), кто(план_б5), кто(урок_а_проведен)))
        т.проверить("У1" in состав(группа_а, 2) and "У1" not in состав(группа_а, 3) and "У1" in состав(группа_б, 3),
                    "%s: состав — У1 в А на +2, не в А на +3, в Б на +3" % что,
                    "А+2 %s, А+3 %s, Б+3 %s" % (состав(группа_а, 2), состав(группа_а, 3), состав(группа_б, 3)))
    как_после_перевода("2")

    # ── 3: отмена проведения возвращает всё, перепроведение — снова перевод ──
    ошибка_отмены, сообщения_отмены = ф.записать(перевод, "ОтменаПроведения")
    т.проверить(ошибка_отмены is None and "У1" in кто(план_а4) and "У1" not in кто(план_б5)
                and "У1" in состав(группа_а, 5) and "У1" not in состав(группа_б, 5),
                "3: отмена проведения — У1 снова в плане А +4 и в составе А, из плана Б +5 и состава Б ушёл",
                "%s %s; А+4 %s, Б+5 %s" % (ошибка_отмены, тексты(сообщения_отмены), кто(план_а4), кто(план_б5)))
    ошибка, сообщения = ф.записать(перевод, "Проведение")
    как_после_перевода("3 перепроведение")

    # ── 4: отказ — после даты есть проведённый урок группы «Из» с этим учеником ──
    до = (кто(план_а4), состав(группа_а, -4))
    _, (ошибка, сообщения) = ф.перевод([у2], из_группы=группа_а, в_группу=группа_б, день=ф.день(-7))
    т.проверить(ошибка is not None and "проведённых уроках" in тексты(сообщения)
                and c.String(урок_а_проведен) in тексты(сообщения),
                "4: перевод с −7 при проведённом уроке А −5 с учеником — отказ с перечнем уроков", тексты(сообщения))
    т.проверить((кто(план_а4), состав(группа_а, -4)) == до and "У2" not in состав(группа_б, -4),
                "4: после отказа ни планы, ни состав групп не изменились")

    # ── 5: смешанный список — часть выбыла: отказ целиком ──
    _, (ошибка, сообщения) = ф.перевод([у2, у4], из_группы=группа_а, в_группу=группа_б, день=ф.день(3))
    т.проверить(ошибка is not None and "выбыл" in тексты(сообщения) and c.String(у4) in тексты(сообщения),
                "5: в списке выбывший — отказ целиком с причиной про него", тексты(сообщения))
    т.проверить("У2" in кто(план_а4) and "У2" in состав(группа_а, 5) and "У2" not in состав(группа_б, 5),
                "5: второй ученик списка не переведён (частичных изменений нет)")

    # ── 6: выбытие ──
    _, (ошибка, сообщения) = ф.перевод([у2], из_группы=группа_а, день=ф.день(3))
    т.проверить(ошибка is None and "У2" not in кто(план_а4) and "У2" in кто(план_а2) and "У2" not in состав(группа_а, 3),
                "6: выбытие с +3 — ушёл из плана А +4 и из состава, план А +2 до даты прежний",
                "%s %s; А+4 %s" % (ошибка, тексты(сообщения), кто(план_а4)))
    т.проверить("больше нет групп" in тексты(сообщения) and not bool(у2.ПолучитьОбъект().Выбыл),
                "6: подсказка «больше нет групп», отметка «Выбыл» не ставится (В29)", тексты(сообщения))
    _, (ошибка, сообщения) = ф.перевод([у5], из_группы=группа_а, день=ф.день(3))
    т.проверить(ошибка is None and кто(план_а4) == set() and not помечен(план_а4) and "У5" in кто(план_а2),
                "6: план, в котором не осталось учеников, остаётся в расписании группы и не помечен на удаление (В29)",
                "%s %s; А+4 %s" % (ошибка, тексты(сообщения), кто(план_а4)))

    # ── 7: состав на дату в прошлом, более поздний документ, другой предмет ──
    т.проверить(состав(группа_а, -11) == set() and состав(группа_а, -10) == {"У1", "У2"},
                "7: состав А на −11 пуст, на −10 — У1 и У2 (выбывший У4 не в составе)",
                "−11 %s, −10 %s" % (состав(группа_а, -11), состав(группа_а, -10)))
    _, (ошибка, сообщения) = ф.перевод([у1], из_группы=группа_а, в_группу=группа_в, день=ф.день(1))
    т.проверить(ошибка is not None and "сначала отмените" in тексты(сообщения),
                "7: перевод раньше уже проведённого перевода той же пары — отказ «позже есть … сначала отмените»",
                тексты(сообщения))
    черновик, _ = ф.перевод([у3], из_группы=группа_б, в_группу=группа_в, день=ф.день(6), режим="Запись")
    вид = c.Документы.УЗ_ПереводУченика.Предпросмотр(черновик.Ссылка)
    предупреждения = " | ".join(вид.Предупреждения.Получить(н) for н in range(вид.Предупреждения.Количество()))
    т.проверить("разные предметы" in предупреждения and вид.Ошибки.Количество() == 0,
                "7: у группы «В» другой предмет — предупреждение про абонемент, не отказ", предупреждения)

    # ── 8: шаг обновления данных 6 — строки групп карточки прежней версии → документы и регистр ──
    старый = ф.ученик("из прежней версии")
    о = старый.ПолучитьОбъект()
    for группа, нач, кон in ((группа_а, -20, -10), (группа_а, -5, None), (группа_б, None, None)):
        с = о.ГруппыОбученияПрежние.Добавить()
        с.ГруппаОбучения = группа
        if нач is not None:
            с.ДатаНачала = ф.день(нач)
        if кон is not None:
            с.ДатаОкончания = ф.день(кон)
    о.Записать()
    имена[c.String(старый)] = "С"

    def документы_старого():
        return т.выбрать("ВЫБРАТЬ РАЗЛИЧНЫЕ П.Ссылка КАК Ссылка ИЗ Документ.УЗ_ПереводУченика.Ученики КАК П "
                         "ГДЕ П.Ученик = &У", У=старый)

    def убрать_перенос():
        тз = документы_старого()
        for н in range(тз.Количество()):
            т.удалить_объект(тз.Получить(н).Ссылка, загрузка=True)
    т.убрать(убрать_перенос, "документы переноса состава")
    c.УЗ_ОбновлениеДанных.ШагСоставГрупп()
    было_документов = документы_старого().Количество()
    ответы = [bool(состав_групп.ВГруппеНаДату(старый, группа_а, ф.день(сдвиг, 12))) for сдвиг in (-15, -8, -3)]
    т.проверить(ответы == [True, False, True] and bool(состав_групп.ВГруппеНаДату(старый, группа_б, ф.день(0, 12)))
                and было_документов == 4,
                "8: шаг 6 — А с −20 по −10 и снова с −5, Б бессрочно; четыре документа (зачисления в А с −20 и −5, выбытие из А с −9, зачисление в Б)",
                "А −15/−8/−3 %s, документов %d" % (ответы, было_документов))
    c.УЗ_ОбновлениеДанных.ШагСоставГрупп()
    т.проверить(документы_старого().Количество() == было_документов,
                "8: повторный шаг 6 ничего не добавляет (перенесённые пары пропускаются)")


if __name__ == "__main__":
    запустить("перевод_ученика", сценарий)
