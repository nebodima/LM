"""Урок: цена строки и скидка пересчитываются при каждой записи (аудит 28.09: учёт №1–2, Codex A04–A05).

Было: цена строки (ЦенаТарифа) считалась, только если равна 0 — смена часов, даты, тарифа строки при
программной записи оставляла старую цену; срок действия скидки не проверялся; скидка больше цены давала
отрицательную сумму (Расход с минусом зачислял деньги ученику); скидка с нулевыми коэффициентами роняла
запись на первой строке и «переносила» скидку предыдущего ученика на следующих.

    python tools\\тесты\\тест_урок_цена.py --база=C:\\1c_bases\\UZ_UNF_B
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from фабрика import Фабрика  # noqa: E402

МЕТКА = "УЗ тест цены урока"


def сценарий(т):
    ф = Фабрика(т, МЕТКА)
    c = т.c
    педагог = ф.педагог()
    ученик = ф.ученик()
    ученик2 = ф.ученик("ученик 2")

    за_час = ф.элемент("УЗ_Тарифы", "1 000 за час", Сумма=1000, КоличествоЧасов=1, КоличествоУроков=0)
    за_урок = ф.элемент("УЗ_Тарифы", "8 000 за 8 уроков", Сумма=8000, КоличествоУроков=8)
    за_4 = ф.элемент("УЗ_Тарифы", "6 000 за 4 урока", Сумма=6000, КоличествоУроков=4)
    с_историей = ф.элемент("УЗ_Тарифы", "история цен", ИспользоватьИсториюЦен=True)
    ф.цена_тарифа(с_историей, ф.день(-10), 1000, уроков=1)
    ф.цена_тарифа(с_историей, ф.день(0), 2000, уроков=1)

    def строка(тариф, **поля):
        return dict(Ученик=поля.pop("Ученик", ученик), Тариф=тариф, Явка=True, СписатьОплату=True, **поля)

    def перечитать(д):
        return д.Ссылка.ПолучитьОбъект()

    # ── часы: часовой тариф, 1 ч → 2 ч ──
    д = ф.урок(педагог, ф.день(0, 8), 1, [строка(за_час)])
    ошибка, _ = ф.записать(д, "Запись")
    т.проверить(ошибка is None and д.Ученики.Получить(0).Сумма == 1000, "часовой тариф, 1 ч — 1 000",
                ошибка or д.Ученики.Получить(0).Сумма)
    д = перечитать(д)
    д.КоличествоЧасов = 2
    ф.записать(д, "Запись")
    т.проверить(перечитать(д).Ученики.Получить(0).Сумма == 2000, "урок продлили до 2 ч — сумма 2 000 (не старая цена)",
                перечитать(д).Ученики.Получить(0).Сумма)

    # ── дата: цена по истории цен на новую дату ──
    д = ф.урок(педагог, ф.день(-1, 10), 1, [строка(с_историей)])
    ф.записать(д, "Запись")
    т.проверить(перечитать(д).Сумма == 1000, "урок вчера — цена вчерашней записи истории 1 000", перечитать(д).Сумма)
    д = перечитать(д)
    д.Дата = ф.день(0, 10)
    ф.записать(д, "Запись")
    т.проверить(перечитать(д).Сумма == 2000, "урок перенесли на сегодня — цена сегодняшней записи 2 000",
                перечитать(д).Сумма)

    # ── тариф строки сменили программно (без обнуления цены) ──
    д = ф.урок(педагог, ф.день(0, 12), 1, [строка(за_час)])
    ф.записать(д, "Запись")
    д = перечитать(д)
    д.Ученики.Получить(0).Тариф = за_4
    ф.записать(д, "Запись")
    т.проверить(перечитать(д).Сумма == 1500, "тариф строки сменили на «6 000 за 4 урока» — 1 500 за урок",
                перечитать(д).Сумма)

    # ── скидки ──
    def скидка(имя, **реквизиты):
        return ф.элемент("УЗ_Скидки", имя, **реквизиты)
    просрочена = скидка("50% до позавчера", КоэффициентПроцент=50, ПериодДействияС=ф.день(-30),
                        ПериодДействияПо=ф.день(-2))
    ещё_нет = скидка("50% с завтра", КоэффициентПроцент=50, ПериодДействияС=ф.день(1))
    действует = скидка("10% сейчас", КоэффициентПроцент=10, ПериодДействияС=ф.день(-2), ПериодДействияПо=ф.день(0))
    больше_цены = скидка("1 500 рублей", КоэффициентСумма=1500)
    больше_ста = скидка("150%", КоэффициентПроцент=150)
    сто_руб = скидка("100 рублей", КоэффициентСумма=100)
    пустая = скидка("0/0")

    def сумма_со_скидкой(ск, час, что, ожидаем_сумму, ожидаем_скидку):
        д = ф.урок(педагог, ф.день(0, час), 1, [строка(за_урок, Скидка=ск)])
        ошибка, _ = ф.записать(д, "Запись")
        if ошибка is not None:
            т.проверить(False, что, ошибка)
            return
        с = перечитать(д).Ученики.Получить(0)
        т.проверить(с.Сумма == ожидаем_сумму and с.СуммаСкидки == ожидаем_скидку, что,
                    "сумма %s, скидка %s" % (с.Сумма, с.СуммаСкидки))

    сумма_со_скидкой(просрочена, 13, "просроченная скидка не действует: 1 000, скидка 0", 1000, 0)
    сумма_со_скидкой(ещё_нет, 14, "скидка с завтрашнего дня сегодня не действует: 1 000", 1000, 0)
    сумма_со_скидкой(действует, 15, "скидка в сроке (по сегодня включительно): 900, скидка 100", 900, 100)
    сумма_со_скидкой(больше_цены, 16, "скидка 1 500 ₽ при цене 1 000 — сумма 0, не минус", 0, 1000)
    сумма_со_скидкой(больше_ста, 17, "скидка 150 % — сумма 0, не минус", 0, 1000)

    # ── скидка 0/0: первая строка не роняет запись, вторая не берёт скидку предыдущей ──
    д = ф.урок(педагог, ф.день(-1, 18), 1, [строка(за_урок, Скидка=пустая)])
    ошибка, _ = ф.записать(д, "Проведение")
    т.проверить(ошибка is None, "скидка 0/0 в первой строке — урок проводится", ошибка or "")
    д = ф.урок(педагог, ф.день(0, 19), 1, [строка(за_урок, Скидка=сто_руб),
                                            строка(за_урок, Скидка=пустая, Ученик=ученик2)])
    ошибка, _ = ф.записать(д, "Запись")
    if т.проверить(ошибка is None, "две строки: скидка 100 ₽, затем 0/0 — запись", ошибка or ""):
        с1, с2 = перечитать(д).Ученики.Получить(0), перечитать(д).Ученики.Получить(1)
        т.проверить(с1.Сумма == 900, "первая строка со скидкой 100 ₽ — 900", с1.Сумма)
        т.проверить(с2.Сумма == 1000 and с2.СуммаСкидки == 0,
                    "вторая строка 0/0 — 1 000 без скидки (не перенос скидки предыдущего)",
                    "сумма %s, скидка %s" % (с2.Сумма, с2.СуммаСкидки))

    # A3-01: включили «историю цен» у тарифа с ценой в карточке — прошлые даты не остаются без цены
    карточка = ф.элемент("УЗ_Тарифы", "цена в карточке", Сумма=700, КоличествоУроков=1)

    def убрать_историю():
        набор = c.РегистрыСведений.УЗ_ЦеныТарифов.СоздатьНаборЗаписей()
        набор.Отбор.Тариф.Установить(карточка)
        набор.Записать()
    т.убрать(убрать_историю, "история цен тарифа «цена в карточке»")
    о = карточка.ПолучитьОбъект()
    о.ИспользоватьИсториюЦен = True
    о.Записать()
    цена = c.Документы.УЗ_Урок.ЦенаТарифаНаДату(карточка, ф.день(-30))
    т.проверить(цена is not None and float(цена.Сумма) == 700,
                "включение истории цен: цена карточки 700 действует на прошлые даты", цена and цена.Сумма)


if __name__ == "__main__":
    запустить("урок_цена", сценарий)
