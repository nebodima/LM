"""Урок: правила учёта по решениям владельца 28.09.2026 («как в типовых», docs\\аудит_полный_2026-09-28.md, раздел 7).

  В2  урок по абонементу стоит ЦенаАбонемента / КоличествоЗанятий (часовой — пропорционально часам);
      без абонемента или у абонемента без цены — по тарифу;
  В4  приостановка — с даты начала включительно по дату возобновления не включая; срок абонемента
      продлевается на дни приостановки;
  В6  урок без единой явки: «за занятие» и «за час» не начисляются; «с человека» — по явке;
  В8  новая цена тарифа — только с даты после последнего проведённого урока по тарифу (будущее — свободно),
      прошлые цены не меняются;
  В10 урок нельзя провести раньше его начала — будущий урок только записывается.
Каждая проверка правила краснела на коде до правки (см. отчёт волны 1).

    python tools\\тесты\\тест_урок_правила.py --база=C:\\1c_bases\\UZ_UNF_B
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from фабрика import Фабрика  # noqa: E402

МЕТКА = "УЗ тест правил урока"


def сценарий(т):
    ф = Фабрика(т, МЕТКА)
    c = т.c
    ученик = ф.ученик()
    ученик2 = ф.ученик("ученик 2")
    ученик3 = ф.ученик("ученик 3")
    педагог = ф.педагог()
    тариф = ф.элемент("УЗ_Тарифы", "1 000 за урок", Сумма=1000, КоличествоУроков=1)

    def проведён(итог, что):
        т.проверить(итог[0] is None, что, "%s %s" % итог)

    def отказ(итог, что, слово, поле=None):
        ошибка, сообщения = итог
        нужные = [(текст, п) for текст, п in сообщения if слово in текст and (поле is None or поле in п)]
        т.проверить(ошибка is not None and нужные, что, "ошибка: %s, сообщения: %s" % (ошибка, сообщения))

    def перечитать(д):
        return д.Ссылка.ПолучитьОбъект()

    # ── В2: цена урока по абонементу ──
    аб_8 = ф.абонемент(ученик, "6 400 за 8 занятий", КоличествоЗанятий=8, ЦенаАбонемента=6400)
    аб_часы = ф.абонемент(ученик2, "3 000 за 6 часов", КоличествоЧасов=6, ЦенаАбонемента=3000)
    аб_без_цены = ф.абонемент(ученик3, "без цены", КоличествоЗанятий=8)
    д = ф.урок(педагог, ф.день(-1, 8), 1.5, [
        dict(Ученик=ученик, Абонемент=аб_8, Тариф=тариф, Явка=True, СписатьОплату=True),
        dict(Ученик=ученик2, Абонемент=аб_часы, Явка=True, СписатьОплату=True),
        dict(Ученик=ученик3, Абонемент=аб_без_цены, Тариф=тариф, Явка=True, СписатьОплату=True)])
    ошибка, сообщения = ф.записать(д, "Запись")
    if т.проверить(ошибка is None, "В2: урок с тремя абонементами записан", "%s %s" % (ошибка, сообщения)):
        с = перечитать(д).Ученики
        т.проверить(с.Получить(0).Сумма == 800, "В2: абонемент 6 400 / 8 занятий — урок 800 (не тариф 1 000)",
                    с.Получить(0).Сумма)
        т.проверить(с.Получить(1).Сумма == 750, "В2: абонемент 3 000 / 6 ч, урок 1,5 ч — 750 (тариф не указан)",
                    с.Получить(1).Сумма)
        т.проверить(с.Получить(2).Сумма == 1000, "В2: абонемент без цены — по тарифу 1 000", с.Получить(2).Сумма)
    проведён(ф.записать(перечитать(д), "Проведение"), "В2: урок по абонементу без тарифа проводится (цена абонемента)")

    # ── В4: приостановка и продление срока ──
    аб_пауза = ф.абонемент(ученик, "с приостановкой", КоличествоЗанятий=20, ДатаНачала=ф.день(-30),
                           ДатаАктивации=ф.день(-30), ДатаОкончания=ф.день(-8))
    о = аб_пауза.ПолучитьОбъект()
    п = о.Приостановки.Добавить()
    п.ДатаПриостановки = ф.день(-20)
    п.ДатаВозобновления = ф.день(-15)   # 5 дней паузы → срок до −3
    о.Записать()

    def урок_абонемента(сдвиг):
        return ф.записать(ф.урок(педагог, ф.день(сдвиг, 12), 1, [dict(Ученик=ученик, Абонемент=аб_пауза, Явка=True)]),
                          "Проведение")
    отказ(урок_абонемента(-20), "В4: урок в день начала приостановки — отказ", "приостановлен")
    отказ(урок_абонемента(-16), "В4: урок внутри приостановки — отказ", "приостановлен")
    проведён(урок_абонемента(-15), "В4: урок в день возобновления — проводится")
    проведён(урок_абонемента(-4), "В4: урок после исходного срока, в пределах продления на 5 дней — проводится")
    отказ(урок_абонемента(-2), "В4: урок после продлённого срока — отказ", "дата окончания")

    # ── В6: начисления педагогу без явки ──
    def начислено(ставка_поля, строки, час):
        ставка = ф.элемент("УЗ_СтавкиПедагогов", "ставка %d" % час, **ставка_поля)
        п = ф.педагог("педагог %d" % час, СтавкаПедагога=ставка)
        д = ф.урок(п, ф.день(-2, час), 1, строки, СтавкаПедагога=ставка)
        ошибка, сообщения = ф.записать(д, "Проведение")
        if ошибка is not None:
            return "ошибка: %s %s" % (ошибка, сообщения)
        return float(перечитать(д).НачисленоПедагогу)
    неявка = [dict(Ученик=ученик2, Тариф=тариф, Явка=False, СписатьОплату=True)]
    явка = [dict(Ученик=ученик2, Тариф=тариф, Явка=True, СписатьОплату=True)]
    н = начислено(dict(ОплатаЗаЗанятие=500), неявка, 8)
    т.проверить(н == 0, "В6: никто не пришёл — «за занятие» не начисляется", н)
    н = начислено(dict(ОплатаЗаЗанятие=500), явка, 9)
    т.проверить(н == 500, "В6: есть явка — «за занятие» 500", н)
    н = начислено(dict(ОплатаЗаЧас=1000), неявка, 10)
    т.проверить(н == 0, "В6: никто не пришёл — «за час» не начисляется", н)
    н = начислено(dict(ОплатаСЧеловека=300), [
        dict(Ученик=ученик, Явка=True, СписатьОплату=False),
        dict(Ученик=ученик2, Явка=True, СписатьОплату=False),
        dict(Ученик=ученик3, Тариф=тариф, Явка=False, СписатьОплату=True)], 11)
    т.проверить(н == 600, "В6: «с человека» по явке: 2 явки × 300 = 600 (не по отметке «К оплате»)", н)
    н = начислено(dict(ПроцентСОплатыУченика=40), неявка, 12)
    т.проверить(н == 400, "В6: «% с оплаты» — от оплаты и без явки: 40 % от 1 000", н)

    # ── В8: цена тарифа после последнего проведённого урока ──
    с_историей = ф.элемент("УЗ_Тарифы", "история цен", ИспользоватьИсториюЦен=True)
    ф.цена_тарифа(с_историей, ф.день(-10), 1000, уроков=1)
    проведён(ф.записать(ф.урок(педагог, ф.день(-1, 14), 1,
                               [dict(Ученик=ученик2, Тариф=с_историей, Явка=True, СписатьОплату=True)]), "Проведение"),
             "В8: урок по тарифу с историей цен проводится (вчера)")

    def новая_цена(сдвиг, сумма):
        c.ПолучитьСообщенияПользователю(True)
        з = c.РегистрыСведений.УЗ_ЦеныТарифов.СоздатьМенеджерЗаписи()
        з.Период = ф.день(сдвиг)
        з.Тариф = с_историей
        з.Сумма = сумма
        з.КоличествоУроков = 1
        try:
            з.Записать()
            ошибка = None
        except Exception as е:
            ошибка = str(е)
        if ошибка is None and сдвиг != -10:
            период = ф.день(сдвиг)

            def удалить():
                н = c.РегистрыСведений.УЗ_ЦеныТарифов.СоздатьМенеджерЗаписи()
                н.Период = период
                н.Тариф = с_историей
                н.Прочитать()
                if н.Выбран():
                    н.Удалить()
            т.убрать(удалить, "новая цена тарифа")
        return ошибка
    т.проверить(новая_цена(0, 1200) is None, "В8: новая цена с сегодняшнего дня (после урока вчера) — записывается")
    т.проверить(новая_цена(5, 1500) is None, "В8: цена на будущее — записывается")
    т.проверить(новая_цена(-1, 1100) is not None, "В8: цена с даты последнего урока — отказ")
    т.проверить(новая_цена(-5, 1100) is not None, "В8: цена задним числом до урока — отказ")
    т.проверить(новая_цена(-10, 900) is not None, "В8: правка прошлой цены, по которой проведён урок — отказ")

    # ── В10: будущий урок только записывается ──
    завтра = ф.урок(педагог, ф.день(1, 10), 1, [dict(Ученик=ученик2, Явка=False)])
    отказ(ф.записать(завтра, "Проведение"), "В10: урок завтра провести нельзя — отказ у поля «Дата»", "раньше", "Дата")
    будущий = ф.урок(педагог, ф.день(1, 12), 1, [dict(Ученик=ученик2, Явка=False)])
    ошибка, сообщения = ф.записать(будущий, "Запись")
    т.проверить(ошибка is None, "В10: будущий урок записывается (план)", "%s %s" % (ошибка, сообщения))


if __name__ == "__main__":
    запустить("урок_правила", сценарий)
