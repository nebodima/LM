"""Касса не уходит в минус (решение владельца В14; повторный аудит Codex C04).

Было: РКО расходовал кассу без проверки остатка (выплата 5 000 из пустой кассы проводилась); перемещение между
кассами проверяло только текущий остаток — задним числом выдавались деньги, пришедшие позже. Стало: общая
функция Справочники.УЗ_Кассы.ДоступныйОстатокДляРасхода — меньшее из остатка на момент документа и текущего
(с движениями более поздними датами), без движений самого документа, под блокировкой кассы; ей проверяют
и РКО, и перемещение между кассами.

    python tools\\тесты\\тест_касса_минус.py --база=C:\\1c_bases\\UZ_UNF_A
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import дата, запустить  # noqa: E402
from _деньги import Данные  # noqa: E402

МЕТКА = "_Тест касса в минус"


def сценарий(т):
    c = т.c
    д = Данные(т, МЕТКА)
    виды = c.Перечисления.УЗ_ВидыОпераций
    касса = д.элемент("УЗ_Кассы", "касса")
    вторая = д.элемент("УЗ_Кассы", "вторая касса")
    # в кассе 1 000 с 10.09.2026 10:00
    д.движения("УЗ_Касса", д.регистратор(), [("+", дата(2026, 9, 10, 10), {"Касса": касса, "Сумма": 1000})])

    def остаток():
        return float(c.Справочники.УЗ_Кассы.ОстатокДенег(касса))

    статья = д.элемент("УЗ_СтатьиДвиженияДенег", "аренда")   # прочий расход — со статьёй

    def рко(сумма, когда):
        р = д.документ("УЗ_РасходДенег", Дата=когда, Касса=касса, СуммаДокумента=сумма, ВидОперации=виды.ПрочийРасход,
                       СтатьяЗатрат=статья)
        return р, д.записать(р)

    _, ош = рко(1500, дата(2026, 9, 11, 10))
    т.проверить(ош is not None and "в минус" in ош and остаток() == 1000,
                "РКО 1 500 при остатке 1 000 — отказ «касса уйдёт в минус», остаток 1 000", ош)
    _, ош = рко(500, дата(2026, 9, 9, 10))
    т.проверить(ош is not None and "в минус" in ош, "РКО 500 от 09.09 — отказ: деньги пришли 10.09 (остаток на дату 0)", ош)
    р, ош = рко(800, дата(2026, 9, 15, 10))
    т.проверить(ош is None and остаток() == 200, "РКО 800 от 15.09 проведён, остаток 200", ош or остаток())
    _, ош = рко(300, дата(2026, 9, 12, 10))
    т.проверить(ош is not None and "в минус" in ош,
                "РКО 300 от 12.09 — отказ: на 12.09 было 1 000, но 800 уже выданы 15.09 (текущий остаток 200)", ош)
    о = р.Ссылка.ПолучитьОбъект()
    о.СуммаДокумента = 1000
    ош = д.записать(о)
    т.проверить(ош is None and остаток() == 0, "перепроведение РКО на весь остаток (1 000) — свои движения не мешают",
                ош or остаток())
    _, ош = рко(0.01, дата(2026, 9, 16, 10))
    т.проверить(ош is not None and "в минус" in ош, "из пустой кассы ещё 0,01 — отказ", ош)

    # перемещение между кассами: остаток на дату перемещения
    о = р.Ссылка.ПолучитьОбъект()
    о.Записать(c.РежимЗаписиДокумента.ОтменаПроведения)
    п = д.документ("УЗ_ПеремещениеДенег", Дата=дата(2026, 9, 9, 12), Сумма=500, ВидОперации=виды.ВнутренняяКасса,
                   КассаОтправитель=касса, КассаПолучатель=вторая)
    ош = д.записать(п)
    т.проверить(ош is not None and "в минус" in ош and остаток() == 1000,
                "перемещение 500 от 09.09 — отказ: на 09.09 в кассе 0 (было: текущий остаток 1 000 разрешал)", ош)
    п.Дата = дата(2026, 9, 10, 12)
    ош = д.записать(п)
    т.проверить(ош is None and остаток() == 500, "перемещение 500 от 10.09 проведено, остаток 500", ош or остаток())


if __name__ == "__main__":
    запустить("касса_минус", сценарий)
