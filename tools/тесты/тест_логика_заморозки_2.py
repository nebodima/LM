"""Логика заморозок, часть 2: docs/логики/заморозки.md, сценарии 11–14 — заморозка и уроки, помощник, панель.

Сценарии (К — красный на старом коде, проверено прогоном до правки 28.09.2026):
  №11 В17: урок −15 проведён по абонементу, потом пауза −20→−10 — отказ записи с номером урока (К: пауза записана,
      срок +10 — двойная выгода, перепроведение урока −15 — отказ)
  №12 З-6: пауза −20→−10, урок −12 строкой без абонемента по тарифу — проводится с предупреждением «приостановлен
      абонемент … — урок по тарифу» (К: молча по тарифу)
  №13 З-7: помощник заполняет будущие уроки абонементом на первую дату; пауза +10→+20 — в уроке +12 абонемента нет,
      в уроке +22 он есть (К: абонемент во всех датах, урок +12 потом не проведётся)
  №14 З-8: панель ученика в дни паузы — «приостановлен до …» (К: «8 из 8», о паузе ни слова)
  №17 карточка: состояние «приостановлен до» — дата возобновления, срок с продлением

    python tools\\тесты\\тест_логика_заморозки_2.py --база=C:\\1c_bases\\UZ_UNF_B
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from фабрика import Фабрика  # noqa: E402
from _логика_абонементов import абонемент_с_паузами, вызов, есть_слово, структура, та_же  # noqa: E402

МЕТКА = "УЗ тест логики заморозок 2"


def сценарий(т):
    c = т.c
    ф = Фабрика(т, МЕТКА)
    предмет = ф.элемент("УЗ_ПредметыОбучения", "математика")
    педагог = ф.педагог()
    тариф = ф.элемент("УЗ_Тарифы", "8 000 за 8", Сумма=8000, КоличествоУроков=8)
    д = ф.день

    def убрать_уроки():
        тз = т.выбрать("ВЫБРАТЬ У.Ссылка КАК Ссылка ИЗ Документ.УЗ_Урок КАК У ГДЕ У.Педагог = &П", П=педагог)
        for н in range(тз.Количество()):
            т.удалить_объект(тз.Получить(н).Ссылка, загрузка=True)
    т.убрать(убрать_уроки, "уроки помощника")

    def урок(ученик, день, абонемент=None, час=10):
        поля = dict(Ученик=ученик, Явка=True, СписатьОплату=True, Тариф=тариф)
        if абонемент is not None:
            поля["Абонемент"] = абонемент
        у = ф.урок(педагог, д(день, час), 1, [поля], ПредметОбучения=предмет)
        return у, ф.записать(у, "Проведение")

    # ── №11: В17 — пауза поверх проведённого урока ──
    ученик11 = ф.ученик("Проведенов")
    а11, ошибка, _ = абонемент_с_паузами(ф, ученик11, "с уроком", [], ДатаОкончания=д(20), ПредметОбучения=предмет)
    у11, итог = урок(ученик11, -15, а11)
    т.проверить(итог[0] is None, "№11: урок −15 по абонементу проведён", итог)
    о = а11.ПолучитьОбъект()
    с = о.Приостановки.Добавить()
    с.ДатаПриостановки = д(-20)
    с.ДатаВозобновления = д(-10)
    c.ПолучитьСообщенияПользователю(True)
    _, ошибка = вызов(lambda: о.Записать())
    сообщения = [" ".join(str(м.Текст).split()) for м in c.ПолучитьСообщенияПользователю(True)]
    номер = str(у11.Ссылка.Номер).lstrip("0")
    т.проверить(ошибка is not None and any("проведены уроки" in м and номер in м for м in сообщения),
                "№11 (В17): пауза −20→−10 поверх проведённого урока — отказ с номером урока", (ошибка, сообщения))
    т.проверить(c.Справочники.УЗ_Абонемент.СостояниеАбонемента(а11, д(0)).Срок.date() == д(20).date(),
                "№11: срок не продлён (+20)")

    # ── №12: З-6 — урок без абонемента в дни паузы ──
    ученик12 = ф.ученик("Паузин")
    а12, _, _ = абонемент_с_паузами(ф, ученик12, "с паузой", [(д(-20), д(-10))], ДатаОкончания=д(20),
                                    ПредметОбучения=предмет)
    у12, итог = урок(ученик12, -12, None, 12)
    т.проверить(итог[0] is None and float(у12.Ссылка.ПолучитьОбъект().Ученики.Получить(0).Сумма) == 1000,
                "№12: урок строкой без абонемента в дни паузы — по тарифу 1 000", итог)
    т.проверить(есть_слово(итог[1], "приостановлен абонемент"),
                "№12 (З-6): предупреждение «у ученика приостановлен абонемент — урок по тарифу»", итог[1])

    # ── №13: З-7 — помощник на будущие даты ──
    ученик13 = ф.ученик("Будущев")
    а13, _, _ = абонемент_с_паузами(ф, ученик13, "будущая пауза", [(д(10), д(20))], ДатаНачала=д(-5),
                                    ДатаАктивации=д(-5), ДатаОкончания=д(60), ПредметОбучения=предмет)

    def помощник(день):
        параметры = структура(c, Дата=д(день, 10), КоличествоЧасов=1, ПредметОбучения=предмет, Педагог=педагог,
                              Помещение=c.Справочники.УЗ_Помещения.ПустаяСсылка(),
                              ГруппаОбучения=c.Справочники.УЗ_ГруппыОбучения.ПустаяСсылка())
        итог = c.Документы.УЗ_Урок.ЗаписатьУчениковВУрок(параметры, т.массив(структура(
            c, Ученик=ученик13, Абонемент=а13, Тариф=тариф, СписатьОплату=True, Явка=False)), True)
        if not итог.Успех or итог.Урок is None:
            return "не записан"
        return итог.Урок.ПолучитьОбъект().Ученики.Получить(0).Абонемент
    в_паузе = помощник(12)
    после = помощник(22)
    т.проверить(в_паузе != "не записан" and в_паузе.Пустая(),
                "№13 (З-7): урок помощника +12 (в паузе +10→+20) — без абонемента", c.String(в_паузе))
    т.проверить(та_же(c, после, а13),"№13: урок помощника +22 (после паузы) — с абонементом", c.String(после))

    # ── №14 и №17: панель и карточка в дни паузы ──
    ученик14 = ф.ученик("Сейчаспаузов")
    а14, _, _ = абонемент_с_паузами(ф, ученик14, "пауза сейчас", [(д(-3), д(5))], ДатаОкончания=д(20),
                                    ПредметОбучения=предмет)
    группа = c.Справочники.УЗ_ГруппыОбучения.СоздатьЭлемент()
    группа.Наименование = МЕТКА + " группа"
    группа.ПредметОбучения = предмет
    группа.Записать()
    ссылка_группы = группа.Ссылка
    т.убрать(lambda: т.удалить_объект(ссылка_группы), "группа")
    текст, ошибка = вызов(lambda: c.Обработки.УЗ_ПанельУченика.ОсталосьУроковТекстом(ученик14, ссылка_группы, 0))
    ждём = "приостановлен до " + д(5).strftime("%d.%m.%Y")
    т.проверить(ошибка is None and текст.startswith(ждём) and "8 из 8 зан." in текст,
                "№14 (З-8): панель — «%s (8 из 8 зан.)»" % ждём, (ошибка, текст))
    состояние = c.Справочники.УЗ_Абонемент.СостояниеАбонемента(а14, д(0))
    т.проверить(состояние.Приостановлен and состояние.ДатаВозобновления.date() == д(5).date()
                and состояние.Срок.date() == д(28).date(),
                "№17: карточка — «приостановлен до +5», срок +20 + 8 = +28",
                (состояние.Приостановлен, состояние.ДатаВозобновления, состояние.Срок))


if __name__ == "__main__":
    запустить("логика_заморозки_2", сценарий)
