"""Кассы: основная касса, остаток денег в кассе и «Переместить деньги» из расчёта зарплаты.

Аудит 28.09 (сводка, раздел 2 п.2; Codex «обработчики»): кнопка «Переместить деньги» в расчёте
зарплаты вызывала несуществующий Справочники.УЗ_Кассы.ПолучитьОсновнуюКассу() — падала.
Учёт №20 «Остаток в кассе по первой строке»: проверено на базе 28.09 — виртуальная таблица
Остатки сворачивает измерения, которых нет в запросе (Клиент, Предмет…), строка одна; здесь это
закреплено проверкой суммы по двум клиентам.

Основная касса — непомеченная с реквизитом «Основная», иначе предопределённая ОсновнаяКасса.
Тест временно снимает «Основная» с касс базы и возвращает как было.

    python tools\\тесты\\тест_кассы.py --база=C:\\1c_bases\\UZ_UNF_A
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import дата, запустить  # noqa: E402
from _деньги import Данные, сообщения  # noqa: E402

МЕТКА = "_Тест кассы"


def ид(c, ссылка):
    return c.String(ссылка.УникальныйИдентификатор())


def сценарий(т):
    c = т.c
    д = Данные(т, МЕТКА)

    # ── основная касса ──
    з = c.NewObject("Запрос")
    з.Текст = "ВЫБРАТЬ К.Ссылка КАК Ссылка ИЗ Справочник.УЗ_Кассы КАК К ГДЕ К.Основная"
    выборка = з.Выполнить().Выбрать()
    основные = []
    while выборка.Следующий():
        основные.append(выборка.Ссылка)

    def отметить(касса, значение):
        о = касса.ПолучитьОбъект()
        о.Основная = значение
        о.ОбменДанными.Загрузка = True
        о.Записать()

    for касса in основные:
        отметить(касса, False)
        т.убрать(lambda к=касса: отметить(к, True), "вернуть «Основная»")

    предопределённая = c.Справочники.УЗ_Кассы.ОсновнаяКасса
    т.проверить(ид(c, c.Справочники.УЗ_Кассы.ПолучитьОсновнуюКассу()) == ид(c, предопределённая),
                "нет отмеченной основной — основная = предопределённая «Основная касса»")
    своя = д.элемент("УЗ_Кассы", "основная", Основная=True)
    т.проверить(ид(c, c.Справочники.УЗ_Кассы.ПолучитьОсновнуюКассу()) == ид(c, своя),
                "касса с реквизитом «Основная» — она и основная")
    о = своя.ПолучитьОбъект()
    о.ПометкаУдаления = True
    о.Записать()
    т.проверить(ид(c, c.Справочники.УЗ_Кассы.ПолучитьОсновнуюКассу()) == ид(c, предопределённая),
                "помеченная на удаление основной не считается")
    о = своя.ПолучитьОбъект()
    о.ПометкаУдаления = False
    о.Записать()

    # ── остаток кассы: два клиента — одна сумма ──
    касса = д.элемент("УЗ_Кассы", "зал")
    иванов = д.элемент("УЗ_ФизЛица", "Иванов")
    петров = д.элемент("УЗ_ФизЛица", "Петров")
    педагог = д.элемент("УЗ_ФизЛица", "педагог", ЭтоПедагог=True)
    носитель = д.регистратор()
    когда = дата(2026, 9, 1, 10)
    д.движения("УЗ_Касса", носитель, [("+", когда, {"Касса": касса, "Клиент": иванов, "Сумма": 5000}),
                                      ("+", когда, {"Касса": касса, "Клиент": петров, "Сумма": 3000})])
    т.проверить(float(c.Справочники.УЗ_Кассы.ОстатокДенег(касса)) == 8000,
                "остаток кассы = 5 000 Иванова + 3 000 Петрова = 8 000",
                c.Справочники.УЗ_Кассы.ОстатокДенег(касса))

    # ── «Переместить деньги» из расчёта зарплаты: весь остаток в основную кассу ──
    р = д.документ("УЗ_РасчетЗарплаты", Дата=дата(2026, 9, 2, 12), Педагог=педагог, Касса=касса,
                   ДатаНачала=дата(2026, 8, 1), ДатаОкончания=дата(2026, 8, 31))
    сообщения(c)
    перемещение = р.ПереместитьОстатокВОсновнуюКассу()
    д.следить(перемещение)
    т.проверить(not перемещение.Пустая(), "перемещение создано", сообщения(c))
    if not перемещение.Пустая():
        о = перемещение.ПолучитьОбъект()
        т.проверить(о.Проведен and float(о.Сумма) == 8000 and ид(c, о.КассаПолучатель) == ид(c, своя),
                    "перемещение проведено: 8 000 в основную кассу",
                    "проведён %s, сумма %s, получатель %s" % (о.Проведен, о.Сумма, c.String(о.КассаПолучатель)))
        т.проверить(float(c.Справочники.УЗ_Кассы.ОстатокДенег(касса)) == 0, "касса зала после перемещения пуста")

    # пустая касса — перемещать нечего, документ не создаётся
    перемещение = р.ПереместитьОстатокВОсновнуюКассу()
    д.следить(перемещение)
    т.проверить(перемещение.Пустая() and "нечего" in сообщения(c), "пустая касса — перемещение не создаётся")


if __name__ == "__main__":
    запустить("кассы", сценарий)
