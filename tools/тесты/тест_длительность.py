"""Длительность урока на экране — «Ч:ММ», в объекте — число часов с 4 знаками (визуальный аудит 28.09.2026, правка №1).

Было: поле «Длительность» урока показывало реквизит объекта КоличествоЧасов (Число 12,4) как есть — «1,5000»,
«0,6667». Стало: в форме урока реквизит формы «Длительность» (Дата, только время, формат ДФ=Ч:мм), перевод
в/из часов объекта — общими функциями УЗ_ОбщийКлиентСервер.ВремяИзЧасов / ЧасыИзВремени через целые минуты.

Проверяется:
  1. перевод в базе: 1,5 ч ↔ «1:30», 40 минут ↔ 0,6667 ч (и обратно «0:40»), 0 ч ↔ пустое время;
     представление для списков и текстов — «1:30», «0:40»;
  2. форма урока (src_ext): реквизит «Длительность» — время, поле с форматом ДФ=Ч:мм, при изменении пишет
     в объект ЧасыИзВремени, при открытии/пересчёте читает ВремяИзЧасов; реквизит объекта остаётся Число(12,4).
Мутация: в ЧасыИзВремени убрать Окр(…, 4) — краснеет «40 мин → 0,6667»; в ВремяИзЧасов убрать Окр — краснеет
«0,6667 → 0:40» (0,6667 × 60 = 40,002 мин).

    python tools\\тесты\\тест_длительность.py --база=C:\\1c_bases\\UZ_UNF_B
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить, дата  # noqa: E402

КОРЕНЬ = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), "src_ext")
ФОРМА = os.path.join(КОРЕНЬ, "Documents", "УЗ_Урок", "Forms", "ФормаДокумента", "Ext")


def _прочитать(путь):
    with open(путь, encoding="utf-8-sig") as ф:
        return ф.read()


def сценарий(т):
    c = т.c
    м = c.УЗ_ОбщийКлиентСервер

    def показ(часы):
        """Время поля так, как его покажет ДФ=Ч:мм: часы:минуты времени дня (пустая дата — пусто)."""
        время = м.ВремяИзЧасов(часы)
        return "%d:%02d" % (время.hour, время.minute)

    т.проверить(показ(1.5) == "1:30", "1,5 ч на экране — «1:30»", показ(1.5))
    т.проверить(float(м.ЧасыИзВремени(м.ВремяИзЧасов(1.5))) == 1.5, "«1:30» обратно — 1,5 ч",
                м.ЧасыИзВремени(м.ВремяИзЧасов(1.5)))
    сорок = дата(2026, 9, 28, 0, 40)
    т.проверить(float(м.ЧасыИзВремени(сорок)) == 0.6667,
                "40 минут («0:40») — 0,6667 ч (4 знака, как в реквизите объекта)", м.ЧасыИзВремени(сорок))
    т.проверить(показ(0.6667) == "0:40", "0,6667 ч на экране — «0:40» (через целые минуты)", показ(0.6667))
    т.проверить(float(м.ЧасыИзВремени(м.ВремяИзЧасов(0.6667))) == 0.6667, "0,6667 ч туда и обратно — без потерь",
                м.ЧасыИзВремени(м.ВремяИзЧасов(0.6667)))
    т.проверить(float(м.ЧасыИзВремени(м.ВремяИзЧасов(0))) == 0 and м.ПредставлениеДлительности(0) == "0:00",
                "0 ч — пустое время (0 часов обратно), в тексте «0:00»", м.ПредставлениеДлительности(0))
    т.проверить(м.ПредставлениеДлительности(1.5) == "1:30" and м.ПредставлениеДлительности(0.6667) == "0:40"
                and м.ПредставлениеДлительности(2) == "2:00",
                "представление для списков и текстов: 1:30, 0:40, 2:00",
                "%s %s %s" % (м.ПредставлениеДлительности(1.5), м.ПредставлениеДлительности(0.6667),
                              м.ПредставлениеДлительности(2)))

    xml = _прочитать(os.path.join(ФОРМА, "Form.xml"))
    реквизит = re.search(r'<Attribute name="Длительность".*?</Attribute>', xml, re.S)
    т.проверить(bool(реквизит) and "xs:dateTime" in реквизит.group(0) and "<v8:DateFractions>Time<" in реквизит.group(0),
                "форма урока: реквизит «Длительность» — время (Дата, только время)")
    поле = re.search(r'<InputField name="Длительность".*?</InputField>', xml, re.S)
    т.проверить(bool(поле) and "<DataPath>Длительность</DataPath>" in поле.group(0)
                and "ДФ=Ч:мм" in поле.group(0) and "ДлительностьПриИзменении" in поле.group(0),
                "форма урока: поле «Длительность» — ДФ=Ч:мм, обработчик ДлительностьПриИзменении")
    т.проверить("<DataPath>Объект.КоличествоЧасов</DataPath>" not in xml,
                "форма урока: число часов объекта на экран не выводится («1,5000»)")
    код = _прочитать(os.path.join(ФОРМА, "Form", "Module.bsl"))
    т.проверить("Объект.КоличествоЧасов = УЗ_ОбщийКлиентСервер.ЧасыИзВремени(Длительность)" in код
                and код.count("Длительность = УЗ_ОбщийКлиентСервер.ВремяИзЧасов(Объект.КоличествоЧасов)") >= 2,
                "модуль формы: ввод пишет ЧасыИзВремени, открытие и пересчёт читают ВремяИзЧасов")
    объект = _прочитать(os.path.join(КОРЕНЬ, "Documents", "УЗ_Урок.xml"))
    часы = re.search(r"<Name>КоличествоЧасов</Name>.*?</Type>", объект, re.S).group(0)
    т.проверить("<v8:FractionDigits>4</v8:FractionDigits>" in часы and "xs:decimal" in часы,
                "реквизит объекта КоличествоЧасов не тронут: Число, 4 знака")


if __name__ == "__main__":
    запустить("длительность", сценарий)
