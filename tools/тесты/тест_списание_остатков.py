"""Списание остатков (УЗ_СписаниеОстатков): часы ученика в регистре — секунды (учёт №10).

Было: Движение.Часы = КоличествоЧасов без * 3600, колонка «Кол-во ч.» целая (10.0) — списали 2 ч,
в регистр ушло 2 секунды; полчаса не ввести. Стало: секунды, колонка и итог шапки дробные.

    python tools\\тесты\\тест_списание_остатков.py --база=C:\\1c_bases\\UZ_UNF_A
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import дата, запустить  # noqa: E402
from _деньги import Данные  # noqa: E402

МЕТКА = "_Тест списание остатков"


def сценарий(т):
    c = т.c
    д = Данные(т, МЕТКА)
    ученик = д.элемент("УЗ_ФизЛица", "ученик")
    документ = д.документ("УЗ_СписаниеОстатков", Дата=дата(2026, 9, 3, 10))
    строка = документ.ТЗСписания.Добавить()
    строка.Ученик = ученик
    строка.КоличествоЧасов = 1.5
    строка.КоличествоУроков = 1
    ош = д.записать(документ)
    т.проверить(ош is None, "списание остатков проведено", ош)
    т.проверить(float(документ.Ссылка.ПолучитьОбъект().ТЗСписания.Получить(0).КоличествоЧасов) == 1.5,
                "колонка «Кол-во ч.» хранит полчаса: 1,5 ч",
                документ.Ссылка.ПолучитьОбъект().ТЗСписания.Получить(0).КоличествоЧасов)
    т.проверить(float(документ.Ссылка.ПолучитьОбъект().КоличествоЧасов) == 1.5, "итог часов в шапке 1,5")
    часы, строк = д.итог("УЗ_СписанияСуммЗаУроки", документ.Ссылка, "Часы")
    # списание — Расход: вклад в остаток −5 400 с
    т.проверить(строк == 1 and часы == -5400, "в регистр ушло 1,5 ч = 5 400 секунд (Расход)",
                "строк %s, часы %s" % (строк, часы))


if __name__ == "__main__":
    запустить("списание_остатков", сценарий)
