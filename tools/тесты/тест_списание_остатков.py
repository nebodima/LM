"""Списание остатков (УЗ_СписаниеОстатков): часы ученика в регистре — секунды (учёт №10); знаки уроков и явок —
как у проведённого урока (ошибки справки №23); ввод на основании физ. лица заполняет остатки (№22).

Было: Движение.Часы = КоличествоЧасов без * 3600, колонка «Кол-во ч.» целая (10.0) — списали 2 ч,
в регистр ушло 2 секунды; полчаса не ввести. Стало: секунды, колонка и итог шапки дробные.
№23. Урок пишет Расход с уроками и явками −1 (в остатке «использовано» +1), часами и суммой с плюсом; списание
писало уроки и явки с плюсом — списание 1 урока «возвращало» урок. Стало: вклад в остаток уроков, явок, часов и
суммы у списания того же знака, что у урока (сверка с настоящим проведённым уроком).
№22. «Ввести на основании» из списка физ. лиц открывал пустой документ (обработки заполнения не было). Стало:
строка на каждый предмет с ненулевым остатком денег, сумма — весь остаток; проведение сводит остаток к нулю.

    python tools\\тесты\\тест_списание_остатков.py --база=C:\\1c_bases\\UZ_UNF_A
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import дата, запустить  # noqa: E402
from _деньги import Данные, сейчас  # noqa: E402
from фабрика import Фабрика  # noqa: E402

МЕТКА = "_Тест списание остатков"


def знак(число):
    return (число > 0) - (число < 0)


def сценарий(т):
    c = т.c
    д = Данные(т, МЕТКА)
    ф = Фабрика(т, МЕТКА)
    ученик = д.элемент("УЗ_ФизЛица", "ученик")
    документ = д.документ("УЗ_СписаниеОстатков", Дата=дата(2026, 9, 3, 10))
    строка = документ.ТЗСписания.Добавить()
    строка.Ученик = ученик
    строка.КоличествоЧасов = 1.5
    строка.КоличествоУроков = 1
    строка.КоличествоЯвок = 1
    строка.Сумма = 100
    ош = д.записать(документ)
    т.проверить(ош is None, "списание остатков проведено", ош)
    т.проверить(float(документ.Ссылка.ПолучитьОбъект().ТЗСписания.Получить(0).КоличествоЧасов) == 1.5,
                "колонка «Кол-во ч.» хранит полчаса: 1,5 ч",
                документ.Ссылка.ПолучитьОбъект().ТЗСписания.Получить(0).КоличествоЧасов)
    т.проверить(float(документ.Ссылка.ПолучитьОбъект().КоличествоЧасов) == 1.5, "итог часов в шапке 1,5")
    часы, строк = д.итог("УЗ_СписанияСуммЗаУроки", документ.Ссылка, "Часы")
    # списание — Расход: вклад в остаток −5 400 с
    т.проверить(строк == 1 and часы == -5400, "в регистр ушло 1,5 ч = 5 400 секунд (Расход)",
                "строк %s, часы %s" % (строк, часы))

    # ── №23: знаки — как у настоящего проведённого урока (явка, 1 ч) ──
    педагог = ф.педагог()
    урок = ф.урок(педагог, ф.день(-1, 10), 1, [dict(Ученик=ученик, Явка=True)])
    ошибка, сообщения = ф.записать(урок)
    т.проверить(ошибка is None, "урок-образец (явка, 1 ч) проведён", "%s %s" % (ошибка, сообщения))
    for ресурс, ждём in (("КоличествоУроков", 1), ("КоличествоЯвок", 1), ("Часы", -5400), ("Сумма", -100)):
        у_списания, _ = д.итог("УЗ_СписанияСуммЗаУроки", документ.Ссылка, ресурс)
        у_урока, _ = д.итог("УЗ_СписанияСуммЗаУроки", урок.Ссылка, ресурс)
        т.проверить(у_списания == ждём, "списание: вклад в остаток «%s» = %s" % (ресурс, ждём), у_списания)
        if ресурс != "Сумма":   # урок-образец без оплаты — сумма 0, знак суммы сверен с описанием урока выше
            т.проверить(знак(у_списания) == знак(у_урока),
                        "знак «%s» у списания тот же, что у урока" % ресурс,
                        "списание %s, урок %s" % (у_списания, у_урока))

    # ── №22: ввод на основании физ. лица — остатки денег по предметам ──
    должник = д.элемент("УЗ_ФизЛица", "ученик на основании")
    п1 = д.элемент("УЗ_ПредметыОбучения", "предмет 1")
    п2 = д.элемент("УЗ_ПредметыОбучения", "предмет 2")
    носитель = д.регистратор()
    орг = c.РегистрыСведений.УЗ_Настройки.Настройки().Организация   # В12: списание — остатки организации документа
    д.движения("УЗ_СписанияСуммЗаУроки", носитель, [
        ("+", дата(2026, 9, 1, 9), dict(Клиент=должник, ПредметОбучения=п1, Сумма=500, Организация=орг)),
        ("-", дата(2026, 9, 2, 9), dict(Клиент=должник, ПредметОбучения=п2, Сумма=200, Организация=орг)),
    ])
    на_основании = c.Документы.УЗ_СписаниеОстатков.СоздатьДокумент()
    на_основании.Заполнить(должник)
    def ключ(ссылка):
        return c.String(ссылка.УникальныйИдентификатор())
    строки = {ключ(на_основании.ТЗСписания.Получить(н).ПредметОбучения):
              float(на_основании.ТЗСписания.Получить(н).Сумма) for н in range(на_основании.ТЗСписания.Количество())}
    т.проверить(строки == {ключ(п1): 500.0, ключ(п2): -200.0},
                "на основании физ. лица: строка на предмет, сумма — остаток (+500 и −200)", строки)
    на_основании.Дата = сейчас()
    на_основании.Комментарий = МЕТКА
    ош = д.записать(на_основании)
    т.проверить(ош is None, "списание на основании проведено", ош)
    остаток = т.выбрать("""ВЫБРАТЬ О.ПредметОбучения КАК Предмет, О.СуммаОстаток КАК Остаток
        ИЗ РегистрНакопления.УЗ_СписанияСуммЗаУроки.Остатки(, Клиент = &К) КАК О""", К=должник)
    т.проверить(остаток.Количество() == 0, "после списания остаток денег ученика по каждому предмету — 0",
                [(c.String(остаток.Получить(н).Предмет), остаток.Получить(н).Остаток)
                 for н in range(остаток.Количество())])


if __name__ == "__main__":
    запустить("списание_остатков", сценарий)
