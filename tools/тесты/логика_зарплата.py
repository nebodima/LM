"""Логика зарплаты, часть 1: сценарии 1–12 из docs/логики/зарплата.md §5 (начисление в уроке) и ставка группы.

Начисление педагогу — Документы.УЗ_Урок.НачисленияПоСтавке, его пишет проведение урока прямо в УЗ_РасчетыПоЗарплате
(R24: урок начисление не хранит): «с человека» — по явкам, «%» — от оплаты учеников (после скидки, до копеек;
материалы не вычитаются — В15), «за занятие» и «за час» — только при явке (В6); доплаты сверх ставки — документ
«Начисление педагогам» на основании урока (перепроведение урока их не трогает); сумма «вместо ставки» — ставка урока
очищена + доплата; смена педагога (Документы.УЗ_Урок.ПриСменеПедагога — её зовёт форма) — ставка нового педагога;
ставка урока по умолчанию — ставка группы, иначе педагога («ставка по виду работ»).
Менеджер без права зарплаты (ставку не меняет, начисление не читает) — тест_ревью_зарплата_урока.py.

Красные на старом коде (28.09.2026, UZ_UNF_D до правки): №12 (смена педагога в форме очищала всю таблицу начислений;
функции ПриСменеПедагога не было), ставка группы (реквизита не было — групповой урок начислял по ставке карточки).

    python tools\\тесты\\логика_зарплата.py --база=C:\\1c_bases\\UZ_UNF_D
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить  # noqa: E402
from фабрика import Фабрика  # noqa: E402
from логика_урок import безопасно, деньги, строка, перечитать  # noqa: E402

МЕТКА = "_Тест логика зарплаты"


def начисления(т, урок):
    """Движения урока в УЗ_РасчетыПоЗарплате: [(вид «+»/«-», сумма, комментарий)]."""
    c = т.c
    тз = т.выбрать("""ВЫБРАТЬ Р.ВидДвижения КАК Вид, Р.Сумма КАК Сумма, Р.Комментарий КАК Комментарий
        ИЗ РегистрНакопления.УЗ_РасчетыПоЗарплате КАК Р ГДЕ Р.Регистратор = &У УПОРЯДОЧИТЬ ПО Р.НомерСтроки""", У=урок.Ссылка)
    приход = c.String(c.ВидДвиженияНакопления.Приход)
    return [("+" if c.String(тз.Получить(н).Вид) == приход else "-", деньги(тз.Получить(н).Сумма),
             str(тз.Получить(н).Комментарий)) for н in range(тз.Количество())]


def сценарий(т):
    c = т.c
    ф = Фабрика(т, МЕТКА)
    ученики = [ф.ученик("ученик %d" % н) for н in range(1, 5)]
    за_урок = ф.элемент("УЗ_Тарифы", "1 000 за урок", Сумма=1000, КоличествоУроков=1)
    час = [7]

    def провести(ставка, строки, часов=1, педагог=None, **реквизиты):
        """Урок вчера (каждый — в свой час) со ставкой → (урок, ошибка, сообщения)."""
        час[0] += 1
        п = педагог or ф.педагог("педагог %d" % час[0])
        д = ф.урок(п, ф.день(-1, час[0]), часов, строки, СтавкаПедагога=ставка, **реквизиты)
        ош, сооб = ф.записать(д)
        return д, ош, сооб

    def ставка(имя, **р):
        return ф.элемент("УЗ_СтавкиПедагогов", имя, **р)

    у1, у2, у3, у4 = ученики
    за_занятие = ставка("500 за занятие", ОплатаЗаЗанятие=500)

    # 1. «за занятие» 500, 3 ученика, явка 1
    д, ош, сооб = провести(за_занятие, [строка(у1, Тариф=за_урок), строка(у2, Тариф=за_урок, Явка=False),
                                        строка(у3, Тариф=за_урок, Явка=False)])
    т.проверить(ош is None and начисления(т, д) == [("+", 500, "#ОплатаЗаЗанятие")],
                "1: «за занятие» 500, явка 1 из 3 — строка #ОплатаЗаЗанятие 500, приход долга 500", ош or начисления(т, д))

    # 2. явок 0 (все «К оплате») — начисления нет, ученикам списано
    д, ош, сооб = провести(за_занятие, [строка(у1, Тариф=за_урок, Явка=False), строка(у2, Тариф=за_урок, Явка=False)])
    т.проверить(ош is None and начисления(т, д) == [] and деньги(д.Сумма) == 2000,
                "2: никто не пришёл — педагогу 0, движений нет (В6); ученикам списано 2 000", ош or (начисления(т, д), д.Сумма))

    # 3. «за час» 1 000, индивидуальный 90 мин, явка — 1 500
    за_час = ставка("1 000 за час", ОплатаЗаЧас=1000)
    д, ош, сооб = провести(за_час, [строка(у1, Тариф=за_урок)], 1.5)
    т.проверить(ош is None and начисления(т, д) == [("+", 1500, "#ОплатаЗаЧас")], "3: «за час» 1 000, 90 мин — 1 500,00",
                ош or начисления(т, д))

    # 4. «за час», 60 мин, явок 0 — 0
    д, ош, сооб = провести(за_час, [строка(у1, Тариф=за_урок, Явка=False)])
    т.проверить(ош is None and начисления(т, д) == [], "4: «за час», никто не пришёл — 0 (В6)", ош or начисления(т, д))

    # 5. «с человека» 300: 2 явки (одна без оплаты), 1 неявка с оплатой, 1 неявка без оплаты — 600
    с_чел = ставка("300 с человека", ОплатаСЧеловека=300)
    д, ош, сооб = провести(с_чел, [строка(у1, Тариф=за_урок), строка(у2, Тариф=за_урок, СписатьОплату=False),
                                   строка(у3, Тариф=за_урок, Явка=False), строка(у4, Явка=False, СписатьОплату=False)])
    т.проверить(ош is None and [с[:2] for с in начисления(т, д)] == [("+", 600)], "5: «с человека» 300 × 2 явки = 600",
                ош or начисления(т, д))

    # 6. «%» 40, ученик 1 000, неявка «К оплате» — 400 (от оплаты, без явки)
    п40 = ставка("40 %", ПроцентСОплатыУченика=40)
    д, ош, сооб = провести(п40, [строка(у1, Тариф=за_урок, Явка=False)])
    т.проверить(ош is None and [с[:2] for с in начисления(т, д)] == [("+", 400)], "6: «%» 40 от оплаченной неявки 1 000 — 400",
                ош or начисления(т, д))

    # 7. «%» 30: 2 ученика по 1 000, у одного скидка 10 % — база 1 900 → 570
    п30 = ставка("30 %", ПроцентСОплатыУченика=30)
    ск10 = ф.элемент("УЗ_Скидки", "10 %", КоэффициентПроцент=10)
    д, ош, сооб = провести(п30, [строка(у1, Тариф=за_урок), строка(у2, Тариф=за_урок, Скидка=ск10)])
    т.проверить(ош is None and [с[:2] for с in начисления(т, д)] == [("+", 570)],
                "7: «%» 30 от оплаты после скидки 1 000 + 900 = 1 900 — 570", ош or начисления(т, д))

    # 8. «%» 30: ученик 2 000, доп. расход «набор» 800 — 600 (В15: от оплаты ученика, материалы не вычитаются)
    за_2000 = ф.элемент("УЗ_Тарифы", "2 000 за урок", Сумма=2000, КоличествоУроков=1)
    статья = ф.элемент("УЗ_СтатьиДвиженияДенег", "наборы")
    час[0] += 1
    д = ф.урок(ф.педагог("педагог робототехники"), ф.день(-1, час[0]), 1, [строка(у1, Тариф=за_2000)], СтавкаПедагога=п30)
    р = д.Расходы.Добавить()
    р.СтатьяЗатрат = статья
    р.Сумма = 800
    ош, сооб = ф.записать(д)
    т.проверить(ош is None and [с[:2] for с in начисления(т, д)] == [("+", 600)],
                "8: «%» 30 от оплаты 2 000 при доп. расходе 800 — 600 (В15)", ош or начисления(т, д))

    # 9. сумма «вместо ставки» (прежде — «Не изменять»): руководитель очищает ставку урока и вводит доплату 500 —
    # после перепроведения урок по ставке не начисляет, педагогу 500 доплатой
    педагог9 = ф.педагог("педагог фиксированной суммы", СтавкаПедагога=за_занятие)
    д, ош, _ = провести(за_занятие, [строка(у1, Тариф=за_урок)], педагог=педагог9)
    о = перечитать(д)
    о.СтавкаПедагога = c.Справочники.УЗ_СтавкиПедагогов.ПустаяСсылка()
    ош, _ = ф.записать(о)
    доплата9, (ош9, _) = ф.доплата(д, 500, "за урок по договорённости")
    ош2, _ = ф.записать(перечитать(д))
    т.проверить(ош is None and ош9 is None and ош2 is None and начисления(т, д) == [] and ф.начислено_педагогу(доплата9) == 500,
                "9: ставка урока очищена, доплата 500 — урок по ставке не начисляет, педагогу 500 документом",
                ош or ош9 or ош2 or начисления(т, д))

    # 10. ставка действовала до −10 дней — урок вчера: 0 и сообщение «не действует»
    старая = ставка("старая 500", ОплатаЗаЗанятие=500, ОкончаниеДействия=ф.день(-10))
    д, ош, сооб = провести(старая, [строка(у1, Тариф=за_урок)])
    т.проверить(ош is None and начисления(т, д) == [] and any("не действует" in с for с, _ in сооб),
                "10: ставка вне срока — начисления нет, предупреждение «не действует»", ош or (начисления(т, д), сооб))

    # 11. 500 по ставке + доплата 200 документом на основании урока — перепроведение урока доплату не трогает: 700
    педагог11 = ф.педагог("педагог доплаты", СтавкаПедагога=за_занятие)
    час[0] += 1
    д = ф.урок(педагог11, ф.день(-1, час[0]), 1, [строка(у1, Тариф=за_урок)], СтавкаПедагога=за_занятие)
    ф.записать(д)
    доплата11, (ош11, _) = ф.доплата(д, 200)
    ош, _ = ф.записать(перечитать(д))
    т.проверить(ош is None and ош11 is None and ф.начислено_педагогу(д) == 500 and ф.начислено_педагогу(доплата11) == 200
                and c.String(доплата11.ДокументОснования) == c.String(д.Ссылка)
                and c.String(доплата11.Педагог) == c.String(педагог11),
                "11: урок 500 по ставке + доплата 200 на основании урока (педагог и урок заполнены) — после перепроведения "
                "урока 500 + 200", ош or ош11 or (ф.начислено_педагогу(д), ф.начислено_педагогу(доплата11)))

    # 12. смена педагога (как в форме) — ставка нового педагога; обратно — прежняя
    другой = ф.педагог("другой педагог", СтавкаПедагога=за_час)
    о = перечитать(д)
    о.Педагог = другой
    _, ош = безопасно(lambda: c.Документы.УЗ_Урок.ПриСменеПедагога(о))
    сменили = c.String(о.СтавкаПедагога)
    о.Педагог = педагог11
    _, ош2 = безопасно(lambda: c.Документы.УЗ_Урок.ПриСменеПедагога(о))
    т.проверить(ош is None and ош2 is None and сменили == c.String(за_час) and c.String(о.СтавкаПедагога) == c.String(за_занятие),
                "12: смена педагога — ставка нового педагога («за час»), обратно — «за занятие»",
                "%s %s %s → %s" % (ош, ош2, сменили, c.String(о.СтавкаПедагога)))

    # ставка группы («ставка по виду работ»): педагог «за час», у группы «с человека» — групповой урок по ставке группы
    педагог_г = ф.педагог("педагог группы", СтавкаПедагога=за_час)
    группа = ф.элемент("УЗ_ГруппыОбучения", "группа со ставкой", Педагог=педагог_г)
    _, ош = безопасно(lambda: установить_ставку_группы(группа, с_чел))
    т.проверить(ош is None, "ставка группы: у группы есть реквизит «Ставка педагога»", ош)
    час[0] += 1
    д = ф.урок(педагог_г, ф.день(-1, час[0]), 1, [строка(у1, Тариф=за_урок), строка(у2, Тариф=за_урок)], ГруппаОбучения=группа)
    ош, сооб = ф.записать(д)
    т.проверить(ош is None and c.String(перечитать(д).СтавкаПедагога) == c.String(с_чел)
                and [с[:2] for с in начисления(т, д)] == [("+", 600)],
                "ставка группы: групповой урок — ставка группы «с человека» 300 × 2 = 600 (не «за час» педагога)",
                ош or (c.String(перечитать(д).СтавкаПедагога), начисления(т, д)))
    час[0] += 1
    д = ф.урок(педагог_г, ф.день(-1, час[0]), 1, [строка(у1, Тариф=за_урок)])
    ош, сооб = ф.записать(д)
    т.проверить(ош is None and [с[:2] for с in начисления(т, д)] == [("+", 1000)],
                "ставка группы: индивидуальный урок того же педагога — его ставка «за час» 1 000", ош or начисления(т, д))
    ставка_по_умолчанию, ош = безопасно(lambda: c.Документы.УЗ_Урок.СтавкаПедагогаПоУмолчанию(педагог_г, группа))
    т.проверить(ош is None and c.String(ставка_по_умолчанию) == c.String(с_чел),
                "ставка группы: форма урока и календарь берут ставку группы (СтавкаПедагогаПоУмолчанию)", ош or ставка_по_умолчанию)


def установить_ставку_группы(группа, ставка):
    о = группа.ПолучитьОбъект()
    о.СтавкаПедагога = ставка
    о.Записать()


if __name__ == "__main__":
    запустить("логика_зарплата", сценарий)
