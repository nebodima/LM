"""Логика урока, часть 1: сценарии 1–10 из docs/логики/урок_и_списание.md §5 (числа — оттуда).

Цена строки — одна функция Документы.УЗ_Урок.ЦенаСтрокиУрока (В2, В8, В13, В20, В23, В25): абонемент строки →
тариф строки на дату урока; «за уроки» — сумма / уроки, «за часы» — пропорционально минутам урока; урок 0 ч по
часовому тарифу — отказ (В25); скидка к уроку по абонементу не применяется (В23). Тариф строки по умолчанию —
Документы.УЗ_Урок.ТарифСтрокиУченика: ученика → группы → урока (В20) — одинаково в форме, помощнике и панели.
Регистр УЗ_СписанияСуммЗаУроки — Расход: Сумма +, Часы +секунды на ученика, КоличествоУроков −1, КоличествоЯвок −1
только при явке.

Красные на старом коде (28.09.2026, база UZ_UNF_D до правки): №8 (урок 0 ч по часовому тарифу проводился с суммой 0),
№9 (функции ТарифСтрокиУченика не было; панель брала тариф группы 500 вместо личного 2 000), №10 (скидка 10 % к
абонементу: 720 вместо 800).

    python tools\\тесты\\тест_логика_урок.py --база=C:\\1c_bases\\UZ_UNF_D
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import запустить, текст_ошибки  # noqa: E402
from фабрика import Фабрика  # noqa: E402

МЕТКА = "_Тест логика урока"
ЧАС40 = 0.6667   # 40 минут (В13: 4 знака)


def безопасно(действие):
    """(значение, None) или (None, текст ошибки) — новая функция продукта на старом коде даёт красную проверку,
    а не падение всего теста."""
    try:
        return действие(), None
    except Exception as е:
        return None, текст_ошибки(е)


def деньги(значение):
    return round(float(значение or 0), 2)


def движения(т, урок):
    """Строки регистра УЗ_СписанияСуммЗаУроки урока: список словарей."""
    c = т.c
    тз = т.выбрать("""ВЫБРАТЬ Р.ВидДвижения КАК Вид, Р.Часы КАК Часы, Р.Сумма КАК Сумма, Р.КоличествоУроков КАК Уроков,
        Р.КоличествоЯвок КАК Явок, Р.Явка КАК Явка, Р.Абонемент КАК Абонемент
        ИЗ РегистрНакопления.УЗ_СписанияСуммЗаУроки КАК Р ГДЕ Р.Регистратор = &У УПОРЯДОЧИТЬ ПО Р.НомерСтроки""",
                   У=урок.Ссылка)
    расход = c.String(c.ВидДвиженияНакопления.Расход)
    итог = []
    for н in range(тз.Количество()):
        с = тз.Получить(н)
        итог.append(dict(Расход=c.String(с.Вид) == расход, Часы=float(с.Часы), Сумма=деньги(с.Сумма),
                         Уроков=float(с.Уроков), Явок=float(с.Явок), Явка=bool(с.Явка),
                         Абонемент=not с.Абонемент.Пустая()))
    return итог


def использовано(ф, абонемент):
    """Занятий абонемента использовано (Расход КоличествоУроков −1 на строку)."""
    return ф.число("""ВЫБРАТЬ ЕСТЬNULL(СУММА(-Р.КоличествоУроков), 0) ИЗ РегистрНакопления.УЗ_СписанияСуммЗаУроки КАК Р
        ГДЕ Р.Абонемент = &А И Р.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Расход)""", А=абонемент)


def строка(ученик, **поля):
    поля.setdefault("Явка", True)
    поля.setdefault("СписатьОплату", True)
    return dict(Ученик=ученик, **поля)


def перечитать(д):
    return д.Ссылка.ПолучитьОбъект()


def сценарий(т):
    c = т.c
    ф = Фабрика(т, МЕТКА)
    педагог = ф.педагог()
    ученик = ф.ученик()
    за_час = ф.элемент("УЗ_Тарифы", "1 000 за 1 ч", Сумма=1000, КоличествоЧасов=1)
    за_8 = ф.элемент("УЗ_Тарифы", "8 000 за 8 уроков", Сумма=8000, КоличествоУроков=8)

    # 1. тариф 1 000 за 1 ч, урок 40 мин, явка + «К оплате»
    д = ф.урок(педагог, ф.день(-1, 9), ЧАС40, [строка(ученик, Тариф=за_час)])
    ош, сооб = ф.записать(д)
    дв = движения(т, д)
    т.проверить(ош is None and деньги(д.Сумма) == 666.67, "1: 40 мин по 1 000 ₽/ч — сумма 666,67", ош or сооб or д.Сумма)
    т.проверить(len(дв) == 1 and дв[0]["Расход"] and дв[0]["Часы"] == 2400 and дв[0]["Сумма"] == 666.67
                and дв[0]["Уроков"] == -1 and дв[0]["Явок"] == -1,
                "1: регистр — Расход: Часы +2 400 с, Сумма 666,67, КолУроков −1, Явок −1", дв)
    т.проверить((перечитать(д).Окончание - перечитать(д).Дата).total_seconds() == 2400, "1: окончание = начало + 40 мин",
                перечитать(д).Окончание)

    # 2. урок 1 ч → 2 ч: 1 000 → 2 000
    д = ф.урок(педагог, ф.день(-1, 10), 1, [строка(ученик, Тариф=за_час)])
    ф.записать(д)
    было = деньги(перечитать(д).Сумма)
    о = перечитать(д)
    о.КоличествоЧасов = 2
    ош, сооб = ф.записать(о)
    т.проверить(было == 1000 and деньги(перечитать(д).Сумма) == 2000, "2: урок 1 ч → 2 ч по часовому тарифу: 1 000 → 2 000",
                "%s → %s %s" % (было, перечитать(д).Сумма, ош or ""))

    # 3. тариф 8 000 за 8 уроков, урок 2 ч — длительность не влияет
    д = ф.урок(педагог, ф.день(-1, 13), 2, [строка(ученик, Тариф=за_8)])
    ош, сооб = ф.записать(д)
    дв = движения(т, д)
    т.проверить(ош is None and деньги(д.Сумма) == 1000 and len(дв) == 1 and дв[0]["Часы"] == 7200,
                "3: поурочный тариф 8 000/8, урок 2 ч — 1 000, Часы +7 200 с", ош or дв)

    # 4–5. абонемент 6 400 / 8
    ученик_аб = ф.ученик("ученик с абонементом")
    аб = ф.абонемент(ученик_аб, "6 400 за 8", КоличествоЗанятий=8, ЦенаАбонемента=6400)
    д = ф.урок(педагог, ф.день(-1, 15), 1, [строка(ученик_аб, Тариф=за_8, Абонемент=аб, СписатьОплату=False)])
    ош, сооб = ф.записать(д)
    дв = движения(т, д)
    т.проверить(ош is None and len(дв) == 1 and дв[0]["Сумма"] == 0 and дв[0]["Уроков"] == -1 and дв[0]["Явок"] == -1
                and not дв[0]["Абонемент"] and использовано(ф, аб) == 0,
                "4: явка без «К оплате» с абонементом — сумма 0, КолУроков −1, Явок −1, абонемент не расходуется (Р7)",
                "%s %s исп. %s" % (ош or "", дв, использовано(ф, аб)))
    д = ф.урок(педагог, ф.день(-1, 16), 1, [строка(ученик_аб, Тариф=за_8, Абонемент=аб, Явка=False)])
    ош, сооб = ф.записать(д)
    дв = движения(т, д)
    т.проверить(ош is None and len(дв) == 1 and дв[0]["Сумма"] == 800 and дв[0]["Уроков"] == -1 and дв[0]["Явок"] == 0
                and not дв[0]["Явка"] and дв[0]["Абонемент"] and использовано(ф, аб) == 1,
                "5: неявка «К оплате» по абонементу 6 400/8 — 800, Явок 0, Явка = Ложь, занятие абонемента израсходовано (В3)",
                "%s %s исп. %s" % (ош or "", дв, использовано(ф, аб)))

    # 6. заметка к неоплачиваемой строке (настройка учёта)
    н = c.РегистрыСведений.УЗ_Настройки.СоздатьМенеджерЗаписи()
    н.Прочитать()
    было = (н.ТребоватьОписаниеКНеоплаченнымУрокам, н.ТребоватьОписаниеКНеоплаченнымУрокамС)

    def вернуть():
        в = c.РегистрыСведений.УЗ_Настройки.СоздатьМенеджерЗаписи()
        в.Прочитать()
        в.ТребоватьОписаниеКНеоплаченнымУрокам, в.ТребоватьОписаниеКНеоплаченнымУрокамС = было
        в.Записать()
    т.убрать(вернуть, "настройки учёта")
    н.ТребоватьОписаниеКНеоплаченнымУрокам = True
    н.ТребоватьОписаниеКНеоплаченнымУрокамС = ф.день(-30)
    н.Записать()
    ош, сооб = ф.записать(ф.урок(педагог, ф.день(-1, 17), 1, [строка(ученик, Явка=False, СписатьОплату=False)]))
    т.проверить(ош is not None and any("заметка" in с for с, _ in сооб), "6: нет явки, нет «К оплате», нет заметки — отказ",
                ош or сооб)
    д = ф.урок(педагог, ф.день(-1, 18), 1, [строка(ученик, Явка=False, СписатьОплату=False, Заметка="болел")])
    ош, сооб = ф.записать(д)
    т.проверить(ош is None and движения(т, д) == [], "6: с заметкой — проводится без движений", ош or движения(т, д))
    вернуть()

    # 7. часовой абонемент 5,3 ч (хотели 8 × 40 мин): 4 ч 40 мин + 40 мин = 19 200 с > 19 080 с
    ученик_ч = ф.ученик("ученик часового абонемента")
    аб_ч = ф.абонемент(ученик_ч, "5,3 ч", КоличествоЧасов=5.3, ЦенаАбонемента=5300)
    д = ф.урок(педагог, ф.день(-2, 8), 4.6667, [строка(ученик_ч, Абонемент=аб_ч)])
    ош, сооб = ф.записать(д)
    т.проверить(ош is None, "7: 7 занятий по 40 мин (4 ч 40 мин) по часовому абонементу 5,3 ч — проводится", ош or сооб)
    ош, сооб = ф.записать(ф.урок(педагог, ф.день(-2, 13), ЧАС40, [строка(ученик_ч, Абонемент=аб_ч)]))
    т.проверить(ош is not None and any("Не хватает" in с for с, _ in сооб),
                "7: восьмое занятие 40 мин — отказ «Не хватает» (19 200 с > 19 080 с)", ош or сооб)

    # 8. часовой тариф, урок 0 ч «К оплате» — отказ (В25), а не бесплатный урок
    ош, сооб = ф.записать(ф.урок(педагог, ф.день(-2, 15), 0, [строка(ученик, Тариф=за_час)]))
    т.проверить(ош is not None and any("0 ч" in с for с, _ in сооб),
                "8: урок 0 ч по часовому тарифу «К оплате» — отказ (было: сумма 0, молча бесплатно)", ош or сооб)

    # 9. личный «2 000 за 1 ч», группа с тарифом «4 000 за 8 уроков» — форма / помощник / панель одинаково (В20)
    from тест_панель_ученика import группа_обучения, список
    личный = ф.элемент("УЗ_Тарифы", "личный 2 000 за 1 ч", Сумма=2000, КоличествоЧасов=1)
    тариф_группы = ф.элемент("УЗ_Тарифы", "группа 4 000 за 8", Сумма=4000, КоличествоУроков=8)
    рок = ф.ученик("рок-школа")
    о = рок.ПолучитьОбъект()
    о.Тариф = личный
    о.Записать()
    новичок = ф.ученик("без личного тарифа")
    группа = группа_обучения(т, ф, "математика", педагог, тариф_группы)
    выбран, ош = безопасно(lambda: c.Документы.УЗ_Урок.ТарифСтрокиУченика(рок, группа))
    т.проверить(ош is None and c.String(выбран) == c.String(личный),
                "9: тариф строки — личный тариф ученика важнее тарифа группы (одна функция для формы и помощника)", ош or выбран)
    выбран, ош = безопасно(lambda: c.Документы.УЗ_Урок.ТарифСтрокиУченика(новичок, группа))
    т.проверить(ош is None and c.String(выбран) == c.String(тариф_группы), "9: без личного тарифа — тариф группы",
                ош or выбран)
    #урок 1,5 ч по личному тарифу — вне группы: старая панель брала тариф из прошлого урока ЭТОЙ группы
    д = ф.урок(педагог, ф.день(-3, 8), 1.5, [строка(рок, Тариф=личный)])
    ош, сооб = ф.записать(д)
    т.проверить(ош is None and деньги(д.Сумма) == 3000, "9: урок 1,5 ч по личному «2 000 за 1 ч» — 3 000",
                ош or сооб or д.Сумма)
    панель = c.Обработки.УЗ_ПанельУченика

    def убрать_уроки_группы():
        тз = т.выбрать("ВЫБРАТЬ У.Ссылка КАК Ссылка ИЗ Документ.УЗ_Урок КАК У ГДЕ У.ГруппаОбучения = &Г", Г=группа)
        for н in range(тз.Количество()):
            т.удалить_объект(тз.Получить(н).Ссылка, загрузка=True)
    т.убрать(убрать_уроки_группы, "уроки группы панели")
    итог = список(панель.ЗаписатьУченикаВГруппу(рок, группа, т.массив(панель.НачалоУрокаГруппы(группа, ф.день(-4)))))
    сумма = ф.число("""ВЫБРАТЬ СУММА(Р.Сумма) ИЗ РегистрНакопления.УЗ_СписанияСуммЗаУроки КАК Р
        ГДЕ Р.Клиент = &К И Р.Регистратор.ГруппаОбучения = &Г""", К=рок, Г=группа)
    т.проверить(len(итог) == 1 and итог[0].Успех and сумма == 2000,
                "9: панель ученика — урок группы 1 ч по личному тарифу 2 000 (было: тариф группы 500)",
                "%s; сумма %s" % ([(с.Описание, с.ДопОписание) for с in итог], сумма))

    # 10. абонемент 6 400 / 8 и скидка ученика 10 % — урок 800 (скидка уже в цене абонемента, В23)
    ученик_ск = ф.ученик("ученик со скидкой")
    аб_ск = ф.абонемент(ученик_ск, "6 400 за 8 со скидкой", КоличествоЗанятий=8, ЦенаАбонемента=6400)
    скидка = ф.элемент("УЗ_Скидки", "10 %", КоэффициентПроцент=10)
    д = ф.урок(педагог, ф.день(-3, 11), 1, [строка(ученик_ск, Тариф=за_8, Абонемент=аб_ск, Скидка=скидка)])
    ош, сооб = ф.записать(д)
    с = перечитать(д).Ученики.Получить(0)
    т.проверить(ош is None and деньги(с.Сумма) == 800 and деньги(с.СуммаСкидки) == 0,
                "10: урок по абонементу 6 400/8 со скидкой ученика 10 % — 800, скидка 0 (было 720: скидка второй раз)",
                "%s сумма %s скидка %s" % (ош or "", с.Сумма, с.СуммаСкидки))


if __name__ == "__main__":
    запустить("логика_урок", сценарий)
