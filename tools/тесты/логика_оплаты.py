"""Логика оплат (docs/логики/оплаты.md, сценарии с числами): баланс ученика — одна функция УЗ_Сервер.ОстатокДенегУченика
по организации, предмету и дате во всех местах оплат; бонусы (В24); возврат ограничен авансом (В5); абонемент в
возврате и списании; назначение платежа — из регистра.

Сценарии (организация А — своя тестовая, тариф 1 000 ₽/урок; «старый код» — src_ext до правок логик 28.09.2026):
  О1  ПКО 8 000 гитара, урок 1 000 → касса +8 000, гитара +7 000, долг к оплате 0.
  О2  ПКО 5 000 без предмета, урок математики 1 000 → долг по математике 0 (аванс без предмета зачитывается), всего
      +4 000. Старый код: «Рассчитать задолженность» по математике = 1 000 — деньги второй раз (функции долга не было).
  О3  ПКО 3 000 гитара + перемещение 2 000 вокал → гитара, 5 уроков гитары → неоплаченных уроков нет; 6-й урок —
      неоплаченный ровно он. Старый код: назначение считало только документы ПКО — уроки 4 и 5 «не оплачены».
  О4  карта 300 бонусов, ПКО 700 ₽ + 300 бонусов → касса +700, карта −300, баланс +1 000.
  О5  ПКО «Внутренняя касса», 0 ₽ + 300 бонусов → отказ. Старый код: проводился, ученику +300.
  О6  ПКО только бонусами (0 ₽ + 100) → печать без кассового ордера. Старый код: КО-1 «на 100 рублей».
  О7  ПКО 500 без кассы → отказ. Старый код: деньги в пустую кассу.
  О8  ПКО «Касса ученики» без ученика → отказ. Старый код: проводился.
  О9  аванс гитары 1 000, возврат 1 500 → отказ; возврат 1 000 → баланс 0, часы не тронуты (В5). Старый код: −500.
  О10 абонемент организации А 8 000: приход на основании — организация абонемента и неоплаченный остаток (8 000,
      после оплаты 5 000 — 3 000); 3 урока по абонементу; возврат на основании абонемента — 5 000, остаток
      абонемента 0. Старый код: организация из настроек и полная цена второй раз, РКО по абонементу не было.
  О11 гитара +3 000: перемещение 3 001 → отказ; 3 000 → гитара 0, вокал +3 000; гитара → гитара — отказ (старый код:
      проводилось).
  О12 списание остатков бонусами: карта 300, списать 500 → отказ; карта «Не действует» → отказ; −200 (начислить) на
      действующую → +200. Старый код: карта уходила в −200, просроченная списывалась.
  О13 списание остатков на основании ученика с оплаченным абонементом 5 000 → строка по абонементу, после проведения
      остаток абонемента 0. Старый код: строка без абонемента — абонемент «оплачено 5 000» навсегда.

    python tools\\тесты\\логика_оплаты.py --база=C:\\1c_bases\\UZ_UNF_C
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from сеанс import дата, запустить, текст_ошибки  # noqa: E402
from _деньги import Данные  # noqa: E402
from фабрика import Фабрика  # noqa: E402

МЕТКА = "_Тест логика оплат"


def сценарий(т):
    c = т.c
    д = Данные(т, МЕТКА)
    ф = Фабрика(т, МЕТКА)
    виды = c.Перечисления.УЗ_ВидыОпераций
    орг = ф.организация("А")
    касса = д.элемент("УЗ_Кассы", "касса")
    гитара = д.элемент("УЗ_ПредметыОбучения", "гитара")
    вокал = д.элемент("УЗ_ПредметыОбучения", "вокал")
    математика = д.элемент("УЗ_ПредметыОбучения", "математика")
    педагог = д.элемент("УЗ_ФизЛица", "педагог", ЭтоПедагог=True)
    тариф = д.элемент("УЗ_Тарифы", "1 000 за урок", Сумма=1000, КоличествоУроков=1, КоличествоЧасов=1)
    носитель = д.регистратор()

    def ученик(имя):
        return д.элемент("УЗ_ФизЛица", имя)

    def остаток(кто, предмет=None, абонемент=None):
        if абонемент is not None:
            тз = т.выбрать("ВЫБРАТЬ ЕСТЬNULL(СУММА(Ост.СуммаОстаток), 0) КАК Сумма ИЗ РегистрНакопления.УЗ_СписанияСуммЗаУроки."
                           "Остатки(, Абонемент = &Абонемент) КАК Ост", Абонемент=абонемент)
            return float(тз.Получить(0).Сумма)
        # None в COM приходит NULL — «все предметы» (Неопределено) только без аргумента
        if предмет is None:
            return float(c.УЗ_Сервер.ОстатокДенегУченика(кто, орг))
        return float(c.УЗ_Сервер.ОстатокДенегУченика(кто, орг, предмет))

    def долг(кто, предмет=None):
        try:
            if предмет is None:
                return float(c.УЗ_Сервер.ЗадолженностьУченика(кто, орг))
            return float(c.УЗ_Сервер.ЗадолженностьУченика(кто, орг, предмет))
        except Exception as е:
            return "ошибка: " + текст_ошибки(е, 100)

    def пко(кто, сумма, предмет=None, **поля):
        поля.setdefault("Касса", касса)
        поля.setdefault("ВидОперации", виды.КассаУченики)
        п = д.документ("УЗ_ПриходДенег", Дата=поля.pop("Дата", дата(2026, 9, 1, 9)), ФизЛицо=кто, СуммаДокумента=сумма,
                       Организация=орг, **поля)
        if предмет is not None:
            п.ПредметОбучения = предмет
        return п, д.записать(п)

    def урок_расход(кто, предмет, сумма, когда, **поля):
        """Урок «К оплате» деньгами — движением на носителе (урок ведёт свой агент)."""
        д.движения("УЗ_СписанияСуммЗаУроки", носитель, [("-", когда, dict({"Клиент": кто, "ПредметОбучения": предмет,
                                                                          "Сумма": сумма, "Организация": орг}, **поля))])

    # ── О1 ──
    у1 = ученик("О1")
    п, ош = пко(у1, 8000, гитара)
    урок_расход(у1, гитара, 1000, дата(2026, 9, 2, 10))
    т.проверить(ош is None and д.итог("УЗ_Касса", п.Ссылка)[0] == 8000 and остаток(у1, гитара) == 7000 and долг(у1, гитара) == 0,
                "О1: ПКО 8 000 гитара, урок 1 000 — касса +8 000, гитара +7 000, долг 0",
                (ош, остаток(у1, гитара), долг(у1, гитара)))

    # ── О2: аванс без предмета ──
    у2 = ученик("О2")
    _, ош = пко(у2, 5000)
    урок_расход(у2, математика, 1000, дата(2026, 9, 2, 10))
    т.проверить(ош is None and остаток(у2, математика) == -1000 and остаток(у2) == 4000 and долг(у2, математика) == 0
                and долг(у2) == 0,
                "О2: ПКО 5 000 без предмета, урок математики 1 000 — долг по математике 0, всего +4 000 (второй раз не берём)",
                (ош, остаток(у2, математика), остаток(у2), долг(у2, математика)))

    # ── О3: назначение платежа из регистра ──
    у3 = ученик("О3")
    пко(у3, 3000, гитара)
    пко(у3, 2000, вокал)
    пер = д.документ("УЗ_ПеремещениеДенег", Дата=дата(2026, 9, 1, 12), Клиент=у3, Сумма=2000, Организация=орг,
                     СделатьДвиженияПоВзаиморасчетам=True, ПредметОбученияОтправитель=вокал, ПредметОбученияПолучатель=гитара)
    ош_пер = д.записать(пер)

    def урок(день):
        у = ф.урок(педагог, дата(2026, 9, день, 10), 1, [dict(Ученик=у3, Тариф=тариф, Явка=True, СписатьОплату=True)],
                   Организация=орг, ПредметОбучения=гитара)
        return ф.записать(у)[0]
    ошибки_уроков = [о for о in (урок(день) for день in range(2, 7)) if о]

    def неоплаченные():
        try:
            return [(в.year, в.month, в.day) for в in c.УЗ_Сервер.НеоплаченныеУрокиУченика(у3, орг, гитара)]
        except Exception as е:
            return "ошибка: " + текст_ошибки(е, 100)
    т.проверить(ош_пер is None and not ошибки_уроков and остаток(у3, гитара) == 0 and неоплаченные() == [],
                "О3: ПКО 3 000 + перемещение 2 000 на гитару, 5 уроков по 1 000 — баланс 0, неоплаченных уроков нет",
                (ош_пер, ошибки_уроков, остаток(у3, гитара), неоплаченные()))
    ош = урок(7)
    т.проверить(ош is None and неоплаченные() == [(2026, 9, 7)],
                "О3: 6-й урок — неоплаченный ровно он (07.09)", (ош, неоплаченные()))

    # ── О4–О6, О12: бонусы ──
    у4 = ученик("О4")
    карта = ф.карта(у4, "карта")
    д.движения("УЗ_ДвижениеДисконтныхКарт", носитель, [("+", дата(2026, 9, 1, 8), {"ДисконтнаяКарта": карта, "Клиент": у4,
                                                                                 "СуммаБонусов": 300})])

    def бонусы():
        return float(c.Документы.УЗ_ПриходДенег.ОстатокБонусовКарты(карта))
    п, ош = пко(у4, 700, гитара, ДисконтнаяКарта=карта, СуммаБонусов=300)
    т.проверить(ош is None and д.итог("УЗ_Касса", п.Ссылка)[0] == 700 and бонусы() == 0 and остаток(у4, гитара) == 1000,
                "О4: ПКО 700 ₽ + 300 бонусов — касса +700, карта −300, баланс ученика +1 000",
                (ош, бонусы(), остаток(у4, гитара)))
    д.движения("УЗ_ДвижениеДисконтныхКарт", д.регистратор(), [("+", дата(2026, 9, 1, 8), {"ДисконтнаяКарта": карта,
                                                                                        "Клиент": у4, "СуммаБонусов": 300})])
    _, ош = пко(у4, 0, None, ВидОперации=виды.ВнутренняяКасса, ДисконтнаяКарта=карта, СуммаБонусов=300)
    т.проверить(ош is not None and "только в оплату ученика" in ош and бонусы() == 300 and остаток(у4) == 1000,
                "О5: ПКО «Внутренняя касса» бонусами — отказ, ученику не зачислено (было: +300)", ош)
    п, ош = пко(у4, 0, гитара, ДисконтнаяКарта=карта, СуммаБонусов=100, Касса=c.Справочники.УЗ_Кассы.ПустаяСсылка())
    печать = c.УЗ_Печать.СформироватьСвоейПечатью("Документ.УЗ_ПриходДенег", "ПКО", п.Ссылка).ТабличныйДокумент
    т.проверить(ош is None and т.найти_текст(печать, "только бонусами")
                and not т.найти_текст(печать, "ПРИХОДНЫЙ КАССОВЫЙ ОРДЕР") and остаток(у4, гитара) == 1100,
                "О6: ПКО только бонусами (100) без кассы проведён, печать — не кассовый ордер (было: КО-1 на 100 ₽)",
                (ош, т.найти_текст(печать, "ПРИХОДНЫЙ КАССОВЫЙ ОРДЕР")))

    # ── О7, О8: обязательные ──
    _, ош = пко(у1, 500, гитара, Касса=c.Справочники.УЗ_Кассы.ПустаяСсылка())
    т.проверить(ош is not None and "кассу" in ош, "О7: ПКО 500 без кассы — отказ (было: деньги в пустую кассу)", ош)
    _, ош = пко(c.Справочники.УЗ_ФизЛица.ПустаяСсылка(), 500, гитара)
    т.проверить(ош is not None and "ученика" in ош, "О8: ПКО «Касса ученики» без ученика — отказ", ош)

    # ── О9: возврат ≤ аванса (В5) ──
    def возврат(кто, сумма, предмет, **поля):
        р = д.документ("УЗ_РасходДенег", Дата=поля.pop("Дата", дата(2026, 9, 10, 10)), Касса=касса, ФизЛицо=кто,
                       ВидОперации=виды.КассаУченики, СуммаДокумента=сумма, Организация=орг, **поля)
        if предмет is not None:
            р.ПредметОбучения = предмет
        return р, д.записать(р)
    у9 = ученик("О9")
    пко(у9, 1000, гитара)
    _, ош = возврат(у9, 1500, гитара)
    т.проверить(ош is not None and "оплачено вперёд 1 000" in ош.replace("\xa0", " ") and остаток(у9, гитара) == 1000,
                "О9: аванс 1 000, возврат 1 500 — отказ (было: баланс −500)", ош)
    р, ош = возврат(у9, 1000, гитара)
    т.проверить(ош is None and остаток(у9, гитара) == 0 and д.итог("УЗ_СписанияСуммЗаУроки", р.Ссылка, "Часы")[0] == 0,
                "О9: возврат 1 000 — баланс 0, часы не тронуты (В5)", ош)

    # ── О10: приход и возврат на основании абонемента ──
    у10 = ученик("О10")
    аб = ф.абонемент(у10, "абонемент О10", ПредметОбучения=гитара, КоличествоЗанятий=8, ЦенаАбонемента=8000,
                     Организация=орг)

    def пко_по_абонементу(сумма=None):
        п = д.документ("УЗ_ПриходДенег")
        п.Заполнить(аб)
        заполнено = (c.String(п.Организация) == c.String(орг), float(п.СуммаДокумента))
        п.Дата, п.Касса = дата(2026, 9, 1, 9), касса
        if сумма is not None:
            п.СуммаДокумента = сумма
        return заполнено, д.записать(п)
    заполнено1, ош1 = пко_по_абонементу(5000)
    заполнено2, ош2 = пко_по_абонементу()
    т.проверить(заполнено1 == (True, 8000.0) and заполнено2 == (True, 3000.0) and ош1 is None and ош2 is None,
                "О10: приход на основании абонемента — организация абонемента, сумма — неоплаченный остаток: 8 000, "
                "после оплаты 5 000 — 3 000 (было: организация из настроек и снова 8 000)", (заполнено1, заполнено2, ош1, ош2))
    урок_расход(у10, гитара, 3000, дата(2026, 9, 3, 10), Абонемент=аб)
    р = д.документ("УЗ_РасходДенег")
    try:
        р.Заполнить(аб)
    except Exception as е:
        print("  (РКО на основании абонемента: %s)" % текст_ошибки(е, 100))
    заполнено = (c.String(р.ФизЛицо) == c.String(у10), c.String(р.Организация) == c.String(орг), float(р.СуммаДокумента))
    р.Дата, р.Касса = дата(2026, 9, 4, 10), касса
    ош_р = д.записать(р)
    т.проверить(заполнено == (True, True, 5000.0) and ош_р is None and остаток(у10, абонемент=аб) == 0 and остаток(у10) == 0,
                "О10: 3 урока по абонементу, возврат на основании абонемента — ученик, организация и 5 000 заполнены, "
                "остаток абонемента 0 (было: возврат мимо абонемента, «оплачен полностью»)", (заполнено, ош_р,
                                                                                    остаток(у10, абонемент=аб)))

    # ── О11: перемещение между предметами ──
    у11 = ученик("О11")
    пко(у11, 3000, гитара)

    def перемещение(сумма, с_предмета, на_предмет):
        п = д.документ("УЗ_ПеремещениеДенег", Дата=дата(2026, 9, 5, 10), Клиент=у11, Сумма=сумма, Организация=орг,
                       СделатьДвиженияПоВзаиморасчетам=True, ПредметОбученияОтправитель=с_предмета,
                       ПредметОбученияПолучатель=на_предмет)
        return д.записать(п)
    ош = перемещение(3001, гитара, вокал)
    т.проверить(ош is not None and "остаток" in ош, "О11: перемещение 3 001 при остатке 3 000 — отказ", ош)
    ош = перемещение(3000, гитара, вокал)
    т.проверить(ош is None and остаток(у11, гитара) == 0 and остаток(у11, вокал) == 3000,
                "О11: перемещение 3 000 — гитара 0, вокал +3 000", ош)
    ош = перемещение(100, вокал, вокал)
    т.проверить(ош is not None and "совпадают" in ош, "О11: вокал → вокал — отказ (было: проводилось)", ош)

    # ── О12: бонусы в списании остатков ──
    у12 = ученик("О12")
    карта12 = ф.карта(у12, "карта О12")
    нет = ф.карта(у12, "карта О12 не действует", НеДействует=True)
    д.движения("УЗ_ДвижениеДисконтныхКарт", носитель, [("+", дата(2026, 9, 1, 8), {"ДисконтнаяКарта": к, "Клиент": у12,
                                                                                 "СуммаБонусов": 300}) for к in (карта12, нет)])

    def списание_бонусов(к, сумма):
        с = д.документ("УЗ_СписаниеОстатков", Дата=дата(2026, 9, 6, 10), Организация=орг)
        стр = с.ДисконтныеКарты.Добавить()
        стр.ДисконтнаяКарта, стр.СуммаБонусов = к, сумма
        return д.записать(с)

    def бонусы12(к):
        return float(c.Документы.УЗ_ПриходДенег.ОстатокБонусовКарты(к))
    ош = списание_бонусов(карта12, 500)
    т.проверить(ош is not None and "Недостаточно бонусов" in ош and бонусы12(карта12) == 300,
                "О12: списание 500 бонусов с карты, где 300, — отказ (было: карта −200)", ош)
    ош = списание_бонусов(нет, 100)
    т.проверить(ош is not None and "не действует" in ош, "О12: списание с карты «Не действует» — отказ", ош)
    ош = списание_бонусов(карта12, -200)
    т.проверить(ош is None and бонусы12(карта12) == 500, "О12: строка −200 — начисление, карта +200", ош)

    # ── О13: списание остатков по абонементу ──
    у13 = ученик("О13")
    аб13 = ф.абонемент(у13, "абонемент О13", ПредметОбучения=гитара, КоличествоЗанятий=5, ЦенаАбонемента=5000)
    п = д.документ("УЗ_ПриходДенег")
    п.Заполнить(аб13)
    п.Дата, п.Касса, п.Организация = дата(2026, 9, 1, 9), касса, орг
    д.записать(п)
    с = д.документ("УЗ_СписаниеОстатков", Организация=орг)
    с.Заполнить(у13)
    с.Дата = дата(2026, 9, 8, 10)
    строки = [(c.String(стр.Абонемент), float(стр.Сумма)) for стр in с.ТЗСписания]
    ош = д.записать(с)
