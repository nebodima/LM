"""Тестовые объекты «УЗ тест …» в базе стенда: отчёт и, по ключу, уборка.

Тесты создают свои объекты с меткой в начале наименования или комментария («УЗ тест отчетов», «УЗ тест прав …»)
и убирают за собой. Оборванный прогон (снятый процесс, упавший COM) оставляет их в базе: в отчётах и списках
чужие строки, в остатках — чужие суммы. Этот скрипт — убрать то, что осталось.

Что считается тестовым (и только это):
  * элементы и группы своих справочников УЗ_* и заимствованных Организации/Пользователи — наименование
    начинается с «УЗ тест»;
  * документы УЗ_* — комментарий начинается с «УЗ тест», ИЛИ документ ссылается (реквизит шапки или строка
    табличной части) на тестовый элемент справочника: урок тестовой группы, ПКО тестового ученика — те же
    остатки теста; оставить их — значит оставить битые ссылки после удаления справочника;
  * записи независимых регистров сведений УЗ_* (цены тарифов, настройки ученика …), у которых измерение —
    тестовый элемент: без этого в регистре остались бы «<Объект не найден>»;
  * пользователи информационной базы с именем «УЗ тест …» (тест прав заводит менеджера и руководителя).

Уборка: документ — отмена проведения и удаление (не отменяется — например, дата запрета — движения снимаются
наборами записей по регистратору в режиме загрузки, как сеанс.удалить_объект); справочник — удаление, при
отказе — в режиме загрузки. Живые объекты без метки не трогаются. Замок базы — общий с деплоем и прогоном.

    python tools\\убрать_тестовые.py --база=C:\\1c_bases\\UZ_UNF                          — проверка (по умолчанию)
    python tools\\убрать_тестовые.py --база=C:\\1c_bases\\UZ_BP --пользователь=1 --исправить
    python tools\\убрать_тестовые.py --база=C:\\1c_bases\\UZ_UT --пользователь=Admin --проверка

Код выхода: --проверка — 1, если тестовые объекты есть; --исправить — 1, если после уборки хоть один остался.
"""
import os
import sys
import time

sys.dont_write_bytecode = True
ПАПКА = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(ПАПКА, "тесты"))
sys.path.insert(0, ПАПКА)
import сеанс  # noqa: E402
import отпечаток_src  # noqa: E402

МЕТКА = "УЗ тест"
ЗАИМСТВОВАННЫЕ = ("Организации", "Пользователи")
ЖДАТЬ_ЗАМОК = 180


def замок(база):
    """Замок базы, общий с деплоем и прогоном (%TEMP%\\уз_прогон\\<база>.lock). None — не дождались."""
    import msvcrt
    import tempfile
    папка = os.path.join(tempfile.gettempdir(), "уз_прогон")
    os.makedirs(папка, exist_ok=True)
    срок = time.time() + ЖДАТЬ_ЗАМОК
    while True:
        ф = open(os.path.join(папка, отпечаток_src.имя_базы(база) + ".lock"), "a+")
        ф.seek(0)
        try:
            msvcrt.locking(ф.fileno(), msvcrt.LK_NBLCK, 1)
            return ф
        except OSError:
            ф.close()
        if time.time() > срок:
            return None
        print("  базу держит деплой или прогон — жду 5 с", flush=True)
        time.sleep(5)


def выбрать(c, текст, **параметры):
    з = c.NewObject("Запрос")
    з.Текст = текст
    for к, в in параметры.items():
        з.УстановитьПараметр(к, в)
    return з.Выполнить().Выгрузить()


def колонка(т):
    return [т.Получить(н).Ссылка for н in range(т.Количество())]


class Уборка:
    def __init__(self, c):
        self.c = c
        self.справочники = {}      # имя справочника -> [ссылка]
        self.документы = {}        # имя документа -> [(ссылка, причина)]
        self.записи = {}           # регистр -> [(измерение, ссылка, записей)]
        self.пользователи = []     # имена пользователей ИБ

    # ── поиск ──
    def найти(self):
        c = self.c
        self.справочники, self.документы, self.записи, self.пользователи = {}, {}, {}, []
        for мд in c.Метаданные.Справочники:
            if not (мд.Имя.startswith("УЗ_") or мд.Имя in ЗАИМСТВОВАННЫЕ) or мд.ДлинаНаименования == 0:
                continue
            т = выбрать(c, "ВЫБРАТЬ Т.Ссылка КАК Ссылка ИЗ Справочник.%s КАК Т ГДЕ Т.Наименование ПОДОБНО &Метка"
                        % мд.Имя, Метка=МЕТКА + "%")
            if т.Количество():
                self.справочники[мд.Имя] = колонка(т)
        тестовые = c.NewObject("Массив")
        типы = []
        for имя, список in self.справочники.items():
            типы.append(c.NewObject("ОписаниеТипов", "СправочникСсылка." + имя))
            for с in список:
                тестовые.Добавить(с)

        def ссылается(тип):
            return any(тип.СодержитТип(т.Типы().Получить(0)) for т in типы)

        for мд in c.Метаданные.Документы:
            if not мд.Имя.startswith("УЗ_"):
                continue
            условия = []
            if мд.Реквизиты.Найти("Комментарий") is not None:
                условия.append("Д.Комментарий ПОДОБНО &Метка")
            if типы:
                for р in мд.Реквизиты:
                    if ссылается(р.Тип):
                        условия.append("Д.%s В (&Тестовые)" % р.Имя)
                for тч in мд.ТабличныеЧасти:
                    for р in тч.Реквизиты:
                        if ссылается(р.Тип):
                            условия.append("Д.Ссылка В (ВЫБРАТЬ Т.Ссылка ИЗ Документ.%s.%s КАК Т ГДЕ Т.%s В (&Тестовые))"
                                           % (мд.Имя, тч.Имя, р.Имя))
            if not условия:
                continue
            т = выбрать(c, "ВЫБРАТЬ РАЗЛИЧНЫЕ Д.Ссылка КАК Ссылка ИЗ Документ.%s КАК Д ГДЕ %s"
                        % (мд.Имя, "\n ИЛИ ".join(условия)), Метка=МЕТКА + "%", Тестовые=тестовые)
            if т.Количество():
                self.документы[мд.Имя] = колонка(т)
        if типы:
            подчинение = c.String(c.Метаданные.СвойстваОбъектов.РежимЗаписиРегистра.ПодчинениеРегистратору)
            for мд in c.Метаданные.РегистрыСведений:
                if not мд.Имя.startswith("УЗ_") or c.String(мд.РежимЗаписи) == подчинение:
                    continue
                for изм in мд.Измерения:
                    if not ссылается(изм.Тип):
                        continue
                    т = выбрать(c, "ВЫБРАТЬ Р.%s КАК Ссылка, КОЛИЧЕСТВО(*) КАК Записей ИЗ РегистрСведений.%s КАК Р "
                                   "ГДЕ Р.%s В (&Тестовые) СГРУППИРОВАТЬ ПО Р.%s" % (изм.Имя, мд.Имя, изм.Имя, изм.Имя),
                                Тестовые=тестовые)
                    for н in range(т.Количество()):
                        с = т.Получить(н)
                        self.записи.setdefault(мд.Имя, []).append((изм.Имя, с.Ссылка, int(с.Записей)))
        for п in c.ПользователиИнформационнойБазы.ПолучитьПользователей():
            if п.Имя.startswith(МЕТКА):
                self.пользователи.append(п.Имя)
        return self.всего()

    def всего(self):
        return (sum(len(с) for с in self.справочники.values()) + sum(len(с) for с in self.документы.values())
                + sum(len(с) for с in self.записи.values()) + len(self.пользователи))

    def отчет(self):
        c = self.c
        for имя, список in sorted(self.документы.items()):
            print("  Документ.%-35s %4d; например %s" % (имя, len(список), "; ".join(c.String(с) for с in список[:2])))
        for имя, список in sorted(self.справочники.items()):
            print("  Справочник.%-33s %4d; например %s" % (имя, len(список), "; ".join(c.String(с) for с in список[:3])))
        for имя, список in sorted(self.записи.items()):
            print("  РегистрСведений.%-28s ключей %3d, записей %4d" % (имя, len(список), sum(з for _, _, з in список)))
        if self.пользователи:
            print("  пользователи ИБ: %s" % ", ".join(self.пользователи))

    # ── уборка ──
    def убрать(self):
        c = self.c
        ошибки = []
        for имя, список in self.документы.items():
            for ссылка in список:
                о = ссылка.ПолучитьОбъект()
                if о is None:
                    continue
                try:
                    if о.Проведен:
                        о.Записать(c.РежимЗаписиДокумента.ОтменаПроведения)
                    о.Удалить()
                except Exception as е:
                    try:           # отмена проведения запрещена (дата запрета, проверки) — движения наборами
                        сеанс.удалить_объект(c, ссылка, загрузка=True)
                    except Exception as е2:
                        ошибки.append("Документ.%s %s: %s / %s" % (имя, c.String(ссылка), сеанс.текст_ошибки(е),
                                                                   сеанс.текст_ошибки(е2)))
        for имя, список in self.записи.items():
            менеджер = getattr(c.РегистрыСведений, имя)
            for изм, ссылка, _ in список:
                набор = менеджер.СоздатьНаборЗаписей()
                getattr(набор.Отбор, изм).Установить(ссылка)
                набор.ОбменДанными.Загрузка = True
                набор.Записать()
        # подчинённые и вложенные элементы уходят вместе с владельцем/группой — несколько проходов
        for _ in range(3):
            for имя, список in self.справочники.items():
                for ссылка in список:
                    о = ссылка.ПолучитьОбъект()
                    if о is None:
                        continue
                    try:
                        о.Удалить()
                    except Exception:
                        try:
                            сеанс.удалить_объект(c, ссылка, загрузка=True)
                        except Exception as е:
                            ошибки.append("Справочник.%s %s: %s" % (имя, c.String(ссылка), сеанс.текст_ошибки(е)))
        for имя in self.пользователи:
            п = c.ПользователиИнформационнойБазы.НайтиПоИмени(имя)
            if п is not None:
                try:
                    п.Удалить()
                except Exception as е:
                    ошибки.append("пользователь ИБ %s: %s" % (имя, сеанс.текст_ошибки(е)))
        return ошибки


def main():
    сеанс.настроить_вывод()
    база = сеанс.аргумент("база")
    if not база:
        sys.exit("укажите --база=C:\\1c_bases\\UZ_UNF (и --пользователь=, если не Администратор)")
    исправить = "--исправить" in sys.argv
    з = замок(база)
    if з is None:
        sys.exit("база занята деплоем или прогоном дольше %d с — не трогаю" % ЖДАТЬ_ЗАМОК)
    c, сек = сеанс.подключить(база, сеанс.аргумент("пользователь", сеанс.ПОЛЬЗОВАТЕЛЬ_ПО_УМОЛЧАНИЮ))
    print("база %s, подключение %.1f с, режим %s" % (база, сек, "исправить" if исправить else "проверка"))
    у = Уборка(c)
    н = time.time()
    всего = у.найти()
    у.отчет()
    print("тестовых объектов всего: %d (%.2f с)" % (всего, time.time() - н))
    if not исправить or not всего:
        return 1 if всего and not исправить else 0
    н = time.time()
    ошибки = у.убрать()
    for о in ошибки[:20]:
        print("  НЕ УДАЛЁН %s" % о)
    print("убрано за %.2f с; пересчёт:" % (time.time() - н))
    осталось = у.найти()
    у.отчет()
    print("тестовых объектов осталось: %d" % осталось)
    return 1 if осталось else 0


if __name__ == "__main__":
    sys.exit(main())
