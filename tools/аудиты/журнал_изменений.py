# -*- coding: utf-8 -*-
"""журнал_изменений — версия расширения описана в журнале изменений.

Правило проекта (как в «Путевых листах»): подняли <Version> в Configuration.xml — дописали блок
«## <версия> — …» в docs/журнал-изменений.md. Иначе покупатель получает .cfe с номером, про который нигде
не сказано, что в нём нового, а карточка Инфостарта расходится с поставкой (недостоверные сведения).

Проверяется:
  * у расширения есть <Version> (пустая версия — платформа не покажет, что стоит у покупателя);
  * в docs/журнал-изменений.md репозитория есть заголовок второго уровня, начинающийся этой версией
    («## 2.0.0.1 — …»); упоминание в тексте не считается — блок должен быть.

Каталог не репозиторий (выгрузка LM и т.п.) — сверять не с чем, аудит молчит (строка сводки).

    python tools/аудиты/журнал_изменений.py [каталог]
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import общее  # noqa: E402

ИМЯ = "журнал_изменений"
ЖУРНАЛ = os.path.join("docs", "журнал-изменений.md")


def проверить(исх):
    р = общее.Результат(ИМЯ)
    репо = общее.корень_репо(исх)
    if репо is None:
        р.сводка.append("каталог — не репозиторий УЗ и не фикстура: журнал не сверялся")
        return р
    конфигурация = os.path.join(исх.корень, "Configuration.xml")
    if not os.path.isfile(конфигурация):
        р.ошибка("Configuration.xml", 0, "нет Configuration.xml — версию расширения взять неоткуда")
        return р
    т = общее.читать(конфигурация)
    м = re.search(r"<Version>([^<]*)</Version>", т)
    версия = м.group(1).strip() if м else ""
    строка = т.count("\n", 0, м.start()) + 1 if м else 0
    if not версия:
        р.ошибка("Configuration.xml", строка, "у расширения пустая версия <Version> — у покупателя не видно, что стоит")
        return р
    журнал = os.path.join(репо, ЖУРНАЛ)
    if not os.path.isfile(журнал):
        р.ошибка(ЖУРНАЛ.replace("\\", "/"), 0, "нет журнала изменений — версия %s нигде не описана" % версия)
        return р
    заголовки = re.findall(r"(?m)^##\s+(\S+)", общее.читать(журнал))
    if версия not in заголовки:
        р.ошибка("Configuration.xml", строка, "версия %s не описана в %s: нет блока «## %s — …» (есть: %s)"
                 % (версия, ЖУРНАЛ.replace("\\", "/"), версия, ", ".join(заголовки[:5]) or "ни одного"))
    р.проверено = "версия %s, блоков в журнале %d" % (версия, len(заголовки))
    return р


if __name__ == "__main__":
    общее.запустить_один(sys.modules[__name__])
