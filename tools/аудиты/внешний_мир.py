# -*- coding: utf-8 -*-
"""внешний_мир — наружу из базы ходят только почта и HTTP провайдеров сообщений, и только через песочницу.

Повторный аудит 28.09.2026 (N05): тест оповещений мог отправить настоящие письма ученикам копии базы с рабочими
настройками SMTP. Теперь письмо уходит из единственной точки — функции Послать общего модуля УЗ_Почта, которая
ДО подключения к серверу SMTP проверяет песочницу сеанса (ПесочницаВключена: тесты включают её при подключении,
tools/тесты/сеанс.py). Этот аудит держит правило по исходникам:

  * Новый ИнтернетПочта — только в УЗ_Почта, в функциях Послать и ДоступностьИнтернетПочты;
  * в Послать проверка ПесочницаВключена() стоит раньше Подключиться(…);
  * ДоступностьИнтернетПочты подключается только к 127.0.0.1 (письмо никуда не уходит);
  * этап 2.2 (Telegram, SMS, WhatsApp): Новый HTTPСоединение — только в УЗ_ПровайдерыСообщений, в функциях
    ВыполнитьHTTP (единственная точка запросов к провайдерам) и ПроверитьHTTP (проба безопасного режима); в
    ВыполнитьHTTP проверка ПесочницаВключена() стоит раньше создания соединения, ПроверитьHTTP ходит только
    на 127.0.0.1;
  * других каналов наружу нет: HTTPСоединение вне провайдеров, FTPСоединение, WSПрокси/WSОпределения, COMОбъект,
    ЗапуститьПриложение/НачатьЗапускПриложения, КомандаСистемы. Понадобится канал — сделать для него такую же
    единственную точку с песочницей и защиту в тестах, потом добавить сюда разрешение.

Комментарии и строки не считаются.

    python tools/аудиты/внешний_мир.py [каталог]
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import общее  # noqa: E402

ИМЯ = "внешний_мир"
ПОЧТА = "CommonModules/УЗ_Почта/Ext/Module.bsl"
ТОЧКИ_ПОЧТЫ = {"послать", "доступностьинтернетпочты"}
ГРАНИЦА = r"(?<![\wЁё.])"
КАНАЛЫ = [
    (r"Новый\s+(HTTPСоединение|FTPСоединение|WSПрокси|WSОпределения|COMОбъект)\b", "Новый %s"),
    (r"New\s+(HTTPConnection|FTPConnection|WSProxy|WSDefinitions|COMObject)\b", "New %s"),
    (ГРАНИЦА + r"(ЗапуститьПриложение|НачатьЗапускПриложения|ЗапуститьПриложениеАсинх|КомандаСистемы|RunApp|System)\s*\(",
     "%s()"),
]
ПОЧТА_СОЗДАТЬ = r"Новый\s+ИнтернетПочта\b|New\s+InternetMail\b"
ПРОВАЙДЕРЫ = "CommonModules/УЗ_ПровайдерыСообщений/Ext/Module.bsl"
ТОЧКИ_HTTP = {"выполнитьhttp", "проверитьhttp"}
HTTP_СОЗДАТЬ = r"Новый\s+HTTPСоединение|New\s+HTTPConnection"


def тела(м):
    """{ключ имени процедуры: (начало, конец)} — смещения в коде модуля."""
    итог = {}
    объявления = м.объявления()
    for номер, (начало, имя, _) in enumerate(объявления):
        конец = объявления[номер + 1][0] if номер + 1 < len(объявления) else len(м.код)
        итог[общее.ключ(имя)] = (начало, конец)
    return итог


def процедура_в(тела_модуля, смещение):
    for имя, (н, к) in тела_модуля.items():
        if н <= смещение < к:
            return имя
    return None


def проверить(исх):
    р = общее.Результат(ИМЯ)
    модулей = 0
    for м in исх.модули():
        модулей += 1
        отн = исх.отн(м.путь).replace("\\", "/")
        к = м.код
        тела_модуля = None
        for шаблон, вид in КАНАЛЫ:
            for найд in re.finditer("(?i)" + шаблон, к):
                if отн.endswith(ПРОВАЙДЕРЫ) and re.match("(?i)" + HTTP_СОЗДАТЬ, найд.group(0)):
                    тела_модуля = тела_модуля or тела(м)
                    if процедура_в(тела_модуля, найд.start()) in ТОЧКИ_HTTP:
                        continue
                р.ошибка(отн, м.строка(найд.start()), "канал наружу %s без песочницы: сделать единую точку с "
                         "проверкой песочницы (как УЗ_Почта.Послать) и защиту в тестах" % (вид % найд.group(1)))
        for найд in re.finditer("(?i)" + ПОЧТА_СОЗДАТЬ, к):
            if отн.endswith(ПОЧТА):
                тела_модуля = тела_модуля or тела(м)
                if процедура_в(тела_модуля, найд.start()) in ТОЧКИ_ПОЧТЫ:
                    continue
            р.ошибка(отн, м.строка(найд.start()), "Новый ИнтернетПочта вне УЗ_Почта.Послать: письмо уйдёт мимо "
                     "песочницы (тесты на копиях баз разошлют его ученикам)")
        if отн.endswith(ПРОВАЙДЕРЫ):
            тела_модуля = тела_модуля or тела(м)
            if "выполнитьhttp" in тела_модуля:
                н, кон = тела_модуля["выполнитьhttp"]
                тело = к[н:кон]
                песочница = re.search(r"(?i)ПесочницаВключена\s*\(", тело)
                соединение = re.search("(?i)" + HTTP_СОЗДАТЬ, тело)
                if соединение and (not песочница or песочница.start() > соединение.start()):
                    р.ошибка(отн, м.строка(н + соединение.start()),
                             "ВыполнитьHTTP: соединение с сервисом без проверки ПесочницаВключена() перед ним")
            if "проверитьhttp" in тела_модуля:
                н, кон = тела_модуля["проверитьhttp"]
                адреса = [л for _, л, с in м.литералы if н <= с < кон and re.match(r"[\w.-]+\.\w+$|\d+\.\d+\.\d+\.\d+$", л)]
                if any(а != "127.0.0.1" for а in адреса):
                    р.ошибка(отн, м.строка(н), "ПроверитьHTTP подключается не к 127.0.0.1: %s" % ", ".join(адреса))
        if not отн.endswith(ПОЧТА):
            continue
        тела_модуля = тела_модуля or тела(м)
        if "послать" in тела_модуля:
            н, кон = тела_модуля["послать"]
            тело = к[н:кон]
            песочница = re.search(r"(?i)ПесочницаВключена\s*\(", тело)
            подключение = re.search(r"(?i)\.\s*Подключиться\s*\(", тело)
            if подключение and (not песочница or песочница.start() > подключение.start()):
                р.ошибка(отн, м.строка(н + подключение.start()),
                         "Послать: подключение к серверу SMTP без проверки ПесочницаВключена() перед ним")
        if "доступностьинтернетпочты" in тела_модуля:
            н, кон = тела_модуля["доступностьинтернетпочты"]
            адреса = [л for _, л, с in м.литералы if н <= с < кон and re.match(r"[\w.-]+\.\w+$|\d+\.\d+\.\d+\.\d+$", л)]
            if any(а != "127.0.0.1" for а in адреса):
                р.ошибка(отн, м.строка(н), "ДоступностьИнтернетПочты подключается не к 127.0.0.1: %s" % ", ".join(адреса))
    р.проверено = "модулей %d" % модулей
    return р


