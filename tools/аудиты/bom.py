# -*- coding: utf-8 -*-
"""bom — у каждого .bsl и .xml исходников есть метка UTF-8 (BOM), как в выгрузке платформы.

Перенесено из «Путевых листов» (проверка_bom.py). Платформа выгружает модули и разметку
с меткой; файл, записанный скриптом или редактором без неё, после следующей выгрузки из
базы «меняется» целиком в git — и настоящая правка тонет в шуме. В ПЛ проверка смотрела
только изменённые в git файлы и из-за экранированных кириллических путей полгода отвечала
«0» на всё; здесь проверяются все файлы исходников — без git, без путей в кавычках.

    python tools/аудиты/bom.py [каталог]
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import общее  # noqa: E402

ИМЯ = "bom"


def проверить(исх):
    р = общее.Результат(ИМЯ)
    файлов = 0
    for путь in исх.файлы(".bsl", ".xml"):
        файлов += 1
        with open(путь, "rb") as ф:
            if ф.read(3) != b"\xef\xbb\xbf":
                р.ошибка(исх.отн(путь), 1, "нет метки UTF-8 (BOM) — платформа выгружает с ней, файл «изменится» "
                         "целиком при следующей выгрузке")
    р.проверено = "файлов %d" % файлов
    return р


if __name__ == "__main__":
    общее.запустить_один(sys.modules[__name__])
