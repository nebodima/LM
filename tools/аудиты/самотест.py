def прогнать(действие=None, только=None):
    """Аудиты на копии фикстур с подложенным действием. только — список аудитов (мутации смотрят один свой аудит:
    так самотест укладывается в бюджет; чистые фикстуры и контроли гоняют все)."""
    временный = tempfile.mkdtemp(prefix="аудиты_самотест_")
    корень = os.path.join(временный, "src")
    try:
        shutil.copytree(ФИКСТУРЫ, корень)
        if действие:
            действие(корень)
        итог = {}
        for имя, р, ошибка, _ in все_аудиты.прогнать(корень, только=только):
            if р is None:
                raise RuntimeError("аудит %s упал:\n%s" % (имя, ошибка))
            итог[имя] = р
        return итог
    finally:
        shutil.rmtree(временный, ignore_errors=True)
        import стандарт_форм
        import качество_кода
        стандарт_форм.ИСКЛЮЧЕНИЯ_САМОТЕСТА.clear()
        качество_кода.ОСОЗНАННО_САМОТЕСТА.clear()


def показать(итог):
    for имя, р in итог.items():
        for з in р.ошибки + р.предупреждения:
            print("        %s: %s" % (имя, з))


def _случай(вид_случая, номер):
    """Один случай самотеста в отдельном процессе: мутация («м») смотрит свой аудит, контроль («к») — все."""
    if вид_случая == "м":
        аудит, _, _, действие = МУТАЦИИ[номер]
        р = прогнать(действие, [аудит])[аудит]
        return len(р.ошибки), len(р.предупреждения), ["%s: %s" % (аудит, з) for з in р.ошибки + р.предупреждения]
    итог = прогнать(КОНТРОЛИ[номер][1])
    return ["%s: %s" % (имя, з) for имя, р in итог.items() for з in р.ошибки + р.предупреждения]


def главный():
    общее.настроить_вывод()
    плохо = 0
    print("Чистые фикстуры:")
    чистые = прогнать()
    всего = sum(len(р.ошибки) + len(р.предупреждения) for р in чистые.values())
    print("  %s замечаний и предупреждений: %d" % ("[OK]" if всего == 0 else "[!!]", всего))
    if всего:
        плохо += 1
        показать(чистые)

    # случаи независимы (каждый — своя копия фикстур): параллельно по ядрам, печать — по порядку
    from concurrent.futures import ProcessPoolExecutor
    with ProcessPoolExecutor(max_workers=min(8, os.cpu_count() or 4)) as пул:
        мутации = list(пул.map(_случай, ["м"] * len(МУТАЦИИ), range(len(МУТАЦИИ)), chunksize=4))
        контроли = list(пул.map(_случай, ["к"] * len(КОНТРОЛИ), range(len(КОНТРОЛИ))))

    print("\nМутации (ровно одна подложенная ошибка → ровно одно замечание нужного аудита):")
    поймано = 0
    for номер, ((аудит, вид, что, _), (ошибок, предупреждений, замечания)) in enumerate(zip(МУТАЦИИ, мутации), 1):
        получено, другое = (ошибок, предупреждений) if вид == "ошибки" else (предупреждений, ошибок)
        ок = получено == 1 and другое == 0
        поймано += ок
        print("  %s %2d. %-24s %-15s %s — получено %d" % (
            "[OK]" if ок else "[!!]", номер, аудит, вид, что, получено))
        if not ок or ПОДРОБНО:
            for з in замечания:
                print("        " + з)

    print("\nКонтроли (законное, похожее на ошибку → 0 во всех аудитах):")
    ложных = 0
    for номер, ((что, _), замечания) in enumerate(zip(КОНТРОЛИ, контроли), 1):
        ложных += bool(замечания)
        print("  %s К%d. %s — замечаний %d" % ("[OK]" if not замечания else "[!!]", номер, что, len(замечания)))
        for з in замечания:
            print("        " + з)

    print("\n" + "=" * 70)
    print("поймано %d из %d" % (поймано, len(МУТАЦИИ)))
    print("ложных срабатываний %d из %d" % (ложных, len(КОНТРОЛИ)))
    покрытие = sorted(set(все_аудиты.АУДИТЫ) - {а for а, _, _, _ in МУТАЦИИ})
    if покрытие:
        print("аудиты без мутаций: " + ", ".join(покрытие))
    sys.exit(1 if плохо or поймано != len(МУТАЦИИ) or ложных or покрытие else 0)


if __name__ == "__main__":
    главный()
