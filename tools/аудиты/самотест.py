def прогнать(действие=None):
    временный = tempfile.mkdtemp(prefix="аудиты_самотест_")
    корень = os.path.join(временный, "src")
    try:
        shutil.copytree(ФИКСТУРЫ, корень)
        if действие:
            действие(корень)
        итог = {}
        for имя, р, ошибка, _ in все_аудиты.прогнать(корень):
            if р is None:
                raise RuntimeError("аудит %s упал:\n%s" % (имя, ошибка))
            итог[имя] = р
        return итог
    finally:
        shutil.rmtree(временный, ignore_errors=True)


def показать(итог):
    for имя, р in итог.items():
        for з in р.ошибки + р.предупреждения:
            print("        %s: %s" % (имя, з))


def главный():
    общее.настроить_вывод()
    плохо = 0
    print("Чистые фикстуры:")
    чистые = прогнать()
    всего = sum(len(р.ошибки) + len(р.предупреждения) for р in чистые.values())
    print("  %s замечаний и предупреждений: %d" % ("[OK]" if всего == 0 else "[!!]", всего))
    if всего:
        плохо += 1
        показать(чистые)

    print("\nМутации (ровно одна подложенная ошибка → ровно одно замечание нужного аудита):")
    поймано = 0
    for номер, (аудит, вид, что, действие) in enumerate(МУТАЦИИ, 1):
        итог = прогнать(действие)
        р = итог[аудит]
        получено = len(р.ошибки if вид == "ошибки" else р.предупреждения)
        другое = len(р.предупреждения if вид == "ошибки" else р.ошибки)
        ок = получено == 1 and другое == 0
        поймано += ок
        print("  %s %2d. %-24s %-15s %s — получено %d" % (
            "[OK]" if ок else "[!!]", номер, аудит, вид, что, получено))
        if not ок or ПОДРОБНО:
            показать({аудит: р})

    print("\nКонтроли (законное, похожее на ошибку → 0 во всех аудитах):")
    ложных = 0
    for номер, (что, действие) in enumerate(КОНТРОЛИ, 1):
        итог = прогнать(действие)
        всего = sum(len(р.ошибки) + len(р.предупреждения) for р in итог.values())
        ложных += bool(всего)
        print("  %s К%d. %s — замечаний %d" % ("[OK]" if not всего else "[!!]", номер, что, всего))
        if всего:
            показать(итог)

    print("\n" + "=" * 70)
    print("поймано %d из %d" % (поймано, len(МУТАЦИИ)))
    print("ложных срабатываний %d из %d" % (ложных, len(КОНТРОЛИ)))
    покрытие = sorted(set(все_аудиты.АУДИТЫ) - {а for а, _, _, _ in МУТАЦИИ})
    if покрытие:
        print("аудиты без мутаций: " + ", ".join(покрытие))
    sys.exit(1 if плохо or поймано != len(МУТАЦИИ) or ложных or покрытие else 0)


if __name__ == "__main__":
    главный()
