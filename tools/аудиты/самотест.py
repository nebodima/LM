def заменить(отн, старое, новое):
    def д(корень):
        п = os.path.join(корень, отн)
        т = общее.читать(п)
        if т.count(старое) != 1:
            raise AssertionError("мутация: «%s» в %s встречается %d раз" % (старое, отн, т.count(старое)))
        with open(п, "w", encoding="utf-8-sig", newline="") as ф:
            ф.write(т.replace(старое, новое))
    return д


def в_модуль(код):
    """Вставить процедуру в модуль объекта перед #КонецЕсли."""
    return заменить(ОМ, "\n#КонецЕсли", "\n" + код + "\n\n#КонецЕсли")


def в_форму(код):
    return заменить(ФМ, "\tОбъект.Расшифровка.Очистить();", код + "\n\tОбъект.Расшифровка.Очистить();")


def дописать(отн, текст):
    def д(корень):
        with open(os.path.join(корень, отн), "a", encoding="utf-8", newline="") as ф:
            ф.write(текст)
    return д


def без_bom(отн):
    def д(корень):
        п = os.path.join(корень, отн)
        with open(п, "rb") as ф:
            данные = ф.read()
        with open(п, "wb") as ф:
            ф.write(данные[3:] if данные[:3] == b"\xef\xbb\xbf" else данные)
    return д


def сплошная_картинка(отн):
    def д(корень):
        from PIL import Image
        Image.new("RGBA", (16, 16), (40, 90, 160, 255)).save(os.path.join(корень, отн))
    return д


def создать_копию(из_отн, в_отн, старое, новое):
    def д(корень):
        т = общее.читать(os.path.join(корень, из_отн)).replace(старое, новое)
        with open(os.path.join(корень, в_отн), "w", encoding="utf-8-sig", newline="") as ф:
            ф.write(т)
    return д


def удалить(*отн):
    def д(корень):
        for о in отн:
            os.remove(os.path.join(корень, о))
    return д


