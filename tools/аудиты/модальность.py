# -*- coding: utf-8 -*-
"""модальность — синхронных модальных вызовов нет.

В типовых УНФ/БП/УТ режим модальности запрещён: синхронный вызов в расширении
падает «Использование модальных окон в данном режиме запрещено», а в веб-клиенте
не работает вовсе. Правило владельца — модальных окон нет нигде. Замена:
ПоказатьВопрос / ПоказатьПредупреждение / ОткрытьФорму с ОписаниеОповещения,
НачатьПомещениеФайла, ДиалогВыбораФайла.Показать(…).

Ловим: Вопрос(, Предупреждение(, ОткрытьМодально(, ОткрытьФормуМодально(,
ВвестиЧисло/Строку/Дату/Значение(, Диалог.Выбрать() у ДиалогВыбораФайла,
синхронные ПоместитьФайл(ы)/ПолучитьФайл(ы), синхронное подключение и установку
расширения работы с файлами. Комментарии и строки не считаются; своя процедура
модуля с таким именем — тоже.

    python tools/аудиты/модальность.py [каталог] [--только-продукт]
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import общее  # noqa: E402

ИМЯ = "модальность"
_ГРАНИЦА = r"(?<![\wЁё.])"
ВЫЗОВЫ = [
    ("Вопрос", "Вопрос() → ПоказатьВопрос()"),
    ("Предупреждение", "Предупреждение() → ПоказатьПредупреждение() или оповещение"),
    ("ОткрытьФормуМодально", "ОткрытьФормуМодально() → ОткрытьФорму(…, ОписаниеОповещения)"),
    ("ВвестиЧисло", "ВвестиЧисло() → ПоказатьВводЧисла()"),
    ("ВвестиСтроку", "ВвестиСтроку() → ПоказатьВводСтроки()"),
    ("ВвестиДату", "ВвестиДату() → ПоказатьВводДаты()"),
    ("ВвестиЗначение", "ВвестиЗначение() → ПоказатьВводЗначения()"),
    ("ПоместитьФайл", "ПоместитьФайл() → НачатьПомещениеФайла()"),
    ("ПоместитьФайлы", "ПоместитьФайлы() → НачатьПомещениеФайлов()"),
    ("ПолучитьФайл", "ПолучитьФайл() → НачатьПолучениеФайлов()"),
    ("ПолучитьФайлы", "ПолучитьФайлы() → НачатьПолучениеФайлов()"),
    ("ПодключитьРасширениеРаботыСФайлами", "→ НачатьПодключениеРасширенияРаботыСФайлами()"),
    ("УстановитьРасширениеРаботыСФайлами", "→ НачатьУстановкуРасширенияРаботыСФайлами()"),
    ("ВыбратьЦвет", "ВыбратьЦвет() → ДиалогВыбораЦвета.Показать()"),
]


def проверить(исх):
    р = общее.Результат(ИМЯ)
    модулей = 0
    for м in исх.модули():
        модулей += 1
        к = м.код
        свои = {общее.ключ(имя) for _, имя, _ in м.объявления()}
        отн = исх.отн(м.путь)
        for имя, совет in ВЫЗОВЫ:
            if общее.ключ(имя) in свои:
                continue
            for найд in re.finditer(r"(?i)%s%s\s*\(" % (_ГРАНИЦА, имя), к):
                р.ошибка(отн, м.строка(найд.start()), "синхронный вызов " + совет)
        for найд in re.finditer(r"(?i)\.\s*ОткрытьМодально\s*\(", к):
            р.ошибка(отн, м.строка(найд.start()), "Форма.ОткрытьМодально() → ОткрытьФорму(…, ОписаниеОповещения)")
        диалоги = {общее.ключ(н.group(1)) for н in re.finditer(
            r"(?i)([\wЁё.]+)\s*=\s*Новый\s+ДиалогВыбораФайла", к)}
        for найд in re.finditer(r"(?i)([\wЁё.]+)\s*\.\s*Выбрать\s*\(\s*\)", к):
            if общее.ключ(найд.group(1)) in диалоги:
                р.ошибка(отн, м.строка(найд.start()),
                         "%s.Выбрать() у ДиалогВыбораФайла → .Показать(ОписаниеОповещения)" % найд.group(1))
    р.проверено = "модулей %d" % модулей
    return р


