# -*- coding: utf-8 -*-
"""начальная_страница — расширение не занимает начальную страницу хозяина.

Перенесено из «Путевых листов» (аудит_начальной_страницы.py; решение владельца 20.09.2026:
начальную страницу типовой конфигурации не заменяем). «Учёт занятий» встаёт на УНФ, БП, УТ:
у них на начальной странице свои формы («Пульс бизнеса», текущие дела), и двигать чужой
экран — особенно молча при первом входе — нельзя. Модуль приложения УЗ прямо обещает
«Начальную страницу и остальной запуск хозяина не трогаем»; аудит это стережёт.

Нарушения:
  * в Configuration.xml расширения объявлена HomePageWorkArea с формами, или есть
    Ext/HomePageWorkArea.xml с формами;
  * код (вне комментариев) пишет настройки начальной страницы: `НастройкиНачальнойСтраницы`,
    ключ хранилища «Общее/НастройкиНачальнойСтраницы», `ФормыНачальнойСтраницы`.

    python tools/аудиты/начальная_страница.py [каталог]
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import общее  # noqa: E402

ИМЯ = "начальная_страница"
ПРИЗНАК = re.compile(r"(?i)НастройкиНачальнойСтраницы|ФормыНачальнойСтраницы|HomePageSettings|"
                     r"ФормаНачальнойСтраницы|НачальнаяСтраница\s*\.")


def проверить(исх):
    р = общее.Результат(ИМЯ)
    for путь in (os.path.join(исх.корень, "Configuration.xml"),
                 os.path.join(исх.корень, "Ext", "HomePageWorkArea.xml")):
        if not os.path.isfile(путь) or исх.продукт:
            continue
        т = общее.читать(путь)
        for м in re.finditer(r"<HomePageWorkArea>(.*?)</HomePageWorkArea>|<WorkingAreaTemplate>", т, re.S):
            форм = re.findall(r"<Form>([^<]+)</Form>", м.group(0))
            if форм or м.group(0).startswith("<WorkingAreaTemplate>"):
                р.ошибка(исх.отн(путь), т.count("\n", 0, м.start()) + 1,
                         "расширение объявляет начальную страницу%s — у хозяина она своя, не занимаем"
                         % ((": " + ", ".join(форм)) if форм else ""))
                break
    модулей = 0
    for м in исх.модули():
        модулей += 1
        # код без комментариев — и строки отдельно: ключ хранилища настроек задают строкой
        места = [(м.строка(н.start()), н.group(0)) for н in ПРИЗНАК.finditer(м.код)]
        for лит in м.литералы:
            места += [(м.строка_в_литерале(лит, н.start()), н.group(0)) for н in ПРИЗНАК.finditer(лит[1])]
        for строка, что in sorted(места)[:1]:
            р.ошибка(исх.отн(м.путь), строка, "«%s» — код трогает начальную страницу хозяина" % что.strip(" ."))
    р.проверено = "модулей %d" % модулей
    return р


if __name__ == "__main__":
    общее.запустить_один(sys.modules[__name__])
