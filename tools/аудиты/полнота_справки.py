# -*- coding: utf-8 -*-
"""полнота_справки — у каждой формы, которую видит пользователь, есть справка F1; раздел знает про каждый объект.

Перенесено из «Путевых листов» (аудит_полноты_справки.py) и переведено на справку форм. Новую форму легко
завести и забыть рассказать о ней: F1 на ней откроет общую справку платформы, и покупатель решит, что справки
у продукта нет. Проверяем:

  * у каждой формы своих объектов есть Ext/Help.xml и Ext/Help/ru.html с настоящим текстом (не пустышка);
  * у каждого своего справочника и документа есть справка объекта (на неё ссылаются справки форм);
  * у каждого своего раздела верхнего уровня есть справка-оглавление, и она называет каждый объект, который
    стоит в видимых разделах (подраздел с IncludeInCommandInterface=false — служебный, его не требуем).

Формы, которые человек не открывает, названы ниже ПОИМЁННО с причиной — а не отброшены по маске: молча
отброшенная форма и есть та самая забытая. Исключение на форму, которой больше нет, — тоже замечание.

    python tools/аудиты/полнота_справки.py [каталог]
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import общее  # noqa: E402
import справка_общее as сп  # noqa: E402

ИМЯ = "полнота_справки"
МИНИМУМ_ТЕКСТА = 80     # символов текста: меньше — это заголовок без справки

ИСКЛЮЧЕНИЯ = {
}


def синоним(путь):
    текст = общее.читать(путь).split("<ChildObjects>")[0]
    м = re.search(r"<Synonym>\s*<v8:item>\s*<v8:lang>ru</v8:lang>\s*<v8:content>([^<]*)</v8:content>", текст)
    return м.group(1).strip() if м else ""


def слова(текст):
    """Слова по первым пяти буквам: справка склоняет названия («в кассовом журнале»), продукт — нет."""
    итог = []
    for слово in общее.ключ(текст).split():
        слово = слово.strip("«»\"',.;:()[]—–-/")
        if слово:
            итог.append(слово[:5])
    return итог


def разделы(исх):
    """[(xml, видим, [ссылки содержимого], отн_папки)] — все подсистемы с вложенными."""
    итог = []
    корень = os.path.join(исх.корень, "Subsystems")

    def обойти(папка, отн):
        if not os.path.isdir(папка):
            return
        for файл in sorted(os.listdir(папка)):
            if not файл.endswith(".xml"):
                continue
            имя = файл[:-4]
            текст = общее.читать(os.path.join(папка, файл))
            видим = "<IncludeInCommandInterface>false</IncludeInCommandInterface>" not in текст
            состав = re.findall(r"<xr:Item xsi:type=\"xr:MDObjectRef\">([^<]+)</xr:Item>", текст)
            итог.append((os.path.join(папка, файл), видим, состав, отн + [имя]))
            обойти(os.path.join(папка, имя, "Subsystems"), отн + [имя, "Subsystems"])

    обойти(корень, ["Subsystems"])
    return итог


def проверить(исх):
    р = общее.Результат(ИМЯ)
    страницы = {os.path.normcase(с.ext): с for с in сп.страницы(исх)}

    def справка(ext):
        с = страницы.get(os.path.normcase(ext))
        return с if с is not None and с.есть_xml and с.есть_html else None

    # ── формы ──
    форм = 0
    for ф in исх.формы():
        if not ф.своя:
            continue
        if ф.имя in ИСКЛЮЧЕНИЯ:
            continue
        форм += 1
        с = справка(os.path.dirname(ф.путь))
        if с is None:
            р.ошибка(ф.отн, 1, "у формы нет справки (Ext/Help.xml + Ext/Help/ru.html) — F1 откроет общую "
                     "справку платформы")
        elif len(с.текст) < МИНИМУМ_ТЕКСТА:
            р.ошибка(с.отн, 1, "справка формы пустая (%d символов текста) — заголовок без объяснения" % len(с.текст))
    for имя, почему in ИСКЛЮЧЕНИЯ.items():
        части = имя.split("/")
        владелец = исх.найти(общее.ВИДЫ.get(части[0], ""), части[1]) if len(части) > 1 else None
        if владелец is not None and not os.path.isfile(os.path.join(исх.корень, *части, "Ext", "Form.xml")):
            р.ошибка(имя, 0, "в ИСКЛЮЧЕНИЯХ форма, которой больше нет (%s) — убрать строку" % почему)

    # ── объекты ──
    объектов = 0
    for о in исх.объекты:
        if о.тип not in ("Catalog", "Document") or о.заимствован or not о.xml:
            continue
        объектов += 1
        ext = os.path.join(исх.корень, общее.ПАПКА_ВИДА[о.тип], о.имя, "Ext")
        с = справка(ext)
        if с is None:
            р.ошибка(исх.отн(о.xml), 1, "у объекта нет справки (Ext/Help.xml + Ext/Help/ru.html): «Подробнее» "
                     "из справки его форм ведёт в пустоту")
        elif len(с.текст) < МИНИМУМ_ТЕКСТА:
            р.ошибка(с.отн, 1, "справка объекта пустая (%d символов текста)" % len(с.текст))

    # ── разделы: оглавление называет каждый объект видимых разделов ──
    все = разделы(исх)
    текст_разделов = []
    for xml, видим, состав, отн in все:
        с = справка(os.path.join(исх.корень, *отн, "Ext"))
        if len(отн) == 2 and с is None:
            р.ошибка(исх.отн(xml), 1, "у раздела нет справки-оглавления — F1 в разделе откроет пустоту")
        if с is not None:
            текст_разделов.append(" ".join(слова(с.текст)))
    тело = " " + " ".join(текст_разделов) + " "
    названо = 0
    if текст_разделов:
        видимые = [(xml, состав) for xml, видим, состав, отн in все if видим]
        уже = set()
        for xml, состав in видимые:
            for ссылка in состав:
                тип, _, имя = ссылка.partition(".")
                о = исх.найти(тип, имя)
                if о is None or not о.xml or ссылка in уже:
                    continue
                уже.add(ссылка)
                назв = синоним(о.xml)
                if not назв:
                    continue
                названо += 1
                ч = слова(назв)
                полное, короткое = " ".join(ч), " ".join(ч[:2])
                if " %s " % полное not in тело and " %s " % короткое not in тело:
                    р.ошибка(исх.отн(xml), 1, "«%s» стоит в разделе, а оглавление справки о нём молчит" % назв)
    р.проверено = "форм %d (исключено %d), объектов %d, объектов в оглавлении %d" % (
        форм, len(ИСКЛЮЧЕНИЯ), объектов, названо)
    return р


