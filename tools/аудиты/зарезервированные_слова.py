import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import общее  # noqa: E402

ИМЯ = "зарезервированные_слова"

ЗАРЕЗЕРВИРОВАННЫЕ = """
И And Или Or Не Not По To Для For Каждого Each Из In Цикл Do Пока While Если If Тогда Then
Иначе Else ИначеЕсли ElsIf КонецЕсли EndIf КонецЦикла EndDo Возврат Return Новый New Знач Val
Перем Var Экспорт Export Попытка Try Исключение Except КонецПопытки EndTry ВызватьИсключение Raise
Прервать Break Продолжить Continue Перейти Goto Процедура Procedure Функция Function
КонецПроцедуры EndProcedure КонецФункции EndFunction Истина True Ложь False
Неопределено Undefined NULL Выполнить Execute ДобавитьОбработчик AddHandler
УдалитьОбработчик RemoveHandler Асинх Async Ждать Await
""".split()
ГЛОБАЛЬНЫЙ_КОНТЕКСТ = """
Метаданные Константы Справочники Документы Перечисления Обработки Отчеты РегистрыСведений
РегистрыНакопления ПараметрыСеанса ЭтотОбъект ЭтаФорма Элементы Символы
""".split()
ЗАПРЕЩЕНО = {общее.ключ(с): с for с in ЗАРЕЗЕРВИРОВАННЫЕ + ГЛОБАЛЬНЫЙ_КОНТЕКСТ}

СЛОВА_ЗАПРОСА = """
В И ИЛИ НЕ ПО ИЗ КАК ГДЕ ДЛЯ ЕСТЬ NULL ИСТИНА ЛОЖЬ НЕОПРЕДЕЛЕНО МЕЖДУ ПОДОБНО ВЫБОР
КОГДА ТОГДА ИНАЧЕ КОНЕЦ ВСЕ ПЕРВЫЕ РАЗЛИЧНЫЕ РАЗРЕШЕННЫЕ ИМЕЮЩИЕ ОБЪЕДИНИТЬ ИТОГИ
ПОМЕСТИТЬ УНИЧТОЖИТЬ ЛЕВОЕ ПРАВОЕ ВНУТРЕННЕЕ ПОЛНОЕ СОЕДИНЕНИЕ ВОЗР УБЫВ
ВЫБРАТЬ СГРУППИРОВАТЬ УПОРЯДОЧИТЬ
AND OR NOT IN AS BY FROM WHERE SELECT FOR IS NULL TRUE FALSE CASE WHEN THEN ELSE END ALL TOP
DISTINCT ALLOWED HAVING UNION TOTALS INTO DROP LEFT RIGHT INNER FULL JOIN ON ASC DESC
""".split()
# «КАК Ссылка» законно: ССЫЛКА — оператор, но псевдоним из него платформа принимает
СЛОВА_ЗАПРОСА = {общее.ключ(с) for с in СЛОВА_ЗАПРОСА}


def запрещено(имя):
    к = общее.ключ(имя)
    if к in ЗАПРЕЩЕНО:
        return "зарезервированное слово «%s»" % ЗАПРЕЩЕНО[к]
    if len(имя) == 1:
        return "однобуквенное имя «%s»" % имя
    return None


def проверить(исх):
    р = общее.Результат(ИМЯ)
    модулей = запросов = 0

    def отметить(м, смещ, где, имя):
        причина = запрещено(имя)
        if причина:
            р.ошибка(исх.отн(м.путь), м.строка(смещ), "%s: %s" % (где, причина))

    for м in исх.модули():
        модулей += 1
        к = м.код
        for смещ, имя, параметры in м.объявления():
            отметить(м, смещ, "имя процедуры/функции", имя)
            for п, п_смещ in параметры:
                отметить(м, п_смещ, "параметр «%s»" % имя, п)
        for найд in re.finditer(r"(?i)(?<![\wЁё.])Перем\s+([^;]+);", к):
            поз = найд.start(1)
            for часть in найд.group(1).split(","):
                с = re.match(r"\s*([\wЁё]+)", часть)
                if с:
                    отметить(м, поз + с.start(1), "Перем", с.group(1))
                поз += len(часть) + 1
        for найд in re.finditer(r"(?i)(?<![\wЁё.])Для\s+Каждого\s+([\wЁё]+)\s+Из(?![\wЁё])", к):
            отметить(м, найд.start(1), "Для Каждого", найд.group(1))
        for найд in re.finditer(r"(?i)(?<![\wЁё.])Для\s+([\wЁё]+)\s*=", к):
            отметить(м, найд.start(1), "счётчик Для", найд.group(1))
        for найд in re.finditer(r"(?im)(?:^|;|(?<![\wЁё])Тогда(?![\wЁё])|(?<![\wЁё])Иначе(?![\wЁё])|"
                                r"(?<![\wЁё])Цикл(?![\wЁё])|(?<![\wЁё])Попытка(?![\wЁё])|"
                                r"(?<![\wЁё])Исключение(?![\wЁё]))[ \t]*([А-Яа-яЁёA-Za-z_][\wЁё]*)[ \t]*=(?!=)", к):
            отметить(м, найд.start(1), "присваивание", найд.group(1))
        for лит in м.литералы:
            if not общее.это_запрос(лит[1]):
                continue
            запросов += 1
            текст = общее.очистить_запрос(лит[1])
            for найд in re.finditer(r"(?i)(?<![\wЁё])(?:КАК|AS)\s+([\wЁё]+)(?![\wЁё.])", текст):
                if общее.ключ(найд.group(1)) in СЛОВА_ЗАПРОСА:
                    р.ошибка(исх.отн(м.путь), м.строка_в_литерале(лит, найд.start()),
                             "псевдоним в запросе «КАК %s» — ключевое слово языка запросов" % найд.group(1))
    р.проверено = "модулей %d, текстов запросов %d" % (модулей, запросов)
    return р


