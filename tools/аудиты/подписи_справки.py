# -*- coding: utf-8 -*-
"""подписи_справки — каждая надпись в «ёлочках» из справки F1 существует в продукте.

Перенесено из «Путевых листов» (аудит_подписей_справки.py). Справка называет кнопки, поля, вкладки, документы
и отчёты в кавычках-ёлочках: «Записать и закрыть», «Кол-во уроков», «Панель ученика». Покупатель читает их как
точный адрес и ищет глазами ровно эту надпись. Если продукт переименовали, а справку — нет (или справку писали
по догадке, как черновик Codex 23.09 в ПЛ: «красный индикатор», несуществующий раздел), человек ищет то, чего
нет, и решает, что сломалось у него.

Словарь продукта: все <v8:content> исходников (заголовки элементов и команд, синонимы объектов, реквизитов,
значений перечислений), строки НСтр("ru = '…'") и заголовки, которые модули ставят сами (… .Заголовок = "…").
Плюс надписи платформы, которых в исходниках нет. Сравнение по словам с первыми пятью буквами: справка
склоняет («в „Кассовом журнале“»), продукт — нет; число слов своё, так что «Расход» ≠ «Расход денег (РКО)».

    python tools/аудиты/подписи_справки.py [каталог]
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import общее  # noqa: E402
import справка_общее as сп  # noqa: E402

ИМЯ = "подписи_справки"

# Кавычки стоят не только вокруг надписей: цитаты, примеры, пояснения. Надписью быть не может:
НЕ_ПОДПИСИ = re.compile(
    r"^(?:[а-яёa-z]|\d)"       # с маленькой буквы или с цифры — пример или оборот речи
    r"|^[^«»]{61,}$"           # длинная фраза: цитата сообщения, а не надпись
    r"|[.!?]$"                 # законченное предложение (сообщение программы)
)

# Надписи платформы и общие места, за которые продукт не отвечает (в исходниках их нет)
ПЛАТФОРМА = сп.КНОПКИ_ПЛАТФОРМЫ | сп.ВКЛАДКИ_ПЛАТФОРМЫ | {
    "Все функции", "Администрирование", "Главное меню", "Сервис", "Функции для технического специалиста",
    "Да", "Нет", "ОК", "Отмена", "Готово", "Далее", "Назад", "Наименование", "Код", "Дата", "Номер",
    "Проведен", "Пометка удаления", "Владелец", "Родитель", "Ссылка", "Период", "Регистратор",
}

# Посмотрено глазами и признано своим (пример данных, сообщение чужой конфигурации). Новая непарная надпись
# сюда сама не попадёт: её надо исправить или объяснить и внести руками.
СОГЛАСОВАНО = {
}


def ключ(надпись):
    слова = []
    for слово in сп.ключ(надпись).split():
        слово = слово.strip(".,:;()[]«»\"")
        if слово:
            слова.append(слово[:5])
    return " ".join(слова)


def надписи_продукта(исх):
    найдено = set()
    для_xml = re.compile(r"<v8:content>([^<]{2,160})</v8:content>")
    for путь in исх.файлы(".xml"):
        if os.path.basename(путь) == "Help.xml":
            continue
        for м in для_xml.finditer(общее.читать(путь)):
            найдено.add(м.group(1).strip())
    для_нстр = re.compile(r"НСтр\(\s*\"ru\s*=\s*'([^']{2,160})'")
    для_заголовка = re.compile(r"\.(?:Заголовок|Текст)\s*=\s*\"([^\"]{2,160})\"")     # и шапки отчётов, которые рисует код
    for м in исх.модули():
        for образец in (для_нстр, для_заголовка):
            for н in образец.finditer(м.текст):
                найдено.add(н.group(1).strip())
    for ф in исх.формы():
        найдено |= set(сп.надписи_формы(ф)[0])      # кнопки команд без заголовка — по имени команды
    return найдено


def проверить(исх):
    р = общее.Результат(ИМЯ)
    ключи = {ключ(н) for н in надписи_продукта(исх)}
    свои = {ключ(н) for н in ПЛАТФОРМА | set(СОГЛАСОВАНО)}
    всего = 0
    for стр in сп.страницы(исх):
        if not стр.есть_html:
            continue
        for м in re.finditer(r"«([^«»]{2,80})»", стр.текст):
            подпись = м.group(1).strip()
            if НЕ_ПОДПИСИ.search(подпись):
                continue
            всего += 1
            к = ключ(подпись)
            if к in ключи or к in свои:
                continue
            # склейка из двух: «Ещё → Изменить выделенные», «Настройки / Настройки почты»
            части = [ч.strip() for ч in re.split(r"→|/", подпись) if ч.strip()]
            if len(части) > 1 and all(ключ(ч) in ключи or ключ(ч) in свои for ч in части):
                continue
            р.ошибка(стр.отн, стр.строка(подпись), "«%s» — такой надписи в продукте нет" % подпись)
    р.проверено = "надписей в кавычках %d, надписей продукта %d" % (всего, len(ключи))
    return р


