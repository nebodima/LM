# -*- coding: utf-8 -*-
"""дубли_формы — одно и то же сведение на форме не должно быть дважды.

Перенесено из «Путевых листов» (аудит_дублей_формы.py). Форма растёт правками, и дубли
заводятся сами: поле перенесли на вкладку, а старое забыли; кнопка попала и в панель,
и в подменю. Человек видит два места для одного значения и правит их по-разному.

Дефекты:
  * один реквизит двумя полями ввода (одинаковый DataPath, оба доступны для ввода;
    копия «только просмотр» и надпись законны — они опознают строку);
  * одна команда двумя кнопками (кнопки контекстного меню не в счёт — меню дублирует панель
    по замыслу платформы);
  * пустые группы — обёртки, из которых поля вынесли;
  * поле без данных — поле ввода/флажок без DataPath, остаток прежней раскладки.

    python tools/аудиты/дубли_формы.py [каталог]
"""
import collections
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import общее  # noqa: E402

ИМЯ = "дубли_формы"
ПОЛЯ = {"InputField", "CheckBoxField", "LabelField", "PictureField", "RadioButtonField",
        "TextDocumentField", "HTMLDocumentField"}
КОНТЕЙНЕРЫ = {"UsualGroup", "Page", "ColumnGroup", "ButtonGroup", "Popup"}


def проверить(исх):
    р = общее.Результат(ИМЯ)
    форм = 0
    for ф in исх.формы():
        if not ф.своя:
            continue
        форм += 1
        родители = ф.родители()
        пути = collections.defaultdict(list)
        команды = collections.defaultdict(list)
        for узел in ф.корень.iter():
            тег = общее.местное(узел.tag)
            имя = узел.get("name", "")
            if тег in ПОЛЯ:
                путь = общее.свойство(узел, "DataPath")
                if путь:
                    читается = общее.свойство(узел, "ReadOnly") == "true" or тег == "LabelField"
                    if not читается:
                        пути[путь].append(имя)
                elif тег != "LabelField":
                    р.ошибка(ф.отн, ф.строка_элемента(имя), "%s «%s» без данных (нет DataPath) — остаток "
                             "прежней раскладки" % (тег, имя))
            elif тег == "Button":
                команда = общее.свойство(узел, "CommandName")
                у = узел
                в_меню = False
                while у in родители:
                    у = родители[у]
                    if общее.местное(у.tag) == "ContextMenu":
                        в_меню = True
                        break
                if команда and not в_меню:
                    команды[команда].append(имя)
            elif тег in КОНТЕЙНЕРЫ:
                дети = узел.find(общее.ЛФ + "ChildItems")
                if дети is not None and len(дети) == 0:
                    р.ошибка(ф.отн, ф.строка_элемента(имя), "пустая группа %s «%s»" % (тег, имя))
        for путь, имена in sorted(пути.items()):
            if len(имена) > 1:
                р.ошибка(ф.отн, ф.строка_элемента(имена[1]), "два поля ввода на «%s»: %s"
                         % (путь, ", ".join(имена)))
        for команда, кнопки in sorted(команды.items()):
            if len(кнопки) > 1:
                р.ошибка(ф.отн, ф.строка_элемента(кнопки[1]), "одна команда %s двумя кнопками: %s"
                         % (команда, ", ".join(кнопки)))
    р.проверено = "форм %d" % форм
    return р


