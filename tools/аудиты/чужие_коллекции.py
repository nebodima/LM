# -*- coding: utf-8 -*-
"""чужие_коллекции — обращения к элементам стиля и картинкам конфигурации-хозяина.

Перенесено из «Путевых листов» (аудит_чужих_коллекций.py). `ЦветаСтиля.X`, `ШрифтыСтиля.X`,
`БиблиотекаКартинок.X` берут элемент из КОНФИГУРАЦИИ, если он не платформенный: в УНФ он
есть, в БП или демо-пустышке может не быть, и форма падает целиком ещё до открытия
(«непредвиденная ошибка» вместо экрана). В ПЛ так дважды падала форма кода листа — ловил
только живой клик.

Чей элемент — решают выгрузки хозяев (те же, что у аудита сверка_хозяев): X есть среди
общих картинок / элементов стиля хоть одного хозяина — значит конфигурационный, и обращение
к нему из расширения — замечание (с перечнем, у кого его нет). Свои элементы (УЗ_…) и
платформенные (ДиалогИнформация, АктивныеПользователи… — их нет ни в одной выгрузке) законны.
Слой совместимости УЗ_Среда не проверяется. Модули БСП ловит аудит ноль_бсп.

    python tools/аудиты/чужие_коллекции.py [каталог]
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import общее  # noqa: E402
import сверка_хозяев  # noqa: E402

ИМЯ = "чужие_коллекции"
ОБРАЩЕНИЕ = re.compile(r"(?<![\wЁё.])(ЦветаСтиля|ШрифтыСтиля|БиблиотекаКартинок|StyleColors|StyleFonts|PictureLib)"
                       r"\s*\.\s*([\wЁё]+)")
ПАПКА = {"ЦветаСтиля": "StyleItems", "ШрифтыСтиля": "StyleItems", "StyleColors": "StyleItems",
         "StyleFonts": "StyleItems", "БиблиотекаКартинок": "CommonPictures", "PictureLib": "CommonPictures"}


def проверить(исх):
    р = общее.Результат(ИМЯ)
    свои = {общее.ключ(о.имя) for о in исх.объекты if о.тип in ("CommonPicture", "StyleItem") and not о.заимствован}
    хозяева = {и: п for и, п in сверка_хозяев.выгрузки(исх).items()
               if os.path.isfile(os.path.join(п, "Configuration.xml"))}
    if not хозяева:
        р.сводка.append("выгрузок хозяев нет — чьи элементы стиля и картинки, решить не с чем")
    модулей = 0
    for м in исх.модули():
        модулей += 1
        if общее.это_слой_совместимости(м.путь):
            continue
        for найд in ОБРАЩЕНИЕ.finditer(м.код):
            коллекция, имя = найд.groups()
            if общее.ключ(имя) in свои:
                continue
            есть = [х for х, п in хозяева.items() if os.path.isfile(os.path.join(п, ПАПКА[коллекция], имя + ".xml"))]
            if not есть:
                continue            # платформенный элемент — есть везде
            нет = [х for х in хозяева if х not in есть]
            р.ошибка(исх.отн(м.путь), м.строка(найд.start()),
                     "%s.%s — элемент конфигурации хозяина (%s%s), не расширения: где его нет, форма упадёт "
                     "до открытия" % (коллекция, имя, "есть: " + ", ".join(есть),
                                      ("; нет: " + ", ".join(нет)) if нет else "; нет в демо-пустышке"))
    р.проверено = "модулей %d, хозяев %d" % (модулей, len(хозяева))
    return р


if __name__ == "__main__":
    общее.запустить_один(sys.modules[__name__])
