# -*- coding: utf-8 -*-
"""имена — префикс УЗ_, ни следа LM_, ни латиницы внутри русского слова.

1. Каждый собственный объект расширения называется с «УЗ_»: расширение живёт в
   чужой конфигурации, префикс отличает наши объекты и исключает совпадения
   с объектами хозяина. Заимствованные (ObjectBelonging=Adopted) пропускаются,
   а вот собственные реквизиты/ТЧ/формы/команды внутри заимствованного объекта
   префикс обязаны иметь.
2. Подстроки «LM_» нет нигде — ни в именах, ни в коде, ни в комментариях.
3. В именах и идентификаторах нет латиницы вперемешку с кириллицей внутри слова:
   латинская «c» в «ПолучитьОстаткиЧаcовИСумм» — два разных имени для 1С и
   ошибка «не найдено», которую глазами не видно. Стык «ВыборWebЦвета» законен:
   считаем ошибкой строчную букву не своего алфавита сразу за буквой другого
   алфавита и одиночную «чужую» букву между буквами другого алфавита.

    python tools/аудиты/имена.py [каталог] [--только-продукт]
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import общее  # noqa: E402

ИМЯ = "имена"
_СЛОВО = re.compile(r"[\wЁё]+")


def _алфавит(с):
    if "a" <= с.lower() <= "z":
        return "lat"
    if "а" <= с.lower() <= "я" or с in "ёЁ":
        return "cyr"
    return None


def смешение(слово):
    """Описание смешения алфавитов в слове или None."""
    буквы = list(слово)
    for i in range(1, len(буквы)):
        а, б = _алфавит(буквы[i - 1]), _алфавит(буквы[i])
        if а and б and а != б:
            if буквы[i].islower():
                return "«%s»: %s буква «%s» сразу за «%s»" % (
                    слово, "латинская" if б == "lat" else "русская", буквы[i], буквы[i - 1])
            # одиночная чужая буква между двумя буквами другого алфавита: ОСТAТОК
            if i + 1 < len(буквы) and _алфавит(буквы[i + 1]) == а:
                return "«%s»: одиночная %s буква «%s»" % (
                    слово, "латинская" if б == "lat" else "русская", буквы[i])
    return None


def проверить(исх):
    р = общее.Результат(ИМЯ)
    объектов = 0

    # 1. префикс
    for о in исх.объекты:
        if о.тип == "Language":
            continue
        if о.заимствован:
            о.разобрать()
            for вид, имя, заимств in о.дочерние:
                if заимств is False and not имя.startswith(общее.ПРЕФИКС):
                    р.ошибка(исх.отн(о.xml), 0, "%s «%s» в заимствованном %s.%s — без префикса %s"
                             % (вид, имя, о.тип, о.имя, общее.ПРЕФИКС))
            if о.каталог:
                формы = os.path.join(о.каталог, "Forms")
                if os.path.isdir(формы):
                    for ф in sorted(os.listdir(формы)):
                        if ф.endswith(".xml"):
                            т = общее.читать(os.path.join(формы, ф)).split("<ChildObjects>")[0]
                            if "<ObjectBelonging>Adopted</ObjectBelonging>" not in т \
                                    and not ф.startswith(общее.ПРЕФИКС):
                                р.ошибка(исх.отн(os.path.join(формы, ф)), 0,
                                         "своя форма «%s» в заимствованном %s.%s — без префикса %s"
                                         % (ф[:-4], о.тип, о.имя, общее.ПРЕФИКС))
            continue
        объектов += 1
        if not о.имя.startswith(общее.ПРЕФИКС):
            р.ошибка(исх.отн(о.xml), 0, "%s.%s — имя без префикса %s" % (о.тип, о.имя, общее.ПРЕФИКС))

    # 2 и 3. LM_ и смешение алфавитов
    файлов = 0
    for путь in исх.файлы(".xml", ".bsl", ".html", ".htm", ".txt"):
        файлов += 1
        т = общее.читать(путь)
        отн = исх.отн(путь)
        for номер, строка in enumerate(т.splitlines(), 1):
            if "LM_" in строка:
                р.ошибка(отн, номер, "подстрока LM_: %s" % строка.strip()[:90])
        видено = set()

        def смесь(номер, слово):
            if (номер, слово) in видено:
                return
            видено.add((номер, слово))
            что = смешение(слово)
            if что:
                р.ошибка(отн, номер, "смешение алфавитов в имени " + что)

        if путь.endswith(".xml"):
            for найд in re.finditer(r"<Name>([^<]+)</Name>|\bname=\"([^\"]+)\"", т):
                имя = найд.group(1) or найд.group(2)
                номер = т.count("\n", 0, найд.start()) + 1
                for слово in _СЛОВО.findall(имя):
                    смесь(номер, слово)
        elif путь.endswith(".bsl"):
            м = общее.Модуль(путь, т)
            for найд in _СЛОВО.finditer(м.код):
                смесь(м.строка(найд.start()), найд.group(0))
            for лит in м.литералы:
                if общее.это_запрос(лит[1]):
                    for найд in _СЛОВО.finditer(лит[1]):
                        смесь(м.строка_в_литерале(лит, найд.start()), найд.group(0))
    р.проверено = "объектов %d, файлов %d" % (объектов, файлов)
    return р


if __name__ == "__main__":
    общее.запустить_один(sys.modules[__name__])
