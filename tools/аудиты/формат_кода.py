"""формат_кода — модули BSL оформлены одинаково: отступы, длина строк, пустые строки, области.

Вопрос владельца 28.09.2026: «код отформатирован?». Правила (как в стандартах 1С и в коде хозяев):

  * отступ — только табуляция: пробел в отступе (в том числе «таб + пробелы» для выравнивания) — замечание;
  * хвостовые пробелы и табы в конце строки (кроме строк внутри многострочного литерала — там это текст);
  * строка длиннее ДЛИНА символов (таб = 4) — перенести по операторам/параметрам;
  * между методами — пустая строка; три и больше пустых строк подряд — замечание;
  * #Область и #КонецОбласти парные; в большом модуле (от БОЛЬШОЙ_МОДУЛЬ строк) каждый метод — внутри
    области верхнего уровня из стандартного набора (ПрограммныйИнтерфейс, СлужебныеПроцедурыИФункции,
    ОбработчикиСобытий…): человек, открывший модуль, сразу видит, что наружу, а что внутреннее.

    python tools/аудиты/формат_кода.py [каталог]
"""
