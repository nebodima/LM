ИМЯ = "формат_кода"
ДЛИНА = 120
ТАБ = 4
БОЛЬШОЙ_МОДУЛЬ = 300
ОБЛАСТИ = ("ОписаниеПеременных", "ПрограммныйИнтерфейс", "СлужебныйПрограммныйИнтерфейс",
           "СлужебныеПроцедурыИФункции", "ОбработчикиСобытий", "ОбработчикиСобытийФормы",
           "ОбработчикиСобытийЭлементовШапкиФормы", "ОбработчикиСобытийЭлементовТаблицыФормы",
           "ОбработчикиКомандФормы", "ОбработчикиОповещений", "Инициализация")
_ОБЛАСТЬ = re.compile(r"(?im)^[ \t]*#(Область|Region)[ \t]+([\wЁё]+)|^[ \t]*#(КонецОбласти|EndRegion)\b")


def ширина(строка):
    return len(строка.expandtabs(ТАБ))


def стандартная_область(имя):
    return any(имя == о or (о == "ОбработчикиСобытийЭлементовТаблицыФормы" and имя.startswith(о)) for о in ОБЛАСТИ)


def в_литерале(м, смещение):
    """Смещение — внутри строкового литерала (между кавычками)."""
    начала = м.__dict__.get("_начала_литералов")
    if начала is None:
        начала = м._начала_литералов = [н for н, _ in м.диапазоны_литералов]
    i = bisect.bisect_right(начала, смещение - 1) - 1
    return i >= 0 and смещение < м.диапазоны_литералов[i][1]


def проверить(исх):
    р = общее.Результат(ИМЯ)
    модулей = строк_всего = 0
    for м in исх.модули():
        модулей += 1
        отн = исх.отн(м.путь)
        строки = м.текст.split("\n")
        строк_всего += len(строки)
        смещение = 0
        пустых = 0
        for номер, стр in enumerate(строки, 1):
            s = стр.rstrip("\r")
            отступ = re.match(r"[ \t]*", s).group(0)
            внутри = в_литерале(м, смещение)
            if " " in отступ and s.strip() and (not внутри or s.strip().startswith("|")):
                р.ошибка(отн, номер, "отступ пробелами — только табуляция")
            хвост = len(s) - len(s.rstrip(" \t"))
            if хвост and s.strip() and not в_литерале(м, смещение + len(s) - 1):
                р.ошибка(отн, номер, "пробелы в конце строки")
            if ширина(s) > ДЛИНА:
                р.ошибка(отн, номер, "строка %d символов (предел %d) — перенести" % (ширина(s), ДЛИНА))
            if s.strip():
                пустых = 0
            else:
                пустых += 1
                if пустых == 3 and not в_литерале(м, смещение):
                    р.ошибка(отн, номер, "три пустые строки подряд")
            смещение += len(стр) + 1

        методы = м.методы()
        for пред, след in zip(методы, методы[1:]):
            между = строки[пред.строка_конца:след.начало_шапки - 1]
            if not any(not с.strip() for с in между):
                р.ошибка(отн, след.начало_шапки, "%s: нет пустой строки перед методом" % след.имя)

        # области
        стек, верхние = [], []
        for о in _ОБЛАСТЬ.finditer(м.код):
            if о.group(2):
                стек.append((о.group(2), о.start()))
            elif стек:
                имя, нач = стек.pop()
                if not стек:
                    верхние.append((имя, нач, о.end()))
            else:
                р.ошибка(отн, м.строка(о.start()), "#КонецОбласти без #Область")
        for имя, нач in стек:
            р.ошибка(отн, м.строка(нач), "#Область %s без #КонецОбласти" % имя)
        if len(строки) >= БОЛЬШОЙ_МОДУЛЬ:
            for имя, нач, _ in верхние:
                if not стандартная_область(имя):
                    р.ошибка(отн, м.строка(нач), "область верхнего уровня «%s» не из стандартного набора — вложить "
                             "в ПрограммныйИнтерфейс/СлужебныеПроцедурыИФункции/ОбработчикиСобытий…" % имя)
            for мт in методы:
                if not any(н < мт.начало < к for _, н, к in верхние):
                    р.ошибка(отн, мт.строка, "%s: метод большого модуля (%d строк) вне области" % (мт.имя, len(строки)))
    р.проверено = "модулей %d, строк %d" % (модулей, строк_всего)
    return р


