"""сверка_хозяев — всё, на что расширение опирается у хозяина, есть во всех трёх конфигурациях.

Перенесено из «Путевых листов» (сверка_структуры_конфигураций.py) — там сверка шла по живым
базам через COM; здесь по XML-выгрузкам хозяев, офлайн, за доли секунды. Расширение читает
у хозяина организации, пользователей и (через УЗ_Среда) методы БСП. Обращения идут строкой
или через проверки, поэтому исчезнувший реквизит ничего не роняет — молча возвращает пустоту:
ПКО печатается без ИНН, автор не подставляется.

Опоры, которые сверяются с каждой выгрузкой хозяина:
  * заимствованные объекты и их заимствованные реквизиты — есть у хозяина;
  * поля таблиц хозяина в текстах запросов («Справочник.Организации КАК О» … «О.Поле»);
  * `УЗ_Общий.ЗначениеРеквизита(Организация…, "Поле")`, `Справочники.Пользователи.НайтиПоРеквизиту("Поле")`;
  * в УЗ_Среда: `ЕстьОбщийМодуль("М")`, `Вычислить("М.Метод(…)")` — модуль есть и метод экспортный,
    `НайтиПоПолномуИмени("ОбщаяФорма.Ф")` — форма есть.

Выгрузки хозяев: УНФ 3.0.12, БП, УТ 11.5 (ВЫГРУЗКИ ниже). Нет выгрузки на диске — предупреждение,
а не молчаливый ноль. У фикстур самотеста — свои мини-выгрузки в папке «_хозяева».

    python tools/аудиты/сверка_хозяев.py [каталог]
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import общее  # noqa: E402

ИМЯ = "сверка_хозяев"
ВЫГРУЗКИ = {
    "УНФ": r"C:\Users\User02\Documents\dumps\UNF_3012",
    "БП": r"C:\Users\User02\Documents\PRODIGY\cf_dump_bp",
    "УТ": r"C:\Users\User02\Documents\IMPORTTRADE\УТ_11_5",
}
СТАНДАРТНЫЕ = {общее.ключ(и) for и in (
    "Ссылка", "Наименование", "Код", "ПометкаУдаления", "Родитель", "Владелец", "Предопределенный",
    "ИмяПредопределенныхДанных", "ВерсияДанных", "ЭтоГруппа", "Представление", "Номер", "Дата", "Проведен",
    "Ref", "Description", "Code", "DeletionMark", "Parent", "Owner")}
ТАБЛИЦЫ = {"справочник": "Catalog", "документ": "Document", "регистрсведений": "InformationRegister"}
# ЗначениеРеквизита(<выражение>, "Поле"): чей реквизит — по слову в выражении
ПО_СЛОВУ = (("организац", "Организации"), ("пользовател", "Пользователи"))


def выгрузки(исх):
    свои = os.path.join(исх.корень, "_хозяева")
    if os.path.isdir(свои):
        return {и: os.path.join(свои, и) for и in sorted(os.listdir(свои))}
    if os.path.normcase(исх.корень) == os.path.normcase(os.path.abspath(общее.КАТАЛОГ_ПО_УМОЛЧАНИЮ)):
        return dict(ВЫГРУЗКИ)
    return {}


class Хозяин:
    def __init__(self, имя, корень):
        self.имя, self.корень, self._кэш = имя, корень, {}

    def файл(self, *части):
        путь = os.path.join(self.корень, *части)
        if путь not in self._кэш:
            self._кэш[путь] = общее.читать(путь) if os.path.isfile(путь) else None
        return self._кэш[путь]

    def объект(self, тип, имя):
        return self.файл(общее.ПАПКА_ВИДА[тип], имя + ".xml")

    def реквизиты(self, тип, имя):
        т = self.объект(тип, имя)
        if т is None:
            return None
        return {общее.ключ(и) for и in re.findall(r"<(?:Attribute|Dimension|Resource) uuid=[^>]*>\s*<Properties>"
                                                  r"\s*<Name>([^<]+)</Name>", т)}

    def экспорт(self, модуль, метод):
        т = self.файл("CommonModules", модуль, "Ext", "Module.bsl")
        if т is None:
            return None
        return bool(re.search(r"(?im)^[ \t]*(?:Процедура|Функция)[ \t]+%s[ \t]*\([^)]*\)[ \t]*Экспорт"
                              % re.escape(метод), т))


def _опоры(исх):
    """[(путь, строка, вид, данные)] — всё, что расширение берёт у хозяина."""
    опоры = []
    for о in исх.объекты:
        if not о.заимствован or not о.xml or о.тип in ("Configuration", "Language"):
            continue
        опоры.append((о.xml, 1, "объект", (о.тип, о.имя)))
        for вид, имя, заимств in о.разобрать().дочерние:
            if заимств and вид in ("Attribute", "Dimension", "Resource"):
                опоры.append((о.xml, 1, "реквизит", (о.тип, о.имя, имя)))
    def чужой_объект(тип, имя):
        о = исх.найти(тип, имя)
        return о is None or о.заимствован

    for м in исх.модули():
        for лит in м.литералы:
            т = лит[1]
            if not общее.это_запрос(т):
                continue
            т = общее.очистить_запрос(т)
            for н in re.finditer(r"(?i)(?<![\wЁё.])(Справочник|Документ|РегистрСведений)\.([\wЁё]+)\s+(?:КАК|AS)\s+"
                                 r"([\wЁё]+)", т):
                тип = ТАБЛИЦЫ[н.group(1).casefold()]
                if not чужой_объект(тип, н.group(2)):
                    continue
                for поле in re.finditer(r"(?<![\wЁё.])%s\.([\wЁё]+)" % re.escape(н.group(3)), т):
                    опоры.append((м.путь, м.строка_в_литерале(лит, поле.start()), "реквизит",
                                  (тип, н.group(2), поле.group(1))))
        код = м.код
        for н in re.finditer(r"ЗначениеРеквизита\(\s*([^,]+),", код):
            выражение = н.group(1).casefold()
            хвост = м.текст[н.end():н.end() + 80]
            имя = re.match(r'\s*"([\wЁё]+)"', хвост)
            if not имя:
                continue
            for слово, справочник in ПО_СЛОВУ:
                if слово in выражение:
                    опоры.append((м.путь, м.строка(н.start()), "реквизит", ("Catalog", справочник, имя.group(1))))
        for н in re.finditer(r"Справочники\.([\wЁё]+)\.НайтиПоРеквизиту\(", код):
            if not чужой_объект("Catalog", н.group(1)):
                continue
            имя = re.match(r'\s*"([\wЁё]+)"', м.текст[н.end():н.end() + 80])
            if имя:
                опоры.append((м.путь, м.строка(н.start()), "реквизит", ("Catalog", н.group(1), имя.group(1))))
        if общее.это_слой_совместимости(м.путь):
            for н in re.finditer(r'ЕстьОбщийМодуль\(\s*"([\wЁё]+)"', м.текст):
                опоры.append((м.путь, м.строка(н.start()), "модуль", н.group(1)))
            for н in re.finditer(r'(?:Вычислить|Выполнить)\(\s*"([\wЁё]+)\.([\wЁё]+)\s*\(', м.текст):
                опоры.append((м.путь, м.строка(н.start()), "метод", (н.group(1), н.group(2))))
            for н in re.finditer(r'НайтиПоПолномуИмени\(\s*"ОбщаяФорма\.([\wЁё]+)"', м.текст):
                опоры.append((м.путь, м.строка(н.start()), "форма", н.group(1)))
    return опоры


def проверить(исх):
    р = общее.Результат(ИМЯ)
    хозяева = []
    for имя, путь in выгрузки(исх).items():
        if os.path.isfile(os.path.join(путь, "Configuration.xml")):
            хозяева.append(Хозяин(имя, путь))
        else:
            р.предупреждение(путь, 0, "выгрузки хозяина %s нет — сверка с ним не выполнена" % имя)
    if not хозяева:
        р.сводка.append("выгрузок хозяев для этого каталога нет — сверка не выполнялась")
        return р
    опоры = _опоры(исх)
    видено = set()
    for путь, строка, вид, данные in опоры:
        for х in хозяева:
            беда = None
            if вид == "объект":
                if х.объект(*данные) is None:
                    беда = "нет объекта %s.%s" % данные
            elif вид == "реквизит":
                тип, объект, поле = данные
                if общее.ключ(поле) in СТАНДАРТНЫЕ:
                    continue
                реквизиты = х.реквизиты(тип, объект)
                if реквизиты is None:
                    беда = "нет объекта %s.%s" % (тип, объект)
                elif общее.ключ(поле) not in реквизиты:
                    беда = "у %s.%s нет реквизита «%s» — вернётся пустота" % (тип, объект, поле)
            elif вид == "модуль":
                if х.файл("CommonModules", данные + ".xml") is None:
                    беда = "нет общего модуля %s" % данные
            elif вид == "метод":
                есть = х.экспорт(*данные)
                if есть is None:
                    беда = "нет общего модуля %s" % данные[0]
                elif not есть:
                    беда = "у %s нет экспортного метода %s" % данные
            elif вид == "форма":
                if х.файл("CommonForms", данные + ".xml") is None:
                    беда = "нет общей формы %s" % данные
            ключ = (путь, строка, х.имя, беда)
            if беда and ключ not in видено:
                видено.add(ключ)
                р.ошибка(исх.отн(путь), строка, "%s: %s" % (х.имя, беда))
    р.проверено = "опор %d, хозяев %d (%s)" % (len(опоры), len(хозяева), ", ".join(х.имя for х in хозяева))
    return р


