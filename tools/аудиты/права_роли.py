"""права_роли — две роли продукта «как в типовых»: менеджер и руководитель; у секретов прав нет ни у одной.

Перенесено из «Путевых листов» (audit_rights.py). Там дважды обжигались: у новых отчётов и
команды не было права View — объект есть в метаданных и в подсистеме, а в интерфейсе
сотрудника его нет; справочник «Виды тары» был только на чтение, и добавить вид тары не мог
никто. Живой тест прав (tools/тесты/тест_права.py) ловит это на базе за минуты; этот аудит —
по исходникам за миллисекунды.

Правила (docs/роли_и_права.md):
  * УЗ_Руководитель («Учёт занятий: руководитель») — каждому своему объекту рабочий набор:
    справочник — чтение, просмотр, добавление, изменение, интерактивное добавление, редактирование,
    пометка удаления; документ — то же плюс проведение и отмена проведения; регистры — чтение,
    просмотр, изменение; отчёт и обработка — использование и просмотр; журнал — чтение и просмотр;
    общая команда, общая форма, подсистема, критерий отбора — просмотр; константа — чтение.
    Служебные: УЗ_ДатыЗапрета — чтение, просмотр, изменение, редактирование; УЗ_ВерсииДанных —
    чтение и изменение без просмотра;
  * УЗ_ОсновнаяРоль («Учёт занятий: менеджер») — рабочий набор, кроме МЕНЕДЖЕРУ (права ровно такие:
    зарплата, расходы, полная ведомость по кассе, выгрузка фото — никаких; ставки, настройки, версия
    данных — только чтение для кода; регистры зарплаты и расходов — только запись движений урока);
    РКО он записывает лишь с видом «Касса ученики» (условие на Insert/Update/Delete);
  * секреты: регистр и общая форма УЗ_НастройкиПочты (пароль SMTP) — прав НЕТ ни у одной роли;
  * InteractiveDelete / InteractiveDeleteMarked не выдаются никому: удаление мимо ссылочной
    проверки оставляет ссылки в никуда, для людей есть пометка удаления;
  * права на объект, которого нет в исходниках, — мусор после переименования;
  * повторный аудит 28.09.2026: у менеджера сняты «Просмотр» и «Редактирование» зарплатных полей урока и карточки
    педагога (S03), кассовый журнал читается с условием по дате &УЗ_НачалоПросмотраКассы (S04), у регистров
    накопления нет Edit — ручной правки движений (S02); права на параметры сеанса — ровно по списку.

    python tools/аудиты/права_роли.py [каталог]
"""
