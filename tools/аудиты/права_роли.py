def _правила_28_09(р, исх, путь, роль, права, известные):
    """S02–S04 и параметры сеанса (повторный аудит 28.09.2026)."""
    отн = исх.отн(путь)
    for полное, нужно in ПАРАМЕТРЫ_СЕАНСА.get(роль, {}).items():
        if not os.path.isfile(os.path.join(исх.корень, "SessionParameters", полное.split(".")[1] + ".xml")):
            continue
        выдано, строка, _ = права.get(полное, (set(), 0, ""))
        if выдано != нужно:
            р.ошибка(отн, строка, "%s — у роли %s права ровно: %s, а выдано: %s" % (
                полное, роль, ", ".join(sorted(нужно)), ", ".join(sorted(выдано)) or "ничего"))
    for полное, (выдано, строка, блок) in sorted(права.items()):
        for условие in re.findall(r"<condition>(.*?)</condition>", блок, re.S):
            параметр = re.search(r"&amp;(\w+)", условие)
            if параметр and os.path.isfile(os.path.join(исх.корень, "SessionParameters", параметр.group(1) + ".xml")):
                р.ошибка(отн, строка, "%s — в ограничении доступа роли %s параметр сеанса расширения &%s: в сеансе без "
                         "клиента (COM, фоновое и регламентное задание, HTTP) его никто не установит — чтение падает "
                         "«неинициализированного значения параметра сеанса»; границу держать в регистре и брать "
                         "подзапросом" % (полное, роль, параметр.group(1)))
        if полное.startswith("AccumulationRegister.") and полное.count(".") == 1 and "Edit" in выдано:
            р.ошибка(отн, строка, "%s — у роли %s право Edit: ручная правка движений в обход проведения и дат "
                     "запрета (движения пишет проведение — ему хватает Update; как в типовых — только «Полные "
                     "права»)" % (полное, роль))
    if роль != РОЛЬ:
        return
    т = общее.читать(путь)
    for объект, поля in ЗАРПЛАТНЫЕ_ПОЛЯ.items():
        if объект not in известные:
            continue
        for поле, снять in поля.items():
            полное = "%s.%s" % (объект, поле)
            м = re.search(r"<object>\s*<name>%s</name>(.*?)</object>" % re.escape(полное), т, re.S)
            снято = м and all(re.search(r"<name>%s</name>\s*<value>false</value>" % п, м.group(1)) for п in снять)
            if not снято:
                р.ошибка(отн, 0, "%s — у менеджера должно быть снято: %s (зарплата педагога видна в форме, списке и "
                         "настройке списка)" % (полное, ", ".join(снять)))
            elif "View" not in снять and re.search(r"<name>View</name>\s*<value>false</value>", м.group(1)):
                р.ошибка(отн, 0, "%s — «Просмотр» снимать нельзя: модуль формы обращается к элементу по имени, без "
                         "права платформа его не создаёт — форма не открывается" % полное)
    for полное in С_УСЛОВИЕМ_КАССЫ:
        if полное not in известные or полное not in права:
            continue
        _, строка, блок = права[полное]
        чтение = re.search(r"<name>Read</name>\s*<value>true</value>(.*?)</right>", блок, re.S)
        if чтение and УСЛОВИЕ_КАССЫ not in чтение.group(1):
            р.ошибка(отн, строка, "%s — чтение без условия по дате (подзапрос к %s): менеджер видит кассу старше "
                     "своей недели" % (полное, УСЛОВИЕ_КАССЫ))
    for полное in ЧТЕНИЕ_ГДЕ_ЛОЖЬ:
        if полное not in известные or полное not in права:
            continue
        _, строка, блок = права[полное]
        чтение = re.search(r"<name>Read</name>\s*<value>true</value>(.*?)</right>", блок, re.S)
        if чтение and not re.search(r"<condition>\s*ГДЕ\s+ЛОЖЬ\s*</condition>", чтение.group(1)):
            р.ошибка(отн, строка, "%s — «Чтение» менеджеру только с условием «ГДЕ ЛОЖЬ» (зарплата ему не видна)"
                     % полное)
    if ДОП_РАСХОДЫ in известные and ДОП_РАСХОДЫ in права:
        _, строка, блок = права[ДОП_РАСХОДЫ]
        чтение = re.search(r"<name>Read</name>\s*<value>true</value>(.*?)</right>", блок, re.S)
        if чтение and not УСЛОВИЕ_ДОП_РАСХОДОВ.search(чтение.group(1)):
            р.ошибка(отн, строка, "%s — «Чтение» менеджеру только документов по уроку (ГДЕ ДокументОснования <> "
                     "пустой урок): прочие доп. расходы ему не видны, а документ по уроку нужен проверке «один "
                     "источник расходов урока» (R06)" % ДОП_РАСХОДЫ)
    # журнал с условием чтения: у роли «Чтение» каждого документа журнала, иначе условие журнала не действует
    for полное, (выдано, строка, блок) in sorted(права.items()):
        if not полное.startswith("DocumentJournal.") or "Read" not in выдано or "<condition>" not in блок:
            continue
        xml = os.path.join(исх.корень, "DocumentJournals", полное.split(".")[1] + ".xml")
        if not os.path.isfile(xml):
            continue
        документы = re.findall(r'<xr:Item xsi:type="xr:MDObjectRef">(Document\.[^<.]+)</xr:Item>',
                               общее.читать(xml).split("</RegisteredDocuments>")[0])
        без_чтения = [д for д in документы if "Read" not in права.get(д, (set(), 0, ""))[0]]
        if без_чтения:
            р.ошибка(отн, строка, "%s — у журнала условие чтения, а у роли нет «Чтение» документов журнала: %s — "
                     "платформа тогда условие журнала не применяет (дайте «Чтение» с условием «ГДЕ ЛОЖЬ»)"
                     % (полное, ", ".join(без_чтения)))


def _состав(исх):
    """Полные имена своих объектов, которым нужны права (включая вложенные подсистемы)."""
    итог = []
    for о in исх.объекты:
        if о.заимствован or о.тип not in РАБОЧИЙ_НАБОР:
            continue
        if о.тип == "Subsystem":
            def обойти(имя, xml, каталог):
                итог.append(("Subsystem", имя, xml))
                папка = os.path.join(каталог, "Subsystems") if каталог else ""
                if os.path.isdir(папка):
                    for ф in sorted(os.listdir(папка)):
                        if ф.endswith(".xml"):
                            обойти("%s.Subsystem.%s" % (имя, ф[:-4]), os.path.join(папка, ф),
                                   os.path.join(папка, ф[:-4]))
            обойти(о.имя, о.xml, о.каталог)
        else:
            итог.append((о.тип, о.имя, о.xml))
    return итог


def _проверить_роль(р, исх, роль, состав, исключения):
    """Рабочий набор, исключения, секреты, опасные права, мусор. → {полное имя: (права, строка, блок)}"""
    путь = os.path.join(исх.корень, "Roles", роль, "Ext", "Rights.xml")
    т = общее.читать(путь)
    отн = исх.отн(путь)
    права = {}
    for м in re.finditer(r"<object>\s*<name>([^<]+)</name>(.*?)</object>", т, re.S):
        права[м.group(1)] = (set(re.findall(r"<name>(\w+)</name>\s*<value>true</value>", м.group(2))),
                             т.count("\n", 0, м.start()) + 1, м.group(2))
    известные = {"%s.%s" % (тип, имя) for тип, имя, _ in состав}
    for тип, имя, xml in состав:
        полное = "%s.%s" % (тип, имя)
        выдано, строка, _ = права.get(полное, (set(), 0, ""))
        if полное in СЕКРЕТЫ:
            if выдано:
                р.ошибка(отн, строка, "%s — секрет (пароль SMTP), у роли %s прав быть не должно, а выдано: %s"
                         % (полное, роль, ", ".join(sorted(выдано))))
            continue
        if полное in исключения:
            нужно = исключения[полное]
            if выдано != нужно:
                р.ошибка(отн, строка, "%s — у роли %s права ровно: %s, а выдано: %s" % (
                    полное, роль, ", ".join(sorted(нужно)) or "никаких", ", ".join(sorted(выдано)) or "ничего"))
            continue
        нет = [п for п in РАБОЧИЙ_НАБОР[тип] if п not in выдано]
        if not выдано:
            р.ошибка(отн, 0, "%s — прав в роли %s нет совсем: объект не виден" % (полное, роль))
        elif нет:
            р.ошибка(отн, строка, "%s — в роли %s не хватает прав: %s" % (полное, роль, ", ".join(нет)))
    for полное, (выдано, строка, _) in sorted(права.items()):
        for п in ОПАСНЫЕ:
            if п in выдано:
                р.ошибка(отн, строка, "%s — выдано %s: удаление мимо ссылочной проверки" % (полное, п))
        тип = полное.split(".", 1)[0]
        if тип in РАБОЧИЙ_НАБОР and ".Subsystem." not in полное.split(".", 2)[-1] and полное not in известные \
                and полное.split(".")[1].startswith(общее.ПРЕФИКС) and полное.count(".") == 1:
            р.ошибка(отн, строка, "%s — права на объект, которого нет в исходниках" % полное)
    return права


def _проверить_педагога(р, исх, путь, известные):
    """Роль педагога — только своё (правила ПЕДАГОГУ_* и шапка модуля)."""
    т = общее.читать(путь)
    отн = исх.отн(путь)
    права = {}
    for м in re.finditer(r"<object>\s*<name>([^<]+)</name>(.*?)</object>", т, re.S):
        права[м.group(1)] = (set(re.findall(r"<name>(\w+)</name>\s*<value>true</value>", м.group(2))),
                             т.count("\n", 0, м.start()) + 1, м.group(2))
    for полное, (выдано, строка, блок) in sorted(права.items()):
        if not выдано or полное.startswith("Configuration."):
            continue
        тип = полное.split(".", 1)[0]
        if полное in СЕКРЕТЫ:
            р.ошибка(отн, строка, "%s — секрет (пароль SMTP), у роли педагога прав быть не должно" % полное)
            continue
        if тип == "SessionParameter":
            лишние = выдано - ПЕДАГОГУ_ПАРАМЕТРЫ_СЕАНСА.get(полное, set())
            if лишние:
                р.ошибка(отн, строка, "%s — у роли педагога лишние права: %s" % (полное, ", ".join(sorted(лишние))))
            continue
        допустимо = ПЕДАГОГУ_ОБЯЗАТЕЛЬНО[полное] if тип == "DataProcessor" and полное in ПЕДАГОГУ_ОБЯЗАТЕЛЬНО \
            else ПЕДАГОГУ_ДОПУСТИМО.get(тип, set())
        лишние = выдано - допустимо
        if лишние:
            почему = ("отчёт на СКД без «Просмотр» уроков и физ. лиц у педагога пуст, зарплата — страница «Мои уроки»"
                      if тип in ("Report", "CommonForm", "CommonCommand", "DocumentJournal", "DataProcessor")
                      else "списки и карточки ему не нужны — данные даёт «Мои уроки»")
            р.ошибка(отн, строка, "%s — у роли педагога лишние права: %s (педагогу — только своё: %s)" % (
                полное, ", ".join(sorted(лишние)), почему))
        if тип == "Document":
            с_условием = {"Read", "Update"}
        elif тип == "AccumulationRegister" and полное not in ПЕДАГОГУ_ЧТЕНИЕ_БЕЗ_УСЛОВИЯ:
            с_условием = {"Read"}
        else:
            с_условием = set()
        for п in sorted(с_условием & выдано):
            м = re.search(r"<name>%s</name>\s*<value>true</value>(.*?)</right>" % п, блок, re.S)
            if not м or ПЕДАГОГУ_УСЛОВИЕ not in м.group(1):
                р.ошибка(отн, строка, "%s — у роли педагога право %s без ограничения по текущему пользователю "
                         "(Т.Педагог.Пользователь = &ТекущийПользователь): педагог читает и меняет чужие уроки и "
                         "видит чужую зарплату" % (полное, п))
    for полное, нужно in ПЕДАГОГУ_ОБЯЗАТЕЛЬНО.items():
        нет = нужно - права.get(полное, (set(), 0, ""))[0]
        if полное in известные and нет:
            р.ошибка(отн, 0, "%s — у роли педагога нет прав %s: рабочего места педагога нет" % (
                полное, ", ".join(sorted(нет))))
    for полное, (выдано, строка, _) in sorted(права.items()):
        тип = полное.split(".", 1)[0]
        if выдано and тип not in ("Configuration", "SessionParameter") and полное.count(".") == 1 \
                and полное.split(".")[1].startswith(общее.ПРЕФИКС) and полное not in известные:
            р.ошибка(отн, строка, "%s — права на объект, которого нет в исходниках" % полное)


def _основные_роли(р, исх):
    """Основных ролей у расширения быть не должно. Если у расширения в базе включено «Использовать основные роли
    для всех пользователей» (ИспользоватьОсновныеРолиДляВсехПользователей; загрузка конфигуратором его не меняет,
    БСП хозяина снимает только при обновлении ролей пользователей), основная роль достаётся КАЖДОМУ пользователю
    сверх его ролей: РольДоступна её не видит, а ПравоДоступа и запросы — видят. Так на копиях БП/УТ роль менеджера
    получали все, включая педагога (28.09.2026). Роли выдаются профилями групп доступа."""
    путь = os.path.join(исх.корень, "Configuration.xml")
    if not os.path.isfile(путь):
        return
    текст = общее.читать(путь)
    м = re.search(r"<DefaultRoles>(.*?)</DefaultRoles>", текст, re.S)
    if м and "<xr:Item" in м.group(1):
        р.ошибка(исх.отн(путь), текст[:м.start()].count("\n") + 1,
                 "у расширения основные роли (%s) — при «Использовать основные роли для всех пользователей» "
                 "их права получит каждый пользователь базы; оставить <DefaultRoles/>"
                 % ", ".join(re.findall(r"Role\.(\w+)", м.group(1))))


def проверить(исх):
    р = общее.Результат(ИМЯ)
    _основные_роли(р, исх)
    путь = os.path.join(исх.корень, "Roles", РОЛЬ, "Ext", "Rights.xml")
    if not os.path.isfile(путь):
        if исх.найти("Role", РОЛЬ) or not исх.продукт:
            р.ошибка("Roles/%s/Ext/Rights.xml" % РОЛЬ, 0, "нет файла прав основной роли — сотруднику не видно ничего")
        return р
    состав = _состав(исх)
    известные = {"%s.%s" % (тип, имя) for тип, имя, _ in состав}
    # менеджер: исключения — только для объектов, которые есть в исходниках
    права = _проверить_роль(р, исх, РОЛЬ, состав, {к: в for к, в in МЕНЕДЖЕРУ.items() if к in известные})
    _правила_28_09(р, исх, путь, РОЛЬ, права, известные)
    if РКО in известные and РКО in права:
        _, строка, блок = права[РКО]
        for п in ПРАВА_С_УСЛОВИЕМ:
            м = re.search(r"<name>%s</name>\s*<value>true</value>(.*?)</right>" % п, блок, re.S)
            if м and УСЛОВИЕ_РКО not in м.group(1):
                р.ошибка(исх.отн(путь), строка, "%s — у роли %s право %s без условия «%s»: менеджер запишет "
                         "выплату зарплаты или прочий расход" % (РКО, РОЛЬ, п, УСЛОВИЕ_РКО))
    # руководитель: обязателен, если в продукте есть зарплата
    путь_рук = os.path.join(исх.корень, "Roles", РОЛЬ_РУКОВОДИТЕЛЯ, "Ext", "Rights.xml")
    if os.path.isfile(путь_рук):
        права_рук = _проверить_роль(р, исх, РОЛЬ_РУКОВОДИТЕЛЯ, состав, СЛУЖЕБНЫЕ)
        _правила_28_09(р, исх, путь_рук, РОЛЬ_РУКОВОДИТЕЛЯ, права_рук, известные)
    elif "Document.УЗ_РасчетЗарплаты" in известные or исх.найти("Role", РОЛЬ_РУКОВОДИТЕЛЯ):
        р.ошибка("Roles/%s/Ext/Rights.xml" % РОЛЬ_РУКОВОДИТЕЛЯ, 0,
                 "нет файла прав роли руководителя — зарплату и настройки вести некому")
    путь_пед = os.path.join(исх.корень, "Roles", РОЛЬ_ПЕДАГОГА, "Ext", "Rights.xml")
    if os.path.isfile(путь_пед):
        _проверить_педагога(р, исх, путь_пед, известные)
    р.проверено = "своих объектов %d, объектов в роли менеджера %d" % (len(состав), len(права))
    return р


