# -*- coding: utf-8 -*-
"""права_роли — у каждого своего объекта есть рабочие права в УЗ_ОсновнаяРоль, у секретов — никаких.

Перенесено из «Путевых листов» (audit_rights.py). Там дважды обжигались: у новых отчётов и
команды не было права View — объект есть в метаданных и в подсистеме, а в интерфейсе
сотрудника его нет; справочник «Виды тары» был только на чтение, и добавить вид тары не мог
никто. Живой тест прав (tools/тесты/тест_права.py) ловит это на базе за минуты; этот аудит —
по исходникам за миллисекунды.

Правила (docs/роли_и_права.md):
  * своему объекту выдан рабочий набор: справочник — чтение, просмотр, добавление, изменение,
    интерактивное добавление, редактирование, пометка удаления; документ — то же плюс
    проведение и отмена проведения; регистры — чтение, просмотр, изменение; отчёт и обработка —
    использование и просмотр; журнал — чтение и просмотр; общая команда, общая форма,
    подсистема, критерий отбора — просмотр; константа — чтение;
  * служебные: УЗ_ДатыЗапрета — только чтение и просмотр (запись — администратору),
    УЗ_ВерсииДанных — чтение и изменение без просмотра;
  * секреты: регистр и общая форма УЗ_НастройкиПочты (пароль SMTP) — у роли прав НЕТ;
  * InteractiveDelete / InteractiveDeleteMarked не выдаются никому: удаление мимо ссылочной
    проверки оставляет ссылки в никуда, для людей есть пометка удаления;
  * права на объект, которого нет в исходниках, — мусор после переименования.

    python tools/аудиты/права_роли.py [каталог]
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import общее  # noqa: E402

ИМЯ = "права_роли"
РОЛЬ = "УЗ_ОсновнаяРоль"
РАБОЧИЙ_НАБОР = {
    "Catalog": ["Read", "View", "Insert", "Update", "InteractiveInsert", "Edit", "InteractiveSetDeletionMark"],
    "Document": ["Read", "View", "Insert", "Update", "InteractiveInsert", "Edit", "InteractiveSetDeletionMark",
                 "Posting", "UndoPosting", "InteractivePosting"],
    "InformationRegister": ["Read", "View", "Update"],
    "AccumulationRegister": ["Read", "View", "Update"],
    "Report": ["Use", "View"], "DataProcessor": ["Use", "View"],
    "DocumentJournal": ["Read", "View"],
    "CommonCommand": ["View"], "CommonForm": ["View"], "Subsystem": ["View"], "FilterCriterion": ["View"],
    "Constant": ["Read"],
}
# служебные объекты: права ровно такие (лишнее — тоже замечание)
СЛУЖЕБНЫЕ = {
    "InformationRegister.УЗ_ДатыЗапрета": {"Read", "View"},
    "InformationRegister.УЗ_ВерсииДанных": {"Read", "Update"},
}
СЕКРЕТЫ = {"InformationRegister.УЗ_НастройкиПочты", "CommonForm.УЗ_НастройкиПочты"}
ОПАСНЫЕ = ("InteractiveDelete", "InteractiveDeleteMarked")


def _состав(исх):
    """Полные имена своих объектов, которым нужны права (включая вложенные подсистемы)."""
    итог = []
    for о in исх.объекты:
        if о.заимствован or о.тип not in РАБОЧИЙ_НАБОР:
            continue
        if о.тип == "Subsystem":
            def обойти(имя, xml, каталог):
                итог.append(("Subsystem", имя, xml))
                папка = os.path.join(каталог, "Subsystems") if каталог else ""
                if os.path.isdir(папка):
                    for ф in sorted(os.listdir(папка)):
                        if ф.endswith(".xml"):
                            обойти("%s.Subsystem.%s" % (имя, ф[:-4]), os.path.join(папка, ф),
                                   os.path.join(папка, ф[:-4]))
            обойти(о.имя, о.xml, о.каталог)
        else:
            итог.append((о.тип, о.имя, о.xml))
    return итог


def проверить(исх):
    р = общее.Результат(ИМЯ)
    путь = os.path.join(исх.корень, "Roles", РОЛЬ, "Ext", "Rights.xml")
    if not os.path.isfile(путь):
        if исх.найти("Role", РОЛЬ) or not исх.продукт:
            р.ошибка("Roles/%s/Ext/Rights.xml" % РОЛЬ, 0, "нет файла прав основной роли — сотруднику не видно ничего")
        return р
    т = общее.читать(путь)
    отн = исх.отн(путь)
    права = {}
    for м in re.finditer(r"<object>\s*<name>([^<]+)</name>(.*?)</object>", т, re.S):
        права[м.group(1)] = (set(re.findall(r"<name>(\w+)</name>\s*<value>true</value>", м.group(2))),
                             т.count("\n", 0, м.start()) + 1)
    состав = _состав(исх)
    известные = {"%s.%s" % (тип, имя) for тип, имя, _ in состав}
    for тип, имя, xml in состав:
        полное = "%s.%s" % (тип, имя)
        выдано, строка = права.get(полное, (set(), 0))
        if полное in СЕКРЕТЫ:
            if выдано:
                р.ошибка(отн, строка, "%s — секрет (пароль SMTP), у роли прав быть не должно, а выдано: %s"
                         % (полное, ", ".join(sorted(выдано))))
            continue
        if полное in СЛУЖЕБНЫЕ:
            нужно = СЛУЖЕБНЫЕ[полное]
            if выдано != нужно:
                р.ошибка(отн, строка, "%s — служебный: права ровно %s, а выдано %s" % (
                    полное, ", ".join(sorted(нужно)), ", ".join(sorted(выдано)) or "ничего"))
            continue
        нет = [п for п in РАБОЧИЙ_НАБОР[тип] if п not in выдано]
        if not выдано:
            р.ошибка(отн, 0, "%s — прав в роли %s нет совсем: сотруднику объект не виден" % (полное, РОЛЬ))
        elif нет:
            р.ошибка(отн, строка, "%s — не хватает прав: %s" % (полное, ", ".join(нет)))
    for полное, (выдано, строка) in sorted(права.items()):
        for п in ОПАСНЫЕ:
            if п in выдано:
                р.ошибка(отн, строка, "%s — выдано %s: удаление мимо ссылочной проверки" % (полное, п))
        тип = полное.split(".", 1)[0]
        if тип in РАБОЧИЙ_НАБОР and ".Subsystem." not in полное.split(".", 2)[-1] and полное not in известные \
                and полное.split(".")[1].startswith(общее.ПРЕФИКС) and полное.count(".") == 1:
            р.ошибка(отн, строка, "%s — права на объект, которого нет в исходниках" % полное)
    р.проверено = "своих объектов %d, объектов в роли %d" % (len(состав), len(права))
    return р


if __name__ == "__main__":
    общее.запустить_один(sys.modules[__name__])
