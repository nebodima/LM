# -*- coding: utf-8 -*-
"""печать — параметры макетов, которые никто не заполняет, и параметры на текстовом формате.

Перенесено из «Путевых листов» (аудит_печати.py). Ячейка-параметр макета печатает то,
что положил в неё код; нет кода — в бланке пустое место, и заметить это можно, только
распечатав документ с полными данными («Тип контейнера» годами стоял пустым в журнале).

Сверяются два списка: параметры, объявленные в табличных макетах объекта (схемы
компоновки не в счёт), и параметры, которые код объекта или общих модулей задаёт:
`.Параметры.Имя = …`, `Параметры.Вставить("Имя")`, а при массовом заполнении
(`Параметры.Заполнить(…)`, `ЗаполнитьЗначенияСвойств(…)`) — псевдонимы «КАК Имя»
запросов (НЕ все слова модуля: так в ПЛ проверка не могла покраснеть по построению).

Второе правило: ячейка с <parameter>, чей формат объявлен <fillType>Text</fillType>, —
противоречие в самом файле: платформа такой параметр выбрасывает.
Третье: макет, имя которого не называет строкой ни один модуль объекта и ни один общий модуль
(ПолучитьМакет("Имя") вне комментариев), — мёртвый или забытый; его параметры не сверяются.

    python tools/аудиты/печать.py [каталог]
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import общее  # noqa: E402

ИМЯ = "печать"
ПЛАТФОРМЕННЫЕ = {"имямакета", "количествоэкземпляров", "синониммакета"}   # заполняет платформа/БСП


def _параметры_макета(т):
    имена = {}
    for м in re.finditer(r"<parameter>([^<]+)</parameter>", т):
        имена.setdefault(м.group(1).strip(), м.start())
    for м in re.finditer(r"\[([А-Яа-яЁёA-Za-z_][\wЁё.]*)\]", т):
        имена.setdefault(м.group(1).split(".")[0].strip(), м.start())
    return {и: с for и, с in имена.items() if общее.ключ(и) not in ПЛАТФОРМЕННЫЕ}


def _на_текстовом_формате(т):
    """[(параметр, смещение)] ячеек с <parameter>, чей формат верхнего уровня — fillType=Text."""
    заливка = []
    for н in [м.start() for м in re.finditer(r"\n\t<format>", т)]:
        конец = т.find("\n\t</format>", н)
        м = re.search(r"<fillType>(\w+)</fillType>", т[н:конец])
        заливка.append(м.group(1) if м else "")
    беды = []
    for ячейка in re.finditer(r"<c>\s*(?:<i>\d+</i>\s*)?<c>(.*?)</c>\s*</c>", т, re.S):
        параметр = re.search(r"<parameter>([^<]+)</parameter>", ячейка.group(1))
        формат = re.search(r"<f>(\d+)</f>", ячейка.group(1))
        if параметр and формат:
            f = int(формат.group(1))
            if f < len(заливка) and заливка[f] == "Text":
                беды.append((параметр.group(1).strip(), ячейка.start()))
    return беды


def _заполняемые(тексты):
    имена, псевдонимы, массовое = set(), set(), False
    for т in тексты:
        имена.update(re.findall(r"\.Параметры\.([\wЁё]+)\s*=", т))
        имена.update(re.findall(r'Параметры\.Вставить\(\s*"([\wЁё]+)"', т))
        if "Параметры.Заполнить(" in т or "ЗаполнитьЗначенияСвойств(" in т:
            массовое = True
        псевдонимы.update(re.findall(r"(?i)\b(?:КАК|AS)\s+([А-Яа-яЁёA-Za-z_][\wЁё]*)", т))
    итог = имена | (псевдонимы if массовое else set())
    return {общее.ключ(и) for и in итог}


def проверить(исх):
    р = общее.Результат(ИМЯ)
    общие_модули = [м for м in исх.модули() if "/CommonModules/" in м.путь.replace("\\", "/")]
    общие = [м.текст for м in общие_модули]
    макетов = параметров = 0
    for о in исх.объекты:
        if not о.каталог or о.заимствован:
            continue
        папка = os.path.join(о.каталог, "Templates")
        if not os.path.isdir(папка):
            continue
        свои_модули = [м for м in исх.модули()
                       if os.path.normcase(м.путь).startswith(os.path.normcase(о.каталог + os.sep))]
        код = _заполняемые([м.текст for м in свои_модули] + общие)
        # имена макетов, которые код называет строкой (ПолучитьМакет("Имя")) — вне комментариев
        названы = {общее.ключ(л[1]) for м in свои_модули + общие_модули for л in м.литералы}
        for имя in sorted(os.listdir(папка)):
            путь = os.path.join(папка, имя, "Ext", "Template.xml")
            if not os.path.isfile(путь):
                continue
            т = общее.читать(путь)
            if "http://v8.1c.ru/8.2/data/spreadsheet" not in т[:600]:
                continue            # схема компоновки, двоичный макет — не табличный документ
            макетов += 1
            if общее.ключ(имя) not in названы:
                р.ошибка(исх.отн(путь), 1, "%s.%s: макет не получает ни один модуль (ПолучитьМакет(\"%s\")) — "
                         "мёртвый или забытый" % (о.имя, имя, имя))
                continue
            параметры = _параметры_макета(т)
            параметров += len(параметры)
            for п, смещ in sorted(параметры.items()):
                if общее.ключ(п) not in код:
                    р.ошибка(исх.отн(путь), т.count("\n", 0, смещ) + 1,
                             "%s.%s: параметр «%s» никто не заполняет — в бланке будет пусто" % (о.имя, имя, п))
            for п, смещ in _на_текстовом_формате(т):
                р.ошибка(исх.отн(путь), т.count("\n", 0, смещ) + 1,
                         "%s.%s: параметр «%s» в ячейке с fillType=Text — платформа его выбросит" % (о.имя, имя, п))
    р.проверено = "табличных макетов %d, параметров %d" % (макетов, параметров)
    return р


