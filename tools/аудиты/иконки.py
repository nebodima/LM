# -*- coding: utf-8 -*-
"""иконки — где иконка нужна, а её нет, и где она задана мимо цели.

Перенесено из «Путевых листов» (аудит_иконок.py). Кнопка без иконки в плотной панели
читается медленнее подписи; а иконка, заданная «мимо цели», хуже отсутствующей: разметка
выглядит одетой, а на экране пусто, и следующий проход считает место сделанным.

Проверяется (только свои формы и объекты):
  * кнопка командной панели своей команды без картинки (ни у кнопки, ни у команды);
  * картинка есть, а режим отображения (Representation) не задан — видна одна подпись;
  * Representation=Text при заданной картинке — картинку гасит;
  * вкладка без картинки, когда у соседних вкладок того же набора картинки есть;
  * своя общая команда и своя подсистема без картинки;
  * HeaderPicture у поля вне таблицы — у поля нет шапки, платформа свойство отбрасывает;
  * своя картинка (CommonPicture.УЗ_…) на стандартной команде — у неё картинка платформы;
  * ссылка на CommonPicture.УЗ_…, которой нет в библиотеке расширения.

Не перенесено правило ПЛ «у карточки кнопка записи объявлена явно» — это решение владельца
ПЛ о виде панели, для «Учёта занятий» такого решения нет.

    python tools/аудиты/иконки.py [каталог]
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import общее  # noqa: E402

ИМЯ = "иконки"
ЛФ = общее.ЛФ
СТАНДАРТНЫЕ = re.compile(r"StandardCommand\.|^Form\.Command\.(Записать|Провести|ПровестиИЗакрыть|"
                         r"ЗаписатьИЗакрыть|ОтменитьПроведение|УстановитьПометкуУдаления)$")
ССЫЛКА = re.compile(r"CommonPicture\.([\wЁё]+)")


def _картинка_команды(ф, команда, общие_с_картинкой):
    """Есть ли картинка у команды, которую вызывает кнопка (её кнопка наследует)."""
    if команда.startswith("Form.Command."):
        имя = команда.split(".", 2)[2]
        блок = ф.корень.find(ЛФ + "Commands")
        if блок is not None:
            for к in блок:
                if к.get("name") == имя:
                    return к.find(ЛФ + "Picture") is not None
        return False
    if команда.startswith("CommonCommand."):
        return команда.split(".", 1)[1] in общие_с_картинкой
    м = re.match(r"(\w+)\.([\wЁё]+)\.Command\.([\wЁё]+)$", команда)
    if м:
        о = ф.исх.найти(м.group(1), м.group(2))
        if о and о.xml:
            т = общее.читать(о.xml)
            блок = re.search(r"<Command uuid[^>]*>\s*<Properties>\s*<Name>%s</Name>(.*?)</Command>"
                             % re.escape(м.group(3)), т, re.S)
            return bool(блок and "<Picture>" in блок.group(1))
    return False


def проверить(исх):
    р = общее.Результат(ИМЯ)
    префикс = общее.ПРЕФИКС
    картинки = {о.имя for о in исх.объекты if о.тип == "CommonPicture"}
    общие_с_картинкой = set()
    for о in исх.объекты:
        if о.тип in ("CommonCommand", "Subsystem") and not о.заимствован:
            if "<Picture>" in общее.читать(о.xml):
                общие_с_картинкой.add(о.имя)
            else:
                р.ошибка(исх.отн(о.xml), 1, "%s «%s» без картинки" % (
                    "общая команда" if о.тип == "CommonCommand" else "подсистема", о.имя))
    # вложенные подсистемы лежат в папке родителя — Исходники их не перечисляют
    for о in исх.объекты:
        if о.тип == "Subsystem" and о.каталог and not о.заимствован:
            for к, _, фф in os.walk(о.каталог):
                for ф in фф:
                    п = os.path.join(к, ф)
                    if ф.endswith(".xml") and os.path.basename(к) == "Subsystems" and \
                            "<Picture>" not in общее.читать(п):
                        р.ошибка(исх.отн(п), 1, "подсистема «%s» без картинки" % ф[:-4])

    кнопок = 0
    for ф in исх.формы():
        if not ф.своя:
            continue
        родители = ф.родители()
        for кнопка in ф.корень.iter(ЛФ + "Button"):
            имя = кнопка.get("name", "?")
            команда = общее.свойство(кнопка, "CommandName", "")
            своя_картинка = кнопка.find(ЛФ + "Picture")
            виды = кнопка.findall(ЛФ + "Representation")
            вид = (виды[0].text or "").strip() if виды else ""
            if своя_картинка is not None and вид == "Text":
                р.ошибка(ф.отн, ф.строка_элемента(имя), "кнопка «%s»: Representation=Text гасит заданную "
                         "картинку" % имя)
            if команда and СТАНДАРТНЫЕ.search(команда):
                if своя_картинка is not None and "CommonPicture." + префикс in "".join(своя_картинка.itertext()):
                    р.ошибка(ф.отн, ф.строка_элемента(имя), "кнопка «%s»: своя картинка на стандартной команде "
                             "%s — у неё картинка платформы" % (имя, команда))
                continue
            if not команда or общее.свойство(кнопка, "Type") != "CommandBarButton":
                continue
            # кнопки контекстного меню копируют панель — иконки у них те же
            у = кнопка
            в_меню = False
            while у in родители:
                у = родители[у]
                if общее.местное(у.tag) == "ContextMenu":
                    в_меню = True
                    break
            if в_меню:
                continue
            кнопок += 1
            есть = своя_картинка is not None or _картинка_команды(ф, команда, общие_с_картинкой)
            if not есть:
                р.ошибка(ф.отн, ф.строка_элемента(имя), "кнопка «%s» (%s) без иконки" % (имя, команда))
            elif not виды:
                р.ошибка(ф.отн, ф.строка_элемента(имя), "кнопка «%s»: картинка есть, а Representation не задан "
                         "— видна одна подпись" % имя)

        for набор in ф.корень.iter(ЛФ + "Pages"):
            дети = набор.find(ЛФ + "ChildItems")
            if дети is None:
                continue
            страницы = [с for с in дети if общее.местное(с.tag) == "Page"]
            одетые = [с for с in страницы if с.find(ЛФ + "Picture") is not None]
            if одетые:
                for с in страницы:
                    if с.find(ЛФ + "Picture") is None:
                        р.ошибка(ф.отн, ф.строка_элемента(с.get("name")), "вкладка «%s» без картинки, а у соседних "
                                 "вкладок набора «%s» картинки есть" % (с.get("name"), набор.get("name")))

        for узел in ф.корень.iter(ЛФ + "HeaderPicture"):
            у, в_таблице, владелец = узел, False, None
            while у in родители:
                у = родители[у]
                if владелец is None and у.get("name"):
                    владелец = у.get("name")
                if общее.местное(у.tag) == "Table":
                    в_таблице = True
                    break
            if not в_таблице:
                р.ошибка(ф.отн, ф.строка_элемента(владелец), "«%s»: HeaderPicture у поля вне таблицы — шапки нет, "
                         "платформа свойство отбрасывает" % владелец)

    for путь in исх.файлы(".xml"):
        т = общее.читать(путь)
        if "CommonPicture." not in т:
            continue
        for м in ССЫЛКА.finditer(т):
            имя = м.group(1)
            if имя.startswith(префикс) and имя not in картинки:
                р.ошибка(исх.отн(путь), т.count("\n", 0, м.start()) + 1,
                         "CommonPicture.%s — такой картинки в библиотеке расширения нет" % имя)
    р.проверено = "картинок %d, кнопок своих команд %d" % (len(картинки), кнопок)
    return р


if __name__ == "__main__":
    общее.запустить_один(sys.modules[__name__])
