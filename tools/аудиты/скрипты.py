# -*- coding: utf-8 -*-
"""скрипты — опись проверок сходится сама: диск, запускатель и документация говорят об одном.

Перенесено из «Путевых листов» (аудит_скриптов.py). Опись, которую держат руками, устаревает:
в ПЛ в живых руководствах было ~15 путей на удалённые скрипты, а CLAUDE.md обещал «74 из 74»
при 85 тестах в ядре. Поэтому сверяются три источника:

  * диск ↔ запускатель: каждый аудит tools/аудиты/*.py (модуль с функцией проверить) входит
    в список АУДИТЫ все_аудиты.py, и каждое имя списка есть на диске; каждый
    tools/тесты/тест_*.py запускается прогоном (есть def сценарий и запустить(…));
  * документация ↔ диск: опись docs/проверки.md называет каждый аудит и каждый тест, а
    всякий путь tools/…/*.py в docs/*.md существует — такой путь читается как «иди и запусти»;
  * каждый скрипт tools/ представляется докстрокой и компилируется (битая правка ловится до
    того, как выстрелит посреди прогона).

    python tools/аудиты/скрипты.py
"""
import glob
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import общее  # noqa: E402

ИМЯ = "скрипты"
СЛУЖЕБНЫЕ = {"общее", "все_аудиты", "самотест"}
ОПИСЬ = os.path.join("docs", "проверки.md")


def _читать(путь):
    return общее.читать(путь) if os.path.isfile(путь) else ""


def проверить(исх):
    р = общее.Результат(ИМЯ)
    репо = общее.корень_репо(исх)
    if репо is None:
        р.сводка.append("каталог — не репозиторий УЗ и не фикстура: опись не сверялась")
        return р

    def отн(путь):
        return os.path.relpath(путь, репо).replace("\\", "/")

    аудиты_папка = os.path.join(репо, "tools", "аудиты")
    запускатель = os.path.join(аудиты_папка, "все_аудиты.py")
    т = _читать(запускатель)
    м = re.search(r"АУДИТЫ\s*=\s*\[(.*?)\]", т, re.S)
    в_списке = re.findall(r'"([^"]+)"', м.group(1)) if м else []
    if not м:
        р.ошибка(отн(запускатель), 0, "нет списка АУДИТЫ — запускатель не прогонит ни одного аудита")
    на_диске = set()
    for путь in sorted(glob.glob(os.path.join(аудиты_папка, "*.py"))):
        имя = os.path.basename(путь)[:-3]
        if имя in СЛУЖЕБНЫЕ:
            continue
        if re.search(r"(?m)^def проверить\(", _читать(путь)):
            на_диске.add(имя)
            if имя not in в_списке:
                р.ошибка(отн(путь), 1, "аудит «%s» не входит в АУДИТЫ все_аудиты.py — написан и не гоняется" % имя)
    for имя in в_списке:
        if имя not in на_диске:
            р.ошибка(отн(запускатель), 0, "в АУДИТЫ есть «%s», а файла %s.py с проверить() нет" % (имя, имя))

    тесты = []
    for путь in sorted(glob.glob(os.path.join(репо, "tools", "тесты", "тест_*.py"))):
        текст = _читать(путь)
        тесты.append(os.path.basename(путь)[:-3])
        if not re.search(r"(?m)^def сценарий\(", текст) or "запустить(" not in текст:
            р.ошибка(отн(путь), 1, "тест без def сценарий(т) / запустить(…) — прогон.py его не выполнит")

    опись = os.path.join(репо, ОПИСЬ)
    текст_описи = _читать(опись)
    if not текст_описи:
        р.ошибка(ОПИСЬ.replace("\\", "/"), 0, "нет описи проверок")
    else:
        for имя in sorted(на_диске) + тесты:
            if not re.search(r"(?<![\wЁё])%s(?![\wЁё])" % re.escape(имя), текст_описи):
                р.ошибка(отн(опись), 0, "опись не называет «%s» — проверка есть, а в описи её нет" % имя)
    for док in sorted(glob.glob(os.path.join(репо, "docs", "*.md"))):
        текст = _читать(док)
        for н in re.finditer(r"tools[/\\][\wЁё./\\-]+?\.py\b", текст):
            if not os.path.isfile(os.path.join(репо, н.group(0).replace("\\", "/"))):
                р.ошибка(отн(док), текст.count("\n", 0, н.start()) + 1, "путь %s — такого файла нет" % н.group(0))

    скриптов = 0
    for к, папки, файлы in os.walk(os.path.join(репо, "tools")):
        папки[:] = [п for п in папки if п != "__pycache__"]
        for ф in sorted(файлы):
            if not ф.endswith(".py"):
                continue
            путь = os.path.join(к, ф)
            скриптов += 1
            текст = _читать(путь)
            if '"""' not in текст[:600] and "'''" not in текст[:600]:
                р.ошибка(отн(путь), 1, "скрипт без докстроки — через месяц никто не скажет, зачем он")
            try:
                compile(текст, путь, "exec", dont_inherit=True)
            except SyntaxError as е:
                р.ошибка(отн(путь), е.lineno or 0, "не компилируется: %s" % е.msg)
    р.проверено = "аудитов %d, тестов %d, скриптов tools %d" % (len(на_диске), len(тесты), скриптов)
    return р


if __name__ == "__main__":
    общее.запустить_один(sys.modules[__name__])
