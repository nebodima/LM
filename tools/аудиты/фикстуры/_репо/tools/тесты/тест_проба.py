"""Фикстура самотеста: честный COM-тест в формате сеанс.py (краснеет, когда должен)."""
from сеанс import запустить


def сценарий(т):
    выборка = т.выбрать("ВЫБРАТЬ 1 КАК Один")
    т.проверить(выборка.Количество() == 1, "запрос вернул строку")
    if выборка.Количество():
        т.проверить(выборка.Получить(0).Один == 1, "значение строки")
        т.проверить(True is not False, "вторая проверка")
    else:
        т.проверить(False, "данных нет — проверять нечего, это провал")
    try:
        т.c.НесуществующийМетод()
        т.проверить(False, "несуществующий метод должен падать")
    except Exception:
        т.проверить(True, "несуществующий метод падает")
    try:
        т.c.Удалить()
    except Exception:  # уборка: объект мог удалить сосед
        pass


if __name__ == "__main__":
    запустить("проба", сценарий)
