"""схема_платформы — XML исходников только из того, что платформа 8.3.27 умеет загрузить.

Грабля 28.09.2026 (UZ_BP_E, «Перевод ученика»): в форме — несуществующая картинка `StdPicture.FillForm`,
у реквизита табличной части — свойства `FillFromFillingValue`/`FillValue` (у реквизита ТЧ их нет).
Агент конфигуратора (`config load-files`) ответил «ок» и не загрузил НИЧЕГО; пакетная загрузка назвала
причину только в /Out («Исключение XDTO … Form.xml», «Неверное свойство объекта метаданных»). Ловим до
конфигуратора, за миллисекунды:

  * `StdPicture.<Имя>` — только из списка картинок платформы (все, что встречаются в выгрузках типовых
    УНФ 3.0.12 и БП 3.0 на 8.3.27) плюс `ДОПОЛНИТЕЛЬНЫЕ_КАРТИНКИ` — проверенные вручную;
  * свойства (`<Properties>`) объекта метаданных и его вложенных частей — только те, что в выгрузках
    типовых встречаются в том же контексте: «Document.TabularSection.Attribute» — реквизит ТЧ документа,
    «Catalog.Attribute» — реквизит справочника и т.д. Контекста нет в типовых — предупреждение (схема не знает).

Схема — tools/аудиты/схема_платформы.json, собирается из выгрузок:

    python tools/аудиты/схема_платформы.py --собрать C:/Users/User02/Documents/dumps/UNF_3012 C:/Users/User02/Documents/PRODIGY/cf_dump_bp
    python tools/аудиты/схема_платформы.py            # проверить src_ext
"""
import io
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import общее  # noqa: E402

ИМЯ = "схема_платформы"
СХЕМА = os.path.join(общее.ПАПКА_АУДИТОВ, "схема_платформы.json")
КАРТИНКА = re.compile(r"StdPicture\.([A-Za-z0-9_]+)")
# свойства, которых нет в выгрузке основной конфигурации, но есть у объектов расширения (заимствование)
СВОЙСТВА_РАСШИРЕНИЯ = {"ObjectBelonging", "ExtendedConfigurationObject", "ConfigurationExtensionPurpose",
                       "KeepMappingToExtendedConfigurationObjectsByIDs", "NamePrefix"}
# картинки платформы, которых нет в типовых, но загрузка проверена на 8.3.27: форма с ними загружена в базу и
# выгружена обратно с той же ссылкой (выгрузки %TEMP%\uz_agent\UZ_BP_C, UZ_BP_E, UZ_UNF_A\dump, 29.09.2026)
ДОПОЛНИТЕЛЬНЫЕ_КАРТИНКИ = {"Next", "AppearanceRightArrowYellow"}


def _м(т):
    return общее.местное(т)


def _части(узел, контекст, итог):
    """Свойства узла метаданных и его вложенных частей: итог[контекст] |= {имена свойств}."""
    свойства = next((у for у in узел if _м(у.tag) == "Properties"), None)
    if свойства is None:
        return
    итог.setdefault(контекст, set()).update(_м(у.tag) for у in свойства)
    дети = next((у for у in узел if _м(у.tag) == "ChildObjects"), None)
    for ребёнок in (дети if дети is not None else []):
        _части(ребёнок, контекст + "." + _м(ребёнок.tag), итог)


def свойства_файла(корень_xml):
    """{контекст: {свойства}} объекта метаданных из его XML (<MetaDataObject><Document>…)."""
    итог = {}
    узел = next(iter(корень_xml), None) if корень_xml is not None else None
    if узел is not None:
        _части(узел, _м(узел.tag), итог)
    return итог


def собрать(выгрузки):
    import xml.etree.ElementTree as ET
    картинки, свойства, файлов = set(), {}, 0
    for выгрузка in выгрузки:
        for папка, _, фф in os.walk(выгрузка):
            for ф in фф:
                if not ф.endswith(".xml"):
                    continue
                п = os.path.join(папка, ф)
                with open(п, "rb") as поток:
                    данные = поток.read()
                файлов += 1
                if b"StdPicture." in данные:
                    картинки.update(КАРТИНКА.findall(данные.decode("utf-8", "replace")))
                # объект метаданных — <Раздел>/<Имя>.xml прямо под корнем выгрузки
                отн = os.path.relpath(п, выгрузка).split(os.sep)
                if len(отн) == 2 and отн[0] in общее.ВИДЫ:
                    try:
                        for к, с in свойства_файла(ET.fromstring(данные)).items():
                            свойства.setdefault(к, set()).update(с)
                    except ET.ParseError as е:   # честно: битый файл выгрузки — не повод падать, но видно
                        print("пропущен битый XML выгрузки %s: %s" % (п, е))
    with io.open(СХЕМА, "w", encoding="utf-8", newline="\n") as поток:
        json.dump({"описание": "Картинки платформы (StdPicture) и свойства метаданных по контексту — из выгрузок "
                               "типовых на 8.3.27. Пересобрать: схема_платформы.py --собрать <выгрузки>.",
                   "выгрузки": [os.path.abspath(в) for в in выгрузки],
                   "картинки": sorted(картинки),
                   "свойства": {к: sorted(с) for к, с in sorted(свойства.items())}},
                  поток, ensure_ascii=False, indent=1)
    print("схема собрана: файлов %d, картинок %d, контекстов %d → %s" % (файлов, len(картинки), len(свойства), СХЕМА))


def проверить(исх):
    р = общее.Результат(ИМЯ)
    if not os.path.isfile(СХЕМА):
        р.ошибка(СХЕМА, 0, "нет схемы платформы — собрать: схема_платформы.py --собрать <выгрузки типовых>")
        return р
    данные = json.load(io.open(СХЕМА, encoding="utf-8"))
    картинки = set(данные["картинки"]) | ДОПОЛНИТЕЛЬНЫЕ_КАРТИНКИ
    схема = {к: set(с) | СВОЙСТВА_РАСШИРЕНИЯ for к, с in данные["свойства"].items()}
    файлов = ссылок = 0
    for путь in исх.файлы(".xml"):
        текст = общее.читать(путь)
        файлов += 1
        for м in КАРТИНКА.finditer(текст):
            ссылок += 1
            if м.group(1) not in картинки:
                р.ошибка(исх.отн(путь), текст.count("\n", 0, м.start()) + 1,
                         "StdPicture.%s — такой картинки у платформы нет: агент конфигуратора ответит «ок» и не "
                         "загрузит ничего, пакетная загрузка — «Исключение XDTO»" % м.group(1))
    неизвестные = set()
    for о in исх.объекты:
        if not о.xml:
            continue
        for контекст, свойства in sorted(свойства_файла(исх.xml(о.xml)).items()):
            if контекст not in схема:
                неизвестные.add(контекст)
                continue
            for с in sorted(свойства - схема[контекст]):
                р.ошибка(исх.отн(о.xml), 0, "%s: свойство <%s> у «%s» платформа не знает: загрузка откажет "
                                            "(«Неверное свойство объекта метаданных», агент при этом молчит) или "
                                            "молча его выбросит" % (о.имя, с, контекст))
    for к in sorted(неизвестные):
        р.предупреждение(СХЕМА, 0, "контекста «%s» нет в выгрузках типовых — свойства не сверены" % к)
    р.проверено = "xml-файлов %d, ссылок на StdPicture %d, картинок в схеме %d" % (файлов, ссылок, len(картинки))
    return р


if __name__ == "__main__":
    общее.настроить_вывод()
    if "--собрать" in sys.argv:
        собрать([а for а in sys.argv[1:] if not а.startswith("--")])
    else:
        общее.запустить_один(sys.modules[__name__])
