# -*- coding: utf-8 -*-
"""элементы_форм — обращения `Элементы.<Имя>` в модуле формы ведут к существующему элементу.

Перенесено из «Путевых листов» (аудит_элементов_форм.py). Владелец открыл накладную и
получил «Поле объекта не обнаружено (ВыгрузитьXML)»: в модуле `Элементы.ВыгрузитьXML`, а
кнопка на форме зовётся `ФормаВыгрузитьXML` (так платформа называет кнопку из команды).
Имя элемента разрешается при выполнении — компиляция и /CheckModules молчат.

    python tools/аудиты/элементы_форм.py [каталог]
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import общее  # noqa: E402

ИМЯ = "элементы_форм"
МЕТОДЫ_КОЛЛЕКЦИИ = {"количество", "найти", "индекс", "вставить", "добавить", "удалить", "сдвинуть",
                    "переместить", "count", "find", "insert", "add", "delete", "move"}
ОБРАЩЕНИЕ = re.compile(r"(?<![\wЁё.])Элементы\s*\.\s*([\wЁё]+)")
НЕ_ЭЛЕМЕНТЫ = ("Attributes", "Commands", "Parameters", "CommandInterface")


def _имена_элементов(ф):
    имена = set()

    def обойти(узел):
        for ребёнок in узел:
            if общее.местное(ребёнок.tag) in НЕ_ЭЛЕМЕНТЫ:
                continue
            if ребёнок.get("name") and общее.местное(ребёнок.tag) != "Event":
                имена.add(общее.ключ(ребёнок.get("name")))
            обойти(ребёнок)
    обойти(ф.корень)
    return имена


def проверить(исх):
    р = общее.Результат(ИМЯ)
    форм = 0
    for ф in исх.формы():
        if not ф.своя or not ф.модуль:
            continue
        форм += 1
        имена = None
        м = ф.модуль
        for найд in ОБРАЩЕНИЕ.finditer(м.код):
            имя = найд.group(1)
            к = общее.ключ(имя)
            if к in МЕТОДЫ_КОЛЛЕКЦИИ:
                continue
            if имена is None:
                имена = _имена_элементов(ф)
            if к in имена:
                continue
            похожие = sorted(и for и in имена if к in и or (len(и) > 3 and и in к))[:3]
            р.ошибка(исх.отн(м.путь), м.строка(найд.start()), "на форме нет элемента «%s»%s — «Поле объекта не "
                     "обнаружено» при выполнении" % (имя, ("; похожие: " + ", ".join(похожие)) if похожие else ""))
    р.проверено = "модулей форм %d" % форм
    return р


if __name__ == "__main__":
    общее.запустить_один(sys.modules[__name__])
