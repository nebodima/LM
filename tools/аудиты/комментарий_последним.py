# -*- coding: utf-8 -*-
"""комментарий_последним — «Комментарий» стоит последним: и в реквизитах, и на форме.

Перенесено из «Путевых листов» (проверка_комментария_последним.py; правило владельца
07.09.2026). Форму, которую не рисовали руками, платформа строит по порядку реквизитов, и
«Комментарий» оказывался посреди характеристик. Человек читает форму сверху вниз: свободная
строка для заметки посреди полей выглядит чужой, а поля под ней — забытыми.

  * в своих справочниках, документах и регистрах сведений «Комментарий» — последний
    реквизит шапки (табличные части живут своим порядком);
  * в своих формах элемент с данными «…Комментарий» — последний ВИДИМЫЙ в своей группе; исключение —
    подвал документа по стандарту форм УЗ: «Подвал» = Комментарий слева + группа «Итоги» справа.

    python tools/аудиты/комментарий_последним.py [каталог]
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import общее  # noqa: E402

ИМЯ = "комментарий_последним"
ЛФ = общее.ЛФ


def _видимый(у):
    return общее.свойство(у, "Visible") != "false"


def проверить(исх):
    р = общее.Результат(ИМЯ)
    объектов = 0
    for о in исх.объекты:
        if о.тип not in ("Catalog", "Document", "InformationRegister") or о.заимствован or not о.xml:
            continue
        т = общее.читать(о.xml)
        голова = т.split("<TabularSection", 1)[0]
        имена = [(м.group(1), м.start()) for м in
                 re.finditer(r'<Attribute uuid="[^"]+">\s*<Properties>\s*<Name>([^<]+)</Name>', голова)]
        список = [и for и, _ in имена]
        if "Комментарий" not in список:
            continue
        объектов += 1
        поз = список.index("Комментарий")
        if поз != len(список) - 1:
            р.ошибка(исх.отн(о.xml), т.count("\n", 0, имена[поз][1]) + 1,
                     "«Комментарий» — реквизит %d из %d; после него: %s" % (поз + 1, len(список),
                                                                          ", ".join(список[поз + 1:][:5])))
    форм = 0
    for ф in исх.формы():
        if not ф.своя:
            continue
        форм += 1
        for узел in ф.корень.iter():
            дети = узел.find(ЛФ + "ChildItems") if общее.местное(узел.tag) != "ChildItems" else None
            if дети is None or общее.местное(узел.tag) in ("AutoCommandBar", "CommandBar", "ContextMenu"):
                continue
            видимые = [д for д in дети if _видимый(д)]
            for н, д in enumerate(видимые):
                путь = общее.свойство(д, "DataPath") or ""
                после = [х.get("name") for х in видимые[н + 1:]]
                if узел.get("name") == "Подвал" and после == ["Итоги"]:
                    continue    # подвал документа по стандарту (docs/визуал/архитектор.md, раздел 3): слева комментарий, справа итоги
                if путь.split(".")[-1].endswith("Комментарий") and н != len(видимые) - 1:
                    р.ошибка(ф.отн, ф.строка_элемента(д.get("name")), "«%s» (%s) — элемент %d из %d в «%s»; после "
                             "него: %s" % (д.get("name"), путь, н + 1, len(видимые), узел.get("name") or "форма",
                                           ", ".join(str(х.get("name")) for х in видимые[н + 1:][:4])))
    р.проверено = "объектов с «Комментарием» %d, форм %d" % (объектов, форм)
    return р


if __name__ == "__main__":
    общее.запустить_один(sys.modules[__name__])
