class Блоки:
    """Разбор тела метода: циклы (начало, конец), обработчики исключений (начало, конец), глубина,
    операторы перехода (смещение, слово)."""

    def __init__(self, код, начало, конец):
        self.циклы, self.обработчики, self.переходы = [], [], []
        self.глубина, self.где_глубина = 0, начало
        стек = []
        for т in _ТОКЕНЫ.finditer(код, начало, конец):
            слово = т.group(1).lower()
            if слово in _ОТКРЫВАЮТ:
                начало_блока = т.start()
                if слово in ("для", "for"):
                    # заголовок «Для Каждого … Из Выражение Цикл» вычисляется один раз — не тело цикла
                    ц = re.compile(r"(?i)(?<![\wЁё])(Цикл|Do)(?![\wЁё])").search(код, т.end(), конец)
                    начало_блока = ц.end() if ц else т.start()
                стек.append([_ОТКРЫВАЮТ[слово], начало_блока, None])
                if len(стек) > self.глубина:
                    self.глубина, self.где_глубина = len(стек), т.start()
            elif слово in _ЗАКРЫВАЮТ:
                while стек and стек[-1][0] != _ЗАКРЫВАЮТ[слово]:
                    стек.pop()
                if стек:
                    вид, откр, искл = стек.pop()
                    if вид == "цикл":
                        self.циклы.append((откр, т.start()))
                    elif вид == "попытка" and искл is not None:
                        self.обработчики.append((искл, т.start()))
            elif слово in ("исключение", "except"):
                if стек and стек[-1][0] == "попытка":
                    стек[-1][2] = т.end()
            elif слово in _ПЕРЕХОД:
                self.переходы.append((т.start(), т.end(), слово))

    def в_цикле(self, смещение):
        return any(н < смещение < к for н, к in self.циклы)


def недостижимое(код, начало_после, конец_метода):
    """Смещение первого оператора после оператора перехода, если это не граница блока (иначе None)."""
    i = начало_после
    # конец оператора: «;» или граница блока без «;»
    т = код.find(";", i, конец_метода)
    г = _ГРАНИЦА_БЛОКА.search(код, i, конец_метода)
    if т < 0 or (г and г.start() < т):
        return None
    i = т + 1
    while i < конец_метода:
        с = код[i]
        if с in " \t\r\n;":
            i += 1
            continue
        if с == "#":                      # инструкция препроцессора — до конца строки
            к = код.find("\n", i)
            i = конец_метода if к < 0 else к
            continue
        if с == "~":                      # метка перехода
            return None
        if _ГРАНИЦА_БЛОКА.match(код, i):
            return None
        return i
    return None


