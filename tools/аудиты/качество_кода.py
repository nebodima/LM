def контекст_метода(вид, мет, флаги_общего):
    """{"клиент", "сервер"} — где выполняется метод."""
    д = мет.директива.lower()
    if вид in ("форма", "команда"):
        if д.startswith("&наклиентенасервере"):
            return {"клиент", "сервер"}
        if д.startswith("&наклиенте"):
            return {"клиент"}
        if д.startswith("&насервере"):
            return {"сервер"}
        return {"сервер"} if вид == "форма" else {"клиент"}
    if вид == "общий":
        return {к for к in ("клиент", "сервер") if к in флаги_общего}
    if вид == "сервер":
        return {"сервер"}
    if вид == "клиент":
        return {"клиент"}
    return set()


