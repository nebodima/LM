# -*- coding: utf-8 -*-
"""форматы_чисел — строка формата разбирается платформой, а в HTML ноль печатается нулём.

Перенесено из «Путевых листов» (проверка_форматов_чисел.py). Два способа потерять число:

  * неразбираемый формат: группы разрядов задаются запятой («ЧГ=3,0»); с пробелом
    («ЧГ=3 0») платформа не разбирает строку ЦЕЛИКОМ и молча возвращает пустоту — сумма
    в панели импорта ПЛ не печаталась никогда;
  * по умолчанию `Формат(0, "ЧДЦ=2")` — пустая строка. В таблице это удобно, а в HTML, где
    число стоит рядом с подписью, читается «Сумма: ₽». В строках, собирающих HTML, нужен «ЧН=».

    python tools/аудиты/форматы_чисел.py [каталог]
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import общее  # noqa: E402

ИМЯ = "форматы_чисел"
ФОРМАТ = re.compile(r'(?<![\wЁё.])Формат\(([^;"\n]*?),\s*"([^"\n]*)"\s*\)')
ПРОБЕЛ = re.compile(r"(Ч[А-ЯЁ]+)=(\d+\s+\d+)")
РАЗМЕТКА = re.compile(r"HTML|<span|<div|<td|<b>|<p>|<br")


def проверить(исх):
    р = общее.Результат(ИМЯ)
    форматов = 0
    for м in исх.модули():
        строки = м.текст.split("\n")
        for найд in ФОРМАТ.finditer(м.текст):
            if м.код[найд.start():найд.start() + 6] != "Формат":
                continue            # в комментарии или внутри строки
            форматов += 1
            формат = найд.group(2)
            номер = м.строка(найд.start())
            испорчен = ПРОБЕЛ.search(формат)
            if испорчен:
                р.ошибка(исх.отн(м.путь), номер, "«%s»: группы разрядов задаются запятой — платформа не разберёт "
                         "формат и вернёт пустоту" % испорчен.group(0))
            if not РАЗМЕТКА.search(строки[номер - 1]):
                continue
            только_дата = not re.search(r"(^|;)\s*Ч", формат) and re.search(r"Д[ЛФП]*=", формат)
            if "ЧН=" not in формат and not только_дата:
                р.ошибка(исх.отн(м.путь), номер, "формат «%s» в HTML без «ЧН=» — ноль напечатается пустотой"
                         % формат)
    р.проверено = "форматов со строкой %d" % форматов
    return р


if __name__ == "__main__":
    общее.запустить_один(sys.modules[__name__])
