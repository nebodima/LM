# -*- coding: utf-8 -*-
"""ссылки_на_метаданные — обращения к объектам и полям, которых нет в исходниках.

Компилятор модуля не проверяет ни `Справочники.X` (ошибка — при выполнении),
ни тексты запросов (это строки): переименовали LM_Кассы → УЗ_Кассы, а в запросе
осталось `Справочник.LM_Кассы` — узнаем при проведении. Поэтому:

  * в коде BSL: Справочники.X / Документы.X / РегистрыНакопления.X / РегистрыСведений.X /
    Перечисления.X[.Значение] / Отчеты.X / Обработки.X / ЖурналыДокументов.X / Константы.X
    (и Метаданные.<те же>.X) — X есть среди объектов исходников (свой или заимствованный);
  * в строках: Тип("СправочникСсылка.X"), ОткрытьФорму("Документ.X.Форма…"), "ОбщаяФорма.X";
  * в текстах запросов: таблицы `Справочник.X`, `Документ.X.ТЧ`, `РегистрНакопления.X.Остатки(…)`,
    значения `ЗНАЧЕНИЕ(Перечисление.X.Y)` и поля `Псевдоним.Поле` — по реквизитам из XML
    объекта, стандартным полям и полям виртуальных таблиц (Остатки: <Ресурс>Остаток и т.д.).

У заимствованных объектов поля не проверяются (их набор задаёт хозяин). Строки в
модуле слоя совместимости УЗ_Среда не проверяются: там законно живут имена хозяина.

    python tools/аудиты/ссылки_на_метаданные.py [каталог] [--только-продукт]
"""
import collections
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import общее  # noqa: E402

ИМЯ = "ссылки_на_метаданные"
_ИМЯ = r"[А-Яа-яЁёA-Za-z_][\wЁё]*"

СТАНДАРТНЫЕ = {общее.ключ(п) for п in """
Ссылка Дата Номер Проведен ПометкаУдаления Период Регистратор НомерСтроки Наименование Код Родитель
Владелец ЭтоГруппа Активность ВидДвижения Представление МоментВремени ВерсияДанных Предопределенный
ИмяПредопределенныхДанных Порядок Тип
""".split()}
ПОЛЯ_ПЕРИОДА = {общее.ключ(п) for п in """
Период ПериодСекунда ПериодМинута ПериодЧас ПериодДень ПериодНеделя ПериодДекада ПериодМесяц
ПериодКвартал ПериодПолугодие ПериодГод Регистратор НомерСтроки МоментВремени
""".split()}
СУФФИКСЫ = {
    "Остатки": ("Остаток",),
    "Обороты": ("Оборот", "Приход", "Расход"),
    "ОстаткиИОбороты": ("НачальныйОстаток", "КонечныйОстаток", "Оборот", "Приход", "Расход"),
}
ФОРМЫ_ОБЪЕКТА = {общее.ключ(ф) for ф in """
Форма ФормаОбъекта ФормаСписка ФормаВыбора ФормаГруппы ФормаВыбораГруппы ФормаЗаписи
ФормаДокумента ФормаЭлемента ФормаОтчета ФормаНастроек ФормаВарианта МенеджерЗначения ПустаяСсылка
""".split()}

_ТАБЛИЦЫ = "|".join(sorted(общее.ТАБЛИЦЫ_ЗАПРОСА, key=len, reverse=True))
_СУФФИКС_ТИПА = r"(?:Ссылка|Объект|Менеджер|Выборка|Список|НаборЗаписей|МенеджерЗаписи|КлючЗаписи|Запись)?"
_В_СТРОКЕ = re.compile(r"(?<![\wЁё.&])(%s)(%s)\.(%s)(?:\.(%s))?" % (_ТАБЛИЦЫ, _СУФФИКС_ТИПА, _ИМЯ, _ИМЯ))
_В_КОДЕ = re.compile(r"(?:(?<=Метаданные\.)|(?<![\wЁё.]))(%s)\s*\.\s*(%s)(\s*\()?(?:\s*\.\s*(%s)(\s*\()?)?" % (
    "|".join(sorted(общее.КОЛЛЕКЦИИ_КОДА, key=len, reverse=True)), _ИМЯ, _ИМЯ))


def _пропустить_скобки(т, поз):
    """Если с позиции (после пробелов) идёт «(…)» — вернуть позицию за ней."""
    j = поз
    while j < len(т) and т[j] in " \t\r\n":
        j += 1
    if j >= len(т) or т[j] != "(":
        return поз
    глубина = 0
    while j < len(т):
        if т[j] == "(":
            глубина += 1
        elif т[j] == ")":
            глубина -= 1
            if глубина == 0:
                return j + 1
        j += 1
    return len(т)


def поля_таблицы(о, часть):
    """Множество допустимых полей (ключи) для таблицы или None — не проверять."""
    о.разобрать()
    к = общее.ключ
    своё = {к(п) for п in о.реквизиты | о.измерения | о.ресурсы | о.графы | set(о.тч)}
    if часть is None:
        return своё | СТАНДАРТНЫЕ
    чк = к(часть)
    for имя, колонки in о.тч.items():
        if к(имя) == чк:
            return {к(п) for п in колонки} | {к("Ссылка"), к("НомерСтроки"), к("Представление")}
    if часть in СУФФИКСЫ:
        итог = {к(и) for и in о.измерения}
        for ресурс in о.ресурсы:
            итог |= {к(ресурс + с) for с in СУФФИКСЫ[часть]}
        if часть != "Остатки":
            итог |= ПОЛЯ_ПЕРИОДА
        return итог
    if часть in ("СрезПоследних", "СрезПервых"):
        return своё | {к("Период"), к("Регистратор"), к("Активность"), к("НомерСтроки")}
    return None


def проверить_часть(о, часть, контекст_значения):
    """Текст ошибки для «Таблица.X.<часть>» или None."""
    о.разобрать()
    к = общее.ключ
    if к(часть) == к("ПустаяСсылка"):
        return None
    if о.тип == "Enum":
        if к(часть) in {к(з) for з in о.значения}:
            return None
        return "у перечисления %s нет значения %s" % (о.имя, часть)
    if контекст_значения:
        if к(часть) in {к(п) for п in о.предопределенные}:
            return None
        return "у %s нет предопределённого %s" % (о.имя, часть)
    if о.тип in ("Catalog", "Document", "ChartOfCharacteristicTypes", "ExchangePlan", "BusinessProcess", "Task"):
        if к(часть) in {к(т) for т in о.тч}:
            return None
        return "у %s нет табличной части %s" % (о.имя, часть)
    if о.тип == "AccumulationRegister":
        допустимые = ("Обороты",) if о.вид_регистра == "Turnovers" else ("Остатки", "Обороты", "ОстаткиИОбороты")
        if часть in допустимые:
            return None
        return "у регистра накопления %s (%s) нет виртуальной таблицы %s" % (о.имя, о.вид_регистра or "?", часть)
    if о.тип == "InformationRegister":
        if часть in ("СрезПоследних", "СрезПервых") and о.периодичность not in ("", "Nonperiodical"):
            return None
        return "у регистра сведений %s (%s) нет таблицы %s" % (о.имя, о.периодичность or "?", часть)
    return None


def проверить(исх):
    р = общее.Результат(ИМЯ)
    модулей = запросов = полей = 0
    отсутствующие = collections.Counter()

    def нет_объекта(отн, строка, тип, имя, как):
        р.ошибка(отн, строка, "%s — объекта %s.%s нет в исходниках" % (как, тип, имя))
        отсутствующие["%s.%s" % (тип, имя)] += 1

    for м in исх.модули():
        модулей += 1
        отн = исх.отн(м.путь)
        свои = м.локальные_имена() | общее.реквизиты_формы(м.путь)
        # ── код ──
        for найд in _В_КОДЕ.finditer(м.код):
            коллекция, имя, метод, часть, вызов = найд.groups()
            после_метаданных = м.код[max(0, найд.start() - 11):найд.start()] == "Метаданные."
            if метод:
                continue            # Метаданные.Документы.Найти(…), .Индекс(…) — метод коллекции
            if not после_метаданных and общее.ключ(коллекция) in свои:
                continue
            тип = общее.КОЛЛЕКЦИИ_КОДА[коллекция]
            о = исх.найти(тип, имя)
            строка = м.строка(найд.start())
            if о is None:
                нет_объекта(отн, строка, тип, имя, "%s.%s" % (коллекция, имя))
                continue
            if тип == "Enum" and часть and not вызов and not после_метаданных and not о.заимствован:
                ош = проверить_часть(о, часть, False)
                if ош:
                    р.ошибка(отн, строка, "%s.%s.%s — %s" % (коллекция, имя, часть, ош))
        # ── строки ──
        if общее.это_слой_совместимости(м.путь):
            continue
        for лит in м.литералы:
            содержимое = лит[1]
            запрос = общее.это_запрос(содержимое)
            текст = общее.очистить_запрос(содержимое) if запрос else содержимое
            if запрос:
                запросов += 1
            псевдонимы_всех = {общее.ключ(п) for п in re.findall(r"(?i)(?<![\wЁё])КАК\s+(%s)" % _ИМЯ, текст)} \
                if запрос else set()
            for найд in _В_СТРОКЕ.finditer(текст):
                вид, суффикс, имя, часть = найд.groups()
                тип = общее.ТАБЛИЦЫ_ЗАПРОСА[вид]
                о = исх.найти(тип, имя)
                if о is None and общее.ключ(вид) in псевдонимы_всех:
                    continue            # «ИЗ … КАК Документ» — дальше «Документ.Поле» это псевдоним
                строка = м.строка_в_литерале(лит, найд.start())
                if о is None:
                    нет_объекта(отн, строка, тип, имя, "«%s%s.%s»" % (вид, суффикс, имя))
                    continue
                if not запрос or not часть or суффикс or о.заимствован:
                    continue
                перед = текст[max(0, найд.start() - 12):найд.start()]
                значение = bool(re.search(r"(?i)ЗНАЧЕНИЕ\s*\(\s*$", перед))
                ош = проверить_часть(о, часть, значение)
                if ош:
                    р.ошибка(отн, строка, "«%s.%s.%s» — %s" % (вид, имя, часть, ош))
            if not запрос:
                continue
            # поля по псевдонимам: каждый пакет и каждая часть ОБЪЕДИНИТЬ — отдельно
            поз = 0
            for сегмент in re.split(r"(?i)(;|(?<![\wЁё])ОБЪЕДИНИТЬ(?:\s+ВСЕ)?(?![\wЁё]))", текст):
                начало = поз
                поз += len(сегмент)
                псевдонимы = collections.defaultdict(list)
                for найд in _В_СТРОКЕ.finditer(сегмент):
                    вид, суффикс, имя, часть = найд.groups()
                    if суффикс:
                        continue
                    тип = общее.ТАБЛИЦЫ_ЗАПРОСА[вид]
                    о = исх.найти(тип, имя)
                    if о is None or о.заимствован:
                        continue
                    за = _пропустить_скобки(сегмент, найд.end())
                    п = re.match(r"\s*(?i:КАК)\s+(%s)" % _ИМЯ, сегмент[за:])
                    if not п:
                        continue
                    if часть and проверить_часть(о, часть, False):
                        continue        # неверная таблица уже отмечена выше, поля не разбираем
                    допустимые = поля_таблицы(о, часть)
                    if допустимые is not None:
                        псевдонимы[общее.ключ(п.group(1))].append((о, часть, допустимые))
                if not псевдонимы:
                    continue
                for найд in re.finditer(r"(?<![\wЁё.&])(%s)\.(%s)" % (_ИМЯ, _ИМЯ), сегмент):
                    пс, поле = найд.group(1), найд.group(2)
                    варианты = псевдонимы.get(общее.ключ(пс))
                    if not варианты:
                        continue
                    полей += 1
                    if any(общее.ключ(поле) in доп for _, _, доп in варианты):
                        continue
                    о, часть, _ = варианты[0]
                    таблица = о.имя + ("." + часть if часть else "")
                    р.ошибка(отн, м.строка_в_литерале(лит, начало + найд.start()),
                             "поле %s.%s — у таблицы %s.%s такого поля нет" % (пс, поле, о.тип, таблица))
    р.проверено = "модулей %d, текстов запросов %d, полей по псевдонимам %d" % (модулей, запросов, полей)
    if отсутствующие:
        р.сводка.append("нет в исходниках (× раз): " + ", ".join(
            "%s×%d" % (и, к) for и, к in отсутствующие.most_common(20)))
    return р


