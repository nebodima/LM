"""Все офлайн-аудиты исходников УЗ_ext одним запуском (секунды, без 1С).

    python tools/аудиты/все_аудиты.py                       # src_ext
    python tools/аудиты/все_аудиты.py C:/путь/к/исходникам
    python tools/аудиты/все_аудиты.py --каталог C:/Users/User02/LESSONS_MANAGER --только-продукт
    python tools/аудиты/все_аудиты.py --только ноль_бсп,модальность --все-строки

Код возврата 1 — если есть хоть одно замечание или аудит упал. Предупреждения
(ноль_бсп: строковые вызовы БСП вне УЗ_Среда) печатаются, но код возврата не меняют.
Самотест самих аудитов (каждый обязан краснеть): python tools/аудиты/самотест.py
Бюджет всех аудитов вместе с чтением исходников — БЮДЖЕТ_СЕК (5 с); время печатается в сводке.
Опись аудитов и тестов — docs/проверки.md (её сверяет аудит «скрипты»).
"""
import importlib
import os
import sys
import time
import traceback

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import общее  # noqa: E402

АУДИТЫ = ["ноль_бсп", "зарезервированные_слова", "имена", "форм_id", "модальность", "ссылки_на_метаданные",
          "свойства_формы",
          # перенесены из «Путевых листов» 28.09.2026 (опись — docs/проверки.md)
          "вложенность_форм", "дерево_форм", "дубли_формы", "иконки", "компоновка_форм", "обработчики",
          "печать", "повторы_тегов", "скрипты", "честность_проверок", "чужие_коллекции", "элементы_форм",
          "начальная_страница", "автозаполнение", "bom", "вёрстка_панелей", "форматы_чисел", "сетка_форм",
          "ширина_заголовков", "комментарий_последним", "малые_иконки", "права_роли",
          "совместимость_метаданных", "сверка_хозяев"]
БЮДЖЕТ_СЕК = 5.0


def прогнать(каталог, продукт=False, только=None):
    """[(имя, Результат или None, текст_исключения, секунды)] — для самотеста и запускателя."""
    исх = общее.Исходники(каталог, продукт)
    if not исх.объекты:
        # пустой каталог — не «0 замечаний», а нечего проверять: зелёным это быть не должно
        return [("исходники", None, "в %s нет ни одного объекта метаданных — проверять нечего" % каталог, 0.0)]
    итог = []
    for имя in АУДИТЫ:
        if только and имя not in только:
            continue
        н = time.time()
        try:
            модуль = importlib.import_module(имя)
            итог.append((имя, модуль.проверить(исх), None, time.time() - н))
        except SystemExit as е:
            итог.append((имя, None, str(е), time.time() - н))
        except Exception:
            итог.append((имя, None, traceback.format_exc(), time.time() - н))
    return итог


def главный():
    общее.настроить_вывод()

    def лишние(п):
        п.add_argument("--только", default="", help="список аудитов через запятую")

    а = общее.аргументы(__doc__.strip().splitlines()[0], лишние)
    только = [и.strip() for и in а.только.split(",") if и.strip()] or None
    н = time.time()
    результаты = прогнать(а.каталог, а.только_продукт, только)
    print("Исходники: %s%s" % (а.каталог, " (только продукт LM)" if а.только_продукт else ""))
    всего = предупр = упало = 0
    for имя, р, ошибка, сек in результаты:
        if р is None:
            упало += 1
            print("=" * 78)
            print("АУДИТ %s УПАЛ:\n%s" % (имя, ошибка))
            continue
        общее.напечатать(р, 0 if а.все_строки else а.макс)
        всего += len(р.ошибки)
        предупр += len(р.предупреждения)
    print("=" * 78)
    print("СВОДКА")
    for имя, р, ошибка, сек in результаты:
        if р is None:
            print("  %-26s УПАЛ" % имя)
        else:
            print("  %-26s замечаний %5d  предупреждений %3d  (%.1f с)" % (
                имя, len(р.ошибки), len(р.предупреждения), сек))
    всего_сек = time.time() - н
    print("время: %.1f с (бюджет %.0f с)%s" % (всего_сек, БЮДЖЕТ_СЕК,
                                              "  ПРЕДУПРЕЖДЕНИЕ: бюджет превышен" if всего_сек > БЮДЖЕТ_СЕК else ""))
    if упало:
        print("аудитов упало: %d" % упало)
    print("ИТОГО замечаний: %d%s" % (всего, (", предупреждений: %d" % предупр) if предупр else ""))
    sys.exit(1 if всего or упало else 0)


if __name__ == "__main__":
    главный()
