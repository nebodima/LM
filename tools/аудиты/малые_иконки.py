# -*- coding: utf-8 -*-
"""малые_иконки — значок влезает в свой квадрат, не срезан по краю и не теряется.

Перенесено из «Путевых листов» (проверка_малых_иконок.py). Платформа рисует картинку в
отведённом квадрате как есть: рисунок, упёршийся в границы растра, выглядит обрезанным (у
грузовика пропадает бампер), рисунок меньше половины квадрата теряется среди подписей.

Для каждой своей общей картинки берётся растр, который платформа показывает при 100 %
(Picture.png, или 100.png / Picture.png из набора Picture.zip), и по альфа-каналу:
  * касается края больше чем с одной стороны — «режется по краю»;
  * занимает меньше 45 % стороны — «мелкий в своём квадрате»;
  * непрозрачных точек < 8 % — «почти пустой», > 92 % — «сплошное пятно».

    python tools/аудиты/малые_иконки.py [каталог]
"""
import io
import os
import sys
import zipfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import общее  # noqa: E402

ИМЯ = "малые_иконки"
МАЛО = 0.45
МНОГО_СТОРОН = 1


def _растр(каталог):
    from PIL import Image
    папка = os.path.join(каталог, "Ext", "Picture")
    png = os.path.join(папка, "Picture.png")
    if os.path.isfile(png):
        return Image.open(png).convert("RGBA"), png
    архив = os.path.join(папка, "Picture.zip")
    if os.path.isfile(архив):
        with zipfile.ZipFile(архив) as z:
            имена = z.namelist()
            файл = next((и for и in ("100.png", "Picture.png") if и in имена), None)
            if файл is None:
                файл = next((и for и in имена if и.lower().endswith(".png")), None)
            if файл:
                return Image.open(io.BytesIO(z.read(файл))).convert("RGBA"), архив
        return None, архив
    return None, None


def проверить(исх):
    р = общее.Результат(ИМЯ)
    наборов = 0
    for о in исх.объекты:
        if о.тип != "CommonPicture" or о.заимствован:
            continue
        наборов += 1
        картинка, путь = _растр(о.каталог) if о.каталог else (None, None)
        где = исх.отн(путь or о.xml)
        if картинка is None:
            р.ошибка(где, 1, "«%s»: нет растра (Picture.png или png в Picture.zip)" % о.имя)
            continue
        альфа = картинка.split()[3]
        рамка = альфа.getbbox()
        if рамка is None:
            р.ошибка(где, 1, "«%s»: пустой рисунок" % о.имя)
            continue
        ш, в = картинка.size
        x0, y0, x1, y1 = рамка
        стороны = sum((x0 == 0, y0 == 0, x1 == ш, y1 == в))
        дх, ду = (x1 - x0) / float(ш), (y1 - y0) / float(в)
        доля = sum(1 for п in альфа.getdata() if п > 24) / float(ш * в)
        беды = []
        if стороны > МНОГО_СТОРОН:
            беды.append("режется по краю (%d стороны)" % стороны)
        if дх < МАЛО or ду < МАЛО:
            беды.append("рисунок мелкий в своём квадрате (%.0f%%×%.0f%%)" % (дх * 100, ду * 100))
        if доля < 0.08:
            беды.append("почти пустой (%.0f%%)" % (доля * 100))
        if доля > 0.92:
            беды.append("сплошное пятно (%.0f%%)" % (доля * 100))
        if беды:
            р.ошибка(где, 1, "«%s» %d×%d: %s" % (о.имя, ш, в, "; ".join(беды)))
    р.проверено = "картинок %d" % наборов
    return р


