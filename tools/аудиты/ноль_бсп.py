"""ноль_бсп — в исходниках расширения нет обращений к объектам БСП.

Решение владельца (27.09.2026): БСП в УЗ_ext не используем — ни кода, ни вызовов,
ни объектов (лицензия). Вызвать БСП ХОЗЯИНА можно только через слой совместимости
`УЗ_Среда`, строкой в Вычислить()/Выполнить() после проверки метаданных (как ПЛ_Среда).

Словарь имён БСП (`имена_бсп.txt`) строится из выгрузки LM ключом --обновить-словарь:
всё, что входит в подсистемы СтандартныеПодсистемы (рекурсивно) и
ПодключаемыеОтчетыИОбработки, плюс все общие модули, общие формы, общие картинки,
элементы стиля, определяемые типы, общие команды, параметры сеанса и
функциональные опции LM, кроме собственных объектов продукта и двух
заимствуемых справочников (Организации, Пользователи).

Что считается нарушением (ошибкой):
  * в коде BSL (вне строк и комментариев): `МодульБСП.Что-то`, `Справочники.X`,
    `РегистрыСведений.X`, `Метаданные.ОбщиеМодули.X`, `ПараметрыСеанса.X`,
    `БиблиотекаКартинок.X`, `ЦветаСтиля.X`… где X — объект БСП;
  * в XML: `CommonPicture.X`, `StyleItem.X`, `CommonForm.X`, `CommonCommand.X`,
    `DefinedType.X`, `Catalog.X`…, `cfg:CatalogRef.X`…, `style:X`, таблицы БСП
    в текстах запросов СКД, заимствование объекта БСП в Configuration.xml.
Предупреждение (не ошибка): строка с именем модуля БСП в модуле, где есть
Вычислить()/Выполнить(), — вне модуля УЗ_Среда (такие вызовы живут только там).

    python tools/аудиты/ноль_бсп.py [каталог] [--только-продукт]
    python tools/аудиты/ноль_бсп.py --обновить-словарь [--lm C:/Users/User02/LESSONS_MANAGER]
"""
import collections
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import общее  # noqa: E402

ИМЯ = "ноль_бсп"
СЛОВАРЬ = os.path.join(общее.ПАПКА_АУДИТОВ, "имена_бсп.txt")

# Виды, которые берутся из выгрузки LM целиком (а не только из состава подсистем)
ВИДЫ_ЦЕЛИКОМ = ("CommonModules", "CommonForms", "CommonPictures", "StyleItems", "DefinedTypes",
                "CommonCommands", "SessionParameters", "FunctionalOptions")
# Собственные объекты продукта LM (в подсистемах БСП встречаются как типы-источники)
СВОИ_ИМЕНА = {"LM", "LM_ОповещениеПоEmail", "ОбновлениеИнформационнойБазыМК", "ПанельОтчетовLM",
              # картинки продукта вне подсистем БСП: используются только формой LM_Календарь
              "Больше", "Меньше"}
СВОИ_ОБЪЕКТЫ = {("Catalog", "Кассы"), ("Catalog", "СтатьиЗатрат"), ("Catalog", "ДоговорыКонтрагентов"),
                ("Document", "ПриходныйКассовыйОрдер"), ("Document", "РасходныйКассовыйОрдер")}
ЗАИМСТВОВАННЫЕ = {("Catalog", "Организации"), ("Catalog", "Пользователи")}


# ─────────────────────────── словарь ───────────────────────────

def построить_словарь(lm):
    записи = set()
    подсистемы = os.path.join(lm, "Subsystems")
    файлы = [os.path.join(подсистемы, "СтандартныеПодсистемы.xml"),
             os.path.join(подсистемы, "ПодключаемыеОтчетыИОбработки.xml")]
    for к, _, фф in os.walk(os.path.join(подсистемы, "СтандартныеПодсистемы")):
        файлы += [os.path.join(к, ф) for ф in фф if ф.endswith(".xml")]
    for ф in файлы:
        if not os.path.exists(ф):
            raise SystemExit("нет файла подсистемы: " + ф)
        for ссылка in re.findall(r'<xr:Item xsi:type="xr:MDObjectRef">([^<]+)</xr:Item>', общее.читать(ф)):
            if "." in ссылка:                   # голые uuid — битые ссылки состава, пропускаем
                тип, имя = ссылка.split(".", 1)
                записи.add((тип, имя))
    for папка in ВИДЫ_ЦЕЛИКОМ:
        for ф in os.listdir(os.path.join(lm, папка)):
            if ф.endswith(".xml"):
                записи.add((общее.ВИДЫ[папка], ф[:-4]))
    итог = sorted((т, и) for т, и in записи
                  if not и.startswith("LM_") and и not in СВОИ_ИМЕНА
                  and (т, и) not in СВОИ_ОБЪЕКТЫ and (т, и) not in ЗАИМСТВОВАННЫЕ)
    with open(СЛОВАРЬ, "w", encoding="utf-8", newline="\n") as ф:
        ф.write("# Имена объектов БСП (из выгрузки LM %s), формат Тип.Имя.\n" % lm)
        ф.write("# Генерируется: python tools/аудиты/ноль_бсп.py --обновить-словарь. Руками не править.\n")
        ф.write("# Исключены: свои объекты продукта (LM*, Кассы, СтатьиЗатрат, ПКО, РКО, Больше/Меньше)\n")
        ф.write("# и заимствуемые Catalog.Организации, Catalog.Пользователи.\n")
        for т, и in итог:
            ф.write("%s.%s\n" % (т, и))
    по_типам = collections.Counter(т for т, _ in итог)
    return итог, по_типам


def загрузить_словарь():
    if not os.path.exists(СЛОВАРЬ):
        raise SystemExit("нет словаря %s — выполните ноль_бсп.py --обновить-словарь" % СЛОВАРЬ)
    словарь = collections.defaultdict(dict)
    for строка in общее.читать(СЛОВАРЬ).splitlines():
        строка = строка.strip()
        if not строка or строка.startswith("#"):
            continue
        тип, имя = строка.split(".", 1)
        словарь[тип][общее.ключ(имя)] = имя
    return словарь


# ─────────────────────────── проверка ───────────────────────────

_ИМЯ = r"[А-Яа-яЁёA-Za-z_][\wЁё]*"
_ТИПЫ_XML = sorted(set(общее.ВИДЫ.values()), key=len, reverse=True)
_XML_ССЫЛКА = re.compile(r"(?<![\w:.])(%s)\.(%s)" % ("|".join(_ТИПЫ_XML), _ИМЯ))
_XML_CFG = re.compile(r"cfg:(%s)[A-Za-z]*\.(%s)" % ("|".join(_ТИПЫ_XML), _ИМЯ))
_XML_СТИЛЬ = re.compile(r"style:(%s)" % _ИМЯ)
_XML_ЗАПРОС = re.compile(r"(?<![\wЁё.&])(%s)\.(%s)" % ("|".join(sorted(общее.ТАБЛИЦЫ_ЗАПРОСА, key=len, reverse=True)), _ИМЯ))
_КОД_КОЛЛЕКЦИЯ = re.compile(r"(?:(?<=Метаданные\.)|(?<![\wЁё.]))(%s)\s*\.\s*(%s)" % (
    "|".join(sorted(set(общее.ГЛОБАЛЬНЫЕ_КОЛЛЕКЦИИ) | set(общее.КОЛЛЕКЦИИ_МЕТАДАННЫХ), key=len, reverse=True)), _ИМЯ))
_КОД_МОДУЛЬ = re.compile(r"(?<![\wЁё.])(%s)\s*\.\s*[\wЁё]" % _ИМЯ)
_ВЫЧИСЛИТЬ = re.compile(r"(?i)(?<![\wЁё.])(Вычислить|Выполнить|Eval|Execute)\s*\(")


def _тип_коллекции(коллекция, после_метаданных):
    if после_метаданных:
        return общее.КОЛЛЕКЦИИ_МЕТАДАННЫХ.get(коллекция)
    return общее.ГЛОБАЛЬНЫЕ_КОЛЛЕКЦИИ.get(коллекция)


def проверить(исх):
    р = общее.Результат(ИМЯ)
    бсп = загрузить_словарь()
    модули_бсп = бсп.get("CommonModule", {})
    по_бсп = collections.Counter()
    по_объектам = collections.Counter()
    файлов = 0

    def отметить(путь, строка, что, имя_бсп):
        р.ошибка(исх.отн(путь), строка, что)
        по_бсп[имя_бсп] += 1
        о = исх.объект_файла(путь)
        по_объектам["%s.%s" % (о.тип, о.имя) if о else исх.отн(путь).split("/")[0]] += 1

    # ── BSL ──
    for м in исх.модули():
        файлов += 1
        свои = м.локальные_имена() | общее.реквизиты_формы(м.путь)
        о = исх.объект_файла(м.путь)
        if о and м.путь.replace("\\", "/").endswith(("/Ext/ObjectModule.bsl", "/Ext/RecordSetModule.bsl")):
            о.разобрать()
            свои |= {общее.ключ(и) for и in о.реквизиты | set(о.тч)}
        код = м.код
        for найд in _КОД_КОЛЛЕКЦИЯ.finditer(код):
            коллекция, имя = найд.group(1), найд.group(2)
            после_метаданных = код[max(0, найд.start() - 11):найд.start()] == "Метаданные."
            if not после_метаданных and общее.ключ(коллекция) in свои:
                continue            # реквизит формы или переменная с таким именем
            тип = _тип_коллекции(коллекция, после_метаданных)
            if not тип:
                continue
            if общее.ключ(имя) in бсп.get(тип, {}):
                отметить(м.путь, м.строка(найд.start()), "%s.%s — объект БСП (%s)" % (коллекция, имя, тип),
                         "%s.%s" % (тип, бсп[тип][общее.ключ(имя)]))
        for найд in _КОД_МОДУЛЬ.finditer(код):
            имя = найд.group(1)
            к = общее.ключ(имя)
            if к in модули_бсп and к not in свои:
                отметить(м.путь, м.строка(найд.start()), "%s. — вызов общего модуля БСП" % имя,
                         "CommonModule." + модули_бсп[к])
        # строки с именами модулей БСП — законны только в слое совместимости
        if not общее.это_слой_совместимости(м.путь) and _ВЫЧИСЛИТЬ.search(код):
            for лит in м.литералы:
                for найд in re.finditer(r"(?<![\wЁё.])(%s)\s*\." % _ИМЯ, лит[1]):
                    к = общее.ключ(найд.group(1))
                    if к in модули_бсп:
                        р.предупреждение(исх.отн(м.путь), м.строка_в_литерале(лит, найд.start()),
                                         "строка с вызовом БСП «%s.» для Вычислить/Выполнить вне %s"
                                         % (модули_бсп[к], общее.СЛОЙ_СОВМЕСТИМОСТИ))
                        break

    # ── XML ──
    for путь in исх.файлы(".xml"):
        файлов += 1
        т = общее.читать(путь)
        переводы = [x.start() for x in re.finditer("\n", т)]

        def строка(смещ):
            import bisect
            return bisect.bisect_right(переводы, смещ - 1) + 1

        видено = set()

        def проверить_имя(тип, имя, смещ, как):
            к = общее.ключ(имя)
            if к in бсп.get(тип, {}):
                с = строка(смещ)
                if (с, тип, к) in видено:
                    return
                видено.add((с, тип, к))
                отметить(путь, с, "%s — объект БСП" % как, "%s.%s" % (тип, бсп[тип][к]))

        for найд in _XML_ССЫЛКА.finditer(т):
            проверить_имя(найд.group(1), найд.group(2), найд.start(), найд.group(0))
        for найд in _XML_CFG.finditer(т):
            проверить_имя(найд.group(1), найд.group(2), найд.start(), найд.group(0))
        for найд in _XML_СТИЛЬ.finditer(т):
            проверить_имя("StyleItem", найд.group(1), найд.start(), найд.group(0))
        for найд in _XML_ЗАПРОС.finditer(т):
            тип = общее.ТАБЛИЦЫ_ЗАПРОСА[найд.group(1)]
            проверить_имя(тип, найд.group(2), найд.start(), найд.group(0))
        if os.path.basename(путь) == "Configuration.xml":
            н = т.find("<ChildObjects>")
            for найд in re.finditer(r"<(%s)>(%s)</\1>" % ("|".join(_ТИПЫ_XML), _ИМЯ), т[max(н, 0):]):
                проверить_имя(найд.group(1), найд.group(2), max(н, 0) + найд.start(),
                              "в составе расширения %s.%s" % (найд.group(1), найд.group(2)))

    р.проверено = "файлов %d, имён БСП в словаре %d" % (файлов, sum(len(в) for в in бсп.values()))
    if по_бсп:
        р.сводка.append("чаще всего (объект БСП × раз): " + ", ".join(
            "%s×%d" % (и, к) for и, к in по_бсп.most_common(15)))
        р.сводка.append("где (объект расширения × раз): " + ", ".join(
            "%s×%d" % (и, к) for и, к in по_объектам.most_common(15)))
    return р


def главный():
    if "--обновить-словарь" in sys.argv:
        общее.настроить_вывод()
        lm = общее.КОРЕНЬ_РЕПО
        if "--lm" in sys.argv:
            lm = sys.argv[sys.argv.index("--lm") + 1]
        итог, по_типам = построить_словарь(lm)
        print("словарь %s: %d имён" % (СЛОВАРЬ, len(итог)))
        for т, к in sorted(по_типам.items()):
            print("  %-28s %d" % (т, к))
        return
    общее.запустить_один(sys.modules[__name__])


if __name__ == "__main__":
    главный()
