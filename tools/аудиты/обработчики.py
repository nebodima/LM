# -*- coding: utf-8 -*-
"""обработчики — обработчики формы и её элементов подключены и подключены к своему.

Перенесено из «Путевых листов» (аудит_обработчиков.py + проверка_обработчиков_форм.py).
Процедура в модуле формы — ещё не событие: платформа зовёт её, только если в Form.xml
стоит <Event name="…">. Без этой строки код лежит мёртвым (форма «Настройки» ПЛ
открывалась пустой, вкладка с секретом висела на виду). Обратное хуже: событие в
разметке указывает на процедуру, которой нет, — форма упадёт у покупателя в момент события.

В ПЛ события формы (ПриСозданииНаСервере…) проверялись, а события ПОЛЕЙ — нет: процедура
«КонтрагентПриИзменении» была написана и не подключена, подстановка адреса молча не работала.
Здесь проверяется и то, и другое:

  1. событие/действие команды указывает на процедуру, которой в модуле нет;
  2. процедура события формы (ПриОткрытии, ОбработкаОповещения…) есть, а в разметке не подключена;
  3. процедура события элемента (<Элемент>ПриИзменении, …НачалоВыбора, …ПриАктивизацииСтроки…)
     не подключена ни к одному событию, не вызывается из кода и не передаётся строкой —
     мёртвый код, который выглядит как связь;
  4. у элемента два блока <Events> или одно событие дважды — платформа оставит один;
  5. к полю подключён чужой обработчик, хотя для него написан свой «<Поле>ПриИзменении».

    python tools/аудиты/обработчики.py [каталог]
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import общее  # noqa: E402

ИМЯ = "обработчики"
ЛФ = общее.ЛФ
к = общее.ключ

СОБЫТИЯ_ФОРМЫ = {
    "ПриСозданииНаСервере": "OnCreateAtServer", "ПриОткрытии": "OnOpen", "ПриЗакрытии": "OnClose",
    "ПередЗакрытием": "BeforeClose", "ПриПовторномОткрытии": "OnReopen",
    "ОбработкаОповещения": "NotificationProcessing", "ОбработкаВыбора": "ChoiceProcessing",
    "ПриЧтенииНаСервере": "OnReadAtServer", "ПередЗаписью": "BeforeWrite", "ПослеЗаписи": "AfterWrite",
    "ПередЗаписьюНаСервере": "BeforeWriteAtServer", "ПриЗаписиНаСервере": "OnWriteAtServer",
    "ПослеЗаписиНаСервере": "AfterWriteAtServer", "ОбработкаЗаписиНового": "NewWriteProcessing",
    "ОбработкаПроверкиЗаполненияНаСервере": "FillCheckProcessingAtServer",
    "ПередЗагрузкойДанныхИзНастроекНаСервере": "BeforeLoadDataFromSettingsAtServer",
    "ПриЗагрузкеДанныхИзНастроекНаСервере": "OnLoadDataFromSettingsAtServer",
    "ПриСохраненииДанныхВНастройкахНаСервере": "OnSaveDataInSettingsAtServer",
    "ВнешнееСобытие": "ExternalEvent", "ОбработкаАктивизацииОбъекта": "ActivationProcessing",
    "ПриИзмененииПараметров": "OnChangeParameters",
    "ПриЗагрузкеВариантаНаСервере": "OnLoadVariantAtServer",
    "ПередЗагрузкойВариантаНаСервере": "BeforeLoadVariantAtServer",
    "ПриСохраненииВариантаНаСервере": "OnSaveVariantAtServer",
    "ПриЗагрузкеПользовательскихНастроекНаСервере": "OnLoadUserSettingsAtServer",
    "ПриСохраненииПользовательскихНастроекНаСервере": "OnSaveUserSettingsAtServer",
    "ПриОбновленииСоставаПользовательскихНастроекНаСервере": "OnUpdateUserSettingSetAtServer",
}
# Окончания имён обработчиков элементов (так их называет конфигуратор: <Элемент><Событие>).
# Характерные ловятся и без элемента (элемент переименовали — обработчик осиротел),
# общие слова («Выбор», «Нажатие») — только если элемент с таким началом имени есть на форме.
ХАРАКТЕРНЫЕ = ("ПриИзменении", "НачалоВыбораИзСписка", "НачалоВыбора", "ОбработкаВыбора", "АвтоПодбор",
               "ОкончаниеВводаТекста", "ИзменениеТекстаРедактирования", "ОбработкаНавигационнойСсылки",
               "ПриАктивизацииСтроки", "ПриАктивизацииПоля", "ПриАктивизацииЯчейки", "ПередНачаломДобавления",
               "ПередУдалением", "ПослеУдаления", "ПриНачалеРедактирования", "ПередНачаломИзменения",
               "ПередОкончаниемРедактирования", "ПриОкончанииРедактирования", "НачалоПеретаскивания",
               "ПроверкаПеретаскивания", "ОкончаниеПеретаскивания", "ПриСменеСтраницы", "ОбработкаРасшифровки",
               "ПередРазворачиванием", "ПередСворачиванием", "ПриВыводеПериода", "ОбработкаДополнительнойРасшифровки",
               "ДокументСформирован", "ПриНажатии", "ВыборЗначения")
ОБЩИЕ = ("Выбор", "Очистка", "Открытие", "Нажатие", "Регулирование", "Создание", "Перетаскивание")
_ПРОЦЕДУРА = re.compile(r"(?im)^[ \t]*(?:Асинх[ \t]+)?(?:Процедура|Функция)[ \t]+([\wЁё]+)[ \t]*\(")
_ТЕГ_ЭЛЕМЕНТА = re.compile(r'<(InputField|CheckBoxField|LabelField|RadioButtonField|Table|Button|PictureField|'
                           r'LabelDecoration|PictureDecoration|HTMLDocumentField|SpreadSheetDocumentField|Pages|'
                           r'CalendarField|PlannerField|TextDocumentField|UsualGroup|Page)\s+name="([^"]+)"')
_ПОД = {"OnChange": "ПриИзменении", "StartChoice": "НачалоВыбора", "Selection": "Выбор", "Clearing": "Очистка"}


def проверить(исх):
    р = общее.Результат(ИМЯ)
    форм = 0
    for ф in исх.формы():
        if not ф.своя:
            continue
        форм += 1
        модуль = ф.модуль
        текст = модуль.текст if модуль else ""
        объявлены = {к(м.group(1)): м for м in _ПРОЦЕДУРА.finditer(модуль.код)} if модуль else {}
        # привязки: (владелец, событие, обработчик, узел_события)
        привязки = []
        родители = ф.родители()
        for соб in ф.корень.iter(ЛФ + "Event"):
            у = соб
            владелец = "(форма)"
            while у in родители:
                у = родители[у]
                if у.get("name") and общее.местное(у.tag) not in ("Events", "Event"):
                    владелец = у.get("name")
                    break
            привязки.append((владелец, соб.get("name", ""), (соб.text or "").strip()))
        действия = []
        команды = ф.корень.find(ЛФ + "Commands")
        if команды is not None:
            for команда in команды:
                действие = общее.свойство(команда, "Action")
                if действие:
                    действия.append((команда.get("name", ""), действие.strip()))
        подключены = {к(п[2]) for п in привязки} | {к(д) for _, д in действия}

        # 1. указан, но не написан
        for владелец, событие, обработчик in привязки:
            if обработчик and к(обработчик) not in объявлены:
                р.ошибка(ф.отн, ф.строка(ф.текст.find(">%s</Event>" % обработчик)),
                         "%s.%s → %s: процедуры в модуле нет — форма упадёт при событии" % (владелец, событие,
                                                                                        обработчик))
        for команда, действие in действия:
            if к(действие) not in объявлены:
                р.ошибка(ф.отн, ф.строка_элемента(команда), "команда «%s» → %s: процедуры в модуле нет"
                         % (команда, действие))
        if not модуль:
            continue

        def используется(имя):
            # вызов из кода, передача строкой (ОписаниеОповещения("Имя"…), ПодключитьОбработчикОжидания)
            return len(re.findall(r"(?<![\wЁё])%s(?![\wЁё])" % re.escape(имя), текст, re.I)) > 1

        элементы = sorted({и for _, и in _ТЕГ_ЭЛЕМЕНТА.findall(ф.текст)}, key=len, reverse=True)
        for ключ_имени, м in объявлены.items():
            имя = м.group(1)
            if ключ_имени in подключены:
                continue
            строка = модуль.строка(м.start(1))
            # 2. событие формы
            if ключ_имени in {к(и) for и in СОБЫТИЯ_ФОРМЫ}:
                if not используется(имя):
                    событие = next(в for и, в in СОБЫТИЯ_ФОРМЫ.items() if к(и) == ключ_имени)
                    р.ошибка(исх.отн(модуль.путь), строка, "процедура «%s» есть, а событие формы не подключено: "
                             "нужно <Event name=\"%s\">%s</Event>" % (имя, событие, имя))
                continue
            # 3. событие элемента
            элемент = next((э for э in элементы if ключ_имени.startswith(к(э)) and
                            ключ_имени[len(э):] in {к(с) for с in ХАРАКТЕРНЫЕ + ОБЩИЕ}), None)
            характерное = next((с for с in ХАРАКТЕРНЫЕ if ключ_имени.endswith(к(с)) and len(имя) > len(с)), None)
            if (элемент or характерное) and not используется(имя):
                if элемент:
                    что = "обработчик элемента «%s» не подключён ни к одному событию и не вызывается — " \
                          "мёртвая связь" % элемент
                else:
                    что = "похож на обработчик события «%s», но элемента с таким именем на форме нет и " \
                          "процедура не вызывается — осиротевший обработчик" % характерное
                р.ошибка(исх.отн(модуль.путь), строка, "«%s»: %s" % (имя, что))

        # 4. два блока событий / событие дважды
        for узел in ф.корень.iter():
            if not узел.get("name") or общее.местное(узел.tag) in ("Event", "Attribute", "Column", "Command"):
                continue
            блоки = узел.findall(ЛФ + "Events")
            if len(блоки) > 1:
                р.ошибка(ф.отн, ф.строка_элемента(узел.get("name")), "у «%s» %d блока <Events> — платформа оставит "
                         "один обработчик, какой — не определено" % (узел.get("name"), len(блоки)))
            имена = [с.get("name") for б in блоки for с in б]
            for с in sorted({с for с in имена if имена.count(с) > 1}):
                р.ошибка(ф.отн, ф.строка_элемента(узел.get("name")), "у «%s» событие %s указано дважды"
                         % (узел.get("name"), с))

        # 5. чужой обработчик, хотя свой написан
        for владелец, событие, обработчик in привязки:
            if владелец == "(форма)" or событие not in _ПОД:
                continue
            свой = владелец + _ПОД[событие]
            if к(обработчик) != к(свой) and к(свой) in объявлены:
                р.ошибка(ф.отн, ф.строка_элемента(владелец), "%s.%s → %s, а для поля написан %s — он не подключён"
                         % (владелец, событие, обработчик, свой))
    р.проверено = "форм %d" % форм
    return р


