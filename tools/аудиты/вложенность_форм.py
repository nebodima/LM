# -*- coding: utf-8 -*-
"""вложенность_форм — таблица в таблице и страница вне набора страниц роняют клиент.

Перенесено из «Путевых листов» (аудит_вложенности_форм.py). Там таблицу документов
положили внутрь таблицы грузов — конфигуратор загрузил молча, проверка синтаксиса и
85 тестов остались зелёными, а клиент при открытии карточки умирал с
«Недопустимое значение аргумента функции property != nullptr [xdto]». Разметку
платформа кладёт в базу как есть: что во что вложено, видит только клиент — падением.

Правила: в таблице нет другой таблицы, страницы и набора страниц; страница живёт
только внутри набора страниц.

    python tools/аудиты/вложенность_форм.py [каталог]
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import общее  # noqa: E402

ИМЯ = "вложенность_форм"
# «Pages» раньше «Page»: иначе чередование съест набор страниц как страницу
КОНТЕЙНЕР = re.compile(r'<(/?)(Table|Pages|Page|UsualGroup|ButtonGroup|CommandBar|Popup|ChildItems)'
                       r'(\s+name="([^"]+)")?[^>]*?(/?)>')
ЗАПРЕТ = {"Table": {"Table": "таблица внутри таблицы", "Page": "страница внутри таблицы",
                    "Pages": "набор страниц внутри таблицы"}}


def проверить(исх):
    р = общее.Результат(ИМЯ)
    форм = 0
    for ф in исх.формы():
        if not ф.своя:
            continue
        форм += 1
        стек = []
        for м in КОНТЕЙНЕР.finditer(ф.текст):
            закрывающий, тег, _, имя, пустой = м.groups()
            if закрывающий:
                # ищем свой открывающий: одиночный лишний тег не сбивает весь разбор
                for н in range(len(стек) - 1, -1, -1):
                    if стек[н][0] == тег:
                        del стек[н:]
                        break
                continue
            if пустой:
                continue
            for родитель, имя_родителя in стек:
                беда = ЗАПРЕТ.get(родитель, {}).get(тег)
                if беда:
                    р.ошибка(ф.отн, ф.строка(м.start()), "%s: «%s» лежит в «%s» — клиент упадёт с ошибкой XDTO"
                             % (беда, имя or "без имени", имя_родителя or "без имени"))
                    break
            if тег == "Page" and not any(т == "Pages" for т, _ in стек):
                р.ошибка(ф.отн, ф.строка(м.start()),
                         "страница «%s» вне набора страниц — вкладки не будет" % (имя or "без имени"))
            стек.append((тег, имя))
    р.проверено = "форм %d" % форм
    return р


