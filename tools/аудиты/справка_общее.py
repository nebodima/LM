# -*- coding: utf-8 -*-
"""Общее для аудитов справки F1 (справка, полнота_справки, подписи_справки): где лежит справка и что в ней.

Справка в выгрузке 1С — пара файлов в папке Ext владельца: `Ext/Help.xml` (свойства: язык страницы) и
`Ext/Help/ru.html` (сам текст). Владелец — форма (`<Объект>/Forms/<Форма>/Ext`, `CommonForms/<Форма>/Ext`),
объект (`<Объект>/Ext`) или раздел (`Subsystems/…/Ext`). Блок <Help> внутри Form.xml платформа при загрузке
молча выбрасывает (ПЛ, 23.09.2026: F1 не работал с задачи 16) — поэтому справка только отдельными файлами.

Сам по себе модуль не аудит (нет `проверить`), его разделяют три аудита справки.
"""
import html
import os
import re

import общее

ПРОСТРАНСТВО = "http://v8.1c.ru/8.3/xcf/extrnprops"

# Надписи стандартных команд платформы 8.3 (интерфейс «Такси»): в разметке формы их нет — рисует платформа.
КНОПКИ_ПЛАТФОРМЫ = {
    "Записать и закрыть", "Записать", "Провести и закрыть", "Провести", "Отмена проведения", "Создать",
    "Создать группу", "Скопировать", "Изменить", "Пометить на удаление", "Найти", "Отменить поиск", "Ещё",
    "Выбрать", "Печать", "Обновить", "Закрыть", "Сформировать", "Настройки", "Создать на основании",
    "Удалить", "Перечитать", "Справка", "Выгрузить", "Загрузить",
}
ВКЛАДКИ_ПЛАТФОРМЫ = {"Основное"}


def ключ(надпись):
    """Для сравнения надписей: регистр, ё/е, многоточие и лишние пробелы не важны."""
    н = общее.ключ(надпись).replace(" ", " ")
    н = re.sub(r"(\.\.\.|…)+$", "", н.strip())
    return re.sub(r"\s+", " ", н).strip()


def из_имени(имя):
    """«ПодборУчеников» → «Подбор учеников»: так платформа подписывает команду без заголовка."""
    слова = re.findall(r"[А-ЯЁA-Z][а-яёa-z0-9]*|[а-яёa-z0-9]+", имя)
    if not слова:
        return имя
    return " ".join([слова[0]] + [с.lower() for с in слова[1:]])


class Страница:
    """Одна страница справки: ru.html и/или Help.xml в одной папке Ext."""

    def __init__(self, исх, папка_ext):
        self.исх = исх
        self.ext = папка_ext
        self.путь_html = os.path.join(папка_ext, "Help", "ru.html")
        self.путь_xml = os.path.join(папка_ext, "Help.xml")
        self.есть_html = os.path.isfile(self.путь_html)
        self.есть_xml = os.path.isfile(self.путь_xml)
        self.отн = исх.отн(self.путь_html if self.есть_html else self.путь_xml)
        части = исх.отн(папка_ext).split("/")[:-1]          # без «Ext»
        self.части = части
        if части[0] == "Subsystems":
            self.вид = "раздел"
        elif части[0] == "CommonForms" or (len(части) >= 4 and части[2] == "Forms"):
            self.вид = "форма"
        else:
            self.вид = "объект"
        self.сырой = общее.читать(self.путь_html) if self.есть_html else ""
        # текст для человека: без тегов, с раскрытыми &-сущностями
        без_тегов = re.sub(r"<[^>]+>", " ", re.sub(r"<!--.*?-->", " ", self.сырой, flags=re.S))
        self.текст = re.sub(r"[ \t\r\n]+", " ", html.unescape(без_тегов)).strip()

    def строка(self, фрагмент):
        н = self.сырой.find(фрагмент)
        return self.сырой.count("\n", 0, н) + 1 if н >= 0 else 1

    def папка_формы(self):
        """Путь к Ext формы (для страницы формы) — там же лежит Form.xml."""
        return self.ext if self.вид == "форма" else None


def страницы(исх):
    """Все страницы справки исходников (кэш на прогон)."""
    if getattr(исх, "_страницы_справки", None) is None:
        папки = set()
        for путь in исх.файлы(".html", ".xml"):
            имя = os.path.basename(путь)
            родитель = os.path.dirname(путь)
            if имя == "ru.html" and os.path.basename(родитель) == "Help":
                папки.add(os.path.dirname(родитель))
            elif имя == "Help.xml" and os.path.basename(родитель) == "Ext":
                папки.add(родитель)
        исх._страницы_справки = [Страница(исх, п) for п in sorted(папки)]
    return list(исх._страницы_справки)


def надписи_формы(форма):
    """(кнопки, вкладки, все) — надписи формы, как их видит человек (ключами ключ())."""
    кнопки, вкладки, все = set(), set(), set()
    if форма.корень is None:
        return кнопки, вкладки, все
    кэш = getattr(форма, "_надписи_справки", None)
    if кэш is not None:
        return кэш
    лф = общее.ЛФ
    м = форма.модуль
    код = м.текст if м is not None else ""
    родители = форма.родители()

    def видим(узел):
        """Не спрятан ни сам, ни группой выше; спрятанное, которое модуль показывает (…Видимость =), — видимо."""
        у = узел
        while у is not None:
            if (общее.свойство(у, "Visible", "") or "").strip() == "false" and \
                    not re.search(r"Элементы\.%s\.Видимость\s*=" % re.escape(у.get("name", "")), код):
                return False
            у = родители.get(у)
        return True

    команды = {}
    узел_команд = форма.корень.find(лф + "Commands")
    if узел_команд is not None:
        for к in узел_команд.findall(лф + "Command"):
            имя = к.get("name", "")
            команды[имя] = общее.заголовок(к) or из_имени(имя)
    for узел in форма.корень.iter():
        тег = общее.местное(узел.tag)
        з = общее.заголовок(узел)
        if з:
            все.add(ключ(з))
        if тег in ("Button", "Popup", "ButtonGroup"):
            if not видим(узел):
                continue
            if з:
                кнопки.add(ключ(з))
            команда = общее.свойство(узел, "CommandName", "") or ""
            if команда.startswith("Form.Command.") and not з:
                имя = команда[len("Form.Command."):]
                кнопки.add(ключ(команды.get(имя, из_имени(имя))))
        elif тег == "Page" and видим(узел):
            вкладки.add(ключ(з or из_имени(узел.get("name", ""))))
    # заголовки, которые модуль формы ставит сам: Элементы.X.Заголовок = "…" / НСтр("ru = '…'")
    for н in re.finditer(r"\.Заголовок\s*=\s*(?:НСтр\(\s*\"ru\s*=\s*'([^']+)'|\"([^\"]+)\")", код):
        т = н.group(1) or н.group(2)
        кнопки.add(ключ(т))
        вкладки.add(ключ(т))
    кнопки.discard("")
    вкладки.discard("")
    форма._надписи_справки = (кнопки, вкладки, все | кнопки | вкладки)
    return форма._надписи_справки


def кнопки_и_вкладки(исх):
    """Видимые кнопки и вкладки всего продукта (кэш): справка часто зовёт на соседнюю форму
    («кнопкой «Создать цену» в карточке тарифа»), поэтому сверяем с продуктом, а не с одной формой."""
    if getattr(исх, "_кнопки_вкладки_справки", None) is None:
        кнопки = {ключ(к) for к in КНОПКИ_ПЛАТФОРМЫ}
        вкладки = {ключ(в) for в in ВКЛАДКИ_ПЛАТФОРМЫ}
        for ф in исх.формы():
            к, в, _ = надписи_формы(ф)
            кнопки |= к
            вкладки |= в
        исх._кнопки_вкладки_справки = (кнопки, вкладки)
    return исх._кнопки_вкладки_справки
