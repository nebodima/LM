# -*- coding: utf-8 -*-
"""справка — справка F1 не зовёт туда, чего в продукте нет, и дойдёт до базы.

Перенесено из «Путевых листов» (аудит_справки.py) и расширено под справку форм. Справка — то, чем покупатель
заменяет разработчика: пока она обучает искать несуществующее, она хуже её отсутствия — человек считает, что
не нашёл сам. Ловим то, что уже случалось в ПЛ и в черновике Codex (28.09.2026):

  * кнопка «X» / вкладка «X», которых нет на этой форме (для справки объекта — ни на одной его форме);
  * ссылка <a href> не на справку существующего объекта/формы/раздела, или на объект без справки;
  * справка, которая не дойдёт до базы: ru.html без Help.xml (и наоборот), Help.xml не того формата,
    блок <Help> внутри Form.xml (платформа его молча выбрасывает — в ПЛ F1 так не работал никогда);
  * хвосты черновика и техника на виду у покупателя: «[уточнить]», «src:», HTML-комментарии, имена УЗ_…;
  * внешние ресурсы: картинки, скрипты, стили, ссылки http — справка должна открываться без сети.

    python tools/аудиты/справка.py [каталог]
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import общее  # noqa: E402
import справка_общее as сп  # noqa: E402

ИМЯ = "справка"
ССЫЛКА = re.compile(r"^((?:Subsystem\.[\wЁё]+)(?:\.Subsystem\.[\wЁё]+)*|[A-Za-z]+\.[\wЁё]+(?:\.Form\.[\wЁё]+)?)/Help$")
ТЕГ = re.compile(r"<\s*([A-Za-z]+)\b([^>]*)>")
ЗАПРЕТНЫЕ_ТЕГИ = {"img", "script", "style", "iframe", "object", "embed", "frame", "form", "input"}
ВО_ВНЕ = re.compile(r"(?:src|href)\s*=\s*\"(?:https?:|file:|//|mailto:)", re.I)
КНОПКА = re.compile(r"кнопк\w*\s*«([^«»]{2,60})»", re.I)
ВКЛАДКА = re.compile(r"вкладк\w*\s*«([^«»]{2,60})»", re.I)


def цель_ссылки(исх, адрес):
    """Путь к папке Ext, где должна лежать справка по адресу вида Catalog.X/Help, или None, если объекта нет."""
    м = ССЫЛКА.match(адрес)
    if not м:
        return None
    части = м.group(1).split(".")
    if части[0] == "Subsystem":
        путь = [общее.ПАПКА_ВИДА["Subsystem"]]
        for тип, имя in zip(части[0::2], части[1::2]):
            if тип != "Subsystem":
                return None
            if len(путь) > 1:
                путь.append("Subsystems")
            путь.append(имя)
        return os.path.join(исх.корень, *путь, "Ext") if os.path.isfile(
            os.path.join(исх.корень, *путь[:-1], путь[-1] + ".xml")) else None
    тип, имя = части[0], части[1]
    if тип not in общее.ПАПКА_ВИДА or исх.найти(тип, имя) is None:
        return None
    папка = os.path.join(исх.корень, общее.ПАПКА_ВИДА[тип], имя)
    if len(части) == 4:
        if тип == "CommonForm":
            return None
        форма = os.path.join(папка, "Forms", части[3])
        return os.path.join(форма, "Ext") if os.path.isfile(os.path.join(форма, "Ext", "Form.xml")) else None
    return os.path.join(папка, "Ext")


def проверить(исх):
    р = общее.Результат(ИМЯ)
    страницы = сп.страницы(исх)
    ссылок = названий = 0
    for стр in страницы:
        # ── дойдёт ли до базы ──
        if not стр.есть_xml:
            р.ошибка(стр.отн, 1, "есть Help/ru.html, но нет Ext/Help.xml — платформа такую справку не загрузит")
            continue
        xml = общее.читать(стр.путь_xml)
        if сп.ПРОСТРАНСТВО not in xml or not re.search(r"<Page>\s*ru\s*</Page>", xml):
            р.ошибка(исх.отн(стр.путь_xml), 1, "Help.xml не того формата: нужен <Help xmlns=\"%s\"> с <Page>ru</Page>"
                     % сп.ПРОСТРАНСТВО)
        # версия формата — как у владельца: иначе пакетная загрузка отказывает целиком («версия формата
        # отличается от версии ранее загруженных файлов»), а агент конфигуратора молча не грузит ничего (28.09.2026)
        владелец = os.path.join(стр.ext, "Form.xml")
        if not os.path.isfile(владелец):
            владелец = os.path.dirname(стр.ext) + ".xml"
        своя = re.search(r"<Help\b[^>]*\bversion=\"([\d.]+)\"", xml)
        его = re.search(r"<(?:MetaDataObject|Form)\b[^>]*\bversion=\"([\d.]+)\"", общее.читать(владелец)[:3000]) \
            if os.path.isfile(владелец) else None
        if своя and его and своя.group(1) != его.group(1):
            р.ошибка(исх.отн(стр.путь_xml), 2, "версия формата Help.xml %s, а у %s — %s: загрузка откажет (пакетно) "
                     "или молча ничего не загрузит (агент); выровнять: python tools/справка_help_xml.py"
                     % (своя.group(1), os.path.basename(владелец), его.group(1)))
        if not стр.есть_html:
            р.ошибка(исх.отн(стр.путь_xml), 1, "Help.xml ссылается на страницу ru, а файла Help/ru.html нет")
            continue
        # ── внешнее и техническое ──
        for м in ТЕГ.finditer(стр.сырой):
            тег = м.group(1).lower()
            if тег == "link" and "v8help://service_book" in м.group(2):
                continue            # стиль справки самой платформы — как в каждой выгрузке
            if тег not in ЗАПРЕТНЫЕ_ТЕГИ and тег != "link" and not ВО_ВНЕ.search(м.group(2)):
                continue
            р.ошибка(стр.отн, стр.строка(м.group(0)), "«%s» — внешние ресурсы и скрипты в справке запрещены: "
                     "она должна открываться без сети и без сюрпризов" % м.group(0).strip()[:40])
        for хвост, почему in (("[уточнить]", "вопрос черновика остался в тексте"),
                              ("src:", "ссылка черновика на исходники"),
                              ("<!--", "HTML-комментарий (хвост черновика)")):
            if хвост in стр.сырой:
                р.ошибка(стр.отн, стр.строка(хвост), "«%s»: %s" % (хвост, почему))
        техника = re.search(r"\bУЗ_[\wЁё]+", стр.текст)
        if техника:
            р.ошибка(стр.отн, стр.строка(техника.group(0)), "«%s» — имя метаданных на виду у покупателя"
                     % техника.group(0))
        # ── ссылки ──
        for м in re.finditer(r"<a\b[^>]*\bhref\s*=\s*\"([^\"]*)\"", стр.сырой, re.I):
            ссылок += 1
            адрес = м.group(1)
            цель = цель_ссылки(исх, адрес)
            if цель is None:
                р.ошибка(стр.отн, стр.строка(м.group(0)), "ссылка «%s» ведёт не на справку объекта продукта — "
                         "такого адреса нет" % адрес)
            elif not os.path.isfile(os.path.join(цель, "Help", "ru.html")):
                р.ошибка(стр.отн, стр.строка(м.group(0)), "ссылка «%s»: у объекта нет своей справки — "
                         "откроется пустая страница" % адрес)
        # ── кнопки и вкладки, которые справка обещает ──
        кнопки, вкладки = сп.кнопки_и_вкладки(исх)
        for образец, набор, что in ((КНОПКА, кнопки, "кнопки"), (ВКЛАДКА, вкладки, "вкладки")):
            for м in образец.finditer(стр.текст):
                названий += 1
                if сп.ключ(м.group(1)) not in набор:
                    р.ошибка(стр.отн, стр.строка(м.group(1)), "%s «%s» нет ни на одной форме продукта (или она "
                             "спрятана: Visible=false, и модуль её не показывает)" % (что, м.group(1)))
    # ── блок <Help> в разметке формы: платформа его выбрасывает ──
    for ф in исх.формы():
        if ф.корень is not None and ф.корень.find(общее.ЛФ + "Help") is not None:
            р.ошибка(ф.отн, ф.строка(ф.текст.find("<Help")), "блок <Help> внутри Form.xml платформа молча "
                     "выбрасывает — справку формы класть в Ext/Help.xml + Ext/Help/ru.html")
    р.проверено = "страниц справки %d, ссылок %d, названных кнопок/вкладок %d" % (len(страницы), ссылок, названий)
    return р


