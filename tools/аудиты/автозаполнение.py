# -*- coding: utf-8 -*-
"""автозаполнение — обработчик ПриИзменении поля действительно реагирует.

Перенесено из «Путевых листов» (аудит_автозаполнения.py) в общей части. Поле с обработчиком
«ПриИзменении» выглядит связанным, но связь бывает мнимой:

  * обработчик пуст — заготовка конфигуратора, в которую ничего не написали;
  * половинчатая реакция — подстановка идёт только в ПУСТОЕ поле («Если Не
    ЗначениеЗаполнено(Объект.X) Тогда Объект.X = …») и никого не спрашивает: сменил клиента —
    адрес остался от прежнего, человек этого не видит.

Не перенесено правило ПЛ «у поля-ссылки нет обработчика ПриИзменении»: оно держится на
реестре согласованных полей предметной области ПЛ (СОГЛАСОВАНО, ~60 записей с причинами);
без такого реестра для «Учёта занятий» оно даёт шум, а не находки.
(«Обработчик указан, а процедуры нет» ловит аудит обработчики.)

    python tools/аудиты/автозаполнение.py [каталог]
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import общее  # noqa: E402

ИМЯ = "автозаполнение"
ЛФ = общее.ЛФ
ПОЛЯ = ("InputField", "CheckBoxField", "RadioButtonField")


def _тело(код, имя):
    м = re.search(r"(?im)^[ \t]*Процедура[ \t]+%s[ \t]*\([^)]*\)[^\n]*\n(.*?)^[ \t]*КонецПроцедуры"
                  % re.escape(имя), код, re.S)
    return м.group(1) if м else None


def _половинчатая(код, тело):
    куски = [тело]
    for вызов in re.findall(r"([\wЁё]+НаСервере)\s*\(", тело):
        серверное = _тело(код, вызов)
        if серверное:
            куски.append(серверное)
    целиком = "\n".join(куски)
    if re.search(r"ПоказатьВопрос|Вопрос\s*\(", целиком):
        return None
    условия = re.findall(r"(?i)НЕ\s+ЗначениеЗаполнено\s*\(\s*Объект\.([\wЁё]+)\s*\)", целиком)
    присвоены = set(re.findall(r"Объект\.([\wЁё]+)\s*=", целиком))
    общие = sorted(set(условия) & присвоены)
    return общие[0] if общие else None


def проверить(исх):
    р = общее.Результат(ИМЯ)
    полей = 0
    for ф in исх.формы():
        if not ф.своя or not ф.модуль:
            continue
        код = ф.модуль.код          # без комментариев и строк
        for узел in ф.корень.iter():
            if общее.местное(узел.tag) not in ПОЛЯ or общее.свойство(узел, "ReadOnly") == "true":
                continue
            события = узел.find(ЛФ + "Events")
            обработчик = None
            if события is not None:
                for с in события:
                    if с.get("name") == "OnChange":
                        обработчик = (с.text or "").strip()
            if not обработчик:
                continue
            полей += 1
            тело = _тело(код, обработчик)
            if тело is None:
                continue            # нет процедуры — замечание аудита обработчики
            имя = узел.get("name")
            строка = ф.модуль.строка(re.search(r"Процедура[ \t]+%s" % re.escape(обработчик), код).start())
            if not тело.strip():
                р.ошибка(исх.отн(ф.модуль.путь), строка, "«%s»: обработчик ПриИзменении поля «%s» пуст — связь "
                         "мнимая" % (обработчик, имя))
                continue
            защищено = _половинчатая(код, тело)
            if защищено:
                р.ошибка(исх.отн(ф.модуль.путь), строка, "«%s»: Объект.%s подставляется только в пустое поле — "
                         "при смене «%s» старое значение молча остаётся (спросить или перезаполнить)"
                         % (обработчик, защищено, имя))
    р.проверено = "полей с ПриИзменении %d" % полей
    return р


if __name__ == "__main__":
    общее.запустить_один(sys.modules[__name__])
