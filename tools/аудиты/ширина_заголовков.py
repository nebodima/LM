# -*- coding: utf-8 -*-
"""ширина_заголовков — заголовок колонки-флажка помещается в её ширину.

Перенесено из «Путевых листов» (проверка_ширины_заголовков.py). Обычную колонку платформа
умещает сама, а колонка с флажком считает ширину по флажку и режет заголовок многоточием:
человек читает «Обрат…» и «Стоимость рука…». Значок в шапке (HeaderPicture) у флажка с
заголовком — почти запрет: даже расширение не помогло, помогло только удаление значка
(снимок живого стенда ПЛ 07.09.2026).

Правило узкое намеренно (широкая версия в ПЛ дала 71 замечание при трёх настоящих):
у флажка с заголовком и заданной шириной Width ≥ длины заголовка, значка в шапке нет.

    python tools/аудиты/ширина_заголовков.py [каталог]
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import общее  # noqa: E402

ИМЯ = "ширина_заголовков"
ЛФ = общее.ЛФ


def проверить(исх):
    р = общее.Результат(ИМЯ)
    флажков = 0
    for ф in исх.формы():
        if not ф.своя:
            continue
        for э in ф.корень.iter(ЛФ + "CheckBoxField"):
            ширина = общее.свойство(э, "Width")
            подпись = общее.заголовок(э)
            if not ширина or not подпись:
                continue
            флажков += 1
            имя = э.get("name")
            if э.find(ЛФ + "HeaderPicture") is not None:
                р.ошибка(ф.отн, ф.строка_элемента(имя), "флажок «%s» («%s»): значок в шапке — заголовок будет "
                         "обрезан" % (имя, подпись))
            elif ширина.strip().isdigit() and int(ширина) < len(подпись):
                р.ошибка(ф.отн, ф.строка_элемента(имя), "флажок «%s» («%s»): ширина %s, заголовку нужно %d — "
                         "будет «%s…»" % (имя, подпись, ширина, len(подпись), подпись[:max(1, int(ширина) - 1)]))
    р.проверено = "флажков с шириной и заголовком %d" % флажков
    return р


if __name__ == "__main__":
    общее.запустить_один(sys.modules[__name__])
