# -*- coding: utf-8 -*-
"""честность_проверок — проверка, которая не может покраснеть, — не проверка.

Перенесено из «Путевых листов» (аудит_честности_проверок.py). Ревизия ПЛ 29.08.2026 нашла
девяносто дефектов, из них восемьдесят восемь — в самих проверках: четыре теста ядра печатали
«ошибок: 1» и завершались нулём, контрольные примеры расчёта топлива формально проверялись,
а уронить прогон не могли. Руками такое не выловить — тест выглядит написанным.

В tools/тесты/тест_*.py (формат сеанс.py: т.проверить(условие, что)) и в самих аудитах:
  * немой тест — ни одного т.проверить(…) и ни одного raise: провал не дойдёт до кода возврата;
  * проглоченная ошибка — except, который гасит исключение (pass, присваивание) и идёт дальше,
    не отмечая провала и не уходя (raise/return/continue/break); уборка — законное место молчания;
  * условие, которое не может стать ложным — т.проверить(True, …), сравнение с самим собой,
    len(…) >= 0;
  * молчаливый пропуск — две и больше проверок под «если данные нашлись» (Следующий(), Количество(),
    len) без else: на пустой базе они не выполнятся и не покраснеют.
В исходниках 1С:
  * две копии одной логики — одноимённая процедура в модуле формы и в модуле объекта/менеджера,
    и форма не просто зовёт менеджер (в ПЛ форма звала свою копию разбора даты, а тест — правильную).

Осознанное исключение — «# честно: причина» на строке замечания или строкой выше.

    python tools/аудиты/честность_проверок.py
"""
import ast
import glob
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import общее  # noqa: E402

ИМЯ = "честность_проверок"
ПРОВЕРКИ = ("проверить", "проверка", "check")
УБОРКА = ("уборк", "убрать", "удалить", "удален", "чистк", "atexit", "закрыть", "reconfigure")
# события платформы: одноимённые обработчики формы и объекта — разные события, а не копии логики
СОБЫТИЯ = {общее.ключ(и) for и in (
    "ПередЗаписью", "ПриЗаписи", "ПослеЗаписи", "ОбработкаПроведения", "ОбработкаУдаленияПроведения",
    "ОбработкаЗаполнения", "ОбработкаПроверкиЗаполнения", "ПриКопировании", "ПередУдалением",
    "ПриУстановкеНовогоКода", "ПриУстановкеНовогоНомера", "ОбработкаПолученияДанныхВыбора",
    "ОбработкаПолученияФормы", "ОбработкаПолученияПредставления", "ОбработкаПолученияПолейПредставления",
    "ПриСозданииНаСервере", "ПриОткрытии", "ОбработкаОповещения", "ОбработкаВыбора", "ПриЧтенииНаСервере",
    "ПередЗаписьюНаСервере", "ПриЗаписиНаСервере", "ПослеЗаписиНаСервере", "ОбработкаПроверкиЗаполненияНаСервере",
    "ПриКомпоновкеРезультата", "ОбработкаКоманды")}
_ЗАГОЛОВОК = re.compile(r"(?im)^[ \t]*(?:Функция|Процедура)[ \t]+([\wЁё]+)[ \t]*\(")


def _имя_вызова(у):
    if not isinstance(у, ast.Call):
        return ""
    ф = у.func
    return ф.attr if isinstance(ф, ast.Attribute) else getattr(ф, "id", "")


def _прощено(строки, номер):
    return any(0 <= номер - 1 + сдвиг < len(строки) and "# честно:" in строки[номер - 1 + сдвиг]
               for сдвиг in (0, -1))


def _провал(у):
    return _имя_вызова(у) in ПРОВЕРКИ and у.args and isinstance(у.args[0], ast.Constant) and у.args[0].value is False


def _в_попытке_с_провалом(дерево, вызов):
    """«True» честен, если в той же попытке стоит та же проверка с False: в теле try — «дошли без
    исключения», а провал придёт через except; или наоборот — в except «упало, как и ждали», а в
    теле try после ожидаемого исключения стоит проверить(False)."""
    for узел in ast.walk(дерево):
        if not isinstance(узел, ast.Try):
            continue
        в_теле = any(у is вызов for ч in узел.body for у in ast.walk(ч))
        в_обработчике = any(у is вызов for обр in узел.handlers for у in ast.walk(обр))
        if в_теле and any(_провал(у) for обр in узел.handlers for у in ast.walk(обр)):
            return True
        if в_обработчике and any(_провал(у) for ч in узел.body for у in ast.walk(ч)):
            return True
    return False


def _питон(р, путь, отн, тест):
    текст = общее.читать(путь)
    строки = текст.splitlines()
    try:
        дерево = ast.parse(текст)
    except SyntaxError as е:
        р.ошибка(отн, е.lineno or 0, "не разбирается: %s" % е.msg)
        return

    def отметить(номер, что):
        if not _прощено(строки, номер):
            р.ошибка(отн, номер, что)

    вызовы = [у for у in ast.walk(дерево) if isinstance(у, ast.Call)]
    if тест:
        проверок = [у for у in вызовы if _имя_вызова(у) in ПРОВЕРКИ]
        if not проверок and not any(isinstance(у, ast.Raise) for у in ast.walk(дерево)):
            отметить(1, "немой тест: ни одного т.проверить(…) и ни одного raise — прогон увидит успех при любых "
                        "ошибках")
        for у in проверок:
            if not у.args:
                continue
            усл, беда = у.args[0], None
            if isinstance(усл, ast.Constant) and усл.value is True and not _в_попытке_с_провалом(дерево, у):
                беда = "условие — литеральная истина"
            elif isinstance(усл, ast.Compare) and len(усл.ops) == 1:
                левое, правое = усл.left, усл.comparators[0]
                if ast.dump(левое) == ast.dump(правое):
                    беда = "значение сравнивается само с собой"
                elif isinstance(усл.ops[0], ast.GtE) and isinstance(правое, ast.Constant) and правое.value == 0 \
                        and _имя_вызова(левое) == "len":
                    беда = "длина всегда неотрицательна"
            if беда:
                отметить(у.lineno, "проверка не может покраснеть: %s" % беда)
        for узел in ast.walk(дерево):
            if not isinstance(узел, ast.If) or узел.orelse:
                continue
            внутри = sum(1 for у in ast.walk(узел) if _имя_вызова(у) in ПРОВЕРКИ)
            условие = ast.dump(узел.test)
            if внутри >= 2 and any(с in условие for с in ("Следующий", "Next", "Количество", "Count", "'len'")):
                отметить(узел.lineno, "молчаливый пропуск: %d проверок под «если данные нашлись» без else — на "
                                      "пустой базе они не выполнятся и не покраснеют" % внутри)
    for узел in ast.walk(дерево):
        if not isinstance(узел, ast.ExceptHandler):
            continue
        молчит = all(isinstance(у, ast.Pass) or (isinstance(у, ast.Expr) and isinstance(у.value, ast.Constant))
                     or (isinstance(у, ast.Assign) and not any(isinstance(в, ast.Call) for в in ast.walk(у)))
                     for у in узел.body)
        отмечает = any(_имя_вызова(у) in ПРОВЕРКИ + ("ошибка", "print") for у in ast.walk(узел))
        уходит = any(isinstance(у, (ast.Raise, ast.Return, ast.Continue, ast.Break)) for у in ast.walk(узел))
        окрестность = "\n".join(строки[max(0, узел.lineno - 7):узел.lineno + 1]).lower()
        if молчит and not отмечает and not уходит and not any(с in окрестность for с in УБОРКА):
            отметить(узел.lineno, "проглоченная ошибка: except гасит исключение и идёт дальше — провал невидим")


def проверить(исх):
    р = общее.Результат(ИМЯ)
    файлов = 0
    репо = общее.корень_репо(исх)
    if репо is not None:
        for путь in sorted(glob.glob(os.path.join(репо, "tools", "тесты", "*.py")) +
                           glob.glob(os.path.join(репо, "tools", "аудиты", "*.py"))):
            файлов += 1
            отн = os.path.relpath(путь, репо).replace("\\", "/")
            _питон(р, путь, отн, os.path.basename(путь).startswith("тест_") and "/тесты/" in отн)
    else:
        р.сводка.append("каталог — не репозиторий УЗ и не фикстура: тесты не читались")

    # две копии одной логики: модуль формы против модуля объекта / менеджера
    форм = 0
    for ф in исх.формы():
        if not ф.своя or not ф.модуль or not ф.владелец or not ф.владелец.каталог:
            continue
        форм += 1
        свои = {общее.ключ(и): и for и in _ЗАГОЛОВОК.findall(ф.модуль.код)}
        for сосед in ("ObjectModule.bsl", "ManagerModule.bsl"):
            м = исх.модуль(os.path.join(ф.владелец.каталог, "Ext", сосед))
            if not м:
                continue
            for к in sorted(set(свои) & {общее.ключ(и) for и in _ЗАГОЛОВОК.findall(м.код)} - СОБЫТИЯ):
                имя = свои[к]
                тело = re.search(r"(?is)(?:Функция|Процедура)\s+%s\s*\(.*?(?:КонецФункции|КонецПроцедуры)"
                                 % re.escape(имя), ф.модуль.код)
                if тело and re.search(r"(?:Документы|Справочники|РегистрыСведений|РегистрыНакопления|Обработки|"
                                      r"Отчеты|РеквизитФормыВЗначение\([^)]*\)|ОбъектОбработки|Объект)[.\wЁё]*\.%s\s*\("
                                      % re.escape(имя), тело.group(0)):
                    continue                # обёртка: логика одна, в форме только вызов
                р.ошибка(исх.отн(ф.модуль.путь), ф.модуль.строка(тело.start()) if тело else 1,
                         "«%s» есть и в модуле формы, и в %s — две копии одной логики расходятся молча"
                         % (имя, сосед))
    р.проверено = "python-файлов %d, форм с модулем объекта %d" % (файлов, форм)
    return р


