# -*- coding: utf-8 -*-
"""вёрстка_панелей — в командной панели живут только кнопки; вёрстка там рвёт веб-клиент.

Перенесено из «Путевых листов» (проверка_вёрстки_панелей.py). Форма кода листа была собрана
так: надписи, картинка, группа сведений и поле стояли внутри <AutoCommandBar> при пустом
<ChildItems> формы. Толстый клиент это как-то рисовал, а веб-клиент рвал соединение: сервер
за 200 мс писал «форма готова», браузер показывал «Потеряно соединение» — ни ошибки, ни
строки в журнале. Полдня разбора и три ложных подозрения.

Правило: в командной панели (автоматической и заведённой руками) — только Button,
ButtonGroup, Popup, CommandBar; всё остальное — в теле формы.

    python tools/аудиты/вёрстка_панелей.py [каталог]
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import общее  # noqa: E402

ИМЯ = "вёрстка_панелей"
СВОИ = {"Button", "ButtonGroup", "CommandBar", "Popup", "SearchStringAddition", "ViewStatusAddition",
        "SearchControlAddition"}


def проверить(исх):
    р = общее.Результат(ИМЯ)
    форм = панелей = 0
    for ф in исх.формы():
        if not ф.своя:
            continue
        форм += 1
        for панель in ф.корень.iter():
            if общее.местное(панель.tag) not in ("AutoCommandBar", "CommandBar"):
                continue
            дети = панель.find(общее.ЛФ + "ChildItems")
            if дети is None:
                continue
            панелей += 1
            for э in дети:
                тег = общее.местное(э.tag)
                if тег not in СВОИ:
                    р.ошибка(ф.отн, ф.строка_элемента(э.get("name")), "в командной панели «%s» лежит %s «%s» — "
                             "перенести в тело формы: веб-клиент на такой форме рвёт соединение"
                             % (панель.get("name"), тег, э.get("name")))
    р.проверено = "форм %d, панелей %d" % (форм, панелей)
    return р


if __name__ == "__main__":
    общее.запустить_один(sys.modules[__name__])
