# -*- coding: utf-8 -*-
"""компоновка_форм — формы собраны так, как их собирают типовые конфигурации 1С.

Перенесено из «Путевых листов» (аудит_компоновки_форм.py; разбор девяти форм БП, УТ, УНФ:
лучшие формы почти ничего не задают руками — подпись это заголовок поля, ширину и
выравнивание ставит платформа, цвета только стилевые). Ловит отступления:

  * надпись вместо подписи — декорация-надпись и сразу за ней поле без заголовка в
    горизонтальном ряду: колонку подписей платформа выравнивает, только если подпись —
    заголовок самого поля;
  * цвет числом (#EDF4FC, web:…) вместо стилевого — форма не следует за темой;
  * таблица короче 7 строк в форме объекта (стандарт 1С #722 п. 1.4.1);
  * ширина у поля-ссылки вне таблицы — её ставит платформа по типу;
  * высота без предела — многострочное/HTML-поле без высоты и растяжки; таблица со снятой
    растяжкой (VerticalStretch=false) без HeightInTableRows (растяжка таблицы — по умолчанию);
  * две командные панели — у таблицы «Список» формы списка своя панель рядом с панелью
    формы (два ряда «Создать / Ещё»);
  * не помещается по ширине — сумма заданных ширин ряда больше 1280 px (эталон 1280×768).

Осознанное исключение — комментарий в Form.xml `<!-- компоновка: ИмяЭлемента причина -->`.
Долга (списка принятых замечаний, как в ПЛ) нет: всё найденное показывается.

    python tools/аудиты/компоновка_форм.py [каталог]
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import общее  # noqa: E402

ИМЯ = "компоновка_форм"
ЛФ = общее.ЛФ
ДОСТУПНО_PX = 1280 - 40
ПИКСЕЛЕЙ_НА_СИМВОЛ = 23.0 / 1.5
ПИКСЕЛЕЙ_НА_БУКВУ_ПОДПИСИ = 12.5 / 1.5
МИНИМУМ_СТРОК = 7
ПОЛЯ = {"InputField", "CheckBoxField", "LabelField", "PictureField", "RadioButtonField", "TextDocumentField",
        "HTMLDocumentField", "LabelDecoration", "PictureDecoration", "Button"}
ЦВЕТА = ("TextColor", "BackColor", "BorderColor", "TitleTextColor", "TitleBackColor", "FooterTextColor",
         "FooterBackColor", "HeaderTextColor", "HeaderBackColor")
ЧИСЛОВЫЕ_СЛОВА = ("дата", "время", "количество", "сумма", "цена", "ставка", "процент", "скидк", "бонус",
                  "остаток", "долг", "оплат", "номерстроки", "час", "минут", "стоимост", "коэффициент")
СТРОКОВЫЕ_СЛОВА = ("номер", "код", "коммент", "наименование", "адрес", "текст", "телефон", "почта",
                   "пароль", "описание", "примечание", "фамилия", "имя", "отчество")


def _род_типа(вид):
    if вид in ("xs:decimal", "xs:dateTime", "xs:boolean", "v8:StandardPeriod"):
        return "число"
    if вид == "xs:string":
        return "строка"
    if вид in ("cfg:DynamicList", "v8:ValueTable", "v8:ValueTree", "v8:FormattedString", "v8:ValueListType"):
        return "?"
    return "ссылка"


def _типы_объекта(о, кэш):
    """Реквизит шапки → род значения по XML объекта формы."""
    if о is None or not о.xml:
        return {}
    if о.xml not in кэш:
        типы = {}
        т = общее.читать(о.xml).split("<TabularSection", 1)[0]
        for м in re.finditer(r"<Attribute uuid=[^>]*>.*?<Name>([^<]+)</Name>.*?<Type>(.*?)</Type>", т, re.S):
            виды = re.findall(r"<v8:Type>([^<]+)</v8:Type>", м.group(2))
            типы.setdefault(м.group(1), _род_типа(виды[0]) if len(виды) == 1 else "?")
        кэш[о.xml] = типы
    return кэш[о.xml]


def _род_значения(путь, типы_объекта, типы_формы):
    if not путь:
        return "?"
    части = путь.split(".")
    if части[0] == "Объект" and len(части) == 2 and типы_объекта.get(части[1], "?") != "?":
        return типы_объекта[части[1]]
    if len(части) == 1 and типы_формы.get(части[0], "?") != "?":
        return типы_формы[части[0]]
    низ = части[-1].lower()
    if низ in ("number", "code", "description"):
        return "строка"
    if низ in ("date", "linenumber"):
        return "число"
    if any(с in низ for с in ЧИСЛОВЫЕ_СЛОВА):
        return "число"
    if any(с in низ for с in СТРОКОВЫЕ_СЛОВА):
        return "строка"
    return "ссылка"


def проверить(исх):
    р = общее.Результат(ИМЯ)
    кэш = {}
    форм = 0
    for ф in исх.формы():
        if not ф.своя:
            continue
        форм += 1
        прощённые = " ".join(re.findall(r"<!--\s*компоновка:(.*?)-->", ф.текст, re.S))
        корень = ф.корень
        форма_объекта = ф.вид.startswith(("ФормаДокумента", "ФормаЭлемента", "ФормаЗаписи", "ФормаГруппы")) or \
            (ф.вид.startswith("Форма") and not ф.вид.startswith(("ФормаСписка", "ФормаВыбора")) and
             ф.имя.split("/")[0] in ("Documents", "Catalogs"))
        форма_документа = ф.имя.startswith("Documents/") and форма_объекта
        типы_объекта = _типы_объекта(ф.владелец, кэш)
        типы_формы = {}
        реквизиты = корень.find(ЛФ + "Attributes")
        if реквизиты is not None:
            for а in реквизиты:
                тип = а.find(ЛФ + "Type")
                виды = [] if тип is None else [э.text for э in тип if общее.местное(э.tag) == "Type"]
                if а.get("name") and len(виды) == 1:
                    типы_формы[а.get("name")] = _род_типа(виды[0])
        панель = корень.find(ЛФ + "AutoCommandBar")
        панель_формы_сама = панель is not None and общее.свойство(панель, "Autofill") != "false"
        элементы = ф.элементы()
        if элементы is None:
            continue

        def отметить(элемент, что):
            if элемент and re.search(r"(?<![\wЁё])%s(?![\wЁё])" % re.escape(элемент), прощённые):
                return
            р.ошибка(ф.отн, ф.строка_элемента(элемент), "«%s»: %s" % (элемент, что))

        def обойти(узел, в_таблице):
            тег = общее.местное(узел.tag)
            имя = узел.get("name", "")
            def св(и, умолч=None):
                return общее.свойство(узел, и, умолч)
            for цвет in ЦВЕТА:
                з = св(цвет)
                if з and not з.startswith("style:") and з.strip() not in ("auto", ""):
                    отметить(имя, "цвет числом %s=%s — нужен стилевой цвет (style:…)" % (цвет, з))
            if тег == "HTMLDocumentField" and форма_документа:
                отметить(имя, "HTML-поле в форме документа — показ средствами формы 1С")
            растянут = св("VerticalStretch") == "true"
            высота = св("Height") or св("HeightInTableRows") or св("AutoMaxHeight") == "false"
            if тег == "HTMLDocumentField" and not растянут and not высота:
                отметить(имя, "высота без предела: HTML-поле тянется за содержимым")
            if тег == "InputField" and св("MultiLine") == "true" and not растянут and not высота:
                отметить(имя, "высота без предела: многострочный текст выталкивает соседей")
            список_формы = имя == "Список" and not форма_объекта
            if список_формы and тег == "Table" and св("CommandBarLocation") != "None" and панель_формы_сама:
                отметить(имя, "две командные панели: у таблицы списка своя панель рядом с панелью формы — "
                              "CommandBarLocation=None")
            # у таблицы растяжка по вертикали включена по умолчанию: выгрузка из базы явное
            # VerticalStretch=true выбрасывает (проверено 28.09.2026 на UZ_UNF_A), в УНФ 385 таблиц форм
            # документов без высоты и растяжки — все тянутся по окну. Без предела только таблица,
            # у которой растяжку сняли, а высоту не задали
            if тег == "Table" and св("VerticalStretch") == "false" and not высота and not список_формы:
                отметить(имя, "высота без предела: растяжка снята (VerticalStretch=false), а HeightInTableRows нет")
            строк = св("HeightInTableRows")
            if тег == "Table" and форма_объекта and строк and строк.isdigit() and \
                    int(строк) < МИНИМУМ_СТРОК and not растянут:
                отметить(имя, "таблица короче 7 строк (HeightInTableRows=%s, стандарт #722)" % строк)
            if тег == "InputField" and not в_таблице and св("Width") and св("MultiLine") != "true":
                if _род_значения(св("DataPath"), типы_объекта, типы_формы) == "ссылка":
                    отметить(имя, "ширина у ссылки Width=%s — её ставит платформа; длинное ограничивают MaxWidth"
                             % св("Width"))
            дети = узел.find(ЛФ + "ChildItems")
            if дети is None:
                return
            горизонтально = тег in ("UsualGroup", "Page") and св("Group", "Vertical") in ("Horizontal",
                                                                                          "AlwaysHorizontal")
            список = [д for д in дети if общее.местное(д.tag) in ПОЛЯ or
                      общее.местное(д.tag) in ("UsualGroup", "Table", "Pages", "Page")]
            if горизонтально:
                for а, б in zip(список, список[1:]):
                    if (общее.местное(а.tag) == "LabelDecoration" and
                            общее.местное(б.tag) in ("InputField", "CheckBoxField", "LabelField", "RadioButtonField")
                            and общее.свойство(б, "TitleLocation") == "None"
                            and общее.свойство(а, "Hyperlink") != "true"):
                        отметить(б.get("name", ""), "надпись «%s» вместо подписи — подпись это заголовок поля"
                                 % общее.заголовок(а)[:30])
                сумма = 0.0
                for д in список:
                    ш = общее.свойство(д, "Width")
                    if ш and ш.isdigit():
                        сумма += int(ш) * ПИКСЕЛЕЙ_НА_СИМВОЛ
                        if общее.свойство(д, "TitleLocation") not in ("None", "Top", "Bottom") and \
                                общее.местное(д.tag) != "LabelDecoration":
                            сумма += len(общее.заголовок(д)) * ПИКСЕЛЕЙ_НА_БУКВУ_ПОДПИСИ + 8
                if сумма > ДОСТУПНО_PX:
                    отметить(имя, "не помещается по ширине: заданные ширины ряда %d px при %d доступных на 1280"
                             % (сумма, ДОСТУПНО_PX))
            for д in дети:
                обойти(д, в_таблице or тег == "Table")

        for д in элементы:
            обойти(д, False)
    р.проверено = "форм %d" % форм
    return р


