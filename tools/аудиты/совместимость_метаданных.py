# -*- coding: utf-8 -*-
"""совместимость_метаданных — с прошлого выпуска ни один объект и реквизит не удалён и не переименован без миграции.

Перенесено из «Путевых листов» (compat_check.py). У покупателя в базе уже лежат данные
прошлой версии расширения: удалённый или переименованный реквизит при обновлении
расширения — потерянные данные (платформа молча выбросит колонку), сменённый тип или
точность — обрезанные значения, а дата без времени обнуляет время при каждой записи.

Эталон — снимок состава метаданных выпущенной версии: tools/аудиты/эталон_метаданных.json
(у фикстур самотеста — свой, рядом с исходниками). Сверяются справочники, документы,
регистры, перечисления, отчёты, обработки, общие модули, общие формы, константы: объекты,
реквизиты шапки, реквизиты табличных частей, измерения, ресурсы, значения перечислений —
с типом, длиной, точностью и составом даты.

  * удалено / тип изменён — ОШИБКА, если в эталоне нет записи в разделе «миграции»
    (ключ — «Объект» или «Объект|Поле», значение — где миграция: обработчик в УЗ_ОбновлениеДанных);
  * добавлено — не ошибка, печатается в сводке (новое станет эталоном при выпуске).

    python tools/аудиты/совместимость_метаданных.py            # сверить
    python tools/аудиты/совместимость_метаданных.py --принять  # при выпуске: текущее → эталон
"""
import io
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import общее  # noqa: E402

ИМЯ = "совместимость_метаданных"
ЭТАЛОН = os.path.join(общее.ПАПКА_АУДИТОВ, "эталон_метаданных.json")
РАЗДЕЛЫ = ("Catalogs", "Documents", "InformationRegisters", "AccumulationRegisters", "Enums", "DataProcessors",
           "Reports", "CommonModules", "CommonForms", "Constants")
ЧАСТИ = ("Attribute", "Dimension", "Resource", "EnumValue", "TabularSection")


def _м(т):
    return общее.местное(т)


def _тип(свойства):
    тип = next((у for у in свойства if _м(у.tag) == "Type"), None)
    if тип is None:
        return ""
    виды = sorted({(у.text or "").strip() for у in тип.iter() if _м(у.tag) == "Type" and у is not тип})
    подпись = ",".join(виды) or "?"
    знач = {_м(у.tag): (у.text or "").strip() for у in тип.iter()}
    if "Digits" in знач:
        подпись += "(%s.%s)" % (знач["Digits"], знач.get("FractionDigits", "0"))
    elif "Length" in знач:
        подпись += "(%s)" % знач["Length"]
    elif "DateFractions" in знач:
        подпись += "(%s)" % знач["DateFractions"]
    return подпись


def путь_эталона(исх):
    свой = os.path.join(исх.корень, "эталон_метаданных.json")
    if os.path.isfile(свой):
        return свой
    if os.path.normcase(исх.корень) == os.path.normcase(os.path.abspath(общее.КАТАЛОГ_ПО_УМОЛЧАНИЮ)):
        return ЭТАЛОН
    return None


def состав(исх):
    """{«Раздел.Объект»: {«Вид:Имя» или «ТабличнаяЧасть:ТЧ.Реквизит»: тип}} — только свои объекты."""
    итог = {}
    for о in исх.объекты:
        раздел = общее.ПАПКА_ВИДА.get(о.тип)
        if раздел not in РАЗДЕЛЫ or о.заимствован or not о.xml:
            continue
        корень = исх.xml(о.xml)
        узел = next(iter(корень), None) if корень is not None else None
        поля = {}
        дети = next((у for у in узел if _м(у.tag) == "ChildObjects"), None) if узел is not None else None
        for ребёнок in (дети if дети is not None else []):
            вид = _м(ребёнок.tag)
            if вид not in ЧАСТИ:
                continue
            свойства = next((у for у in ребёнок if _м(у.tag) == "Properties"), [])
            имя = next(((у.text or "").strip() for у in свойства if _м(у.tag) == "Name"), "")
            if not имя:
                continue
            if вид != "TabularSection":
                поля["%s:%s" % (вид, имя)] = _тип(свойства)
                continue
            поля["TabularSection:%s" % имя] = ""
            вложенные = next((у for у in ребёнок if _м(у.tag) == "ChildObjects"), [])
            for кол in вложенные:
                св = next((у for у in кол if _м(у.tag) == "Properties"), [])
                и = next(((у.text or "").strip() for у in св if _м(у.tag) == "Name"), "")
                if и:
                    поля["TabularSection:%s.%s" % (имя, и)] = _тип(св)
        итог["%s.%s" % (раздел, о.имя)] = поля
    return итог


def проверить(исх):
    р = общее.Результат(ИМЯ)
    путь = путь_эталона(исх)
    if путь is None:
        р.сводка.append("эталона для этого каталога нет (не src_ext и не фикстуры) — сверка не выполнялась")
        return р
    if not os.path.isfile(путь):
        р.ошибка(путь, 0, "нет эталона метаданных — сверять не с чем (при выпуске: совместимость_метаданных.py "
                          "--принять)")
        return р
    данные = json.load(io.open(путь, encoding="utf-8"))
    было, миграции = данные.get("состав", {}), данные.get("миграции", {})
    сейчас = состав(исх)
    отн = os.path.relpath(путь, исх.корень).replace("\\", "/")
    новых = 0
    for объект in sorted(set(было) | set(сейчас)):
        старое, новое = было.get(объект), сейчас.get(объект)
        if старое is None:
            новых += 1
            р.сводка.append("+ новый объект %s" % объект)
            continue
        if новое is None:
            if объект not in миграции:
                р.ошибка(отн, 0, "%s: объект удалён или переименован, миграции нет — данные покупателя "
                              "потеряются при обновлении" % объект)
            continue
        for поле in sorted(set(старое) | set(новое)):
            ключ = "%s|%s" % (объект, поле)
            if поле not in новое:
                if ключ not in миграции:
                    р.ошибка(отн, 0, "%s: %s удалён или переименован, миграции нет" % (объект, поле))
            elif поле not in старое:
                новых += 1
                р.сводка.append("+ %s: %s (%s)" % (объект, поле, новое[поле]))
            elif старое[поле] != новое[поле] and ключ not in миграции:
                р.ошибка(отн, 0, "%s: %s — тип был %s, стал %s, миграции нет" % (объект, поле, старое[поле],
                                                                               новое[поле]))
    р.проверено = "объектов %d, эталон %s, добавлено с выпуска %d" % (len(сейчас), os.path.basename(путь), новых)
    if len(р.сводка) > 12:
        р.сводка[:] = р.сводка[:10] + ["… добавлений всего %d" % новых]
    return р


def принять(каталог):
    исх = общее.Исходники(каталог)
    # src_ext → tools/аудиты/эталон_метаданных.json; любой другой каталог (фикстуры) — свой эталон рядом
    путь = путь_эталона(исх) or os.path.join(исх.корень, "эталон_метаданных.json")
    миграции = {}
    if os.path.isfile(путь):
        миграции = json.load(io.open(путь, encoding="utf-8")).get("миграции", {})
    сейчас = состав(исх)
    with io.open(путь, "w", encoding="utf-8", newline="\n") as ф:
        json.dump({"описание": "Состав метаданных выпущенной версии УЗ_ext. Меняется только ключом --принять "
                               "при выпуске. «миграции»: ключ «Раздел.Объект» или «Раздел.Объект|Вид:Поле» → "
                               "где перенос данных.", "миграции": {}, "состав": сейчас},
                  ф, ensure_ascii=False, indent=1, sort_keys=True)
    print("эталон принят: объектов %d → %s%s" % (len(сейчас), путь,
                                                  " (записи миграций сброшены: %d)" % len(миграции) if миграции else ""))


if __name__ == "__main__":
    if "--принять" in sys.argv:
        общее.настроить_вывод()
        аргументы = [а for а in sys.argv[1:] if not а.startswith("--")]
        принять(аргументы[0] if аргументы else общее.КАТАЛОГ_ПО_УМОЛЧАНИЮ)
    else:
        общее.запустить_один(sys.modules[__name__])
