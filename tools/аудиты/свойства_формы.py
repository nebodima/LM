# -*- coding: utf-8 -*-
"""свойства_формы — локальная переменная с именем свойства формы.

В модуле формы голое имя `Доступность`, `Заголовок`, `ТолькоПросмотр`, `Элементы`, `Окно`…
— это свойство самой формы, а не новая переменная. `Доступность = УЗ_Почта.Доступность…();`
присваивает форме Структуру, и форма не открывается совсем: «Ошибка при установке значения
атрибута контекста (Доступность) … Несоответствие типов» (УЗ_НастройкиПочты, осмотр 28.09.2026, №1).
Компиляция и /CheckModules этого не ловят — только открытие формы.

Ошибка, если в модуле формы (…/Ext/Form/Module.bsl):
- присваивается свойство только для чтения (`Элементы`, `Окно`, `Команды`, `Параметры`…);
- свойство-значение (`Доступность`, `Заголовок`, `ТолькоПросмотр`…) используется как переменная:
  справа `Новый …`, или в той же процедуре к нему обращаются через точку/индекс (`Доступность.Поле`),
  или оно счётчик `Для Каждого`.
Законно и не ловится: `Заголовок = НСтр("…");`, `Элементы.Поле.Доступность = Ложь;`.

    python tools/аудиты/свойства_формы.py [каталог] [--только-продукт]
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import общее  # noqa: E402

ИМЯ = "свойства_формы"

ТОЛЬКО_ЧТЕНИЕ = """
Элементы Окно Команды Параметры КоманднаяПанель ИмяФормы УникальныйИдентификатор ЭтаФорма ЭтотОбъект
""".split()
ЗНАЧЕНИЯ = """
Доступность Заголовок ТолькоПросмотр Видимость Модифицированность АвтоЗаголовок ЗакрыватьПриВыборе
ЗакрыватьПриЗакрытииВладельца РежимОткрытияОкна ТекущийЭлемент ВладелецФормы КлючНазначенияИспользования
КлючСохраненияПоложенияОкна ПоложениеКоманднойПанели ИнтервалАвтообновления Автообновление
СостояниеОкна ВариантМасштаба Масштаб ПоложениеОкна ПроверятьЗаполнение РежимВыбора МножественныйВыбор
""".split()
К_ЧТЕНИЕ = {общее.ключ(с): с for с in ТОЛЬКО_ЧТЕНИЕ}
К_ЗНАЧЕНИЯ = {общее.ключ(с): с for с in ЗНАЧЕНИЯ}

_НАЧАЛО = (r"(?im)(?:^|;|(?<![\wЁё])Тогда(?![\wЁё])|(?<![\wЁё])Иначе(?![\wЁё])|"
           r"(?<![\wЁё])Цикл(?![\wЁё])|(?<![\wЁё])Попытка(?![\wЁё])|"
           r"(?<![\wЁё])Исключение(?![\wЁё]))[ \t]*([А-Яа-яЁёA-Za-z_][\wЁё]*)[ \t]*=(?!=)[ \t]*(Новый(?![\wЁё]))?")


def тела(код):
    """[(начало, конец)] процедур и функций модуля."""
    итог = []
    for м in re.finditer(r"(?im)^[ \t]*(?:Асинх[ \t]+)?(?:Процедура|Функция)[ \t]+[\wЁё]+[ \t]*\(", код):
        к = re.search(r"(?im)^[ \t]*Конец(?:Процедуры|Функции)(?![\wЁё])", код[м.end():])
        итог.append((м.start(), м.end() + (к.end() if к else len(код) - м.end())))
    return итог


def проверить(исх):
    р = общее.Результат(ИМЯ)
    форм = 0
    for м in исх.модули():
        if not м.путь.replace("\\", "/").endswith("/Ext/Form/Module.bsl"):
            continue
        форм += 1
        к = м.код
        отн = исх.отн(м.путь)
        границы = тела(к)

        def тело(смещ):
            for н, кон in границы:
                if н <= смещ < кон:
                    return к[н:кон]
            return к

        for найд in re.finditer(_НАЧАЛО, к):
            имя = найд.group(1)
            кл = общее.ключ(имя)
            if кл in К_ЧТЕНИЕ:
                р.ошибка(отн, м.строка(найд.start(1)),
                         "присваивание свойству формы «%s» (только чтение) — назовите переменную иначе" % К_ЧТЕНИЕ[кл])
                continue
            if кл not in К_ЗНАЧЕНИЯ:
                continue
            как_объект = найд.group(2) or re.search(
                r"(?i)(?<![\wЁё.])%s\s*[.\[]" % re.escape(имя), тело(найд.start()))
            if как_объект:
                р.ошибка(отн, м.строка(найд.start(1)),
                         "«%s» — свойство формы, а используется как переменная: присваивание меняет саму форму "
                         "(«Несоответствие типов» при открытии) — назовите переменную иначе" % К_ЗНАЧЕНИЯ[кл])
        for найд in re.finditer(r"(?i)(?<![\wЁё.])Для\s+Каждого\s+([\wЁё]+)\s+Из(?![\wЁё])", к):
            кл = общее.ключ(найд.group(1))
            if кл in К_ЧТЕНИЕ or кл in К_ЗНАЧЕНИЯ:
                р.ошибка(отн, м.строка(найд.start(1)),
                         "счётчик «Для Каждого %s» — свойство формы, назовите переменную иначе" % найд.group(1))
    р.проверено = "модулей форм %d" % форм
    return р


if __name__ == "__main__":
    общее.запустить_один(sys.modules[__name__])
