# -*- coding: utf-8 -*-
"""сетка_форм — в одной вертикальной группе поля начинаются на одной вертикали.

Перенесено из «Путевых листов» (проверка_сетки_форм.py). Поля с обычным заголовком
слева платформа выравнивает сама по самой длинной подписи группы. Ступеньки дают другие
строки: горизонтальная группа «надпись-декорация своей ширины + поле без заголовка» и
поле без заголовка, начинающееся от края. Глазами это первое, что замечает владелец.

Для каждой вертикальной группы (и страницы) считается, с какого места начинается первое
поле ввода в строках такого вида; разброс больше 26 px (треть сантиметра) — сбитая сетка.
Не ступенька: строка, где первым стоит поле с заголовком слева (заголовок уходит в общую колонку
подписей группы), надпись НАД полем во вложенной вертикальной группе, содержимое группы-«всплывашки»
(Behavior=PopUp) — в строке от неё только кнопка.

    python tools/аудиты/сетка_форм.py [каталог]
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import общее  # noqa: E402

ИМЯ = "сетка_форм"
ЛФ = общее.ЛФ
ПИКСЕЛЕЙ_НА_СИМВОЛ = 15.3
ПИКСЕЛЕЙ_НА_БУКВУ = 8.3
ПОРОГ = 26
ВЫРОВНЕНО = "<выровнено платформой>"


def _заголовок_слева(узел):
    return общее.свойство(узел, "TitleLocation") not in ("None", "Top", "Bottom", "Right")


def _начало_поля(строка, первый=True):
    """Сдвиг первого поля строки от края группы. None — строка в вертикали не участвует:
    первым в строке стоит поле с заголовком слева — платформа ставит его заголовок в общую колонку
    подписей группы (ChildrenAlign по умолчанию; замер 28.09.2026: «Наименование», «Цвет отображения»,
    «Фото» в трёх горизонтальных строках карточки предмета — поля с одного x=622)."""
    дети = строка.find(ЛФ + "ChildItems")
    if дети is None:
        return None, None
    вертикально = общее.свойство(строка, "Group", "Vertical") == "Vertical"
    сдвиг = 0.0
    for узел in дети:
        тег = общее.местное(узел.tag)
        if общее.свойство(узел, "Visible") == "false":
            continue
        if тег in ("LabelDecoration", "PictureDecoration"):
            if вертикально:
                continue               # надпись над полем, а не слева от него
            ш = общее.свойство(узел, "Width")
            сдвиг += int(ш) * ПИКСЕЛЕЙ_НА_СИМВОЛ if ш and ш.isdigit() else \
                len(общее.заголовок(узел)) * ПИКСЕЛЕЙ_НА_БУКВУ + 20
            первый = False
        elif тег == "Button":
            первый = False
        elif тег == "CheckBoxField":
            return None, None          # флажок рисуется от края, в вертикали полей не участвует
        elif тег in ("InputField", "LabelField"):
            if _заголовок_слева(узел):
                if первый:
                    return None, ВЫРОВНЕНО  # заголовок в общей колонке подписей группы
                сдвиг += len(общее.заголовок(узел)) * ПИКСЕЛЕЙ_НА_БУКВУ + 8
            return сдвиг, узел.get("name")
        elif тег == "UsualGroup":
            if общее.свойство(узел, "Behavior") == "PopUp":
                первый = False
                continue               # содержимое во всплывающем окне, в строке — только кнопка группы
            внутри, имя = _начало_поля(узел, первый)
            if внутри is not None:
                return сдвиг + внутри, имя
            if имя == ВЫРОВНЕНО:
                return None, ВЫРОВНЕНО
            if not вертикально:
                первый = False
    return None, None


def проверить(исх):
    р = общее.Результат(ИМЯ)
    групп = 0
    for ф in исх.формы():
        if not ф.своя:
            continue
        for группа in ф.корень.iter():
            if общее.местное(группа.tag) not in ("UsualGroup", "Page"):
                continue
            if (общее.свойство(группа, "Group") or "Vertical") != "Vertical":
                continue
            дети = группа.find(ЛФ + "ChildItems")
            if дети is None:
                continue
            групп += 1
            начала = []
            for строка in дети:
                тег = общее.местное(строка.tag)
                if тег == "UsualGroup" and общее.свойство(строка, "Group") in ("Horizontal", "AlwaysHorizontal"):
                    сдвиг, имя = _начало_поля(строка)
                elif тег in ("InputField", "LabelField") and общее.свойство(строка, "TitleLocation") == "None":
                    сдвиг, имя = 0.0, строка.get("name")
                else:
                    continue
                if сдвиг is not None:
                    начала.append((сдвиг, имя))
            if len(начала) < 2:
                continue
            низ, верх = min(начала), max(начала)
            if верх[0] - низ[0] > ПОРОГ:
                р.ошибка(ф.отн, ф.строка_элемента(группа.get("name")), "группа «%s»: поля начинаются вразнобой, "
                         "разброс %d px («%s» %d, «%s» %d)" % (группа.get("name"), верх[0] - низ[0], низ[1],
                                                             низ[0], верх[1], верх[0]))
    р.проверено = "вертикальных групп %d" % групп
    return р


