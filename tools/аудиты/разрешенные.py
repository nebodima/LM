# -*- coding: utf-8 -*-
"""разрешенные — запросы, которые читают таблицы с ограничением доступа хозяина, выполняются с РАЗРЕШЕННЫЕ.

Ограничение доступа на уровне записей (RLS) в запросе без РАЗРЕШЕННЫЕ не фильтрует, а роняет весь запрос
«Нарушение прав доступа», как только в выборку попадает запрещённая запись. Типовые УНФ/БП/УТ ограничивают
по организациям (и не только) свои справочники и документы — у нас им не управляем, поэтому:

1. любой запрос (каждый запрос пакета), в источниках которого есть таблица хозяина (не УЗ_: Справочник.Организации,
   Справочник.Пользователи…), начинается с ВЫБРАТЬ РАЗРЕШЕННЫЕ. ЗНАЧЕНИЕ(Справочник.Организации.ПустаяСсылка) —
   не чтение таблицы и не считается. Codex 3, находка 10: форма первого запуска с «ВЫБРАТЬ ПЕРВЫЕ 2 … ИЗ
   Справочник.Организации» не открывалась у руководителя, которому хозяин запретил одну из организаций;
2. в рабочих местах ролей с ограничением записей своих таблиц (РАБОЧИЕ_МЕСТА: «Мои уроки» педагога, первый запуск)
   РАЗРЕШЕННЫЕ — у каждого запроса, какие бы таблицы он ни читал (педагог видит только свои уроки и зарплату).

    python tools/аудиты/разрешенные.py [каталог]
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import общее  # noqa: E402

ИМЯ = "разрешенные"
РАБОЧИЕ_МЕСТА = ("DataProcessors/УЗ_МоиУроки/", "CommonForms/УЗ_ПервыйЗапуск/")
_ТАБЛИЦА = re.compile(r"(?i)(?<![\wЁё.])(Справочник|Документ|РегистрСведений|РегистрНакопления|РегистрБухгалтерии|"
                      r"ПланВидовХарактеристик|ПланСчетов|ЖурналДокументов|Catalog|Document|InformationRegister|"
                      r"AccumulationRegister)\.([\wЁё]+)")
_ЗНАЧЕНИЕ = re.compile(r"(?i)(ЗНАЧЕНИЕ|VALUE)\s*\([^()]*\)")
_РАЗРЕШЕННЫЕ = re.compile(r"(?is)^\s*(ВЫБРАТЬ|SELECT)\s+(РАЗРЕШЕННЫЕ|ALLOWED)(?![\wЁё])")
_ВЫБРАТЬ = re.compile(r"(?i)(?<![\wЁё])(ВЫБРАТЬ|SELECT)(?![\wЁё])")


def проверить(исх):
    р = общее.Результат(ИМЯ)
    запросов = 0
    for м in исх.модули():
        отн = исх.отн(м.путь).replace("\\", "/")
        рабочее_место = отн.startswith(РАБОЧИЕ_МЕСТА)
        for лит in м.литералы:
            содержимое = лит[1]
            if not общее.это_запрос(содержимое):
                continue
            текст = общее.очистить_запрос(содержимое)
            начало = 0
            for часть in текст.split(";"):
                смещение = начало
                начало += len(часть) + 1
                if not _ВЫБРАТЬ.search(часть):
                    continue          # УНИЧТОЖИТЬ и пустой хвост пакета
                запросов += 1
                if _РАЗРЕШЕННЫЕ.match(часть):
                    continue
                без_значений = _ЗНАЧЕНИЕ.sub(lambda н: " " * len(н.group(0)), часть)
                чужие = sorted({"%s.%s" % (вид, имя) for вид, имя in _ТАБЛИЦА.findall(без_значений)
                                if not имя.upper().startswith("УЗ_")})
                строка = м.строка_в_литерале(лит, смещение + len(часть) - len(часть.lstrip()))
                if чужие:
                    р.ошибка(отн, строка, "запрос читает таблицу хозяина (%s) без РАЗРЕШЕННЫЕ — при ограничении "
                             "доступа хозяина он падает «Нарушение прав доступа»" % ", ".join(чужие))
                elif рабочее_место:
                    р.ошибка(отн, строка, "запрос рабочего места ограниченной роли без РАЗРЕШЕННЫЕ — чужая запись "
                             "(урок другого педагога) уронит его «Нарушение прав доступа»")
    р.проверено = "запросов %d" % запросов
    return р


if __name__ == "__main__":
    общее.запустить_один(sys.modules[__name__])
