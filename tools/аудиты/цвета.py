# -*- coding: utf-8 -*-
"""цвета — цвета и шрифты только из палитры: элементы стиля УЗ_* и модуль УЗ_ПалитраПовтИсп.

Вопрос владельца 28.09.2026: «цвета и стили типизированы?». Было: 32 цвета «#RRGGBB» в формах и макетах,
web-цвет, десяток «Новый Цвет(…)» и «WebЦвета.…» в коде — один и тот же «долг» был тёмно-красным, оранжевым и
ярко-красным в соседних формах. Палитра смыслов (docs/визуал/дизайнер.md, раздел 3) задана элементами стиля
StyleItems/УЗ_*.xml (расширение 8.3.27 их поддерживает, проверено загрузкой и выгрузкой 28.09.2026); формы, схемы
компоновки и макеты ссылаются на них «style:УЗ_…», код берёт цвета функциями УЗ_ОбщийКлиентСервер (они читают
УЗ_ПалитраПовтИсп — единственный модуль с ЦветаСтиля/ШрифтыСтиля: на клиенте этих коллекций нет).

Замечание:
  * в XML (формы, табличные макеты) — цвет «#RRGGBB», «web:…» или «win:…» вне StyleItems;
  * «style:УЗ_…», которого нет среди StyleItems (опечатка — платформа молча покажет цвет по умолчанию);
  * схема СКД: элементы стиля РАСШИРЕНИЯ платформа при загрузке схемы не видит («Исключение XDTO … при чтении
    файла» — проверено загрузкой 28.09.2026, формы и табличные макеты их видят). Поэтому в схеме цвет пишется
    числом, но только значением элемента палитры (StyleItems/УЗ_*.xml); другое число, «web:», «style:УЗ_…» —
    замечание;
  * в коде — «Новый Цвет(r, g, b)», «WebЦвета.Имя», «WindowsЦвета.Имя», «Новый Шрифт("Arial", …)» (шрифт с
    гарнитурой или размером; «Новый Шрифт(, , Истина)» — жирный от текущего — можно);
  * ЦветаСтиля./ШрифтыСтиля. вне УЗ_ПалитраПовтИсп.
Законно: «Новый Цвет» без параметров (авто), WebЦвета[Имя] — цвет помещения/предмета/педагога, который выбрал
пользователь (это данные, а не оформление), элементы стиля платформы «style:FormTextColor» и т.п.

    python tools/аудиты/цвета.py [каталог]
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import общее  # noqa: E402

ИМЯ = "цвета"
МОДУЛЬ_ПАЛИТРЫ = "УЗ_ПалитраПовтИсп"
_СЫРОЙ_XML = re.compile(r"(?<![\w&])(#[0-9A-Fa-f]{6})(?![0-9A-Fa-f])|>((?:web|win):[A-Za-z]+)<")
_СТИЛЬ_XML = re.compile(r"style:(УЗ_[\wЁё]+)")
_КОД = [
    (re.compile(r"(?i)(?<![\wЁё.])Новый\s+(Цвет|Color)\s*\(\s*[^)\s]"), "Новый Цвет(r, g, b) — цвет палитры "
     "УЗ_ОбщийКлиентСервер.Цвет…() (элемент стиля УЗ_*)"),
    (re.compile(r"(?i)(?<![\wЁё.])(WebЦвета|WebColors|WindowsЦвета|WindowsColors)\s*\.\s*[\wЁё]+"),
     "именованный web/windows-цвет — цвет палитры УЗ_ОбщийКлиентСервер.Цвет…()"),
    (re.compile(r"(?i)(?<![\wЁё.])Новый\s+(Шрифт|Font)\s*\(\s*(\"|\d)"),
     "шрифт с гарнитурой/размером — шрифт стиля (УЗ_ОбщийКлиентСервер.ШрифтПечати())"),
]
_СТИЛЬ_КОДА = re.compile(r"(?i)(?<![\wЁё.])(ЦветаСтиля|ШрифтыСтиля|StyleColors|StyleFonts)\s*\.\s*([\wЁё]+)")


def проверить(исх):
    р = общее.Результат(ИМЯ)
    стили = {общее.ключ(о.имя) for о in исх.по_типу.get("StyleItem", {}).values()}
    значения = set()
    for о in исх.по_типу.get("StyleItem", {}).values():
        if о.xml:
            м = re.search(r'<Value xsi:type="v8ui:Color">(#[0-9A-Fa-f]{6})</Value>', общее.читать(о.xml))
            if м:
                значения.add(м.group(1).upper())
    файлов = ссылок = 0
    for путь in исх.файлы(".xml"):
        отн = исх.отн(путь)
        if отн.startswith("StyleItems/"):
            continue
        т = общее.читать(путь)
        if "#" not in т and "web:" not in т and "win:" not in т and "style:УЗ_" not in т:
            continue
        файлов += 1
        схема = "<DataCompositionSchema" in т[:600]
        for м in _СЫРОЙ_XML.finditer(т):
            # цвета в XML — только значения тегов/атрибутов; «#» внутри текстов справки и запросов не цвет
            до = т[max(0, м.start() - 1):м.start()]
            if м.group(1) and до not in (">", '"'):
                continue
            if схема and м.group(1) and м.group(1).upper() in значения:
                continue            # цвет палитры числом — единственный способ для схемы СКД расширения
            р.ошибка(отн, т.count("\n", 0, м.start()) + 1, "сырой цвет %s — элемент стиля УЗ_* (style:УЗ_…)" % (
                м.group(1) or м.group(2)))
        for м in _СТИЛЬ_XML.finditer(т):
            ссылок += 1
            if схема:
                р.ошибка(отн, т.count("\n", 0, м.start()) + 1, "style:%s в схеме СКД — элемент стиля расширения схема "
                         "не видит (XDTO при загрузке): цвет палитры числом, значением из StyleItems" % м.group(1))
            elif общее.ключ(м.group(1)) not in стили:
                р.ошибка(отн, т.count("\n", 0, м.start()) + 1, "style:%s — такого элемента стиля нет в StyleItems" %
                         м.group(1))
    for м in исх.модули():
        отн = исх.отн(м.путь)
        к = м.код
        палитра = ("/%s/" % МОДУЛЬ_ПАЛИТРЫ) in м.путь.replace("\\", "/")
        с_литералами = м.код_с_литералами()      # шрифт узнаётся по гарнитуре — строке «"Arial"»
        for шаблон, совет in _КОД:
            for н in шаблон.finditer(с_литералами if "Шрифт" in шаблон.pattern else к):
                р.ошибка(отн, м.строка(н.start()), совет)
        for н in _СТИЛЬ_КОДА.finditer(к):
            if not палитра:
                р.ошибка(отн, м.строка(н.start()), "%s.%s вне %s — на клиенте этой коллекции нет; цвет — функцией "
                         "УЗ_ОбщийКлиентСервер" % (н.group(1), н.group(2), МОДУЛЬ_ПАЛИТРЫ))
            elif общее.ключ(н.group(2)) not in стили:
                р.ошибка(отн, м.строка(н.start()), "%s.%s — такого элемента стиля нет в StyleItems" % (
                    н.group(1), н.group(2)))
    р.проверено = "XML с цветами %d, ссылок на стиль УЗ_ %d, элементов стиля %d" % (файлов, ссылок, len(стили))
    return р


if __name__ == "__main__":
    общее.запустить_один(sys.modules[__name__])
