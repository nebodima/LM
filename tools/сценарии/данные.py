    c = т.c
    ф = Фабрика(т, "УЗС")
    мама = ф.элемент("УЗ_ФизЛица", "Мама Семейная")
    статья = ф.элемент("УЗ_СтатьиДвиженияДенег", "Взнос семьи")
    организация = c.РегистрыСведений.УЗ_Настройки.Настройки().Организация
    for имя, долг in (("Семейный Петя", 300), ("Семейная Катя", 200)):
        ученик = c.Справочники.УЗ_ФизЛица.СоздатьЭлемент()
        ученик.Наименование = "УЗС " + имя
        ученик.Родитель = c.Справочники.УЗ_ФизЛица.Ученики
