НАШИ_РОЛИ = {"руководитель": "УЗ_Руководитель", "менеджер": "УЗ_ОсновнаяРоль", "педагог": "УЗ_Педагог"}
# Тест-менеджер работает в своей пустой базе (прогон_сценариев.БАЗА_МЕНЕДЖЕРА) — пользователь ему здесь не нужен
ПРЕФИКС = "УЗ_"


class Т:
    """Минимум от сеанс.Тест, который нужен функциям тест_права (т.c, т.выбрать)."""

    def __init__(self, c):
        self.c = c

    def убрать(self, действие, что="", пакет=False):
        """Уборка — снимком ссылок (данные.убрать), не по одной: фабрике достаточно заглушки."""

    def выбрать(self, текст, **параметры):
        з = self.c.NewObject("Запрос")
        з.Текст = текст
        for к, в in параметры.items():
            з.УстановитьПараметр(к, в)
        return з.Выполнить().Выгрузить()


def элемент_есть(т, пользователь_ИБ):
    """Элемент справочника Пользователи с этим пользователем ИБ (без него БСП не пускает в сеанс)."""
    return т.выбрать("ВЫБРАТЬ ПЕРВЫЕ 1 П.Ссылка КАК Ссылка ИЗ Справочник.Пользователи КАК П "
                     "ГДЕ П.ИдентификаторПользователяИБ = &И", И=пользователь_ИБ.УникальныйИдентификатор).Количество() > 0


def имя_пользователя(роль):
    return "УЗС " + роль


def виды(c):
    """(Справочник|Документ, имя) объектов расширения."""
    итог = []
    for вид, коллекция in (("Документ", c.Метаданные.Документы), ("Справочник", c.Метаданные.Справочники)):
        for к in range(коллекция.Количество()):
            имя = коллекция.Получить(к).Имя
            if имя.startswith(ПРЕФИКС):
                итог.append((вид, имя))
    # организации хозяина: подготовка справки на вычет заводит свою («УЗС Школа справок») — новая за прогон
    # убирается, как всё (прежде оставалась, и следующий прогон находил две одноимённые — ввод по строке не выбирал)
    итог.append(("Справочник", "Организации"))
    return итог


def снимок(т):
    """{(вид, имя): множество идентификаторов}."""
    c = т.c
    итог = {}
    for вид, имя in виды(c):
        тз = т.выбрать("ВЫБРАТЬ Т.Ссылка КАК Ссылка ИЗ %s.%s КАК Т" % (вид, имя))
        итог[(вид, имя)] = {c.String(тз.Получить(к).Ссылка.УникальныйИдентификатор()) for к in range(тз.Количество())}
    return итог


def подготовить(т, роли):
    """Пользователи ролей (заново) и снимок базы для уборки. → (снимок, настройки до)."""
    c = т.c
    # «Информационная база перемещена» — модальное окно БСП при входе в копию базы: менеджер и клиент висели.
    # Ответ «Это копия» (работа с внешними ресурсами остаётся запрещённой — копии это и нужно) — один раз
    c.БлокировкаРаботыСВнешнимиРесурсами.ЗапретитьРаботуСВнешнимиРесурсами()
    конфигурация = c.Метаданные.Имя
    # пользователи ролей живут между прогонами: заведение — 3 с на каждого, а первый вход нового пользователя
    # в клиент дольше (БСП заполняет его настройки). Пересоздаётся тот, у кого набор ролей не тот
    for роль in роли:
        имя = имя_пользователя(роль)
        нужные = set(ОБЩИЕ_РОЛИ + РОЛИ_ХОЗЯИНА[конфигурация] + [НАШИ_РОЛИ[роль]])
        есть = c.ПользователиИнформационнойБазы.НайтиПоИмени(имя)
        if есть is not None and {р.Имя for р in есть.Роли} == нужные and элемент_есть(т, есть):
            continue
        удалить_пользователя(т, имя)
        завести_пользователя(т, имя, sorted(нужные))
    настройки = c.РегистрыСведений.УЗ_Настройки.Настройки()
    # ссылки — идентификаторами: уборка идёт в ДРУГОМ COM-соединении, ссылка этого там записалась бы пустой
    # (так 28.09.2026 обнулились настройки учёта UZ_BP_C)
    # помощник первого запуска дописывает организацию в найденную кассу без организации (ПерваяНастройкаКасса) —
    # это правка СУЩЕСТВУЮЩЕГО объекта, снимок новых её не видит; 28.09.2026 так касса UZ_BP_C стала кассой
    # «Вторая ООО», и тест логика_касса покраснел. Запоминаем организации всех касс и возвращаем
    кассы = {}
    тз = т.выбрать("ВЫБРАТЬ К.Ссылка КАК Ссылка, К.Организация КАК Организация ИЗ Справочник.УЗ_Кассы КАК К")
    for к in range(тз.Количество()):
        кассы[ид(c, тз.Получить(к).Ссылка)] = ид(c, тз.Получить(к).Организация)
    return снимок(т), {"Организация": ("Организации", ид(c, настройки.Организация)),
                       "Касса": ("УЗ_Кассы", ид(c, настройки.Касса)), "кассы": кассы,
                       "сообщения": настройки_сообщений(т)}


ПОЛЯ_КАНАЛА = ("Включен", "АдресСервиса", "Логин", "Отправитель", "ИмяБота", "СмещениеОбновлений")
ПОЛЯ_ШАБЛОНА = ("Включено", "ЗаЧасов", "ОсталосьЗанятий", "ЗаДней", "Тема", "Текст", "КраткийТекст")


def настройки_сообщений(т):
    """Каналы сообщений и шаблоны (этап 2.2) до прогона — сценарий руководителя их меняет. Ключи доступа в снимок
    (файл на диске) не пишутся: есть ли ключ Telegram — только признак; тестовый ключ ставит и убирает подготовка."""
    c = т.c
    каналы = []
    тз = т.выбрать("ВЫБРАТЬ Н.Канал КАК Канал, Н.Провайдер КАК Провайдер, Н.Включен КАК Включен, Н.АдресСервиса КАК "
                   "АдресСервиса, Н.Логин КАК Логин, Н.Отправитель КАК Отправитель, Н.ИмяБота КАК ИмяБота, "
                   "Н.СмещениеОбновлений КАК СмещениеОбновлений ИЗ РегистрСведений.УЗ_НастройкиКаналов КАК Н")
    for к in range(тз.Количество()):
        с = тз.Получить(к)
        запись = {п: (float(getattr(с, п)) if п == "СмещениеОбновлений" else getattr(с, п)) for п in ПОЛЯ_КАНАЛА}
        запись["Канал"] = имя_значения(c, с.Канал)
        запись["Провайдер"] = имя_значения(c, с.Провайдер)
        каналы.append(запись)
    шаблоны = []
    тз = т.выбрать("ВЫБРАТЬ Ш.Вид КАК Вид, Ш.Включено КАК Включено, Ш.ЗаЧасов КАК ЗаЧасов, Ш.ОсталосьЗанятий КАК "
                   "ОсталосьЗанятий, Ш.ЗаДней КАК ЗаДней, Ш.Тема КАК Тема, Ш.Текст КАК Текст, Ш.КраткийТекст КАК "
                   "КраткийТекст ИЗ РегистрСведений.УЗ_ШаблоныСообщений КАК Ш")
    for к in range(тз.Количество()):
        с = тз.Получить(к)
        запись = {п: (float(getattr(с, п)) if п in ("ЗаЧасов", "ОсталосьЗанятий", "ЗаДней") else getattr(с, п))
                  for п in ПОЛЯ_ШАБЛОНА}
        запись["Вид"] = имя_значения(c, с.Вид)
        шаблоны.append(запись)
    ключ = c.РегистрыСведений.УЗ_КлючиКаналов.СоздатьМенеджерЗаписи()
    ключ.Канал = c.Перечисления.УЗ_КаналыСообщений.Телеграм
    ключ.Прочитать()
    return {"каналы": каналы, "шаблоны": шаблоны, "ключ_был": bool(ключ.Выбран() and c.String(ключ.Ключ))}


def имя_значения(c, значение):
    """Имя значения перечисления («Телеграм») или "" для пустого."""
    if значение is None or значение.Пустая():
        return ""
    мд = значение.Метаданные()
    return мд.ЗначенияПеречисления.Получить(getattr(c.Перечисления, мд.Имя).Индекс(значение)).Имя


def вернуть_сообщения(т, было):
    """Каналы и шаблоны — как до прогона; тестовый ключ Telegram, если его ставила подготовка, — убрать."""
    c = т.c
    for имя, поля, ключ in (("УЗ_НастройкиКаналов", было.get("каналы", []), "Канал"),
                            ("УЗ_ШаблоныСообщений", было.get("шаблоны", []), "Вид")):
        перечисление = "УЗ_КаналыСообщений" if ключ == "Канал" else "УЗ_ВидыСообщений"
        набор = getattr(c.РегистрыСведений, имя).СоздатьНаборЗаписей()
        for запись in поля:
            з = набор.Добавить()
            for п, в in запись.items():
                if п == ключ:
                    в = getattr(getattr(c.Перечисления, перечисление), в)
                elif п == "Провайдер":
                    в = getattr(c.Перечисления.УЗ_ПровайдерыСообщений, в) if в else c.Перечисления.УЗ_ПровайдерыСообщений.ПустаяСсылка()
                setattr(з, п, в)
        набор.Записать()
    if not было.get("ключ_был", True):
        з = c.РегистрыСведений.УЗ_КлючиКаналов.СоздатьМенеджерЗаписи()
        з.Канал = c.Перечисления.УЗ_КаналыСообщений.Телеграм
        з.Прочитать()
        if з.Выбран():
            з.Удалить()


def каналы_сообщений(т):
    """Сценарий руководителя «каналы сообщений» (этап 2.2): ученик с согласием и привязанным Telegram (чат 1001) и
    ключ Telegram. Сценарий ставит адрес сервиса 127.0.0.1:1 (закрытый порт этой машины) — сообщения никуда не
    уходят ни из «Проверить канал», ни из «Сообщения ученику». Ключ копии, если он есть, не трогается; нет —
    ставится тестовый и убирается уборкой (снимок помнит, что ключа не было)."""
    c = т.c
    ученик = c.Справочники.УЗ_ФизЛица.СоздатьЭлемент()
    ученик.Наименование = "УЗС Сообщения Ученик"
    ученик.Родитель = c.Справочники.УЗ_ФизЛица.Ученики
    ученик.ОповеститьПоEmail = True
    ученик.ПредпочитаемыйКанал = c.Перечисления.УЗ_КаналыСообщений.Телеграм
    ученик.Записать()
    привязка = c.РегистрыСведений.УЗ_ПривязкиКаналов.СоздатьМенеджерЗаписи()
    привязка.ФизЛицо = ученик.Ссылка
    привязка.Канал = c.Перечисления.УЗ_КаналыСообщений.Телеграм
    привязка.Адрес = "1001"
    привязка.Записать()
    # флажки «Отправлять через Telegram» и «О занятии» сценарий ставит щелчком клиента тестирования: в копии, где
    # они уже включены (UZ_BP_R 30.09.2026 — бот владельца), щелчок их СНИМАЛ, и «Сообщение ученику» видело канал
    # выключенным. Исходное состояние — выключены; прежние настройки вернёт уборка (снимок «сообщения»).
    for регистр, поле, отбор, значение in (("УЗ_НастройкиКаналов", "Включен", "Канал", c.Перечисления.УЗ_КаналыСообщений.Телеграм),
                                           ("УЗ_ШаблоныСообщений", "Включено", "Вид", c.Перечисления.УЗ_ВидыСообщений.Занятие)):
        з = getattr(c.РегистрыСведений, регистр).СоздатьМенеджерЗаписи()
        setattr(з, отбор, значение)
        з.Прочитать()
        if з.Выбран() and getattr(з, поле):
            setattr(з, поле, False)
            з.Записать()
    ключ = c.РегистрыСведений.УЗ_КлючиКаналов.СоздатьМенеджерЗаписи()
    ключ.Канал = c.Перечисления.УЗ_КаналыСообщений.Телеграм
    ключ.Прочитать()
    if not ключ.Выбран() or not c.String(ключ.Ключ):
        ключ.Канал = c.Перечисления.УЗ_КаналыСообщений.Телеграм
        ключ.Ключ = "0:uzs-scenario"
        ключ.Записать()


def сохранить_снимок(путь, база, до, настройки_до):
    """Снимок «до прогона» — в файл, пока уборка не прошла. Прогон, прерванный на середине (кончилась лицензия 1С,
    закрыли окно, Ctrl+C), оставлял в базе свои объекты, а следующий прогон брал их в свой снимок «до» и уже не
    убирал: 28.09.2026 помощник первого запуска нашёл кассу, предмет, педагога, группу «уже есть» (создано 0 из 6),
    ПКО и расчёт зарплаты посчитали 0. Файл живёт до успешной уборки; следующий прогон начинает с уборки по нему."""
    with open(путь, "w", encoding="utf-8") as ф:
        json.dump({"база": os.path.normcase(os.path.abspath(база)),
                   "до": [[вид, имя, sorted(иды)] for (вид, имя), иды in до.items()],
                   "настройки": настройки_до}, ф, ensure_ascii=False)


def прочитать_снимок(путь, база):
    """→ (до, настройки_до) прерванного прогона этой базы | None."""
    if not os.path.exists(путь):
        return None
    with open(путь, encoding="utf-8") as ф:
        д = json.load(ф)
    if д.get("база") != os.path.normcase(os.path.abspath(база)):
        return None
    return {(вид, имя): set(иды) for вид, имя, иды in д["до"]}, д["настройки"]


def ид(c, ссылка):
    return c.String(ссылка.УникальныйИдентификатор()) if ссылка is not None and not ссылка.Пустая() else None


