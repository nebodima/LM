        д.Дата = ф.день(-1, 10)
        д.ФизЛицо = ученик.Ссылка
        д.Организация = организация
        д.СтатьяЗатрат = статья
        д.Сумма = долг
        д.Комментарий = "УЗС сценарий"
        ошибка, сообщения = ф.записать(д)
        if ошибка:
            raise RuntimeError("подготовка: долг %s не начислен: %s %s" % (имя, ошибка, сообщения))


