"""Подготовка и уборка данных сценариев — под администратором через COM (одно соединение до ролей, одно после:
одновременно с клиентом роли и менеджером COM не держим — лицензий мало).

Пользователи ролей заводятся тем же кодом, что в тест_права.py (наборы ролей хозяина — docs/роли_и_права.md), без
пароля. Уборка — всё, что появилось за прогон: снимок ссылок справочников и документов «Учёта занятий» до прогона,
после — новые удаляются (документы вместе с движениями, сеанс.удалить_объект), записи независимых регистров
сведений УЗ_ с новыми ссылками в измерениях, пользователи ролей; настройки учёта (организация, касса) —
как были до помощника первого запуска.
"""
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "тесты"))
import сеанс  # noqa: E402
from тест_права import ОБЩИЕ_РОЛИ, РОЛИ_ХОЗЯИНА, завести_пользователя, удалить_пользователя  # noqa: E402

НАШИ_РОЛИ = {"руководитель": "УЗ_Руководитель", "менеджер": "УЗ_ОсновнаяРоль", "педагог": "УЗ_Педагог"}
# Тест-менеджер работает в своей пустой базе (прогон_сценариев.БАЗА_МЕНЕДЖЕРА) — пользователь ему здесь не нужен
ПРЕФИКС = "УЗ_"


class Т:
    """Минимум от сеанс.Тест, который нужен функциям тест_права (т.c, т.выбрать)."""

    def __init__(self, c):
        self.c = c

    def убрать(self, действие, что="", пакет=False):
        """Уборка — снимком ссылок (данные.убрать), не по одной: фабрике достаточно заглушки."""

    def выбрать(self, текст, **параметры):
        з = self.c.NewObject("Запрос")
        з.Текст = текст
        for к, в in параметры.items():
            з.УстановитьПараметр(к, в)
        return з.Выполнить().Выгрузить()


def элемент_есть(т, пользователь_ИБ):
    """Элемент справочника Пользователи с этим пользователем ИБ (без него БСП не пускает в сеанс)."""
    return т.выбрать("ВЫБРАТЬ ПЕРВЫЕ 1 П.Ссылка КАК Ссылка ИЗ Справочник.Пользователи КАК П "
                     "ГДЕ П.ИдентификаторПользователяИБ = &И", И=пользователь_ИБ.УникальныйИдентификатор).Количество() > 0


def имя_пользователя(роль):
    return "УЗС " + роль


def виды(c):
    """(Справочник|Документ, имя) объектов расширения."""
    итог = []
    for вид, коллекция in (("Документ", c.Метаданные.Документы), ("Справочник", c.Метаданные.Справочники)):
        for к in range(коллекция.Количество()):
            имя = коллекция.Получить(к).Имя
            if имя.startswith(ПРЕФИКС):
                итог.append((вид, имя))
    return итог


def снимок(т):
    """{(вид, имя): множество идентификаторов}."""
    c = т.c
    итог = {}
    for вид, имя in виды(c):
        тз = т.выбрать("ВЫБРАТЬ Т.Ссылка КАК Ссылка ИЗ %s.%s КАК Т" % (вид, имя))
        итог[(вид, имя)] = {c.String(тз.Получить(к).Ссылка.УникальныйИдентификатор()) for к in range(тз.Количество())}
    return итог


def подготовить(т, роли):
    """Пользователи ролей (заново) и снимок базы для уборки. → (снимок, настройки до)."""
    c = т.c
    # «Информационная база перемещена» — модальное окно БСП при входе в копию базы: менеджер и клиент висели.
    # Ответ «Это копия» (работа с внешними ресурсами остаётся запрещённой — копии это и нужно) — один раз
    c.БлокировкаРаботыСВнешнимиРесурсами.ЗапретитьРаботуСВнешнимиРесурсами()
    конфигурация = c.Метаданные.Имя
    # пользователи ролей живут между прогонами: заведение — 3 с на каждого, а первый вход нового пользователя
    # в клиент дольше (БСП заполняет его настройки). Пересоздаётся тот, у кого набор ролей не тот
    for роль in роли:
        имя = имя_пользователя(роль)
        нужные = set(ОБЩИЕ_РОЛИ + РОЛИ_ХОЗЯИНА[конфигурация] + [НАШИ_РОЛИ[роль]])
        есть = c.ПользователиИнформационнойБазы.НайтиПоИмени(имя)
        if есть is not None and {р.Имя for р in есть.Роли} == нужные and элемент_есть(т, есть):
            continue
        удалить_пользователя(т, имя)
        завести_пользователя(т, имя, sorted(нужные))
    настройки = c.РегистрыСведений.УЗ_Настройки.Настройки()
    # ссылки — идентификаторами: уборка идёт в ДРУГОМ COM-соединении, ссылка этого там записалась бы пустой
    # (так 28.09.2026 обнулились настройки учёта UZ_BP_C)
    # помощник первого запуска дописывает организацию в найденную кассу без организации (ПерваяНастройкаКасса) —
    # это правка СУЩЕСТВУЮЩЕГО объекта, снимок новых её не видит; 28.09.2026 так касса UZ_BP_C стала кассой
    # «Вторая ООО», и тест логика_касса покраснел. Запоминаем организации всех касс и возвращаем
    кассы = {}
    тз = т.выбрать("ВЫБРАТЬ К.Ссылка КАК Ссылка, К.Организация КАК Организация ИЗ Справочник.УЗ_Кассы КАК К")
    for к in range(тз.Количество()):
        кассы[ид(c, тз.Получить(к).Ссылка)] = ид(c, тз.Получить(к).Организация)
    return снимок(т), {"Организация": ("Организации", ид(c, настройки.Организация)),
                       "Касса": ("УЗ_Кассы", ид(c, настройки.Касса)), "кассы": кассы}


def сохранить_снимок(путь, база, до, настройки_до):
    """Снимок «до прогона» — в файл, пока уборка не прошла. Прогон, прерванный на середине (кончилась лицензия 1С,
    закрыли окно, Ctrl+C), оставлял в базе свои объекты, а следующий прогон брал их в свой снимок «до» и уже не
    убирал: 28.09.2026 помощник первого запуска нашёл кассу, предмет, педагога, группу «уже есть» (создано 0 из 6),
    ПКО и расчёт зарплаты посчитали 0. Файл живёт до успешной уборки; следующий прогон начинает с уборки по нему."""
    with open(путь, "w", encoding="utf-8") as ф:
        json.dump({"база": os.path.normcase(os.path.abspath(база)),
                   "до": [[вид, имя, sorted(иды)] for (вид, имя), иды in до.items()],
                   "настройки": настройки_до}, ф, ensure_ascii=False)


def прочитать_снимок(путь, база):
    """→ (до, настройки_до) прерванного прогона этой базы | None."""
    if not os.path.exists(путь):
        return None
    with open(путь, encoding="utf-8") as ф:
        д = json.load(ф)
    if д.get("база") != os.path.normcase(os.path.abspath(база)):
        return None
    return {(вид, имя): set(иды) for вид, имя, иды in д["до"]}, д["настройки"]


def ид(c, ссылка):
    return c.String(ссылка.УникальныйИдентификатор()) if ссылка is not None and not ссылка.Пустая() else None


def чужие_данные(т):
    """Урок другого педагога на сегодня — педагогу роли «открыть чужой урок» (отказ). Не проведён (план): педагогу
    он не виден ни в каком виде. → навигационная ссылка."""
    from фабрика import Фабрика
    ф = Фабрика(т, "УЗС")
    чужой = ф.педагог("Чужой педагог")
    д = ф.урок(чужой, ф.день(0, 3), 1)
    ошибка, сообщения = ф.записать(д, "Запись")
    if ошибка:
        raise RuntimeError("подготовка: урок чужого педагога не записан: %s %s" % (ошибка, сообщения))
    return т.c.String(т.c.ПолучитьНавигационнуюСсылку(д.Ссылка))


def семья_должников(т):
    """Мама платит за двоих детей (этап 2.1, В33/В35): у Пети и Кати плательщик «УЗС Мама Семейная» (основной),
    долги — начислениями ученику 300 и 200 в организации учёта по умолчанию. Менеджер оплачивает их одним приходом
    («Заполнить по долгам» → 500). Уборка — снимком ссылок, как всё за прогон."""
    from фабрика import Фабрика
    c = т.c
    ф = Фабрика(т, "УЗС")
    мама = ф.элемент("УЗ_ФизЛица", "Мама Семейная")
    статья = ф.элемент("УЗ_СтатьиДвиженияДенег", "Взнос семьи")
    организация = c.РегистрыСведений.УЗ_Настройки.Настройки().Организация
    for имя, долг in (("Семейный Петя", 300), ("Семейная Катя", 200)):
        ученик = c.Справочники.УЗ_ФизЛица.СоздатьЭлемент()
        ученик.Наименование = "УЗС " + имя
        ученик.Родитель = c.Справочники.УЗ_ФизЛица.Ученики
        строка = ученик.Плательщики.Добавить()
        строка.Плательщик = мама
        строка.КемПриходится = "мама"
        строка.Основной = True
        ученик.Записать()
        д = c.Документы.УЗ_НачислениеУченику.СоздатьДокумент()
        д.Дата = ф.день(-1, 10)
        д.ФизЛицо = ученик.Ссылка
        д.Организация = организация
        д.СтатьяЗатрат = статья
        д.Сумма = долг
        д.Комментарий = "УЗС сценарий"
        ошибка, сообщения = ф.записать(д)
        if ошибка:
            raise RuntimeError("подготовка: долг %s не начислен: %s %s" % (имя, ошибка, сообщения))


def переменные(т):
    """Значения шагов {имя}: даты и ссылки, которые сценарию не найти самому."""
    сегодня = сеанс.сегодня()
    import datetime
    семья_должников(т)
    return {"чужой_урок": чужие_данные(т), "сегодня": сегодня.strftime("%d.%m.%Y"),
            "завтра": (сегодня + datetime.timedelta(days=1)).strftime("%d.%m.%Y"),
            # как в представлении урока (ДФ='д.ММ.гг (Ч:мм)'): день БЕЗ ведущего нуля — «1.10.26», не «01.10.26»
            "сегодня_кратко": "%d.%s" % (сегодня.day, сегодня.strftime("%m.%y")),
            # время групповых уроков помощника: урок сегодня уже начался — его можно провести (будущий нельзя).
            # 0:01 — начался в любое время суток, кроме первой минуты (её и переход суток прогон пережидает:
            # прогон_сценариев.дождаться_дня)
            "время": "0:01"}


def убрать(т, до, настройки_до, роли, убрать_пользователей=False):
    """Удалить всё новое за прогон. → список строк отчёта."""
    c = т.c
    после = снимок(т)
    отчет = []
    новые = []
    # документы — первыми (их движения ссылаются на справочники), потом справочники
    for (вид, имя), иды in sorted(после.items(), key=lambda п: п[0][0] != "Документ"):
        for новый in иды - до.get((вид, имя), set()):
            коллекция = c.Документы if вид == "Документ" else c.Справочники
            новые.append((вид, имя, getattr(коллекция, имя).ПолучитьСсылку(c.NewObject("УникальныйИдентификатор", новый))))
    if новые:
        отчет.append("новых объектов: %d (%s)" % (len(новые), ", ".join(sorted({и for _, и, _ in новые}))))
    ссылки = c.NewObject("Массив")
    for _, _, ссылка in новые:
        ссылки.Добавить(ссылка)
    # записи независимых регистров сведений с новыми ссылками в измерениях (цены тарифов, группы учеников, …)
    регистры = c.Метаданные.РегистрыСведений
    for к in range(регистры.Количество()):
        мд = регистры.Получить(к)
        if not мд.Имя.startswith(ПРЕФИКС) or c.String(мд.РежимЗаписи) == "ПодчинениеРегистратору":
            continue
        for и in range(мд.Измерения.Количество()):
            изм = мд.Измерения.Получить(и).Имя
            тз = т.выбрать("ВЫБРАТЬ РАЗЛИЧНЫЕ Р.%s КАК З ИЗ РегистрСведений.%s КАК Р ГДЕ Р.%s В (&Новые)"
                           % (изм, мд.Имя, изм), Новые=ссылки)
            for н in range(тз.Количество()):
                набор = getattr(c.РегистрыСведений, мд.Имя).СоздатьНаборЗаписей()
                getattr(набор.Отбор, изм).Установить(тз.Получить(н).З)
                набор.ОбменДанными.Загрузка = True
                набор.Записать()
    ошибки = []
    for вид, имя, ссылка in новые:
        # предопределённый элемент (касса ОсновнаяКасса) не наш: платформа сама его не вернёт, а продукт на него
        # опирается (основная касса по умолчанию). Новым он выглядит, если его удалили и создали заново
        if вид == "Справочник" and ссылка.Предопределенный:
            continue
        try:
            сеанс.удалить_объект(c, ссылка, загрузка=True)
        except Exception as е:
            ошибки.append("%s.%s: %s" % (вид, имя, сеанс.текст_ошибки(е, 150)))
    if ошибки:
        отчет.append("не удалены: " + "; ".join(ошибки))
    for ид_кассы, ид_организации in настройки_до.pop("кассы", {}).items():
        касса = c.Справочники.УЗ_Кассы.ПолучитьСсылку(c.NewObject("УникальныйИдентификатор", ид_кассы)).ПолучитьОбъект()
        if касса is None:
            continue
        организация = (c.Справочники.Организации.ПолучитьСсылку(c.NewObject("УникальныйИдентификатор", ид_организации))
                       if ид_организации else c.Справочники.Организации.ПустаяСсылка())
        if ид(c, касса.Организация) != ид_организации:
            касса.Организация = организация
            касса.ОбменДанными.Загрузка = True
            касса.Записать()
            отчет.append("касса «%s»: организация возвращена" % касса.Наименование)
    значения = c.NewObject("Структура")
    for ключ, (справочник, ид_) in настройки_до.items():
        менеджер = getattr(c.Справочники, справочник)
        значения.Вставить(ключ, менеджер.ПолучитьСсылку(c.NewObject("УникальныйИдентификатор", ид_)) if ид_
                          else менеджер.ПустаяСсылка())
    c.РегистрыСведений.УЗ_Настройки.ЗаписатьНастройки(значения)
    if убрать_пользователей:
        for роль in НАШИ_РОЛИ:
            удалить_пользователя(т, имя_пользователя(роль))
        отчет.append("пользователи ролей удалены")
    return отчет
