def свободный_порт():
    with socket.socket() as с:
        с.bind(("127.0.0.1", 0))
        return с.getsockname()[1]


def погасить(процесс):
    if процесс and процесс.poll() is None:
        subprocess.run(["taskkill", "/F", "/T", "/PID", str(процесс.pid)], capture_output=True)
        try:
            процесс.wait(10)
        except Exception:
            pass


def прогнать_роль(роль, пользователь, сценарии, переменные, сторож, запуск=1):
    """Запуск с повтором: «Текущему соединению с информационной базой не назначен сеанс» — клиент или менеджер
    не получил лицензию (сеансы только что снятого клиента ещё не освобождены, либо лицензии заняли чужие
    процессы 1С на этом ПК) — через 3 с ещё раз, до 3 попыток."""
    for попытка in range(3):
        итог, сек, снимки = _прогнать_роль(роль, пользователь, сценарии, переменные, сторож, запуск)
        журналы = ""
        for кто in ("клиент", "менеджер"):
            путь = os.path.join(ИТОГИ, "%s_%s.log" % (кто, роль))
            if os.path.exists(путь):
                журналы += open(путь, encoding="utf-8-sig", errors="replace").read()
        if итог is not None or "не назначен сеанс" not in журналы:
            return итог, сек, снимки
        печать("  %s: сеанс не назначен (лицензия?) — повтор через 3 с" % роль)
        time.sleep(3)
    return итог, сек, снимки


def _прогнать_роль(роль, пользователь, сценарии, переменные, сторож, запуск=1):
    """Тест-клиент роли + тест-менеджер с исполнителем. Возвращает (итог исполнителя | None, секунд, снимки)."""
    порт = свободный_порт()
    итог_файл = os.path.join(ИТОГИ, "итог_%s.json" % роль)
    задание_файл = os.path.join(ИТОГИ, "задание_%s.json" % роль)
    if os.path.exists(итог_файл):
        os.remove(итог_файл)
    задание = dict(порт=порт, итог=итог_файл, снимки=ИТОГИ, роль="%s_%d" % (роль, запуск), переменные=переменные,
                   сценарии=сценарии)
    with open(задание_файл, "w", encoding="utf-8") as ф:
        json.dump(задание, ф, ensure_ascii=False, indent=1)
    н = time.time()
    клиент = менеджер = None
    снимки = []
    try:
        клиент = subprocess.Popen([ТОНКИЙ, "ENTERPRISE", "/F", БАЗА, "/N", пользователь] + ОБЩИЕ_КЛЮЧИ +
                                  ["/TESTCLIENT", "-TPort", str(порт), "/Out", os.path.join(ИТОГИ, "клиент_%s.log" % роль)])
        сторож.пиды.add(клиент.pid)
        менеджер = subprocess.Popen([ТОНКИЙ, "ENTERPRISE", "/F", БАЗА_МЕНЕДЖЕРА] + ОБЩИЕ_КЛЮЧИ +
                                    ["/TESTMANAGER", "/Execute", EPF, "/C", задание_файл, "/Out", os.path.join(ИТОГИ, "менеджер_%s.log" % роль)])
        сторож.пиды.add(менеджер.pid)
        срок = н + float(аргумент("таймаут", 3 * БЮДЖЕТ_РОЛИ))
        связь = None
        while менеджер.poll() is None and time.time() < срок:
            if связь is None and os.path.exists(итог_файл):
                связь = time.time() - н
                if аргумент("замер"):
                    печать("  %s: исполнитель на связи через %.1f с после запуска" % (роль, связь))
            for имя in os.listdir(ИТОГИ):
                if имя.endswith(".запрос") and имя.startswith(роль + "_"):
                    запрос = os.path.join(ИТОГИ, имя)
                    try:
                        снимки += окна.снимок({клиент.pid}, запрос[:-len(".запрос")] + ".png")
                    except Exception as е:
                        печать("  снимок не снят: %s" % е)
                    os.remove(запрос)
            time.sleep(0.05)
        if менеджер.poll() is None:
            печать("  ТАЙМАУТ роли %s: %d с" % (роль, 3 * БЮДЖЕТ_РОЛИ))
            try:
                снимки += окна.снимок({клиент.pid}, os.path.join(ИТОГИ, "%s_таймаут.png" % роль))
                снимки += окна.снимок({менеджер.pid}, os.path.join(ИТОГИ, "%s_таймаут_менеджер.png" % роль))
            except Exception:
                pass
        if аргумент("замер"):
            печать("  %s: менеджер завершился через %.1f с после запуска" % (роль, time.time() - н))
    finally:
        погасить(менеджер)
        погасить(клиент)
        сторож.пиды.clear()
    сек = time.time() - н
    итог = None
    if os.path.exists(итог_файл):
        try:
            итог = json.load(open(итог_файл, encoding="utf-8-sig"))
        except ValueError as е:
            печать("  итог нечитаем: %s" % е)
    return итог, сек, снимки


