def зонд_сценарий(ссылки):
    шаги = [dict(д="зонд", метка="старт")]
    for ссылка in ссылки.split(";"):
        шаги += [dict(д="открыть", ссылка=ссылка), dict(д="ждать", сек=2), dict(д="зонд", метка=ссылка),
                 dict(д="закрыть")]
    return [dict(имя="зонд", шаги=шаги)]


def прогнать_роль_целиком(роль, сценарии, переменные, сторож):
    """Все сценарии роли; после провала исполнитель останавливается (изменённую форму не закрыть без модального
    вопроса) — остальные сценарии идут в новом клиенте. → (шаги, секунд, запусков)."""
    шаги, сек_всего, запуск = [], 0.0, 0
    остаток = list(сценарии)
    while остаток:
        запуск += 1
        итог, сек, _ = прогнать_роль(роль, данные.имя_пользователя(роль), остаток, переменные, сторож, запуск)
        сек_всего += сек
        новые = (итог or {}).get("шаги", [])
        шаги += новые
        if (итог or {}).get("зонд"):
            with open(os.path.join(ИТОГИ, "зонд_%s.txt" % роль), "a", encoding="utf-8") as ф:
                for з in итог["зонд"]:
                    ф.write("ЗОНД %s\n%s\n" % (з["метка"], "\n".join(з["строки"])))
        начатые = {ш["сценарий"] for ш in новые if ш["сценарий"]}
        if итог is None or not итог.get("готово"):
            # менеджер не дописал итог (таймаут, падение): начатый последним сценарий — провал, дальше — заново
            последний = новые[-1]["сценарий"] if новые else (остаток[0]["имя"] if остаток else "")
            шаги.append(dict(сценарий=последний or "(роль)", номер=0, д="итог", что="исполнитель не завершился",
                             итог="провал", подробности="нет итога: таймаут роли или падение менеджера", сек=сек,
                             снимок=""))
            начатые.add(последний)
        if any(ш["итог"] == "провал" and not ш["сценарий"] for ш in новые):
            break      # нет связи с клиентом — повтор не поможет
        прежний = len(остаток)
        остаток = [с for с in остаток if с["имя"] not in начатые]
        if len(остаток) == прежний:
            break
    return шаги, сек_всего, запуск


def самопроверка(шаги):
    """Каждый шаг «ложный» обязан покраснеть, остальные — позеленеть. → (строки отчёта, ок)."""
    отчет, ок = [], True
    for ш in шаги:
        if not ш["сценарий"]:
            continue
        ложный = "ЛОЖНЫЙ" in (ш["что"] or "")
        if ложный and ш["итог"] != "провал":
            ок = False
            отчет.append("НЕ ПОЙМАН ложный шаг: %s / %s" % (ш["сценарий"], ш["что"]))
        elif not ложный and ш["итог"] == "провал":
            ок = False
            отчет.append("красный НЕ ложный шаг: %s / %s — %s" % (ш["сценарий"], ш["что"], ш["подробности"][:200]))
    всего = sum(1 for ш in шаги if "ЛОЖНЫЙ" in (ш["что"] or ""))
    поймано = sum(1 for ш in шаги if "ЛОЖНЫЙ" in (ш["что"] or "") and ш["итог"] == "провал")
    отчет.insert(0, "самопроверка: ложных шагов поймано %d из %d" % (поймано, всего))
    return отчет, ок and всего > 0 and поймано == всего


# Окно полуночи. Сценарии проводят сегодняшний урок помощника в {время} (0:01 — данные.переменные) и ищут его
# по «сегодня»: в 00:00 он ещё не начался («раньше начала провести нельзя»), а прогон, начатый в 23:59, кончается
# уже завтра — «сегодня» подготовки и клиента расходятся. Клиент роли — отдельный процесс 1С в поясе базы: закрепить
# ему время, как COM-тестам (сеанс.закрепить_время), нельзя (часовой пояс базы меняется только монопольно).
# Поэтому в окне прогон ждёт (до 12 мин): с ОКНО_ПОЛУНОЧИ[0] — до 00:02 следующего дня, до ОКНО_ПОЛУНОЧИ[1] — до неё.
ОКНО_ПОЛУНОЧИ = (datetime.time(23, 50), datetime.time(0, 2))


def дождаться_дня(пиши, часы=datetime.datetime.now):
    сейчас = часы()
    if ОКНО_ПОЛУНОЧИ[1] <= сейчас.time() < ОКНО_ПОЛУНОЧИ[0]:
        return 0.0
    день = сейчас.date() + datetime.timedelta(days=1 if сейчас.time() >= ОКНО_ПОЛУНОЧИ[0] else 0)
    срок = datetime.datetime.combine(день, ОКНО_ПОЛУНОЧИ[1])
    ждать = (срок - сейчас).total_seconds()
    пиши("окно полуночи (%s): жду до %s, %.0f с — сценарии проводят урок «сегодня в 0:01»"
         % (сейчас.strftime("%H:%M:%S"), срок.strftime("%d.%m %H:%M"), ждать))
    time.sleep(max(0.0, ждать))
    return ждать


