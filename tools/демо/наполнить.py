    # ── уроки ──
    def уроки(self):
        c = self.c
        абонементы = {}      # (ученик, группа) → [ссылка, осталось занятий, номер, срок]
        разовых = {}         # ученик → неоплаченных разовых занятий
        self.приостановка = None
        занятия = self.занятия()
        лог("занятий по расписанию: %d (%s — %s)" % (len(занятия), НАЧАЛО, КОНЕЦ_ПЛАНА))
        сделано = 0
        for момент, группа in занятия:
            имя_г, педагог, помещение, тариф_г, часов, _ = ГРУППЫ[группа]
            предмет = предмет_группы(группа)
            прошёл = момент < ТЕПЕРЬ
            ключ = "%s/%s" % (группа, момент.strftime("%Y%m%d%H%M"))
            д, новый = self.документ("УЗ_Урок", ключ)
            # свой генератор на урок: повторный запуск повторяет те же явки, не завися от уже созданного
            сл = random.Random(ключ)
            состав = [у for у, данные in УЧЕНИКИ.items() if группа in данные[3]]
            строки = []
            for у in состав:
                фио, _, _, _, тариф_у = УЧЕНИКИ[у]
                тариф_строки = тариф_у if группа != "ансамбль" or тариф_у == "разовое" else "абонемент4"
                явка = сл.random() < 0.9
                к_оплате = True
                заметка = ""
                абонемент = None
                if прошёл:
                    if тариф_строки.startswith("абонемент"):
                        а = абонементы.get((у, группа))
                        приостановлен = (у == ПРИОСТАНОВКА and self.приостановка
                                         and self.приостановка[0] <= момент.date() < self.приостановка[1])
                        if приостановлен:
                            явка, к_оплате, заметка = False, False, "Абонемент приостановлен: болезнь"
                        else:
                            if а is None or а[1] <= 0 or момент.date() > а[3]:
                                номер = (а[2] + 1) if а else 1
                                оплачен = not (у in ДОЛЖНИКИ and номер >= 2)
                                ссылка = self.абонемент(у, группа, предмет, тариф_строки, момент, номер, оплачен)
                                а = [ссылка, ТАРИФЫ[тариф_строки][2], номер,
                                     момент.date() + datetime.timedelta(days=35)]
                                абонементы[(у, группа)] = а
                            а[1] -= 1
                            абонемент = а[0]
                    else:
                        if not явка and сл.random() < 0.6:
                            к_оплате, заметка = False, "Предупредил заранее"
                        if к_оплате:
                            разовых[у] = разовых.get(у, 0) + 1
                            # платят за 4 занятия вперёд; должник перестаёт платить в этом месяце
                            if разовых[у] == 1 and not (у in ДОЛЖНИКИ and момент.date() >= СЕГОДНЯ.replace(day=1)):
                                скидка = 0.9 if у in СЕМЕЙНАЯ_СКИДКА else 1
                                self.приход(у, "разовые/%s/%s" % (у, момент.strftime("%Y%m%d%H%M")),
                                            момент - datetime.timedelta(minutes=10),
                                            int(ТАРИФЫ["разовое"][1] * 4 * скидка), предмет, "разовое", None,
                                            "Оплата 4 занятий")
                            if разовых[у] == 4:
                                разовых[у] = 0
                else:
                    явка = False
                строки.append(dict(Ученик=self.ученики[у], Тариф=self.тарифы[тариф_строки], Явка=явка,
                                   СписатьОплату=к_оплате, Заметка=заметка,
                                   **({"Абонемент": абонемент} if абонемент is not None else {}),
                                   **({"Скидка": self.скидка} if у in СЕМЕЙНАЯ_СКИДКА else {})))
            if not новый:
                if прошёл and not д.Проведен:
                    self.записать(д, "Урок", True)
                continue
            д.Дата = дата(момент.year, момент.month, момент.day, момент.hour, момент.minute)
            д.Организация = self.организация
            д.Педагог = self.педагоги[педагог]
            д.СтавкаПедагога = self.ставки[педагог]
            д.ГруппаОбучения = self.группы[группа]
            д.ПредметОбучения = self.предметы[предмет]
            д.Помещение = self.помещения[помещение]
            д.Тариф = self.тарифы[тариф_г]
            д.КоличествоЧасов = часов
            if прошёл:
                д.ТемаУрока = сл.choice(ТЕМЫ[предмет])
                д.ДомашнееЗадание = сл.choice(ЗАДАНИЯ)
            for поля in строки:
                с = д.Ученики.Добавить()
                for к, в in поля.items():
                    setattr(с, к, в)
            self.записать(д, "Урок", прошёл)
            сделано += 1
            if сделано % 20 == 0:
                лог("  уроков создано: %d" % сделано)

