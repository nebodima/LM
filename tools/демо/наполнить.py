    @staticmethod
    def время_окончания(начало, часов):
        минут = начало[0] * 60 + начало[1] + int(round(часов * 60))
        return дата(100, 1, 1, минут // 60, минут % 60)

    # ── расписание ──
    def занятия(self):
        """Все занятия периода по расписанию групп: (дата-время, ключ группы), по порядку."""
        итог = []
        д = НАЧАЛО
        while д < КОНЕЦ_ПЛАНА:
            день = ДНИ[д.weekday()]
            for ключ, (_, _, _, _, _, дни) in ГРУППЫ.items():
                if день in дни:
                    ч, м = дни[день]
                    итог.append((datetime.datetime(д.year, д.month, д.day, ч, м), ключ))
            д += datetime.timedelta(days=1)
        итог.sort()
        return итог

    # ── абонементы и оплаты ──
    def абонемент(self, ученик, группа, предмет, тариф_ключ, начало, номер, оплачен=True):
        """Новый абонемент ученика с даты первого урока + ПКО на его цену за 15 минут до урока."""
        c = self.c
        имя_т, цена, уроков, _ = ТАРИФЫ[тариф_ключ]
        конец = начало.date() + datetime.timedelta(days=35)
        ключ = "%s/%s/%d" % (ученик, группа, номер)
        а = self.элемент(
            "УЗ_Абонемент", ключ, "%s, %d зан. с %s" % (предмет, уроков, начало.strftime("%d.%m.%y")),   # наименование — до 30 символов
            ФизЛицо=self.ученики[ученик], ПредметОбучения=self.предметы[предмет], Тариф=self.тарифы[тариф_ключ],
            ДатаНачала=дата(начало.year, начало.month, начало.day), ДатаАктивации=дата(начало.year, начало.month, начало.day),
            ДатаОкончания=дата(конец.year, конец.month, конец.day), Активный=True, КоличествоЗанятий=уроков,
            ЦенаАбонемента=цена)
        if ученик == ПРИОСТАНОВКА and номер == 2:
            о = а.ПолучитьОбъект()
            с = начало.date() + datetime.timedelta(days=10)
            по = с + datetime.timedelta(days=7)
            if о.Приостановки.Количество() == 0:
                п = о.Приостановки.Добавить()
                п.ДатаПриостановки = дата(с.year, с.month, с.day)
                п.ДатаВозобновления = дата(по.year, по.month, по.day)
                п.ДатаИзменения = дата(с.year, с.month, с.day, 10)
                п.Комментарий = "Болезнь, справка от врача"
                о.Записать()
            self.приостановка = (с, по)
        if оплачен:
            момент = начало - datetime.timedelta(minutes=15)
            self.приход(ученик, "абонемент/" + ключ, момент, цена, предмет, тариф_ключ, а,
                        "Оплата абонемента «%s»" % имя_т)
        return а

