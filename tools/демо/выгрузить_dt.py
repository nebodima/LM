"""Выгрузка демо-базы «Учёт занятий» (студия «Ассоль») в .dt — из копии, с зачисткой секретов.

    python tools\\демо\\выгрузить_dt.py
    python tools\\демо\\выгрузить_dt.py --источник=C:\\1c_bases\\UZ_DEMO --копия=C:\\1c_bases\\UZ_DEMO_DT --пользователь=Администратор

Порядок (образец — «Путевые листы», make_demo_base.py + docs/демо-база.md, адаптировано: у «Учёта занятий» демо не
пустышка, а копия типовой УНФ с расширением):
  1. база владельца (источник) никем не открыта — файл 1Cv8.1CD открывается монопольно; иначе СТОП (владелец в базе,
     веб-стенд 8095 или чужой сеанс) — ничего не копируем;
  2. копируется только 1Cv8.1CD в папку копии (прежняя копия удаляется); источник больше не трогается;
  3. в копии — отдельным процессом через COM — зачистка секретов: настройки почты УЗ_НастройкиПочты (сервер, логин,
     пароль SMTP), журнал рассылки, безопасное хранилище хозяина (пароли учётных записей почты, интернет-сервисов БСП),
     пароли пользователей ИБ (вход без пароля), чужие расширения (ПЛ_ext и др. — в .dt попал бы их код); печатается, сколько чего было; проверка 152-ФЗ — у физлиц продукта
     только вымышленные телефоны «+7 900 000-…» и почта «@example.ru» (иначе ПРЕДУПРЕЖДЕНИЕ со списком);
  4. пакетный конфигуратор /DumpIB копии; файл больше 50 МБ в git не кладётся — выгрузка идёт в
     C:\\1c_bases\\выпуск\\, в releases\\демо\\ остаётся только README.md;
  5. проверка: .dt есть и не пуст, журнал конфигуратора без ошибок. Время каждого шага печатается.

Внимание: в .dt — конфигурация УНФ фирмы «1С». Покупателям и в открытый доступ её не отдавать
(docs/юридические-правила.md, docs/демо-база.md).
"""
import os
import shutil
import subprocess
import sys
import time

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "тесты"))
from сеанс import аргумент, настроить_вывод, подключить, текст_ошибки  # noqa: E402
import платформа  # noqa: E402

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
EXE = платформа.exe()
ИМЯ_DT = "УчетЗанятий_2.0_демо.dt"
ПРЕДЕЛ_GIT = 50 * 1024 * 1024
ВЫПУСК = r"C:\1c_bases\выпуск"


def шаг(имя, начало):
    print("  %6.1f с  %s" % (time.time() - начало, имя), flush=True)


def база_свободна(путь):
    """1Cv8.1CD открывается монопольно — значит, её не держит ни клиент, ни веб-стенд, ни COM."""
    import win32file
    try:
        h = win32file.CreateFile(путь, win32file.GENERIC_READ, 0, None, win32file.OPEN_EXISTING, 0, None)
    except Exception as е:
        return False, str(е)
    h.Close()
    return True, ""


def зачистить(копия, пользователь):
    """Отдельный процесс: COM-сеанс копии держит базу до выхода процесса, а /DumpIB нужна свободная база."""
    c, сек = подключить(копия, пользователь, закрепить=False)
    print("  подключение к копии %.1f с" % сек)

    def очистить_регистр(имя):
        if c.Метаданные.РегистрыСведений.Найти(имя) is None:
            print("  %-34s нет в конфигурации" % имя)
            return
        менеджер = getattr(c.РегистрыСведений, имя)
        было = менеджер.Выбрать()
        записей = 0
        while было.Следующий():
            записей += 1
        набор = менеджер.СоздатьНаборЗаписей()
        набор.ОбменДанными.Загрузка = True
        try:
            набор.Записать(True)
            print("  %-34s записей было %d — очищен" % (имя, записей))
        except Exception as е:
            print("  %-34s записей было %d — НЕ очищен: %s" % (имя, записей, текст_ошибки(е)))
            raise

    очистить_регистр("УЗ_НастройкиПочты")
    очистить_регистр("УЗ_ЖурналРассылки")
    try:
        c.УстановитьПривилегированныйРежим(True)
    except Exception:
        pass   # во внешнем соединении администратору и так доступно всё
    очистить_регистр("БезопасноеХранилищеДанных")
    if c.Метаданные.Справочники.Найти("УчетныеЗаписиЭлектроннойПочты") is not None:
        з = c.NewObject("Запрос")
        з.Текст = "ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК К ИЗ Справочник.УчетныеЗаписиЭлектроннойПочты КАК У ГДЕ НЕ У.ПометкаУдаления"
        в = з.Выполнить().Выбрать()
        в.Следующий()
        print("  учётных записей почты хозяина       %d (пароли — в безопасном хранилище, очищено)" % int(в.К))

    сброшено = []
    for п in c.ПользователиИнформационнойБазы.ПолучитьПользователей():
        if п.ПарольУстановлен:
            п.Пароль = ""
            п.Записать()
            сброшено.append(п.Имя)
    print("  пользователей ИБ %d, пароль снят у: %s" % (
        c.ПользователиИнформационнойБазы.ПолучитьПользователей().Количество(), ", ".join(сброшено) or "ни у кого"))

    з = c.NewObject("Запрос")
    з.Текст = ("ВЫБРАТЬ Ф.Наименование КАК Имя, Ф.Телефон КАК Телефон, Ф.EMail КАК Почта ИЗ Справочник.УЗ_ФизЛица КАК Ф "
               "ГДЕ НЕ Ф.ЭтоГруппа И (Ф.Телефон <> \"\" И НЕ Ф.Телефон ПОДОБНО \"+7 900 000-%\" "
               "ИЛИ Ф.EMail <> \"\" И НЕ Ф.EMail ПОДОБНО \"%@example.ru\")")
    тз = з.Выполнить().Выгрузить()
    if тз.Количество():
        print("  ПРЕДУПРЕЖДЕНИЕ 152-ФЗ: физлиц с настоящими на вид контактами %d:" % тз.Количество())
        for н in range(min(тз.Количество(), 10)):
            с = тз.Получить(н)
            print("    %s | %s | %s" % (с.Имя, с.Телефон, с.Почта))
    else:
        print("  контакты физлиц продукта — только вымышленные (+7 900 000-…, @example.ru)")

    # последним: после удаления расширения таблицы этого сеанса «несовместимы с текущими расширениями»
    чужие = []
    for р in c.РасширенияКонфигурации.Получить():
        if р.Имя != "УЗ_ext":
            чужие.append(р.Имя)
            р.Удалить()
    print("  расширения кроме УЗ_ext удалены: %s" % (", ".join(чужие) or "их не было"))


def главный():
    настроить_вывод()
    источник = аргумент("источник", r"C:\1c_bases\UZ_DEMO")
    копия = аргумент("копия", r"C:\1c_bases\UZ_DEMO_DT")
    пользователь = аргумент("пользователь", "Администратор")
    if "--зачистить" in sys.argv:
        зачистить(копия, пользователь)
        return 0
    выход = аргумент("выход", os.path.join(КОРЕНЬ, "releases", "демо", ИМЯ_DT))
    н = time.time()
    print("Демо-база: %s → копия %s → %s" % (источник, копия, выход))

    файл = os.path.join(источник, "1Cv8.1CD")
    свободна, почему = база_свободна(файл)
    if not свободна:
        print("СТОП: база %s открыта (владелец, веб-стенд или сеанс) — не копирую. %s" % (источник, почему))
        return 1
    шаг("источник свободен", н)
    if os.path.isdir(копия):
        shutil.rmtree(копия)
    os.makedirs(копия)
    shutil.copy2(файл, os.path.join(копия, "1Cv8.1CD"))
    шаг("скопирован 1Cv8.1CD (%.0f МБ)" % (os.path.getsize(файл) / 1048576), н)

    код = subprocess.call([sys.executable, os.path.abspath(__file__), "--зачистить", "--копия=" + копия,
                           "--пользователь=" + пользователь], timeout=180)
    if код:
        print("СТОП: зачистка копии не прошла (код %d) — .dt не выгружаю" % код)
        return 1
    шаг("секреты зачищены", н)

    os.makedirs(os.path.dirname(выход), exist_ok=True)
    журнал = os.path.join(копия, "dumpib.log")
    код = subprocess.call([EXE, "DESIGNER", "/F", копия, "/N", пользователь, "/DumpIB", выход,
                           "/DisableStartupDialogs", "/DisableStartupMessages", "/Out", журнал], timeout=900)
    текст = open(журнал, encoding="utf-8-sig", errors="replace").read().strip() if os.path.isfile(журнал) else ""
    шаг("/DumpIB код %d, журнал: %s" % (код, текст or "пуст"), н)
    if код or not os.path.isfile(выход) or os.path.getsize(выход) == 0:
        print("ОШИБКА: .dt не создан")
        return 1

    размер = os.path.getsize(выход)
    if размер > ПРЕДЕЛ_GIT and os.path.commonpath([os.path.abspath(выход), КОРЕНЬ]) == КОРЕНЬ:
        os.makedirs(ВЫПУСК, exist_ok=True)
        куда = os.path.join(ВЫПУСК, os.path.basename(выход))
        shutil.move(выход, куда)
        выход = куда
        шаг("больше 50 МБ — перенесён в %s (в git не кладём)" % ВЫПУСК, н)
    print("ГОТОВО: %s, %.1f МБ, всего %.1f с" % (выход, размер / 1048576, time.time() - н))
    return 0


if __name__ == "__main__":
    sys.exit(главный())
