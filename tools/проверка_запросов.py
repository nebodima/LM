"""Проверка текстов запросов УЗ_ext на живых базах: платформа разбирает текст по метаданным
базы (Запрос.НайтиПараметры), но не выполняет его. Текст запроса — строка, поэтому ни сборка,
ни /CheckModules «Поле не найдено» и «КАК В» не ловят.

Источники текстов: строковые литералы модулей (ВЫБРАТЬ … ИЗ), <QueryText> динамических списков
форм, <query> наборов данных схем компоновки.

Самотест обязателен: три заведомо неверных запроса (неизвестное поле, «КАК В», неизвестная
таблица) должны дать три ошибки, иначе проверке не доверять.

Шаблоны (текст с %1, собирается СтрШаблон) раньше молча пропускались (повторный аудит 28.09.2026, T05). Теперь
каждый шаблон обязан быть в ШАБЛОНЫ: либо варианты подстановки (текст проверяется на каждом), либо причина,
какая другая проверка его покрывает. Шаблон без записи — ошибка проверки, а не пропуск. Самотест шаблонов:
вариант с неизвестным полем обязан дать ошибку.

    python tools\\проверка_запросов.py               — все три базы
    python tools\\проверка_запросов.py УНФ БП         — выбранные
Бюджет: 10 с на базу (один COM-сеанс на базу).
"""
import html
import os
import re
import sys
import time

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "аудиты"))
import общее  # noqa: E402

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ИСХОДНИКИ = os.path.join(КОРЕНЬ, "src_ext")  # корень берётся от расположения скрипта — в рабочей копии git своя src_ext
БАЗЫ = {
    "УНФ": r'File="C:\1c_bases\UZ_UNF";Usr="Администратор";',
    "БП": r'File="C:\1c_bases\UZ_BP";Usr="1";',
    "УТ": r'File="C:\1c_bases\UZ_UT";Usr="Admin";',
}
БЮДЖЕТ_НА_БАЗУ = 10
САМОТЕСТ = [
    ("неизвестное поле", "ВЫБРАТЬ Т.НетТакогоПоля КАК П ИЗ Справочник.УЗ_Кассы КАК Т"),
    ("псевдоним КАК В", "ВЫБРАТЬ Т.Ссылка КАК В ИЗ Справочник.УЗ_Кассы КАК Т"),
    ("неизвестная таблица", "ВЫБРАТЬ Т.Ссылка КАК Ссылка ИЗ Справочник.УЗ_НетТакого КАК Т"),
]


def документы_уз():
    """Полные имена своих документов (Документ.УЗ_…) по исходникам."""
    папка = os.path.join(ИСХОДНИКИ, "Documents")
    return ["Документ." + ф[:-4] for ф in sorted(os.listdir(папка)) if ф.endswith(".xml") and ф.startswith("УЗ_")]


# шаблон: (файл относительно src_ext, строка-примета из текста шаблона) → варианты подстановки [(%1, %2, …)]
# или строка — чем покрыт шаблон, если подставить нечего
ШАБЛОНЫ = {
    # прежняя дата документа для дат запрета: %1 — любой свой документ (подписки УЗ_ДатаЗапрета*)
    ("CommonModules/УЗ_ДатыЗапрета/Ext/Module.bsl", "Т.Дата КАК Дата"): lambda: [(д,) for д in документы_уз()],
    # «Движения документа»: виден ли документ пользователю (ограничение доступа роли) — %1 любой свой документ
    ("Reports/УЗ_ДвиженияДокумента/Forms/ДвиженияДокумента/Ext/Form/Module.bsl", "ИСТИНА КАК Виден"):
        lambda: [(д,) for д in документы_уз()],
    ("CommonModules/УЗ_Общий/Ext/Module.bsl", "Таблица.%1 КАК Значение"):
        "ЗначениеРеквизита(ссылка хозяина, «Реквизит»): поля Организаций/Пользователей в вызовах сверяет аудит "
        "сверка_хозяев с выгрузками УНФ, БП, УТ",
}
САМОТЕСТ_ШАБЛОНА = ("ВЫБРАТЬ Т.НетТакогоПоля КАК Дата ИЗ %1 КАК Т ГДЕ Т.Ссылка = &Ссылка", [("Документ.УЗ_Урок",)])


def подставить(шаблон, значения):
    текст = шаблон
    for номер in range(len(значения), 0, -1):          # %10 раньше %1
        текст = текст.replace("%" + str(номер), значения[номер - 1])
    return текст


def варианты_шаблона(отн, текст):
    """[(метка, текст или None — шаблон без записи в ШАБЛОНЫ)] для шаблона %1."""
    for (файл, примета), варианты in ШАБЛОНЫ.items():
        if отн.replace("\\", "/") == файл and примета in текст:
            if isinstance(варианты, str):
                return []
            return [(" ".join(в), подставить(текст, в)) for в in варианты()]
    return [("шаблон без вариантов", None)]


def тексты_запросов():
    """[(место, текст)] — все тексты запросов в src_ext; у шаблона %1 — по тексту на вариант подстановки,
    у шаблона без записи в ШАБЛОНЫ — текст None (проверка сочтёт его ошибкой)."""
    итог = []
    for папка, _, файлы in os.walk(ИСХОДНИКИ):
        for ф in файлы:
            путь = os.path.join(папка, ф)
            отн = os.path.relpath(путь, ИСХОДНИКИ)
            if ф.endswith(".bsl"):
                м = общее.Модуль(путь, общее.читать(путь))
                for номер, содержимое, _ in м.литералы:
                    if not (общее.это_запрос(содержимое) and re.match(r"(?is)\s*(\|\s*)?(ВЫБРАТЬ|SELECT)\b", содержимое)):
                        continue
                    текст = общее.очистить_запрос(содержимое)
                    if "%1" in содержимое:
                        for метка, вариант in варианты_шаблона(отн, текст):
                            итог.append(("%s:%d [%s]" % (отн, номер, метка), вариант))
                        continue
                    итог.append(("%s:%d" % (отн, номер), текст))
            elif ф in ("Form.xml", "Template.xml"):
                т = общее.читать(путь)
                for мт in re.finditer(r"<(QueryText|query)>(.*?)</\1>", т, re.S):
                    текст = html.unescape(мт.group(2))
                    if общее.это_запрос(текст):
                        строка = т[:мт.start()].count("\n") + 1
                        итог.append(("%s:%d" % (отн, строка), текст))
    return итог


def ошибка_запроса(соединение, текст):
    try:
        запрос = соединение.NewObject("Запрос")
        запрос.Текст = текст
        запрос.НайтиПараметры()
        return None
    except Exception as исключение:  # текст ошибки платформы — в последнем аргументе COM-исключения
        аргументы = getattr(исключение, "excepinfo", None) or исключение.args
        сообщение = str(аргументы[2] if isinstance(аргументы, tuple) and len(аргументы) > 2 else исключение)
        return " ".join(сообщение.split())[:300]


def проверить_соединение(соединение, тексты):
    """Самотест + все тексты в готовом сеансе (его зовёт и общий прогон tools\\прогон.py).
    → (поймано из САМОТЕСТ, [(место, ошибка)])."""
    поймано = sum(1 for _, т in САМОТЕСТ if ошибка_запроса(соединение, т))
    шаблон, варианты = САМОТЕСТ_ШАБЛОНА
    if not all(ошибка_запроса(соединение, подставить(шаблон, в)) for в in варианты):
        поймано -= 1                     # подстановка шаблона сломана — самотест не пройден
    ошибки = []
    for место, текст in тексты:
        if текст is None:
            ошибки.append((место, "шаблон запроса (%1) не описан в ШАБЛОНЫ tools/проверка_запросов.py — текст не "
                                  "проверен: добавьте варианты подстановки или причину"))
            continue
        о = ошибка_запроса(соединение, текст)
        if о:
            ошибки.append((место, о))
    return поймано, ошибки


def проверить_базу(имя, тексты):
    import win32com.client
    начало = time.time()
    соединение = win32com.client.Dispatch("V83.COMConnector").Connect(БАЗЫ[имя])
    подключение = time.time() - начало
    поймано, ошибки = проверить_соединение(соединение, тексты)
    всего = time.time() - начало
    return поймано, ошибки, подключение, всего


def main():
    общее.настроить_вывод()
    for арг in sys.argv[1:]:
        if арг.startswith("--база="):          # своя копия: --база=C:\1c_bases\UZ_UNF_A (вход Администратор)
            БАЗЫ["СВОЯ"] = 'File="%s";Usr="Администратор";' % арг.split("=", 1)[1]
    базы = ["СВОЯ"] if "СВОЯ" in БАЗЫ else ([б for б in sys.argv[1:] if б in БАЗЫ] or list(БАЗЫ))
    тексты = тексты_запросов()
    print("Текстов запросов в src_ext: %d" % len(тексты))
    плохо = 0
    for имя in базы:
        поймано, ошибки, подключение, всего = проверить_базу(имя, тексты)
        метка = "  ПРЕДУПРЕЖДЕНИЕ: бюджет %d с превышен" % БЮДЖЕТ_НА_БАЗУ if всего > БЮДЖЕТ_НА_БАЗУ else ""
        print("== %s: самотест %d из %d, ошибок %d, время %.1f с (подключение %.1f с)%s"
              % (имя, поймано, len(САМОТЕСТ), len(ошибки), всего, подключение, метка))
        if поймано != len(САМОТЕСТ):
            print("  САМОТЕСТ НЕ ПРОЙДЕН — проверке не доверять")
            плохо += 1
        for место, о in ошибки:
            print("  %s: %s" % (место, о))
        плохо += len(ошибки)
    print("ИТОГО ошибок: %d" % плохо)
    return 1 if плохо else 0


if __name__ == "__main__":
    sys.exit(main())
