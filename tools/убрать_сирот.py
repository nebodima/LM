"""Сироты — движения своих регистров УЗ_ с несуществующим регистратором: отчёт и, по ключу, уборка.

Сироты в отчётах — «<Объект не найден>», в остатках — чужие суммы. Появлялись от тестов: тест_права удалял
ПКО и уроки сотрудника в режиме ОбменДанными.Загрузка, а в этом режиме платформа движения документа НЕ удаляет
(опыт 28.09.2026 на UZ_UNF_D: «движений до 1, после удаления 1»; без Загрузки — 0). Причина исправлена в
сеанс.удалить_объект, прогон после каждого теста проверяет, что сирот не прибавилось. Этот скрипт — чтобы
убрать то, что уже накопилось в базах.

Трогает ТОЛЬКО записи регистров накопления и подчинённых регистратору регистров сведений с префиксом УЗ_,
у которых регистратора нет в базе. Живые документы, их движения и регистры хозяина не трогает.

    python tools\\убрать_сирот.py --база=C:\\1c_bases\\UZ_UNF_D                          — проверка (по умолчанию)
    python tools\\убрать_сирот.py --база=C:\\1c_bases\\UZ_UNF_D --исправить              — снять движения сирот
    python tools\\убрать_сирот.py --база=C:\\1c_bases\\UZ_UT_D --пользователь=Admin --проверка

Отчёт: по каждому регистру — сколько регистраторов-сирот и записей, первые регистраторы (вид документа и
начало идентификатора — у удалённого объекта представления нет). --исправить записывает пустой набор с отбором
по мёртвому регистратору (в режиме загрузки — мимо дат запрета), затем считает заново.
Код выхода: --проверка — 1, если сироты есть; --исправить — 1, если после уборки хоть одна осталась.
"""
import os
import sys
import time

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "тесты"))
import сеанс  # noqa: E402


def сироты_регистра(c, регистр):
    """[(регистратор, «Документ.X 1a2b3c4d», записей)] по регистру."""
    з = c.NewObject("Запрос")
    з.Текст = ("ВЫБРАТЬ Р.Регистратор КАК Регистратор, КОЛИЧЕСТВО(*) КАК Записей ИЗ %s КАК Р "
               "ГДЕ Р.Регистратор.Ссылка ЕСТЬ NULL СГРУППИРОВАТЬ ПО Р.Регистратор" % регистр)
    т = з.Выполнить().Выгрузить()
    итог = []
    for н in range(т.Количество()):
        с = т.Получить(н)
        мд = с.Регистратор.Метаданные()
        итог.append((с.Регистратор, "%s %s" % (мд.ПолноеИмя() if мд is not None else "?",
                                                 c.String(с.Регистратор.УникальныйИдентификатор())[:8]),
                     int(с.Записей)))
    return итог


def отчет(c):
    всего = 0
    по_регистрам = {}
    for регистр in сеанс._регистры_с_регистратором(c):
        список = сироты_регистра(c, регистр)
        по_регистрам[регистр] = список
        if список:
            всего += len(список)
            print("  %-45s регистраторов-сирот %3d, записей %4d; например %s"
                  % (регистр, len(список), sum(з for _, _, з in список), "; ".join(к for _, к, _ in список[:3])))
    return всего, по_регистрам


def main():
    сеанс.настроить_вывод()
    база = сеанс.аргумент("база")
    if not база:
        sys.exit("укажите --база=C:\\1c_bases\\UZ_UNF_D (и --пользователь=, если не Администратор)")
    исправить = "--исправить" in sys.argv
    c, сек = сеанс.подключить(база, сеанс.аргумент("пользователь", сеанс.ПОЛЬЗОВАТЕЛЬ_ПО_УМОЛЧАНИЮ))
    print("база %s, подключение %.1f с, режим %s" % (база, сек, "исправить" if исправить else "проверка"))
    н = time.time()
    всего, по_регистрам = отчет(c)
    print("регистраторов-сирот всего: %d (%.2f с)" % (всего, time.time() - н))
    if not исправить:
        return 1 if всего else 0
    if not всего:
        return 0
    н = time.time()
    for регистр, список in по_регистрам.items():
        вид, имя = регистр.split(".", 1)
        менеджер = getattr(c.РегистрыНакопления if вид == "РегистрНакопления" else c.РегистрыСведений, имя)
        for регистратор, _, _ in список:
            набор = менеджер.СоздатьНаборЗаписей()
            набор.Отбор.Регистратор.Установить(регистратор)
            набор.ОбменДанными.Загрузка = True
            набор.Записать()
    print("снято за %.2f с; пересчёт:" % (time.time() - н))
    осталось, _ = отчет(c)
    print("регистраторов-сирот осталось: %d" % осталось)
    return 1 if осталось else 0


if __name__ == "__main__":
    sys.exit(main())
