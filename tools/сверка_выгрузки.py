"""Дошла ли загрузка до конфигурации: выгрузка расширения из конфигуратора обратно (агент: config dump-files
--update) сравнивается с исходниками src_ext.

Зачем (28.09.2026): агент конфигуратора и пакетный /LoadConfigFromFiles на части ошибок XML отвечают «успешно» и
молча выбрасывают загружаемое — несуществующая картинка у команды становится <xr:Ref>0</xr:Ref> (проверено на
UZ_BP_C: CommonPicture.УЗ_НетТакойКартинки), лишнее свойство у реквизита ТЧ отбрасывается; /CheckModules после
этого проверяет не то, а отметка деплоя пишет новый отпечаток. Ни код возврата, ни журнал этого не показывают —
показывает только сравнение с тем, что оказалось в конфигураторе.

Как сравнивается (формат выгрузки конфигуратора не совпадает с src_ext: с 30.09.2026 src_ext сам — выгрузка платформы 2.20, но новые правки пишутся руками: умолчания
false опускаются, права с false не выгружаются, InternalInfo добавляется, порядок другой):
  * модули .bsl — текстом (без BOM, CRLF = LF, без хвостовых пустых строк); пустой модуль (только BOM) конфигуратор
    не выгружает — это не расхождение;
  * XML — ВЛОЖЕНИЕМ ЗНАЧЕНИЙ: каждое непустое значение исходника (тег без пространства имён + текст) есть в выгрузке
    не меньше раз. Выброшенная ссылка или отброшенное свойство — значение исходника, которого в выгрузке нет;
  * справка .html — без пробельных символов; прочее (картинки) — байтами; файлы, которых нет с одной из сторон, —
    расхождение.
Общий формат (права false, идентификаторы настроек списков) учтён в коде. Остальное известное — ЛИНИЯ в репозитории,
tools\\сверка_выгрузки_линия.json: свойства, которые конфигуратор молча отбрасывает у ТЕКУЩИХ исходников (например
<Client>false</Client> у общих модулей — такого свойства в формате 8.3 нет; <Width> колонок УЗ_Урок). Она общая для
всех баз (зависит от src_ext и платформы, не от базы) и сама не меняется: красное — только НОВОЕ относительно неё,
в том числе такое же отбрасываемое свойство в новом объекте. Перезаписать — осознанно, с просмотром git diff.

    python tools\\сверка_выгрузки.py <выгрузка> [--исходники=src_ext]          — сверка с линией, код 1 при новом
    python tools\\сверка_выгрузки.py <выгрузка> --без-линии                    — все расхождения (и известные)
    python tools\\сверка_выгрузки.py <выгрузка> --записать-линию               — линия := всё текущее
Берут: tools\\итерация.py (после применения, параллельно тестам) и tools\\деплой.ps1 (после загрузки, ДО /CheckModules
и применения). Выгрузка — %TEMP%\\uz_agent\\<папка базы>\\dump (агент: config dump-files --update).
"""
import json
import os
import re
import sys
import time
import xml.etree.ElementTree as ET
from collections import Counter

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ЛИНИЯ = os.path.join(os.path.dirname(os.path.abspath(__file__)), "сверка_выгрузки_линия.json")


# Формат конфигуратора, общий для всех объектов (проверено на выгрузке УЗ_ext 28.09.2026), — не расхождение:
#  * права со значением false в Rights.xml не выгружаются (и объект без единого права true — тоже);
#  * идентификаторы пользовательских настроек списков (userSettingID, itemsUserSettingID) конфигуратор не хранит.
НЕ_ХРАНИТ = {"userSettingID", "itemsUserSettingID"}


def _имя(тег):
    return тег.split("}")[-1]


def _без_ложных_прав(корень):
    for объект in list(корень):
        if _имя(объект.tag) != "object":
            continue
        for право in list(объект):
            if _имя(право.tag) == "right" and any(_имя(з.tag) == "value" and (з.text or "").strip() == "false"
                                                 for з in право):
                объект.remove(право)
        if not any(_имя(п.tag) == "right" for п in объект):
            корень.remove(объект)


def _значения(данные, права=False):
    корень = ET.fromstring(данные)
    if права:
        _без_ложных_прав(корень)
    итог = Counter()
    for э in корень.iter():
        текст = (э.text or "").strip()
        if текст and _имя(э.tag) not in НЕ_ХРАНИТ:
            итог["<%s>%s" % (_имя(э.tag), текст)] += 1
    return итог


def расхождения_файла(исходник, выгрузка):
    """[ключи расхождений] файла; пусто — совпадает по смыслу."""
    with open(исходник, "rb") as ф:
        а = ф.read()
    with open(выгрузка, "rb") as ф:
        б = ф.read()
    if а == б:
        return []
    имя = исходник.lower()
    if имя.endswith(".bsl"):
        т = [д.decode("utf-8-sig", "replace").replace("\r\n", "\n").rstrip() for д in (а, б)]
        if т[0] == т[1]:
            return []
        for номер, (с1, с2) in enumerate(zip(*(x.split("\n") for x in т)), 1):
            if с1 != с2:
                return ["текст модуля: строка %d «%s» в исходниках, «%s» в конфигураторе" % (номер, с1.strip()[:70],
                                                                                              с2.strip()[:70])]
        return ["текст модуля: строк %d в исходниках, %d в конфигураторе" % (т[0].count("\n") + 1, т[1].count("\n") + 1)]
    if имя.endswith(".xml"):
        try:
            права = os.path.basename(исходник).lower() == "rights.xml"
            нет = _значения(а, права) - _значения(б, права)
        except ET.ParseError as е:
            return ["XML не разбирается: %s" % е]
        return ["нет значения %s%s" % (к, " ×%d" % ч if ч > 1 else "") for к, ч in sorted(нет.items())]
    if имя.endswith((".html", ".htm", ".txt")) and re.sub(rb"\s", b"", а) == re.sub(rb"\s", b"", б):
        return []
    return ["содержимое отличается (%d и %d байт)" % (len(а), len(б))]


def сверить(выгрузка, исходники):
    """{отн. путь: [ключи расхождений]} по всем файлам."""
    def файлы(папка):
        итог = set()
        for корень, _, имена in os.walk(папка):
            for имя in имена:
                if имя != "ConfigDumpInfo.xml" and not имя.startswith("."):
                    итог.add(os.path.relpath(os.path.join(корень, имя), папка))
        return итог
    в_исходниках, в_выгрузке = файлы(исходники), файлы(выгрузка)
    итог = {}
    for отн in sorted(в_исходниках | в_выгрузке):
        if отн not in в_выгрузке:
            if not (отн.lower().endswith(".bsl") and os.path.getsize(os.path.join(исходники, отн)) <= 3):
                итог[отн] = ["нет в конфигураторе — загрузка не дошла"]
        elif отн not in в_исходниках:
            итог[отн] = ["в конфигураторе есть, в исходниках нет"]
        else:
            р = расхождения_файла(os.path.join(исходники, отн), os.path.join(выгрузка, отн))
            if р:
                итог[отн] = р
    return итог


def сверить_с_линией(выгрузка, исходники, линия=ЛИНИЯ):
    """(новые {отн: [ключи]}, строка для печати). Известное из линии — не расхождение; линия не меняется сама."""
    сейчас = сверить(выгрузка, исходники)
    try:
        было = json.load(open(линия, encoding="utf-8"))
    except (OSError, ValueError):
        было = {}
    новые, известных, устарело = {}, 0, 0
    for п, ключи in сейчас.items():
        знаем = set(было.get(п.replace(os.sep, "/"), []))
        н = [к for к in ключи if к not in знаем]
        известных += len(ключи) - len(н)
        if н:
            новые[п] = н
    for п, ключи in было.items():
        есть = set(сейчас.get(п.replace("/", os.sep), []))
        устарело += sum(1 for к in ключи if к not in есть)
    строка = "известных расхождений формата (линия %s): %d, новых: %d%s" % (
        os.path.basename(линия), известных, sum(len(к) for к in новые.values()),
        "; в линии устарело %d — исправлены в src_ext, линию можно перезаписать (--записать-линию)" % устарело
        if устарело else "")
    return новые, строка


def записать_линию(выгрузка, исходники, линия=ЛИНИЯ):
    сейчас = сверить(выгрузка, исходники)
    with open(линия, "w", encoding="utf-8", newline="\n") as ф:
        json.dump({п.replace(os.sep, "/"): к for п, к in sorted(сейчас.items())}, ф, ensure_ascii=False, indent=1)
    return сейчас


def main():
    for п in (sys.stdout, sys.stderr):
        п.reconfigure(encoding="utf-8")
    арг = {а.split("=", 1)[0]: (а.split("=", 1)[1] if "=" in а else "") for а in sys.argv[1:] if а.startswith("--")}
    пути = [а for а in sys.argv[1:] if not а.startswith("--")]
    if not пути:
        sys.exit(__doc__)
    н = time.time()
    исходники = арг.get("--исходники") or os.path.join(КОРЕНЬ, "src_ext")
    линия = арг.get("--линия") or ЛИНИЯ
    if "--записать-линию" in арг:
        сейчас = записать_линию(пути[0], исходники, линия)
        print("линия записана: %s — %d файлов; проверьте git diff: в линию попадает ВСЁ текущее" % (линия, len(сейчас)))
        return 0
    if "--без-линии" in арг:
        новые = сверить(пути[0], исходники)
    else:
        новые, строка = сверить_с_линией(пути[0], исходники, линия)
        print(строка)
    for отн, ключи in новые.items():
        print("РАСХОЖДЕНИЕ %s: %s" % (отн, "; ".join(ключи[:4]) + (" …и ещё %d" % (len(ключи) - 4) if len(ключи) > 4 else "")))
    print("ИТОГО новых расхождений исходников с конфигуратором: %d (%.2f с)" % (len(новые), time.time() - н))
    return 1 if новые else 0


if __name__ == "__main__":
    sys.exit(main())