# Все COM-тесты и проверка запросов на трёх тестовых базах, с замером времени.
#   .\tools\все_тесты.ps1              — УНФ, БП, УТ
#   .\tools\все_тесты.ps1 -Базы УНФ
# Бюджет одного теста — 12 с (сценарий ≤10 с + подключение ~6 с к файловой базе считается отдельно в выводе теста).
param([string[]]$Базы = @('УНФ', 'БП', 'УТ'))
$Корень = Split-Path $PSScriptRoot -Parent
$Стенд = @{
	'УНФ' = @('C:\1c_bases\UZ_UNF', 'Администратор')
	'БП'  = @('C:\1c_bases\UZ_BP', '1')
	'УТ'  = @('C:\1c_bases\UZ_UT', 'Admin')
}
$Бюджет = 12
$Провалов = 0
$Начало = Get-Date
foreach ($Имя in $Базы) {
	$База, $Пользователь = $Стенд[$Имя]
	foreach ($Тест in (Get-ChildItem "$Корень\tools\тесты" -Filter 'тест_*.py').BaseName) {
		$Старт = Get-Date
		$Вывод = python "$Корень\tools\тесты\$Тест.py" "--база=$База" "--пользователь=$Пользователь" 2>&1
		$Код = $LASTEXITCODE
		$Сек = [math]::Round(((Get-Date) - $Старт).TotalSeconds, 1)
		$Метка = if ($Сек -gt $Бюджет) { "ПРЕДУПРЕЖДЕНИЕ: бюджет $Бюджет с" } else { '' }
		'{0,-4} {1,-24} код {2}  {3,5} с  {4}' -f $Имя, $Тест, $Код, $Сек, $Метка
		if ($Код -ne 0) {
			$Провалов++
			$Вывод | Select-String 'FAIL|ОШИБКА|Error' | Select-Object -First 5 | ForEach-Object { '       ' + $_.Line }
		}
	}
}
python "$Корень\tools\проверка_запросов.py" @Базы | Select-Object -Last ($Базы.Count + 1)
if ($LASTEXITCODE -ne 0) { $Провалов++ }
"ИТОГО провалов: $Провалов   время: $([int]((Get-Date) - $Начало).TotalSeconds) с"
exit [int]($Провалов -gt 0)
