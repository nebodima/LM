# Все COM-тесты и проверка запросов на тестовых базах — тонкая обёртка над tools\прогон.py
# (одно COM-подключение на базу, базы параллельно; бюджеты и сводку печатает прогон.py).
#   .\tools\все_тесты.ps1                      — УНФ, БП, УТ
#   .\tools\все_тесты.ps1 -Базы УНФ,БП
#   .\tools\все_тесты.ps1 -Тест печать         — один тест («запросы» — только проверка запросов)
#   .\tools\все_тесты.ps1 -База C:\1c_bases\UZ_UNF_A -Пользователь Администратор   — своя копия
#   -БезСверки                                  — не сверять расширение в базе с src_ext (печатается)
#   -Быстро                                     — рабочий цикл: только тесты, затронутые изменениями с прошлого
#                                                 зелёного полного прогона (без ключа — полный, граница этапа)
param([string[]]$Базы = @(), [string]$Тест = '', [string]$База = '', [string]$Пользователь = '', [switch]$Подробно, [switch]$БезСверки,
	[switch]$Быстро)
$env:PYTHONIOENCODING = 'utf-8'
$Аргументы = @()
if ($Базы.Count) { $Аргументы += "--базы=$($Базы -join ',')" }
if ($Тест) { $Аргументы += "--тест=$Тест" }
if ($База) { $Аргументы += "--база=$База" }
if ($Пользователь) { $Аргументы += "--пользователь=$Пользователь" }
if ($Подробно) { $Аргументы += '--подробно' }
if ($БезСверки) { $Аргументы += '--без-сверки' }
if ($Быстро) { $Аргументы += '--быстро' }
python "$PSScriptRoot\прогон.py" @Аргументы
exit $LASTEXITCODE
