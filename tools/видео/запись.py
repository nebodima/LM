def проход(имя, публикация, сцены):
    папка = os.path.join(ВЫХОД, "записи", имя)
    if not СУХО and os.path.isdir(папка):
        for ф in os.listdir(папка):
            os.remove(os.path.join(папка, ф))
    х = cdp.Хром()
    запись = None
    метки = []
    try:
        н = time.time()
        х.открыть(СТЕНД % публикация)
        х.закрыть_оповещения()
        print("%s: клиент загружен за %.0f с" % (имя, time.time() - н), flush=True)
        if not СУХО:
            запись = cdp.Запись(х.адрес_страницы(), папка)
            запись.начать()
            time.sleep(1.0)
        for сцена, шаги in сцены:
            н = time.time()
            х.закрыть_оповещения()
            метки.append({"сцена": сцена, "начало": time.time()})
            шаги(х)
            метки[-1]["конец"] = time.time()
            ошибка = х.окно_ошибки()
            print("  %-14s %5.1f с (реплика %4.1f с)%s" % (сцена, time.time() - н, ГОЛОС.get(сцена, 0),
                                                         "  ОКНО ОШИБКИ: " + ошибка if ошибка else ""), flush=True)
    finally:
        if запись:
            запись.закончить()
            with open(os.path.join(папка, "метки.json"), "w", encoding="utf-8") as ф:
                json.dump({"кадры": [[т, os.path.basename(п)] for т, п in запись.кадры], "сцены": метки}, ф,
                          ensure_ascii=False)
            print("  кадров: %d" % len(запись.кадры))
        х.закрыть()


