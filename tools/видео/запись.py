class Сцена:
    """Отсчёт сцены: пауза() добирает время до доли реплики диктора, чтобы картинка шла вровень с текстом."""

    def __init__(self, имя):
        self.имя = имя
        self.начало = time.time()
        self.длина = ГОЛОС.get(имя, 15.0)

    def до(self, доля):
        """Ждать, пока от начала сцены не пройдёт доля реплики (0..1). Если уже прошла — сразу дальше."""
        осталось = self.начало + self.длина * доля - time.time()
        if осталось > 0:
            time.sleep(осталось)


