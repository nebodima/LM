def активное(х):
    return х.js("document.activeElement ? document.activeElement.id : ''") or ""


def ждать_поле(х, конец_ид, секунд=4):
    """Ввод в таблицу — только когда поле ячейки действительно в редактировании: иначе буквы уходят в поиск
    по списку (открывается окно «Найти») и строка теряется."""
    срок = time.time() + секунд
    while time.time() < срок:
        if активное(х).endswith(конец_ид):
            return True
        time.sleep(0.2)
    raise RuntimeError("поле %s не в редактировании (активно: %s)" % (конец_ид, активное(х)))


def в_ячейку(х, текст, поле):
    """Набрать в ячейку и дать клиенту принять набранное: Tab сразу после набора теряет значение строки."""
