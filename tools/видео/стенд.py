def роли_педагога():
    """Роли пользователя педагога — заново, прямо перед проходом «педагог»: УНФ (управление доступом БСП) при входе
    администратора приводит роли пользователей ИБ к группам доступа, а педагог в них не состоит — роли стираются,
    и вход кончается «Нет прав на запуск требуемого вида клиента» (29.09.2026)."""
    from тест_права import ОБЩИЕ_РОЛИ, РОЛИ_ХОЗЯИНА
    c, _ = сеанс.подключить(ВИДЕО, "Администратор", закрепить=False)
    п = c.ПользователиИнформационнойБазы.НайтиПоИмени(ПЕДАГОГ_ПОЛЬЗОВАТЕЛЬ)
    есть = {р.Имя for р in п.Роли}
    for имя in ОБЩИЕ_РОЛИ + РОЛИ_ХОЗЯИНА[c.Метаданные.Имя] + ["УЗ_Педагог"]:
        if имя not in есть:
            п.Роли.Добавить(c.Метаданные.Роли.Найти(имя))
    п.Записать()
    del c


