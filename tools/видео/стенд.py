ШАБЛОН_VRD = """<?xml version="1.0" encoding="UTF-8"?>
<point xmlns="http://v8.1c.ru/8.2/virtual-resource-system"
		xmlns:xs="http://www.w3.org/2001/XMLSchema"
		xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
		base="/%s"
		ib="File=&quot;%s&quot;;Usr=&quot;%s&quot;;">
	<ws pointEnableCommon="false"/>
	<standardOdata enable="false" reuseSessions="autouse" sessionMaxAge="20" poolSize="10" poolTimeout="5"/>
</point>
"""


def конфиг():
    os.makedirs(ЛОГИ, exist_ok=True)
    строки = ["# Свой экземпляр Apache видеозаписи «Учёт занятий 2.0» (tools\\видео\\стенд.py); C:\\Apache24\\conf не трогает",
              'ServerRoot "C:/Apache24"', "Listen 127.0.0.1:%d" % ПОРТ, "ServerName 127.0.0.1:%d" % ПОРТ,
              'PidFile "%s/httpd%d.pid"' % (ЛОГИ.replace("\\", "/"), ПОРТ),
              'ErrorLog "%s/error.log"' % ЛОГИ.replace("\\", "/"), "LogLevel warn"]
    строки += ["LoadModule %s modules/mod_%s.so" % (м, м.replace("_module", "")) for м in
               ("authz_core_module", "mime_module", "log_config_module", "alias_module", "dir_module")]
    строки += ['LoadModule _1cws_module "%s"' % ПЛАТФОРМА, "TypesConfig conf/mime.types",
               'DocumentRoot "%s/"' % list(ПУБЛИКАЦИИ.values())[0][0].replace("\\", "/"),
               "<Directory />", "    AllowOverride none", "    Require all denied", "</Directory>"]
    for публ, (папка, база, пользователь) in ПУБЛИКАЦИИ.items():
        os.makedirs(папка, exist_ok=True)
        with open(os.path.join(папка, "default.vrd"), "w", encoding="utf-8") as ф:
            ф.write(ШАБЛОН_VRD % (публ, база, пользователь))
        п = папка.replace("\\", "/")
        строки += ['Alias "/%s" "%s/"' % (публ, п), '<Directory "%s/">' % п, "    AllowOverride None",
                   "    Options None", "    Require all granted", "    SetHandler 1c-application",
                   '    ManagedApplicationDescriptor "%s/default.vrd"' % п, "</Directory>"]
    with open(КОНФИГ, "w", encoding="utf-8") as ф:
        ф.write("\n".join(строки) + "\n")


def pid_файл():
    return os.path.join(ЛОГИ, "httpd%d.pid" % ПОРТ)


def старт():
    # перезапуск, а не «поднять, если не запущен»: веб-сеансы прошлых загрузок клиента висят до таймаута и каждый
    # держит лицензию 1С (находка сессии «Путевых листов», 30.09.2026) — остановка Apache их сбрасывает
    if os.path.exists(pid_файл()):
        стоп()
    конфиг()
    subprocess.Popen([APACHE, "-f", КОНФИГ], creationflags=0x00000008 | 0x00000200,
                     stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, stdin=subprocess.DEVNULL)
    for _ in range(40):
        time.sleep(0.5)
        if os.path.exists(pid_файл()):
            print("Apache видео: http://127.0.0.1:%d/uzv/ru_RU/ и /uzs/ (pid %s)" % (ПОРТ, open(pid_файл()).read().strip()))
            return 0
    print("Apache не поднялся — %s\\error.log" % ЛОГИ)
    return 1


def стоп():
    if not os.path.exists(pid_файл()):
        print("Apache видео не запущен")
        return 0
    pid = open(pid_файл()).read().strip()
    # только свой процесс и его дочерний (по pid, не по имени образа — рядом Apache Путевых листов)
    subprocess.run(["taskkill", "/PID", pid, "/T", "/F"], capture_output=True)
    try:
        os.remove(pid_файл())
    except OSError:
        pass
    print("Apache видео остановлен (pid %s)" % pid)
    return 0


if __name__ == "__main__":
    настроить_вывод()
    if "--копии" in sys.argv:
        копии()
    if "--подготовить" in sys.argv:
        подготовить_видео()
        подготовить_пустую()
