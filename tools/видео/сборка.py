def иконка(размер):
    """Значок раздела «Учёт занятий» — из архива картинки расширения (в нём варианты 85…400 %)."""
    import zipfile
    путь = os.path.join(ИКОНКА, "Picture.zip")
    if not os.path.isfile(путь):
        return None
    with zipfile.ZipFile(путь) as z:
        for имя in ("400.png", "300.png", "200.png"):
            if имя in z.namelist():
                return Image.open(io.BytesIO(z.read(имя))).convert("RGBA").resize((размер, размер), Image.LANCZOS)
    return None


def строки_по_ширине(текст, ш, размер_шрифта, жирный=False):
    ф = шрифт(размер_шрифта, жирный)
    слова, строки, текущая = текст.split(), [], ""
    for с in слова:
        проба = (текущая + " " + с).strip()
        if ф.getlength(проба) > ш and текущая:
            строки.append(текущая)
            текущая = с
        else:
            текущая = проба
    if текущая:
        строки.append(текущая)
    return строки


