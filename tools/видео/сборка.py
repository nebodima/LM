def уложить(кадры, длина, цель, ускорение_макс=None):
    """Длительности кадров, чтобы сцена длилась цель: сжать неподвижные промежутки (> 1,2 с), затем равномерно."""
    моменты = [т for т, _ in кадры] + [длина]
    длит = [max(0.001, моменты[i + 1] - моменты[i]) for i in range(len(кадры))]
    всего = sum(длит)
    if всего > цель:
        лишнее = всего - цель
        паузы = [(i, д) for i, д in enumerate(длит) if д > 1.2]
        запас = sum(д - 1.2 for _, д in паузы)
        доля = min(1.0, лишнее / запас) if запас > 0 else 0
        for i, д in паузы:
            длит[i] = д - (д - 1.2) * доля
        всего = sum(длит)
    if всего > цель:
        к = цель / всего
        длит = [д * к for д in длит]
    elif всего < цель:
        длит[-1] += цель - всего
    return длит


