# ───────────────────────── субтитры ─────────────────────────

def время_srt(с):
    мс = int(round(с * 1000))
    return "%02d:%02d:%02d,%03d" % (мс // 3600000, мс // 60000 % 60, мс // 1000 % 60, мс % 1000)


def куски_текста(текст, предел=80):
    предложения = re.split(r"(?<=[.!?])\s+", текст.strip())
    итог = []
    for п in предложения:
        while len(п) > предел:
            разрез = max(п.rfind(", ", 0, предел), п.rfind(" — ", 0, предел), п.rfind(": ", 0, предел))
            if разрез < 20:
                разрез = п.rfind(" ", 0, предел)
            итог.append(п[:разрез + 1].strip())
            п = п[разрез + 1:].strip()
        if п:
            итог.append(п)
    return итог


def на_экран(текст):
    """Субтитр читают глазами: «одна-эс» → «1С», «два ноль» → «2.0», «эф-один» → «F1»."""
    return текст.replace("одна-эс", "1С").replace("два ноль", "2.0").replace("эф-один", "F1")


def субтитры(реплики_время, путь):
    """реплики_время: [(начало реплики в ролике, секунд речи, текст)]."""
    номер, строки = 0, []
    for начало, секунд, текст in реплики_время:
        куски = куски_текста(на_экран(текст))
        всего = sum(len(к) for к in куски) or 1
        т = начало
        for к in куски:
            д = секунд * len(к) / всего
            номер += 1
            строки.append("%d\n%s --> %s\n%s\n" % (номер, время_srt(т), время_srt(т + д - 0.05), к))
            т += д
    with io.open(путь, "w", encoding="utf-8-sig", newline="\r\n") as ф:
        ф.write("\n".join(строки))


