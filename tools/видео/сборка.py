def кадры_проверки(ролик, шаг=10):
    папка = os.path.join(ВЫХОД, "проверка", os.path.splitext(os.path.basename(ролик))[0])
    shutil.rmtree(папка, ignore_errors=True)
    os.makedirs(папка)
    выполнить(["-i", ролик, "-vf", "fps=1/%d,scale=960:-1" % шаг, os.path.join(папка, "к%03d.jpg")], "кадры")
    return папка


