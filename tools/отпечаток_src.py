"""Отпечаток src_ext и отметка деплоя: чем сверяется «в базе то, что в src_ext».

Отпечаток — sha256 по содержимому всех файлов src_ext (относительный путь + байты; ConfigDumpInfo.xml не в
счёт), первые 12 знаков. Не зависит от времени файлов и от того, из какой рабочей копии считали.

Отметка деплоя — %TEMP%\\уз_прогон\\c_1c_bases_uz_unf_d.деплой.json: {"src": отпечаток залитого src_ext, "время": …,
"хеш_в_базе": ХешСумма расширения}. Деплой пишет её после удачных загрузки, проверки модулей и применения,
с пустым «хеш_в_базе». Первый прогон после деплоя читает ХешСумму расширения УЗ_ext через COM и
записывает её (привязка); дальше прогон краснеет, если
  * отметки нет — база залита не деплоем, неизвестно, какой код проверяем;
  * отпечаток рабочей копии ≠ отметке — src_ext изменён после деплоя, в базе старый код;
  * ХешСумма в базе ≠ привязанной — расширение в базе перезалили мимо деплоя.
Деплой (tools\\деплой.ps1, шаг «отметка деплоя») зовёт отметку с ключом --хеш-из-базы: отметка сразу получает
ХешСумму расширения из базы (COM-подключение, ~6 с) — привязка делается деплоем в момент применения, а не первым
прогоном (повторный аудит 28.09.2026, T06): чужая заливка между деплоем и прогоном даёт красный прогон.
Привязка «первым прогоном» остаётся только для отметки без ХешСуммы (ручной вызов без ключа) — прогон печатает,
кем привязана ХешСумма. Версия выпуска (Configuration.xml, формат 1С из четырёх чисел) меняется только правкой
Configuration.xml — деплой тогда грузит расширение полной загрузкой; прогон сверяет версию в базе с src_ext.

    python tools\\отпечаток_src.py                       — отпечаток src_ext этой рабочей копии
    python tools\\отпечаток_src.py --отметить=C:\\1c_bases\\UZ_UNF_D   — записать отметку деплоя (зовёт деплой)
    python tools\\отпечаток_src.py --отметить=C:\\1c_bases\\UZ_UNF_D --хеш-из-базы --пользователь=Администратор
                                                         — то же и сразу ХешСумма расширения из базы
    python tools\\отпечаток_src.py --каталог=%TEMP%\\уз_мутации_гейта\\src   — другая папка (деплой с -Исходники)
"""
import datetime
import hashlib
import json
import os
import re
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import адрес_базы  # noqa: E402

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(КОРЕНЬ, "src_ext")
ЖУРНАЛЫ = os.path.join(tempfile.gettempdir(), "уз_прогон")


def отпечаток(каталог=SRC):
    х = hashlib.sha256()
    файлы = []
    for корень, папки, имена in os.walk(каталог):
        папки[:] = sorted(п for п in папки if п != "__pycache__")
        for имя in имена:
            if имя == "ConfigDumpInfo.xml":
                continue
            путь = os.path.join(корень, имя)
            файлы.append((os.path.relpath(путь, каталог).replace("\\", "/").lower(), путь))
    for отн, путь in sorted(файлы):
        х.update(отн.encode("utf-8") + b"\0")
        with open(путь, "rb") as ф:
            х.update(ф.read())
        х.update(b"\0")
    return х.hexdigest()[:12]


def имя_базы(база):
    """То же имя, что у замка прогона/деплоя (прогон.py _замок, деплой.ps1)."""
    return re.sub(r"[^\w]+", "_", адрес_базы.ключ(база)).strip("_")


def файл_отметки(база):
    return os.path.join(ЖУРНАЛЫ, имя_базы(база) + ".деплой.json")


def прочитать(база):
    try:
        with open(файл_отметки(база), encoding="utf-8") as ф:
            return json.load(ф)
    except (OSError, ValueError):
        return None


def записать(база, отметка):
    os.makedirs(ЖУРНАЛЫ, exist_ok=True)
    with open(файл_отметки(база), "w", encoding="utf-8") as ф:
        json.dump(отметка, ф, ensure_ascii=False)


def сверить(база, хеш_в_базе, src=None):
    """(ошибка или None, строка для печати) — сверка отметки деплоя, отпечатка src_ext и ХешСуммы в базе."""
    src = src or отпечаток()
    о = прочитать(база)
    if о is None:
        return ("нет отметки деплоя — база залита не tools\\деплой.ps1, неизвестно, какой код проверяем "
                "(src_ext %s); залейте: tools\\деплой.ps1 -СвояБаза %s" % (src, база)), ""
    if о.get("src") != src:
        return ("src_ext изменён после деплоя: в базе %s (деплой %s), в рабочей копии %s — в базе старый код; "
                "залейте деплоем" % (о.get("src"), о.get("время"), src)), ""
    if not о.get("хеш_в_базе"):
        о["хеш_в_базе"] = хеш_в_базе
        о["привязка"] = "первый прогон"
        записать(база, о)
        return None, ("расширение: src %s (деплой %s), ХешСумма %s — привязана первым прогоном (слабая привязка: "
                      "чужая заливка до прогона принята бы как своя; деплою — ключ --хеш-из-базы)") % (
            src, о.get("время"), хеш_в_базе)
    if о["хеш_в_базе"] != хеш_в_базе:
        return ("ХешСумма УЗ_ext в базе %s ≠ привязанной %s — расширение перезалито мимо деплоя"
                % (хеш_в_базе, о["хеш_в_базе"])), ""
    return None, "расширение: src %s (деплой %s), ХешСумма совпадает (привязана: %s)" % (
        src, о.get("время"), о.get("привязка", "первый прогон"))


def версия_src(каталог=SRC):
    """Версия расширения из src_ext/Configuration.xml (<Version>) — её сверяет прогон с версией в базе."""
    with open(os.path.join(каталог, "Configuration.xml"), encoding="utf-8-sig") as ф:
        найдено = re.search(r"<Version>([^<]*)</Version>", ф.read())
    return найдено.group(1) if найдено else ""


def хеш_из_базы(база, пользователь):
    """ХешСумма расширения УЗ_ext в базе (файловой или серверной) — COM-подключение (без песочницы: код продукта не зовём)."""
    import win32com.client
    c = win32com.client.Dispatch("V83.COMConnector").Connect(адрес_базы.строка_com(база, пользователь))
    for р in c.РасширенияКонфигурации.Получить():
        if р.Имя == "УЗ_ext":
            return c.Base64Строка(р.ХешСумма)       # как в прогон.py (сверка отметки)
    raise SystemExit("в базе %s нет расширения УЗ_ext" % база)


def main():
    for п in (sys.stdout, sys.stderr):
        п.reconfigure(encoding="utf-8")
    база = next((а.split("=", 1)[1] for а in sys.argv[1:] if а.startswith("--отметить=")), None)
    имя = next((а.split("=", 1)[1] for а in sys.argv[1:] if а.startswith("--имя-базы=")), None)
    if имя:                  # имя замка/отметки базы — деплой.ps1 берёт его отсюда, чтобы совпадало с прогоном
        print(имя_базы(имя))
        return 0
    каталог = next((а.split("=", 1)[1] for а in sys.argv[1:] if а.startswith("--каталог=")), SRC)
    src = отпечаток(каталог)
    if база:
        отметка = {"src": src, "время": datetime.datetime.now().strftime("%d.%m.%Y %H:%M:%S"), "хеш_в_базе": ""}
        if "--хеш-из-базы" in sys.argv[1:]:
            пользователь = next((а.split("=", 1)[1] for а in sys.argv[1:] if а.startswith("--пользователь=")),
                                "Администратор")
            отметка.update(хеш_в_базе=хеш_из_базы(база, пользователь), привязка="деплой")
        записать(база, отметка)
    print(src)
    return 0


if __name__ == "__main__":
    sys.exit(main())
