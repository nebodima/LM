def _сервер_жив(база):
    try:
        с = json.load(open(файл_состояния(база), encoding="utf-8"))
    except (OSError, ValueError):
        return None
    import psutil
    try:
        if not psutil.Process(с["pid"]).is_running() or "итерация" not in " ".join(psutil.Process(с["pid"]).cmdline()):
            return None
    except (psutil.NoSuchProcess, psutil.AccessDenied, KeyError):
        return None
    return с


def _запустить_сервер(база, пользователь):
    флаги = subprocess.DETACHED_PROCESS | subprocess.CREATE_NEW_PROCESS_GROUP | subprocess.CREATE_NO_WINDOW
    журнал = open(os.path.join(агент.папка(база), "итерация.log"), "a", encoding="utf-8")
    subprocess.Popen([sys.executable, os.path.abspath(__file__), "сервер", "--база=" + база,
                      "--пользователь=" + пользователь], creationflags=флаги, close_fds=True,
                     stdin=subprocess.DEVNULL, stdout=журнал, stderr=журнал,
                     env=dict(os.environ, PYTHONIOENCODING="utf-8"))
    журнал.close()
    срок = time.time() + 20
    while time.time() < срок:
        с = _сервер_жив(база)
        if с and с.get("порт"):
            return с
        time.sleep(0.05)
    raise RuntimeError("сервер итераций не поднялся за 20 с (журнал %s)" % os.path.join(агент.папка(база), "итерация.log"))


def _запрос(с, запрос, печатать=True):
    """Запрос серверу; строки ответа печатаются по мере прихода. → код выхода."""
    к = socket.create_connection(("127.0.0.1", с["порт"]), timeout=10)
    к.settimeout(None)
    к.sendall((json.dumps(запрос, ensure_ascii=False) + "\n").encode("utf-8"))
    буфер = b""
    код = 1
    with к:
        while True:
            кусок = к.recv(65536)
            if not кусок:
                break
            буфер += кусок
            while b"\n" in буфер:
                строка, буфер = буфер.split(b"\n", 1)
                т = строка.decode("utf-8", "replace")
                if т.startswith("\x00"):
                    код = json.loads(т[1:])["код"]
                elif печатать:
                    print(т, flush=True)
    return код


