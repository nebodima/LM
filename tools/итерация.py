def отпечаток_файлов(папка):
    """{путь от папки через «\\»: "длина|время UTC в тиках .NET"} — формат деплой.ps1 (Отпечаток-Файлов)."""
    итог = {}
    for корень, _, имена in os.walk(папка):
        for имя in имена:
            if имя == "ConfigDumpInfo.xml":
                continue
            путь = os.path.join(корень, имя)
            с = os.stat(путь)
            # тики .NET: 100 нс с 01.01.0001; st_mtime_ns — с 01.01.1970
            итог[os.path.relpath(путь, папка)] = "%d|%d" % (с.st_size, с.st_mtime_ns // 100 + 621355968000000000)
    return итог


def зеркало(из, в, нужно):
    """Копия изменённых файлов в папку агента (агент грузит только из-под своего /AgentBaseDir). → скопировано."""
    есть = отпечаток_файлов(в) if os.path.isdir(в) else {}
    скопировано = 0
    for отн, отп in нужно.items():
        if есть.get(отн) == отп:
            continue
        куда = os.path.join(в, отн)
        os.makedirs(os.path.dirname(куда), exist_ok=True)
        shutil.copy2(os.path.join(из, отн), куда)      # время записи сохраняется — отпечаток зеркала = исходника
        скопировано += 1
    for отн in set(есть) - set(нужно):
        os.remove(os.path.join(в, отн))
    return скопировано


def фоновый(имя, команда, таймаут):
    """Процесс в фоне (офлайн-проверки параллельно конфигуратору): {имя, код, текст, сек, поток}."""
    ф = {"имя": имя, "код": None, "текст": "", "сек": 0.0}

    def ждать():
        н = time.time()
        # пониже приоритетом: процессор нужнее конфигуратору (update-db-cfg — ~5 с чистого счёта одного потока)
        п = subprocess.Popen(команда, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                             env=dict(os.environ, PYTHONIOENCODING="utf-8"),
                             creationflags=subprocess.BELOW_NORMAL_PRIORITY_CLASS)

        try:
            ф["текст"] = п.communicate(timeout=таймаут)[0].decode("utf-8", "replace")
            ф["код"] = п.returncode
        except subprocess.TimeoutExpired:
            п.kill()
            ф["текст"], ф["код"] = "ТАЙМАУТ %d с: процесс снят" % таймаут, 99
        ф["сек"] = time.time() - н
    ф["поток"] = threading.Thread(target=ждать, daemon=True)
    ф["поток"].start()
    return ф


def трасса():
    """Текущее исключение с кадрами. traceback.format_exc в Python 3.11 падает на кириллице в строке с «^^^»
    (UnicodeDecodeError) — кадры печатаются сами, как в tools\\тесты\\сеанс.py."""
    тип, е, тб = sys.exc_info()
    кадры = "".join("    %s:%d %s\n" % (os.path.basename(к.filename), к.lineno, к.line) for к in traceback.extract_tb(тб))
    return "%s: %s\n%s" % (getattr(тип, "__name__", тип), " ".join(str(е).split())[:500], кадры)


