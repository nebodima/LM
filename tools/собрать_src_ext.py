def обработать_форму(т, отн, модель):
    """Form.xml: переименования, картинки/стили/общие команды БСП."""
    if отн in ПРАВКИ_ФОРМ:
        т = ПРАВКИ_ФОРМ[отн](т, отн)
    т = переименовать_весь_текст(т)
    корень = etree.fromstring(т.lstrip("﻿").encode("utf-8"),
                              etree.XMLParser(remove_blank_text=False, resolve_entities=False))
    for эл in list(корень.iter()):
        if not isinstance(эл.tag, str) or эл.getparent() is None:
            continue
        з = (эл.text or "").strip()
        # хранилище настроек БСП у формы (ХранилищеВариантовОтчетов) — убрать, будет стандартное
        if лок(эл.tag) == "SettingsStorage" and з and not модель.разрешить(з):
            удалить(эл)
            ЖУРНАЛ["свойства"].append("%s: SettingsStorage = %s -> убрано" % (отн, з))
            continue
        # общие картинки
        if з.startswith("CommonPicture.") and not модель.разрешить(з):
            имя = з.split(".", 1)[1]
            if имя in КАРТИНКИ_БСП:
                эл.text = "StdPicture." + КАРТИНКИ_БСП[имя]
                ЖУРНАЛ["картинки"].append("%s: %s -> %s" % (отн, имя, эл.text))
            else:
                ЖУРНАЛ["ошибки_сборки"].append("%s: картинка %s — нет соответствия в КАРТИНКИ_БСП" % (отн, з))
        # элементы стиля (текстом)
        if з.startswith("style:"):
            имя = з[6:]
            if имя in СТИЛИ_БСП:
                if СТИЛИ_БСП[имя] is None:
                    удалить(эл)
                    ЖУРНАЛ["стили"].append("%s: %s (%s) -> убрано" % (отн, имя, лок(эл.tag)))
                    continue
                эл.text = "style:" + СТИЛИ_БСП[имя]
                ЖУРНАЛ["стили"].append("%s: %s -> %s" % (отн, имя, эл.text))
        for а, знач in list(эл.attrib.items()):
            if знач.startswith("style:") and знач[6:] in СТИЛИ_БСП:
                нов = СТИЛИ_БСП[знач[6:]]
                if нов is None:
                    del эл.attrib[а]
                else:
                    эл.set(а, "style:" + нов)
                ЖУРНАЛ["стили"].append("%s: %s (атрибут) -> %s" % (отн, знач, нов))
        # общие команды БСП (СтруктураПодчиненности, ИсторияИзменений …)
        if лок(эл.tag) in ("CommandName", "Command") and з.startswith("CommonCommand.") and not модель.разрешить(з):
            владелец = эл.getparent()
            if лок(эл.tag) == "Command":        # CommandInterface/…/Item
                удалить(владелец)
            else:                                # Button
                удалить(владелец)
            ЖУРНАЛ["команды_бсп"].append("%s: убрана %s (%s)" % (отн, з, владелец.get("name") or лок(владелец.tag)))
            continue
        # команда командного интерфейса по uuid («0:uuid») — у переносимых объектов uuid новые,
        # а в LM такие ссылки висят на команды БСП; убираем
        if лок(эл.tag) == "Command" and re.match(r"^\d+:[0-9a-f-]{36}$", з):
            владелец = эл.getparent()
            удалить(владелец)
            ЖУРНАЛ["команды_бсп"].append("%s: убрана команда по uuid %s" % (отн, з))
    # опустевшие панели командного интерфейса
    for эл in list(корень.iter()):
        if isinstance(эл.tag, str) and лок(эл.tag) in ("NavigationPanel", "CommandBar") and \
                эл.getparent() is not None and лок(эл.getparent().tag) == "CommandInterface" and not len(эл):
            удалить(эл)
    for эл in list(корень.iter()):
        if isinstance(эл.tag, str) and лок(эл.tag) == "CommandInterface" and not len(эл):
            удалить(эл)
    return ДЕКЛ + etree.tostring(корень, encoding="unicode")


def перенести_папку(запись, кл, старое, модель):
    """Всё содержимое папки объекта LM (модули, формы, макеты, команды, справка, картинка)."""
    папка = ПАПКА[кл]
    откуда = os.path.join(ИСТОЧНИК, папка, старое)
    куда = os.path.join(ЦЕЛЬ, папка, запись["имя"])
    if not os.path.isdir(откуда):
        return
    исключено = ИСКЛЮЧЕНИЯ.get((кл, старое), [])
    for корень_п, _, файлы in os.walk(откуда):
        for ф in sorted(файлы):
            путь = os.path.join(корень_п, ф)
            отн_об = os.path.relpath(путь, откуда).replace("\\", "/")
            отн = "%s/%s/%s" % (папка, старое, отн_об)          # путь в выгрузке LM (ключ ПРАВОК)
            if отн_об in ("Ext/Predefined.xml", "Ext/Schedule.xml"):
                continue                                         # пишутся вместе с объектом
            if any(отн_об == и or отн_об.startswith(и + "/") or отн_об.startswith(и + ".") for и in исключено):
                continue
            части = отн_об.split("/")
            форма_или_макет = части[0] in ("Forms", "Templates", "Commands")
            if форма_или_макет and not ПЕРЕНОСИТЬ_ФОРМЫ:
                continue
            if ф.endswith(".bsl") and not ПЕРЕНОСИТЬ_МОДУЛИ:
                continue
            цель = os.path.join(куда, *части)
            ЖУРНАЛ["файлов"] += 1
            if ф.endswith(".bsl"):
                т = io.open(путь, encoding="utf-8-sig").read().replace("\r\n", "\n")
                писать(цель, преобразовать_bsl(т, отн))
                ЖУРНАЛ["модулей"] += 1
            elif len(части) == 2 and части[0] in ("Forms", "Templates") and ф.endswith(".xml"):
                к = читать_дерево(путь)                         # метаданные формы/макета: имя + uuid
                переименовать_дерево(к)
                почистить_синонимы(к)
                новые_uuid(к, запись["полное"], запись["полное"] + "|")
                писать_дерево(цель, к, ВЕРСИЯ_ФОРМАТА_ПЕРЕНОСА)
                if части[0] == "Forms":
                    ЖУРНАЛ["форм_перенесено"] += 1
            elif ф == "Form.xml":
                т = io.open(путь, encoding="utf-8-sig").read().replace("\r\n", "\n")
                писать(цель, обработать_форму(применить_правки_текста(т, отн), отн, модель))
            elif ф.endswith((".xml", ".html", ".txt")):
                т = io.open(путь, encoding="utf-8-sig").read().replace("\r\n", "\n")
