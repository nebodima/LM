class Снимок:
    """Файлы каталога в памяти (отн. путь -> текст). Самотест подменяет один файл, не копируя каталог."""

    def __init__(self, каталог=None, файлы=None, прочие=None):
        self.файлы = {} if файлы is None else файлы
        self.прочие = set() if прочие is None else прочие    # не xml/bsl — только имена
        self._деревья = {}
        if каталог:
            for корень, _, фф in os.walk(каталог):
                for ф in фф:
                    п = os.path.join(корень, ф)
                    отн = os.path.relpath(п, каталог)
                    if ф.endswith((".xml", ".bsl")):
                        self.файлы[отн] = io.open(п, encoding="utf-8-sig", errors="replace").read()
                    else:
                        self.прочие.add(отн)

    def с_заменой(self, отн, текст):
        н = Снимок(файлы=dict(self.файлы), прочие=self.прочие)
        н._деревья = {к: з for к, з in self._деревья.items() if к != отн}
        н.файлы[отн] = текст
        return н

    def дерево(self, отн):
        """lxml-дерево или исключение разбора (кэшируется)."""
        if отн not in self._деревья:
            try:
                т = re.sub(r"^﻿?<\?xml[^>]*\?>", "", self.файлы[отн], count=1)
                self._деревья[отн] = etree.fromstring(
                    т.encode("utf-8"), etree.XMLParser(remove_blank_text=False, resolve_entities=False))
            except Exception as е:
                self._деревья[отн] = е
        return self._деревья[отн]


