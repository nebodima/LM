def закомментировать_оператор(т, нач, что, отн):
    """Закомментировать оператор, начинающийся вызовом в позиции нач (до ')' и ';').
    Возвращает новый текст или None, если оператор нельзя безопасно закомментировать."""
    скобка = т.find("(", нач)
    арг, конец = разобрать_аргументы(т, скобка) if скобка >= 0 else (None, None)
    if арг is None:
        return None
    нс = т.rfind("\n", 0, нач) + 1
    перед = т[нс:нач]
    if перед.strip():                         # «Х = Вызов(...)» — переменная останется неопределённой
        return None
    кс = т.find("\n", конец)
    кс = len(т) if кс < 0 else кс
    хвост = т[конец:кс].strip()
    if хвост not in ("", ";") and not хвост.startswith(("//", ";//", "; //")):
        return None
    отступ = перед
    строки = т[нс:кс].split("\n")
    блок = [отступ + "//TODO УЗ: " + что] + ["//" + с for с in строки]
    return т[:нс] + "\n".join(блок) + т[кс:]


def слой_совместимости(т, отн):
    """Замена вызовов БСП на УЗ_* и комментирование прочих вызовов БСП (в коде, не в строках)."""
    ре = re.compile(r"(?<![A-Za-zА-Яа-яЁё0-9_.])(%s)\s*\.\s*(%s)\s*\(" % (_ИД, _ИД))
    # 1) однозначные замены
    маска = маска_кода(т)
    части, поз = [], 0
    for м in ре.finditer(т):
        if м.start() < поз or not в_коде(маска, м.start()):
            continue
        ключ = "%s.%s" % (м.group(1), м.group(2))
        if ключ not in ЗАМЕНЫ_БСП:
            continue
        нов, карта = ЗАМЕНЫ_БСП[ключ]
        арг, конец = разобрать_аргументы(т, м.end() - 1)
        if арг is None:
            ЖУРНАЛ["ошибки_сборки"].append("%s:%d: не разобраны аргументы %s" % (отн, номер_строки(т, м.start()), ключ))
            continue
        if арг == [""]:
            арг = []
        потеряно = [а for i, а in enumerate(арг) if i not in карта and а]
        новые = [арг[i] if i < len(арг) else "" for i in карта]
        while новые and not новые[-1]:
            новые.pop()
        части.append(т[поз:м.start()])
        части.append("%s(%s)" % (нов, ", ".join(новые)))
        поз = конец
        ЖУРНАЛ["бсп"].append("%s: %s -> %s%s" % (отн, ключ, нов,
                                                ("  (отброшены аргументы БСП: %s)" % ", ".join(потеряно))
                                                if потеряно else ""))
    т = "".join(части) + т[поз:]
    # 2) убрать вызовы (строкой ниже — повторный поиск, т.к. текст меняется)
    бсп = модули_бсп()
    свои = локальные_имена(т)
    while True:
        маска = маска_кода(т)
        найдено = None
        for м in ре.finditer(т):
            if not в_коде(маска, м.start()):
                continue
            ключ = "%s.%s" % (м.group(1), м.group(2))
            if ключ in УБРАТЬ_БСП:
                найдено = (м, УБРАТЬ_БСП[ключ])
                break
            if м.group(1).lower() in бсп and м.group(1).lower() not in свои:
                найдено = (м, "%s — нет в расширении (БСП/не переносится)" % ключ)
                break
        if not найдено:
            break
        м, что = найдено
        нов = закомментировать_оператор(т, м.start(), что, отн)
        if нов is None:
            ЖУРНАЛ["ошибки_сборки"].append("%s:%d: вызов %s.%s нельзя закомментировать механически — нужна ПРАВКА"
                                           % (отн, номер_строки(т, м.start()), м.group(1), м.group(2)))
            break
        т = нов
        ЖУРНАЛ["бсп"].append("%s: %s.%s закомментирован (TODO УЗ: %s)" % (отн, м.group(1), м.group(2), что))
    return т


# --------------------------------------------------------------------------- однобуквенные имена
# Правило владельца: однобуквенные имена не используются. Переименование — только токены кода
# (не строки, не комментарии, не свойства после точки), без учёта регистра, как в 1С.
ЗАМЕНА_БУКВ = {"с": "ДанныеС", "i": "Индекс", "ф": "ФайлФото", "д": "ДанныеСтроки", "х": "ЗначениеХ",
               "к": "Ключ", "н": "НомерН"}


def убрать_однобуквенные(т, отн):
    объявлены = set()
    for ре in (r"(?i)(?<![\wЁё.])Для\s+Каждого\s+(%s)\s+Из(?![\wЁё])" % _ИД,
               r"(?i)(?<![\wЁё.])Для\s+(%s)\s*=" % _ИД,
               r"(?im)(?:^|;|(?<![\wЁё])Тогда(?![\wЁё])|(?<![\wЁё])Иначе(?![\wЁё])|(?<![\wЁё])Цикл(?![\wЁё])|"
               r"(?<![\wЁё])Попытка(?![\wЁё])|(?<![\wЁё])Исключение(?![\wЁё]))[ \t]*(%s)[ \t]*=(?!=)" % _ИД):
        маска = маска_кода(т)
        for м in re.finditer(ре, т):
            if len(м.group(1)) == 1 and в_коде(маска, м.start(1)):
                объявлены.add(м.group(1).lower())
    for буква in sorted(объявлены):
        нов = ЗАМЕНА_БУКВ.get(буква)
        if нов is None:
            ЖУРНАЛ["ошибки_сборки"].append("%s: однобуквенное имя «%s» — нет замены в ЗАМЕНА_БУКВ" % (отн, буква))
            continue
        занято = {с.lower() for с in re.findall(_ИД, т)}
        итог, н = нов, 1
        while итог.lower() in занято:
            итог, н = "%s%d" % (нов, н), н + 1
        маска = маска_кода(т)
        части, поз, раз = [], 0, 0
        for м in re.finditer(r"(?<![A-Za-zА-Яа-яЁё0-9_.])(%s)(?![A-Za-zА-Яа-яЁё0-9_])" % re.escape(буква), т,
                             re.IGNORECASE):
            if not в_коде(маска, м.start()):
                continue
            части.append(т[поз:м.start()])
            части.append(итог)
            поз = м.end()
            раз += 1
        т = "".join(части) + т[поз:]
        ЖУРНАЛ["однобуквенные"].append("%s: «%s» -> %s (%d)" % (отн, буква, итог, раз))
    return т


