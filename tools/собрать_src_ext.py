# ------------------------------------------------------------------ разметка BSL: код/строки/комментарии
def маска_кода(т):
    """bytearray: 1 — символ кода, 2 — строковый литерал, 0 — дата-литерал или комментарий."""
    м = bytearray(len(т))
    i, n = 0, len(т)
    while i < n:
        ч = т[i]
        if ч == '"':
            м[i] = 2
            i += 1
            while i < n:
                if т[i] == '"':
                    м[i] = 2
                    i += 1
                    if i < n and т[i] == '"':   # "" внутри строки
                        м[i] = 2
                        i += 1
                        continue
                    break
                if т[i] == "\n":                # продолжение строки: строки-комментарии внутри литерала
                    j = i + 1
                    while j < n and т[j] in " \t":
                        j += 1
                    if т.startswith("//", j):
                        к = т.find("\n", j)
                        i = n if к < 0 else к
                        continue
                м[i] = 2
                i += 1
            continue
        if ч == "'":
            к = т.find("'", i + 1)
            i = n if к < 0 else к + 1
            continue
        if ч == "/" and т.startswith("//", i):
            к = т.find("\n", i)
            i = n if к < 0 else к
            continue
        м[i] = 1
        i += 1
    return м


def в_коде(маска, поз):
    return 0 <= поз < len(маска) and маска[поз] == 1


def номер_строки(т, поз):
    return т.count("\n", 0, поз) + 1


def разобрать_аргументы(т, поз_скобки):
    """т[поз_скобки] == '('. Возвращает ([аргументы как текст], позиция после ')') или (None, None)."""
    глубина, i, n, нач, арг = 0, поз_скобки, len(т), поз_скобки + 1, []
    while i < n:
        ч = т[i]
        if ч == '"':
            i += 1
            while i < n:
                if т[i] == '"':
                    if т.startswith('""', i):
                        i += 2
                        continue
                    break
                i += 1
            i += 1
            continue
        if ч == "'":
            к = т.find("'", i + 1)
            i = n if к < 0 else к + 1
            continue
        if ч in "([":
            глубина += 1
        elif ч in ")]":
            глубина -= 1
            if глубина == 0:
                арг.append(т[нач:i])
                return [а.strip() for а in арг], i + 1
        elif ч == "," and глубина == 1:
            арг.append(т[нач:i])
            нач = i + 1
        i += 1
    return None, None


_ИД = r"[A-Za-zА-Яа-яЁё_][A-Za-zА-Яа-яЁё0-9_]*"


def локальные_имена(т):
    """Имена, которые модуль сам объявляет/присваивает (чтобы не путать переменную с общим модулем)."""
    имена = set()
    for м in re.finditer(r"(?im)(?:^|;|Тогда|Иначе|Цикл|Попытка|Исключение)[ \t]*(%s)[ \t]*=(?!=)" % _ИД, т):
        имена.add(м.group(1).lower())
    for м in re.finditer(r"(?i)(?<![\wЁё.])Для\s+(?:Каждого\s+)?(%s)" % _ИД, т):
        имена.add(м.group(1).lower())
    for м in re.finditer(r"(?i)(?<![\wЁё.])Перем\s+([^;]+);", т):
        имена |= {ч.strip().split()[0].lower() for ч in м.group(1).split(",") if ч.strip()}
    for м in re.finditer(r"(?im)^\s*(?:Процедура|Функция|Procedure|Function)\s+%s\s*\(([^)]*)\)" % _ИД, т):
        for п in м.group(1).split(","):
            с = re.match(r"\s*(?:Знач\s+)?(%s)" % _ИД, п)
            if с:
                имена.add(с.group(1).lower())
    return имена


