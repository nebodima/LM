def _проверить_bsl(отн, т, модель, ош):
    маска = маска_кода(т)
    код = "".join(ч if маска[i] == 1 or ч == "\n" else " " for i, ч in enumerate(т))
    код_строки = "".join(ч if маска[i] or ч == "\n" else " " for i, ч in enumerate(т))   # без комментариев

    def стр(поз):
        return код.count("\n", 0, поз) + 1
    # 7. обращение к общему модулю LM «LM.»
    for м in re.finditer(r"(?<![A-Za-zА-Яа-яЁё0-9_.])LM\s*\.", код_строки):
        ош("%s:%d: обращение «LM.» (модуль LM переименован в %s)" % (отн, стр(м.start()), МОДУЛЬ_СЕРВЕР))
    # 8. общие модули / картинки / стили / общие формы, которых нет в src_ext
    свои_имена = локальные_имена(код)
    for м in re.finditer(r"(?<![A-Za-zА-Яа-яЁё0-9_.])(%s)\s*\.\s*%s" % (_ИД, _ИД), код):
        н = м.group(1).lower()
        if н in имена_lm("CommonModules") and н not in модель.модули_нижн and н not in свои_имена:
            ош("%s:%d: вызов общего модуля %s — его нет в src_ext (БСП/не переносится)"
               % (отн, стр(м.start()), м.group(1)))
    for м in re.finditer(r"(?<![A-Za-zА-Яа-яЁё0-9_.])(БиблиотекаКартинок|PictureLib|ЦветаСтиля|StyleColors|"
                         r"ШрифтыСтиля|StyleFonts|РамкиСтиля|StyleBorders)\s*\.\s*(%s)" % _ИД, код):
        коллекция, имя = м.group(1), м.group(2)
        if коллекция in ("БиблиотекаКартинок", "PictureLib"):
            if имя.lower() in имена_lm("CommonPictures") and not модель.есть_объект("CommonPicture", имя):
                ош("%s:%d: общая картинка %s — её нет в src_ext" % (отн, стр(м.start()), имя))
        elif имя.lower() in имена_lm("StyleItems") and not модель.есть_объект("StyleItem", имя):
            ош("%s:%d: элемент стиля %s — его нет в src_ext" % (отн, стр(м.start()), имя))
    # слой совместимости УЗ_Среда законно называет формы хозяина строкой (после проверки метаданных:
    # «ОбщаяФорма.ПечатьДокументов» БСП покупателя) — как и вызовы БСП через Вычислить (аудит ноль_бсп)
    слой = re.split(r"[\\/]", отн)[:2] == ["CommonModules", "УЗ_Среда"]
    for м in re.finditer(r"ОбщаяФорма\.(%s)|CommonForm\.(%s)" % (_ИД, _ИД), код_строки):
        if слой:
            break
        имя = м.group(1) or м.group(2)
        if not модель.есть_объект("CommonForm", имя):
            ош("%s:%d: общая форма %s — её нет в src_ext" % (отн, стр(м.start()), имя))
    # 9. зарезервированные слова как идентификаторы; процедуры с именем глобального метода
    for ре, где in ((r"(?i)(?<![\wЁё.])Для\s+Каждого\s+(%s)\s+Из(?![\wЁё])" % _ИД, "Для Каждого"),
                    (r"(?i)(?<![\wЁё.])Для\s+(%s)\s*=" % _ИД, "счётчик Для"),
                    (r"(?im)(?:^|;)[ \t]*(%s)[ \t]*=(?!=)" % _ИД, "присваивание")):
        for м in re.finditer(ре, код):
            if м.group(1).lower() in ЗАРЕЗЕРВИРОВАННЫЕ:
                ош("%s:%d: %s: зарезервированное слово «%s» как имя" % (отн, стр(м.start(1)), где, м.group(1)))
    for м in re.finditer(r"(?i)(?<![\wЁё.])Перем\s+([^;]+);", код):
        for ч in м.group(1).split(","):
            с = re.match(r"\s*(%s)" % _ИД, ч)
            if с and с.group(1).lower() in ЗАРЕЗЕРВИРОВАННЫЕ:
                ош("%s:%d: Перем: зарезервированное слово «%s»" % (отн, стр(м.start()), с.group(1)))
    for м in re.finditer(r"(?im)^[ \t]*(?:Асинх[ \t]+)?(?:Процедура|Функция|Procedure|Function)[ \t]+(%s)[ \t]*\(([^)]*)\)"
                         % _ИД, код):
        имя = м.group(1)
        if имя.lower() in ЗАРЕЗЕРВИРОВАННЫЕ:
            ош("%s:%d: имя процедуры — зарезервированное слово «%s»" % (отн, стр(м.start()), имя))
        if имя.lower() in ГЛОБАЛЬНЫЕ_МЕТОДЫ:
            ош("%s:%d: процедура/функция «%s» перекрывает метод глобального контекста" % (отн, стр(м.start()), имя))
        for п in м.group(2).split(","):
            с = re.match(r"\s*(?:Знач\s+)?(%s)" % _ИД, п)
            if с and с.group(1).lower() in ЗАРЕЗЕРВИРОВАННЫЕ:
                ош("%s:%d: параметр «%s» процедуры %s — зарезервированное слово" % (отн, стр(м.start()), с.group(1), имя))
    # 11. парность операторных скобок (ловит испорченную точечную правку до конфигуратора)
    счёт = {}
    for м in re.finditer(r"(?i)(?<![A-Za-zА-Яа-яЁё0-9_.])(Процедура|КонецПроцедуры|Функция|КонецФункции|Если|КонецЕсли|"
                         r"Цикл|КонецЦикла|Попытка|КонецПопытки)(?![A-Za-zА-Яа-яЁё0-9_])", код):
        к = м.group(1).lower()
        счёт[к] = счёт.get(к, 0) + 1
    for откр, закр in (("процедура", "конецпроцедуры"), ("функция", "конецфункции"), ("если", "конецесли"),
                       ("цикл", "конеццикла"), ("попытка", "конецпопытки")):
        if счёт.get(откр, 0) != счёт.get(закр, 0):
            ош("%s: непарные операторные скобки %s/%s: %d/%d"
               % (отн, откр, закр, счёт.get(откр, 0), счёт.get(закр, 0)))
    # 10. модальные вызовы
    for м in РЕ_МОДАЛЬНЫЕ.finditer(код):
        ош("%s:%d: модальный вызов «%s» — только асинхронно (ПоказатьВопрос/…/ОписаниеОповещения)"
           % (отн, стр(м.start()), м.group(0).strip()))
    диалоги = {д.lower() for д in re.findall(r"(?i)(%s)\s*=\s*Новый\s+(?:ДиалогВыбораФайла|FileDialog)" % _ИД, код)}
    for м in re.finditer(r"(?<![A-Za-zА-Яа-яЁё0-9_.])(%s)\s*\.\s*Выбрать\s*\(\s*\)" % _ИД, код):
        if м.group(1).lower() in диалоги:
            ош("%s:%d: модальный %s.Выбрать() диалога — только .Показать(ОписаниеОповещения)"
               % (отн, стр(м.start()), м.group(1)))


def проверить(каталог, тихо=False, снимок=None):
    ошибки = []

    def ош(т):
        ошибки.append(т)

    сн = снимок or Снимок(каталог)
    # 1. XML корректен, нет LM_
    for отн in sorted(set(сн.файлы) | сн.прочие):
        if "LM_" in отн:
            ош("имя файла содержит LM_: %s" % отн)
    for отн, т in сн.файлы.items():
        if отн.endswith(".xml") and isinstance(сн.дерево(отн), Exception):
            ош("XML не разбирается: %s: %s" % (отн, сн.дерево(отн)))
        if "LM_" in т:
            ош("подстрока LM_ в %s" % отн)
    модель = модель_снимка(сн)
    модель.модули_нижн = {и.lower() for (кл, и) in модель.объекты if кл == "CommonModule"}
    модель.подпись = tuple(sorted("%s.%s" % о for о in модель.объекты
                                  if о[0] in ("CommonModule", "CommonPicture", "StyleItem", "CommonForm")))
    деревья = {отн: сн.дерево(отн) for отн in сн.файлы
               if отн.endswith(".xml") and not isinstance(сн.дерево(отн), Exception)}

    # 2. uuid уникальны
    виденные = {}
    for отн, к in деревья.items():
        for эл in к.iter():
            if not isinstance(эл.tag, str):
                continue
            кандидаты = []
            if эл.get("uuid") is not None:
                кандидаты.append(эл.get("uuid"))
            if лок(эл.tag) == "Item" and эл.get("id") and отн.endswith("Predefined.xml"):
                кандидаты.append(эл.get("id"))
            if лок(эл.tag) in ("TypeId", "ValueId", "ObjectId"):
                кандидаты.append((эл.text or "").strip())
            for у in кандидаты:
                if not РЕ_UUID.match(у):
                    ош("не uuid: %r в %s" % (у, отн))
                    continue
                у = у.lower()
                if у in виденные and виденные[у] != (отн, id(эл)):
                    ош("uuid %s повторяется: %s и %s" % (у, виденные[у][0], отн))
                виденные.setdefault(у, (отн, id(эл)))

    # 3. ссылки разрешаются (в т.ч. CommonPicture/CommonForm/CommonCommand/StyleItem в формах);
    #    стили style:X — свой элемент стиля или стандартный платформы
    for отн, к in деревья.items():
        for эл in к.iter():
            if not isinstance(эл.tag, str):
                continue
            значения = [(эл.text or "").strip()] + [з for а, з in эл.attrib.items() if а not in ("uuid", "version")]
            for з in значения:
                if not з:
                    continue
                if з.startswith("style:"):
                    имя = з[6:]
                    if имя not in СТИЛИ_ПЛАТФОРМЫ and not модель.есть_объект("StyleItem", имя):
                        ош("элемент стиля %s — нет ни в src_ext, ни среди стандартных (%s)" % (з, отн))
                    continue
                if not РЕ_ПУТЬ.match(з):
                    continue
                if not модель.разрешить(з):
                    ош("битая ссылка %s в %s" % (з, отн))
            if эл.get(XSI + "type") == "xr:DesignTimeRef" and re.match(r"^[0-9a-f-]{36}\.", (эл.text or "").strip()):
                ош("ссылка по uuid (объекта нет) %s в %s" % (эл.text.strip(), отн))
            м = re.match(r"^\d+:([0-9a-f-]{36})$", (эл.text or "").strip()) if лок(эл.tag) == "Command" else None
            if м and м.group(1).lower() not in виденные:
                ош("команда по uuid %s — такого объекта в src_ext нет (%s)" % (эл.text.strip(), отн))

    # 4. состав Configuration.xml = файлы; 5. имена с префиксом
    пк = деревья.get("Configuration.xml")
    if пк is None:
        ош("нет Configuration.xml")
    else:
        заявлено = {(лок(д.tag), д.text) for д in mdo(пк).find(MD + "ChildObjects") if isinstance(д.tag, str)}
        файлы = объекты_снимка(сн)
        for о in sorted(заявлено - файлы):
            ош("в Configuration.xml есть %s.%s, файла нет" % о)
        for о in sorted(файлы - заявлено):
            ош("файл %s.%s не зарегистрирован в Configuration.xml" % о)
        св = mdo(пк).find(MD + "Properties")
        for тег, надо in (("Name", ИМЯ_РАСШИРЕНИЯ), ("NamePrefix", ПРЕФИКС),
                          ("ConfigurationExtensionPurpose", "AddOn"),
                          ("ConfigurationExtensionCompatibilityMode", "Version8_3_24"),
                          ("KeepMappingToExtendedConfigurationObjectsByIDs", "true")):
            if св.findtext(MD + тег) != надо:
                ош("Configuration.xml: %s != %s" % (тег, надо))
        # версия — формат 1С «Р.П.В.С» (четыре числа): её показывает «Расширения конфигурации», по ней покупатель
        # отличает поставку; поставщик заполнен (R02/R03 повторного аудита 28.09.2026)
        версия = св.findtext(MD + "Version") or ""
        if not re.fullmatch(r"\d+\.\d+\.\d+\.\d+", версия):
            ош("Configuration.xml: Version «%s» — нужен формат 1С из четырёх чисел, например 1.0.0.1" % версия)
        if not (св.findtext(MD + "Vendor") or "").strip():
            ош("Configuration.xml: Vendor пуст — поставщик «%s»" % ПОСТАВЩИК)
    for (кл, имя), инфо in модель.объекты.items():
        if not инфо["adopted"] and not имя.startswith(ПРЕФИКС):
            ош("имя без префикса %s: %s.%s" % (ПРЕФИКС, кл, имя))
    for п in модель.подсистемы:
        if not п.split(".")[-1].startswith(ПРЕФИКС):
            ош("подсистема без префикса: %s" % п)
    # 6. регламентные: метод существует
    for (кл, имя), _ in модель.объекты.items():
        if кл == "ScheduledJob":
            к = деревья.get(os.path.join("ScheduledJobs", имя + ".xml"))
            м = к is not None and mdo(к).findtext(MD + "Properties/" + MD + "MethodName")
            if м and not модель.разрешить(м):
                ош("регламентное %s: метод %s не найден" % (имя, м))
    # 7–10. модули BSL
    for отн, т in сн.файлы.items():
        if отн.endswith(".bsl"):
            проверить_bsl(отн, т, модель, ош)
    if not тихо:
        for о in ошибки[:60]:
            print("  ОШИБКА:", о)
        if len(ошибки) > 60:
            print("  ... ещё", len(ошибки) - 60)
    return ошибки


