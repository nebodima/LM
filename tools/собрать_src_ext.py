def часы_в_списке_выбора(т, отн):
    """Урок.ФормаДокумента: список выбора поля КоличествоЧасов — значения-время -> часы числом."""
    нач = т.find('<InputField name="КоличествоЧасов"')
    if нач < 0:
        ЖУРНАЛ["ошибки_сборки"].append("%s: поле КоличествоЧасов не найдено" % отн)
        return т
    кон = т.find("</InputField>", нач)
    кусок = т[нач:кон]

    def зам(м):
        часы = int(м.group(1)) + int(м.group(2)) / 60.0
        return '<Value xsi:type="xs:decimal">%s</Value>' % ("%g" % часы)
    нов, n = re.subn(r'<Value xsi:type="xs:dateTime">0001-01-01T(\d\d):(\d\d):00</Value>', зам, кусок)
    ЖУРНАЛ["часы"].append("%s: список выбора поля КоличествоЧасов — %d значений время -> часы" % (отн, n))
    return т[:нач] + нов + т[кон:]


