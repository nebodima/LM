def применить_правки_кода(т, отн):
    правки = ПРАВКИ_КОДА.get(отн)
    if not правки:
        return т
    строки = т.split("\n")
    for описание, было, стало in правки:
        if было is None:
            строки = list(стало) + строки
            ЖУРНАЛ["правки"].append("%s: %s" % (отн, описание))
            continue
        if isinstance(было, tuple) and было[0] == "тело":      # всё тело процедуры/функции по имени
            нач = [i for i, с in enumerate(строки)
                   if re.match(r"^\s*(?:Процедура|Функция)\s+%s\s*\(" % re.escape(было[1]), с, re.I)]
            if len(нач) != 1:
                ЖУРНАЛ["ошибки_сборки"].append("%s: правка «%s» — процедур %d" % (отн, описание, len(нач)))
                continue
            кон = next((i for i in range(нач[0] + 1, len(строки))
                        if re.match(r"^\s*(?:КонецПроцедуры|КонецФункции)", строки[i])), None)
            if кон is None:
                ЖУРНАЛ["ошибки_сборки"].append("%s: правка «%s» — нет конца процедуры" % (отн, описание))
                continue
            строки[нач[0] + 1:кон] = ["\t//TODO УЗ: " + стало[1]] + ["//" + с for с in строки[нач[0] + 1:кон]]
            ЖУРНАЛ["правки"].append("%s: %s" % (отн, описание))
            continue
        образец = [с.strip() for с in было]
        места = [i for i in range(len(строки) - len(образец) + 1)
                 if all(строки[i + к].strip() == образец[к] for к in range(len(образец)))]
        if len(места) != 1:
            ЖУРНАЛ["ошибки_сборки"].append("%s: правка «%s» — мест %d (нужно ровно 1)" % (отн, описание, len(места)))
            continue
        i = места[0]
        if isinstance(стало, tuple) and стало[0] == "//":
            отступ = re.match(r"[ \t]*", строки[i]).group(0)
            новые = [отступ + "//TODO УЗ: " + стало[1]] + ["//" + с for с in строки[i:i + len(образец)]]
        else:
            новые = list(стало)
        строки[i:i + len(образец)] = новые
        ЖУРНАЛ["правки"].append("%s: %s" % (отн, описание))
    return "\n".join(строки)


def преобразовать_bsl(т, отн):
    """Весь конвейер модуля: правки -> часы -> слой совместимости -> однобуквенные -> переименования."""
    т = применить_правки_кода(т, отн)
    if отн in ЧАСЫ_ФАЙЛЫ:
        т = перевести_часы(т, отн)
    т = слой_совместимости(т, отн)
    т = убрать_однобуквенные(т, отн)
    return переименовать_весь_текст(т, бсл=True)


