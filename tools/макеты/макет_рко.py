class Макет:
    def __init__(self, c):
        self.c = c
        self.тд = c.NewObject("ТабличныйДокумент")
        self.тонкая = c.NewObject("Линия", c.ТипЛинииЯчейкиТабличногоДокумента.Сплошная, 1)
        self.мелкий = c.NewObject("Шрифт", "Arial", 6)
        self.обычный = c.NewObject("Шрифт", "Arial", 8)
        self.жирный = c.NewObject("Шрифт", "Arial", 10, True)
        self.жирный_мелкий = c.NewObject("Шрифт", "Arial", 8, True)

    def обл(self, строка, к1, к2=None, строка2=None):
        к2 = к2 or к1
        строка2 = строка2 or строка
        о = self.тд.Область("R%dC%d:R%dC%d" % (строка, к1, строка2, к2))
        if к2 > к1 or строка2 > строка:
            о.Объединить()
        о.Шрифт = self.обычный
        о.ВертикальноеПоложение = self.c.ВертикальноеПоложение.Центр
        return о

    def текст(self, строка, к1, к2, текст, шрифт=None, положение="Лево", рамка=False, низ=False, перенос=False,
              строка2=None):
        о = self.обл(строка, к1, к2, строка2)
        о.Текст = текст
        if шрифт is not None:
            о.Шрифт = шрифт
        о.ГоризонтальноеПоложение = getattr(self.c.ГоризонтальноеПоложение, положение)
        if перенос:
            о.РазмещениеТекста = self.c.ТипРазмещенияТекстаТабличногоДокумента.Переносить
        if рамка:
            о.Обвести(self.тонкая, self.тонкая, self.тонкая, self.тонкая)
        if низ:
            о.ГраницаСнизу = self.тонкая
        return о

    def параметр(self, строка, к1, к2, имя, **кв):
        о = self.текст(строка, к1, к2, "", **кв)
        о.Заполнение = self.c.ТипЗаполненияОбластиТабличногоДокумента.Параметр
        о.Параметр = имя
        return о


