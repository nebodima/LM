def главный():
    import win32com.client
    sys.stdout.reconfigure(encoding="utf-8")
    база = r"C:\1c_bases\UZ_UNF_C"
    for а in sys.argv[1:]:
        if а.startswith("--база="):
            база = а.split("=", 1)[1]
    н = time.time()
    c = платформа.коннектор().Connect('File="%s";Usr="Администратор";' % база)
    тд = построить(c)
    запись = c.NewObject("ЗаписьXML")
    запись.УстановитьСтроку("UTF-8")
    c.СериализаторXDTO.ЗаписатьXML(запись, тд)
    текст = запись.Закрыть()
    # сериализатор пишет корень <SpreadsheetDocument …>, выгрузка конфигурации — <document …>
    import re
    текст = re.sub(r"^<\?xml[^>]*\?>\s*", "", текст)
    м = re.match(r"<(\w+)", текст)
    if м and м.group(1) != "document":
        корень = м.group(1)
        текст = "<document" + текст[len(корень) + 1:]
        текст = re.sub(r"</%s>\s*$" % корень, "</document>", текст)
    # тексты, заданные через COM, сериализуются с языком «#»; макет конфигурации без
    # languageSettings и с «#» загружается, но тексты ячеек теряет — как у рукописного XML.
    # Приводим к виду выгрузки конфигурации (как макет ПКО): язык ru и блок languageSettings.
    текст = текст.replace("<v8:lang>#</v8:lang>", "<v8:lang>ru</v8:lang>")
    if "<languageSettings>" not in текст:
        поз = текст.index(">") + 1
        текст = (текст[:поз] + "\n\t<languageSettings>\n\t\t<currentLanguage>ru</currentLanguage>\n"
                 "\t\t<defaultLanguage>ru</defaultLanguage>\n\t\t<languageInfo>\n\t\t\t<id>ru</id>\n"
                 "\t\t\t<code>Русский</code>\n\t\t\t<description>Русский</description>\n\t\t</languageInfo>\n"
                 "\t</languageSettings>" + текст[поз:])
    os.makedirs(os.path.dirname(ЦЕЛЬ), exist_ok=True)
    with open(ЦЕЛЬ, "w", encoding="utf-8-sig", newline="\n") as ф:
        ф.write('<?xml version="1.0" encoding="UTF-8"?>\n' + текст)
    print("макет КО-2: %s (%d символов, %.1f с)" % (ЦЕЛЬ, len(текст), time.time() - н))


if __name__ == "__main__":
    главный()
