class Лист:
    """Строки одной области: ячейки ставятся по колонкам 1..40."""

    def __init__(self):
        self.строки = []

    def строка(self, высота=None, ячейки=None):
        с = {"cells": ячейки or []}
        if высота:
            с["height"] = высота
        self.строки.append(с)
        return с["cells"]

    def пусто(self, высота=None):
        self.строка(высота)


def текст(кол, т, до=None, стиль="подпись"):
    я = {"col": кол, "text": т, "style": стиль}
    if до and до > кол:
        я["span"] = до - кол + 1
    return я


def клетки(кол, имя, с=1, по=None, стиль="клетка"):
    """Знакоместа имя_с … имя_по с колонки кол подряд."""
    по = по or ПОЛЯ[имя]
    return [{"col": кол + i, "param": "%s_%d" % (имя, с + i), "style": стиль} for i in range(по - с + 1)]


def дата(кол, имя):
    """ДД.ММ.ГГГГ: 2 клетки, точка, 2 клетки, точка, 4 клетки (п. 13)."""
    return (клетки(кол, имя, 1, 2) + [текст(кол + 2, ".", стиль="точка")] + клетки(кол + 3, имя, 3, 4)
            + [текст(кол + 5, ".", стиль="точка")] + клетки(кол + 6, имя, 5, 8))


def шапка_страницы(л, номер):
    """ИНН, КПП организации и «Стр.» — верх каждой страницы (п. 15–17)."""
    л.строка(20, [текст(9, "ИНН", 11, "подпись_право")] + клетки(12, "ИНН"))
    л.пусто(4)
    л.строка(20, [текст(9, "КПП", 11, "подпись_право")] + клетки(12, "КПП")
             + [текст(22, "Стр.", 24, "подпись_право")]
             + [текст(25 + i, ч, стиль="клетка") for i, ч in enumerate("%03d" % номер)])


def физлицо(л):
    """Фамилия, имя, отчество, ИНН, дата рождения и документ — налогоплательщика (стр. 1) и обучаемого (стр. 2)."""
    for подпись, имя in (("Фамилия", "Фамилия"), ("Имя", "Имя"), ("Отчество", "Отчество")):
        л.строка(20, [текст(1, подпись, 5)] + клетки(6, имя))
        л.пусто(4)
    л.строка(20, [текст(1, "ИНН²", 5)] + клетки(6, "ИННФизЛица") + [текст(20, "Дата рождения", 27, "подпись_право")]
             + дата(29, "ДатаРождения"))
    л.пусто(6)
    л.строка(16, [текст(1, "Сведения о документе, удостоверяющем личность:", 40)])
    л.строка(20, [текст(1, "Код вида документа", 7)] + клетки(8, "КодДокумента")
             + [текст(12, "Серия и номер", 20, "подпись_право")] + клетки(21, "СерияНомер"))
    л.пусто(4)
    л.строка(20, [текст(1, "Дата выдачи", 7)] + дата(8, "ДатаВыдачи"))


