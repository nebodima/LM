class _Тройник(io.TextIOBase):
    """Пишет и в журнал базы, и в буфер текущего теста (из буфера берём строки ошибок для сводки)."""
    def __init__(self, основной):
        self.основной = основной
        self.буфер = io.StringIO()

    def write(self, текст):
        self.основной.write(текст)
        self.буфер.write(текст)
        return len(текст)

    def flush(self):
        self.основной.flush()


def _строки_ошибок(текст, сколько=6):
    return [с.rstrip() for с in текст.splitlines() if re.search(r"ОШИБКА|FAIL|САМОТЕСТ", с)][:сколько]


def _замок(база):
    """Замок базы (общий с деплоем): байт 0 файла %TEMP%\\уз_прогон\\c_1c_bases_uz_unf_d.lock, пока жив процесс.
    None — занято."""
    import msvcrt
    os.makedirs(ЖУРНАЛЫ, exist_ok=True)
    ф = open(os.path.join(ЖУРНАЛЫ, отпечаток_src.имя_базы(база) + ".lock"), "a+")
    ф.seek(0)
    try:
        msvcrt.locking(ф.fileno(), msvcrt.LK_NBLCK, 1)
    except OSError:
        ф.close()
        return None
    return ф


class _Ожидание:
    """Сколько процесс базы ждал занятую базу — пишется в файл рядом с журналом: родитель продлевает на
    столько таймаут и печатает ожидание в итоге (бюджет не съедается молча)."""
    def __init__(self, файл):
        self.файл, self.сек = файл, 0.0

    def ждать(self, сек, причина):
        print("  ожидание: %s — жду %d с (всего ждали %.0f с)" % (причина, сек, self.сек), flush=True)
        time.sleep(сек)
        self.сек += сек
        if self.файл:
            with open(self.файл, "w", encoding="utf-8") as ф:
                ф.write("%.1f" % self.сек)


