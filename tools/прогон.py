"""Единый прогон COM-тестов и проверки запросов УЗ_ext: один процесс и ОДНО COM-подключение на базу,
в нём все тесты tools\\тесты\\тест_*.py по очереди (функция сценарий(т)) и проверка текстов запросов
(tools\\проверка_запросов.py). Базы идут параллельно — отдельными процессами (COM в разных процессах
независим).

    python tools\\прогон.py                              — УНФ, БП, УТ
    python tools\\прогон.py --базы=УНФ,БП                — выбранные базы стенда
    python tools\\прогон.py --тест=печать                — один тест (имя без «тест_»; «запросы» — проверка запросов)
    python tools\\прогон.py --база=C:\\1c_bases\\UZ_UNF_A --пользователь=Администратор   — своя копия
    python tools\\прогон.py --подробно                   — полный вывод тестов, не только ошибки
    python tools\\прогон.py --копии=_E                   — те же три базы на своих копиях UZ_UNF_E, UZ_BP_E, UZ_UT_E
    python tools\\прогон.py --без-сверки                 — не сверять расширение в базе с src_ext (печатается)

Бюджеты: сценарий теста ≤ 10 с (ПРЕДУПРЕЖДЕНИЕ), весь прогон трёх баз ≤ 45 с (цель).
Подключение (~6–8 с к файловой базе) печатается отдельно. Жёсткий таймаут процесса базы — 3× бюджета
прогона (135 с) плюс напечатанное ожидание занятой базы: зависший COM-сеанс снимается, база — «ТАЙМАУТ».
Замок на базу (%TEMP%\\уз_прогон\\c_1c_bases_uz_unf_d.lock для UZ_UNF_D) общий с деплоем: прогон и деплой в одну базу одновременно
не идут — прогон ждёт до 3 мин и печатает ожидание (оно вне бюджета, но видно в итоге).
В начале прогон сверяет, что в базе расширение из этого src_ext (отпечаток_src.py: отметка деплоя и
ХешСумма УЗ_ext) — иначе строка «расширение» красная: зелёный прогон по старому коду не выдаётся за проверку.
Тест аудит_данных идёт последним: после уборки всех тестов сирот и битых ссылок быть не должно.
Тест без единой проверки — провал. Журналы — %TEMP%\\уз_прогон\\УНФ.log (своя копия — СВОЯ_UZ_UNF_D.log).
Код выхода: 0 — всё зелёное, 1 — есть провалы.
"""
