"""Единый прогон COM-тестов и проверки запросов УЗ_ext: один процесс и ОДНО COM-подключение на базу,
в нём все тесты tools\\тесты\\тест_*.py по очереди (функция сценарий(т)) и проверка текстов запросов
(tools\\проверка_запросов.py). Базы идут параллельно — отдельными процессами (COM в разных процессах
независим).

    python tools\\прогон.py                              — УНФ, БП, УТ
    python tools\\прогон.py --базы=УНФ,БП                — выбранные базы стенда
    python tools\\прогон.py --тест=печать                — один тест (имя без «тест_»; «запросы» — проверка запросов)
    python tools\\прогон.py --база=C:\\1c_bases\\UZ_UNF_A --пользователь=Администратор   — своя копия
    python tools\\прогон.py --подробно                   — полный вывод тестов, не только ошибки

Бюджеты: сценарий теста ≤ 10 с (ПРЕДУПРЕЖДЕНИЕ), весь прогон трёх баз ≤ 45 с (цель).
Подключение (~6–8 с к файловой базе) печатается отдельно. Два прогона в одну базу одновременно не
пускаются (замок-файл на базу). Полные журналы баз — %TEMP%\\уз_прогон\\<база>.log.
Код выхода: 0 — всё зелёное, 1 — есть провалы.
"""
import contextlib
import glob
import importlib
import io
import json
import os
import re
import subprocess
import sys
import tempfile
import time

sys.dont_write_bytecode = True   # __pycache__ частично лежит в git — прогон не должен пачкать рабочую копию
ПАПКА = os.path.dirname(os.path.abspath(__file__))
ТЕСТЫ = os.path.join(ПАПКА, "тесты")
sys.path.insert(0, ТЕСТЫ)
sys.path.insert(0, ПАПКА)
import сеанс  # noqa: E402

СТЕНД = {
    "УНФ": (r"C:\1c_bases\UZ_UNF", "Администратор"),
    "БП": (r"C:\1c_bases\UZ_BP", "1"),
    "УТ": (r"C:\1c_bases\UZ_UT", "Admin"),
}
БЮДЖЕТ_ТЕСТА = сеанс.БЮДЖЕТ_СЕК
БЮДЖЕТ_ПРОГОНА = 45
ЖУРНАЛЫ = os.path.join(tempfile.gettempdir(), "уз_прогон")
ПОПЫТОК_ПОДКЛЮЧЕНИЯ = 3
ПАУЗА_ПРИ_БЛОКИРОВКЕ = 60


# ───────────────────────── дочерний процесс: одна база ─────────────────────────

class _Тройник(io.TextIOBase):
    """Пишет и в журнал базы, и в буфер текущего теста (из буфера берём строки ошибок для сводки)."""
    def __init__(self, основной):
        self.основной = основной
        self.буфер = io.StringIO()

    def write(self, текст):
        self.основной.write(текст)
        self.буфер.write(текст)
        return len(текст)

    def flush(self):
        self.основной.flush()


def _строки_ошибок(текст, сколько=6):
    return [с.rstrip() for с in текст.splitlines() if re.search(r"ОШИБКА|FAIL|САМОТЕСТ", с)][:сколько]


def _замок(база):
    """Не пускаем второй прогон в ту же базу: блокировка файла держится, пока жив процесс."""
    import msvcrt
    os.makedirs(ЖУРНАЛЫ, exist_ok=True)
    имя = re.sub(r"[^\w]+", "_", os.path.normcase(os.path.abspath(база))).strip("_")
    ф = open(os.path.join(ЖУРНАЛЫ, имя + ".lock"), "a+")
    try:
        msvcrt.locking(ф.fileno(), msvcrt.LK_NBLCK, 1)
    except OSError:
        ф.close()
        return None
    return ф


def _подключить(база, пользователь):
    """Подключение; если базу держит конфигуратор (грузят расширение) — ждём минуту, до 3 попыток."""
    for попытка in range(1, ПОПЫТОК_ПОДКЛЮЧЕНИЯ + 1):
        try:
            return сеанс.подключить(база, пользователь)
        except Exception as е:
            текст = сеанс.текст_ошибки(е)
            блокировка = re.search(r"блокир|монопольн|заблокир|используется|lock", текст, re.I)
            if not блокировка or попытка == ПОПЫТОК_ПОДКЛЮЧЕНИЯ:
                raise
            print("подключение: база занята (%s) — жду %d с, попытка %d из %d"
                  % (текст[:150], ПАУЗА_ПРИ_БЛОКИРОВКЕ, попытка, ПОПЫТОК_ПОДКЛЮЧЕНИЯ), flush=True)
            time.sleep(ПАУЗА_ПРИ_БЛОКИРОВКЕ)


def _тесты(фильтр):
    имена = [os.path.splitext(os.path.basename(п))[0][len("тест_"):]
             for п in sorted(glob.glob(os.path.join(ТЕСТЫ, "тест_*.py")))]
    if фильтр:
        имена = [и for и in имена if и == фильтр.replace("тест_", "", 1)]
    return имена


def прогнать_базу(имя, база, пользователь, фильтр, файл_итога):
    """Все тесты и проверка запросов в одном COM-сеансе. Итог — JSON в файл_итога."""
    сеанс.настроить_вывод()
    итог = {"база": имя, "путь": база, "подключение": 0.0, "тесты": [], "ошибка": ""}
    начало = time.time()
    замок = _замок(база)
    try:
        if замок is None:
            итог["ошибка"] = "в базу %s уже идёт другой прогон — второй не запускаю" % база
            return итог
        try:
            c, итог["подключение"] = _подключить(база, пользователь)
        except Exception as е:
            итог["ошибка"] = "подключение: %s" % сеанс.текст_ошибки(е)
            return итог
        print("== база %s (%s), подключение %.1f с" % (имя, база, итог["подключение"]), flush=True)

        настоящий = sys.stdout
        for тест in _тесты(фильтр):
            тройник = _Тройник(настоящий)
            with contextlib.redirect_stdout(тройник):
                т = None
                try:
                    модуль = importlib.import_module("тест_" + тест)
                    т = сеанс.Тест(тест, c=c, база=база)
                    т.выполнить(модуль.сценарий)
                    код = т.итог()
                except Exception as е:        # тест не импортировался / не создался — следующие идут
                    print("  ОШИБКА тест %s не запущен: %s" % (тест, сеанс.текст_ошибки(е)))
                    код = 1
            итог["тесты"].append({"имя": тест, "код": код, "сек": round(т.сек if т else 0.0, 2),
                                  "проверок": т.проверок if т else 0,
                                  "ошибки": _строки_ошибок(тройник.буфер.getvalue()) if код else []})

        if not фильтр or фильтр == "запросы":
            import проверка_запросов as пз
            тройник = _Тройник(настоящий)
            н = time.time()
            with contextlib.redirect_stdout(тройник):
                print("== проверка запросов")
                try:
                    тексты = пз.тексты_запросов()
                    поймано, ошибки = пз.проверить_соединение(c, тексты)
                    if поймано != len(пз.САМОТЕСТ):
                        print("  САМОТЕСТ НЕ ПРОЙДЕН: поймано %d из %d — проверке не доверять"
                              % (поймано, len(пз.САМОТЕСТ)))
                    for место, о in ошибки:
                        print("  ОШИБКА %s: %s" % (место, о))
                    код = 1 if ошибки or поймано != len(пз.САМОТЕСТ) else 0
                    print("== запросы: текстов %d, самотест %d из %d, ошибок %d"
                          % (len(тексты), поймано, len(пз.САМОТЕСТ), len(ошибки)))
                    проверок = len(тексты)
                except Exception as е:
                    print("  ОШИБКА проверка запросов упала: %s" % сеанс.текст_ошибки(е))
                    код, проверок = 1, 0
            итог["тесты"].append({"имя": "запросы", "код": код, "сек": round(time.time() - н, 2),
                                  "проверок": проверок,
                                  "ошибки": _строки_ошибок(тройник.буфер.getvalue()) if код else []})
        return итог
    finally:
        итог["всего"] = round(time.time() - начало, 2)
        with open(файл_итога, "w", encoding="utf-8") as ф:
            json.dump(итог, ф, ensure_ascii=False)
        if замок is not None:
            замок.close()


# ───────────────────────── родитель: базы параллельно, сводка ─────────────────────────

def _базы_из_аргументов():
    своя = сеанс.аргумент("база")
    if своя:
        return [("СВОЯ", своя, сеанс.аргумент("пользователь", сеанс.ПОЛЬЗОВАТЕЛЬ_ПО_УМОЛЧАНИЮ))]
    имена = [и.strip() for и in сеанс.аргумент("базы", ",".join(СТЕНД)).split(",") if и.strip()]
    неизвестные = [и for и in имена if и not in СТЕНД]
    if неизвестные:
        sys.exit("неизвестные базы: %s (есть %s)" % (", ".join(неизвестные), ", ".join(СТЕНД)))
    return [(и,) + СТЕНД[и] for и in имена]


def main():
    сеанс.настроить_вывод()
    if сеанс.аргумент("дочерний"):
        итог = прогнать_базу(сеанс.аргумент("дочерний"), сеанс.аргумент("база"), сеанс.аргумент("пользователь"),
                             сеанс.аргумент("тест", ""), сеанс.аргумент("итог"))
        return 1 if итог["ошибка"] or any(т["код"] for т in итог["тесты"]) else 0

    фильтр = сеанс.аргумент("тест", "")
    if фильтр and фильтр != "запросы" and not _тесты(фильтр):
        sys.exit("нет теста %s (есть: %s, запросы)" % (фильтр, ", ".join(_тесты(""))))
    подробно = "--подробно" in sys.argv
    базы = _базы_из_аргументов()
    os.makedirs(ЖУРНАЛЫ, exist_ok=True)
    начало = time.time()
    процессы = []
    for имя, база, пользователь in базы:
        журнал = os.path.join(ЖУРНАЛЫ, имя + ".log")
        файл_итога = os.path.join(ЖУРНАЛЫ, имя + ".json")
        if os.path.exists(файл_итога):
            os.remove(файл_итога)
        аргументы = [sys.executable, os.path.abspath(__file__), "--дочерний=" + имя, "--база=" + база,
                     "--пользователь=" + пользователь, "--итог=" + файл_итога]
        if фильтр:
            аргументы.append("--тест=" + фильтр)
        поток = open(журнал, "w", encoding="utf-8")
        окружение = dict(os.environ, PYTHONIOENCODING="utf-8")
        процессы.append((имя, журнал, файл_итога, поток,
                         subprocess.Popen(аргументы, stdout=поток, stderr=subprocess.STDOUT, env=окружение)))

    провалов = 0
    for имя, журнал, файл_итога, поток, процесс in процессы:
        процесс.wait()
        поток.close()
        if подробно:
            print(open(журнал, encoding="utf-8").read())
        try:
            итог = json.load(open(файл_итога, encoding="utf-8"))
        except Exception:
            провалов += 1
            print("%-4s ПРОЦЕСС УПАЛ (код %s), журнал %s" % (имя, процесс.returncode, журнал))
            for с in open(журнал, encoding="utf-8", errors="replace").read().splitlines()[-8:]:
                print("       " + с)
            continue
        if итог["ошибка"]:
            провалов += 1
            print("%-4s ОШИБКА %s" % (имя, итог["ошибка"]))
            continue
        print("%-4s подключение %.1f с" % (имя, итог["подключение"]))
        сценарии = 0.0
        провалов_базы = 0
        for т in итог["тесты"]:
            сценарии += т["сек"]
            метка = "  ПРЕДУПРЕЖДЕНИЕ: бюджет %d с" % БЮДЖЕТ_ТЕСТА if т["сек"] > БЮДЖЕТ_ТЕСТА else ""
            print("%-4s %-16s код %d  %5.1f с  проверок %3d%s"
                  % (имя, т["имя"], т["код"], т["сек"], т["проверок"], метка))
            if т["код"]:
                провалов_базы += 1
                for с in т["ошибки"]:
                    print("       " + с.strip())
        провалов += провалов_базы
        print("%-4s итог: провалов %d из %d, сценарии %.1f с, процесс %.1f с%s"
              % (имя, провалов_базы, len(итог["тесты"]), сценарии, итог["всего"],
                 ("  журнал " + журнал) if провалов_базы else ""))
    всего = time.time() - начало
    метка = "  ПРЕДУПРЕЖДЕНИЕ: цель %d с превышена" % БЮДЖЕТ_ПРОГОНА if всего > БЮДЖЕТ_ПРОГОНА else ""
    print("ИТОГО: баз %d, провалов %d, время %.1f с (цель ≤ %d с)%s"
          % (len(базы), провалов, всего, БЮДЖЕТ_ПРОГОНА, метка))
    return 1 if провалов else 0


if __name__ == "__main__":
    sys.exit(main())
