def _процессов_1с():
    """Клиенты 1С на машине сейчас: процессы 1cv8* и процессы баз других прогонов (COM-сеанс внутри python)."""
    import psutil
    итог = 0
    for п in psutil.process_iter(["name", "cmdline"]):
        имя = (п.info["name"] or "").lower()
        if имя.startswith("1cv8"):
            итог += 1
        elif имя.startswith("python") and any(а.startswith("--дочерний=") for а in (п.info["cmdline"] or [])):
            итог += 1
    return итог


