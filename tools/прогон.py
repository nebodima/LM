def _базы_из_аргументов():
    своя = сеанс.аргумент("база")
    if своя:
        return [("СВОЯ", своя, сеанс.аргумент("пользователь", сеанс.ПОЛЬЗОВАТЕЛЬ_ПО_УМОЛЧАНИЮ))]
    имена = [и.strip() for и in сеанс.аргумент("базы", ",".join(СТЕНД)).split(",") if и.strip()]
    неизвестные = [и for и in имена if и not in СТЕНД]
    if неизвестные:
        sys.exit("неизвестные базы: %s (есть %s)" % (", ".join(неизвестные), ", ".join(СТЕНД)))
    копии = сеанс.аргумент("копии", "")   # --копии=_E → C:\1c_bases\UZ_UNF_E, UZ_BP_E, UZ_UT_E (свои копии стенда)
    return [(и, СТЕНД[и][0] + копии, СТЕНД[и][1]) for и in имена]


def main():
    сеанс.настроить_вывод()
    if сеанс.аргумент("дочерний"):
        список = сеанс.аргумент("тесты")
        итог = прогнать_базу(сеанс.аргумент("дочерний"), сеанс.аргумент("база"), сеанс.аргумент("пользователь"),
                             сеанс.аргумент("тест", ""), сеанс.аргумент("итог"), сеанс.аргумент("src"),
                             сеанс.аргумент("ожидание"), список.split(",") if список else None,
                             "--без-запросов" not in sys.argv)
        return 1 if итог["ошибка"] or any(т["код"] for т in итог["тесты"]) else 0

    фильтр = сеанс.аргумент("тест", "")
    if фильтр and фильтр != "запросы" and not _тесты(фильтр):
        sys.exit("нет теста %s (есть: %s, запросы)" % (фильтр, ", ".join(_тесты(""))))
    подробно = "--подробно" in sys.argv
    базы = _базы_из_аргументов()
    os.makedirs(ЖУРНАЛЫ, exist_ok=True)
    начало = time.time()
    # сверка «в базе то, что в src_ext»: --без-сверки — осознанный прогон по чужому коду (печатается)
    src = "-" if "--без-сверки" in sys.argv else отпечаток_src.отпечаток()
    print("src_ext: %s (%.2f с)%s" % (src, time.time() - начало,
                                      "  — СВЕРКА С БАЗОЙ ВЫКЛЮЧЕНА (--без-сверки)" if src == "-" else ""))
    # двойники: весь набор тестов (без --тест) делится на основную базу и её копию — если хватает лицензий
    двойники = not фильтр and "--без-двойников" not in sys.argv
    ожидание_родителя = _Ожидание(None)
    с_двойником = set()
    if двойники:
        # двойников столько, сколько влезает в предел клиентов 1С (остальные базы — одним процессом)
        клиентов = _процессов_1с()
        влезает = max(0, min(len(базы), ПРЕДЕЛ_КЛИЕНТОВ_1С - клиентов - len(базы)))
        с_двойником = {имя for имя, _, _ in базы[:влезает]}
        if влезает < len(базы):
            print("ПРЕДУПРЕЖДЕНИЕ: клиентов 1С на машине %d (1cv8 и базы других прогонов) + процессов прогона %d > "
                  "предела %d (лицензии/ключ защиты) — двойники только у %d баз из %d, прогон дольше. "
                  "Висящие агенты: tools\\агенты.ps1" % (клиентов, 2 * len(базы), ПРЕДЕЛ_КЛИЕНТОВ_1С, влезает, len(базы)))
    история = _история()
    # двойники всех баз обновляются одновременно (копия УТ 6,7 ГБ — до 3 с, остальные меньше)
    состояние_двойников = {}
    if с_двойником:
        from concurrent.futures import ThreadPoolExecutor
        with ThreadPoolExecutor(len(с_двойником)) as пул:
            будущие = {имя: пул.submit(обновить_двойник, база, os.path.normpath(база) + ДВОЙНИК, ожидание_родителя)
                       for имя, база, _ in базы if имя in с_двойником}
        for имя in будущие:
            состояние_двойников[имя] = будущие[имя].result()
            print("%-4s %s" % (имя, состояние_двойников[имя][1]))
    задания = []          # (метка, база, пользователь, файл журнала, список тестов или None, проверять запросы, ключ истории)
    for имя, база, пользователь in базы:
        # своя копия: имя журнала по папке базы — прогоны разных копий из разных сессий не затирают друг друга
        файл = (имя + сеанс.аргумент("копии", "")) if имя != "СВОЯ" else "СВОЯ_" + os.path.basename(os.path.normpath(база))
        готов = состояние_двойников.get(имя, (False, ""))[0]
        двойник = os.path.normpath(база) + ДВОЙНИК
        if готов:
            # нет своей истории (первый прогон этой базы) — история той же конфигурации с другой копии, иначе прикидка
            время = история.get(файл) or next((в for к, в in история.items() if к.split("_")[0] == имя), None) or ПРИКИДКА
            основная, вторая = разделить(_тесты(""), время)
            задания.append((имя, база, пользователь, файл, основная, True, файл))
            задания.append((имя + ДВОЙНИК, двойник, пользователь, файл + ДВОЙНИК, вторая, False, файл))
        else:
            задания.append((имя, база, пользователь, файл, None, True, файл))
    процессы = []
    for имя, база, пользователь, файл, список, запросы, _ in задания:
        журнал = os.path.join(ЖУРНАЛЫ, файл + ".log")
        файл_итога = os.path.join(ЖУРНАЛЫ, файл + ".json")
        файл_ожидания = os.path.join(ЖУРНАЛЫ, файл + ".ожидание")
        for старый in (файл_итога, файл_ожидания):
            if os.path.exists(старый):
                os.remove(старый)
        аргументы = [sys.executable, os.path.abspath(__file__), "--дочерний=" + имя, "--база=" + база,
                     "--пользователь=" + пользователь, "--итог=" + файл_итога, "--src=" + src,
                     "--ожидание=" + файл_ожидания]
        if фильтр:
            аргументы.append("--тест=" + фильтр)
        if список is not None:
            аргументы.append("--тесты=" + ",".join(список))
        if not запросы:
            аргументы.append("--без-запросов")
        if "--все-ядра" in sys.argv:
            аргументы.append("--все-ядра")
        поток = open(журнал, "w", encoding="utf-8")
        окружение = dict(os.environ, PYTHONIOENCODING="utf-8")
        процессы.append((имя, журнал, файл_итога, поток,
                         subprocess.Popen(аргументы, stdout=поток, stderr=subprocess.STDOUT, env=окружение),
                         файл_ожидания))

    # жёсткий таймаут: 3× бюджета прогона + сколько процесс базы честно прождал занятую базу;
    # --таймаут=сек — только для проверки самого таймаута (мутация: --таймаут=3 обязан дать «ТАЙМАУТ»)
    таймаут = int(сеанс.аргумент("таймаут", ТАЙМАУТ))
    таймауты = set()
    while any(п.poll() is None for _, _, _, _, п, _ in процессы):
        for имя, _, _, _, процесс, файл_ожидания in процессы:
            if процесс.poll() is not None:
                continue
            try:
                ждали = float(open(файл_ожидания, encoding="utf-8").read())
            except (OSError, ValueError):
                ждали = 0.0
            if time.time() - начало > таймаут + ждали + ожидание_родителя.сек:
                процесс.kill()
                таймауты.add(имя)
        time.sleep(0.5)

    провалов = 0
    новая_история = {}
    for имя, журнал, файл_итога, поток, процесс, _ in процессы:
        поток.close()
        if имя in таймауты:
            провалов += 1
            print("%-6s ТАЙМАУТ: процесс базы снят через %.0f с (предел %d с = 3× бюджета + ожидание базы), "
                  "журнал %s" % (имя, time.time() - начало, таймаут, журнал))
            for с in open(журнал, encoding="utf-8", errors="replace").read().splitlines()[-8:]:
                print("       " + с)
            continue
        if подробно:
            print(open(журнал, encoding="utf-8").read())
        try:
            итог = json.load(open(файл_итога, encoding="utf-8"))
        except Exception:
            провалов += 1
            print("%-6s ПРОЦЕСС УПАЛ (код %s), журнал %s" % (имя, процесс.returncode, журнал))
            for с in open(журнал, encoding="utf-8", errors="replace").read().splitlines()[-8:]:
                print("       " + с)
            continue
        if итог["ошибка"]:
            провалов += 1
            print("%-6s ОШИБКА %s" % (имя, итог["ошибка"]))
            continue
        print("%-6s подключение %.1f с%s" % (имя, итог["подключение"],
                                             "; ожидание занятой базы %.0f с (вне бюджета)" % итог["ожидание"]
                                             if итог["ожидание"] else ""))
        сценарии = 0.0
        провалов_базы = 0
        for т in итог["тесты"]:
            сценарии += т["сек"]
            метка = "  ПРЕДУПРЕЖДЕНИЕ: бюджет %d с" % БЮДЖЕТ_ТЕСТА if т["сек"] > БЮДЖЕТ_ТЕСТА else ""
            print("%-6s %-16s код %d  %5.1f с  проверок %3d%s"
                  % (имя, т["имя"], т["код"], т["сек"], т["проверок"], метка))
            if т["проверок"] == 0 and т["имя"] != "расширение" and not т["код"]:
                т["код"] = 1
                т["ошибки"] = ["ОШИБКА тест без единой проверки — вышел раньше, чем что-то проверил"]
                print("       тест без единой проверки считается проваленным")
            if т["код"]:
                провалов_базы += 1
                for с in т["ошибки"]:
                    print("       " + с.strip())
        провалов += провалов_базы
        print("%-6s итог: провалов %d из %d, сценарии %.1f с, процесс %.1f с%s"
              % (имя, провалов_базы, len(итог["тесты"]), сценарии, итог["всего"],
                 ("  журнал " + журнал) if провалов_базы else ""))
        # полное время тестов (с подключениями сотрудников и контролем сирот) — для деления на группы в следующий раз
        ключ = next(з[6] for з in задания if з[0] == имя)
        время = новая_история.setdefault(ключ, dict(история.get(ключ, {})))
        for т in итог["тесты"]:
            if "полное" in т:       # сглаживание: время теста скачет от соседей по машине, деление не должно дёргаться
                было = история.get(ключ, {}).get(т["имя"])
                время[т["имя"]] = round((было + т["полное"]) / 2 if было else т["полное"], 2)
    if новая_история:
        try:
            with open(ИСТОРИЯ, "w", encoding="utf-8") as ф:
                json.dump(dict(история, **новая_история), ф, ensure_ascii=False, indent=1)
        except OSError:
            pass
    всего = time.time() - начало
    ждали = ожидание_родителя.сек
    for _, _, файл_итога, _, _, _ in процессы:
        try:
            ждали = max(ждали, json.load(open(файл_итога, encoding="utf-8")).get("ожидание", 0.0))
        except (OSError, ValueError):
            continue
    метка = "  ПРЕДУПРЕЖДЕНИЕ: цель %d с превышена" % БЮДЖЕТ_ПРОГОНА if всего - ждали > БЮДЖЕТ_ПРОГОНА else ""
    print("ИТОГО: баз %d (процессов %d%s), провалов %d, время %.1f с%s (цель ≤ %d с)%s"
          % (len(базы), len(процессы), ", с двойниками" if len(процессы) > len(базы) else "", провалов, всего,
             ", из них ожидание занятой базы %.0f с" % ждали if ждали else "", БЮДЖЕТ_ПРОГОНА, метка))
    return 1 if провалов else 0


if __name__ == "__main__":
    sys.exit(main())
