# ───────────────────────── дочерний процесс: одна база ─────────────────────────

class _Тройник(io.TextIOBase):
    """Пишет и в журнал базы, и в буфер текущего теста (из буфера берём строки ошибок для сводки)."""
    def __init__(self, основной):
        self.основной = основной
        self.буфер = io.StringIO()

    def write(self, текст):
        self.основной.write(текст)
        self.буфер.write(текст)
        return len(текст)

    def flush(self):
        self.основной.flush()


def _строки_ошибок(текст, сколько=6):
    return [с.rstrip() for с in текст.splitlines() if re.search(r"ОШИБКА|FAIL|САМОТЕСТ", с)][:сколько]


def _замок(база):
    """Замок базы (общий с деплоем): байт 0 файла %TEMP%\\уз_прогон\\c_1c_bases_uz_unf_d.lock, пока жив процесс.
    None — занято."""
    import msvcrt
    os.makedirs(ЖУРНАЛЫ, exist_ok=True)
    ф = open(os.path.join(ЖУРНАЛЫ, отпечаток_src.имя_базы(база) + ".lock"), "a+")
    ф.seek(0)
    try:
        msvcrt.locking(ф.fileno(), msvcrt.LK_NBLCK, 1)
    except OSError:
        ф.close()
        return None
    return ф


class _Ожидание:
    """Сколько процесс базы ждал занятую базу — пишется в файл рядом с журналом: родитель продлевает на
    столько таймаут и печатает ожидание в итоге (бюджет не съедается молча)."""
    def __init__(self, файл):
        self.файл, self.сек = файл, 0.0

    def ждать(self, сек, причина):
        print("  ожидание: %s — жду %d с (всего ждали %.0f с)" % (причина, сек, self.сек), flush=True)
        time.sleep(сек)
        self.сек += сек
        if self.файл:
            with open(self.файл, "w", encoding="utf-8") as ф:
                ф.write("%.1f" % self.сек)


def _взять_замок(база, ожидание):
    срок = time.time() + ЖДАТЬ_ЗАМОК
    while True:
        замок = _замок(база)
        if замок is not None or time.time() > срок:
            return замок
        ожидание.ждать(5, "базу держит деплой или другой прогон (замок %s.lock)" % отпечаток_src.имя_базы(база))


def _подключить(база, пользователь, ожидание):
    """Подключение; если базу держит конфигуратор мимо замка (ручной запуск) — ждём по 10 с, до 12 попыток."""
    for попытка in range(1, ПОПЫТОК_ПОДКЛЮЧЕНИЯ + 1):
        try:
            return сеанс.подключить(база, пользователь)
        except Exception as е:
            текст = сеанс.текст_ошибки(е)
            блокировка = re.search(r"блокир|монопольн|заблокир|используется|lock", текст, re.I)
            if not блокировка or попытка == ПОПЫТОК_ПОДКЛЮЧЕНИЯ:
                raise
            ожидание.ждать(ПАУЗА_ПРИ_БЛОКИРОВКЕ, "база занята при подключении (%s), попытка %d из %d"
                           % (текст[:120], попытка, ПОПЫТОК_ПОДКЛЮЧЕНИЯ))


def _сверить_расширение(c, база):
    """[строки ошибок] — в базе ли расширение из этого src_ext (отпечаток_src.сверить)."""
    хеш = None
    for р in c.РасширенияКонфигурации.Получить():
        if р.Имя == "УЗ_ext":
            хеш = c.Base64Строка(р.ХешСумма)
            print("  расширение УЗ_ext в базе: версия %s, ХешСумма %s" % (р.Версия, хеш))
    if хеш is None:
        return ["ОШИБКА в базе нет расширения УЗ_ext"]
    ошибка, строка = отпечаток_src.сверить(база, хеш)
    if ошибка:
        return ["ОШИБКА " + ошибка]
    print("  ок    " + строка)
    return []


def _тесты(фильтр):
    имена = [os.path.splitext(os.path.basename(п))[0][len("тест_"):]
             for п in sorted(glob.glob(os.path.join(ТЕСТЫ, "тест_*.py")))]
    if фильтр:
        имена = [и for и in имена if и == фильтр.replace("тест_", "", 1)]
    return [и for и in имена if и not in ПОСЛЕДНИЕ] + [и for и in имена if и in ПОСЛЕДНИЕ]


def прогнать_базу(имя, база, пользователь, фильтр, файл_итога, src=None, файл_ожидания=None):
    """Все тесты и проверка запросов в одном COM-сеансе. Итог — JSON в файл_итога."""
    сеанс.настроить_вывод()
    итог = {"база": имя, "путь": база, "подключение": 0.0, "тесты": [], "ошибка": "", "ожидание": 0.0}
    начало = time.time()
    ожидание = _Ожидание(файл_ожидания)
    замок = _взять_замок(база, ожидание)
    try:
        if замок is None:
            итог["ошибка"] = "база %s занята деплоем или другим прогоном дольше %d с" % (база, ЖДАТЬ_ЗАМОК)
            return итог
        try:
            c, итог["подключение"] = _подключить(база, пользователь, ожидание)
        except Exception as е:
            итог["ошибка"] = "подключение: %s" % сеанс.текст_ошибки(е)
            return итог
        print("== база %s (%s), подключение %.1f с" % (имя, база, итог["подключение"]), flush=True)
        н = time.time()
        try:
            ошибки = _сверить_расширение(c, база) if src != "-" else []
        except Exception as е:
            ошибки = ["ОШИБКА сверка расширения упала: %s" % сеанс.текст_ошибки(е)]
        for о in ошибки:
            print("  " + о)
        итог["тесты"].append({"имя": "расширение", "код": int(bool(ошибки)), "сек": round(time.time() - н, 2),
                              "проверок": 1 if src != "-" else 0, "ошибки": ошибки})

        настоящий = sys.stdout
        for тест in _тесты(фильтр):
            тройник = _Тройник(настоящий)
            with contextlib.redirect_stdout(тройник):
                т = None
                try:
                    модуль = importlib.import_module("тест_" + тест)
                    т = сеанс.Тест(тест, c=c, база=база)
                    т.выполнить(модуль.сценарий)
                    код = т.итог()
                except Exception as е:        # тест не импортировался / не создался — следующие идут
                    print("  ОШИБКА тест %s не запущен: %s" % (тест, сеанс.текст_ошибки(е)))
                    код = 1
            итог["тесты"].append({"имя": тест, "код": код, "сек": round(т.сек if т else 0.0, 2),
                                  "проверок": т.проверок if т else 0,
                                  "ошибки": _строки_ошибок(тройник.буфер.getvalue()) if код else []})

        if not фильтр or фильтр == "запросы":
            import проверка_запросов as пз
            тройник = _Тройник(настоящий)
            н = time.time()
            with contextlib.redirect_stdout(тройник):
                print("== проверка запросов")
                try:
                    тексты = пз.тексты_запросов()
                    поймано, ошибки = пз.проверить_соединение(c, тексты)
                    if поймано != len(пз.САМОТЕСТ):
                        print("  САМОТЕСТ НЕ ПРОЙДЕН: поймано %d из %d — проверке не доверять"
                              % (поймано, len(пз.САМОТЕСТ)))
                    for место, о in ошибки:
                        print("  ОШИБКА %s: %s" % (место, о))
                    код = 1 if ошибки or поймано != len(пз.САМОТЕСТ) else 0
                    print("== запросы: текстов %d, самотест %d из %d, ошибок %d"
                          % (len(тексты), поймано, len(пз.САМОТЕСТ), len(ошибки)))
                    проверок = len(тексты)
                except Exception as е:
                    print("  ОШИБКА проверка запросов упала: %s" % сеанс.текст_ошибки(е))
                    код, проверок = 1, 0
            итог["тесты"].append({"имя": "запросы", "код": код, "сек": round(time.time() - н, 2),
                                  "проверок": проверок,
                                  "ошибки": _строки_ошибок(тройник.буфер.getvalue()) if код else []})
        return итог
    finally:
        итог["ожидание"] = ожидание.сек
        итог["всего"] = round(time.time() - начало, 2)
        with open(файл_итога, "w", encoding="utf-8") as ф:
            json.dump(итог, ф, ensure_ascii=False)
        if замок is not None:
            замок.close()


# ───────────────────────── родитель: базы параллельно, сводка ─────────────────────────

def _базы_из_аргументов():
    своя = сеанс.аргумент("база")
    if своя:
        return [("СВОЯ", своя, сеанс.аргумент("пользователь", сеанс.ПОЛЬЗОВАТЕЛЬ_ПО_УМОЛЧАНИЮ))]
    имена = [и.strip() for и in сеанс.аргумент("базы", ",".join(СТЕНД)).split(",") if и.strip()]
    неизвестные = [и for и in имена if и not in СТЕНД]
    if неизвестные:
        sys.exit("неизвестные базы: %s (есть %s)" % (", ".join(неизвестные), ", ".join(СТЕНД)))
    копии = сеанс.аргумент("копии", "")   # --копии=_E → C:\1c_bases\UZ_UNF_E, UZ_BP_E, UZ_UT_E (свои копии стенда)
    return [(и, СТЕНД[и][0] + копии, СТЕНД[и][1]) for и in имена]


def main():
    сеанс.настроить_вывод()
    if сеанс.аргумент("дочерний"):
        итог = прогнать_базу(сеанс.аргумент("дочерний"), сеанс.аргумент("база"), сеанс.аргумент("пользователь"),
                             сеанс.аргумент("тест", ""), сеанс.аргумент("итог"), сеанс.аргумент("src"),
                             сеанс.аргумент("ожидание"))
        return 1 if итог["ошибка"] or any(т["код"] for т in итог["тесты"]) else 0

    фильтр = сеанс.аргумент("тест", "")
    if фильтр and фильтр != "запросы" and not _тесты(фильтр):
        sys.exit("нет теста %s (есть: %s, запросы)" % (фильтр, ", ".join(_тесты(""))))
    подробно = "--подробно" in sys.argv
    базы = _базы_из_аргументов()
    os.makedirs(ЖУРНАЛЫ, exist_ok=True)
    начало = time.time()
    # сверка «в базе то, что в src_ext»: --без-сверки — осознанный прогон по чужому коду (печатается)
    src = "-" if "--без-сверки" in sys.argv else отпечаток_src.отпечаток()
    print("src_ext: %s (%.2f с)%s" % (src, time.time() - начало,
                                      "  — СВЕРКА С БАЗОЙ ВЫКЛЮЧЕНА (--без-сверки)" if src == "-" else ""))
    процессы = []
    for имя, база, пользователь in базы:
        # своя копия: имя журнала по папке базы — прогоны разных копий из разных сессий не затирают друг друга
        файл = (имя + сеанс.аргумент("копии", "")) if имя != "СВОЯ" else "СВОЯ_" + os.path.basename(os.path.normpath(база))
        журнал = os.path.join(ЖУРНАЛЫ, файл + ".log")
        файл_итога = os.path.join(ЖУРНАЛЫ, файл + ".json")
        файл_ожидания = os.path.join(ЖУРНАЛЫ, файл + ".ожидание")
        for старый in (файл_итога, файл_ожидания):
            if os.path.exists(старый):
                os.remove(старый)
        аргументы = [sys.executable, os.path.abspath(__file__), "--дочерний=" + имя, "--база=" + база,
                     "--пользователь=" + пользователь, "--итог=" + файл_итога, "--src=" + src,
                     "--ожидание=" + файл_ожидания]
        if фильтр:
            аргументы.append("--тест=" + фильтр)
        поток = open(журнал, "w", encoding="utf-8")
        окружение = dict(os.environ, PYTHONIOENCODING="utf-8")
        процессы.append((имя, журнал, файл_итога, поток,
                         subprocess.Popen(аргументы, stdout=поток, stderr=subprocess.STDOUT, env=окружение),
                         файл_ожидания))

    # жёсткий таймаут: 3× бюджета прогона + сколько процесс базы честно прождал занятую базу;
    # --таймаут=сек — только для проверки самого таймаута (мутация: --таймаут=3 обязан дать «ТАЙМАУТ»)
    таймаут = int(сеанс.аргумент("таймаут", ТАЙМАУТ))
    таймауты = set()
    while any(п.poll() is None for _, _, _, _, п, _ in процессы):
        for имя, _, _, _, процесс, файл_ожидания in процессы:
            if процесс.poll() is not None:
                continue
            try:
                ждали = float(open(файл_ожидания, encoding="utf-8").read())
            except (OSError, ValueError):
                ждали = 0.0
            if time.time() - начало > таймаут + ждали:
                процесс.kill()
                таймауты.add(имя)
        time.sleep(0.5)

    провалов = 0
    for имя, журнал, файл_итога, поток, процесс, _ in процессы:
        поток.close()
        if имя in таймауты:
            провалов += 1
            print("%-4s ТАЙМАУТ: процесс базы снят через %.0f с (предел %d с = 3× бюджета + ожидание базы), "
                  "журнал %s" % (имя, time.time() - начало, таймаут, журнал))
            for с in open(журнал, encoding="utf-8", errors="replace").read().splitlines()[-8:]:
                print("       " + с)
            continue
        if подробно:
            print(open(журнал, encoding="utf-8").read())
        try:
            итог = json.load(open(файл_итога, encoding="utf-8"))
        except Exception:
            провалов += 1
            print("%-4s ПРОЦЕСС УПАЛ (код %s), журнал %s" % (имя, процесс.returncode, журнал))
            for с in open(журнал, encoding="utf-8", errors="replace").read().splitlines()[-8:]:
                print("       " + с)
            continue
        if итог["ошибка"]:
            провалов += 1
            print("%-4s ОШИБКА %s" % (имя, итог["ошибка"]))
            continue
        print("%-4s подключение %.1f с%s" % (имя, итог["подключение"],
                                             "; ожидание занятой базы %.0f с (вне бюджета)" % итог["ожидание"]
                                             if итог["ожидание"] else ""))
        сценарии = 0.0
        провалов_базы = 0
        for т in итог["тесты"]:
            сценарии += т["сек"]
            метка = "  ПРЕДУПРЕЖДЕНИЕ: бюджет %d с" % БЮДЖЕТ_ТЕСТА if т["сек"] > БЮДЖЕТ_ТЕСТА else ""
            print("%-4s %-16s код %d  %5.1f с  проверок %3d%s"
                  % (имя, т["имя"], т["код"], т["сек"], т["проверок"], метка))
            if т["проверок"] == 0 and т["имя"] != "расширение" and not т["код"]:
                т["код"] = 1
                т["ошибки"] = ["ОШИБКА тест без единой проверки — вышел раньше, чем что-то проверил"]
                print("       тест без единой проверки считается проваленным")
            if т["код"]:
                провалов_базы += 1
                for с in т["ошибки"]:
                    print("       " + с.strip())
        провалов += провалов_базы
        print("%-4s итог: провалов %d из %d, сценарии %.1f с, процесс %.1f с%s"
              % (имя, провалов_базы, len(итог["тесты"]), сценарии, итог["всего"],
                 ("  журнал " + журнал) if провалов_базы else ""))
    всего = time.time() - начало
    ждали = 0.0
    for _, _, файл_итога, _, _, _ in процессы:
        try:
            ждали = max(ждали, json.load(open(файл_итога, encoding="utf-8")).get("ожидание", 0.0))
        except (OSError, ValueError):
            continue
    метка = "  ПРЕДУПРЕЖДЕНИЕ: цель %d с превышена" % БЮДЖЕТ_ПРОГОНА if всего - ждали > БЮДЖЕТ_ПРОГОНА else ""
    print("ИТОГО: баз %d, провалов %d, время %.1f с%s (цель ≤ %d с)%s"
          % (len(базы), провалов, всего, ", из них ожидание занятой базы %.0f с" % ждали if ждали else "",
             БЮДЖЕТ_ПРОГОНА, метка))
    return 1 if провалов else 0


