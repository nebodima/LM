# Агенты конфигуратора УЗ: посмотреть и остановить вручную (обычно не нужно — у каждого агента есть сторож простоя).
#   .\tools\агенты.ps1                          — то же, что -Список
#   .\tools\агенты.ps1 -Список                  — все процессы 1cv8: СВОИ агенты (база, порт, простой, сторож) и чужие
#   .\tools\агенты.ps1 -Остановить -Все         — все свои агенты (C:\1c_bases\UZ_*, папка %TEMP%\uz_agent)
#   .\tools\агенты.ps1 -Остановить -База УНФ    — агент одной базы: УНФ/БП/УТ, имя папки (UZ_UNF_K) или полный путь
# Чужие процессы (агент DO_3 на docmngr3, пакетные конфигураторы, всё не C:\1c_bases\UZ_*) не останавливаются никогда —
# это решает tools\агент_конфигуратора.py по командной строке процесса, а не по имени базы из параметра.
param([switch]$Список, [switch]$Остановить, [switch]$Все, [string]$База = '')
$env:PYTHONIOENCODING = 'utf-8'
$Скрипт = "$PSScriptRoot\агент_конфигуратора.py"
if ($Остановить) {
	if (-not $Все -and -not $База) { Write-Host 'Остановить: укажите -Все или -База УНФ|БП|УТ|UZ_UNF_K|C:\1c_bases\…'; exit 1 }
	$Арг = @('остановить')
	if ($Все) { $Арг += '--все' }
	if ($База) {
		$Путь = switch ($База) { 'УНФ' { 'C:\1c_bases\UZ_UNF' } 'БП' { 'C:\1c_bases\UZ_BP' } 'УТ' { 'C:\1c_bases\UZ_UT' }
			default { if ([IO.Path]::IsPathRooted($База)) { $База } else { "C:\1c_bases\$База" } } }
		$Арг += "--база=$Путь"
	}
	python $Скрипт @Арг
	$Код = $LASTEXITCODE
	python $Скрипт список
	exit $Код
}
python $Скрипт список
exit $LASTEXITCODE
