    def выполнить(self, до=None):
        готовые = self.готовые_события()
        self.касса_из_базы()
        if готовые:
            print("  возобновление: уже проведено событий %d" % len(готовые))
        обработчик = dict(урок=self.урок, пко=self.пко, пко_прочее=self.пко, рко=self.рко, возврат=self.рко,
                          перемещение=self.перемещение, перенос=self.перемещение, ставка=self.ставка,
                          зарплата=self.зарплата)
        по_месяцам = collections.OrderedDict()
        for с in self.п.события:
            по_месяцам.setdefault((с["когда"].year, с["когда"].month), []).append(с)

        начало_всего = time.time()
        for (г, м), события in по_месяцам.items():
            if до and (г, м) > до:
                break
            сч = collections.Counter()
            сек = collections.Counter()
            н_мес = time.time()
            for с in события:
                if с["ид"] in готовые:
                    continue
                н = time.time()
                try:
                    ош, документов = обработчик[с["вид"]](с)
                except Exception as е:
                    ош, документов = "исключение: " + текст_ошибки(е), 0
                    if СМЕРТЕЛЬНО(ош):
                        raise
                прошло = time.time() - н
                if ош:
                    self.ошибки[с["вид"]].append("%s %s: %s" % (с["ид"], с["когда"], ош))
                    сч[с["вид"] + "_отказ"] += 1
                if документов:
                    сч[с["вид"]] += документов if not ош or с["вид"] == "зарплата" else 0
                    сек[с["вид"]] += прошло
            прошло = time.time() - н_мес
            всего = sum(в for к, в in сч.items() if not к.endswith("_отказ"))
            self.итоги.update(сч)
            self.время.update(сек)
            урок_мс = 1000 * сек["урок"] / сч["урок"] if сч["урок"] else 0
            self.замер.append(dict(месяц="%04d-%02d" % (г, м), документов=всего, сек=round(прошло, 1),
                                   док_в_сек=round(всего / прошло, 1) if прошло else 0, урок_мс=round(урок_мс, 1),
                                   отказов=sum(в for к, в in сч.items() if к.endswith("_отказ")),
                                   по_видам=dict(сч)))
            print("  %04d-%02d: документов %5d за %6.1f с — %5.1f док/с, урок %5.1f мс, отказов %d  (всего %.0f с)"
                  % (г, м, всего, прошло, всего / прошло if прошло else 0, урок_мс, self.замер[-1]["отказов"],
                     time.time() - начало_всего), flush=True)
            self.сохранить()


