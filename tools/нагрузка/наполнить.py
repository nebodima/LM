    def абонемент_на_дату(self, у, предмет, д, часы):
        for и in у.get("абонементы", ()):
            а = self.абонементы[и]
            if а["предмет"] != предмет or not (а["с"] <= д <= а["по_с_паузой"]):
                continue
            if а["пауза"] and а["пауза"][0] <= д < а["пауза"][1]:
                continue
            if а["занятий"] and а["использовано"] >= а["занятий"]:
                continue
            if а["часов"] and а["секунд"] + round(часы * 60) * 60 > а["часов"] * 3600:
                continue
            return а
        return None

