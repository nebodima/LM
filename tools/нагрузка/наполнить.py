    def элемент(self, вид, имя, есть, **поля):
        длина = self.длины.get(вид)
        if длина is None:
            длина = self.длины[вид] = int(getattr(self.c.Метаданные.Справочники, вид).ДлинаНаименования)
        if len(имя) > длина:   # обрезанное платформой имя не найдётся при возобновлении — будут дубли
            raise ValueError("наименование длиннее %d знаков (%s): %s" % (длина, вид, имя))
        if имя in есть:
            return есть[имя]
        о = getattr(self.c.Справочники, вид).СоздатьЭлемент()
        о.Наименование = имя
        for к, в in поля.items():
            if isinstance(в, tuple) and в and в[0] == "ТЧ":
                continue
            setattr(о, к, в)
        for к, в in поля.items():
            if isinstance(в, tuple) and в and в[0] == "ТЧ":
                for строка in в[1]:
                    с = getattr(о, к).Добавить()
                    for кк, вв in строка.items():
                        setattr(с, кк, вв)
        о.Записать()
        есть[имя] = о.Ссылка
        return о.Ссылка

