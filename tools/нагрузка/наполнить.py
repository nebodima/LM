def цена_тарифа(тариф, д):
    """(сумма, уроков, часов) тарифа плана на дату — как история цен УЗ_ЦеныТарифов."""
    цены = [ц for ц in тариф["цены"] if ц[0] <= д]
    return цены[-1][1:] if цены else тариф["цены"][0][1:]


def цена_строки(тариф, абонемент, часы, д):
    if абонемент:
        if абонемент["занятий"]:
            return абонемент["цена"] / абонемент["занятий"]
        return абонемент["цена"] * часы / абонемент["часов"]
    сумма, уроков, часов = цена_тарифа(тариф, д)
    if уроков:
        return сумма / уроков
    if часов:
        return сумма * часы / часов
    return 0.0


