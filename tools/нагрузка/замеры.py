            убираемые.append(д.Ссылка)
            self.мерить("урок", "перепроведение урока, 8 учеников по тарифу", lambda: провести(д), БЮДЖЕТ["урок"])
            # слагаемые проведения по отдельности (что стоит сколько)
            урок = созданные[0]
            self.мерить("урок", "  из них: остаток абонемента (1 запрос, ×8 в уроке)",
                        lambda: self.запрос(ОСТАТОК_АБОНЕМЕНТА, Абонемент=абонементы[0]).Количество())
