                  ФИЗЛИЦА_ПОРЦИЯ, ФИЗЛИЦА_ПОРЦИЯ.replace("//ОТБОР", ОТБОР_ФИЗЛИЦА), ФИЗЛИЦА_СТРОК, КАССОВЫЙ_ЖУРНАЛ,
