def убрать(c, ссылка):
    """Удалить созданное замером (документ — с движениями); при конфликте блокировок — повторить."""
    for попытка in range(20):
        try:
            удалить_объект(c, ссылка, True)
            return
        except Exception as е:
            if "блокиров" not in текст_ошибки(е) or попытка == 19:
                print("  уборка: %s" % текст_ошибки(е))
                return
            time.sleep(0.5)


def тексты_bsl(путь):
    """Тексты запросов из строковых литералов BSL: "ВЫБРАТЬ … |… " → обычный текст."""
    код = open(путь, encoding="utf-8-sig").read()
    итог = []
    for м in re.finditer(r'"(ВЫБРАТЬ(?:[^"]|"")*)"', код):
        строки = [с.strip() for с in м.group(1).replace('""', '"').split("\n")]
        итог.append("\n".join(с[1:] if с.startswith("|") else с for с in строки))
    return итог


class Замеры:
    def __init__(self, c, база, повторов):
        self.c = c
        self.база = база
        self.повторов = повторов
        self.итог = []          # строки таблицы
        self.заметки = {}

    # ── общие ──
    def запрос(self, текст, **параметры):
        з = self.c.NewObject("Запрос")
        з.Текст = текст
        for к, в in параметры.items():
            з.УстановитьПараметр(к, в)
        return з.Выполнить().Выгрузить()

    def мерить(self, раздел, имя, действие, бюджет=None, повторов=None, подробности=""):
        н = time.perf_counter()
        результат = действие()
        холодный = time.perf_counter() - н
        времена = []
        for _ in range(self.повторов if повторов is None else повторов):
            н = time.perf_counter()
            результат = действие()
            времена.append(time.perf_counter() - н)
        медиана = statistics.median(времена) if времена else холодный
        строка = dict(раздел=раздел, имя=имя, сек=round(медиана, 3), холодный=round(холодный, 3),
                      мин=round(min(времена), 3) if времена else None, бюджет=бюджет,
                      превышение=bool(бюджет and медиана > бюджет), подробности=подробности,
                      результат=результат if isinstance(результат, (int, float, str)) else None)
        self.итог.append(строка)
        print("  %-58s %7.3f с (холодный %6.3f)%s%s" % (имя, медиана, холодный,
              "  бюджет %.1f — ПРЕВЫШЕН" % бюджет if строка["превышение"] else ("  бюджет %.1f" % бюджет if бюджет else ""),
              ("  [%s]" % результат) if строка["результат"] not in (None, "") else ""), flush=True)
        return результат

    def ссылка(self, вид, имя):
        т = self.запрос(ПО_ИМЕНИ % вид, Имя=имя)
        if т.Количество() == 0:
            raise RuntimeError("не найден %s «%s» — база не наполнена?" % (вид, имя))
        return т.Получить(0).Ссылка

