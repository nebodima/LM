    # ── отчёты ──
    def отчеты(self):
        c = self.c
        ска = ["УЗ_ВедомостьПоКассе", "УЗ_Взаиморасчеты", "УЗ_ОтчетПоДисконтнымКартам", "УЗ_Расходы",
               "УЗ_РасчетыПоЗарплате", "УЗ_Явки_2"]

        def скд(имя, с, по, вариант=None):
            отчет = getattr(c.Отчеты, имя).Создать()
            if вариант:
                найден = [в for в in отчет.СхемаКомпоновкиДанных.ВариантыНастроек if в.Имя == вариант]
                if not найден:
                    raise RuntimeError("%s: нет варианта %s" % (имя, вариант))
                отчет.КомпоновщикНастроек.ЗагрузитьНастройки(найден[0].Настройки)
            настройки = отчет.КомпоновщикНастроек.ПолучитьНастройки()
            сп = c.NewObject("СтандартныйПериод")
            сп.ДатаНачала = дата(с.year, с.month, с.day)
            сп.ДатаОкончания = дата(по.year, по.month, по.day, 23, 59)
            if not настройки.ПараметрыДанных.УстановитьЗначениеПараметра("Период", сп):
                pass
            макет = c.NewObject("КомпоновщикМакетаКомпоновкиДанных").Выполнить(отчет.СхемаКомпоновкиДанных, настройки)
            процессор = c.NewObject("ПроцессорКомпоновкиДанных")
            процессор.Инициализировать(макет)
            документ = c.NewObject("ТабличныйДокумент")
            вывод = c.NewObject("ПроцессорВыводаРезультатаКомпоновкиДанныхВТабличныйДокумент")
            вывод.УстановитьДокумент(документ)
            вывод.Вывести(процессор)
            return int(документ.ВысотаТаблицы)
        # прогрев: первое чтение макета СКД в сеансе ~3–4 с (фабрика XDTO) — не относится к отчёту
        н = time.perf_counter()
        скд("УЗ_Расходы", datetime.date(2026, 9, 1), datetime.date(2026, 9, 27))
        print("  (прогрев СКД в сеансе: %.1f с — вне замеров)" % (time.perf_counter() - н))
        for имя in ска:
            for метка, (с, по), бюджет in (("год", ГОД, БЮДЖЕТ["отчёт год"]), ("3 года", ТРИ_ГОДА, БЮДЖЕТ["отчёт 3 года"])):
                if имя == "УЗ_Явки_2" and метка == "3 года":
                    бюджет = None       # сетка по дням за 3 года — для сведения; бюджет — у варианта по месяцам ниже
                self.мерить("отчёт", "%s за %s (строк)" % (имя, метка), lambda: скд(имя, с, по), бюджет, повторов=1)
        # «Явки» за 3 года сеткой по дням (1 855 × 1 129 клеток) не читаются и не укладываются в бюджет даже без
        # оформления клеток — для длинных периодов вариант «Явки по месяцам» (28.09.2026, после замера)
        self.мерить("отчёт", "УЗ_Явки_2 по месяцам за 3 года (строк)",
                    lambda: скд("УЗ_Явки_2", ТРИ_ГОДА[0], ТРИ_ГОДА[1], "Явки по месяцам"), БЮДЖЕТ["отчёт 3 года"], повторов=1)
        # отчёты со своей формой — серверный код модуля формы на стенде (tools\тесты\стенд_форм.py)
        for имя, форма in (("УЗ_АналитикаПоУченикам", "ФормаОтчета"), ("УЗ_ВедомостьПоКассеДляМенеджеров", "ФормаОтчета")):
            об, сборка = стенд_форм.создать(c, имя, форма)
            if сборка:
                print("  (стенд %s собран за %.1f с — вне замеров)" % (имя, сборка))
            об.ПриСозданииНаСервере(False, True)
            for метка, (с, по), бюджет in (("год", ГОД, БЮДЖЕТ["отчёт год"]), ("3 года", ТРИ_ГОДА, БЮДЖЕТ["отчёт 3 года"])):
                сп = c.NewObject("СтандартныйПериод")
                сп.ДатаНачала = дата(с.year, с.month, с.day)
                сп.ДатаОкончания = дата(по.year, по.month, по.day, 23, 59)
                об.Период = сп
                if об.Период.ДатаНачала.year != с.year:
                    raise RuntimeError("%s: период стенда не установился" % имя)

                def сформировать():
                    if имя == "УЗ_АналитикаПоУченикам":
                        об.ПолучитьОстатки()
                    else:
                        об.СформироватьНаСервере()
                    return int(об.ТабДок.ВысотаТаблицы)
                self.мерить("отчёт", "%s за %s (строк)" % (имя, метка), сформировать, бюджет, повторов=1)

    # ── разбор превышений: где уходит время ──
    def диагностика(self):
        об = self.обработка()
