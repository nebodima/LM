    def обработка(self):
        if getattr(self, "_обработка", None) is None:
            путь = os.path.join(ЗДЕСЬ, "ЗамерыФорм.bsl")
            модуль = open(путь, encoding="utf-8-sig").read()
            имя = "ЗамерыФормУЗ"
            хэш = hashlib.sha1(модуль.encode("utf-8")).hexdigest()[:12]
            epf = os.path.join(стенд_форм.ПАПКА, "%s_%s.epf" % (имя, хэш))
            if not os.path.exists(epf):
                os.makedirs(стенд_форм.ПАПКА, exist_ok=True)
                with стенд_форм._ЗамокСборки():
                    if not os.path.exists(epf):
                        _, сек = стенд_форм._собрать(имя, хэш, модуль, epf)
                        print("  (обработка замеров собрана за %.1f с — вне замеров)" % сек)
            self._обработка = self.c.ВнешниеОбработки.Создать(epf, False)
        return self._обработка

