"""Мутации COM-проверок: каждая проверка обязана хоть раз покраснеть (навык 1c-proverki-krasnet).

Для каждой мутации: в файл теста (или помощника, или в отметку деплоя) подкладывается ровно одна поломка —
то, что проверка стережёт, — запускается прогон нужного теста в СВОЕЙ базе, ждём код 1 и все нужные красные
строки в журнале; затем файл возвращается байт в байт (сверка хэша до/после). Мутации идут по одной, прогон —
отдельным процессом. Сверка «в базе то, что в src_ext» выключена (--без-сверки) у всех мутаций, кроме своих:
код 1 должен прийти только от подложенной поломки.

    python tools\\мутации_проверок.py --база=C:\\1c_bases\\UZ_UNF_D                — все (~2 мин)
    python tools\\мутации_проверок.py --база=C:\\1c_bases\\UZ_UNF_D --только=сироты  — по имени

Каждая мутация ~10–25 с (подключение ~7 с + тест). Код выхода 1, если хоть одна мутация осталась зелёной
или файл не вернулся. После мутации «сироты» база чистится tools\\убрать_сирот.py --исправить.
"""
import hashlib
import os
import subprocess
import sys
import tempfile
import time

sys.dont_write_bytecode = True
ПАПКА = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(ПАПКА, "тесты"))
sys.path.insert(0, ПАПКА)
import сеанс  # noqa: E402
import отпечаток_src  # noqa: E402

ОТМЕТКА = "{отметка деплоя}"
# (имя, файл относительно tools или ОТМЕТКА, было, стало, тест, красные строки журнала, со сверкой)
МУТАЦИИ = [
    ("сироты", "тесты/сеанс.py",
     "    if c.Метаданные.Документы.Содержит(мд):\n        for р in мд.Движения:",
     "    if False and c.Метаданные.Документы.Содержит(мд):\n        for р in мд.Движения:",
     "права", ("ОШИБКА после теста нет новых сирот",), False),
    ("долг_сумма", "тесты/тест_оповещения.py",
     "    запись.Сумма = ДОЛГ\n", "    запись.Сумма = ДОЛГ + 1\n",
     "оповещения", ("ОШИБКА оповещение о долге",), False),
    ("урок_причина", "тесты/тест_урок.py",
     # отказ по ДРУГОЙ причине: тариф с ценой, но неактивный абонемент — старая проверка это засчитала бы
     "    д = урок(без_цены, 8)\n",
     "    д = урок(в_карточке, 8)\n    д.Ученики.Получить(0).Абонемент = элемент(\"УЗ_Абонемент\", \"неактивный\")\n",
     "урок", ("ОШИБКА к оплате по тарифу без цены",), False),
    ("печать_причина", "тесты/тест_печать.py",
     'c.УЗ_Печать.СформироватьСвоейПечатью("Справочник.Организации", "ПКО", организация)',
     'c.УЗ_Печать.СформироватьСвоейПечатью("Справочник.Организации", "ПКО")',
     "печать", ("ОШИБКА своя печать не печатает чужие менеджеры",), False),
    # ПКО записан, но не проведён — движений нет: все четыре проверки цифр отчётов обязаны покраснеть
    ("отчеты_цифры", "тесты/тест_отчеты.py",
     "    д.Записать(c.РежимЗаписиДокумента.Проведение)  # ПКО теста отчётов\n",
     "    д.Записать(c.РежимЗаписиДокумента.Запись)  # ПКО теста отчётов\n",
     "отчеты", ("ОШИБКА УЗ_ВедомостьПоКассе: ", "ОШИБКА УЗ_ВедомостьПоКассеДляМенеджеров: ",
                "ОШИБКА УЗ_АналитикаПоУченикам: ", "ОШИБКА УЗ_ДвиженияДокумента: "), False),
    ("права_цифры", "тесты/тест_права.py",
     "        д.СуммаДокумента = 8000\n", "        д.СуммаДокумента = 7000\n",
     "права", ("ОШИБКА отчёт сотрудника: в строке его ПКО приход 8 000",), False),
    # сверка «в базе то, что в src_ext»: отметка деплоя говорит о другом src и о другой ХешСумме
    ("сверка_src", ОТМЕТКА, '"src": "', '"src": "0', "запросы", ("ОШИБКА src_ext изменён после деплоя",), True),
    ("сверка_хеш", ОТМЕТКА, '"хеш_в_базе": "', '"хеш_в_базе": "ЧУЖОЙ',
     "запросы", ("ОШИБКА ХешСумма УЗ_ext в базе",), True),
]


def хэш(путь):
    with open(путь, "rb") as ф:
        return hashlib.sha256(ф.read()).hexdigest()


def main():
    сеанс.настроить_вывод()
    база = сеанс.аргумент("база")
    if not база:
        sys.exit("укажите --база= (своя копия: мутации пишут и удаляют тестовые данные)")
    пользователь = сеанс.аргумент("пользователь", сеанс.ПОЛЬЗОВАТЕЛЬ_ПО_УМОЛЧАНИЮ)
    только = сеанс.аргумент("только", "")
    журнал = os.path.join(tempfile.gettempdir(), "уз_прогон", "СВОЯ_%s.log" % os.path.basename(os.path.normpath(база)))
    провалов = 0
    начало = time.time()
    for имя, файл, было, стало, тест, красное, сверка in МУТАЦИИ:
        if только and имя != только:
            continue
        путь = отпечаток_src.файл_отметки(база) if файл == ОТМЕТКА else os.path.join(ПАПКА, файл)
        if not os.path.exists(путь):
            print("%-16s НЕ ПРИМЕНИЛАСЬ: нет файла %s (для сверки — сначала деплой этой базы)" % (имя, путь))
            провалов += 1
            continue
        with open(путь, "rb") as ф:
            исходник = ф.read()
        до = hashlib.sha256(исходник).hexdigest()
        текст = исходник.decode("utf-8")
        if "\r\n" in текст:
            было, стало = было.replace("\n", "\r\n"), стало.replace("\n", "\r\n")
        if текст.count(было) != 1:
            print("%-16s НЕ ПРИМЕНИЛАСЬ: образец найден %d раз в %s" % (имя, текст.count(было), файл))
            провалов += 1
            continue
        н = time.time()
        команда = [sys.executable, os.path.join(ПАПКА, "прогон.py"), "--база=" + база,
                   "--пользователь=" + пользователь, "--тест=" + тест] + ([] if сверка else ["--без-сверки"])
        try:
            with open(путь, "wb") as ф:
                ф.write(текст.replace(было, стало, 1).encode("utf-8"))
            код = subprocess.run(команда, capture_output=True, timeout=300).returncode
        finally:
            with open(путь, "wb") as ф:
                ф.write(исходник)
        вернули = хэш(путь) == до
        with open(журнал, encoding="utf-8", errors="replace") as ф:
            вывод = ф.read()
        нет = [к for к in красное if к not in вывод]
        ок = код == 1 and not нет and вернули
        провалов += not ок
        print("%-16s %s  код %d, красных строк %d из %d%s, файл %s  (%.1f с)"
              % (имя, "КРАСНЕЕТ" if ок else "ПРОВАЛ  ", код, len(красное) - len(нет), len(красное),
                 (" — нет: " + "; ".join(нет)) if нет else "", "возвращён" if вернули else "НЕ ВОЗВРАЩЁН",
                 time.time() - н))
        if имя == "сироты":   # мутация оставила сирот в базе — снять
            subprocess.run([sys.executable, os.path.join(ПАПКА, "убрать_сирот.py"), "--база=" + база,
                            "--пользователь=" + пользователь, "--исправить"], capture_output=True, timeout=120)
    print("ИТОГО: мутаций не покраснело %d, время %.1f с" % (провалов, time.time() - начало))
    return 1 if провалов else 0


if __name__ == "__main__":
    sys.exit(main())
