# -*- coding: utf-8 -*-
"""Приведение модулей BSL к формату, который требует аудит формат_кода (tools/аудиты/формат_кода.py).

Меняет только пробельные символы и переносы вне строковых литералов (смысл кода не трогает):
  * переводы строк — CRLF, как в выгрузке конфигуратора; BOM сохраняется;
  * хвостовые пробелы и табы — убираются (кроме строк внутри многострочного литерала: там это текст);
  * отступ из пробелов — табуляцией (4 пробела = таб);
  * две и больше пустых строк подряд — одна; между методами — ровно одна пустая строка; #Region — #Область;
  * директива компиляции (&НаСервере) стоит прямо над объявлением, комментарий-описание — над ней;
  * строка длиннее 120 символов переносится: хвостовой комментарий — строкой выше, код — после запятой или
    перед «И»/«ИЛИ»/«+» с наименьшей вложенностью скобок, продолжение — с отступом +1 таб; длинный литерал
    делится на «"…" + "…"» по пробелу; строка текста запроса («|…») — по пробелу новой строкой «|».

    python tools/формат_bsl.py                    # все модули src_ext
    python tools/формат_bsl.py путь.bsl [путь…]   # отдельные модули
После правки — python tools/аудиты/формат_кода.py (что осталось — руками) и /CheckModules при деплое.
"""
import io
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "аудиты"))
import общее  # noqa: E402

ДЛИНА = 120
ТАБ = 4


def ширина(с):
    return len(с.expandtabs(ТАБ))


# ─────────────────────────── разбор строки ───────────────────────────

def маска_литералов(стр, в_литерале_с_начала=False):
    """[bool] для каждого символа строки: внутри строкового литерала (включая кавычки)."""
    маска = [False] * len(стр)
    внутри = в_литерале_с_начала
    i = 0
    while i < len(стр):
        с = стр[i]
        if внутри:
            маска[i] = True
            if с == '"':
                if i + 1 < len(стр) and стр[i + 1] == '"':
                    маска[i + 1] = True
                    i += 2
                    continue
                внутри = False
        else:
            if с == '"':
                маска[i] = True
                внутри = True
            elif с == "/" and стр[i:i + 2] == "//":
                break
        i += 1
    return маска, внутри


def начало_комментария(стр, маска):
    i = 0
    while True:
        i = стр.find("//", i)
        if i < 0:
            return -1
        if not маска[i]:
            return i
        i += 2


def перенести(стр, отступ_продолжения, в_литерале=False, запрос=False, глубина=0):
    """Список строк вместо одной длинной (или [стр], если переносить нечем)."""
    if ширина(стр) <= ДЛИНА or глубина > 20:
        return [стр]
    отступ = re.match(r"[ \t]*", стр).group(0)
    маска, _ = маска_литералов(стр, в_литерале)
    if в_литерале and not стр.strip().startswith("|"):
        return [стр]
    if в_литерале:
        # строка текста запроса с константой «""…""» не делится: перенос внутри константы изменил бы запрос
        if not запрос or '""' in стр:
            return [стр]
        # строка текста запроса: делим по пробелу/табу внутри литерала
        лучший = -1
        for i in range(len(стр)):
            if стр[i] in " \t" and маска[i] and ширина(стр[:i]) <= ДЛИНА and i > len(отступ) + 2:
                лучший = i
        if лучший < 0:
            return [стр]
        перв = стр[:лучший].rstrip()
        ост = отступ + "|\t\t" + стр[лучший:].lstrip()
        return [перв] + перенести(ост, отступ_продолжения, True, запрос, глубина + 1)
    к = начало_комментария(стр, маска)
    if к > 0 and стр[:к].strip():
        код, коммент = стр[:к].rstrip(), стр[к:]
        return перенести(отступ + коммент, отступ_продолжения, глубина=глубина + 1) + \
            перенести(код, отступ_продолжения, глубина=глубина + 1)
    if стр.strip().startswith("//"):
        # длинный комментарий: по словам
        текст = стр.strip()[2:]
        слова = текст.split(" ")
        частей = -(-ширина(стр) // ДЛИНА)
        цель = min(ДЛИНА, ширина(отступ + "//") + len(текст) // частей + 12)
        строки, тек = [], ""
        for с in слова:
            кандидат = (тек + " " + с) if тек else с
            if тек and ширина(отступ + "//" + кандидат) > цель:
                строки.append(отступ + "//" + тек)
                тек = с
            else:
                тек = кандидат
        строки.append(отступ + "//" + тек)
        return строки
    # 1) внутренние выравнивающие табы и многопробелья вне литералов — одним пробелом
    сжатая = []
    i, n = 0, len(стр)
    while i < n:
        if i >= len(отступ) and стр[i] in " \t" and not маска[i]:
            j = i
            while j < n and стр[j] in " \t" and not маска[j]:
                j += 1
            сжатая.append(" ")
            i = j
        else:
            сжатая.append(стр[i])
            i += 1
    с2 = "".join(сжатая).rstrip()
    if ширина(с2) <= ДЛИНА:
        return [с2]
    стр = с2
    маска, _ = маска_литералов(стр, в_литерале)
    # 2) точки переноса: после «, » и перед « И »/« ИЛИ »/« + » вне литералов; вложенность скобок
    кандидаты = []
    гл = 0
    for i, с in enumerate(стр):
        if маска[i]:
            continue
        if с in "([":
            гл += 1
            if с == "(" and i + 1 < len(стр) and стр[i + 1] != ")":
                кандидаты.append((i + 1, гл, "после"))
        elif с in ")]":
            гл -= 1
        elif с == "," and i + 1 < len(стр):
            кандидаты.append((i + 1, гл, "после"))
        elif с == " " and i > len(отступ):
            м = re.match(r"(И|и|ИЛИ|Или|или|AND|OR) |\+ ?", стр[i + 1:]) if стр[i + 1:i + 2] != " " else None
            if м and not маска[i + 1] and (стр[i + 1] != "+" or стр[i - 1] not in "(,="):
                кандидаты.append((i, гл, "перед"))
            elif гл == 0 and стр[i + 1:i + 3] == "= " and not re.match(r"(?i)\s*(Если|ИначеЕсли|Пока|Возврат)\b", стр) \
                    and "=" not in стр[len(отступ):i]:
                кандидаты.append((i + 2, гл, "после"))
    годные = [(п, г) for п, г, _ in кандидаты if ширина(стр[:п].rstrip()) <= ДЛИНА and п > len(отступ) + 10]
    if годные:
        мин = min(г for _, г in годные)
        п = max(п for п, г in годные if г == мин)
        перв = стр[:п].rstrip()
        ост = отступ_продолжения + стр[п:].lstrip()
        return [перв] + перенести(ост, отступ_продолжения, глубина=глубина + 1)
    # 3) длинный литерал: делим «"…" + "…"» по пробелу
    лучший, лучший_вне = -1, -1
    for i in range(len(стр)):
        if стр[i] == " " and маска[i] and ширина(стр[:i + 1]) <= ДЛИНА - 1 and i > len(отступ) + 10:
            # позиция внутри литерала, не в начале/конце кавычки; лучше — не внутри «ёлочек»
            if маска[i - 1] and i + 1 < len(стр) and маска[i + 1] and стр[i + 1] != '"':
                лучший = i
                if стр[:i].count("«") == стр[:i].count("»"):
                    лучший_вне = i
    if лучший_вне > len(отступ) + 40:
        лучший = лучший_вне
    if лучший > 0:
        перв = стр[:лучший + 1] + '"'
        ост = отступ_продолжения + '+ "' + стр[лучший + 1:]
        return [перв] + перенести(ост, отступ_продолжения, глубина=глубина + 1)
    return [стр]


# ─────────────────────────── модуль целиком ───────────────────────────

def привести(текст):
    текст = текст.replace("\r\n", "\n").replace("\r", "\n")
    м = общее.Модуль("", текст)
    строки = текст.split("\n")
    # начало каждой строки: внутри литерала? литерал — запрос?
    начала, смещ = [], 0
    for с in строки:
        начала.append(смещ)
        смещ += len(с) + 1
    диап = м.диапазоны_литералов

    def литерал_в(позиция):
        for н, к in диап:
            if н < позиция < к:
                return (н, к)
            if н >= позиция:
                break
        return None

    запросы = {(н, к) for н, к in диап if общее.это_запрос(текст[н:к])}
    новые = []
    пустых = 0
    for номер, стр in enumerate(строки):
        лит = литерал_в(начала[номер])
        if лит is None:
            стр = стр.rstrip(" \t")
        else:
            # хвост внутри литерала — текст строки; убираем только после закрывающей кавычки
            конец_лит = лит[1] - начала[номер]
            if конец_лит <= len(стр):
                стр = стр[:конец_лит] + стр[конец_лит:].rstrip(" \t")
        отступ = re.match(r"[ \t]*", стр).group(0)
        if " " in отступ and стр.strip() and (лит is None or стр.strip().startswith("|")):
            табов = (ширина(отступ) + 2) // ТАБ
            стр = "\t" * табов + стр[len(отступ):]
        if not стр.strip() and лит is None:
            пустых += 1
            if пустых >= 2:
                continue
            новые.append("")
            continue
        пустых = 0
        отступ = re.match(r"[ \t]*", стр).group(0)
        if ширина(стр) > ДЛИНА:
            новые.extend(перенести(стр, отступ + "\t", лит is not None, лит in запросы))
        else:
            новые.append(стр)
    текст = "\n".join(новые)
    текст = re.sub(r"(?im)^([ \t]*)#Region\b", r"\1#Область", текст)
    текст = re.sub(r"(?im)^([ \t]*)#EndRegion\b", r"\1#КонецОбласти", текст)
    текст = порядок_шапок(текст)
    текст = пустые_между_методами(текст)
    return текст.replace("\n", "\r\n")


def порядок_шапок(текст):
    """Директивы (&На…) — прямо над объявлением, комментарии — над директивами."""
    строки = текст.split("\n")
    i = 0
    while i < len(строки):
        if re.match(r"(?i)^[ \t]*(?:Асинх[ \t]+)?(Процедура|Функция)[ \t]+[\wЁё]+[ \t]*\(", строки[i]):
            j = i - 1
            while j >= 0 and (строки[j].strip().startswith("&") or строки[j].strip().startswith("//")):
                j -= 1
            шапка = строки[j + 1:i]
            дир = [с for с in шапка if с.strip().startswith("&")]
            ком = [с for с in шапка if not с.strip().startswith("&")]
            if шапка != ком + дир:
                строки[j + 1:i] = ком + дир
        i += 1
    return "\n".join(строки)


def пустые_между_методами(текст):
    строки = текст.split("\n")
    итог = []
    for i, с in enumerate(строки):
        итог.append(с)
        if re.match(r"(?i)^[ \t]*(КонецПроцедуры|КонецФункции)\b", с) and i + 1 < len(строки):
            след = строки[i + 1]
            if след.strip() and not след.strip().startswith("#"):
                итог.append("")
    return "\n".join(итог)


def обработать(путь):
    with io.open(путь, "rb") as ф:
        данные = ф.read()
    bom = данные.startswith(b"\xef\xbb\xbf")
    текст = данные.decode("utf-8-sig")
    новый = привести(текст)
    if новый != текст:
        with io.open(путь, "wb") as ф:
            ф.write((b"\xef\xbb\xbf" if bom else b"") + новый.encode("utf-8"))
        return True
    return False


def главный():
    общее.настроить_вывод()
    пути = [п for п in sys.argv[1:] if not п.startswith("--")]
    if not пути:
        исх = общее.Исходники(общее.КАТАЛОГ_ПО_УМОЛЧАНИЮ)
        пути = list(исх.файлы(".bsl"))
    изменено = sum(обработать(п) for п in пути)
    print("модулей %d, изменено %d" % (len(пути), изменено))


