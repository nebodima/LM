# Мутации гейта деплоя: каждый гейт обязан покраснеть на подложенной ошибке (навык 1c-proverki-krasnet).
#   .\tools\мутации_гейта.ps1 -База C:\1c_bases\UZ_UNF_D      — только СВОЯ копия: в неё грузится сломанный код
# Копия src_ext → %TEMP%\uz_agent\UZ_UNF_D\gate_src (папка агента этой базы), в копию подкладывается ровно одна ошибка, деплой копии обязан
# вернуть код 1 и красную строку нужного шага:
#   1. «Проба = ;» в общем модуле            → «проверка модулей … ОШИБКА» (и в базу не применено);
#   2. неверное свойство в XML — тип реквизита на несуществующий справочник (cfg:CatalogRef.УЗ_НетТакихКасс)
#      → «загрузка … ОШИБКА» (агент, затем пакетная). Проверено 28.09.2026: НЕИЗВЕСТНЫЙ элемент
#      (<НеверноеСвойство>1</…>) и неверное булево (<Hierarchical>неверно</…>) платформа молча принимает и грузит
#      зелёным — гейт загрузки их не видит, это дело офлайн-аудита XML;
#   3. «Для И = 1 По 2» (красный офлайн-аудит), деплой без -НесмотряНаАудит → «СТОП до загрузки».
# В конце база возвращается деплоем настоящего src_ext (код 0 обязателен). Всё печатается с временем.
#   -Только модуль|свойство|аудит — одна мутация (база всё равно возвращается деплоем src_ext)
param([Parameter(Mandatory)][string]$База, [string]$Пользователь = 'Администратор', [string]$Только = '')
$ErrorActionPreference = 'Stop'
$Корень = Split-Path $PSScriptRoot -Parent
# копия — в ASCII-папке агента базы: из пути с кириллицей агент не грузит, и гейт проверялся бы только пакетно
$Копия = Join-Path ([IO.Path]::GetTempPath()) "uz_agent\$(Split-Path $База -Leaf)\gate_src"
$Часы = [Diagnostics.Stopwatch]::StartNew()
$Провалов = 0

function Копия-Src {
	if (Test-Path $Копия) { Remove-Item $Копия -Recurse -Force }
	New-Item -ItemType Directory -Force $Копия | Out-Null
	Copy-Item -Path "$Корень\src_ext\*" -Destination $Копия -Recurse -Force
}
function Заменить([string]$Отн, [string]$Было, [string]$Стало) {
	$Путь = Join-Path $Копия $Отн
	$Т = [IO.File]::ReadAllText($Путь)
	if (([regex]::Matches($Т, [regex]::Escape($Было))).Count -ne 1) { throw "мутация: образец не найден ровно 1 раз в $Отн" }
	[IO.File]::WriteAllText($Путь, $Т.Replace($Было, $Стало), [Text.UTF8Encoding]::new($true))
}
function Деплой([string[]]$Арг) {
	$Вывод = & pwsh -NoProfile -File "$PSScriptRoot\деплой.ps1" -СвояБаза $База -Пользователь $Пользователь @Арг 2>&1 | Out-String -Width 220
	@{ Код = $LASTEXITCODE; Вывод = $Вывод }
}
function Ждём([string]$Имя, $Р, [int]$Код, [string]$Строка) {
	$Есть = $Р.Вывод -match $Строка
	$Ок = $Р.Код -eq $Код -and $Есть
	if (-not $Ок) { $script:Провалов++; Write-Host $Р.Вывод }
	Write-Host ('{0,6:N1} с  {1,-34} {2}  код {3} (ждали {4}), строка «{5}» {6}' -f $Часы.Elapsed.TotalSeconds, $Имя,
		$(if ($Ок) { 'КРАСНЕЕТ' } else { 'ПРОВАЛ  ' }), $Р.Код, $Код, $Строка, $(if ($Есть) { 'есть' } else { 'НЕТ' }))
}

if (-not $Только -or $Только -eq 'модуль') {
Копия-Src
Заменить 'CommonModules\УЗ_Общий\Ext\Module.bsl' 'Функция ЕстьРеквизит(' "Процедура ПробаГейта()`r`n`tПроба = ;`r`nКонецПроцедуры`r`n`r`nФункция ЕстьРеквизит("
Ждём 'Проба = ; в модуле' (Деплой @('-Исходники', $Копия, '-НесмотряНаАудит')) 1 'проверка модулей\s+[\d,]+ с\s+ОШИБКА'
}
if (-not $Только -or $Только -eq 'свойство') {
Копия-Src
Заменить 'Documents\УЗ_ПриходДенег.xml' '<v8:Type>cfg:CatalogRef.УЗ_Кассы</v8:Type>' '<v8:Type>cfg:CatalogRef.УЗ_НетТакихКасс</v8:Type>'
Ждём 'неверное свойство (тип) в XML' (Деплой @('-Исходники', $Копия, '-НесмотряНаАудит')) 1 'загрузка \(пакетно\)\s+[\d,]+ с\s+ОШИБКА'
}
if (-not $Только -or $Только -eq 'аудит') {
Копия-Src
Заменить 'CommonModules\УЗ_Общий\Ext\Module.bsl' 'Функция ЕстьРеквизит(' "Процедура ПробаАудита()`r`n`tДля И = 1 По 2 Цикл`r`n`tКонецЦикла;`r`nКонецПроцедуры`r`n`r`nФункция ЕстьРеквизит("
Ждём 'красный аудит без ключа' (Деплой @('-Исходники', $Копия)) 1 'СТОП до загрузки'
}

Remove-Item $Копия -Recurse -Force
$Р = Деплой @('-НесмотряНаАудит')
$Ок = $Р.Код -eq 0
if (-not $Ок) { $Провалов++; Write-Host $Р.Вывод }
Write-Host ('{0,6:N1} с  {1,-34} {2}' -f $Часы.Elapsed.TotalSeconds, 'база возвращена деплоем src_ext', $(if ($Ок) { 'ок' } else { 'ОШИБКА' }))
Write-Host "ИТОГО: не покраснело или не вернулось $Провалов, время $([math]::Round($Часы.Elapsed.TotalSeconds, 1)) с"
exit [int]($Провалов -gt 0)
