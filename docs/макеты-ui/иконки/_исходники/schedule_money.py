def snowflake(c, cx, cy, radius, width, branches=True):
    for degree in (-90,-30,30,90,150,210):
        angle=math.radians(degree)
        end=(cx+radius*math.cos(angle),cy+radius*math.sin(angle))
        c.line([(cx,cy),end],T,width)
        if branches:
            inner=(cx+radius*.58*math.cos(angle),cy+radius*.58*math.sin(angle))
            for turn in (-48,48):
                a=math.radians(degree+turn)
                tip=(inner[0]+radius*.37*math.cos(a),inner[1]+radius*.37*math.sin(a))
                c.line([inner,tip],T,width)


