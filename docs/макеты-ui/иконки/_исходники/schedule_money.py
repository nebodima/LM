def star(c,x,y,r,color):
    points=[]
    for step in range(10):
        angle=math.radians(-90+step*36)
        radius=r if step%2==0 else r*.46
        points.append((x+radius*math.cos(angle),y+radius*math.sin(angle)))
    c.poly(points,color)


